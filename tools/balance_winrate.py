def _열쇠(패턴들):
    return tuple(None if p is None else tuple(p) for p in 패턴들)


def _변형(바탕, 목록, R):
    """차례 한두 개를 전력전투·일반공격·스킬 중 무작위로 바꾼 패턴."""
    새 = list(바탕)
    for k in R.sample(range(len(새)), R.choice((1, 2))):
        새[k] = R.choice([전력전투] + list(목록))
    return 새


def _후보(지금, 목록, R, 변형수, 스킬들):
    바탕 = list(지금) if 지금 is not None else [전력전투] * bs.슬롯수
    후보 = [None, ["일반공격"] * bs.슬롯수]
    후보 += [[s] + 바탕[1:] for s in 스킬들]
    후보 += [_변형(바탕, 목록, R) for _ in range(변형수)]
    return 후보


def 다듬기(평가, 행동목록들, R, 반복=2, 변형수=5, 스킬후보들=None, 여유=1):
    """평가(패턴들) -> 학습 승수. 전원 None(전력전투)에서 시작해, 반복마다 파티원을 한 명씩 돌아가며 후보 패턴을
    넣어 보고 승수가 지금 최고보다 `여유` 이상 많으면 바꾼다. 한 바퀴 동안 바뀐 것이 없으면 멈춘다.
    같은 패턴들은 다시 재지 않는다. -> (패턴들, {"시작", "최고", "평가수"})."""
    n = len(행동목록들)
    스킬후보들 = 스킬후보들 or [[] for _ in range(n)]
    캐시 = {}

    def 점(패턴들):
        키 = _열쇠(패턴들)
        if 키 not in 캐시:
            캐시[키] = 평가([None if p is None else list(p) for p in 패턴들])
        return 캐시[키]

    지금 = [None] * n
    시작 = 최고 = 점(지금)
    for _ in range(반복):
        바뀜 = False
        for i in range(n):
            for 후보 in _후보(지금[i], 행동목록들[i], R, 변형수, 스킬후보들[i]):
                시험 = 지금[:i] + [후보] + 지금[i + 1 :]
                v = 점(시험)
                if v >= 최고 + 여유:
                    최고, 지금, 바뀜 = v, 시험, True
        if not 바뀜:
            break
    return 지금, {"시작": 시작, "최고": 최고, "평가수": len(캐시)}


def _스킬_후보(분석판, 구성, 행동목록들, k):
    """분석 전투 판들에서 파티원마다 "썼을 때 승률 - 안 썼을 때 승률"이 큰 직접 스킬 k개(모자라면 보유 순서로 채운다).
    인과는 아니다(오래 버틴 판에서 많이 쓴다) - 시도할 순서를 정할 뿐이고, 받아들일지는 학습 판이 정한다."""
    스킬표 = ba.집계(분석판)["스킬"] if 분석판 else {}
    결과 = []
    for (_, 전), 목록 in zip(구성, 행동목록들):
        점수 = []
        for s in 목록[1:]:
            v = 스킬표.get((전, s))
            if v is not None:
                안 = v["안썼을때승률"]
                점수.append((-(v["썼을때승률"] - (안 if 안 is not None else 0.0)), s))
        고른 = [s for _, s in sorted(점수)][:k]
        고른 += [s for s in 목록[1:] if s not in 고른][: k - len(고른)]
        결과.append(고른)
    return 결과


def 파티_다듬기(환경, 구성, 학습시드, 검증시드, R, 반복=2, 변형수=5, 후보스킬=4):
    """파티 하나 -> {"파티", "패턴": {전직: 패턴 또는 None}, "분석승률", "전력승률", "최고승률"(검증 판),
    "학습": {"시작", "최고", "판", "평가수"}(학습 판 승수)}."""
    목록 = 행동목록(환경, 구성)
    분석판 = [환경.전투(구성, s) for s in 학습시드]
    스킬후보들 = _스킬_후보(분석판, 구성, 목록, 후보스킬)

    def 평가(패턴들):
        return sum(환경.패턴전투(구성, 패턴들, s) for s in 학습시드)

    여유 = max(1, math.ceil(len(학습시드) * 0.05))
    패턴들, 기록 = 다듬기(평가, 목록, R, 반복, 변형수, 스킬후보들, 여유)
    n = len(검증시드)

    def 검증(패턴들):
        return sum(환경.패턴전투(구성, 패턴들, s) for s in 검증시드) / n

    이름 = [전 for _, 전 in 구성]
    return {
        "파티": 이름,
        "패턴": dict(zip(이름, 패턴들)),
        "분석승률": sum(환경.전투(구성, s)["승"] for s in 검증시드) / n,
        "전력승률": 검증([None] * len(구성)),
        "최고승률": 검증(패턴들),
        "학습": {**기록, "판": len(학습시드), "여유": 여유},
    }


def _조각(인수):
    번호들, 판, 반복, 변형수, 후보스킬, 시작시드 = 인수
    환경 = 승률환경()
    학습 = range(학습시드_시작 + 시작시드, 학습시드_시작 + 시작시드 + 판)
    검증 = range(검증시드_시작 + 시작시드, 검증시드_시작 + 시작시드 + 판)
    return [
        (
            i,
            파티_다듬기(
                환경,
                구성,
                학습,
                검증,
                random.Random(시작시드 * 1000 + i),
                반복,
                변형수,
                후보스킬,
            ),
        )
        for i, 구성 in 번호들
    ]


def 승률_실행(파티들, 판, 반복=2, 변형수=5, 후보스킬=4, 일꾼=1, 시작시드=0):
    """파티마다 다듬기 -> 결과 목록(파티 순서). 학습·검증 시드 묶음은 모든 파티가 같다(같은 몬스터와 맞붙는다).
    일꾼이 2 이상이면 파티를 나눠 프로세스로 돈다(결과는 같다)."""
    번호 = list(enumerate(파티들))
    if 일꾼 <= 1:
        결과 = _조각((번호, 판, 반복, 변형수, 후보스킬, 시작시드))
    else:
        조각들 = [
            (번호[i::일꾼], 판, 반복, 변형수, 후보스킬, 시작시드) for i in range(일꾼)
        ]
        with concurrent.futures.ProcessPoolExecutor(일꾼) as ex:
            결과 = [r for 묶음 in ex.map(_조각, 조각들) for r in 묶음]
    결과.sort(key=lambda x: x[0])
    return [r for _, r in 결과]


