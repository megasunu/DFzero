class 승률환경(ba.분석환경):
    def 패턴전투(self, 구성, 패턴들, 시드):
        """파티원마다 패턴으로 한 판 -> 아군 승리인가. 패턴은 그 파티원의 차례 1, 2, ...의 행동("전력전투",
        "일반공격" 또는 스킬)이고, None이거나 패턴이 끝난 뒤 차례는 전력전투다."""
        gf = self.gf
        상태 = self.전투_열기(구성, 시드)
        전투상태 = 상태["전투상태"]
        번호 = {c["캐릭터명"]: i for i, c in enumerate(상태["파티"]["파티원"])}
        차례수 = [0] * len(구성)
        self.support.반응_처리(상태)
        for _ in range(bs.판당_최대턴):
            if gf.전투_종료됨(상태):
                break
            p = gf.현재_턴_참가자(상태)
            if p["진영"] == "아군" and p["생존"]:
                i = 번호.get((p.get("원본") or {}).get("캐릭터명"))
                행동 = 전력전투
                if i is not None:
                    k, 차례수[i] = 차례수[i], 차례수[i] + 1
                    패턴 = 패턴들[i] or []
                    행동 = 패턴[k] if k < len(패턴) else 전력전투
                if 행동 != 전력전투 and gf.아군_차례인가(상태):
                    # 그 차례의 행동 하나를 먼저 쓰고 남은 행동은 일반공격(balance_sim.패턴_차례)
                    bs.패턴_차례(
                        gf, self.scenario, 상태, p, [행동], collections.Counter(), []
                    )
                else:
                    gf.자동전투_한_턴(상태)
            else:
                gf.턴_넘기기(상태)
        return 전투상태["종료"] == "아군승리"


def 행동목록(환경, 구성):
    """파티원마다 ["일반공격", 직접 쓰는 보유 스킬...](반응·연계 스킬은 저절로 나가므로 뺀다)."""
    상태 = 환경.파티(구성)
    정의 = 상태["스킬데이터모음"]
    return [
        ["일반공격"]
        + [s for s in c.get("보유스킬", []) if bs.자동스킬_종류(정의.get(s)) is None]
        for c in 상태["파티"]["파티원"]
    ]


