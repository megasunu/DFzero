"""밸런스 체크 승률용 전투(#691) - 파티원 네 명의 행동 패턴을 돌아가며 다듬어 그 파티의 최고 승률을 찾는다.

    python tools/balance_sim.py 전체 --승률 --묶음 1 --판 20   # 고른 무작위 파티 6개

밸런스 체크 전투는 분석용(#690, 무작위성을 키워 넓게)과 이 승률용(승률을 끌어올려)으로 나눈다(2026-11-13 사용자 결정).
- 패턴: 파티원마다 차례 1~슬롯수의 행동 - "전력전투"(그 차례는 자동전투 전력전투), "일반공격", 또는 스킬(먼저 쓰고
  남은 행동은 일반공격, balance_sim.패턴_차례). None이나 패턴 뒤의 차례는 전력전투. 전원 None(전력전투)에서 시작한다.
- 다듬기: 파티원을 한 명씩 돌아가며(나머지는 지금까지 가장 좋은 패턴으로 고정) 후보 패턴을 같은 학습 시드 묶음으로
  맞대고, 학습 승수가 지금보다 `여유`(기본 학습 판의 5%) 이상 많은 것만 받아들인다 - 몇 판 차이의 운을 좇지 않게.
  후보는 전력전투, 일반공격만, 분석 전투에서 승리와 함께 자주 나온 스킬을 첫 차례에 둔 것, 지금 패턴의 차례 한두 개를
  무작위로 바꾼 것.
- 결과는 학습에 쓰지 않은 검증 시드로 다시 잰다(분석용·전력전투·최고 패턴 모두 같은 검증 판) - 학습 판에 맞춘 운을 뺀다.
게임 규칙과 자동전투 판단은 바꾸지 않는다 - gameflow 창구만 쓴다.
"""

