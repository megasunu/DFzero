class 분석환경:
    """파티 구성마다 캐릭터를 한 번 키워 두고, 판마다 복사본으로 무작위 행동 전투를 돈다."""

    def __init__(self):
        self.gf, self.scenario, self.support, self.rng = bs.게임()
        self.gf.자동전투_방식_설정("전력전투")
        self.상태모음 = {}

    def 파티(self, 구성):
        키 = tuple(tuple(x) for x in 구성)
        if 키 not in self.상태모음:
            self.상태모음[키] = bs.파티_상태(list(키))
        return self.상태모음[키]

    def 전투_열기(self, 구성, 시드):
        """쉰 파티의 복사본으로 시드의 몬스터(balance_sim.조건)와 전투를 연다 -> 게임 상태. 게임 난수도 시드로 맞춘다."""
        gf = self.gf
        원본 = self.파티(구성)
        gf.휴식(원본)
        상태 = copy.deepcopy(원본)
        self.rng.시드(시드)
        rr = random.Random(시드)
        조건 = bs.조건
        몹 = [rr.choice(조건["몬스터"]) for _ in range(rr.randint(*조건["마리"]))]
        gf.전투_시작(상태, 몹, 레벨=조건["몬스터레벨"], 차수=조건["몬스터차수"])
        return 상태

    def 전투(self, 구성, 시드, 섞기=0.3):
        """한 판 -> 판 기록 {"파티", "시드", "승", "라운드", "딜", "받음", "생존", "쓰러진라운드", "스킬", "인형"}.
        딜·받음·생존·쓰러진라운드·스킬은 전직 이름마다. 스킬은 {스킬: {"횟수", "피해"}}(전투 로그 항목 수와
        그 항목들이 적에게 넣은 피해 - 넘친 피해 뺌, 일반공격·반응 포함). 인형은 {인형 이름: 피해}."""
        from game.system.combat import contribution, core

        gf = self.gf
        상태 = self.전투_열기(구성, 시드)
        행동R = random.Random(시드 * 7919 + 1)  # 행동 고르기는 게임 난수와 따로
        전투상태 = 상태["전투상태"]
        이름표 = {c["캐릭터명"]: 전 for c, (_, 전) in zip(상태["파티"]["파티원"], 구성)}
        쓰러짐 = {전: None for 전 in 이름표.values()}
        self.support.반응_처리(상태)
        for _ in range(bs.판당_최대턴):
            if gf.전투_종료됨(상태):
                break
            p = gf.현재_턴_참가자(상태)
            if p["진영"] == "아군" and p["생존"]:
                if gf.아군_차례인가(상태) and 행동R.random() >= 섞기:
                    self._무작위_차례(상태, p, 행동R)
                else:
                    gf.자동전투_한_턴(상태)
            else:
                gf.턴_넘기기(상태)
            for q in 전투상태["참가자"]:
                전 = 이름표.get(q.get("이름"))
                if 전 and not q["생존"] and 쓰러짐[전] is None:
                    쓰러짐[전] = 전투상태["라운드"]
        딜 = core.피해_집계(전투상태)
        받음 = contribution.받은피해_집계(전투상태)
        생존 = {
            이름표[q["이름"]]: bool(q["생존"])
            for q in 전투상태["참가자"]
            if q.get("이름") in 이름표 and not q.get("인형")
        }
        return {
            "파티": [전 for _, 전 in 구성],
            "시드": 시드,
            "승": 전투상태["종료"] == "아군승리",
            "라운드": 전투상태["라운드"],
            "딜": {전: 딜.get(이름, 0) for 이름, 전 in 이름표.items()},
            "받음": {전: 받음.get(이름, 0) for 이름, 전 in 이름표.items()},
            "생존": 생존,
            "쓰러진라운드": 쓰러짐,
            "스킬": _스킬_집계(전투상태, 이름표),
            "인형": {
                q["이름"]: 딜.get(q["이름"], 0)
                for q in 전투상태["참가자"]
                if q.get("인형")
            },
        }

    def _행동_후보(self, 상태, p):
        """직접 쓸 수 있는 보유 스킬(반응·연계는 저절로 나가므로 뺀다) 중 지금 쓸 수 있고 대상이 있는 것."""
        gf, 정의모음 = self.gf, 상태["스킬데이터모음"]
        후보 = []
        for 이름 in p["원본"].get("보유스킬", []):
            if bs.자동스킬_종류(정의모음.get(이름)) is not None:
                continue
            if not gf.스킬_사용_가능여부(상태, p, 이름)[0]:
                continue
            인수 = self.scenario._스킬_인수(상태, p, 이름)
            if 인수 is not None:
                후보.append((이름, 인수))
        return 후보

    def _무작위_차례(self, 상태, p, R):
        """한 차례를 무작위로 - 일반공격이나 쓸 수 있는 스킬 하나를 고르고, 스킬이 일반행동을 쓰지 않았으면 한 번 더
        (최대 3번, balance_sim._시험자_차례와 같은 틀). 적을 노리는 스킬과 남은 일반공격의 대상도 무작위다."""
        gf, 적 = self.gf, self.scenario._살아있는_적
        전투상태 = 상태["전투상태"]

        def 계속():
            return 전투상태["종료"] is None and p["생존"] and 적(상태)

        for _ in range(3):
            if not 계속():
                break
            후보 = self._행동_후보(상태, p)
            k = R.randrange(len(후보) + 1)
            if k == len(후보):  # 일반공격
                break
            이름, 인수 = 후보[k]
            if "중심대상" in 인수 and 인수["중심대상"]["진영"] == "적":
                데이터 = 상태["스킬데이터모음"][이름]
                적들 = [
                    e for e in 적(상태) if not gf.스킬_지정불가인가(상태, 데이터, e)
                ]
                인수 = {"중심대상": R.choice(적들)}
            gf.아군_스킬사용(상태, 이름, **인수)
            if p["행동자원"].get("일반행동", 0) <= 0:
                break
        while 계속() and gf.일반공격_가능여부(상태, p):
            gf.아군_일반공격(상태, R.choice(적(상태)))
        if 전투상태["종료"] is None:
            gf.턴_넘기기(상태)


def _스킬_집계(전투상태, 이름표):
    """전투 로그 -> {전직: {스킬: {"횟수", "피해"}}}. 스킬은 로그 항목의 "스킬"(일반공격 항목은 "일반공격",
    반응 항목은 그 반응 이름). 피해는 그 항목이 적에게 넣은 피해(core.피해_내역을 항목 하나씩 - 넘친 피해 뺌)."""
    from game.system.combat import core

    진영 = {p["이름"]: p["진영"] for p in 전투상태["참가자"]}
    결과 = {전: {} for 전 in 이름표.values()}
    for 항목 in 전투상태["로그"]:
        전 = 이름표.get(항목.get("공격자"))
        종류 = 항목.get("종류")
        if 전 is None:
            continue
        if 종류 == "일반공격":
            스킬 = "일반공격"
        elif 종류 == "반응":
            스킬 = 항목.get("반응")
        else:
            스킬 = 항목.get("스킬")
        if not 스킬:
            continue
        피해 = sum(
            양
            for 귀속, 대상, 양 in core.피해_내역({"로그": [항목]})
            if 귀속 == 항목.get("공격자") and 진영.get(대상) == "적"
        )
        칸 = 결과[전].setdefault(str(스킬), {"횟수": 0, "피해": 0})
        칸["횟수"] += 1
        칸["피해"] += max(피해, 0)
    return 결과


