def _조각(인수):
    파티들, 판, 섞기, 시작시드 = 인수
    환경 = 분석환경()
    return [
        (i, 환경.전투(구성, 시작시드 + s, 섞기))
        for i, 구성 in 파티들
        for s in range(판)
    ]


def 분석_실행(파티들, 판, 섞기=0.3, 일꾼=1, 시작시드=0):
    """파티마다 시드 시작시드..시작시드+판-1로 분석 전투 -> 판 기록 목록(파티 순서, 시드 순서). 일꾼이 2 이상이면
    파티를 나눠 프로세스로 돈다(결과는 같다)."""
    번호 = list(enumerate(파티들))
    if 일꾼 <= 1:
        결과 = _조각((번호, 판, 섞기, 시작시드))
    else:
        조각들 = [(번호[i::일꾼], 판, 섞기, 시작시드) for i in range(일꾼)]
        with concurrent.futures.ProcessPoolExecutor(일꾼) as ex:
            결과 = [r for 묶음 in ex.map(_조각, 조각들) for r in 묶음]
    결과.sort(key=lambda x: (x[0], x[1]["시드"]))
    return [r for _, r in 결과]


