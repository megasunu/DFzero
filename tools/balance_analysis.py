def 고른_파티들(전직표, 묶음, R):
    """{1차 직업: [전직...]} -> 묶음 x (전직 수 / 4)개의 4인 파티 [[(1차, 전직)] ...]. 묶음마다 전직을 섞어 4명씩
    나누므로 모든 전직이 같은 횟수(묶음 수)로 나오고 한 파티에 같은 전직이 없다."""
    전직들 = [(일차, 전) for 일차, 목록 in 전직표.items() for 전 in 목록]
    if len(전직들) % 파티_인원:
        raise ValueError(
            f"전직 {len(전직들)}종은 {파티_인원}명씩 나누어떨어지지 않는다"
        )
    파티들 = []
    for _ in range(묶음):
        섞음 = list(전직들)
        R.shuffle(섞음)
        파티들 += [섞음[i : i + 파티_인원] for i in range(0, len(섞음), 파티_인원)]
    return 파티들


