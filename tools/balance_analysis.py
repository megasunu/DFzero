def 선형_기여(판들):
    """[(파티 전직들, 결과 0~1)] -> {전직: 승률 기여}. 결과 ~ 전직 포함 여부(0/1)의 합으로 맞추는 선형 회귀
    (최소제곱, 파티 인원이 늘 같아 절편과 겹치므로 절편 없이 맞추고 평균을 뺀다). 기여는 "평균 전직 대신 이 전직이
    들어가면 승률이 얼마나 달라지나"다. 정규방정식을 가우스 소거로 푼다(아주 작은 능선 항으로 특이 행렬을 막는다)."""
    전직들 = sorted({j for 파티, _ in 판들 for j in 파티})
    번호 = {j: i for i, j in enumerate(전직들)}
    n = len(전직들)
    A = [[0.0] * n for _ in range(n)]
    b = [0.0] * n
    for 파티, y in 판들:
        ix = [번호[j] for j in 파티]
        for i in ix:
            b[i] += y
            for k in ix:
                A[i][k] += 1.0
    for i in range(n):
        A[i][i] += 1e-9 * max(len(판들), 1)
    계수 = _풀기(A, b)
    평균 = sum(계수) / n if n else 0.0
    return {j: 계수[번호[j]] - 평균 for j in 전직들}


def _풀기(A, b):
    n = len(b)
    M = [row[:] + [b[i]] for i, row in enumerate(A)]
    for c in range(n):
        피벗 = max(range(c, n), key=lambda r: abs(M[r][c]))
        M[c], M[피벗] = M[피벗], M[c]
        for r in range(n):
            if r != c and M[r][c]:
                배 = M[r][c] / M[c][c]
                M[r] = [x - 배 * y for x, y in zip(M[r], M[c])]
    return [M[i][n] / M[i][i] for i in range(n)]


def 집계(판들):
    """판 기록 목록 -> {"전직": {전직: {"판", "승률", "생존율", "딜지분", "판당딜", "판당받음"}},
    "기여": {전직: 승률 기여}, "스킬": {(전직, 스킬): {"판", "횟수", "판당피해", "썼을때승률", "안썼을때승률"}},
    "파티": [{"파티", "판", "승률"}](승률 높은 순), "먼저쓰러짐": {전직: 진 판에서 파티 중 가장 먼저 쓰러진 횟수},
    "인형": {이름: {"판", "판당딜"}}, "판", "승률", "평균라운드"}. 딜지분은 판마다 그 판 파티 딜 중 몫의 평균."""
    전직 = collections.defaultdict(
        lambda: {"판": 0, "승": 0, "생존": 0, "딜지분합": 0.0, "딜": 0, "받음": 0}
    )
    스킬 = collections.defaultdict(lambda: {"판": 0, "횟수": 0, "피해": 0, "승": 0})
    파티 = collections.defaultdict(lambda: [0, 0])
    먼저 = collections.Counter()
    인형 = collections.defaultdict(lambda: [0, 0])
    for r in 판들:
        합 = sum(r["딜"].values())
        for j in r["파티"]:
            d = 전직[j]
            d["판"] += 1
            d["승"] += r["승"]
            d["생존"] += r["생존"].get(j, False)
            d["딜"] += r["딜"].get(j, 0)
            d["받음"] += r["받음"].get(j, 0)
            d["딜지분합"] += r["딜"].get(j, 0) / 합 if 합 else 0.0
            for 이름, v in r["스킬"].get(j, {}).items():
                s = 스킬[(j, 이름)]
                s["판"] += 1
                s["횟수"] += v["횟수"]
                s["피해"] += v["피해"]
                s["승"] += r["승"]
        키 = tuple(r["파티"])
        파티[키][0] += 1
        파티[키][1] += r["승"]
        if not r["승"]:
            쓰러진 = [(v, j) for j, v in r["쓰러진라운드"].items() if v is not None]
            if 쓰러진:
                먼저[min(쓰러진)[1]] += 1
        for 이름, v in r.get("인형", {}).items():
            인형[이름][0] += 1
            인형[이름][1] += v
    전직표 = {
        j: {
            "판": d["판"],
            "승률": d["승"] / d["판"],
            "생존율": d["생존"] / d["판"],
            "딜지분": d["딜지분합"] / d["판"],
            "판당딜": d["딜"] / d["판"],
            "판당받음": d["받음"] / d["판"],
        }
        for j, d in 전직.items()
    }
    스킬표 = {}
    for (j, 이름), s in 스킬.items():
        안판 = 전직[j]["판"] - s["판"]
        스킬표[(j, 이름)] = {
            "판": s["판"],
            "횟수": s["횟수"],
            "판당피해": s["피해"] / s["판"],
            "썼을때승률": s["승"] / s["판"],
            "안썼을때승률": (전직[j]["승"] - s["승"]) / 안판 if 안판 else None,
        }
    n = len(판들)
    return {
        "판": n,
        "승률": sum(r["승"] for r in 판들) / n if n else 0.0,
        "평균라운드": sum(r["라운드"] for r in 판들) / n if n else 0.0,
        "전직": 전직표,
        "기여": 선형_기여([(r["파티"], float(r["승"])) for r in 판들]),
        "스킬": 스킬표,
        "파티": sorted(
            ({"파티": k, "판": v[0], "승률": v[1] / v[0]} for k, v in 파티.items()),
            key=lambda x: (-x["승률"], x["파티"]),
        ),
        "먼저쓰러짐": dict(먼저),
        "인형": {k: {"판": v[0], "판당딜": v[1] / v[0]} for k, v in 인형.items()},
    }


def _오차_문장(요약):
    """전직별 승률의 표준오차(이항, 판 수 평균) - 이보다 작은 차이는 운일 수 있다."""
    if not 요약["전직"]:
        return ""
    n = sum(d["판"] for d in 요약["전직"].values()) / len(요약["전직"])
    p = 요약["승률"]
    오차 = (p * (1 - p) / n) ** 0.5 if n else 0.0
    return (
        f"전직마다 약 {n:.0f}판이면 승률의 표준오차는 약 ±{오차 * 100:.1f}%p다 - "
        "그 두 배보다 작은 차이는 운일 수 있다(판을 늘리면 줄어든다)."
    )


def _퍼(x):
    return "-" if x is None else f"{x * 100:.1f}%"


def 보고서(요약, 정보, 파티_줄=5, 스킬_줄=40):
    """집계 -> 마크다운 보고서(docs/balance/분석.md). 정보: {"판"(파티당), "섞기", "파티"(수), "규칙지문", ...}."""
    줄 = [
        "# 밸런스 체크 - 분석용 전투",
        "",
        "`python tools/balance_sim.py 전체 --분석` 결과(#690). 무작위 4인 파티(전직마다 같은 출전 횟수)가 무작위 행동"
        f"(아군 차례의 {정보['섞기'] * 100:.0f}%는 자동전투 전력전투)으로 싸운 판들이다. 승률을 끌어올린 값은 승률용 전투(#691)가 잰다.",
        "",
        f"- 파티 {정보['파티']}개 x 파티당 {정보['판']}판 = {요약['판']}판, 전체 승률 {_퍼(요약['승률'])}, "
        f"평균 {요약['평균라운드']:.1f}라운드",
        f"- 규칙지문 `{정보.get('규칙지문', '')}`"
        + (f", 커밋 `{정보['커밋']}`" if 정보.get("커밋") else ""),
        "",
        "## 전직",
        "",
        '기여 = 선형 회귀(승패 ~ 파티에 든 전직)로 구한 "평균 전직 대신 들어가면 달라지는 승률". 딜지분은 판마다 파티 딜 중 몫의 평균.',
        _오차_문장(요약),
        "",
        "| 전직 | 판 | 승률 | 기여 | 생존율 | 딜지분 | 판당 딜 | 판당 받은 피해 | 진 판 먼저 쓰러짐 |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for j in sorted(요약["전직"], key=lambda j: -요약["기여"].get(j, 0)):
        d = 요약["전직"][j]
        줄.append(
            f"| {j} | {d['판']} | {_퍼(d['승률'])} | {요약['기여'].get(j, 0) * 100:+.1f}%p | "
            f"{_퍼(d['생존율'])} | {_퍼(d['딜지분'])} | {d['판당딜']:.1f} | {d['판당받음']:.1f} | "
            f"{요약['먼저쓰러짐'].get(j, 0)} |"
        )
    줄 += [
        "",
        "## 스킬",
        "",
        f"쓴 판이 많은 순 상위 {스킬_줄}개. 판당 피해는 그 스킬을 쓴 판에서 그 스킬 로그가 적에게 넣은 피해(넘친 피해 뺌).",
        "썼을 때/안 썼을 때 승률은 그 전직이 나온 판 안에서 비교한 것이라 인과가 아니다(오래 버틴 판일수록 많이 쓴다).",
        "",
        "| 전직 | 스킬 | 쓴 판 | 횟수 | 판당 피해 | 썼을 때 승률 | 안 썼을 때 승률 |",
        "|---|---|---|---|---|---|---|",
    ]
    for (j, 이름), s in sorted(요약["스킬"].items(), key=lambda x: (-x[1]["판"], x[0]))[
        :스킬_줄
    ]:
        줄.append(
            f"| {j} | {이름} | {s['판']} | {s['횟수']} | {s['판당피해']:.1f} | "
            f"{_퍼(s['썼을때승률'])} | {_퍼(s['안썼을때승률'])} |"
        )
    줄 += ["", "## 파티", "", "| 순위 | 파티 | 판 | 승률 |", "|---|---|---|---|"]
    파티들 = 요약["파티"]
    보일것 = list(enumerate(파티들, 1))
    if len(파티들) > 2 * 파티_줄:
        보일것 = 보일것[:파티_줄] + 보일것[-파티_줄:]
    for 순위, p in 보일것:
        줄.append(
            f"| {순위} | {' · '.join(p['파티'])} | {p['판']} | {_퍼(p['승률'])} |"
        )
    if 요약["인형"]:
        줄 += ["", "## 인형", "", "| 인형 | 나온 판 | 판당 딜 |", "|---|---|---|"]
        for 이름, v in sorted(요약["인형"].items()):
            줄.append(f"| {이름} | {v['판']} | {v['판당딜']:.1f} |")
    return "\n".join(줄) + "\n"
