"""밸런스 체크 분석용 전투(#690) - 무작위성을 키워 여러 방법을 써 보며 넓게 훑는다.

    python tools/balance_sim.py 전체 --분석 --묶음 10 --판 30   # 고른 무작위 파티 60개 x 30판

밸런스 체크 전투는 둘로 나눈다(2026-11-13 사용자 결정): 이 분석용 전투와, 승률을 끌어올리는 승률용 전투(#691).
- 파티: 전직 24종이 묶음마다 한 번씩 들어가는 무작위 4인 파티(한 파티에 같은 전직 없음, 고른_파티들).
- 행동: 아군 차례마다 `섞기` 확률로 자동전투 "전력전투", 나머지는 쓸 수 있는 스킬·일반공격 중 무작위(적 대상도 무작위).
- 몬스터와 판 조건은 balance_sim.조건 그대로. 파티마다 같은 시드 묶음을 써서 파티끼리 같은 몬스터와 맞붙는다.
- 집계: 전직별 승률·생존율·딜지분, 선형 회귀로 전직별 승률 기여, 스킬별 사용·피해·썼을 때 승률, 파티 상·하위.
게임 규칙과 자동전투 판단은 바꾸지 않는다 - gameflow 창구만 쓴다.
"""

