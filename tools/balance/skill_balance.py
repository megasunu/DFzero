def 캐릭터_빌드(전투상태, 참가자, 대상=None):
    """전투 중인 아군 참가자의 수치로 빌드를 만든다(장비·버프·특성·칭호 반영). 시나리오 시험이나 측정 파티에서 부른다.
    명중보너스는 능력치 보정치를 뺀 명중률보너스 합(원본·장비·버프·특성·칭호), 데미지보너스는 장비·버프·칭호."""
    from game.system.combat import core, hit, stats, traits

    무기 = (참가자.get("장비데이터") or {}).get("무기")
    보정치 = stats.평타_능력치_보정치(전투상태, 참가자)
    명중 = hit.명중_보정합(전투상태, 참가자, 대상 or 참가자, "보정명중률") - 보정치
    기본 = stats.기본_컨텍스트(전투상태, 참가자)
    데미지 = (
        stats.장비_데미지보너스(참가자, 대상, 전투상태)
        + stats.버프디버프_수치(전투상태, 참가자, "데미지보너스")
        + traits.칭호_수치(전투상태, 참가자, "데미지보너스")
    )
    return 빌드(
        무기=stats.유효_무기공격력(전투상태, 참가자, 무기) if 무기 else "1d1",
        보정치=보정치,
        주문시전보정치=stats.주문시전_보정치(전투상태, 참가자),
        명중보너스=명중,
        데미지보너스=데미지,
        추가공격=(참가자.get("원본") or {}).get("추가공격", 0),
        능력치=기본["능력치"],
        능력치보정치=기본["능력치보정치"],
        이름=f"{참가자['이름']}(레벨 {참가자['원본'].get('레벨')}, {core.차수(참가자)}차수)",
    ), core.차수(참가자)


def 측정파티_빌드(전직):
    """밸런스 측정 파티(tools/balance/balance_sim.py와 같은 조건)에서 그 전직 캐릭터로 전투를 열고 빌드를 만든다."""
    from tools.balance import balance_sim as bs

    m = bs.측정(전직)
    상태 = m._상태(m.기본파티)
    m.gf.휴식(상태)
    m.rng.시드(0)
    조건 = bs.조건
    m.gf.전투_시작(
        상태, list(조건["몬스터"]), 레벨=조건["몬스터레벨"], 차수=조건["몬스터차수"]
    )
    전투상태 = 상태["전투상태"]
    원본 = 상태["파티"]["파티원"][0]
    나 = next(p for p in 전투상태["참가자"] if p["원본"] is 원본)
    적 = next(p for p in 전투상태["참가자"] if p["진영"] == "적")
    return 캐릭터_빌드(전투상태, 나, 적)


