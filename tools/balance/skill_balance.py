def _평가(식, 빌드값, 차수, 치명타=False):
    if isinstance(식, (int, float)):
        return float(식)
    컨텍스트 = 빌드값.컨텍스트(차수)
    if 치명타 and ("보정공격력" in str(식) or "무기공격력" in str(식)):
        # 무기 주사위가 있는 식은 무기 주사위만 는다 - 엔진의 평균은 치명타를 보지 않아 무기 주사위를 직접 두 배로 한다
        컨텍스트["무기공격력"] = "+".join(
            f"{int(개수) * 2}d{면}"
            for 개수, 면 in _주사위식.findall(컨텍스트["무기공격력"])
        )
        치명타 = False
    return float(formula.수식_평가(str(식), 컨텍스트, 치명타=치명타, 평균=True))


_주사위식 = re.compile(r"(\d+)d(\d+)")


def _이점_평균(식, 빌드값, 차수):
    """피해 굴림 이점(두 번 굴려 높은 쪽)의 기대 - 주사위 항을 더하기만 하는 식(예: 1d8+주문시전보정치)만 센다.
    다른 식이면 None(이점 없이 센다)."""
    if not isinstance(식, str) or re.search(r"[-x×÷*/()]", 식):
        return None
    분포 = {0: 1.0}
    주사위평균 = 0.0
    for 개수, 면 in _주사위식.findall(식):
        for _ in range(int(개수)):
            새 = {}
            for 합, 확률 in 분포.items():
                for 눈 in range(1, int(면) + 1):
                    새[합 + 눈] = 새.get(합 + 눈, 0.0) + 확률 / int(면)
            분포 = 새
            주사위평균 += (int(면) + 1) / 2
    누적, 이전, 최대기대 = 0.0, 0.0, 0.0
    for 값 in sorted(분포):
        누적 += 분포[값]
        최대기대 += 값 * (누적**2 - 이전**2)
        이전 = 누적
    return _평가(식, 빌드값, 차수) - 주사위평균 + 최대기대


def 명중배율(명중률, 스킬명중보너스, 빌드값):
    """(실제 명중 확률 / 70%, 비고 또는 None)."""
    if 명중률 in ("자동", "필중", None):
        return 1 / 기준_명중, None
    if 명중률 == "주사위20":  # 백팔염주 - 눈 20에만 맞는다(빌드와 상관없이 5%)
        return (1 / 20) / 기준_명중, None
    if 명중률 == "보정명중률":
        보정 = 빌드값.보정치
    elif 명중률 == "주문시전명중률":
        보정 = 빌드값.주문시전보정치
    else:
        return 1.0, f"명중 {명중률}은 70%로 봄"
    보정합 = 보정 + 빌드값.명중보너스 + 스킬명중보너스
    return contribution.명중확률(보정합, 기준_AC) / 기준_명중, None


def _목록(값, 길이):
    return list(값) if isinstance(값, list) else [값] * 길이


def 부분_기대(부분, 빌드값, 차수):
    """공격 하나(스킬 또는 공격단계)의 기대 피해 합(대상 수까지 곱함)과 비고 목록."""
    비고 = []
    크기별 = 부분.get("크기별공격횟수")
    if 크기별:  # 맞는 적의 크기로 타수가 정해진다 - 몬스터 기본 크기인 중형으로 센다
        비고.append("크기별공격횟수: 중형 기준")
    횟수 = (
        크기별.get("중형", 1)
        if 크기별
        else int(_평가(부분.get("공격횟수", 1), 빌드값, 차수))
    )
    데미지들 = _목록(부분.get("데미지"), 횟수)
    명중들 = _목록(부분.get("명중률", "자동"), 횟수)
    보너스 = _평가(부분.get("데미지보너스") or 0, 빌드값, 차수) + 빌드값.데미지보너스
    명중보너스 = _평가(부분.get("명중보너스") or 0, 빌드값, 차수)
    치명타 = bool(부분.get("강제치명타"))  # 주사위 개수 (1 + 치명타주사위 1)배
    합, 맞는수 = 0.0, 0.0
    for 식, 명중 in zip(데미지들, 명중들):
        if 식 is None:
            continue
        배율, 글 = 명중배율(명중, 명중보너스, 빌드값)
        if 부분.get("명중불리점") and 명중 not in ("자동", "필중", None):
            배율 *= 배율 * 기준_명중  # 불리점 - 명중 확률 p가 p x p
        if 글 and 글 not in 비고:
            비고.append(글)
        이점 = _이점_평균(식, 빌드값, 차수) if 부분.get("_피해이점") else None
        피해 = 이점 if 이점 is not None else _평가(식, 빌드값, 차수, 치명타)
        합 += (피해 + 보너스) * 배율
        맞는수 += 배율 * 기준_명중
    제한 = 부분.get("대상당피격제한")
    if 제한:  # 적랜덤반복 - 한 적이 맞는 수에 한도가 있다. 적 3체로 보고 맞는 수의 기대가 한도 합을 넘으면 줄인다
        한도 = 기준_적수 * int(_평가(제한, 빌드값, 차수))
        if 맞는수 > 한도:
            합 *= 한도 / 맞는수
        비고.append(f"대상당피격제한: 적 {기준_적수}체 기준")
    if 부분.get("라운드종료피해"):  # 라운드 끝에 들어가는 피해 - 내성에 성공하면 절반
        합 *= 내성_피해배율(부분["라운드종료피해"], 빌드값, 차수)
    반복 = 부분.get("명중반복")
    if 반복:  # 맞으면 다시(최대 번까지), 맞을 때마다 명중보너스가 바뀐다 - i번째 시도는 앞의 시도가 모두 맞았을 때만
        변화 = 반복.get("명중보너스변화", 0)
        배율들 = [
            명중배율(명중들[0], 명중보너스 + i * 변화, 빌드값)[0]
            for i in range(int(_평가(반복["최대"], 빌드값, 차수)))
        ]
        이어질확률, 배수 = 1.0, 0.0
        for 배율 in 배율들:
            배수 += 이어질확률 * 배율
            이어질확률 *= 배율 * 기준_명중
        합 *= 배수 / 배율들[0]
    return 합 * 대상_종류(부분)[2], 비고


