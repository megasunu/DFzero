def _지속공격_행(데이터, 빌드값, 차수, 비용값, 결과, 앞비고):
    """지속공격 - "빗나감유지"(빗나가도 그 타격만)거나 턴마다 명중 굴림이 없으면(장판 - 라운드 끝마다, 내성이 있으면
    성공 시 절반) 한 턴의 기대(부가효과·내성실패효과 포함) x 지속턴. 그 밖은 수동 확인."""
    상세 = 데이터["지속공격"]
    if not 상세.get("빗나감유지") and (
        상세.get("매턴명중굴림") is not False or 상세.get("데미지") is None
    ):
        return {**결과, "비고": ["수동 확인: 지속공격(턴마다 판정)"] + 앞비고}
    비고 = _키_비고(
        {k: v for k, v in 데이터.items() if k != "지속공격"},
        [상세],
        빌드값,
        차수,
        빼는키=frozenset(지속공격_반영키 - 반영키),
    )
    기준 = 비용값 * 대상_종류(상세)[1]
    한턴, 글 = 부분_기대(상세, 빌드값, 차수)
    if 상세.get("내성"):
        한턴 *= 내성_피해배율(상세, 빌드값, 차수)
    한턴 += 부가_기대(상세, 빌드값, 차수, 기준)[0]
    실패효과 = 상세.get("내성실패효과")
    if 실패효과:
        실패 = 1 - 내성_성공확률(상세, 빌드값, 차수) if 상세.get("내성") else 1.0
        값, 이름 = 상태이상_값(
            {**실패효과, "내성": None}, 상세, 빌드값, 차수, 기준, 맞음=실패
        )
        한턴 += 값
        if 이름:
            비고.insert(0, f"부가효과 포함: {이름}(내성 실패 시)")
    기대 = 한턴 * int(_평가(상세.get("지속턴", 1), 빌드값, 차수))
    비율 = (기대 / 기준 - 1) * 100 if 기준 else None
    return {
        **결과,
        "대상": 대상_종류(상세)[0],
        "기대": 기대,
        "기준": 기준,
        "비율": 비율,
        "비고": 비고 + 글,
    }


def _파이어볼트(행동):
    """메카 공격 - 메카닉은 레벨 6(소환 스킬을 배우는 2차수 전)에 특성 파이어볼트를 얻어 "메카" 피해 굴림에 이점을 받는다."""
    return (
        {**행동, "_피해이점": True} if "메카" in (행동.get("스킬타입") or ()) else 행동
    )


def 소환수_라운드당(소환수, 빌드값, 차수):
    """(행동표 평균 - 라운드당 기대 피해, 자폭 기대 피해, 비고 목록). 1d6 눈마다 같은 확률."""
    표 = 소환수["행동표"]
    합, 비고 = 0.0, []
    for 행동 in 표.values():
        값, 글 = 부분_기대(_파이어볼트(행동), 빌드값, 차수)
        합 += 값
        비고 += [g for g in 글 if g not in 비고]
    자폭 = (
        부분_기대(_파이어볼트(소환수["자폭공격"]), 빌드값, 차수)[0]
        if "자폭공격" in 소환수
        else 0.0
    )
    return 합 / len(표), 자폭, 비고


def 소환수_라운드수(지속):
    return 소환수_기준라운드 if 지속 is None else min(소환수_기준라운드, 지속)


def _소환수_행(데이터, 빌드값, 차수):
    """메카 소환 스킬 - 라운드당 기대 x 기준 라운드(지속턴이 짧으면 지속턴) vs 비용."""
    _, 소환수, 지속 = 메카소환수(데이터)
    비용값, 비용글 = 비용(데이터, 차수)
    한라운드, _, 글 = 소환수_라운드당(소환수, 빌드값, 차수)
    라운드 = 소환수_라운드수(지속)
    기대 = 한라운드 * 라운드
    비율 = (기대 / 비용값 - 1) * 100 if 비용값 else None
    return {
        "대상": f"소환수 {라운드}라운드",
        "비용": 비용글,
        "기대": 기대,
        "기준": 비용값,
        "비율": 비율,
        "비고": [
            "자폭은 따로(소환수 딜표)",
            "부가효과 포함: 메카 피해 이점(파이어볼트)",
        ]
        + 글,
    }


def 소환수_딜표(직업, 스킬목록, 빌드값=기준빌드, 차수목록=차수들):
    """그 직업의 메카 소환 스킬마다 차수별 라운드당·누적·기준·자폭 표 줄 목록(없으면 빈 목록)."""
    줄 = []
    for 이름, 데이터 in 스킬목록.items():
        찾음 = 메카소환수(데이터)
        if not 찾음:
            continue
        _, 소환수, 지속 = 찾음
        라운드 = 소환수_라운드수(지속)
        for 차 in 차수목록:
            한라운드, 자폭, _ = 소환수_라운드당(소환수, 빌드값, 차)
            기준 = 비용(데이터, 차)[0]
            누적 = [한라운드 * r for r in range(1, 소환수_기준라운드 + 1)]
            누적 = [_수(v) if r <= 라운드 else "-" for r, v in enumerate(누적, 1)]
            비율 = (한라운드 * 라운드 / 기준 - 1) * 100 if 기준 else None
            비율글 = "-" if 비율 is None else f"{비율:+.0f}%"
            지속글 = "전투 끝까지" if 지속 is None else f"{지속}턴(끝나면 자폭)"
            줄.append(
                f"| {이름} | {차} | {_수(한라운드)} | {' | '.join(누적)} | {_수(기준)} | {비율글} "
                f"| {_수(자폭)} | {지속글} |"
            )
    if not 줄:
        return []
    누적머리 = " | ".join(f"{r}라운드 누적" for r in range(1, 소환수_기준라운드 + 1))
    return [
        f"### {직업} 소환수 딜표",
        "",
        f"기준 라운드 {소환수_기준라운드}(지속턴이 더 짧으면 그만큼)의 누적이 위 표의 기대값이다. 자폭은 누적에 넣지 않는다"
        "(로봇전폭 - 보조행동·MP 10, 바이퍼는 지속턴이 끝나면 저절로).",
        "",
        f"| 스킬 | 차수 | 라운드당 | {누적머리} | 기준 | 비율 | 자폭 | 지속 |",
        "|---|---|---|" + "---|" * 소환수_기준라운드 + "---|---|---|---|",
        *줄,
        "",
    ]


def _특수행동_행(이름, 데이터, 스킬목록, 빌드값, 차수):
    """ "특수행동획득"(멀티 헤드샷) - 얻는 특수행동 수 x 그 행동으로 내는 스킬("특수행동지불") 한 번의 기대 피해.
    비용은 이 스킬의 것만(그 행동으로 낸 스킬은 MP가 들지 않는다)."""
    비용값, 비용글 = 비용(데이터, 차수)
    기대, 비고 = 0.0, []
    for 행동, 식 in 데이터["특수행동획득"].items():
        수 = int(_평가(식, 빌드값, 차수))
        for 쓰는이름, 쓰는 in 스킬목록.items():
            if 쓰는.get("특수행동지불") == 행동:
                값, 글 = 부분_기대(쓰는, 빌드값, 차수)
                기대 += 수 * 값
                비고 += [f"{행동} ({식})회 x {쓰는이름}"] + 글
                if 쓰는.get("강제치명타"):
                    비고.append("부가효과 포함: 강제치명타")
    비율 = (기대 / 비용값 - 1) * 100 if 비용값 else None
    return {
        "대상": "단일",
        "비용": 비용글,
        "기대": 기대,
        "기준": 비용값,
        "비율": 비율,
        "비고": 비고,
    }


def _수(값):
    return "-" if 값 is None else f"{값:.2f}".rstrip("0").rstrip(".")


def _칸(행):
    if 행["기대"] is None:
        return "수동 확인"
    비율 = "-" if 행["비율"] is None else f"{행['비율']:+.0f}%"
    return f"{_수(행['기대'])} / {_수(행['기준'])} ({비율})"


def 직업_표(직업, 스킬목록, 빌드값=기준빌드, 차수목록=차수들):
    """한 직업의 마크다운 표 줄 목록(공격 스킬이 없으면 빈 목록)."""
    줄 = []
    for 이름, 데이터 in 스킬목록.items():
        if not 공격스킬인가(데이터):
            continue
        if 메카소환수(데이터):
            행들 = [_소환수_행(데이터, 빌드값, 차) for 차 in 차수목록]
        elif "특수행동획득" in 데이터:
            행들 = [_특수행동_행(이름, 데이터, 스킬목록, 빌드값, 차) for 차 in 차수목록]
        else:
            행들 = [스킬_행(이름, 데이터, 빌드값, 차) for 차 in 차수목록]
        첫 = 행들[0]
        비고 = "; ".join(dict.fromkeys(g for 행 in 행들 for g in 행["비고"]))
        칸들 = " | ".join(_칸(행) for 행 in 행들)
        줄.append(f"| {이름} | {첫['대상']} | {첫['비용']} | {칸들} | {비고} |")
    if not 줄:
        return []
    머리 = " | ".join(f"{차}차수" for 차 in 차수목록)
    return [
        f"## {직업}",
        "",
        f"| 스킬 | 대상 | 비용 | {머리} | 비고 |",
        "|---|---|---|" + "---|" * len(차수목록) + "---|",
        *줄,
        "",
        *소환수_딜표(직업, 스킬목록, 빌드값, 차수목록),
    ]


