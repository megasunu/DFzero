def 직업별_스킬():
    """[(직업 이름, {스킬 이름: 데이터})] - 파일 순서(분류번호). 공용 스킬(0000)은 "공용"."""
    import game.data.job_skill as 패키지

    결과 = []
    for 모듈정보 in sorted(pkgutil.iter_modules(패키지.__path__), key=lambda m: m.name):
        if 모듈정보.name == "job_skill_format":
            continue
        모듈 = importlib.import_module(f"game.data.job_skill.{모듈정보.name}")
        with open(모듈.__file__, encoding="utf-8") as f:
            머리 = re.search(r"#\s*(.+?)\s*스킬\s*\(분류번호", f.read(2000))
        직업 = "공용" if 모듈정보.name == "job_skill_0000" else 머리.group(1)
        결과.append((직업, 모듈.스킬목록))
    return 결과


