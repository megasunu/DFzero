def _평가(식, 빌드값, 차수):
    if isinstance(식, (int, float)):
        return float(식)
    return float(formula.수식_평가(str(식), 빌드값.컨텍스트(차수), 평균=True))


def 명중배율(명중률, 스킬명중보너스, 빌드값):
    """(실제 명중 확률 / 70%, 비고 또는 None)."""
    if 명중률 in ("자동", "필중", None):
        return 1 / 기준_명중, None
    if 명중률 == "주사위20":  # 백팔염주 - 눈 20에만 맞는다(빌드와 상관없이 5%)
        return (1 / 20) / 기준_명중, None
    if 명중률 == "보정명중률":
        보정 = 빌드값.보정치
    elif 명중률 == "주문시전명중률":
        보정 = 빌드값.주문시전보정치
    else:
        return 1.0, f"명중 {명중률}은 70%로 봄"
    보정합 = 보정 + 빌드값.명중보너스 + 스킬명중보너스
    return contribution.명중확률(보정합, 기준_AC) / 기준_명중, None


def _목록(값, 길이):
    return list(값) if isinstance(값, list) else [값] * 길이


def 부분_기대(부분, 빌드값, 차수):
    """공격 하나(스킬 또는 공격단계)의 기대 피해 합(대상 수까지 곱함)과 비고 목록."""
    비고 = []
    크기별 = 부분.get("크기별공격횟수")
    횟수 = (
        크기별.get("중형", 1)
        if 크기별
        else int(_평가(부분.get("공격횟수", 1), 빌드값, 차수))
    )
    데미지들 = _목록(부분.get("데미지"), 횟수)
    명중들 = _목록(부분.get("명중률", "자동"), 횟수)
    보너스 = _평가(부분.get("데미지보너스") or 0, 빌드값, 차수) + 빌드값.데미지보너스
    명중보너스 = _평가(부분.get("명중보너스") or 0, 빌드값, 차수)
    합 = 0.0
    for 식, 명중 in zip(데미지들, 명중들):
        if 식 is None:
            continue
        배율, 글 = 명중배율(명중, 명중보너스, 빌드값)
        if 부분.get("명중불리점") and 명중 not in ("자동", "필중", None):
            배율 *= 배율 * 기준_명중  # 불리점 - 명중 확률 p가 p x p
        if 글 and 글 not in 비고:
            비고.append(글)
        합 += (_평가(식, 빌드값, 차수) + 보너스) * 배율
    반복 = 부분.get("명중반복")
    if 반복:  # 맞으면 다시(최대 번까지), 맞을 때마다 명중보너스가 바뀐다 - i번째 시도는 앞의 시도가 모두 맞았을 때만
        변화 = 반복.get("명중보너스변화", 0)
        배율들 = [
            명중배율(명중들[0], 명중보너스 + i * 변화, 빌드값)[0]
            for i in range(int(_평가(반복["최대"], 빌드값, 차수)))
        ]
        이어질확률, 배수 = 1.0, 0.0
        for 배율 in 배율들:
            배수 += 이어질확률 * 배율
            이어질확률 *= 배율 * 기준_명중
        합 *= 배수 / 배율들[0]
    return 합 * 대상_종류(부분)[2], 비고


def 스킬_행(이름, 데이터, 빌드값, 차수):
    """{"기대", "기준", "비율", "대상", "비용", "비고"} - 셀 수 없으면 "기대"가 None."""
    비용값, 비용글 = 비용(데이터, 차수)
    부분들 = [데이터[k] for k in ("공격단계1", "공격단계2") if k in 데이터] or [데이터]
    비고 = []
    빠진 = sorted(set(데이터) - 반영키)
    for 부분 in 부분들:
        if 부분 is not 데이터:
            빠진 += sorted(set(부분) - 반영키 - 단계_무시키)
        if 부분.get("조건부효과") and "조건부효과" not in 빠진:
            빠진.append("조건부효과")
        if 부분.get("효과"):
            종류 = {e.get("종류", "?") for e in 부분["효과"] if isinstance(e, dict)}
            빠진 += sorted(f"효과:{k}" for k in 종류 if f"효과:{k}" not in 빠진)
    if 빠진:
        비고.append("반영 안 함: " + ", ".join(dict.fromkeys(빠진)))
    대상 = " + ".join(대상_종류(p)[0] for p in 부분들)
    결과 = {"대상": 대상, "비용": 비용글, "기준": None, "기대": None, "비율": None}
    if 이름 in 보충:
        return {**결과, "비고": ["수동 확인: " + 보충[이름]] + 비고}
    if "지속공격" in 데이터:
        return _지속공격_행(데이터, 빌드값, 차수, 비용값, 결과, 비고)
    try:
        기대, 기준 = 0.0, 0.0
        for 부분 in 부분들:
            값, 글 = 부분_기대(부분, 빌드값, 차수)
            기대 += 값
            기준 += 비용값 * 대상_종류(부분)[1]
            비고 += [g for g in 글 if g not in 비고]
    except (ValueError, TypeError, ZeroDivisionError, SyntaxError) as e:
        return {**결과, "비고": [f"수동 확인: 식을 셀 수 없음({e})"] + 비고}
    비율 = (기대 / 기준 - 1) * 100 if 기준 else None
    return {**결과, "기대": 기대, "기준": 기준, "비율": 비율, "비고": 비고}


