def 비용(데이터, 차수):
    """스킬 한 번의 비용을 피해로 바꾼 값과 설명 - (값, "일반행동, MP 10" 같은 글)."""
    값, 글 = 0.0, []
    행동 = 데이터.get("행동")
    if isinstance(행동, list):
        행동 = 행동[0]
    if 데이터.get("일반공격취급") and 행동 == "일반행동":
        값 += 공격칸
        글.append("일반공격취급")
    elif 행동 == "일반행동":
        값 += 차수 * 공격칸
        글.append("일반행동")
    elif 행동 == "보조행동":
        값 += 주사위
        글.append("보조행동")
    elif 행동 == "반응행동":
        값 += 공격칸
        글.append("반응행동")
    elif 행동:
        글.append(str(행동))
    mp = 데이터.get("MP소모") or 0
    if isinstance(mp, (int, float)) and mp:
        값 += (mp // 10) * 공격칸 + (주사위 if mp % 10 >= 5 else 0)
        글.append(f"MP {mp}")
    받기 = (데이터.get("지속공격") or {}).get("턴시작반응받기")
    if 받기:  # 더블 건호크 - 쓴 턴 뒤 남은 턴마다 반응행동으로 받는다
        회수 = int(데이터["지속공격"].get("지속턴", 1)) - 1
        값 += 회수 * 공격칸
        글.append(f"받기 반응행동 {회수}")
    큐브 = (데이터.get("재료소모") or {}).get("무색 큐브 조각", 0)
    if 큐브:
        값 += 큐브 / 5 * 공격칸
        글.append(f"큐브 {큐브}")
    return 값, ", ".join(글) or "없음"


def 대상_종류(부분):
    """(대상 이름, 기준 배율, 기대 피해에 곱할 대상 수)."""
    if 부분.get("추가무작위대상"):
        return "2체", 1.0, 2
    타겟 = 부분.get("타겟") or "적단일"
    if 타겟 == "적3체":
        return "범위", 1.5, 3
    if 타겟 == "적전체":
        return "전체(1체당)", 1 / 3, 1
    return "단일", 1.0, 1


