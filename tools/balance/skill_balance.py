def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--직업", help="이 직업만 화면에 찍는다(파일은 쓰지 않는다)")
    p.add_argument(
        "--측정파티", metavar="전직", help="측정 파티의 그 전직 캐릭터 수치로"
    )
    for 이름, 형 in (
        ("무기", str),
        ("보정치", int),
        ("주문시전보정치", int),
        ("명중보너스", int),
        ("데미지보너스", float),
        ("추가공격", int),
    ):
        p.add_argument(f"--{이름}", type=형)
    a = p.parse_args(argv)
    바꿈 = {
        k: v
        for k, v in vars(a).items()
        if k not in ("직업", "측정파티") and v is not None
    }
    차수목록 = 차수들
    if a.측정파티:
        빌드값, 차수 = 측정파티_빌드(a.측정파티)
        빌드값 = dataclasses.replace(빌드값, **바꿈)
        차수목록 = (차수,)
        a.직업 = a.직업 or a.측정파티
    else:
        빌드값 = dataclasses.replace(
            기준빌드, **바꿈, 이름="지정 빌드" if 바꿈 else 기준빌드.이름
        )
    if not (a.직업 or 바꿈 or a.측정파티):
        with open(표_경로, "w", encoding="utf-8", newline="\n") as f:
            f.write(전체_문서())
        print(f"썼다: {os.path.relpath(표_경로, ROOT)}")
        return 0
    줄 = [f"- {빌드_설명(빌드값)}", ""]
    for 직업, 스킬목록 in 직업별_스킬():
        if a.직업 in (None, 직업):
            줄 += 직업_표(직업, 스킬목록, 빌드값, 차수목록)
    if len(줄) == 2:
        print(f"직업을 찾지 못했다: {a.직업}")
        return 1
    print("\n".join(줄))
    return 0


