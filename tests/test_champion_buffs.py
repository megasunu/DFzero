def test_2단계_버프가_모두_뽑기목록에_있다():
    새것 = {
        "가속-이동",
        "가속-기상",
        "가속-캐스팅",
        "가속-HP회복",
        "회복",
        "인챈트-화속성",
        "인챈트-수속성",
        "인챈트-명속성",
        "인챈트-암속성",
        "분해",
        "흡혈",
        "궤도",
        "감염",
        "흡입",
        "잠재움",
        "강화-상태변화저항",
    } | {f"공격시 {n}" for n in monster_title.챔피언_공격시_상태이상}
    assert 새것 <= set(monster_title.챔피언버프_뽑기목록)
    assert len(monster_title.챔피언_공격시_상태이상) == 13


