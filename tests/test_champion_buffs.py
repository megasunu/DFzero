def test_가속_이동은_우선도_1이다():
    상태, 전투상태 = _전투([_챔피언(), _챔피언(버프=["가속-이동"])])
    a, b = sorted(gf.적_목록(상태), key=lambda p: len(p["원본"]["챔피언버프"]))
    assert stats.유효_우선도(전투상태, b) == stats.유효_우선도(전투상태, a) + 1


def test_가속_기상은_넘어짐에_걸리지_않는다():
    상태, 전투상태 = _전투([_챔피언(버프=["가속-기상"])])
    assert status.상태이상_면역(전투상태, gf.적_목록(상태)[0], "넘어짐")


@pytest.mark.parametrize("버프, 캐스팅", [((), True), (("가속-캐스팅",), False)])
def test_가속_캐스팅은_패턴_캐스팅_없이_바로_쓴다(monkeypatch, 버프, 캐스팅):
    상태, 전투상태 = _전투([_챔피언("라키우스", 버프)])
    챔피언 = gf.적_목록(상태)[0]
    번호 = next(
        k for k, p in 챔피언["원본"]["패턴"].items() if p.get("이름") == "심장 찌르기"
    )
    _주사위(monkeypatch, 번호)  # 패턴 고르기 d6
    monster_actions.몬스터_턴_실행(전투상태, 챔피언)
    글 = [str(항목.get("비고", "")) for 항목 in 전투상태["로그"]]
    assert any("심장 찌르기 캐스팅을 시작했다" in g for g in 글) == 캐스팅


def test_가속_HP회복은_턴_시작에_차수d6_건강보정치를_회복한다(monkeypatch):
    상태, 전투상태 = _전투([_챔피언(버프=["가속-HP회복"])])
    챔피언 = gf.적_목록(상태)[0]
    챔피언["현재HP"] = 1
    _주사위(monkeypatch, 6)
    flow.턴_시작_처리(전투상태, 챔피언)
    건강 = (챔피언["원본"]["건강"] - 10) // 2
    assert 챔피언["현재HP"] == min(1 + 6 + 건강, _최대HP(전투상태, 챔피언))


def test_회복은_턴_시작에_최대체력_20퍼센트를_회복한다():
    상태, 전투상태 = _전투([_챔피언(버프=["회복"])])
    챔피언 = gf.적_목록(상태)[0]
    챔피언["현재HP"] = 1
    flow.턴_시작_처리(전투상태, 챔피언)
    assert 챔피언["현재HP"] == 1 + formula.올림(_최대HP(전투상태, 챔피언) * 0.2)


def test_잠재움은_턴_시작에_무작위_적_하나를_내성_없이_1턴_재운다():
    상태, 전투상태 = _전투([_챔피언(버프=["잠재움"])])
    flow.턴_시작_처리(전투상태, gf.적_목록(상태)[0])
    잠든 = [p for p in _아군(상태) if _걸린(p, "수면")]
    assert len(잠든) == 1
    assert _걸린(잠든[0], "수면")["지속턴"] == 1


