def _끼기(전투상태, 참가자, 장비탭, *이름들):
    참가자["장비데이터"] = dict(
        참가자["장비데이터"],
        **{새_아이템[이름]: _아이템(장비탭, 이름) for 이름 in 이름들},
    )
    참가자["장비보너스"] = 장비.캐릭터_장비_보너스(
        참가자["원본"], 참가자["장비데이터"], 전투상태["세트정의"]
    )


def test_전투는_악세서리_세트도_판정한다(전장):
    전투상태, _, _ = 전장
    assert "스톰패스 멋쟁이" in 전투상태["세트정의"]


def test_스톰패스_아이템은_수속성_속성내성_1씩(전장, 장비탭):
    전투상태, _, 아군 = 전장
    p = 아군[0]
    수, 화 = (
        stats.속성_보정합(전투상태, p, "속성내성", s) for s in ("수속성", "화속성")
    )
    _끼기(전투상태, p, 장비탭, "칠링 래빗풋")
    assert stats.속성_보정합(전투상태, p, "속성내성", "수속성") == 수 + 1
    _끼기(전투상태, p, 장비탭, "로시의 얼음반지", "설산의 보답")
    assert stats.속성_보정합(전투상태, p, "속성내성", "수속성") == 수 + 3
    assert stats.속성_보정합(전투상태, p, "속성내성", "화속성") == 화


def test_스톰패스_세트는_모든_속성강화_1(전장, 장비탭):
    전투상태, _, 아군 = 전장
    p = 아군[0]
    속성들 = ("화속성", "수속성", "명속성", "암속성")
    전 = [stats.속성_보정합(전투상태, p, "속성강화", s) for s in 속성들]
    _끼기(전투상태, p, 장비탭, "칠링 래빗풋", "로시의 얼음반지")
    assert [stats.속성_보정합(전투상태, p, "속성강화", s) for s in 속성들] == 전
    _끼기(전투상태, p, 장비탭, "설산의 보답")
    assert [stats.속성_보정합(전투상태, p, "속성강화", s) for s in 속성들] == [
        v + 1 for v in 전
    ]


def _보정치(전투상태, 대상, 거는상태이상=None):
    return stats.대상_내성굴림(전투상태, 대상, "건강", 10, 거는상태이상=거는상태이상)[2]


def test_상태이상_내성은_그_상태이상을_막는_내성굴림에_더한다(전장, 장비탭):
    전투상태, _, 아군 = 전장
    p = 아군[0]
    기본 = _보정치(전투상태, p)
    _끼기(전투상태, p, 장비탭, "칠링 래빗풋")
    assert _보정치(전투상태, p, "빙결") == 기본 + 1
    assert _보정치(전투상태, p, "기절") == 기본
    assert _보정치(전투상태, p) == 기본  # 피해만 정하는 굴림에는 없다
    # 셋 + 세트(모든 상태이상 내성 1)
    _끼기(전투상태, p, 장비탭, "로시의 얼음반지", "설산의 보답")
    assert _보정치(전투상태, p, "빙결") == 기본 + 4
    assert _보정치(전투상태, p, "기절") == 기본 + 1
    assert _보정치(전투상태, p) == 기본


def test_상태이상을_거는_굴림에_상태이상_내성이_실린다(전장, 장비탭, monkeypatch):
    전투상태, 적, 아군 = 전장
    p = 아군[0]
    기본 = _보정치(전투상태, p)
    _끼기(전투상태, p, 장비탭, "칠링 래빗풋")
    보정치들 = []

    def 내성(보정치, 난이도, **kw):
        보정치들.append(보정치)
        return True, 20

    monkeypatch.setattr(dice_utils, "내성_굴림", 내성)
    적[0]["장비데이터"] = {
        "무기": {
            "이름": "시험 무기",
            "고유효과": [
                {
                    "발동": "명중",
                    "상태이상": "빙결",
                    "내성": {"능력치": "건강", "DC": 10},
                }
            ],
        }
    }
    damage.마봉_명중시효과(전투상태, 적[0], p, {"성공": True})
    assert 보정치들 == [기본 + 1]


def test_학자의_토시는_턴_시작에_MP_4_회복(전장, 장비탭):
    전투상태, _, 아군 = 전장
    p = 아군[0]
    _끼기(전투상태, p, 장비탭, "학자의 토시")
    최대MP = 장비.장비반영_최대MP(p["원본"], p["장비데이터"], 전투상태["세트정의"])
    p["현재MP"] = 최대MP - 10
    flow.턴_시작_처리(전투상태, p)
    assert p["현재MP"] == 최대MP - 6


def test_심장을_뽑는_약지는_명중_시_20퍼센트로_출혈(전장, 장비탭, monkeypatch):
    전투상태, 적, 아군 = 전장
    p = 아군[0]
    _끼기(전투상태, p, 장비탭, "심장을 뽑는 약지")
    난이도들 = []

    def 내성(보정치, 난이도, **kw):
        난이도들.append(난이도)
        return False, 1

    monkeypatch.setattr(dice_utils, "내성_굴림", 내성)
    monkeypatch.setattr(rng.확률, "random", lambda: 0.2)
    damage.마봉_명중시효과(전투상태, p, 적[0], {"성공": True})
    assert 적[0]["상태이상"] == []
    monkeypatch.setattr(rng.확률, "random", lambda: 0.19)
    damage.마봉_명중시효과(전투상태, p, 적[0], {"성공": True})
    근력 = stats.유효_능력치_보정치(전투상태, p, "근력")
    assert 난이도들 == [10 + 근력]
    출혈 = [s for s in 적[0]["상태이상"] if s["이름"] == "출혈"]
    assert len(출혈) == 1 and 출혈[0]["지속턴"] == 1
