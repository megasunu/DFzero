# ---- 레어 이상 기본 옵션


def test_기본옵션은_레어_이상_목걸이_반지_팔찌에만():
    def 옵션(분류, 레어도, 티어):
        return 장비.악세서리_기본옵션({"분류": 분류, "레어도": 레어도, "티어": 티어})

    assert 옵션("목걸이", "레어", 2) == {"최대HP": 4}
    assert 옵션("반지", "레어", 2) == {"최대MP": 2}
    assert 옵션("팔찌", "레어", 2) == {"MP재생": 1}
    assert 옵션("목걸이", "유니크", 3) == {"최대HP": 6}
    assert 옵션("팔찌", "레어", 1) == {}  # 티어-1 = 0
    for 레어도 in ("커먼", "언커먼", "치트"):
        assert 옵션("목걸이", 레어도, 2) == {}
    assert 옵션("귀걸이", "레어", 2) == {}


def test_봉인된_목걸이와_반지에도_기본옵션(장비탭):
    c = support.새게임([("", "귀검사")])["파티"]["파티원"][0]
    목걸이 = 장비탭["목걸이"]["마법으로 봉인된 목걸이"]
    반지 = 장비탭["반지"]["마법으로 봉인된 반지"]
    assert (
        장비.장비반영_최대HP(c, {"목걸이": 목걸이}) == 장비.장비반영_최대HP(c, {}) + 2
    )
    assert 장비.장비반영_최대MP(c, {"반지": 반지}) == 장비.장비반영_최대MP(c, {}) + 1


def test_다프네의_펜던트는_최대HP_14_최대MP_10(장비탭):
    c = support.새게임([("", "귀검사")])["파티"]["파티원"][0]
    펜던트 = {"목걸이": _아이템(장비탭, "다프네의 펜던트")}
    assert 장비.장비반영_최대HP(c, 펜던트) == 장비.장비반영_최대HP(c, {}) + 14
    assert 장비.장비반영_최대MP(c, 펜던트) == 장비.장비반영_최대MP(c, {}) + 10


def test_반지는_최대MP_2_팔찌는_MP재생(장비탭):
    c = support.새게임([("", "귀검사")])["파티"]["파티원"][0]
    약지 = {"반지": _아이템(장비탭, "심장을 뽑는 약지")}
    assert 장비.장비반영_최대MP(c, 약지) == 장비.장비반영_최대MP(c, {}) + 2
    토시 = {"팔찌": _아이템(장비탭, "학자의 토시")}
    assert 장비.장비_보너스_합산(토시)["MP재생"] == 4
    설산 = {"팔찌": _아이템(장비탭, "설산의 보답")}
    assert 장비.장비_보너스_합산(설산)["MP재생"] == 1


