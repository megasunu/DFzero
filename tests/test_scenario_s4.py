"""S4 무기 x 몬스터 종족 (docs/scenarios.md).

레벨 6 전직 캐릭터(직업마다 하나)가 카탈로그의 모든 무기 종류를 사서 끼우고, 다섯 몬스터 종족(고블린, 루가루,
타우, 좀비, 인간)과 각각 **일반공격만으로** 실제로 싸운다. 스킬을 안 쓰므로 무기(주사위/명중/특성)만 드러난다.
무기 사기 -> 착용 -> 전투까지의 이어짐과, 판정 로그의 일관성(명중/치명타/자동실패/피해), 무기 고유 효과
(둔기의 기절은 둔기에서만)를 본다. 무기 하나하나의 수치 규칙은 test_growth.py가 값으로 검사한다.
종족은 던전을 걷지 않고 전투를 직접 연다 - 던전마다 종족이 무작위로 섞여 나와서 특정 종족을 고를 수 없기 때문이다.
"""

import pytest

from game.system import rng
import gameflow as gf
import support
from tests.support import 구현된_전직

직업들 = list(구현된_전직)
# 종족 -> 대표 몬스터(레벨 3, 차수 1로 연다)
종족 = {
    "고블린": "고블린",
    "루가루": "루가루",
    "타우": "타우 아미",
    "좀비": "포레스트 좀비",
    "인간": "화염의 비노슈",
}
최대턴 = 20


def _무기_종류(직업):
    """카탈로그에서 직업의 무기 종류 -> 사 올 아이템(이름순 첫 번째, 커먼/언커먼만 - 치트와 봉인 레어 제외)."""
    카탈로그 = gf.새_게임_시작([("", 직업)])["상점카탈로그"]["장비"]["무기"]
    종류 = {}
    for 이름, 아이템 in sorted(카탈로그.items()):
        if 아이템["분류"] == f"{직업} 무기" and 아이템["레어도"] in ("커먼", "언커먼"):
            종류.setdefault(아이템["타입"], 이름)
    return 종류


def _판정_검사(항목):
    """공격 한 번의 로그가 규칙에 맞는지."""
    판정, 피해 = 항목["판정"], 항목.get("피해", 0)
    if 판정["자동실패"]:
        assert not 판정["성공"] and 피해 == 0, 항목
    elif 판정["치명타"]:
        assert 판정["성공"], 항목
    else:
        assert 판정["성공"] == (판정["명중결과"] >= 판정["대상AC"]), 항목
    if not 판정["성공"]:
        assert 피해 == 0, 항목
    assert 피해 >= 0


def _싸움(직업, 무기타입, 무기이름, 몬스터, 종족이름):
    rng.시드(f"S4-{직업}-{무기타입}-{종족이름}")
    상태 = support.새게임([("", 직업)])
    캐릭터 = 상태["파티"]["파티원"][0]
    support.성장(상태, 캐릭터, 6, 전직=구현된_전직[직업])
    gf.파티_최대치로_회복(상태)

    # 사서 끼운다 (못 드는 종류는 사지 않는다)
    if 무기타입 not in 캐릭터["가용무기"]:
        return None  # 카탈로그에는 있지만 이 직업(전직 포함)이 못 드는 종류
    아이템 = 상태["상점카탈로그"]["장비"]["무기"][무기이름]
    상태["소지품"]["골드"] += 아이템["가격"]
    골드 = 상태["소지품"]["골드"]
    assert gf.상점_구매(상태, "장비", "무기", 무기이름, 1) == 아이템["가격"]
    assert 상태["소지품"]["골드"] == 골드 - 아이템["가격"]
    gf.장비_교체(상태, 캐릭터, "무기", 무기이름)
    assert gf.캐릭터_장착아이템(상태, 캐릭터, "무기")["타입"] == 무기타입

    # 일반공격만으로 싸운다
    gf.전투_시작(상태, [몬스터], 레벨=3, 차수=1)
    support.반응_처리(상태)
    기록 = {"공격": 0, "명중": 0, "치명타": 0, "피해": 0, "기절": 0}
    for _ in range(최대턴):
        if gf.전투_종료됨(상태):
            break
        차례 = gf.현재_턴_참가자(상태)
        if 차례["진영"] == "아군" and 차례["생존"]:
            while 차례["행동자원"].get("일반행동", 0) > 0 and not gf.전투_종료됨(상태):
                적 = next((e for e in gf.적_목록(상태) if e["생존"]), None)
                if 적 is None:
                    break
                gf.아군_일반공격(상태, 적)
                for 항목 in gf.새_로그_가져오기(상태):
                    if 항목.get("공격자") != 캐릭터["캐릭터명"]:
                        continue
                    비고 = 항목.get("비고", "")
                    # 내가 건 기절(몬스터 자기 패턴의 기절과, 내성에 성공해 피한 로그는 제외)
                    if "기절" in 비고 and "부여" in 비고:
                        기록["기절"] += 1
                    if "판정" in 항목:
                        _판정_검사(항목)
                        기록["공격"] += 1
                        기록["명중"] += 항목["판정"]["성공"]
                        기록["치명타"] += 항목["판정"]["치명타"]
                        기록["피해"] += 항목.get("피해", 0)
        if not gf.전투_종료됨(상태):
            gf.턴_넘기기(상태)
    기록["종료"] = 상태["전투상태"]["종료"]
    # 반응(선공 몬스터에게 자동 반격 등)으로 일반공격 없이 끝날 수도 있다
    assert 기록["종료"] in ("아군승리", "적승리"), 기록
    return 기록


@pytest.mark.scenario("S4")
@pytest.mark.parametrize("직업", 직업들)
def test_S4_무기_x_종족(직업, golden):
    무기들 = _무기_종류(직업)
    assert len(무기들) >= 4, 무기들
    결과, 못드는 = {}, []
    for 타입, 이름 in 무기들.items():
        종족별 = {
            종족이름: _싸움(직업, 타입, 이름, 몬스터, 종족이름)
            for 종족이름, 몬스터 in 종족.items()
        }
        if all(v is None for v in 종족별.values()):
            못드는.append(타입)
        else:
            결과[타입] = 종족별
    assert len(결과) >= 4, 결과.keys()
    assert sum(r["공격"] for 종족별 in 결과.values() for r in 종족별.values()) > 20
    # 기절은 귀검사의 둔기(무기의 극의)만 건다
    for 타입, 종족별 in 결과.items():
        if (직업, 타입) != ("귀검사", "둔기"):
            assert not any(r["기절"] for r in 종족별.values()), (
                f"{직업} {타입}이 기절을 걸었다"
            )
    if 직업 == "귀검사":
        assert any(r["기절"] for r in 결과["둔기"].values())
    결과["_못_드는_종류"] = 못드는
    golden(f"scenario_S4_weapons_{직업}", 결과)
