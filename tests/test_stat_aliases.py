"""변동대상 별칭(common_names.변동대상_별칭 - AC보너스/명중률보너스/속도보너스)을 모든 경로가 받는다(#455):
몬스터 특성, 칭호, 상태이상 추가효과, 아군 상시 특성."""

import pytest

from game.data import common_names
from game.system.combat import stats, traits


def _전장():
    전투상태 = {
        "특성정의": {
            "시험특성": {
                "효과": [
                    {"변동대상": "AC보너스", "변동값": 2},
                    {"변동대상": "명중률보너스", "변동값": 3},
                    {"변동대상": "속도보너스", "변동값": 4},
                ]
            }
        },
        "칭호정의": {
            "시험칭호": {
                "효과": [
                    {"변동대상": "AC보너스", "변동값": 5},
                    {"변동대상": "명중률보너스", "변동값": 6},
                    {"변동대상": "속도보너스", "변동값": 7},
                ]
            }
        },
        "상태이상정의": {
            "시험중독": {
                "효과": {
                    "추가효과": {"AC보너스": -1, "명중률보너스": -2, "속도보너스": -3}
                }
            }
        },
        "버프정의": {},
        "디버프정의": {},
        "참가자": [],
    }
    적 = {
        "id": 1,
        "이름": "시험몹",
        "진영": "적",
        "원본": {"특성": ["시험특성"], "칭호": "시험칭호"},
        "상태이상": [{"이름": "시험중독", "지속턴": 3}],
        "버프": [],
        "디버프": [],
    }
    전투상태["참가자"].append(적)
    return 전투상태, 적


@pytest.mark.parametrize("별칭, 이름", list(common_names.변동대상_별칭.items()))
def test_몬스터_특성은_별칭을_받는다(별칭, 이름):
    전투상태, 적 = _전장()
    값 = {"AC보너스": 2, "명중률보너스": 3, "속도보너스": 4}[별칭]
    assert traits.특성_수치(전투상태, 적, 이름) == 값


@pytest.mark.parametrize("별칭, 이름", list(common_names.변동대상_별칭.items()))
def test_칭호는_별칭을_받는다(별칭, 이름):
    전투상태, 적 = _전장()
    값 = {"AC보너스": 5, "명중률보너스": 6, "속도보너스": 7}[별칭]
    assert traits.칭호_수치(전투상태, 적, 이름) == 값


@pytest.mark.parametrize("별칭, 이름", list(common_names.변동대상_별칭.items()))
def test_상태이상_추가효과는_별칭을_받는다(별칭, 이름):
    전투상태, 적 = _전장()
    값 = {"AC보너스": -1, "명중률보너스": -2, "속도보너스": -3}[별칭]
    assert stats._상태이상_추가효과_합(전투상태, 적, 이름) == 값
