    # 장비·버프로도 8을 넘지 않는다(디버프로는 내려간다). 주스탯·보조스탯 보정치는 2당 1이 아니라 1당 1.
    from game.system import character_data_system as 캐릭터데이터
    from game.system import character_levelup_system as 레벨업

    전투상태, _, 귀검사 = _전장()
