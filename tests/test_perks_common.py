def _도발_전장():
    rng.시드(5)
    상태 = support.새게임([("", "귀검사"), ("", "격투가")])
    gf.전투_시작(상태, ["고블린", "고블린"], 레벨=2, 차수=1)
    support.반응_처리(상태)
    전투상태 = 상태["전투상태"]
    for p in 전투상태["참가자"]:
        p["현재HP"] = 999
    적 = [p for p in 전투상태["참가자"] if p["진영"] == "적"]
    귀검사, 격투가 = (
        next(p for p in 전투상태["참가자"] if p["원본"]["직업"] == 직업)
        for 직업 in ("귀검사", "격투가")
    )
    return 전투상태, 적, 귀검사, 격투가


def _도발_쓰기(전투상태, 시전자, monkeypatch, 내성성공):
    monkeypatch.setattr(
        stats,
        "대상_내성굴림",
        lambda 전투상태, 대상, 스탯, 난이도, *a, **k: (
            내성성공,
            20 if 내성성공 else 1,
            0,
        ),
    )
    시전자["행동자원"]["보조행동"] = 1
    return ss.스킬_실행(
        전투상태, 시전자, "도발", dict(gf.스킬데이터모음_생성()["도발"], _이름="도발")
    )


def test_도발은_내성에_실패한_적_전체에_건_사람을_기록해_건다(monkeypatch):
    전투상태, 적, 귀검사, _ = _도발_전장()
    _도발_쓰기(전투상태, 귀검사, monkeypatch, 내성성공=False)
    for e in 적:
        [도발] = [s for s in e["상태이상"] if s["이름"] == "도발"]
        assert 도발["시전자id"] == 귀검사["id"] and 도발["지속턴"] == 2  # 1+차수(1)


def test_도발은_내성에_성공한_적에게_걸리지_않는다(monkeypatch):
    전투상태, 적, 귀검사, _ = _도발_전장()
    _도발_쓰기(전투상태, 귀검사, monkeypatch, 내성성공=True)
    assert all(not e["상태이상"] for e in 적)


def _몬스터가_친_대상(전투상태, 몬스터):
    로그수 = len(전투상태["로그"])
    자원 = dict(몬스터["행동자원"])
    monster_actions.몬스터_턴_실행(전투상태, 몬스터)
    몬스터["행동자원"] = 자원  # 같은 몬스터로 다시 시험한다
    대상들 = set()
    for 항목 in 전투상태["로그"][로그수:]:
        if isinstance(항목, dict) and 항목.get("공격자") == 몬스터["이름"]:
            대상 = 항목.get("대상")
            대상들 |= set(대상) if isinstance(대상, list) else {대상} - {None}
    return 대상들


def test_도발에_걸린_적은_건_사람을_노린다(monkeypatch):
    전투상태, 적, 귀검사, 격투가 = _도발_전장()
    # 어그로로는 늘 격투가를 고르게 해 둔다 - 도발이 그것을 이긴다
    monkeypatch.setattr(
        monster_actions.monster_ai, "타겟_선택", lambda 아군, *a, **k: 격투가
    )
    assert _몬스터가_친_대상(전투상태, 적[0]) <= {격투가["이름"]}
    _도발_쓰기(전투상태, 귀검사, monkeypatch, 내성성공=False)
    assert _몬스터가_친_대상(전투상태, 적[0]) == {귀검사["이름"]}
    귀검사["생존"] = False  # 건 사람이 쓰러지면 원래대로
    assert 귀검사["이름"] not in _몬스터가_친_대상(전투상태, 적[1])


