def test_맞기_전에는_지금_성별의_내성과_공격속성():
    전투상태, 고블린, 귀검사 = _란마_전장("m")
    assert _배율(전투상태, 귀검사) == {"수속성": 1.0, "화속성": 0.5}
    assert "화속성" in stats.공격_속성(귀검사, "보정공격력", None, 전투상태=전투상태)
    전투상태, 고블린, 귀검사 = _란마_전장("f")
    assert _배율(전투상태, 귀검사) == {"수속성": 0.5, "화속성": 1.0}
    assert "수속성" in stats.공격_속성(귀검사, "보정공격력", None, 전투상태=전투상태)


def test_수속성에_맞으면_여자_화속성에_맞으면_남자가_된다():
    전투상태, 고블린, 귀검사 = _란마_전장("m")
    _맞기(전투상태, 고블린, 귀검사, "무속성")
    assert "란마성별" not in 귀검사["원본"]
    _맞기(전투상태, 고블린, 귀검사, "수속성")
    assert 귀검사["원본"]["란마성별"] == "f"
    assert _배율(전투상태, 귀검사) == {"수속성": 0.5, "화속성": 1.0}
    assert stats.공격_속성(귀검사, "보정공격력", None, 전투상태=전투상태) == [
        "무속성",
        "수속성",
    ]
    assert "여자" in 전투상태["로그"][-1]["비고"]
    _맞기(전투상태, 고블린, 귀검사, ["무속성", "화속성"])
    assert 귀검사["원본"]["란마성별"] == "m"
    assert _배율(전투상태, 귀검사) == {"수속성": 1.0, "화속성": 0.5}


