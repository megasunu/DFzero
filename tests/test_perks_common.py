def test_그림은_반대_성별_그림이_있을_때만_바뀐다():
    상태 = support.새게임([("", "귀검사"), ("", "거너")])
    귀검사, 거너 = 상태["파티"]["파티원"]
    귀검사["성별"] = "m"
    assert gf.초상화_코드(귀검사) == "010m"
    귀검사["란마성별"] = "f"  # 010m은 011m으로 보이고 011f가 있다
    assert gf.초상화_코드(귀검사) == "010f"
    거너["전직"], 거너["성별"] = "패러메딕", "m"
    거너["란마성별"] = "f"  # 035f 그림이 없다 - 그림만 그대로(효과는 바뀐다)
    assert gf.초상화_코드(거너) == "035m"


