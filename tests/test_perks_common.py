def _란마_전장(성별="m"):
    전투상태, 고블린, 귀검사 = _전장()
    귀검사["원본"]["성별"] = 성별
    for 이름 in ("낭익천", "남익천"):
        effect_engine.특성_부여(귀검사["원본"], 이름, 특성목록[이름])
    return 전투상태, 고블린, 귀검사


def _맞기(전투상태, 공격자, 대상, 속성):
    판정 = {"성공": True, "자연눈": 10, "치명타": False, "자동실패": False}
    damage.피격_처리(전투상태, 공격자, 대상, 판정, 속성=속성)


def _배율(전투상태, 대상):
    return {s: damage.속성_피해배율(전투상태, 대상, s) for s in ("수속성", "화속성")}


def test_란마_퍽은_2차수_선행없이_낭익천과_남익천을_준다():
    퍽 = 퍽목록["란마 1/2"]
    assert (퍽["분류"], 퍽["타입"], 퍽["차수"], 퍽["선행조건"]) == (
        "퍽",
        ["특성획득"],
        2,
        None,
    )
    assert 퍽["획득특성"] == ["낭익천", "남익천"]
    상태 = support.새게임([("", "귀검사")])
    c = 상태["파티"]["파티원"][0]
    support.성장(상태, c, 8, 전직="웨펀마스터")
    상태["진행도"]["플레이어레벨"] = 9
    후보 = dict(gf.선택가능_퍽목록(c))
    assert "란마 1/2" in 후보
    gf.캐릭터_레벨업_적용(c, **support.퍽_선택값(c, "란마 1/2", 후보["란마 1/2"]))
    assert {"낭익천", "남익천"} <= set(c["보유특성"])
    assert "란마 1/2" not in dict(gf.선택가능_퍽목록(c))
    assert (
        c["저항"] == []
    )  # 저항은 지금 형태에서 그때그때 읽는다(영구 목록에 넣지 않는다)


def test_맞기_전에는_지금_성별의_내성과_공격속성():
    전투상태, 고블린, 귀검사 = _란마_전장("m")
    assert _배율(전투상태, 귀검사) == {"수속성": 1.0, "화속성": 0.5}
    assert "화속성" in stats.공격_속성(귀검사, "보정공격력", None, 전투상태=전투상태)
    전투상태, 고블린, 귀검사 = _란마_전장("f")
    assert _배율(전투상태, 귀검사) == {"수속성": 0.5, "화속성": 1.0}
    assert "수속성" in stats.공격_속성(귀검사, "보정공격력", None, 전투상태=전투상태)


def test_수속성에_맞으면_여자_화속성에_맞으면_남자가_된다():
    전투상태, 고블린, 귀검사 = _란마_전장("m")
    _맞기(전투상태, 고블린, 귀검사, "무속성")
    assert "란마성별" not in 귀검사["원본"]
    _맞기(전투상태, 고블린, 귀검사, "수속성")
    assert 귀검사["원본"]["란마성별"] == "f"
    assert _배율(전투상태, 귀검사) == {"수속성": 0.5, "화속성": 1.0}
    assert stats.공격_속성(귀검사, "보정공격력", None, 전투상태=전투상태) == [
        "무속성",
        "수속성",
    ]
    assert "여자" in 전투상태["로그"][-1]["비고"]
    _맞기(전투상태, 고블린, 귀검사, ["무속성", "화속성"])
    assert 귀검사["원본"]["란마성별"] == "m"
    assert _배율(전투상태, 귀검사) == {"수속성": 1.0, "화속성": 0.5}


