def 효과_시나리오(이름):
    상태 = _전투(시드=41)
    전투상태 = 상태["전투상태"]
    적, 아군 = _적(전투상태), _아군(전투상태, 0)
    전 = [_수치(전투상태, p) for p in (아군, 적)]
    전_요약 = [참가자_요약(p) for p in (아군, 적)]
    for p in (아군, 적):
        ss.이름있는효과_부여(전투상태, p, 이름, 2)
    기록 = {
        "수치변화": [
            support.수치_변화(a, _수치(전투상태, p)) for a, p in zip(전, (아군, 적))
        ]
    }
    부여 = [참가자_요약(p) for p in (아군, 적)]
    기록["부여"] = support.참가자_변화(전_요약, 부여)
    _차례(전투상태, 아군)
    기록["턴시작_행동자원"] = dict(아군["행동자원"])
    기록["기타행동"] = dict(아군["기타행동"])
    로그시작 = len(전투상태["로그"])
    _라운드(상태, 3)
    기록["로그"] = 정리(support.핵심_로그(전투상태, 전투상태["로그"][로그시작:]))
    기록["만료후"] = support.참가자_변화(부여, [참가자_요약(p) for p in (아군, 적)])
    ss.이름있는효과_부여(전투상태, 아군, 이름, 1)
    for 목록 in ("버프", "디버프"):
        ss.이름있는효과_해제(아군, 목록, 이름)
    기록["해제후"] = [정리(아군["버프"]), 정리(아군["디버프"])]
    return 기록, 전_요약


