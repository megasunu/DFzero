def _탈_전투(보유=("탈",), 현재HP=None):
    """레벨 5 귀검사 1인 전투 - 반응 자동 사용(콜백 없음). (전투상태, 아군, 적, 대가)."""
    상태 = support.새게임([("", "귀검사")])
    c = 상태["파티"]["파티원"][0]
    support.성장(상태, c, 5)
    c["보유스킬"] += list(보유)
    gf.전투_시작(상태, ["고블린"], 레벨=1, 차수=1)
    support.반응_처리(상태)
    전투상태 = 상태["전투상태"]
    전투상태["반응선택"] = None
    p = next(x for x in 전투상태["참가자"] if x["진영"] == "아군")
    적 = next(x for x in 전투상태["참가자"] if x["진영"] == "적")
    최대 = stats.유효_최대HP(전투상태, p)
    p["현재HP"] = 최대 if 현재HP is None else 현재HP
    p["임시생명력"] = 0
    p["행동자원"]["반응행동"] = 1
    return 전투상태, p, 적, -(-최대 // 8)


def test_탈은_피해를_무효화하고_최대HP의_8분의1_올림만큼_체력을_깎는다():
    전투상태, p, 적, 대가 = _탈_전투()
    assert 대가 == -(-stats.유효_최대HP(전투상태, p) // 8) and 대가 >= 2
    전 = p["현재HP"]
    # 방어력/보호률을 거치는 보통 피해 - 대가는 그것과 무관하게 고정
    남은 = damage.피해_적용(전투상태, p, 대가 + 50, 공격자=적)
    assert 남은 == 0 and p["현재HP"] == 전 - 대가
    assert p["행동자원"]["반응행동"] == 0
    assert any(x.get("반응") == "탈" for x in 전투상태["로그"])
    # 전투당 1회
    p["행동자원"]["반응행동"] = 1
    전 = p["현재HP"]
    damage.피해_적용(전투상태, p, 대가 + 5, 피해감소무시=True, 공격자=적)
    assert p["현재HP"] == 전 - (대가 + 5)


def test_탈은_피해가_대가_이상이거나_쓰러질_때만_쓴다():
    전투상태, p, 적, 대가 = _탈_전투()
    전 = p["현재HP"]  # 대가보다 작고 쓰러지지 않는 피해에는 쓰지 않는다
    damage.피해_적용(전투상태, p, 대가 - 1, 피해감소무시=True, 공격자=적)
    assert p["현재HP"] == 전 - (대가 - 1) and p["행동자원"]["반응행동"] == 1
    전 = p["현재HP"]
    damage.피해_적용(
        전투상태, p, 대가, 피해감소무시=True, 공격자=적
    )  # 대가와 같으면 쓴다
    assert p["현재HP"] == 전 - 대가 and p["행동자원"]["반응행동"] == 0


def test_탈은_쓰러질_피해면_대가보다_작아도_쓰고_체력_1이_남는다():
    전투상태, p, 적, 대가 = _탈_전투(현재HP=1)
    damage.피해_적용(전투상태, p, 1, 피해감소무시=True, 공격자=적)
    assert p["현재HP"] == 1 and p["생존"] and p["행동자원"]["반응행동"] == 0
    전투상태, p, 적, 대가 = _탈_전투(현재HP=대가)
    damage.피해_적용(전투상태, p, 대가 + 10, 피해감소무시=True, 공격자=적)
    assert p["현재HP"] == 1 and p["생존"]


def test_탈은_임시생명력이_있거나_지속피해면_쓰지_않는다():
    전투상태, p, 적, 대가 = _탈_전투()
    p["임시생명력"] = 3
    전 = p["현재HP"]
    damage.피해_적용(전투상태, p, 대가 + 3, 피해감소무시=True, 공격자=적)
    assert p["현재HP"] == 전 - 대가 and p["행동자원"]["반응행동"] == 1
    p["임시생명력"] = 0
    전 = p["현재HP"]
    damage.피해_적용(전투상태, p, 대가 + 1, 피해감소무시=True)  # 공격자 없음 = 지속피해
    assert p["현재HP"] == 전 - (대가 + 1) and p["행동자원"]["반응행동"] == 1


def test_탈과_다른_피격_반응은_위상변화_탈_피해감소_순서로_묻고_자동이면_첫째를_쓴다():
    전투상태, p, 적, 대가 = _탈_전투(보유=("건가드", "탈", "위상 변화"))
    물은것 = []

    def 묻기(참가자, 후보, 상황):
        물은것.append(후보)
        return None  # 쓰지 않는다

    전투상태["반응선택"] = 묻기
    damage.피해_적용(전투상태, p, 대가 + 20, 피해감소무시=True, 공격자=적)
    이름들 = [n for n, _ in 물은것[0]]
    assert 이름들 == ["위상 변화", "탈", "건가드"]
    assert f"체력 {대가}" in dict(물은것[0])["탈"]
    # 자동 사용이면 대가 없는 위상 변화를 먼저 쓴다
    전투상태["반응선택"] = None
    전 = p["현재HP"]
    damage.피해_적용(전투상태, p, 대가 + 20, 피해감소무시=True, 공격자=적)
    assert p["현재HP"] == 전 and p.get("전투당_특성사용횟수", {}).get("탈", 0) == 0
    # 위상 변화가 없으면 탈이 건가드보다 먼저
    전투상태, p, 적, 대가 = _탈_전투(보유=("건가드", "탈"))
    전 = p["현재HP"]
    damage.피해_적용(전투상태, p, 대가 + 20, 피해감소무시=True, 공격자=적)
    assert p["현재HP"] == 전 - 대가 and p["전투당_특성사용횟수"]["탈"] == 1


