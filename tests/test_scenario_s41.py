"""S41 효과 갱신·상세 로그·마을 전환스킬 실전 (docs/scenarios.md, #74, #426, #429, #432).

기본 4인 파티를 레벨 9까지 키운다(귀검사는 버서커에 레벨 9 퍽 광기, 나머지는 기본 전직, 스킬 전부 습득).
**마을 [스킬]**로 프렌지를 MP 없이 켜고(#432) 선더랜드에 들어가 인카운트를 **실전으로** 치른다 - 프렌지는 전투에
켜진 채 들어가고 끝나도 켜져 있다. 전투 로그는 "자세하게"라 피해 계산의 데미지보너스가 출처 이름으로 남는다
("기타" 없음, #429). 크루세이더는 수호의 축복이 아직 걸려 있을 때(지속턴이 줄었을 때) 다시 걸어 - 같은 스킬이 건
버프는 겹치지 않고 지속턴만 새 값으로 돌아간다(#74 "같은 버프 재사용"). 전투 내내 행동마다 중첩 없는 상태이상이
한 참가자에게 둘 이상 붙지 않는지 본다(#426). 나머지 차례는 스킬 우선 정책(S2)이다.
"""

import pytest

from game.system import rng
import gameflow as gf
import scenario
import support

시드 = 0
_선더랜드 = "dungeon_01A_D05_thunderland"
_전직 = {
    "귀검사": "버서커",
    "격투가": "스트라이커",
    "거너": "레인저",
    "프리스트": "크루세이더",
}
_축복 = "수호의 축복"
전투수 = 6


def _광기_고르기(캐릭터, 후보):
    return next(((이름, 정의) for 이름, 정의 in 후보 if 이름 == "광기"), 후보[0])


def _축복_인스턴스(상태):
    """{(아군, 버프이름): [지속턴...]} - 수호의 축복이 건 버프만."""
    결과 = {}
    for a in gf.아군_목록(상태):
        for b in a["버프"]:
            if b.get("출처스킬") == _축복:
                결과.setdefault((a["이름"], b["이름"]), []).append(b.get("지속턴"))
    return 결과


def _중첩없는_상태이상_겹침(상태):
    정의 = 상태["전투상태"]["상태이상정의"]
    겹침 = []
    for p in 상태["전투상태"]["참가자"]:
        이름들 = [x["이름"] for x in p["상태이상"]]
        for 이름 in set(이름들):
            if 이름들.count(이름) > 1 and not (정의.get(이름) or {}).get("중첩"):
                겹침.append((p["이름"], 이름, 이름들.count(이름)))
    return 겹침


def _다시_걸기(상태, 기록):
    """크루세이더 차례가 시작되면 수호의 축복을 건다. 앞 차례에 건 것이 남아 있으면(지속턴이 줄었다) -
    같은 스킬이 건 버프는 겹치지 않고 지속턴만 새 값으로 늘어난다."""
    시전자 = gf.현재_턴_참가자(상태)
    전 = _축복_인스턴스(상태)
    if not gf.스킬_사용_가능여부(상태, 시전자, _축복)[0]:
        return
    gf.아군_스킬사용(상태, _축복)
    if not 전:  # 첫 시전 - 다음 차례에 다시 건다
        return
    후 = _축복_인스턴스(상태)
    assert set(전) <= set(후), (전, 후)
    for 키, 턴들 in 전.items():
        assert len(턴들) == 1 and len(후[키]) == 1, (키, 턴들, 후[키])  # 겹치지 않는다
        assert 후[키][0] > 턴들[0], (키, 턴들, 후[키])  # 지속턴만 새 값으로
    기록["재사용"] += 1
    기록["재사용_지속턴"].append(sorted({(전[k][0], 후[k][0]) for k in 전}))


def _전투(상태, 기록):
    support.반응_처리(상태)
    사용기록 = []
    for _ in range(300):
        assert not _중첩없는_상태이상_겹침(상태), _중첩없는_상태이상_겹침(상태)
        if gf.전투_종료됨(상태):
            break
        참가자 = gf.현재_턴_참가자(상태)
        if 참가자["진영"] == "아군" and 참가자["생존"]:
            if 참가자["원본"]["전직"] == "크루세이더":
                _다시_걸기(상태, 기록)
            if gf.전투_종료됨(상태):
                break
            scenario.스킬_우선_턴(상태, 사용기록)
        else:
            gf.턴_넘기기(상태)
    else:
        raise AssertionError("전투가 끝나지 않았다")
    return 상태["전투상태"]["종료"]


def _피해_출처(로그):
    """로그 항목 안의 타격/결과 목록까지 훑어 피해내역의 데미지보너스 출처 이름을 모은다."""
    이름들, 남은 = [], list(로그)
    while 남은:
        값 = 남은.pop()
        if isinstance(값, dict):
            if "피해내역" in 값:
                이름들 += [이름 for 이름, _ in 값["피해내역"]["추가"]]
            남은 += [v for k, v in 값.items() if k != "피해내역"]
        elif isinstance(값, list):
            남은 += 값
    return 이름들


@pytest.fixture
def 자세하게():
    원래 = gf.전투로그_방식()
    gf.전투로그_방식_설정("자세하게")
    yield
    gf.전투로그_방식_설정(원래)


@pytest.mark.scenario("S41")
def test_S41_효과갱신_상세로그_마을전환스킬_실전(자세하게, golden):
    rng.시드(시드)
    상태 = support.새게임()
    파티 = 상태["파티"]["파티원"]
    for c in 파티:
        support.성장(
            상태, c, 9, 전직=_전직[c["직업"]], 스킬습득=True, 퍽고르기=_광기_고르기
        )
    gf.파티_최대치로_회복(상태)
    [bs] = [c for c in 파티 if c["직업"] == "귀검사"]
    assert "프렌지" in bs["보유스킬"] and not bs.get("켜진특성")

    # 1) 마을 [스킬] - 전환스킬만 보이고, 프렌지를 MP 없이 켠다
    줄 = gf.전환스킬_목록(상태)
    assert [(z["캐릭터"]["캐릭터명"], z["스킬"]) for z in 줄] == [
        (bs["캐릭터명"], "프렌지")
    ], 줄
    MP = bs["현재MP"]
    assert gf.전환스킬_사용(상태, bs, "프렌지")["성공"]
    assert bs["켜진특성"] == ["프렌지"] and bs["현재MP"] == MP

    # 2) 선더랜드 실전 - 프렌지는 켜진 채, 버프 재사용·상태이상·상세 로그를 본다
    기록 = {"재사용": 0, "재사용_지속턴": [], "전투": []}
    출처 = []
    gf.던전_진입(상태, _선더랜드)
    for _ in range(전투수):
        적 = scenario.인카운트까지_걷기(상태)
        assert bs["켜진특성"] == ["프렌지"]
        assert gf.전환스킬_목록(상태) == []  # 전투 중에는 마을/던전 밖 전환을 못 쓴다
        종료 = _전투(상태, 기록)
        출처 += _피해_출처(상태["전투상태"]["로그"])
        assert gf.전투_결과_정리(상태) == 종료 == "아군승리", 종료
        scenario.보상_수령(상태)
        assert bs["켜진특성"] == ["프렌지"]  # 전투가 끝나도 켜진 채
        기록["전투"].append(적)
        gf.휴식(상태)
        gf.던전_진입(상태, _선더랜드)
    assert 기록["재사용"] >= 1, 기록
    assert len(출처) > 20 and "기타" not in 출처, sorted(set(출처))

    # 3) 마을로 돌아와 끈다
    상태["던전상태"] = None
    assert gf.전환스킬_사용(상태, bs, "프렌지")["성공"]
    assert bs["켜진특성"] == []
    기록["출처"] = sorted(set(출처))
    golden("scenario_S41_effect_refresh", 기록)
