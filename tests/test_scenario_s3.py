"""S3 성장 실전 (docs/scenarios.md).

새 게임에서 로리엔부터 포이즌 선더랜드까지 던전 6개(D01~D06)를 **실제 전투로** 돌파하며 성장한다.
보스를 처음 잡으면 플레이어 레벨이 오르고(D02 2, D04 4, D06 6), 캐릭터는 그 한도까지만 레벨업을 눌러
올릴 수 있다. 레벨 5에서 6으로 갈 때 전직을 고르고, 전직으로 늘어난 무기를 사서 끼운 뒤 한 번 더 싸운다.
레벨업 선택은 support.성장의 결정적 선택(스탯 몰아주기/첫 퍽)이고, 스킬은 골드를 채워 전부 배운다.
성장 단계별 수치와 전투 요약만 골든으로 비교한다. 전투는 S2의 스킬 우선 정책이다.
"""

import pytest

from game.system import rng
import gameflow as gf
import scenario
import support
from tests.support import 구현된_전직

직업들 = list(구현된_전직)
_던전 = {
    1: "dungeon_01A_D01_Lorien",
    2: "dungeon_01A_D02_Hollow_Lorien",
    3: "dungeon_01A_D03_mirkwood",
    4: "dungeon_01A_D04_Hollow_mirkwood",
    5: "dungeon_01A_D05_thunderland",
    6: "dungeon_01A_D06_poison_thunderland",
}
_엘븐가드 = "town_01A_T01_Elvengard"
_헨돈마이어 = "town_01A_T02_hendonmyre"


def _수치(상태, 캐릭터):
    return {
        "레벨": 캐릭터["레벨"],
        "직업표시": gf.캐릭터_직업표시(캐릭터),
        "최대HP": gf.캐릭터_최대HP(상태, 캐릭터),
        "최대MP": gf.캐릭터_최대MP(상태, 캐릭터),
        "특성수": len(캐릭터["보유특성"]),
        "스킬수": len(캐릭터["보유스킬"]),
        "가용무기": list(캐릭터["가용무기"]),
    }


class _패배(Exception):
    pass


class _시나리오:
    def __init__(self, 직업, 시드):
        rng.시드(시드)
        파티 = [직업] + [j for j in 직업들 if j != 직업][:3]
        self.상태 = support.새게임([("", j) for j in 파티])
        self.기록 = {"전투": [], "성장": [], "진행도": [], "패배": [], "시도": {}}

    # -- 전투 -------------------------------------------------------
    def 전투처리(self, 라벨):
        def _처리(상태):
            적 = [e["이름"] for e in gf.적_목록(상태)]
            종료 = scenario.스킬_실전(상태, [])
            self.기록["전투"].append(
                {
                    "라벨": 라벨,
                    "적": 적,
                    "종료": 종료,
                    "라운드": 상태["전투상태"]["라운드"],
                    "아군HP": scenario.전투중_아군_HP(상태),
                }
            )
            if 종료 != "아군승리":
                # 화면과 같다: 전멸하면 HP/MP를 채워 마을로 돌려보낸다(별도 페널티 없음)
                assert gf.전투_결과_정리(상태) == 종료 == "적승리"
                gf.휴식(상태)
                상태["던전상태"] = None
                raise _패배(f"{라벨} {적}")

        return _처리

    def _강제(self, 라벨):
        def _처리(상태):
            적 = [e["이름"] for e in gf.적_목록(상태)]
            support.강제_승리(상태)
            self.기록["전투"].append({"라벨": 라벨, "적": 적, "종료": "강제 승리"})

        return _처리

    def 보스(self, 던전번호, 실전=True):
        라벨 = f"D{던전번호:02d}" + ("" if 실전 else " (강제)")
        처리 = self.전투처리(라벨) if 실전 else self._강제(라벨)
        결과, _ = support.보스_처치(self.상태, 전투처리=처리)
        assert 결과 == "아군승리"
        self.기록["진행도"].append((라벨, self.상태["진행도"]["플레이어레벨"]))

    def 나가기(self, 연결맵, 라벨, 실전=True):
        처리 = self.전투처리(라벨) if 실전 else self._강제(라벨 + " (강제)")
        support.연결로_나가기(self.상태, 연결맵, 전투처리=처리)

    def 원정(self, 이름, 진행, 최대시도=40):
        """진행()을 해 본다. 지면 마을로 돌아와 쉬고 처음부터 다시 한다(성공할 때까지).
        시도 횟수를 기록한다 - 레벨 한도 안의 성장만으로 갈 수 있어야 하므로 최대시도 안에 이겨야 한다."""
        for 시도 in range(1, 최대시도 + 1):
            try:
                진행()
            except _패배 as e:
                self.기록["패배"].append([이름, 시도, str(e)])
                continue
            self.기록["시도"][이름] = 시도
            return
        raise AssertionError(
            f"{이름}: {최대시도}번 시도해도 못 깼다 {self.기록['패배'][-1]}"
        )

    # -- 성장 -------------------------------------------------------
    def 레벨업(self, 목표레벨, 전직=False):
        """플레이어 레벨 한도 안에서 파티 전원을 목표레벨까지 올리고 스킬을 전부 배운다."""
        상태 = self.상태
        PL = 상태["진행도"]["플레이어레벨"]
        assert 목표레벨 <= PL
        단계 = []
        for c in 상태["파티"]["파티원"]:
            전 = _수치(상태, c)
            support.성장(
                상태,
                c,
                목표레벨,
                전직=구현된_전직[c["직업"]] if 전직 else None,
                스킬습득=True,
            )
            assert (
                상태["진행도"]["플레이어레벨"] == PL
            )  # 레벨업이 플레이어 레벨을 건드리지 않는다
            후 = _수치(상태, c)
            assert 후["레벨"] == 목표레벨
            assert 후["최대HP"] > 전["최대HP"] and 후["최대MP"] >= 전["최대MP"]
            assert 후["스킬수"] >= 전["스킬수"] and set(전["가용무기"]) <= set(
                후["가용무기"]
            )
            assert c["전직"] == (구현된_전직[c["직업"]] if 전직 else None)
            단계.append({c["캐릭터명"]: 후})
        self.기록["성장"].append({"플레이어레벨": PL, "목표": 목표레벨, "수치": 단계})
        gf.파티_최대치로_회복(상태)

    def 한도_확인(self, 기대):
        """모두 레벨업 가능/불가가 기대와 같은지(플레이어 레벨 한도)."""
        assert [
            gf.캐릭터_레벨업_가능(self.상태, c) for c in self.상태["파티"]["파티원"]
        ] == [기대] * len(self.상태["파티"]["파티원"])


# 직업마다 끝까지 이기는 시드를 골라 둔다(레벨 1 파티는 로리엔 안쪽 보스에서 3번 중 1번쯤 진다 -
# 전투 규칙이 바뀌어 지면 이 표를 다시 고르고 이유를 커밋에 적는다.
# 거너 0 -> 1(2026-10-08): 종족 잡템 드랍으로 난수 순서가 바뀌어 시드 0은 로리엔 원정 첫 시도가
# 두 번째 보스까지 깬 뒤 돌아오는 길에 져서, 재시도의 "플레이어 레벨 1" 단언에 걸렸다)
시드 = {"귀검사": 0, "격투가": 0, "거너": 1, "마법사": 0, "프리스트": 0}


def 진행(직업, 시드값):
    s = _시나리오(직업, 시드값)
    상태 = s.상태
    PL = lambda: 상태["진행도"]["플레이어레벨"]  # noqa: E731

    # 로리엔 -> 로리엔 안쪽: 처음엔 아무도 레벨업할 수 없다. 안쪽 보스가 플레이어 레벨 2를 연다
    s.한도_확인(False)

    def 로리엔():
        gf.던전_진입(상태, _던전[1])
        전 = PL()
        s.보스(1)
        # 로리엔 보스는 플레이어 레벨을 올리지 않는다(재시도면 앞 시도에서 이미 2일 수 있다)
        assert PL() == 전
        s.나가기(_던전[2], "D01 -> D02 연결로")
        s.보스(2)
        s.나가기(_엘븐가드, "D02 -> 엘븐가드 연결로")

    s.원정("로리엔", 로리엔)
    assert PL() == 2
    s.한도_확인(True)
    gf.휴식(상태)
    s.레벨업(2)
    s.한도_확인(False)

    # 헨돈마이어 개방 -> 머크우드 -> 깊숙한곳: 플레이어 레벨 4
    gf.마을_이동(상태, "헨돈마이어")

    def 머크우드():
        # D04는 레벨 2 파티가 연속으로 깨는 비율이 100번에 2번이라 이 시나리오에서는 강제 승리로 건너뛴다
        # (이슈 #162, #41 후속)
        gf.던전_진입(상태, _던전[3])
        s.보스(3)
        s.나가기(_던전[4], "D03 -> D04 연결로")
        s.보스(4, 실전=False)
        s.나가기(_헨돈마이어, "D04 -> 헨돈마이어 연결로", 실전=False)

    s.원정("머크우드", 머크우드)
    assert PL() == 4
    gf.휴식(상태)
    s.레벨업(4)

    # 선더랜드 -> 마을에서 쉬고 (다시 들어와 숏컷이 열린 뒤) 포이즌 선더랜드: 플레이어 레벨 6.
    # 키놀이 실제로 싸우면서(2026-10-13) 쉬지 않고 D06까지 이어 가면 40번 안에 못 깨게 되어,
    # 플레이어처럼 D05 보스 뒤에 쉬고 따로 원정한다(둘 다 실전 그대로).
    def 선더랜드():
        gf.던전_진입(상태, _던전[5])
        s.보스(5)

    s.원정("선더랜드", 선더랜드)
    gf.휴식(상태)

    def 포이즌_선더랜드():
        gf.던전_진입(상태, _던전[5])  # 다시 들어오면 숏컷이 열려 있다
        s.나가기(_던전[6], "D05 -> D06 연결로")
        s.보스(6)
        s.나가기(_던전[5], "D06 -> D05 연결로")
        s.나가기(_헨돈마이어, "D05 -> 헨돈마이어 연결로")

    s.원정("포이즌 선더랜드", 포이즌_선더랜드)
    assert PL() == 6
    gf.휴식(상태)

    # 레벨 5까지 올린 뒤 6레벨은 전직이 필요하다
    s.레벨업(5)
    assert all(gf.캐릭터_전직_필요(c) for c in 상태["파티"]["파티원"])
    전직전무기 = [set(c["가용무기"]) for c in 상태["파티"]["파티원"]]
    s.레벨업(6, 전직=True)
    assert not any(gf.캐릭터_전직_필요(c) for c in 상태["파티"]["파티원"])
    s.한도_확인(False)  # 플레이어 레벨 6 = 상한. 6레벨 이후는 보스를 더 잡아야 한다

    # 전직으로 늘어난 무기를 사서 끼운다
    샀음 = {}
    for 번호, c in enumerate(상태["파티"]["파티원"]):
        새종류 = set(c["가용무기"]) - 전직전무기[번호]
        후보 = sorted(
            (n, i)
            for n, i in 상태["상점카탈로그"]["장비"]["무기"].items()
            if i["레어도"] in ("커먼", "언커먼") and i["타입"] in 새종류
        )  # 치트와 봉인 레어는 사지 않는다
        if not 후보:
            continue
        이름, 아이템 = 후보[0]
        상태["소지품"]["골드"] += 아이템["가격"]
        gf.상점_구매(상태, "장비", "무기", 이름, 1)
        gf.장비_교체(상태, c, "무기", 이름)
        assert gf.캐릭터_장착아이템(상태, c, "무기")["타입"] == 아이템["타입"]
        샀음[c["캐릭터명"]] = 이름
    s.기록["새_무기"] = 샀음

    # 전직한 파티로 한 번 더 - 새 레벨/스킬/무기로 실전
    def 전직후():
        gf.던전_진입(상태, _던전[5])
        scenario.인카운트까지_걷기(상태)
        s.전투처리("전직 후 D05 인카운트")(상태)
        assert gf.전투_결과_정리(상태) == "아군승리"

    s.원정("전직 후 인카운트", 전직후)

    return s.기록


@pytest.mark.scenario("S3")
@pytest.mark.parametrize("직업", 직업들)
def test_S3_성장_실전(직업, golden):
    golden(f"scenario_S3_growth_{직업}", 진행(직업, 시드[직업]))
