"""S18 봉절 실전 - 봉절이 실제 진행에서 이어진다 (docs/scenarios.md).

기본 4인 파티를 레벨 4까지 키우며 3->4 퍽획득에서 거너가 "봉절"을 고른다(나머지는 결정적 첫 퍽).
로리엔(D01)에서 인카운트 한 번을 [자동전투]로 **실제로** 치른 뒤, 던전 [스킬]로 봉절을 써(MP 5) 14걸음
(10 + 레벨 4) 동안 인카운트도 걸음수도 없고 마지막 걸음에 풀리는지, 풀린 뒤 다시 인카운트가 나와 실전을
치르는지 본다. 다시 써서 남은 걸음을 MP 없이 푸는 것, 던전 안 저장/불러오기 뒤 남은 걸음, 던전을 다시
들어가면 끝나는 것도 본다. 규칙의 값은 tests/test_dungeon_skills.py가 본다.
"""

import pytest

from game.system import rng
import gameflow as gf
import scenario
import support

로리엔 = "dungeon_01A_D01_Lorien"
시드 = 0
_방향 = ("오른쪽", "아래", "왼쪽", "위")


def _퍽고르기(캐릭터, 후보):
    if 캐릭터["직업"] == "거너":
        return next((n, d) for n, d in 후보 if n == "봉절")
    return 후보[0]


def _봉절_걷기(상태):
    """봉절이 풀릴 때까지 걷는다. 걸은 수와 그동안의 결과를 돌려준다."""
    방향, 걸음, 결과들 = 0, 0, []
    while True:
        결과 = gf.던전_이동(상태, _방향[방향])
        if 결과["결과"] != "이동":
            assert 결과["결과"] != "전투시작", 결과
            방향 = (방향 + 1) % len(_방향)
            continue
        걸음 += 1
        결과들.append(결과)
        if 결과.get("봉절해제"):
            return 걸음, 결과들
        assert 걸음 < 100


def _싸우기(상태):
    적 = scenario.인카운트까지_걷기(상태)
    종료 = scenario.실전(상태)
    assert gf.전투_결과_정리(상태) == 종료 == "아군승리"
    scenario.보상_수령(상태)
    return 적


@pytest.mark.scenario("S18")
def test_S18_봉절_실전(golden, 임시_세이브폴더):
    rng.시드(시드)
    상태 = support.새게임()
    파티 = 상태["파티"]["파티원"]
    for 캐릭터 in 파티:
        support.성장(상태, 캐릭터, 4, 퍽고르기=_퍽고르기)
    거너 = next(c for c in 파티 if c["직업"] == "거너")
    assert "봉절" in 거너["보유스킬"]
    gf.파티_최대치로_회복(상태)

    gf.던전_진입(상태, 로리엔)
    첫전투 = _싸우기(상태)

    MP = 거너["현재MP"]
    결과 = gf.던전스킬_사용(상태, 거너, "봉절")
    assert 결과["성공"] and 거너["현재MP"] == MP - 5, 결과
    걸음수 = 상태["던전상태"]["걸음수"]
    걸음, 결과들 = _봉절_걷기(상태)
    assert 걸음 == 10 + 거너["레벨"] == 14
    assert all(r.get("인카운트") is None for r in 결과들)
    assert 상태["던전상태"]["걸음수"] == 걸음수  # 걸음수도 오르지 않았다
    둘째전투 = _싸우기(상태)  # 풀린 뒤에는 다시 적이 나온다

    gf.던전스킬_사용(상태, 거너, "봉절")
    assert any(gf.던전_이동(상태, d)["결과"] == "이동" for d in _방향)  # 한 걸음
    남은 = 상태["던전상태"]["봉절걸음"]
    assert 0 < 남은 < 14
    gf.게임_저장(상태, 1)
    상태 = gf.게임_불러오기(1)
    거너 = next(c for c in 상태["파티"]["파티원"] if c["직업"] == "거너")
    assert 상태["던전상태"]["봉절걸음"] == 남은
    MP = 거너["현재MP"]
    풀기 = gf.던전스킬_사용(상태, 거너, "봉절")  # 남아 있을 때 다시 쓰면 MP 없이 풀린다
    assert 풀기["성공"] and 거너["현재MP"] == MP
    assert 상태["던전상태"]["봉절걸음"] == 0

    gf.던전스킬_사용(상태, 거너, "봉절")
    gf.던전_진입(상태, 로리엔)  # 던전을 나갔다 들어오면 끝난다
    assert 상태["던전상태"]["봉절걸음"] == 0
    golden(
        "scenario_S18_seal",
        {
            "첫전투": 첫전투,
            "둘째전투": 둘째전투,
            "문구": [결과["문구"], 풀기["문구"]],
        },
    )
