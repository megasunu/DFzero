# 측정은 플레이어가 상황을 보고 승률이 높은 행동을 고르는 것을 흉내 낸다(행동 승률표).
# 1) 배우기: 측정할 던전에서 먼저 완전히 무작위로(탐험률 1.0) 측정_학습판수 판을 싸워, (상황, 행동)마다
#    그 행동을 고른 전투의 승패를 센다(몬테카를로 - 전투 결과를 그 전투에서 고른 행동 모두에 준다).
# 2) 재기: 탐험률 0.3 - 30%는 무작위, 70%는 표에서 승률이 가장 높은 행동. 재는 동안에도 계속 센다.
# 3) 퍽(사용자 지정 2026-10-16, 앞으로의 모든 퍽 선택): 측정_파티_준비에 정책을 넘기면 퍽도 같은 탐험률로 고른다 -
#    무작위 아니면 (직업, 레벨, 퍽) 승률표의 최고. 그 판의 전투가 끝날 때마다 고른 퍽 모두에 승패를 센다.
# 기록은 저장하지 않는다 - 밸런스를 바꾸면 낡으므로 측정마다 새로 배운다.

측정_탐험률 = 0.3
측정_학습판수 = 300
_표적종류 = ("HP최저", "보스", "회복", "무작위")


def _구간(값, 최대):
    if not 최대:
        return 0
    비율 = 값 / 최대
    return 0 if 비율 <= 1 / 3 else 1 if 비율 <= 2 / 3 else 2


def _회복하는_적(e):
    return any(
        p.get("타입") == "회복패턴" for p in (e["원본"].get("패턴") or {}).values()
    )


def _표적(상태, 종류, 스킬데이터=None):
    """표적 종류 -> 실제 적(없으면 None). 무작위는 고를 때마다 굴린다.
    스킬데이터가 있으면 그 스킬로 지정할 수 없는 적(하단공격 대 공중에뜸)은 빼고 고른다."""
    적들 = _살아있는_적(상태)
    if 스킬데이터 is not None:
        적들 = [e for e in 적들 if not gf.스킬_지정불가인가(상태, 스킬데이터, e)]
    if not 적들:
        return None
    if 종류 == "HP최저":
        return 적들[0]
    if 종류 == "보스":
        return next((e for e in 적들 if e["원본"].get("칭호") == "보스"), None)
    if 종류 == "회복":
        return next((e for e in 적들 if _회복하는_적(e)), None)
    return random.choice(적들)


class 학습정책:
    """(상황, 행동) -> [승, 전] 표로 행동을 고르는 측정용 플레이어. 상황은 직업, 자기 HP/MP 구간,
    다친 아군이 있나, 남은 적 수, 보스가 살아 있나. 행동은 ("일반공격"|스킬이름, 표적종류|None).
    퍽은 따로 (직업, 레벨, 퍽) -> [승, 전] 표(퍽표)로 고른다. 이번퍽은 지금 판에서 고른 퍽(준비할 때 새로 시작)."""

    def __init__(self, 탐험률=1.0):
        self.탐험률 = 탐험률
        self.표 = {}
        self.이번전투 = []
        self.퍽표 = {}
        self.이번퍽 = []

    def 퍽_고르기(self, 캐릭터, 후보):
        """레벨업 퍽 후보 [(이름, 정의)] 중 하나 - 탐험률만큼 무작위, 나머지는 퍽표의 승률 최고."""
        직업, 레벨 = 캐릭터["직업"], 캐릭터["레벨"] + 1
        if random.random() < self.탐험률:
            고름 = random.choice(후보)
        else:
            최고 = max(self._퍽승률(직업, 레벨, p[0]) for p in 후보)
            고름 = random.choice(
                [p for p in 후보 if self._퍽승률(직업, 레벨, p[0]) == 최고]
            )
        self.이번퍽.append((직업, 레벨, 고름[0]))
        return 고름

    def _퍽승률(self, 직업, 레벨, 퍽):
        승, 전 = self.퍽표.get((직업, 레벨, 퍽), (0, 0))
        return (승 + 1) / (전 + 2)  # 처음 보는 퍽은 0.5

    def 상황(self, 상태, 참가자):
        원본 = 참가자["원본"]
        아군 = [a for a in gf.아군_목록(상태) if a["생존"]]
        적들 = _살아있는_적(상태)
        return (
            원본.get("직업"),
            _구간(참가자["현재HP"], gf.캐릭터_최대HP(상태, 원본)),
            _구간(참가자["현재MP"], gf.캐릭터_최대MP(상태, 원본)),
            any(a["현재HP"] * 2 <= gf.캐릭터_최대HP(상태, a["원본"]) for a in 아군),
            min(len(적들), 4),
            any(e["원본"].get("칭호") == "보스" for e in 적들),
        )

    def 후보(self, 상태, 참가자):
        """지금 할 수 있는 행동 [(키, 실행)]. 적을 노리는 행동은 있는 표적 종류마다 하나씩."""
        후보 = []
        적들 = _살아있는_적(상태)
        있는표적 = [k for k in _표적종류 if _표적(상태, k) is not None] if 적들 else []
        for 이름 in 참가자["원본"]["보유스킬"]:
            if not gf.스킬_사용_가능여부(상태, 참가자, 이름)[0]:
                continue
            if not _쓸_가치가_있나(상태, 참가자, 이름, []):
                continue
            타겟 = gf.스킬_실제_타겟(상태, 상태["스킬데이터모음"][이름])
            if 타겟 in _정책_제외_타겟:
                continue
            if 타겟 and 타겟.startswith("적"):
                데이터 = 상태["스킬데이터모음"][이름]
                for k in 있는표적:
                    if _표적(상태, k, 데이터) is not None:
                        후보.append(((이름, k), self._스킬실행(이름, k)))
                continue
            인수 = _스킬_인수(상태, 참가자, 이름)
            if 인수 is not None:
                후보.append(((이름, None), self._스킬실행(이름, None, 인수)))
        if 참가자["행동자원"].get("일반행동", 0) > 0:
            for k in 있는표적:
                후보.append((("일반공격", k), self._일반공격(k)))
        return 후보

    @staticmethod
    def _스킬실행(이름, 표적종류, 인수=None):
        def 실행(상태):
            if 표적종류 is None:
                gf.아군_스킬사용(상태, 이름, **(인수 or {}))
            else:
                데이터 = 상태["스킬데이터모음"][이름]
                gf.아군_스킬사용(상태, 이름, 중심대상=_표적(상태, 표적종류, 데이터))

        return 실행

    @staticmethod
    def _일반공격(표적종류):
        def 실행(상태):
            gf.아군_일반공격(상태, _표적(상태, 표적종류))

        return 실행

    def _승률(self, 상황, 키):
        승, 전 = self.표.get((상황, 키), (0, 0))
        return (승 + 1) / (전 + 2)  # 처음 보는 행동은 0.5

    def 고르기(self, 상태, 참가자):
        후보 = self.후보(상태, 참가자)
        if not 후보:
            return None
        상황 = self.상황(상태, 참가자)
        if random.random() < self.탐험률:
            키, 실행 = random.choice(후보)
        else:
            최고 = max(self._승률(상황, 키) for 키, _ in 후보)
            키, 실행 = random.choice(
                [(k, f) for k, f in 후보 if self._승률(상황, k) == 최고]
            )
        self.이번전투.append((상황, 키))
        return 실행

    def 턴(self, 상태):
        """아군 한 차례: 할 수 있는 행동이 없을 때까지 고르고 실행한 뒤 턴을 넘긴다."""
        시전자 = gf.현재_턴_참가자(상태)
        전투상태 = 상태["전투상태"]
        for _ in range(20):  # 무한 반복 방지(행동이 안 줄어드는 버그가 있어도 멈춘다)
            if 전투상태["종료"] is not None or not 시전자["생존"]:
                return
            실행 = self.고르기(상태, 시전자)
            if 실행 is None:
                break
            실행(상태)
        else:
            raise AssertionError("한 차례에 20번 넘게 행동했다 - 행동이 줄지 않는다")
        if 전투상태["종료"] is None:
            gf.턴_넘기기(상태)

    def 전투끝(self, 종료):
        이김 = 종료 in ("아군승리", "적도망")
        for 키 in set(self.이번전투):
            칸 = self.표.setdefault(키, [0, 0])
            칸[0] += 이김
            칸[1] += 1
        self.이번전투 = []
        for 키 in set(self.이번퍽):  # 퍽은 판이 끝날 때까지 남긴다 - 다음 전투에도 센다
            칸 = self.퍽표.setdefault(키, [0, 0])
            칸[0] += 이김
            칸[1] += 1


def 퍽_승률표(정책):
    """{(직업, 레벨): [(퍽, 승, 전, 승률)]} - 승률 높은 순. 측정 결과를 보여 줄 때 쓴다."""
    표 = {}
    for (직업, 레벨, 퍽), (승, 전) in 정책.퍽표.items():
        표.setdefault((직업, 레벨), []).append((퍽, 승, 전, 승 / 전 if 전 else 0.0))
    for 줄 in 표.values():
        줄.sort(key=lambda x: (-x[3], -x[2], x[0]))
    return 표


def 측정_학습(한판, 학습판수=측정_학습판수):
    """한판(정책) - 측정할 던전의 한 판(측정_실전에 정책을 넘기는 함수) - 을 무작위로 학습판수 번 돌려 배운 뒤,
    탐험률을 측정_탐험률로 낮춘 정책을 돌려준다. 이 정책으로 같은 한판을 돌려 잰다."""
    정책 = 학습정책(탐험률=1.0)
    for _ in range(학습판수):
        한판(정책)
    정책.탐험률 = 측정_탐험률
    return 정책
