"""S36 런처·메카닉 실전 - 6레벨 특성, 8레벨 버프, 골드 스킬, 설치소환수(랜드러너/카운트다운) (docs/scenarios.md).

거너 둘(런처, 메카닉)이 든 4인 파티를 레벨 9까지 키운다(나머지는 기본 전직, 스킬 전부 습득). 타우 아미·루가루·고블린
(레벨 15 차수 3 - 던전 인카운트는 1~2라운드에 끝나 라운드 끝 효과가 나오지 않는다)과 **실제 전투로** 싸운다. 런처는 미라클 비전이 없으면 걸고 골드 스킬(슈타이어 대전차포·레이저 라이플·양자폭탄)을
가장 덜 쓴 것부터 하나 쓴 뒤 남은 일반행동으로 일반공격한다. 메카닉은 로보틱스가 없으면 걸고, 1라운드에 카운트다운·
랜드러너·메카드롭을 가장 덜 쓴 것부터 하나, 2·3라운드에 트랜스폼(G-2, G-3), 4라운드부터는 랜드러너를 붙이고 바로
로봇전폭을 쓴다(MP가 4라운드까지 남게). 다른 두 파티원은 3라운드까지 차례를 넘기기만 하고(적이 먼저 쓰러져 라운드 끝 효과가 안 나오지 않게) 4라운드부터
스킬 우선 정책으로 싸운다.
랜드러너·카운트다운이 라운드 끝에 실제로 자폭하는지, 양자폭탄 피해가 라운드 끝에 내성굴림과 함께 들어가는지, 레이저
라이플이 밀린 차례에 쏘는지, G-1/G-2/G-3 형태 공격과 로봇전폭 자폭, 회심의 랜드러너 반응이 실제로 나오는지 본다.
수치 규칙은 tests/test_job_launcher.py, tests/test_job_mechanic.py가 값으로 검사한다.
"""

import pytest

from game.system import rng
import gameflow as gf
import scenario
import support
from tests.support import 구현된_전직

적들 = ["타우 아미", "루가루", "고블린"]
시드 = 0
파티구성 = [("", "거너"), ("", "거너"), ("", "귀검사"), ("", "프리스트")]
런처골드 = ("슈타이어 대전차포", "레이저 라이플", "양자폭탄")
메카골드 = ("카운트다운", "랜드러너", "메카드롭")


def _쓰기(상태, p, 이름, 기록, 누적, 대상=None):
    if not gf.스킬_사용_가능여부(상태, p, 이름)[0]:
        return False
    데이터 = 상태["스킬데이터모음"][이름]
    if gf.스킬_실제_타겟(상태, 데이터) in ("자신", "적전체"):
        대상 = None
    gf.아군_스킬사용(상태, 이름, 중심대상=대상)
    기록[이름] = 기록.get(이름, 0) + 1
    누적[이름] = 누적.get(이름, 0) + 1
    return True


def _일반공격(상태, p):
    전투상태 = 상태["전투상태"]
    while 전투상태["종료"] is None and p["생존"]:
        적들 = scenario._살아있는_적(상태)
        if not 적들 or p["행동자원"].get("일반행동", 0) <= 0:
            break
        gf.아군_일반공격(상태, 적들[0])
    if 전투상태["종료"] is None:
        gf.턴_넘기기(상태)


def _골드(상태, p, 목록, 기록, 누적):
    """골드 스킬을 (전투 전체에서) 가장 덜 쓴 것부터 하나."""
    for 이름 in sorted(목록, key=lambda n: 누적.get(n, 0)):
        적들 = scenario._살아있는_적(상태)
        if 적들 and _쓰기(상태, p, 이름, 기록, 누적, 적들[0]):
            return


def _런처_턴(상태, p, 기록, 누적):
    if not any(b["이름"] == "미라클 비전" for b in p["버프"]):
        _쓰기(상태, p, "미라클 비전", 기록, 누적)
    _골드(상태, p, 런처골드, 기록, 누적)
    _일반공격(상태, p)


def _메카닉_턴(상태, p, 기록, 누적):
    전투상태 = 상태["전투상태"]
    if not any(b["이름"] == "로보틱스" for b in p["버프"]):
        _쓰기(상태, p, "로보틱스", 기록, 누적)
    적들 = scenario._살아있는_적(상태)
    라운드 = 전투상태["라운드"]
    if 라운드 >= 4:  # 랜드러너를 붙이고 바로 로봇전폭
        if 적들:
            _쓰기(상태, p, "랜드러너", 기록, 누적, 적들[0])
        if 전투상태.get("설치소환수"):
            _쓰기(상태, p, "로봇전폭", 기록, 누적)
    elif 라운드 == 1:  # 골드 스킬 하나, G-1로 턴을 끝낸다(MP를 4라운드까지 남긴다)
        _골드(상태, p, 메카골드, 기록, 누적)
    elif 적들:  # 2·3라운드에 G-2·G-3
        _쓰기(상태, p, "트랜스폼", 기록, 누적, 적들[0])
    _일반공격(상태, p)


def _전투(상태, 런처, 메카닉, 기록, 누적):
    support.반응_처리(상태)
    for _ in range(400):
        if gf.전투_종료됨(상태):
            break
        참가자 = gf.현재_턴_참가자(상태)
        if 참가자["진영"] == "아군" and 참가자["생존"]:
            if 참가자["원본"] is 런처:
                _런처_턴(상태, 참가자, 기록, 누적)
            elif 참가자["원본"] is 메카닉:
                _메카닉_턴(상태, 참가자, 기록, 누적)
            elif 상태["전투상태"]["라운드"] >= 4:
                scenario.스킬_우선_턴(상태, [])
            else:  # 3라운드까지는 다른 파티원이 적을 먼저 쓰러뜨려 라운드 끝 효과가 안 나오지 않게
                gf.턴_넘기기(상태)
        else:
            gf.턴_넘기기(상태)
    else:
        raise AssertionError("전투가 끝나지 않았다")
    기록["라운드"] = 상태["전투상태"]["라운드"]
    로그 = [항목 for 항목 in 상태["전투상태"]["로그"] if isinstance(항목, dict)]

    def 친_횟수(스킬):
        return sum(1 for 항목 in 로그 if 항목.get("스킬") == 스킬 and 항목.get("타격"))

    for 스킬 in ("랜드러너 자폭", "카운트다운 자폭", "레이저 라이플", "G-1", "G-3"):
        기록[f"{스킬} 타격"] = 친_횟수(스킬)
    기록["G-2 타격"] = 친_횟수("트랜스폼 : G-2")
    기록["양자폭탄 라운드끝"] = sum(
        1 for 항목 in 로그 if 항목.get("스킬") == "양자폭탄" and "난이도" in 항목
    )
    기록["로봇전폭 자폭"] = sum(
        1
        for 항목 in 로그
        if 항목.get("스킬") == "로봇전폭" and "개가 자폭했다" in str(항목.get("비고"))
    )
    기록["회심의 랜드러너"] = sum(
        1 for 항목 in 로그 if 항목.get("반응") == "회심의 랜드러너"
    )
    return 상태["전투상태"]["종료"]


@pytest.mark.scenario("S36")
def test_S36_런처_메카닉_실전(golden):
    rng.시드(시드)
    상태 = support.새게임(파티구성)
    런처, 메카닉, 귀, 프 = 상태["파티"]["파티원"]
    support.성장(상태, 런처, 9, 전직="런처", 스킬습득=True)
    support.성장(상태, 메카닉, 9, 전직="메카닉", 스킬습득=True)
    for c in (귀, 프):
        support.성장(상태, c, 9, 전직=구현된_전직[c["직업"]], 스킬습득=True)
    gf.파티_최대치로_회복(상태)
    assert gf.캐릭터_직업표시(런처).startswith("런처")
    assert gf.캐릭터_직업표시(메카닉).startswith("메카닉")
    assert {"APG-63", "중화기 마스터리", "듀얼 트리거"} <= set(런처["보유특성"])
    assert {"트랜스포메이션", "파이어볼트"} <= set(메카닉["보유특성"])

    전투들 = []
    누적 = {}
    볼것 = (
        "랜드러너 자폭 타격",
        "카운트다운 자폭 타격",
        "레이저 라이플 타격",
        "양자폭탄 라운드끝",
        "G-1 타격",
        "G-2 타격",
        "G-3 타격",
        "로봇전폭 자폭",
        "회심의 랜드러너",
        "메카드롭",
        "슈타이어 대전차포",
    )
    for _ in range(10):
        gf.파티_최대치로_회복(상태)
        gf.휴식(상태)  # 레벨 8 버프는 휴식당 1회
        gf.전투_시작(상태, 적들, 레벨=15, 차수=3)
        기록 = {}
        종료 = _전투(상태, 런처, 메카닉, 기록, 누적)
        assert gf.전투_결과_정리(상태) == 종료 == "아군승리"
        전투들.append(기록)
        if all(sum(b.get(k, 0) for b in 전투들) for k in 볼것):
            break

    합계 = {k: sum(b.get(k, 0) for b in 전투들) for k in 볼것}
    assert all(합계.values()), 전투들
    assert all(b.get("미라클 비전", 0) <= 1 for b in 전투들), 전투들  # 휴식당 1회
    assert all(b.get("로보틱스", 0) <= 1 for b in 전투들), 전투들
    golden("scenario_S36_launcher_mechanic", 전투들)
