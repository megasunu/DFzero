"""S33 검귀 실전 - 6레벨 특성(청혈투귀·검귀의 도 마스터리), 8레벨 귀혼일체, 골드 스킬 (docs/scenarios.md, #330 #332).

귀검사가 든 4인 파티를 레벨 9까지 키운다(귀검사는 5->6에 검귀, 나머지는 기본 전직, 스킬 전부 습득).
검귀는 레벨 2에 고른 무기 마스터리를 6레벨에 잃고, 9레벨 퍽에서도 무기 마스터리를 고를 수 없다.
도(예리한 카타나)를 들고 선더랜드(D05)에 들어가 인카운트를 **실제 전투로** 치른다. 검귀는 차례마다 귀혼일체가
없으면 걸고(행동·MP 소모 없음, 휴식당 1회), 라운드+전투 번호(0부터)가 홀수면 원귀 -> 합격(원귀가 낸 패턴에 따라 이혼일섬/월령참),
짝수면 귀연참 : 극, 남은 행동(추가행동 포함)은 귀연참(MP가 모자라면 일반공격)을 쓴다. 귀혼일체가 MP를
쓰지 않는지, 합격이 원귀의 패턴을 따르는지, 치명타 범위 19(청혈투귀)로 19 눈 치명타가 실제로 나는지 본다.
수치 규칙은 tests/test_job_ghostblade.py가 값으로 검사한다.
"""

import pytest

from game.system import rng
import gameflow as gf
import scenario
import support
from tests.support import 구현된_전직

선더랜드 = "dungeon_01A_D05_thunderland"
시드 = 0
파티구성 = [("", "귀검사"), ("", "격투가"), ("", "거너"), ("", "프리스트")]
전직표 = dict(구현된_전직, 귀검사="검귀")
도 = "예리한 카타나"
끝날조건 = (
    "19눈치명타",
    "합격 : 이혼일섬",
    "합격 : 월령참",
    "귀연참",
    "귀연참 : 극",
)
마스터리5종 = [
    "소검 마스터리",
    "도 마스터리",
    "둔기 마스터리",
    "대검 마스터리",
    "광검 마스터리",
]


def _검귀_턴(상태, g, 기록, 번호):
    """귀혼일체(없으면) -> 라운드+전투 번호가 홀수: 원귀 -> 합격(월령참이면 대상 없이) / 짝수: 귀연참 : 극 ->
    남은 행동(추가행동 포함)은 귀연참, MP가 모자라면 일반공격."""
    전투상태 = 상태["전투상태"]

    def 쓰기(이름, 대상=None):
        if not gf.스킬_사용_가능여부(상태, g, 이름)[0]:
            return False
        표시 = gf.스킬_팝업_줄(상태, g, 이름)["이름"]
        if gf.스킬_실제_타겟(상태, 상태["스킬데이터모음"][이름]) == "적전체":
            대상 = None
        MP = g["현재MP"]
        gf.아군_스킬사용(상태, 이름, 중심대상=대상)
        기록[표시] = 기록.get(표시, 0) + 1
        기록[f"{이름}MP"] = 기록.get(f"{이름}MP", 0) + MP - g["현재MP"]
        return True

    def 적():
        적들 = scenario._살아있는_적(상태)
        return 적들[0] if 적들 else None

    if not any(b["이름"] == "귀혼일체" for b in g["버프"]):
        쓰기("귀혼일체")
    if (전투상태["라운드"] + 번호) % 2 and 적() and 쓰기("원귀", 적()):
        [원귀] = [b for b in g["버프"] if b["이름"] == "원귀"]
        기록[f"원귀 : {원귀['패턴']}"] = 기록.get(f"원귀 : {원귀['패턴']}", 0) + 1
        if 적():
            쓰기("합격", 적())
    elif 적():
        쓰기("귀연참 : 극", 적())
    while 전투상태["종료"] is None and g["생존"] and 적():
        if g["행동자원"].get("일반행동", 0) <= 0 and gf.추가행동_남은수(g) <= 0:
            break
        if not 쓰기("귀연참", 적()):
            gf.아군_일반공격(상태, 적())
            기록["일반공격"] = 기록.get("일반공격", 0) + 1
    if 전투상태["종료"] is None:
        gf.턴_넘기기(상태)


def _전투(상태, 검귀, 기록, 번호):
    support.반응_처리(상태)
    for _ in range(300):
        if gf.전투_종료됨(상태):
            break
        참가자 = gf.현재_턴_참가자(상태)
        if 참가자["진영"] == "아군" and 참가자["생존"]:
            if 참가자["원본"] is 검귀:
                _검귀_턴(상태, 참가자, 기록, 번호)
            else:
                scenario.스킬_우선_턴(상태, [])
        else:
            gf.턴_넘기기(상태)
    else:
        raise AssertionError("전투가 끝나지 않았다")
    # 검귀의 일반공격과 스킬 타격의 명중 판정 전부
    판정들 = []
    for 항목 in 상태["전투상태"]["로그"]:
        if not isinstance(항목, dict) or 항목.get("공격자") != 검귀["캐릭터명"]:
            continue
        if 항목.get("종류") == "일반공격":
            판정들.append(항목["판정"])
        판정들 += [t["판정"] for t in 항목.get("타격") or [] if t.get("판정")]
    기록["치명타"] = sum(1 for 판정 in 판정들 if 판정.get("치명타"))
    기록["19눈치명타"] = sum(
        1 for 판정 in 판정들 if 판정.get("치명타") and 판정.get("자연눈") == 19
    )
    return 상태["전투상태"]["종료"]


@pytest.mark.scenario("S33")
def test_S33_검귀_실전(golden):
    rng.시드(시드)
    상태 = support.새게임(파티구성)
    파티 = 상태["파티"]["파티원"]
    [g] = [c for c in 파티 if c["직업"] == "귀검사"]
    for c in 파티:
        support.성장(
            상태, c, 5 if c is g else 9, 전직=전직표[c["직업"]], 스킬습득=c is not g
        )
    assert any(n in g["보유특성"] for n in 마스터리5종)  # 레벨 2에 고른 무기 마스터리
    support.성장(상태, g, 8, 전직="검귀")
    assert not any(n in g["보유특성"] for n in 마스터리5종)
    assert not any(이름 in 마스터리5종 for 이름, _ in support.퍽_후보(g))  # 9레벨 퍽
    support.성장(상태, g, 9, 스킬습득=True)
    assert gf.캐릭터_직업표시(g).startswith("검귀")
    assert {"청혈투귀", "검귀의 도 마스터리"} <= set(g["보유특성"])
    assert {"귀혼일체", "원귀", "합격", "귀연참", "귀연참 : 극"} <= set(g["보유스킬"])
    상태["소지품"]["장비"][도] = 1
    gf.장비_교체(상태, g, "무기", 도)
    gf.파티_최대치로_회복(상태)

    gf.던전_진입(상태, 선더랜드)
    전투들 = []
    for 번호 in range(12):
        적 = scenario.인카운트까지_걷기(상태)
        기록 = {}
        종료 = _전투(상태, g, 기록, 번호)
        assert gf.전투_결과_정리(상태) == 종료 == "아군승리"
        scenario.보상_수령(상태)
        전투들.append({"적": 적, **기록})
        gf.휴식(상태)  # 귀혼일체는 휴식당 1회 - 마을에서 쉬고 다시 들어간다
        gf.던전_진입(상태, 선더랜드)
        if all(sum(b.get(키, 0) for b in 전투들) for 키 in 끝날조건):
            break

    def 합계(키):
        return sum(b.get(키, 0) for b in 전투들)

    assert all(합계(키) for 키 in 끝날조건), 전투들
    assert 합계("귀혼일체") and 합계("귀혼일체MP") == 0, 전투들  # 소모값 없음
    # 합격은 원귀가 낸 패턴대로 - 이혼일섬은 일섬/연참 뒤, 월령참은 회천 뒤
    assert 합계("합격 : 이혼일섬") <= 합계("원귀 : 일섬") + 합계("원귀 : 연참"), 전투들
    assert 합계("합격 : 월령참") <= 합계("원귀 : 회천"), 전투들
    assert 합계("합격MP") == 10 * (합계("합격 : 이혼일섬") + 합계("합격 : 월령참"))
    assert all(b.get("귀혼일체", 0) <= 1 for b in 전투들), 전투들  # 휴식당 1회
    assert 합계("19눈치명타"), 전투들  # 청혈투귀 - 치명타 범위 19
    golden("scenario_S33_ghostblade", 전투들)
