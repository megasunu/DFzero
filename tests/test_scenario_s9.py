"""S9 포션 - 전투 중 버프포션/회복포션 (docs/scenarios.md).

4인 기본 파티가 로리엔에서 인카운트 4번과 보스전을 **실제 전투로** 치른다. 포션은 조종하는 아군이 자기 차례에
보조행동 1개로 자기 자신에게 마신다. 인카운트마다 처음 조종하는 아군이 하나씩: 가속 포션(그 턴에 바로 일반행동
+1), 오거파워 플라스크(근력 +5), 마나의 속삭임 플라스크(지능 +5), 회복포션. 로리엔 인카운트는 1라운드에 끝나서
버프가 줄지 않으므로, 몇 라운드 가는 보스전에서는 아군 넷이 처음 차례에 버프포션을 하나씩 마시고 지속턴이 자기
턴마다 1씩 주는 것을 본다. 보스전의 두 번째 차례에는 고블린 더스트(소환 아이템, 보조행동)를 써서, 소환된
고블린이 사용자 턴이 끝날 때 공격하는 것을 본다. 버프와 소환수는 전투가 끝나면 남지 않는다. 버프포션은 아직 얻을 곳이 없어(마을 판매목록/드랍표에
없음) 소지품에 직접 넣는다. 중첩/지속턴 갱신 규칙은 test_consumables.py가 값으로 검사한다.
"""

import pytest

from game.system import rng
import gameflow as gf
import scenario
import support
from game.system.combat import stats

로리엔 = "dungeon_01A_D01_Lorien"
시드 = 3
버프포션들 = [
    "가속 포션",
    "오거파워 플라스크",
    "마나의 속삭임 플라스크",
    "샤프아이 포션",
]
포션버프 = {
    "가속 포션": "일반행동증가",
    "오거파워 플라스크": "근력증가",
    "마나의 속삭임 플라스크": "지능증가",
    "샤프아이 포션": "치명타확률증가",
}


def _포션_마시기(상태, 현재, 포션):
    전투상태 = 상태["전투상태"]
    보조 = 현재["행동자원"]["보조행동"]
    일반 = 현재["행동자원"]["일반행동"]
    근력 = stats.유효_능력치값(전투상태, 현재, "근력")
    지능 = stats.유효_능력치값(전투상태, 현재, "지능")
    if 포션 in 포션버프:
        gf.아군_버프포션사용(상태, 포션)
    else:
        gf.아군_포션사용(상태, 포션)
    assert 현재["행동자원"]["보조행동"] == 보조 - 1
    if 포션 == "가속 포션":
        assert 현재["행동자원"]["일반행동"] == 일반 + 1, "마신 턴에 바로 는다"
    else:
        assert 현재["행동자원"]["일반행동"] == 일반
    if 포션 == "오거파워 플라스크":
        assert stats.유효_능력치값(전투상태, 현재, "근력") == 근력 + 5
    if 포션 == "마나의 속삭임 플라스크":
        assert stats.유효_능력치값(전투상태, 현재, "지능") == 지능 + 5


def _전투(상태, 포션들, 더스트=0):
    """조종할 아군은 [자동전투]처럼 무작위 일반공격. 포션들이 남아 있으면 처음 조종하는 아군부터
    차례마다 하나씩 먼저 마신다(한 사람에 하나). 마신 버프의 지속턴을 자기 턴마다 적어 둔다.
    더스트가 남아 있으면 이미 마신 아군이 다음 차례에 고블린 더스트를 하나 쓴다."""
    support.반응_처리(상태)
    남은 = list(포션들)
    마신 = {}
    지속턴 = {}
    소환 = []
    for _ in range(300):
        if gf.전투_종료됨(상태):
            break
        if not gf.아군_차례인가(상태):
            gf.턴_넘기기(상태)
            continue
        현재 = gf.현재_턴_참가자(상태)
        if 현재["이름"] in 마신 and 마신[현재["이름"]] in 포션버프:
            버프 = 포션버프[마신[현재["이름"]]]
            지속턴[현재["이름"]].append(
                next((b["지속턴"] for b in 현재["버프"] if b["이름"] == 버프), 0)
            )
        if 더스트 and 현재["이름"] in 마신 and 현재["이름"] not in 소환:
            보조 = 현재["행동자원"]["보조행동"]
            gf.아군_소환아이템사용(상태, "고블린 더스트")
            assert (
                현재["행동자원"]["보조행동"] == 보조 - 1 and "고블린" in 현재["소환수"]
            )
            소환.append(현재["이름"])
            더스트 -= 1
        elif 남은 and 현재["이름"] not in 마신:
            포션 = 남은.pop(0)
            _포션_마시기(상태, 현재, 포션)
            마신[현재["이름"]] = 포션
            지속턴[현재["이름"]] = []
        gf.자동전투_한_턴(상태)
    else:
        raise AssertionError("전투가 끝나지 않았다")
    assert not 남은 and not 더스트, (
        f"조종할 아군 차례가 모자랐다: {남은}, 더스트 {더스트}"
    )
    로그 = 상태["전투상태"]["로그"]
    고블린공격 = [
        x["스킬"] for x in 로그 if str(x.get("스킬", "")).startswith("고블린의 ")
    ]
    return {
        "종료": 상태["전투상태"]["종료"],
        "라운드": 상태["전투상태"]["라운드"],
        "마신": 마신,
        "지속턴": {이름: 값 for 이름, 값 in 지속턴.items() if 마신[이름] in 포션버프},
        "소환": 소환,
        "고블린공격": len(고블린공격),
    }


def _보스인가(상태):
    return any((e.get("원본") or {}).get("칭호") == "보스" for e in gf.적_목록(상태))


@pytest.mark.scenario("S9")
def test_S9_전투_중_버프포션과_회복포션_실전(golden):
    rng.시드(시드)
    상태 = support.새게임()
    파티 = 상태["파티"]["파티원"]
    상태["소지품"]["포션"] = {
        "가속 포션": 2,
        "오거파워 플라스크": 2,
        "마나의 속삭임 플라스크": 2,
        "샤프아이 포션": 1,
        "초보자용 HP 포션": 1,
    }
    상태["소지품"]["소모품"]["고블린 더스트"] = 2
    능력치전 = {c["캐릭터명"]: gf.캐릭터_유효능력치(상태, c) for c in 파티}
    기록 = {"인카운트": [], "보스전": None}

    gf.던전_진입(상태, 로리엔)
    for 포션 in [
        "가속 포션",
        "오거파워 플라스크",
        "마나의 속삭임 플라스크",
        "초보자용 HP 포션",
    ]:
        if 포션 == "초보자용 HP 포션":
            for (
                c
            ) in 파티:  # 회복포션은 HP가 가득 차면 못 쓴다 - 전투 전에 한 칸 깎아 둔다
                c["현재HP"] = max(1, c["현재HP"] - 1)
        적 = scenario.인카운트까지_걷기(상태)
        요약 = _전투(상태, [포션])
        요약["적"] = 적
        assert gf.전투_결과_정리(상태) == 요약["종료"] == "아군승리"
        scenario.보상_수령(상태)
        기록["인카운트"].append(요약)

    def 처리(상태):
        if not _보스인가(상태):  # 보스 앞까지 가는 길의 인카운트는 포션 없이
            scenario.실전(상태)
            return
        기록["보스전"] = _전투(상태, 버프포션들, 더스트=2)

    결과, _ = support.보스_처치(상태, 전투처리=처리)
    assert 결과 == "아군승리" and 기록["보스전"] is not None
    # 지속턴은 자기 턴마다 1씩 준다(10턴짜리를 마신 뒤 다음 자기 턴 기록은 9)
    지속턴 = 기록["보스전"]["지속턴"]
    assert len(지속턴) == 4 and any(len(값) >= 2 for 값 in 지속턴.values()), 지속턴
    for 값 in 지속턴.values():
        assert 값 == list(range(9, 9 - len(값), -1)), 값

    # 고블린을 부른 아군 둘의 턴이 끝날 때마다 고블린이 공격했다
    assert len(기록["보스전"]["소환"]) == 2 and 기록["보스전"]["고블린공격"] >= 2, 기록[
        "보스전"
    ]
    assert all(not c.get("소환수") for c in 파티)

    # 마신 포션은 소지품에서 빠지고, 버프는 전투 밖 능력치에 남지 않는다
    assert 상태["소지품"]["포션"] == {}
    assert "고블린 더스트" not in 상태["소지품"]["소모품"]
    assert {c["캐릭터명"]: gf.캐릭터_유효능력치(상태, c) for c in 파티} == 능력치전
    golden("scenario_S9_potion", 기록)
