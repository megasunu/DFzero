def test_철갑탄은_방어력_보호율_저항을_무시한다(스핏전장, monkeypatch):
    _, 전투상태, 적, s = 스핏전장
    _굴림(monkeypatch, 15)
    monkeypatch.setattr(stats, "유효_방어력", lambda 전투상태, 대상: 100)
    assert _일반공격_피해(전투상태, s, 적[1]) == 0
    assert _일반공격_피해(전투상태, s, 적[1], "은탄") == 0
    assert _일반공격_피해(전투상태, s, 적[1], "철갑탄") == 8
    적[1]["원본"]["저항"] = ["무속성"]
    assert _일반공격_피해(전투상태, s, 적[1], "철갑탄") == 8


def test_철갑탄도_취약은_그대로_받는다(스핏전장, monkeypatch):
    _, 전투상태, 적, s = 스핏전장
    _굴림(monkeypatch, 15)
    monkeypatch.setattr(stats, "유효_방어력", lambda 전투상태, 대상: 100)
    적[1]["원본"]["취약"] = ["무속성"]
    assert _일반공격_피해(전투상태, s, 적[1], "철갑탄") == 16


def test_장전_버프는_서로_겹치지_않는다(스핏전장):
    _, 전투상태, _, s = 스핏전장
    _장전(전투상태, s, "은탄")
    _장전(전투상태, s, "철갑탄")
    이름들 = {i["이름"] for i in s["버프"] if i["이름"].startswith("장전 : ")}
    assert 이름들 == {"장전 : 철갑탄"}


def test_새_탄은_보조행동과_탄약으로_장전한다(스핏전장):
    _, 전투상태, _, s = 스핏전장
    탄약 = s["보유자원"]["탄약"]
    _쓰기(전투상태, s, "작열탄")
    assert _남은(전투상태, s, "작열탄") == 1 + 2 * core.차수(s)
    assert s["보유자원"]["탄약"] == 탄약 - 1


def test_장전_류탄_스킬이_있으면_전투를_탄약_수류탄_가득_찬_채로_시작한다(스핏전장):
    """#393 - 탄약/수류탄은 최대 2+차수이고 전투마다 가득 찬 채로 시작한다(전투가 끝나면 시작값으로 되돌림)."""
    _, _, _, s = 스핏전장
    최대 = 2 + core.차수(s)
    assert s["보유자원"]["탄약"] == 최대
    assert s["보유자원"]["수류탄"] == 최대


def test_장전_류탄_스킬이_없으면_탄약_수류탄도_없다():
    상태 = support.새게임([("", "귀검사")])
    gf.전투_시작(상태, ["고블린"], 레벨=1, 차수=1)
    p = next(p for p in 상태["전투상태"]["참가자"] if p["진영"] == "아군")
    assert "탄약" not in p["보유자원"] and "수류탄" not in p["보유자원"]
