"""몬스터 밸런스 수정(사용자 지정 2026-11-03, "밸런스 수정" 세션) - 익스펠러류 패턴 데미지보너스 0(랜스 돌격 포함),
하늘성의 친위대장 추가행동 삭제, 종족:용인족 데미지보너스 +1, 미르키우스·라키우스·시우스 근력 +4,
황금의 플라타니 특성 "골렘의 왕"(데미지보너스·방어력·보호률 +1, 상시 슈퍼아머), 지그하르트 모든 능력치 -4."""

import pytest

import gameflow as gf
from game.data.monster.monster_ability import 특성목록
from game.system.combat import traits
from tests import support

_능력치 = ("근력", "민첩", "건강", "지능", "지혜", "매력")
_익스펠러류 = (
    "익스펠러",
    "엑스 익스펠러",
    "헤븐 익스펠러",
    "틴소드맨",
    "레기온",
    "악시온",
)


def _효과(특성, 대상):
    return [e["변동값"] for e in 특성목록[특성]["효과"] if e.get("변동대상") == 대상]


@pytest.mark.parametrize("이름", _익스펠러류)
def test_익스펠러류_패턴에는_데미지보너스가_없다(이름):
    for 번호, 패턴 in gf.몬스터목록[이름]["패턴"].items():
        assert not 패턴.get("데미지보너스"), (이름, 번호)


@pytest.mark.parametrize("특성", ["특수패턴:레기온", "특수패턴:악시온"])
def test_랜스_돌격에도_데미지보너스가_없다(특성):
    assert 특성목록[특성]["대체행동"]["패턴"]["데미지보너스"] == 0


def test_하늘성의_친위대장에는_추가행동이_없다():
    assert _효과("하늘성의 친위대장", "추가행동") == []
    assert _효과("하늘성의 친위대장", "공격속성변경") == ["명속성"]
    assert "한 번 더" not in 특성목록["하늘성의 친위대장"]["설명"]


def test_용인족은_속도보너스_1과_데미지보너스_1():
    assert _효과("종족:용인족", "속도보너스") == [1]
    assert _효과("종족:용인족", "데미지보너스") == [1]
    전투상태, 적, _ = support.시험_전투(["미르키우스"])
    assert traits.특성_수치(전투상태, 적[0], "데미지보너스") == 1


@pytest.mark.parametrize("이름", ["미르키우스", "라키우스", "오라헌터 시우스"])
def test_용인족_3종은_근력_18(이름):
    assert gf.몬스터목록[이름]["근력"] == 18


def test_플라타니는_골렘의_왕():
    플 = gf.몬스터목록["황금의 플라타니"]
    assert 플["특성"] == ["종족:골렘", "골렘의 왕"]
    for 대상 in ("데미지보너스", "방어력", "보호률"):
        assert _효과("골렘의 왕", 대상) == [1], 대상
    assert 특성목록["골렘의 왕"]["전투시작상태"] == "슈퍼아머"
    전투상태, 적, _ = support.시험_전투(["황금의 플라타니"])
    assert {"이름": "슈퍼아머", "지속턴": None} in 적[0]["상태이상"]


def test_지그하르트는_모든_능력치가_4_줄었다():
    지 = gf.몬스터목록["빛의 성주 지그하르트"]
    assert [지[k] for k in _능력치] == [16, 12, 12, 10, 12, 10]
