def test_장비_교체_탭과_다른_직업군_무기_숨김():
    상태 = support.새게임([("", "귀검사"), ("", "마법사")])
    c = next(p for p in 상태["파티"]["파티원"] if p["직업"] == "귀검사")
    장비 = 상태["소지품"]["장비"]
    for 이름 in ("녹슨 소검", "녹슨 대검", "해진 너클", "낡은 빗자루"):
        장비[이름] = 장비.get(이름, 0) + 1
    for 이름 in ("찢어진 천갑 상의", "녹슨 중갑 상의"):
        장비[이름] = 장비.get(이름, 0) + 1
    assert gf.장비_교체_탭목록(상태, c, "무기") == [
        "전체",
        "소검",
        "도",
        "둔기",
        "대검",
        "광검",
    ]
    assert gf.장비_교체_탭목록(상태, c, "하의") == [
        "전체",
        "천갑",
        "가죽",
        "경갑",
        "중갑",
        "판금",
    ]
    assert gf.장비_교체_탭목록(상태, c, "반지") == []
    무기 = {i["이름"] for i, *_ in gf.장비_교체_후보(상태, c, "무기")}
    # 다른 직업군(격투가 너클, 마법사 빗자루)은 [전체]에도 안 나온다
    assert {"녹슨 소검", "녹슨 대검"} <= 무기
    assert not {"해진 너클", "낡은 빗자루"} & 무기
    assert {i["이름"] for i, *_ in gf.장비_교체_후보(상태, c, "무기", "대검")} == {
        "녹슨 대검"
    }
    상의 = {i["이름"] for i, *_ in gf.장비_교체_후보(상태, c, "상의", "중갑")}
    assert 상의 == {"녹슨 중갑 상의"}

    # 같은 직업군이지만 가용무기가 아닌 종류(마법사의 빗자루)는 착용 불가로 나온다
    m = next(p for p in 상태["파티"]["파티원"] if p["직업"] == "마법사")
    빗자루 = [
        h for h in gf.장비_교체_후보(상태, m, "무기") if h[0]["이름"] == "낡은 빗자루"
    ]
    assert 빗자루 and 빗자루[0][2] is False and 빗자루[0][3]
    assert "빗자루" in gf.장비_교체_탭목록(상태, m, "무기")


