def test_상점_해체는_소울과_큐브조각을_준다():
    """장비 1개 -> 레어도 소울 1개 + 큐브 조각(무기 10, 방어구 2, 악세/특수 3).
    조각 색은 무색 80%, 적/청/백/흑 5%, 황금 0%. 장착 중인 장비는 해체할 수 없다."""
    상태 = 새게임([("철수", "귀검사")])
    c = 상태["파티"]["파티원"][0]
    장비 = 상태["소지품"]["장비"]
    무기 = c["장착장비"]["무기"]  # 녹슨 소검(커먼) - 장착 중
    assert gf.상점_해체목록(상태, "무기") == []
    with pytest.raises(ValueError, match="해체할 수 없다"):
        gf.상점_해체(상태, "무기", 무기, 1)

    장비[무기] += 2
    장비["찢어진 천갑 상의"] = 1
    장비["조잡한 반지"] = 1
    장비["치트용 소검"] = 1  # 소울이 없는 레어도 - 해체 목록에 안 나온다
    assert [(a["이름"], n) for a, n, _ in gf.상점_해체목록(상태, "무기")] == [(무기, 2)]

    rng.시드(0)
    얻음 = gf.상점_해체(상태, "무기", 무기, 2)
    assert 얻음["커먼 소울"] == 2
    조각 = {k: v for k, v in 얻음.items() if k.endswith("큐브 조각")}
    assert sum(조각.values()) == 20 and "황금 큐브 조각" not in 조각
    assert 장비[무기] == 1  # 장착 중인 1개만 남는다
    assert gf.상점_해체(상태, "상의", "찢어진 천갑 상의", 1)["커먼 소울"] == 1
    assert "찢어진 천갑 상의" not in 장비
    반지 = gf.상점_해체(상태, "반지", "조잡한 반지", 1)
    assert sum(v for k, v in 반지.items() if k.endswith("조각")) == 3
    재료 = 상태["소지품"]["재료"]
    assert 재료["커먼 소울"] == 4
    assert sum(v for k, v in 재료.items() if k.endswith("조각")) == 20 + 2 + 3

    # 색 확률: 많이 굴리면 무색이 대부분, 황금은 없다
    rng.시드(1)
    장비["찢어진 천갑 하의"] = 500
    많이 = gf.상점_해체(상태, "하의", "찢어진 천갑 하의", 500)
    assert 0.75 < 많이["무색 큐브 조각"] / 1000 < 0.85
    assert "황금 큐브 조각" not in 많이 and 많이.get("흑색 큐브 조각", 0) > 0


def test_해체_전체탭과_일괄해체는_등급과_부위로_고른다():
    상태 = 새게임([("철수", "귀검사")])
    장비 = 상태["소지품"]["장비"]
    언커먼 = "연꽃 반지"
    장비.update(
        {"찢어진 천갑 상의": 2, "찢어진 천갑 하의": 1, "조잡한 반지": 1, 언커먼: 1}
    )
    assert gf.상점_해체_탭목록[0] == "전체"
    assert gf.상점_해체_등급목록 == [
        "커먼",
        "언커먼",
        "레어",
        "유니크",
        "레전더리",
        "에픽",
    ]
    전체 = {(a["이름"], n, 탭) for a, n, 탭 in gf.상점_해체목록(상태, "전체")}
    assert {
        ("찢어진 천갑 상의", 2, "상의"),
        ("조잡한 반지", 1, "반지"),
        (언커먼, 1, "반지"),
    } <= 전체

    # 커먼 + 상의만
    assert gf.상점_일괄해체_대상(상태, "커먼", "상의") == [
        ("찢어진 천갑 상의", 2, "상의")
    ]
    수, 얻음 = gf.상점_일괄해체(상태, "커먼", "상의")
    assert 수 == 2 and 얻음["커먼 소울"] == 2
    assert 언커먼 in 장비 and "찢어진 천갑 하의" in 장비

    # 커먼 + 전체 - 장착 중인 시작 장비는 남는다
    수, 얻음 = gf.상점_일괄해체(상태, "커먼", "전체")
    assert 수 == 2 and 얻음["커먼 소울"] == 2  # 하의 1 + 반지 1
    assert list(얻음)[0] == "커먼 소울"
    assert sum(v for k, v in 얻음.items() if k.endswith("조각")) == 2 + 3
    assert 언커먼 in 장비
    with pytest.raises(ValueError, match="해체할 장비가 없다"):
        gf.상점_일괄해체(상태, "커먼", "전체")
    수, 얻음 = gf.상점_일괄해체(상태, "언커먼", "전체")
    assert 수 == 1 and 얻음["언커먼 소울"] == 1 and 언커먼 not in 장비
