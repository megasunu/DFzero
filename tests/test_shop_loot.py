def test_승리하면_전리품을_소지품에_넣고_팝업_문구로_보여준다(monkeypatch):
    상태 = 새게임()
    전투_열기(상태, ["고블린", "고블린", "겁쟁이 고블린"])
    골드전 = 상태["소지품"]["골드"]
    monkeypatch.setattr(rng.보상, "uniform", lambda a, b: 1.0)
    monkeypatch.setattr(rng.보상, "random", lambda: 0.0)  # 30% 통과
    monkeypatch.setattr(rng.보상, "choices", lambda 후보, weights, k: [후보[0]])
    support.강제_승리(상태)
    assert gf.전투_결과_정리(상태) == "아군승리"
    # 골드 공식 (10+레벨1)x일반1 = 11씩 x3, 커먼무기방어구군 첫 항목(커먼무기군)의 첫 항목(녹슨 소검)이
    # 세 마리 모두에서,
    # 고블린 종족 공용(가죽/손뼈)이 세 마리 모두에서, 팬티는 고블린 두 마리에서,
    # 겁쟁이 고블린 개인 드랍(수염)이 한 마리에서
    assert 상태["전투_전리품"] == {
        "골드": 33,
        "아이템": [
            ("녹슨 소검", 3),
            ("고블린 가죽", 3),
            ("고블린의 손뼈", 3),
            (
                "고블린 수염",
                1,
            ),  # 순서는 전리품을 처리하는 몬스터 순서(이니셔티브)를 따른다
            ("고블린의 팬티", 2),
            ("스위트 민트", 1),  # 로리엔 특별드랍(10%, 한 번만 - #437)
        ],
    }
    assert 상태["소지품"]["골드"] == 골드전 + 33
    assert 상태["소지품"]["장비"]["녹슨 소검"] >= 3
    assert 상태["소지품"]["재료"]["고블린의 팬티"] == 2  # 재료 칸으로
    assert gf.전투_종료_문구(상태, "아군승리") == [
        "전투 승리!",
        "전리품",
        "골드 33",
        "녹슨 소검 x3",
        "고블린 가죽 x3",
        "고블린의 손뼈 x3",
        "고블린 수염",  # 1개면 개수를 안 붙인다
        "고블린의 팬티 x2",
        "스위트 민트",
    ]


