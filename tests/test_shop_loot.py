def test_승리하면_전투_보상_3칸에서_하나를_받는다(monkeypatch):
    상태 = 새게임()
    전투_열기(상태, ["고블린", "고블린"])
    monkeypatch.setattr(
        loot_system, "보상_뽑기", lambda 후보: [후보[0][0], 후보[50][0], 후보[28][0]]
    )
    support.강제_승리(상태)
    gf.전투_결과_정리(상태)
    # 고블린 두 마리 = 커먼무기방어구군(무기 25 + 방어구 25)이 두 번 -> 0번과 50번은 같은 아이템,
    # 28번은 방어구 4번째. 고블린 잡템(가죽/손뼈/팬티)은 장비가 아니라 후보에서 빠진다
    칸 = gf.전투_보상_칸(상태)
    assert 칸[0] == 칸[1] == "녹슨 소검" and 칸[2] == "녹슨 중갑 상의"
    assert gf.전투_보상_대기중(상태)
    보유 = 상태["소지품"]["장비"].get("녹슨 중갑 상의", 0)
    골드 = 상태["소지품"]["골드"]
    전 = gf.전투_종료_문구(상태, "아군승리")
    assert "녹슨 중갑 상의" not in 전
    assert gf.전투_보상_받기(상태, 2) == "녹슨 중갑 상의"
    # 받은 보상은 전투 종료 팝업의 전리품 줄에 더해진다(전리품 기록 자체는 그대로)
