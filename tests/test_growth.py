@pytest.mark.parametrize("직업", list(구현된_전직))
def test_최대MP는_레벨마다_현재_주문시전능력치를_따른다(직업):
    # B6: 기본최대MP(25 + (레벨-1)x(3+주문시전보정치))를 생성/전직 때만 계산해, 레벨업으로
    # 주문시전능력치가 올라도 최대MP가 그대로였던 버그.
    상태 = 새게임([("", 직업)])
    c = 상태["파티"]["파티원"][0]
    for _ in range(9):
        성장(상태, c, c["레벨"] + 1, 전직=구현된_전직[직업])
