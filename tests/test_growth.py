@pytest.mark.parametrize(
    "재질, 능력치",
    [
        ("천갑", {"지능": 1}),  # 마법사 주문시전능력치
        ("가죽", {"민첩": 1}),
        ("경갑", {"근력": 1}),
        ("중갑", {"건강": 1}),
        ("판금", {"건강": 1}),
    ],
)
def test_방어구_숙달_세트_능력치(재질, 능력치):
    from game.system import equipment_system as 장비

    상태 = 새게임([("", "마법사")])
    c = 상태["파티"]["파티원"][0]
    c["보유특성"] += [f"{재질}숙련", f"{재질}숙달"]
    세트 = {슬롯: {"재질": 재질} for 슬롯 in 장비.방어구_슬롯}
    깨짐 = dict(세트, 신발={"재질": "천갑" if 재질 != "천갑" else "가죽"})
    for 이름 in ("근력", "민첩", "건강", "지능"):
        assert 장비.장비반영_능력치(c, 세트)[이름] == c[이름] + 능력치.get(이름, 0)
        assert 장비.장비반영_능력치(c, 깨짐)[이름] == c[이름]
    c["보유특성"].remove(f"{재질}숙련")  # 숙련 없이 숙달만 있으면 발동 안 함
    assert 장비.장비반영_능력치(c, 세트) == 장비.장비반영_능력치(c, 깨짐)


def test_방어구_숙달_전투_AC_방어력과_가죽_지속피해_내성이점():
    from game.system import equipment_system as 장비

    상태 = 새게임([("", "귀검사")])
    c = 상태["파티"]["파티원"][0]
    gf.전투_시작(상태, ["고블린"], 레벨=1, 차수=1)
    전투상태 = 상태["전투상태"]
    p = next(x for x in gf.아군_목록(상태))
    for 재질, 대상, 값 in (("중갑", "AC", 1), ("판금", "AC", 1), ("경갑", "방어력", 1)):
        c["보유특성"] = [f"{재질}숙련"]
        p["장비데이터"] = {슬롯: {"재질": 재질} for 슬롯 in 장비.방어구_슬롯}
        전 = traits.특성_수치(전투상태, p, 대상)
        c["보유특성"].append(f"{재질}숙달")
        assert traits.특성_수치(전투상태, p, 대상) == 전 + 값, 재질

    c["보유특성"] = ["가죽숙련"]
    p["장비데이터"] = {슬롯: {"재질": "가죽"} for 슬롯 in 장비.방어구_슬롯}
    assert not traits.상태이상_내성이점(전투상태, p, "출혈")
    c["보유특성"].append("가죽숙달")
    assert traits.상태이상_내성이점(전투상태, p, "출혈")  # 지속피해형
    assert not traits.상태이상_내성이점(전투상태, p, "기절")
    p["장비데이터"] = dict(p["장비데이터"], 상의={"재질": "천갑"})
    assert not traits.상태이상_내성이점(전투상태, p, "출혈")  # 세트가 깨지면 없음
