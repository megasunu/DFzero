    assert "소검 마스터리" in 퍽이름들 and "천갑숙련" in 퍽이름들
    assert "대검 마스터리" not in 퍽이름들 and "판금숙련" not in 퍽이름들
    assert "로드 마스터리" not in 퍽이름들  # 가용무기가 아니다

