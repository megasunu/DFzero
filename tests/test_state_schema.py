def test_스키마는_빠진_칸과_틀린_타입과_모르는_칸을_잡는다():
    캐릭터 = support.새게임([("", "귀검사")])["파티"]["파티원"][0]
    복사 = dict(캐릭터)
    del 복사["성별"]
    assert 스키마.캐릭터_문제목록(복사) == ["캐릭터 귀검사: '성별' 칸이 없다"]

    복사 = dict(캐릭터, 레벨="3")
    assert "'레벨'은 int여야 하는데 str" in 스키마.캐릭터_문제목록(복사)[0]

    복사 = dict(캐릭터, 레벨=True)  # bool은 int가 아니다
    assert "'레벨'은 int여야 하는데 bool" in 스키마.캐릭터_문제목록(복사)[0]

    복사 = dict(캐릭터, 새칸=1)
    assert 스키마.캐릭터_문제목록(복사) == []  # 엄격하지 않으면 모르는 칸은 넘어간다
    assert 스키마.캐릭터_문제목록(복사, 엄격=True) == [
        "캐릭터 귀검사: 표에 없는 칸 ['새칸']"
    ]

    assert 스키마.캐릭터_문제목록([1, 2]) == ["캐릭터: 딕셔너리가 아니다(list)"]
    assert 스키마.참가자_문제목록(None) == ["참가자: 딕셔너리가 아니다"]


