def _세이브_캐릭터에서_칸_지우기(경로, 칸):
    데이터 = json.loads(경로.read_text(encoding="utf-8"))
    del 데이터["플레이어"]["파티"]["파티원"][0][칸]
    경로.write_text(json.dumps(데이터, ensure_ascii=False), encoding="utf-8")


def test_핵심_칸이_없는_세이브는_손상으로_보고_백업으로_돌아간다(임시_세이브폴더):
    상태 = support.새게임([("", "귀검사")])
    gf.게임_저장(상태, 1)
    gf.게임_저장(상태, 1)  # .bak = 온전한 세이브
    _세이브_캐릭터에서_칸_지우기(임시_세이브폴더 / "slot_1.json", "직업")

    assert save_system.세이브_요약(1)["복구본"] is True  # 본 파일은 못 쓰니 백업으로
    assert gf.게임_불러오기(1)["파티"]["파티원"][0]["직업"] == "귀검사"

    # 백업도 같이 망가졌으면 손상 오류 - 화면이 KeyError로 죽는 대신 슬롯이 "손상됨"이 된다
    _세이브_캐릭터에서_칸_지우기(임시_세이브폴더 / "slot_1.json.bak", "현재HP")
    assert save_system.세이브_요약(1) == {"슬롯번호": 1, "손상": True}
    with pytest.raises(gf.세이브_손상오류):
        gf.게임_불러오기(1)


def test_핵심_검사는_표준_모양_전체를_요구하지_않는다():
    """옛 세이브가 새 칸을 다 갖추지 않아도 읽혀야 한다(불러올 때 gameflow가 채운다) - 핵심 5칸만 본다."""
    최소 = {"캐릭터명": "옛날", "직업": "귀검사", "레벨": 1, "현재HP": 1, "현재MP": 0}
    저장데이터 = {"플레이어": {"파티": {"파티원": [최소]}, "숙소": []}, "진행도": {}}
    assert 스키마.세이브_핵심_문제목록(저장데이터) == []
    저장데이터["플레이어"]["숙소"] = [{"캐릭터명": "빈약"}]
    문제 = 스키마.세이브_핵심_문제목록(저장데이터)
    assert any("숙소[0]: '직업' 칸이 없다" in m for m in 문제) and len(문제) == 4
    assert 스키마.세이브_핵심_문제목록({"플레이어": []}) == [
        "플레이어: 딕셔너리가 아니다"
    ]
    assert 스키마.세이브_핵심_문제목록(
        {"플레이어": {"파티": {"파티원": "x"}, "숙소": []}}
    ) == ["파티원: 목록이 아니다"]
