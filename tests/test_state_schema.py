"""상태 스키마 - 지금 코드가 만드는 캐릭터/참가자/게임상태가 game/system/state_schema.py의 표대로인지 검사한다.

게임 상태는 한글 키 딕셔너리라 필드를 더하거나 이름을 바꿀 때 빠뜨려도 컴파일/린트가 못 잡는다(구조 점검 W-4).
여기서 새 게임 5직업 x 성장(레벨 1/6/10, 전직), 주점 영입, 옛 세이브를 불러온 캐릭터, 전투 참가자(아군/적),
게임상태를 엄격하게(표에 없는 칸도 문제로) 확인한다. 새 칸을 일부러 더했다면 state_schema의 표에 더한다 -
이 테스트가 어느 칸이 다른지 알려 준다.
"""

import json

import pytest

from game.system import rng
import gameflow as gf
from game.system import save_system, state_schema as 스키마
from tests import support

전직 = {
    "귀검사": "웨펀마스터",
    "격투가": "스트라이커",
    "거너": "레인저",
    "마법사": "엘리멘탈마스터",
    "프리스트": "크루세이더",
}


@pytest.mark.parametrize("직업", list(전직))
@pytest.mark.parametrize("레벨", [1, 6, 10])
def test_성장한_캐릭터는_표준_모양이다(직업, 레벨):
    rng.시드(1)
    상태 = support.새게임([("", 직업)])
    캐릭터 = 상태["파티"]["파티원"][0]
    if 레벨 > 1:
        support.성장(상태, 캐릭터, 레벨, 전직=전직[직업] if 레벨 >= 6 else None)
    assert 스키마.캐릭터_문제목록(캐릭터, 엄격=True) == []


def test_영입한_캐릭터와_불러온_캐릭터도_표준_모양이다(임시_세이브폴더):
    상태 = support.새게임(
        [("", "귀검사"), ("", "마법사"), ("", "거너"), ("", "프리스트")]
    )
    상태["소지품"]["골드"] = 10_000
    gf.파티원_영입(상태, "새동료", "격투가")
    숙소 = gf.숙소_목록(상태)
    assert 숙소 and 스키마.캐릭터_문제목록(숙소[0], 엄격=True) == []

    gf.게임_저장(상태, 1)
    불러옴 = gf.게임_불러오기(1)
    for 캐릭터 in 불러옴["파티"]["파티원"] + 불러옴["모험단숙소"]:
        assert 스키마.캐릭터_문제목록(캐릭터, 엄격=True) == []
    assert 스키마.게임상태_문제목록(불러옴) == []


def test_옛_세이브를_불러와도_표준_모양으로_돌아온다(임시_세이브폴더):
    """옛 세이브는 칸이 빠져 있어도 불러올 때(마이그레이션 + 재계산) 표준 모양이 돼야 한다."""
    상태 = support.새게임([("", "마법사")])
    gf.게임_저장(상태, 1)
    경로 = 임시_세이브폴더 / "slot_1.json"
    데이터 = json.loads(경로.read_text(encoding="utf-8"))
    del 데이터["버전"]
    del 데이터["진행도"]["플레이어레벨"]
    for c in 데이터["플레이어"]["파티"]["파티원"]:
        for 칸 in (
            "성별",
            "횟수제한스킬",
            "치명타주사위",
            "전직",
            "직업스타일",
            "레벨당체력증가",
        ):
            c.pop(칸, None)
    경로.write_text(json.dumps(데이터, ensure_ascii=False), encoding="utf-8")
    불러옴 = gf.게임_불러오기(1)
    assert 스키마.캐릭터_문제목록(불러옴["파티"]["파티원"][0], 엄격=True) == []
    assert 스키마.게임상태_문제목록(불러옴) == []


def test_전투_참가자는_표준_모양이다():
    rng.시드(2)
    상태 = support.새게임(
        [("", "귀검사"), ("", "마법사"), ("", "거너"), ("", "프리스트")]
    )
    for c in 상태["파티"]["파티원"]:
        support.성장(상태, c, 10, 전직=전직[c["직업"]])
    gf.파티_최대치로_회복(상태)
    # 몬스터 종류를 넓게: 일반/보스/소환/기타행동이 있는 것
    gf.전투_시작(
        상태,
        ["고블린", "정원사 랄", "결빙의 케라하", "타우 비스트", "황금 고블린"][:4],
        레벨=6,
        차수=2,
    )
    support.반응_처리(상태)
    전투상태 = 상태["전투상태"]
    for 참가자 in 전투상태["참가자"]:
        assert 스키마.참가자_문제목록(참가자, 엄격=True) == [], 참가자["이름"]
    assert 스키마.게임상태_문제목록(상태) == []
    assert {p["진영"] for p in 전투상태["참가자"]} == {"아군", "적"}


