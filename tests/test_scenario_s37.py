"""S37 스핏파이어 실전 - 장전 탄, 공중사격, 류탄, 오버차지 (docs/scenarios.md).

거너 둘(스핏파이어, 레인저)이 든 4인 파티를 레벨 9까지 키운다(나머지는 기본 전직, 스킬 전부 습득). 타우 아미·루가루·
고블린(레벨 15 차수 3)과 **실제 전투로** 싸운다. 스핏파이어는 1라운드에 오버차지를 쓰지 않고 공중사격(보조행동)을 건 뒤
교차사격, 2라운드부터는 오버차지가 없으면 걸고, 장전 탄(냉동탄·작열탄·철갑탄·은탄 중 가장 덜 쓴 것)을 보조행동으로
장전하고 류탄(빙결류탄·섬광류탄 중 가장 덜 쓴 것)을 던진 뒤 남은 일반행동으로 일반공격한다. 레인저는 은탄을 장전하고
난사(사격 - 타격마다 장전)를 쓴다. 다른 두 파티원은 스킬 우선 정책으로 싸운다.

불변식: 공중사격 중에는 고각도 슬라이딩·장전 스킬을 쓸 수 없고 교차사격은 쓸 수 있다. 탄약·수류탄은 전투를
최대(2+차수)로 시작한다. 장전 탄이 실전에서 소모되고(냉동탄 빙결/작열탄 범위·화상 로그), 오버차지 동안은 장전과
수류탄이 줄지 않는다(류탄을 던져도 수류탄 그대로). 수치 규칙은 tests/test_gunner_bullets.py, tests/test_job_spitfire.py.
"""

import pytest

from game.system import rng
import gameflow as gf
import scenario
import support
from game.system.combat import core
from tests.support import 구현된_전직

적들 = ["타우 아미", "루가루", "고블린"]
시드 = 0
파티구성 = [("", "거너"), ("", "거너"), ("", "귀검사"), ("", "프리스트")]
탄들 = ("냉동탄", "작열탄", "철갑탄", "은탄")
류탄들 = ("빙결류탄", "섬광류탄")


누적 = {}  # 전투 전체에서 쓴 횟수 - 탄·류탄을 돌려 쓴다(테스트마다 비운다)


def _쓰기(상태, p, 이름, 기록, 대상=None):
    if not gf.스킬_사용_가능여부(상태, p, 이름)[0]:
        return False
    데이터 = 상태["스킬데이터모음"][이름]
    if gf.스킬_실제_타겟(상태, 데이터) in ("자신", "적전체"):
        대상 = None
    elif gf.스킬_실제_타겟(상태, 데이터) == "아군단일":
        대상 = p  # 장탄공급 - 자신에게
    gf.아군_스킬사용(상태, 이름, 중심대상=대상)
    기록[이름] = 기록.get(이름, 0) + 1
    누적[이름] = 누적.get(이름, 0) + 1
    return True


def _일반공격(상태, p):
    전투상태 = 상태["전투상태"]
    while 전투상태["종료"] is None and p["생존"]:
        적 = scenario._살아있는_적(상태)
        if not 적 or not gf.일반공격_가능여부(상태, p):
            break
        gf.아군_일반공격(상태, 적[0])
    if 전투상태["종료"] is None:
        gf.턴_넘기기(상태)


def _덜쓴(목록):
    return sorted(목록, key=lambda n: 누적.get(n, 0))


def _스핏_턴(상태, p, 기록):
    전투상태 = 상태["전투상태"]
    적 = scenario._살아있는_적(상태)
    if 전투상태["라운드"] == 1:
        if _쓰기(상태, p, "공중사격", 기록):
            assert not gf.스킬_사용_가능여부(상태, p, "고각도 슬라이딩")[0]
            assert not gf.스킬_사용_가능여부(상태, p, "냉동탄")[0]
            기록["공중사격중_교차사격가능"] = int(
                gf.스킬_사용_가능여부(상태, p, "교차사격")[0]
            )
        if 적:
            _쓰기(상태, p, "교차사격", 기록, 적[0])
        _일반공격(상태, p)
        return
    if not any(b["이름"] == "오버차지" for b in p["버프"]):
        _쓰기(상태, p, "오버차지", 기록)
    for 이름 in _덜쓴(탄들):
        if _쓰기(상태, p, 이름, 기록, p):
            break
    for 이름 in _덜쓴(류탄들):
        적 = scenario._살아있는_적(상태)
        수류탄 = p["보유자원"].get("수류탄", 0)
        if 적 and _쓰기(상태, p, 이름, 기록, 적[0]):
            if any(b["이름"] == "오버차지" for b in p["버프"]):
                기록["오버차지_수류탄유지"] = 기록.get("오버차지_수류탄유지", 0) + int(
                    p["보유자원"]["수류탄"] == 수류탄
                )
            break
    _일반공격(상태, p)


def _레인저_턴(상태, p, 기록):
    _쓰기(상태, p, "은탄", 기록, p)
    적 = scenario._살아있는_적(상태)
    if 적:
        _쓰기(상태, p, "난사", 기록, 적[0])
    _일반공격(상태, p)


def _전투(상태, 스핏, 레인저, 기록):
    support.반응_처리(상태)
    for p in 상태["전투상태"]["참가자"]:
        if p["원본"] is 스핏:
            최대 = 2 + core.차수(p)
            assert p["보유자원"]["탄약"] == 최대 and p["보유자원"]["수류탄"] == 최대
    for _ in range(400):
        if gf.전투_종료됨(상태):
            break
        참가자 = gf.현재_턴_참가자(상태)
        if 참가자["진영"] == "아군" and 참가자["생존"]:
            if 참가자["원본"] is 스핏:
                _스핏_턴(상태, 참가자, 기록)
            elif 참가자["원본"] is 레인저:
                _레인저_턴(상태, 참가자, 기록)
            else:
                scenario.스킬_우선_턴(상태, [])
        else:
            gf.턴_넘기기(상태)
    else:
        raise AssertionError("전투가 끝나지 않았다")
    기록["라운드"] = 상태["전투상태"]["라운드"]
    비고들 = [
        str(항목.get("비고"))
        for 항목 in 상태["전투상태"]["로그"]
        if isinstance(항목, dict) and 항목.get("비고")
    ]
    for 탄, 말 in (
        ("냉동탄", "'빙결'"),
        ("작열탄", "'화상'"),
        ("작열탄", "범위 피해"),
    ):
        기록[f"{탄} {말}"] = sum(1 for b in 비고들 if f"'장전 : {탄}'" in b and 말 in b)
    return 상태["전투상태"]["종료"]


@pytest.mark.scenario("S37")
def test_S37_스핏파이어_실전(golden):
    rng.시드(시드)
    누적.clear()
    상태 = support.새게임(파티구성)
    스핏, 레인저, 귀, 프 = 상태["파티"]["파티원"]
    support.성장(상태, 스핏, 9, 전직="스핏파이어", 스킬습득=True)
    support.성장(상태, 레인저, 9, 전직="레인저", 스킬습득=True)
    for c in (귀, 프):
        support.성장(상태, c, 9, 전직=구현된_전직[c["직업"]], 스킬습득=True)
    assert gf.캐릭터_직업표시(스핏).startswith("스핏파이어")
    assert {"강화탄", "매거진 드럼", "유탄 마스터리", "니트로모터", "장탄공급"} <= set(
        스핏["보유특성"]
    )

    전투들 = []
    볼것 = (
        "공중사격",
        "공중사격중_교차사격가능",
        "교차사격",
        "오버차지",
        "냉동탄 '빙결'",
        "작열탄 '화상'",
        "작열탄 범위 피해",
        "빙결류탄",
        "섬광류탄",
        "오버차지_수류탄유지",
        "난사",
    )
    for _ in range(10):
        gf.파티_최대치로_회복(상태)
        gf.휴식(상태)  # 레벨 8 버프는 휴식당 1회
        gf.전투_시작(상태, 적들, 레벨=15, 차수=3)
        기록 = {}
        종료 = _전투(상태, 스핏, 레인저, 기록)
        assert gf.전투_결과_정리(상태) == 종료 == "아군승리"
        전투들.append(기록)
        if all(sum(b.get(k, 0) for b in 전투들) for k in 볼것):
            break

    합계 = {k: sum(b.get(k, 0) for b in 전투들) for k in 볼것}
    assert all(합계.values()), 합계
    assert all(b.get("오버차지", 0) <= 1 for b in 전투들), 전투들  # 휴식당 1회
    golden("scenario_S37_spitfire", 전투들)
