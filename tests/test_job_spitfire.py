def test_공중사격은_보조행동_MP5로_AC와_명중을_올리고_니트로모터면_2턴(스핏전장):
    _, 전투상태, _, s = 스핏전장
    AC = stats.최종AC(전투상태, s)
    명중 = stats.버프디버프_수치(전투상태, s, "명중보너스")
    MP = s["현재MP"] = 50
    s["행동자원"].update(일반행동=1, 보조행동=1)
    ss.스킬_실행(전투상태, s, "공중사격", _스킬("공중사격"))
    assert s["행동자원"]["보조행동"] == 0 and s["현재MP"] == MP - 5
    assert stats.최종AC(전투상태, s) == AC + 1
    assert stats.버프디버프_수치(전투상태, s, "명중보너스") == 명중 + 1
    버프 = next(b for b in s["버프"] if b["이름"] == "공중사격")
    assert 버프["지속턴"] == 2  # 1턴 + 니트로모터 1턴


def test_공중사격_중에는_일반공격_교차사격_류탄만_쓴다(스핏전장):
    _, 전투상태, _, s = 스핏전장
    assert _가능(전투상태, s, "고각도 슬라이딩") and _가능(전투상태, s, "은탄")
    _쓰기(전투상태, s, "공중사격")
    assert not _가능(전투상태, s, "고각도 슬라이딩")
    assert not _가능(전투상태, s, "은탄")  # 장전도 못 한다
    assert not _가능(전투상태, s, "라이징 샷")
    assert _가능(전투상태, s, "교차사격")
    assert _가능(전투상태, s, "빙결류탄") and _가능(전투상태, s, "파열류탄")


