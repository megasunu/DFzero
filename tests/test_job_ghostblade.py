마스터리5종 = [
    "소검 마스터리",
    "도 마스터리",
    "둔기 마스터리",
    "대검 마스터리",
    "광검 마스터리",
]


@pytest.fixture
def 검귀전장():
    """귀검사 -> 검귀 레벨 8(스킬 전부 습득)과 격투가, 고블린 셋. 근력 20(보정치 5), 민첩 10."""
    rng.시드(7)
    상태 = support.새게임([("", "귀검사"), ("", "격투가")])
    c = 상태["파티"]["파티원"][0]
    support.성장(상태, c, 8, 전직="검귀", 스킬습득=True)
    gf.전투_시작(상태, ["고블린", "고블린", "고블린"], 레벨=2, 차수=1)
    support.반응_처리(상태)
    전투상태 = 상태["전투상태"]
    적 = sorted(
        (p for p in 전투상태["참가자"] if p["진영"] == "적"),
        key=lambda p: p["대형위치"],
    )
    검귀 = next(p for p in 전투상태["참가자"] if p["원본"].get("전직") == "검귀")
    for p in 적:
        p["현재HP"] = 999
    검귀["원본"]["근력"] = 20
    검귀["원본"]["민첩"] = 10
    _무기(검귀, "도")
    assert stats.평타_능력치_보정치(전투상태, 검귀) == 5
    return 상태, 전투상태, 적, 검귀


def _무기(p, 종류):
    p["장비데이터"] = dict(
        p.get("장비데이터") or {},
        무기={"이름": "시험 무기", "타입": 종류, "무기공격력": "1d8"},
    )


def _굴림(전투상태, p, 식="보정공격력", 치명타=False):
    컨텍스트 = stats.기본_컨텍스트(전투상태, p, 무기공격력필요=True)
    return stats.피해_굴림(전투상태, p, 식, 컨텍스트, 치명타=치명타)


def _귀혼일체(전투상태, p):
    스킬 = dict(
        gf.전직_레지스트리["귀검사"]["검귀"]["스킬목록"]["귀혼일체"], _이름="귀혼일체"
    )
    ss.버프자원소환_스킬_실행(전투상태, p, 스킬)


