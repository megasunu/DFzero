@pytest.mark.parametrize(
    "패턴, 타격수, 한번",
    [("일섬", 1, 18), ("연참", 4, 5), ("회천", 3, 9)],  # 연참은 9/2 올림
)
def test_원귀는_무작위_패턴으로_치고_원귀_상태가_된다(
    스킬전장, monkeypatch, 패턴, 타격수, 한번
):
    _, 전투상태, 적, 검귀, 피해들, 판정들 = 스킬전장
    MP = 검귀["현재MP"]
    결과 = _원귀(전투상태, 검귀, 적[1], 패턴, monkeypatch)
    assert 결과["스킬"] == f"원귀 : {패턴}"
    assert [피해 for _, 피해 in 피해들] == [한번] * 타격수
    if 패턴 == "회천":  # 지정한 적과 양옆
        assert {이름 for 이름, _ in 피해들} == {e["이름"] for e in 적}
    else:
        assert {이름 for 이름, _ in 피해들} == {적[1]["이름"]}
    assert len(판정들) == (4 if 패턴 == "연참" else 타격수)  # 연참은 타격마다 명중굴림
    assert 검귀["현재MP"] == MP - 10
    assert 검귀["행동자원"]["보조행동"] == 0 and 검귀["행동자원"]["일반행동"] == 1
    [원귀] = [b for b in 검귀["버프"] if b["이름"] == "원귀"]
    assert 원귀["패턴"] == 패턴


