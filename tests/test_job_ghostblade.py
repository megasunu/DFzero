def test_레벨6에_청혈투귀와_검귀의_도_마스터리를_얻고_무기_마스터리는_사라진다():
    rng.시드(7)
    상태 = support.새게임([("", "귀검사")])
    c = 상태["파티"]["파티원"][0]
    support.성장(상태, c, 5)
    가졌던것 = [n for n in 마스터리5종 if n in c["보유특성"]]
    assert 가졌던것  # 레벨 2에 고른 무기 마스터리
    support.성장(상태, c, 6, 전직="검귀")
    assert {"청혈투귀", "검귀의 도 마스터리"} <= set(c["보유특성"])
    assert not any(n in c["보유특성"] for n in 마스터리5종)
    support.성장(상태, c, 8)
    assert "귀혼일체" in c["보유스킬"]


def test_검귀는_퍽으로_무기_마스터리를_다시_고를_수_없다():
    rng.시드(7)
    상태 = support.새게임([("", "귀검사")])
    c = 상태["파티"]["파티원"][0]
    support.성장(상태, c, 5)
    퍽목록 = gf.캐릭터_전체퍽(c)
    assert (
        gf.퍽_선택상태(c, 퍽목록["대검 마스터리"]) is not None
    )  # 귀검사는 고를 수 있다
    support.성장(상태, c, 6, 전직="검귀")
    for 이름 in 마스터리5종:
        assert gf.퍽_선택상태(c, 퍽목록[이름]) is None, 이름


