def test_도를_들면_명중1과_보정치가_한번_더_들어간다(검귀전장, monkeypatch):
    _, 전투상태, _, 검귀 = 검귀전장
    support.주사위고정(monkeypatch, 4)
    명중 = traits.특성_수치(전투상태, 검귀, "명중보너스")
    assert _굴림(전투상태, 검귀) == 4 + 5 + 5
    assert (
        _굴림(전투상태, 검귀, "무기공격력") == 4 + 5
    )  # 무기공격력만 쓰는 공격도 무기 공격
    _무기(검귀, "소검")
    assert _굴림(전투상태, 검귀) == 4 + 5
    assert _굴림(전투상태, 검귀, "무기공격력") == 4
    assert traits.특성_수치(전투상태, 검귀, "명중보너스") == 명중 - 1


def test_도로_치명타가_나면_무기_주사위_대신_치명타_주사위마다_보정치를_더한다(
    검귀전장, monkeypatch
):
    _, 전투상태, _, 검귀 = 검귀전장
    support.주사위고정(monkeypatch, 4)
    # 치명타 주사위 2개(기본 1 + 청혈투귀): 무기 4 + 보정치 5 x 2 + 보정치 5 + 도 마스터리 5
    assert _굴림(전투상태, 검귀, 치명타=True) == 4 + 10 + 5 + 5
    ss.이름있는효과_부여(전투상태, 검귀, "치명타피해증가", 지속턴오버라이드=3)
    assert stats.치명타_주사위수(전투상태, 검귀) == 3
    assert (
        _굴림(전투상태, 검귀, 치명타=True) == 4 + 15 + 5 + 5
    )  # 근력 20이면 5 x 3 = 15
    _무기(검귀, "소검")  # 다른 무기는 원래대로 무기 주사위가 는다
    assert _굴림(전투상태, 검귀, 치명타=True) == 4 * 4 + 5


def test_일반공격도_도_마스터리를_받는다(검귀전장, monkeypatch):
    _, 전투상태, 적, 검귀 = 검귀전장
    받은피해 = []

    def 피해_기록(전투상태, 대상, 피해, **kw):
        받은피해.append(피해)
        return 피해

    monkeypatch.setattr(damage, "피해_적용", 피해_기록)
    monkeypatch.setattr(
        damage,
        "명중_판정",
        lambda *a, **kw: {
            "성공": True,
            "자연눈": 15,
            "치명타": False,
            "자동실패": False,
        },
    )
    support.주사위고정(monkeypatch, 4)
    attacks.일반공격_실행(전투상태, 검귀, 적[0])
    _무기(검귀, "소검")
    attacks.일반공격_실행(전투상태, 검귀, 적[0])
    assert 받은피해[0] - 받은피해[1] == 5


