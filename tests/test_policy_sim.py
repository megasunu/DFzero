"""측정용 전투 정책(tools/policy_sim.py, #675) - 분석용(무작위)과 승률용(몬테카를로 탐색).

실제 비교(수백 판)는 게이트 밖에서 돌린다. 여기서는 몇 판만 돌려 정책의 약속을 지킨다:
합법 행동만 고른다, 같은 시드면 같은 결과, 게임 난수 흐름과 상태를 건드리지 않고 탐색한다, 승률용이 무작위보다 낫다.
"""

import collections
import copy

import gameflow as gf
from game.system import rng
from tools import policy_sim as ps

_파티 = (
    ("귀검사", "웨펀마스터"),
    ("거너", "레인저"),
    ("프리스트", "크루세이더"),
    ("마법사", "엘리멘탈마스터"),
)
_가벼운탐색 = {"후보수": 4, "횟수": 1, "라운드": 1}


def test_균등_파티는_전직마다_같은_횟수로_나오고_한_파티에_같은_전직이_없다():
    파티들 = ps.균등_파티(12, 시드=3)
    assert len(파티들) == 12 and all(len(p) == 4 for p in 파티들)
    assert all(len(set(p)) == 4 for p in 파티들)
    횟수 = collections.Counter(전직 for p in 파티들 for _, 전직 in p)
    assert len(횟수) == 24 and set(횟수.values()) == {2}
    assert ps.균등_파티(12, 시드=3) == 파티들


class _검사하는_무작위(ps.무작위정책):
    """고른 행동이 그 순간 합법인지 본다."""

    def __init__(self, 시드):
        super().__init__(시드)
        self.본수 = 0

    def 고르기(self, 상태, 참가자, 후보):
        i = super().고르기(상태, 참가자, 후보)
        행동, 대상id = 후보[i]
        if 행동 == "일반공격":
            assert gf.일반공격_가능여부(상태, 참가자)
        else:
            assert gf.스킬_사용_가능여부(상태, 참가자, 행동)[0]
        if 대상id is not None:
            대상 = ps.참가자_찾기(상태, 대상id)
            assert 대상["생존"] and 대상["진영"] != "아군"
        self.본수 += 1
        return i


def test_무작위정책은_합법_행동만_고르고_여러_행동을_쓴다():
    정책 = _검사하는_무작위(7)
    행동 = collections.Counter()
    for 시드 in range(3):
        r = ps.한판(_파티, 정책, 시드)
        행동.update((a["전직"], a["행동"]) for a in r["행동"])
    assert 정책.본수 == sum(행동.values()) > 0
    # 일반공격만 반복하지 않는다 - 스킬도 고르게 나온다
    assert (
        sum(n for (_, 행동이름), n in 행동.items() if 행동이름 != "일반공격")
        > 행동[("웨펀마스터", "일반공격")]
    )


def test_한판_결과는_승패_파티원별_딜_받은피해_생존_행동기록을_낸다():
    r = ps.한판(_파티, ps.무작위정책(1), 시드=2)
    assert isinstance(r["승"], bool)
    이름들 = set(r["파티원"])
    assert len(이름들) == 4
    for 칸 in r["파티원"].values():
        assert set(칸) >= {"전직", "딜", "받음", "생존"}
    assert r["행동"] and set(r["행동"][0]) >= {
        "이름",
        "전직",
        "행동",
        "표적",
        "피해",
        "라운드",
    }
    assert {a["이름"] for a in r["행동"]} <= 이름들


def test_같은_시드면_같은_결과이고_정책_시드가_다르면_행동이_달라진다():
    a = ps.한판(_파티, ps.무작위정책(5), 시드=4)
    b = ps.한판(_파티, ps.무작위정책(5), 시드=4)
    c = ps.한판(_파티, ps.무작위정책(6), 시드=4)
    assert a == b
    assert [x["행동"] for x in a["행동"]] != [x["행동"] for x in c["행동"]]
    t1 = ps.한판(_파티, ps.탐색정책(5, **_가벼운탐색), 시드=4)
    t2 = ps.한판(_파티, ps.탐색정책(5, **_가벼운탐색), 시드=4)
    assert t1 == t2


def test_탐색은_게임_상태와_난수_흐름을_건드리지_않는다():
    상태 = ps.전투_준비(_파티, 시드=9)
    정책 = ps.탐색정책(1, **_가벼운탐색)
    참가자 = gf.현재_턴_참가자(상태)
    while 참가자["진영"] != "아군":
        gf.턴_넘기기(상태)
        참가자 = gf.현재_턴_참가자(상태)
    후보 = 정책.후보(상태, 참가자)
    assert len(후보) > 1
    전 = copy.deepcopy(상태["전투상태"])
    난수 = rng.상태()
    i = 정책.고르기(상태, 참가자, 후보)
    assert 0 <= i < len(후보)
    assert rng.상태() == 난수
    assert 상태["전투상태"] == 전


def test_승률용은_무작위보다_잘_싸운다():
    무작위 = [
        ps.한판(_파티, ps.무작위정책(s), 시드=s, 조건=ps.어려운_조건) for s in range(4)
    ]
    탐색 = [
        ps.한판(_파티, ps.탐색정책(s, **_가벼운탐색), 시드=s, 조건=ps.어려운_조건)
        for s in range(4)
    ]
    assert sum(ps.판_점수(r) for r in 탐색) > sum(ps.판_점수(r) for r in 무작위)


def test_행동_요약은_행동별_사용횟수_판당딜_사용한_판과_안_쓴_판의_승률을_낸다():
    판들 = [
        {
            "승": True,
            "행동": [
                {"전직": "A", "행동": "x", "피해": 10},
                {"전직": "A", "행동": "x", "피해": 6},
            ],
        },
        {"승": False, "행동": [{"전직": "A", "행동": "y", "피해": 3}]},
        {"승": True, "행동": [{"전직": "A", "행동": "y", "피해": 1}], "파티원": {}},
    ]
    for r in 판들:
        r["파티원"] = {"a": {"전직": "A"}}
    요약 = ps.행동_요약(판들)
    x = 요약[("A", "x")]
    assert (x["횟수"], x["판"], x["평균피해"]) == (2, 1, 8.0)
    assert x["쓴판승률"] == 1.0 and x["안쓴판승률"] == 0.5
    y = 요약[("A", "y")]
    assert (y["판"], y["쓴판승률"], y["안쓴판승률"]) == (2, 0.5, 1.0)
