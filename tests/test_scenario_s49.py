"""S49 상점 경제 실전 - 상점 탭 거르기, 구매, 전리품 판매, 일괄해체 (docs/scenarios.md, #74).

4인 기본 파티가 로리엔 인카운트 3번과 보스를 **실전으로** 이기고 전리품·보상을 모은다. 엘븐가드로 걸어 돌아와
상점 탭(장비 2줄, 해체 [전체], 무기 직업군 -> 종류, 방어구 재질)으로 마을 판매목록을 걸러 귀검사 무기와
천갑 상의를 산다. 상의 탭 일괄해체로 산 상의를 해체하고(커먼 상의 전리품도 같이, 장착 중인 것은 대상이 아니다),
산 무기를 장착한 뒤 남은 커먼 장비를 [전체] 일괄해체한다 - 다시 하면 대상이 없다. 얻은 소울과 잡템을 팔아
골드를 받고, 산 무기로 로리엔 인카운트를 다시 실전으로 이긴다. 저장/불러오기 뒤 소지품이 그대로다.
해체 재료 확률·판매가 공식 같은 값은 test_shop_loot.py가 본다.
"""

import pytest

from game.data.town.town_01A_T01_Elvengard import 마을정보 as 엘븐가드
from game.system import rng
import gameflow as gf
import scenario
import support

시드 = 1
_로리엔 = "dungeon_01A_D01_Lorien"
_엘븐가드 = "town_01A_T01_Elvengard"
_판매목록 = 엘븐가드["상점판매목록"]


def _인카운트_실전(상태):
    적 = scenario.인카운트까지_걷기(상태)
    종료 = scenario.실전(상태)
    assert gf.전투_결과_정리(상태) == 종료 == "아군승리", 종료
    if gf.전투_보상_대기중(상태):
        scenario.보상_수령(상태)
    return 적


def _장비수(상태):
    return sum(상태["소지품"]["장비"].values())


def _장착수(상태, 이름):
    return sum(
        1 for c in 상태["파티"]["파티원"] for v in c["장착장비"].values() if v == 이름
    )


@pytest.mark.scenario("S49")
def test_S49_상점_경제_실전(golden):
    rng.시드(시드)
    상태 = support.새게임()
    파티 = 상태["파티"]["파티원"]
    귀검사 = next(c for c in 파티 if c["직업"] == "귀검사")
    기록 = {}

    # 1) 로리엔 실전 3번 + 보스 - 전리품과 보상이 소지품에 들어온다
    장비전 = _장비수(상태)
    gf.던전_진입(상태, _로리엔)
    기록["인카운트"] = [_인카운트_실전(상태) for _ in range(3)]
    결과, _ = support.보스_처치(상태, 전투처리=scenario.실전)
    assert 결과 == "아군승리"
    if gf.전투_보상_대기중(상태):
        scenario.보상_수령(상태)
    support.연결로_나가기(상태, _엘븐가드, 전투처리=scenario.실전)
    assert 상태["던전상태"] is None
    gf.휴식(상태)
    기록["모은_장비"] = _장비수(상태) - 장비전
    assert 기록["모은_장비"] > 0

    # 2) 상점 탭 - 장비는 2줄, 해체는 윗줄 맨 앞이 [전체], 소모품은 1줄
    윗줄, 아랫줄 = gf.상점_탭줄("구매", "장비")
    assert 윗줄[0] == "무기" and "상의" in 윗줄 and 아랫줄
    assert gf.상점_탭줄("해체", "장비")[0][0] == "전체"
    assert len(gf.상점_탭줄("구매", "소모품")) == 1
    assert gf.상점_구매목록(상태, "재료", "소울", _판매목록) == []  # 재료는 팔지 않는다

    # 3) 무기 탭 거르기: 직업군 귀검사 -> 종류, 도 탭의 첫 무기를 산다
    직업군탭 = gf.상점_무기_직업군탭(상태)
    assert 직업군탭[0] == "전체" and "귀검사" in 직업군탭
    assert gf.상점_무기_종류탭(상태, None) == []
    종류탭 = gf.상점_무기_종류탭(상태, "귀검사")
    assert (
        종류탭[0] == "전체" and "도" in 종류탭
    )  # 도: 레벨 1 귀검사가 들 수 있는 다른 종류
    무기들 = [
        i
        for i in gf.상점_구매목록(상태, "장비", "무기", _판매목록)
        if gf.상점_분류_일치("무기", i, "귀검사", "도") and i.get("레어도") != "치트"
    ]
    assert 무기들 and all(i["타입"] == "도" for i in 무기들)
    무기 = 무기들[0]["이름"]

    # 4) 방어구 재질 탭: 천갑 상의
    assert gf.상점_방어구_재질탭[0] == "전체" and "상의" in gf.상점_방어구_부위
    상의들 = [
        i
        for i in gf.상점_구매목록(상태, "장비", "상의", _판매목록)
        if gf.상점_분류_일치("상의", i, None, "천갑")
    ]
    assert 상의들 and all(i["재질"] == "천갑" for i in 상의들)
    상의 = 상의들[0]["이름"]

    상태["소지품"]["골드"] += 500
    with pytest.raises(ValueError):
        gf.상점_구매(
            상태, "장비", "상의", 상의, gf.상점_최대구매수량 + 1, 상점판매목록=_판매목록
        )
    골드 = 상태["소지품"]["골드"]
    지불 = gf.상점_구매(상태, "장비", "무기", 무기, 1, 상점판매목록=_판매목록)
    지불 += gf.상점_구매(상태, "장비", "상의", 상의, 2, 상점판매목록=_판매목록)
    assert 상태["소지품"]["골드"] == 골드 - 지불

    # 5) 상의 탭 일괄해체 - 산 상의 2개와 같은 레어도 상의 전리품, 장착 중인 상의는 남는다
    레어도 = 상의들[0]["레어도"]
    assert 레어도 in gf.상점_해체_등급목록
    대상 = gf.상점_일괄해체_대상(상태, 레어도, "상의")
    assert (상의, 상태["소지품"]["장비"][상의] - _장착수(상태, 상의), "상의") in 대상
    assert all(탭 == "상의" for _, _, 탭 in 대상)
    수, 재료 = gf.상점_일괄해체(상태, 레어도, "상의")
    assert 수 == sum(n for _, n, _ in 대상) and 재료
    assert 상태["소지품"]["장비"].get(상의, 0) == _장착수(상태, 상의)
    기록["상의_일괄해체"] = [수, 재료]

    # 6) 산 무기를 장착하고 [전체] 커먼 일괄해체 - 장착 중인 것은 빼고 모두, 다시 하면 대상이 없다
    gf.장비_교체(상태, 귀검사, "무기", 무기)
    assert 귀검사["장착장비"]["무기"] == 무기
    전체대상 = gf.상점_일괄해체_대상(상태, "커먼", "전체")
    assert all(이름 != 무기 for 이름, _, _ in 전체대상)
    if 전체대상:
        수, 재료 = gf.상점_일괄해체(상태, "커먼", "전체")
        assert 수 == sum(n for _, n, _ in 전체대상)
        기록["전체_일괄해체"] = [수, 재료]
    with pytest.raises(ValueError):
        gf.상점_일괄해체(상태, "커먼", "전체")
    assert gf.상점_일괄해체_대상(상태, "커먼", "전체") == []
    assert 귀검사["장착장비"]["무기"] == 무기  # 장착 중인 무기는 남는다

    # 7) 판매 - 소울과 잡템을 판다
    판매 = {}
    for 탭 in ("소울", "잡템"):
        for 아이템, 수량 in gf.상점_판매목록(상태, "재료", 탭):
            골드 = 상태["소지품"]["골드"]
            받음 = gf.상점_판매(상태, "재료", 탭, 아이템["이름"], 수량)
            assert 받음 == gf.상점_판매가(아이템) * 수량
            assert 상태["소지품"]["골드"] == 골드 + 받음
            판매[아이템["이름"]] = [수량, 받음]
        assert gf.상점_판매목록(상태, "재료", 탭) == []
    assert 판매
    기록["판매"] = 판매

    # 8) 산 무기로 다시 실전
    gf.던전_진입(상태, _로리엔)
    기록["다시_인카운트"] = _인카운트_실전(상태)

    # 9) 저장/불러오기
    gf.게임_저장(상태, 1)
    불러옴 = gf.게임_불러오기(1)
    assert 불러옴["소지품"] == 상태["소지품"]
    기록["산_것"] = [무기, 상의]
    기록["골드"] = 상태["소지품"]["골드"]
    golden("scenario_S49_shop_economy", 기록)
