"""S53 자동전투 100라운드 패배 - 이길 수 없는 인카운트 -> 자동전투 101라운드에 패배 -> 패배 귀환 -> 다음 실전 (#670).

레벨 10 웨펀마스터 혼자(측정 장비 + 수속성 레어 무기 나일블루)가 로리엔 인카운트에서 "이뮨-수속성" 챔피언을 만난다.
모든 공격이 수속성이라 피해를 줄 수 없고 상대도 웨펀마스터를 쓰러뜨리지 못해 전투가 끝나지 않는다(이뮨은 의도한 규칙,
2026-11-12 사용자 결정). [자동전투]로 진행하면 100라운드가 지난 뒤 패배로 끝나고, 패배 흐름(결과 정리 -> 패배 귀환:
마을에서 다 회복, 자동 저장)을 탄다. 그 뒤 같은 파티가 챔피언 없는 인카운트를 실전으로 이긴다.
챔피언 버프는 무작위라 이 시나리오만 챔피언 부여를 고정한다(그 뒤 원래대로). 제한 규칙의 경계는 test_autobattle_round_limit.py.
"""

import pytest

from game.system import dungeon_system, rng
import gameflow as gf
import scenario
import support

# 시드 5는 고블린 둘이 웨펀마스터를 쓰러뜨리지 못해 끝나지 않는 시드다(1~4·6·7은 고블린 투척병이 섞여 먼저 진다)
시드 = 5
_로리엔 = "dungeon_01A_D01_Lorien"


def _이뮨_챔피언(등장몬스터, 몬스터목록):
    return [
        {
            "이름": 이름,
            "칭호": "챔피언",
            "돌연변이": "저주받은",
            "챔피언버프": ["이뮨-수속성"],
        }
        for 이름 in 등장몬스터
    ]


@pytest.mark.scenario("S53")
def test_S53_자동전투_100라운드_패배(monkeypatch, 임시_세이브폴더):
    rng.시드(시드)
    상태 = support.새게임([("", "귀검사")])
    scenario.측정_파티_준비(상태, 10, 전직={"귀검사": "웨펀마스터"})
    웨펀마스터 = 상태["파티"]["파티원"][0]
    # 레벨 7부터 측정 조건의 레어 무기 - 웨펀마스터 추천 종류(소검)의 레어는 수속성 나일블루다
    assert 웨펀마스터["장착장비"]["무기"] == "나일블루"
    assert gf.캐릭터_장착아이템(상태, 웨펀마스터, "무기")["속성"] == "수속성"

    # 1) 이길 수 없는 인카운트 - 자동전투가 100라운드 뒤 패배로 끝낸다
    with monkeypatch.context() as m:
        m.setattr(dungeon_system, "챔피언_부여", _이뮨_챔피언)
        gf.던전_진입(상태, _로리엔)
        scenario.인카운트까지_걷기(상태)
    전투상태 = 상태["전투상태"]
    종료 = scenario.실전(상태, 최대반복=1000)
    assert 종료 == "적승리"
    assert 전투상태["라운드"] == gf.자동전투_최대라운드 + 1
    assert any(e["생존"] for e in gf.적_목록(상태))  # 적은 남아 있다
    assert gf.아군_목록(상태)[0]["생존"]  # 쓰러져서 진 것이 아니다
    assert gf.로그_문장들(전투상태["로그"][-1]) == [
        "100라운드가 지나도 전투가 끝나지 않아 패배했다."
    ]

    # 2) 패배 흐름 - 결과 정리, 패배 귀환(마을에서 다 회복, 자동 저장)
    assert gf.전투_결과_정리(상태) == "적승리"
    assert not gf.전투_보상_대기중(상태)
    gf.패배_귀환(상태)
    assert 상태["던전상태"] is None  # 던전을 나와 마을로(#671)
    assert 웨펀마스터["현재HP"] == gf.캐릭터_최대HP(상태, 웨펀마스터)
    assert gf.세이브_존재(gf.자동저장슬롯)

    # 3) 다음 전투 - 챔피언 없는 인카운트는 실전으로 이긴다
    monkeypatch.setattr(dungeon_system, "챔피언_확률", 0.0)
    gf.던전_진입(상태, _로리엔)
    scenario.인카운트까지_걷기(상태)
    전투상태 = 상태["전투상태"]
    종료 = scenario.실전(상태)
    assert 전투상태["라운드"] <= gf.자동전투_최대라운드
    assert gf.전투_결과_정리(상태) == 종료 == "아군승리"
