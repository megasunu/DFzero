def test_윌_오브_피스트는_근력_1과_속도_2():
    rng.시드(5)
    상태 = support.새게임([("", "프리스트")])
    c = 상태["파티"]["파티원"][0]
    support.성장(상태, c, 5)
    근력 = c["근력"]
    # 역할은 그대로 두고 특성의 +1만 본다
    support.성장(
        상태,
        c,
        6,
        전직="인파이터",
        스탯구성={r: c[r] for r in ("주스탯", "보조스탯", "약점스탯")},
    )
    assert c["근력"] == 근력 + 1
    _, 전투상태, _, m = _전장()
    속도 = stats.속도보너스_합(전투상태, m)
    m["원본"]["보유특성"].remove("윌 오브 피스트")
    assert stats.속도보너스_합(전투상태, m) == 속도 - 2


