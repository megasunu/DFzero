def _전장(전직="인파이터", 무기=None):
    """프리스트 -> 전직 레벨 8(골드 스킬 전부)과 귀검사, 고블린 셋(HP 999)."""
    rng.시드(5)
    상태 = support.새게임([("", "프리스트"), ("", "귀검사")])
    인, _ = 상태["파티"]["파티원"]
    support.성장(상태, 인, 8, 전직=전직, 스킬습득=True)
    if 무기:
        상태["소지품"]["장비"][무기] = 1
        gf.장비_교체(상태, 인, "무기", 무기)
    gf.전투_시작(상태, ["고블린", "고블린", "고블린"], 레벨=2, 차수=1)
    support.반응_처리(상태)
    전투상태 = 상태["전투상태"]
    적 = sorted(
        (p for p in 전투상태["참가자"] if p["진영"] == "적"),
        key=lambda p: p["대형위치"],
    )
    for p in 적:
        p["현재HP"] = p["최대HP"] = 999
    m = next(p for p in 전투상태["참가자"] if p["원본"] is 인)
    m["장비보너스"] = {}
    return 상태, 전투상태, 적, m


@pytest.fixture
def 인파이터전장():
    return _전장()


def _스킬(이름):
    return dict(gf.스킬데이터모음_생성()[이름], _이름=이름)


def _쓰기(전투상태, p, 이름, 대상=None):
    p["행동자원"].update(일반행동=1, 보조행동=1)
    p["이번턴_스킬사용횟수"] = {}  # 쓸 때마다 새 턴 - 일반공격취급 턴당 1회(2026-11-03)
    p["현재MP"] = max(p["현재MP"], 50)
    return ss.스킬_실행(전투상태, p, 이름, _스킬(이름), 대상)


def _고정(monkeypatch, 눈=15, 피해=None):
    monkeypatch.setattr(stats.dice_utils, "d20_굴림", lambda 이점=False, 불리=False: 눈)
    monkeypatch.setattr(
        rng.주사위, "randint", (lambda a, b: a) if 피해 is None else 피해
    )


def _텐션(p):
    return next((b.get("중첩", 1) for b in p["버프"] if b["이름"] == "텐션"), 0)


def _개방(p):
    return any(b["이름"] == "텐션 개방" for b in p["버프"])


