def test_텐션은_신격권_5번에_개방되고_개방_중엔_쌓이지_않는다(
    인파이터전장, monkeypatch
):
    _, 전투상태, 적, m = 인파이터전장
    _고정(monkeypatch)
    for i in range(4):
        _쓰기(전투상태, m, "원!투!", 적[0])
        assert _텐션(m) == i + 1
    _쓰기(전투상태, m, "더킹")  # 신격권이 아니다
    assert _텐션(m) == 4
    _쓰기(전투상태, m, "고저스 컴비네이션", 적[0])
    assert _텐션(m) == 0 and _개방(m)
    _쓰기(전투상태, m, "바디블로", 적[1])
    assert _텐션(m) == 0
    # 다음 턴에 텐션행동
    flow.행동자원_채우기(전투상태, m)
    assert m["기타행동"]["텐션행동"] == 1


def test_매스_피스톨은_텐션행동으로만_쓰고_쓰면_개방이_끝난다(
    인파이터전장, monkeypatch
):
    _, 전투상태, 적, m = 인파이터전장
    _고정(monkeypatch)
    assert not ss.사용_가능여부(전투상태, m, _스킬("매스 피스톨"))[0]
    for _ in range(5):
        _쓰기(전투상태, m, "원!투!", 적[0])
    flow.행동자원_채우기(전투상태, m)
    m["현재MP"] = 50
    assert ss.사용_가능여부(전투상태, m, _스킬("매스 피스톨"))[0]
    전 = 999 - 적[1]["현재HP"]
    결과 = ss.스킬_실행(전투상태, m, "매스 피스톨", _스킬("매스 피스톨"), 적[1])
    assert m["현재MP"] == 50
    assert m["행동자원"]["일반행동"] == 1  # 일반행동은 그대로
    assert m["기타행동"]["텐션행동"] == 0
    assert not _개방(m)
    assert _텐션(m) == 0
    assert 결과["타격"][0]["피해"] > 전


def test_신기일체는_일반공격과_일반공격취급에_데미지_2와_속도_2(
    인파이터전장, monkeypatch
):
    _, 전투상태, 적, m = 인파이터전장
    _고정(monkeypatch)
    속도 = stats.속도보너스_합(전투상태, m)
    전 = attacks.일반공격_실행(전투상태, m, 적[0])["피해"]
    _쓰기(전투상태, m, "신기일체")
    assert stats.속도보너스_합(전투상태, m) == 속도 + 2
    후 = attacks.일반공격_실행(전투상태, m, 적[1])["피해"]
    assert 후 == 전 + 2


def test_더킹은_1턴_명중_1_스웨이는_2턴_AC_2(인파이터전장):
    _, 전투상태, _, m = 인파이터전장
    AC = stats.최종AC(전투상태, m)
    _쓰기(전투상태, m, "더킹")
    assert m["현재MP"] == 45 and m["행동자원"]["보조행동"] == 0
    assert stats.버프디버프_수치(전투상태, m, "명중보너스") == 1
    _쓰기(전투상태, m, "스웨이")
    assert stats.최종AC(전투상태, m) == AC + 2
    지속 = {b["이름"]: b.get("지속턴") for b in m["버프"]}
    assert (지속["더킹"], 지속["스웨이"]) == (1, 2)


