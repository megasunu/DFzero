@pytest.fixture
def 스파전장():
    """격투가 -> 스트리트 파이터 레벨 8(골드 스킬 전부 습득)과 귀검사, 고블린 셋(HP 999).
    근력 20(보정치 5), 지능 10."""
    rng.시드(5)
    상태 = support.새게임([("", "격투가"), ("", "귀검사")])
    sf, 귀 = 상태["파티"]["파티원"]
    support.성장(상태, sf, 8, 전직="스트리트 파이터", 스킬습득=True)
    gf.전투_시작(상태, ["고블린", "고블린", "고블린"], 레벨=2, 차수=1)
    support.반응_처리(상태)
    전투상태 = 상태["전투상태"]
