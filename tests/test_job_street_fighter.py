def test_독_바르기는_휴식당_1회_10턴_버프이고_무기_공격_적중시_중독3턴(
    스파전장, monkeypatch
):
    _, 전투상태, 적, s = 스파전장
    스킬 = _스킬("독 바르기")
    assert (스킬["행동"], 스킬["MP소모"], 스킬["지속턴"], 스킬["휴식당횟수"]) == (
        None,
        0,
        10,
        1,
    )
    support.주사위고정(monkeypatch, 15)
    _내성(monkeypatch, 성공=False)
    attacks.일반공격_실행(전투상태, s, 적[0])
    assert "중독" not in _상태(적[0])  # 버프 전에는 없다
    _쓰기(전투상태, s, "독 바르기")
    assert [b["지속턴"] for b in s["버프"] if b["이름"] == "독 바르기"] == [10]
    attacks.일반공격_실행(전투상태, s, 적[0])
    assert _상태(적[0])["중독"] == 3
    _쓰기(전투상태, s, "넨탄", 적[1])  # 무기 주사위를 쓰지 않는 공격에는 없다
    assert "중독" not in _상태(적[1])


def test_클로_마스터리는_명중보너스_대신_클로_무기_공격_적중시_출혈3턴(
    스파전장, monkeypatch
):
    _, 전투상태, 적, s = 스파전장
    _무기(s, "클로")
    특성 = s["원본"]["보유특성"]
    if "클로 마스터리" in 특성:
        특성.remove("클로 마스터리")
    명중 = traits.특성_수치(전투상태, s, "명중보너스")
    특성.append("클로 마스터리")
    assert traits.특성_수치(전투상태, s, "명중보너스") == 명중  # 명중 +1은 없다
    _무기(s, "너클")
    support.주사위고정(monkeypatch, 15)
    기록 = _내성(monkeypatch, 성공=False)
    attacks.일반공격_실행(전투상태, s, 적[0])
    assert "출혈" not in _상태(적[0])  # 클로가 아니면 없다
    _무기(s, "클로")
    attacks.일반공격_실행(전투상태, s, 적[0])
    assert _상태(적[0])["출혈"] == 3
    assert 기록  # 내성굴림을 했다


