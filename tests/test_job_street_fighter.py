def test_크라우치는_격투가_퍽이_아니라_스트리트_파이터_골드_스킬이다():
    rng.시드(5)
    상태 = support.새게임([("", "격투가"), ("", "격투가")])
    a, b = 상태["파티"]["파티원"]
    assert "크라우치" not in gf.캐릭터_전체퍽(a)
    스킬 = gf.전직_레지스트리["격투가"]["스트리트 파이터"]["스킬목록"]["크라우치"]
    assert 스킬["습득방법"] == "구매습득" and "훔쳐배우기스킬" in 스킬["타입"]
    support.성장(상태, a, 6, 전직="스트리트 파이터")
    support.성장(상태, b, 6, 전직="넨마스터")
    a_목록 = {이름: 비용 for 이름, 비용, _ in gf.캐릭터_습득가능_스킬(a)}
    b_목록 = {이름: 비용 for 이름, 비용, _ in gf.캐릭터_습득가능_스킬(b)}
    assert a_목록["크라우치"] == 100 and b_목록["크라우치"] == 500
