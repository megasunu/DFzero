def test_이중투척은_투척_스킬을_명중_5로_두번_쓰고_MP는_한번만(스파전장, monkeypatch):
    _, 전투상태, 적, s = 스파전장
    스킬 = _스킬("이중투척")
    assert (스킬["행동"], 스킬["MP소모"], 스킬["지속턴"], 스킬["휴식당횟수"]) == (
        None,
        0,
        10,
        1,
    )
    support.주사위고정(monkeypatch, 15)
    _내성(monkeypatch, 성공=True)
    _쓰기(전투상태, s, "헬터스켈터", 적[0])
    [한번] = [x for x in 전투상태["로그"] if x.get("스킬") == "헬터스켈터"]
    _쓰기(전투상태, s, "이중투척")
    s["현재MP"] = 50
    s["행동자원"].update(일반행동=1)
    ss.스킬_실행(전투상태, s, "헬터스켈터", _스킬("헬터스켈터"), 적[0])
    assert s["현재MP"] == 40
    기록 = [x for x in 전투상태["로그"] if x.get("스킬") == "헬터스켈터"][1:]
    assert len(기록) == 2
    for x in 기록:
        assert (
            x["타격"][0]["판정"]["명중결과"] == 한번["타격"][0]["판정"]["명중결과"] - 5
        )


def test_이중투척은_투척_아이템을_두개_써서_두번_던진다(스파전장, monkeypatch):
    상태, 전투상태, 적, s = 스파전장
    support.주사위고정(monkeypatch, 15)
    _내성(monkeypatch, 성공=True)
    _쓰기(전투상태, s, "이중투척")
    상태["소지품"]["소모품"]["돌맹이"] = 3
    전투상태["현재턴"] = 전투상태["참가자"].index(s)
    s["행동자원"].update(일반행동=1)
    gf.아군_투척아이템사용(상태, "돌맹이", 적[0])
    assert 상태["소지품"]["소모품"]["돌맹이"] == 1
    assert len([x for x in 전투상태["로그"] if x.get("스킬") == "돌맹이"]) == 2
    # 하나만 남았으면 한 번만 던진다
    s["행동자원"].update(일반행동=1)
    gf.아군_투척아이템사용(상태, "돌맹이", 적[0])
    assert "돌맹이" not in 상태["소지품"]["소모품"]
    assert len([x for x in 전투상태["로그"] if x.get("스킬") == "돌맹이"]) == 3


