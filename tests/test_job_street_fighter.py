def test_독에_익숙함은_중독_피해와_패널티가_0이고_상태는_남는다(스파전장):
    _, 전투상태, _, s = 스파전장
    명중 = stats.버프디버프_수치(전투상태, s, "명중보너스")
    ss.상태이상_부여(전투상태, s, "중독", 3)
    for _ in range(3):
        ss.상태이상_부여(전투상태, s, "중독", 3)  # 중첩을 쌓아도
    assert stats.버프디버프_수치(전투상태, s, "명중보너스") == 명중
    hp = s["현재HP"]
    flow.턴_종료_처리(전투상태, s)
    assert s["현재HP"] == hp
    assert "중독" in _상태(s)


def test_독에_익숙함이_거는_중독_내성굴림은_적이_불리하다(스파전장, monkeypatch):
    _, 전투상태, 적, s = 스파전장
    기록 = _내성(monkeypatch, 성공=True)
    효과 = {"종류": "상태이상", "이름": "중독", "내성": "건강", "난이도": "10"}
    traits.상태이상_효과_적용(전투상태, s, 적[0], 효과, "시험")
    traits.상태이상_효과_적용(전투상태, s, 적[0], dict(효과, 이름="출혈"), "시험")
    assert 기록 == [(False, True), (False, False)]


