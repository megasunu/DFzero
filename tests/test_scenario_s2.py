_D = {
    1: "dungeon_01A_D01_Lorien",
    2: "dungeon_01A_D02_Hollow_Lorien",
    3: "dungeon_01A_D03_mirkwood",
    4: "dungeon_01A_D04_Hollow_mirkwood",
    5: "dungeon_01A_D05_thunderland",
    6: "dungeon_01A_D06_poison_thunderland",
    7: "dungeon_01A_D07_frost_mirkwood",
    8: "dungeon_01A_D08_grakquarak",
    9: "dungeon_01A_D09_blazing_grakquarak",
    10: "dungeon_01A_D10_shadow_thunderland",
}
_엘븐가드 = "town_01A_T01_Elvengard"
_헨돈마이어 = "town_01A_T02_hendonmyre"
최대시도_캠페인 = 12  # 구간마다 실전으로 해 보는 횟수
# 플레이어처럼 마을에서 번 골드로 장비와 포션을 갖춘다: 원정을 나설 때마다 HP 포션을 이만큼 채우고
# (골드가 되는 만큼), 전투에서 HP가 절반 이하인 아군이 자기 차례에 마신다(scenario.스킬_실전의 포션).
_포션 = "초보자용 HP 포션"
_포션_목표 = 60
_장비_부위 = ("무기", "상의", "하의", "어깨", "벨트", "신발")
_최대반복_캠페인 = (
    2000  # 포션을 마시면 전투가 길어진다(라운드는 [자동전투] 제한 100까지)
)


def _수치(상태, 캐릭터):
    return {
        "레벨": 캐릭터["레벨"],
        "최대HP": gf.캐릭터_최대HP(상태, 캐릭터),
        "최대MP": gf.캐릭터_최대MP(상태, 캐릭터),
        "스킬수": len(캐릭터["보유스킬"]),
        "가용무기": set(캐릭터["가용무기"]),
        "약점증가": "약점증가" in 캐릭터.get("보유퍽", []),
    }


def _성장_검사(상태, c, 목표, 전직):
    """[레벨업] 버튼으로 목표까지 키우며 레벨업 수치를 확인한다(옛 S3 성장 실전의 검사)."""
    PL = 상태["진행도"]["플레이어레벨"]
    assert 목표 <= PL and gf.캐릭터_레벨업_가능(상태, c)
    전 = _수치(상태, c)
    scenario.성장(상태, c, 목표, 전직=전직, 스킬습득=True)
    후 = _수치(상태, c)
    assert (
        상태["진행도"]["플레이어레벨"] == PL
    )  # 레벨업이 플레이어 레벨을 건드리지 않는다
    # 퍽 '약점증가'는 주/보조를 뺀 능력치를 8로 내린다 - 새로 고른 레벨업에서는 건강이 내려가 HP·MP가 줄 수 있다
    약점 = 후["약점증가"] and not 전["약점증가"]
    assert 후["레벨"] == 목표 and (약점 or 후["최대HP"] > 전["최대HP"])
    # 전직은 주/보조/약점을 추천으로 바꿔 주문시전 능력치가 내려갈 수 있다 - 그때만 MP가 줄어도 된다
    assert 전직 or 약점 or 후["최대MP"] >= 전["최대MP"]
    assert 후["스킬수"] >= 전["스킬수"] and 전["가용무기"] <= 후["가용무기"]


class _패배(Exception):
    pass


class _캠페인:
    def __init__(self, 시드):
        scenario.시드(시드)
        self.상태 = support.새게임()
        self.구간 = {}
        self.성장 = []
        self._실전 = True
        self._패배_구간 = None

    # -- 전투 -------------------------------------------------------
    def _전투(self, 상태):
        if not self._실전:
            support.강제_승리(상태)
            return
        종료 = scenario.스킬_실전(
            상태, [], 최대반복=_최대반복_캠페인, 포션=_포션, 시간제한=True
        )
        if 종료 != "아군승리":
            assert gf.전투_결과_정리(상태) == 종료 == "적승리"
            gf.휴식(상태)  # 전멸하면 마을로(화면과 같다)
            상태["던전상태"] = None
            raise _패배()

    def 보스(self):
        결과, _ = support.보스_처치(self.상태, 전투처리=self._전투)
        assert 결과 == "아군승리"

    def 나가기(self, 연결맵):
        support.연결로_나가기(self.상태, 연결맵, 전투처리=self._전투)

    def 진입(self, 번호):
        # 마을에서 들어가는 던전은 바로 앞 번호 던전 보스를 깬 뒤에만 열려 있다(순서 해금)
        assert gf.던전_열림(self.상태, _D[번호]), 번호
        gf.던전_진입(self.상태, _D[번호])

    def 원정(self, 이름, 진행):
        """실전으로 최대시도 번 해 보고, 못 깨면 강제 승리로 같은 구간을 건넌다."""
        for 시도 in range(1, 최대시도_캠페인 + 1):
            self._실전 = True
            self.포션_채우기()
            try:
                진행()
            except _패배:
                continue
            self.구간[이름] = {"시도": 시도, "강제": False}
            return
        self._실전 = False
        진행()
        self._실전 = True
        self.구간[이름] = {"시도": 최대시도_캠페인, "강제": True}

    # -- 성장 -------------------------------------------------------
    def 키우기(self):
        """마을에서 파티 전원을 플레이어 레벨 한도까지 키운다(5->6은 전직)."""
        상태 = self.상태
        PL = 상태["진행도"]["플레이어레벨"]
        for c in 상태["파티"]["파티원"]:
            전직 = 구현된_전직[c["직업"]]
            목표 = min(PL, 5)
            if c["레벨"] < 목표:
                _성장_검사(상태, c, 목표, None)
            if PL >= 6 and c["레벨"] < PL:
                _성장_검사(상태, c, PL, 전직 if c["전직"] is None else None)
        gf.파티_최대치로_회복(상태)
        # 플레이어 레벨 한도: 다 키운 뒤에는 아무도 더 못 올린다
        assert not any(gf.캐릭터_레벨업_가능(상태, c) for c in 상태["파티"]["파티원"])
        assert all(c["레벨"] == PL for c in 상태["파티"]["파티원"]), (
            PL,
            [c["레벨"] for c in 상태["파티"]["파티원"]],
        )
        self.성장.append(
            [
                PL,
                [
                    (gf.캐릭터_직업표시(c), c["레벨"], gf.캐릭터_최대HP(상태, c))
                    for c in 상태["파티"]["파티원"]
                ],
            ]
        )
        self.장비_갖추기()

    # -- 장비와 포션 ---------------------------------------------
    def _판매목록(self):
        return gf.현재_마을정보(self.상태).get("상점판매목록")

    def 포션_채우기(self):
        """원정을 나서기 전에 HP 포션을 _포션_목표 개까지 산다(골드가 되는 만큼)."""
        상태 = self.상태
        있음 = 상태["소지품"].get("포션", {}).get(_포션, 0)
        가격 = 상태["상점카탈로그"]["소모품"]["포션"][_포션]["가격"]
        개수 = min(_포션_목표 - 있음, 상태["소지품"]["골드"] // 가격)
        if 개수 > 0:
            gf.상점_구매(상태, "소모품", "포션", _포션, 개수, self._판매목록())

    def 장비_갖추기(self):
        """부위마다(무기부터) 파티 순서로: 소지품에서 낄 수 있는 더 비싼 장비가 있으면 바꿔 끼고, 마을 상점에서
        지금 것보다 비싸고 살 수 있는 장비를 비싼 순으로 사 본다 - 낄 수 없는 것(숙련·직업군)은 되판다.
        값이 비쌀수록 좋은 장비로 본다(플레이어의 단순한 판단). 치트 아이템은 쓰지 않는다."""
        상태 = self.상태
        값 = lambda i: (i or {}).get("가격", 0)  # noqa: E731
        for 슬롯 in _장비_부위:
            for c in 상태["파티"]["파티원"]:
                지금 = gf.캐릭터_장착아이템(상태, c, 슬롯)
                낄것 = [
                    h[0]
                    for h in gf.장비_교체_후보(상태, c, 슬롯)
                    if h[2] and h[1] > 0 and "치트" not in h[0]["이름"]
                ]
                최고 = max(낄것, key=값, default=None)
                if 최고 is not None and 값(최고) > 값(지금):
                    gf.장비_교체(상태, c, 슬롯, 최고["이름"])
                    지금 = 최고
                살것 = sorted(
                    (
                        i
                        for i in gf.상점_구매목록(상태, "장비", 슬롯, self._판매목록())
                        if "치트" not in i["이름"] and 값(i) > 값(지금)
                    ),
                    key=값,
                    reverse=True,
                )
                for i in 살것:
                    if 값(i) > 상태["소지품"]["골드"]:
                        continue
                    gf.상점_구매(상태, "장비", 슬롯, i["이름"], 1, self._판매목록())
                    if any(
                        h[0]["이름"] == i["이름"] and h[2]
                        for h in gf.장비_교체_후보(상태, c, 슬롯)
                    ):
                        gf.장비_교체(상태, c, 슬롯, i["이름"])
                        break
                    gf.상점_판매(상태, "장비", 슬롯, i["이름"], 1)


def 캠페인(시드):
    c = _캠페인(시드)
    상태 = c.상태
    진행도 = 상태["진행도"]
    PL = lambda: 진행도["플레이어레벨"]  # noqa: E731

    def 로리엔():
        c.진입(1)
        c.보스()
        c.나가기(_D[2])
        c.보스()
        c.나가기(_엘븐가드)

    c.원정("D01-D02 로리엔", 로리엔)
    assert PL() == 2
    c.키우기()
    gf.마을_이동(상태, "헨돈마이어")
    # 헨돈마이어 도착 - D03~D10이 다 보이되 머크우드만 열리고 나머지는 비활성
    assert [열림 for _, _, 열림, _ in gf.던전목록_표시(상태)] == [True] + [False] * 7

    def 머크우드():
        c.진입(3)
        c.보스()
        c.나가기(_D[4])
        c.보스()
        c.나가기(_헨돈마이어)

    c.원정("D03-D04 머크우드", 머크우드)
    assert PL() == 3
    c.키우기()

    # 키놀이 실제로 싸우면서 쉬지 않고 D06까지 이어 가기 어려워져, 플레이어처럼
    # D05 보스 뒤에 마을에서 쉬고 포이즌 선더랜드를 따로 원정한다(S2와 같다).
    def 선더랜드():
        c.진입(5)
        c.보스()

    c.원정("D05 선더랜드", 선더랜드)
    gf.휴식(상태)

    def 포이즌_선더랜드():
        c.진입(5)  # 다시 들어오면 숏컷이 열려 있다
        c.나가기(_D[6])
        c.보스()
        c.나가기(_D[5])
        c.나가기(_헨돈마이어)

    c.원정("D06 포이즌 선더랜드", 포이즌_선더랜드)
    assert PL() == 4
    c.키우기()

    def 프로스트():  # 머크우드 숏컷(포이즌 선더랜드 보스 필요)이 열렸다
        c.진입(3)
        c.보스()
        c.나가기(_D[7])
        c.보스()
        c.나가기(_D[3])
        c.나가기(_헨돈마이어)

    c.원정("D03-D07 프로스트 머크우드", 프로스트)

    def 그락카락():
        c.진입(8)
        c.보스()
        c.나가기(_D[9])
        c.보스()
        c.나가기(_D[8])
        c.나가기(_헨돈마이어)

    c.원정("D08-D09 그락카락", 그락카락)
    assert PL() == 5
    c.키우기()

    def 어둠의_선더랜드():  # 선더랜드 북쪽 숏컷(불타는 그락카락 보스 필요)이 열렸다
        c.진입(5)
        c.나가기(_D[10])
        c.보스()
        c.나가기(_D[5])
        c.나가기(_헨돈마이어)

    c.원정("D10 어둠의 선더랜드", 어둠의_선더랜드)
    assert PL() == 6
    c.키우기()

    assert 진행도["클리어한던전"] == {_D[n] for n in range(1, 11)}
    return {"구간": c.구간, "성장": c.성장, "골드": 상태["소지품"]["골드"]}


@pytest.mark.scenario("S2")
# 시드 40개 중 D01~D06은 늘 실전, D07 89%, D10 42%, D08~D09는 1개(시드 15)만 실전.
@pytest.mark.parametrize("시드", [7, 15])
def test_S2_캠페인_실전(시드, golden):
    결과 = 캠페인(시드)
    구간 = 결과["구간"]
    # 7구간 중 5구간 이상을 실전으로 깨야 "실전 캠페인"이다 - 아니면 강제 승리 시나리오와 다를 게 없다
    assert sum(not v["강제"] for v in 구간.values()) >= 5, 구간
    # 장비와 포션을 갖추면 D06까지는 강제 승리 없이 간다(측정: 시드 40개 모두)
    for 이름 in (
        "D01-D02 로리엔",
        "D03-D04 머크우드",
        "D05 선더랜드",
        "D06 포이즌 선더랜드",
    ):
        assert not 구간[이름]["강제"], 구간
    golden(f"scenario_S2_campaign_seed{시드}", 결과)


