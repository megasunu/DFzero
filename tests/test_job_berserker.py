def test_프렌지가_켜져_있으면_턴_시작에_최대HP_10퍼센트를_올림해_잃고_1_아래로_안_간다(
    광기전장,
):
    _, 전투상태, _, bs = 광기전장
    최대 = stats.유효_최대HP(전투상태, bs)
    bs["현재HP"] = 최대
    flow.턴_시작_처리(전투상태, bs)
    assert bs["현재HP"] == 최대  # 꺼져 있으면 그대로
    _프렌지_켜기(전투상태, bs)
    flow.턴_시작_처리(전투상태, bs)
    assert bs["현재HP"] == 최대 - -(-최대 // 10)
    bs["현재HP"] = 2
    flow.턴_시작_처리(전투상태, bs)
    assert bs["현재HP"] == 1


