def 반응_처리(상태):
    if gf.전투시작_반응_대기중(상태):
        gf.전투시작_반응_처리(상태)


def 자동_전투(상태, 최대반복=500):
    """아군은 매 턴 살아있는 첫 적을 일반공격한다. 전투가 끝날 때까지.
    만취 아군은 조종하지 않는다(턴_넘기기가 대신 행동시킨다)."""
    반응_처리(상태)
    for _ in range(최대반복):
        if gf.전투_종료됨(상태):
            return 상태["전투상태"]["종료"]
        참가자 = gf.현재_턴_참가자(상태)
        if gf.아군_차례인가(상태):
            적들 = [e for e in gf.적_목록(상태) if e["생존"]]
            if 적들 and 참가자["행동자원"].get("일반행동", 0) > 0:
                gf.아군_일반공격(상태, 적들[0])
        gf.턴_넘기기(상태)
    raise AssertionError("전투가 끝나지 않았다")


def 강제_승리(상태):
    """살아있는 적 전원에게 감소 무시 피해를 줘서 전투를 아군 승리로 끝낸다."""
    전투상태 = 상태["전투상태"]
    for 적 in gf.적_목록(상태):
        if 적["생존"]:
            damage.피해_적용(전투상태, 적, 10**6, 피해감소무시=True)
    core.종료판정_갱신(전투상태)
    assert 전투상태["종료"] == "아군승리"


def 강제_패배(상태):
    전투상태 = 상태["전투상태"]
    for 아군 in gf.아군_목록(상태):
        damage.피해_적용(전투상태, 아군, 10**6, 피해감소무시=True)
    core.종료판정_갱신(전투상태)
    assert 전투상태["종료"] == "적승리"


