def 레벨업_선택(캐릭터, 퍽순번=0, 퍽고르기=None):
    """다음 레벨업에 넘길 선택값을 결정적으로 만든다.
    스탯: 주스탯에 전부(스탯성장은 주스탯/보조스탯에 1씩). 퍽: 선택 가능한 직업 퍽을 앞에, 공용 퍽을 뒤에 놓은 목록의 퍽순번째.
    퍽고르기(캐릭터, 후보)가 있으면 퍽은 그것이 후보 [(이름, 정의)] 중에서 고른다."""
    항목 = gf.캐릭터_다음_레벨업_항목(캐릭터)
    if 항목 is None:
        return {}
    타입 = 항목["타입"]
    if 타입 == "스탯획득":
        return {"배분": {캐릭터["주스탯"]: 항목["획득"]["배분점수"]}}
    if 타입 == "마스터리선택":
        무기, 방어구 = gf.캐릭터_마스터리_선택지(캐릭터)
        return {"무기마스터리": 무기[0][0], "방어구마스터리": 방어구[0][0]}
    if 타입 == "스타일선택":
        return {"스타일": 항목["획득"]["선택지"][0]}
    if 타입 == "스탯성장":  # 서로 다른 2개에 1점씩 - 주스탯 + 보조스탯
        return {"배분": {캐릭터["주스탯"]: 1, 캐릭터["보조스탯"]: 1}}
    if 타입 == "스킬강화":  # 고를 수 있는 첫 스킬(보유 순서)
        return {"강화스킬": gf.스킬강화_선택지(캐릭터)[0][0]}
    if 타입 == "퍽획득":
        후보 = 퍽_후보(캐릭터)
        if 퍽고르기 is None:
            이름, 정의 = 후보[퍽순번 % len(후보)]
        else:
            이름, 정의 = 퍽고르기(캐릭터, 후보)
        return 퍽_선택값(캐릭터, 이름, 정의)
    return {}


def 퍽_후보(캐릭터):
    """지금 고를 수 있는 퍽 [(이름, 정의)] - 직업 퍽을 앞에, 공용 퍽을 뒤에."""
    직업퍽 = gf.직업_레지스트리[캐릭터["직업"]]["퍽목록"]
    가능 = gf.선택가능_퍽목록(캐릭터)
    return [p for p in 가능 if p[0] in 직업퍽] + [p for p in 가능 if p[0] not in 직업퍽]


def 퍽_선택값(캐릭터, 이름, 정의):
    """퍽 하나를 고른 레벨업 선택값. 스탯 포인트를 주는 퍽은 주스탯에 전부 배분한다."""
    선택 = {
        "퍽이름": 이름,
        "퍽정의": 정의,
        "특성정의": gf.퍽_특성정의_찾기(캐릭터, 정의),
    }
    if "획득스탯포인트" in 정의:
        선택["배분"] = {캐릭터["주스탯"]: 정의["획득스탯포인트"]}
    return 선택


def 스킬_전부_습득(상태, 캐릭터):
    """지금 배울 수 있는 스킬을 데이터 순서대로 전부 배운다(필요한 골드는 먼저 채워 준다)."""
    for 이름, 비용, _ in gf.캐릭터_습득가능_스킬(캐릭터):
        상태["소지품"]["골드"] = 상태["소지품"].get("골드", 0) + 비용
        gf.캐릭터_스킬_습득(상태, 캐릭터, 이름)


def 성장(상태, 캐릭터, 목표레벨, 전직=None, 퍽순번=0, 스킬습득=False, 퍽고르기=None):
    """캐릭터를 목표레벨까지 올린다. 5->6에서 전직을 고른다. 각 레벨의 스냅샷 목록을 돌려준다.
    스킬습득이면 다 키운 뒤 배울 수 있는 스킬을 전부 배운다([스킬습득] 버튼). 퍽고르기는 레벨업_선택에 넘긴다."""
    상태["진행도"]["플레이어레벨"] = max(상태["진행도"]["플레이어레벨"], 목표레벨)
    기록 = []
    while 캐릭터["레벨"] < 목표레벨:
        assert gf.캐릭터_레벨업_가능(상태, 캐릭터)
        if gf.캐릭터_전직_필요(캐릭터):
            선택 = {"전직": 전직}
            # 전직 레벨의 선택값은 전직 테이블 기준으로 다시 만든다
            항목 = gf.캐릭터_다음_레벨업_항목(캐릭터, 전직)
            assert 항목["타입"] == "특성획득"
            if 항목.get("스타일선택지"):
                선택["스타일"] = 항목["스타일선택지"][0]
        else:
            선택 = 레벨업_선택(캐릭터, 퍽순번, 퍽고르기)
        gf.캐릭터_레벨업_적용(캐릭터, **선택)
        기록.append(스냅샷(상태, 캐릭터, 선택))
    if 스킬습득:
        스킬_전부_습득(상태, 캐릭터)
    return 기록


def 스냅샷(상태, 캐릭터, 선택=None):
    return {
        "레벨": 캐릭터["레벨"],
        "선택": {
            k: v for k, v in (선택 or {}).items() if k != "퍽정의" and k != "특성정의"
        },
        "직업표시": gf.캐릭터_직업표시(캐릭터),
        "능력치": {
            s: 캐릭터[s] for s in ("근력", "민첩", "건강", "지능", "지혜", "매력")
        },
        "기본최대HP": 캐릭터["기본최대HP"],
        "기본최대MP": 캐릭터["기본최대MP"],
        "주문시전능력치": 캐릭터["주문시전능력치"],
        "추가공격": 캐릭터["추가공격"],
        "보유특성": list(캐릭터["보유특성"]),
        "보유스킬": list(캐릭터["보유스킬"]),
        "보유퍽": list(gf.캐릭터_보유퍽(캐릭터)),
        "초상화": gf.초상화_코드(캐릭터),
    }


