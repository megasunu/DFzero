"""웨펀마스터 스킬: 류심 : 쾌의 강화류심 보너스는 지정한 적 1체에게만."""

import pytest

import gameflow as gf
from game.system import rng
from game.system import skill_system as ss
from game.system.combat import flow
from tests import support


def _쾌_전장():
    """레벨 6 웨펀마스터 대 고블린 셋(HP 넉넉히), 웨펀마스터 차례에 류심자세."""
    rng.시드(1)
    상태 = support.새게임([("", "귀검사")])
    support.성장(상태, 상태["파티"]["파티원"][0], 6, 전직="웨펀마스터")
    gf.파티_최대치로_회복(상태)
    gf.전투_시작(상태, ["고블린", "고블린", "고블린"], 레벨=2, 차수=1)
    support.반응_처리(상태)
    전투상태 = 상태["전투상태"]
    p = next(x for x in 전투상태["참가자"] if x["진영"] == "아군")
    전투상태["현재턴"] = 전투상태["참가자"].index(p)
    flow.턴_시작_처리(전투상태, p)
    p["현재MP"] = 100
    적 = [x for x in 전투상태["참가자"] if x["진영"] == "적"]
    for x in 적:
        x["현재HP"] = x["최대HP"] = 999
    ss.이름있는효과_부여(전투상태, p, "류심자세", 1)
    return 상태, p, 적


@pytest.mark.parametrize("지정", [0, 1, 2])
def test_류심_쾌의_강화류심_추가피해는_지정한_적에게만_들어간다(monkeypatch, 지정):
    support.주사위고정(monkeypatch, 15)  # d20 15(명중), 피해 주사위는 최대
    피해 = {}
    for 강화 in (False, True):
        상태, p, 적 = _쾌_전장()
        if 강화:
            ss.이름있는효과_부여(상태["전투상태"], p, "강화류심", 1)
        결과 = gf.아군_스킬사용(상태, "류심 : 쾌", 중심대상=적[지정])
        피해[강화] = {t["대상"]: t["피해"] for t in 결과["타격"]}
        if 강화:  # 강화류심은 한 번만 소모된다
            assert not any(b["이름"] == "강화류심" for b in p["버프"])
    지정이름 = 적[지정]["이름"]
    assert set(피해[True]) == set(피해[False])  # 맞는 적은 같다
    for 이름, 값 in 피해[True].items():
        if 이름 == 지정이름:
            assert 값 > 피해[False][이름]  # 보정공격력만큼 더
        else:
            assert 값 == 피해[False][이름], 이름  # 양옆 적은 그대로


# ---- 레벨 13 환영검무 / 3차수 구매 스킬 맹룡단공참


def _13레벨_전장(큐브=5):
    """레벨 13 웨펀마스터(구매 스킬 전부 습득) 대 타우 아미 둘, 그 캐릭터의 차례. 공용 소지품에 무색 큐브 조각."""
    rng.시드(support.추가행동_시드)
    상태 = support.새게임([("", "귀검사")])
    c = 상태["파티"]["파티원"][0]
    support.성장(상태, c, 13, 전직="웨펀마스터", 스킬습득=True)
    gf.파티_최대치로_회복(상태)
    if 큐브:
        상태["소지품"]["재료"]["무색 큐브 조각"] = 큐브
    gf.전투_시작(상태, ["타우 아미", "타우 아미"], 레벨=8, 차수=2)
    support.반응_처리(상태)
    while not gf.아군_차례인가(상태):
        gf.턴_넘기기(상태)
    p = gf.현재_턴_참가자(상태)
    p["현재MP"] = 200
    적 = [e for e in gf.적_목록(상태) if e["생존"]][0]
    적["현재HP"] = 적["최대HP"] = 10**6
    return 상태, p, 적


def test_13레벨에_환영검무를_얻고_맹룡단공참을_살_수_있다():
    상태, p, _ = _13레벨_전장()
    보유 = p["원본"]["보유스킬"]
    assert "환영검무" in 보유 and "맹룡단공참" in 보유


def test_환영검무는_MP30과_큐브조각5개로_4더하기_추가공격만큼_친다():
    상태, p, 적 = _13레벨_전장(큐브=7)
    p["행동자원"]["보조행동"] = 0  # 보조행동 조건은 따로 본다
    MP = p["현재MP"]
    결과 = gf.아군_스킬사용(상태, "환영검무", 중심대상=적)
    assert len(결과["타격"]) == 4 + p["원본"]["추가공격"]
    assert p["현재MP"] == MP - 30
    assert 상태["소지품"]["재료"]["무색 큐브 조각"] == 2
    assert p["행동자원"]["일반행동"] == 0


def test_환영검무는_남은_보조행동을_모두_써서_하나당_한_번_더_친다():
    상태, p, 적 = _13레벨_전장()
    p["행동자원"]["보조행동"] = 2
    결과 = gf.아군_스킬사용(상태, "환영검무", 중심대상=적)
    assert len(결과["타격"]) == 4 + p["원본"]["추가공격"] + 2
    assert p["행동자원"]["보조행동"] == 0
    assert "무색 큐브 조각" not in 상태["소지품"]["재료"]  # 다 쓴 재료는 지운다


def test_무색_큐브_조각이_모자라면_환영검무를_못_쓴다():
    상태, p, _ = _13레벨_전장(큐브=4)
    가능, 사유 = gf.스킬_사용_가능여부(상태, p, "환영검무")
    assert not 가능 and "무색 큐브 조각" in 사유


def test_맹룡단공참은_추가행동으로_거듭_쓰고_쓸_때마다_MP10을_낸다():
    상태, p, 적 = _13레벨_전장()
    MP = p["현재MP"]
    결과 = gf.아군_스킬사용(상태, "맹룡단공참", 중심대상=적)
    assert len(결과["타격"]) == 1
    남은 = gf.추가행동_남은수(p)
    assert 남은 == p["원본"]["추가공격"] > 0
    for _ in range(남은):
        assert gf.스킬_사용_가능여부(상태, p, "맹룡단공참")[0]
        gf.아군_스킬사용(상태, "맹룡단공참", 중심대상=적)
    assert p["현재MP"] == MP - 10 * (남은 + 1)
    assert not gf.스킬_사용_가능여부(상태, p, "맹룡단공참")[0]  # 행동이 다 떨어졌다


def test_연속_타입은_연속제한까지만_한_턴에_쓴다():
    상태, p, _ = _13레벨_전장()
    스킬 = dict(상태["스킬데이터모음"]["맹룡단공참"], _이름="맹룡단공참")
    p["이번턴_스킬사용횟수"]["맹룡단공참"] = 17
    assert ss.사용_가능여부(상태["전투상태"], p, 스킬)[0]
    p["이번턴_스킬사용횟수"]["맹룡단공참"] = 18
    가능, 사유 = ss.사용_가능여부(상태["전투상태"], p, 스킬)
    assert not 가능 and "턴당사용제한" in 사유
