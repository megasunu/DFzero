"""마을 [전문직업] -> [연금술] - 라이언 코크스를 다른 강화 재료로 바꾸고, 무색 큐브 조각으로 포션을 만든다.

규칙은 docs/game-rules.md "연금술".
"""

import pytest

import gameflow as gf
from game.data.item.item_potion import 포션_데이터
from tests import support

회복포션 = list(포션_데이터["회복포션"])


def _준비(코크스=0, 조각=0):
    상태 = support.새게임([("", "귀검사")])
    재료 = 상태["소지품"]["재료"]
    if 코크스:
        재료["라이언 코크스"] = 코크스
    if 조각:
        재료["무색 큐브 조각"] = 조각
    return 상태


def _항목(상태, 탭, 이름):
    return next(h for h in gf.전문직업_연금술목록(상태, 탭) if h["이름"] == 이름)


def test_전문직업_메뉴에_연금술이_있고_구현됨이다():
    assert "연금술" in gf.전문직업_메뉴
    assert "연금술" in gf.전문직업_구현됨
    assert gf.연금술_탭목록 == ["전체", "재료", "소모품"]


def test_재료_탭은_라이언_코크스_1개로_모순의_결정체와_강렬한_기운을_만든다():
    상태 = _준비(코크스=1)
    목록 = gf.전문직업_연금술목록(상태, "재료")
    assert [h["이름"] for h in 목록] == ["모순의 결정체", "강렬한 기운"]
    for 항목 in 목록:
        assert 항목["재료"] == [("라이언 코크스", 1, 1)]
        assert 항목["재료글"] == "라이언 코크스 1/1"
        assert 항목["제작가능"] is True


def test_다른_재료를_라이언_코크스로_바꾸는_목록은_없다():
    이름들 = [h["이름"] for h in gf.전문직업_연금술목록(_준비(), "전체")]
    assert "라이언 코크스" not in 이름들


def test_소모품_탭은_HP_MP_포션을_가격만큼의_무색_큐브_조각으로_만든다():
    목록 = gf.전문직업_연금술목록(_준비(조각=15), "소모품")
    assert [h["이름"] for h in 목록] == 회복포션
    for 항목 in 목록:
        가격 = 포션_데이터["회복포션"][항목["이름"]]["가격"]
        assert 항목["재료"] == [("무색 큐브 조각", 가격, 15)]
        assert 항목["제작가능"] is (15 >= 가격)


def test_전체_탭은_재료와_소모품을_합친_것이다():
    상태 = _준비()
    assert gf.전문직업_연금술목록(상태, "전체") == (
        gf.전문직업_연금술목록(상태, "재료") + gf.전문직업_연금술목록(상태, "소모품")
    )


def test_재료_연금술은_라이언_코크스를_빼고_재료를_넣고_도감에_등록한다():
    상태 = _준비(코크스=2)
    골드 = 상태["소지품"]["골드"]
    gf.전문직업_연금술(상태, _항목(상태, "재료", "모순의 결정체"))
    gf.전문직업_연금술(상태, _항목(상태, "재료", "강렬한 기운"))
    재료 = 상태["소지품"]["재료"]
    assert "라이언 코크스" not in 재료
    assert 재료["모순의 결정체"] == 1 and 재료["강렬한 기운"] == 1
    assert 상태["소지품"]["골드"] == 골드
    도감 = 상태["진행도"]["도감"]["재료"]
    assert "모순의 결정체" in 도감 and "강렬한 기운" in 도감


def test_포션_연금술은_무색_큐브_조각을_빼고_포션을_넣는다():
    상태 = _준비(조각=25)
    포션 = 회복포션[1]  # 입문자용 HP 포션, 20G
    전 = 상태["소지품"].get("포션", {}).get(포션, 0)
    gf.전문직업_연금술(상태, _항목(상태, "소모품", 포션))
    assert 상태["소지품"]["재료"]["무색 큐브 조각"] == 5
    assert 상태["소지품"]["포션"][포션] == 전 + 1


def test_재료가_모자라면_아무것도_바뀌지_않는다():
    상태 = _준비(조각=9)
    with pytest.raises(ValueError, match="무색 큐브 조각"):
        gf.전문직업_연금술(상태, _항목(상태, "소모품", 회복포션[0]))
    with pytest.raises(ValueError, match="라이언 코크스"):
        gf.전문직업_연금술(상태, _항목(상태, "재료", "강렬한 기운"))
    assert 상태["소지품"]["재료"] == {"무색 큐브 조각": 9}
