"""S19 소울브링어 실전 - 어둠의 친화, 사슬 해제, 잔영의 케이가, 달빛베기 (docs/scenarios.md, #244).

귀검사가 든 4인 파티를 레벨 8까지 키운다(귀검사는 5->6에 소울브링어, 나머지는 기본 전직, 스킬 전부 습득).
선더랜드(D05) 인카운트를 **실제 전투로** 치른다. 소울브링어는 차례마다 잔영의 케이가가 없으면 걸고(휴식당 1회라
전투가 끝날 때마다 마을로 돌아가 쉬고 다시 들어간다), 홀수 라운드는
귀참, 짝수 라운드는 달빛베기를 쓴 뒤 남은 일반행동으로 일반공격한다. 나머지 파티원은 일반공격만 한다(2026-10-22 - 전에는 스킬 우선).
홀수 번째 전투는 먼저 귀신 : 카잔을 깐다(장판 - 2026-10-22).
귀참 뒤 귀참드라이브(보조행동·MP 10, 카잔 장판이면 그 아래 귀참도), 달빛베기 뒤 양손올려베기(추가공격 소모),
케이가 추가 타격이 실제로 나오는지와
케이가 지속(5 + 사슬 해제 5 = 10턴)을 본다. 수치 규칙은 tests/test_job_soul_bender.py가 값으로 검사한다.
"""

import pytest

from game.system import rng
import gameflow as gf
import scenario
import support
from tests.support import 구현된_전직

선더랜드 = "dungeon_01A_D05_thunderland"
# 0 -> 6(2026-10-26): 추천 주/보조/약점(#420)으로 능력치가 바뀌어 옛 시드는 효과가 안 나온다
시드 = 6
파티구성 = [("", "귀검사"), ("", "격투가"), ("", "거너"), ("", "프리스트")]
전직표 = dict(구현된_전직, 귀검사="소울브링어")


def _소울브링어_턴(상태, sb, 기록, 번호):
    전투상태 = 상태["전투상태"]

    def 쓰기(이름):
        적들 = scenario._살아있는_적(상태)
        if not 적들 or not gf.스킬_사용_가능여부(상태, sb, 이름)[0]:
            return False
        # 달빛베기·귀참은 HP가 가장 많은 적에게 - 버텨야 양손올려베기·귀참드라이브가 나간다
        대상 = 적들[-1] if 이름 in ("달빛베기", "귀참") else 적들[0]
        if 이름 == "귀참" and any(b["이름"] == "카잔버프" for b in sb["버프"]):
            기록["카잔장판귀참"] = 기록.get("카잔장판귀참", 0) + 1
        gf.아군_스킬사용(상태, 이름, 중심대상=대상)
        기록[이름] = 기록.get(이름, 0) + 1
        return True

    if 번호 % 2 and not any(b["이름"] == "카잔버프" for b in sb["버프"]):
        쓰기("귀신 : 카잔")  # 일반행동을 쓰므로 이번 차례에는 귀참/달빛베기가 없다

    if not any(b["이름"] == "잔영의 케이가" for b in sb["버프"]):
        if 쓰기("잔영의 케이가"):
            기록.setdefault("케이가지속", set()).update(
                b["지속턴"] for b in sb["버프"] if b["이름"] == "잔영의 케이가"
            )
    # 전투마다 첫 스킬을 바꾼다 - 귀신이 많아 한 라운드에 끝나는 전투가 많다(#247 골드 귀신)
    # 카잔을 까는 홀수 전투와 짝을 맞춰 두 전투마다 바꾼다(2026-10-22)
    첫째 = (전투상태["라운드"] + 번호 // 2) % 2
    순서 = ["귀참", "달빛베기"] if 첫째 else ["달빛베기", "귀참"]
    for 이름 in 순서:
        if 전투상태["종료"] is not None or 쓰기(이름):
            break
    while 전투상태["종료"] is None and sb["생존"]:
        적들 = scenario._살아있는_적(상태)
        if not 적들 or sb["행동자원"].get("일반행동", 0) <= 0:
            break
        gf.아군_일반공격(상태, 적들[0])
    if 전투상태["종료"] is None:
        gf.턴_넘기기(상태)


def _일반공격_턴(상태):
    """나머지 파티원은 일반공격만 한다 - 스킬로 적이 먼저 쓰러지면 귀참드라이브가 나갈 틈이 없다."""
    적들 = scenario._살아있는_적(상태)
    if 적들:
        gf.아군_일반공격(상태, 적들[0])
    if not gf.전투_종료됨(상태):
        gf.턴_넘기기(상태)


def _전투(상태, 기록, 번호):
    support.반응_처리(상태)
    for _ in range(300):
        if gf.전투_종료됨(상태):
            break
        참가자 = gf.현재_턴_참가자(상태)
        if 참가자["진영"] == "아군" and 참가자["생존"]:
            if 참가자["원본"].get("전직") == "소울브링어":
                _소울브링어_턴(상태, 참가자, 기록, 번호)
            else:
                _일반공격_턴(상태)
        else:
            gf.턴_넘기기(상태)
    else:
        raise AssertionError("전투가 끝나지 않았다")
    로그 = [항목 for 항목 in 상태["전투상태"]["로그"] if isinstance(항목, dict)]
    for 이름, 키 in (
        ("귀참 - 귀참드라이브", "귀참드라이브"),
        ("달빛베기 - 양손올려베기", "양손올려베기"),
    ):
        기록[키] = 기록.get(키, 0) + sum(1 for 항목 in 로그 if 항목.get("스킬") == 이름)
    기록["케이가추가타격"] = 기록.get("케이가추가타격", 0) + sum(
        1
        for 항목 in 로그
        for 타격 in 항목.get("타격") or []
        if isinstance(타격, dict) and 타격.get("추가타격") == "잔영의 케이가"
    )
    return 상태["전투상태"]["종료"]


@pytest.mark.scenario("S19")
def test_S19_소울브링어_실전(golden):
    rng.시드(시드)
    상태 = support.새게임(파티구성)
    파티 = 상태["파티"]["파티원"]
    for c in 파티:
        support.성장(상태, c, 8, 전직=전직표[c["직업"]], 스킬습득=True)
    gf.파티_최대치로_회복(상태)
    [sb] = [c for c in 파티 if c["직업"] == "귀검사"]
    assert gf.캐릭터_직업표시(sb).startswith("소울브링어")
    assert {"어둠의 친화", "사슬 해제"} <= set(sb["보유특성"])
    assert {"잔영의 케이가", "귀참", "달빛베기"} <= set(sb["보유스킬"])
    assert "암속성" in sb["저항"] and "명속성" in sb["취약"]

    gf.던전_진입(상태, 선더랜드)
    전투들 = []
    for 번호 in range(10):
        적 = scenario.인카운트까지_걷기(상태)
        기록 = {}
        종료 = _전투(상태, 기록, 번호)
        assert gf.전투_결과_정리(상태) == 종료 == "아군승리"
        scenario.보상_수령(상태)
        # 잔영의 케이가는 휴식당 1회(#247) - 마을로 돌아가 쉬고 다시 들어간다
        if 기록.get("잔영의 케이가"):
            assert sb["횟수제한스킬"]["휴식제한스킬"]["잔영의 케이가"] == 0
        gf.휴식(상태)
        gf.던전_진입(상태, 선더랜드)
        기록["케이가지속"] = sorted(기록.get("케이가지속", set()))
        전투들.append({"적": 적, **기록})
        합 = {
            k: sum(b.get(k, 0) for b in 전투들)
            for k in ("귀참드라이브", "양손올려베기", "카잔장판귀참")
        }
        if all(합.values()):
            break

    def 합계(키):
        return sum(b.get(키, 0) for b in 전투들)

    assert 합계("귀참") and 합계("귀참드라이브") and 합계("카잔장판귀참"), 전투들
    assert 합계("귀참드라이브") <= 합계(
        "귀참"
    )  # 귀참마다 많아야 한 번(대상이 쓰러지면 없다)
    assert 합계("달빛베기") and 합계("양손올려베기"), 전투들
    assert 합계("양손올려베기") <= 합계("달빛베기")
    assert 합계("케이가추가타격"), 전투들
    assert all(b["케이가지속"] in ([], [10]) for b in 전투들), 전투들
    golden("scenario_S19_soul_bender", 전투들)
