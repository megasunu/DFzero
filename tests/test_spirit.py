@pytest.mark.parametrize("이름", list(_정령))
def test_정령은_분류_타입_크기_등급과_능력치가_정해져_있다(이름):
    특성, 주스탯, 단계 = _정령[이름]
    주값, 나머지, 크기, 등급 = _단계[단계]
    몬스터 = gf.몬스터목록[이름]
    assert 몬스터["분류"] == "정령"
    assert 몬스터["타입"] == ["정령형"]
    assert 몬스터["크기"] == 크기
    assert 몬스터["적등급"] == 등급
    assert 몬스터["특성"] == ["종족:정령", 특성]
    assert {k: 몬스터[k] for k in _능력치} == {
        k: 주값 if k == 주스탯 else 나머지 for k in _능력치
    }


@pytest.mark.parametrize("이름", list(_정령))
def test_정령_패턴은_소환수_행동표에_주스탯_보정치와_판정을_붙인_것(이름):
    _, 주스탯, _ = _정령[이름]
    원본 = 소환수목록[이름]["행동표"]
    패턴 = gf.몬스터목록[이름]["패턴"]
    assert set(패턴) == set(원본) == set(range(1, 7))
    for 번호, 행동 in 원본.items():
        p = 패턴[번호]
        assert p["이름"] == 행동["이름"]
        assert p["타입"] == "공격패턴"
        assert p["타겟"] == 행동["타겟"]
        assert p["속성"] == 행동["속성"]
        assert p["공격타입"] == 행동["공격타입"]
        assert p["데미지"] == f"{행동['데미지']}+{주스탯}보정치"
        assert p["명중률"] == f"{주스탯}판정"
        assert p.get("공격횟수", 1) == 행동.get("공격횟수", 1)
        assert p.get("각공격명중굴림", False) == 행동.get("각공격명중굴림", False)


