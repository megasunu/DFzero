@pytest.mark.parametrize("이름", ["나이아스", "플레임 헐크"])
def test_속성_정령의_공격은_모두_자기_속성이다(monkeypatch, 이름):
    속성, _ = _속성[_정령[이름][0]]
    전투상태, 몬스터, _ = _전장(이름)
    무속성패턴 = dict(gf.몬스터목록[이름]["패턴"][1], 속성="무속성", 타겟="적단일")
    받은 = []
    원래 = damage.피해_적용

    def 기록(*a, **k):
        받은.append(k.get("속성"))
        return 원래(*a, **k)

    monkeypatch.setattr(damage, "피해_적용", 기록)
    monkeypatch.setattr(monster_ai, "행동_선택", lambda p: 무속성패턴)
    monkeypatch.setattr(
        damage,
        "명중_판정",
        lambda *a, **k: {
            "성공": True,
            "자연눈": 15,
            "치명타": False,
            "자동실패": False,
        },
    )
    전투상태["현재턴"] = 전투상태["참가자"].index(몬스터)
    flow.턴_시작_처리(전투상태, 몬스터)
    monster_actions.몬스터_턴_실행(전투상태, 몬스터)
    assert 받은 and set(받은) == {속성}
