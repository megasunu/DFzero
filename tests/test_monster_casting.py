"""몬스터 패턴 캐스팅과 차수 행동(2026-10-30 사용자 지정, #485).

캐스팅 패턴("캐스팅우선도" - 이블아이 파괴광선, 라키우스 심장 찌르기)을 고르면 그 차례가 밀리고(이번 라운드 우선도를
내림), 밀린 차례에 캐스팅을 쏜 뒤 그 차례의 남은 행동(차수)을 이어서 한다. 이어서 하는 행동에서 또 캐스팅이 나오면
다시 밀려 같은 라운드 안에 쏜다. 캐스팅은 다음 라운드로 넘어가지 않는다.
"""

from game.system import monster_ai
from game.system.combat import monster_actions
from game.system.skill import skill_run
from tests import support


def _전장(이름, 차수=2, 첫순서=True):
    전투상태, [몬스터], 아군 = support.시험_전투([이름])
    몬스터["원본"] = {**몬스터["원본"], "차수": 차수}
    목록 = 전투상태["참가자"]
    목록.remove(몬스터)
    if 첫순서:
        목록.insert(0, 몬스터)
    else:
        목록.append(몬스터)
    전투상태["현재턴"] = 목록.index(몬스터)
    return 전투상태, 몬스터, 아군


def _패턴(몬스터, 이름):
    return next(p for p in 몬스터["원본"]["패턴"].values() if p["이름"] == 이름)


def _차례대로(monkeypatch, 패턴들):
    남은 = list(패턴들)
    monkeypatch.setattr(monster_ai, "행동_선택", lambda p: 남은.pop(0))
    return 남은


def _몬스터_행동(전투상태, 몬스터):
    """몬스터의 차례(첫 차례든 밀린 차례든)를 실행하고 그동안 쌓인 로그의 패턴 이름을 돌려준다."""
    시작 = len(전투상태["로그"])
    monster_actions.몬스터_턴_실행(전투상태, 몬스터)
    이름들 = [
        x.get("패턴")
        for x in 전투상태["로그"][시작:]
        if x.get("공격자") == 몬스터["이름"] and x.get("패턴")
    ]
    # 범위 패턴(파괴광선)은 대상마다 로그가 하나씩이다 - 이어진 같은 이름은 한 번으로 센다
    return [n for i, n in enumerate(이름들) if i == 0 or 이름들[i - 1] != n]


def _다음_몬스터_차례(전투상태, 몬스터):
    """아군은 아무것도 하지 않고 다음 몬스터 차례까지 넘긴다 - (라운드, 밀린 차례인지)."""
    for _ in range(20):
        다음 = skill_run.다음_턴(전투상태)
        if 다음 is 몬스터:
            return 전투상태["라운드"], bool(몬스터.get("캐스팅발사"))
    raise AssertionError("차례가 오지 않는다")


def test_캐스팅을_시작하면_남은_행동은_밀린_차례에_캐스팅을_쏜_뒤_이어서_한다(
    monkeypatch,
):
    전투상태, 눈, _ = _전장("이블아이의 왼쪽눈")
    _차례대로(monkeypatch, [_패턴(눈, "파괴광선"), _패턴(눈, "석화광선")])
    assert _몬스터_행동(전투상태, 눈) == []  # 캐스팅만 시작
    assert 눈["캐스팅시작"]
    라운드, 밀린차례 = _다음_몬스터_차례(전투상태, 눈)
    assert (라운드, 밀린차례) == (1, True)
    assert _몬스터_행동(전투상태, 눈) == ["파괴광선", "석화광선"]
    assert not 눈.get("캐스팅시작")


def test_이어서_한_행동에서_또_캐스팅하면_다시_밀려_같은_라운드에_쏜다(monkeypatch):
    전투상태, 눈, _ = _전장("이블아이의 왼쪽눈")
    _차례대로(monkeypatch, [_패턴(눈, "파괴광선"), _패턴(눈, "파괴광선")])
    우선도 = 눈.get("우선도", 0)
    _몬스터_행동(전투상태, 눈)
    assert _다음_몬스터_차례(전투상태, 눈) == (1, True)
    assert _몬스터_행동(전투상태, 눈) == [
        "파괴광선"
    ]  # 첫 캐스팅을 쏘고 두 번째 캐스팅 시작
    assert 눈["캐스팅시작"]
    assert _다음_몬스터_차례(전투상태, 눈) == (1, True)
    assert 눈["우선도"] == 우선도 - 2
    assert _몬스터_행동(전투상태, 눈) == ["파괴광선"]
    assert _다음_몬스터_차례(전투상태, 눈) == (2, False)  # 다음 라운드의 보통 차례


def test_라운드_마지막_순서에서_캐스팅해도_같은_라운드에_쏘고_이어서_한다(monkeypatch):
    전투상태, 눈, _ = _전장("이블아이의 왼쪽눈", 첫순서=False)
    _차례대로(monkeypatch, [_패턴(눈, "파괴광선"), _패턴(눈, "석화광선")])
    _몬스터_행동(전투상태, 눈)
    assert _다음_몬스터_차례(전투상태, 눈) == (1, True)
    assert _몬스터_행동(전투상태, 눈) == ["파괴광선", "석화광선"]


def test_라키우스_심장_찌르기도_캐스팅_뒤_남은_행동을_이어서_한다(monkeypatch):
    전투상태, 라키우스, _ = _전장("라키우스")
    라키우스["상태이상"] = []
    _차례대로(
        monkeypatch, [_패턴(라키우스, "심장 찌르기"), _패턴(라키우스, "창 찌르기")]
    )
    assert _몬스터_행동(전투상태, 라키우스) == []
    assert _다음_몬스터_차례(전투상태, 라키우스) == (1, True)
    assert _몬스터_행동(전투상태, 라키우스) == ["심장 찌르기", "창 찌르기"]


def test_캐스팅이_행동불가로_끊기면_남은_행동도_하지_않는다(monkeypatch):
    전투상태, 눈, _ = _전장("이블아이의 왼쪽눈")
    _차례대로(monkeypatch, [_패턴(눈, "파괴광선"), _패턴(눈, "석화광선")])
    _몬스터_행동(전투상태, 눈)
    _다음_몬스터_차례(전투상태, 눈)
    눈["상태이상"].append({"이름": "기절", "지속턴": 1})
    assert _몬스터_행동(전투상태, 눈) == []


def test_1차수면_캐스팅_뒤_이어서_할_행동이_없다(monkeypatch):
    전투상태, 눈, _ = _전장("이블아이의 왼쪽눈", 차수=1)
    남은 = _차례대로(monkeypatch, [_패턴(눈, "파괴광선"), _패턴(눈, "석화광선")])
    _몬스터_행동(전투상태, 눈)
    _다음_몬스터_차례(전투상태, 눈)
    assert _몬스터_행동(전투상태, 눈) == ["파괴광선"]
    assert len(남은) == 1
