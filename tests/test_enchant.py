"""마법부여 - 비노슈(무기에 화속성, 100G) (#178, 2026-11-11 사용자 결정).

규칙은 docs/game-rules.md "마법부여".
"""

import pytest

import gameflow as gf
from game.system import (
    collection_system,
    dismantle_system,
    enhance_system,
    loot_system,
    magic_seal_system,
    shop_system,
)
from game.system.combat import stats
from tests import support

무기 = "강철 소검"  # 언커먼 1티어 100G 1d6, 무속성
방어구 = "실키얀 상의"


def _준비(골드=10000):
    상태 = support.새게임([("", "귀검사")])
    상태["소지품"]["골드"] = 골드
    for 레어도 in ("언커먼", "레어"):
        상태["소지품"]["재료"][f"{레어도} 소울"] = 100
    상태["소지품"]["재료"]["라이언 코크스"] = 100
    상태["소지품"]["재료"]["강렬한 기운"] = 100
    return 상태


def _항목(상태, 탭, 이름, 착용=False):
    for 항목 in gf.전문직업_마법부여목록(상태, 탭):
        if 항목["이름"] == 이름 and (항목["캐릭터"] is not None) == 착용:
            return 항목
    raise AssertionError(f"{탭} 목록에 {이름} 없음")


def _부여(상태, 이름, 착용=False, 부여="비노슈", 탭="무기"):
    return gf.전문직업_마법부여(상태, _항목(상태, 탭, 이름, 착용), 부여)


def _장착(상태, 슬롯, 이름):
    귀검사 = 상태["파티"]["파티원"][0]
    상태["소지품"]["장비"][이름] = 상태["소지품"]["장비"].get(이름, 0) + 1
    gf.장비_교체(상태, 귀검사, 슬롯, 이름)
    return 귀검사


