def test_마법부여는_구현됨이고_탭은_부위_두_줄이다():
    assert "마법부여" in gf.전문직업_구현됨
    assert gf.마법부여_탭줄() == [
        ["무기", "상의", "하의", "어깨", "벨트", "신발"],
        ["목걸이", "반지", "팔찌", "보조장비", "마법석", "귀걸이"],
    ]


def test_목록은_그_부위의_소지품과_장착_장비이고_착용중은_캐릭터마다_한_줄이다():
    상태 = _준비()
    상태["소지품"]["장비"][무기] = 2
    _장착(상태, "무기", 무기)
    줄들 = [
        (항목["이름"], 항목["캐릭터"] is not None, 항목["수량"])
        for 항목 in gf.전문직업_마법부여목록(상태, "무기")
        if 항목["이름"] == 무기
    ]
    assert sorted(줄들) == [(무기, False, 2), (무기, True, 1)]
    assert all(
        항목["아이템"]["분류"] == "상의"
        for 항목 in gf.전문직업_마법부여목록(상태, "상의")
    )


def test_봉인된_장비는_목록에_없다():
    상태 = _준비()
    상태["소지품"]["장비"]["마법으로 봉인된 소검"] = 1
    assert "마법으로 봉인된 소검" not in [
        항목["이름"] for 항목 in gf.전문직업_마법부여목록(상태, "무기")
    ]


def test_적용할_마법부여가_없는_부위는_불가로_나온다():
    상태 = _준비()
    상태["소지품"]["장비"][방어구] = 1
    항목 = _항목(상태, "상의", 방어구)
    assert 항목["불가"] == "적용할 수 있는 마법부여가 없습니다."
    assert gf.전문직업_마법부여선택지(상태, 항목) == []
    with pytest.raises(ValueError):
        gf.전문직업_마법부여(상태, 항목, "비노슈")


def test_무기의_선택지는_비노슈_100G_화속성이다():
    상태 = _준비()
    상태["소지품"]["장비"][무기] = 1
    항목 = _항목(상태, "무기", 무기)
    assert 항목["불가"] is None
    [선택지] = gf.전문직업_마법부여선택지(상태, 항목)
    assert 선택지["이름"] == "비노슈"
    assert 선택지["비용글"] == "100G"
    assert "화속성" in 선택지["설명"]
    assert 선택지["불가"] is None


