def test_비노슈를_부여하면_100G를_내고_이름이_바뀌고_화속성이_된다():
    상태 = _준비(골드=150)
    상태["소지품"]["장비"][무기] = 2
    새이름 = _부여(상태, 무기)
    assert 새이름 == f"{무기} [비노슈]"
    assert 상태["소지품"]["골드"] == 50
    assert 상태["소지품"]["장비"] == {**상태["소지품"]["장비"], 무기: 1, 새이름: 1}
    데이터 = 상태["상점카탈로그"]["장비"]["무기"][새이름]
    # 효과는 장비 안의 "마법부여" 딕셔너리에 따로 - 무기 원래 속성은 그대로
    assert 데이터["마법부여"] == {
        "이름": "비노슈",
        "설명": "무기에 화속성을 부여한다.",
        "속성": "화속성",
    }
    원래 = 상태["상점카탈로그"]["장비"]["무기"][무기]
    assert 데이터.get("속성") == 원래.get("속성")
    assert 원래.get("속성", "무속성") != "화속성"


