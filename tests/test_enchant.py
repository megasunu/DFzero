def test_강화한_무기에_부여하면_강화가_남고_부여한_무기도_강화된다():
    상태 = _준비()
    상태["소지품"]["장비"][무기] = 2
    강화 = enhance_system.이름_짓기(무기, {"강화": 1})
    gf.전문직업_강화(
        상태,
        next(
            h
            for h in gf.전문직업_강화목록(상태, "무기강화")
            if h["이름"] == 무기 and h["캐릭터"] is None
        ),
        "무기강화",
    )
    부여강화 = _부여(상태, 강화)
    assert 부여강화 == f"+1강 {무기} [비노슈]"
    카탈로그 = 상태["상점카탈로그"]["장비"]["무기"]
    assert 카탈로그[부여강화]["속성"] == "화속성"
    assert 카탈로그[부여강화]["무기공격력"] == "1d6+1d4"
    # 부여 먼저, 강화 나중
    부여 = _부여(상태, 무기)
    재련 = gf.전문직업_강화(
        상태,
        next(
            h
            for h in gf.전문직업_강화목록(상태, "무기재련")
            if h["이름"] == 부여 and h["캐릭터"] is None
        ),
        "무기재련",
    )
    assert 재련 == f"+1재 {무기} [비노슈]"
    assert 카탈로그[재련]["속성"] == "화속성"
    assert 카탈로그[재련]["명중률보너스"] == 카탈로그[무기].get("명중률보너스", 0) + 1


