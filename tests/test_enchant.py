def test_부여한_무기는_상점_도감_드랍_봉인변환에_나오지_않는다():
    상태 = _준비()
    상태["소지품"]["장비"][무기] = 1
    이름 = _부여(상태, 무기)
    마법 = magic_seal_system.마법의_이름("마법으로 봉인된 소검", "강타")
    상태["소지품"]["장비"][마법] = 1
    마법부여 = _부여(상태, 마법)
    장비 = 상태["상점카탈로그"]["장비"]
    assert 이름 not in [
        a["이름"] for a in shop_system.구매목록(상태["상점카탈로그"], "장비", "무기")
    ]
    assert 이름 not in [a["이름"] for a in collection_system.장비_목록(장비, "무기")]
    for _ in range(200):
        assert loot_system.레어도_장비_뽑기(장비, "언커먼") != 이름
    assert 마법부여 not in {
        항목["이름"] for 항목 in gf.전문직업_봉인목록(상태, "봉인변환")
    }
