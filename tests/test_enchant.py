def test_착용중인_무기에_부여하면_장착칸도_바뀌고_전투에서_화속성으로_친다():
    상태 = _준비()
    귀검사 = _장착(상태, "무기", 무기)
    새이름 = _부여(상태, 무기, 착용=True)
    assert 귀검사["장착장비"]["무기"] == 새이름
    assert 상태["장비데이터모음"][귀검사["캐릭터명"]]["무기"]["이름"] == 새이름
    gf.전투_시작(상태, ["고블린"], 레벨=1, 차수=1)
    support.반응_처리(상태)
    아군 = next(p for p in 상태["전투상태"]["참가자"] if p["진영"] == "아군")
    assert stats.공격_속성(아군, "무기공격력", None) == "화속성"
    assert (
        stats.공격_속성(아군, "1d6", "수속성") == "수속성"
    )  # 무기 주사위가 없는 피해는 그대로


