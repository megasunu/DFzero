"""S12 카겔/봄 카겔과 투척 아이템 (docs/scenarios.md).

4인 기본 파티(귀검사/격투가/거너/프리스트)를 레벨 3까지 키우고 스킬을 전부 배운다. 카겔과 봄 카겔은 하늘성
몬스터지만 하늘성 인카운트가 아직 없어서, 로리엔(D01)에 들어가 카겔 2 + 봄 카겔 1과의 전투를 직접 연다(S4처럼).
전투는 **실제로 굴린다** - 소지품의 표창/폭탄은 조종하는 아군이 차례가 오면 먼저 던지고(일반행동 1개),
프리스트는 쓸 수 있으면 카겔에게 홀리 스매쉬를 먼저 쓰고, 나머지는 스킬 우선 정책(tests/scenario.py)으로 싸운다. 전투마다 마을에서 휴식하고 다시 들어가며 카겔의 네 패턴
(표창 던지기, 다중 표창 던지기, 폭탄 던지기, 다중 폭탄 던지기)이 모두 나올 때까지 최대 6번 싸운다.

불변식: 샹들리에 몬스터는 공중에뜸/넘어짐이 실제로 걸리지 않는다(거너 라이징 샷은 면역 로그로 막힌다).
다중 폭탄 던지기는 범위가 겹쳐 한 턴에 같은 아군이 두 번 이상 맞는다. 표창(아이템과 카겔 패턴)에서만
출혈이 걸린다. 홀리 스매쉬는 카겔에게 늘 "공중에뜸 대상" 추가 피해를 준다. 이긴 전투는 드랍(표창/폭탄 30%)이
소지품에 들어온다. 수치 규칙은 test_combat_rules.py/test_shop_loot.py/test_consumables.py/test_data_integrity.py가 값으로 본다.
"""

from collections import Counter

import pytest

from game.system import rng
import gameflow as gf
import scenario
import support
from game.system.combat import damage, status

로리엔 = "dungeon_01A_D01_Lorien"
# 9 -> 15(2026-10-26): 추천 주/보조/약점(#420)으로 능력치가 바뀌어 옛 시드는 효과가 안 나온다
# 15 -> 19(2026-10-27): 로리엔 스위트 민트 특별드랍 굴림(#437)으로 흐름이 밀려 15는 폭탄이 양 끝 적에 떨어진다(#438)
시드 = 19  # 난수 흐름 분리(2026-10-20) 뒤 시드 0은 이 시나리오의 효과가 안 나온다. 8 -> 9: 귀참·귀참드라이브(2026-10-22) 뒤 8은 한 판을 진다
적구성 = ["카겔", "봄 카겔", "카겔"]
네패턴 = {"표창 던지기", "다중 표창 던지기", "폭탄 던지기", "다중 폭탄 던지기"}


def _카겔인가(참가자):
    return 참가자["진영"] == "적" and "샹들리에" in (참가자["원본"].get("특성") or [])


def _던지기(상태, 참가자, 던짐):
    """소지품에 표창/폭탄이 있으면 하나 던진다(일반행동 1개). 폭탄은 가운데 적을 중심으로."""
    for 이름 in ("표창", "폭탄"):
        if 상태["소지품"]["소모품"].get(이름, 0) <= 0:
            continue
        if 참가자["행동자원"].get("일반행동", 0) <= 0:
            return
        # 가운데 적 = 대형위치 가운데(적 목록은 턴 순서라 위치 순이 아니다)
        적 = sorted(
            (e for e in gf.적_목록(상태) if e["생존"]), key=lambda e: e["대형위치"]
        )
        일반, 개수 = 참가자["행동자원"]["일반행동"], 상태["소지품"]["소모품"][이름]
        중심 = 적[len(적) // 2]
        # 폭탄은 중심과 바로 옆 칸의 산 적 - 옆 칸이 죽어 비었으면 그만큼 적다
        범위 = 1 + len(damage.양옆_이웃(상태["전투상태"], 중심))
        결과 = gf.아군_투척아이템사용(상태, 이름, 중심)
        assert 참가자["행동자원"]["일반행동"] == 일반 - 1
        assert 상태["소지품"]["소모품"].get(이름, 0) == 개수 - 1
        assert len(결과["타격"]) == (1 if 이름 == "표창" else 범위)
        던짐.append(이름)
        return


def _홀리스매쉬(상태, 참가자):
    """프리스트는 쓸 수 있으면 먼저 카겔에게 홀리 스매쉬(공중에뜸 대상 추가 피해)를 쓴다."""
    카겔 = [e for e in gf.적_목록(상태) if e["생존"] and _카겔인가(e)]
    if (
        카겔
        and 참가자["원본"]["직업"] == "프리스트"
        and gf.스킬_사용_가능여부(상태, 참가자, "홀리 스매쉬")[0]
    ):
        gf.아군_스킬사용(상태, "홀리 스매쉬", 카겔[0])


def _불변식(상태):
    for e in gf.적_목록(상태):
        if _카겔인가(e):
            이름들 = {i["이름"] for i in e["상태이상"]}
            assert not 이름들 & {"공중에뜸", "넘어짐"}, (e["이름"], 이름들)
            assert status.상태이상_판정(상태["전투상태"], e, "공중에뜸")


def _전투(상태):
    """한 전투를 끝까지. 요약(종료/라운드/던짐/패턴/면역/출혈/홀리 스매쉬)을 돌려준다."""
    support.반응_처리(상태)
    전투상태 = 상태["전투상태"]
    # 홀리 스매쉬 추가 피해를 피해내역으로 본다(굴림에는 영향 없음)
    전투상태["상세로그"] = True
    사용기록, 던짐 = [], []
    for _ in range(300):
        _불변식(상태)
        if gf.전투_종료됨(상태):
            break
        참가자 = gf.현재_턴_참가자(상태)
        if 참가자["진영"] == "아군" and 참가자["생존"]:
            _던지기(상태, 참가자, 던짐)
            if not gf.전투_종료됨(상태):
                _홀리스매쉬(상태, 참가자)
            if not gf.전투_종료됨(상태):
                scenario.스킬_우선_턴(상태, 사용기록)
        else:
            gf.턴_넘기기(상태)
    else:
        raise AssertionError("전투가 끝나지 않았다")

    로그 = 전투상태["로그"]
    카겔이름 = {p["이름"] for p in 전투상태["참가자"] if _카겔인가(p)}
    # 패턴 한 번 = 같은 카겔이 이어서 남긴 줄들(대상마다 한 줄, 사이의 출혈 "비고" 줄은 건너뛴다)
    사용들 = []  # [(패턴, [대상...])]
    지금 = None  # (공격자, 패턴)
    for x in 로그:
        공격자, 패턴이름 = x.get("공격자"), x.get("패턴")
        if 공격자 in 카겔이름 and 패턴이름:
            if 지금 != (공격자, 패턴이름):
                사용들.append((패턴이름, []))
                지금 = (공격자, 패턴이름)
            사용들[-1][1].append(x["대상"])
        elif not (지금 and 공격자 == 지금[0] and "비고" in x):
            지금 = None
    패턴 = Counter(이름 for 이름, _ in 사용들)
    다중폭탄_최다피격 = [
        max(Counter(대상들).values())
        for 이름, 대상들 in 사용들
        if 이름 == "다중 폭탄 던지기"
    ]

    # 아군 스킬/아이템은 타격의 효과로그, 몬스터 패턴은 "비고" 줄로 남는다
    출혈출처 = Counter()
    for x in 로그:
        for 타격 in x.get("타격") or []:
            if any(
                "'출혈'" in 글 and "실패" in 글 for 글 in 타격.get("효과로그") or []
            ):
                출혈출처[x.get("스킬")] += 1
        비고 = str(x.get("비고", ""))
        if (
            "'출혈' 상태이상 부여" in 비고
        ):  # "'표창 던지기' 패턴 - '출혈' 상태이상 부여"
            출혈출처[비고.split("'")[1]] += 1
    면역 = sum(
        1
        for x in 로그
        if str(x.get("대상")) in 카겔이름 and "상태이상 면역" in str(x.get("비고", ""))
    )
    스매쉬 = [
        t
        for x in 로그
        if x.get("스킬") == "홀리 스매쉬"
        for t in x.get("타격") or []
        if t.get("대상") in 카겔이름 and t["판정"]["성공"]
    ]
    return {
        "종료": 전투상태["종료"],
        "라운드": 전투상태["라운드"],
        "던짐": 던짐,
        "패턴": dict(sorted(패턴.items())),
        "다중폭탄_최다피격": 다중폭탄_최다피격,
        "출혈출처": dict(sorted(출혈출처.items())),
        "공중에뜸_넘어짐_면역": 면역,
        "카겔_홀리스매쉬_명중": len(스매쉬),
        "_스매쉬": 스매쉬,
    }


@pytest.mark.scenario("S12")
def test_S12_카겔_봄카겔_투척_실전(golden):
    rng.시드(시드)
    상태 = support.새게임()
    파티 = 상태["파티"]["파티원"]
    for c in 파티:
        support.성장(상태, c, 3, 스킬습득=True)
    상태["소지품"]["소모품"].update({"표창": 1, "폭탄": 1})
    기록 = []
    본패턴 = set()
    for _ in range(6):
        # 전투마다 마을에서 휴식하고(S5와 같다) 다시 들어가 카겔 무리를 만난다
        gf.휴식(상태)
        상태["던전상태"] = None
        assert all(c["현재HP"] == gf.캐릭터_최대HP(상태, c) for c in 파티)
        gf.던전_진입(상태, 로리엔)
        gf.전투_시작(상태, 적구성, 레벨=3, 차수=1)
        요약 = _전투(상태)
        스매쉬 = 요약.pop("_스매쉬")
        for t in 스매쉬:  # 공중에뜸 대상 추가 피해(보정공격력)가 붙었다
            assert any(
                이름 == "조건부효과" and 값 > 0 for 이름, 값 in t["피해내역"]["추가"]
            ), t
        assert gf.전투_결과_정리(상태) == 요약["종료"]
        if 요약["종료"] == "아군승리":
            얻음 = dict(상태["전투_전리품"]["아이템"])
            요약["드랍"] = {k: 얻음[k] for k in ("표창", "폭탄") if k in 얻음}
            후 = scenario.소지품_아이템수(상태)
            for 이름, 개수 in 요약["드랍"].items():
                assert 후.get(이름, 0) >= 개수
            요약["보상"] = scenario.보상_수령(상태)[0]
        기록.append(요약)
        본패턴 |= set(요약["패턴"])
        if 요약["종료"] != "아군승리" or 본패턴 >= 네패턴:
            break

    assert 기록[-1]["종료"] == "아군승리", 기록
    assert 본패턴 >= 네패턴, 본패턴
    assert 기록[0]["던짐"] == ["표창", "폭탄"]
    # 다중 폭탄 던지기는 범위가 겹쳐 같은 아군이 한 턴에 두 번 이상 맞는다(아군 둘 이상 살아 있을 때)
    assert any(n >= 2 for r in 기록 for n in r["다중폭탄_최다피격"]), 기록
    # 출혈은 표창(아이템)과 카겔의 표창 패턴에서만 걸린다
    출처 = set().union(*(r["출혈출처"] for r in 기록))
    assert 출처 <= {"표창", "표창 던지기", "다중 표창 던지기"}, 출처
    assert sum(r["카겔_홀리스매쉬_명중"] for r in 기록) >= 1, 기록
    golden("scenario_S12_kagel", 기록)
