    [bs2] = [c for c in 불러옴["파티"]["파티원"] if c["직업"] == "귀검사"]
    assert 스킬 in bs2["보유스킬"]
    golden("scenario_S12_steal_learn", {"스킬": 스킬, "전투": 전투들})


