def test_학습정책은_전투가_끝날_때마다_고른_퍽에_승패를_센다():
    import scenario

    rng.시드(1)
    정책 = scenario.학습정책(탐험률=1.0)
    상태 = 새게임()
    scenario.측정_파티_준비(상태, 4, 정책=정책)
    고른퍽 = list(정책.이번퍽)
    assert len(고른퍽) == 4
    for _ in range(2):  # 한 판에 전투가 두 번 - 퍽은 두 번 다 센다
        gf.전투_시작(상태, ["고블린", "고블린", "고블린"], 레벨=1, 차수=1)
        scenario.측정_실전(상태, 정책=정책)
        gf.휴식(상태)
    assert 정책.이번퍽 == 고른퍽
    for 키 in 고른퍽:
        assert 정책.퍽표[키][1] == 2
    표 = scenario.퍽_승률표(정책)
    assert {퍽 for 퍽, *_ in 표[("귀검사", 4)]} == {고른퍽[0][2]}
    # 새로 준비하면 이번 판의 퍽 기록은 새로 시작한다
    scenario.측정_파티_준비(새게임(), 4, 정책=정책)
    assert len(정책.이번퍽) == 4


# ---------------------- 하단공격은 공중에 뜬 적을 노리지 않는다 (tests/scenario.py 학습정책)


def test_학습정책은_하단공격_스킬로_공중에_뜬_적을_고르지_않는다():
    """표적 종류(HP최저 등)가 가리키는 적이 공중에 떠 있으면 하단공격 스킬은 지정할 수 있는 적을 노린다 -
    전부 떠 있으면 그 스킬은 후보에 없다. 예전에는 지정할 수 없는 적을 골라 스킬_실행이 ValueError를 냈다."""
    import scenario
    from game.system import skill_system as ss

    상태, p, _ = support.추가행동_전장()
    p["원본"]["보유스킬"].append("웨이브")
    적 = sorted(gf.적_목록(상태), key=lambda e: e["대형위치"])
    적[0]["현재HP"] = 1  # HP최저 표적 = 띄운 적
    ss.상태이상_부여(상태["전투상태"], 적[0], "공중에뜸", 1)
    정책 = scenario.학습정책(탐험률=1.0)
    웨이브 = [(키, 실행) for 키, 실행 in 정책.후보(상태, p) if 키[0] == "웨이브"]
    assert 웨이브
    시작 = len(상태["전투상태"]["로그"])
    dict(웨이브)[("웨이브", "HP최저")](상태)
    [줄] = [x for x in 상태["전투상태"]["로그"][시작:] if x.get("스킬") == "웨이브"]
    assert 적[0]["이름"] not in str(줄.get("대상"))
    ss.상태이상_부여(상태["전투상태"], 적[1], "공중에뜸", 1)
    assert not [키 for 키, _ in 정책.후보(상태, p) if 키[0] == "웨이브"]


# ---------------------- 감옥도 노린다 (#504, tests/scenario.py 학습정책)


def test_학습정책은_동료가_감옥에_갇히면_감옥을_노리는_행동을_후보에_넣는다():
    """비노슈 운석 감옥(진영 "감옥")은 적_목록에 없지만 아군이 칠 수 있다(공격대상_목록) - 정책도 표적 "감옥"으로
    고를 수 있어야 한다. 예전에는 후보에 없어 감옥을 한 번도 치지 않았다."""
    import scenario
    from game.system.combat import monster_actions

    rng.시드(5)
    상태 = 새게임()
    gf.전투_시작(상태, [{"이름": "화염의 비노슈"}], 레벨=5, 차수=1)
    support.반응_처리(상태)
    p = support.아군_차례로(상태, "귀검사")
    정책 = scenario.학습정책(탐험률=1.0)
    assert not [키 for 키, _ in 정책.후보(상태, p) if 키[1] == "감옥"]
    비노슈 = gf.적_목록(상태)[0]
    패턴 = next(x for x in 비노슈["원본"]["패턴"].values() if x["타입"] == "감옥패턴")
    갇힌 = next(a for a in gf.아군_목록(상태) if a is not p)
    monster_actions.감옥_걸기(상태["전투상태"], 비노슈, 갇힌, 패턴, "시험")
    [감옥] = [q for q in gf.공격대상_목록(상태) if q["진영"] == "감옥"]
    후보 = dict(정책.후보(상태, p))
    assert ("일반공격", "감옥") in 후보
    시작 = len(상태["전투상태"]["로그"])
    후보[("일반공격", "감옥")](상태)
    [줄] = [x for x in 상태["전투상태"]["로그"][시작:] if x.get("종류") == "일반공격"]
    assert 줄["대상"] == 감옥["이름"]


