def _샌드백_자동전투_스킬(공격):
    """방어스킬을 가진 레벨 9 파티로 샌드백 전투를 열고 아군 차례 6번을 [자동전투] - 아군이 쓴 스킬 이름 집합."""
    import scenario

    원래 = gf.자동전투_방식()
    gf.자동전투_방식_설정("전력전투")
    try:
        rng.시드(1)
        상태 = 새게임([("", 직업) for 직업, _ in _방어_파티])
        for c, (_, 전직) in zip(상태["파티"]["파티원"], _방어_파티):
            support.성장(상태, c, 9, 전직=전직, 스킬습득=True)
        scenario.샌드백_전투(상태, 9, 차수=2, 공격=공격)
        이름들 = {a["이름"] for a in gf.아군_목록(상태)}
        차례 = 0
        while 차례 < 6 and not gf.전투_종료됨(상태):
            if gf.아군_차례인가(상태):
                gf.자동전투_한_턴(상태)
                차례 += 1
            else:
                gf.턴_넘기기(상태)
        return {
            x["스킬"]
            for x in 상태["전투상태"]["로그"]
            if x.get("공격자") in 이름들 and x.get("스킬")
        }
    finally:
        gf.자동전투_방식_설정(원래)


def _방어스킬(이름):
    return gf.스킬데이터모음_생성()[이름].get("방어스킬") is True


def test_방어스킬_표시는_받는_피해만_줄이는_버프에만_있다():
    모음 = gf.스킬데이터모음_생성()
    assert {n for n, d in 모음.items() if d.get("방어스킬")} == {
        "가드",
        "사무치는 광기",
        "넨가드",
        "무기막기",
        "수호의 축복",
        "편애",  # 인챈트리스 - 수호의 축복과 같다
        "신성한 빛",
        "장갑강화",
        "완충모듈",
        "기동강화",
    }
    assert not 모음["분신"].get("방어스킬")  # 환영폭쇄의 재료라 방어스킬이 아니다


def test_전력전투는_공격하지_않는_적만_있으면_방어스킬을_쓰지_않는다():
    쓴것 = _샌드백_자동전투_스킬(공격=False)
    assert 쓴것, "스킬을 하나도 쓰지 않았다"
    assert not {n for n in 쓴것 if _방어스킬(n)}, 쓴것


def test_전력전투는_공격하는_적이_있으면_방어스킬을_쓴다():
    쓴것 = _샌드백_자동전투_스킬(공격=True)
    assert {n for n in 쓴것 if _방어스킬(n)}, 쓴것
