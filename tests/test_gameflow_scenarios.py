def _상세_전투줄(상태, c):
    """상세정보 전투 줄에서 (AC, 명중 보정, 데미지보너스)."""
    줄들 = dict(gf.캐릭터_상세정보(상태, c))["전투"]
    AC = int(줄들[0].split(":")[1])
    명중 = int(줄들[1].split(":")[1].split()[0])
    데미지 = int(줄들[2].split(":")[1])
    return AC, 명중, 데미지


