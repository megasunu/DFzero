def test_상점에서_사서_입고_팔기():
    상태 = 새게임([("", "귀검사")])
    c = 상태["파티"]["파티원"][0]
    엘븐 = gf.현재_마을정보(상태)["상점판매목록"]
    assert gf.상점_탭목록("장비")[0] == "무기" and gf.상점_보유골드(상태) == 0
    assert [i["이름"] for i in gf.상점_구매목록(상태, "장비", "상의", 엘븐)][:2] == [
        "찢어진 천갑 상의",
        "마리아의 천 상의",
    ]
    with pytest.raises(ValueError, match="골드"):
        gf.상점_구매(상태, "장비", "상의", "녹슨 중갑 상의", 1, 엘븐)
    상태["소지품"]["골드"] = 100
    assert gf.상점_구매(상태, "장비", "무기", "치트용 소검", 1, 엘븐) == 0
    assert gf.상점_구매(상태, "장비", "하의", "허름한 경갑 하의", 1, 엘븐) == 10
    assert gf.상점_구매(상태, "장비", "상의", "녹슨 중갑 상의", 1, 엘븐) == 10

    AC전 = gf.캐릭터_상세정보(상태, c)[2][1][0]
    후보 = {i["이름"]: 가능 for i, _, 가능, _ in gf.장비_교체_후보(상태, c, "상의")}
    # 입고 있는 경갑 상의는 후보에서 빠진다. 방어구는 재질 제한 없이 입는다
    assert 후보 == {"녹슨 중갑 상의": True}
    with pytest.raises(ValueError, match="아이템이 아니다"):
        gf.장비_교체(상태, c, "하의", "녹슨 중갑 상의")
    gf.장비_교체(상태, c, "하의", "허름한 경갑 하의")
    gf.장비_교체(상태, c, "무기", "치트용 소검")
    assert gf.캐릭터_장착아이템(상태, c, "무기")["이름"] == "치트용 소검"
    assert 상태["장비데이터모음"][c["캐릭터명"]]["하의"]["이름"] == "허름한 경갑 하의"

    # 상의를 벗으면 AC가 1 떨어진다(경갑 상의 AC보너스 1)
    gf.장비_해제(상태, c, "상의")
    AC후 = gf.캐릭터_상세정보(상태, c)[2][1][0]
    assert (AC전, AC후) == ("AC: 12", "AC: 11")
    with pytest.raises(ValueError, match="무기는 해제"):
        gf.장비_해제(상태, c, "무기")

    판매 = {i["이름"]: n for i, n in gf.상점_판매목록(상태, "장비", "상의")}
    assert 판매 == {"허름한 경갑 상의": 1, "녹슨 중갑 상의": 1}
    assert gf.상점_판매(상태, "장비", "상의", "녹슨 중갑 상의", 1) == 2
    assert gf.상점_보유골드(상태) == 100 - 20 + 2


