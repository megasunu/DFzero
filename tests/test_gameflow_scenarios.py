def test_자동전투는_일반행동을_다_쓰고_턴을_넘긴다(monkeypatch):
    상태 = 새게임()
    전투_열기(상태, ["타우 아미", "고블린", "고블린"])
    현재 = 아군_차례로(상태, "귀검사")
    행동수 = 현재["행동자원"]["일반행동"]
    assert 행동수 >= 1
    전투상태 = 상태["전투상태"]
    고른대상 = []  # 적을 고른 호출마다 그 순간의 (진영, 생존) 목록
    원래선택 = rng.대상.choice

    def 기록선택(후보):
        if 후보 and 후보[0].get("진영") == "적":
            고른대상.append([(p["진영"], p["생존"]) for p in 후보])
        return 원래선택(후보)

    monkeypatch.setattr(rng.대상, "choice", 기록선택)
    넘김 = []
    # 자동전투_한_턴이 부르는 턴_넘기기를 가로챈다 - 구현 모듈(ctl_autobattle)이 가져온 이름을 바꿔야 한다
    # (gf는 재수출 창구라 gf의 이름을 바꿔도 컨트롤러 안의 호출은 그대로다)
    원래넘기기 = ctl_autobattle.턴_넘기기
    monkeypatch.setattr(
        ctl_autobattle, "턴_넘기기", lambda s: 넘김.append(1) or 원래넘기기(s)
    )

    gf.자동전투_한_턴(상태)
    if 전투상태["종료"] is None:
        assert 넘김 == [1]
    assert 현재["행동자원"]["일반행동"] == 0 or 전투상태["종료"] is not None
    assert 1 <= len(고른대상) <= 행동수
    for 후보 in 고른대상:  # 매번 그 순간 살아 있는 적만 후보
        assert 후보 and all(후 == ("적", True) for 후 in 후보)
    일반공격로그 = [
        기록
        for 기록 in 전투상태["로그"]
        if 기록.get("공격자") == 현재["이름"] and "판정" in 기록
    ]
    assert len(일반공격로그) >= len(고른대상)


def _마법사_자동전투_로그(상태, 마법사):
    """마법사 차례에 [자동전투]를 한 번 누르고, 그 사이 마법사가 남긴 로그."""
    전투상태 = 상태["전투상태"]
    넘김 = []
    시작 = len(전투상태["로그"])
    원래넘기기 = ctl_autobattle.턴_넘기기
    ctl_autobattle.턴_넘기기 = lambda s: 넘김.append(1)
    try:
        gf.자동전투_한_턴(상태)
    finally:
        ctl_autobattle.턴_넘기기 = 원래넘기기
    return [
        기록 for 기록 in 전투상태["로그"][시작:] if 기록.get("공격자") == 마법사["이름"]
    ]


