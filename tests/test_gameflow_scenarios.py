    del 데이터["진행도"]["플레이어레벨"]
    del 데이터["플레이어"]["선택된초상화"]
    데이터["플레이어"]["레벨"] = 3
    for c in 데이터["플레이어"]["파티"]["파티원"]:
        del c["성별"], c["횟수제한스킬"], c["치명타주사위"]
        c["보유특성"] += ["엘레멘탈 번"]  # 레벨 8 버프로 바뀌어 없어진 특성
        c["보유특성"] += ["웨펀마스터"]  # 무기의 극의로 이름이 바뀐 특성
        c["기본최대HP"] = c["현재HP"] = 99  # 옛 HP 공식 값
        c.pop("레벨당체력증가", None)
        c.pop("직업스타일", None)  # 직업스타일 성장 도입 전
        c["추가공격"] = 5
    경로.write_text(json.dumps(데이터, ensure_ascii=False), encoding="utf-8")
    불러옴 = gf.게임_불러오기(1)
    c = 불러옴["파티"]["파티원"][0]
    assert 불러옴["진행도"]["플레이어레벨"] == 3
    assert 불러옴["선택된초상화"] == "001m"
    assert "엘레멘탈 번" not in c["보유특성"] and "마법재능" in c["보유특성"]
    assert "웨펀마스터" not in c["보유특성"] and "무기의 극의" in c["보유특성"]
    # 불러올 때 새 HP 공식으로 다시 계산(현재HP는 새 최대치로 자름)
    # 마법사 레벨 1, 건강 10(기본 약점은 근력): 기본체력 4+0=4, 4 + 올림(2)
    assert (c["기본최대HP"], c["현재HP"], c["레벨당체력증가"]) == (6, 6, 4)
    # 옛 레벨 10 추가공격은 버리고 직업스타일 성장으로 다시 계산
    assert (c["직업스타일"], c["추가공격"], c["추가공격획득"]) == ("비전직", 0, 0)
    assert c["치명타주사위"] == 1
    assert (c["성별"], c["전직"], c["횟수제한스킬"]) == (
        "m",
        None,
        {"휴식제한스킬": {}},
    )


