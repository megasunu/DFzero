def test_캠페인_전체_진행(golden):
    """엘븐가드에서 시작해 던전 10개의 보스를 순서대로 잡는다. 인카운트는
    시드 1로 고정, 전투 결과는 강제 승리(전투 규칙은 test_combat_*가 검사)."""
    random.seed(1)
    상태 = 새게임()
    진행도 = 상태["진행도"]
    기록 = []

    assert [m["마을명"] for m in gf.이동가능마을목록(상태)] == ["엘븐가드"]
    assert gf.이동가능던전목록(상태) == [_던전(1)]
    with pytest.raises(ValueError):
        gf.마을_이동(상태, "헨돈마이어")

    # 로리엔 -> 로리엔 안쪽 -> 엘븐가드
    gf.던전_진입(상태, _던전(1))
    _보스(상태, 기록)
    assert 진행도["플레이어레벨"] == 1  # 로리엔 보스는 레벨 트리거가 없다
    assert 연결로_나가기(상태, _던전(2), 기록)["타입"] == "던전"
    assert 상태["던전상태"]["위치"] == (0, 3)
    _보스(상태, 기록)
    assert 진행도["플레이어레벨"] == 2
    assert 연결로_나가기(상태, "town_01A_T01_Elvengard", 기록) == {
        "타입": "마을",
        "마을명": "엘븐가드",
    }
    assert 상태["던전상태"] is None

    # 헨돈마이어 개방
    assert [m["마을명"] for m in gf.이동가능마을목록(상태)] == [
        "엘븐가드",
        "헨돈마이어",
    ]
    gf.마을_이동(상태, "헨돈마이어")
    assert gf.이동가능던전목록(상태) == [_던전(3), _던전(5), _던전(8)]
    # 순서 해금: 바로 앞 번호 던전의 보스를 깨야 열린다(목록엔 보이되 비활성)
    assert [열림 for _, _, 열림 in gf.던전목록_표시(상태)] == [True, False, False]

    # 머크우드 -> 깊숙한곳 -> 헨돈마이어
    gf.던전_진입(상태, _던전(3))
    assert (
        상태["던전상태"]["그리드"][5][3] != "O"
    )  # 숏컷(포이즌 선더랜드 보스 필요) 닫힘
    _보스(상태, 기록)
    연결로_나가기(상태, _던전(4), 기록)
    _보스(상태, 기록)
    assert 진행도["플레이어레벨"] == 4
    assert (
        연결로_나가기(상태, "town_01A_T02_hendonmyre", 기록)["마을명"] == "헨돈마이어"
    )
    assert [열림 for _, _, 열림 in gf.던전목록_표시(상태)] == [True, True, False]

    # 선더랜드 보스 -> 자기 숏컷 개방 -> 포이즌 선더랜드
    gf.던전_진입(상태, _던전(5))
    _보스(상태, 기록)
    gf.던전_진입(상태, _던전(5))  # 다시 들어오면 그리드가 새로 만들어진다
    assert 상태["던전상태"]["그리드"][5][3] == "O"  # 해금상태_적용
    assert 상태["던전상태"]["그리드"][1][3] != "O"  # 불타는 그락카락 보스가 필요
    연결로_나가기(상태, _던전(6), 기록)
    _보스(상태, 기록)
    assert 진행도["플레이어레벨"] == 6

    # 머크우드 숏컷 개방 -> 프로스트 머크우드
    gf.던전_진입(상태, _던전(3))
    assert 상태["던전상태"]["그리드"][5][3] == "O"
    _보스(상태, 기록)  # 보스는 다시 나온다(오브젝트는 던전마다 리셋)
    연결로_나가기(상태, _던전(7), 기록)
    _보스(상태, 기록)

    # 그락카락 -> 불타는 그락카락 -> 선더랜드 북쪽 숏컷 -> 어둠의 선더랜드
    assert gf.던전_열림(상태, _던전(8))  # 프로스트 머크우드(D07) 보스를 깼다
    gf.던전_진입(상태, _던전(8))
    _보스(상태, 기록)
    assert 진행도["플레이어레벨"] == 8
    연결로_나가기(상태, _던전(9), 기록)
    _보스(상태, 기록)
    gf.던전_진입(상태, _던전(5))
    assert 상태["던전상태"]["그리드"][1][3] == "O"
    연결로_나가기(상태, _던전(10), 기록)
    _보스(상태, 기록)
    assert 진행도["플레이어레벨"] == 10

    assert 진행도["클리어한던전"] == {_던전(n) for n in range(1, 11)}
    기록.append(("클리어한오브젝트", sorted(진행도["클리어한오브젝트"])))
    golden("scenario_campaign", 기록)


