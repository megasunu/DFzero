                assert 템["AC보너스"] == ac, (템["이름"], 템["AC보너스"], ac)
                # 해제 불가 패널티: 판금만 부위마다 아이템 수치로(숙련으로 안 없어진다)
                패널티 = 판금_부위별_패널티[부위] if 재질 == "판금" else {}
                assert 템["속도보너스"] == 패널티.get("속도보너스", 0), 템["이름"]
                for 키 in ("데미지보너스", "명중률보너스", "치명타주사위"):
                    assert 템.get(키, 0) == 패널티.get(키, 0), (템["이름"], 키)
                assert 템["스탯보너스"] == 패널티.get("스탯보너스", {}), 템["이름"]


