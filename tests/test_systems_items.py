def test_패셔니스트는_입은_방어구의_서로_다른_재질_수에_따라_단계별로_누적된다():
    """2종류 AC +1, 3종류 중갑/판금 공용 패널티 삭제, 4종류 매력 +2, 5종류 매력 +3(합 +5)."""
    재질순 = ["판금", "중갑", "경갑", "가죽", "천갑"]

    def 입힘(재질수):
        return {
            슬롯: ({"재질": 재질순[i]} if i < 재질수 else None)
            for i, 슬롯 in enumerate(장비.방어구_슬롯)
        }

    # 재질 수, AC, 매력, 공용 패널티 삭제
    기대 = [(0, 0, 0, False), (1, 0, 0, False), (2, 1, 0, False)]
    기대 += [(3, 1, 0, True), (4, 1, 2, True), (5, 1, 5, True)]
    for 재질수, AC, 매력, 면제 in 기대:
        장착 = 입힘(재질수)
        없음 = _캐릭터()
        있음 = _캐릭터(보유특성=["패셔니스트"])
        assert 장비.방어구_재질수(장착) == 재질수
        assert 장비.최종AC_계산(있음, 장착) - 장비.최종AC_계산(없음, 장착) == AC
        assert (
            장비.장비반영_능력치(있음, 장착)["매력"]
            == 장비.장비반영_능력치(없음, 장착)["매력"] + 매력
        )
        보너스 = 장비.캐릭터_장비_보너스(있음, 장착)
        assert 보너스["스탯보너스"]["매력"] == 매력
        중갑입음 = 재질수 >= 1
        assert 장비.중갑_패널티_재질(없음, 장착) == 재질순[: min(재질수, 2)]
        if 중갑입음 and 면제:
            assert 장비.중갑_패널티_재질(있음, 장착) == []
            assert 보너스["MP소모배율"] == 1
            assert (보너스["명중률보너스"], 보너스["속도보너스"]) == (0, 0)
        elif 중갑입음:
            assert 보너스["MP소모배율"] == 2
            assert (보너스["명중률보너스"], 보너스["속도보너스"]) == (-1, -5)
        assert 장비.캐릭터_장비_보너스(없음, 장착)["스탯보너스"]["매력"] == 0

    # 입지 않은 부위는 세지 않고, 같은 재질은 한 번만 센다
    assert 장비.방어구_재질수({"상의": {"재질": "판금"}, "하의": {"재질": "판금"}}) == 1
    assert 장비.방어구_재질수({"상의": None, "무기": {"재질": "경갑"}}) == 0

    # 판금 부위별 패널티(아이템 수치)는 패셔니스트로도 없어지지 않는다
    장착 = 입힘(5)
    장착["상의"] = {"재질": "판금", "데미지보너스": -2}
    있음 = _캐릭터(보유특성=["패셔니스트"])
    assert 장비.캐릭터_장비_보너스(있음, 장착)["데미지보너스"] == -2


