    for 수량, 메시지 in [
        (0, "1 이상"),
        (1.5, "1 이상"),
        (100, "99개"),
        (1, "골드가 부족"),
    ]:
        with pytest.raises(ValueError, match=메시지):
            상점.구매_처리(p, 카탈로그, "소모품", "포션", "초보자용 HP 포션", 수량)
    with pytest.raises(ValueError, match="팔지 않는다"):
        상점.구매_처리(p, 카탈로그, "장비", "무기", "강철 소검", 1, ["녹슨 소검"])
    assert 상점.보유_골드({}) == 0  # 소지품이 없으면 만들어서 0


