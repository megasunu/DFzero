"""S8 주류 - 취기/만취 (docs/scenarios.md).

4인 기본 파티가 마을에서 술을 마시고(귀검사는 4잔으로 만취, 프리스트는 와인 1잔으로 취기 1) 로리엔에서
인카운트 2번을 **실제 전투로** 치른다. 첫 전투에서 처음 조종하는 아군이 럼주를 마신다(보조행동). 만취한
귀검사는 조종하지 않고 턴_넘기기가 대신 행동시킨다(수면 또는 적/아군 무작위 대상 행동). 취기/만취는 전투와
세이브를 넘어 남고, 마을 휴식으로 풀린다.
주류는 아직 얻을 곳이 없어(마을 판매목록/드랍표에 없음) 소지품에 직접 넣는다. 회복/중첩 수치 규칙은
test_consumables.py가 값으로 검사한다.
"""

import pytest

from game.system import rng
import gameflow as gf
import scenario
import support

로리엔 = "dungeon_01A_D01_Lorien"
시드 = 3


def _음주상태(상태):
    return {c["캐릭터명"]: gf.음주_표시(c["상태이상"]) for c in 상태["파티"]["파티원"]}


def _전투(상태, 술=None):
    """조종할 아군은 [자동전투]처럼 무작위 일반공격, 술이 있으면 처음 조종하는 아군이 먼저 마신다."""
    support.반응_처리(상태)
    마심 = 술 is None
    for _ in range(300):
        if gf.전투_종료됨(상태):
            break
        if not gf.아군_차례인가(상태):
            gf.턴_넘기기(상태)
            continue
        현재 = gf.현재_턴_참가자(상태)
        assert gf.음주_표시(현재["상태이상"]) != "만취", "만취 아군을 조종했다"
        if not 마심:
            보조 = 현재["행동자원"]["보조행동"]
            회복, 결과 = gf.아군_주류사용(상태, 술)
            assert 결과.startswith("취기") and set(회복) == {"HP", "MP"}
            assert 현재["행동자원"]["보조행동"] == 보조 - 1
            마심 = 현재["이름"]
        gf.자동전투_한_턴(상태)
    else:
        raise AssertionError("전투가 끝나지 않았다")
    assert 마심, "조종할 아군 차례가 오지 않았다"
    로그 = 상태["전투상태"]["로그"]
    return {
        "종료": 상태["전투상태"]["종료"],
        "마신사람": 마심 if 술 else None,
        "라운드": 상태["전투상태"]["라운드"],
        "만취행동": [
            x["행동"] for x in 로그 if str(x.get("행동", "")).startswith("만취 - ")
        ],
        "음주": {p["이름"]: gf.음주_표시(p["상태이상"]) for p in gf.아군_목록(상태)},
    }


@pytest.mark.scenario("S8")
def test_S8_주류_취기_만취_실전(golden):
    rng.시드(시드)
    상태 = support.새게임()
    귀검사, _, _, 프리스트 = 상태["파티"]["파티원"]
    상태["소지품"]["소모품"].update({"맥주": 4, "와인": 1, "럼주": 1})
    매력전 = gf.캐릭터_유효능력치(상태, 프리스트)["매력"]

    # 마을: 귀검사 맥주 4잔(취기 1 -> 2 -> 3 -> 만취), 프리스트 와인 1잔
    결과들 = [gf.캐릭터_주류사용(상태, 귀검사, "맥주")[1] for _ in range(4)]
    assert 결과들 == ["취기 1", "취기 2", "취기 3", "만취"]
    gf.캐릭터_주류사용(상태, 프리스트, "와인")
    기록 = {"마신뒤": _음주상태(상태), "전투": []}

    gf.던전_진입(상태, 로리엔)
    for 번째, 술 in enumerate(("럼주", None)):
        적 = scenario.인카운트까지_걷기(상태)
        요약 = _전투(상태, 술)
        요약["적"] = 적
        assert gf.전투_결과_정리(상태) == 요약["종료"] == "아군승리"
        scenario.보상_수령(상태)
        # 만취/취기는 전투 뒤에도 남고, 전투 중 걸린 수면은 남지 않는다
        assert 귀검사["상태이상"] == [{"이름": "취기", "중첩": 3}, {"이름": "만취"}]
        assert 프리스트["상태이상"][0]["이름"] == "취기"
        assert gf.캐릭터_유효능력치(상태, 프리스트)["매력"] == (
            매력전 - 프리스트["상태이상"][0]["중첩"]
        )
        요약["전투뒤"] = _음주상태(상태)
        기록["전투"].append(요약)

    # 만취한 귀검사는 자기 차례를 만취 행동(수면/무작위 행동)으로 보냈다
    assert any(요약["만취행동"] for 요약 in 기록["전투"]), 기록["전투"]

    # 세이브 왕복에도 남는다
    gf.게임_저장(상태, 1)
    불러옴 = gf.게임_불러오기(1)
    assert _음주상태(불러옴) == _음주상태(상태)

    # 마을 휴식으로 풀린다
    gf.휴식(상태)
    assert all(c["상태이상"] == [] for c in 상태["파티"]["파티원"])
    assert gf.캐릭터_유효능력치(상태, 프리스트)["매력"] == 매력전
    기록["휴식뒤"] = _음주상태(상태)
    golden("scenario_S8_drink", 기록)
