def test_로그_모양별_읽기():
    """총피해(스킬) / 타격 목록만(장판) / 타격에 대상이 없으면 항목 대상(몬스터 패턴 모양) / 피해 칸(비고)."""
    전투상태, 적, 아군 = 시험_전투(["고블린", "고블린"])
    a, b = 아군[0]["이름"], 적[0]["이름"]
    전투상태["로그"] = [
        {
            "공격자": a,
            "타격": [{"대상": b, "피해": 4}, {"비고": "대상 없음"}],
            "총피해": 4,
        },
        {"공격자": a, "대상": [b], "타격": [{"대상": b, "피해": 5}]},
        {"공격자": a, "대상": b, "타격": [{"피해": 6}], "총피해": 6},
        {"공격자": a, "대상": b, "총피해": 7, "비고": "지속공격 자동 발동"},
        {"공격자": a, "대상": b, "피해": 8, "비고": "홀딩 피해"},
        {"공격자": a, "대상": b, "피해": 9, "넘친피해": {b: 2}},
        {"공격자": a, "대상": b, "행동": "도망"},
    ]
    assert core.피해_집계(전투상태)[a] == 4 + 5 + 6 + 7 + 8 + 9 - 2


def test_넘친피해는_쓰러뜨린_타격의_귀속에게서_뺀다():
    """넘친피해는 다음 로그 항목에 붙는다 - 명중 때 적의 특성 줄이 먼저 쌓이면 그 줄에 붙고(공격자는 적),
    몹몰이처럼 뒤따르는 줄이 쓰러뜨리면 앞 공격 줄에 붙는다. 어느 쪽이든 쓰러뜨린 타격의 귀속에게서 뺀다."""
    전투상태, 적, 아군 = 시험_전투(["고블린", "고블린"])
    a, b, c = 아군[0]["이름"], 적[0]["이름"], 적[1]["이름"]
    전투상태["로그"] = [
        {"공격자": b, "대상": a, "비고": "특성 - 출혈 부여", "넘친피해": {b: 3}},
        {"공격자": a, "대상": b, "피해": 10},
        {
            "공격자": a,
            "타격": [{"대상": c, "피해": 0}],
            "총피해": 0,
            "넘친피해": {c: 2},
        },
        {"공격자": a, "대상": c, "피해": 5, "비고": "몹몰이"},
    ]
    assert core.피해_집계(전투상태)[a] == (10 - 3) + (5 - 2)


