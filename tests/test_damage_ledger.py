def test_집계는_적이_실제로_받은_피해와_맞는다(monkeypatch):
    """레벨 9 전원 자동전투(24종 시험자마다 두 판) - 로그에서 읽은 적의 피해 합(넘친 피해 빼기 전)이 피해_적용이 적에게 돌려준
    값의 합과 같고, 적에게 들어간 피해는 모두 참가자(아군·적·인형)에게 귀속된다(상태이상 이름으로 남지 않는다)."""
    받은 = []
    원래 = damage.피해_적용

    def 감시(전투상태, 대상, 피해량, **kw):
        r = 원래(전투상태, 대상, 피해량, **kw)
        if 대상.get("진영") == "적":
            받은.append(r)
        return r

    monkeypatch.setattr(damage, "피해_적용", 감시)
    for 직업 in [j for 전직들 in gameflow.전직_레지스트리.values() for j in 전직들]:
        m = bs.측정(직업)
        gf = m.gf
        상태 = m._상태(m.기본파티)
        for 시드 in range(2):
            gf.휴식(상태)
            m.rng.시드(시드)
            rr = random.Random(시드)
            몹 = [
                rr.choice(bs.조건["몬스터"])
                for _ in range(rr.randint(*bs.조건["마리"]))
            ]
            받은.clear()  # 전투 시작 때 들어가는 피해부터 센다
            gf.전투_시작(상태, 몹, 레벨=20, 차수=3)
            m.support.반응_처리(상태)
            for _ in range(bs.판당_최대턴):
                if gf.전투_종료됨(상태):
                    break
                p = gf.현재_턴_참가자(상태)
                if p["진영"] == "아군" and p["생존"]:
                    gf.자동전투_한_턴(상태)
                else:
                    gf.턴_넘기기(상태)
            전투상태 = 상태["전투상태"]
            진영 = {p["이름"]: p["진영"] for p in 전투상태["참가자"]}
            적행 = [r for r in core.피해_내역(전투상태) if 진영.get(r[1]) == "적"]
            assert sum(r[2] for r in 적행 if r[2] > 0) == sum(받은), (직업, 시드)
            assert {r[0] for r in 적행 if r[0] not in 진영} == set(), (직업, 시드)
            gf.전투_결과_정리(상태)
