def test_지속피해는_건_사람마다_따로():
    전투상태, 적, 아군 = 시험_전투(["고블린"])
    가, 나 = _출혈(전투상태, 적[0], 아군[0]), _출혈(전투상태, 적[0], 아군[1])
    assert 가 is not 나 and 가["부여자id"] == 아군[0]["id"]
    정의 = 전투상태["상태이상정의"]["출혈"]
    damage.지속피해_적용(전투상태, 적[0], 가, 정의)
    damage.지속피해_적용(전투상태, 적[0], 나, 정의)
    첫째, 둘째 = 전투상태["로그"][-2:]
    assert 첫째["공격자"] == "출혈"  # 화면 문장은 그대로
    assert (첫째["귀속"], 둘째["귀속"]) == (아군[0]["이름"], 아군[1]["이름"])
    집계 = core.피해_집계(전투상태)
    assert 집계[아군[0]["이름"]] == 첫째["피해"] > 0
    assert 집계[아군[1]["이름"]] == 둘째["피해"] > 0


