def test_넘친_피해는_빼고_로그에_남는다():
    전투상태, 적, 아군 = 시험_전투(["고블린"])
    적[0]["현재HP"] = 3
    피해 = damage.피해_적용(전투상태, 적[0], 10, 피해감소무시=True, 공격측=아군[0])
