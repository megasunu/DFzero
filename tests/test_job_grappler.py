def _스킬(이름):
    return dict(gf.스킬데이터모음_생성()[이름], _이름=이름)


def _쓰기(전투상태, p, 이름, 대상=None):
    p["행동자원"].update(일반행동=1, 보조행동=1)
    p["현재MP"] = max(p["현재MP"], 50)
    return ss.스킬_실행(전투상태, p, 이름, _스킬(이름), 대상)


def _내성_성공(monkeypatch):
    monkeypatch.setattr(
        stats.dice_utils,
        "내성_굴림",
        lambda 보정치, 난이도, 이점=False, 불리=False: (True, 99),
    )


def _상태(p):
    return {i["이름"]: i.get("지속턴") for i in p["상태이상"]}


def _충격파_로그(전투상태):
    return [
        x
        for x in 전투상태["로그"]
        if "강렬한 테이크 다운 - 충격파" in str(x.get("비고", ""))
    ]


def _HP_채우기(적):
    for p in 적:
        p["현재HP"] = 999


