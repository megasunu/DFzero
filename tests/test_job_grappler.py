def test_반드시_잡는다_중_홀딩이_남은_동안_시전자는_슈퍼아머(그플전장, monkeypatch):
    _, 전투상태, 적, g = 그플전장
    support.주사위고정(monkeypatch, 15)
    _쓰기(전투상태, g, "수플렉스", 적[0])
    assert "슈퍼아머" not in _상태(g)  # 버프 전에는 없다
    hit_effects.홀딩_발동(전투상태, 적[0])
    _쓰기(전투상태, g, "반드시 잡는다!")
    _쓰기(전투상태, g, "수플렉스", 적[0])
    assert "슈퍼아머" in _상태(g)
    이니 = g["이니셔티브"]
    hit_effects.경직_적용(전투상태, g, 5)
