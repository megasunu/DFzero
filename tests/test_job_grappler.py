def test_강렬한_테이크다운은_네_스킬이_맞힌_적에게만_타격마다_1d4_충격파(
    그플전장, monkeypatch
):
    _, 전투상태, 적, g = 그플전장
    특성 = job_ability_020f.특성목록["강렬한 테이크 다운"]
    assert 특성["스킬사용시효과"][0]["효과"]["데미지"] == "1d4"
    support.주사위고정(monkeypatch, 15)
    for 이름 in ("수플렉스", "에어슈타이너"):  # 단일 - 양옆에는 없다
        _HP_채우기(적)
        전투상태["로그"].clear()
        _쓰기(전투상태, g, 이름, 적[1])
        assert [x["대상"] for x in _충격파_로그(전투상태)] == [적[1]["이름"]], 이름
    _HP_채우기(적)
    전투상태["로그"].clear()
    결과 = _쓰기(전투상태, g, "로플링", 적[1])  # 붙잡은 적과 던져 맞힌 적에게 하나씩
    던져_맞은 = 결과["던지기"]["타격"][0]["대상"]
    assert sorted(x["대상"] for x in _충격파_로그(전투상태)) == sorted(
        [적[1]["이름"], 던져_맞은]
    )
    _HP_채우기(적)
    전투상태["로그"].clear()
    _쓰기(전투상태, g, "스파이어", 적[1])  # 맞은 셋에게 하나씩
    로그 = _충격파_로그(전투상태)
    assert sorted(x["대상"] for x in 로그) == sorted(p["이름"] for p in 적)
    assert all(x["피해"] <= 4 for x in 로그)
    # 한 스킬의 충격파는 한 공격 - 함께 맞은 몹몰이끼리는 피해를 주고받지 않는다
    assert not [x for x in 전투상태["로그"] if "몹몰이 -" in str(x.get("비고", ""))]
    전투상태["로그"].clear()
    _쓰기(전투상태, g, "넥스냅", 적[1])  # 네 스킬이 아니면 없다
    assert not _충격파_로그(전투상태)


