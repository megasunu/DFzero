"""S38 패러메딕 실전 - 버프군 중첩 금지, 버프 모듈, 사격 스킬 (docs/scenarios.md).

거너(패러메딕)·프리스트(크루세이더)가 든 4인 파티를 레벨 9까지 키운다(나머지는 기본 전직, 스킬 전부 습득). 타우 아미·
루가루·고블린(레벨 15 차수 3)과 **실제 전투로** 싸운다. 크루세이더는 1라운드에 용맹의 축복·수호의 축복·신성한 빛 중
쓸 수 있는 것을 쓰고 일반공격한다. 패러메딕은 그 뒤 무기강화(A군)를 걸고, 버프 모듈(장갑강화 B군·완충모듈 C군·기동강화
D군·정화모듈 중 가장 덜 쓴 것)을 홀수 라운드에 하나, 짝수 라운드에는 지정사격·후퇴기동·확인사격 중 가장 덜 쓴 것을 쓴다. 나머지는 스킬 우선
정책으로 싸운다.

불변식: 같은 버프군 스킬의 버프는 한 참가자에게 한 스킬 것만 남는다(무기강화를 걸면 용맹의 축복 버프가 사라진다).
완충모듈의 임시생명력은 버프에 담겨 적의 피해를 실제로 막고, 지정사격·확인사격은 치명타가 나지 않는다. 후퇴기동을 쓰면
회피률증가가 붙는다. 수치 규칙은 tests/test_job_paramedic.py.
"""

import pytest

from game.system import rng
from game.system.combat import damage
import gameflow as gf
import scenario
import support
from tests.support import 구현된_전직

적들 = ["타우 아미", "루가루", "고블린"]
시드 = 0
파티구성 = [("", "거너"), ("", "프리스트"), ("", "귀검사"), ("", "마법사")]
모듈 = ("장갑강화", "완충모듈", "기동강화", "정화모듈")
사격 = ("지정사격", "후퇴기동", "확인사격")
군 = {
    "용맹의 축복": "A",
    "무기강화": "A",
    "수호의 축복": "B",
    "장갑강화": "B",
    "신성한 빛": "C",
    "완충모듈": "C",
}
누적 = {}


def _쓰기(상태, p, 이름, 기록, 대상=None):
    if not gf.스킬_사용_가능여부(상태, p, 이름)[0]:
        return False
    데이터 = 상태["스킬데이터모음"][이름]
    if gf.스킬_실제_타겟(상태, 데이터) not in ("적단일", "적3체"):
        대상 = None
    gf.아군_스킬사용(상태, 이름, 중심대상=대상)
    기록[이름] = 기록.get(이름, 0) + 1
    누적[이름] = 누적.get(이름, 0) + 1
    return True


def _일반공격(상태, p):
    전투상태 = 상태["전투상태"]
    while 전투상태["종료"] is None and p["생존"]:
        적 = scenario._살아있는_적(상태)
        if not 적 or not gf.일반공격_가능여부(상태, p):
            break
        gf.아군_일반공격(상태, 적[0])
    if 전투상태["종료"] is None:
        gf.턴_넘기기(상태)


def _군_검사(상태, 기록):
    """같은 군 스킬이 건 버프가 한 참가자에게 둘 이상 남지 않는다."""
    for p in 상태["전투상태"]["참가자"]:
        if p["진영"] != "아군":
            continue
        출처 = {b.get("출처스킬") for b in p["버프"] if b.get("출처스킬") in 군}
        for g in "ABC":
            assert len([s for s in 출처 if 군[s] == g]) <= 1, (p["이름"], 출처)
        if "무기강화" in 출처:
            기록["무기강화_뒤_용맹없음"] = 기록.get("무기강화_뒤_용맹없음", 0) + int(
                "용맹의 축복" not in 출처
            )


def _크루_턴(상태, p, 기록):
    if 상태["전투상태"]["라운드"] == 1:
        for 이름 in ("용맹의 축복", "수호의 축복", "신성한 빛"):
            _쓰기(상태, p, 이름, 기록)
    else:
        scenario.스킬_우선_턴(상태, [])
        return
    _일반공격(상태, p)


def _메딕_턴(상태, p, 기록):
    _쓰기(상태, p, "무기강화", 기록)
    if (
        상태["전투상태"]["라운드"] % 2
    ):  # 홀수 라운드에 버프 모듈, 짝수 라운드에 사격 스킬(MP)
        for 이름 in sorted(모듈, key=lambda n: 누적.get(n, 0)):
            if _쓰기(상태, p, 이름, 기록):
                break
        _군_검사(상태, 기록)
        _일반공격(상태, p)
        return
    for 이름 in sorted(사격, key=lambda n: 누적.get(n, 0)):
        적 = scenario._살아있는_적(상태)
        if 적 and _쓰기(상태, p, 이름, 기록, 적[0]):
            if 이름 == "후퇴기동":
                기록["후퇴기동_회피"] = 기록.get("후퇴기동_회피", 0) + int(
                    any(b["이름"] == "회피률증가" for b in p["버프"])
                )
            break
    _일반공격(상태, p)


def _전투(상태, 메딕, 크루, 기록):
    support.반응_처리(상태)
    for _ in range(400):
        if gf.전투_종료됨(상태):
            break
        참가자 = gf.현재_턴_참가자(상태)
        if 참가자["진영"] == "아군" and 참가자["생존"]:
            if 참가자["원본"] is 메딕:
                _메딕_턴(상태, 참가자, 기록)
            elif 참가자["원본"] is 크루:
                _크루_턴(상태, 참가자, 기록)
            else:
                scenario.스킬_우선_턴(상태, [])
        else:
            gf.턴_넘기기(상태)
        _군_검사(상태, 기록)
    else:
        raise AssertionError("전투가 끝나지 않았다")
    기록["라운드"] = 상태["전투상태"]["라운드"]
    로그 = [항목 for 항목 in 상태["전투상태"]["로그"] if isinstance(항목, dict)]
    for 이름 in ("지정사격", "확인사격"):
        타격 = [
            t
            for 항목 in 로그
            if 항목.get("스킬") == 이름
            for t in 항목.get("타격") or []
            if isinstance(t, dict) and t.get("판정")
        ]
        assert not any(t["판정"].get("치명타") for t in 타격), 이름
    return 상태["전투상태"]["종료"]


@pytest.mark.scenario("S38")
def test_S38_패러메딕_실전(golden, monkeypatch):
    rng.시드(시드)
    누적.clear()
    흡수 = []
    원래 = damage.버프임시생명력_흡수

    def 흡수_기록(대상, 피해):  # 완충모듈 임시생명력이 실제로 피해를 막는지 센다
        전 = sum(
            b.get("임시생명력", 0)
            for b in 대상.get("버프") or []
            if b["이름"] == "완충모듈"
        )
        남은피해 = 원래(대상, 피해)
        후 = sum(
            b.get("임시생명력", 0)
            for b in 대상.get("버프") or []
            if b["이름"] == "완충모듈"
        )
        if 후 < 전:
            흡수.append(전 - 후)
        return 남은피해

    monkeypatch.setattr(damage, "버프임시생명력_흡수", 흡수_기록)
    상태 = support.새게임(파티구성)
    메딕, 크루, 귀, 마 = 상태["파티"]["파티원"]
    support.성장(상태, 메딕, 9, 전직="패러메딕", 스킬습득=True)
    support.성장(상태, 크루, 9, 전직="크루세이더", 스킬습득=True)
    for c in (귀, 마):
        support.성장(상태, c, 9, 전직=구현된_전직[c["직업"]], 스킬습득=True)
    assert gf.캐릭터_직업표시(메딕).startswith("패러메딕")
    assert {"강습슈트", "전장정보"} <= set(메딕["보유특성"])

    전투들 = []
    볼것 = (
        "무기강화",
        "무기강화_뒤_용맹없음",
        "장갑강화",
        "완충모듈",
        "기동강화",
        "정화모듈",
        "완충_흡수",
        "지정사격",
        "확인사격",
        "후퇴기동_회피",
    )
    for _ in range(10):
        gf.파티_최대치로_회복(상태)
        gf.휴식(상태)  # 레벨 8 버프는 휴식당 1회
        gf.전투_시작(상태, 적들, 레벨=15, 차수=3)
        기록 = {}
        흡수.clear()
        종료 = _전투(상태, 메딕, 크루, 기록)
        기록["완충_흡수"] = len(흡수)
        assert gf.전투_결과_정리(상태) == 종료 == "아군승리"
        전투들.append(기록)
        if all(sum(b.get(k, 0) for b in 전투들) for k in 볼것):
            break

    합계 = {k: sum(b.get(k, 0) for b in 전투들) for k in 볼것}
    assert all(합계.values()), 합계
    assert all(b.get("무기강화", 0) <= 1 for b in 전투들), 전투들  # 휴식당 1회
    golden("scenario_S38_paramedic", 전투들)
