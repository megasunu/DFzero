"""S54 소모품·경제 빈칸 실전 - 보상 칸 표시, 전투 종료 문구, 포션 거절, 장비 교체 탭 (docs/scenarios.md, #74).

S9/S39/S40/S48/S49가 덮지 않은 곳만 실전 흐름으로 지나간다. 4인 기본 파티가 로리엔 인카운트를 **실전으로**
싸운 뒤 전투 종료 문구(전리품 골드·아이템, 받은 보상)와 보상 칸 둘째 줄(무기 종류·방어구 재질)·셋째 줄
(보유/착용 개수)을 화면이 부르는 함수로 읽어 소지품과 맞춘다. 보스를 실전으로 이기며 쓰러진 아군에게 전투 밖
HP 포션을 먹이려 하면 거절되고, 레벨 제한 포션과 소지품에 없는 포션도 거절된다 - 셋 다 소지품이 줄지 않는다.
마을로 걸어 돌아와 휴식한 뒤 장비 교체 팝업과 같은 호출(탭 목록 -> 처음 탭 -> 후보)로 상의를 바꾸고 해제한다
(해제한 상의는 소지품에 남고, 무기는 해제가 막힌다). 다시 실전으로 싸우고 저장/불러오기 뒤 장비가 그대로다.
값 하나하나(사유 문구, 탭 규칙)는 단위 테스트(test_consumables.py 등)가 본다.
"""

import pytest

from game.system import rng
import gameflow as gf
import scenario
import support

시드 = (
    4  # 보스전에서 아군 하나가 쓰러지는 시드(쓰러진 캐릭터 포션 거절을 실전으로 본다)
)
_로리엔 = "dungeon_01A_D01_Lorien"
_엘븐가드 = "town_01A_T01_Elvengard"


def _보유(상태, 카테고리, 이름):
    return 상태["소지품"].get(카테고리, {}).get(이름, 0)


def _착용수(상태, 이름):
    return sum(
        1
        for c in 상태["파티"]["파티원"]
        for 장착 in c["장착장비"].values()
        if 장착 == 이름
    )


def _보유표시_기대(상태, 이름):
    """화면 문구를 소지품과 장착 칸에서 따로 계산한다(소지품 장비 개수에는 착용 중인 것도 든다)."""
    착용 = _착용수(상태, 이름)
    보유 = _보유(상태, "장비", 이름) - 착용
    조각 = ([f"보유 {보유}"] if 보유 else []) + ([f"착용 {착용}"] if 착용 else [])
    return " / ".join(조각)


def _부위_기대(상태, 이름):
    아이템 = gf.아이템_찾기(상태, 이름)
    if 아이템.get("재질"):
        return f"{아이템['재질']} {아이템['분류']}"
    assert 아이템["분류"].endswith(" 무기"), 아이템  # 로리엔 보상은 무기·방어구뿐
    return f"무기({아이템['타입']})"


def _종료_문구_검사(상태, 종료):
    줄들 = gf.전투_종료_문구(상태, 종료)
    전리품 = 상태["전투_전리품"]
    assert 줄들[:2] == ["전투 승리!", "전리품"]
    assert (f"골드 {전리품['골드']}" in 줄들) == bool(전리품["골드"])
    for 이름, 개수 in 전리품["아이템"]:
        assert any(줄 == 이름 or 줄.startswith(f"{이름} x") for 줄 in 줄들), 줄들
    return 줄들


@pytest.mark.scenario("S54")
def test_S54_소모품_경제_빈칸_실전(golden):
    rng.시드(시드)
    상태 = support.새게임()
    기록 = {}
    파티 = 상태["파티"]["파티원"]
    귀검사 = next(c for c in 파티 if c["직업"] == "귀검사")

    # 1) 로리엔 인카운트 실전 -> 전투 종료 문구와 보상 칸 표시
    gf.던전_진입(상태, _로리엔)
    기록["첫전투_적"] = scenario.인카운트까지_걷기(상태)
    종료 = scenario.실전(상태)
    assert gf.전투_결과_정리(상태) == 종료 == "아군승리"
    _종료_문구_검사(상태, 종료)
    assert gf.전투_보상_대기중(상태)
    칸 = gf.전투_보상_칸(상태)
    표시 = {}
    for 이름 in 칸:
        assert gf.전투_보상_부위(상태, 이름) == _부위_기대(상태, 이름)
        assert gf.전투_보상_보유표시(상태, 이름) == _보유표시_기대(상태, 이름)
        표시[이름] = [gf.전투_보상_부위(상태, 이름), gf.전투_보상_보유표시(상태, 이름)]
    기록["보상칸"] = 표시
    받은 = gf.전투_보상_받기(상태, 0)
    assert 받은 == 칸[0]
    assert 받은 in gf.전투_종료_문구(상태, 종료)  # 받은 보상도 전리품 줄에 붙는다
    assert gf.전투_보상_보유표시(상태, 받은) == _보유표시_기대(상태, 받은)
    assert "보유" in gf.전투_보상_보유표시(상태, 받은)
    # 착용 중인 무기를 하나 더 가지면 "보유 N / 착용 M"
    무기 = 귀검사["장착장비"]["무기"]
    assert gf.전투_보상_보유표시(상태, 무기) == "착용 1"
    상태["소지품"]["장비"][무기] += 1
    assert gf.전투_보상_보유표시(상태, 무기) == "보유 1 / 착용 1"
    assert gf.전투_보상_보유표시(상태, "없는 장비") == ""

    # 2) 보스 실전 - 아군 하나가 쓰러진 채 이긴다
    결과, _ = support.보스_처치(상태, 전투처리=scenario.실전)
    assert 결과 == "아군승리"
    if gf.전투_보상_대기중(상태):
        scenario.보상_수령(상태)
    쓰러진 = [c for c in 파티 if c["현재HP"] <= 0]
    assert 쓰러진, scenario.파티_HP(상태)
    다친 = next(c for c in 파티 if 0 < c["현재HP"] < gf.캐릭터_최대HP(상태, c))
    기록["보스뒤_HP"] = scenario.파티_HP(상태)

    # 3) 전투 밖 포션 거절 셋 - 쓰러짐, 레벨 제한, 소지품에 없음. 어느 것도 소지품을 줄이지 않는다
    상태["소지품"].setdefault("포션", {})
    상태["소지품"]["포션"]["초보자용 HP 포션"] = 1
    상태["소지품"]["포션"]["입문자용 HP 포션"] = 1  # 레벨제한 6(파티는 레벨 1~2)
    사유 = dict((n, r) for n, _, r in gf.캐릭터_회복포션_목록(상태, 쓰러진[0]))
    assert 사유["초보자용 HP 포션"] == "쓰러진 캐릭터는 마실 수 없다."
    with pytest.raises(ValueError, match="쓰러진"):
        gf.캐릭터_포션사용(상태, 쓰러진[0], "초보자용 HP 포션")
    사유 = dict((n, r) for n, _, r in gf.캐릭터_회복포션_목록(상태, 다친))
    assert 사유["입문자용 HP 포션"] == "레벨 6 이상만 쓸 수 있다."
    assert 사유["초보자용 HP 포션"] is None
    assert "숙련자용 HP 포션" not in 사유  # 없는 포션은 목록에 안 나온다
    with pytest.raises(ValueError, match="레벨 6"):
        gf.캐릭터_포션사용(상태, 다친, "입문자용 HP 포션")
    with pytest.raises(ValueError, match="소지품에 없다"):
        gf.캐릭터_포션사용(상태, 다친, "숙련자용 HP 포션")
    assert 상태["소지품"]["포션"] == {"초보자용 HP 포션": 1, "입문자용 HP 포션": 1}
    assert all(c["현재HP"] <= 0 for c in 쓰러진)
    HP전 = 다친["현재HP"]
    대상, 회복 = gf.캐릭터_포션사용(상태, 다친, "초보자용 HP 포션")
    assert 대상 == "HP" and 다친["현재HP"] == HP전 + 회복 > HP전
    assert _보유(상태, "포션", "초보자용 HP 포션") == 0
    기록["포션"] = [쓰러진[0]["캐릭터명"], 다친["캐릭터명"], 회복]

    # 4) 마을로 걸어 돌아와 휴식 - 쓰러진 아군도 가득 찬다
    support.연결로_나가기(상태, _엘븐가드, 전투처리=scenario.실전)
    gf.휴식(상태)
    assert all(c["현재HP"] == gf.캐릭터_최대HP(상태, c) for c in 파티)

    # 5) 장비 교체 팝업 - 탭 목록 -> 처음 탭 -> 후보 -> 교체 -> 해제
    탭 = gf.장비_교체_탭목록(상태, 귀검사, "상의")
    assert 탭[0] == "전체" and "경갑" in 탭
    assert gf.장비_교체_탭목록(상태, 귀검사, "목걸이") == []
    assert gf.장비_교체_처음탭(상태, 귀검사, "목걸이") is None
    assert gf.장비_교체_처음탭(상태, 귀검사, "무기") == "전체"
    처음탭 = {c["캐릭터명"]: gf.장비_교체_처음탭(상태, c, "상의") for c in 파티}
    for c in 파티:
        숙련 = [t for t in 탭 if f"{t}숙련" in c.get("보유특성", [])]
        assert 처음탭[c["캐릭터명"]] == (숙련[0] if 숙련 else "전체")
    기록["상의_처음탭"] = 처음탭
    전에 = 귀검사["장착장비"]["상의"]
    assert gf.아이템_세트정보(상태, gf.캐릭터_장착아이템(상태, 귀검사, "상의")) is None
    assert gf.아이템_마법부여정보(gf.캐릭터_장착아이템(상태, 귀검사, "상의")) is None
    후보 = gf.장비_교체_후보(상태, 귀검사, "상의")
    for 재질 in 탭[1:]:  # 재질 탭 후보는 [전체] 후보 중 그 재질만
        assert [
            h[0]["이름"] for h in gf.장비_교체_후보(상태, 귀검사, "상의", 재질)
        ] == [h[0]["이름"] for h in 후보 if h[0]["재질"] == 재질]
    # 착용 가능한 첫 후보(남는 같은 상의여도 된다 - 후보는 착용분을 뺀 개수만 나온다)
    새상의 = next(h[0]["이름"] for h in 후보 if h[2] and h[1] > 0)
    gf.장비_교체(상태, 귀검사, "상의", 새상의)
    assert gf.캐릭터_장착아이템(상태, 귀검사, "상의")["이름"] == 새상의
    개수 = _보유(상태, "장비", 새상의)
    gf.장비_해제(상태, 귀검사, "상의")
    assert gf.캐릭터_장착아이템(상태, 귀검사, "상의") is None
    assert _보유(상태, "장비", 새상의) == 개수  # 해제한 상의는 소지품에 남는다
    assert gf.전투_보상_보유표시(상태, 새상의) == _보유표시_기대(상태, 새상의)
    with pytest.raises(ValueError, match="무기는 해제할 수 없다"):
        gf.장비_해제(상태, 귀검사, "무기")
    기록["상의"] = [전에, 새상의]

    # 6) 상의 없이 다시 실전
    gf.던전_진입(상태, _로리엔)
    기록["둘째전투_적"] = scenario.인카운트까지_걷기(상태)
    종료 = scenario.실전(상태)
    assert gf.전투_결과_정리(상태) == 종료 == "아군승리"
    _종료_문구_검사(상태, 종료)
    if gf.전투_보상_대기중(상태):
        scenario.보상_수령(상태)

    # 7) 저장/불러오기 - 장비·소지품 그대로
    gf.게임_저장(상태, 1)
    불러옴 = gf.게임_불러오기(1)
    assert 불러옴["소지품"] == 상태["소지품"]
    assert [c["장착장비"] for c in 불러옴["파티"]["파티원"]] == [
        c["장착장비"] for c in 파티
    ]
    기록["남은_포션"] = dict(상태["소지품"]["포션"])
    golden("scenario_S54_consumable_gaps", 기록)
