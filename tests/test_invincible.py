"""상태이상 "무적"(#623, 사용자 지정 2026-11-10) - 적의 공격 피해를 받지 않는다.

홀딩무적(시전자무적 홀딩)과 같은 판정이다: 공격한 쪽이 다른 진영일 때만 막고, 공격자가 없는
지속피해(출혈 등)와 같은 편의 피해는 그대로 받는다.
"""

from game.data.buff.status_effects import 상태이상목록
from game.system.combat import damage
from tests.support import 시험_전투


def _무적_전투():
    전투상태, 적, 아군 = 시험_전투(["고블린"])
    아군[0]["상태이상"].append({"이름": "무적", "지속턴": 2})
    return 전투상태, 적, 아군


def test_무적_정의가_있다():
    정의 = 상태이상목록["무적"]
    assert 정의["분류"] == "상태변화"
    assert 정의["효과"].get("피해무효") is True


def test_적의_공격_피해를_받지_않는다():
    전투상태, 적, 아군 = _무적_전투()
    assert damage.피해_적용(전투상태, 아군[0], 30, 공격자=적[0]) == 0
    assert 아군[0]["현재HP"] == 999
    assert any(r.get("비고") == "무적 - 피해 무효" for r in 전투상태.get("로그", [])), (
        "피해 무효 로그가 남아야 한다"
    )


def test_지속피해와_같은_편_피해는_받는다():
    전투상태, 적, 아군 = _무적_전투()
    damage.피해_적용(전투상태, 아군[0], 5, 피해감소무시=True)
    assert 아군[0]["현재HP"] == 994
    damage.피해_적용(전투상태, 아군[0], 5, 피해감소무시=True, 공격자=아군[1])
    assert 아군[0]["현재HP"] == 989


def test_무적이_없으면_피해를_받는다():
    전투상태, 적, 아군 = 시험_전투(["고블린"])
    damage.피해_적용(전투상태, 아군[0], 5, 피해감소무시=True, 공격자=적[0])
    assert 아군[0]["현재HP"] == 994
