from game.system import skill_system as ss
from game.system.combat import core, damage, traits
from tests import support

중급마법 = ["플레임 스트라이크", "보이드", "칠링팬스", "썬버스트"]
상급마법 = ["썬더콜링", "아크틱 피스트", "나이트 할로우", "할로윈 버스터"]


@pytest.fixture
def 엘마전장(monkeypatch):
    """마법사 -> 엘리멘탈마스터 레벨 8(스킬 전부 습득)과 귀검사, 고블린 셋(모두 HP 999). 맞아서 생기는
    경직(이니셔티브 -1)은 꺼서 캐스팅이 내린 몫만 보이게 한다."""
    monkeypatch.setattr(damage, "경직_적용", lambda *a, **k: None)
    rng.시드(5)
    상태 = support.새게임([("", "마법사"), ("", "귀검사")])
    엘, 귀 = 상태["파티"]["파티원"]
    support.성장(상태, 엘, 8, 전직="엘리멘탈마스터", 스킬습득=True)
    support.성장(상태, 귀, 8, 전직="웨펀마스터")
    gf.전투_시작(상태, ["고블린", "고블린", "고블린"], 레벨=2, 차수=1)
    support.반응_처리(상태)
    전투상태 = 상태["전투상태"]
    적 = sorted(
        (p for p in 전투상태["참가자"] if p["진영"] == "적"),
        key=lambda p: p["대형위치"],
    )
    for p in 전투상태["참가자"]:  # 주사위를 고정해도 아무도 쓰러지지 않게
        p["현재HP"] = p["최대HP"] = 999
    e = next(p for p in 전투상태["참가자"] if p["원본"] is 엘)
    return 상태, 전투상태, 적, e


def _스킬(이름):
    return dict(gf.스킬데이터모음_생성()[이름], _이름=이름)


def _차례로(상태, p):
    """p의 차례가 될 때까지 턴을 넘긴다(적 턴은 자동)."""
    전투상태 = 상태["전투상태"]
    for _ in range(40):
        if gf.현재_턴_참가자(상태) is p:
            return
        gf.턴_넘기기(상태)
        if 전투상태["종료"] is not None:
            raise AssertionError("전투가 끝났다")
    raise AssertionError("차례가 오지 않았다")


def _이동캐스팅_빼기(e):
    e["원본"]["보유특성"].remove("이동캐스팅")


def _캐스팅중(e):
    return any(s["이름"] == "캐스팅" for s in e["상태이상"])


# ------------------------------------------------------------------ 레벨 6 특성


def test_레벨6에_메모라이즈와_이동캐스팅을_얻고_지능이_1_오른다():
    상태 = support.새게임([("", "마법사")])
    (엘,) = 상태["파티"]["파티원"]
    support.성장(상태, 엘, 5)
    지능 = 엘["지능"]
    support.성장(상태, 엘, 6, 전직="엘리멘탈마스터")
    assert {"메모라이즈", "이동캐스팅"} <= set(엘["보유특성"])
    assert 엘["지능"] == 지능 + 1


def test_메모라이즈는_하급_중급_상급마법에만_데미지보너스1(엘마전장):
    _, 전투상태, _, e = 엘마전장
    for 타입 in ("하급마법", "중급마법", "상급마법"):
        assert (
            traits.특성_수치(전투상태, e, "데미지보너스", 스킬타입=["스킬", 타입]) == 1
        )
    assert traits.특성_수치(전투상태, e, "데미지보너스", 스킬타입=["스킬"]) == 0
    assert traits.특성_수치(전투상태, e, "데미지보너스") == 0  # 일반공격


def test_메모라이즈_데미지보너스는_마법_피해에_실제로_붙는다(엘마전장, monkeypatch):
    _, 전투상태, 적, e = 엘마전장
    support.주사위고정(monkeypatch, 15)

    def 피해():
        e["행동자원"].update(일반행동=1)
        e["현재MP"] = 99
        HP = 적[0]["현재HP"]
        ss.스킬_실행(전투상태, e, "랜턴파이어", _스킬("랜턴파이어"), 적[0])
        return HP - 적[0]["현재HP"]

    있음 = 피해()
    e["원본"]["보유특성"].remove("메모라이즈")
    assert 있음 == 피해() + 1


def test_메모라이즈로_하급마법을_보조행동으로_쓸_수_없다(엘마전장):
    _, 전투상태, _, e = 엘마전장
    e["기타행동"] = {"쇼타임행동": 0}
    e["행동자원"].update(일반행동=0, 보조행동=1)
    assert not ss.사용_가능여부(전투상태, e, _스킬("랜턴파이어"))[0]
    e["행동자원"]["일반행동"] = 1
    assert ss.일반행동_지불수단_목록(전투상태, e, _스킬("랜턴파이어")) == ["일반행동"]


def test_이동캐스팅은_캐스팅_상태_동안_명중보너스1(엘마전장):
    _, 전투상태, _, e = 엘마전장
    기본 = traits.특성_수치(전투상태, e, "명중보너스")
    e["상태이상"].append({"이름": "캐스팅", "지속턴": None})
    assert traits.특성_수치(전투상태, e, "명중보너스") == 기본 + 1
    _이동캐스팅_빼기(e)
    assert traits.특성_수치(전투상태, e, "명중보너스") == 기본


# ------------------------------------------------------------------ 캐스팅시간


def test_중급마법은_우선도1_상급마법은_우선도2_축염포는_우선도1_캐스팅():
    모음 = gf.스킬데이터모음_생성()
    for 이름 in 중급마법:
        assert "캐스팅" in 모음[이름]["타입"]
        assert 모음[이름]["캐스팅시간"] == {"우선도": -1}
    for 이름 in 상급마법:
        assert "캐스팅" in 모음[이름]["타입"]
        assert 모음[이름]["캐스팅시간"] == {"우선도": -2}
    assert 모음["축염포"]["캐스팅시간"] == {"우선도": -1}


def test_이동캐스팅이_없으면_상급마법_캐스팅은_우선도2가_내려간다(
    엘마전장, monkeypatch
):
    상태, _, 적, e = 엘마전장
    _이동캐스팅_빼기(e)
    _차례로(상태, e)
    우선도, 이니 = e.get("우선도", 0), e["이니셔티브"]
    e["현재MP"] = 99
    gf.아군_스킬사용(상태, "아크틱 피스트", 중심대상=적[0])
    assert _캐스팅중(e)
    HP = sum(x["현재HP"] for x in 적)
    support.주사위고정(monkeypatch, 15)
    gf.턴_넘기기(상태)
    _차례로(상태, e)
    assert (e["우선도"], e["이니셔티브"]) == (우선도 - 2, 이니)
    assert not _캐스팅중(e)
    assert sum(x["현재HP"] for x in 적) < HP


@pytest.mark.parametrize(
    "이름, 감소", [("플레임 스트라이크", 6), ("아크틱 피스트", 12)]
)
def test_이동캐스팅은_우선도_대신_우선도1당_이니셔티브를_10빼기2차수(
    엘마전장, 이름, 감소
):
    상태, _, 적, e = 엘마전장
    assert core.차수(e) == 2
    _차례로(상태, e)
    우선도, 이니 = e.get("우선도", 0), e["이니셔티브"]
    e["현재MP"] = 99
    gf.아군_스킬사용(상태, 이름, 중심대상=적[0])
    gf.턴_넘기기(상태)
    _차례로(상태, e)
    assert (e["우선도"], e["이니셔티브"]) == (우선도, 이니 - 감소)


def test_이동캐스팅_감소량이_0이면_캐스팅을_거쳐_바로_다음_차례에_쏜다(
    엘마전장, monkeypatch
):
    상태, 전투상태, 적, e = 엘마전장
    _차례로(상태, e)
    monkeypatch.setattr(core, "차수", lambda p: 5)
    e["현재MP"] = 99
    이니 = e["이니셔티브"]
    gf.아군_스킬사용(상태, "아크틱 피스트", 중심대상=적[0])
    assert _캐스팅중(e)  # 캐스팅은 했다
    HP = sum(x["현재HP"] for x in 적)
    gf.턴_넘기기(상태)
    assert gf.현재_턴_참가자(상태) is e  # 남은 순서보다 먼저 밀린 차례가 온다
    assert e["이니셔티브"] == 이니
    assert not _캐스팅중(e)
    assert sum(x["현재HP"] for x in 적) < HP


