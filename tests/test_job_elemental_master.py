def test_반복지정_마법은_고른_대상을_맡겨_두었다가_친다(엘마전장, monkeypatch):
    상태, 전투상태, 적, e = 엘마전장
    _차례로(상태, e)
    e["현재MP"] = 99
    횟수 = 2 + core.차수(e)
    gf.아군_스킬사용(상태, "썬더콜링", 지정대상목록=[적[2]] * 횟수)
    support.주사위고정(monkeypatch, 15)
    HP = [x["현재HP"] for x in 적]
    gf.턴_넘기기(상태)
    _차례로(상태, e)
    assert [x["현재HP"] for x in 적][:2] == HP[:2]
    assert 적[2]["현재HP"] < HP[2]
