def test_메카드롭은_3턴_동안_자기_턴이_끝날_때마다_랜드러너_2개(메카전장):
    _, 전투상태, _, m = 메카전장
    _쓰기(전투상태, m, "메카드롭")
    for 턴 in range(3):
        skill_run.턴종료_버프공격(전투상태, m)
        assert len(전투상태["설치소환수"]) == 2 * (턴 + 1)
        flow.턴_시작_처리(전투상태, m)
    assert "메카드롭" not in [b["이름"] for b in m["버프"]]


