def test_G3은_라운드가_끝날_때_무작위_적에게_2회(메카전장, monkeypatch):
    _, 전투상태, 적, m = 메카전장
    _명중(monkeypatch)
    m["버프"] = [b for b in m["버프"] if b["이름"] != "G-1"] + [{"이름": "G-3"}]
