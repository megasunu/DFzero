def test_로봇전폭은_모든_메카를_바로_자폭시키고_자폭마다_1d4_주문보정을_더한다(
    메카전장, monkeypatch
):
    _, 전투상태, 적, m = 메카전장
    _명중(monkeypatch)
    _쓰기(전투상태, m, "랜드러너", 적[0])
    _쓰기(전투상태, m, "카운트다운", 적[1])
    _주사위(monkeypatch, [])
    _쓰기(전투상태, m, "로봇전폭")
    assert 전투상태["설치소환수"] == []
    보정 = stats.주문시전_보정치(전투상태, m)
    # 랜드러너 2d8(2) + 보정 + 1d4(1) + 보정 + 데미지보너스 1, 화속성강화 2
    assert _피해(적)[0] == -(-(2 + 보정 + 1 + 보정 + 1) * 12 // 10)
    # 카운트다운 3d8(3) + 보정 + 1d4(1) + 보정
    assert _피해(적)[1] == -(-(3 + 보정 + 1 + 보정) * 12 // 10)
    assert m["행동자원"]["보조행동"] == 0
