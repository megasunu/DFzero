def test_회심의_랜드러너는_피격되면_반응행동으로_1차수_랜드러너를_붙인다(메카전장):
    _, 전투상태, 적, m = 메카전장
    m["행동자원"]["반응행동"] = 1
    m["현재HP"] = 50
    m["전투당_특성사용횟수"] = {
        "건가드": 1
    }  # 건가드(피해 감소)가 반응행동을 먼저 쓰지 않게
    damage.피해_적용(전투상태, m, 3, 공격자=적[0])
    assert m["행동자원"]["반응행동"] == 0
    assert 전투상태["설치소환수"] == [
        {
            "이름": "랜드러너",
            "시전자id": m["id"],
            "대상id": 적[0]["id"],
            "폭발라운드": 전투상태["라운드"],
            "차수": 1,
        }
    ]
    문장 = gf.로그_문장들(전투상태["로그"][-1])
    assert "회심의 랜드러너" in 문장[0]
    assert 문장[1] == f"{적[0]['이름']}에게 랜드러너을(를) 붙였다."
    # 반응행동이 없으면 붙이지 않는다
    reactions.피격설치_반응(전투상태, m, 적[1])
