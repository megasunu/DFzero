"""크루세이더(051f) 아리아(#830) - 채널링 3턴, 둘을 함께 채널링한다(해제 규칙은 combat.channeling 머리말).

용맹의 아리아(레벨 13): 일반행동·MP 30·무색 큐브 조각 5개, 아군 전체 근력·지능 +주문시전보정치, 자기 차례 시작마다
적 전체 (차수)d4+지능보정치-2(명중 굴림 없음). 재생의 아리아(크루세이더 전용 3차수 퍽): 일반행동(용맹의 아리아 채널링
중이면 보조행동)·MP 30, 쓸 때와 자기 차례 시작마다 아군 전체 (차수)d4+주문시전보정치 회복. 채널링 중에는 슈퍼아머.
다른 행동을 하거나 쓰러지거나 무력화되면 풀리고, 용맹의 아리아가 올린 근력·지능도 함께 사라진다."""

import pytest

import gameflow as gf
from game.data.perks.perks_class_050f import 퍽목록
from game.system import rng
from game.system.combat import stats
from tests import support

용맹 = "용맹의 아리아"
재생 = "재생의 아리아"


def _크루(monkeypatch, 재생퍽=True):
    """레벨 13 크루세이더(3차수, 재생의 아리아 보유)와 귀검사 대 고블린 셋(HP 많음), 크루세이더의 차례. 주사위 3."""
    rng.시드(support.추가행동_시드)
    상태 = support.새게임([("", "프리스트"), ("", "귀검사")])
    크 = 상태["파티"]["파티원"][0]
    support.성장(상태, 크, 13, 전직="크루세이더", 스킬습득=True)
    if 재생퍽:
        크["보유스킬"].append(재생)
    gf.파티_최대치로_회복(상태)
    상태["소지품"]["재료"]["무색 큐브 조각"] = 50
    gf.전투_시작(상태, ["고블린", "고블린", "고블린"], 레벨=2, 차수=1)
    support.반응_처리(상태)
    for e in gf.적_목록(상태):
        e["현재HP"] = e["최대HP"] = 10**6
        e["행동자원"] = {k: 0 for k in e["행동자원"]}
    support.주사위고정(monkeypatch, 3)
    p = _차례까지(상태, 크)
    return 상태, p


def _차례까지(상태, 원본):
    """그 캐릭터의 다음 차례까지 턴을 넘긴다(적은 행동자원을 지워 두지 않으면 친다)."""
    if gf.현재_턴_참가자(상태)["원본"] is 원본:
        gf.턴_넘기기(상태)
    while gf.현재_턴_참가자(상태)["원본"] is not 원본:
        gf.턴_넘기기(상태)
        for e in gf.적_목록(상태):
            e["행동자원"] = {k: 0 for k in e["행동자원"]}
    p = gf.현재_턴_참가자(상태)
    p["현재MP"] = 200
    return p


def _아군(상태):
    return [p for p in 상태["전투상태"]["참가자"] if p["진영"] == "아군"]


def _아리아들(p):
    return sorted(b["이름"] for b in p["버프"] if b.get("아리아"))


def _슈퍼아머(p):
    return any(s["이름"] == "슈퍼아머" for s in p["상태이상"])


def _근력_출처(p):
    return [b.get("출처스킬") for b in p["버프"] if b["이름"] == "근력증가"]


def test_용맹의_아리아는_레벨13_스킬이고_재생의_아리아는_크루세이더_전용_3차수_퍽():
    from game.data.job_level import job_level_051f_crusader as 표

    assert 표.레벨업테이블[13]["획득"]["획득스킬"] == [용맹]
    퍽 = 퍽목록[재생]
    assert (퍽["차수"], 퍽["선행조건"], 퍽["획득스킬"]) == (
        3,
        {"전직": "크루세이더"},
        재생,
    )
    모음 = gf.스킬데이터모음_생성()
    assert (모음[용맹]["MP소모"], 모음[용맹]["재료소모"], 모음[용맹]["지속턴"]) == (
        30,
        {"무색 큐브 조각": 5},
        3,
    )
    assert (모음[재생]["MP소모"], 모음[재생]["행동"], 모음[재생]["지속턴"]) == (
        30,
        "일반행동",
        3,
    )


def test_용맹의_아리아는_아군_근력_지능을_올리고_슈퍼아머로_채널링한다(monkeypatch):
    상태, p = _크루(monkeypatch)
    assert 용맹 in p["원본"]["보유스킬"]
    보정 = stats.주문시전_보정치(상태["전투상태"], p)
    gf.아군_스킬사용(상태, 용맹)
    assert (p["현재MP"], 상태["소지품"]["재료"]["무색 큐브 조각"]) == (170, 45)
    assert p["행동자원"]["일반행동"] == 0
    for q in _아군(상태):
        (근력,) = [b for b in q["버프"] if b["이름"] == "근력증가"]
        assert (근력["중첩"], 근력["지속턴"]) == (보정, 3)
    assert _아리아들(p) == ["채널링 : 용맹의 아리아"] and _슈퍼아머(p)
    assert gf.채널링_확인대기(상태) == []  # 아리아는 묻지 않는다


def test_용맹의_아리아는_자기_차례_시작마다_적_전체를_명중굴림_없이_친다(monkeypatch):
    상태, p = _크루(monkeypatch)
    monkeypatch.setattr(
        stats, "장비_데미지보너스", lambda 참가자, 대상=None, 전투상태=None: 0
    )
    gf.아군_스킬사용(상태, 용맹)
    전 = [e["현재HP"] for e in gf.적_목록(상태)]
    p = _차례까지(상태, p["원본"])
    전투상태 = 상태["전투상태"]
    문맥 = stats.기본_컨텍스트(전투상태, p)
    기대 = (
        3 * 문맥["차수"] + stats.유효_능력치_보정치(전투상태, p, "지능") - 2
    )  # 주사위 3 고정
    assert [전[i] - e["현재HP"] for i, e in enumerate(gf.적_목록(상태))] == [기대] * 3


def test_재생의_아리아는_용맹의_아리아_채널링_중이면_보조행동으로_함께_채널링한다(
    monkeypatch,
):
    상태, p = _크루(monkeypatch)
    gf.아군_스킬사용(상태, 용맹)
    for q in _아군(상태):
        q["현재HP"] = 1
    gf.아군_스킬사용(상태, 재생)
    assert (p["행동자원"]["일반행동"], p["행동자원"]["보조행동"]) == (0, 0)
    assert _아리아들(p) == ["채널링 : 용맹의 아리아", "채널링 : 재생의 아리아"]
    회복 = 3 * stats.기본_컨텍스트(상태["전투상태"], p)["차수"] + stats.주문시전_보정치(
        상태["전투상태"], p
    )
    기대 = [min(1 + 회복, stats.유효_최대HP(상태["전투상태"], q)) for q in _아군(상태)]
    assert [q["현재HP"] for q in _아군(상태)] == 기대
    # 다음 차례 시작에 다시 회복하고 둘 다 남는다
    p = _차례까지(상태, p["원본"])
    assert [q["현재HP"] for q in _아군(상태) if q is p] == [1 + 2 * 회복]
    assert len(_아리아들(p)) == 2 and _슈퍼아머(p)


def test_재생의_아리아만_쓰면_일반행동을_쓴다(monkeypatch):
    상태, p = _크루(monkeypatch)
    gf.아군_스킬사용(상태, 재생)
    assert (p["행동자원"]["일반행동"], p["행동자원"]["보조행동"]) == (0, 1)
    assert _아리아들(p) == ["채널링 : 재생의 아리아"] and _슈퍼아머(p)


def test_다른_행동을_하면_아리아가_풀리고_올린_근력과_슈퍼아머도_사라진다(monkeypatch):
    상태, p = _크루(monkeypatch)
    gf.아군_스킬사용(상태, 용맹)
    p = _차례까지(상태, p["원본"])
    assert _아리아들(p) and all(용맹 in _근력_출처(q) for q in _아군(상태))
    gf.아군_스킬사용(상태, "수호의 축복")
    assert _아리아들(p) == [] and not _슈퍼아머(p)
    assert all(용맹 not in _근력_출처(q) for q in _아군(상태))


def test_아리아는_3턴이_지나면_끝나고_슈퍼아머도_풀린다(monkeypatch):
    상태, p = _크루(monkeypatch)
    gf.아군_스킬사용(상태, 용맹)
    원본 = p["원본"]
    남음 = []
    for _ in range(4):
        p = _차례까지(상태, 원본)
        남음.append(bool(_아리아들(p)))
    assert 남음[0] and not 남음[-1]
    assert not _슈퍼아머(p)


def test_아리아를_쓴_차례가_지나야_채널링을_이어_가는_중이다(monkeypatch):
    """#831 - 쓴 차례에는 다른 행동을 해도 풀리지 않으므로 자동전투가 평소대로 하고, 다음 차례부터 지킨다."""
    상태, p = _크루(monkeypatch)
    assert not gf._아리아_유지중(p)
    gf.아군_스킬사용(상태, 용맹)
    assert not gf._아리아_유지중(p)
    p = _차례까지(상태, p["원본"])
    assert gf._아리아_유지중(p)


@pytest.mark.parametrize("방식", ["기본전투", "자동전투", "전력전투"])
def test_자동전투는_아리아_채널링을_끊지_않고_다른_아리아만_쓴다(monkeypatch, 방식):
    """#831 - 채널링을 이어 가는 중이면 아리아가 아닌 스킬·일반공격을 하지 않는다. 기본전투는 스킬을 쓰지 않고,
    자동전투·전력전투는 다친 아군이 있으면 재생의 아리아(용맹의 아리아 채널링 중이라 보조행동)를 함께 걸고,
    남은 일반행동으로도 재생의 아리아를 다시 쓸 수 있다(쓸 때 회복한다)."""
    상태, p = _크루(monkeypatch)
    gf.아군_스킬사용(상태, 용맹)
    p = _차례까지(상태, p["원본"])
    for q in _아군(상태):
        q["현재HP"] = 1
    gf.자동전투_방식_설정(방식)
    적HP = [e["현재HP"] for e in gf.적_목록(상태)]
    로그 = 상태["전투상태"]["로그"]
    시작 = len(로그)
    gf.자동전투_한_턴(상태)
    assert "채널링 : 용맹의 아리아" in _아리아들(p) and _슈퍼아머(p)
    쓴것 = {
        항목.get("스킬", "일반공격")
        for 항목 in 로그[시작:]
        if 항목.get("공격자") == p["이름"] and 항목.get("종류") != "비고"
    }
    assert 쓴것 <= {용맹, 재생}
    assert [e["현재HP"] for e in gf.적_목록(상태)] == 적HP
    if 방식 == "기본전투":
        assert p["행동자원"]["일반행동"] == 1 and not 쓴것
    else:
        assert 쓴것 == {재생} and "채널링 : 재생의 아리아" in _아리아들(p)
