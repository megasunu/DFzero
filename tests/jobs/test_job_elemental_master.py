    _날씨(전투상태, 날씨)
    support.주사위고정(monkeypatch, 15)
    for _ in range(2):  # 날씨가 이어지는 동안 매번
        _차례로(상태, e)
        e["현재MP"] = 99
        이니 = e["이니셔티브"]
