    assert rp["현재MP"] == 200 - 30
    assert rp["기타행동"]["헤드샷행동"] == 4  # 3차수 + 1
    assert gf.스킬_팝업_줄(상태, rp, "헤드샷")["행동"] == "[헤드샷]"
