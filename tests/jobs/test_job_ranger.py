def _이동사격_고르기(캐릭터, 후보):
    return next(((이름, 정의) for 이름, 정의 in 후보 if 이름 == "이동사격"), 후보[0])


@pytest.fixture
def 레인저전장():
    """레벨 13 레인저(레벨 9 퍽 이동사격, 골드 스킬 전부 습득)와 귀검사, 고블린 셋(HP 999)."""
    rng.시드(5)
    상태 = support.새게임([("", "거너"), ("", "귀검사")])
    r, _ = 상태["파티"]["파티원"]
    support.성장(상태, r, 13, 전직="레인저", 스킬습득=True, 퍽고르기=_이동사격_고르기)
    gf.전투_시작(상태, ["고블린", "고블린", "고블린"], 레벨=2, 차수=1)
    support.반응_처리(상태)
    전투상태 = 상태["전투상태"]
    적 = sorted(
        (p for p in 전투상태["참가자"] if p["진영"] == "적"),
        key=lambda p: p["대형위치"],
    )
    for p in 적:
        p["현재HP"] = p["최대HP"] = 999
        p["원본"] = {**p["원본"], "저항": [], "취약": [], "면역": []}
    rp = next(p for p in 전투상태["참가자"] if p["원본"] is r)
    rp["장비보너스"] = {}
    rp["현재MP"] = 200
    return 상태, 전투상태, 적, rp


def _스킬(이름):
    return dict(gf.스킬데이터모음_생성()[이름], _이름=이름)


def _굴림(monkeypatch, 눈):
    """명중 d20은 눈으로 고정, 피해 주사위는 전부 최댓값."""
    monkeypatch.setattr(stats.dice_utils, "d20_굴림", lambda 이점=False, 불리=False: 눈)
    monkeypatch.setattr(rng.주사위, "randint", lambda a, b: b)


