def test_난사는_불리점으로_굴린다(레인저전장, monkeypatch):
    _, 전투상태, 적, rp = 레인저전장
    기록 = []
    monkeypatch.setattr(
        stats.dice_utils,
        "d20_굴림",
        lambda 이점=False, 불리=False: 기록.append(불리) or 15,
    )
    rp["행동자원"]["일반행동"] = 1
    결과 = ss.스킬_실행(전투상태, rp, "난사", _스킬("난사"), 적[0])
    # 3차수 - 2+3x2 = 8타, 모두 불리점
    assert len([t for t in 결과["타격"] if "판정" in t]) == 8
    assert 기록 and all(기록)


def test_난사의_대상당제한은_맞은_타격만_센다(레인저전장, monkeypatch):
    _, 전투상태, 적, rp = 레인저전장
    눈들 = iter([1, 1, 1] + [15] * 20)  # 처음 세 타는 빗나간다
    monkeypatch.setattr(
        stats.dice_utils, "d20_굴림", lambda 이점=False, 불리=False: next(눈들)
    )
    monkeypatch.setattr(rng.주사위, "randint", lambda a, b: b)
    rp["행동자원"]["일반행동"] = 1
    결과 = ss.스킬_실행(전투상태, rp, "난사", _스킬("난사"), 적[0])
    맞음 = {}
    for t in 결과["타격"]:
        if (t.get("판정") or {}).get("성공"):
            맞음[t["대상"]] = 맞음.get(t["대상"], 0) + 1
    # 적 셋 x 제한 3 = 9 >= 맞은 5타 - 어느 적도 3번 넘게 맞지 않는다
    assert sum(맞음.values()) == 5 and max(맞음.values()) <= 3


