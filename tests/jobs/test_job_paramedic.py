def _13레벨_메딕(monkeypatch, 큐브=5):
    """레벨 13 패러메딕(3차수) 대 고블린 셋, 그 캐릭터의 차례. 명중은 늘 성공하고 대상과 굴림 종류를 적는다,
    주사위는 3, 장비 데미지보너스는 0으로 고정한다."""
    rng.시드(support.추가행동_시드)
    상태 = support.새게임([("", "거너")])
    c = 상태["파티"]["파티원"][0]
    support.성장(상태, c, 13, 전직="패러메딕", 스킬습득=True)
    gf.파티_최대치로_회복(상태)
    상태["소지품"]["재료"]["무색 큐브 조각"] = 큐브
    gf.전투_시작(상태, ["고블린", "고블린", "고블린"], 레벨=2, 차수=1)
    support.반응_처리(상태)
    while not gf.아군_차례인가(상태):
        gf.턴_넘기기(상태)
    p = gf.현재_턴_참가자(상태)
    p["현재MP"] = 200
    p["행동자원"].update(일반행동=1, 보조행동=1)
    적 = sorted(gf.적_목록(상태), key=lambda e: e["대형위치"])
    for e in 적:
        e["생존"] = True
        e["현재HP"] = e["최대HP"] = 10**6
    굴림 = []

    def 판정(전투상태, 공격자, 대상, 명중률종류, *a, **k):
        굴림.append((대상["id"], 명중률종류))
        return {"성공": True, "자연눈": 15, "치명타": False, "자동실패": False}

    monkeypatch.setattr(hit, "명중_판정", 판정)
    monkeypatch.setattr(
        stats, "장비_데미지보너스", lambda 참가자, 대상=None, 전투상태=None: 0
    )
    support.주사위고정(monkeypatch, 3)
    return 상태, p, 적, 굴림


