def test_사이드_매서커_스택은_다른_일반공격취급_스킬에도_끊기지_않고_다음_턴에_사라진다(
    미스트리스13,
):
    상태, 전투상태, 적, m = 미스트리스13
    데이터 = _스킬("사이드 매서커")
    m["행동자원"]["일반행동"] = 1
    ss.스킬_실행(전투상태, m, "사이드 매서커", 데이터, 적[0])
    m["행동자원"]["일반행동"] = 1
    ss.스킬_실행(
        전투상태, m, "롤링 러쉬", _스킬("롤링 러쉬"), 적[0]
    )  # 다른 일반공격취급 스킬
    assert _스택(m)
    m["행동자원"]["일반행동"] = 1
    ss.스킬_실행(전투상태, m, "사이드 매서커", 데이터, 적[0])
    assert m["현재MP"] == 200 - 30 - 10
    assert 상태["소지품"]["재료"]["무색 큐브 조각"] == 15
    flow.턴_시작_처리(전투상태, m)  # 다음 자기 턴 - 스택이 사라져 다시 비용을 낸다
    assert not _스택(m)
    m["행동자원"]["일반행동"] = 1
    ss.스킬_실행(전투상태, m, "사이드 매서커", 데이터, 적[0])
    assert m["현재MP"] == 200 - 30 - 10 - 30
    assert 상태["소지품"]["재료"]["무색 큐브 조각"] == 10


