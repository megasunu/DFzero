def test_일발화약성은_적의_상태이상_종류마다_1d8을_더한다(스파전장, monkeypatch):
    """지속피해형·무력화CC·약화CC만 센다(크레이지 발칸과 같다). 같은 이름은 하나, 몹몰이(상태변화)는 빼고,
    이번에 맞아서 걸리는 화상은 그 투척에 들어가지 않는다."""
    _, 전투상태, 적, s = 스파전장
    support.주사위고정(monkeypatch, 15)
    _내성(monkeypatch, 성공=False)
    ss.상태이상_부여(전투상태, 적[0], "출혈", 3)
    ss.상태이상_부여(전투상태, 적[0], "출혈", 3)
    ss.상태이상_부여(전투상태, 적[0], "둔화", 2)
    ss.상태이상_부여(전투상태, 적[0], "몹몰이", 2)
    _쓰기(전투상태, s, "일발화약성", 적[0])
    근력 = stats.유효_능력치_보정치(전투상태, s, "근력")
    방어 = stats.유효_방어력(전투상태, 적[0])
