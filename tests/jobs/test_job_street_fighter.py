def _무기(p, 종류):
    p["장비데이터"] = dict(
        p.get("장비데이터") or {},
        무기={"이름": "시험 무기", "타입": 종류, "무기공격력": "1d4"},
    )


def _스킬(이름):
    return dict(gf.스킬데이터모음_생성()[이름], _이름=이름)


def _쓰기(전투상태, p, 이름, 대상=None):
    p["행동자원"].update(일반행동=1, 보조행동=1)
    p["이번턴_스킬사용횟수"] = {}  # 쓸 때마다 새 턴 - 일반공격취급 턴당 1회
    p["현재MP"] = max(p["현재MP"], 50)
    return ss.스킬_실행(전투상태, p, 이름, _스킬(이름), 대상)


def _내성(monkeypatch, 성공):
    """내성굴림 결과를 고정하고, 불린 (이점, 불리) 기록을 돌려준다."""
    기록 = []

    def 가짜(보정치, 난이도, 이점=False, 불리=False):
        기록.append((이점, 불리))
        return 성공, 난이도

    monkeypatch.setattr(stats.dice_utils, "내성_굴림", 가짜)
    return 기록


def _상태(p):
    return {i["이름"]: i.get("지속턴") for i in p["상태이상"]}


