def _스킬(이름):
    return dict(gf.스킬데이터모음_생성()[이름], _이름=이름)


def _쓰기(전투상태, p, 이름, 대상=None):
    p["행동자원"].update(일반행동=1, 보조행동=1)
    p["현재MP"] = max(p["현재MP"], 50)
    return ss.스킬_실행(전투상태, p, 이름, _스킬(이름), 대상)


def _명중(monkeypatch, 눈=15):
    monkeypatch.setattr(stats.dice_utils, "d20_굴림", lambda 이점=False, 불리=False: 눈)


def _주사위(monkeypatch, 눈들):
    """피해 주사위를 눈들 순서로, 다 쓰면 1로 굴린다."""
    흐름 = itertools.chain(눈들, itertools.repeat(1))
    monkeypatch.setattr(rng.주사위, "randint", lambda a, b: next(흐름))


def _피해(적):
    return [999 - p["현재HP"] for p in 적]


def _형태(p):
    return [b["이름"] for b in p["상태이상"] if b["이름"] in ("G-1", "G-2", "G-3")]


