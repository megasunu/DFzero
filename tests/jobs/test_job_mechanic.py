def _카운트다운_양(전투상태, m):
    양 = stats.주문시전_보정치(전투상태, m) * core.차수(m)
    assert 양 > 0
    return 양


def _맞기(전투상태, m, 피해, 공격자):
    """방어·반응 없이 피해만 - 건가드/회심의 랜드러너가 끼지 않게 반응행동을 비운다."""
    m["행동자원"]["반응행동"] = 0
    damage.피해_적용(
        전투상태, m, 피해, 공격자=공격자, 피해감소무시=True, 방어력무시=True
    )
    reactions.반응대기_처리(전투상태)


def test_카운트다운을_붙이면_주문시전보정치x차수만큼_임시생명력을_얻고_피해를_먼저_막는다(
    메카전장, monkeypatch
):
    _, 전투상태, 적, m = 메카전장
    _명중(monkeypatch)
    _쓰기(전투상태, m, "카운트다운", 적[0])
    양 = _카운트다운_양(전투상태, m)
    assert 전투상태["설치소환수"][0]["임시생명력"] == 양
    HP = m["현재HP"]
    _맞기(전투상태, m, 양 - 1, 적[1])
    assert m["현재HP"] == HP
    assert 전투상태["설치소환수"][0]["임시생명력"] == 1
    assert _피해(적) == [0, 0, 0]


