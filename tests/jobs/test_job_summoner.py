def test_에체베리아는_교감이면_바로_초고밀도_레이져를_네_속성으로_친다(monkeypatch):
    from game.system.combat import damage

    상태, p, _, 적 = _두명_소환사(monkeypatch, 레벨=13)
    속성들 = []
    원래 = damage.피해_적용

    def 적용(전투상태, 대상, 양, **k):
        속성들.append(k.get("속성"))
        return 원래(전투상태, 대상, 양, **k)

    monkeypatch.setattr(damage, "피해_적용", 적용)
    시작 = len(상태["전투상태"]["로그"])
    gf.아군_스킬사용(상태, "정령소환 : 에체베리아")
    타격 = [e for e in _새로그(상태, 시작) if e.get("타격")]
    assert 타격 and 타격[0].get("스킬") == "에체베리아의 초고밀도 레이져", 타격
    # 속성 목록 그대로 피해에 넘긴다 - 대상이 가장 아픈 쪽으로 받는다(심판관 선례)
    assert 속성들 and all(
        sorted(s) == sorted(["화속성", "수속성", "명속성", "암속성"]) for s in 속성들
    )


