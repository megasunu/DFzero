def test_사슬_해제_달빛베기는_추가공격을_써서_암속성_양손올려베기를_더한다(
    소울브링어전장, monkeypatch
):
    _, 전투상태, 적, sb = 소울브링어전장
    굴림 = []

    def 판정(전투상태, 공격자, 대상, 명중률종류, *a, **k):
        굴림.append(명중률종류)
        return dict(_명중(), 성공=명중률종류 == "주문시전명중률")

    monkeypatch.setattr(damage, "명중_판정", 판정)
    _주사위고정(monkeypatch, 1)  # 내성굴림 실패
    _달빛베기_쓰기(전투상태, sb, 적[0], 추가공격=1)
