    assert 케이가["타입"] == ["스킬", "귀신"] and 케이가["습득방법"] == "레벨습득"
    assert (케이가["행동"], 케이가["타겟"], 케이가["MP소모"]) == (None, "자신", 0)
    MP = sb["현재MP"]
