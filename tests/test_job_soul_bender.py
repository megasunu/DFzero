def test_귀신_공격_식은_귀신마다_1d4빼기1이고_칼라는_1d12_케이가는_추가_피해(
    소울브링어전장,
):
    _, 전투상태, _, sb = 소울브링어전장
    # 레벨 8 소울브링어(스킬 전부 습득): 귀신 : 카잔, 잔영의 케이가, 귀신 : 브레멘, 귀신 : 라사
    귀신 = ss.귀신공격_구성(전투상태, sb)
    assert 귀신["식"] == "(1d4-1)+(1d4-1)+(1d4-1)+(1d4-1)+(1d8+지능보정치)"
    assert 귀신["이점"] is True  # 카잔
    _귀신_더하기(전투상태, sb, "귀신 : 칼라", "귀신 : 사야")
    귀신 = ss.귀신공격_구성(전투상태, sb)
    assert (
        귀신["식"] == "(1d4-1)+(1d4-1)+(1d4-1)+(1d4-1)+(1d12)+(1d4-1)+(1d8+지능보정치)"
    )
    assert 귀신["속성"] == ["암속성", "수속성"]  # 사야


def test_귀참_뒤_귀신_공격은_지능_명중굴림을_따로_하고_명중해야_귀신_효과가_걸린다(
    소울브링어전장, monkeypatch
):
    _, 전투상태, 적, sb = 소울브링어전장
    _귀신_더하기(전투상태, sb, "귀신 : 브레멘", "귀신 : 라사")
    굴림 = []

    def 판정(전투상태, 공격자, 대상, 명중률종류, *a, **k):
        굴림.append(명중률종류)
        return dict(_명중(), 성공=명중률종류 == "지능판정")

    monkeypatch.setattr(damage, "명중_판정", 판정)
    _귀참_쓰기(전투상태, sb, 적[0])
    assert 굴림 == ["보정명중률", "지능판정"]  # 귀참이 빗나가도 귀신 공격은 따로
    (로그,) = _로그(전투상태, "귀참 - 귀신 공격")
