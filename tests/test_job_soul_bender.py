    e = 적[0]
    monkeypatch.setattr(damage, "명중_판정", lambda *a, **k: _명중())
    _주사위고정(monkeypatch, 20)  # 내성 성공 - 공중에뜸 없이 피해만

    def 셋째타_피해(취약):
        e["원본"] = dict(e["원본"], 취약=취약, 저항=[])
        e["현재HP"] = 999
