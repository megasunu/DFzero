    assert 추가타격수("고어크로스") == 1  # 한 번 치는 무기공격력x2
    # 달빛베기 2타로 적[0]이 떠 있다 - 하단공격인 웨이브는 내려온 뒤로 친다
    적[0]["상태이상"] = [s for s in 적[0]["상태이상"] if s["이름"] != "공중에뜸"]
    assert 추가타격수("웨이브") == 0  # 무기 주사위가 없는 주문
    assert 추가타격수("귀참") == 0  # 보정공격력이지만 귀참은 뺀다


