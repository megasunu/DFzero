@pytest.fixture
def 전장():
    random.seed(7)
    상태 = support.새게임([("", "귀검사"), ("", "격투가")])
    gf.전투_시작(상태, ["고블린", "고블린", "고블린"], 레벨=2, 차수=1)
    support.반응_처리(상태)
    전투상태 = 상태["전투상태"]
    적 = sorted(
        (p for p in 전투상태["참가자"] if p["진영"] == "적"),
        key=lambda p: p["대형위치"],
    )
    귀검사 = next(p for p in 전투상태["참가자"] if p["원본"].get("직업") == "귀검사")
