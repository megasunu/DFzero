def _귀신_더하기(전투상태, sb, *이름들):
    """아직 데이터가 없는 귀신(사야/칼라)을 시험용 귀신 타입 스킬로 쥐여 준다. 이미 가진 귀신(브레멘/라사 -
    [스킬습득]으로 배움)은 그대로 둔다."""
    for 이름 in 이름들:
        if 이름 in sb["원본"]["보유스킬"]:
            continue
        전투상태["스킬정의"].setdefault(
            이름, {"분류": "버프스킬", "타입": ["스킬", "귀신"]}
        )
        sb["원본"]["보유스킬"] = list(sb["원본"]["보유스킬"]) + [이름]


def _귀참_쓰기(전투상태, sb, 대상):
    sb["행동자원"].update(일반행동=1, 보조행동=1)
    sb["현재MP"] = 999
    ss.스킬_실행(전투상태, sb, "귀참", _스킬("귀참"), 대상)


def _로그(전투상태, 스킬):
    return [
        항목
        for 항목 in 전투상태["로그"]
        if isinstance(항목, dict) and 항목.get("스킬") == 스킬
    ]


