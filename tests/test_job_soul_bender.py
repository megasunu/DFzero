def test_케이가는_무기_주사위_스킬의_타격마다_붙고_귀참과_주문에는_안_붙는다(
    소울브링어전장, monkeypatch
):
    _, 전투상태, 적, sb = 소울브링어전장
    _케이가_걸기(전투상태, sb)
    monkeypatch.setattr(hit, "명중_판정", lambda *a, **k: _명중())

    def 추가타격수(이름):
        결과 = ss.공격스킬_실행(전투상태, sb, _스킬(이름), 적[0])
        return sum(1 for t in 결과["타격"] if t.get("추가타격") == "잔영의 케이가")

    assert 추가타격수("달빛베기") == 2  # 1타, 2타마다
