def _사야_내성(monkeypatch, 성공):
    """사야의 건강 내성굴림 결과를 정한다 - 명중 굴림은 하지 않는다."""
    굴림 = []

    def 내성(전투상태, 대상, 내성스탯, 난이도, *a, **k):
        굴림.append((대상["이름"], 내성스탯, 난이도))
        return 성공, 20 if 성공 else 1, 0

    def 명중(*a, **k):
        raise AssertionError("장판스킬 지속공격은 명중 굴림을 하지 않는다")

    monkeypatch.setattr(stats, "대상_내성굴림", 내성)
    monkeypatch.setattr(hit, "명중_판정", 명중)
    monkeypatch.setattr(
        stats, "장비_데미지보너스", lambda 참가자, 대상=None, 전투상태=None: 0
    )
    return 굴림


def _사야_피해(전투상태, sb, 눈):
    """((1+차수)d4+주문시전보정치)÷2-2 - 주사위 눈을 고정했을 때(2차수 소울브링어)."""
