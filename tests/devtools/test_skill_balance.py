# ---------------------------------------------------------------- 소환수 스킬 (R = 3, 2026-11-26 - 처음엔 4)


def test_소환수_기준라운드는_3다():
    assert sb.소환수_기준라운드 == 3


def test_메카_소환스킬은_소환수와_지속턴을_찾고_다른_소환은_세지_않는다():
    assert sb.메카소환수(_스킬("템페스트"))[0] == "템페스트"
    assert sb.메카소환수(_스킬("템페스트"))[2] is None  # 전투 끝까지
    assert sb.메카소환수(_스킬("바이퍼"))[2] == 5
    assert sb.메카소환수(_스킬("카운트다운")) is None  # 설치소환수는 공격스킬로 센다
    assert sb.메카소환수({"분류": "소환스킬", "버프획득": ["고블린소환"]}) is None


def test_소환수_행은_행동표_평균의_3라운드_합을_비용과_견준다():
    # 템페스트 3차수: 머신건 1d8+3+1 = 8.5, 미사일 1d12+3+1 = 10.5 -> 평균 9.5, 명중 +1이라 x 75/70
    _, 소환수, _ = sb.메카소환수(_스킬("템페스트"))
    한라운드, 자폭, _ = sb.소환수_라운드당(소환수, sb.기준빌드, 3)
    assert 한라운드 == pytest.approx(9.5 * 0.75 / 0.7)
    assert 자폭 == pytest.approx(3 * 6.5 + 3)  # (차수)d12+주문시전보정치, 명중 70%
    값 = sb._소환수_행(_스킬("템페스트"), sb.기준빌드, 3)
    assert 값["기대"] == pytest.approx(3 * 9.5 * 0.75 / 0.7)
    assert 값["기준"] == 45  # 일반행동 3 x 7.5 + MP 30
    # 바이퍼: 1d6+3-1 = 5.5, 2차수 기준 15 + MP 10 = 22.5
    바이퍼 = sb._소환수_행(_스킬("바이퍼"), sb.기준빌드, 2)
    assert (바이퍼["기대"], 바이퍼["기준"]) == (pytest.approx(16.5), 22.5)


