def test_소환수_행은_행동표_평균의_3라운드_합을_비용과_견준다():
    # 템페스트 3차수: 머신건 1d8+3+1, 미사일 1d12+3+1 - 파이어볼트 피해 이점(높은 쪽 1d8 5.8125, 1d12 8.4861)
    # 평균 (9.8125 + 12.4861) / 2, 명중 +1이라 x 75/70
    _, 소환수, _ = sb.메카소환수(_스킬("템페스트"))
    한라운드, 자폭, _ = sb.소환수_라운드당(소환수, sb.기준빌드, 3)
    평균 = (5.8125 + 4 + 1222 / 144 + 4) / 2
    assert 한라운드 == pytest.approx(평균 * 0.75 / 0.7)
    assert 자폭 == pytest.approx(
        3 * 6.5 + 3
    )  # (차수)d12+주문시전보정치 - 식이 이점 계산 밖, 명중 70%
    값 = sb._소환수_행(_스킬("템페스트"), sb.기준빌드, 3)
    assert 값["기대"] == pytest.approx(3 * 평균 * 0.75 / 0.7)
    assert 값["기준"] == 45  # 일반행동 3 x 7.5 + MP 30
    # 바이퍼: 1d6 이점(161/36)+3-1, 2차수 기준 15 + MP 10 = 22.5
    바이퍼 = sb._소환수_행(_스킬("바이퍼"), sb.기준빌드, 2)
    assert (바이퍼["기대"], 바이퍼["기준"]) == (
        pytest.approx(3 * (161 / 36 + 2)),
        22.5,
    )


