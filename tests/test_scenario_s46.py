"""S46 라이너스의 세리아 구출 의뢰 실전 (docs/scenarios.md).

새 게임 엘븐가드 [NPC]에서 라이너스의 퀘스트를 받고, 로리엔을 **실제 전투로** 걸어 보스(세리아의 감옥)를 깬 뒤
마을로 걸어 돌아와 보고하고 보상을 받는다. 세리아는 그 클리어 뒤에야 [NPC] 목록에 나온다(다른 마을은 test_npc_quest.py).
세이브/불러오기를 거쳐도 퀘스트 상태가 남는다. 판정 하나하나는 test_npc_quest.py가 본다.
"""

import pytest

from game.system import rng
import gameflow as gf
import scenario
import support

시드 = 1
로리엔 = "dungeon_01A_D01_Lorien"
의뢰 = "세리아_구출_의뢰"


def _실전(상태):
    """support.걸어가기/보스_처치의 전투처리 - 실제로 굴린다(정리는 그 도우미가 한다).
    앞 전투의 보상이 남아 있으면 먼저 받는다."""
    if gf.전투_보상_대기중(상태):
        scenario.보상_수령(상태)
    assert scenario.실전(상태) == "아군승리"


def _퀘스트_상태(상태):
    대화 = gf.NPC_대화(상태, "라이너스")
    return next(q for q in 대화["퀘스트"] if q["ID"] == 의뢰)["상태"]


@pytest.mark.scenario("S46")
def test_S46_라이너스의_세리아_구출_의뢰_실전(임시_세이브폴더):
    rng.시드(시드)
    상태 = support.새게임()

    # 1) 엘븐가드 [NPC] - 라이너스만 있고 세리아 구출을 부탁한다
    assert gf.마을_NPC_목록(상태) == ["라이너스"]
    assert gf.NPC_말걸기(상태, "라이너스")["대사"] == "로리엔에서 세리아를 구출해주게."
    gf.퀘스트_수락(상태, 의뢰)
    assert _퀘스트_상태(상태) == "진행중"

    # 2) 로리엔 실전 - 보스(세리아의 감옥)까지 걸어가며 만난 전투도 실제로 싸운다
    gf.던전_진입(상태, 로리엔)
    결과, _ = support.보스_처치(상태, 전투처리=_실전)
    assert 결과 == "아군승리"
    scenario.보상_수령(상태)

    # 3) 걸어서 엘븐가드로 돌아온다 - 세리아가 [NPC]에 생기고 퀘스트는 보고할 수 있다
    도착 = support.연결로_나가기(상태, "town_01A_T01_Elvengard", 전투처리=_실전)
    if gf.전투_보상_대기중(상태):
        scenario.보상_수령(상태)
    assert 도착["타입"] == "마을" and 도착["마을명"] == "엘븐가드"
    assert gf.마을_NPC_목록(상태) == ["라이너스", "세리아"]
    assert gf.NPC_대화(상태, "세리아")["퀘스트"] == []
    assert _퀘스트_상태(상태) == "완료가능"

    # 4) 세이브/불러오기를 거쳐도 상태가 남고, 보고하면 보상을 한 번 받는다
    gf.게임_저장(상태, 1)
    상태 = gf.게임_불러오기(1)
    assert _퀘스트_상태(상태) == "완료가능"
    골드 = 상태["소지품"]["골드"]
    assert gf.퀘스트_완료_보고(상태, 의뢰) == {"골드": 10}
    assert 상태["소지품"]["골드"] == 골드 + 10
    assert _퀘스트_상태(상태) == "완료"
