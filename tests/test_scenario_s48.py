"""S48 전투 밖 소모품 실전 - 상점 구매, 항아리, 속성 플라스크, 전투 밖 회복포션·음식 (docs/scenarios.md, #74).

4인 기본 파티가 엘븐가드 상점(마을 판매목록)에서 회복포션·항아리·속성 플라스크를 산다. 만진의 항아리를 열어
언커먼 장비를 얻고, 귀검사 무기에 샐러맨더 플라스크(화속성)를 마을에서 바른다(같은 속성은 다시 못 바른다).
로리엔 인카운트를 **실전으로** 싸우며 귀검사의 일반공격 속성 후보에 화속성이 들어가는 것을 보고,
둘째 인카운트에서는 처음 차례가 온 아군이 잭프로스트 플라스크를 보조행동으로 바른다(전투 중 부여). 보스를 스킬 우선 정책으로 실전으로 이긴 뒤
다친 캐릭터에게 전투 밖 HP 포션, MP를 쓴 캐릭터에게 MP 포션, 칸나의 푸딩(HP·MP 50%)을 먹인다 - 가득 찬
캐릭터와 "미정" 음식은 거절되고 소모하지 않는다. 마을 휴식으로 부여 속성이 풀리고, 저장/불러오기 뒤 소지품이 그대로다.
값 하나하나(회복량 공식, 사유 문구)는 test_consumables.py가 본다.
"""

import pytest

from game.data.town.town_01A_T01_Elvengard import 마을정보 as 엘븐가드
from game.system import rng
from game.system.combat import attacks, stats
import gameflow as gf
import scenario
import support

시드 = 1
_로리엔 = "dungeon_01A_D01_Lorien"
_엘븐가드 = "town_01A_T01_Elvengard"
_판매목록 = 엘븐가드["상점판매목록"]
_장바구니 = [
    ("포션", "초보자용 HP 포션", 2),
    ("포션", "초보자용 MP 포션", 2),
    ("항아리", "만진의 항아리", 1),
    ("부여", "샐러맨더 플라스크", 1),
    ("부여", "잭프로스트 플라스크", 1),
]


def _보유(상태, 카테고리, 이름):
    return 상태["소지품"].get(카테고리, {}).get(이름, 0)


def _직업(상태, 직업):
    return next(c for c in 상태["파티"]["파티원"] if c["직업"] == 직업)


def _참가자(상태, 캐릭터):
    return next(p for p in 상태["전투상태"]["참가자"] if p["원본"] is 캐릭터)


def _인카운트_실전(상태, 차례마다=None):
    """인카운트까지 걸어 [자동전투]로 싸운다. 차례마다(상태, 참가자)는 아군 차례가 올 때마다 먼저 부른다."""
    적 = scenario.인카운트까지_걷기(상태)
    support.반응_처리(상태)
    for _ in range(300):
        if gf.전투_종료됨(상태):
            break
        if gf.아군_차례인가(상태):
            if 차례마다:
                차례마다(상태, gf.현재_턴_참가자(상태))
            gf.자동전투_한_턴(상태)
        else:
            gf.턴_넘기기(상태)
    종료 = 상태["전투상태"]["종료"]
    assert gf.전투_결과_정리(상태) == 종료 == "아군승리", 종료
    if gf.전투_보상_대기중(상태):
        scenario.보상_수령(상태)
    return 적


def _가장_빈(상태, 키, 최대):
    """현재값이 최대보다 가장 많이 모자란 캐릭터와 모자란 양."""
    캐릭터 = max(상태["파티"]["파티원"], key=lambda c: 최대(상태, c) - c[f"현재{키}"])
    return 캐릭터, 최대(상태, 캐릭터) - 캐릭터[f"현재{키}"]


@pytest.mark.scenario("S48")
def test_S48_전투_밖_소모품_실전(golden):
    rng.시드(시드)
    상태 = support.새게임()
    기록 = {}
    귀검사 = _직업(상태, "귀검사")

    # 1) 엘븐가드 상점 - 마을 판매목록으로 산다(최대 구매수량은 골드로 정해진다)
    상태["소지품"]["골드"] = 200
    for 탭, 이름, 수량 in _장바구니:
        assert 이름 in [
            i["이름"] for i in gf.상점_구매목록(상태, "소모품", 탭, _판매목록)
        ]
        골드 = 상태["소지품"]["골드"]
        금액 = gf.상점_구매(상태, "소모품", 탭, 이름, 수량, 상점판매목록=_판매목록)
        assert 상태["소지품"]["골드"] == 골드 - 금액
    assert _보유(상태, "포션", "초보자용 HP 포션") == 2
    with pytest.raises(ValueError):  # 판매목록에 없는 포션은 못 산다
        gf.상점_구매(
            상태, "소모품", "포션", "숙련자용 HP 포션", 1, 상점판매목록=_판매목록
        )
    기록["구매뒤_골드"] = 상태["소지품"]["골드"]

    # 2) 항아리 - 언커먼 장비 하나가 소지품에 들어오고 항아리는 줄어든다
    장비 = gf.항아리_열기(상태, "만진의 항아리")
    assert 장비["레어도"] == "언커먼"
    assert _보유(상태, "장비", 장비["이름"]) == 1
    assert _보유(상태, "소모품", "만진의 항아리") == 0
    with pytest.raises(ValueError):
        gf.항아리_열기(상태, "만진의 항아리")
    기록["항아리"] = 장비["이름"]

    # 3) 마을에서 속성 플라스크 - 귀검사 무기에 화속성, 같은 속성은 다시 못 바르고 줄지 않는다
    gf.캐릭터_부여아이템사용(상태, 귀검사, "샐러맨더 플라스크")
    assert 귀검사["무기속성부여"] == ["화속성"]
    assert _보유(상태, "소모품", "샐러맨더 플라스크") == 0

    # 4) 로리엔 첫 인카운트 실전 - 귀검사의 일반공격이 화속성
    gf.던전_진입(상태, _로리엔)
    속성 = []

    def _속성_보기(상태, 참가자):
        if 참가자["원본"] is 귀검사 and not 속성:
            적 = next(p for p in 상태["전투상태"]["참가자"] if p["진영"] == "적")
            속성.append(stats.부여_무기속성(참가자))
            # 무속성과 화속성 중 더 아픈 쪽 - 저항/취약이 같으면 무기 속성(무속성)이 남는다
            속성.append(attacks.일반공격_속성(상태["전투상태"], 참가자, 적))

    기록["첫전투"] = _인카운트_실전(상태, _속성_보기)
    assert 속성[0] == ["화속성"], 속성
    assert 속성[1] in ("무속성", "화속성")
    기록["귀검사_일반공격_속성"] = 속성[1]
    assert 귀검사["무기속성부여"] == ["화속성"]  # 전투가 끝나도 휴식 전까지

    # 5) 둘째 인카운트 - 처음 차례가 온 아군이 잭프로스트 플라스크(보조행동)
    발랐다 = []

    def _전투중_부여(상태, 참가자):
        if not 발랐다:
            목록 = gf.아군_부여아이템_목록(상태)
            assert [(n, 수, 사유) for n, 수, 사유 in 목록] == [
                ("잭프로스트 플라스크", 1, None)
            ]
            보조 = 참가자["행동자원"]["보조행동"]
            gf.아군_부여아이템사용(상태, "잭프로스트 플라스크")
            assert 참가자["행동자원"]["보조행동"] == 보조 - 1
            발랐다.append(참가자["원본"])

    기록["둘째전투"] = _인카운트_실전(상태, _전투중_부여)
    assert len(발랐다) == 1
    바른 = 발랐다[0]
    assert 바른.get("무기속성부여", [])[-1:] == ["수속성"]
    기록["전투중_부여"] = [바른["캐릭터명"], list(바른["무기속성부여"])]
    assert _보유(상태, "소모품", "잭프로스트 플라스크") == 0

    # 6) 보스 실전(스킬 우선 - MP를 쓴다)
    사용 = []
    결과, _ = support.보스_처치(상태, 전투처리=lambda s: scenario.스킬_실전(s, 사용))
    assert 결과 == "아군승리"
    if gf.전투_보상_대기중(상태):
        scenario.보상_수령(상태)

    # 7) 전투 밖 회복포션 - 가득 찬 캐릭터는 거절, 다친 캐릭터는 회복하고 1개 준다
    HP캐릭터, 빈HP = _가장_빈(상태, "HP", gf.캐릭터_최대HP)
    MP캐릭터, 빈MP = _가장_빈(상태, "MP", gf.캐릭터_최대MP)
    assert 빈HP > 0 and 빈MP > 0, (빈HP, 빈MP)
    가득 = next(
        (c for c in 상태["파티"]["파티원"] if c["현재HP"] == gf.캐릭터_최대HP(상태, c)),
        None,
    )
    if 가득 is not None:
        사유 = dict((n, r) for n, _, r in gf.캐릭터_회복포션_목록(상태, 가득))
        assert 사유["초보자용 HP 포션"]
        with pytest.raises(ValueError):
            gf.캐릭터_포션사용(상태, 가득, "초보자용 HP 포션")
    assert _보유(상태, "포션", "초보자용 HP 포션") == 2
    HP전 = HP캐릭터["현재HP"]
    대상, 회복 = gf.캐릭터_포션사용(상태, HP캐릭터, "초보자용 HP 포션")
    assert 대상 == "HP" and 0 < 회복 <= 빈HP
    assert HP캐릭터["현재HP"] == HP전 + 회복
    assert _보유(상태, "포션", "초보자용 HP 포션") == 1
    MP전 = MP캐릭터["현재MP"]
    대상, MP회복 = gf.캐릭터_포션사용(상태, MP캐릭터, "초보자용 MP 포션")
    assert 대상 == "MP" and 0 < MP회복 <= 빈MP
    assert MP캐릭터["현재MP"] == MP전 + MP회복
    기록["포션"] = {
        "HP": [HP캐릭터["캐릭터명"], 빈HP, 회복],
        "MP": [MP캐릭터["캐릭터명"], 빈MP, MP회복],
    }

    # 8) 음식 - 칸나의 푸딩은 HP·MP를 올리고, "미정" 음식은 거절되고 남는다(음식은 상점에 없어 직접 넣는다)
    상태["소지품"]["소모품"]["칸나의 푸딩"] = 1
    상태["소지품"]["소모품"]["언더풋 특산 치즈"] = 1
    with pytest.raises(ValueError, match="데이터 없음"):
        gf.캐릭터_음식사용(상태, HP캐릭터, "언더풋 특산 치즈")
    assert _보유(상태, "소모품", "언더풋 특산 치즈") == 1
    먹을 = max(
        상태["파티"]["파티원"],
        key=lambda c: (
            gf.캐릭터_최대HP(상태, c)
            - c["현재HP"]
            + gf.캐릭터_최대MP(상태, c)
            - c["현재MP"]
        ),
    )
    전 = (먹을["현재HP"], 먹을["현재MP"])
    음식회복 = gf.캐릭터_음식사용(상태, 먹을, "칸나의 푸딩")
    assert set(음식회복) == {"HP", "MP"} and sum(음식회복.values()) > 0
    assert (먹을["현재HP"], 먹을["현재MP"]) == (
        전[0] + 음식회복["HP"],
        전[1] + 음식회복["MP"],
    )
    assert 먹을["현재HP"] <= gf.캐릭터_최대HP(상태, 먹을)
    assert _보유(상태, "소모품", "칸나의 푸딩") == 0
    기록["음식"] = [먹을["캐릭터명"], 음식회복]

    # 9) 마을로 돌아와 휴식 - 부여 속성이 풀린다
    support.연결로_나가기(상태, _엘븐가드, 전투처리=scenario.실전)
    gf.휴식(상태)
    assert all("무기속성부여" not in c for c in 상태["파티"]["파티원"])

    # 10) 저장/불러오기 - 소지품 그대로
    gf.게임_저장(상태, 1)
    불러옴 = gf.게임_불러오기(1)
    assert 불러옴["소지품"] == 상태["소지품"]
    기록["남은_소모품"] = {k: dict(상태["소지품"][k]) for k in ("포션", "소모품")}
    golden("scenario_S48_consumables", 기록)
