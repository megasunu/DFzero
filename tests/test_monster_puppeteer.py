def test_마스터_도그리의_값과_패턴():
    m = gf.몬스터목록["마스터 도그리"]
    assert m["이미지"] == "asset_monster_master_dogri.webp"
    assert (m["적등급"], m["지능"], m["데미지보너스"]) == ("네임드", 18, 0)
    assert m["특성"][2:] == ["인형관의 주인"]
    p = m["패턴"]
    assert [p[i]["이름"] for i in range(1, 7)] == [
        "근접 공격",
        "근접 공격",
        "폭발 기둥",
        "폭발 기둥",
        "인형조종",
        "연쇄 폭발 기둥",
    ]
    for i, 타겟 in ((3, "적단일"), (6, "적3체")):
        단계1, 단계2 = p[i]["공격단계1"], p[i]["공격단계2"]
        assert (단계1["타겟"], 단계1["속성"], 단계1["데미지"]) == (
            타겟,
            "무속성",
            "1d4+지능보정치",
        )
        assert (단계2["타겟"], 단계2["속성"], 단계2["데미지"]) == (
            타겟,
            "화속성",
            "1d4+지능보정치",
        )
        assert 단계2["기준대상"] == "공격단계1"
    assert p[5]["타입"] == "상태이상패턴"
    assert p[5]["효과"] == {"종류": "상태이상", "이름": "혼란", "지속턴": 2}


