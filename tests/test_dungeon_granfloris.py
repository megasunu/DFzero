@pytest.mark.parametrize("파일명", list(_출현표))
def test_그란플로리스_인카운트는_출현그룹_하나에_지정한_가중치다(파일명):
    그룹들 = gf.던전_레지스트리[파일명]["인카운트"]["출현그룹"]
    assert len(그룹들) == 1
    assert 그룹들[0]["출현몬스터"] == _출현표[파일명]
    for 이름 in _출현표[파일명]:
        assert 이름 in gf.몬스터목록, 이름


@pytest.mark.parametrize(
    "파일명, 정령",
    [
        ("dungeon_01A_D07_frost_mirkwood", "나이아스"),
        ("dungeon_01A_D09_blazing_grakquarak", "아도르"),
    ],
)
def test_정령은_일반_출현에서_빠지고_보스전에만_나온다(파일명, 정령):
    맵 = gf.던전_레지스트리[파일명]
    assert all(정령 not in g["출현몬스터"] for g in 맵["인카운트"]["출현그룹"])
    [보스전] = [o for o in 맵["오브젝트"].values() if o.get("타입") == "보스전투"]
    assert [m["이름"] for m in 보스전["전투몬스터"]].count(정령) == 2
