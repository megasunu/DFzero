"""던전 밸런스 측정 도구(tools/dungeon_sim.py, #491) - 조정안 적용, 피해 집계, 판 재현.

실제 측정(던전당 수백 판)은 게이트 밖에서 돌린다(결과는 docs/balance/하늘성.md). 여기서는 몇 판만 돌린다.
"""

import gameflow as gf
from game.system import dungeon_system
from tools import dungeon_sim as ds

_D11 = "dungeon_02A_D11_amon_lower"


def test_던전_코드로_파일을_찾는다():
    assert ds.던전_찾기("D11", gf.던전_레지스트리) == _D11
    assert ds.던전_찾기(_D11, gf.던전_레지스트리) == _D11


def test_조정은_사본에만_적용되고_원본_데이터는_그대로다():
    원본 = gf.던전_레지스트리[_D11]["인카운트"]
    전 = dict(원본)
    새 = ds.조정_인카운트(원본, {"레벨+": -2, "차수": 1, "마리": [1, 3]})
    assert (새["레벨"], 새["차수"], 새["출현마리수"]) == (원본["레벨"] - 2, 1, (1, 3))
    assert 원본 == 전
    _, 오브젝트 = ds.보스_오브젝트(gf.던전_레지스트리[_D11])
    항목, 레벨, 차수 = ds.조정_보스(오브젝트, {"보스마리": 2, "차수": 1})
    assert 항목 == 오브젝트["전투몬스터"][:2] and 항목[0]["칭호"] == "보스"
    assert (레벨, 차수) == (오브젝트["레벨"], 1)
    assert len(오브젝트["전투몬스터"]) == 5


def test_마리_빼기_조정안은_출현마리수_양끝을_줄이되_1_밑으로_가지_않는다():
    정보 = {"인카운트": {"출현마리수": (1, 4)}}
    조정 = ds.조정_풀기("B 마리-1", 정보)
    assert 조정["마리"] == [1, 3] and 조정["보스마리"] == 3


def test_피해_집계는_적이_준_피해만_몬스터와_패턴마다_더한다():
    로그 = [
        {"종류": "타격", "공격자": "카겔 A", "패턴": "표창", "총피해": 4},
        {"종류": "타격", "공격자": "카겔 B", "패턴": "표창", "총피해": 3},
        {"종류": "일반공격", "공격자": "카겔 A", "피해": 2},
        {"종류": "일반공격", "공격자": "레인저", "피해": 9},  # 아군
        {"종류": "타격", "공격자": "카겔 A", "패턴": "표창", "총피해": 0},
    ]
    합 = ds.피해_집계(로그, {"카겔 A": "카겔", "카겔 B": "카겔"})
    assert 합 == {("카겔", "표창"): 7, ("카겔", "일반공격"): 2}


def test_요약은_승률과_피해_비율을_낸다():
    결과 = [
        {"승": True, "라운드": 4, "피해": {"카겔|표창": 6}},
        {"승": False, "라운드": 6, "피해": {"카겔|표창": 2, "골렘|때리기": 2}},
    ]
    r = ds.요약(결과)
    assert (r["판"], r["승"], r["승률"], r["평균라운드"]) == (2, 1, 0.5, 5.0)
    assert r["피해상위"][0] == ["카겔|표창", 4.0, 0.8]
    assert ds.몬스터별_피해(r["피해상위"]) == {"카겔": 0.8, "골렘": 0.2}


def test_같은_시드는_같은_결과이고_일꾼_수와_상관없다():
    조건 = {"던전": "D11", "종류": "인카운트", "레벨": 6}
    한번 = ds.재기(조건, 4, 시작시드=7)
    assert 한번 == ds.재기(조건, 4, 시작시드=7)
    assert 한번["판"] == 4 and 0 <= 한번["승"] <= 4
    # 조각을 나눠도 같은 시드 집합이면 요약이 같다(프로세스 없이 조각만 확인)
    둘 = ds._조각((조건, [7, 9])) + ds._조각((조건, [8, 10]))
    assert ds.요약(둘)["승"] == 한번["승"]


def test_보스와_원정도_끝까지_돌고_챔피언_조정은_끝나면_되돌린다():
    전 = dungeon_system.챔피언_확률
    보스 = ds.재기({"던전": "D11", "종류": "보스", "레벨": 6}, 1, 시작시드=3)
    assert 보스["판"] == 1 and 보스["평균라운드"] > 0
    원정 = ds.재기(
        {"던전": "D12", "종류": "원정", "레벨": 15, "조정": {"챔피언": False}},
        1,
        시작시드=3,
    )
    assert 원정["판"] == 1 and 원정["평균라운드"] > 0
    assert dungeon_system.챔피언_확률 == 전
