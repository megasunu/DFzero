# 자동전투 라운드 제한(#670, 2026-11-12 사용자 결정) - 자동전투로 진행할 때 100라운드가 지나도 끝나지 않으면 패배.
# 라운드는 전투 시작부터 센다. 손으로 싸울 때는 제한이 없다. 구현은 game/controller/ctl_autobattle.py.

import gameflow as gf
from game.system import rng
from tests import support


def _아군_차례_전투(라운드):
    rng.시드(1)
    상태 = support.새게임([("", "귀검사")])
    gf.전투_시작(상태, ["고블린"], 레벨=1, 차수=1)
    support.반응_처리(상태)
    while not gf.아군_차례인가(상태):
        gf.턴_넘기기(상태)
    for 적 in gf.적_목록(상태):  # 이번 차례에 끝나지 않게
        적["현재HP"] = 999
    상태["전투상태"]["라운드"] = 라운드
    return 상태


def test_제한은_100라운드다():
    assert gf.자동전투_최대라운드 == 100


def test_100라운드까지는_자동전투가_그대로_진행한다():
    상태 = _아군_차례_전투(100)
    gf.자동전투_한_턴(상태)
    assert 상태["전투상태"]["종료"] is None


def test_100라운드가_지나면_자동전투는_패배로_끝난다():
    상태 = _아군_차례_전투(101)
    아군HP = gf.아군_목록(상태)[0]["현재HP"]
    gf.자동전투_한_턴(상태)
    전투상태 = 상태["전투상태"]
    assert 전투상태["종료"] == "적승리"
    assert gf.전투_종료됨(상태)
    assert gf.아군_목록(상태)[0]["현재HP"] == 아군HP  # 행동 없이 바로 끝난다
    마지막 = 전투상태["로그"][-1]
    assert gf.로그_문장들(마지막) == ["100라운드가 지나도 전투가 끝나지 않아 패배했다."]
    assert gf.전투_결과_정리(상태) == "적승리"
    assert gf.전투_종료_문구(상태, "적승리") == ["전투 패배!"]


def test_손으로_싸우면_100라운드가_지나도_끝나지_않는다():
    상태 = _아군_차례_전투(150)
    gf.아군_일반공격(상태, gf.적_목록(상태)[0])
    gf.턴_넘기기(상태)
    assert 상태["전투상태"]["종료"] is None


def test_이미_끝난_전투에서는_아무것도_하지_않는다():
    상태 = _아군_차례_전투(101)
    상태["전투상태"]["종료"] = "아군승리"
    로그수 = len(상태["전투상태"]["로그"])
    gf.자동전투_한_턴(상태)
    assert 상태["전투상태"]["종료"] == "아군승리"
    assert len(상태["전투상태"]["로그"]) == 로그수
