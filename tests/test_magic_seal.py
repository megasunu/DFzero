def _착용(상태, 참가자, 탭, 능력, 슬롯=None):
    봉인이름 = {
        "무기": "마법으로 봉인된 소검",
        "상의": "마법으로 봉인된 천갑 상의",
        "하의": "마법으로 봉인된 천갑 하의",
        "반지": "마법으로 봉인된 반지",
        "보조장비": "마법으로 봉인된 보조장비",
        "귀걸이": "마법으로 봉인된 귀걸이",
    }[탭]
    아이템 = (
        _마법의(상태, 탭, 봉인이름, 능력)
        if 능력
        else 상태["상점카탈로그"]["장비"][탭][봉인이름]
    )
    참가자["장비데이터"][슬롯 or 탭] = 아이템
    return 아이템


def _타입(monkeypatch, 몬스터, 타입):
    monkeypatch.setitem(몬스터, "원본", {**몬스터["원본"], "타입": 타입})


def _주사위(monkeypatch, 값):
    monkeypatch.setattr(dice_utils.random, "randint", lambda a, b: min(max(값, a), b))


def test_기력_참선은_전투_안팎의_최대HP를_올린다(마봉전장):
    상태, 전투상태, 아군, _ = 마봉전장
    귀검사 = 아군[0]
    전 = stats.유효_최대HP(전투상태, 귀검사)
    _착용(상태, 귀검사, "상의", "기력")
    assert stats.유효_최대HP(전투상태, 귀검사) == 전 + 5
    _착용(상태, 귀검사, "무기", "참선")
    assert stats.유효_최대HP(전투상태, 귀검사) == 전 + 15
    # 전투 밖(캐릭터 화면 등)도 같은 함수
    원본 = 귀검사["원본"]
    assert equipment_system.장비반영_최대HP(
        원본, 귀검사["장비데이터"]
    ) == equipment_system.장비반영_최대HP(
        원본, {**귀검사["장비데이터"], "상의": None, "무기": None}
    ) + 15 + (0)


