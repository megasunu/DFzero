def test_몬스터_크기_분류와_표시_배율():
    크기 = {n: d.get("크기") for n, d in gf.몬스터목록.items()}
    for n, d in gf.몬스터목록.items():
        기대 = {
            "고블린": "소형",
            "루가루": "소형",
            "좀비": "중형",
            "인간": "중형",
            "용족": "소형",
            "골렘": "중형",  # 2026-10-29
            "갑옷형": "중형",  # 익스펠러 2026-10-29
            "시험용": "대형",  # 거대 누골
        }.get(d["분류"])
        if "인형사" in d["타입"]:  # 인형사 4종은 인간이지만 소형(2026-10-28)
            기대 = "소형"
        if d["분류"] == "타우":
            기대 = "대형" if n in ("타우 비스트", "타우킹 샤우타") else "중형"
        assert 크기[n] == 기대, (n, d["분류"], 크기[n])
    p = lambda 원본, 이름="x": {"이름": 이름, "원본": 원본}  # noqa: E731
    assert [gf.적_표시_배율(p({"크기": k})) for k in ("소형", "중형", "대형")] == [
        0.5,
        0.75,
        1.0,
    ]
    assert gf.적_표시_배율(p({})) == 0.75  # 없으면 중형
    with pytest.raises(ValueError, match="크기"):
        gf.적_표시_배율(p({"크기": "거대"}))


def test_공격연출_바닥은_크기_그림의_가운데에_맞추되_칸_바닥_아래로는_안_간다():
    """연출의 세로 가운데 = 크기 그림(칸 높이 x 소형 0.5/중형 0.75/대형 1)의 가운데,
    칸 바닥보다 낮으면 바닥(사용자 지정 2026-10-14)."""
    바닥 = gf.공격연출_바닥  # (칸높이, 연출높이, 크기배율) -> 칸 바닥에서 연출 바닥까지
    assert 바닥(100, 60, 0.5) == 0  # 소형: 가운데 25 < 연출 절반 30 -> 바닥에 붙음
    assert 바닥(100, 60, 0.75) == 7.5  # 중형: 37.5 - 30
    assert 바닥(100, 60, 1.0) == 20  # 대형: 50 - 30
    assert 바닥(100, 20, 0.5) == 15  # 작은 연출은 소형도 조금 뜬다
    assert 바닥(100, 60, 0.75) < 바닥(100, 60, 1.0)


