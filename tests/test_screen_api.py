def _주사위(monkeypatch, 값):

    monkeypatch.setattr(rng.주사위, "randint", lambda a, b: min(max(값, a), b))


def _새로그(상태):
    gf.새_로그_가져오기(상태)  # 앞에서 쌓인 것은 버린다


def _문장(상태):
    return [줄 for 항목 in gf.새_로그_가져오기(상태) for 줄 in gf.로그_문장들(항목)]


