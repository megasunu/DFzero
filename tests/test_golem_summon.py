"""인형사의 골렘 소환(#464, 2026-10-29 사용자 결정 / 2026-10-30 캐스팅 삭제 #485) - 진흙/돌/강철 인형사의 차례가
시작될 때 체력이 절반 이하면 전투당 한 번 진흙/스톤/청동 골렘을 곧바로 부르고, 그 차례의 행동은 그대로 한다.

- 골렘의 레벨·차수는 인형사의 값, 부른 라운드에는 쉬고 다음 라운드부터 움직인다.
- 살아 있는 적이 다섯이면 부르지 못하고 다음 차례에 다시 본다. 칸이 다섯 다 찼으면 쓰러진 적의 칸을 넘겨받는다.
- 차례 시작에 행동불가면 부르지 않고 다음 차례에 다시 본다. 부른 골렘을 쓰러뜨리면 골드·드랍을 준다.

규칙은 docs/game-rules.md "인형사 몬스터".
"""

import pytest

import gameflow as gf
from game.system import loot_system
from game.system.combat import damage, monster_actions, stats
from game.system.skill import skill_run
from tests import support


def _전장(몬스터들=("진흙 인형사",), 레벨=3, 차수=1):
    상태 = support.새게임(
        [("", "귀검사"), ("", "격투가"), ("", "거너"), ("", "마법사")]
    )
    gf.전투_시작(상태, list(몬스터들), 레벨=레벨, 차수=차수)
    support.반응_처리(상태)
    전투상태 = 상태["전투상태"]
    for p in 전투상태["참가자"]:
        if p["진영"] == "아군":
            p["현재HP"] = 999
    return 상태, 전투상태


def _적(전투상태, 이름):
    return next(p for p in 전투상태["참가자"] if p["이름"] == 이름)


def _반피_아래(전투상태, 몬스터):
    몬스터["현재HP"] = (int(stats.유효_최대HP(전투상태, 몬스터)) - 1) // 2


def _차례로(전투상태, 몬스터):
    """몬스터 차례가 될 때까지 다음_턴을 넘긴다(아군은 아무것도 하지 않음, 다른 적은 패턴대로)."""
    for _ in range(40):
        다음 = skill_run.다음_턴(전투상태)
        if 다음 is 몬스터:
            return 다음
        if 다음["진영"] == "적":
            monster_actions.몬스터_턴_실행(전투상태, 다음)
    raise AssertionError("차례가 오지 않는다")


def _행동한_패턴(전투상태, 시작, 몬스터):
    return [
        x
        for x in 전투상태["로그"][시작:]
        if x.get("공격자") == 몬스터["이름"] and x.get("패턴")
    ]


def _인형사_차례(전투상태, 인형사):
    전투상태["현재턴"] = 전투상태["참가자"].index(인형사)
    monster_actions.몬스터_턴_실행(전투상태, 인형사)


@pytest.mark.parametrize(
    "인형사, 골렘",
    [
        ("진흙 인형사", "진흙 골렘"),
        ("돌 인형사", "스톤 골렘"),
        ("강철 인형사", "청동 골렘"),
    ],
)
def test_인형사는_차례_시작에_체력이_절반_이하면_골렘을_부르고_행동한다(인형사, 골렘):
    상태, 전투상태 = _전장((인형사,), 레벨=4, 차수=2)
    주인 = _적(전투상태, 인형사)
    _반피_아래(전투상태, 주인)
    시작 = len(전투상태["로그"])
    _인형사_차례(전투상태, 주인)
    새것 = _적(전투상태, 골렘)
    assert (새것["원본"]["레벨"], 새것["원본"]["차수"]) == (4, 2)
    assert 새것["생존"] and 새것["현재HP"] == stats.유효_최대HP(전투상태, 새것) > 1
    assert 새것 in gf.적_목록(상태)
    assert 주인["소환사용"] and not 주인.get("캐스팅시작")
    assert not any(s["이름"] == "캐스팅" for s in 주인["상태이상"])
    assert len(_행동한_패턴(전투상태, 시작, 주인)) == 2  # 부른 뒤 차수만큼 행동한다
    문장 = [줄 for 항목 in 전투상태["로그"][시작:] for 줄 in gf.로그_문장들(항목)]
    assert any(f"{골렘} 소환!" in 줄 for 줄 in 문장), 문장


def test_체력이_정확히_절반이면_부른다():
    _, 전투상태 = _전장()
    주인 = _적(전투상태, "진흙 인형사")
    주인["현재HP"] = stats.유효_최대HP(전투상태, 주인) / 2
    _인형사_차례(전투상태, 주인)
    assert 주인.get("소환사용")


def test_체력이_절반보다_많으면_부르지_않고_패턴을_쓴다():
    _, 전투상태 = _전장()
    주인 = _적(전투상태, "진흙 인형사")
    주인["현재HP"] = int(stats.유효_최대HP(전투상태, 주인)) // 2 + 1
    시작 = len(전투상태["로그"])
    _인형사_차례(전투상태, 주인)
    assert _행동한_패턴(전투상태, 시작, 주인)
    assert not 주인.get("소환사용")


def test_마스터_도그리는_소환하지_않는다():
    _, 전투상태 = _전장(("마스터 도그리",))
    도그리 = _적(전투상태, "마스터 도그리")
    _반피_아래(전투상태, 도그리)
    _인형사_차례(전투상태, 도그리)
    assert not 도그리.get("소환사용") and not 도그리.get("캐스팅시작")


def test_부른_골렘은_그_라운드에는_쉬고_다음_라운드부터_움직인다():
    _, 전투상태 = _전장()
    주인 = _적(전투상태, "진흙 인형사")
    _반피_아래(전투상태, 주인)
    _인형사_차례(전투상태, 주인)
    골렘 = _적(전투상태, "진흙 골렘")
    라운드 = 전투상태["라운드"]
    차례받음 = []
    for _ in range(30):
        다음 = skill_run.다음_턴(전투상태)
        if 다음 is 골렘:
            차례받음.append(전투상태["라운드"])
            break
        if 다음["진영"] == "적":
            monster_actions.몬스터_턴_실행(전투상태, 다음)
    assert 차례받음 == [라운드 + 1]


def test_소환은_전투당_한_번이다():
    _, 전투상태 = _전장()
    주인 = _적(전투상태, "진흙 인형사")
    _반피_아래(전투상태, 주인)
    _인형사_차례(전투상태, 주인)
    _차례로(전투상태, 주인)  # 다음 라운드의 자기 차례
    시작 = len(전투상태["로그"])
    monster_actions.몬스터_턴_실행(전투상태, 주인)
    assert not 주인.get("캐스팅시작")
    assert _행동한_패턴(전투상태, 시작, 주인)
    assert (
        sum(p["원본"].get("몬스터명") == "진흙 골렘" for p in 전투상태["참가자"]) == 1
    )


def test_차례_시작에_행동불가면_부르지_않고_다음_차례에_다시_본다():
    _, 전투상태 = _전장()
    주인 = _적(전투상태, "진흙 인형사")
    _반피_아래(전투상태, 주인)
    주인["상태이상"].append({"이름": "기절", "지속턴": 1})
    _인형사_차례(전투상태, 주인)
    assert not any(p["원본"].get("몬스터명") == "진흙 골렘" for p in 전투상태["참가자"])
    assert not 주인.get("소환사용")
    주인["상태이상"] = []
    _인형사_차례(전투상태, 주인)
    assert 주인["소환사용"] and _적(전투상태, "진흙 골렘")


def test_살아_있는_적이_다섯이면_부르지_못하고_다음_차례에_다시_본다():
    _, 전투상태 = _전장(("진흙 인형사",) + ("고블린",) * 4)
    주인 = _적(전투상태, "진흙 인형사")
    _반피_아래(전투상태, 주인)
    _인형사_차례(전투상태, 주인)
    assert not any(p["원본"].get("몬스터명") == "진흙 골렘" for p in 전투상태["참가자"])
    assert not 주인.get("소환사용")
    고블린 = next(
        p for p in 전투상태["참가자"] if p["원본"].get("몬스터명") == "고블린"
    )
    고블린["생존"] = False
    _인형사_차례(전투상태, 주인)
    assert 주인["소환사용"] and _적(전투상태, "진흙 골렘")


def test_칸이_찼으면_쓰러진_적의_칸을_넘겨받는다():
    상태, 전투상태 = _전장(("진흙 인형사",) + ("고블린",) * 4)
    주인 = _적(전투상태, "진흙 인형사")
    쓰러진 = next(p for p in gf.적_목록(상태) if p is not 주인)
    damage.피해_적용(전투상태, 쓰러진, 10**6, 피해감소무시=True)
    _반피_아래(전투상태, 주인)
    _인형사_차례(전투상태, 주인)
    골렘 = _적(전투상태, "진흙 골렘")
    칸 = gf.적_목록(상태)
    assert len(칸) == 5 and 골렘 in 칸 and 쓰러진 not in 칸
    assert 골렘["대형위치"] == 쓰러진["대형위치"]
    assert 쓰러진 in 전투상태["참가자"]  # 보상 대상에는 남는다


def test_부른_골렘을_쓰러뜨리면_골드와_드랍을_굴린다(monkeypatch):
    상태, 전투상태 = _전장()
    주인 = _적(전투상태, "진흙 인형사")
    _반피_아래(전투상태, 주인)
    _인형사_차례(전투상태, 주인)
    받은 = []
    원래 = loot_system.전리품_판정

    def 기록(몬스터원본목록, *a, **k):
        받은.extend(m["몬스터명"] for m in 몬스터원본목록)
        return 원래(몬스터원본목록, *a, **k)

    monkeypatch.setattr(loot_system, "전리품_판정", 기록)
    support.강제_승리(상태)
    gf.전투_결과_정리(상태)
    assert sorted(받은) == ["진흙 골렘", "진흙 인형사"]


def test_같은_골렘이_또_나오면_이름에_B를_붙인다():
    _, 전투상태 = _전장(("진흙 인형사", "진흙 인형사"))
    for 이름 in ("진흙 인형사 A", "진흙 인형사 B"):
        주인 = _적(전투상태, 이름)
        _반피_아래(전투상태, 주인)
        _인형사_차례(전투상태, 주인)
    이름들 = sorted(
        p["이름"]
        for p in 전투상태["참가자"]
        if p["원본"].get("몬스터명") == "진흙 골렘"
    )
    assert 이름들 == ["진흙 골렘", "진흙 골렘 B"]
    assert len({p["id"] for p in 전투상태["참가자"]}) == len(전투상태["참가자"])


def test_골렘_소환_특성은_인형사_셋에게만_있다():
    특성 = {
        이름: [t for t in gf.몬스터목록[이름]["특성"] if t.startswith("골렘소환")]
        for 이름 in ("진흙 인형사", "돌 인형사", "강철 인형사", "마스터 도그리")
    }
    assert 특성 == {
        "진흙 인형사": ["골렘소환:진흙"],
        "돌 인형사": ["골렘소환:스톤"],
        "강철 인형사": ["골렘소환:청동"],
        "마스터 도그리": [],
    }
