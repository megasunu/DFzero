"""쓰러진 참가자는 행동하지 않는다 - 차례 시작 피해(홀딩·살의의 파동), 자동전투 중 반격, 차례 끝 지속피해로
쓰러진 뒤에도 그 차례의 행동·특성이 이어지던 버그."""

import gameflow as gf
from game.system import rng

import support


def _쓰러진_뒤_행동(상태, 이름, 시작):
    """로그[시작:]에서 이름이 쓰러진 기록 뒤에 이름이 공격자인 기록들."""
    로그 = 상태["전투상태"]["로그"][시작:]
    for i, 항목 in enumerate(로그):
        쓰러짐 = list(항목.get("쓰러짐") or [])
        for 타 in 항목.get("타격") or []:
            쓰러짐 += 타.get("쓰러짐") or []
        if 이름 in 쓰러짐:
            return [x for x in 로그[i + 1 :] if x.get("공격자") == 이름]
    raise AssertionError(f"{이름}이(가) 쓰러지지 않았다")


def _내_차례까지(상태, 직업):
    while not (
        gf.아군_차례인가(상태) and gf.현재_턴_참가자(상태)["원본"]["직업"] == 직업
    ):
        gf.턴_넘기기(상태)
    p = gf.현재_턴_참가자(상태)
    p["현재HP"] = p["최대HP"] = 999
    p["현재MP"] = 99
    return p


def test_홀딩_피해로_차례_시작에_쓰러진_몬스터는_그_차례에_행동하지_않는다(monkeypatch):
    rng.시드(1)
    상태 = support.새게임([("", "격투가")])
    gf.전투_시작(상태, ["고블린", "고블린"], 레벨=1, 차수=1)
    support.반응_처리(상태)
    _내_차례까지(상태, "격투가")
    적 = [e for e in gf.적_목록(상태) if e["생존"]][0]
    support.주사위고정(monkeypatch, 20)
    gf.아군_스킬사용(상태, "수플렉스", 중심대상=적)
    assert any(x["이름"] == "홀딩" for x in 적["상태이상"])
    적["현재HP"] = 1
    시작 = len(상태["전투상태"]["로그"])
    gf.턴_넘기기(상태)
    assert not 적["생존"]
    assert _쓰러진_뒤_행동(상태, 적["이름"], 시작) == []
    assert 상태["전투상태"]["종료"] is None  # 다른 고블린이 남아 전투는 이어진다


def test_살의의_파동_차례_시작_피해로_쓰러진_몬스터는_행동하지_않는다(monkeypatch):
    rng.시드(1)
    상태 = support.새게임([("", "귀검사")])
    support.성장(상태, 상태["파티"]["파티원"][0], 8, 전직="아수라")
    gf.파티_최대치로_회복(상태)
    gf.전투_시작(상태, ["고블린", "고블린"], 레벨=1, 차수=1)
    support.반응_처리(상태)
    _내_차례까지(상태, "귀검사")
    gf.아군_스킬사용(상태, "살의의 파동")
    적 = [e for e in gf.적_목록(상태) if e["생존"]]
    for e in 적:
        e["현재HP"] = 1
    support.주사위고정(monkeypatch, 1)  # 내성 실패
    시작 = len(상태["전투상태"]["로그"])
    gf.턴_넘기기(상태)
    for e in 적:
        if not e["생존"]:
            assert _쓰러진_뒤_행동(상태, e["이름"], 시작) == []


def test_자동전투_중_반격으로_쓰러진_아군은_남은_공격을_하지_않는다():
    rng.시드(3)
    상태 = support.새게임([("", "격투가"), ("", "프리스트")])
    for c in 상태["파티"]["파티원"]:
        전직 = "스트리트 파이터" if c["직업"] == "격투가" else "크루세이더"
        support.성장(상태, c, 8, 전직=전직)
    gf.파티_최대치로_회복(상태)
    gf.전투_시작(상태, ["오라헌터 시우스"], 레벨=8, 차수=2)
    support.반응_처리(상태)
    p = _내_차례까지(상태, "격투가")
    p["현재HP"] = 1
    적 = gf.적_목록(상태)[0]
    적["현재HP"] = 적["최대HP"] = 999
    적["버프"].append({"이름": "전기 방벽", "지속턴": 5})
    시작 = len(상태["전투상태"]["로그"])
    gf.자동전투_한_턴(상태)
    assert not p["생존"]
    공격들 = [
        x
        for x in 상태["전투상태"]["로그"][시작:]
        if x.get("공격자") == p["이름"] and x.get("종류") == "일반공격"
    ]
    assert len(공격들) == 1  # 반격으로 쓰러진 첫 공격 하나뿐


def test_차례_끝_지속피해로_쓰러진_몬스터의_턴종료_특성은_발동하지_않는다():
    rng.시드(3)
    상태 = support.새게임([("", "귀검사")])
    gf.전투_시작(상태, ["굴 구위시"], 레벨=10, 차수=2)
    support.반응_처리(상태)
    for p in 상태["전투상태"]["참가자"]:
        p["현재HP"] = p["최대HP"] = 999
    적 = gf.적_목록(상태)[0]
    적["현재HP"] = 1
    적["상태이상"].append({"이름": "중독", "지속턴": 3})
    시작 = len(상태["전투상태"]["로그"])
    for _ in range(3):
        if gf.전투_종료됨(상태):
            break
        gf.턴_넘기기(상태)
    assert not 적["생존"]
    assert _쓰러진_뒤_행동(상태, 적["이름"], 시작) == []
