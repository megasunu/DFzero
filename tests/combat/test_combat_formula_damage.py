def test_수식_평가_문법(monkeypatch):
    support.주사위고정(monkeypatch, 3)
    ctx = {
        "차수": 2,
        "보정치": 4,
        "주문시전보정치": 1,
        "추가공격": 1,
        "레벨": 5,
        "무기공격력": "1d6",
        "능력치": {"민첩": 14, "건강": "?"},
    }
    assert formula.수식_평가(7, ctx) == 7
    assert formula.수식_평가("2차수+보정치", ctx) == 8  # 숫자 뒤 키워드는 곱셈
    assert formula.수식_평가("(차수)d8+주문시전보정치", ctx) == 3 * 2 + 1
    assert (
        formula.수식_평가("민첩보정치+건강보정치", ctx) == 2 + 0
    )  # 숫자 아닌 능력치는 10 취급
    assert formula.수식_평가("보정공격력x2", ctx) == (3 + 4) * 2
    assert formula.수식_평가("무기공격력+추가공격+레벨", ctx) == 3 + 1 + 5
    assert formula.수식_평가("(차수+1)d6÷2", ctx) == 3 * 3 / 2
    # 치명타: 주사위 개수 x (1 + 치명타주사위), 고정 값은 1회분
    assert formula.수식_평가("1d6", ctx, 치명타=True) == 2 * 3
    assert formula.수식_평가("3d10+5", ctx, 치명타=True) == 6 * 3 + 5
    assert formula.수식_평가("3d10+5", ctx, 치명타=0) == 3 * 3 + 5  # 0이면 그대로
    assert (
        formula.수식_평가("(차수)d8", ctx, 치명타=2) == 2 * 3 * 3
    )  # 무기 없으면 NdM에
    # 무기 주사위가 있으면 치명타 주사위는 무기 주사위에만: 1d6 -> 3d6, 2d8 그대로
    assert (
        formula.수식_평가(
            "보정공격력+(대상상태이상수)d8", dict(ctx, 대상상태이상수=2), 치명타=2
        )
        == 3 * 3 + 4 + 2 * 3
    )
    assert (
        formula.수식_평가("(대상상태이상수)d8+1", ctx, 치명타=True) == 1
    )  # 0개 항은 0
    assert formula.수식_평가("(0)d6+1", ctx) == 1  # 개수 0이면 0
    # 일발화약성의 대상 상태이상 종류 수(skill_attack이 컨텍스트에 넣는다)
    assert formula.수식_평가("(대상상태이상수)d8", dict(ctx, 대상상태이상수=2)) == 3 * 2
    assert formula.수식_평가("(대상상태이상수)d8+1", ctx) == 1  # 없으면 0개
    with pytest.raises(ValueError, match="처리할 수 없는"):
        formula.수식_평가("미지의값", ctx)


def test_수식_평균은_주사위를_굴리지_않고_기대값으로(monkeypatch):
    # 전력전투가 스킬의 기대 피해를 비교할 때 쓴다 - 무작위 수를 쓰지 않아야 전투 순서가 안 바뀐다
    monkeypatch.setattr(
        rng.주사위, "randint", lambda a, b: pytest.fail("굴리면 안 된다")
    )
    평 = formula.수식_평가
    assert 평("2d6+3", {}, 평균=True) == 2 * 3.5 + 3
    assert 평("(차수+1)d6÷2", {"차수": 2}, 평균=True) == 3 * 3.5 / 2
    assert 평("보정공격력", {"무기공격력": "1d8", "보정치": 2}, 평균=True) == 4.5 + 2
    assert 평("0d8+1", {}, 평균=True) == 1
    assert 평("3d10+5", {}, 평균=True, 치명타=True) == 6 * 5.5 + 5


