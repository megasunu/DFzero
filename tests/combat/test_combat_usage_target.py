def test_판정과_대상_조회는_조건부효과의_무기주사위를_굴리지_않는다(전장):
    """#770 - 조건부효과의 "데미지보너스"(보정공격력)는 무기 주사위를 굴린다. 사용 가능 판정과 대상 종류 조회는
    보너스가 필요 없으므로 굴리지 않는다 - 화면에서 스킬을 살펴보기만 해도 난수 흐름이 밀리면 안 된다."""
    상태, 전투상태, _, 아군 = 전장
    p = 아군[0]
    flow.턴_시작_처리(전투상태, p)
    이름 = _조건부_시험스킬(상태, 데미지보너스="보정공격력", 명중보너스=1)
    조건부효과 = 상태["스킬데이터모음"][이름]["조건부효과"]
    전 = rng.상태()
    gf.스킬_사용_가능여부(상태, p, 이름)
    gf.스킬_실제_타겟(상태, 상태["스킬데이터모음"][이름])
    덮어쓰기 = ss.조건부효과_평가(전투상태, p, None, 조건부효과, 보너스계산=False)
    assert rng.상태() == 전
    assert 덮어쓰기["데미지보너스"] == 0 and 덮어쓰기["명중보너스"] == 0
    # 보너스를 구하면 실제로 굴린다 - 위 검사가 헛돌지 않는다는 확인
    보너스 = ss.조건부효과_평가(전투상태, p, None, 조건부효과)
    assert rng.상태() != 전
    assert 보너스["데미지보너스"] > 0 and 보너스["명중보너스"] == 1


def test_몬스터에는_MP_칸이_없다(전장):
    _, 전투상태, 적, 아군 = 전장
    assert all("현재MP" not in p for p in 적) and all("현재MP" in p for p in 아군)
    assert all("최대MP" not in d for d in gf.몬스터목록.values())
    p = 적[0]
    flow.턴_시작_처리(전투상태, p)
    # MP가 드는 스킬은 보유 0으로 보고 거부한다
    가능, 사유 = ss.사용_가능여부(전투상태, p, support.시험_스킬(MP소모=1))
    assert not 가능 and "MP가 부족" in 사유 and "보유 0" in 사유
    # MP가 안 드는 스킬은 MP 칸 없이도 쓰고 소비해도 MP 칸이 생기지 않는다
    assert ss.사용_가능여부(전투상태, p, support.시험_스킬()) == (True, None)
    ss.자원_소비_처리(전투상태, p, support.시험_스킬())
    assert "현재MP" not in p


def test_사용가능여부_행동자원과_쇼타임(전장):
    _, 전투상태, _, 아군 = 전장
    p = 아군[0]
    p["행동자원"] = {"일반행동": 0, "보조행동": 1, "반응행동": 0}
    assert (
        "'일반행동'이(가) 남아있지 않다"
        in ss.사용_가능여부(전투상태, p, support.시험_스킬())[1]
    )
    assert ss.사용_가능여부(전투상태, p, support.시험_스킬(행동="보조행동"))[0]
    assert not ss.사용_가능여부(
        전투상태, p, support.시험_스킬(행동=["일반행동", "보조행동"])
    )[0]
    마법 = support.시험_스킬(타입=["스킬", "하급마법"])
    p["기타행동"] = {"쇼타임행동": 1}
    assert ss.사용_가능여부(전투상태, p, 마법)[0]  # 쇼타임행동이 일반행동을 대신
    assert not ss.사용_가능여부(전투상태, p, support.시험_스킬())[
        0
    ]  # 마법이 아니면 대신 못 함
    assert ss.사용_가능여부(전투상태, p, support.시험_스킬(행동="전체소모"))[0]
    p["행동자원"] = {"일반행동": 0, "보조행동": 0, "반응행동": 0}
    assert (
        "하나도" in ss.사용_가능여부(전투상태, p, support.시험_스킬(행동="전체소모"))[1]
    )


def test_행동지불_선택지와_고른_수단으로_소비(전장):
    _, 전투상태, _, 아군 = 전장
    p = 아군[0]
    하급 = support.시험_스킬(타입=["스킬", "하급마법"])
    p["기타행동"] = {"쇼타임행동": 1}
    p["행동자원"] = {"일반행동": 1, "보조행동": 1, "반응행동": 0}
    assert ss.일반행동_지불수단_목록(전투상태, p, 하급) == ["쇼타임행동", "일반행동"]
    assert (
        ss.일반행동_지불수단_목록(전투상태, p, support.시험_스킬(행동="보조행동")) == []
    )
    ss.자원_소비_처리(전투상태, p, 하급, 행동지불="일반행동")
    assert (p["행동자원"]["일반행동"], p["행동자원"]["보조행동"]) == (0, 1)
    assert p["기타행동"]["쇼타임행동"] == 1
    # 낼 수 없는 수단을 고르면 스킬_실행이 거부한다(보조행동으로 일반행동을 대신 내는 길은 없다)
    with pytest.raises(ValueError, match="쓸 수 없다"):
        ss.스킬_실행(
            전투상태,
            p,
            "시험",
            support.시험_스킬(
                분류="버프스킬", 타겟="자신", 명중률="자동", 타입=["스킬", "하급마법"]
            ),
            행동지불="보조행동",
        )


