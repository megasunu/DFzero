def test_사용가능여부_각_사유(전장):
    _, 전투상태, _, 아군 = 전장
    p = 아군[0]
    flow.턴_시작_처리(전투상태, p)
    assert ss.사용_가능여부(전투상태, p, support.시험_스킬()) == (True, None)
    assert (
        "MP가 부족" in ss.사용_가능여부(전투상태, p, support.시험_스킬(MP소모=999))[1]
    )
    assert ss.사용_가능여부(
        전투상태, p, support.시험_스킬(MP소모=999), MP소모오버라이드=0
    )[0]
    assert (
        "자원이 부족"
        in ss.사용_가능여부(전투상태, p, support.시험_스킬(자원소모={"탄약": 1}))[1]
    )
    assert ss.사용_가능여부(
        전투상태, p, support.시험_스킬(자원소모={"탄약": 1}), 자원소모오버라이드={}
    )[0]
    p["이번턴_스킬사용횟수"] = {"시험": 1}
    assert (
        "턴당사용제한"
        in ss.사용_가능여부(전투상태, p, support.시험_스킬(턴당사용제한=1))[1]
    )
    p["전투당_스킬사용횟수"] = {"시험": 2}
    assert (
        "전투당횟수"
        in ss.사용_가능여부(전투상태, p, support.시험_스킬(전투당횟수="1+차수"))[1]
    )
    p["원본"]["횟수제한스킬"]["휴식제한스킬"]["시험"] = 0
    assert "휴식당" in ss.사용_가능여부(전투상태, p, support.시험_스킬(휴식당횟수=2))[1]
    assert ss.휴식_남은횟수(전투상태, p, support.시험_스킬(휴식당횟수=2)) == (0, 2)
    assert ss.휴식_남은횟수(전투상태, p, support.시험_스킬()) is None


def _조건부_시험스킬(상태, **kw):
    """조건이 늘 맞는(HP 비율 100% 이하) 조건부효과 하나를 단 시험 스킬을 스킬데이터모음에 넣는다."""
    상태["스킬데이터모음"]["시험_조건부"] = support.시험_스킬(
        조건부효과=[{"조건": "HP비율이하", "조건값": 1.0, **kw}]
    )
    return "시험_조건부"


def test_사용가능여부는_조건부효과의_MP소모를_실행처럼_본다(전장):
    """#770 - 실행(스킬_실행)은 조건부효과의 "MP소모"로 덮어써서 내는데, 판정(화면·자동전투)도 같은 값을 본다."""
