def test_효과_아군버프_해제(전장):
    _, 전투상태, 적, 아군 = 전장
    ss.효과_적용(
        전투상태,
        아군[0],
        적[0],
        [{"종류": "아군버프", "이름": "속도증가", "타겟": "자신", "지속턴": 2}],
    )
    assert [b["이름"] for b in 아군[0]["버프"]] == ["속도증가"]
    for 이름 in ("속도증가", "근력증가", "류심자세"):
        ss.이름있는효과_부여(전투상태, 적[0], 이름, 1)
    ss.효과_적용(
        전투상태,
        아군[0],
        적[0],
        [{"종류": "버프해제", "대상": "지정", "이름": "근력증가"}],
    )
    assert sorted(b["이름"] for b in 적[0]["버프"]) == ["류심자세", "속도증가"]
    ss.효과_적용(전투상태, 아군[0], 적[0], [{"종류": "버프해제", "해제개수": 5}])
    assert [b["이름"] for b in 적[0]["버프"]] == [
        "류심자세"
    ]  # 자원류 효과는 해제 대상 아님
    ss.이름있는효과_부여(전투상태, 아군[1], next(iter(디버프목록)), 1)
    ss.효과_적용(전투상태, 아군[0], 아군[1], [{"종류": "디버프해제"}])
    assert 아군[1]["디버프"] == []


def test_효과_범위분배(전장):
    _, 전투상태, 적, 아군 = 전장
    hp = [p["현재HP"] for p in 적]
    로그 = ss.효과_적용(
        전투상태,
        아군[0],
        적[1],
        [{"종류": "범위분배", "대상": "양옆1체씩", "피해량": "주대상피해÷2"}],
        주대상피해=4,
    )
    assert (
        len(로그) == 2 and 적[0]["현재HP"] == hp[0] - 2 and 적[2]["현재HP"] == hp[2] - 2
    )
    적[2]["생존"] = False
    로그 = ss.효과_적용(
        전투상태,
        아군[0],
        적[1],
        [{"종류": "범위분배", "대상": "양옆1체씩", "피해량": 0.5}],
        주대상피해=2,
    )
    assert len(로그) == 1  # 죽은 이웃은 건너뛴다
    assert ss.효과_적용(
        전투상태,
        아군[0],
        적[0],
        [{"종류": "범위분배", "대상": "양옆1체씩", "피해량": None}],
    ) == [f"{적[1]['이름']}에게 범위분배 피해 0"]
    assert (
        "지원하지 않는다"
        in ss.효과_적용(
            전투상태, 아군[0], 적[0], [{"종류": "범위분배", "대상": "전체"}]
        )[0]
    )


def test_조건_확인(전장):
    _, 전투상태, 적, 아군 = 전장
    p = 아군[0]
    assert not ss.조건_확인(전투상태, p, None, "적상태", "공중에뜸")
    ss.상태이상_부여(전투상태, 적[0], "공중에뜸", 1, None)
    assert ss.조건_확인(전투상태, p, 적[0], "적상태", "공중에뜸")
    assert not ss.조건_확인(전투상태, p, None, "아군상태", "속도증가")
    ss.이름있는효과_부여(전투상태, p, "속도증가", 1)
    assert ss.조건_확인(전투상태, p, None, "아군상태", "속도증가")
    p["현재HP"] = 1
    assert ss.조건_확인(전투상태, p, None, "HP비율이하", 0.5)
    assert not ss.조건_확인(전투상태, p, None, "특성보유", "없는특성")
    assert not ss.조건_확인(전투상태, p, None, "모르는조건", 1)
