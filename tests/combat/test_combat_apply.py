def test_샹들리에는_상시_공중에뜸으로_판정되고_공중에뜸과_넘어짐에_면역이다(전장):
    # 카겔/봄 카겔 특성: 상시 공중에뜸 상태로 판정되지만 공중에뜸/넘어짐
    # 면역이라 행동불가는 없다. 공중에뜸 대상을 보는 조건(홀리 스매쉬 추가 피해, 공중연속베기,
    # 특성의 "적상태" 조건부효과)은 모두 충족된다.
    _, 전투상태, 적, 아군 = 전장
    전투상태["특성정의"]["시험:공중적"] = {
        "분류": "몬스터특성",
        "발동조건": None,
        "효과": [],
        "조건부효과": {
            "발동조건": "적상태",
            "조건값": "공중에뜸",
            "효과": [{"변동대상": "명중보너스", "변동값": 2}],
        },
        "설명": "",
    }
    아군[0]["원본"] = {**아군[0]["원본"], "특성": ["시험:공중적"]}
    assert traits.특성_수치(전투상태, 아군[0], "명중보너스") == 0

    적[0]["원본"] = {**적[0]["원본"], "특성": ["샹들리에"]}
    for 이름 in ("공중에뜸", "넘어짐"):
        assert status.상태이상_면역(전투상태, 적[0], 이름)
        assert not status.상태이상_면역(전투상태, 적[1], 이름)
    assert status.상태이상_판정(전투상태, 적[0], "공중에뜸")
    assert not status.상태이상_판정(전투상태, 적[0], "넘어짐")
    assert not status.상태이상_판정(전투상태, 적[1], "공중에뜸")
    assert 적[0]["상태이상"] == []  # 실제로 걸린 것은 아니다 - 행동불가 없음
    assert not status.상태이상_플래그(전투상태, 적[0], "행동불가")

    assert skill_target.조건_확인(전투상태, 아군[0], 적[0], "적상태", "공중에뜸")
    assert not skill_target.조건_확인(전투상태, 아군[0], 적[1], "적상태", "공중에뜸")
    assert "공중에뜸" in reactions.상태이상_이름목록(전투상태, 적[0])
    assert "공중에뜸" not in reactions.상태이상_이름목록(전투상태, 적[1])
    assert traits.특성_수치(전투상태, 아군[0], "명중보너스") == 2

    # 공중에뜸을 "해제"해도(홀리 스매쉬) 상시 판정은 남는다
    ss.상태이상_해제(전투상태, 적[0], "공중에뜸")
    assert status.상태이상_판정(전투상태, 적[0], "공중에뜸")


