    보정 = stats.유효_능력치_보정치(전투상태, 대상, "건강")
    assert stats.내성굴림_보정치(전투상태, 대상, "건강") == 보정
    resources.몬스터_버프_부여(전투상태, 대상, 이름, 3)
    assert stats.내성굴림_보정치(전투상태, 대상, "건강") == 보정 + 차이
    # 보너스가 없으면 DC에 꼭 맞는 눈 - 내성증가면 성공, 내성감소면 실패
