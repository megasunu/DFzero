def _내성불리점_상태(전투상태):
    """효과 "내성굴림불리점"을 가진 시험 상태이상 이름 - 저주는 모든 능력치 -1이다."""
    전투상태["상태이상정의"] = {
        **전투상태["상태이상정의"],
        "시험불리점": {"분류": "약화CC", "효과": {"내성굴림불리점": True}},
    }
    return "시험불리점"


def test_대상_내성굴림은_보정치와_내성굴림불리점_상태를_쓴다(전장, monkeypatch):
    _, 전투상태, 적, _ = 전장
    대상 = 적[0]
    보정 = stats.내성굴림_보정치(전투상태, 대상, "건강")
    굴림 = iter([15, 4])
    monkeypatch.setattr(rng.주사위, "randint", lambda a, b: next(굴림))
    assert stats.대상_내성굴림(전투상태, 대상, "건강", 10) == (
        15 + 보정 >= 10,
        15 + 보정,
        보정,
    )
    assert stats.내성굴림_이점불리(전투상태, 대상) == (0, 0)
    ss.상태이상_부여(전투상태, 대상, _내성불리점_상태(전투상태), 3, None)
    assert stats.내성굴림_이점불리(전투상태, 대상) == (0, 1)
    굴림 = iter([15, 4])  # 불리점 - 두 번 굴려 낮은 쪽
    assert stats.대상_내성굴림(전투상태, 대상, "건강", 10)[1] == 4 + 보정


def test_주스탯_내성은_이점_약점스탯_내성은_불리점(전장):
    # 주스탯 내성굴림 이점, 약점스탯 불리점(약점제거면 약점이 아니다), 보조스탯은 없음
    _, 전투상태, 적, 아군 = 전장
    p = 아군[0]
    c = p["원본"]
    assert stats.내성굴림_이점불리(전투상태, p) == (0, 0)  # 몬스터처럼 스탯 지정 없음
    assert stats.내성굴림_이점불리(전투상태, p, 내성스탯=c["주스탯"]) == (1, 0)
    assert stats.내성굴림_이점불리(전투상태, p, 내성스탯=c["보조스탯"]) == (0, 0)
    assert stats.내성굴림_이점불리(전투상태, p, 내성스탯=c["약점스탯"]) == (0, 1)
    c["보유특성"].append("약점제거")
    assert stats.내성굴림_이점불리(전투상태, p, 내성스탯=c["약점스탯"]) == (0, 0)
    assert stats.내성굴림_이점불리(전투상태, 적[0], 내성스탯="근력") == (
        0,
        0,
    )  # 몬스터는 없다
    ss.상태이상_부여(
        전투상태, p, _내성불리점_상태(전투상태), 3, None
    )  # 주스탯 이점 1 + 불리점 1 = 상쇄
    assert stats.내성굴림_이점불리(전투상태, p, 내성스탯=c["주스탯"]) == (1, 1)


def test_명중_이점_불리점은_개수로_합산한다(전장, monkeypatch):
    # 이점 2(대상 회피불리점 + 공격자 버프 명중이점) vs 불리점 1(공격자 명중불리점) - 이점
    _, 전투상태, 적, 아군 = 전장
    공격자, 대상 = 아군[0], 적[0]
    monkeypatch.setattr(
        stats,
        "버프_효과원소목록",
        lambda 전, 참, 키: [{}] if (참 is 공격자 and 키 == "명중이점") else [],
    )
    플래그 = {(id(대상), "회피불리점"), (id(공격자), "명중불리점")}
    monkeypatch.setattr(
        status, "상태이상_플래그", lambda 전, 참, 키: (id(참), 키) in 플래그
    )
    굴림 = iter([3, 17])
    monkeypatch.setattr(rng.주사위, "randint", lambda a, b: next(굴림))
    판정 = hit.명중_판정_계산(전투상태, 공격자, 대상, "보정명중률")
    assert 판정["자연눈"] == 17  # 두 번 굴려 높은 쪽


@pytest.mark.parametrize("이름, 차이", [("내성증가", 1), ("내성감소", -1)])
def test_내성증가_내성감소는_모든_내성굴림에_더해진다(전장, monkeypatch, 이름, 차이):
    # 변동대상 "내성보너스" - 스킬 효과와 몬스터/특성 쪽 상태이상 내성 모두
    _, 전투상태, 적, 아군 = 전장
