    로그 = ss.효과_적용(전투상태, 아군[0], 대상, 효과)[0]
    assert ("내성 성공!" if 차이 > 0 else "내성 실패!") in 로그
    대상["상태이상"] = []
    traits.상태이상_효과_적용(
        전투상태,
        아군[0],
        대상,
        {"종류": "상태이상", "이름": "기절", "내성": "건강", "난이도": "15"},
        "시험",
    )
    assert bool(대상["상태이상"]) == (차이 < 0)


