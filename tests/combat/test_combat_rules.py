@pytest.mark.parametrize("타겟", ["적단일", "아군단일", "적3체"])
def test_대상이_잘못되면_스킬_비용을_쓰지_않는다(전장, 타겟):
    # B7: 자원_소비_처리가 타겟_확장(대상 검증)보다 먼저라, 대상 없이 부르면 오류가
    # 나도 MP/행동/횟수가 이미 빠져 있던 버그.
    _, 전투상태, 적, 아군 = 전장
    p = 아군[0]
    flow.턴_시작_처리(전투상태, p)
    스킬 = support.시험_스킬(타겟=타겟, MP소모=5, 휴식당횟수=3)
    전 = (dict(p["행동자원"]), p["현재MP"], dict(p.get("이번턴_스킬사용횟수", {})))
    with pytest.raises(ValueError, match="지정해야"):
        ss.스킬_실행(전투상태, p, "시험", 스킬)
    ss.상태이상_부여(전투상태, 적[0], "은신", 3, None)
    if 타겟 == "적단일":
        with pytest.raises(ValueError, match="지정 불가"):
            ss.스킬_실행(전투상태, p, "시험", 스킬, 중심대상=적[0])
    후 = (dict(p["행동자원"]), p["현재MP"], dict(p.get("이번턴_스킬사용횟수", {})))
    assert 후 == 전
    assert "시험" not in p["원본"]["횟수제한스킬"]["휴식제한스킬"]


def test_쓰러진_대상은_지정할_수_없다(전장):
    # B12: 로직 계층이 죽은 대상을 막지 않아, 죽은 적을 일반공격하거나 죽은 아군에게
    # 회복을 걸면 "현재HP > 0인데 생존 False" 같은 모순 상태가 됐다.
    상태, 전투상태, 적, 아군 = 전장
    p = 아군[0]
    flow.턴_시작_처리(전투상태, p)
    전투상태["현재턴"] = 전투상태["참가자"].index(p)
    적[0]["현재HP"], 적[0]["생존"] = 0, False
    아군[1]["현재HP"], 아군[1]["생존"] = 0, False
    with pytest.raises(ValueError, match="쓰러져"):
        gf.아군_일반공격(상태, 적[0])
    assert p["행동자원"]["일반행동"] == 1
    for 타겟, 대상 in (("적단일", 적[0]), ("아군단일", 아군[1])):
        with pytest.raises(ValueError, match="쓰러져"):
            ss.스킬_실행(
                전투상태, p, "시험", support.시험_스킬(타겟=타겟), 중심대상=대상
            )
    assert p["행동자원"]["일반행동"] == 1
    assert (아군[1]["현재HP"], 아군[1]["생존"]) == (0, False)


