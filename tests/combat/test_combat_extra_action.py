def test_수식은_쓰지_않는_일반공격_보정치를_계산하지_않는다():
    """기본_컨텍스트의 "보정치"(평타스탯 중 최대)는 수식에 보정치/보정공격력/무기공격력이 있을 때만 계산한다.
    평타스탯이 빈 참가자도 주문시전보정치·능력치 보정치만 쓰는 수식은 계산되고, 보정치를 쓰는 수식에서만 멈춘다."""
    전투상태, _, 아군 = support.시험_전투(["고블린"])
    p = 아군[0]
    p["원본"]["평타스탯"] = []
    컨텍스트 = stats.기본_컨텍스트(전투상태, p)
    주문 = stats.주문시전_보정치(전투상태, p)
    근력 = stats.유효_능력치_보정치(전투상태, p, "근력")
    assert formula.수식_평가("3+주문시전보정치", 컨텍스트) == 3 + 주문
    assert formula.수식_평가("3+근력보정치", 컨텍스트) == 3 + 근력
    with pytest.raises(ValueError):
        formula.수식_평가("3+보정치", 컨텍스트)
    p["원본"]["평타스탯"] = ["근력"]
    assert formula.수식_평가("3+보정치", stats.기본_컨텍스트(전투상태, p)) == 3 + 근력


def test_특성_캐시는_특성과_장비가_바뀌면_다시_고른다():
    """특성 캐시: 보유특성·켜진특성·무기·방어구 세트 재질이 전투 중 바뀌어도 낡은 값을 돌려주지 않는다.
    특성마다 명중보너스를 2의 거듭제곱으로 두어 합으로 어느 특성이 골렸는지 본다."""
    traits.특성_캐시_비우기()
    정의모음 = {
        "상시": {"효과": {"변동대상": "명중보너스", "변동값": 1}},
        "토글": {"토글": True, "효과": {"변동대상": "명중보너스", "변동값": 2}},
        "소검": {"무기조건": "소검", "효과": {"변동대상": "명중보너스", "변동값": 4}},
        "판금": {"방어구조건": "판금", "효과": {"변동대상": "명중보너스", "변동값": 8}},
        "강화": {"분류": "강화특성", "효과": {"변동대상": "명중보너스", "변동값": 16}},
        "트리거": {
            "발동조건": "피격시",
            "효과": {"변동대상": "명중보너스", "변동값": 32},
        },
    }
    전투상태 = {"캐릭터특성정의": 정의모음, "참가자": []}
    원본 = {"보유특성": ["상시", "강화", "트리거"], "켜진특성": []}
    참가자 = {"진영": "아군", "원본": 원본, "장비데이터": {}, "버프": [], "디버프": []}

    def 합():
        return traits.특성_수치(전투상태, 참가자, "명중보너스")

    assert 합() == 1
    assert 합() == 1  # 캐시에서
    원본["보유특성"].extend(["토글", "소검", "판금"])  # 같은 목록을 그 자리에서 바꿔도
    assert 합() == 1
    원본["켜진특성"].append("토글")
    assert 합() == 1 + 2
    참가자["장비데이터"]["무기"] = {"타입": ["소검", "마법봉인"]}
    assert 합() == 1 + 2 + 4
    for 부위 in ("상의", "하의", "어깨", "벨트", "신발"):
        참가자["장비데이터"][부위] = {"재질": "판금"}
    assert 합() == 1 + 2 + 4 + 8
    참가자["장비데이터"]["신발"] = {"재질": "가죽"}
    del 참가자["장비데이터"]["무기"]
    원본["보유특성"].remove("상시")
    assert 합() == 2
    # 같은 특성 이름이라도 다른 정의모음 객체면 그 모음의 정의를 쓴다
    다른모음 = {
        k: {**v, "효과": {**v["효과"], "변동값": 100}} for k, v in 정의모음.items()
    }
    다른전투 = {"캐릭터특성정의": 다른모음, "참가자": []}
    assert traits.특성_수치(다른전투, 참가자, "명중보너스") == 100


def test_특성_캐시는_크기가_넘쳐도_맞는_값을_준다(monkeypatch):
    traits.특성_캐시_비우기()
    monkeypatch.setattr(traits, "_정의목록_캐시_최대", 2)
    정의모음 = {
        f"특성{i}": {"효과": {"변동대상": "명중보너스", "변동값": i + 1}}
        for i in range(3)
    }
    전투상태 = {"캐릭터특성정의": 정의모음, "참가자": []}
    for _ in range(2):
        for i in range(3):
            참가자 = {
                "진영": "아군",
                "원본": {"보유특성": [f"특성{i}"]},
                "장비데이터": {},
                "버프": [],
                "디버프": [],
            }
            assert traits.특성_수치(전투상태, 참가자, "명중보너스") == i + 1
