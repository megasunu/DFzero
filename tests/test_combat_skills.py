def _스킬_소유직업():
    소유 = {}
    for 직업, 정보 in gf.직업_레지스트리.items():
        for 이름 in 정보["스킬목록"]:
            소유[이름] = 직업
    for 직업, 전직들 in gf.전직_레지스트리.items():
        for 정보 in 전직들.values():
            for 이름 in 정보["스킬목록"]:
                소유[이름] = 직업
    return 소유


