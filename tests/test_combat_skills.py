def 정리(값, 깊이=0):
    """골든용 직렬화: 참가자 참조는 이름으로, 순환/깊은 구조는 잘라낸다."""
    if 깊이 > 8:
        return "..."
    if isinstance(값, dict):
        if "진영" in 값 and "원본" in 값:
            return f"<{값['이름']}>"
        return {str(k): 정리(v, 깊이 + 1) for k, v in 값.items()}
    if isinstance(값, (list, tuple, set)):
        return [정리(v, 깊이 + 1) for v in 값]
    if isinstance(값, (str, int, float, bool)) or 값 is None:
        return 값
    return str(값)


def 참가자_요약(p):
    요약 = {
        "이름": p["이름"],
        "진영": p["진영"],
        "생존": p["생존"],
        "HP": p["현재HP"],
    }
    if "현재MP" in p:  # 몬스터는 MP 칸이 없다
        요약["MP"] = p["현재MP"]
    return 요약 | {
        "버프": 정리(p["버프"]),
        "디버프": 정리(p["디버프"]),
        "상태이상": 정리(p["상태이상"]),
        "행동자원": dict(p["행동자원"]),
        "기타행동": dict(p.get("기타행동", {})),
        "보유자원": dict(p.get("보유자원") or {}),
        "버프스택": dict(p.get("버프스택") or {}),
    }


def 전장_준비(직업, 시드):
    """직업을 선두로 한 레벨 10(전직) 파티와 적 4체의 전투를 연다."""
    random.seed(시드)
    나머지 = [j for j in 전직 if j != 직업][:3]
    상태 = support.새게임([("", 직업)] + [("", j) for j in 나머지])
    for c in 상태["파티"]["파티원"]:
        support.성장(상태, c, 10, 전직=전직[c["직업"]], 스킬습득=True)
    gf.파티_최대치로_회복(상태)
    gf.전투_시작(상태, 적_구성, 레벨=6, 차수=2)
    support.반응_처리(상태)
    return 상태


def 차례_주기(상태, 참가자):
    전투상태 = 상태["전투상태"]
    전투상태["현재턴"] = 전투상태["참가자"].index(참가자)
    flow.턴_시작_처리(전투상태, 참가자)


def 준비됨_적용(상태, 시전자, 표적):
    전투상태 = 상태["전투상태"]
    시전자["보유자원"].update({"탄약": 5, "수류탄": 5})
    for 이름 in ("류심자세", "강화류심"):
        ss.이름있는효과_부여(전투상태, 시전자, 이름, 3)
    for 특성 in ("스타일리쉬", "장탄공급"):
        if 특성 not in 시전자["원본"]["보유특성"]:
            시전자["원본"]["보유특성"].append(특성)
    ss.상태이상_부여(전투상태, 표적, "공중에뜸", 2, None)
    # 회복/해제 스킬이 할 일이 있게: 아군 하나를 다치게 하고, 적에게 버프/아군에게 디버프
    아군 = [p for p in 전투상태["참가자"] if p["진영"] == "아군"]
    아군[1]["현재HP"] = max(1, 아군[1]["현재HP"] // 3)
    ss.이름있는효과_부여(전투상태, 표적, "속도증가", 1)
    ss.이름있는효과_부여(전투상태, 아군[1], next(iter(디버프목록)), 1)


def 스킬_시나리오(스킬, 준비):
    직업 = 스킬_소유[스킬]
    데이터 = 스킬데이터[스킬]
    상태 = 전장_준비(직업, 시드=11)
    전투상태 = 상태["전투상태"]
    시전자 = next(
        p for p in 전투상태["참가자"] if p["원본"] is 상태["파티"]["파티원"][0]
    )
    if 스킬 not in 시전자["원본"]["보유스킬"]:
        시전자["원본"]["보유스킬"].append(스킬)
    적들 = [p for p in 전투상태["참가자"] if p["진영"] == "적" and p["생존"]]
    아군들 = [p for p in 전투상태["참가자"] if p["진영"] == "아군"]
    차례_주기(상태, 시전자)
    if 준비:
        준비됨_적용(상태, 시전자, 적들[0])

    타겟 = str(데이터.get("타겟"))
    중심 = (
        적들[0]
        if 타겟.startswith("적")
        else (아군들[1] if 타겟 == "아군단일" else 시전자)
    )
    지정 = [적들[0], 적들[1], 적들[0]] if 타겟 == "적반복지정" else None

    기록 = {
        "사용가능": 정리(ss.사용_가능여부(전투상태, 시전자, 데이터)),
        "휴식남은": 정리(ss.휴식_남은횟수(전투상태, 시전자, 데이터)),
    }
    로그시작 = len(전투상태["로그"])
    try:
        기록["결과"] = 정리(
            gf.아군_스킬사용(상태, 스킬, 중심대상=중심, 지정대상목록=지정)
        )
    except Exception as e:  # noqa: BLE001 - 예외도 현재 동작으로 기록한다
        기록["예외"] = f"{type(e).__name__}: {e}"
    기록["로그"] = 정리(전투상태["로그"][로그시작:])
    기록["직후"] = [참가자_요약(p) for p in 전투상태["참가자"]]
    기록["재사용가능"] = 정리(ss.사용_가능여부(전투상태, 시전자, 데이터))

    로그시작 = len(전투상태["로그"])
    for _ in range(2 * len(전투상태["참가자"])):
        if gf.전투_종료됨(상태):
            break
        gf.턴_넘기기(상태)  # 아군은 행동 없이 넘긴다 - 몬스터 턴과 지속효과만 진행
    기록["이후로그"] = 정리(전투상태["로그"][로그시작:])
    기록["이후"] = [참가자_요약(p) for p in 전투상태["참가자"]]
    기록["종료"] = 전투상태["종료"]
    return 기록


@pytest.mark.parametrize("직업", list(전직))
def test_스킬_전수(직업, golden):
    결과 = {}
    for 스킬, 소유 in 스킬_소유.items():
        if 소유 != 직업 or 스킬데이터[스킬]["분류"] == "반응스킬":
            continue  # 반응스킬은 직접 쓰지 않는다 - test_combat_effects 반응 전투
        결과[스킬] = {
            "기본": 스킬_시나리오(스킬, 준비=False),
            "준비됨": 스킬_시나리오(스킬, 준비=True),
        }
    golden(f"combat_skills_{직업}", 결과)


