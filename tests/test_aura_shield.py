"""마법사 특성 "오라 실드"(#412, 2026-11-13 사용자 결정 - 기본 켜짐).

레벨 3에 특성과 함께 전환스킬 "오라 실드"를 얻고, 특성은 켜진 채로 시작한다. 켜져 있으면 적의 공격·능력
피해를 주문시전보정치만큼 줄이고 줄인 만큼 MP를 쓴다(MP가 모자라면 모자란 만큼은 그대로 들어온다).
배틀메이지 강화오라실드면 MP를 쓰지 않고 근력·민첩 보정치만큼 더 줄인다. 지속피해는 줄이지 않는다."""

import json

import pytest

from game.system import rng
import gameflow as gf
from game.system import skill_system as ss
from game.system.combat import damage, stats
from tests import support


def _마법사(레벨=3, 전직=None):
    rng.시드(11)
    상태 = support.새게임([("", "마법사"), ("", "귀검사")])
    c = 상태["파티"]["파티원"][0]
    support.성장(상태, c, 레벨, 전직=전직)
    return 상태, c


def _전투(상태, c):
    """위상 변화(피격 시 피해무효 반응)가 끼어들지 않게 빼고 고블린 하나와 전투를 연다."""
    if "위상 변화" in c["보유스킬"]:
        c["보유스킬"].remove("위상 변화")
    gf.전투_시작(상태, ["고블린"], 레벨=1, 차수=1)
    support.반응_처리(상태)
    전투상태 = 상태["전투상태"]
    m = next(p for p in 전투상태["참가자"] if p.get("원본") is c)
    적 = next(p for p in 전투상태["참가자"] if p["진영"] == "적")
    return 전투상태, m, 적


def _맞기(전투상태, m, 적, 피해, **옵션):
    """m이 적에게 피해를 받는다 - (HP 감소, MP 감소)."""
    m["현재HP"] = 500
    HP, MP = m["현재HP"], m["현재MP"]
    damage.피해_적용(전투상태, m, 피해, 공격자=적, **옵션)
    return HP - m["현재HP"], MP - m["현재MP"]


def _끈_피해(전투상태, m, 적, 피해, **옵션):
    """같은 피해를 오라 실드를 끈 채로 받았을 때의 HP 감소(방어구 방어력 등은 그대로)."""
    켜진 = m["원본"]["켜진특성"]
    m["원본"]["켜진특성"] = [n for n in 켜진 if n != "오라 실드"]
    try:
        return _맞기(전투상태, m, 적, 피해, **옵션)[0]
    finally:
        m["원본"]["켜진특성"] = 켜진


def _스킬(이름):
    return dict(gf.스킬데이터모음_생성()[이름], _이름=이름)


def test_레벨3_마법사는_오라실드_특성과_전환스킬을_얻고_켜진_채로_시작한다():
    _, c = _마법사(3)
    assert "오라 실드" in c["보유특성"]
    assert "오라 실드" in c["보유스킬"]
    assert c["켜진특성"] == ["오라 실드"]
    데이터 = gf.스킬데이터모음_생성()["오라 실드"]
    assert 데이터["분류"] == "전환스킬" and 데이터["전환특성"] == "오라 실드"


def test_레벨2_마법사는_아직_오라실드가_없다():
    _, c = _마법사(2)
    assert "오라 실드" not in c["보유특성"]
    assert "오라 실드" not in (c.get("켜진특성") or [])


def test_켜진_오라실드는_피해를_주문시전보정치만큼_줄이고_그만큼_MP를_쓴다():
    상태, c = _마법사(3)
    전투상태, m, 적 = _전투(상태, c)
    보정 = stats.주문시전_보정치(전투상태, m)
    assert 보정 > 0
    m["현재MP"] = 50
    기준 = _끈_피해(전투상태, m, 적, 30)
    HP감소, MP감소 = _맞기(전투상태, m, 적, 30)
    assert HP감소 == 기준 - 보정
    assert MP감소 == 보정
    assert any("오라 실드" in str(줄) for 줄 in 전투상태["로그"])


def test_MP가_모자라면_모자란_만큼_피해가_그대로_들어온다():
    상태, c = _마법사(3)
    전투상태, m, 적 = _전투(상태, c)
    보정 = stats.주문시전_보정치(전투상태, m)
    assert 보정 >= 2
    m["현재MP"] = 1
    기준 = _끈_피해(전투상태, m, 적, 30)
    HP감소, MP감소 = _맞기(전투상태, m, 적, 30)
    assert (HP감소, MP감소) == (기준 - 1, 1)
    assert m["현재MP"] == 0
    # MP가 0이면 줄지 않는다
    assert _맞기(전투상태, m, 적, 30) == (기준, 0)


def test_피해가_감소량보다_작으면_받은_피해만큼만_MP를_쓴다():
    상태, c = _마법사(3)
    전투상태, m, 적 = _전투(상태, c)
    m["현재MP"] = 50
    기준 = _끈_피해(전투상태, m, 적, 1, 방어력무시=True)
    assert 0 < 기준 < stats.주문시전_보정치(전투상태, m)
    assert _맞기(전투상태, m, 적, 1, 방어력무시=True) == (0, 기준)


def test_지속피해와_공격자_없는_피해는_줄이지_않는다():
    상태, c = _마법사(3)
    전투상태, m, 적 = _전투(상태, c)
    m["현재MP"] = 50
    assert _맞기(전투상태, m, 적, 20, 피해감소무시=True) == (20, 0)  # 출혈 등 지속피해
    m["현재HP"] = 500
    damage.피해_적용(전투상태, m, 20, 방어력무시=True)  # 공격자 없는 피해
    assert m["현재HP"] == 480 and m["현재MP"] == 50


def test_끈_오라실드는_효과가_없고_전환스킬은_행동없이_한_차례에_한_번만_바꾼다():
    상태, c = _마법사(3)
    전투상태, m, 적 = _전투(상태, c)
    m["현재MP"] = 50
    행동 = dict(m["행동자원"])
    ss.스킬_실행(전투상태, m, "오라 실드", _스킬("오라 실드"))
    assert c["켜진특성"] == [] and m["행동자원"] == 행동
    기준 = _끈_피해(전투상태, m, 적, 30)
    assert _맞기(전투상태, m, 적, 30) == (기준, 0)
    가능, _ = ss.사용_가능여부(전투상태, m, _스킬("오라 실드"))
    assert not 가능


def test_전투_밖_전환스킬_목록에_오라실드가_나오고_끄고_켤_수_있다():
    상태, c = _마법사(3)
    [줄] = [줄 for 줄 in gf.전환스킬_목록(상태) if 줄["스킬"] == "오라 실드"]
    assert 줄["가능"] and 줄["전환"] == "켜짐" and 줄["캐릭터"] is c
    assert "껐다" in gf.전환스킬_사용(상태, c, "오라 실드")["문구"]
    assert c["켜진특성"] == []
    assert "켰다" in gf.전환스킬_사용(상태, c, "오라 실드")["문구"]
    assert c["켜진특성"] == ["오라 실드"]


def test_강화오라실드는_MP를_쓰지_않고_근력민첩_보정치만큼_더_줄인다():
    상태, c = _마법사(6, 전직="배틀메이지")
    assert "강화오라실드" in c["보유특성"] and c["켜진특성"] == ["오라 실드"]
    전투상태, m, 적 = _전투(상태, c)
    능력치 = stats.유효_능력치(전투상태, m)
    추가 = (능력치["근력"] - 10) // 2 + (능력치["민첩"] - 10) // 2
    감소 = stats.주문시전_보정치(전투상태, m) + 추가
    m["현재MP"] = 0
    기준 = _끈_피해(전투상태, m, 적, 40)
    assert 기준 > 감소
    assert _맞기(전투상태, m, 적, 40) == (기준 - 감소, 0)


@pytest.mark.parametrize("켜짐", [True, False])
def test_오라실드는_세이브와_불러오기로_켜진_상태가_이어진다(임시_세이브폴더, 켜짐):
    상태, c = _마법사(3)
    if not 켜짐:
        gf.전환스킬_사용(상태, c, "오라 실드")
    gf.게임_저장(상태, 1)
    불러옴 = gf.게임_불러오기(1)
    m = 불러옴["파티"]["파티원"][0]
    assert ("오라 실드" in m["켜진특성"]) is 켜짐


def test_버전18_세이브의_마법사는_오라실드_스킬을_얻고_켜진다(임시_세이브폴더):
    상태, c = _마법사(3)
    gf.게임_저장(상태, 1)
    경로 = 임시_세이브폴더 / "slot_1.json"
    옛 = json.loads(경로.read_text(encoding="utf-8"))
    옛["버전"] = 18
    for 캐릭터 in 옛["플레이어"]["파티"]["파티원"]:
        캐릭터["보유스킬"] = [n for n in 캐릭터["보유스킬"] if n != "오라 실드"]
        캐릭터.pop("켜진특성", None)
    경로.write_text(json.dumps(옛, ensure_ascii=False), encoding="utf-8")
    마법사, 귀검사 = gf.게임_불러오기(1)["파티"]["파티원"]
    assert "오라 실드" in 마법사["보유스킬"] and 마법사["켜진특성"] == ["오라 실드"]
    assert "오라 실드" not in 귀검사["보유스킬"]
    assert "오라 실드" not in (귀검사.get("켜진특성") or [])
