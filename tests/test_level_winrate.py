def test_초기_준비는_새_게임_그대로다():
    파티 = _등록()["레벨"]["1"]["파티"][0]
    상태 = lw.파티_상태(1, "초기", 파티)
    새것 = gf.새_게임_시작([("", j) for j in 파티["직업"]])
    for c, 원래 in zip(상태["파티"]["파티원"], 새것["파티"]["파티원"]):
        assert c["레벨"] == 1
        assert (
            gf.캐릭터_장착아이템(상태, c, "무기")["이름"]
            == (gf.캐릭터_장착아이템(새것, 원래, "무기")["이름"])
        )
        assert c["보유스킬"] == 원래["보유스킬"]


def _상태(레벨, 이름):
    조건 = next(c for c in lw.조건들(_등록(), [레벨]) if c["파티"]["이름"] == 이름)
    return 조건, lw.파티_상태(레벨, 조건["준비"], 조건["파티"], 조건["설정"])


def test_성장_준비는_레벨까지_올리고_한_명만_봉인된_무기를_낀다():
    직업표 = _등록()["직업"]
    for 파티 in _등록()["레벨"]["2"]["파티"]:
        조건, 상태 = _상태(2, 파티["이름"])
        봉인 = 파티["봉인"]
        새것 = gf.새_게임_시작([("", j) for j in 파티["직업"]])
        for c, 원래 in zip(상태["파티"]["파티원"], 새것["파티"]["파티원"]):
            assert c["레벨"] == 2
            표 = 직업표[c["직업"]]
            # 무기 마스터리는 지정 무기, 방어구 마스터리는 시작 장비 재질
            assert f"{표['무기']} 마스터리" in c["보유특성"]
            assert f"{표['방어구']}숙련" in c["보유특성"]
            assert 표["방어구"] in gf.캐릭터_장착아이템(상태, c, "상의")["타입"]
            assert c["보유스킬"] == 원래["보유스킬"]  # 레벨 2는 스킬을 배우지 않는다
            무기 = gf.캐릭터_장착아이템(상태, c, "무기")
            if c["직업"] == 봉인["직업"]:
                assert 무기["이름"] == 봉인["아이템"]
                assert "마법봉인" in 무기["타입"]  # 봉인을 풀지 않았다
            else:
                assert 무기["이름"] == gf.캐릭터_장착아이템(새것, 원래, "무기")["이름"]


def test_레벨_3부터_골드_스킬까지_전부_배우고_4는_능력치향상_5는_주보조에_1씩():
    이름 = "마법사 없음"
    능력치 = {}
    for 레벨 in (2, 3, 4, 5):
        _, 상태 = _상태(레벨, 이름)
        for c in 상태["파티"]["파티원"]:
            남은 = gf.캐릭터_습득가능_스킬(c)
            assert (남은 == []) == (레벨 >= 3), (레벨, c["직업"], 남은)
            능력치[레벨, c["직업"]] = (c[c["주스탯"]], c[c["보조스탯"]])
    for _, j in [k for k in 능력치 if k[0] == 2]:
        assert 능력치[4, j][0] == 능력치[3, j][0] + 2  # 퍽 능력치향상 2점을 주스탯에
        assert 능력치[4, j][1] == 능력치[3, j][1]
        assert 능력치[5, j] == (능력치[4, j][0] + 1, 능력치[4, j][1] + 1)


def test_레벨_3_4_5는_언커먼_무기가_하나씩_늘고_방어구는_4에_둘_5에_넷():
    등록 = _등록()
    직업표 = 등록["직업"]
    for 레벨, 무기수, 방어구수 in ((3, 1, 0), (4, 2, 2), (5, 3, 4)):
        for 파티 in 등록["레벨"][str(레벨)]["파티"]:
            _, 상태 = _상태(레벨, 파티["이름"])
            assert len(파티["언커먼무기"]) == 무기수
            assert len(파티["언커먼방어구"]) == 방어구수
            무기, 방어구 = [], []
            for c in 상태["파티"]["파티원"]:
                템 = gf.캐릭터_장착아이템(상태, c, "무기")
                if c["직업"] == 파티["봉인"]["직업"]:
                    assert 템["이름"] == 파티["봉인"]["아이템"]  # 레어 봉인은 그대로
                elif 템["레어도"] == "언커먼":
                    assert 템["이름"] == 직업표[c["직업"]]["언커먼무기"]
                    무기.append(c["직업"])
                부위 = [gf.캐릭터_장착아이템(상태, c, p) or {} for p in lw.방어구부위]
                if all(i.get("레어도") == "언커먼" for i in 부위):
                    assert all(i["재질"] == 직업표[c["직업"]]["방어구"] for i in 부위)
                    방어구.append(c["직업"])
                else:
                    assert not any(i.get("레어도") == "언커먼" for i in 부위)
            assert sorted(무기) == sorted(파티["언커먼무기"])
            assert sorted(방어구) == sorted(파티["언커먼방어구"])
        if 레벨 > 3:  # 앞 레벨의 언커먼 무기는 그대로 두고 한 명씩 더한다
            for 앞, 지금 in zip(
                등록["레벨"][str(레벨 - 1)]["파티"], 등록["레벨"][str(레벨)]["파티"]
            ):
                assert 지금["언커먼무기"][:-1] == 앞["언커먼무기"]


def test_등록_파티의_봉인은_마법사_둘_다른_직업_셋이다():
    봉인 = [p["봉인"]["직업"] for p in _등록()["레벨"]["2"]["파티"]]
    assert 봉인.count("마법사") == 2
    다른 = [j for j in 봉인 if j != "마법사"]
    assert len(다른) == 3 and len(set(다른)) == 3


def test_같은_시드는_일꾼_수와_상관없이_같은_결과이고_표가_나온다(tmp_path):
    등록 = _등록()
    목록 = [
        c
        for c in lw.조건들(등록, [1, 2])
        if c["파티"]["이름"] == "프리스트 없음" and c["던전"] in ("D01", "D03")
    ]
    assert {(c["레벨"], c["종류"]) for c in 목록} == {
        (레벨, 종류) for 레벨 in (1, 2) for 종류 in ("인카운트", "보스", "원정")
    }
    하나 = lw.재기(목록, 2, 1000, 1)
    둘 = lw.재기(목록, 2, 1000, 2)
    assert [(r["승"], r["평균라운드"]) for r in 하나] == [
        (r["승"], r["평균라운드"]) for r in 둘
    ]
    글 = lw.표(하나, 2, 1000)
    assert "## 레벨 1 (준비: 초기)" in 글 and "## 레벨 2 (준비: 성장)" in 글
    assert "귀검사: 마법으로 봉인된 도" in 글


