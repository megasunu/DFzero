"""레벨별 등록 파티 승률 도구(tools/level_winrate.py, #790) - 등록 검사, 파티 준비, 판 재현, 표.

실제 측정(조건마다 수백 판)은 깃허브 액션 "Level winrate"(버튼 실행)에서 돌린다. 여기서는 몇 판만 돌린다.
"""

import copy
import json

import gameflow as gf
from tools import level_winrate as lw


def _등록():
    return lw.등록_읽기()


def test_저장소의_등록_파일은_문제가_없다():
    assert lw.등록_검사(_등록()) == []


def test_등록_검사는_잘못된_직업_인원_던전_봉인을_잡는다():
    등록 = copy.deepcopy(_등록())
    레벨1 = 등록["레벨"]["1"]
    레벨1["던전"].append("D99")
    레벨1["종류"].append("산책")
    레벨1["파티"][0]["직업"] = ["귀검사", "격투가", "거너"]
    레벨1["파티"][1]["직업"][0] = "웨펀마스터"
    레벨1["파티"][2]["봉인"] = {"직업": "거너", "아이템": "마법으로 봉인된 봉"}
    레벨1["파티"][3]["봉인"] = {"직업": "거너", "아이템": "녹슨 소검"}
    레벨1["파티"][4]["이름"] = 레벨1["파티"][3]["이름"]
    등록["레벨"]["3"] = dict(레벨1, 준비="초기")
    문제 = "\n".join(lw.등록_검사(등록))
    for 조각 in (
        "없는 던전 D99",
        "종류는",
        "직업은 4개",
        "없는 1차 직업 웨펀마스터",
        "봉인 직업 거너이 파티에 없다",
        "녹슨 소검은 레어 마법봉인 무기가 아니다",
        "파티 이름이 겹친다",
        "레벨 3: 준비 '초기'는 레벨 1만",
    ):
        assert 조각 in 문제, 조각


def test_초기_준비는_새_게임_그대로다():
    파티 = _등록()["레벨"]["1"]["파티"][0]
    상태 = lw.파티_상태(1, "초기", 파티)
    새것 = gf.새_게임_시작([("", j) for j in 파티["직업"]])
    for c, 원래 in zip(상태["파티"]["파티원"], 새것["파티"]["파티원"]):
        assert c["레벨"] == 1
        assert (
            gf.캐릭터_장착아이템(상태, c, "무기")["이름"]
            == (gf.캐릭터_장착아이템(새것, 원래, "무기")["이름"])
        )
        assert c.get("스킬") == 원래.get("스킬")


def test_성장_준비는_레벨까지_올리고_한_명만_봉인된_무기를_낀다():
    for 파티 in _등록()["레벨"]["2"]["파티"]:
        상태 = lw.파티_상태(2, "성장", 파티)
        봉인 = 파티["봉인"]
        새것 = gf.새_게임_시작([("", j) for j in 파티["직업"]])
        for c, 원래 in zip(상태["파티"]["파티원"], 새것["파티"]["파티원"]):
            assert c["레벨"] == 2
            무기 = gf.캐릭터_장착아이템(상태, c, "무기")
            if c["직업"] == 봉인["직업"]:
                assert 무기["이름"] == 봉인["아이템"]
                assert "마법봉인" in 무기["타입"]  # 봉인을 풀지 않았다
            else:
                assert 무기["이름"] == gf.캐릭터_장착아이템(새것, 원래, "무기")["이름"]


def test_등록_파티의_봉인은_마법사_둘_다른_직업_셋이다():
    봉인 = [p["봉인"]["직업"] for p in _등록()["레벨"]["2"]["파티"]]
    assert 봉인.count("마법사") == 2
    다른 = [j for j in 봉인 if j != "마법사"]
    assert len(다른) == 3 and len(set(다른)) == 3


def test_같은_시드는_일꾼_수와_상관없이_같은_결과이고_표가_나온다(tmp_path):
    등록 = _등록()
    목록 = [
        c
        for c in lw.조건들(등록, [1, 2])
        if c["파티"]["이름"] == "프리스트 없음" and c["던전"] in ("D01", "D03")
    ]
    assert {(c["레벨"], c["종류"]) for c in 목록} == {
        (레벨, 종류) for 레벨 in (1, 2) for 종류 in ("인카운트", "보스", "원정")
    }
    하나 = lw.재기(목록, 2, 1000, 1)
    둘 = lw.재기(목록, 2, 1000, 2)
    assert [(r["승"], r["평균라운드"]) for r in 하나] == [
        (r["승"], r["평균라운드"]) for r in 둘
    ]
    글 = lw.표(하나, 2, 1000)
    assert "## 레벨 1 (준비: 초기)" in 글 and "## 레벨 2 (준비: 성장)" in 글
    assert "귀검사: 마법으로 봉인된 도" in 글


def test_윌슨_구간():
    assert lw.윌슨_구간(0, 0) == (0.0, 0.0)
    아래, 위 = lw.윌슨_구간(5, 10)
    assert 0.23 < 아래 < 0.24 and 0.76 < 위 < 0.77
    assert lw.윌슨_구간(10, 10)[1] == 1.0


def test_명령은_표와_결과_파일을_쓰고_문제가_있으면_멈춘다(tmp_path):
    등록 = _등록()
    등록["레벨"] = {"1": dict(등록["레벨"]["1"], 던전=["D01"], 종류=["인카운트"])}
    등록["레벨"]["1"]["파티"] = 등록["레벨"]["1"]["파티"][:1]
    경로 = tmp_path / "등록.json"
    경로.write_text(json.dumps(등록, ensure_ascii=False), encoding="utf-8")
    표, 출력 = tmp_path / "표.md", tmp_path / "결과.json"
    인수 = ["--등록", str(경로), "--판", "2", "--일꾼", "1"]
    assert lw.main(인수 + ["--표", str(표), "--출력", str(출력)]) == 0
    assert "D01 인카운트" in 표.read_text(encoding="utf-8")
    assert json.loads(출력.read_text(encoding="utf-8"))["결과"][0]["판"] == 2
    assert lw.main(인수 + ["--레벨", "9"]) == 2
    등록["레벨"]["1"]["준비"] = "아무거나"
    경로.write_text(json.dumps(등록, ensure_ascii=False), encoding="utf-8")
    assert lw.main(인수) == 2
