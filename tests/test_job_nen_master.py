def _d20_처음만(monkeypatch, 처음, 나머지):
    """d20은 처음 한 번만 `처음`, 그 뒤는 `나머지`. 다른 주사위는 가장 큰 눈."""
    본 = []

    def 굴림(a, b):
        if b == 20:
            본.append(b)
            return 처음 if len(본) == 1 else 나머지
        return b

    monkeypatch.setattr(rng.주사위, "randint", 굴림)


