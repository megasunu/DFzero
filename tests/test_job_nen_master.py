def _주사위고정(monkeypatch, 값):
    monkeypatch.setattr(rng.주사위, "randint", lambda a, b: min(max(값, a), b))


def _스킬(이름):
    return dict(gf.스킬데이터모음_생성()[이름], _이름=이름)


def _쓰기(전투상태, p, 이름, 대상=None):
    p["행동자원"].update(일반행동=1, 보조행동=1)
    p["현재MP"] = max(p["현재MP"], 50)
    return ss.스킬_실행(전투상태, p, 이름, _스킬(이름), 대상)


def _보정치(전투상태, p):
    return stats.기본_컨텍스트(전투상태, p)["주문시전보정치"]


def _차례로(상태, p):
    """p의 차례가 될 때까지 턴을 넘긴다(적 턴은 자동)."""
    전투상태 = 상태["전투상태"]
    for _ in range(40):
        if gf.현재_턴_참가자(상태) is p:
            return
        gf.턴_넘기기(상태)
        if 전투상태["종료"] is not None:
            raise AssertionError("전투가 끝났다")
    raise AssertionError("차례가 오지 않았다")


