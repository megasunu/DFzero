def test_샤레도는_체력이_낮아도_골렘을_부르지_않는다():
    전투상태, 적, _ = _전장("얼음인형 샤레도")
    적[0]["현재HP"] = 1
    assert traits.체력소환(전투상태, 적[0]) is None


def test_빛의_성주는_명속성_공격과_명속강2와_명속성_저항():
    전투상태, 적, 아군 = _전장("빛의 성주 지그하르트")
    지그 = 적[0]
    # 저항 - 명속성 피해 절반
    지그["현재HP"] = 지그["최대HP"] = 999
    damage.피해_적용(전투상태, 지그, 10, 속성="명속성")
    assert 지그["현재HP"] == 999 - 5
    # 명속강 2 - 명속성 피해 1.2배
    assert damage.속성_최종배율(전투상태, 지그, 아군[0], "명속성", False) == 1.2
    # 모든 공격은 명속성이 된다
    assert traits.특성_문자열_변동값_목록(전투상태, 지그, "공격속성변경") == ["명속성"]


def test_지그하르트는_체력이_절반_이하가_되면_한_번_임시체력_30():
    전투상태, 적, _ = _전장("빛의 성주 지그하르트")
    지그 = 적[0]
    지그["기본최대HP"] = 지그["최대HP"] = 지그["현재HP"] = 100
    assert stats.유효_최대HP(전투상태, 지그) == 100
    damage.피해_적용(전투상태, 지그, 49)  # 51 - 아직 절반 초과
    assert 지그.get("임시생명력", 0) == 0
    damage.피해_적용(전투상태, 지그, 1)  # 50 - 절반 이하
    assert (지그["현재HP"], 지그["임시생명력"]) == (50, 30)
    assert any("임시생명력 30" in str(x.get("비고")) for x in 전투상태["로그"]), (
        전투상태["로그"][-3:]
    )
    damage.피해_적용(전투상태, 지그, 10)  # 임시체력이 먼저 깎인다
    assert (지그["현재HP"], 지그["임시생명력"]) == (50, 20)
    damage.피해_적용(전투상태, 지그, 40)  # 다 깎이고 실제 체력 20 피해
    assert (지그["현재HP"], 지그["임시생명력"]) == (30, 0)
    damage.피해_적용(전투상태, 지그, 5)  # 전투당 한 번
    assert (지그["현재HP"], 지그["임시생명력"]) == (25, 0)


def test_지그하르트가_한_번에_쓰러지면_임시체력을_받지_않는다():
    전투상태, 적, _ = _전장("빛의 성주 지그하르트")
    지그 = 적[0]
    지그["기본최대HP"] = 지그["최대HP"] = 지그["현재HP"] = 100
    damage.피해_적용(전투상태, 지그, 200)
    assert 지그["현재HP"] <= 0 and 지그.get("임시생명력", 0) == 0
