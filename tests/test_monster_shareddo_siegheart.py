"""얼음인형 샤레도와 빛의 성주 지그하르트(2026-10-30 사용자 지정).

- 얼음인형 샤레도: 돌 인형사 패턴에서 돌 대신 얼음, 얼음 공격(3·4·6번)은 수속성. 골렘소환 없음, 돌연변이:수.
- 지그하르트: 분류 기타, 타입 복합체. 특성 "빛의 성주"(모든 공격 명속성, 명속강 2, 명속성 저항),
  "특수패턴:지그하르트"(체력이 절반 이하가 되면 전투당 한 번 임시체력 30 - 전투가 끝날 때까지 남는다).

패턴 데이터 값은 전수 골든(test_combat_monsters)이 본다. 여기는 규칙을 정확한 값으로 본다.
"""

import gameflow as gf
from game.system.combat import damage, stats, traits
from tests import support


def _전장(*이름들):
    전투상태, 적, 아군 = support.시험_전투(list(이름들))
    return 전투상태, 적, sorted(아군, key=lambda p: p["대형위치"])


# ------------------------------------------------------------- 데이터


def test_샤레도는_돌_인형사의_얼음판이다():
    돌, 얼음 = gf.몬스터목록["돌 인형사"], gf.몬스터목록["얼음인형 샤레도"]
    assert 얼음["적등급"] == "네임드" and 얼음["크기"] == "소형"
    assert 얼음["특성"] == ["종족:인간", "종족:인형사", "돌연변이:수"]
    for k in ("근력", "민첩", "건강", "지능", "지혜", "매력", "역할군"):
        assert 얼음[k] == 돌[k], k
    이름 = {n: p["이름"] for n, p in 얼음["패턴"].items()}
    assert 이름 == {
        1: "근접 공격",
        2: "근접 공격",
        3: "얼음 던지기",
        4: "얼음 던지기",
        5: "빙결",
        6: "얼음기둥",
    }
    assert [얼음["패턴"][n]["속성"] for n in (1, 2, 3, 4, 6)] == [
        "무속성",
        "무속성",
        "수속성",
        "수속성",
        "수속성",
    ]
    assert 얼음["패턴"][5]["효과"]["이름"] == "빙결"


def test_지그하르트_데이터():
    d = gf.몬스터목록["빛의 성주 지그하르트"]
    assert (d["분류"], d["타입"], d["적등급"], d["크기"], d["역할군"]) == (
        "기타",
        ["복합체"],
        "네임드",
        "중형",
        "딜러",
    )
    assert [d[k] for k in ("근력", "민첩", "건강", "지능", "지혜", "매력")] == [
        20,
        16,
        16,
        14,
        16,
        14,
    ]
    assert d["특성"] == ["빛의 성주", "특수패턴:지그하르트"]
    요약 = {
        n: (p["이름"], p["타겟"], p["데미지"], p["공격타입"], p["공격횟수"])
        for n, p in d["패턴"].items()
    }
    assert 요약 == {
        1: ("빛의 검", "적단일", "1d8+근력보정치", "참격", 1),
        2: ("빛의 검", "적단일", "1d8+근력보정치", "참격", 1),
        3: ("레이저", "적단일", "1d8+지능보정치", "관통", 1),
        4: ("레이저", "적단일", "1d8+지능보정치", "관통", 1),
        5: ("노바", "적전체", "1d4+지능보정치", "역장", 1),
        6: ("번개쇄도", "적랜덤반복", "1d8+지능보정치", "역장", 3),
    }
    assert d["패턴"][6]["각공격명중굴림"] is True


