@pytest.mark.parametrize("파일명", [_천해, _심해])
def test_천해와_심해는_3x3_넓은_맵이고_아래_입구_위_전투이벤트다(파일명):
    맵 = gf.던전_레지스트리[파일명]
    지도 = 맵["지도"]
    assert len(지도) == 17 and all(len(줄) == 17 for 줄 in 지도)
    for y in range(1, 16):
        assert 지도[y][1:16] == "O" * 15
    assert 지도[16][8] == "#" and 지도[0][8] == "@"
    assert 맵["오브젝트"][(8, 0)]["클리어시"] == "연결지역화"


def test_미들오션은_천해_심해_부유성으로_이어진다():
    천해, 심해 = gf.던전_레지스트리[_천해], gf.던전_레지스트리[_심해]
    assert 천해["연결지역"][(8, 16)]["연결맵"] == _웨스트코스트
    assert 천해["연결지역"][(8, 0)] == {"연결맵": _심해, "진입좌표": (8, 15)}
    assert 심해["연결지역"][(8, 16)] == {"연결맵": _천해, "진입좌표": (8, 1)}
    assert 심해["연결지역"][(8, 0)]["연결맵"] == _부유성
    assert 심해["연결지역"][(8, 0)]["진입좌표"] == (3, 45)


def _부유성_이벤트_좌표(번호):
    return (3, 1 + 5 * (9 - 번호))


def test_부유성은_5x5_방_9개가_세로로_이어지고_방마다_전투이벤트다():
    맵 = gf.던전_레지스트리[_부유성]
    지도 = 맵["지도"]
    assert len(지도) == 47 and all(len(줄) == 7 for 줄 in 지도)
    assert 지도[0] == "XXX#XXX" and 지도[46] == "XXX#XXX"
    for 번호 in range(1, 10):
        x, y = _부유성_이벤트_좌표(번호)
        assert 지도[y] == "XXX@XXX"  # 방 맨 윗줄은 가운데 전투이벤트, 나머지 4칸은 막힘
        for 줄 in 지도[y + 1 : y + 5]:
            assert 줄 == "XOOOOOX"
    assert "인카운트" not in 맵
    assert len(맵["오브젝트"]) == 9


def test_부유성_방마다_몬스터가_정해져_있고_9번_방만_보스다():
    오브젝트들 = gf.던전_레지스트리[_부유성]["오브젝트"]
    for 번호, 이름들 in _부유성_방.items():
        오브젝트 = 오브젝트들[_부유성_이벤트_좌표(번호)]
        몬스터들 = _몬스터들(오브젝트)
        assert [m["이름"] for m in 몬스터들] == 이름들, 번호
        칭호 = [m.get("칭호") for m in 몬스터들]
        if 번호 == 9:
            assert 칭호 == ["보스", None]
        else:
            assert 칭호 == [None] * len(이름들), 번호
        assert (오브젝트["레벨"], 오브젝트["차수"]) == (9, 3)
        assert 오브젝트["클리어시"] == "통행가능화"


def test_부유성은_전투이벤트를_이겨야_다음_방으로_간다():
    rng.시드(0)
    상태 = support.새게임()
    gf.던전_진입(상태, _부유성)
    던전 = 상태["던전상태"]
    assert 던전["위치"] == (3, 45)
    for 번호 in range(1, 10):
        x, y = _부유성_이벤트_좌표(번호)
        # 이기기 전에는 이벤트 너머로 갈 길이 없다
        assert support.경로(던전["그리드"], 던전["위치"], (x, y - 1)) is None
        support.걸어가기(상태, (x, y + 1))
        오브젝트 = 던전["맵정보"]["오브젝트"][(x, y)]
        assert gf.오브젝트_상호작용(상태, (x, y), 오브젝트) == {"결과": "전투시작"}
        나온것 = sorted(e["원본"]["몬스터명"] for e in gf.적_목록(상태))
        assert 나온것 == sorted(_부유성_방[번호])
        support.강제_승리(상태)
        gf.전투_결과_정리(상태)
        assert town_system.오브젝트_클리어됨(상태["진행도"], _부유성, (x, y))
        assert 던전["그리드"][y][x] == "O"
    assert 던전["맵정보"]["연결지역"][(3, 0)]["연결맵"] == _웨스트코스트
    assert support.경로(던전["그리드"], 던전["위치"], (3, 0)) is not None


