def test_살의의_파동이_있으면_적은_턴_시작마다_역장_피해를_받는다(
    아수라전장, monkeypatch
):
    상태, 전투상태, 적, 아수라 = 아수라전장
    _살의_걸기(상태, 아수라)
    support.주사위고정(monkeypatch, 1)  # 지혜 내성 1 - 실패, (차수)d4 = 차수
    flow.턴_시작_처리(전투상태, 적[0])
    # 보정치 없이 (차수)d4(2026-10-22 사용자 결정 - 전에는 1d4+주문시전보정치)
    assert _차수(전투상태, 아수라) >= 2  # 옛 식(1+보정치 0)과 갈리게
    assert 적[0]["현재HP"] == 999 - _차수(전투상태, 아수라)
    로그 = 전투상태["로그"][-1]
    assert 로그["스킬"] == "살의의 파동" and 로그["타격"][0]["내성"] == "실패"
    # 공중에 떠 있어도 맞는다
    ss.상태이상_부여(전투상태, 적[1], "공중에뜸", 1)
    flow.턴_시작_처리(전투상태, 적[1])
    assert 적[1]["현재HP"] < 999


