"""귀검사 웨이브와 하단공격 타입(2026-10-21 사용자 결정, #325)."""

import pytest

import gameflow as gf
from game.system import skill_system as ss
from tests import support


@pytest.fixture
def 전장():
    """레벨 6 웨펀마스터(웨이브 보유) 대 타우 아미 둘, 그 캐릭터의 차례."""
    상태, p, _ = support.추가행동_전장()
    p["원본"]["보유스킬"].append("웨이브")
    적 = sorted(gf.적_목록(상태), key=lambda e: e["대형위치"])
    for e in 적:
        e["현재HP"] = e["최대HP"] = 10**6
    return 상태, p, 적


def _스킬(이름):
    return dict(gf.스킬데이터모음_생성()[이름], _이름=이름)


def _띄우기(상태, 대상):
    ss.상태이상_부여(상태["전투상태"], 대상, "공중에뜸", 1)


# ------------------------------------------------------------------ 웨이브


def test_파동검_지열은_웨이브로_이름이_바뀌고_무속성_역장_하단공격이다():
    모음 = gf.스킬데이터모음_생성()
    assert "파동검 지열" not in 모음
    웨이브 = 모음["웨이브"]
    assert "하단공격" in 웨이브["타입"]
    assert (웨이브["속성"], 웨이브["공격타입"]) == ("무속성", "역장")
    # 수치는 그대로
    assert 웨이브["데미지"] == "(차수)d8+주문시전보정치"
    assert (웨이브["데미지보너스"], 웨이브["MP소모"]) == (3, 5)
    assert 웨이브["명중률"] == "주문시전명중률"


# ------------------------------------------------------------------ 하단공격


def test_하단공격은_공중에뜸_적을_지정할_수_없고_비용도_쓰지_않는다(전장):
    상태, p, 적 = 전장
    _띄우기(상태, 적[0])
    MP = p["현재MP"]
    with pytest.raises(ValueError, match="공중"):
        gf.아군_스킬사용(상태, "웨이브", 중심대상=적[0])
    assert p["현재MP"] == MP
    gf.아군_스킬사용(상태, "웨이브", 중심대상=적[1])  # 떠 있지 않은 적은 된다
    assert p["현재MP"] == MP - 5


def test_하단공격이_아니면_공중에뜸_적도_지정할_수_있다(전장):
    상태, p, 적 = 전장
    _띄우기(상태, 적[0])
    gf.아군_스킬사용(상태, "귀참", 중심대상=적[0])


def test_하단공격_범위_공격은_공중에뜸_적에게_피해를_주지_못한다(전장, monkeypatch):
    상태, p, 적 = 전장
    전투상태 = 상태["전투상태"]
    _띄우기(상태, 적[1])
    support.주사위고정(monkeypatch, 20)  # 모두 명중
    범위 = dict(_스킬("웨이브"), 타겟="적3체")
    결과 = ss.공격스킬_실행(전투상태, p, 범위, 적[0])
    맞음, 뜸 = 결과["타격"]
    assert 맞음["대상"] == 적[0]["이름"] and 맞음["피해"] > 0
    assert 뜸["대상"] == 적[1]["이름"] and 뜸["피해"] == 0
    assert 뜸.get("공중회피") is True and "판정" not in 뜸
    assert 적[1]["현재HP"] == 10**6
    문장 = gf.로그_문장들(전투상태["로그"][-1])
    assert any(
        적[1]["이름"] in 줄 and "공중에 떠 있어 맞지 않았다" in 줄 for 줄 in 문장
    )


def test_전력전투는_하단공격_스킬을_공중에뜸_적에게_쓰지_않는다(전장):
    상태, p, 적 = 전장
    웨이브 = 상태["스킬데이터모음"]["웨이브"]
    _띄우기(상태, 적[0])
    인수 = gf._전력전투_인수(상태, 웨이브, p)
    assert 인수 == {"중심대상": 적[1]}
    _띄우기(상태, 적[1])
    assert gf._전력전투_인수(상태, 웨이브, p) is None
    # 하단공격이 아닌 스킬은 그대로 고른다
    assert gf._전력전투_인수(상태, 상태["스킬데이터모음"]["귀참"], p) is not None
