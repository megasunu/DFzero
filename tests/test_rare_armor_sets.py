def _구성품(세트명):
    재질, 이름 = 레어세트[세트명]
    if isinstance(이름, dict):
        return 재질, 이름
    return 재질, {슬롯: f"{이름} {부위}" for 슬롯, 부위 in _부위이름.items()}


@pytest.fixture(scope="module")
def 장비탭():
    return gf._상점_카탈로그_생성()["장비"]


def _세트장비(장비탭, 세트명, 빼기=()):
    _, 구성 = _구성품(세트명)
    return {슬롯: 장비탭[슬롯][이름] for 슬롯, 이름 in 구성.items() if 슬롯 not in 빼기}


