def _입히기(전투상태, 참가자, 장비탭, 세트명):
    참가자["장비데이터"] = dict(참가자["장비데이터"], **_세트장비(장비탭, 세트명))
    참가자["장비보너스"] = 장비.캐릭터_장비_보너스(
        참가자["원본"], 참가자["장비데이터"], 전투상태["세트정의"]
    )


def test_신록의_축복은_방어력_1과_턴_시작_HP_MP_재생(전장, 장비탭):
    전투상태, _, 아군 = 전장
    p = 아군[0]
    방어력 = stats.유효_방어력(전투상태, p)
    _입히기(전투상태, p, 장비탭, "신록의 축복")
    assert stats.유효_방어력(전투상태, p) == 방어력 + 1

    최대HP = stats.유효_최대HP(전투상태, p)
    최대MP = 장비.장비반영_최대MP(p["원본"], p["장비데이터"], 전투상태["세트정의"])
    p["현재HP"], p["현재MP"] = 최대HP - 3, 최대MP - 3
    flow.턴_시작_처리(전투상태, p)
    assert (p["현재HP"], p["현재MP"]) == (최대HP - 2, 최대MP - 2)
    # 최대치를 넘지 않는다
    p["현재HP"], p["현재MP"] = 최대HP, 최대MP
    flow.턴_시작_처리(전투상태, p)
    assert (p["현재HP"], p["현재MP"]) == (최대HP, 최대MP)


