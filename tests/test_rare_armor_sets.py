def test_드래고닉은_HP_절반_이하에서_데미지_1과_모든_속성내성_1(전장, 장비탭):
    전투상태, _, 아군 = 전장
    p = 아군[0]
    내성 = stats.속성_보정합(전투상태, p, "속성내성", "화속성")
    _입히기(전투상태, p, 장비탭, "드래고닉 스킨 중갑")
    최대HP = stats.유효_최대HP(전투상태, p)
    p["현재HP"] = 최대HP
    기본 = stats.장비_데미지보너스(p, None, 전투상태)
    p["현재HP"] = 최대HP // 2
    assert stats.장비_데미지보너스(p, None, 전투상태) == 기본 + 1
    p["현재HP"] = 최대HP // 2 + 1
    assert stats.장비_데미지보너스(p, None, 전투상태) == 기본
    for 속성 in ("화속성", "수속성", "명속성", "암속성"):
        assert stats.속성_보정합(전투상태, p, "속성내성", 속성) == 내성 + 1


def test_초합금은_치명타로_맞을_때_상대_치명타주사위_1_감소(전장, 장비탭):
    전투상태, 적, 아군 = 전장
    p, 몬스터 = 아군[0], 적[0]
    기본 = stats.치명타_주사위수(전투상태, 몬스터, 대상=p)
    _입히기(전투상태, p, 장비탭, "초합금 고로아투스 전투복")
    assert stats.치명타_주사위수(전투상태, 몬스터, 대상=p) == 기본 - 1
