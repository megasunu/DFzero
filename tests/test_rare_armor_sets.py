def test_몬스터_패턴_공격은_맞는_대상을_치명타주사위에_넘긴다(전장, monkeypatch):
    """주사위 20 고정 - 고블린의 공격이 치명타가 되고, 그 치명타주사위 계산에 맞는 아군이 넘어간다."""
    전투상태, 적, 아군 = 전장
    받은 = []
    원래 = stats.치명타_주사위수

    def 기록(전투상태, 공격자, 대상=None):
        받은.append(대상)
        return 원래(전투상태, 공격자, 대상=대상)

    monkeypatch.setattr(stats, "치명타_주사위수", 기록)
    support.주사위고정(monkeypatch, 20)
    monster_actions.몬스터_턴_실행(전투상태, 적[0])
    assert 받은 and all(대상 in 아군 for 대상 in 받은)
