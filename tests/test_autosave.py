"""자동 저장 슬롯(2026-11-10) - 맨 위 칸(0번)은 마을에 올 때마다 덮어쓰는 자동 저장, 1~3번은 수동 저장.

마을에 오는 길: 새 게임 시작, 패배 귀환, 던전 연결 칸으로 귀환, 다른 마을로 이동.
마을 안 작업(상점, 휴식)은 자동 저장하지 않는다. 새 게임은 화면이 gameflow.자동_저장을 부른다.
"""

import json

import gameflow as gf
from game.system import save_system
from tests import support
from tests.support import 던전파일명, 새게임

자동 = save_system.자동저장슬롯


def _저장본(폴더):
    return json.loads((폴더 / f"slot_{자동}.json").read_text(encoding="utf-8"))


def test_자동저장_슬롯은_0번이고_목록_맨_위에_있다(임시_세이브폴더):
    assert 자동 == 0
    요약 = gf.전체_세이브_요약()
    assert [s["슬롯번호"] for s in 요약] == [0, 1, 2, 3]
    assert all(s.get("비어있음") for s in 요약)


def test_자동_저장은_0번에_마을_상태로_덮어쓰고_수동_슬롯은_건드리지_않는다(
    임시_세이브폴더,
):
    상태 = 새게임()
    assert gf.자동_저장(상태) is True
    상태["소지품"]["골드"] = 1234
    gf.던전_진입(상태, 던전파일명(1))  # 던전 안이어도 자동 저장 칸은 마을 상태로만 쓴다
    gf.자동_저장(상태)
    저장 = _저장본(임시_세이브폴더)
    assert 저장["던전위치"] is None
    assert 저장["플레이어"]["소지품"]["골드"] == 1234
    for 번호 in (1, 2, 3):
        assert not gf.세이브_존재(번호)
    불러옴 = gf.게임_불러오기(자동)
    assert 불러옴["소지품"]["골드"] == 1234 and not 불러옴.get("던전상태")


def test_자동_저장이_실패해도_게임은_멈추지_않는다(임시_세이브폴더, monkeypatch):
    def 실패(*_a, **_k):
        raise OSError("디스크가 가득 찼다")

    monkeypatch.setattr(save_system, "_원자적_쓰기", 실패)
    assert gf.자동_저장(새게임()) is False


def test_패배_귀환은_휴식하고_자동_저장한다(임시_세이브폴더):
    상태 = 새게임()
    gf.던전_진입(상태, 던전파일명(1))
    위치, 오브젝트 = next(iter(상태["던전상태"]["맵정보"]["오브젝트"].items()))
    gf.오브젝트_상호작용(상태, 위치, 오브젝트)
    support.강제_패배(상태)
    assert gf.전투_결과_정리(상태) == "적승리"
    assert not gf.세이브_존재(자동)
    gf.패배_귀환(상태)
    assert all(c["현재HP"] > 0 for c in 상태["파티"]["파티원"])
    저장 = _저장본(임시_세이브폴더)
    assert all(c["현재HP"] > 0 for c in 저장["플레이어"]["파티"]["파티원"])
    assert 저장["던전위치"] is None


def test_던전_연결_칸으로_마을에_오면_자동_저장한다(임시_세이브폴더):
    상태 = 새게임()
    gf.던전_진입(상태, 던전파일명(1))
    gf.연결지역_처리(상태, {"연결맵": 던전파일명(2), "진입좌표": None})
    assert not gf.세이브_존재(자동), "던전에서 던전으로 갈 때는 저장하지 않는다"
    결과 = gf.연결지역_처리(상태, {"연결맵": "town_01A_T01_Elvengard"})
    assert 결과["타입"] == "마을"
    저장 = _저장본(임시_세이브폴더)
    assert 저장["던전위치"] is None and 저장["진행도"]["현재마을"] == "엘븐가드"


def test_다른_마을로_이동하면_자동_저장한다(임시_세이브폴더):
    상태 = 새게임()
    상태["진행도"]["클리어한던전"].update(gf.던전_레지스트리)  # 마을을 전부 연다
    목표 = gf.이동가능마을목록(상태)[0]["마을명"]
    gf.마을_이동(상태, 목표)
    assert _저장본(임시_세이브폴더)["진행도"]["현재마을"] == 목표


def test_마을_안_작업은_자동_저장하지_않는다(임시_세이브폴더):
    상태 = 새게임()
    상태["소지품"]["골드"] = 10_000
    gf.상점_구매(상태, "소모품", "포션", "초보자용 HP 포션", 1)
    gf.휴식(상태)
    assert not gf.세이브_존재(자동)


def test_자동저장_칸도_다른_슬롯처럼_요약된다(임시_세이브폴더):
    상태 = 새게임()
    gf.자동_저장(상태)
    요약 = gf.전체_세이브_요약()[0]
    assert 요약["슬롯번호"] == 0 and 요약["현재마을"] == 상태["진행도"]["현재마을"]
    assert 요약["대표캐릭터명"] == 상태["파티"]["파티원"][0]["캐릭터명"]
