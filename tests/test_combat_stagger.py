# "홀딩" 태그 공격이 맞으면 피해는 대상의 다음 차례 시작에 들어가고, 그때까지 대상은 상태이상 "홀딩"
# (그 대상을 노리는 공격은 명중굴림에 이점)이다. 시전자가 쓰러지거나 무력화CC에 걸리면 피해 없이 끝난다.


def _수플렉스(격, 전투상태, 대상):
    격["행동자원"].update(일반행동=1, 보조행동=1)
    스킬 = dict(gf.스킬데이터모음_생성()["수플렉스"], _이름="수플렉스")
    return ss.스킬_실행(전투상태, 격, "수플렉스", 스킬, 대상)


def _홀딩(p):
    return [s for s in p["상태이상"] if s["이름"] == "홀딩"]


def test_수플렉스와_넥업사이드_2단계는_홀딩_스킬이다():
    모음 = gf.스킬데이터모음_생성()
    assert {"잡기", "홀딩"} <= set(모음["수플렉스"]["타입"])
    넥 = 모음["넥 업 사이드"]
    assert "홀딩" not in (넥["공격단계1"].get("타입") or [])
    assert {"잡기", "홀딩"} <= set(넥["공격단계2"]["타입"])


def test_홀딩_피해는_대상의_차례_시작에_들어가고_홀딩이_풀린다(전장, monkeypatch):
    전투상태, 귀, 격, 적 = 전장
    _줄세우기(전투상태, [(격, 30), (적[0], 20), (적[1], 20), (귀, 10), (적[2], 5)])
    monkeypatch.setattr(damage, "명중_판정", _명중)
    로그수 = len(전투상태["로그"])
    _수플렉스(격, 전투상태, 적[0])
    assert 적[0]["현재HP"] == 999 and len(_홀딩(적[0])) == 1
