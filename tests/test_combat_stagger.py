    문장 = [줄 for 항목 in 전투상태["로그"][로그수:] for 줄 in gf.로그_문장들(항목)]
    assert not any("0의 데미지" in 줄 for 줄 in 문장)
    assert any("붙잡았다" in 줄 for 줄 in 문장)
    flow.턴_시작_처리(전투상태, 적[0])
    assert 적[0]["현재HP"] < 999 and not _홀딩(적[0])


