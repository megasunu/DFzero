"""경직(2026-10-20 사용자 결정) - 모든 공격의 명중 타격마다 맞은 대상의 이번 라운드 순서가 늦어진다.

일반 공격은 이니셔티브 -1, "잡기"·"경직" 태그 공격은 우선도 -1. 슈퍼아머·경직불가는 걸리지 않고,
잡기불가는 "잡기" 경직만 걸리지 않는다. 아직 행동하지 않은 참가자만 순서가 다시 정렬되고,
다음 라운드에는 다시 계산된다. 전투 기록에는 남기지 않는다."""

import random

import pytest

import gameflow as gf
from game.system import monster_ai, skill_system as ss
from game.system.combat import attacks, damage, flow, monster_actions
from tests import support


@pytest.fixture
def 전장():
    """귀검사·격투가(레벨 3, 스킬 전부)와 고블린 셋. 모두 HP를 넉넉히 둔다."""
    random.seed(3)
    상태 = support.새게임([("", "귀검사"), ("", "격투가")])
    for c in 상태["파티"]["파티원"]:
        support.성장(상태, c, 3, 스킬습득=True)
    gf.전투_시작(상태, ["고블린", "고블린", "고블린"], 레벨=2, 차수=1)
    support.반응_처리(상태)
    전투상태 = 상태["전투상태"]
    for p in 전투상태["참가자"]:
        p["현재HP"] = 999
    귀 = next(p for p in 전투상태["참가자"] if p["원본"].get("직업") == "귀검사")
    격 = next(p for p in 전투상태["참가자"] if p["원본"].get("직업") == "격투가")
    적 = sorted(
        (p for p in 전투상태["참가자"] if p["진영"] == "적"),
        key=lambda p: p["대형위치"],
    )
    return 전투상태, 귀, 격, 적


def _줄세우기(전투상태, 순서, 현재=0):
    """참가자를 (참가자, 이니셔티브) 순서대로 세우고 우선도를 0으로 둔다. 현재는 지금 차례의 칸."""
    for p, 값 in 순서:
        p["우선도"], p["이니셔티브"] = 0, 값
    전투상태["참가자"] = [p for p, _ in 순서]
    전투상태["현재턴"] = 현재


def _이름들(전투상태):
    return [p["이름"] for p in 전투상태["참가자"]]


def _명중(*a, **k):
    return {"성공": True, "자연눈": 15, "치명타": False, "자동실패": False}


def _빗나감(*a, **k):
    return {"성공": False, "자연눈": 2, "치명타": False, "자동실패": False}


def test_일반공격이_맞으면_이니셔티브가_1_내려가고_뒤의_순서가_다시_정렬된다(
    전장, monkeypatch
):
    전투상태, 귀, 격, 적 = 전장
    _줄세우기(전투상태, [(귀, 30), (적[0], 20), (적[1], 20), (격, 10), (적[2], 5)])
    monkeypatch.setattr(damage, "명중_판정", _명중)
    로그수 = len(전투상태["로그"])
    attacks.일반공격_실행(전투상태, 귀, 적[0])
    assert (적[0]["이니셔티브"], 적[0]["우선도"]) == (19, 0)
    assert _이름들(전투상태) == [
        귀["이름"],
        적[1]["이름"],
        적[0]["이름"],
        격["이름"],
        적[2]["이름"],
    ]
    assert not any(
        "경직" in str(r) for r in 전투상태["로그"][로그수:]
    )  # 기록하지 않는다


def test_빗나가면_경직이_없다(전장, monkeypatch):
    전투상태, 귀, 격, 적 = 전장
    _줄세우기(전투상태, [(귀, 30), (적[0], 20), (적[1], 20), (격, 10), (적[2], 5)])
