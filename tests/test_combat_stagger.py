    gf.전투_시작(상태, ["고블린"], 레벨=2, 차수=1)
    support.반응_처리(상태)
    전투상태 = 상태["전투상태"]
    나 = next(p for p in 전투상태["참가자"] if p["진영"] == "아군")
    적 = next(p for p in 전투상태["참가자"] if p["진영"] == "적")
    적["현재HP"] = 999
    _줄세우기(전투상태, [(나, 30), (적, 20)])
    monkeypatch.setattr(damage, "명중_판정", _명중)
