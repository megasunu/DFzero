"""S13 마봉효과 실전 - 봉인해제/봉인변환한 장비의 효과가 실제 전투에 반영된다 (docs/scenarios.md).

4인 기본 파티의 귀검사에게 "마법으로 봉인된 귀걸이"와 "마법으로 봉인된 천갑 상의"를 입히고, 마을
[전문직업] 창구(gf.전문직업_봉인해제/봉인변환)로 봉인을 푼 뒤 귀걸이는 명중 시 상태이상 능력, 상의는
기력(최대 HP +5)이 나올 때까지 바꾼다(얻는 경로인 포린의 항아리는 무작위라 소지품에 직접 넣는다).
로리엔(D01) 인카운트를 [자동전투]로 **실제로** 치러 귀검사의 공격이 명중할 때 귀걸이의 상태이상
내성굴림(DC12 건강)이 일어나는지, 전투 안 최대 HP가 전투 밖 최대 HP(기력 반영)와 같은지 본다.
효과 하나하나의 수치 규칙은 tests/test_magic_seal.py "전투 반영" 절이 값으로 검사한다.
"""

import pytest

from game.system import rng
import gameflow as gf
import scenario
import support
from game.data.equipment.eq_00_magic_seal import 마봉능력
from game.system.combat import stats

로리엔 = "dungeon_01A_D01_Lorien"
시드 = 2  # 난수 흐름 분리(2026-10-20) 뒤 시드 0은 이 시나리오의 효과가 안 나온다
귀걸이 = "마법으로 봉인된 귀걸이"
상의 = "마법으로 봉인된 천갑 상의"


def _능력(상태, 탭, 이름):
    return 상태["상점카탈로그"]["장비"][탭][이름]["마봉능력"]


def _풀고_바꾸기(상태, 캐릭터, 슬롯, 탭, 맞나):
    """장착 중인 봉인 장비를 풀고, 맞는 능력이 나올 때까지 봉인변환한다. 바꾼 횟수와 최종 능력."""
    [항목] = [
        h
        for h in gf.전문직업_봉인목록(상태, "봉인해제")
        if h["캐릭터"] is 캐릭터 and h["슬롯"] == 슬롯
    ]
    이름 = gf.전문직업_봉인해제(상태, 항목)
    횟수 = 0
    while not 맞나(_능력(상태, 탭, 이름)):
        [항목] = [
            h
            for h in gf.전문직업_봉인목록(상태, "봉인변환")
            if h["캐릭터"] is 캐릭터 and h["슬롯"] == 슬롯
        ]
        이름 = gf.전문직업_봉인변환(상태, 항목)
        횟수 += 1
        assert 횟수 < 100
    assert 캐릭터["장착장비"][슬롯] == 이름
    return 이름, 횟수


@pytest.mark.scenario("S13")
def test_S13_마봉효과_실전(golden):
    rng.시드(시드)
    상태 = support.새게임()
    귀검사 = next(c for c in 상태["파티"]["파티원"] if c["직업"] == "귀검사")
    소지품 = 상태["소지품"]
    소지품["골드"] = 100000
    소지품["재료"]["레어 소울"] = 1000
    소지품["장비"][귀걸이] = 1
    소지품["장비"][상의] = 1
    gf.장비_교체(상태, 귀검사, "귀걸이", 귀걸이)
    gf.장비_교체(상태, 귀검사, "상의", 상의)
    봉인HP = gf.캐릭터_최대HP(상태, 귀검사)

    상태이상능력 = {n for n, a in 마봉능력.items() if "상태이상" in a["효과"][0]}
    귀걸이이름, 귀걸이변환 = _풀고_바꾸기(
        상태, 귀검사, "귀걸이", "귀걸이", lambda n: n in 상태이상능력
    )
    상의이름, 상의변환 = _풀고_바꾸기(
        상태, 귀검사, "상의", "상의", lambda n: n == "기력"
    )
    assert gf.캐릭터_최대HP(상태, 귀검사) == 봉인HP + 5
    gf.파티_최대치로_회복(상태)

    gf.던전_진입(상태, 로리엔)
    기록 = []
    for _ in range(5):
        적 = scenario.인카운트까지_걷기(상태)
        참가자 = next(p for p in 상태["전투상태"]["참가자"] if p["원본"] is 귀검사)
        assert stats.유효_최대HP(상태["전투상태"], 참가자) == gf.캐릭터_최대HP(
            상태, 귀검사
        )
        종료 = scenario.실전(상태)
        발동 = [
            항목
            for 항목 in 상태["전투상태"]["로그"]
            if isinstance(항목, dict)
            and str(항목.get("비고", "")).startswith(f"'{귀걸이이름}' - ")
        ]
        # 발동은 귀검사의 공격이 명중했을 때만 - 내성굴림(DC 12)을 굴린 기록이 같이 남는다
        for 항목 in 발동:
            assert 항목["공격자"] == 귀검사["캐릭터명"]
            if "내성" in 항목:
                assert 항목["내성"]["DC"] == 12
        assert gf.전투_결과_정리(상태) == 종료
        기록.append(
            {
                "적": 적,
                "종료": 종료,
                "발동": len(발동),
                "걸림": sum("상태이상 부여" in 항목["비고"] for 항목 in 발동),
            }
        )
        if 종료 != "아군승리":
            break
        scenario.보상_수령(상태)
        if sum(r["발동"] for r in 기록) >= 3:
            break

    assert sum(r["발동"] for r in 기록) > 0, 기록
    golden(
        "scenario_S13_magic_seal",
        {
            "귀걸이": 귀걸이이름,
            "귀걸이_변환횟수": 귀걸이변환,
            "상의": 상의이름,
            "상의_변환횟수": 상의변환,
            "전투": 기록,
        },
    )
