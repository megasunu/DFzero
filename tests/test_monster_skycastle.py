def _피해_기록(monkeypatch):
    기록 = []
    원래 = damage.피해_적용

    def 기록하며(전투상태, 대상, 피해, **k):
        기록.append((대상["이름"], 피해))
        return 원래(전투상태, 대상, 피해, **k)

    monkeypatch.setattr(damage, "피해_적용", 기록하며)
    return 기록


def test_파괴광선은_양_옆에_절반(monkeypatch):
    전투상태, [눈], 아군 = _전장("이블아이의 왼쪽눈")
    monkeypatch.setattr(
        damage,
        "명중_판정",
        lambda *a, **k: {
            "성공": True,
            "자연눈": 15,
            "치명타": False,
            "자동실패": False,
        },
    )
    monkeypatch.setattr(rng.주사위, "randint", lambda a, b: b)
    기록 = _피해_기록(monkeypatch)
    _차례(전투상태, 눈, monkeypatch, _패턴("이블아이의 왼쪽눈", 6), 아군[1])
    # 1d12 최대 12 + 지능 14 보정치 2 = 14, 양 옆은 7
    assert sorted(기록, key=lambda x: x[1]) == sorted(
        [(아군[0]["이름"], 7), (아군[1]["이름"], 14), (아군[2]["이름"], 7)],
        key=lambda x: x[1],
    )


def _사악한_눈(monkeypatch, 발동):
    monkeypatch.setattr(rng.확률, "random", lambda: 0.0 if 발동 else 0.99)


def test_사악한_눈은_맞으면_때린_상대에게_반격하고_라운드당_한_번(monkeypatch):
    전투상태, [눈], 아군 = _전장("이블아이의 오른쪽눈")
    _사악한_눈(monkeypatch, True)
    기록 = _피해_기록(monkeypatch)
    damage.피격_처리(전투상태, 아군[0], 눈, {"성공": True})
    assert [x[0] for x in 기록] == [아군[0]["이름"]]
    assert 1 <= 기록[0][1] <= 6
    damage.피격_처리(전투상태, 아군[1], 눈, {"성공": True})
    assert len(기록) == 1  # 같은 라운드에는 다시 터지지 않는다
    전투상태["라운드"] += 1
    damage.피격_처리(전투상태, 아군[1], 눈, {"성공": True})
    assert [x[0] for x in 기록] == [아군[0]["이름"], 아군[1]["이름"]]


