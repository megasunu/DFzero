def _전장(*이름들):
    전투상태, 적, 아군 = support.시험_전투(list(이름들))
    for p in 적:  # 익스펠러 계열의 석상은 이 파일의 주제가 아니다
        p["상태이상"] = [s for s in p["상태이상"] if s["이름"] != "석상"]
    아군 = sorted(아군, key=lambda p: p["대형위치"])
    return 전투상태, 적, 아군


def _상태(참가자, 이름):
    return [s for s in 참가자["상태이상"] if s["이름"] == 이름]


def _패턴(이름, 번호):
    return gf.몬스터목록[이름]["패턴"][번호]


def _차례(전투상태, 몬스터, monkeypatch, 패턴=None, 대상=None):
    """몬스터가 턴을 시작하고 행동한 뒤 턴을 끝낸다. 이번 차례에 쌓인 로그를 돌려준다."""
    if 패턴 is not None:
        monkeypatch.setattr(monster_ai, "행동_선택", lambda p: 패턴)
    if 대상 is not None:
        monkeypatch.setattr(monster_ai, "타겟_선택", lambda *a, **k: 대상)
    시작 = len(전투상태["로그"])
    전투상태["현재턴"] = 전투상태["참가자"].index(몬스터)
    flow.턴_시작_처리(전투상태, 몬스터)
    monster_actions.몬스터_턴_실행(전투상태, 몬스터)
    flow.턴_종료_처리(전투상태, 몬스터)
    return 전투상태["로그"][시작:]


def _문장들(로그):
    return [z for x in 로그 for z in gf.로그_문장들(x)]


def _타격_로그(로그):
    return [x for x in 로그 if x.get("종류") == "타격"]


def _차수(몬스터, 차수):
    몬스터["원본"] = {**몬스터["원본"], "차수": 차수}


