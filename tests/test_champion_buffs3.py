"""챔피언 버프 3단계(#548) - 기타-부활, 폭주, 기습, 텔레포트, 이뮨-물리·마법, 강화-물리·마법방어.
무기공격 = 피해식에 무기공격력/보정공격력이 들어가는 공격과 일반공격, 차수공격 = (차수)dN 주사위 공격(#546)."""

import pytest

import gameflow as gf
from game.data.monster import monster_title
from game.system import rng
from game.system.combat import attacks, damage, flow, formula, monster_actions, stats
from tests.support import 새게임, 전투_열기


def _챔피언(이름="고블린", 버프=()):
    return {
        "이름": 이름,
        "칭호": "챔피언",
        "돌연변이": "돌연변이",
        "챔피언버프": list(버프),
    }


def _전투(몬스터들):
    rng.시드(3)
    상태 = 새게임()
    전투_열기(상태, 몬스터들)
    return 상태, 상태["전투상태"]


def _주사위(monkeypatch, 값):
    monkeypatch.setattr(rng.주사위, "randint", lambda a, b: min(max(a, 값), b))


def _최대HP(전투상태, p):
    return formula.올림(stats.유효_최대HP(전투상태, p))


def _아군(상태):
    return [p for p in gf.아군_목록(상태) if p["생존"]]


def test_3단계_버프가_모두_뽑기목록에_있다():
    새것 = {
        "기타-부활",
        "폭주",
        "기습",
        "텔레포트",
        "이뮨-물리",
        "이뮨-마법",
        "강화-물리방어",
        "강화-마법방어",
    }
    assert 새것 <= set(monster_title.챔피언버프_뽑기목록)


# ---------------------------------------------------------------- 무기공격 / 차수공격


@pytest.mark.parametrize(
    ("식", "일반공격취급", "분류"),
    [
        ("보정공격력", False, {"무기공격"}),
        ("무기공격력+2", False, {"무기공격"}),
        ("(차수)d8+주문시전보정치", False, {"주사위공격"}),
        ("(차수+1)d4+주문시전보정치", False, {"주사위공격"}),
        ("1d8+주문시전보정치", False, set()),
        ("1d8", True, {"무기공격"}),  # 일반공격취급
    ],
)
def test_공격_분류(식, 일반공격취급, 분류):
    assert set(stats.공격_분류(식, 일반공격취급)) == 분류


@pytest.mark.parametrize(
    ("버프", "분류", "배율"),
    [
        ("이뮨-물리", "무기공격", 0),
        ("이뮨-물리", "주사위공격", 1),
        ("이뮨-마법", "주사위공격", 0),
        ("이뮨-마법", "무기공격", 1),
        ("강화-물리방어", "무기공격", 0.5),
        ("강화-마법방어", "주사위공격", 0.5),
    ],
)
def test_이뮨과_강화방어는_그_분류_피해를_없애거나_절반으로(버프, 분류, 배율):
    상태, 전투상태 = _전투([_챔피언(버프=[버프])])
    챔피언, 아군 = gf.적_목록(상태)[0], _아군(상태)[0]
    챔피언["현재HP"] = 999
    최종 = damage.피해_적용(
        전투상태, 챔피언, 20, 공격측=아군, 피해감소무시=True, 공격분류=(분류,)
    )
    assert 최종 == formula.올림(20 * 배율)


def test_이뮨_물리_챔피언에게_일반공격은_피해가_없다(monkeypatch):
    상태, 전투상태 = _전투([_챔피언(버프=["이뮨-물리"])])
    챔피언, 아군 = gf.적_목록(상태)[0], _아군(상태)[0]
    챔피언["현재HP"] = 999
    _주사위(monkeypatch, 20)
    결과 = attacks.일반공격_실행(전투상태, 아군, 챔피언)
    assert 결과["판정"]["성공"] and 챔피언["현재HP"] == 999


# ---------------------------------------------------------------- 부활 / 폭주


def test_기타_부활은_한_번_최대체력으로_되살아난다():
    상태, 전투상태 = _전투([_챔피언(버프=["기타-부활"])])
    챔피언, 아군 = gf.적_목록(상태)[0], _아군(상태)[0]
    damage.피해_적용(전투상태, 챔피언, 9999, 공격측=아군, 피해감소무시=True)
    assert 챔피언["생존"] and 챔피언["현재HP"] == _최대HP(전투상태, 챔피언)
    assert any("부활" in str(e.get("비고")) for e in 전투상태["로그"])
    damage.피해_적용(전투상태, 챔피언, 9999, 공격측=아군, 피해감소무시=True)
    assert not 챔피언["생존"]


def test_폭주는_HP가_절반_이하가_되면_그_차례가_끝날_때_보너스_턴을_한_번_얻는다():
    상태, 전투상태 = _전투([_챔피언(버프=["폭주"])])
    챔피언, 아군 = gf.적_목록(상태)[0], _아군(상태)[0]
    for p in _아군(상태):
        p["현재HP"] = 999
    챔피언["현재HP"] = _최대HP(전투상태, 챔피언)
    damage.피해_적용(
        전투상태, 챔피언, 챔피언["현재HP"] // 2 + 1, 공격측=아군, 피해감소무시=True
    )
    시작 = len(전투상태["로그"])
    flow.턴_종료_처리(전투상태, 아군)
    새로그 = 전투상태["로그"][시작:]
    assert any(e.get("공격자") == 챔피언["이름"] and e.get("패턴") for e in 새로그), (
        새로그
    )
    # 두 번째로 절반 아래로 내려가도 다시 얻지 않는다
    damage.피해_적용(전투상태, 챔피언, 1, 공격측=아군, 피해감소무시=True)
    시작 = len(전투상태["로그"])
    flow.턴_종료_처리(전투상태, 아군)
    assert not any(
        e.get("공격자") == 챔피언["이름"] and e.get("패턴")
        for e in 전투상태["로그"][시작:]
    )


def test_폭주가_없으면_보너스_턴도_없다():
    상태, 전투상태 = _전투([_챔피언()])
    챔피언, 아군 = gf.적_목록(상태)[0], _아군(상태)[0]
    damage.피해_적용(
        전투상태, 챔피언, 챔피언["현재HP"] // 2 + 1, 공격측=아군, 피해감소무시=True
    )
    assert not 전투상태.get("보너스턴대기")


# ---------------------------------------------------------------- 기습 / 텔레포트


def test_기습은_전투_시작_때_패턴을_한_번_쓴다():
    상태, 전투상태 = _전투([_챔피언(버프=["기습"])])
    챔피언 = gf.적_목록(상태)[0]
    assert any(
        e.get("공격자") == 챔피언["이름"] and e.get("패턴") for e in 전투상태["로그"]
    )
    상태, 전투상태 = _전투([_챔피언()])
    챔피언 = gf.적_목록(상태)[0]
    assert not any(
        e.get("공격자") == 챔피언["이름"] and e.get("패턴") for e in 전투상태["로그"]
    )


def test_텔레포트는_첫_차례에_이탈하고_보상이_없다():
    상태, 전투상태 = _전투([_챔피언(버프=["텔레포트"]), "고블린"])
    챔피언 = gf.적_목록(상태)[0]
    flow.턴_시작_처리(전투상태, 챔피언)
    결과 = monster_actions.몬스터_턴_실행(전투상태, 챔피언)
    assert 결과["텔레포트"] and not 챔피언["생존"] and 챔피언.get("도망")
    (항목,) = [e for e in 전투상태["로그"] if e.get("텔레포트")]
    assert gf.로그_문장들(항목) == [f"{챔피언['이름']}는 텔레포트를 썼다!"]
