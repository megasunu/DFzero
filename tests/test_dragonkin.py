def test_용인족_3종은_능력치와_특성과_등급을_가지고_등록된다():
    기대 = {
        "미르키우스": ("asset_monster_mirkius.webp", "엘리트", ["종족:용인족"]),
        "라키우스": (
            "asset_monster_rakius.webp",
            "네임드",
            ["종족:용인족", "돌연변이:명", "특수패턴:라키우스"],
        ),
        "오라헌터 시우스": (
            "asset_monster_sius.webp",
            "네임드",
            ["종족:용인족", "오라헌터", "특수패턴:시우스"],
        ),
    }
    능력치 = ("근력", "민첩", "건강", "지능", "지혜", "매력")
    for 이름, (그림, 등급, 특성) in 기대.items():
        m = gf.몬스터목록[이름]
        assert (m["이미지"], m["적등급"], m["특성"]) == (그림, 등급, 특성), 이름
        assert m["분류"] == "용족" and m["타입"] == ["용족", "용인족", "인간형"], 이름
        assert [m[k] for k in 능력치] == [16, 14, 14, 10, 10, 12], 이름
    assert {p["이름"] for p in gf.몬스터목록["미르키우스"]["패턴"].values()} == {
        "창 찌르기"
    }
    시우스 = gf.몬스터목록["오라헌터 시우스"]["패턴"]
    assert [시우스[i]["이름"] for i in range(1, 7)] == ["창 찌르기"] * 5 + [
        "조건부행동"
    ]
    라키 = gf.몬스터목록["라키우스"]["패턴"]
    assert [라키[i]["이름"] for i in range(1, 7)] == ["창 찌르기"] * 3 + [
        "심장 찌르기",
        "심장 찌르기",
        "조건부행동",
    ]


