def _전장(*몬스터들):
    return support.시험_전투(list(몬스터들))


def _적(적, 이름):
    return next(p for p in 적 if p["원본"]["몬스터명"] == 이름)


def _패턴만(몬스터, 번호):
    """1~6 굴림 대신 늘 그 번호의 패턴을 쓰게 한다."""
    몬스터["원본"] = dict(몬스터["원본"], 패턴={1: 몬스터["원본"]["패턴"][번호]})


def _감옥_끄기(몬스터):
    몬스터["원본"] = dict(
        몬스터["원본"],
        특성=[t for t in 몬스터["원본"]["특성"] if t != "특수패턴:라키우스"],
    )


def _차례(전투상태, 몬스터):
    전투상태["현재턴"] = 전투상태["참가자"].index(몬스터)
    return monster_actions.몬스터_턴_실행(전투상태, 몬스터)


def _감옥들(전투상태):
    return [p for p in 전투상태["참가자"] if p.get("감옥") and p["생존"]]


def _분신들(전투상태):
    return [p for p in 전투상태["참가자"] if p.get("분신")]


def _오라_무기(참가자):
    참가자["장비데이터"] = dict(
        참가자.get("장비데이터") or {},
        무기={"오라": [{"변동대상": "방어력", "변동값": 1}]},
    )


