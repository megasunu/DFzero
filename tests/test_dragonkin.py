    _버프_쓰기(전투상태, 아군[1], "시험 버프", _버프스킬())
    assert (
        len([x for x in 전투상태["로그"][시작:] if x.get("패턴") == "창 찌르기"]) == 1
    )
    _패턴만(시우스, 1)
    _차례(전투상태, 시우스)
    시작 = len(전투상태["로그"])
    _버프_쓰기(전투상태, 아군[1], "시험 버프", _버프스킬())
    찌르기 = [x for x in 전투상태["로그"][시작:] if x.get("패턴") == "창 찌르기"]
    assert len(찌르기) == 1 and 찌르기[0]["대상"] == 아군[1]["이름"]


