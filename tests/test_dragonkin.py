def test_아군이_버프_스킬을_쓰면_시우스가_곧바로_창_찌르기를_한_번_쓴다(monkeypatch):
    전투상태, 적, 아군 = _전장("오라헌터 시우스")
    시우스 = 적[0]
    support.주사위고정(monkeypatch, 20)
    시작 = len(전투상태["로그"])
    _버프_쓰기(전투상태, 아군[0], "시험 버프", _버프스킬())
    찌르기 = [x for x in 전투상태["로그"][시작:] if x.get("패턴") == "창 찌르기"]
