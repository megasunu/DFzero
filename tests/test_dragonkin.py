def test_체력이_절반_이하면_쓰러진_적의_칸에_분신을_부른다(monkeypatch):
    전투상태, 적, 아군 = _전장("미르키우스", "라키우스")
    미르, 라키 = 적
    _패턴만(라키, 1)
    support.주사위고정(monkeypatch, 20)
    미르["현재HP"], 미르["생존"] = 0, False
    최대 = stats.유효_최대HP(전투상태, 라키)
    라키["현재HP"] = int(최대) // 2
    _차례(전투상태, 라키)
    분신 = _분신들(전투상태)
    assert len(분신) == 1
    분신 = 분신[0]
    assert 분신["대형위치"] == 미르["대형위치"] and 미르.get("칸비움")
    assert 분신["원본"]["몬스터명"] == "라키우스"
    assert 분신["이름"] == "라키우스의 분신"
    assert "특수패턴:라키우스" not in 분신["원본"]["특성"]
    assert "분신" in 분신["원본"]["특성"]
    assert 분신["현재HP"] == max(1, formula.올림(stats.유효_최대HP(전투상태, 분신)))
    # 전투당 한 번
    분신["현재HP"], 분신["생존"] = 0, False
    _차례(전투상태, 라키)
    assert len(_분신들(전투상태)) == 1


