def test_감옥은_명중_굴림이_AC와_속도보너스를_넘지_못하면_피한다(monkeypatch):
    전투상태, 적, 아군 = _전장("라키우스")
    라키 = 적[0]
    _패턴만(라키, 1)
    for p in 아군:
        p["장비보너스"] = dict(p.get("장비보너스") or {}, 속도보너스=0)
    # d20 10 + 민첩보정치 2 + 명중보너스 = 대상 AC면 맞는다 - 속도보너스 1이 더해지면 피한다
    support.주사위고정(monkeypatch, 10)
    명중값 = damage.명중_판정_계산(전투상태, 라키, 아군[0], "민첩판정")["명중결과"]
    for p in 아군:
        p["AC보정_시험"] = 명중값
    monkeypatch.setattr(
        stats, "최종AC", lambda 전투상태, 대상: 대상.get("AC보정_시험", 10)
    )
    monkeypatch.setattr(
        stats,
        "속도보너스_합",
        lambda 전투상태, 대상: 1 if 대상.get("진영") == "아군" else 0,
    )
    _차례(전투상태, 라키)
    assert not _감옥들(전투상태)
    assert [x for x in 전투상태["로그"] if "감옥'을 피함" in str(x.get("비고"))]
    monkeypatch.setattr(stats, "속도보너스_합", lambda 전투상태, 대상: 0)
    _차례(전투상태, 라키)
    assert len(_감옥들(전투상태)) == 1


