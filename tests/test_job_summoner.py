def test_소환사로_전직하면_주문시전능력치가_매력이고_최대MP도_매력을_따른다():
    # docs/game-rules.md "소환사 정령/계약소환" - 명중은 모두 주문시전명중률=소환사 매력(#711).
    상태, 캐릭터 = _레벨6_소환사()
    assert 캐릭터["주문시전능력치"] == "매력"
    매력보정 = (캐릭터["매력"] - 10) // 2
    지능보정 = (캐릭터["지능"] - 10) // 2
    assert 매력보정 != 지능보정  # 둘이 같으면 아래 비교가 아무것도 가리지 못한다
    assert 캐릭터["기본최대MP"] == 25 + 5 * (3 + 매력보정) + 10  # 캐스터 6레벨 성장 +10
    gf.전투_시작(상태, ["고블린"], 레벨=1, 차수=1)
    소환사 = next(p for p in 상태["전투상태"]["참가자"] if p["진영"] == "아군")
    assert stats.주문시전_보정치(상태["전투상태"], 소환사) == 매력보정


def test_지능으로_전직한_옛_세이브의_소환사는_불러올_때_매력으로_바로잡힌다(
    임시_세이브폴더,
):
    상태, 캐릭터 = _레벨6_소환사()
    바른MP = 캐릭터["기본최대MP"]
    캐릭터["주문시전능력치"] = "지능"  # 고치기 전 전직한 캐릭터
    캐릭터["기본최대MP"] = 캐릭터["현재MP"] = 바른MP - 7
