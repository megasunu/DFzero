def _소환사_차례(레벨=6, 퍽고르기=None):
    상태 = 새게임([("", "마법사")])
    성장(
        상태,
        상태["파티"]["파티원"][0],
        레벨,
        전직="소환사",
        스킬습득=True,
        퍽고르기=퍽고르기,
    )
    gf.전투_시작(상태, ["고블린", "고블린", "고블린"], 레벨=1, 차수=1)
    support.반응_처리(상태)
    while not gf.아군_차례인가(상태):
        gf.턴_넘기기(상태)
    참가자 = gf.현재_턴_참가자(상태)
    참가자["현재MP"] = 999
    return 상태, 참가자


def _마릿수(참가자):
    return {
        b["이름"]: b.get("중첩", 1)
        for b in 참가자["버프"]
        if b["이름"].endswith("소환")
    }


def test_정령소환_한도_상급조건_환수희생():
    rng.시드(5)
    상태, 참가자 = _소환사_차례()
    assert 참가자["기타행동"]["교감행동"] == 1  # 교감 - 차수(2)-1
    gf.아군_스킬사용(상태, "정령소환 : 아도르")
    assert 참가자["행동자원"]["일반행동"] == 1  # 교감행동으로 냈다
    참가자["행동자원"]["일반행동"] = 9
    gf.아군_스킬사용(상태, "정령소환 : 스토커")
    gf.아군_스킬사용(상태, "정령소환 : 위스프")  # 차수 2 - 먼저 부른 아도르가 돌아간다
    assert _마릿수(참가자) == {"스토커소환": 1, "위스프소환": 1}
    assert not gf.스킬_사용_가능여부(상태, 참가자, "정령소환 : 플레임 헐크")[0]
    gf.아군_스킬사용(상태, "정령소환 : 데드 멀커")  # 스토커 한 마리를 내보낸다
    assert _마릿수(참가자) == {"위스프소환": 1, "데드 멀커소환": 1}
    gf.아군_스킬사용(상태, "계약소환 : 산도르")
    assert not gf.스킬_사용_가능여부(상태, 참가자, "계약소환 : 산도르")[0]
    assert all(
        any(b["이름"] == "산도르의 오라" for b in p["버프"])
        for p in 상태["전투상태"]["참가자"]
        if p["진영"] == "아군"
    )
    gf.아군_스킬사용(상태, "환수희생")
    assert "위스프" not in 참가자["소환수"] and "위스프소환" not in _마릿수(참가자)


def _정령계약(캐릭터, 후보):
    return next((p for p in 후보 if p[0] == "정령계약"), 후보[0])  # 레벨 3은 아무거나


def test_정령계약_하급대신_중급_상급은_소모없이():
    rng.시드(5)
    상태, 참가자 = _소환사_차례(레벨=9, 퍽고르기=_정령계약)
    참가자["행동자원"]["일반행동"] = 9
    전투 = 상태["전투상태"]
    assert stats.속성_보정합(전투, 참가자, "속성강화", "화속성") == 0
    gf.아군_스킬사용(상태, "정령소환 : 아도르")  # 하급 아도르 대신 중급 샐리스트
    assert _마릿수(참가자) == {"샐리스트소환": 1}
    assert not gf.스킬_사용_가능여부(상태, 참가자, "정령소환 : 아도르")[0]  # 한 마리씩
    for p in 전투["참가자"]:
        if p["진영"] == "아군":  # 아군 전체 오라 - 화속성 강화/내성 +2
            assert stats.속성_보정합(전투, p, "속성강화", "화속성") == 2
            assert stats.속성_보정합(전투, p, "속성내성", "화속성") == 2
    assert stats.속성_보정합(전투, 참가자, "속성강화", "수속성") == 0
    # 상급정령은 하급정령 없이 부르고 아무것도 내보내지 않는다
    assert gf.스킬_사용_가능여부(상태, 참가자, "정령소환 : 아퀘리스")[0]
    gf.아군_스킬사용(상태, "정령소환 : 아퀘리스")
    gf.아군_스킬사용(상태, "정령소환 : 플레임 헐크")
    assert _마릿수(참가자) == {
        "샐리스트소환": 1,
        "아퀘리스소환": 1,
        "플레임 헐크소환": 1,
    }
    for 하급, 중급 in [
        ("스토커", "셰이드"),
        ("위스프", "알리시아"),
        ("나이아스", "라트리아"),
    ]:
        gf.아군_스킬사용(상태, f"정령소환 : {하급}")
        assert f"{중급}소환" in _마릿수(참가자) and f"{하급}소환" not in _마릿수(참가자)
    assert not gf.스킬_사용_가능여부(상태, 참가자, "환수희생")[0]  # 하급정령이 없다


