    mp = p["현재MP"]
    gf.아군_스킬사용(상태, "채찍질", 중심대상=적[0])
    assert 적[0]["현재HP"] < 999 and p["현재MP"] == mp - 5
    gf.아군_스킬사용(상태, "채찍질", 중심대상=아군)
    (기동,) = [b for b in 아군["버프"] if b["이름"] == "기동강화"]
    assert 기동["지속턴"] == 3 and 아군["현재HP"] == 999


