"""S40 모험단 운영 실전 - 주점 영입·대기·합류·추방, 보상 포기, 장비 해제, 해체 (docs/scenarios.md, #74).

기본 4인 파티에 주점에서 마법사를 영입한다(파티가 차서 모험단 숙소로). 프리스트를 숙소에 대기시키고 마법사를
합류시켜 로리엔 인카운트를 **실전으로** 싸운다. 보스를 이긴 뒤 보상 3칸 대신 포기 골드를 받는다. 마을로 돌아와
마법사의 상의를 벗기고(장비는 소지품에 남는다 - 무기는 못 벗긴다) 그 상의를 해체해 재료를 얻는다. 마법사를
추방하면 그 무기도 해체할 수 있게 되고, 프리스트를 다시 합류시켜 다음 인카운트를 실전으로 싸운다. 저장/불러오기
뒤에도 파티와 숙소가 그대로다. 규칙 하나하나의 값(골드 부족, 이름 겹침, 20명 한계)은
test_gameflow_scenarios.py::test_주점_영입_대기_합류_추방이 본다.
"""

import pytest

from game.system import rng
import gameflow as gf
import scenario
import support

시드 = 1
_로리엔 = "dungeon_01A_D01_Lorien"
_엘븐가드 = "town_01A_T01_Elvengard"


def _이름들(목록):
    return [c["캐릭터명"] for c in 목록]


def _인카운트_실전(상태):
    """인카운트까지 걸어 [자동전투]로 싸우고 정리한다. (적 이름들, 아군 참가자 이름들, 종료)."""
    적 = scenario.인카운트까지_걷기(상태)
    아군 = [p["이름"] for p in 상태["전투상태"]["참가자"] if p["진영"] == "아군"]
    종료 = scenario.실전(상태)
    assert gf.전투_결과_정리(상태) == 종료 == "아군승리", 종료
    if gf.전투_보상_대기중(상태):
        scenario.보상_수령(상태)
    return {"적": 적, "아군": 아군}


def _해체할_수_있나(상태, 이름):
    return any(d["이름"] == 이름 for d, _, _ in gf.상점_해체목록(상태, "전체"))


def _해체(상태, 이름):
    """이름 장비 1개를 해체한다. (얻은 재료, 해체 전후 개수)."""
    탭 = next(t for d, _, t in gf.상점_해체목록(상태, "전체") if d["이름"] == 이름)
    전 = 상태["소지품"]["장비"].get(이름, 0)
    재료전 = dict(상태["소지품"].get("재료", {}))
    얻음 = gf.상점_해체(상태, 탭, 이름, 1)
    assert 얻음 and 상태["소지품"]["장비"].get(이름, 0) == 전 - 1
    for 재료, 개수 in 얻음.items():
        assert 상태["소지품"]["재료"][재료] == 재료전.get(재료, 0) + 개수
    return 얻음


@pytest.mark.scenario("S40")
def test_S40_모험단_운영_실전(golden):
    rng.시드(시드)
    상태 = support.새게임()
    파티 = 상태["파티"]["파티원"]
    기록 = {}

    # 1) 주점 영입 - 파티가 차 있어 숙소로, 영입 비용만큼 골드가 준다
    상태["소지품"]["골드"] += gf.영입_비용
    골드 = 상태["소지품"]["골드"]
    마법사, 자리 = gf.파티원_영입(상태, "", "마법사")
    assert 자리 == "숙소" and gf.숙소_목록(상태) == [마법사]
    assert 상태["소지품"]["골드"] == 골드 - gf.영입_비용
    # 2) 프리스트 대기 -> 마법사 합류
    프리스트 = next(c for c in 파티 if c["직업"] == "프리스트")
    gf.파티원_대기(상태, 프리스트)
    gf.파티원_합류(상태, 마법사)
    assert _이름들(gf.숙소_목록(상태)) == [프리스트["캐릭터명"]]
    assert 마법사 in 파티 and 프리스트 not in 파티

    # 3) 로리엔 실전 - 영입한 마법사가 싸우고, 대기한 프리스트는 빠진다
    gf.던전_진입(상태, _로리엔)
    첫전투 = _인카운트_실전(상태)
    assert 마법사["캐릭터명"] in 첫전투["아군"]
    assert 프리스트["캐릭터명"] not in 첫전투["아군"]
    기록["첫전투"] = 첫전투

    # 4) 보스를 이기고 보상 대신 포기 골드
    결과, _ = support.보스_처치(상태, 전투처리=scenario.실전)
    assert 결과 == "아군승리" and gf.전투_보상_대기중(상태)
    칸 = gf.전투_보상_칸(상태)
    골드 = 상태["소지품"]["골드"]
    assert gf.전투_보상_포기(상태) == gf.보상_포기_골드
    assert 상태["소지품"]["골드"] == 골드 + gf.보상_포기_골드
    assert not gf.전투_보상_대기중(상태)
    with pytest.raises(ValueError):
        gf.전투_보상_받기(상태, 0)  # 포기한 뒤에는 칸을 받을 수 없다
    기록["포기한_칸"] = 칸
    support.연결로_나가기(상태, _엘븐가드, 전투처리=scenario.실전)
    assert 상태["던전상태"] is None

    # 5) 장비 해제 - 무기는 못 벗기고, 상의는 소지품에 남아 해체할 수 있게 된다
    상의 = 마법사["장착장비"]["상의"]
    assert 상의 and not _해체할_수_있나(상태, 상의)
    with pytest.raises(ValueError):
        gf.장비_해제(상태, 마법사, "무기")
    최대HP = gf.캐릭터_최대HP(상태, 마법사)
    gf.장비_해제(상태, 마법사, "상의")
    assert 마법사["장착장비"]["상의"] is None
    assert gf.캐릭터_장착아이템(상태, 마법사, "상의") is None
    assert 마법사["현재HP"] <= gf.캐릭터_최대HP(상태, 마법사) <= 최대HP
    assert _해체할_수_있나(상태, 상의)
    # 6) 해체 - 상의 1개가 재료가 된다
    기록["상의_해체"] = [상의, _해체(상태, 상의)]

    # 7) 추방 - 마법사의 무기가 풀려 해체할 수 있다. 프리스트를 다시 합류
    무기 = 마법사["장착장비"]["무기"]
    assert not _해체할_수_있나(상태, 무기)
    gf.파티원_추방(상태, 마법사)
    assert 마법사 not in 파티 and 마법사 not in gf.숙소_목록(상태)
    assert _해체할_수_있나(상태, 무기)
    기록["무기_해체"] = [무기, _해체(상태, 무기)]
    gf.파티원_합류(상태, 프리스트)
    assert gf.숙소_목록(상태) == [] and 프리스트 in 파티

    # 8) 다시 실전 - 돌아온 프리스트가 싸운다
    gf.휴식(상태)
    gf.던전_진입(상태, _로리엔)
    둘째전투 = _인카운트_실전(상태)
    assert 프리스트["캐릭터명"] in 둘째전투["아군"]
    assert 마법사["캐릭터명"] not in 둘째전투["아군"]
    기록["둘째전투"] = 둘째전투

    # 9) 저장/불러오기 - 파티·숙소·소지품 그대로
    gf.게임_저장(상태, 1)
    불러옴 = gf.게임_불러오기(1)
    assert _이름들(불러옴["파티"]["파티원"]) == _이름들(파티)
    assert gf.숙소_목록(불러옴) == []
    assert 불러옴["소지품"] == 상태["소지품"]
    기록["파티"] = _이름들(파티)
    기록["재료"] = dict(상태["소지품"]["재료"])
    golden("scenario_S40_party_management", 기록)
