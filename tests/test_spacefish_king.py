def test_체력이_절반_이하면_매_행동을_공충노도로_명속성_타격_2회(monkeypatch):
    전투상태, 왕, 아군 = _전장()
    _패턴만(왕, 1)
    왕["원본"] = {**왕["원본"], "차수": 2}
    support.주사위고정(monkeypatch, 20)
    왕["현재HP"] = stats.유효_최대HP(전투상태, 왕) // 2
    로그 = _차례(전투상태, 왕)
    타격 = [x for x in 로그 if x.get("종류") == "타격"]
    assert {x["패턴"] for x in 타격} == {"공충노도"}
    assert len(타격) == 4  # 차수 2 x 2회
    패턴 = 특성목록["특수패턴:크로쿠타"]["대체행동"]["패턴"]
    assert (패턴["데미지"], 패턴["속성"], 패턴["공격타입"], 패턴["명중률"]) == (
        "1d4+근력보정치",
        "명속성",
        "타격",
        "근력판정",
    )


