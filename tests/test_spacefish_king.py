def test_왕의_식사는_입힌_피해의_절반을_회복한다(monkeypatch):
    전투상태, 왕, 아군 = _전장()
    _공충노도_끄기(왕)
    _패턴만(왕, 5)
    대상 = _한명만(아군)
    support.주사위고정(monkeypatch, 20)
    왕["현재HP"] = 1
    로그 = _차례(전투상태, 왕)
    피해 = sum(x["총피해"] for x in 로그 if x.get("종류") == "타격")
    assert 피해 > 0
    # 버프가 없어 공어의 왕 회복은 없다 - 피해의 절반(내림)만 회복
    assert 왕["현재HP"] == min(stats.유효_최대HP(전투상태, 왕), 1 + 피해 // 2)
    assert 999 - 대상["현재HP"] == 피해


