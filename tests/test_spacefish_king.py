from tests import support

크로쿠타 = "공왕 크로쿠타"


def _전장():
    전투상태, 적, 아군 = support.시험_전투([크로쿠타])
    return 전투상태, 적[0], sorted(아군, key=lambda p: p["대형위치"])


def _패턴만(몬스터, 번호):
    """1~6 굴림 대신 늘 그 번호의 패턴을 쓰게 한다."""
    몬스터["원본"] = dict(몬스터["원본"], 패턴={1: 몬스터["원본"]["패턴"][번호]})


def _공충노도_끄기(몬스터):
    몬스터["원본"] = dict(
        몬스터["원본"],
        특성=[t for t in 몬스터["원본"]["특성"] if t != "특수패턴:크로쿠타"],
    )


def _한명만(아군):
    for p in 아군[1:]:
        p["생존"] = False
    return 아군[0]


def _차례(전투상태, 몬스터):
    전투상태["현재턴"] = 전투상태["참가자"].index(몬스터)
    시작 = len(전투상태["로그"])
    monster_actions.몬스터_턴_실행(전투상태, 몬스터)
    return 전투상태["로그"][시작:]


def _무작위상태(참가자):
    return [
        s for s in 참가자["상태이상"] if s["이름"] in common_names.무작위상태이상_목록
    ]


