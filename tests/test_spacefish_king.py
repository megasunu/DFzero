def test_명중하면_버프를_모두_빼앗고_버프마다_1d8_건강보정치_회복(monkeypatch):
    전투상태, 왕, 아군 = _전장()
    _공충노도_끄기(왕)
    _패턴만(왕, 1)
    대상 = _한명만(아군)
    대상["버프"] += [
        {"이름": "공격력증가", "지속턴": 2, "고정값": 4},
        {"이름": "속도증가", "지속턴": 1},
    ]
    support.주사위고정(monkeypatch, 20)
    최대 = stats.유효_최대HP(전투상태, 왕)
    왕["현재HP"] = 1
    _차례(전투상태, 왕)
    assert [b["이름"] for b in 대상["버프"]] == []
    assert {"이름": "공격력증가", "지속턴": 2, "고정값": 4} in 왕["버프"]
    assert {"이름": "속도증가", "지속턴": 1} in 왕["버프"]
    # 1d8(8) + 건강보정치(건강 16 -> 3) = 11, 버프 둘이면 22(최대HP까지)
    assert 왕["현재HP"] == min(최대, 1 + 22)


def test_명중하면_내성굴림_없이_무작위_상태이상_하나(monkeypatch):
    전투상태, 왕, 아군 = _전장()
    _공충노도_끄기(왕)
    _패턴만(왕, 1)
    대상 = _한명만(아군)
    support.주사위고정(monkeypatch, 20)
    로그 = _차례(전투상태, 왕)
    걸린것 = _무작위상태(대상)
    assert len(걸린것) == 1
    분류 = 전투상태["상태이상정의"][걸린것[0]["이름"]].get("분류")
    assert 걸린것[0]["지속턴"] == common_names.무작위상태이상_지속턴.get(
        분류, common_names.무작위상태이상_기본지속턴
    )
    assert not [x for x in 로그 if x.get("내성")]


