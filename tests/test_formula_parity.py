@pytest.mark.filterwarnings(
    "ignore::SyntaxWarning"
)  # 옛 eval이 "2(3)" 같은 식에 내는 경고
def test_무작위_계산식도_옛_평가기와_같다():
    생성기 = random.Random(20261006)
    비교 = 성공 = 0
    for _ in range(1500):
        식 = "".join(생성기.choice(조각들) for _ in range(생성기.randint(1, 9)))
        정규화 = (
            식.replace("x", "*").replace("X", "*").replace("×", "*").replace("÷", "/")
        )
        if "**" in 정규화 or "//" in 정규화:
            continue  # 지수는 새 평가기가 일부러 제한한다(_최대_지수) - 아래에서 따로 비교한다
        for 시드 in (0, 5):
            옛 = _결과(수식_평가_이전, 식, dict(수식_컨텍스트), False, 시드=시드)
            새 = _결과(formula.수식_평가, 식, dict(수식_컨텍스트), False, 시드=시드)
            assert 옛 == 새, (식, 시드, 옛, 새)
            비교 += 1
            성공 += 옛[0] == "값"
    assert 비교 > 1000 and 성공 > 100, (비교, 성공)  # 실패만 비교하는 검사가 되지 않게


