def test_안전_평가는_계산식만_계산한다():
    assert formula.안전_평가(" 1+2*3 ") == 7
    assert formula.안전_평가("_올림(1.2)") == 2
    assert formula.안전_평가("(1+2)*(3+4)/2") == 10.5
    with pytest.raises(ZeroDivisionError):
        formula.안전_평가("1/0")
    with pytest.raises(SyntaxError):
        formula.안전_평가("1+")
    with pytest.raises(ValueError):  # 빈 식은 계산식이 아니다(허용 글자가 하나도 없음)
        formula.안전_평가("")


