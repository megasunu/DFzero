def _결과(함수, *인자, 시드):
    rng.시드(시드)
    try:
        값 = 함수(*인자)
    except Exception:  # noqa: BLE001 - 어떤 종류든 "실패"로만 비교한다
        return ("실패", None)
    # 옛 eval은 말이 안 되는 "()"에서 빈 튜플을 돌려줬다. 숫자가 아닌 결과는 호출하는 쪽이 전부
    # 실패와 똑같이(기본값/0) 다루므로(participants/monster_actions/loot_system) 실패로 비교한다.
    if not isinstance(값, (int, float)) or isinstance(값, bool):
        return ("실패", None)
    return ("값", 값)


