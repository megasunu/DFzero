"""격투가(020f) 1차 계열 규칙 - 분신(#278, 2026-10-20 사용자 결정)."""

import pytest

from game.system import rng
import gameflow as gf
from game.system import skill_system as ss
from game.system.combat import damage, stats
from tests import support


@pytest.fixture
def 격투가전장():
    """격투가 레벨 3(분신 습득)과 고블린 둘."""
    rng.시드(3)
    상태 = support.새게임([("", "격투가")])
    c = 상태["파티"]["파티원"][0]
    support.성장(상태, c, 3)
    assert "분신" in c["보유스킬"]
    c[c["주문시전능력치"]] = (
        16  # 주문시전보정치 +3 - 레벨 3 기본값(+0)이면 실드가 0이다
    )
    gf.전투_시작(상태, ["고블린", "고블린"], 레벨=2, 차수=1)
    support.반응_처리(상태)
    전투상태 = 상태["전투상태"]
    격 = next(p for p in 전투상태["참가자"] if p["진영"] == "아군")
    적 = [p for p in 전투상태["참가자"] if p["진영"] == "적"]
    return 전투상태, 격, 적


def _스킬(이름):
    return dict(gf.스킬데이터모음_생성()[이름], _이름=이름)


def _분신(전투상태, 격):
    격["행동자원"].update(일반행동=1, 보조행동=1)
    격["현재MP"] = 99
    return ss.스킬_실행(전투상태, 격, "분신", _스킬("분신"))


def _실드(격):
    항목 = next((b for b in 격["버프"] if b["이름"] == "분신"), None)
    return None if 항목 is None else 항목.get("분신실드")


def _보정치(전투상태, 격):
    return stats.기본_컨텍스트(전투상태, 격)["주문시전보정치"]


def test_분신은_차수더하기2개를_주문시전보정치_실드로_만든다(격투가전장):
    전투상태, 격, _ = 격투가전장
    _분신(전투상태, 격)
    보정 = _보정치(전투상태, 격)
    assert 보정 > 0
    assert _실드(격) == [보정] * 3  # 비전직 차수 1 -> 3개


def test_분신이_피해를_순서대로_흡수하고_넘친_피해는_다음_분신으로(격투가전장):
    전투상태, 격, 적 = 격투가전장
    _분신(전투상태, 격)
    보정 = _보정치(전투상태, 격)
    HP = 격["현재HP"]
    damage.피해_적용(전투상태, 격, 보정 + 1, 공격자=적[0], 피해감소무시=True)
    assert _실드(격) == [보정 - 1, 보정]  # 첫 분신은 부서지고 1이 다음 분신으로
    assert 격["현재HP"] == HP


def test_분신이_모두_부서지면_남은_피해를_본체가_받고_버프가_사라진다(격투가전장):
    전투상태, 격, 적 = 격투가전장
    _분신(전투상태, 격)
    보정 = _보정치(전투상태, 격)
    HP = 격["현재HP"]
    damage.피해_적용(전투상태, 격, 보정 * 3 + 2, 공격자=적[0], 피해감소무시=True)
    assert _실드(격) is None
    assert 격["현재HP"] == HP - 2


def test_분신을_다시_쓰면_실드가_새로_채워진다(격투가전장):
    전투상태, 격, 적 = 격투가전장
    _분신(전투상태, 격)
    보정 = _보정치(전투상태, 격)
    damage.피해_적용(전투상태, 격, 보정, 공격자=적[0], 피해감소무시=True)
    assert len(_실드(격)) == 2
    _분신(전투상태, 격)
    assert _실드(격) == [보정] * 3
