def test_속성_면역_강화_내성(전장, monkeypatch):
    """면역 0, 속성강화/속성내성은 합연산 - 1 + 0.1 x (강화 - 내성)을 방어력 뒤 최종피해에 곱하고
    저항/취약과는 곱연산. 화/수/명/암에만 붙고 무속성은 강화/내성이 없다(사용자 결정 2026-10-12)."""
    _, 전투상태, 적, 아군 = 전장
    p, e = 아군[0], 적[0]
    e["원본"] = dict(e["원본"], 면역=["암속성"], 저항=["수속성"], 취약=["명속성"])
    방어력 = stats.유효_방어력(전투상태, e)
    assert damage.피해_속성배율(전투상태, e, "암속성") == 0

    def 피해(속성, 원래=40):
        e["현재HP"] = 999
        return damage.피해_적용(전투상태, e, 원래, 속성=속성, 공격측=p)

    assert 피해("암속성") == 0  # 면역
    기본 = 40 - 방어력
    assert 피해("화속성") == 기본
    p["버프"].append({"이름": "엘레멘탈 번", "중첩": 2})  # 모든 속성강화 +2
    assert 피해("화속성") == formula.올림(기본 * 1.2)
    assert 피해("수속성") == formula.올림(최종피해(20, 방어력) * 1.2)  # 저항과 곱연산
    assert 피해("명속성") == formula.올림(최종피해(80, 방어력) * 1.2)  # 취약과 곱연산
    assert 피해("암속성") == 0  # 면역은 강화와 상관없이 0
    # 속성내성: 대상 쪽, 속성별 - 특정 속성 버프를 데이터 없이 정의에 넣어 확인
    # 전투상태["버프정의"]는 실제 버프 목록(버프목록)과 같은 딕셔너리다 - 시험용 정의가
    # 다른 테스트(데이터 무결성 등)에 새지 않게 monkeypatch로 넣는다.
    monkeypatch.setitem(
        전투상태["버프정의"],
        "화내성",
        {"효과": [{"변동대상": "속성내성", "속성": "화속성", "변동값": 1}]},
    )
    e["버프"].append({"이름": "화내성", "중첩": 3})
    assert 피해("화속성") == formula.올림(
        기본 * (1 + 0.1 * (2 - 3))
    )  # 합연산: 0.9배(곱연산이면 0.84)
    assert 피해("수속성") == formula.올림(
        최종피해(20, 방어력) * 1.2
    )  # 다른 속성은 그대로
    assert 피해("무속성") == 기본  # 무속성은 강화("전체" 포함)도 내성도 없다
    e["버프"][-1]["중첩"] = 1
    assert 피해("화속성") == formula.올림(기본 * 1.1)
    e["버프"][-1]["중첩"] = 15  # 내성이 훨씬 크면 0 아래로 안 내려감
    assert 피해("화속성") == 0
    assert damage.피해_적용(전투상태, e, 40, 속성=None) == 기본  # 속성 없음(지속피해)


