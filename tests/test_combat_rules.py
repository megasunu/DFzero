def test_수식은_쓰지_않는_일반공격_보정치를_계산하지_않는다():
    """기본_컨텍스트의 "보정치"(평타스탯 중 최대)는 수식에 보정치/보정공격력/무기공격력이 있을 때만 계산한다(#367).
    평타스탯이 빈 참가자도 주문시전보정치·능력치 보정치만 쓰는 수식은 계산되고, 보정치를 쓰는 수식에서만 멈춘다."""
    전투상태, _, 아군 = support.시험_전투(["고블린"])
    p = 아군[0]
    p["원본"]["평타스탯"] = []
    컨텍스트 = stats.기본_컨텍스트(전투상태, p)
    주문 = stats.주문시전_보정치(전투상태, p)
