    assert 평("2d6+3", {}, 평균=True) == 2 * 3.5 + 3
    assert 평("(차수+1)d6÷2", {"차수": 2}, 평균=True) == 3 * 3.5 / 2
    assert 평("보정공격력", {"무기공격력": "1d8", "보정치": 2}, 평균=True) == 4.5 + 2
    assert 평("0d8+1", {}, 평균=True) == 1
