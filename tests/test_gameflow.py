    이름들 = [c["캐릭터명"] for c in 상태["파티"]["파티원"]]
    assert 이름들 == ["가나다라마바", "철수", "abcdefghijkl", "철수abcdefgh"]
    assert (
        gf.이름_자르기("가나다라마bc가") == "가나다라마bc"
    )  # 마지막 한글은 2칸이 모자람


