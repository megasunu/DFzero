def test_옛_세이브를_불러오면_빠진_레벨1_스킬을_보충한다(임시_세이브폴더):
    # 레벨 1 스킬이 나중에 추가되면 그 전에 만든 캐릭터에게는 없다 - 불러올 때
    # 직업 스킬목록의 레벨 1 스킬 중 빠진 것을 보유스킬 끝에 넣는다(있는 것은 그대로).
    상태 = gf.새_게임_시작([("", "귀검사"), ("", "거너")])
    귀검사, 거너 = 상태["파티"]["파티원"]
    assert 귀검사["보유스킬"][:2] == ["귀참", "어퍼 슬래쉬"]
    귀검사["보유스킬"] = ["귀참"]
    거너["보유스킬"] = []
    gf.게임_저장(상태, 1)
    불러옴 = gf.게임_불러오기(1)
    귀검사, 거너 = 불러옴["파티"]["파티원"]
    assert 귀검사["보유스킬"] == ["귀참", "어퍼 슬래쉬"]
    assert 거너["보유스킬"] == ["라이징 샷", "잭스파이크"]
    # 다시 불러와도 겹치지 않는다
    gf.게임_저장(불러옴, 1)
    assert gf.게임_불러오기(1)["파티"]["파티원"][1]["보유스킬"] == [
        "라이징 샷",
        "잭스파이크",
    ]


def test_던전_안에서_저장하면_불러올_때_그_던전_그_위치로(임시_세이브폴더):
    상태 = gf.새_게임_시작([("", j) for j in 기대_직업목록[:4]])
    gf.던전_진입(상태, "dungeon_01A_D01_Lorien")
    for 방향 in ("오른쪽", "왼쪽", "아래", "위"):
        결과 = gf.던전_이동(상태, 방향)
        if 결과["결과"] == "이동":
            break
    if 상태.get("전투상태"):
        상태["전투상태"] = None  # 인카운트가 떴어도 위치 저장만 본다
    던전 = 상태["던전상태"]
    gf.게임_저장(상태, 1)
    불러옴 = gf.게임_불러오기(1)
