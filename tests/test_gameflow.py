def test_세이브_불러오기_왕복(임시_세이브폴더):
    상태 = gf.새_게임_시작([("", j) for j in 기대_직업목록[:4]])
    상태["파티"]["파티원"][0]["현재HP"] -= 1
    gf.게임_저장(상태, 1)
    assert gf.세이브_존재(1)
    assert (임시_세이브폴더 / "slot_1.json").exists()

