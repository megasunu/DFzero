"""마을 [전문직업] -> [인형사] 인형제작(2026-10-19 사용자 결정).

규칙은 docs/game-rules.md "인형사".
"""

import pytest

import gameflow as gf
from game.data.ability.job_ability_040f import 특성목록
from game.data.item.item_doll import 인형_데이터
from tests import support


def _준비(소울=10):
    상태 = support.새게임([("", "귀검사")])
    상태["소지품"]["재료"]["레어 소울"] = 소울
    return 상태


def test_전문직업_메뉴_끝에_인형사가_있고_구현됨이다():
    assert gf.전문직업_메뉴[-1] == "인형사"
    assert "인형사" in gf.전문직업_구현됨


def test_인형제작_목록은_인형마다_재료와_보유수를_보여준다():
    상태 = _준비(소울=4)
    항목 = gf.전문직업_인형목록(상태)[0]  # 상점 인형(#508)이 뒤에 붙는다
    assert 항목["이름"] == "28호"
    assert 항목["재료"] == [("레어 소울", 10, 4)]
    assert 항목["재료글"] == "레어 소울 4/10"
    assert 항목["제작가능"] is False
    상태["소지품"]["재료"]["레어 소울"] = 10
    assert gf.전문직업_인형목록(상태)[0]["제작가능"] is True


def test_인형제작은_레어_소울_10개로_소지품에_인형_1개를_넣고_도감에_등록한다():
    상태 = _준비(소울=12)
    골드 = 상태["소지품"]["골드"]
    gf.전문직업_인형제작(상태, "28호")
    assert 상태["소지품"]["재료"]["레어 소울"] == 2
    assert 상태["소지품"]["소모품"]["28호"] == 1
    assert 상태["소지품"]["골드"] == 골드  # 골드는 들지 않는다
    assert 상태["진행도"]["도감"]["인형"] == ["28호"]
    assert 상태["파티"]["인형"] is None  # 쓰는 것은 소지품 [사용]


def test_인형제작에서_소울을_다_쓰면_재료_항목이_사라진다():
    상태 = _준비(소울=10)
    gf.전문직업_인형제작(상태, "28호")
    assert "레어 소울" not in 상태["소지품"]["재료"]


def test_인형제작은_재료가_모자라면_아무것도_바꾸지_않는다():
    상태 = _준비(소울=9)
    with pytest.raises(ValueError, match="레어 소울이 부족합니다"):
        gf.전문직업_인형제작(상태, "28호")
    assert 상태["소지품"]["재료"]["레어 소울"] == 9
    assert "28호" not in 상태["소지품"]["소모품"]
    assert 상태["진행도"]["도감"].get("인형", []) == []


def test_인형_상세보기는_이름_스타일_수식_능력치_보너스_패턴을_보여준다():
    assert gf.전문직업_인형상세("28호") == [
        "이름: 28호",
        "직업스타일: 캐스터",
        "HP = (6 + 건강보정) + 올림(레벨 × (6 + 건강보정) ÷ 2)",
        "AC = 14 + 민첩보정",
        "근력 8  민첩 12  건강 10  지능 16  지혜 10  매력 10",
        "명중보너스 +0   데미지보너스 +0",
        "무기: 세련된 너클 (바꿀 수 없음)",
        "패턴",
        "1. 넨탄",
        "2. 넨탄",
        "3. 넨탄",
        "4. 활성화 숨결",
        "5. 카이",
        "6. 넨가드",
    ]


def test_28호_데이터에는_제작재료와_두_보너스가_있다():
    인형 = 인형_데이터["28호"]
    assert 인형["제작재료"] == {"레어 소울": 10}
    assert 인형["명중보너스"] == 0 and 인형["데미지보너스"] == 0


def test_특성_인형_28호의_설명은_나선의_넨과_뇌명이다():
    assert 특성목록["인형:28호"]["설명"] == "나선의 넨과 뇌명 상태를 같이 얻는다."


def test_도감에_인형_분류가_있고_인형_데이터가_목록이다():
    상태 = _준비()
    assert gf.도감_대분류목록[-1] == "인형"
    assert gf.도감_탭줄(상태, "인형") == [["인형"]]
    목록 = gf.도감_목록(상태, "인형", "인형")
    assert [항목["이름"] for 항목, _ in 목록] == list(
        인형_데이터
    )  # 28호 + 상점 인형 5(#508)
    assert not any(등록 for _, 등록 in 목록)
    assert gf.도감_등록현황(상태, "인형") == (0, 6)
    gf.전문직업_인형제작(상태, "28호")
    assert gf.도감_등록현황(상태, "인형") == (1, 6)


def test_인형_분류가_없는_옛_도감도_등록할_수_있다():
    상태 = _준비()
    상태["진행도"]["도감"].pop("인형", None)
    gf.전문직업_인형제작(상태, "28호")
    assert 상태["진행도"]["도감"]["인형"] == ["28호"]


def test_모든_인형의_스타일은_밀리_캐스터_하이브리드_중_하나다():
    assert all(
        인형["스타일"] in ("밀리", "캐스터", "하이브리드")
        for 인형 in 인형_데이터.values()
    )
