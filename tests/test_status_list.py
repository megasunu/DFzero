"""전투 화면 효과 목록(#627) - 칸을 누르면 뜨는 팝업에 나열할, 지금 걸린 상태이상·디버프·버프 전부.

아이콘(#623)과 달리 아이콘이 없는 상태도 모두 나오고, 남은 턴·중첩 수를 붙인다(사용자 지정 2026-11-10).
"""

import gameflow as gf
from game.system import rng
from tests.support import 새게임, 전투_열기


def _전투():
    rng.시드(3)
    상태 = 새게임()
    전투_열기(상태, ["고블린"])
    return 상태


def _깨끗이(참가자):
    for 칸 in ("상태이상", "디버프", "버프"):
        참가자[칸] = []


def test_묶음별로_걸린_것_전부를_건_순서대로():
    상태 = _전투()
    적 = gf.적_목록(상태)[0]
    _깨끗이(적)
    적["상태이상"] += [
        {"이름": "도발", "지속턴": 2},  # 아이콘 없음
        {"이름": "출혈", "지속턴": 3, "중첩": 2},
    ]
    적["디버프"] += [{"이름": "명중률감소", "중첩": 1}]
    적["버프"] += [{"이름": "속도증가", "중첩": 4}]
    assert gf.상태_목록(상태, 적) == [
        ("상태이상", ["도발 (2턴)", "출혈 (3턴, 2중첩)"]),
        ("디버프", ["명중률감소"]),
        ("버프", ["속도증가 (4중첩)"]),
    ]


def test_걸린_것이_없으면_빈_목록():
    상태 = _전투()
    아군 = gf.아군_목록(상태)[0]
    _깨끗이(아군)
    assert gf.상태_목록(상태, 아군) == []


def test_홀딩무적은_시전자의_상태이상에():
    상태 = _전투()
    아군 = gf.아군_목록(상태)[0]
    적 = gf.적_목록(상태)[0]
    _깨끗이(아군)
    _깨끗이(적)
    적["상태이상"].append(
        {"이름": "홀딩", "지속턴": 2, "시전자id": 아군["id"], "시전자무적": True}
    )
    assert gf.상태_목록(상태, 아군) == [("상태이상", ["무적 (홀딩)"])]
    assert gf.상태_목록(상태, 적) == [("상태이상", ["홀딩 (2턴)"])]


def test_챔피언_버프는_따로_맨_아래_묶음():
    상태 = _전투()
    적 = gf.적_목록(상태)[0]
    _깨끗이(적)
    적["원본"]["챔피언버프"] = ["흡혈", "재생"]
    적["버프"].append({"이름": "축복"})
    assert gf.상태_목록(상태, 적) == [
        ("버프", ["축복"]),
        ("챔피언 버프", ["흡혈", "재생"]),
    ]


def test_쓰러지거나_도망친_대상은_챔피언_버프만():
    상태 = _전투()
    적 = gf.적_목록(상태)[0]
    적["상태이상"].append({"이름": "출혈", "지속턴": 2})
    적["원본"]["챔피언버프"] = ["흡혈"]
    적["생존"] = False
    assert gf.상태_목록(상태, 적) == [("챔피언 버프", ["흡혈"])]
    적["생존"], 적["도망"] = True, True
    assert gf.상태_목록(상태, 적) == [("챔피언 버프", ["흡혈"])]
