# 자동전투 포션(#177) - 설정 "자동전투 포션"을 켜면 [자동전투] 차례의 아군이 HP 절반 이하일 때
# 공격 전에 쓸 수 있는 HP 회복포션(데이터 순서 첫 것 = 가장 낮은 티어) 하나를 먼저 마신다. 기본은 꺼짐.

import json

import pytest

import gameflow as gf
from game.controller import ctl_autobattle
from support import 새게임, 성장, 아군_차례로, 전투_열기


def _한_턴(상태):
    """현재 아군 차례에 [자동전투]를 한 번 누른다 - 이어지는 몬스터 턴은 돌리지 않는다."""
    원래넘기기 = ctl_autobattle.턴_넘기기
    ctl_autobattle.턴_넘기기 = lambda s: None
    try:
        gf.자동전투_한_턴(상태)
    finally:
        ctl_autobattle.턴_넘기기 = 원래넘기기


def _준비(포션들, HP비율=0.5):
    """귀검사 혼자 타우 아미와 싸우는 차례 - HP를 최대의 HP비율로(내림, 최소 1) 깎아 둔다."""
    상태 = 새게임([("", "귀검사")])
    상태["소지품"]["포션"] = dict(포션들)
    전투_열기(상태, ["타우 아미"])
    현재 = 아군_차례로(상태, "귀검사")
    최대 = gf.캐릭터_최대HP(상태, 현재["원본"])
    현재["현재HP"] = max(1, int(최대 * HP비율))
    return 상태, 현재


def _아이템_로그(상태):
    return [x for x in 상태["전투상태"]["로그"] if x.get("아이템")]


def test_자동전투_포션은_기본_꺼짐이고_꺼져_있으면_마시지_않는다():
    assert gf.자동전투_포션_여부() is False
    상태, 현재 = _준비({"초보자용 HP 포션": 2})
    _한_턴(상태)
    assert 상태["소지품"]["포션"]["초보자용 HP 포션"] == 2
    assert _아이템_로그(상태) == []


@pytest.mark.parametrize("방식", ["일반공격", "전력전투"])
def test_켜면_HP_절반_이하인_아군이_공격_전에_HP포션_하나를_마신다(방식):
    gf.자동전투_포션_설정(True)
    gf.자동전투_방식_설정(방식)
    상태, 현재 = _준비({"초보자용 HP 포션": 2})
    HP전 = 현재["현재HP"]
    보조전 = 현재["행동자원"]["보조행동"]
    _한_턴(상태)
    assert 상태["소지품"]["포션"]["초보자용 HP 포션"] == 1  # 한 턴에 하나만
    로그 = 상태["전투상태"]["로그"]
    아이템 = _아이템_로그(상태)
    assert [x["아이템"] for x in 아이템] == ["초보자용 HP 포션"]
    # 공격보다 먼저 - 이 아군의 첫 행동 로그가 포션
    첫행동 = next(x for x in 로그 if x.get("공격자") == 현재["이름"])
    assert 첫행동.get("아이템") == "초보자용 HP 포션"
    assert 현재["현재HP"] > HP전 or not 현재["생존"]
    assert 현재["행동자원"]["보조행동"] <= 보조전 - 1


def test_HP가_절반을_넘으면_마시지_않는다():
    gf.자동전투_포션_설정(True)
    상태, 현재 = _준비({"초보자용 HP 포션": 1}, HP비율=1.0)
    최대 = gf.캐릭터_최대HP(상태, 현재["원본"])
    현재["현재HP"] = 최대 // 2 + 1
    _한_턴(상태)
    assert 상태["소지품"]["포션"]["초보자용 HP 포션"] == 1


def test_MP포션과_레벨제한에_걸린_포션은_고르지_않는다():
    gf.자동전투_포션_설정(True)
    상태, 현재 = _준비(
        {"초보자용 MP 포션": 3, "입문자용 HP 포션": 3}
    )  # 입문자용은 레벨 6부터
    _한_턴(상태)
    assert 상태["소지품"]["포션"] == {"초보자용 MP 포션": 3, "입문자용 HP 포션": 3}
    assert _아이템_로그(상태) == []


def test_쓸_수_있는_HP포션이_여럿이면_가장_낮은_티어를_마신다():
    gf.자동전투_포션_설정(True)
    상태 = 새게임([("", "귀검사")])
    성장(상태, 상태["파티"]["파티원"][0], 6, 전직="웨펀마스터")
    상태["소지품"]["포션"] = {"입문자용 HP 포션": 1, "초보자용 HP 포션": 1}
    전투_열기(상태, ["타우 아미"])
    현재 = 아군_차례로(상태, "귀검사")
    현재["현재HP"] = 1
    _한_턴(상태)
    assert 상태["소지품"]["포션"] == {"입문자용 HP 포션": 1}


def test_보조행동이_없으면_마시지_않는다():
    gf.자동전투_포션_설정(True)
    상태, 현재 = _준비({"초보자용 HP 포션": 1})
    현재["행동자원"]["보조행동"] = 0
    _한_턴(상태)
    assert 상태["소지품"]["포션"]["초보자용 HP 포션"] == 1


def test_설정_파일에서_자동전투_포션을_켜고_모르는_값은_꺼짐(tmp_path):
    경로 = str(tmp_path / "설정.json")
    with open(경로, "w", encoding="utf-8") as f:
        json.dump({"자동전투포션": True}, f)
    gf.설정_파일_불러오기(경로)
    assert gf.자동전투_포션_여부() is True
    with open(경로, "w", encoding="utf-8") as f:
        json.dump({}, f)
    gf.설정_파일_불러오기(경로)
    assert gf.자동전투_포션_여부() is False
