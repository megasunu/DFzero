# ------------------------------------------------------------------ 5 장판 지속공격(귀신 : 사야)


def test_사야_기대피해는_지속턴만큼_센다(monkeypatch):
    상태, _, p = _전장("귀검사", "소울브링어")
    전체 = gf.스킬_기대피해(상태, p, "귀신 : 사야")
    데이터 = 상태["스킬데이터모음"]["귀신 : 사야"]
    한번 = {**데이터, "지속공격": {**데이터["지속공격"], "지속턴": 1}}
    monkeypatch.setitem(상태["스킬데이터모음"], "귀신 : 사야", 한번)
    한번값 = gf.스킬_기대피해(상태, p, "귀신 : 사야")
    assert 한번값 > 0
    assert 전체 == 한번값 * 데이터["지속공격"]["지속턴"]


# ------------------------------------------------------------------ 6 버프 겹침·버프군·지속(#606)


def _버프_주기(대상, 출처, 지속턴=3):
    대상.setdefault("버프", []).append(
        {"이름": "방어증가", "중첩": 2, "지속턴": 지속턴, "출처스킬": 출처}
    )


def test_같은_버프군이_모두에게_걸려_있으면_걸지_않는다():
    상태, _, p = _전장("거너", "패러메딕")
    for a in gf.아군_목록(상태):
        _버프_주기(a, "수호의 축복")  # 다른 아군(크루세이더)이 건 버프B군
    assert not _쓸만한가(상태, p, "장갑강화")


def test_다른_아군이_건_같은_버프도_겹치지_않는다():
    상태, _, p = _전장("거너", "패러메딕")
    for a in gf.아군_목록(상태):
        _버프_주기(a, "장갑강화")
    assert not _쓸만한가(상태, p, "장갑강화")


def test_곧_끝나는_버프는_다시_건다():
    상태, _, p = _전장("거너", "패러메딕")
    for a in gf.아군_목록(상태):
        _버프_주기(a, "수호의 축복", 지속턴=1)
    assert _쓸만한가(상태, p, "장갑강화")


def test_점수는_새로_받는_대상_수와_지속을_센다():
    상태, _, p = _전장("거너", "패러메딕")
    # 아군 2명 x 버프 3개 x 2중첩 x 지속 3
    assert gf._버프_점수(상태, p, "장갑강화")[2] == 2 * 3 * 2 * 3
    _버프_주기(gf.아군_목록(상태)[1], "수호의 축복")
    assert gf._버프_점수(상태, p, "장갑강화")[2] == 1 * 3 * 2 * 3


def test_지속_가중은_3에서_멈춘다(monkeypatch):
    상태, _, p = _전장("프리스트", "크루세이더")
    모음 = 상태["스킬데이터모음"]
    데이터 = 모음["용맹의 축복"]  # 10턴
    점수 = gf._버프_점수(상태, p, "용맹의 축복")[2]
    monkeypatch.setitem(모음, "용맹의 축복", {**데이터, "지속턴": 3})
    assert gf._버프_점수(상태, p, "용맹의 축복")[2] == 점수
    monkeypatch.setitem(모음, "용맹의 축복", {**데이터, "지속턴": 1})
    assert gf._버프_점수(상태, p, "용맹의 축복")[2] * 3 == 점수


