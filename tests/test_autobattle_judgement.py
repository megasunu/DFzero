# ------------------------------------------------------------------ 8 장판 먼저, 일반행동 약화는 뒤로, 연계 합산(#650)


_공격과_약화 = ["귀신 : 브레멘", "툼스톤", "삼연참", "귀신 : 사야"]


def test_장판이_없으면_사야를_다른_공격보다_먼저_깐다():
    상태, _, p = _전장("귀검사", "소울브링어")
    p["원본"]["보유스킬"] = list(_공격과_약화)
    assert gf.전력전투_고르기(상태, p)[0] == "귀신 : 사야"


def test_사야가_모든_적에게_깔려_있으면_다시_깔지_않는다():
    상태, _, p = _전장("귀검사", "소울브링어")
    p["원본"]["보유스킬"] = list(_공격과_약화)
    for e in gf.적_목록(상태):
        e.setdefault("상태이상", []).append(
            {"이름": "귀신 : 사야", "지속턴": 3, "종류": "지속공격"}
        )
    assert gf.전력전투_고르기(상태, p)[0] not in ("귀신 : 사야", "귀신 : 브레멘")


def test_일반행동_약화는_공격스킬보다_뒤다():
    상태, _, p = _전장("귀검사", "소울브링어")
    p["원본"]["보유스킬"] = list(_공격과_약화)
    for e in gf.적_목록(상태):
        e.setdefault("상태이상", []).append(
            {"이름": "귀신 : 사야", "지속턴": 3, "종류": "지속공격"}
        )
    assert _쓸만한가(상태, p, "귀신 : 브레멘")
    assert gf.전력전투_고르기(상태, p)[0] != "귀신 : 브레멘"
    # 일반공격보다 나은 공격스킬이 없으면 약화를 건다
    p["원본"]["보유스킬"] = ["귀신 : 브레멘"]
    assert gf.전력전투_고르기(상태, p)[0] == "귀신 : 브레멘"


def test_보조행동_약화는_공격보다_먼저다():
    상태, _, p = _전장("귀검사", "소울브링어")
    p["원본"]["보유스킬"] = ["도발", "툼스톤"]
    assert gf.전력전투_고르기(상태, p)[0] == "도발"


def test_공격_평가에_이어_나갈_연계스킬을_따로_더한다():
    상태, _, p = _전장("귀검사", "소울브링어")
    본 = gf.스킬_기대피해(상태, p, "귀참")
    연계 = gf.스킬_기대피해(상태, p, "귀참드라이브", 적수=1)
    assert 연계 > 0
    assert gf.공격_평가(상태, p, "귀참") == 본 + 연계
    # 연계를 낼 MP가 없으면 더하지 않는다
    p["현재MP"] = 5
    assert gf.공격_평가(상태, p, "귀참") == 본
    # 연계스킬이 없는 공격은 그대로
    p["현재MP"] = 999
    assert gf.공격_평가(상태, p, "툼스톤") == gf.스킬_기대피해(상태, p, "툼스톤")
