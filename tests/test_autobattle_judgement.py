# 자동전투 "전력전투" 판단(#602) - 자기 방어 버프, 아군 해제 기준, 버프 고르기, 스킬제한 버프, 장판 기대피해.
# 판단 코드는 game/controller/ctl_autobattle.py.

import gameflow as gf
from game.system import rng
from tests import support


def _전장(직업, 전직, 동료=("격투가",), 적=("고블린", "고블린", "고블린")):
    """직업 -> 전직 레벨 8(스킬 전부 습득)과 동료들 대 적 - 시험자의 차례, 적 HP 999."""
    rng.시드(7)
    상태 = support.새게임([("", 직업)] + [("", j) for j in 동료])
    c = 상태["파티"]["파티원"][0]
    support.성장(상태, c, 8, 전직=전직, 스킬습득=True)
    gf.전투_시작(상태, list(적), 레벨=2, 차수=1)
    support.반응_처리(상태)
    전투상태 = 상태["전투상태"]
    for p in 전투상태["참가자"]:
        if p["진영"] == "적":
            p["현재HP"] = 999
        else:
            p["현재HP"] = gf.캐릭터_최대HP(상태, p["원본"])
    for _ in range(50):
        if gf.현재_턴_참가자(상태)["원본"] is c:
            break
        gf.턴_넘기기(상태)
    p = gf.현재_턴_참가자(상태)
    assert p["원본"] is c
    p["현재MP"] = 999
    return 상태, 전투상태, p


def _쓸만한가(상태, p, 이름):
    return gf._전력전투_쓸만한가(상태, p, 이름, 상태["스킬데이터모음"][이름])


def _최대HP(상태, p):
    return gf.캐릭터_최대HP(상태, p["원본"])


# ------------------------------------------------------------------ 1 자기 방어 버프(가드·무기막기)


def test_가드는_HP가_넉넉하면_쓰지_않는다():
    상태, _, p = _전장("귀검사", "웨펀마스터")
    p["현재HP"] = _최대HP(상태, p)
    assert not _쓸만한가(상태, p, "가드")
    assert gf.전력전투_고르기(상태, p)[0] != "가드"


def test_가드는_HP가_절반_이하면_쓴다():
    상태, _, p = _전장("귀검사", "웨펀마스터")
    p["현재HP"] = _최대HP(상태, p) // 2
    assert _쓸만한가(상태, p, "가드")


def test_무기막기도_같은_기준이다():
    상태, _, p = _전장("프리스트", "크루세이더")
    p["원본"]["보유스킬"].append("무기막기")
    p["현재HP"] = _최대HP(상태, p)
    assert not _쓸만한가(상태, p, "무기막기")
    p["현재HP"] = _최대HP(상태, p) // 2
    assert _쓸만한가(상태, p, "무기막기")


def test_아군_전체_방어_버프는_HP가_넉넉해도_쓴다():
    상태, _, p = _전장("프리스트", "크루세이더")
    p["현재HP"] = _최대HP(상태, p)
    assert _쓸만한가(상태, p, "수호의 축복")


# ------------------------------------------------------------------ 2 아군 해제(큐어)


def _디버프_걸기(대상, 이름):
    대상.setdefault("디버프", []).append({"이름": 이름, "지속턴": 3})


def test_큐어는_아군_해로운_효과가_하나면_쓰지_않는다():
    상태, _, p = _전장("프리스트", "크루세이더")
    _디버프_걸기(gf.아군_목록(상태)[1], "공격력감소")
    assert not _쓸만한가(상태, p, "큐어")


def test_큐어는_아군_해로운_효과가_둘이면_쓴다():
    상태, _, p = _전장("프리스트", "크루세이더")
    아군 = gf.아군_목록(상태)
    _디버프_걸기(아군[0], "공격력감소")
    _디버프_걸기(아군[1], "공격력감소")
    assert _쓸만한가(상태, p, "큐어")


# ------------------------------------------------------------------ 3 버프 고르기


def test_크루세이더는_행동_없는_용맹의_축복_다음에_수호의_축복을_고른다():
    상태, 전투상태, p = _전장("프리스트", "크루세이더")
    assert (
        gf.전력전투_고르기(상태, p)[0] == "용맹의 축복"
    )  # 행동을 쓰지 않는 버프가 먼저
    gf._전력전투_기록(상태)[f"{p['id']}:용맹의 축복"] = 전투상태["라운드"]
    assert gf.전력전투_고르기(상태, p)[0] == "수호의 축복"


def test_패러메딕은_행동_없는_무기강화_다음에_장갑강화를_고른다():
    상태, 전투상태, p = _전장("거너", "패러메딕")
    assert gf.전력전투_고르기(상태, p)[0] == "무기강화"  # 행동을 쓰지 않는 버프가 먼저
    gf._전력전투_기록(상태)[f"{p['id']}:무기강화"] = 전투상태["라운드"]
    assert gf.전력전투_고르기(상태, p)[0] == "장갑강화"  # 목록에서 앞선 공중사격보다


def test_HP가_절반_이하면_자기_방어가_다른_버프보다_먼저다():
    상태, 전투상태, p = _전장("귀검사", "웨펀마스터")
    p["현재HP"] = _최대HP(상태, p) // 2
    for s in p["원본"]["보유스킬"]:  # 행동을 쓰지 않는 버프는 이미 걸었다
        if 상태["스킬데이터모음"][s].get("행동") is None:
            gf._전력전투_기록(상태)[f"{p['id']}:{s}"] = 전투상태["라운드"]
    assert gf.전력전투_고르기(상태, p)[0] == "가드"


