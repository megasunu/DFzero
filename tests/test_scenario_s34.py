"""S34 소울브링어 골드 스킬 실전 - 귀신 : 브레멘(디버프스킬), 귀신 : 라사(장판 지속공격), 툼스톤 (docs/scenarios.md, #350).

귀검사가 든 4인 파티를 레벨 8까지 키운다(귀검사는 5->6에 소울브링어, 나머지는 기본 전직, 스킬 전부 습득).
선더랜드(D05) 인카운트를 **실제 전투로** 치른다. 소울브링어는 차례마다 세 스킬 중 그 전투에서 아직 안 쓴
것을 쓰고(시작 스킬은 전투마다 라사 -> 툼스톤 -> 브레멘으로 돌린다) 남은 일반행동으로 일반공격한다. 나머지 파티원은 일반공격만 해서
(스킬로 한 라운드에 끝나지 않게) 라운드가 끝날 때의 라사가 실제로 나오게 한다.
라사가 명중 굴림 없이 건강 내성으로 치는지, 라운드가 끝날 때만 치는지, 툼스톤이 한 번에 많아야 6번 치는지를
본다. 수치 규칙은 tests/test_job_soul_bender.py가 값으로 검사한다.
"""

import pytest

from game.system import rng
import gameflow as gf
import scenario
import support
from tests.support import 구현된_전직

선더랜드 = "dungeon_01A_D05_thunderland"
시드 = 0
파티구성 = [("", "귀검사"), ("", "격투가"), ("", "거너"), ("", "프리스트")]
전직표 = dict(구현된_전직, 귀검사="소울브링어")


_스킬들 = ("귀신 : 라사", "툼스톤", "귀신 : 브레멘")


def _소울브링어_턴(상태, sb, 기록, 번호):
    """전투마다 시작 스킬을 돌린다(번호 0: 라사, 1: 툼스톤, 2: 브레멘) - 한 전투에 쓴 것은 다시 안 쓰고 다음 것."""
    쓴것 = 기록.setdefault("_쓴것", [])
    순서 = _스킬들[번호 % 3 :] + _스킬들[: 번호 % 3]
    이름 = next(
        (n for n in 순서 if n not in 쓴것), 순서[1]
    )  # 셋 다 썼으면 툼스톤/다음 것
    적들 = scenario._살아있는_적(상태)
    if 적들 and gf.스킬_사용_가능여부(상태, sb, 이름)[0]:
        gf.아군_스킬사용(상태, 이름, 중심대상=적들[0])
        기록[이름] = 기록.get(이름, 0) + 1
        쓴것.append(이름)
    _일반공격_턴(상태, sb)


def _일반공격_턴(상태, 참가자):
    전투상태 = 상태["전투상태"]
    while 전투상태["종료"] is None and 참가자["생존"]:
        적들 = scenario._살아있는_적(상태)
        if not 적들 or 참가자["행동자원"].get("일반행동", 0) <= 0:
            break
        gf.아군_일반공격(상태, 적들[0])
    if 전투상태["종료"] is None:
        gf.턴_넘기기(상태)


def _전투(상태, 기록, 번호):
    support.반응_처리(상태)
    전투상태 = 상태["전투상태"]
    라사_라운드 = []  # 라사가 친 차례 뒤의 라운드 번호 - 라운드 끝에 치므로 다음 라운드 번호다
    라운드밖 = 0  # 라운드가 넘어가지 않은 차례에 나온 라사 타격(있으면 안 된다)
    for _ in range(400):
        if gf.전투_종료됨(상태):
            break
        참가자 = gf.현재_턴_참가자(상태)
        로그수, 라운드 = len(전투상태["로그"]), 전투상태["라운드"]
        if 참가자["진영"] == "아군" and 참가자["생존"]:
            if 참가자["원본"].get("전직") == "소울브링어":
                _소울브링어_턴(상태, 참가자, 기록, 번호)
            else:
                _일반공격_턴(상태, 참가자)
        else:
            gf.턴_넘기기(상태)
        친것 = [
            항목
            for 항목 in 전투상태["로그"][로그수:]
            if isinstance(항목, dict)
            and 항목.get("스킬") == "귀신 : 라사"
            and 항목.get("타격")
        ]
        if 친것 and 전투상태["라운드"] == 라운드 and 전투상태["종료"] is None:
            라운드밖 += len(친것)
        if 친것:
            라사_라운드.append(전투상태["라운드"])
    else:
        raise AssertionError("전투가 끝나지 않았다")
    로그 = [항목 for 항목 in 전투상태["로그"] if isinstance(항목, dict)]
    라사 = [
        t
        for 항목 in 로그
        if 항목.get("스킬") == "귀신 : 라사"
        for t in 항목.get("타격") or []
    ]
    기록["라사타격"] = len(라사)
    기록["라사명중굴림"] = sum(1 for t in 라사 if "판정" in t)
    기록["라사내성실패"] = sum(1 for t in 라사 if t.get("내성") == "실패")
    기록["툼스톤타수"] = [
        len(항목.get("타격") or [])
        for 항목 in 로그
        if 항목.get("스킬") == "툼스톤" and 항목.get("종류") == "타격"
    ]
    기록["라사라운드"] = sorted(set(라사_라운드))
    기록["라사라운드밖"] = 라운드밖
    기록.pop("_쓴것", None)
    return 전투상태["종료"]


@pytest.mark.scenario("S34")
def test_S34_소울브링어_골드_스킬_실전(golden):
    rng.시드(시드)
    상태 = support.새게임(파티구성)
    파티 = 상태["파티"]["파티원"]
    for c in 파티:
        support.성장(상태, c, 8, 전직=전직표[c["직업"]], 스킬습득=True)
    gf.파티_최대치로_회복(상태)
    [sb] = [c for c in 파티 if c["직업"] == "귀검사"]
    assert {"귀신 : 브레멘", "귀신 : 라사", "툼스톤"} <= set(sb["보유스킬"])

    gf.던전_진입(상태, 선더랜드)
    전투들 = []
    for 번호 in range(6):
        적 = scenario.인카운트까지_걷기(상태)
        기록 = {}
        종료 = _전투(상태, 기록, 번호)
        assert gf.전투_결과_정리(상태) == 종료 == "아군승리"
        scenario.보상_수령(상태)
        gf.휴식(상태)
        gf.던전_진입(상태, 선더랜드)
        전투들.append({"적": 적, **기록})
        if all(
            sum(b.get(k, 0) for b in 전투들)
            for k in ("라사타격", "툼스톤", "귀신 : 브레멘")
        ):
            break

    def 합계(키):
        return sum(b.get(키, 0) for b in 전투들)

    assert 합계("귀신 : 브레멘") and 합계("귀신 : 라사") and 합계("툼스톤"), 전투들
    assert 합계("라사타격"), 전투들
    assert 합계("라사명중굴림") == 0  # 장판스킬 지속공격은 명중 굴림이 없다
    assert 합계("라사라운드밖") == 0  # 시전자 턴 끝이 아니라 라운드가 끝날 때만 친다
    assert all(1 <= n <= 6 for b in 전투들 for n in b["툼스톤타수"]), 전투들
    golden("scenario_S34_soul_bender_gold", 전투들)
