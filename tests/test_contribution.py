def _끄기(전투상태, 참가자):
    전투상태["기여끄기"] = 참가자["id"]


# ------------------------------------------------------------------ 끄기


def test_끄지_않으면_건_사람을_남기지_않는다():
    """보통 전투는 그대로 - 버프 인스턴스에 칸이 늘지 않는다(골든 불변)."""
    전투상태, 적, 아군 = 시험_전투(["고블린"])
    skill_grant.이름있는효과_부여(전투상태, 아군[1], "뇌명", 시전자=아군[0])
    assert "부여자id" not in 아군[1]["버프"][-1]


def test_끈_버퍼가_남에게_건_버프는_수치에_들어가지_않는다():
    전투상태, 적, 아군 = 시험_전투(["고블린"])
    전 = stats.버프디버프_수치(전투상태, 아군[1], "명중보너스")
    _끄기(전투상태, 아군[0])
    skill_grant.이름있는효과_부여(전투상태, 아군[1], "뇌명", 시전자=아군[0])
    assert 아군[1]["버프"][-1]["부여자id"] == 아군[0]["id"]  # 버프는 걸려 있다
    assert stats.버프디버프_수치(전투상태, 아군[1], "명중보너스") == 전
    전투상태["기여끄기"] = 아군[2]["id"]  # 다른 사람을 끄면 효과가 난다
    assert stats.버프디버프_수치(전투상태, 아군[1], "명중보너스") > 전


def test_끈_버퍼가_자기에게_건_버프는_그대로():
    전투상태, 적, 아군 = 시험_전투(["고블린"])
    전 = stats.버프디버프_수치(전투상태, 아군[0], "명중보너스")
    _끄기(전투상태, 아군[0])
    skill_grant.이름있는효과_부여(전투상태, 아군[0], "뇌명", 시전자=아군[0])
    assert stats.버프디버프_수치(전투상태, 아군[0], "명중보너스") > 전


def test_끈_버퍼가_적에게_건_디버프도_수치에_들어가지_않는다():
    전투상태, 적, 아군 = 시험_전투(["고블린"])
    전 = stats.최종AC(전투상태, 적[0])
    _끄기(전투상태, 아군[0])
    skill_grant.이름있는효과_부여(전투상태, 적[0], "회피률감소", 시전자=아군[0])
    assert 적[0]["디버프"][-1]["부여자id"] == 아군[0]["id"]
    assert stats.최종AC(전투상태, 적[0]) == 전
    del 전투상태["기여끄기"]
    assert stats.최종AC(전투상태, 적[0]) < 전


def test_끈_버퍼의_효과원소_버프도_꺼진다():
    """숫자로 더하지 않는 효과(이점·추가 피해 등 - 버프_효과원소목록)도 끈다."""
    전투상태, 적, 아군 = 시험_전투(["고블린"])
