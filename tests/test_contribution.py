def test_명중확률은_d20과_자연20_펌블을_본다():
    assert contribution.명중확률(0, 11) == pytest.approx(0.5)
    assert contribution.명중확률(0, 30) == pytest.approx(0.05)  # 20은 맞는다
    assert contribution.명중확률(30, 5) == pytest.approx(0.95)  # 1은 빗나간다
    assert contribution.명중확률(2, 11) - contribution.명중확률(1, 11) == pytest.approx(
        0.05
    )


def test_기대값은_전투_없이_버프의_명중과_피해_몫을_낸다():
    전투상태, 적, 아군 = 시험_전투(["고블린"])
    전 = contribution.일반공격_기대피해(전투상태, 아군[1], 적[0])
    아군[1]["버프"].append({"이름": "뇌명", "중첩": 1})  # 명중 +1
    후 = contribution.일반공격_기대피해(전투상태, 아군[1], 적[0])
    assert 후 > 전 > 0


