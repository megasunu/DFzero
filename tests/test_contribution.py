def _크루세이더_전장(끄기):
    import copy

    m = bs.측정("크루세이더")
    상태 = copy.deepcopy(m._상태(m.기본파티))
    m.gf.휴식(상태)
    m.gf.전투_시작(상태, ["고블린"], 레벨=20, 차수=3)
    전투상태 = 상태["전투상태"]
    나 = next(
        p
        for p in 전투상태["참가자"]
        if p["원본"].get("캐릭터명") == 상태["파티"]["파티원"][0]["캐릭터명"]
    )
    if 끄기:
        _끄기(전투상태, 나)
    남 = next(p for p in 전투상태["참가자"] if p["진영"] == "아군" and p is not 나)
    return 상태, 전투상태, 나, 남


@pytest.mark.parametrize("끄기", [False, True])
def test_끈_전투에서도_버퍼는_같은_비용을_내고_버프도_걸린다(끄기):
    """용맹의 축복(아군 전체 근력·지능) - 끈 판에서도 버프는 걸리지만 남의 근력은 그대로다."""
    from game.system import skill_system

    상태, 전투상태, 나, 남 = _크루세이더_전장(끄기)
    근력 = stats.유효_능력치값(전투상태, 남, "근력")
    skill_system.스킬_실행(
        전투상태, 나, "용맹의 축복", 상태["스킬데이터모음"]["용맹의 축복"]
    )
    assert any(b["이름"] == "근력증가" for b in 남["버프"])
    늘었다 = stats.유효_능력치값(전투상태, 남, "근력") > 근력
    assert 늘었다 is not 끄기
    assert stats.유효_능력치값(전투상태, 나, "근력") > 0  # 자기 버프는 그대로


def test_끈_판과_본_판의_비용은_같다():
    from game.system import skill_system

    쓴것 = []
    for 끄기 in (False, True):
        상태, 전투상태, 나, 남 = _크루세이더_전장(끄기)
        데이터 = 상태["스킬데이터모음"]["용맹의 축복"]  # 휴식당 1회, MP 0
        전 = (나["현재MP"], skill_system.휴식_남은횟수(전투상태, 나, 데이터))
        # 화면·자동전투가 스킬 전에 내는 비용
        skill_system.자원_소비_처리(전투상태, 나, 데이터)
        skill_system.스킬_실행(전투상태, 나, "용맹의 축복", 데이터)
        후 = (나["현재MP"], skill_system.휴식_남은횟수(전투상태, 나, 데이터))
        쓴것.append((전, 후))
    assert 쓴것[0] == 쓴것[1] and 쓴것[0][0] != 쓴것[0][1]  # 같은 비용을 냈다


