def test_지표는_기여도를_지분에서_뺀다():
    """두 판 평균값으로 - A는 혼자 친다, B는 A에게 버프를 줘서 A의 딜을 40에서 60으로 올리고 받는 피해를 30에서 20으로 줄인다."""
    본 = {"딜": {"A": 60, "B": 40}, "받음": {"A": 20, "B": 30}}
    끈 = {
        "A": {"딜": {"A": 60, "B": 40}, "받음": {"A": 20, "B": 30}},
        "B": {"딜": {"A": 40, "B": 40}, "받음": {"A": 30, "B": 30}},
    }
    지표 = contribution.지표_계산(본, 끈)
    # 딜: 파티 100 - A 직접 60 중 20은 B 몫 -> A 40%, B 직접 40% + 기여 20%
    assert 지표["A"]["딜지분"] == pytest.approx(40)
    assert 지표["B"]["딜지분"] == pytest.approx(40)
    assert 지표["B"]["딜기여도"] == pytest.approx(20)
    assert 지표["A"]["딜기여도"] == pytest.approx(0)
    # 탱: 실제 50 + B가 막아 준 10 = 60 - A는 버프 없이 받았을 30(50%), B 30(50%), B 기여 10(1/6)
    assert 지표["A"]["탱지분"] == pytest.approx(50)
    assert 지표["B"]["탱지분"] == pytest.approx(50)
    assert 지표["B"]["탱기여도"] == pytest.approx(100 * 10 / 60)


def test_자기를_끈_전투의_자기_딜은_기여로_세지_않는다():
    본 = {"딜": {"A": 50, "B": 50}, "받음": {"A": 0, "B": 0}}
    끈 = {
        "A": {"딜": {"A": 50, "B": 50}, "받음": {"A": 0, "B": 0}},
        "B": {
            "딜": {"A": 50, "B": 10},
            "받음": {"A": 0, "B": 0},
        },  # B 본인 딜 변화는 노이즈
    }
    지표 = contribution.지표_계산(본, 끈)
    assert 지표["B"]["딜기여도"] == 0 and 지표["B"]["딜지분"] == pytest.approx(50)


