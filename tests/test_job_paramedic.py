@pytest.fixture
def 메딕전장():
    """거너 -> 패러메딕 레벨 8(골드 스킬 전부 습득)과 프리스트 -> 크루세이더 레벨 8, 고블린 셋(HP 999)."""
    rng.시드(5)
    상태 = support.새게임([("", "거너"), ("", "프리스트")])
    메딕, 크루 = 상태["파티"]["파티원"]
    support.성장(상태, 메딕, 8, 전직="패러메딕", 스킬습득=True)
    support.성장(상태, 크루, 8, 전직="크루세이더", 스킬습득=True)
    gf.전투_시작(상태, ["고블린", "고블린", "고블린"], 레벨=2, 차수=1)
    support.반응_처리(상태)
    전투상태 = 상태["전투상태"]
    적 = [p for p in 전투상태["참가자"] if p["진영"] == "적"]
    for p in 적:
        p["현재HP"] = p["최대HP"] = 999
    m = next(p for p in 전투상태["참가자"] if p["원본"] is 메딕)
    k = next(p for p in 전투상태["참가자"] if p["원본"] is 크루)
    return 상태, 전투상태, 적, m, k


def _스킬(이름):
    return dict(gf.스킬데이터모음_생성()[이름], _이름=이름)


def _쓰기(전투상태, p, 이름, 대상=None):
    p["행동자원"].update(일반행동=1, 보조행동=1)
    p["현재MP"] = max(p["현재MP"], 50)
    return ss.스킬_실행(전투상태, p, 이름, _스킬(이름), 대상)


def _d20(monkeypatch, 눈):
    monkeypatch.setattr(stats.dice_utils, "d20_굴림", lambda 이점=False, 불리=False: 눈)
    monkeypatch.setattr(rng.주사위, "randint", lambda a, b: b)


def _버프(p, 이름):
    return [b for b in p["버프"] if b["이름"] == 이름]


def test_레벨6에_특성_둘을_레벨8에_무기강화를_얻고_골드_스킬을_산다(메딕전장):
    _, _, _, m, _ = 메딕전장
    c = m["원본"]
    assert {"강습슈트", "전장정보"} <= set(c["보유특성"])
    assert {
        "무기강화",
        "기동강화",
        "장갑강화",
        "정화모듈",
        "완충모듈",
        "확인사격",
        "후퇴기동",
        "지정사격",
    } <= set(c["보유스킬"])
    assert "훔쳐배우기스킬" in _스킬("후퇴기동")["타입"]


def test_강습슈트는_AC_명중_속도를_전장정보는_속성내성을_올린다(메딕전장):
    _, 전투상태, _, m, _ = 메딕전장
    assert traits.특성_수치(전투상태, m, "AC") >= 1
    assert traits.특성_수치(전투상태, m, "명중보너스") >= 1
    assert traits.특성_수치(전투상태, m, "속도") >= 2
    for 속성 in ("화속성", "수속성", "명속성", "암속성"):
        assert stats.속성_보정합(전투상태, m, "속성내성", 속성) >= 1


def test_전장정보는_지능과_지혜를_1씩_올린다():
    상태 = support.새게임([("", "거너")])
    c = 상태["파티"]["파티원"][0]
    support.성장(상태, c, 5)
    지능, 지혜 = c["지능"], c["지혜"]
    support.성장(상태, c, 6, 전직="패러메딕")
    assert (c["지능"], c["지혜"]) == (지능 + 1, 지혜 + 1)


def test_무기강화와_용맹의_축복은_MP_0_휴식당_1회_버프A군():
    for 이름 in ("무기강화", "용맹의 축복"):
        스킬 = _스킬(이름)
        assert 스킬["MP소모"] == 0 and 스킬["휴식당횟수"] == 1, 이름
        assert "버프A군" in 스킬["타입"], 이름
        assert 스킬["버프획득"] == ["근력증가", "지능증가"] and 스킬["지속턴"] == 10
    assert "버프B군" in _스킬("수호의 축복")["타입"]
    assert "버프B군" in _스킬("장갑강화")["타입"]
    assert "버프C군" in _스킬("신성한 빛")["타입"]
    assert "버프C군" in _스킬("완충모듈")["타입"]
    assert "버프D군" in _스킬("기동강화")["타입"]


def test_같은_군의_버프는_겹치지_않고_나중에_건_것만_남는다(메딕전장):
    _, 전투상태, _, m, k = 메딕전장
    _쓰기(전투상태, k, "용맹의 축복")
    assert {b.get("출처스킬") for b in _버프(m, "근력증가")} == {"용맹의 축복"}
    _쓰기(전투상태, m, "무기강화")
    assert {b.get("출처스킬") for b in _버프(m, "근력증가")} == {"무기강화"}
    assert {b.get("출처스킬") for b in _버프(k, "지능증가")} == {"무기강화"}
    _쓰기(전투상태, k, "수호의 축복")
    _쓰기(전투상태, m, "장갑강화")
    assert {b.get("출처스킬") for b in _버프(m, "방어증가")} == {"장갑강화"}
    # 다른 군(A군 무기강화)은 그대로
    assert _버프(m, "근력증가")


def test_기동강화는_아군_전체_AC_1_속도_5_3턴(메딕전장):
    _, 전투상태, _, m, k = 메딕전장
    AC = stats.최종AC(전투상태, k)
    속도 = stats.버프디버프_수치(전투상태, k, "속도")
    _쓰기(전투상태, m, "기동강화")
    assert stats.최종AC(전투상태, k) == AC + 1
    assert stats.버프디버프_수치(전투상태, k, "속도") == 속도 + 5
    assert _버프(k, "기동강화")[0]["지속턴"] == 3
    assert _스킬("기동강화")["MP소모"] == 10


def test_정화모듈은_큐어처럼_디버프를_지운다(메딕전장):
    _, 전투상태, _, m, k = 메딕전장
    ss.이름있는효과_부여(전투상태, k, "방어감소", 1)
    assert k["디버프"]
    _쓰기(전투상태, m, "정화모듈")
    assert not k["디버프"]
    assert _스킬("정화모듈")["휴식당횟수"] == 5


def test_완충모듈_임시생명력은_피해를_막고_3턴_뒤_사라진다(메딕전장, monkeypatch):
    _, 전투상태, 적, m, k = 메딕전장
    _d20(monkeypatch, 15)
    _쓰기(전투상태, m, "완충모듈")
    버프 = _버프(k, "완충모듈")
    assert 버프 and 버프[0]["지속턴"] == 3 and 버프[0]["임시생명력"] > 0
    양 = 버프[0]["임시생명력"]
    HP = k["현재HP"]
    damage.피해_적용(전투상태, k, 1, 피해감소무시=True, 공격자=적[0])
    assert k["현재HP"] == HP and 버프[0]["임시생명력"] == 양 - 1
    k["버프"].remove(버프[0])  # 지속턴이 다 되면 버프와 함께 사라진다
    damage.피해_적용(전투상태, k, 1, 피해감소무시=True, 공격자=적[0])
    assert k["현재HP"] == HP - 1


def test_완충모듈과_신성한_빛은_C군이라_겹치지_않는다(메딕전장):
    _, 전투상태, _, m, k = 메딕전장
    _쓰기(전투상태, k, "신성한 빛")
    assert _버프(m, "신성한 빛")
    _쓰기(전투상태, m, "완충모듈")
    assert not _버프(m, "신성한 빛") and _버프(m, "완충모듈")


@pytest.mark.parametrize("이름", ["확인사격", "용아", "지정사격"])
def test_확인사격_용아_지정사격은_필중이고_치명타가_나지_않는다(
    메딕전장, monkeypatch, 이름
):
    _, 전투상태, 적, m, _ = 메딕전장
    _d20(monkeypatch, 20)
    결과 = _쓰기(전투상태, m, 이름, 적[0])
    assert 결과["타격"] and all(t["판정"]["성공"] for t in 결과["타격"])
    assert not any(t["판정"]["치명타"] for t in 결과["타격"])


def test_지정사격은_3회_확인사격은_5MP_사격(메딕전장, monkeypatch):
    _, 전투상태, 적, m, _ = 메딕전장
    _d20(monkeypatch, 15)
    assert len(_쓰기(전투상태, m, "지정사격", 적[0])["타격"]) == 3
    assert _스킬("지정사격")["MP소모"] == 20
    확인 = _스킬("확인사격")
    assert 확인["MP소모"] == 5 and 확인["일반공격취급"] and "사격" in 확인["타입"]
    assert "사격" in _스킬("지정사격")["타입"] and "사격" in _스킬("후퇴기동")["타입"]


@pytest.mark.parametrize("눈", [1, 15])
def test_후퇴기동은_명중과_상관없이_회피률증가_2스택_2턴(메딕전장, monkeypatch, 눈):
    _, 전투상태, 적, m, _ = 메딕전장
    _d20(monkeypatch, 눈)
    _쓰기(전투상태, m, "후퇴기동", 적[0])
    회피 = _버프(m, "회피률증가")
    assert sum(b.get("중첩", 1) for b in 회피) == 2
    assert all(b["지속턴"] == 2 for b in 회피)
    스킬 = _스킬("후퇴기동")
    assert 스킬["MP소모"] == 10 and 스킬["일반공격취급"]


