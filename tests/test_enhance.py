@pytest.mark.parametrize(
    "선택지, 재료",
    [
        ("무기강화", "라이언 코크스"),
        ("무기증폭", "모순의 결정체"),
        ("무기재련", "강렬한 기운"),
    ],
)
def test_강화는_라이언_코크스_증폭은_모순의_결정체_재련은_강렬한_기운을_소울만큼_쓴다(
    선택지, 재료
):
    상태 = _준비(소울=5)
    상태["소지품"]["장비"][언커먼무기] = 1
