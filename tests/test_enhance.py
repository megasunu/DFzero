def test_무기강화는_무기_주사위에_1d4를_더하고_가격과_소울을_치른다():
    상태 = _준비(골드=1000, 소울=5)
    상태["소지품"]["장비"][언커먼무기] = 1
    새이름 = _강화(상태, "무기강화", 언커먼무기)
    assert 새이름 == "+1강 강철 소검"
    무기 = 상태["상점카탈로그"]["장비"]["무기"][새이름]
    assert 무기["무기공격력"] == "1d6+1d4"
    assert 무기["강화원본"] == 언커먼무기 and 무기["강화"] == 1
    assert 상태["소지품"]["골드"] == 1000 - 100 * 1  # 가격 x (0+1)^2
    assert 상태["소지품"]["재료"]["언커먼 소울"] == 5 - 1
    assert 상태["소지품"]["재료"]["라이언 코크스"] == 5 - 1
    assert 상태["소지품"]["장비"] == {**상태["소지품"]["장비"], 새이름: 1}
    assert 언커먼무기 not in 상태["소지품"]["장비"]


def test_비용은_가격_곱하기_현재수치더하기1의_제곱이고_최대는_장비의_차수다():
    상태 = _준비(골드=10000, 소울=10)
    상태["소지품"]["장비"][유니크무기] = 1
    첫비용 = _항목(상태, "무기강화", 유니크무기)["비용"]
    assert 첫비용 == {"골드": 400, "유니크 소울": 1, "라이언 코크스": 1}
    이름 = _강화(상태, "무기강화", 유니크무기)
    항목 = _항목(상태, "무기강화", 이름)
    assert 항목["비용"] == {"골드": 400 * 4, "유니크 소울": 4, "라이언 코크스": 4}
    이름 = gf.전문직업_강화(상태, 항목, "무기강화")
    assert 이름 == "+2강 성물:로켈의 글라디우스"
    assert 상태["소지품"]["골드"] == 10000 - 400 - 1600
    assert 상태["소지품"]["재료"]["유니크 소울"] == 10 - 1 - 4
    # 2티어 무기는 +2까지
    항목 = _항목(상태, "무기강화", 이름)
    assert 항목["불가"] and "최대" in 항목["불가"]
    with pytest.raises(ValueError):
        gf.전문직업_강화(상태, 항목, "무기강화")


def test_강화와_증폭은_하나만_재련은_함께_된다():
    상태 = _준비()
    상태["소지품"]["장비"][언커먼무기] = 1
    이름 = _강화(상태, "무기강화", 언커먼무기)
    assert "강화" in _항목(상태, "무기증폭", 이름)["불가"]
    with pytest.raises(ValueError):
        gf.전문직업_강화(상태, _항목(상태, "무기증폭", 이름), "무기증폭")
    이름 = _강화(상태, "무기재련", 이름)
    assert 이름 == "+1강1재 강철 소검"
    무기 = 상태["상점카탈로그"]["장비"]["무기"][이름]
    원본 = 상태["상점카탈로그"]["장비"]["무기"][언커먼무기]
    assert 무기["명중률보너스"] == 원본["명중률보너스"] + 1
    assert 무기["무기공격력"] == "1d6+1d4"
    # 증폭한 무기는 강화할 수 없다
    상태["소지품"]["장비"][언커먼무기] = 1
    증폭 = _강화(상태, "무기증폭", 언커먼무기)
    assert 증폭 == "+1증 강철 소검"
    assert "증폭" in _항목(상태, "무기강화", 증폭)["불가"]


