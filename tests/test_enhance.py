    assert dismantle_system.소울_이름(카탈로그[이름]) == "언커먼 소울"
    전 = dict(상태["소지품"]["재료"])
    gf.상점_해체(상태, "무기", 언커먼무기, 1)
    원본몫 = {k: v - 전.get(k, 0) for k, v in 상태["소지품"]["재료"].items()}
    전 = dict(상태["소지품"]["재료"])
    gf.상점_해체(상태, "무기", 이름, 1)
