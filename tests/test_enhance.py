def _방어구_다섯(상태, 강화할수):
    귀검사 = 상태["파티"]["파티원"][0]
    이름들 = [f"실키얀 {부위}" for 부위 in ("상의", "하의", "어깨", "벨트", "신발")]
    for 부위, 이름 in zip(("상의", "하의", "어깨", "벨트", "신발"), 이름들):
        _장착(상태, 부위, 이름)
    for 이름 in 이름들[:강화할수]:
        _강화(상태, "방어구강화", 이름, 착용=True)
    return 귀검사


def _AC(상태, 귀검사):
    return equipment_system.최종AC_계산(귀검사, _장착데이터(상태))


def test_방어구_강화_합계_5당_AC가_1_오른다():
    상태 = _준비()
    귀검사 = _방어구_다섯(상태, 0)
    기본 = _AC(상태, 귀검사)
    상태 = _준비()
    귀검사 = _방어구_다섯(상태, 4)
    assert _AC(상태, 귀검사) == 기본
    assert 귀검사["장착장비"]["상의"] == "+1강 실키얀 상의"
    상태 = _준비()
    귀검사 = _방어구_다섯(상태, 5)
    assert _AC(상태, 귀검사) == 기본 + 1


