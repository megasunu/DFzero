유니크무기 = "성물:로켈의 글라디우스"  # 유니크 2티어 400G 1d6


def _준비(골드=100000, 소울=100):
    상태 = support.새게임([("", "귀검사")])
    소지품 = 상태["소지품"]
    소지품["골드"] = 골드
    for 레어도 in ("언커먼", "레어", "유니크", "레전더리"):
        소지품["재료"][f"{레어도} 소울"] = 소울
    for 재료 in ("라이언 코크스", "모순의 결정체", "강렬한 기운"):
        소지품["재료"][재료] = 소울
    return 상태


def _항목(상태, 선택지, 이름, 착용=None):
    for 항목 in gf.전문직업_강화목록(상태, 선택지):
        if 항목["이름"] == 이름 and (항목["캐릭터"] is not None) == bool(착용):
            return 항목
    raise AssertionError(f"{선택지} 목록에 {이름} 없음")


def _강화(상태, 선택지, 이름, 착용=None):
    return gf.전문직업_강화(상태, _항목(상태, 선택지, 이름, 착용), 선택지)


def _장착(상태, 슬롯, 이름):
    귀검사 = 상태["파티"]["파티원"][0]
    상태["소지품"]["장비"][이름] = 상태["소지품"]["장비"].get(이름, 0) + 1
    gf.장비_교체(상태, 귀검사, 슬롯, 이름)
    return 귀검사


def _장착데이터(상태):
    return 상태["장비데이터모음"][상태["파티"]["파티원"][0]["캐릭터명"]]


