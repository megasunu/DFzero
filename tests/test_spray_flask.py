def test_플라스크는_마을과_던전에서_캐릭터에게_쓰고_속성이_쌓인다():
    상태 = 새게임([("", "귀검사"), ("", "마법사")])
    귀검사, 마법사 = 상태["파티"]["파티원"]
    상태["소지품"]["소모품"] = {"샐러맨더 플라스크": 2, "어둠의 속삭임 포션": 1}
    종류들 = {a["이름"]: 종류 for a, _, 종류 in gf.소지품_목록(상태, "소모품", "부여")}
    assert 종류들 == {"샐러맨더 플라스크": "부여", "어둠의 속삭임 포션": "부여"}

    assert "화속성" in gf.캐릭터_부여아이템사용(상태, 귀검사, "샐러맨더 플라스크")
    assert 귀검사["무기속성부여"] == ["화속성"] and "무기속성부여" not in 마법사
    with pytest.raises(ValueError, match="이미"):
        gf.캐릭터_부여아이템사용(상태, 귀검사, "샐러맨더 플라스크")
    assert 상태["소지품"]["소모품"]["샐러맨더 플라스크"] == 1  # 막히면 줄지 않는다

    gf.던전_진입(상태, 로리엔)
    gf.캐릭터_부여아이템사용(상태, 귀검사, "어둠의 속삭임 포션")
    assert 귀검사["무기속성부여"] == ["화속성", "암속성"]
    assert "어둠의 속삭임 포션" not in 상태["소지품"]["소모품"]
    with pytest.raises(ValueError, match="없다"):
        gf.캐릭터_부여아이템사용(상태, 마법사, "알리시아 플라스크")


