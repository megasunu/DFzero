def _왕복(상태):
    x, y = 상태["던전상태"]["위치"]
    for 가기, 돌아오기, (dx, dy) in (
        ("오른쪽", "왼쪽", (1, 0)),
        ("왼쪽", "오른쪽", (-1, 0)),
        ("아래", "위", (0, 1)),
        ("위", "아래", (0, -1)),
    ):
        if dungeon_system.칸_문자(상태["던전상태"]["그리드"], (x + dx, y + dy)) == "O":
            return 가기, 돌아오기
    raise AssertionError("걸을 수 있는 이웃 칸이 없다")


def _걷기(상태, 걸음):
    가기, 돌아오기 = _왕복(상태)
    결과들 = []
    for i in range(걸음):
        결과 = gf.던전_이동(상태, 가기 if i % 2 == 0 else 돌아오기)
        assert 결과["결과"] == "이동", 결과
        결과들.append(결과)
    return 결과들


