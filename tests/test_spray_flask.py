def test_벌레퇴치_스프레이는_10걸음_동안_인카운트도_걸음수도_없다(늘_인카운트):
    상태 = _던전_파티({"벌레퇴치 스프레이": 2})
    문구 = gf.스프레이_사용(상태, "벌레퇴치 스프레이")
    assert "10걸음" in 문구
    assert 상태["소지품"]["소모품"]["벌레퇴치 스프레이"] == 1
    assert gf.스프레이_남은걸음(상태) == 10

    결과들 = _걷기(상태, 10)
    assert 늘_인카운트 == [] and 상태["던전상태"]["걸음수"] == 0
    assert [bool(r.get("스프레이해제")) for r in 결과들] == [False] * 9 + [True]
    assert gf.스프레이_남은걸음(상태) is None

    _걷기(상태, 1)  # 11걸음째부터 다시 센다
    assert 늘_인카운트 == [1] and 상태["던전상태"]["걸음수"] == 1


def test_여러_스프레이는_각각_따로_센다(늘_인카운트):
    상태 = _던전_파티({"벌레퇴치 스프레이": 1, "실버 스프레이": 1})
    gf.스프레이_사용(상태, "실버 스프레이")
    _걷기(상태, 5)
    gf.스프레이_사용(상태, "벌레퇴치 스프레이")
    assert 상태["던전상태"]["스프레이"] == [15, 10]
    assert gf.스프레이_남은걸음(상태) == 15

    결과들 = _걷기(상태, 10)
    assert 상태["던전상태"]["스프레이"] == [5]
    assert not any(r.get("스프레이해제") for r in 결과들)  # 아직 하나 남았다
    결과들 = _걷기(상태, 5)
    assert 결과들[-1].get("스프레이해제") and 상태["던전상태"]["스프레이"] == []
    assert 늘_인카운트 == [] and 상태["던전상태"]["걸음수"] == 0


def test_스프레이와_봉절은_따로_줄어든다(늘_인카운트):
    상태 = _던전_파티({"벌레퇴치 스프레이": 1})
