    gf.연결지역_처리(상태, 다음)
    assert gf.스프레이_남은걸음(상태) == "∞"

    gf.던전_진입(상태, 로리엔)  # 마을에서 다시 들어오면 새 던전상태
    assert gf.스프레이_남은걸음(상태) is None


