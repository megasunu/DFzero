"""전투 화면 상태 아이콘(#623) - 그림 칸 오른쪽 아래에 쌓을 아이콘 고르기.

아이콘은 game/assets/status/의 19개뿐이고(사용자 지정 2026-11-10), 그 밖의 상태는 아이콘이 없다.
"""

from pathlib import Path

import gameflow as gf
from game.data.buff.buff import 버프목록
from game.data.buff.debuff import 디버프목록
from game.data.buff.status_effects import 상태이상목록
from game.system import rng
from tests.support import 새게임, 전투_열기

_에셋 = Path(__file__).resolve().parent.parent / "game" / "assets" / "status"


def _전투():
    rng.시드(3)
    상태 = 새게임()
    전투_열기(상태, ["고블린"])
    return 상태


def _이름들(상태, 참가자):
    return [이름 for 이름, _ in gf.상태_아이콘(상태, 참가자)]


def test_아이콘은_19개이고_그림이_모두_있다():
    assert len(gf.상태아이콘_파일) == 19
    for 파일 in gf.상태아이콘_파일.values():
        assert (_에셋 / 파일).is_file(), 파일
    assert sorted(p.name for p in _에셋.glob("*.png")) == sorted(
        gf.상태아이콘_파일.values()
    )


def test_대응하는_상태가_게임에_있다():
    for 이름 in gf.상태아이콘_파일:
        원래 = "일반행동증가" if 이름 == "가속" else 이름
        assert 원래 in 상태이상목록 or 원래 in 디버프목록 or 원래 in 버프목록, 이름


def test_걸린_상태만_정해진_순서로_돌려준다():
    상태 = _전투()
    적 = gf.적_목록(상태)[0]
    적["상태이상"] += [
        {"이름": "축복", "지속턴": 2},
        {"이름": "도발", "지속턴": 2},  # 아이콘 없음
        {"이름": "출혈", "지속턴": 2, "중첩": 3},
        {"이름": "기절", "지속턴": 1},
    ]
    적["디버프"] += [{"이름": "방어감소", "지속턴": 2}, {"이름": "명중률감소"}]
    적["버프"] += [{"이름": "일반행동증가", "지속턴": 2}, {"이름": "속도증가"}]
    assert _이름들(상태, 적) == ["출혈", "기절", "가속", "축복", "방어감소"]
    assert dict(gf.상태_아이콘(상태, 적))["출혈"] == "asset_status_bleeding.png"


def test_같은_상태가_여러_번이어도_아이콘은_하나():
    상태 = _전투()
    아군 = gf.아군_목록(상태)[0]
    아군["상태이상"] += [{"이름": "중독", "지속턴": 2}, {"이름": "중독", "지속턴": 3}]
    assert _이름들(상태, 아군) == ["중독"]


def test_무적은_홀딩무적이_남은_시전자에게만():
    상태 = _전투()
    아군 = gf.아군_목록(상태)[0]
    적 = gf.적_목록(상태)[0]
    assert "무적" not in _이름들(상태, 아군)
    적["상태이상"].append(
        {"이름": "홀딩", "지속턴": 2, "시전자id": 아군["id"], "시전자무적": True}
    )
    assert _이름들(상태, 아군) == ["무적"]
    assert "무적" not in _이름들(상태, 적)


def test_무적_상태이상도_무적_아이콘이고_하나만():
    상태 = _전투()
    아군 = gf.아군_목록(상태)[0]
    적 = gf.적_목록(상태)[0]
    아군["상태이상"].append({"이름": "무적", "지속턴": 2})
    assert _이름들(상태, 아군) == ["무적"]
    적["상태이상"].append(
        {"이름": "홀딩", "지속턴": 2, "시전자id": 아군["id"], "시전자무적": True}
    )
    assert _이름들(상태, 아군) == ["무적"]


def test_무적_아닌_홀딩은_아이콘이_없다():
    상태 = _전투()
    아군 = gf.아군_목록(상태)[0]
    적 = gf.적_목록(상태)[0]
    적["상태이상"].append({"이름": "홀딩", "지속턴": 2, "시전자id": 아군["id"]})
    assert _이름들(상태, 아군) == []


def test_쓰러진_대상은_아이콘이_없다():
    상태 = _전투()
    적 = gf.적_목록(상태)[0]
    적["상태이상"].append({"이름": "화상", "지속턴": 2})
    적["생존"] = False
    assert _이름들(상태, 적) == []
