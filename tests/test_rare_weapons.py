def _무기(참가자, **칸):
    """참가자가 든 무기에 칸을 더한 사본을 쥐여 준다."""
    무기 = dict(참가자["장비데이터"]["무기"], 이름="시험 무기", **칸)
    참가자["장비데이터"]["무기"] = 무기
    return 무기


def _확률(monkeypatch, 값):
    monkeypatch.setattr(rng.확률, "random", lambda: 값)


def _버프들(참가자, 이름):
    return [b for b in 참가자["버프"] if b["이름"] == 이름]


