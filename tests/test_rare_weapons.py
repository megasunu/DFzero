def test_오라는_장착자를_포함한_아군_전원에게_붙는다(전장):
    전투상태, 적, 아군 = 전장
    전 = [stats.유효_방어력(전투상태, a) for a in 아군]
    적전 = stats.유효_방어력(전투상태, 적[0])
    _무기(아군[2], 오라=[{"변동대상": "방어력", "변동값": 1}])
    assert [stats.유효_방어력(전투상태, a) for a in 아군] == [v + 1 for v in 전]
    assert stats.유효_방어력(전투상태, 적[0]) == 적전


def test_같은_오라는_가장_높은_값_하나만(전장):
    전투상태, _, 아군 = 전장
    전 = stats.버프디버프_수치(전투상태, 아군[0], "데미지보너스")
    _무기(아군[1], 오라=[{"변동대상": "데미지보너스", "변동값": 1}])
