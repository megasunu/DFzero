def _매드_전장(무기이름):
    from game.controller import ctl_battle

    rng.시드(5)
    상태 = support.새게임([("", "마법사")])
    c = 상태["파티"]["파티원"][0]
    support.성장(상태, c, 8, 전직="인챈트리스", 스킬습득=True)
    상태["소지품"]["장비"][무기이름] = 1
    gf.장비_교체(상태, c, "무기", 무기이름)
    gf.전투_시작(상태, ["고블린"], 레벨=2, 차수=1)
    support.반응_처리(상태)
    전투상태 = 상태["전투상태"]
    시전자 = next(p for p in 전투상태["참가자"] if p["원본"] is c)
    ctl_battle.스킬_인형소환(상태, 시전자, "매드")
    매드 = next(p for p in 전투상태["참가자"] if p.get("인형") and p["생존"])
    적 = next(p for p in 전투상태["참가자"] if p["진영"] == "적")
    적["현재HP"] = 적["최대HP"] = 10**6
    적["원본"]["AC"] = 1
    return 상태, 전투상태, 매드, 적


def _매드_더_빅_피해(monkeypatch, 무기이름):
    상태, 전투상태, 매드, 적 = _매드_전장(무기이름)
    support.주사위고정(monkeypatch, 15)  # 명중(치명타 아님), d4는 4
    flow.턴_시작_처리(전투상태, 매드)
    전 = 적["현재HP"]
    ss.스킬_실행(
        전투상태, 매드, "매드 더 빅", 상태["스킬데이터모음"]["매드 더 빅"], 중심대상=적
    )
    return 전 - 적["현재HP"]


def test_인형사의_청소도구는_매드_패턴_타격마다_1d4를_더한다(monkeypatch):
    기본 = _매드_더_빅_피해(monkeypatch, "낡은 빗자루")
    assert 기본 > 0
    # 매드 더 빅은 2회 공격 - 타격마다 1d4(4)
    assert _매드_더_빅_피해(monkeypatch, "인형사의 청소도구") == 기본 + 8
