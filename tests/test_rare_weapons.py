def _강화(강화들, 이름, 스킬):
    return equipment_system.스킬강화_적용({"무기": {"스킬강화": 강화들}}, 이름, 스킬)


def test_스킬강화는_이름이나_타입이_맞는_스킬만_바꾼다():
    스킬 = {"데미지": "보정공격력", "공격횟수": 1, "타입": ["스킬"]}
    assert _강화([{"스킬": "다른 스킬", "공격횟수": 2}], "시험", 스킬) is 스킬
    바뀜 = _강화([{"스킬": "시험", "공격횟수": 2}], "시험", 스킬)
    assert 바뀜["공격횟수"] == 3 and 스킬["공격횟수"] == 1  # 원본은 그대로
    assert (
        _강화([{"스킬": "x", "공격횟수": 2}], "시험", {"공격횟수": "2+차수"})[
            "공격횟수"
        ]
        == "2+차수"
    )
    assert _강화(
        [{"스킬": "시험", "공격횟수": 2}],
        "시험",
        {"데미지": "보정치", "공격횟수": "2+차수"},
    )["공격횟수"] == ("(2+차수)+2")


