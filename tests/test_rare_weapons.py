    _무기(p, 고유효과=[{"발동": "명중", "확률": 0.5, "버프": "민첩증가", "지속턴": 2}])
    _확률(monkeypatch, 0.6)
    damage.마봉_명중시효과(전투상태, p, 적[0], {"성공": True})
