def test_상태이상_저항은_그_내성굴림에_이점_취약은_불리점(전장):
    전투상태, _, 아군 = 전장
    p = 아군[0]
    기본 = stats.내성굴림_이점불리(전투상태, p, "저주", "지혜")
    혼란기본 = stats.내성굴림_이점불리(전투상태, p, "혼란", "지혜")
    무기 = p["장비데이터"]["무기"]
    _무기(p, 고유효과=[{"변동대상": "상태이상내성이점", "변동값": "저주"}])
