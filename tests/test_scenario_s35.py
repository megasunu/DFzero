"""S35 능력치 역할 다시 고르기 실전 - 전직 역할 고르기, 레테의 눈물·강물 (docs/scenarios.md, #351).

귀검사가 든 4인 파티를 레벨 5까지 키운 뒤, 귀검사는 전직하며 전직별 표(소울브링어: 지능/민첩/매력)를 고르고
나머지는 기본 전직을 한다(역할 그대로). 마을 상점에서 레테의 눈물·강물을 100골드씩 사서 눈물은 격투가 계열에게,
강물은 거너 계열에게 쓴다(레벨 1로 - 배운 스킬 값을 돌려받음). 강물을 쓴 캐릭터를 다시 레벨 6까지 키우고
선더랜드(D05) 인카운트를 **실제 전투로** 치른다. 수치 규칙은 tests/test_lethe.py가 값으로 검사한다.
"""

import pytest

from game.system import rng
import gameflow as gf
import scenario
import support
from tests.support import 구현된_전직

선더랜드 = "dungeon_01A_D05_thunderland"
시드 = 0
파티구성 = [("", "귀검사"), ("", "격투가"), ("", "거너"), ("", "프리스트")]


def _구성(c):
    return {r: c[r] for r in ("주스탯", "보조스탯", "약점스탯")}


def _전투(상태):
    support.반응_처리(상태)
    for _ in range(300):
        if gf.전투_종료됨(상태):
            break
        참가자 = gf.현재_턴_참가자(상태)
        if 참가자["진영"] == "아군" and 참가자["생존"]:
            scenario.스킬_우선_턴(상태, [])
        else:
            gf.턴_넘기기(상태)
    else:
        raise AssertionError("전투가 끝나지 않았다")
    return 상태["전투상태"]["종료"]


@pytest.mark.scenario("S35")
def test_S35_능력치_다시_고르기_실전(golden):
    rng.시드(시드)
    상태 = support.새게임(파티구성)
    귀검사, 격투가, 거너, 프리스트 = 상태["파티"]["파티원"]
    for c in 상태["파티"]["파티원"]:
        support.성장(상태, c, 5)
    # 전직 - 귀검사는 전직별 표를 고르고, 나머지는 역할 그대로
    상태["진행도"]["플레이어레벨"] = 6
    표 = gf.전직_기본_스탯구성("소울브링어")
    전 = dict(귀검사)
    gf.캐릭터_레벨업_적용(귀검사, 전직="소울브링어", 스탯구성=표)
    assert (
        _구성(귀검사) == 표 and 귀검사["지능"] == 전["근력"] - 1
    )  # 귀수 +1은 근력에 남는다
    for c in (격투가, 거너, 프리스트):
        support.성장(상태, c, 6, 전직=구현된_전직[c["직업"]])

    # 마을 상점에서 레테 둘을 산다
    판매목록 = gf.현재_마을정보(상태)["상점판매목록"]
    상태["소지품"]["골드"] = 200
    for 이름 in ("레테의 눈물", "레테의 강물"):
        assert gf.상점_구매(상태, "소모품", "특수", 이름, 1, 판매목록) == 100
    assert 상태["소지품"]["골드"] == 0

    # 눈물 - 격투가 계열의 주/보조를 맞바꾼다
    눈물구성 = {
        "주스탯": 격투가["보조스탯"],
        "보조스탯": 격투가["주스탯"],
        "약점스탯": 격투가["약점스탯"],
    }
    주값 = 격투가[격투가["주스탯"]]
    gf.레테의_눈물_사용(상태, 격투가, 눈물구성)
    assert _구성(격투가) == 눈물구성 and 격투가["레벨"] == 6
    보너스 = gf._특성_능력치보너스(격투가)
    assert 격투가[눈물구성["주스탯"]] - 보너스.get(
        눈물구성["주스탯"], 0
    ) == 주값 - 보너스.get(
        눈물구성["보조스탯"], 0
    )  # 옛 주스탯 값(특성 보너스 뺌)이 새 주스탯으로

    # 강물 - 거너 계열을 배운 스킬째 레벨 1로, 다시 6까지
    support.스킬_전부_습득(상태, 거너)
    상태["소지품"]["골드"] = 0
    환급 = gf.레테_환급골드(거너)
    assert 환급 > 0
    assert gf.레테의_강물_사용(상태, 거너, _구성(거너)) == 환급
    assert (거너["레벨"], 거너["전직"], 상태["소지품"]["골드"]) == (1, None, 환급)
    support.성장(상태, 거너, 6, 전직=구현된_전직["거너"])
    gf.파티_최대치로_회복(상태)

    gf.던전_진입(상태, 선더랜드)
    전투들 = []
    for _ in range(2):
        적 = scenario.인카운트까지_걷기(상태)
        종료 = _전투(상태)
        라운드 = 상태["전투상태"]["라운드"]
        assert gf.전투_결과_정리(상태) == 종료 == "아군승리"
        scenario.보상_수령(상태)
        전투들.append({"적": 적, "라운드": 라운드})
        gf.휴식(상태)
        gf.던전_진입(상태, 선더랜드)
    golden(
        "scenario_S35_stat_roles",
        {
            "역할": {c["캐릭터명"]: _구성(c) for c in 상태["파티"]["파티원"]},
            "환급": 환급,
            "전투": 전투들,
        },
    )
