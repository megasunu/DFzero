def test_역할_교환은_역할끼리_값을_옮기고_밀린_값은_빈_자리로_간다():
    캐릭터 = {
        **dict(zip(능력치, [15, 13, 10, 8, 11, 10])),
        "주스탯": "근력",
        "보조스탯": "민첩",
        "약점스탯": "지능",
    }
    생성.역할_교환(캐릭터, 소울, 특성보너스={"근력": 1})
    # 기본값(특성 뺌) 근14 민13 건10 지8 혜11 매10 -> 지14 민13 매8, 밀린 근력 자리에 매력의 10
    assert _값(캐릭터) == {
        "근력": 10 + 1,  # 특성 +1은 근력에 남는다
        "민첩": 13,
        "건강": 10,
        "지능": 14,
        "지혜": 11,
        "매력": 8,
    }
    assert _구성(캐릭터) == 소울


def test_역할_교환은_같은_구성이면_그대로다():
    캐릭터 = {
        **dict(zip(능력치, [15, 13, 10, 8, 11, 10])),
        "주스탯": "근력",
        "보조스탯": "민첩",
        "약점스탯": "지능",
    }
    전 = dict(캐릭터)
    생성.역할_교환(캐릭터, _구성(캐릭터), 특성보너스={"근력": 1})
    assert 캐릭터 == 전


def test_약점증가면_새_약점들은_8을_넘지_않는다():
    """약점증가 - 주/보조를 뺀 모두가 약점(8 상한). 역할을 바꿔도 새 약점들은 8 이하다."""
    캐릭터 = {
        **dict(zip(능력치, [14, 12, 8, 8, 8, 8])),
        "주스탯": "근력",
        "보조스탯": "민첩",
        "약점스탯": "지능",
        "보유특성": ["약점증가"],
    }
    생성.역할_교환(캐릭터, {**소울, "약점스탯": "근력"}, 특성보너스={"건강": 1})
    assert (캐릭터["지능"], 캐릭터["민첩"]) == (14, 12)
    assert all(캐릭터[n] <= 8 for n in ("근력", "건강", "지혜", "매력"))


