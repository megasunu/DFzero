    c = 상태["파티"]["파티원"][0]
    support.성장(상태, c, 6, 전직="웨펀마스터")
    광검 = next(
        n
        for n, a in 상태["상점카탈로그"]["장비"]["무기"].items()
        if a.get("타입") == "광검" and a.get("레어도") != "치트"
    )
    상태["소지품"].setdefault("장비", {})[광검] = 1
    gf.장비_교체(상태, c, "무기", 광검)
    상의 = c["장착장비"]["상의"]
    _레테_보유(상태, "레테의 강물")
    gf.레테의_강물_사용(상태, c, _구성(c))
    시작무기 = gf.캐릭터_미리보기("귀검사", _구성(c))["장착장비"]["무기"]
