def test_레테의_강물은_레벨1로_되돌리고_배운_스킬_골드를_돌려준다():
    rng.시드(0)
    상태 = support.새게임([("", "귀검사"), ("", "격투가")])
    c = 상태["파티"]["파티원"][0]
    처음이름 = c["캐릭터명"]
    support.성장(상태, c, 8, 전직="소울브링어")
    assert c["캐릭터명"] != 처음이름  # 전직하며 직업 부분이 바뀌었다
    상태["소지품"]["골드"] = 0
    낸골드 = 0
    for 이름, 비용, _ in gf.캐릭터_습득가능_스킬(c):
        상태["소지품"]["골드"] += 비용
        낸골드 += gf.캐릭터_스킬_습득(상태, c, 이름)
    assert 낸골드 >= 300  # 브레멘·사야·툼스톤 100씩 + 귀검사 골드 스킬
    assert 상태["소지품"]["골드"] == 0
    assert gf.레테_환급골드(c) == 낸골드
    _레테_보유(상태, "레테의 강물")
    새것 = gf.캐릭터_미리보기("귀검사", 소울)
    환급 = gf.레테의_강물_사용(상태, c, 소울)
    assert 환급 == 낸골드 == 상태["소지품"]["골드"]
    assert "레테의 강물" not in 상태["소지품"]["소모품"]
    assert (c["레벨"], c["전직"], c["직업"]) == (1, None, "귀검사")
    assert c["캐릭터명"] == 처음이름  # 전직 이름에서 되돌린다
    assert c["보유스킬"] == 새것["보유스킬"] and c["보유특성"] == 새것["보유특성"]
    assert c.get("보유퍽", []) == [] and _구성(c) == 소울
    assert _값(c) == _값(새것)
    assert (c["현재HP"], c["현재MP"]) == (새것["기본최대HP"], 새것["기본최대MP"])
    assert c is 상태["파티"]["파티원"][0]  # 같은 객체(파티 자리 그대로)
    assert gf.캐릭터_레벨업_가능(상태, c)  # 다시 키울 수 있다


def test_레테의_강물은_못_드는_무기를_시작_무기로_바꾸고_나머지_장비는_둔다():
    rng.시드(0)
