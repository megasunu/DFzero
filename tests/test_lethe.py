    assert c["장착장비"]["무기"] == 시작무기
    assert 상태["소지품"]["장비"][광검] == 1  # 광검은 소지품에 남는다
    assert 상태["소지품"]["장비"][시작무기] >= 1
    assert c["장착장비"]["상의"] == 상의


