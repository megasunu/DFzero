능력치 = ["근력", "민첩", "건강", "지능", "지혜", "매력"]
소울 = {"주스탯": "지능", "보조스탯": "민첩", "약점스탯": "매력"}


def _값(캐릭터):
    return {n: 캐릭터[n] for n in 능력치}


def _구성(캐릭터):
    return {r: 캐릭터[r] for r in ("주스탯", "보조스탯", "약점스탯")}


