def _모두_이어짐(맵):
    """입장좌표에서 "O"/"#"/"@" 칸을 따라 지도의 모든 이동 가능 칸에 닿는다."""
    격자 = 맵["지도"]
    칸들 = {(x, y) for y, 행 in enumerate(격자) for x, c in enumerate(행) if c in "O#@"}
    본 = {맵["입장좌표"]}
    할일 = [맵["입장좌표"]]
    while 할일:
        x, y = 할일.pop()
        for 이웃 in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
            if 이웃 in 칸들 and 이웃 not in 본:
                본.add(이웃)
                할일.append(이웃)
    return 본 == 칸들


