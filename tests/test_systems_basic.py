def test_스탯역할_터치_순서():
    """터치마다 주 -> 보조 -> 일반 -> 약점 -> 주 순서, 다른 능력치가 이미 가진
    주/보조/약점은 건너뛴다(일반은 몇 개든 된다)."""
    구성 = {"주스탯": "근력", "보조스탯": "민첩", "약점스탯": "지능"}
    assert 생성.스탯역할(구성, "근력") == "주스탯"
    assert 생성.스탯역할(구성, "건강") == "일반"
    # 근력(주): 보조는 민첩이 가짐 -> 건너뛰고 일반
    구성 = 생성.스탯역할_다음(구성, "근력")
    assert 구성 == {"주스탯": None, "보조스탯": "민첩", "약점스탯": "지능"}
    # 건강(일반): 약점은 지능이 가짐 -> 건너뛰고 비어 있는 주
    구성 = 생성.스탯역할_다음(구성, "건강")
    assert 구성 == {"주스탯": "건강", "보조스탯": "민첩", "약점스탯": "지능"}
    # 민첩(보조) -> 일반, 지능(약점): 주는 건강이 가짐 -> 보조
    구성 = 생성.스탯역할_다음(구성, "민첩")
    구성 = 생성.스탯역할_다음(구성, "지능")
    assert 구성 == {"주스탯": "건강", "보조스탯": "지능", "약점스탯": None}
    # 매력(일반) -> 약점(비어 있음)
    구성 = 생성.스탯역할_다음(구성, "매력")
    assert 구성 == {"주스탯": "건강", "보조스탯": "지능", "약점스탯": "매력"}
    # 셋이 다 차 있으면 일반 능력치는 터치해도 일반 그대로
    assert 생성.스탯역할_다음(구성, "근력") == 구성
    # 원래 구성은 바뀌지 않는다
    원래 = {"주스탯": "근력", "보조스탯": None, "약점스탯": None}
    assert 생성.스탯역할_다음(원래, "근력") == {
        "주스탯": None,
        "보조스탯": "근력",
        "약점스탯": None,
    }
