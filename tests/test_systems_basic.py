def test_던전_순서_해금은_바로_앞_번호_던전_보스_클리어():
    전체 = [
        "dungeon_01A_D01_Lorien",
        "dungeon_01A_D04_Hollow_mirkwood",
        "dungeon_01A_D05_thunderland",
        "dungeon_02A_D11_amon_lower",
        "dungeon_02A_D12_amon_upper",
    ]
    진행도 = {"클리어한던전": set()}
