"""S43 용인족 실전 (docs/scenarios.md, #170).

귀검사·격투가·프리스트·거너를 밸런스 측정 조건으로 레벨 5까지 키우고 프리스트에게 배틀마스터(오라)를 쥐여 준다.
미르키우스 둘·라키우스, 이어서 미르키우스·오라헌터 시우스와 **실전으로**(스킬 우선 정책) 싸운다. 라키우스가 차례마다
감옥을 치고(갇히거나 피함) 심장 찌르기를 캐스팅하는지, 시우스가 오라를 내던 프리스트를 쓰러뜨리면 강화를 얻는지,
감옥은 늘 체력 10 이하에 아군만 가두는지, 이긴 전투의 보상을 받는지 본다. 분신·버프 강탈은 시드 37에서 나오지 않는다 -
값은 test_dragonkin.py가 본다.
"""

import pytest

from game.system import rng
import gameflow as gf
import scenario
import support

시드 = 37  # 7이었다 - 시우스 6번이 라키우스 6번과 같아진 뒤(2026-10-30) 오라 사냥이 안 나와 바꿈
_파티 = [("", "귀검사"), ("", "격투가"), ("", "프리스트"), ("", "거너")]
_전투들 = (["미르키우스", "미르키우스", "라키우스"], ["미르키우스", "오라헌터 시우스"])


def _세기(로그, 글):
    return sum(글 in str(x.get("비고", "")) for x in 로그)


@pytest.mark.scenario("S43")
def test_S43_용인족_실전():
    rng.시드(시드)
    상태 = support.새게임(_파티)
    scenario.측정_파티_준비(상태, 5)
    프리스트 = 상태["파티"]["파티원"][2]
    상태["소지품"]["장비"]["배틀마스터"] = 1
    gf.장비_교체(상태, 프리스트, "무기", "배틀마스터")
    기록 = {"결과": [], "감옥": 0, "캐스팅": 0, "오라사냥": 0}
    for 몬스터들 in _전투들:
        gf.휴식(상태)
        gf.전투_시작(상태, 몬스터들, 레벨=5, 차수=1)
        결과 = scenario.스킬_실전(상태, [])
        전투상태 = 상태["전투상태"]
        로그 = 전투상태["로그"]
        기록["감옥"] += _세기(로그, "에 갇힘") + _세기(로그, "'감옥'을 피함")
        기록["캐스팅"] += _세기(로그, "심장 찌르기 캐스팅을 시작")
        기록["오라사냥"] += _세기(로그, "오라를 내던")
        for 감옥 in (p for p in 전투상태["참가자"] if p.get("감옥")):
            assert 감옥["기본최대HP"] <= 10
            갇힌 = next(p for p in 전투상태["참가자"] if p["id"] == 감옥["갇힌id"])
            assert 갇힌["진영"] == "아군"
        기록["결과"].append(결과)
        gf.전투_결과_정리(상태)
        if 결과 != "아군승리":
            break
        if gf.전투_보상_대기중(상태):
            scenario.보상_수령(상태)
    assert 기록["결과"] == ["아군승리", "아군승리"], 기록
    assert 기록["감옥"] >= 1 and 기록["캐스팅"] >= 1, 기록
    assert 기록["오라사냥"] >= 1, 기록
