"""S5 패배 복귀와 도망 (docs/scenarios.md).

- 패배: 레벨 1 둘(귀검사+격투가)이서 로리엔 보스에 도전해 **실제로** 진다. 전멸하면 기록/전리품 없이 HP 0으로 돌아오고,
  휴식으로 완전히 회복한 뒤 다시 도전해 이길 때까지 반복한다(화면과 같다: 별도 페널티 없음).
- 도망: 인카운트와 보스전에서 도망을 성공할 때까지 시도한다. 실패하면 턴이 넘어가고, 성공하면 전리품/보상/
  클리어 기록 없이 던전에 그대로 남는다. 도망친 뒤에도 같은 던전에서 계속 싸워 이긴다.
전투는 [자동전투]와 같은 호출(tests/scenario.py 실전)이고, 도망 판정 자체의 규칙은 test_gameflow_scenarios.py가 값으로 검사한다.
"""

import pytest

from game.system import rng
import gameflow as gf
import scenario
import support

로리엔 = "dungeon_01A_D01_Lorien"
시드_패배 = 8  # 0 -> 5: 탱커 역할군 -1/-1(2026-10-07) 뒤 시드 0~4는 지지 않는다. 5 -> 7: 고블린/투척병 개인 드랍(2026-10-08)으로 난수 순서가 바뀌어 5, 6은 지지 않는다. 7 -> 8: 난수 흐름 분리(2026-10-20)로 7은 지지 않는다
시드_도망 = 0
최대시도 = 30


class _패배(Exception):
    pass


def _진행도_스냅샷(상태):
    진행도 = 상태["진행도"]
    return (
        sorted(진행도["클리어한던전"]),
        sorted(진행도["클리어한오브젝트"]),
        진행도["플레이어레벨"],
    )


def _패배_처리(상태, 기록, 시도, 골드전, 진행도전):
    """전멸한 전투를 정리하고 화면처럼 마을로 돌려보낸 뒤(휴식) 규칙을 확인한다."""
    assert gf.전투_결과_정리(상태) == "적승리"
    파티 = 상태["파티"]["파티원"]
    assert all(c["현재HP"] == 0 for c in 파티)
    assert 상태["전투_전리품"] is None and 상태["전투_보상"] is None
    assert not gf.전투_보상_대기중(상태)
    assert 상태["소지품"]["골드"] == 골드전  # 전리품/보상 골드 없음
    assert _진행도_스냅샷(상태) == 진행도전  # 보스 클리어 기록 없음
    assert any(c["현재MP"] < gf.캐릭터_최대MP(상태, c) for c in 파티), "MP를 안 썼다"
    gf.휴식(상태)
    상태["던전상태"] = None
    assert all(c["현재HP"] == gf.캐릭터_최대HP(상태, c) > 0 for c in 파티)
    assert all(c["현재MP"] == gf.캐릭터_최대MP(상태, c) for c in 파티)
    기록["패배"].append(시도)


@pytest.mark.scenario("S5")
def test_S5_패배_휴식_재도전(golden):
    rng.시드(시드_패배)
    상태 = support.새게임([("", "귀검사"), ("", "격투가")])
    기록 = {"패배": [], "전투": []}

    for 시도 in range(1, 최대시도 + 1):
        골드전 = 상태["소지품"]["골드"]
        gf.던전_진입(상태, 로리엔)

        def 전투처리(s, 시도=시도):
            # 이 전투 직전의 골드/진행도 - 앞선 인카운트에서 이긴 전리품은 이미 들어왔다
            골드전, 진행도전 = s["소지품"]["골드"], _진행도_스냅샷(s)
            적 = [e["이름"] for e in gf.적_목록(s)]
            종료 = scenario.스킬_실전(
                s, []
            )  # 스킬을 써서 MP가 줄어야 휴식 회복을 볼 수 있다
            기록["전투"].append([시도, 적, 종료, s["전투상태"]["라운드"]])
            if 종료 == "적승리":
                _패배_처리(s, 기록, 시도, 골드전, 진행도전)
                raise _패배(시도)

        try:
            결과, 위치 = support.보스_처치(상태, 전투처리=전투처리)
        except _패배:
            continue
        # 이겼다: 보스 클리어가 기록되고 전리품/보상이 생긴다
        assert 결과 == "아군승리"
        assert 상태["진행도"]["클리어한던전"] == {로리엔}
        assert 상태["소지품"]["골드"] > 골드전
        assert gf.전투_보상_대기중(상태)
        기록["승리한_시도"] = 시도
        break
    else:
        pytest.fail(f"{최대시도}번 시도해도 이기지 못했다")

    assert 기록["패배"], "한 번도 지지 않았다 - 시드를 다시 고른다"
    golden("scenario_S5_defeat_retry", 기록)


def _도망_성공까지(상태, 기록, 라벨):
    """아군 차례마다 도망을 시도한다. 실패하면 턴이 넘어가는 것과 성공했을 때의 상태를 확인하고,
    (시도 횟수, 도망 직전 파티 HP)를 돌려준다. 시도 도중 전투가 져서 끝나면 AssertionError."""
    support.반응_처리(상태)
    시도 = 0
    for _ in range(60):
        assert not gf.전투_종료됨(상태), f"{라벨}: 도망 못 하고 전투가 끝났다"
        차례 = gf.현재_턴_참가자(상태)
        if 차례["진영"] != "아군" or not 차례["생존"]:
            gf.턴_넘기기(상태)
            continue
        시도 += 1
        이전 = (상태["전투상태"]["라운드"], 차례["이름"])
        성공, 굴림, 난이도 = gf.아군_도망시도(상태)
        assert 난이도 is not None and 굴림 is not None and 난이도 >= 10
        assert 성공 == (굴림 >= 난이도) == (상태["전투상태"]["종료"] == "전투이탈")
        if 성공:
            기록.append([라벨, 시도, "성공"])
            return 시도
        # 실패하면 현재 캐릭터의 턴이 끝난다 - 같은 캐릭터가 같은 라운드에 또 시도할 수 없다
        지금 = gf.현재_턴_참가자(상태)
        assert (상태["전투상태"]["라운드"], 지금["이름"]) != 이전 or gf.전투_종료됨(
            상태
        )
        기록.append([라벨, 시도, "실패"])
    pytest.fail(f"{라벨}: 60번 안에 도망치지 못했다")


@pytest.mark.scenario("S5")
def test_S5_도망(golden):
    rng.시드(시드_도망)
    상태 = support.새게임()
    기록 = {"도망": [], "전투": []}
    gf.던전_진입(상태, 로리엔)

    # 1) 인카운트에서 도망 - 전리품/보상/기록이 없고 던전 위치도 그대로
    scenario.인카운트까지_걷기(상태)
    위치 = 상태["던전상태"]["위치"]
    골드, 장비, 진행도 = (
        상태["소지품"]["골드"],
        scenario.소지품_장비수(상태),
        _진행도_스냅샷(상태),
    )
    _도망_성공까지(상태, 기록["도망"], "인카운트")
    assert gf.전투_결과_정리(상태) == "전투이탈"
    assert gf.전투_종료_문구(상태, "전투이탈") == ["도망쳤다!"]
    assert 상태["전투_전리품"] is None and 상태["전투_보상"] is None
    assert not gf.전투_보상_대기중(상태)
    assert (상태["소지품"]["골드"], scenario.소지품_장비수(상태)) == (골드, 장비)
    assert _진행도_스냅샷(상태) == 진행도
    assert 상태["던전상태"] is not None and 상태["던전상태"]["위치"] == 위치
    assert 상태["전투상태"] is None

    # 2) 도망친 뒤에도 같은 던전에서 다음 인카운트를 이긴다 - 전리품이 정상으로 들어온다
    scenario.인카운트까지_걷기(상태)
    골드 = 상태["소지품"]["골드"]
    종료 = scenario.실전(상태)
    기록["전투"].append(["도망 뒤 인카운트", 종료])
    assert gf.전투_결과_정리(상태) == 종료 == "아군승리"
    assert 상태["소지품"]["골드"] > 골드 and gf.전투_보상_대기중(상태)
    scenario.보상_수령(상태)

    # 3) 보스전에서도 도망친다 - 보스는 클리어되지 않고 다시 도전할 수 있다
    던전 = 상태["던전상태"]
    보스위치, 오브젝트 = next(
        (p, o) for p, o in 던전["맵정보"]["오브젝트"].items() if o["타입"] == "보스전투"
    )
    x, y = 보스위치
    앞칸 = next(
        p
        for p in ((x - 1, y), (x, y - 1), (x, y + 1), (x + 1, y))
        if support.경로(던전["그리드"], 던전["위치"], p) is not None
        and 던전["그리드"][p[1]][p[0]] == "O"
    )

    def 인카운트_이기기(s):
        종료 = scenario.실전(s)
        기록["전투"].append(["보스 가는 길 인카운트", 종료])
        assert 종료 == "아군승리"

    support.걸어가기(상태, 앞칸, 전투처리=인카운트_이기기)
    gf.휴식(상태)  # 보스 앞에서 정비했다고 본다(마을 휴식 호출) - 도망 판정과 무관
    assert gf.오브젝트_상호작용(상태, 보스위치, 오브젝트) == {"결과": "전투시작"}
    _도망_성공까지(상태, 기록["도망"], "보스")
    assert gf.전투_결과_정리(상태) == "전투이탈"
    assert 로리엔 not in 상태["진행도"]["클리어한던전"]
    assert not 상태["진행도"]["클리어한오브젝트"]
    assert (
        상태["던전상태"]["그리드"][보스위치[1]][보스위치[0]] != "O"
    )  # 보스 칸이 아직 막혀 있다

    # 4) 다시 도전해 이긴다 - 이제 클리어가 기록된다
    gf.휴식(상태)
    assert gf.오브젝트_상호작용(상태, 보스위치, 오브젝트) == {"결과": "전투시작"}
    종료 = scenario.실전(상태)
    기록["전투"].append(["보스 재도전", 종료])
    assert gf.전투_결과_정리(상태) == 종료 == "아군승리"
    assert 상태["진행도"]["클리어한던전"] == {로리엔}
    assert 상태["던전상태"]["그리드"][보스위치[1]][보스위치[0]] == "O"
    golden("scenario_S5_flee", 기록)
