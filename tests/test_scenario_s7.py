"""S7 2차수 진입 실전 (docs/scenarios.md, #180).

1차수 던전 D01~D09를 깬 기록(S6이 실전으로 지나가는 구간 - 여기서는 진행도로 세운다)과 레벨 8까지
키운 기본 4인 파티로 시작한다. 헨돈마이어에서 선더랜드 북쪽 숏컷으로 어둠의 선더랜드(D10)에 들어가
**인카운트와 보스를 실전으로** 깨고 마을로 돌아온다(지면 마을에서 쉬고 원정을 처음부터 - S6과 같다).
보스를 깨면 플레이어 레벨 10이 되고 웨스트코스트가 열린다. 파티를 10까지 키워 웨스트코스트로 옮긴 뒤
하층 두 곳(아몬/세피로타)과 천해(미들오션)에 들어가 걷고, 상층/심해로 가는 길을 막은 보스·포탈 앞에서
말을 건다. 하늘성 몬스터가 아직 없어(#170, 주인 결정 대기) 인카운트가 없고 보스·포탈 전투는
"몬스터데이터없음"이다 - 몬스터가 들어오면 이 단언이 깨지니 그때 실전으로 바꾼다. 웨스트코스트에서
쉬고 저장/불러오기 뒤에도 마을·진행도가 그대로다.
"""

import pytest

from game.system import rng, town_system
import gameflow as gf
import scenario
import support
from tests.support import 구현된_전직

_헨돈마이어 = "town_01A_T02_hendonmyre"
_웨스트코스트 = "town_02A_T03_westcoast"
_D05 = "dungeon_01A_D05_thunderland"
_D10 = "dungeon_01A_D10_shadow_thunderland"
# 마을에서 바로 들어가는 2차수 던전 -> 막힌 오브젝트 좌표와 그 너머의 연결맵
_하늘성 = {
    "dungeon_02A_D11_amon_lower": ((19, 1), "dungeon_02A_D12_amon_upper"),
    "dungeon_02A_D13_sephiroth_lower": ((19, 1), "dungeon_02A_D14_sephiroth_upper"),
    "dungeon_02A_D15_middleocean_shallow": (
        (16, 3),
        "dungeon_02A_D16_middleocean_deep",
    ),
}
최대시도 = (
    12  # D10 원정을 실전으로 해 보는 횟수 - 넘으면 실패(강제 승리로 건너뛰지 않는다)
)


class _패배(Exception):
    pass


def _실전(상태):
    종료 = scenario.스킬_실전(상태, [])
    if 종료 != "아군승리":
        assert gf.전투_결과_정리(상태) == 종료 == "적승리"
        gf.휴식(상태)  # 전멸하면 마을로(화면과 같다)
        상태["던전상태"] = None
        raise _패배()


def _1차수_끝(상태):
    """D01~D09 보스를 깬 진행도(S6이 실전으로 지나간다) - 던전 클리어와 보스 오브젝트 기록(숏컷 해금 조건)."""
    진행도 = 상태["진행도"]
    for 파일명 in gf.던전_레지스트리:
        if not 파일명.startswith("dungeon_01A_") or 파일명 == _D10:
            continue
        town_system.던전_클리어_처리(진행도, 파일명)
        for 좌표, 오브젝트 in gf.던전_레지스트리[파일명]["오브젝트"].items():
            if 오브젝트.get("타입") == "보스전투":
                town_system.오브젝트_클리어_기록(진행도, 파일명, 좌표)
    진행도["플레이어레벨"] = 8


def _키우기(상태):
    PL = 상태["진행도"]["플레이어레벨"]
    for c in 상태["파티"]["파티원"]:
        if c["레벨"] < 5:
            support.성장(상태, c, 5, 스킬습득=True)
        support.성장(
            상태,
            c,
            PL,
            전직=구현된_전직[c["직업"]] if c["전직"] is None else None,
            스킬습득=True,
        )
    gf.파티_최대치로_회복(상태)
    return [(gf.캐릭터_직업표시(c), c["레벨"]) for c in 상태["파티"]["파티원"]]


def _마을명들(상태):
    return [m["마을명"] for m in gf.이동가능마을목록(상태)]


def _어둠의_선더랜드(상태):
    """헨돈마이어 -> 선더랜드 북쪽 숏컷 -> D10 보스 -> 헨돈마이어. (보스를 깬 시도, 돌아온 방법)을 돌려준다.
    보스를 깬 뒤 돌아오다 전멸해도 클리어 기록은 남고 마을로 간다(화면과 같다) - "전멸"로 적는다."""
    for 시도 in range(1, 최대시도 + 1):
        try:
            gf.던전_진입(상태, _D05)
            support.연결로_나가기(상태, _D10, 전투처리=_실전)
            결과, _ = support.보스_처치(상태, 전투처리=_실전)
            assert 결과 == "아군승리"
        except _패배:
            continue
        try:
            support.연결로_나가기(상태, _D05, 전투처리=_실전)
            support.연결로_나가기(상태, _헨돈마이어, 전투처리=_실전)
            return 시도, "걸어서"
        except _패배:
            return 시도, "전멸"
    raise AssertionError(f"D10 보스를 실전으로 {최대시도}번 안에 못 깼다")


def _하늘성_둘러보기(상태, 파일명):
    """마을에서 들어가 막힌 보스/포탈 앞까지 걷고 말을 건 뒤 마을로 돌아온다."""
    막힘, 너머 = _하늘성[파일명]
    gf.던전_진입(상태, 파일명)
    던전 = 상태["던전상태"]
    입장 = 던전["위치"]
    오브젝트 = 던전["맵정보"]["오브젝트"][막힘]
    x, y = 막힘
    앞칸 = next(
        p
        for p in ((x - 1, y), (x, y + 1), (x, y - 1), (x + 1, y))
        if 던전["그리드"][p[1]][p[0]] == "O"
        and support.경로(던전["그리드"], 입장, p) is not None
    )
    # 인카운트가 없으니 전투 없이 걸어간다(전투처리가 불리면 실패)
    support.걸어가기(상태, 앞칸, 전투처리=_인카운트_없음)
    걸음 = 던전["걸음수"]
    # 막힌 칸으로는 못 들어가고(오브젝트), 말을 걸면 몬스터가 아직 없다
    방향 = support.경로(던전["그리드"], 앞칸, 막힘)[0]
    assert gf.던전_이동(상태, 방향)["결과"] == "오브젝트"
    상호작용 = gf.오브젝트_상호작용(상태, 막힘, 오브젝트)
    assert 상호작용 == {"결과": "몬스터데이터없음"}, 상호작용
    assert 상태.get("전투상태") is None
    assert not town_system.오브젝트_클리어됨(상태["진행도"], 파일명, 막힘)
    # 상층/심해로 가는 연결은 막힌 칸 너머에 있다(지금은 갈 수 없다)
    assert 너머 in {c["연결맵"] for c in 던전["맵정보"]["연결지역"].values()}
    support.연결로_나가기(상태, _웨스트코스트, 전투처리=_인카운트_없음)
    assert 상태["던전상태"] is None
    assert 상태["진행도"]["현재마을"] == "웨스트코스트"
    return {"입장": list(입장), "막힘": list(막힘), "걸음": 걸음}


def _인카운트_없음(상태):
    raise AssertionError(
        f"하늘성에 인카운트가 떴다: {[e['이름'] for e in gf.적_목록(상태)]}"
    )


@pytest.mark.scenario("S7")
def test_S7_2차수_진입(golden):
    rng.시드(1)
    상태 = support.새게임()
    _1차수_끝(상태)
    성장 = {8: _키우기(상태)}
    gf.마을_이동(상태, "헨돈마이어")
    assert "웨스트코스트" not in _마을명들(상태)

    # 1) 어둠의 선더랜드 실전 - 보스를 깨면 플레이어 레벨 10, 웨스트코스트 개방
    시도, 귀환 = _어둠의_선더랜드(상태)
    진행도 = 상태["진행도"]
    assert 진행도["플레이어레벨"] == 10
    assert _D10 in 진행도["클리어한던전"]
    assert "웨스트코스트" in _마을명들(상태)
    성장[10] = _키우기(상태)

    # 2) 웨스트코스트 - 하층 두 곳과 천해만 바로 열려 있다(상층/심해는 포탈 너머)
    gf.마을_이동(상태, "웨스트코스트")
    assert gf.현재_마을정보(상태)["마을명"] == "웨스트코스트"
    목록 = gf.던전목록_표시(상태)
    assert [(f, 열림) for f, _, 열림, _ in 목록] == [(f, True) for f in _하늘성]

    # 3) 하층/천해 둘러보기 - 인카운트 없음, 막힌 보스·포탈은 몬스터 미정
    하늘성 = {f: _하늘성_둘러보기(상태, f) for f in _하늘성}
    assert 진행도["플레이어레벨"] == 10  # 2차수 보스가 없어 더 오르지 않는다

    # 4) 웨스트코스트에서 쉬고 저장/불러오기 - 마을과 진행도가 그대로
    scenario_hp = scenario.파티_HP(상태)
    gf.휴식(상태)
    gf.게임_저장(상태, 1)
    불러옴 = gf.게임_불러오기(1)
    assert 불러옴["진행도"] == 진행도
    assert 불러옴["진행도"]["현재마을"] == "웨스트코스트"
    assert scenario.파티_HP(불러옴) == scenario.파티_HP(상태)
    assert [f for f, _, 열림, _ in gf.던전목록_표시(불러옴) if 열림] == list(_하늘성)

    golden(
        "scenario_S7_second_tier",
        {
            "D10_시도": 시도,
            "D10_귀환": 귀환,
            "성장": 성장,
            "하늘성": 하늘성,
            "쉬기_전_HP": scenario_hp,
            "클리어한던전": len(진행도["클리어한던전"]),
        },
    )
