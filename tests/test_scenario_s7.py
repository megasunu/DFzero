"""S7 2차수 진입 실전 (docs/scenarios.md, #180).

1차수 던전 D01~D09를 깬 기록(S6이 실전으로 지나가는 구간 - 여기서는 진행도로 세운다)과 레벨 5까지
키운 기본 4인 파티로 시작한다. 헨돈마이어에서 선더랜드 북쪽 숏컷으로 어둠의 선더랜드(D10)에 들어가
**인카운트와 보스를 실전으로** 깨고 마을로 돌아온다(지면 마을에서 쉬고 원정을 처음부터 - S6과 같다).
최대시도 번 안에 못 깨면 S6처럼 강제 승리로 건너고 골든에 "강제"로 남긴다(밸런스 확인용).
보스를 깨면 플레이어 레벨 6이 되고 웨스트코스트가 열린다. 파티를 6까지 키워(5->6 전직) 웨스트코스트로 옮긴 뒤
하층 두 곳(아몬/세피로타)과 천해(미들오션)에 들어가 **인카운트를 실전으로** 싸우며 걷고, 상층/심해로 가는 길을
막은 전투이벤트 앞에서 말을 건다(2026-10-30 하늘성 몬스터 배치) - 그 던전의 몬스터(맨 앞이 "보스")가 나오고 실전으로
싸운다. 이기면 클리어가 기록되고, 지면 마을에서 쉰다(화면과 같다). 결과는 골든으로 비교한다. 웨스트코스트에서
쉬고 저장/불러오기 뒤에도 마을·진행도가 그대로다.
"""

import pytest

from game.system import rng, town_system
import gameflow as gf
import scenario
import support
from tests.support import 구현된_전직

_헨돈마이어 = "town_01A_T02_hendonmyre"
_웨스트코스트 = "town_02A_T03_westcoast"
_D05 = "dungeon_01A_D05_thunderland"
_D10 = "dungeon_01A_D10_shadow_thunderland"
# 마을에서 바로 들어가는 2차수 던전 -> 막힌 오브젝트 좌표와 그 너머의 연결맵
_하늘성 = {
    "dungeon_02A_D11_amon_lower": ((19, 1), "dungeon_02A_D12_amon_upper"),
    "dungeon_02A_D13_sephiroth_lower": ((19, 1), "dungeon_02A_D14_sephiroth_upper"),
    "dungeon_02A_D15_middleocean_shallow": (
        (8, 0),
        "dungeon_02A_D16_middleocean_deep",
    ),
}
최대시도 = (
    12  # D10 원정을 실전으로 해 보는 횟수 - 넘으면 실패(강제 승리로 건너뛰지 않는다)
)


class _패배(Exception):
    pass


def _실전(상태):
    종료 = scenario.스킬_실전(상태, [])
    if 종료 != "아군승리":
        assert gf.전투_결과_정리(상태) == 종료 == "적승리"
        gf.휴식(상태)  # 전멸하면 마을로(화면과 같다)
        상태["던전상태"] = None
        raise _패배()


def _1차수_끝(상태):
    """D01~D09 보스를 깬 진행도(S6이 실전으로 지나간다) - 던전 클리어와 보스 오브젝트 기록(숏컷 해금 조건)."""
    진행도 = 상태["진행도"]
    for 파일명 in gf.던전_레지스트리:
        if not 파일명.startswith("dungeon_01A_") or 파일명 == _D10:
            continue
        town_system.던전_클리어_처리(진행도, 파일명)
        for 좌표, 오브젝트 in gf.던전_레지스트리[파일명]["오브젝트"].items():
            if 오브젝트.get("타입") == "보스전투":
                town_system.오브젝트_클리어_기록(진행도, 파일명, 좌표)
    진행도["플레이어레벨"] = 5  # 그락카락(D08) 보스까지 깬 레벨


def _키우기(상태):
    PL = 상태["진행도"]["플레이어레벨"]
    for c in 상태["파티"]["파티원"]:
        if c["레벨"] < 5:
            support.성장(상태, c, 5, 스킬습득=True)
        support.성장(
            상태,
            c,
            PL,
            전직=구현된_전직[c["직업"]] if c["전직"] is None else None,
            스킬습득=True,
        )
    gf.파티_최대치로_회복(상태)
    return [(gf.캐릭터_직업표시(c), c["레벨"]) for c in 상태["파티"]["파티원"]]


def _마을명들(상태):
    return [m["마을명"] for m in gf.이동가능마을목록(상태)]


def _어둠의_선더랜드(상태):
    """헨돈마이어 -> 선더랜드 북쪽 숏컷 -> D10 보스 -> 헨돈마이어. (보스를 깬 시도, 돌아온 방법)을 돌려준다.
    보스를 깬 뒤 돌아오다 전멸해도 클리어 기록은 남고 마을로 간다(화면과 같다) - "전멸"로 적는다.
    최대시도 번 다 지면 강제 승리로 같은 길을 건너고 "강제"로 적는다(S6과 같다)."""
    for 시도 in range(1, 최대시도 + 1):
        try:
            gf.던전_진입(상태, _D05)
            support.연결로_나가기(상태, _D10, 전투처리=_실전)
            결과, _ = support.보스_처치(상태, 전투처리=_실전)
            assert 결과 == "아군승리"
        except _패배:
            continue
        try:
            support.연결로_나가기(상태, _D05, 전투처리=_실전)
            support.연결로_나가기(상태, _헨돈마이어, 전투처리=_실전)
            return 시도, "걸어서"
        except _패배:
            return 시도, "전멸"
    gf.던전_진입(상태, _D05)
    support.연결로_나가기(상태, _D10)
    support.보스_처치(상태)
    support.연결로_나가기(상태, _D05)
    support.연결로_나가기(상태, _헨돈마이어)
    return 최대시도, "강제"


def _하늘성_둘러보기(상태, 파일명):
    """마을에서 들어가 인카운트를 실전으로 싸우며 막힌 전투이벤트 앞까지 걷고, 말을 걸어 실전으로 싸운 뒤
    이기면 마을로 걸어 돌아온다. 도중에 지면 마을에서 쉰다(화면과 같다)."""
    막힘, 너머 = _하늘성[파일명]
    gf.던전_진입(상태, 파일명)
    던전 = 상태["던전상태"]
    입장 = 던전["위치"]
    오브젝트 = 던전["맵정보"]["오브젝트"][막힘]
    # 상층/심해로 가는 연결은 막힌 칸 너머에 있다
    assert 너머 in {c["연결맵"] for c in 던전["맵정보"]["연결지역"].values()}
    x, y = 막힘
    앞칸 = next(
        p
        for p in ((x - 1, y), (x, y + 1), (x, y - 1), (x + 1, y))
        if 0 <= p[1] < len(던전["그리드"])
        and 던전["그리드"][p[1]][p[0]] == "O"
        and support.경로(던전["그리드"], 입장, p) is not None
    )
    기록 = []
    요약 = {"입장": list(입장), "막힘": list(막힘)}
    try:
        support.걸어가기(상태, 앞칸, 기록, 전투처리=_실전)
        요약["걸음"] = 던전["걸음수"]
        방향 = support.경로(던전["그리드"], 앞칸, 막힘)[0]
        assert gf.던전_이동(상태, 방향)["결과"] == "오브젝트"
        assert gf.오브젝트_상호작용(상태, 막힘, 오브젝트) == {"결과": "전투시작"}
        요약["전투이벤트"] = "적승리"  # 이기면 아래에서 바꾼다
        적 = gf.적_목록(상태)
        보스 = [e["원본"]["몬스터명"] for e in 적 if e["원본"].get("칭호") == "보스"]
        assert 보스 == [오브젝트["전투몬스터"][0]["이름"]], 보스
        _실전(상태)
        assert gf.전투_결과_정리(상태) == "아군승리"
        assert town_system.오브젝트_클리어됨(상태["진행도"], 파일명, 막힘)
        요약["전투이벤트"] = "아군승리"
        support.연결로_나가기(상태, _웨스트코스트, 기록, 전투처리=_실전)
        요약["귀환"] = "걸어서"
    except _패배:
        요약.setdefault("전투이벤트", "도달 못 함")
        요약.setdefault("귀환", "전멸")
    assert 상태["던전상태"] is None
    assert 상태["진행도"]["현재마을"] == "웨스트코스트"
    요약["인카운트"] = [이름들 for _, _, _, 이름들 in 기록]
    return 요약


@pytest.mark.scenario("S7")
def test_S7_2차수_진입(golden):
    rng.시드(1)
    상태 = support.새게임()
    _1차수_끝(상태)
    성장 = {5: _키우기(상태)}
    gf.마을_이동(상태, "헨돈마이어")
    assert "웨스트코스트" not in _마을명들(상태)

    # 1) 어둠의 선더랜드 실전 - 보스를 깨면 플레이어 레벨 6, 웨스트코스트 개방
    시도, 귀환 = _어둠의_선더랜드(상태)
    진행도 = 상태["진행도"]
    assert 진행도["플레이어레벨"] == 6
    assert _D10 in 진행도["클리어한던전"]
    assert "웨스트코스트" in _마을명들(상태)
    성장[6] = _키우기(상태)

    # 2) 웨스트코스트 - 하늘성 일곱 곳이 번호 순으로 보이고 아몬 하층만 열려 있다(순서 해금)
    gf.마을_이동(상태, "웨스트코스트")
    assert gf.현재_마을정보(상태)["마을명"] == "웨스트코스트"
    목록 = gf.던전목록_표시(상태)
    assert [f for f, *_ in 목록] == sorted(
        f for f in gf.던전_레지스트리 if f.startswith("dungeon_02A_")
    )
    assert [열림 for _, _, 열림, _ in 목록] == [True] + [False] * 6

    # 3) 하층/천해 둘러보기 - 인카운트와 전투이벤트를 실전으로. 상층/심해 원정은 S7 범위 밖이라
    # 세피로타 하층·천해 앞에서는 바로 앞 던전(아몬 상층·세피로타 상층) 클리어를 기록해 연다
    하늘성 = {}
    for f in _하늘성:
        앞던전 = {
            "dungeon_02A_D13_sephiroth_lower": "dungeon_02A_D12_amon_upper",
            "dungeon_02A_D15_middleocean_shallow": "dungeon_02A_D14_sephiroth_upper",
        }.get(f)
        if 앞던전:
            assert not gf.던전_열림(상태, f), f
            town_system.던전_클리어_처리(진행도, 앞던전)
        assert gf.던전_열림(상태, f), f
        gf.휴식(상태)
        하늘성[f] = _하늘성_둘러보기(상태, f)
    assert any(v["인카운트"] for v in 하늘성.values())  # 하늘성에 몬스터가 나온다
    assert 진행도["플레이어레벨"] == 6  # 하층·천해 전투이벤트에는 레벨업 트리거가 없다

    # 4) 웨스트코스트에서 쉬고 저장/불러오기 - 마을과 진행도가 그대로
    scenario_hp = scenario.파티_HP(상태)
    gf.휴식(상태)
    gf.게임_저장(상태, 1)
    불러옴 = gf.게임_불러오기(1)
    assert 불러옴["진행도"] == 진행도
    assert 불러옴["진행도"]["현재마을"] == "웨스트코스트"
    assert scenario.파티_HP(불러옴) == scenario.파티_HP(상태)
    assert gf.던전목록_표시(불러옴) == gf.던전목록_표시(상태)

    golden(
        "scenario_S7_second_tier",
        {
            "D10_시도": 시도,
            "D10_귀환": 귀환,
            "성장": 성장,
            "하늘성": 하늘성,
            "쉬기_전_HP": scenario_hp,
            "클리어한던전": len(진행도["클리어한던전"]),
        },
    )
