"""버프에서 상태변화로 바뀐 것들(2026-10-28 사용자 결정, #462).

상태이상(타입 "상태이상")은 출혈처럼 지속 피해를 주고, 상태변화(타입 "상태변화")는 피해 없이 약화/강화
상태가 된다. 축복·저주(모든 능력치 +1/-1), 아수라의 살의의 파동·정신이 번쩍!, 메카닉의 G-1~G-3은
버프가 아니라 상태변화다 - 참가자 "상태이상"에 걸리고 상태이상 정의(status_effects.py, job_status.py)를 읽는다.
"""

import pytest

from game.data.buff.buff import 버프목록
from game.data.buff.job_status import 직업상태변화목록
from game.data.buff.status_effects import 상태이상목록
from game.system import skill_system as ss
from game.system.combat import stats
from tests import support

옮긴_것 = ("축복", "살의의 파동", "정신이 번쩍!", "G-1", "G-2", "G-3")


@pytest.fixture
def 전장():
    전투상태, 적, 아군 = support.시험_전투(["고블린"])
    return 전투상태, 적[0], 아군[0]


def _이름들(참가자, 목록):
    return [항목["이름"] for 항목 in 참가자.get(목록) or []]


def test_옮긴_것은_버프가_아니라_상태변화다():
    for 이름 in 옮긴_것:
        assert 이름 not in 버프목록, 이름
        정의 = 상태이상목록[이름]
        assert (정의["분류"], 정의["타입"]) == ("상태변화", "상태변화"), 이름
    # 직업 전용 상태변화는 job_status.py에 있다
    assert set(직업상태변화목록) == {"살의의 파동", "정신이 번쩍!", "G-1", "G-2", "G-3"}


def test_저주는_약화CC이고_모든_능력치_1_감소로_축복의_반대다():
    저주, 축복 = 상태이상목록["저주"], 상태이상목록["축복"]
    assert (저주["분류"], 저주["타입"]) == ("약화CC", "상태변화")
    assert 저주["효과"] == {"추가효과": {"전체": -1}}
    assert 축복["효과"] == {"추가효과": {"전체": 1}}


def test_축복과_저주는_상태이상으로_걸려_모든_능력치를_바꾼다(전장):
    전투상태, _, p = 전장
    전 = {s: stats.유효_능력치값(전투상태, p, s) for s in ("근력", "지능", "매력")}
    ss.상태이상_부여(전투상태, p, "축복", 3)
    ss.상태이상_부여(전투상태, p, "축복", 3)  # 중첩 - 인스턴스마다 +1
    assert {s: stats.유효_능력치값(전투상태, p, s) for s in 전} == {
        s: v + 2 for s, v in 전.items()
    }
    ss.상태이상_부여(전투상태, p, "저주", 3)
    assert {s: stats.유효_능력치값(전투상태, p, s) for s in 전} == {
        s: v + 1 for s, v in 전.items()
    }
    assert "축복" not in _이름들(p, "버프")


def test_저주는_이제_내성굴림에_불리점을_주지_않는다(전장):
    전투상태, 고블린, _ = 전장
    ss.상태이상_부여(전투상태, 고블린, "저주", 3)
    assert stats.내성굴림_이점불리(전투상태, 고블린) == (0, 0)


def test_버프처럼_이름으로_걸어도_상태변화는_상태이상에_걸린다(전장):
    # 스킬 "버프획득", 특성 효과 {"종류": "버프"}, "전투시작버프"는 이 길로 건다
    전투상태, _, p = 전장
    ss.이름있는효과_부여(전투상태, p, "정신이 번쩍!", 시전자=p)
    assert "정신이 번쩍!" in _이름들(p, "상태이상")
    assert "정신이 번쩍!" not in _이름들(p, "버프")
    항목 = next(i for i in p["상태이상"] if i["이름"] == "정신이 번쩍!")
    assert "지속턴" not in 항목  # 지속턴이 없으면 전투가 끝날 때까지


def test_상태변화는_버프해제로_지워지지_않는다(전장):
    전투상태, _, p = 전장
    ss.이름있는효과_부여(전투상태, p, "정신이 번쩍!", 시전자=p)
    ss.이름있는효과_해제(p, "버프", "정신이 번쩍!")
    assert "정신이 번쩍!" in _이름들(p, "상태이상")


def test_살의의_파동은_건_사람을_기록한다(전장):
    전투상태, _, p = 전장
    다른 = next(x for x in 전투상태["참가자"] if x["진영"] == "아군" and x is not p)
    ss.이름있는효과_부여(전투상태, 다른, "살의의 파동", 지속턴오버라이드=3, 시전자=p)
    항목 = next(i for i in 다른["상태이상"] if i["이름"] == "살의의 파동")
    assert (항목["시전자id"], 항목["지속턴"]) == (p["id"], 3)
