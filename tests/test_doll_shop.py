from game.system.combat import flow, stats
from tests import support

능력치순 = ("근력", "민첩", "건강", "지능", "지혜", "매력")

# 이름: (체력 직업, 능력치, 시작 특성, 무기, 행동표 1~6)
기대 = {
    "아라드의 흔한 귀검사": (
        "귀검사",
        (14, 12, 10, 8, 10, 10),
        "귀수",
        "녹슨 소검",
        ["평타"] * 3 + ["어퍼 슬래쉬"] * 2 + ["귀참"],
    ),
    "아라드의 흔한 격투가": (
        "격투가",
        (12, 13, 11, 10, 10, 8),
        "단련된 육체",
        "허술한 통파",
        ["평타"] * 3 + ["어퍼컷"] * 2 + ["넨탄"],
    ),
    "아라드의 흔한 거너": (
        "거너",
        (8, 14, 10, 12, 10, 10),
        "군인",
        "조악한 보우건",
        ["평타"] * 3 + ["잭스파이크"] * 2 + ["라이징 샷"],
    ),
    "아라드의 흔한 마법사": (
        "마법사",
        (10, 8, 10, 14, 12, 10),
        "마법재능",
        "부패한 스태프",
        ["매직미사일"] * 3 + ["천격"] * 2 + ["랜턴파이어"],
    ),
    "아라드의 흔한 프리스트": (
        "프리스트",
        (13, 8, 10, 12, 11, 10),
        "성직자",
        "허술한 십자가",
        ["평타"] * 3 + ["라이징 슬래쉬"] * 2 + ["홀리 스매쉬"],
    ),
}


def _상태(이름=None, 개수=1, 플레이어레벨=4):
    상태 = support.새게임()
    상태["진행도"]["플레이어레벨"] = 플레이어레벨
    if 이름:
        상태["소지품"]["소모품"][이름] = 개수
    return 상태


@pytest.mark.parametrize("이름", list(기대))
def test_상점_인형의_데이터는_직업_추천_능력치와_시작장비를_따른다(이름):
    직업, 능력치, 특성, 무기, 행동표 = 기대[이름]
    데이터 = 인형_데이터[이름]
    assert 데이터["체력"] == 직업
    assert 데이터["기본AC"] == 12
    assert 데이터["주문시전능력치"] == "지능"
    assert 데이터["스타일"] == "밀리"
    assert 데이터["인형무기"] == 무기
    assert 데이터["가격"] == 50
    assert 데이터["제작재료"] == {"무색 큐브 조각": 5}
    assert [데이터["행동표"][i] for i in range(1, 7)] == 행동표
    # 행동표의 스킬은 모두 있는 스킬이다("평타"만 스킬이 아니다)
    상태 = _상태(이름)
    assert all(p == "평타" or p in 상태["스킬데이터모음"] for p in 행동표)
    gf.인형_사용(상태, 이름)
    인형 = 상태["파티"]["인형"]
    assert tuple(인형[n] for n in 능력치순) == 능력치  # 특성 +1이 두 번 붙지 않는다
    assert 특성 in 인형["보유특성"]


def test_상점_인형은_전투에서_AC_12_더하기_민첩보정이고_무기를_든다():
    이름 = "아라드의 흔한 거너"  # 민첩 14 -> 보정 +2
    상태 = _상태(이름)
    gf.인형_사용(상태, 이름)
    gf.전투_시작(상태, ["고블린"], 레벨=2, 차수=1)
    support.반응_처리(상태)
    인형 = next(p for p in gf.아군_목록(상태) if p.get("인형"))
    assert stats.최종AC(상태["전투상태"], 인형) == 12 + 2
    assert 인형["장비데이터"]["무기"]["이름"] == "조악한 보우건"


def _인형_차례(monkeypatch, 이름, 주사위):
    상태 = _상태(이름)
    gf.인형_사용(상태, 이름)
    gf.전투_시작(상태, ["고블린"], 레벨=2, 차수=1)
    support.반응_처리(상태)
    인형 = next(p for p in gf.아군_목록(상태) if p.get("인형"))
    전투상태 = 상태["전투상태"]
    전투상태["현재턴"] = 전투상태["참가자"].index(인형)
    flow.턴_시작_처리(전투상태, 인형)
    support.주사위고정(monkeypatch, 주사위)
    시작 = len(전투상태["로그"])
    gf.인형_턴(상태, 인형)
    return 전투상태["로그"][시작:]


def test_인형의_평타는_무기로_일반공격을_한_번_한다(monkeypatch):
    새로그 = _인형_차례(monkeypatch, "아라드의 흔한 귀검사", 1)
    평타 = [e for e in 새로그 if e.get("종류") == "일반공격"]
    assert len(평타) == 1, 새로그  # 1차수 밀리 - 한 번
    assert 평타[0]["공격자"] == "아라드의 흔한 귀검사"
    assert not any(e.get("쉼") for e in 새로그)


def test_마법사_인형의_1번은_매직미사일이다(monkeypatch):
    새로그 = _인형_차례(monkeypatch, "아라드의 흔한 마법사", 1)
    assert any(e.get("스킬") == "매직미사일" for e in 새로그), 새로그


def test_상점_인형은_인형_탭에서_50골드에_사고_10골드에_판다():
    이름 = "아라드의 흔한 프리스트"
    상태 = _상태()
    assert "인형" in gf.상점_탭목록("소모품")
    판매 = 엘븐가드["상점판매목록"]
    구매가능 = [a["이름"] for a in gf.상점_구매목록(상태, "소모품", "인형", 판매)]
    assert 구매가능 == list(기대)  # 28호는 상점에서 팔지 않는다
    골드 = 상태["소지품"]["골드"] = 200
    gf.상점_구매(상태, "소모품", "인형", 이름, 2, 판매)
    assert 상태["소지품"]["소모품"][이름] == 2
    assert 상태["소지품"]["골드"] == 골드 - 100
    상태["소지품"]["소모품"]["28호"] = 1
    판매목록 = [(a["이름"], n) for a, n in gf.상점_판매목록(상태, "소모품", "인형")]
    assert 판매목록 == [(이름, 2)]
    gf.상점_판매(상태, "소모품", "인형", 이름, 1)
    assert 상태["소지품"]["골드"] == 골드 - 100 + 10


def test_28호는_상점판매목록에_이름이_있어도_사지_못한다():
    상태 = _상태()
    assert all(
        a["이름"] != "28호" for a in gf.상점_구매목록(상태, "소모품", "인형", ["28호"])
    )


def test_상점_인형은_인형사에서_무색_큐브_조각_5개로_만든다():
    이름 = "아라드의 흔한 격투가"
    상태 = _상태()
    상태["소지품"]["재료"]["무색 큐브 조각"] = 7
    골드 = 상태["소지품"]["골드"]
    항목 = next(h for h in gf.전문직업_인형목록(상태) if h["이름"] == 이름)
    assert 항목["재료"] == [("무색 큐브 조각", 5, 7)] and 항목["제작가능"] is True
    gf.전문직업_인형제작(상태, 이름)
    assert 상태["소지품"]["재료"]["무색 큐브 조각"] == 2
    assert 상태["소지품"]["소모품"][이름] == 1
    assert 상태["소지품"]["골드"] == 골드
