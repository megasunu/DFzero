# 자동전투 대상 고르기와 방식 - 잡기불가 적에게 잡기 스킬을 쓰지 않음(#759).
# 판단 코드는 game/controller/ctl_autobattle.py.

import gameflow as gf
from game.system import rng
from tests import support


def _전장(직업, 전직, 적=("고블린", "고블린", "고블린")):
    """직업 -> 전직 레벨 8(스킬 전부 습득)과 격투가 동료 대 적 - 시험자의 차례, 적 HP 999, MP 넉넉."""
    rng.시드(7)
    gf.자동전투_방식_설정("전력전투")  # 남은 적을 가장 약한 순으로 본다
    상태 = support.새게임([("", 직업), ("", "격투가")])
    c = 상태["파티"]["파티원"][0]
    support.성장(상태, c, 8, 전직=전직, 스킬습득=True)
    gf.전투_시작(상태, list(적), 레벨=2, 차수=1)
    support.반응_처리(상태)
    전투상태 = 상태["전투상태"]
    for p in 전투상태["참가자"]:
        if p["진영"] == "적":
            p["현재HP"] = 999
    for _ in range(50):
        if gf.현재_턴_참가자(상태)["원본"] is c:
            break
        gf.턴_넘기기(상태)
    p = gf.현재_턴_참가자(상태)
    assert p["원본"] is c
    p["현재MP"] = 999
    return 상태, 전투상태, p


def _적(전투상태, 몬스터명):
    return [
        e
        for e in 전투상태["참가자"]
        if e["진영"] == "적" and e["원본"].get("몬스터명") == 몬스터명
    ]


def _인수(상태, p, 이름):
    return gf._전력전투_인수(상태, 상태["스킬데이터모음"][이름], p)


# ------------------------------------------------------------------ 1 잡기불가(#759)


def test_잡기_스킬은_잡기불가_적을_건너뛰고_다른_적을_고른다():
    상태, 전투상태, p = _전장("격투가", "그래플러", 적=("진흙 골렘", "고블린"))
    골렘 = _적(전투상태, "진흙 골렘")[0]
    골렘["현재HP"] = 1  # 가장 약해도 고르지 않는다
    인수 = _인수(상태, p, "수플렉스")
    assert 인수["중심대상"]["원본"]["몬스터명"] == "고블린"


def test_칠_수_있는_적이_모두_잡기불가면_잡기_스킬은_쓰지_않는다():
    상태, _, p = _전장("격투가", "그래플러", 적=("진흙 골렘", "진흙 골렘"))
    assert _인수(상태, p, "수플렉스") is None
    고른 = gf.전력전투_고르기(상태, p)
    assert 고른 is None or 고른[0] != "수플렉스"


def test_잡기가_아닌_스킬은_잡기불가_적도_고른다():
    상태, _, p = _전장("격투가", "그래플러", 적=("진흙 골렘", "진흙 골렘"))
    assert _인수(상태, p, "로킥") is not None


def test_그랩_캐논이_있으면_잡기불가_적에게도_잡기_스킬을_쓴다():
    상태, 전투상태, p = _전장("격투가", "그래플러", 적=("진흙 골렘", "고블린"))
    골렘 = _적(전투상태, "진흙 골렘")[0]
    골렘["현재HP"] = 1
    p["원본"].setdefault("보유특성", []).append("그랩 캐논")
    assert _인수(상태, p, "수플렉스")["중심대상"] is 골렘


# ------------------------------------------------------------------ 2 동점·적반복지정(#760)


def test_평가가_같은_공격은_이번_전투에서_덜_쓴_것을_고른다():
    상태, 전투상태, p = _전장("프리스트", "미스트리스")
    셋 = ("러스트 핸드", "프라이드 악셀", "슬로스 바디")
    # 보조행동 공격 셋만 남긴다(버프·자원 단계가 먼저 고르지 않게)
    p["원본"]["보유스킬"] = [s for s in p["원본"]["보유스킬"] if s in 셋]
    평가 = {s: gf.공격_평가(상태, p, s) for s in p["원본"]["보유스킬"]}
    assert len(set(평가.values())) == 1 and len(평가) >= 2  # 전제: 동점
    첫째 = gf.전력전투_고르기(상태, p)[0]
    assert 첫째 in 평가
    전투상태.setdefault("자동전투사용", {})[f"{p['id']}:{첫째}"] = 1
    둘째 = gf.전력전투_고르기(상태, p)[0]
    assert 둘째 in 평가 and 둘째 != 첫째


def test_한_차례에_쓴_스킬은_사용_횟수를_센다():
    상태, 전투상태, p = _전장("프리스트", "미스트리스")
    gf.전력전투_한_차례(상태)
    assert 전투상태["자동전투사용"]
    assert all(k.startswith(f"{p['id']}:") for k in 전투상태["자동전투사용"])


def test_썬더콜링은_가장_약한_적부터_돌아가며_대상을_정한다():
    상태, 전투상태, p = _전장("마법사", "엘리멘탈마스터")
    적 = [e for e in 전투상태["참가자"] if e["진영"] == "적"]
    for hp, e in zip((30, 10, 20), 적):
        e["현재HP"] = hp
    인수 = _인수(상태, p, "썬더콜링")
    목록 = 인수["지정대상목록"]
    횟수 = gf.현재참가자_수치(상태, 상태["스킬데이터모음"]["썬더콜링"]["공격횟수"])
    assert len(목록) == 횟수
    순서 = sorted(적, key=lambda e: e["현재HP"])
    assert 목록 == [순서[i % 3] for i in range(횟수)]
    gf.아군_스킬사용(상태, "썬더콜링", **인수)  # 실제로 낼 수 있다(캐스팅 시작)
    assert p.get("캐스팅", {}).get("스킬") == "썬더콜링"
