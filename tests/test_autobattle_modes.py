def _공격스킬(상태, p):
    return [
        s
        for s in p["원본"]["보유스킬"]
        if 상태["스킬데이터모음"][s].get("분류") == "공격스킬"
    ]


def test_골고루면_일반공격보다_약한_공격스킬도_후보다():
    상태, _, p = _전장("프리스트", "미스트리스")
    약한 = [
        s
        for s in _공격스킬(상태, p)
        if 0 < gf.공격_평가(상태, p, s) < gf.일반공격_기대피해(상태, p)
        and gf.스킬_사용_가능여부(상태, p, s)[0]
    ]
    assert 약한  # 전제: 일반공격보다 약한 스킬이 있다
    데이터 = 상태["스킬데이터모음"][약한[0]]
    assert not gf._전력전투_쓸만한가(상태, p, 약한[0], 데이터)
    assert gf._전력전투_쓸만한가(상태, p, 약한[0], 데이터, 골고루=True)


def test_골고루면_이번_전투에_가장_적게_쓴_공격을_고른다():
    상태, 전투상태, p = _전장("거너", "런처")
    p["원본"]["보유스킬"] = _공격스킬(상태, p)  # 버프·자원 단계를 빼고 공격만
    사용 = 전투상태.setdefault("자동전투사용", {})
    본것 = []
    for _ in range(3):
        이름 = gf.전력전투_고르기(상태, p, 골고루=True)[0]
        assert 이름 not in 본것  # 한 번 쓴 것은 다른 스킬이 다 나갈 때까지 뒤로
        본것.append(이름)
        사용[f"{p['id']}:{이름}"] = 1
    # 같은 횟수면 평가가 큰 것 - 첫째는 전력전투가 고르는 것과 같다
    사용.clear()
    assert gf.전력전투_고르기(상태, p, 골고루=True) == gf.전력전투_고르기(상태, p)


def _한판_쓴_공격(방식):
    gf.자동전투_방식_설정(방식)
    rng.시드(3)
    상태 = support.새게임([("", "거너"), ("", "격투가")])
    c = 상태["파티"]["파티원"][0]
    support.성장(상태, c, 8, 전직="런처", 스킬습득=True)
    gf.전투_시작(상태, ["고블린"] * 4, 레벨=4, 차수=1)
    support.반응_처리(상태)
    for e in 상태["전투상태"]["참가자"]:
        if e["진영"] == "적":
            e["현재HP"] = 200
    for _ in range(400):
        if gf.전투_종료됨(상태):
            break
        if gf.아군_차례인가(상태):
            gf.현재_턴_참가자(상태)["현재MP"] = 999
            gf.자동전투_한_턴(상태)
        else:
            gf.턴_넘기기(상태)
    공격 = set(
        _공격스킬(상태, next(q for q in 상태["전투상태"]["참가자"] if q["원본"] is c))
    )
    return {
        e["스킬"]
        for e in 상태["전투상태"]["로그"]
        if e.get("공격자") == c["캐릭터명"] and e.get("스킬") in 공격
    }


def test_자동전투_방식은_전력전투보다_여러_공격스킬을_쓴다():
    골고루 = _한판_쓴_공격("자동전투")
    전력 = _한판_쓴_공격("전력전투")
    assert len(골고루) > len(전력)
    assert _한판_쓴_공격("기본전투") == set()  # 기본전투는 스킬을 쓰지 않는다
