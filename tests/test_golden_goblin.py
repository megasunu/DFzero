def _황금_전투(몬스터들, 레벨=3):
    rng.시드(5)
    상태 = 새게임()
    gf.던전_진입(상태, 던전파일명(1))
    gf.전투_시작(상태, 몬스터들, 레벨=레벨, 차수=1)
    support.반응_처리(상태)
    황금 = next(p for p in gf.적_목록(상태) if p["원본"]["몬스터명"] == "황금 고블린")
    return 상태, 황금


def _도망칠_때까지_턴_넘기기(상태, 황금):
    for _ in range(200):
        if 황금.get("도망") or gf.전투_종료됨(상태):
            return
        gf.턴_넘기기(상태)


def test_황금_고블린은_고블린에_모든_능력치_4를_더한다():
    상태, 황금 = _황금_전투(["고블린", "황금 고블린"])
    고블린 = next(p for p in gf.적_목록(상태) if p is not 황금)
    for 이름 in ("근력", "민첩", "건강", "지능", "지혜", "매력"):
        assert 황금["원본"][이름] == 고블린["원본"][이름] + 4
    assert (
        gf.몬스터목록["황금 고블린"]["근력"] == gf.몬스터목록["고블린"]["근력"]
    )  # 데이터는 그대로
    # 레벨3 딜러: 고블린 기본체력 4 -> 4+6-1 = 9, 황금 6 -> 6+9-1 = 14 / AC는 민첩보정치 +2
    assert (고블린["현재HP"], 황금["현재HP"]) == (9, 14)
    전투상태 = 상태["전투상태"]
    assert stats.최종AC(전투상태, 황금) == stats.최종AC(전투상태, 고블린) + 2


def test_황금_고블린_혼자면_자기_턴_5번_뒤_도망치고_보상이_없다():
    상태, 황금 = _황금_전투(["황금 고블린"])
    골드 = 상태["소지품"]["골드"]
    _도망칠_때까지_턴_넘기기(상태, 황금)
    assert 황금["도망"] and not 황금["생존"] and 황금["끝난턴수"] == 5
    assert 황금["현재HP"] > 0  # 쓰러진 것이 아니다
    assert any(
        기록.get("공격자") == "황금 고블린" and 기록.get("행동") == "도망쳤다!"
        for 기록 in 상태["전투상태"]["로그"]
    )
    assert gf.전투_결과_정리(상태) == "적도망"
    assert 상태["전투_전리품"] is None and 상태["전투_보상"] is None
    assert 상태["소지품"]["골드"] == 골드
    assert gf.전투_종료_문구(상태, "적도망") == ["적이 도망쳤다!"]


def test_다른_적을_잡았으면_황금_고블린이_도망쳐도_승리_전리품은_잡은_적_것만():
    상태, 황금 = _황금_전투(["고블린", "황금 고블린"])
    고블린 = next(p for p in gf.적_목록(상태) if p is not 황금)
    damage.피해_적용(상태["전투상태"], 고블린, 10**6, 피해감소무시=True)
    _도망칠_때까지_턴_넘기기(상태, 황금)
    assert 황금["도망"]
    assert gf.전투_결과_정리(상태) == "아군승리"
    전리품 = 상태["전투_전리품"]
    assert (
        8 <= 전리품["골드"] <= 16
    )  # 고블린 공식 (10+레벨)x0.7~1.3 올림만(황금 고블린 몫 없음)
    언커먼 = {
        이름
        for 탭 in 상태["상점카탈로그"]["장비"].values()
        for 이름, d in 탭.items()
        if d.get("레어도") == "언커먼"
    }
    assert not {이름 for 이름, _ in 전리품["아이템"]} & 언커먼
    assert not set(gf.전투_보상_칸(상태)) & 언커먼  # 보상 후보도 고블린 드랍표뿐


def test_황금_고블린을_잡으면_10더하기레벨_x10_골드와_언커먼_장비_하나():
    상태, 황금 = _황금_전투(["황금 고블린"], 레벨=3)
    support.강제_승리(상태)
    assert gf.전투_결과_정리(상태) == "아군승리"
    전리품 = 상태["전투_전리품"]
    assert 91 <= 전리품["골드"] <= 169  # (10+3)x10 x 0.7~1.3
    레어도 = {
        n: d.get("레어도")
        for 탭 in 상태["상점카탈로그"]["장비"].values()
        for n, d in 탭.items()
    }
    # 개인 드랍(황금고블린군) 언커먼 1개 + 로리엔 공용 드랍(커먼방어구군 30%)이 붙을 수 있다.
    # 장비가 아닌 것은 고블린 종족 공용 잡템(고블린공용군)뿐이다.
    장비 = [(이름, 개수) for 이름, 개수 in 전리품["아이템"] if 이름 in 레어도]
    잡템 = {이름 for 이름, _ in 전리품["아이템"] if 이름 not in 레어도}
    assert 잡템 <= {"고블린 가죽", "고블린의 손뼈"}
    언커먼 = [(이름, 개수) for 이름, 개수 in 장비 if 레어도[이름] == "언커먼"]
    assert len(언커먼) == 1 and 언커먼[0][1] == 1
    assert all(레어도[이름] in ("언커먼", "커먼") for 이름, _ in 장비)
    assert all(칸 and 레어도[칸] in ("언커먼", "커먼") for 칸 in gf.전투_보상_칸(상태))


def test_드랍은_던전_공용_드랍표와_몬스터_개인_드랍표를_둘_다_굴린다():
    """던전 안이면 던전 공용 드랍표 뒤에 몬스터 드랍표(종족 공용 + 개인)를 붙인다."""
    상태 = 새게임()
    전투_열기(상태, ["황금 고블린"])
    support.강제_승리(상태)
    (대상,) = gf._전리품_대상(상태, 상태["전투상태"])
    assert [r["이름"] for r in 대상["드랍표"]] == [
        "커먼무기방어구군",
        "고블린공용군",
        "황금고블린군",
    ]
    상태["던전상태"] = None  # 던전 밖이면 몬스터 쪽 드랍만
    (대상,) = gf._전리품_대상(상태, 상태["전투상태"])
    assert [r["이름"] for r in 대상["드랍표"]] == ["고블린공용군", "황금고블린군"]


def test_인카운트는_1퍼센트로_한_마리를_황금_고블린으로_바꾼다(monkeypatch):
    상태 = 새게임()
    gf.던전_진입(상태, 던전파일명(1))
    던전상태 = 상태["던전상태"]
    던전상태["걸음수"] = 999  # 인카운트 확률 100%
    # 던전 흐름의 모든 굴림(인카운트, 몬스터 고르기의 가중치 굴림 포함)을 한 값으로 - 교체 판정은 < 0.01
    monkeypatch.setattr(rng.던전, "random", lambda: 0.0)
    적 = dungeon_system.인카운트_판정(던전상태)["등장몬스터"]
    assert 적.count("황금 고블린") == 1
    monkeypatch.setattr(rng.던전, "random", lambda: 0.01)  # 교체 판정 실패
    assert "황금 고블린" not in dungeon_system.인카운트_판정(던전상태)["등장몬스터"]


