def _가장_빈(상태, 키, 최대):
    """현재값이 최대보다 가장 많이 모자란 캐릭터와 모자란 양 - 포션을 못 마시는 쓰러진 캐릭터는 뺀다."""
    살아있는 = [c for c in 상태["파티"]["파티원"] if c["현재HP"] > 0]
    캐릭터 = max(살아있는, key=lambda c: 최대(상태, c) - c[f"현재{키}"])
    return 캐릭터, 최대(상태, 캐릭터) - 캐릭터[f"현재{키}"]


