"""S11 도감·업적 (docs/scenarios.md).

4인 기본 파티가 새 게임에서 로리엔 인카운트 5번과 보스를 **실제 전투로** 치른다. 처치한 몬스터와 전리품/전투
보상으로 들어온 장비·재료가 도감에 등록되는지, 일반/보스 전투 승리가 따로 세어지는지, 일반전투 5회·몬스터 도감
3종·세리아 구출(로리엔 보스)·1레벨 업적이 달성되는지, 달성 전 업적은 받을 수 없는지, 세이브/불러오기 뒤에도
기록이 남고 [보상 전부 받기]가 업적마다 10골드(세리아 구출은 봉인 레어 무기)를 주는지를 본다. 단위 규칙은 test_collection_achievement.py.
"""

import pytest

from game.system import rng
import gameflow as gf
import scenario
import support

로리엔 = "dungeon_01A_D01_Lorien"
시드 = 1


def _처치한_적(상태):
    return {
        e["원본"]["몬스터명"]
        for e in gf.적_목록(상태)
        if not e["생존"] and not e.get("도망")
    }


def _실전_기록(상태, 처치, 들어온):
    """실전 -> 처치한 적 기록 -> 결과 정리 -> 보상 수령. 소지품에 들어온 (칸, 이름)을 모은다."""
    종료 = scenario.실전(상태)
    처치 |= _처치한_적(상태)
    assert gf.전투_결과_정리(상태) == 종료 == "아군승리", 종료
    for 이름, _ in 상태["전투_전리품"]["아이템"]:
        들어온.add(이름)
    받음 = scenario.보상_수령(상태)
    if 받음[0] == "아이템":
        들어온.add(받음[1])


@pytest.mark.scenario("S11")
def test_S11_도감_업적_실전(임시_세이브폴더):
    rng.시드(시드)
    상태 = support.새게임()
    진행도 = 상태["진행도"]
    assert gf.업적_받을_보상_수(상태) == 1  # 1레벨 달성은 처음부터
    gf.던전_진입(상태, 로리엔)
    처치, 들어온 = set(), set()

    # 1) 인카운트 5번 - 일반 전투 승리 5, 처치한 몬스터가 도감에
    for 번 in range(1, 6):
        scenario.인카운트까지_걷기(상태)
        _실전_기록(상태, 처치, 들어온)
        assert 진행도["업적기록"] == {"일반전투승리": 번, "보스전투승리": 0}
    assert set(진행도["도감"]["몬스터"]) == 처치

    # 2) 보스 - 보스 전투 승리 1, 세리아 구출
    def 보스전(s):
        종료 = scenario.실전(s)
        처치.update(_처치한_적(s))
        return 종료

    결과, _ = support.보스_처치(상태, 전투처리=보스전)
    assert 결과 == "아군승리"
    scenario.보상_수령(상태)
    assert 진행도["업적기록"]["보스전투승리"] == 1
    assert "겁쟁이 고블린" in 진행도["도감"]["몬스터"]
    assert set(진행도["도감"]["몬스터"]) == 처치

    # 전리품/보상으로 들어온 장비와 재료는 전부 도감에 있다
    등록 = set(진행도["도감"]["장비"]) | set(진행도["도감"]["재료"])
    도감대상 = {
        a["이름"]
        for 대분류 in ("장비", "재료")
        for 줄 in gf.도감_탭줄(상태, 대분류)
        for 탭 in 줄
        for a, _ in gf.도감_목록(상태, 대분류, 탭)
    }
    assert 들어온 & 도감대상 and (들어온 & 도감대상) <= 등록

    # 3) 업적 - 달성한 것과 아닌 것
    달성 = {
        줄["ID"]
        for 분류 in gf.업적_분류목록
        for 줄 in gf.업적_목록(상태, 분류)
        if 줄["달성"]
    }
    assert 달성 >= {"레벨_1", "몬스터도감_3", "일반전투_5", "세리아_구출"}
    assert "보스전투_2" not in 달성
    with pytest.raises(ValueError, match="달성하지"):
        gf.업적_보상_받기(상태, "보스전투_2")

    # 4) 던전 안에서 저장 -> 불러오기 -> 전부 받기
    gf.게임_저장(상태, 1)
    상태 = gf.게임_불러오기(1)
    assert 상태["진행도"]["도감"] == 진행도["도감"]
    assert 상태["진행도"]["업적기록"] == 진행도["업적기록"]
    골드 = 상태["소지품"]["골드"]
    assert gf.업적_보상_받기(상태, "레벨_1") == {"골드": 10, "아이템": []}
    수, 합 = gf.업적_보상_전부_받기(상태)
    # 세리아 구출은 랜덤 레어 무기(마법으로 봉인된 무기 하나), 나머지는 10골드씩
    assert 수 == len(달성) - 1 and 합["골드"] == 10 * (수 - 1)
    [(무기, 개수)] = 합["아이템"]
    assert 개수 == 1
    assert 무기.startswith("마법으로 봉인된 ") and 상태["소지품"]["장비"][무기] == 1
    assert 상태["소지품"]["골드"] == 골드 + 10 * (len(달성) - 1)
    assert gf.업적_받을_보상_수(상태) == 0
