"""S1 첫 던전 실전 (docs/scenarios.md).

4인 기본 파티가 새 게임에서 로리엔 인카운트 2회와 보스를 **실제 전투로** 치르고, 전리품과 보상을
받아 장비를 바꾸고 상점에 팔고 세이브/불러오기를 거친 뒤 한 번 더 싸운다. 전투 사이에 휴식하지 않는다 -
HP가 전투를 건너 이어지는지가 검사 대상이다. 전투 규칙 자체는 test_combat_*.py가 검사한다.
"""

import pytest

from game.system import rng
import gameflow as gf
import scenario
import support

시드 = 1


def _던전1():
    return "dungeon_01A_D01_Lorien"


def _전투_한_번(상태, 이름들, 기록):
    """실전 -> 결과 정리 -> 보상 수령, 그리고 전투가 남긴 것이 소지품에 맞게 들어갔는지 검사한다."""
    골드전 = 상태["소지품"]["골드"]
    장비전 = scenario.소지품_아이템수(상태)
    HP전 = scenario.파티_HP(상태)
    # 앞 전투의 피해가 이어져 들어온다(HP 0인 파티원은 전투에 들어오지 않는다 - party_system.생존자_목록)
    assert scenario.전투중_아군_HP(상태) == {k: v for k, v in HP전.items() if v > 0}
    종료 = scenario.실전(상태)
    라운드 = 상태["전투상태"]["라운드"]
    assert gf.전투_결과_정리(상태) == 종료
    assert 종료 == "아군승리", f"{이름들}: {종료}"
    HP = scenario.파티_HP(상태)
    # 정리가 참가자 HP를 캐릭터 원본에 되돌려 썼고, 휴식 없이는 HP가 늘지 않는다
    assert all(0 <= HP[k] <= HP전[k] for k in HP) and any(v > 0 for v in HP.values())
    전리품 = 상태["전투_전리품"]
    assert 상태["소지품"]["골드"] == 골드전 + 전리품["골드"]
    assert gf.전투_보상_대기중(상태)
    받음 = scenario.보상_수령(상태)
    assert not gf.전투_보상_대기중(상태)
    장비후 = scenario.소지품_아이템수(상태)
    늘어난 = {
        k: 장비후.get(k, 0) - 장비전.get(k, 0)
        for k in 장비후
        if 장비후.get(k, 0) != 장비전.get(k, 0)
    }
    기대 = {}
    for 이름, 개수 in 전리품["아이템"]:
        기대[이름] = 기대.get(이름, 0) + 개수
    if 받음[0] == "아이템":
        기대[받음[1]] = 기대.get(받음[1], 0) + 1
    assert 늘어난 == 기대
    기록.append(
        {
            "적": 이름들,
            "종료": 종료,
            "라운드": 라운드,
            "HP": HP,
            "전리품": {"골드": 전리품["골드"], "아이템": 전리품["아이템"]},
            "보상": 받음,
        }
    )


def _착용_가능한_교체(상태, 캐릭터):
    """소지품에서 지금 착용 가능하고 장착 중인 것과 다른 아이템 (슬롯, 이름)을 하나 찾는다."""
    for 슬롯 in gf.장비_슬롯목록:
        현재 = (gf.캐릭터_장착아이템(상태, 캐릭터, 슬롯) or {}).get("이름")
        for 아이템, 수량, 가능, _ in gf.장비_교체_후보(상태, 캐릭터, 슬롯):
            if 가능 and 수량 > 0 and 아이템["이름"] != 현재:
                return 슬롯, 아이템["이름"]
    return None


def _팔_수_있는_장비(상태):
    """장착 중이 아닌 장비 하나 (탭, 이름)."""
    for 탭 in gf.상점_탭목록("장비"):
        for 아이템, 수량 in gf.상점_판매목록(상태, "장비", 탭):
            if 수량 > 0:
                return 탭, 아이템["이름"]
    return None


@pytest.mark.scenario("S1")
def test_S1_첫_던전_실전(golden):
    rng.시드(시드)
    상태 = support.새게임()
    파티 = 상태["파티"]["파티원"]
    assert [c["직업"] for c in 파티] == ["귀검사", "격투가", "거너", "프리스트"]
    골드0 = 상태["소지품"]["골드"]
    gf.던전_진입(상태, _던전1())
    기록 = {"전투": []}

    # 1) 인카운트 2회 - 휴식 없이 이어서 싸운다
    for _ in range(2):
        이름들 = scenario.인카운트까지_걷기(상태)
        assert gf.전투_종료됨(상태) is False and not gf.전투_보상_대기중(상태)
        _전투_한_번(상태, 이름들, 기록["전투"])
        assert 상태["전투상태"] is None
    assert 상태["소지품"]["골드"] > 골드0

    # 2) 보스 - 이긴 기록이 진행도에 남고 오브젝트가 통행 가능해진다
    보스전 = []
    결과, 위치 = support.보스_처치(상태, 보스전, 전투처리=lambda s: _보스전투(s, 기록))
    assert 결과 == "아군승리"
    assert 상태["던전상태"]["그리드"][위치[1]][위치[0]] == "O"
    assert gf.전투_보상_대기중(상태)
    scenario.보상_수령(상태)

    # 3) 받은 장비를 입는다 - 장비데이터모음이 다시 만들어지고 HP는 새 최대치 이하
    무기사용자 = 파티[0]
    교체 = _착용_가능한_교체(상태, 무기사용자)
    assert 교체, "소지품에 입을 수 있는 새 장비가 없다"
    슬롯, 이름 = 교체
    gf.장비_교체(상태, 무기사용자, 슬롯, 이름)
    assert gf.캐릭터_장착아이템(상태, 무기사용자, 슬롯)["이름"] == 이름
    assert 상태["장비데이터모음"][무기사용자["캐릭터명"]][슬롯]["이름"] == 이름
    assert 무기사용자["현재HP"] <= gf.캐릭터_최대HP(상태, 무기사용자)
    기록["착용"] = [슬롯, 이름]

    # 4) 상점에 판다 - 받은 골드가 소지품에 더해지고 개수가 준다
    팔것 = _팔_수_있는_장비(상태)
    assert 팔것, "팔 수 있는 장비가 없다"
    탭, 팔이름 = 팔것
    골드, 개수 = 상태["소지품"]["골드"], 상태["소지품"]["장비"][팔이름]
    받음 = gf.상점_판매(상태, "장비", 탭, 팔이름, 1)
    assert 상태["소지품"]["골드"] == 골드 + 받음
    assert 상태["소지품"]["장비"].get(팔이름, 0) == 개수 - 1
    기록["판매"] = [탭, 팔이름, 받음]

    # 5) 세이브 -> 불러오기 - 소지품/진행도/파티/장착이 그대로 돌아온다
    gf.게임_저장(상태, 1)
    불러옴 = gf.게임_불러오기(1)
    assert 불러옴["소지품"] == 상태["소지품"]
    assert 불러옴["진행도"] == 상태["진행도"]
    assert scenario.파티_HP(불러옴) == scenario.파티_HP(상태)
    assert (
        gf.캐릭터_장착아이템(불러옴, 불러옴["파티"]["파티원"][0], 슬롯)["이름"] == 이름
    )
    assert 불러옴["진행도"]["플레이어레벨"] == 상태["진행도"]["플레이어레벨"]

    # 6) 불러온 게임으로 다시 던전에 들어가 한 번 더 싸운다
    gf.던전_진입(불러옴, _던전1())
    이름들 = scenario.인카운트까지_걷기(불러옴)
    _전투_한_번(불러옴, 이름들, 기록["전투"])
    assert 불러옴["진행도"]["플레이어레벨"] == 상태["진행도"]["플레이어레벨"]

    기록["최종"] = {
        "골드": 불러옴["소지품"]["골드"],
        "HP": scenario.파티_HP(불러옴),
        "플레이어레벨": 불러옴["진행도"]["플레이어레벨"],
    }
    golden("scenario_S1_first_dungeon", 기록)


def _보스전투(상태, 기록):
    골드전 = 상태["소지품"]["골드"]
    HP전 = scenario.파티_HP(상태)
    assert scenario.전투중_아군_HP(상태) == HP전
    종료 = scenario.실전(상태)
    HP = scenario.전투중_아군_HP(상태)
    assert all(HP[k] <= HP전[k] for k in HP)
    기록["보스"] = {"종료": 종료, "라운드": 상태["전투상태"]["라운드"], "HP": HP}
    assert 종료 == "아군승리", f"보스전: {종료}"
    assert 상태["소지품"]["골드"] == 골드전  # 정리 전에는 전리품이 아직 안 들어갔다
