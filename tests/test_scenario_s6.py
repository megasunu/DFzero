    gf.장비_교체(상태, g, "무기", 도)
    gf.파티_최대치로_회복(상태)

    gf.던전_진입(상태, 선더랜드)
    전투들 = []
    for 번호 in range(12):
        적 = scenario.인카운트까지_걷기(상태)
        기록 = {}
        종료 = _전투_검귀(상태, g, 기록, 번호)
