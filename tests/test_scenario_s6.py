# 귀영보·귀영섬(골드 스킬, 2026-11-16) - 레벨 8 소울브링어가 귀영보(기본 켜짐)를 사서 라운드 시작마다 MP 10으로
# 은신하고, 은신 중이면 귀영섬(보조행동)을 쓴 뒤 일반공격한다. 은신이 실제로 걸리고, 귀영섬이 나가며,
# 행동을 쓰면 은신이 풀리는지 본다(행동 뒤에는 은신이 없다).
def _전투_귀영(상태, 기록):
    support.반응_처리(상태)
    전투상태 = 상태["전투상태"]
    for _ in range(400):
        if gf.전투_종료됨(상태):
            break
        참가자 = gf.현재_턴_참가자(상태)
        if not (참가자["진영"] == "아군" and 참가자["생존"]):
            gf.턴_넘기기(상태)
            continue
        if 참가자["원본"].get("전직") == "소울브링어":
            은신 = any(i["이름"] == "은신" for i in 참가자["상태이상"])
            기록["은신차례"] = 기록.get("은신차례", 0) + 은신
            적들 = scenario._살아있는_적(상태)
            if 은신 and 적들 and gf.스킬_사용_가능여부(상태, 참가자, "귀영섬")[0]:
                gf.아군_스킬사용(상태, "귀영섬", 중심대상=적들[0])
                기록["귀영섬"] = 기록.get("귀영섬", 0) + 1
                assert not any(i["이름"] == "은신" for i in 참가자["상태이상"])
        _일반공격_턴_소울골드(상태, 참가자)
    else:
        raise AssertionError("전투가 끝나지 않았다")
    기록["은신로그"] = 기록.get("은신로그", 0) + sum(
        1
        for 항목 in 전투상태["로그"]
        if isinstance(항목, dict) and "은신했다(귀영보)" in str(항목.get("비고", ""))
    )
    return 전투상태["종료"]


