# 캐릭터 그림(game/assets/character/) 도트 크기 통일 - 필드 플레이어와 전투 아군 그림이
# 모든 직업에 같은 "도트 하나당 화면 크기"를 쓴다(2026-11-10 사용자 요청, 몬스터 제외).
# 실제 화면 배치는 tools/ui_smoke.py가 확인한다 - 여기는 배율과 겹침 순서 계산만.

import gameflow


def test_도트배율은_보통_크기_그림이_틀에_맞는_크기를_정수로_반올림한다():
    # 기준은 캐릭터 그림 65장의 폭/높이 중앙값(31x39)
    assert gameflow.캐릭터_기준_크기 == (31, 39)
    # 전투 칸(약 255x385, 칸에 맞춘 크기의 2/3): min(8.23, 9.87) * 2/3 = 5.48 -> 5
    assert gameflow.캐릭터_도트배율(255, 385, 2 / 3) == 5
    # 필드 칸 안쪽(약 65x65): min(2.10, 1.67) = 1.67 -> 2
    assert gameflow.캐릭터_도트배율(65, 65) == 2


def test_도트배율은_그림과_상관없이_틀_크기로만_정해지고_최소_1이다():
    assert gameflow.캐릭터_도트배율(10, 10) == 1
    assert gameflow.캐릭터_도트배율(0, 0) == 1
    # 같은 틀이면 어느 직업이든 같은 값 - 그림 크기를 받지 않는다
    assert gameflow.캐릭터_도트배율(310, 390) == 10


def test_넓은_그림일수록_뒤에_그린다():
    # 그림 폭(도트) 목록 -> 그리는 순서(칸 번호, 뒤에서 앞으로). 넓어 칸을 넘는 그림이
    # 먼저(뒤에) 그려져 이웃 캐릭터가 그 위를 덮는다. 같은 폭은 원래 순서.
    assert gameflow.캐릭터_그리는_순서([22, 71, 31, 66]) == [1, 3, 2, 0]
    assert gameflow.캐릭터_그리는_순서([30, 30, 40]) == [2, 0, 1]
    assert gameflow.캐릭터_그리는_순서([]) == []
