시드_메스가키 = 0


def _전투_메스가키(상태, 프리스트):
    """프리스트의 첫 차례에 도발, 나머지는 [자동전투]."""
    support.반응_처리(상태)
    도발씀 = False
    for _ in range(300):
        if gf.전투_종료됨(상태):
            return 상태["전투상태"]["종료"]
        참가자 = gf.현재_턴_참가자(상태)
        if not 도발씀 and gf.아군_차례인가(상태) and 참가자["원본"] is 프리스트:
            보조 = 참가자["행동자원"]["보조행동"]
            gf.아군_스킬사용(상태, "도발")
            assert 참가자["행동자원"]["보조행동"] == 보조 - 1
            도발씀 = True
        if gf.아군_차례인가(상태):
            gf.자동전투_한_턴(상태)
        else:
            gf.턴_넘기기(상태)
    raise AssertionError("전투가 끝나지 않았다")


