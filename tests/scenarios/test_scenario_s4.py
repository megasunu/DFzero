def _세기(로그, 글):
    return sum(글 in str(x.get("비고", "")) for x in 로그)


@pytest.mark.scenario("S4")
def test_S4_용인족_실전():
    scenario.시드(시드_용인족)
    상태 = support.새게임(_파티)
    scenario.측정_파티_준비(상태, 5)
    프리스트 = 상태["파티"]["파티원"][2]
    상태["소지품"]["장비"]["배틀마스터"] = 1
    gf.장비_교체(상태, 프리스트, "무기", "배틀마스터")
    기록 = {"결과": [], "감옥": 0, "차징": 0, "오라사냥": 0}
    for 몬스터들 in _전투들:
        gf.휴식(상태)
        gf.전투_시작(상태, 몬스터들, 레벨=5, 차수=1)
        결과 = scenario.스킬_실전(상태, [])
        전투상태 = 상태["전투상태"]
        로그 = 전투상태["로그"]
        기록["감옥"] += _세기(로그, "에 갇힘") + _세기(로그, "'감옥'을 피함")
        기록["차징"] += _세기(로그, "심장 찌르기 차징을 시작")
        기록["오라사냥"] += _세기(로그, "오라를 내던")
        for 감옥 in (p for p in 전투상태["참가자"] if p.get("감옥")):
            assert 감옥["기본최대HP"] <= 10
            갇힌 = next(p for p in 전투상태["참가자"] if p["id"] == 감옥["갇힌id"])
            assert 갇힌["진영"] == "아군"
        기록["결과"].append(결과)
        gf.전투_결과_정리(상태)
        if 결과 != "아군승리":
            break
        if gf.전투_보상_대기중(상태):
            scenario.보상_수령(상태)
    assert 기록["결과"] == ["아군승리", "아군승리"], 기록
    assert 기록["감옥"] >= 1 and 기록["차징"] >= 1, 기록
    assert 기록["오라사냥"] >= 1, 기록


