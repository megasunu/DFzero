# S5 장비강화 실전 - 착용 중인 무기 강화·재련 -> 실전 -> 세이브 왕복 -> 실전 (docs/scenarios.md).
#
# 4인 기본 파티의 귀검사가 언커먼 강철 소검을 장착하고, [전문직업] > [연금술]로 라이언 코크스 1개를 강렬한 기운으로
# 바꾼 뒤 [장비강화]로 착용 중인 그 무기를 무기강화(+1d4) -> 무기재련(명중 +1)해 "+1강1재 강철 소검"을 만든다(골드,
# 언커먼 소울, 강화는 라이언 코크스·재련은 강렬한 기운을 치른다). 같은 무기는
# 증폭할 수 없다. 로리엔 인카운트를 **실전으로** 이기는 동안 귀검사의 무기 주사위가 "1d6+1d4"다. 저장/불러오기 뒤에도
# 장착 칸과 카탈로그에 강화한 무기가 남고, 다시 실전으로 이긴다. 수치 규칙(비용 제곱, 최대 수치, 부위별 합계 보너스)은
# test_enhance.py가 본다.
# ======================================================================


시드_강화 = 1
_로리엔 = "dungeon_01A_D01_Lorien"
_무기_강화 = "강철 소검"


def _인카운트_실전(상태, 귀검사):
    scenario.인카운트까지_걷기(상태)
    전투상태 = 상태["전투상태"]
    참가자 = next(p for p in 전투상태["참가자"] if p.get("원본") is 귀검사)
    무기 = 상태["장비데이터모음"][귀검사["캐릭터명"]]["무기"]
    주사위 = stats.유효_무기공격력(전투상태, 참가자, 무기)
    종료 = scenario.실전(상태)
    assert gf.전투_결과_정리(상태) == 종료 == "아군승리", 종료
    if gf.전투_보상_대기중(상태):
        scenario.보상_수령(상태)
    return 주사위


@pytest.mark.scenario("S5")
def test_S5_장비강화_실전():
    scenario.시드(시드_강화)
    상태 = support.새게임()
    귀검사 = next(c for c in 상태["파티"]["파티원"] if c["직업"] == "귀검사")
    소지품 = 상태["소지품"]
    소지품["장비"][_무기_강화] = 1
    gf.장비_교체(상태, 귀검사, "무기", _무기_강화)
    소지품["골드"] = 1000
    소지품["재료"]["언커먼 소울"] = 5
    소지품["재료"]["라이언 코크스"] = 2

    # 0) [연금술]로 라이언 코크스 1개를 재련 재료 강렬한 기운으로 바꾼다
    기운 = next(
        h for h in gf.전문직업_연금술목록(상태, "재료") if h["이름"] == "강렬한 기운"
    )
    gf.전문직업_연금술(상태, 기운)
    assert (소지품["재료"]["라이언 코크스"], 소지품["재료"]["강렬한 기운"]) == (1, 1)

    # 1) 착용 중인 무기를 강화 -> 재련 (항상 성공, 100G + 언커먼 소울 1 + 그 종류 재료 1씩)
    def 착용줄(선택지):
        return next(
            i
            for i in gf.전문직업_강화목록(상태, 선택지)
            if i["캐릭터"] is 귀검사 and i["슬롯"] == "무기"
        )

    assert gf.전문직업_강화(상태, 착용줄("무기강화"), "무기강화") == "+1강 강철 소검"
    이름 = gf.전문직업_강화(상태, 착용줄("무기재련"), "무기재련")
    assert 이름 == 귀검사["장착장비"]["무기"] == "+1강1재 강철 소검"
    assert (소지품["골드"], 소지품["재료"]["언커먼 소울"]) == (800, 3)
    assert "라이언 코크스" not in 소지품["재료"] and "강렬한 기운" not in 소지품["재료"]
    assert "강화" in 착용줄("무기증폭")["불가"]  # 강화한 무기는 증폭할 수 없다
    원본 = 상태["상점카탈로그"]["장비"]["무기"][_무기_강화]
    무기 = 상태["장비데이터모음"][귀검사["캐릭터명"]]["무기"]
    assert 무기["명중률보너스"] == 원본["명중률보너스"] + 1

    # 2) 실전 - 귀검사의 무기 주사위에 1d4가 붙는다
    gf.던전_진입(상태, _로리엔)
    assert _인카운트_실전(상태, 귀검사) == "1d6+1d4"

    # 3) 세이브 왕복 뒤에도 강화한 무기를 들고 실전
    gf.게임_저장(상태, 1)
    상태 = gf.게임_불러오기(1)
    귀검사 = next(c for c in 상태["파티"]["파티원"] if c["직업"] == "귀검사")
    assert 귀검사["장착장비"]["무기"] == 이름
    assert 이름 in 상태["상점카탈로그"]["장비"]["무기"]
    if 상태.get("던전상태") is None:
        gf.던전_진입(상태, _로리엔)
    assert _인카운트_실전(상태, 귀검사) == "1d6+1d4"
