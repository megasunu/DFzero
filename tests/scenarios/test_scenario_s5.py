# 밸런스 측정 조건 레벨 7 파티(무작위 한 명이 레어 무기·레어 방어구 세트·금도금 세트)가 아몬 하층(D11)을 걸어
# 인카운트를 실전으로 싸운다. 전투마다 아라드의 흔한 인형 하나가 들어오고, 이긴 전투의 전리품에서 레어 장비가
