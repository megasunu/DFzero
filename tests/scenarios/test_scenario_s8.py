# S8 인파이터 레벨 13 실전 - 추적(바디블로), 텐션행동 기간틱 캐넌, 헤븐리 컴비네이션(3차수) (#840).
#
# 프리스트가 든 4인 파티를 레벨 13까지 키운다(프리스트 -> 인파이터, 나머지는 구현된 전직, 스킬 전부 습득 - 사이드 너클·
# 할로우 백(2차수)·헤븐리 컴비네이션(3차수)을 [스킬습득]으로 사고 레벨 13에 기간틱 캐넌을 얻는다). 타우 아미·루가루·고블린을
# 실제 전투로 치른다(적 HP 3배 - 인파이터가 텐션 5를 모을 만큼 차례를 갖게). 레벨 13 인파이터의 MP(장비 없이 49)로는
# 헤븐리 컴비네이션(MP 30)과 텐션 5(신격권 5번)를 한 전투에 다 할 수 없어, 전투마다 번갈아 한다: 짝수 번째 전투는 원!투!(MP 5)로
# 텐션을 모으고, 홀수 번째는 헤븐리 컴비네이션부터. 텐션 개방 중이면 기간틱 캐넌을 텐션행동으로 쓴다. 나머지 MP는 바디블로·
# 사이드 너클·할로우 백 순서, 없으면 일반공격. 대상은 가장 약한 적, 바디블로만 HP가 가장 많은 적을 고른다(추적이 대상을
# 바꾸는지 보려고). 다른 셋은 스킬 우선 정책.
# 불변식: 기간틱 캐넌을 텐션행동으로 쓰면 MP는 그대로·큐브 조각 5개·일반행동 그대로·개방이 끝난다, 바디블로는 고른 적이
# 아니라 가장 강한 적(보스 -> 네임드 -> 엘리트 -> 일반, 같으면 HP 낮은 적)을 친다, 헤븐리 컴비네이션은 3단계가 다 나간다.
# 수치는 tests/jobs/test_job_infighter.py.
