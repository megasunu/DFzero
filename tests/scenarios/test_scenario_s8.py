시드_인파이터13 = 0
파티구성_인파이터 = [("", "프리스트"), ("", "귀검사"), ("", "마법사"), ("", "거너")]
적들_인파이터 = ["타우 아미", "루가루", "고블린"]
_인파이터_순서 = (
    ("원!투!", "바디블로", "사이드 너클", "할로우 백"),  # 텐션 모으기
    ("헤븐리 컴비네이션", "바디블로", "원!투!", "사이드 너클", "할로우 백"),
)


def _개방(p):
    return any(b["이름"] == "텐션 개방" for b in p["버프"])


def _가장_강한_순위(p):
    원본 = p.get("원본") or {}
    등급 = (
        0
        if 원본.get("칭호") == "보스"
        else {"네임드": 1, "엘리트": 2}.get(원본.get("적등급"), 3)
    )
    return (등급, p["현재HP"])


def _칠_적(상태):
    후보 = [
        e for e in gf.적_목록(상태) if e["생존"] and not gf.지정불가_상태인가(상태, e)
    ]
    return min(후보, key=lambda e: e["현재HP"]) if 후보 else None


def _인파이터_차례(상태, p, 기록, 순서):
    재료 = 상태["소지품"]["재료"]
    for _ in range(10):
        if gf.전투_종료됨(상태) or not p["생존"]:
            return
        대상 = _칠_적(상태)
        if 대상 is None:
            return
        if _개방(p) and gf.스킬_사용_가능여부(상태, p, "기간틱 캐넌")[0]:
            전 = (p["현재MP"], 재료.get("무색 큐브 조각", 0), p["행동자원"]["일반행동"])
            gf.아군_스킬사용(상태, "기간틱 캐넌", 중심대상=대상)
            assert (p["현재MP"], 재료.get("무색 큐브 조각", 0)) == (전[0], 전[1] - 5)
            assert p["행동자원"]["일반행동"] == 전[2] and not _개방(p)
            기록["기간틱 캐넌(텐션행동)"] = 기록.get("기간틱 캐넌(텐션행동)", 0) + 1
            continue
        이름 = next(
            (
                n
                for n in 순서
                if n in p["원본"]["보유스킬"] and gf.스킬_사용_가능여부(상태, p, n)[0]
            ),
            None,
        )
        if 이름 is None:
            break
        순위전 = {
            e["이름"]: _가장_강한_순위(e)
            for e in gf.적_목록(상태)
            if e["생존"] and not gf.지정불가_상태인가(상태, e)
        }
        if (
            이름 == "바디블로"
        ):  # 추적이 대상을 바꾸는지 보려고 HP가 가장 많은 적을 고른다
            대상 = max(
                (e for e in gf.적_목록(상태) if e["이름"] in 순위전),
                key=lambda e: e["현재HP"],
            )
        개방전 = _개방(p)
        결과 = gf.아군_스킬사용(상태, 이름, 중심대상=대상)
        기록[이름] = 기록.get(이름, 0) + 1
        if 이름 == "바디블로":  # 추적 - 고른 대상이 아니라 쓰기 전 가장 강한 적
            assert 순위전[결과["타격"][0]["대상"]] == min(순위전.values())
            if 결과["타격"][0]["대상"] != 대상["이름"]:
                기록["바디블로(고른 적 대신)"] = (
                    기록.get("바디블로(고른 적 대신)", 0) + 1
                )
        if 이름 == "헤븐리 컴비네이션":
            assert all(f"{n}단계" in 결과 for n in (1, 2, 3))
        if _개방(p) and not 개방전:
            기록["텐션 개방"] = 기록.get("텐션 개방", 0) + 1
    while not gf.전투_종료됨(상태) and p["생존"] and gf.일반공격_가능여부(상태, p):
        대상 = _칠_적(상태)
        if 대상 is None:
            break
        gf.아군_일반공격(상태, 대상)


def _전투_인파이터13(상태, 인, 기록, 순서):
    support.반응_처리(상태)
    for e in gf.적_목록(상태):
        e["현재HP"] = e["최대HP"] = e["현재HP"] * 3  # 시험 전투 도우미들과 같은 방법
    for _ in range(600):
        if gf.전투_종료됨(상태):
            break
        참가자 = gf.현재_턴_참가자(상태)
        if 참가자["진영"] == "아군" and 참가자["생존"] and 참가자["원본"] is 인:
            _인파이터_차례(상태, 참가자, 기록, 순서)
            if not gf.전투_종료됨(상태):
                gf.턴_넘기기(상태)
        elif 참가자["진영"] == "아군" and 참가자["생존"]:
            scenario.스킬_우선_턴(상태, [])
        else:
            gf.턴_넘기기(상태)
    else:
        raise AssertionError("전투가 끝나지 않았다")
    기록["종료"] = 상태["전투상태"]["종료"]
    기록["라운드"] = 상태["전투상태"]["라운드"]
    return 기록["종료"]


@pytest.mark.scenario("S8")
def test_S8_인파이터_레벨13_실전(golden):
    scenario.시드(시드_인파이터13)
    상태 = support.새게임(파티구성_인파이터)
    인, *나머지 = 상태["파티"]["파티원"]
    scenario.성장(상태, 인, 13, 전직="인파이터", 스킬습득=True)
    for c in 나머지:
        scenario.성장(상태, c, 13, 전직=구현된_전직[c["직업"]], 스킬습득=True)
    assert {"사이드 너클", "할로우 백", "헤븐리 컴비네이션", "기간틱 캐넌"} <= set(
        인["보유스킬"]
    )
    볼것 = (
        "텐션 개방",
        "기간틱 캐넌(텐션행동)",
        "헤븐리 컴비네이션",
        "바디블로(고른 적 대신)",
    )
    전투들 = []
    for n in range(10):
        상태["소지품"]["재료"]["무색 큐브 조각"] = 20
        gf.파티_최대치로_회복(상태)
        gf.전투_시작(상태, 적들_인파이터, 레벨=15, 차수=3)
        기록 = {}
        종료 = _전투_인파이터13(상태, 인, 기록, _인파이터_순서[n % 2])
        assert gf.전투_결과_정리(상태) == 종료 == "아군승리"
        전투들.append(기록)
        if all(sum(b.get(k, 0) for b in 전투들) for k in 볼것):
            break
    합계 = {k: sum(b.get(k, 0) for b in 전투들) for k in 볼것}
    assert all(합계.values()), 전투들
    golden("scenario_S8_infighter_lv13", 전투들)
