"""S50 쇼타임 행동 지불 수단 선택 실전 (docs/scenarios.md, #74 - 이슈의 "메모라이즈 지불 수단 선택").

주점에서 영입한 마법사를 레벨 9 엘리멘탈마스터로 키워(레벨 8 -> 9 퍽 쇼타임, 스킬 전부 습득) 프리스트 대신 파티에 넣고
로리엔 보스를 **실전으로** 싸운다. 마법사의 첫 차례에 쇼타임(보조행동, MP 10)을 걸면 그 차례에는 지불 수단이
일반행동뿐이고, 다음 차례 시작에 쇼타임행동 1이 생겨 하급마법의 지불 수단이 둘이 된다(화면은 행동 선택 팝업을
띄운다 - `스킬_행동선택지`). 팝업에서 기본 순서가 아닌 일반행동을 고르면 일반행동만 줄고, 남은 쇼타임행동으로
하급마법을 한 번 더 쓴다(한 차례에 마법 둘). 둘째 차례에 쇼타임을 다시 걸면, 셋째 차례에는 고르지 않고 쓸 때
기본 순서대로 쇼타임행동이 먼저 나간다. 나머지 아군은 [자동전투]다. 보스까지 가는 길의 인카운트도 같은
방식으로 싸우고(대개 둘째 차례 전에 끝난다), 골든과 차례 셋 이상 검사는 보스전 것이다.
메모라이즈는 2026-10-22에 지능 +1·마법 데미지보너스로 바뀌어 지불 수단 선택이 없다 - 선택 팝업이 실제로 뜨는
곳은 쇼타임(과 소환사 교감)이라 쇼타임으로 본다. 규칙 값은 test_combat_rules.py의 지불 수단 테스트가 본다.
"""

import pytest

from game.system import rng
import gameflow as gf
import support

시드 = 1
_로리엔 = "dungeon_01A_D01_Lorien"
_하급마법 = "랜턴파이어"


def _쇼타임_퍽(캐릭터, 후보):
    return next(((n, d) for n, d in 후보 if n == "쇼타임"), 후보[0])


def _살아있는_적(상태):
    return next(
        p for p in 상태["전투상태"]["참가자"] if p["진영"] == "적" and p["생존"]
    )


def _쇼타임(참가자):
    return (참가자.get("기타행동") or {}).get("쇼타임행동", 0)


@pytest.mark.scenario("S50")
def test_S50_쇼타임_지불_수단_선택_실전(golden):
    rng.시드(시드)
    상태 = support.새게임()
    파티 = 상태["파티"]["파티원"]
    상태["소지품"]["골드"] += gf.영입_비용
    마법사, _ = gf.파티원_영입(상태, "", "마법사")
    support.성장(
        상태, 마법사, 9, 전직="엘리멘탈마스터", 퍽고르기=_쇼타임_퍽, 스킬습득=True
    )
    assert "쇼타임" in 마법사["보유스킬"] and _하급마법 in 마법사["보유스킬"]
    gf.파티원_대기(상태, next(c for c in 파티 if c["직업"] == "프리스트"))
    gf.파티원_합류(상태, 마법사)
    gf.휴식(상태)
    전투들 = []  # 전투마다 마법사 차례 기록 - 가는 길 인카운트도 같은 방식으로 싸운다

    def _마법사_차례(상태, 참가자):
        """마법사 차례 하나를 직접 조종한다. 끝까지 썼으면 True(턴을 넘긴다)."""
        차례들 = 전투들[-1]
        번호 = len(차례들) + 1
        선택지 = gf.스킬_행동선택지(상태, 참가자, _하급마법)
        차례 = {"번호": 번호, "쇼타임행동": _쇼타임(참가자), "선택지": 선택지}
        차례들.append(차례)
        if 번호 == 1:
            assert 선택지 == ["일반행동"] and _쇼타임(참가자) == 0
            gf.아군_스킬사용(상태, "쇼타임")
            # 버프는 걸렸지만 쇼타임행동은 다음 차례 시작에 생긴다
            assert gf.스킬_행동선택지(상태, 참가자, _하급마법) == ["일반행동"]
            return False
        if 번호 == 2:
            assert 선택지 == ["쇼타임행동", "일반행동"], 선택지
            gf.아군_스킬사용(
                상태, _하급마법, 중심대상=_살아있는_적(상태), 행동지불="일반행동"
            )
            assert 참가자["행동자원"]["일반행동"] == 0 and _쇼타임(참가자) == 1
            차례["일반행동으로"] = True
            if gf.전투_종료됨(상태):
                return True
            assert gf.스킬_행동선택지(상태, 참가자, _하급마법) == ["쇼타임행동"]
            assert gf.스킬_사용_가능여부(상태, 참가자, _하급마법)[0]
            gf.아군_스킬사용(
                상태, _하급마법, 중심대상=_살아있는_적(상태), 행동지불="쇼타임행동"
            )
            assert _쇼타임(참가자) == 0
            assert gf.스킬_행동선택지(상태, 참가자, _하급마법) == []
            차례["쇼타임행동으로"] = True
            if not gf.전투_종료됨(상태):
                gf.아군_스킬사용(상태, "쇼타임")  # 보조행동은 남아 있다
            return True
        if 번호 == 3:
            assert 선택지 == ["쇼타임행동", "일반행동"], 선택지
            gf.아군_스킬사용(상태, _하급마법, 중심대상=_살아있는_적(상태))
            # 고르지 않으면 기본 순서 - 쇼타임행동이 먼저
            assert _쇼타임(참가자) == 0 and 참가자["행동자원"]["일반행동"] == 1
            차례["기본순서"] = "쇼타임행동"
        return False

    def _전투(상태):
        support.반응_처리(상태)
        전투들.append([])
        for _ in range(300):
            if gf.전투_종료됨(상태):
                return 상태["전투상태"]["종료"]
            if not gf.아군_차례인가(상태):
                gf.턴_넘기기(상태)
                continue
            참가자 = gf.현재_턴_참가자(상태)
            if 참가자["원본"] is 마법사:
                if _마법사_차례(상태, 참가자):
                    if not gf.전투_종료됨(상태):
                        gf.턴_넘기기(상태)
                    continue
            gf.자동전투_한_턴(상태)
        raise AssertionError("전투가 끝나지 않았다")

    gf.던전_진입(상태, _로리엔)
    결과, _ = support.보스_처치(상태, 전투처리=_전투)
    assert 결과 == "아군승리"
    차례들 = 전투들[-1]  # 보스전
    assert len(차례들) >= 3, 차례들
    assert 차례들[1].get("쇼타임행동으로") and 차례들[2].get("기본순서")
    golden("scenario_S50_showtime_payment", 차례들)
