def _진행도(**추가):
    진행도 = {
        "플레이어레벨": 1,
        "클리어한오브젝트": set(),
        **achievement_system.빈_진행기록(),
    }
    진행도.update(추가)
    return 진행도


def test_조건_종류마다_진행값을_진행도에서_읽는다():
    진행도 = _진행도(플레이어레벨=3)
    assert achievement_system.진행값(진행도, _업적("레벨_3")) == (3, 3)
    assert achievement_system.달성(진행도, _업적("레벨_3"))
    assert not achievement_system.달성(진행도, _업적("레벨_4"))

    진행도["도감"]["몬스터"] = ["고블린", "고블린 투척병"]
    assert achievement_system.진행값(진행도, _업적("몬스터도감_3")) == (2, 3)
    진행도["도감"]["몬스터"].append("타우 아미")
    assert achievement_system.달성(진행도, _업적("몬스터도감_3"))

    진행도["업적기록"]["일반전투승리"] = 4
    진행도["업적기록"]["보스전투승리"] = 2
    assert not achievement_system.달성(진행도, _업적("일반전투_5"))
    assert achievement_system.달성(진행도, _업적("보스전투_2"))

    assert achievement_system.진행값(진행도, _업적("세리아_구출")) == (0, 1)
    진행도["클리어한오브젝트"].add(("dungeon_01A_D01_Lorien", (15, 3)))
    assert achievement_system.진행값(진행도, _업적("세리아_구출")) == (1, 1)


def test_진행값은_목표를_넘지_않게_보여준다():
    진행도 = _진행도(플레이어레벨=7)
