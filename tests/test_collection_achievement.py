def test_상점에서_산_포션과_장비는_도감에_등록된다():
    상태 = support.새게임([("", "귀검사")])
    상태["소지품"]["골드"] = 10**6
    gf.상점_구매(상태, "소모품", "포션", "초보자용 HP 포션", 1)
    gf.상점_구매(상태, "장비", "상의", "찢어진 천갑 상의", 1)
    gf.상점_구매(상태, "소모품", "항아리", "만진의 항아리", 1)
    assert "초보자용 HP 포션" in 상태["진행도"]["도감"]["소모품"]
    assert "찢어진 천갑 상의" in 상태["진행도"]["도감"]["장비"]
    gf.항아리_열기(상태, "만진의 항아리")
    장비 = [
        n for n in 상태["소지품"]["장비"] if n not in ("녹슨 소검", "허름한 경갑 상의")
    ]
    assert set(장비) <= set(상태["진행도"]["도감"]["장비"])


