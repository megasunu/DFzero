def test_장비_아이템_보상과_후보가_없는_랜덤장비():
    상태 = support.새게임([("", "귀검사")])
    카탈로그 = 상태["상점카탈로그"]
    플레이어 = gf.플레이어뷰(상태)
    진행도 = 상태["진행도"]
    업적 = {
        "ID": "시험",
        "조건": {"종류": "플레이어레벨", "목표": 1},
        "보상": {"골드": 5, "아이템": [("강철 소검", 1), ("초보자용 HP 포션", 2)]},
    }
    받음 = achievement_system.보상_받기(진행도, 플레이어, 업적, 카탈로그)
    assert 받음 == {
        "골드": 5,
        "아이템": [("강철 소검", 1), ("초보자용 HP 포션", 2)],
    }
    assert 상태["소지품"]["장비"]["강철 소검"] == 1
    assert 상태["소지품"]["포션"]["초보자용 HP 포션"] == 2
    assert "강철 소검" in 진행도["도감"]["장비"]
    assert gf.업적_보상_문구(받음) == "5G, 강철 소검, 초보자용 HP 포션 x2"

    # 없는 아이템이나 후보가 없는 랜덤장비는 받음으로 적지 않는다(보상이 조용히 사라지지 않게)
    for 보상 in (
        {"아이템": [("없는 아이템", 1)]},
        {"랜덤장비": {"부위": "무기", "레어도": "에픽"}},
    ):
        업적 = {**업적, "ID": "시험2", "보상": 보상}
        with pytest.raises(ValueError):
            achievement_system.보상_받기(진행도, 플레이어, 업적, 카탈로그)
        assert "시험2" not in 진행도["받은업적"]


