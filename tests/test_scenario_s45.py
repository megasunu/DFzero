"""S45 - 공어 연속전투와 공왕 크로쿠타(2026-11-03 사용자 결정, #490) 실전.

측정 조건 레벨 8 파티가 미들오션 천해에서 공어·대공어와 실전으로 싸워 이기고, 연속전투로 이어진 공왕 크로쿠타
(보스 칭호) + 대공어 2 + 공어 2와도 실전으로 싸운다. 두 전투를 모두 이기면 보상 두 번을 차례로 받고,
업적 "공왕 크로쿠타 처치"에서 크로쿠타의 가시를 받는다. 연속전투 판정만 확률 1로 고정한다(마리당 1%라
실전 굴림으로는 거의 나오지 않는다)."""

import pytest

from game.data.achievement.achievement_list import 업적_목록
from game.system import achievement_system, rng
import gameflow as gf
import scenario
import support

시드 = 1  # 레벨 8 파티가 두 전투를 모두 이기는 시드(6 -> 0 #476 몬스터 행동불가, 0 -> 1 공중에뜸 차례끝 감소, 둘 다 2026-11-05)
_천해 = "dungeon_02A_D15_middleocean_shallow"


@pytest.mark.scenario("S45")
def test_S45_공어_연속전투_크로쿠타_실전():
    rng.시드(시드)
    상태 = support.새게임()
    scenario.측정_파티_준비(상태, 8)
    gf.휴식(상태)
    gf.던전_진입(상태, _천해)
    맵 = 상태["던전상태"]["맵정보"]
    상태["던전상태"]["맵정보"] = {
        **맵,
        "연속전투": {**맵["연속전투"], "마리당확률": 1.0},
    }
    인카운트 = 맵["인카운트"]
    gf.전투_시작(상태, ["공어", "대공어"], 레벨=인카운트["레벨"], 차수=인카운트["차수"])
    assert scenario.측정_실전(상태) == "아군승리"
    가방 = 상태["소지품"]["골드"]
    assert gf.전투_결과_정리(상태) == "연속전투"
    assert 상태["소지품"]["골드"] == 가방 and not gf.전투_보상_대기중(상태)

    gf.연속전투_시작(상태)
    적 = gf.적_목록(상태)
    왕 = next(p for p in 적 if p["원본"]["몬스터명"] == "공왕 크로쿠타")
    assert 왕["원본"]["칭호"] == "보스" and len(적) == 5
    종료 = scenario.측정_실전(상태)
    로그 = 상태["전투상태"]["로그"]
    assert 종료 == "아군승리", 종료
    # 크로쿠타의 패턴이 실제로 나왔다(깨물기/만독 불 침/왕의 식사/공충노도 중 하나 이상)
    assert {
        x.get("패턴")
        for x in 로그
        if x.get("종류") == "타격" and x.get("공격자") == 왕["이름"]
    } & {"깨물기", "만독 불 침", "왕의 식사", "공충노도"}
    assert gf.전투_결과_정리(상태) == "아군승리"
    assert 상태["소지품"]["골드"] > 가방
    for _ in range(2):  # 첫 전투 보상, 크로쿠타 전투 보상
        assert gf.전투_보상_대기중(상태)
        scenario.보상_수령(상태)
    assert not gf.전투_보상_대기중(상태)

    업적 = next(u for u in 업적_목록 if u["ID"] == "공왕_크로쿠타_처치")
    assert achievement_system.받을_수_있음(상태["진행도"], 업적)
    전 = 상태["소지품"]["장비"].get("크로쿠타의 가시", 0)
    achievement_system.보상_받기(
        상태["진행도"], gf.플레이어뷰(상태), 업적, 상태["상점카탈로그"]
    )
    assert 상태["소지품"]["장비"]["크로쿠타의 가시"] == 전 + 1
