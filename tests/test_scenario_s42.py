"""S42 레어 무기 실전 (docs/scenarios.md, #437).

귀검사·거너·프리스트 둘 파티에 1레벨에 들 수 있는 일반 레어 무기를 쥐여 준다 - 귀검사 복수의 영혼도(명중 시 저주),
거너 마우저 C96(명중 시 50% 축복), 프리스트 둘 다 배틀마스터(오라 데미지보너스 +1). 로리엔과 로리엔 안쪽에서
인카운트를 **실전으로**([자동전투]) 치른다. 매 차례 살아 있는 아군 전원이 오라를 하나만 받는지(배틀마스터가 둘이어도 +1),
축복이 같은 무기에서 겹치지 않는지 보고, 스위트 민트 특별 드랍이 몇 전투를 치러도 한 번만 나오는지 본다.
"""

import pytest

from game.system import rng
from game.system.combat import stats
import gameflow as gf
import scenario
import support

시드 = 0
전투수 = 8
_파티 = [("", "귀검사"), ("", "거너"), ("", "프리스트"), ("", "프리스트")]
_무기 = {"귀검사": "복수의 영혼도", "거너": "마우저 C96", "프리스트": "배틀마스터"}
_오라 = {"데미지보너스": 1, "속도": 0}


def _차례_검사(상태, 기록):
    전투상태 = 상태["전투상태"]
    for a in gf.아군_목록(상태):
        if not a["생존"]:
            continue
        for 변동대상, 값 in _오라.items():
            assert stats.오라_수치(전투상태, a, 변동대상) == 값, (a["이름"], 변동대상)
        축복 = [b.get("기원") for b in a["버프"] if b["이름"] == "축복"]
        assert len(축복) == len(set(축복)), (
            a["이름"],
            축복,
        )  # 같은 기원은 겹치지 않는다


def _로그_세기(상태, 기록):
    """전투 로그의 비고에서 마우저 C96이 건 축복을 센다(쓰러뜨린 공격으로 전투가 끝나도 남는다).
    복수의 영혼도의 저주는 쓰러뜨린 공격에는 안 걸려 시드에 따라 안 나온다 - 단위 테스트가 지킨다."""
    for 항목 in 상태["전투상태"]["로그"]:
        비고 = str(항목.get("비고", ""))
        기록["축복"] += "'마우저 C96' - '축복' 버프 획득" in 비고


def _전투(상태, 기록):
    support.반응_처리(상태)
    for _ in range(300):
        if gf.전투_종료됨(상태):
            return 상태["전투상태"]["종료"]
        _차례_검사(상태, 기록)
        if gf.아군_차례인가(상태):
            gf.자동전투_한_턴(상태)
        else:
            gf.턴_넘기기(상태)
    raise AssertionError("전투가 끝나지 않았다")


@pytest.mark.scenario("S42")
def test_S42_레어_무기_실전():
    rng.시드(시드)
    상태 = support.새게임(_파티)
    for c in 상태["파티"]["파티원"]:
        이름 = _무기[c["직업"]]
        상태["소지품"]["장비"][이름] = 상태["소지품"]["장비"].get(이름, 0) + 1
        gf.장비_교체(상태, c, "무기", 이름)
        assert c["장착장비"]["무기"] == 이름
    기록 = {"축복": 0, "결과": [], "민트": 0}
    for 번호 in range(전투수):
        if 번호 % 4 == 0:  # 로리엔 -> 로리엔 안쪽을 번갈아
            gf.파티_최대치로_회복(상태)
            gf.던전_진입(상태, support.던전파일명(1 + 번호 // 4 % 2))
        scenario.인카운트까지_걷기(상태)
        결과 = _전투(상태, 기록)
        _로그_세기(상태, 기록)
        기록["결과"].append(결과)
        gf.전투_결과_정리(상태)
        if 결과 != "아군승리":
            break
        기록["민트"] += dict(상태["전투_전리품"]["아이템"]).get("스위트 민트", 0)
        if gf.전투_보상_대기중(상태):
            scenario.보상_수령(상태)
    assert 기록["결과"].count("아군승리") >= 4, 기록["결과"]
    assert 기록["축복"] > 0  # 마우저 C96이 한 번은 축복을 걸었다
    assert 기록["민트"] <= 1
    assert 상태["소지품"]["장비"].get("스위트 민트", 0) == 기록["민트"]
