def _봉절_파티():
    상태, 술사 = _파티(퍽보유=False)
    술사["보유스킬"].append("봉절")
    술사["현재MP"] = 20
    gf.던전_진입(상태, 로리엔)
    return 상태, 술사


def _왕복(상태):
    """지금 칸과 걸을 수 있는 이웃 칸 사이를 오가는 방향 두 개(가기, 돌아오기)."""
    from game.system import dungeon_system

    x, y = 상태["던전상태"]["위치"]
    for 가기, 돌아오기, (dx, dy) in (
        ("오른쪽", "왼쪽", (1, 0)),
        ("왼쪽", "오른쪽", (-1, 0)),
        ("아래", "위", (0, 1)),
        ("위", "아래", (0, -1)),
    ):
        if dungeon_system.칸_문자(상태["던전상태"]["그리드"], (x + dx, y + dy)) == "O":
            return 가기, 돌아오기
    raise AssertionError("걸을 수 있는 이웃 칸이 없다")


def _걷기(상태, 걸음):
    가기, 돌아오기 = _왕복(상태)
    결과들 = []
    for i in range(걸음):
        결과 = gf.던전_이동(상태, 가기 if i % 2 == 0 else 돌아오기)
        assert 결과["결과"] == "이동", 결과
        결과들.append(결과)
    return 결과들


def test_봉절은_1차수_선행없는_던전스킬_획득이다():
    퍽 = 퍽목록["봉절"]
    assert (퍽["분류"], 퍽["타입"], 퍽["차수"], 퍽["선행조건"]) == (
        "퍽",
        ["스킬획득"],
        1,
        None,
    )
    assert 퍽["획득스킬"] == "봉절"
    스킬 = 공용스킬["봉절"]
    assert (스킬["분류"], 스킬["습득퍽"], 스킬["MP소모"]) == ("던전스킬", "봉절", 5)


def test_봉절은_MP_5로_10더하기_레벨_걸음_동안_적도_걸음수도_없다(monkeypatch):
    from game.system import dungeon_system

    상태, 술사 = _봉절_파티()
    술사["레벨"] = 3
    결과 = gf.던전스킬_사용(상태, 술사, "봉절")
    assert 결과["성공"], 결과
    assert 술사["현재MP"] == 15
    assert 상태["던전상태"]["봉절걸음"] == 13
    monkeypatch.setattr(
        dungeon_system, "인카운트_판정", lambda *_: {"등장몬스터": ["고블린"]}
    )
    결과들 = _걷기(상태, 13)
    assert all(r.get("인카운트") is None for r in 결과들)
    assert 상태["던전상태"]["걸음수"] == 0
    assert 상태["던전상태"]["봉절걸음"] == 0
    assert [r.get("봉절해제") for r in 결과들] == [None] * 12 + [True]
    # 풀리면 다시 걸음수가 오르고 적이 나온다
    가기, _ = _왕복(상태)
    assert gf.던전_이동(상태, 가기)["결과"] == "전투시작"


def test_봉절이_남아_있을_때_다시_쓰면_MP_없이_풀린다():
    상태, 술사 = _봉절_파티()
    gf.던전스킬_사용(상태, 술사, "봉절")
    줄 = next(줄 for 줄 in gf.던전스킬_목록(상태) if 줄["스킬"] == "봉절")
    assert 줄["가능"] and 줄["해제"]
    술사["현재MP"] = 0  # MP가 없어도 풀 수 있다
    결과 = gf.던전스킬_사용(상태, 술사, "봉절")
    assert 결과["성공"] and "풀" in 결과["문구"], 결과
    assert 술사["현재MP"] == 0 and 상태["던전상태"]["봉절걸음"] == 0
    줄 = next(줄 for 줄 in gf.던전스킬_목록(상태) if 줄["스킬"] == "봉절")
    assert not 줄["가능"] and not 줄["해제"] and "MP" in 줄["사유"]


def test_봉절은_던전을_나가면_끝난다():
    상태, 술사 = _봉절_파티()
    gf.던전스킬_사용(상태, 술사, "봉절")
    gf.던전_진입(
        상태, 로리엔
    )  # 다시 들어오면(마을을 거쳐도, 이어진 던전도) 새 던전상태
    assert 상태["던전상태"]["봉절걸음"] == 0


def test_봉절은_던전_안_저장_불러오기에서_남는다(임시_세이브폴더):
    상태, 술사 = _봉절_파티()
    gf.던전스킬_사용(상태, 술사, "봉절")
    _걷기(상태, 2)
    남은 = 상태["던전상태"]["봉절걸음"]
    gf.게임_저장(상태, 1)
    불러옴 = gf.게임_불러오기(1)
    assert 불러옴["던전상태"]["봉절걸음"] == 남은 > 0
