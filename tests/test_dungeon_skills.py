# 던전 화면 스킬("분류":"던전스킬") - 던전에서 전투 밖에 쓰는 스킬. 유루캠 퍽의 "던전 캠핑"
# (2026-10-19 사용자 결정). 규칙은 docs/game-rules.md "던전 화면 스킬".

import random

import gameflow as gf
from game.data.job_skill.job_skill_0000 import 스킬목록 as 공용스킬
from game.data.perks.perks_class_0000 import 퍽목록
from tests import support

로리엔 = "dungeon_01A_D01_Lorien"


def _파티(퍽보유=True):
    random.seed(0)
    상태 = support.새게임()
    캠퍼 = 상태["파티"]["파티원"][0]
    if 퍽보유:
        캠퍼["보유스킬"].append("던전 캠핑")
    return 상태, 캠퍼


def _던전_캠핑_줄(상태):
    return next(
        (줄 for 줄 in gf.던전스킬_목록(상태) if 줄["스킬"] == "던전 캠핑"), None
    )


def test_유루캠은_1차수_선행없는_던전_캠핑_스킬획득이다():
    퍽 = 퍽목록["유루캠"]
    assert (퍽["분류"], 퍽["차수"], 퍽["선행조건"]) == ("스킬획득", 1, None)
    assert 퍽["획득스킬"] == "던전 캠핑"
    스킬 = 공용스킬["던전 캠핑"]
    assert (스킬["분류"], 스킬["습득방법"], 스킬["습득퍽"]) == (
        "던전스킬",
        "퍽습득",
        "유루캠",
    )
    assert 스킬["휴식당횟수"] == 1 and 스킬["MP소모"] == 0
    assert "유루유리" not in 퍽목록


def test_유루캠_퍽을_고르면_던전_캠핑을_배운다():
    상태, 캠퍼 = _파티(퍽보유=False)
    캠퍼["레벨"] = 3
    상태["진행도"]["플레이어레벨"] = 4
    후보 = dict(gf.선택가능_퍽목록(캠퍼))
    assert "유루캠" in 후보
    gf.캐릭터_레벨업_적용(캠퍼, **support.퍽_선택값(캠퍼, "유루캠", 후보["유루캠"]))
    assert "던전 캠핑" in 캠퍼["보유스킬"]


def test_던전_캠핑은_파티원_전체_HP를_최대치로_채우고_쓰러진_파티원도_일으킨다():
    상태, 캠퍼 = _파티()
    gf.던전_진입(상태, 로리엔)
    파티 = 상태["파티"]["파티원"]
    파티[1]["현재HP"] = 0  # 쓰러짐
    파티[2]["현재HP"] = 1
    for c in 파티:
        c["현재MP"] = 0
    파티[3]["상태이상"] = [{"이름": "취기", "중첩": 1}]
    줄 = _던전_캠핑_줄(상태)
    assert 줄["가능"] and 줄["남은"] == (1, 1)

    결과 = gf.던전스킬_사용(상태, 캠퍼, "던전 캠핑")
    assert 결과["성공"], 결과
    for c in 파티:
        assert c["현재HP"] == gf.캐릭터_최대HP(상태, c)
        assert c["현재MP"] == 0  # HP만 채운다
    assert 파티[3]["상태이상"] == [{"이름": "취기", "중첩": 1}]


def test_던전_캠핑은_마을에서_휴식할_때까지_한_번뿐():
    상태, 캠퍼 = _파티()
    gf.던전_진입(상태, 로리엔)
    assert gf.던전스킬_사용(상태, 캠퍼, "던전 캠핑")["성공"]
    줄 = _던전_캠핑_줄(상태)
    assert not 줄["가능"] and 줄["남은"] == (0, 1) and "휴식" in 줄["사유"]
    assert not gf.던전스킬_사용(상태, 캠퍼, "던전 캠핑")["성공"]

    gf.휴식(상태)
    gf.던전_진입(상태, 로리엔)
    assert _던전_캠핑_줄(상태)["가능"]


def test_던전_캠핑은_던전에서만_쓴다():
    상태, 캠퍼 = _파티()
    assert 상태.get("던전상태") is None  # 마을
    assert gf.던전스킬_목록(상태) == []
    assert not gf.던전스킬_사용(상태, 캠퍼, "던전 캠핑")["성공"]


def test_던전_캠핑은_전투에서_쓸_수_없다():
    상태, 캠퍼 = _파티()
    gf.던전_진입(상태, 로리엔)
    gf.전투_시작(상태, ["고블린"], 레벨=1, 차수=1)
    support.반응_처리(상태)
    assert gf.던전스킬_목록(상태) == []
    참가자 = next(p for p in 상태["전투상태"]["참가자"] if p.get("원본") is 캠퍼)
    가능, 사유 = gf.스킬_사용_가능여부(상태, 참가자, "던전 캠핑")
    assert not 가능 and "던전" in 사유


def test_쓰러진_캐릭터는_던전_캠핑을_쓸_수_없다():
    상태, 캠퍼 = _파티()
    gf.던전_진입(상태, 로리엔)
    캠퍼["현재HP"] = 0
    줄 = _던전_캠핑_줄(상태)
    assert not 줄["가능"] and "쓰러" in 줄["사유"]
    assert not gf.던전스킬_사용(상태, 캠퍼, "던전 캠핑")["성공"]


def test_던전스킬이_없으면_목록이_비어_있다():
    상태, _ = _파티(퍽보유=False)
    gf.던전_진입(상태, 로리엔)
    assert gf.던전스킬_목록(상태) == []
