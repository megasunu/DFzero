def test_음식은_최대치의_50퍼센트를_올림으로_회복하고_소지품에서_빠진다():
    상태 = 새게임([("", "마법사")])
    마법사 = 상태["파티"]["파티원"][0]
    상태["소지품"]["소모품"] = {"칸나의 수제빵": 1, "칸나의 푸딩": 1}
    with pytest.raises(ValueError, match="가득"):
        gf.캐릭터_음식사용(상태, 마법사, "칸나의 수제빵")
    최대HP = gf.캐릭터_최대HP(상태, 마법사)
    최대MP = gf.캐릭터_최대MP(상태, 마법사)
    마법사["현재HP"] = 1
    회복 = gf.캐릭터_음식사용(상태, 마법사, "칸나의 수제빵")
    assert 회복 == {"HP": min(최대HP - 1, -(-최대HP // 2))}
    assert 마법사["현재HP"] == 1 + 회복["HP"]
    assert "칸나의 수제빵" not in 상태["소지품"]["소모품"]
    마법사["현재HP"], 마법사["현재MP"] = 최대HP, 0
    회복 = gf.캐릭터_음식사용(상태, 마법사, "칸나의 푸딩")
    assert 회복 == {"HP": 0, "MP": -(-최대MP // 2)}
    마법사["현재HP"] = 0
    상태["소지품"]["소모품"]["칸나의 우유"] = 1
    with pytest.raises(ValueError, match="쓰러진"):
        gf.캐릭터_음식사용(상태, 마법사, "칸나의 우유")


