def test_전투_중_포션은_보조행동으로_자신에게만():
    rng.시드(3)
    상태 = 새게임([("", "귀검사")])
    gf.전투_시작(상태, ["고블린"], 레벨=1, 차수=1)
    support.반응_처리(상태)
    while not gf.아군_차례인가(상태):
        gf.턴_넘기기(상태)
    참가자 = gf.현재_턴_참가자(상태)
    참가자["현재HP"] = 1
    상태["소지품"]["포션"] = {"초보자용 HP 포션": 2}
    보조 = 참가자["행동자원"]["보조행동"]
    일반 = 참가자["행동자원"]["일반행동"]

    회복 = gf.아군_포션사용(상태, "초보자용 HP 포션")
    assert 회복 >= 1 and 참가자["현재HP"] == 1 + 회복
    assert 참가자["행동자원"]["보조행동"] == 보조 - 1
    assert 참가자["행동자원"]["일반행동"] == 일반  # 공격/스킬은 그대로
    assert 상태["소지품"]["포션"]["초보자용 HP 포션"] == 1
    assert 상태["전투상태"]["로그"][-1] == {
        "공격자": 참가자["이름"],
        "행동": f"초보자용 HP 포션 사용 - HP {회복} 회복",
        "아이템": "초보자용 HP 포션",
        "결과": f"HP {회복} 회복",
        "종류": "아이템",
    }
    참가자["행동자원"]["보조행동"] = 0
    참가자["현재HP"] = 1
    [(_, _, 사유)] = gf.아군_회복포션_목록(상태)
    assert "보조행동" in 사유
    with pytest.raises(ValueError, match="보조행동"):
        gf.아군_포션사용(상태, "초보자용 HP 포션")


