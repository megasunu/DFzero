def test_전투_밖_포션은_파티원에게_쓰고_소지품에서_빠진다():
    상태 = 새게임([("", "마법사"), ("", "귀검사")])
    마법사, 귀검사 = 상태["파티"]["파티원"]
    상태["소지품"]["포션"] = {"초보자용 HP 포션": 2, "입문자용 HP 포션": 1}
    목록 = gf.캐릭터_회복포션_목록(상태, 귀검사)
    assert [(이름, 개수) for 이름, 개수, _ in 목록] == [
        ("초보자용 HP 포션", 2),
        ("입문자용 HP 포션", 1),
    ]
    assert "가득" in 목록[0][2] and "레벨 6" in 목록[1][2]
    with pytest.raises(ValueError, match="가득"):
        gf.캐릭터_포션사용(상태, 귀검사, "초보자용 HP 포션")

    귀검사["현재HP"] = 1
    대상, 회복 = gf.캐릭터_포션사용(상태, 귀검사, "초보자용 HP 포션")
    최대 = gf.캐릭터_최대HP(상태, 귀검사)
    assert 대상 == "HP" and 1 <= 회복 <= 최대 - 1 and 귀검사["현재HP"] == 1 + 회복
    assert 상태["소지품"]["포션"]["초보자용 HP 포션"] == 1

    마법사["현재MP"] = 0
    상태["소지품"]["포션"]["초보자용 MP 포션"] = 1
    대상, 회복 = gf.캐릭터_포션사용(상태, 마법사, "초보자용 MP 포션")
    assert 대상 == "MP" and 마법사["현재MP"] == 회복 >= 1
    assert "초보자용 MP 포션" not in 상태["소지품"]["포션"]
    with pytest.raises(ValueError, match="회복포션이 아니다"):
        gf.캐릭터_포션사용(상태, 마법사, "샤프아이 포션")


