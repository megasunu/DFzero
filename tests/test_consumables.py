def test_소지품_목록은_탭별_보유_개수와_사용_종류():
    상태 = 새게임([("", "귀검사")])
    상태["소지품"]["소모품"] = {
        "만진의 항아리": 2,
        "칸나의 수제빵": 1,
        "럼주": 1,
        "돌맹이": 3,
    }
    상태["소지품"]["포션"] = {"초보자용 HP 포션": 1, "샤프아이 포션": 1}
    상태["소지품"]["재료"] = {"커먼 소울": 4}

    def 줄(대분류, 탭):
        return [
            (a["이름"], 수, 종류) for a, 수, 종류 in gf.소지품_목록(상태, 대분류, 탭)
        ]

    assert 줄("소모품", "항아리") == [("만진의 항아리", 2, "항아리")]
    assert 줄("소모품", "음식") == [("칸나의 수제빵", 1, "음식")]
    assert 줄("소모품", "주류") == [("럼주", 1, "주류")]
    assert 줄("소모품", "투척 아이템") == [("돌맹이", 3, None)]
    assert 줄("소모품", "포션") == [
        ("초보자용 HP 포션", 1, "회복포션"),
        ("샤프아이 포션", 1, None),
    ]
    assert 줄("재료", "소울") == [("커먼 소울", 4, None)]
    # 장비는 장착 중인 것도 센다(시작 장비)
    무기 = 상태["파티"]["파티원"][0]["장착장비"]["무기"]
    assert (무기, 1, None) in 줄("장비", "무기")
    # 소지품은 상점 탭에 "인형"(상점에서 사고팔지 않음)을 더한다
    assert gf.소지품_탭줄(상태, "소모품") == [gf.상점_탭목록("소모품") + ["인형"]]
    assert "소울" in gf.소지품_탭줄(상태, "재료")[0]
    assert gf.소지품_탭줄(상태, "장비") == gf.상점_탭줄("판매", "장비")


