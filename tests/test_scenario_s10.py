"""S10 속성강화 - 엘리멘탈마스터 엘레멘탈 번 (docs/scenarios.md).

마법사가 든 4인 파티를 레벨 8까지 키운다(5->6 전직: 웨펀마스터/엘리멘탈마스터/레인저/크루세이더, 스킬 전부
습득). 엘리멘탈마스터는 레벨 8에 버프 스킬 '엘레멘탈 번'(속성강화 +1, 10턴)을 얻는다. 선더랜드(D05)에서
인카운트를 **실제 전투로** 치르며 스킬 우선 정책(tests/scenario.py)으로 싸운다 - 정책은 버프 스킬을 공격 스킬보다
먼저 쓰므로 엘리멘탈마스터는 첫 차례에 엘레멘탈 번을 걸고 속성 공격 스킬을 쓴다. 버프가 걸린 동안 엘리멘탈마스터의
속성 최종배율은 화/수/명/암 1.1배, 무속성(일반공격) 1배인지 본다(합연산 규칙, 사용자 결정 2026-10-12). 배율 수치
규칙은 test_combat_rules.py::test_속성_면역_강화_내성이 값으로 검사한다.
"""

import pytest

from game.system import rng
import gameflow as gf
import scenario
import support
from game.system.combat import damage
from tests.support import 구현된_전직

선더랜드 = "dungeon_01A_D05_thunderland"
시드 = 2  # 난수 흐름 분리(2026-10-20) 뒤 시드 0은 이 시나리오의 효과가 안 나온다
파티구성 = [("", "귀검사"), ("", "마법사"), ("", "거너"), ("", "프리스트")]
속성들 = ["화속성", "수속성", "명속성", "암속성"]


def _엘마(상태):
    return next(p for p in 상태["전투상태"]["참가자"] if p["원본"]["직업"] == "마법사")


def _전투(상태, 사용기록):
    """스킬 우선 정책으로 끝까지. 엘리멘탈마스터 차례가 끝날 때마다 엘레멘탈 번이 걸려 있으면
    속성 최종배율을 적어 둔다."""
    support.반응_처리(상태)
    배율 = []
    for _ in range(300):
        if gf.전투_종료됨(상태):
            break
        참가자 = gf.현재_턴_참가자(상태)
        if 참가자["진영"] == "아군" and 참가자["생존"]:
            scenario.스킬_우선_턴(상태, 사용기록)
            엘마 = _엘마(상태)
            if 참가자 is 엘마 and any(b["이름"] == "엘레멘탈 번" for b in 엘마["버프"]):
                적 = next((e for e in gf.적_목록(상태) if e["생존"]), None)
                if 적 is not None:
                    배율.append(
                        {
                            속성: damage.속성_최종배율(상태["전투상태"], 엘마, 적, 속성)
                            for 속성 in 속성들 + ["무속성"]
                        }
                    )
        else:
            gf.턴_넘기기(상태)
    else:
        raise AssertionError("전투가 끝나지 않았다")
    return 상태["전투상태"]["종료"], 배율


@pytest.mark.scenario("S10")
def test_S10_엘레멘탈_번_속성강화_실전(golden):
    rng.시드(시드)
    상태 = support.새게임(파티구성)
    파티 = 상태["파티"]["파티원"]
    for c in 파티:
        support.성장(상태, c, 8, 전직=구현된_전직[c["직업"]], 스킬습득=True)
    gf.파티_최대치로_회복(상태)
    [엘마원본] = [c for c in 파티 if c["직업"] == "마법사"]
    assert gf.캐릭터_직업표시(엘마원본).startswith("엘리멘탈마스터")
    assert "엘레멘탈 번" in 엘마원본["보유스킬"]
    # 정책은 보유스킬 순서대로 쓴다 - 무속성 스킬(매직미사일, 천격)이 일반행동을 먼저 가져가지 않게 속성
    # 스킬을 앞으로(메모라이즈로 하급마법을 보조행동으로 쓰던 길이 2026-10-22에 없어졌다)
    모음 = 상태["스킬데이터모음"]
    엘마원본["보유스킬"].sort(key=lambda n: 모음[n].get("속성") not in 속성들)

    gf.던전_진입(상태, 선더랜드)
    기록 = {"전투": []}
    for _ in range(3):
        if any(
            r["스킬"] == "엘레멘탈 번" for 전투 in 기록["전투"] for r in 전투["스킬"]
        ):
            break
        적 = scenario.인카운트까지_걷기(상태)
        사용기록 = []
        종료, 배율 = _전투(상태, 사용기록)
        assert gf.전투_결과_정리(상태) == 종료 == "아군승리"
        scenario.보상_수령(상태)
        엘마이름 = 엘마원본["캐릭터명"]
        기록["전투"].append(
            {
                "적": 적,
                "스킬": [
                    {"스킬": r["스킬"], "분류": r["분류"]}
                    for r in 사용기록
                    if r["시전자"] == 엘마이름
                ],
                "배율": 배율,
            }
        )

    엘마스킬 = [r for 전투 in 기록["전투"] for r in 전투["스킬"]]
    assert any(r["스킬"] == "엘레멘탈 번" for r in 엘마스킬), 기록
    스킬모음 = 상태["스킬데이터모음"]
    assert any(
        r["분류"] == "공격스킬" and 스킬모음[r["스킬"]].get("속성") in 속성들
        for r in 엘마스킬
    ), 엘마스킬
    배율들 = [b for 전투 in 기록["전투"] for b in 전투["배율"]]
    assert 배율들, "엘레멘탈 번이 걸린 채로 엘리멘탈마스터 차례가 끝난 적이 없다"
    for b in 배율들:
        assert b == {
            "화속성": 1.1,
            "수속성": 1.1,
            "명속성": 1.1,
            "암속성": 1.1,
            "무속성": 1.0,
        }, b
    # 전투가 끝나면 버프는 남지 않는다 - 다음 전투 첫 차례에 다시 건다
    golden("scenario_S10_elemental_burn", 기록)
