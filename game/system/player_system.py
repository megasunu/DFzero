# player_format.py 양식 처리. "레벨"/"소지품"처럼 파티 전체가 공유하는
# 값을 다루고, 파티원 구성 자체는 party_system.py가 담당한다(이 파일은
# 그 결과를 "파티" 키에 담아 들고 있을 뿐).

from game.system import party_system

소지품_카테고리 = ["장비", "소모품", "포션", "재료", "퀘스트아이템"]


def 빈_소지품():
    """골드 0, 나머지 카테고리는 빈 딕셔너리로 시작하는 소지품."""
    return {
        "골드": 0,
        "장비": {},
        "소모품": {},
        "포션": {},
        "재료": {},
        "퀘스트아이템": {},
    }


def 빈_플레이어():
    """파티원이 없는 빈 파티, 레벨 1, 빈 소지품으로 시작하는 플레이어."""
    return {
        "레벨": 1,
        "파티": party_system.빈_파티(),
        "소지품": 빈_소지품(),
    }


def 골드_추가(플레이어, 금액):
    """플레이어 소지품의 골드에 금액을 더한다. 금액이 음수면
    ValueError(골드를 깎는 용도는 아직 없음)."""
    if 금액 < 0:
        raise ValueError("골드_추가()에는 음수를 넣을 수 없다.")
    소지품 = 플레이어.setdefault("소지품", 빈_소지품())
    소지품["골드"] = 소지품.get("골드", 0) + 금액


def 아이템_추가(플레이어, 카테고리, 아이템이름, 개수=1):
    """소지품의 해당 카테고리에 아이템을 개수만큼 더한다. 카테고리가
    소지품_카테고리에 없거나 개수가 1 미만이면 ValueError."""
    if 카테고리 not in 소지품_카테고리:
        raise ValueError(
            f"'{카테고리}'는 소지품 카테고리가 아니다. "
            f"{소지품_카테고리} 중 하나여야 한다."
        )
    if 개수 <= 0:
        raise ValueError("아이템_추가()의 개수는 1 이상이어야 한다.")

    소지품 = 플레이어.setdefault("소지품", 빈_소지품())
    보유칸 = 소지품.setdefault(카테고리, {})
    보유칸[아이템이름] = 보유칸.get(아이템이름, 0) + 개수


def 재료_현황(플레이어, 제작재료):
    """[(재료 이름, 필요 개수, 보유 개수)] - 제작재료({이름: 개수}) 순서대로."""
    보유 = 플레이어.get("소지품", {}).get("재료", {})
    return [(이름, 개수, 보유.get(이름, 0)) for 이름, 개수 in 제작재료.items()]


def 재료로_제작(플레이어, 카테고리, 아이템이름, 제작재료):
    """제작재료({재료 이름: 개수})를 소지품 "재료"에서 빼고 아이템 1개를 카테고리에 더한다(인형사).
    하나라도 모자라면 아무것도 바꾸지 않고 ValueError. 다 쓴 재료는 항목을 지운다."""
    for 이름, 필요, 보유수 in 재료_현황(플레이어, 제작재료):
        if 보유수 < 필요:
            raise ValueError(f"{이름}이 부족합니다({필요}개 필요).")
    재료 = 플레이어["소지품"]["재료"]
    for 이름, 필요 in 제작재료.items():
        재료[이름] -= 필요
        if 재료[이름] <= 0:
            del 재료[이름]
    아이템_추가(플레이어, 카테고리, 아이템이름)
