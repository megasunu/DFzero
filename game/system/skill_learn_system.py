# =====================
# 스킬 습득 시스템
# =====================
# 파티 화면 [스킬습득]으로 골드를 내고 스킬을 배운다. 레벨업으로는 스킬을
# 배우지 않는다("초기습득" 스킬은 캐릭터를 만들 때 자동으로 배우고 - character_creation_system.py -
# "레벨습득" 스킬은 레벨업으로 얻는다. 둘 다 [스킬습득] 목록에 오르지 않는다).
#
# 배울 수 있는 스킬은 지금 직업 계열의 job_skill_XX.py "스킬목록" 중
# "습득방법"이 "구매습득"이고 아직 없는 스킬이다. 1차 계열(예: 귀검사)은
# 차수 1, 1차 전직(예: 웨펀마스터)은 차수 2 - 전직한 캐릭터는 두 목록을
# 다 배울 수 있다. 비용은 50 x 차수 골드. 캐릭터 레벨이 스킬의 "습득레벨"(그 차수의 시작 레벨
# 1+5x(차수-1) - 구매습득_레벨)이 되어야 산다(#365).
#
# 훔쳐배우기(#365): 같은 계열 다른 전직의 목록(훔쳐배우기목록)에서 "타입"에 "훔쳐배우기스킬"이 있는
# 구매습득 스킬도 산다 - 비용은 5배. 어떤 목록을 넘길지(전직 후에만, 특성을 스킬처럼 바꾼 항목)는
# 호출하는 쪽(ctl_skills)이 정한다.
#
# 직업 이름 → 스킬목록 연결은 호출하는 쪽(gameflow)이 찾아 넘긴다.
#
# "분류"가 "특성스킬"인 항목(넨마스터 수플렉스 썬더 #280)은 배우면 보유스킬 대신 "획득특성"을 얻는다
# (이미 그 특성이 있으면 목록에서 빠진다).

from game.system import effect_engine

스킬습득_골드단위 = 50
훔쳐배우기_배수 = 5
훔쳐배우기_태그 = "훔쳐배우기스킬"


def 스킬습득_비용(차수):
    return 스킬습득_골드단위 * 차수


def 구매습득_레벨(차수):
    """차수의 시작 레벨 - 1, 6, 11, 16. 구매습득 스킬의 "습득레벨"이 이 값이다."""
    return 1 + 5 * (차수 - 1)


def _구매스킬들(차수별스킬목록, 훔쳐배우기목록):
    """[(스킬이름, 차수, 비용, 스킬데이터)] - 가졌는지와 레벨은 보지 않는다."""
    for 차수, 스킬목록 in 차수별스킬목록:
        for 이름, 스킬 in 스킬목록.items():
            if 스킬.get("습득방법") == "구매습득":
                yield 이름, 차수, 스킬습득_비용(차수), 스킬
    for 차수, 스킬목록 in 훔쳐배우기목록:
        for 이름, 스킬 in 스킬목록.items():
            if 스킬.get("습득방법") == "구매습득" and 훔쳐배우기_태그 in (
                스킬.get("타입") or []
            ):
                yield 이름, 차수, 스킬습득_비용(차수) * 훔쳐배우기_배수, 스킬


def _가졌나(캐릭터, 이름, 스킬):
    특성 = 스킬.get("획득특성")
    if 특성:
        return 특성 in 캐릭터["보유특성"]
    return 이름 in 캐릭터["보유스킬"]


def 습득가능_스킬목록(캐릭터, 차수별스킬목록, 훔쳐배우기목록=()):
    """[(스킬이름, 차수, 비용, 스킬데이터)] - 데이터 순서(차수 낮은 것부터, 훔쳐배우기는 맨 뒤).

    차수별스킬목록 : [(차수, {스킬이름: 스킬데이터}), ...]
    훔쳐배우기목록 : 같은 모양 - 다른 전직의 목록(태그가 붙은 것만 5배 값으로)"""
    return [
        (이름, 차수, 비용, 스킬)
        for 이름, 차수, 비용, 스킬 in _구매스킬들(차수별스킬목록, 훔쳐배우기목록)
        if not _가졌나(캐릭터, 이름, 스킬) and 캐릭터["레벨"] >= 스킬.get("습득레벨", 1)
    ]


def 배운스킬_골드(캐릭터, 차수별스킬목록, 훔쳐배우기목록=()):
    """[스킬습득]으로 배웠을 스킬의 값 합계 - 레테의 강물이 돌려준다(#351). 산 기록은 따로 없어서, 지금 직업
    계열 목록에서 골드로 살 수 있는 스킬(습득가능_스킬목록의 조건)을 가졌으면 그 값으로 센다. 훔쳐배운 것은
    5배 값이다(#365 - 예전에 퍽으로 얻은 것도 구분할 수 없어 같이 센다). 특성스킬은 그 특성을 가졌으면 센다."""
    return sum(
        비용
        for 이름, _차수, 비용, 스킬 in _구매스킬들(차수별스킬목록, 훔쳐배우기목록)
        if _가졌나(캐릭터, 이름, 스킬)
    )


def 스킬_습득(
    캐릭터, 소지품, 스킬이름, 차수별스킬목록, 특성정의모음=None, 훔쳐배우기목록=()
):
    """골드를 내고 스킬을 배운다. 낸 골드를 반환한다. 배울 수 없는 스킬이거나
    골드가 모자라면 ValueError(캐릭터/소지품은 바뀌지 않는다). "특성스킬"이면 특성정의모음에서
    "획득특성"의 정의를 찾아 특성으로 준다."""
    for 이름, _차수, 비용, _스킬 in 습득가능_스킬목록(
        캐릭터, 차수별스킬목록, 훔쳐배우기목록
    ):
        if 이름 == 스킬이름:
            break
    else:
        raise ValueError(f"'{스킬이름}'은(는) 지금 배울 수 있는 스킬이 아니다.")
    if 소지품.get("골드", 0) < 비용:
        raise ValueError(f"골드가 모자란다({비용}골드 필요).")
    소지품["골드"] -= 비용
    특성 = _스킬.get("획득특성")
    if 특성:
        effect_engine.특성_부여(캐릭터, 특성, (특성정의모음 or {}).get(특성))
        return 비용
    캐릭터["보유스킬"].append(스킬이름)
    전환 = _스킬.get(
        "전환특성"
    )  # 골드로 배우는 전환스킬(나선의 넨 #280)은 켜고 끌 특성도 함께
    if 전환 and 전환 not in 캐릭터["보유특성"]:
        effect_engine.특성_부여(캐릭터, 전환, (특성정의모음 or {}).get(전환))
    return 비용
