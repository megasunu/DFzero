# =====================
# 회복포션 사용 시스템
# =====================
# item_potion.py "회복포션"을 마셔 HP/MP를 회복한다.
#   - 회복량 = "회복값" 수식(예: "(차수)d10+건강보정치")을 굴린 값. 수식의 "차수"는
#     포션의 "티어"다. HP 포션은 건강보정치, MP 포션은 주문시전보정치를 쓰는데,
#     보정치는 호출하는 쪽이 넘긴다(전투 중이면 버프/장비 반영 값).
#   - 굴린 값이 "최소회복값"보다 작으면 그 값으로 올리고, 최대치를 넘는 만큼은 버린다.
#   - 캐릭터 레벨이 "레벨제한" 미만이거나, 쓰러졌거나(HP 0), 이미 가득 찼거나,
#     소지품에 없으면 쓸 수 없다.
# 전투 중에는 보조행동 1개를 쓰고 자기 자신에게만 쓴다(gameflow.아군_포션사용).
# 전투 밖에서는 파티원 아무에게나 쓴다(gameflow.캐릭터_포션사용).
#
# 음식(item_food.py "음식")도 여기서 다룬다 - 전투 밖에서만, 파티원 아무에게나(gameflow.캐릭터_음식사용).
#   - "회복대상"(["HP"], ["HP", "MP"] ...)마다 최대치 x "회복값"(예: "50%")을 1 단위로 올림해 회복한다.
#   - 회복대상/회복값이 "미정"이면 "데이터 없음"(소모하지 않는다).
#   - 쓰러졌거나(HP 0), 회복대상이 모두 가득 찼거나, 소지품에 없으면 먹을 수 없다.

from game.system.combat import formula

소지품_카테고리 = "포션"


def 회복량_굴림(포션, 보정치):
    """포션의 "회복값" 수식을 굴린다. "최소회복값"보다 작으면 그 값으로 올린다
    (최대치 제한은 포션_적용이 한다)."""
    식 = 포션["회복값"]
    for 키워드 in ("주문시전보정치", "건강보정치"):
        식 = 식.replace(키워드, f"({보정치})")
    굴림 = formula.올림(formula.수식_평가(식, {"차수": 포션["티어"]}))
    return max(포션.get("최소회복값", 0), 굴림)


def 사용불가_사유(포션, 레벨, 현재HP, 현재값, 최대값, 보유수):
    """쓸 수 없으면 사유 문자열, 쓸 수 있으면 None.
    현재값/최대값은 포션의 "회복대상"(HP/MP) 기준이다."""
    if 보유수 <= 0:
        return "소지품에 없다."
    if 레벨 < 포션.get("레벨제한", 1):
        return f"레벨 {포션['레벨제한']} 이상만 쓸 수 있다."
    if 현재HP <= 0:
        return "쓰러진 캐릭터는 마실 수 없다."
    if 현재값 >= 최대값:
        return f"{포션['회복대상']}가 이미 가득 찼다."
    return None


def 포션_적용(대상, 포션, 보정치, 최대값):
    """대상(캐릭터 또는 전투 참가자)의 "현재HP"/"현재MP"를 회복량만큼 올린다.
    실제로 오른 양을 돌려준다."""
    키 = f"현재{포션['회복대상']}"
    전 = 대상[키]
    대상[키] = min(최대값, 전 + 회복량_굴림(포션, 보정치))
    return 대상[키] - 전


def 소지품_차감(소지품, 포션이름):
    """소지품["포션"]에서 1개를 뺀다. 0개가 되면 항목을 지운다."""
    소지품_차감_카테고리(소지품, 소지품_카테고리, 포션이름)


def 소지품_차감_카테고리(소지품, 카테고리, 이름):
    """소지품[카테고리]에서 1개를 뺀다(주류는 "소모품"). 0개가 되면 항목을 지운다."""
    칸 = 소지품.setdefault(카테고리, {})
    if 칸.get(이름, 0) <= 0:
        raise ValueError(f"'{이름}'이(가) 소지품에 없다.")
    칸[이름] -= 1
    if 칸[이름] == 0:
        del 칸[이름]


# -------------------------------------------------------------- 음식


def 음식_회복비율(음식):
    """ "50%" -> 50. 회복대상이나 회복값이 정해지지 않았으면("미정") None."""
    값, 대상 = 음식.get("회복값"), 음식.get("회복대상")
    if not isinstance(대상, list) or not (isinstance(값, str) and 값.endswith("%")):
        return None
    try:
        return int(값[:-1])
    except ValueError:
        return None


def 음식_사용불가_사유(음식, 현재HP, 현재값들, 최대값들, 보유수):
    """먹을 수 없으면 사유 문자열, 먹을 수 있으면 None. 현재값들/최대값들: {"HP": n, "MP": n}."""
    if 보유수 <= 0:
        return "소지품에 없다."
    if 음식_회복비율(음식) is None:
        return "데이터 없음"
    if 현재HP <= 0:
        return "쓰러진 캐릭터는 먹을 수 없다."
    if all(현재값들[종류] >= 최대값들[종류] for 종류 in 음식["회복대상"]):
        return f"{', '.join(음식['회복대상'])}가 이미 가득 찼다."
    return None


def 음식_적용(대상, 음식, 최대값들):
    """회복대상마다 최대치 x 비율(올림)만큼 올린다. 실제로 오른 양 {"HP": n, ...}."""
    비율 = 음식_회복비율(음식)
    결과 = {}
    for 종류 in 음식["회복대상"]:
        키 = f"현재{종류}"
        전 = 대상[키]
        대상[키] = max(전, min(최대값들[종류], 전 + -(-최대값들[종류] * 비율 // 100)))
        결과[종류] = 대상[키] - 전
    return 결과


