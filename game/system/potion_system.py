# item_consumable.py "부여" - 캐릭터["무기속성부여"](속성 목록)에 더한다. 무기 공격의 속성 계산
# (combat.attacks.일반공격_속성, skill_attack._타격_속성)이 버프 "무기속성추가"와 같이 읽고,
# 마을 휴식(ctl_town.휴식)으로 풀린다.


def 무기속성_부여(캐릭터, 속성):
    """캐릭터의 무기에 속성을 더한다(다른 속성은 쌓인다). 이미 있는 속성이면 ValueError."""
    목록 = 캐릭터.setdefault("무기속성부여", [])
    if 속성 in 목록:
        raise ValueError(f"이미 {속성}이 부여돼 있다.")
    목록.append(속성)
