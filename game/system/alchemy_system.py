# 규칙은 docs/game-rules.md "연금술".
#
# - 재료: 라이언 코크스 1개 -> 모순의 결정체 1개 / 강렬한 기운 1개(장비강화의 증폭·재련 재료).
#   다른 재료를 라이언 코크스로 바꾸는 길은 없다.
# - 소모품: 회복포션(HP/MP 포션 4등급씩)을 그 가격만큼의 무색 큐브 조각으로 만든다.
# - 한 번에 1개, 골드는 들지 않는다. 재료가 모자라면 아무것도 바뀌지 않는다(player_system.재료로_제작).

from game.data.item.item_potion import 포션_데이터
from game.system import player_system

탭목록 = ["전체", "재료", "소모품"]

# 탭 -> [(만들 아이템, 소지품 칸, {재료: 개수})]
_재료_목록 = [
    ("모순의 결정체", "재료", {"라이언 코크스": 1}),
    ("강렬한 기운", "재료", {"라이언 코크스": 1}),
]
_소모품_목록 = [
    (이름, "포션", {"무색 큐브 조각": 포션["가격"]})
    for 이름, 포션 in 포션_데이터["회복포션"].items()
]
_탭별 = {"재료": _재료_목록, "소모품": _소모품_목록}


def 레시피목록(탭):
    """[{"이름", "칸", "재료": {이름: 개수}}] - "전체"는 재료 다음 소모품."""
    목록 = _재료_목록 + _소모품_목록 if 탭 == "전체" else _탭별[탭]
    return [{"이름": 이름, "칸": 칸, "재료": dict(재료)} for 이름, 칸, 재료 in 목록]


def 재료_결과물():
    """재료 탭에서 만드는 재료 이름들(도감 재료 목록에 넣는다)."""
    return [이름 for 이름, _, _ in _재료_목록]


def 제작(플레이어, 레시피):
    """레시피 하나로 1개를 만든다. 모자라면 ValueError(아무것도 바뀌지 않는다)."""
    player_system.재료로_제작(플레이어, 레시피["칸"], 레시피["이름"], 레시피["재료"])
