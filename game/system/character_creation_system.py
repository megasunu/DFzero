def 기본_스탯구성(직업):
    """그 직업의 기본 {"주스탯", "보조스탯", "약점스탯"} - 표의 복사본."""
    return dict(직업별_주보조약점스탯[직업])


def 전직_기본_스탯구성(전직, 캐릭터=None):
    """그 전직의 기본 {"주스탯", "보조스탯", "약점스탯"} - 표의 복사본. 표에 없는 전직은
    캐릭터의 지금 역할(사용자 결정 2026-10-26, #403 - 전에는 KeyError로 전직 화면이 멈췄다)."""
    if 전직 not in 전직별_주보조약점스탯 and 캐릭터 is not None:
        return {역할: 캐릭터.get(역할) for 역할 in _역할별_점수}
    return dict(전직별_주보조약점스탯[전직])


def 스탯역할(스탯구성, 스탯이름):
    """스탯이름이 맡은 역할 - "주스탯"/"보조스탯"/"약점스탯", 아니면 "일반"."""
    for 역할 in _역할별_점수:
        if 스탯구성.get(역할) == 스탯이름:
            return 역할
    return "일반"


def 스탯역할_다음(스탯구성, 스탯이름):
    """스탯이름을 한 번 터치한 뒤의 새 스탯구성(원래 것은 그대로 둔다).
    역할은 주스탯 -> 보조스탯 -> 일반 -> 약점스탯 -> 주스탯 순서로 바뀌고,
    다른 능력치가 이미 맡은 주/보조/약점은 건너뛴다. 일반은 몇 개든 될 수
    있으므로 건너뛰지 않는다. 그래서 주/보조/약점이 비는 순간이 생길 수
    있고, 캐릭터를 만들기 전에 스탯구성_검사()가 막는다."""
    새구성 = {역할: 스탯구성.get(역할) for 역할 in _역할별_점수}
    지금 = 스탯역할(새구성, 스탯이름)
    if 지금 != "일반":
        새구성[지금] = None
    위치 = 스탯역할_순서.index(지금)
    for 칸 in range(1, len(스탯역할_순서) + 1):
        다음 = 스탯역할_순서[(위치 + 칸) % len(스탯역할_순서)]
        if 다음 == "일반":
            return 새구성
        if 새구성[다음] is None:
            새구성[다음] = 스탯이름
            return 새구성
    return 새구성


def 스탯구성_검사(스탯구성):
    """주/보조/약점스탯이 모두 골라졌고, 서로 다른 능력치인지 본다.
    아니면 ValueError(화면 안내 줄에 그대로 보인다)."""
    고른것 = [스탯구성.get(역할) for 역할 in _역할별_점수]
    if any(스탯 is None for 스탯 in 고른것):
        raise ValueError("주스탯/보조스탯/약점스탯을 모두 골라 주세요.")
    if any(스탯 not in 능력치_목록 for 스탯 in 고른것):
        raise ValueError(f"없는 능력치가 있습니다: {고른것}")
    if len(set(고른것)) != len(고른것):
        raise ValueError("주스탯/보조스탯/약점스탯은 서로 다른 능력치여야 합니다.")


def 역할_교환(캐릭터, 새구성, 특성보너스=None):
    """주/보조/약점 역할을 새구성으로 바꾸고 역할끼리 값을 옮긴다(2026-10-21 사용자 결정, #351 - 전직,
    레테의 눈물·강물). 옛 주스탯의 값이 새 주스탯으로, 보조·약점도 같다. 역할이 없던 능력치는 그대로 두고,
    밀려 값이 빈 자리에는 쓰이지 않은 값을 능력치 순서대로 채운다.

    특성보너스({능력치: 값}) - 특성이 그 능력치에 직접 더한 값(레벨 1 특성 +1 등)은 역할과 별개라
    옮기지 않고 원래 능력치에 남긴다. 약점제거의 +2와 약점증가의 8은 약점 역할의 값이라 따라간다 -
    약점증가면 끝에 새 약점들을 상한(8)으로 내린다. 새구성은 스탯구성_검사를 통과해야 한다(ValueError)."""
    스탯구성_검사(새구성)
    보너스 = 특성보너스 or {}
    기본 = {n: 캐릭터[n] - 보너스.get(n, 0) for n in 능력치_목록}
    옛 = {역할: 캐릭터.get(역할) for 역할 in _역할별_점수}
    옛역할 = {n for n in 옛.values() if n}
    새값 = {새구성[역할]: 기본[옛[역할]] for 역할 in _역할별_점수 if 옛[역할]}
    for n in 능력치_목록:  # 역할이 없던 능력치는 새 역할을 받지 않았으면 제자리
        if n not in 옛역할 and n not in 새값:
            새값[n] = 기본[n]
    # 값을 잃은 자리(옛 역할이었지만 새 역할이 아님)에, 새 역할에 밀린 값(역할이 없던 능력치의 값)을
    빈자리 = [n for n in 능력치_목록 if n not in 새값]
    밀린값 = [n for n in 능력치_목록 if n not in 옛역할 and n in 새구성.values()]
    for 자리, 출처 in zip(빈자리, 밀린값):
        새값[자리] = 기본[출처]
    for n in 능력치_목록:
        캐릭터[n] = 새값[n] + 보너스.get(n, 0)
    for 역할 in _역할별_점수:
        캐릭터[역할] = 새구성[역할]
    if "약점증가" in (캐릭터.get("보유특성") or []):
        for n in 캐릭터데이터.약점스탯_목록(캐릭터):
            캐릭터[n] = min(캐릭터[n], 캐릭터데이터.약점상한)


def 초기능력치_생성(직업, 스탯구성=None):
    """능력치(근력~매력) 초기값을 만든다. 주스탯 13점, 보조스탯 12점,
    약점스탯 8점, 나머지 능력치는 10점이다. 스탯구성(플레이어가 고른 것)이
    None이면 직업별_주보조약점스탯의 기본값을 쓴다. 비어 있는 역할(None)은
    점수를 바꾸지 않는다 - 고르는 도중의 미리보기용.

    반환값은 (능력치딕셔너리, 주스탯이름, 보조스탯이름, 약점스탯이름)
    튜플이다."""
    if 스탯구성 is None:
        스탯구성 = 직업별_주보조약점스탯[직업]
    능력치 = {스탯이름: 기본스탯_점수 for 스탯이름 in 능력치_목록}
    for 역할, 점수 in _역할별_점수.items():
        if 스탯구성.get(역할) is not None:
            능력치[스탯구성[역할]] = 점수

    return (
        능력치,
        스탯구성.get("주스탯"),
        스탯구성.get("보조스탯"),
        스탯구성.get("약점스탯"),
    )


def 캐릭터_생성(
    캐릭터명,
    직업,
    레벨1_레벨업항목,
    레벨1_특성정의모음,
    시작무기데이터,
    주문시전능력치=None,
    직업스킬목록=None,
    스탯구성=None,
):
    """새 레벨 1 캐릭터를 만든다.

    캐릭터명, 직업     : 문자열. 직업은 직업별_주보조약점스탯에 등록된
                          이름이어야 한다 (예: "귀검사").
    레벨1_레벨업항목   : 해당 직업 job_level_XX.py의 "레벨업테이블"에서
                          키 1(레벨 1)에 해당하는 항목. "타입":"특성획득"
                          형식이어야 한다 (job_level_format.py 참고).
    레벨1_특성정의모음 : {특성이름: 특성정의, ...} 형태의 딕셔너리.
                          레벨1_레벨업항목의 "획득"."획득특성"에 있는
                          특성 이름들을, 그 특성이 정의된 job_ability_XX.py
                          "특성목록"에서 찾은 실제 정의와 매칭해서 넘긴다.
                          이 정의의 "효과"를 읽어서 능력치 등을 즉시
                          반영하는 데 쓴다.
    시작무기데이터     : 레벨1_레벨업항목["시작장비"] 이름에 해당하는
                          eq_weapon_XX.py 무기 데이터 딕셔너리
                          (예: 귀검사무기목록["녹슨 소검"]).
    주문시전능력치     : 지능이 아닌 직업만 지정. 예) "지혜". None이면 지능
    직업스킬목록       : 해당 직업 job_skill_XX.py의 "스킬목록". 여기서
                          "습득방법"이 "초기습득"인 스킬을 적힌 순서대로
                          전부 배우고 시작한다. 생략하면 스킬 없이 시작한다.

    스탯구성           : 플레이어가 고른 {"주스탯", "보조스탯", "약점스탯"}.
                          생략하면 직업 기본값. 검사(스탯구성_검사)는 부르는
                          쪽이 한다 - 화면 미리보기는 고르는 도중의 구성으로도
                          만든다. 능력치는 초기능력치_생성()이 계산해서 채운다.
    """
    캐릭터 = 캐릭터데이터.빈_캐릭터()

    캐릭터["캐릭터명"] = 캐릭터명
    캐릭터["직업"] = 직업
    캐릭터["주문시전능력치"] = 주문시전능력치 or "지능"

    능력치, 주스탯, 보조스탯, 약점스탯 = 초기능력치_생성(직업, 스탯구성)
    for 스탯이름 in 능력치_목록:
        캐릭터[스탯이름] = 능력치[스탯이름]
    캐릭터["주스탯"] = 주스탯
    캐릭터["보조스탯"] = 보조스탯
    캐릭터["약점스탯"] = 약점스탯

    _레벨1_특성_부여(캐릭터, 레벨1_레벨업항목, 레벨1_특성정의모음)
    _초기_자원_설정(캐릭터, 레벨1_레벨업항목)
    _시작_장비_설정(캐릭터, 레벨1_레벨업항목)
    레벨1_스킬_습득(캐릭터, 직업스킬목록 or {})
    _평타스탯_설정(캐릭터, 시작무기데이터)

    return 캐릭터


def _레벨1_특성_부여(캐릭터, 레벨1_레벨업항목, 특성정의모음):
    """job_level_format.py의 <획득 하위 양식> 1) "특성" 형식을 그대로
    처리한다. "획득특성"은 특성 이름 하나거나 이름 리스트일 수 있다.
    character_levelup_system.py의 레벨업 처리와 같은 방식이다."""
    획득 = 레벨1_레벨업항목["획득"]
    특성이름들 = 획득["획득특성"]
    if isinstance(특성이름들, str):
        특성이름들 = [특성이름들]

    for 특성이름 in 특성이름들:
        effect_engine.특성_부여(캐릭터, 특성이름, 특성정의모음[특성이름])


def _초기_자원_설정(캐릭터, 레벨1_레벨업항목):
    """MP는 프로젝트 공식(레벨 1은 최대 25)대로 계산해서
    채운다. HP는 기본체력 + 올림(레벨 x 기본체력 / 2)로 계산한다
    (기본체력 = "레벨당체력증가" + 건강보정치, job_level_format.py 참고). 이 함수는 레벨 1 생성 시점만 다룬다."""
    캐릭터["기본최대MP"] = 캐릭터데이터.기본최대MP_계산(캐릭터)
    캐릭터["현재MP"] = 캐릭터["기본최대MP"]

    캐릭터["기본최대HP"] = 캐릭터데이터.기본최대HP_계산(
        캐릭터, 레벨1_레벨업항목["레벨당체력증가"]
    )
    캐릭터["현재HP"] = 캐릭터["기본최대HP"]


def _시작_장비_설정(캐릭터, 레벨1_레벨업항목):
    """job_level_XX.py 레벨 1 항목의 "기본가용무기"/"시작장비"/"시작상의"를
    그대로 반영한다. "가용무기"는 비전직부터 쓸 수 있는 무기 종류 목록이고,
    "시작장비"는 처음부터 장착하고 시작하는 무기 이름, "시작상의"는
    처음부터 장착하고 시작하는 상의 이름이다 (job_level_format.py 참고)."""
    캐릭터["가용무기"] = list(레벨1_레벨업항목["기본가용무기"])
    캐릭터["장착장비"]["무기"] = 레벨1_레벨업항목["시작장비"]
    캐릭터["장착장비"]["상의"] = 레벨1_레벨업항목["시작상의"]


def 레벨1_스킬_습득(캐릭터, 직업스킬목록):
    """직업 스킬목록에서 "습득방법"이 "초기습득"인 스킬을 적힌 순서대로
    보유스킬에 넣는다(job_skill_format.py "습득방법" 참고). 그 밖의 스킬은
    파티 화면 [스킬습득]으로 골드를 내고 배운다(skill_learn_system.py).
    이미 가진 스킬은 건너뛰므로 불러올 때 다시 불러도 된다 - 시작 스킬이 나중에
    추가되면 옛 세이브의 캐릭터에게 빠진 것만 끝에 붙는다(ctl_session.게임_불러오기)."""
    for 스킬이름, 스킬 in 직업스킬목록.items():
        if 스킬.get("습득방법") == "초기습득":
            if 스킬이름 not in 캐릭터["보유스킬"]:
                캐릭터["보유스킬"].append(스킬이름)


def _평타스탯_설정(캐릭터, 시작무기데이터):
    """character_format.py 기준 "평타스탯" = 기본 근력 + 무기의
    "무기능력치" + 특성으로 추가된 후보. 특성으로 추가되는 부분은
    해당 특성을 얻을 때(퍽/레벨업 처리 쪽에서) 이 리스트에 추가해주면
    된다. 여기서는 생성 시점 기준으로 근력과 장착한 시작 무기의
    "무기능력치"만 합친다."""
    후보 = ["근력"]
    for 스탯이름 in 시작무기데이터["무기능력치"]:
        if 스탯이름 not in 후보:
            후보.append(스탯이름)

    캐릭터["평타스탯"] = 후보
