# 몬스터 특성(monster_ability.py) 반영
# =====================================================
# 몬스터 데이터의 "특성" 리스트(예: ["종족:고블린"])는 아래 두 갈래로
# 반영한다:
#
# 1) 상시 효과("효과"가 리스트인 종족특성/일부 몬스터특성, 예: 종족:타우
#    최대HP 증가, 체력증가): _특성_목록()이 참가자 원본의 "특성"을
#    전투상태["특성정의"](전투_시작()의 정의모음["특성정의"])에서 찾고,
#    특성_수치()/특성_문자열_변동값_목록()이 버프디버프_수치()와 같은
#    "변동대상" 어휘(AC/최대HP/데미지보너스/명중보너스/속도/저항/취약)로
#    최종AC/유효_최대HP/명중_판정/유효_이니셔티브/피해_적용에 합산된다.
#    "조건부효과"(종족:좀비의 '출혈' 적 존재 시 등)도 조건이 충족될 때만
#    같은 방식으로 더해진다.
# 2) 트리거형 효과("효과"가 "종류":"상태이상"/"데미지"/"데미지+상태이상"
#    딕셔너리인 몬스터특성, 예: 화염의 마녀/빙결의 마녀/냉기방출/기상
#    충격파): "발동조건"에 따라 피격_처리()(공격명중시) / 턴_종료_처리()
#    (턴종료시) / 턴_시작_처리()의 상태이상 만료 시점(OO 해제시)에서
#    각각 발동한다. skill_system.py의 상태이상 부여 로직(중첩/부여버프
#    처리 등)만큼 정교하지는 않다 - 이름/지속턴만 반영하는 최소 버전
#    이며, combat 패키지가 skill_system.py를 부르지 않는 구조(순환
#    참조 방지)라 별도로 최소 구현했다.
#
# 몬스터 패턴 자체의 "효과"/"명중실패시효과"(타우 아미 들이받기의 기절
# 등)는 _몬스터_패턴_실행()이 같은 최소 구현(상태이상_효과_적용)으로
# 적용한다.
#
# 몬스터 패턴의 "타겟":"적전체"/"적3체"(포효/무리 가드/블리자드/아이스
# 스피어/메테오/체인 메테오 등)는 몬스터_턴_실행()이 monster_ai가 고른
# 기본 대상에서 실제 대상 목록으로 넓힌다("적3체"는 밸런스 기준의
# 범위공격처럼 대형위치 기준 좌우 인접, 최대 3체/구석이면 2체).
# "체인 메테오"처럼 "공격횟수"와 "적3체"가 같이 있으면, 공격횟수만큼
# "볼리를 반복"하는 것으로 해석해 매 회차마다 대상 목록 전체를 다시
# 공격한다("메테오를 3번 연속으로 쓰는 스킬" - 확정된 해석은 아니다,
# 확인 필요).
# "타겟":"적랜덤" + "대상수": n은 기본 대상과 상관없이 서로 다른 생존자 n명을 무작위로
# 고른다(루스 세리말리온 아이스 바운스).
# "공격단계1"/"공격단계2"...(스킬 "분할공격"과 같은 양식)는 단계마다 타겟/명중/효과를
# 따로 실행하고, "기준대상":"공격단계N"이면 그 단계의 대상을 중심으로 범위를 잡는다
# (하스 세리말리온 하강공격). 공격 패턴의 "자신버프획득"/"자신버프해제"는 명중과
# 상관없이 공격 뒤에 적용한다(상승/하강의 "상승"). "조건부행동"의 조건 {"보유버프": 이름}은
# 몬스터가 그 버프를 가졌는지로 패턴을 고른다(monster_ai.행동_선택).
#
# 속성이 리스트인 경우(예: 굴 구위시 ["무속성","수속성","암속성"]) -
# "더 높은 데미지 쪽 속성으로 적용"(속성 다중판정의 기본 설정)을
# 피해_적용()에서 반영한다: 각 속성으로 계산했을 때의 배율(저항
# 0.5배/취약 2배) 중 가장 큰 배율을 쓴다.
#
# =====================================================
# AC
# =====================================================
# - 아군 AC: 장비 전 부위(gameflow가 장비데이터모음에 방어구/악세서리까지
#   넣는다) + 세트효과(전투상태["세트정의"], 구성품 전부 장착 시) + 버프/
#   장비로 늘어난 민첩(추가민첩) + 캐릭터 특성의 AC(판금숙련/견문색 등,
#   전투상태["캐릭터특성정의"] - _캐릭터특성_수치 참고)를 반영한다.
# - 몬스터 AC: 역할군 "AC" 수식(monster_format.py 역할군공식)을 버프로 바뀐 민첩으로 평가하고, 원본의
#   "AC보너스"와 칭호(monster_title.py, 전투상태["칭호정의"])의 AC를
#   더한다.
# - 몬스터 칭호: 최대HP 배율/변동값, AC, 명중률보너스, 데미지보너스를
#   반영한다(칭호_수치/칭호_배율 참고). 몬스터 시작 HP도
#   유효_최대HP(특성/칭호 반영)로 채운다 - 종족:타우/체력증가/보스 칭호의
#   최대HP 변동이 실제 시작 체력에 들어간다.
#
# =====================================================
# 캐릭터 특성/장비 스탯/몬스터 데미지보너스
# =====================================================
# - 캐릭터 특성: 특성_수치()가 아군이면 "보유특성"까지 더한다 -
#   명중보너스(무기의 극의/계시/[공격주문 전용 조건]/
#   선빵필승·암살자[첫 라운드]), 데미지보너스(무기의 극의/패황색
#   [약점속성 조건도 지원]), AC(판금숙련/견문색/암살자[첫 라운드]),
#   방어력(중갑숙련/철금강/가죽숙련/무장색), 속도(종족:루가루/계시/
#   선빵필승/암살자), 치명타범위(급소지정), 행동보너스
#   (머슬시프트). 토글/반응/강화/트리거형 특성은 다루지 않는다.
# - 장비 스탯보너스: 전투_시작()이 장비(전 부위+세트) 보너스를
#   참가자["장비보너스"]에 캐싱하고, 유효_능력치값()/유효_능력치_보정치()가
#   그 "스탯보너스"를 더한다 - 명중/데미지 보정치, 주문시전보정치, 내성,
#   수식의 "OO보정치" 전부에 반영된다(AC는 equipment_system 쪽에서 이미
#   장비 민첩을 더하므로 추가민첩에는 버프만 넣는다).
# - 치명타범위: 유효_치명타범위()가 버프/특성 확장을 반영한다
#   (skill_system.스킬_명중_판정도 사용).
# - 치명타주사위: 치명타면 피해 주사위가 참가자 "치명타주사위"(기본 1) + 버프/
#   디버프/특성 증감만큼 는다 - stats.치명타_주사위수(아군 피해_굴림, 몬스터 패턴/소환수).
# - 버프 효과 원소의 "무기조건": 그 무기를 들었을 때만 버프디버프_수치()에 더한다.
#   캐릭터 특성 효과 원소의 "무기조건"도 같다(무기의 극의). 그 특성의 "무기공격력"(무기
#   주사위 대체)/"일반공격추가피해"/"명중시상태이상"은 traits.캐릭터특성_무기효과()로 읽는다.
# - 속성: 무기 주사위를 쓰는 피해는 무기 "속성", 아니면 스킬 속성(stats.공격_속성, 없으면
#   무속성). 저항 0.5/취약 2/면역 0, 속성강화/속성내성 1당 ±10%를 최종피해에 곱한다
#   (damage.피해_적용/속성_최종배율).
# - 몬스터 원본 "데미지보너스": 몬스터_데미지보너스()가 원본 값+역할군+버프/디버프+특성+칭호를
#   합쳐 패턴 공격과 자폭 패턴 피해에 더한다.
# - 장비 명중률보너스/데미지보너스(전 부위+활성 세트): 장비_수치()로 읽어
#   명중_판정(모든 명중 굴림), 일반공격_실행, skill_system.공격_1회(모든 공격
#   스킬)에 더한다 - 투척 아이템(스킬 데이터 "장비보너스제외")만 빼고. 아군 최대HP도 장비 건강을 반영한다
#   (equipment_system.장비반영_최대HP).
# - "데미지" 키가 없는 몬스터 패턴: 몬스터_턴_실행()이 "타입"
#   버프패턴(_몬스터_버프패턴_실행)/회복패턴(_몬스터_회복패턴_실행)과
#   "실패시데미지" 내성형 공격패턴(_몬스터_내성패턴_실행, 포효 등)을 따로
#   처리한다. 그 밖에 "데미지"가 없는 패턴은 오류 대신 로그만 남기고 넘긴다.
# - 영창패턴(케라하 블리자드/비노슈 메테오): 자신에게 "주문영창"을 걸고 턴을 마친다. 다음 턴에
#   특성 "특수패턴:케라하/비노슈"의 대체행동(조건 "자신상태이상")이 패턴 대신 그 주문을 시전한다.
#   행동불가형 상태이상/침묵이 걸리면 주문영창이 풀린다(status.영창_방해).
# - 감옥패턴(얼음감옥/운석폭발): 대상을 감옥에 가둔다(monster_actions.감옥_걸기). 감옥은 진영 "감옥"
#   참가자(턴 없음, 승패/보상 제외, AC 1 - 대실패만 빗나감, 저항/취약은 특성 "감옥:얼음/운석")다.
#   갇힌 사람이 적을 노리면 감옥이 대신 받고(status.감옥_대상, 넘친 피해는 사라짐), 다른 아군은
#   대상 고르기와 "적전체" 공격으로 감옥을 때린다. 지속턴은 갇힌 사람의 턴 끝에 세고, 다 되면
#   "만료시폭발"(운석)이 터진다. 감옥은 한 사람에 하나 - 새 감옥이 오면 앞 감옥의 벌칙 뒤 교체.
#   몬스터가 얻은 "소환:OO" 버프는 그 몬스터의 턴 종료 시 소환수로 행동한다
#   (몬스터_소환수_행동_실행, summon_00.py 행동표).

# 이 패키지는 위 설계를 모듈로 나눈 것이다(R4). 호출부(gameflow, skill_system, tests)는
# 필요한 모듈을 직접 불러 쓴다 - 예: from game.system.combat import flow, stats
# (R5에서 옛 이름을 다시 내보내던 호환 모듈 combat_system.py를 지웠다).
#
#   core             공용 - 전투 로그 기록, 차수, 전투 종료 판정(전투상태만 보는 함수 - reactions와 flow가 같이 쓴다)
#   formula          수식 평가 - 데미지 문법/다이스/무기공격력
#   participants     참가자 인스턴스 생성(아군/몬스터), 몬스터 수식 컨텍스트
#   traits           몬스터 특성/캐릭터 특성/칭호 수치와 발동(공격명중시/턴종료시/해제시/전투시작시)
#   status           상태이상 조회 - 정의/면역/플래그/행동제한, 은신 자동해제
#   stats            수치 집계 - 버프/디버프/장비/특성 반영 능력치, AC/방어력/보호률/최대HP, 이니셔티브/우선도, 수식 컨텍스트, 몬스터 패턴 수식
#   resources        효과 정의 조회와 자원(보유/소모), 몬스터 버프 부여
