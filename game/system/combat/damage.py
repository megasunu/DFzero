def 홀딩_목록(참가자):
    return [s for s in 참가자.get("상태이상", []) if s.get("이름") == "홀딩"]


def 홀딩_걸기(
    전투상태,
    시전자,
    대상,
    출처,
    피해,
    속성=None,
    추가피해목록=None,
    최종피해배율=1,
    무적=False,
    충격파=None,
    슈퍼아머=False,
):
    """ "홀딩" 태그 공격이 맞았을 때 - 굴린 피해(방어/속성 전)를 상태이상 "홀딩" 인스턴스에 맡긴다.
    피해_적용은 대상의 다음 차례 시작(홀딩_발동)에 한다. 피격_처리(경직)보다 먼저 불러야
    이미 행동한 대상의 홀딩 전용 차례가 생긴다. 무적이면 이 홀딩이 남은 동안 시전자는 적의 공격 피해를
    받지 않고(홀딩무적인가), 충격파(스킬 "충격파")는 피해가 들어갈 때 이어서 굴린다(마운트 #378).
    슈퍼아머면(반드시 잡는다! #381) 이 홀딩이 남은 동안 시전자는 "슈퍼아머" 상태다(지속턴 없이 "홀딩연동" -
    홀딩이 풀리면 _홀딩슈퍼아머_정리가 지운다)."""
    항목 = {
        "이름": "홀딩",
        "지속턴": None,
        "시전자id": 시전자["id"],
        "출처": 출처,
        "보류피해": 피해,
        "속성": 속성,
        "추가피해목록": [list(항목) for 항목 in 추가피해목록 or []],
        "최종피해배율": 최종피해배율,
    }
    if 무적:
        항목["시전자무적"] = True
    if 충격파:
        항목["충격파"] = dict(충격파)
    대상.setdefault("상태이상", []).append(항목)
    if 슈퍼아머:
        항목["시전자슈퍼아머"] = True
        if not any(s.get("홀딩연동") for s in 시전자.get("상태이상", [])):
            시전자.setdefault("상태이상", []).append(
                {"이름": "슈퍼아머", "홀딩연동": True}
            )


def _홀딩슈퍼아머_정리(전투상태):
    """ "시전자슈퍼아머" 홀딩이 하나도 남지 않은 시전자에게서 "홀딩연동" 슈퍼아머를 지운다."""
    남은시전자 = {
        항목.get("시전자id")
        for p in 전투상태["참가자"]
        for 항목 in 홀딩_목록(p)
        if 항목.get("시전자슈퍼아머")
    }
    for p in 전투상태["참가자"]:
        if p.get("id") in 남은시전자:
            continue
        if any(s.get("홀딩연동") for s in p.get("상태이상", [])):
            p["상태이상"] = [s for s in p["상태이상"] if not s.get("홀딩연동")]


def 홀딩무적인가(전투상태, 참가자):
    """참가자가 건 "시전자무적" 홀딩(마운트 #378)이 아직 남아 있나 - 그런 홀딩이 있을 때만 끊긴 홀딩을 먼저 정리한다."""

    def 남았나():
        return any(
            항목.get("시전자무적") and 항목.get("시전자id") == 참가자.get("id")
            for p in 전투상태["참가자"]
            for 항목 in 홀딩_목록(p)
        )

    if not 남았나():
        return False
    홀딩_정리(전투상태)
    return 남았나()


def _시전자(전투상태, 항목):
    return next(
        (p for p in 전투상태["참가자"] if p.get("id") == 항목.get("시전자id")), None
    )


def _무력화(전투상태, 참가자):
    return any(
        (전투상태["상태이상정의"].get(s.get("이름")) or {}).get("분류") == "무력화CC"
        for s in 참가자.get("상태이상", [])
    )


def 홀딩_정리(전투상태):
    """건 사람이 쓰러졌거나 무력화CC에 걸린 홀딩은 피해 없이 푼다(사용자 결정). 홀딩이 뜻을 갖는 곳
    (명중 판정의 이점, 차례 시작의 피해, 홀딩 전용 차례)마다 먼저 부른다."""
    for p in 전투상태["참가자"]:
        for 항목 in 홀딩_목록(p):
            시전자 = _시전자(전투상태, 항목)
            if 시전자 is None or not 시전자["생존"] or _무력화(전투상태, 시전자):
                p["상태이상"].remove(항목)
    _홀딩슈퍼아머_정리(전투상태)


def 홀딩_발동(전투상태, 대상):
    """대상의 차례 시작(또는 홀딩 전용 차례) - 맡아 둔 홀딩 피해를 넣고 홀딩을 푼다."""
    홀딩_정리(전투상태)
    for 항목 in 홀딩_목록(대상):
        대상["상태이상"].remove(항목)
        if not 대상["생존"]:
            continue
        시전자 = _시전자(전투상태, 항목)
        피해 = 피해_적용(
            전투상태,
            대상,
            max(0, 항목["보류피해"]),
            속성=항목.get("속성"),
            추가피해목록=[tuple(x) for x in 항목.get("추가피해목록") or []] or None,
            공격측=시전자,
            최종피해배율=항목.get("최종피해배율", 1),
        )
        core.로그(
            전투상태,
            {
                "공격자": 시전자["이름"],
                "대상": 대상["이름"],
                "피해": 피해,
                "비고": f"{항목.get('출처')} - 홀딩 피해",
            },
            종류="비고",
        )
        if 항목.get("충격파"):
            충격파_발동(전투상태, 시전자, 대상, 항목["충격파"], 항목.get("출처"))
    _홀딩슈퍼아머_정리(전투상태)


def _양옆_포함(전투상태, 대상):
    """대상과 같은 편의 대형위치 양옆(살아 있는 참가자, 빈 칸은 건너뛰지 않는다) - 대상 포함."""
    같은편 = sorted(
        (p for p in 전투상태["참가자"] if p["진영"] == 대상["진영"]),
        key=lambda p: p.get("대형위치", 0),
    )
    i = next(n for n, p in enumerate(같은편) if p is 대상)
    return [p for p in 같은편[max(0, i - 1) : i + 2] if p["생존"]]


def 충격파_발동(전투상태, 시전자, 중심, 원소, 출처):
    """충격파 - 중심과 양옆에게 따로 "명중률"로 굴리고, 맞으면 "데미지"를 준다. "내성"이 있으면(크레이지 발칸 #378)
    맞은 대상은 그 내성굴림(난이도는 시전자 기준 수식)에 성공하면 절반(버림), 없으면(강렬한 테이크 다운 #381) 그대로."""
    컨텍스트 = stats.기본_컨텍스트(전투상태, 시전자)
    대상들 = _양옆_포함(전투상태, 중심)
    with 몹몰이_공격대상(전투상태, 대상들):
        for p in 대상들:
            _충격파_1회(전투상태, 시전자, p, 원소, 출처, 컨텍스트)


def _충격파_1회(전투상태, 시전자, p, 원소, 출처, 컨텍스트):
    if not p["생존"]:
        return
    판정 = 명중_판정_계산(전투상태, 시전자, p, 원소.get("명중률", "근력판정"))
    공격연출_기록(전투상태, p, 판정, None, 원소.get("공격타입", "타격"))
    피해 = 0
    if 판정["성공"]:
        피해 = max(0, int(formula.수식_평가(원소["데미지"], 컨텍스트)))
        난이도 = formula.수식_평가(str(원소.get("난이도", "10")), 컨텍스트)
        if (
            원소.get("내성")
            and stats.대상_내성굴림(전투상태, p, 원소["내성"], 난이도)[0]
        ):
            피해 //= 2
        피해 = 피해_적용(전투상태, p, 피해, 공격측=시전자)
    core.로그(
        전투상태,
        {
            "공격자": 시전자["이름"],
            "대상": p["이름"],
            "피해": 피해,
            "비고": f"{출처} - 충격파" + ("" if 판정["성공"] else " 빗나감"),
        },
        종류="비고",
    )


def 피격_처리(
    전투상태, 공격자, 대상, 판정, 속성=None, 특성발동=True, 태그=(), 경직량=1
):
    """명중 시 상태이상 부가효과를 처리한다: 경직(경직_적용 - 태그는 공격의 "타입"), 감전(피격시추가피해),
    수면(무조건 해제), 빙결(화속성 피격시 해제), 은신/집중(내성굴림
    실패 시 해제 - DC는 인스턴스의 "해제난이도", 기본 10). 이어서
    공격자의 "발동조건":"공격명중시" 몬스터특성(화염의 마녀/빙결의
    마녀 등)도 여기서 함께 발동시킨다(일반공격_실행/_몬스터_패턴_실행
    공용 훅). 특성발동=False면 상태이상 부가효과만 처리하고 특성은 발동하지 않는다."""
    if not 판정.get("성공"):
        return
    경직_적용(전투상태, 대상, 태그, 경직량)
    for 항목, 정의 in list(status.상태이상_정의_목록(전투상태, 대상)):
        효과 = 정의.get("효과", {})

        if 효과.get("타입") == "피격시추가피해" and 효과.get("발동시점") == "피격시":
            피해 = formula.수식_평가(효과.get("수식", "0"), {"차수": core.차수(대상)})
            최종피해 = 피해_적용(
                전투상태,
                대상,
                피해,
                피해감소무시=효과.get("피해감소무시", False),
                방어력무시=효과.get("방어력무시", False),
            )
            core.로그(
                전투상태,
                {
                    "공격자": 항목["이름"],
                    "대상": 대상["이름"],
                    "피해": 최종피해,
                    "비고": "지속피해형 피격시추가피해",
                },
                종류="비고",
            )

        해제조건 = 효과.get("해제조건")
        속성들 = 속성 if isinstance(속성, list) else [속성]
        화속성피격 = "화속성" in [속성_정식명(s) for s in 속성들]
        if 해제조건 == "피격시":
            if 항목 in 대상.get("상태이상", []):
                대상["상태이상"].remove(항목)
        elif 해제조건 == "화속성피격시" and 화속성피격:
            if 항목 in 대상.get("상태이상", []):
                대상["상태이상"].remove(항목)
        elif isinstance(해제조건, list):
            for 조건항목 in 해제조건:
                내성스탯 = 조건항목.get("내성")
                if 조건항목.get("조건") == "피격시" and 내성스탯:
                    난이도 = 항목.get("해제난이도", 10)
                    if not stats.대상_내성굴림(전투상태, 대상, 내성스탯, 난이도)[0]:
                        if 항목 in 대상.get("상태이상", []):
                            대상["상태이상"].remove(항목)
                    break

    속성목록 = 속성 if isinstance(속성, list) else [속성]
    traits.형태_변환(
        전투상태, 대상, [속성_정식명(s) for s in 속성목록 if s]
    )  # 란마 1/2
    # 운석 폭발처럼 몬스터 본인의 공격이 아닌 피해는 마녀 특성 등을 다시 걸지 않는다
    if not 특성발동:
        return
    traits.특성_공격명중시_발동(전투상태, 공격자, 대상)
    특성_명중시_대상변동(전투상태, 공격자, 대상)
    traits.특성_피격시_발동(
        전투상태, 공격자, 대상
    )  # 맞은 쪽의 "피격시효과"(독샘의 주인)
    장비_피격시효과(전투상태, 공격자, 대상)  # 맞은 쪽 장비의 "발동":"피격"(알트브라움)


