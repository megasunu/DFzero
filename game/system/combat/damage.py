def 유효_치명타범위(전투상태, 참가자):
    """치명타가 나는 최소 d20 눈. 기본 20에서 버프/특성의 "치명타범위"
    (치명타확률증가/급소지정 등, 양수 = 범위 확장)만큼 내려간다."""
    기본 = 참가자.get("치명타범위", 20)
    확장 = (
        stats.버프디버프_수치(전투상태, 참가자, "치명타범위")
        + traits.특성_수치(전투상태, 참가자, "치명타범위")
        + stats.마봉_수치(참가자, "치명타범위")
        + stats.공격태그_조건_수치(전투상태, 참가자, "치명타범위")
    )
    return max(2, 기본 - 확장)


def 유효_집요함(전투상태, 참가자):
    """빗나간 공격에 주는 피해 - 버프/디버프/특성의 "집요함"과 장비 "집요함"의 합(0 아래는 0)."""
    값 = (
        stats.버프디버프_수치(전투상태, 참가자, "집요함")
        + traits.특성_수치(전투상태, 참가자, "집요함")
        + stats.장비_수치(참가자, "집요함")
    )
    return max(0, 값)


