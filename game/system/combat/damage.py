def 유효_치명타범위(전투상태, 참가자):
    """치명타가 나는 최소 d20 눈. 기본 20에서 버프/특성의 "치명타범위"
    (치명타확률증가/급소지정 등, 양수 = 범위 확장)만큼 내려간다."""
    기본 = 참가자.get("치명타범위", 20)
    확장 = (
        stats.버프디버프_수치(전투상태, 참가자, "치명타범위")
        + traits.특성_수치(전투상태, 참가자, "치명타범위")
        + stats.마봉_수치(참가자, "치명타범위")
    )
    return max(2, 기본 - 확장)


def 유효_집요함(전투상태, 참가자):
    """빗나간 공격에 주는 피해 - 버프/디버프/특성의 "집요함"과 장비 "집요함"의 합(0 아래는 0)."""
    값 = (
        stats.버프디버프_수치(전투상태, 참가자, "집요함")
        + traits.특성_수치(전투상태, 참가자, "집요함")
        + stats.장비_수치(참가자, "집요함")
    )
    return max(0, 값)


def 유효_흡혈(전투상태, 참가자):
    """입힌 피해의 1%당 회복하는 "흡혈" - 버프/디버프/특성과 장비의 합(기본 0, 0 아래는 0)."""
    값 = (
        stats.버프디버프_수치(전투상태, 참가자, "흡혈")
        + traits.특성_수치(전투상태, 참가자, "흡혈")
        + stats.장비_수치(참가자, "흡혈")
    )
    return max(0, 값)


def _부자유친(전투상태, 공격측, 대상, 최종피해):
    """포켓몬 특성 부자유친(특성 "공격후추가피해비율") - 공격 피해(타격마다)의 그 비율(1/4, 올림)만큼 추가 피해.
    명중굴림·치명타·추가 효과가 없다 - 공격한 참가자 없이 그대로 깎는다(방어·속성 없음, 다시 붙지 않음)."""
    비율 = sum(
        v
        for v in status.특성_변동값목록(전투상태, 공격측, "공격후추가피해비율")
        if isinstance(v, (int, float))
    )
    if 비율 <= 0 or 최종피해 <= 0 or 대상["현재HP"] <= 0:
        return
    추가 = formula.올림(최종피해 * 비율)
    실제 = 피해_적용(전투상태, 대상, 추가, 피해감소무시=True)
    전투상태.setdefault("뒤따를로그", []).append(
        {
            "공격자": 공격측["이름"],
            "대상": 대상["이름"],
            "피해": 실제,
            "비고": "부자유친",
            "종류": "비고",
        }
    )


def _속성흡수량(전투상태, 대상, 부분들):
    """포켓몬 흡수 특성(마중물/타오르는불꽃/피뢰침/정의의마음) - 특성 "속성흡수"에 든 속성으로 들어온 피해(속성
    배율 전, 올림)의 합. 그 속성은 면역이라 피해는 0이고 이만큼 회복한다(사용자 결정 2026-10-20)."""
    흡수속성 = {
        속성_정식명(s) for s in traits.캐릭터특성_문자열값(전투상태, 대상, "속성흡수")
    }
    if not 흡수속성:
        return 0
    return sum(
        formula.올림(max(0, 값))
        for 값, s in 부분들
        if s is not None and 속성_정식명(s) in 흡수속성
    )


def _속성흡수_회복(전투상태, 대상, 양):
    최대HP = formula.올림(stats.유효_최대HP(전투상태, 대상))
    실회복 = max(0, min(양, 최대HP - 대상["현재HP"]))
    대상["현재HP"] += 실회복
    # HP가 가득이어도 남긴다 - 면역으로 피해가 0이 된 까닭을 보여 준다
    전투상태.setdefault("뒤따를로그", []).append(
        {
            "대상": 대상["이름"],
            "회복": 실회복,
            "비고": "속성 흡수",
            "종류": "비고",
        }
    )


def _흡혈_발동(전투상태, 흡혈자, 대상, 최종피해):
    """흡혈(2026-10-19 사용자 결정): 입힌 최종피해 x 흡혈% 만큼(올림, 최대HP까지) 회복한다.
    출혈에 걸린 대상이면 두 배. 중독에 걸린 대상이면 흡혈자가 내성굴림 없이 1턴간 1차수
    중독에 걸린다(타격마다). 로그는 "뒤따를로그"로 공격 줄 뒤에 붙인다. 피해_적용이 공격한
    참가자가 있을 때만 부른다 - 지속피해형(출혈/중독 등)은 공격자가 없어 흡혈하지 않는다."""
    흡혈 = 유효_흡혈(전투상태, 흡혈자)
    if 흡혈 <= 0 or 최종피해 <= 0 or not 흡혈자.get("생존", True):
        return
    배수 = 2 if status.상태이상_판정(전투상태, 대상, "출혈") else 1
    양 = -(-최종피해 * 흡혈 * 배수 // 100)  # 올림
    최대HP = formula.올림(stats.유효_최대HP(전투상태, 흡혈자))
    실회복 = max(0, min(양, 최대HP - 흡혈자["현재HP"]))
    흡혈자["현재HP"] += 실회복
    뒤 = 전투상태.setdefault("뒤따를로그", [])
    if 실회복 > 0:
        뒤.append(
            {
                "공격자": 흡혈자["이름"],
                "대상": 대상["이름"],
                "회복": 실회복,
                "비고": "흡혈",
                "종류": "비고",
            }
        )
    if status.상태이상_판정(전투상태, 대상, "중독"):
        if status.상태이상_면역(전투상태, 흡혈자, "중독"):
            return
        흡혈자.setdefault("상태이상", []).append(
            {"이름": "중독", "지속턴": 1, "중첩": 1, "차수": 1}
        )
        뒤.append(
            {
                "공격자": 흡혈자["이름"],
                "대상": 흡혈자["이름"],
                "비고": "흡혈 - '중독' 상태이상 부여",
                "종류": "비고",
            }
        )
    if not 뒤:
        전투상태.pop("뒤따를로그")


def 유효_펌블범위(전투상태, 공격자, 대상=None):
    """자동실패(펌블)가 나는 최대 d20 눈. 기본 1(참가자 "펌블범위")에 공격자의
    버프/디버프/특성 "펌블범위"(펌블확률증가 +1, 펌블확률감소 -1)와, 대상이 있으면
    대상의 "피격펌블범위"(피격펌블증가 +1, 피격펌블감소 -1 - 나를 공격하는 쪽의
    펌블 확률)를 더한다. 0이면 자연 1도 펌블이 아니다(0 아래로는 안 내려감).
    "치명타펌블연동" 특성(얀데레)이 있으면 치명타범위가 20에서 낮아진 만큼 더한다
    (유효_치명타범위를 그때그때 본다 - 버프/특성/마봉 모두)."""
    기본 = 공격자.get("펌블범위", 1)
    증감 = stats.버프디버프_수치(전투상태, 공격자, "펌블범위") + traits.특성_수치(
        전투상태, 공격자, "펌블범위"
    )
    if traits.특성_수치(전투상태, 공격자, "치명타펌블연동") > 0:
        증감 += 20 - 유효_치명타범위(전투상태, 공격자)
    if 대상 is not None:
        증감 += stats.버프디버프_수치(
            전투상태, 대상, "피격펌블범위"
        ) + traits.특성_수치(전투상태, 대상, "피격펌블범위")
    return max(0, formula.올림(기본 + 증감))


def 명중_판정(
    전투상태,
    공격자,
    대상,
    명중률종류,
    명중보너스=0,
    장비보너스=True,
    명중배수=1,
    명중이점=False,
):
    """명중_판정_계산()으로 판정한 뒤, 아군이 적의 공격을 받는 경우
    캐릭터 반응스킬(회피형 - 크라우치 등, 회피성공시 반격 - 백스텝커터/
    리벤저)을 적용한다(피격판정_반응 참고). 장비보너스=False면 장비 명중률보너스를
    더하지 않는다(투척 아이템 - 소모품은 장비 보너스를 받지 않는다). 명중배수는 명중 보정
    전체에 곱한다(원펀맨 - 굴림은 한 번). 명중이점은 스킬의 "명중이점"(이혼일섬 #332)."""
    판정 = 명중_판정_계산(
        전투상태,
        공격자,
        대상,
        명중률종류,
        명중보너스,
        장비보너스=장비보너스,
        명중배수=명중배수,
        명중이점=명중이점,
    )
    if 대상.get("진영") == "아군" and 공격자.get("진영") != "아군":
        판정 = reactions.가드_반응(전투상태, 공격자, 대상, 판정)
        판정 = reactions.피격판정_반응(전투상태, 공격자, 대상, 판정, 명중률종류)
    return 판정


def 명중_판정_계산(
    전투상태,
    공격자,
    대상,
    명중률종류,
    명중보너스=0,
    장비보너스=True,
    명중배수=1,
    명중이점=False,
):
    """명중률종류(job_skill_format.py 값, 또는 몬스터 패턴의 "OO판정")에
    따라 판정한다. 반환값: {"성공", "자연눈", "치명타", "자동실패"}.

    "대상"이 "피격시강제치명타" 상태면 명중률종류와 상관없이 항상
    명중+치명타로 처리한다. "대상"의 "회피불리점"은 공격자에게 이점을,
    "공격자"의 "명중불리점"은 공격자 본인에게 불리를 준다. 특성의 "명중이점"
    (공격자)은 이점을, "회피이점"(대상)은 공격자에게 불리를 준다(심안). 버프의 "명중이점"(공격자)과
    "회피불리점"(대상)도 공격자에게 이점을 준다(폭주)."""
    홀딩_정리(전투상태)  # 끊긴 홀딩의 이점이 남지 않게
    강제치명타 = status.상태이상_플래그(전투상태, 대상, "피격시강제치명타")

    if 명중률종류 == "자동":
        return {"성공": True, "자연눈": None, "치명타": 강제치명타, "자동실패": False}

    # 이점·불리점은 출처마다 하나씩 세어 많은 쪽 하나만 적용한다(같으면 없음 - 사용자 결정)
    이점수 = sum(
        (
            status.상태이상_플래그(전투상태, 대상, "회피불리점"),
            status.특성_플래그(전투상태, 공격자, "명중이점"),
            # 버프 "명중이점"(공격자)/"회피불리점"(대상) - 폭주(#247)
            bool(stats.버프_효과원소목록(전투상태, 공격자, "명중이점")),
            bool(stats.버프_효과원소목록(전투상태, 대상, "회피불리점")),
            명중이점,  # 스킬의 "명중이점"(이혼일섬 #332)
        )
    )
    불리수 = sum(
        (
            status.상태이상_플래그(전투상태, 공격자, "명중불리점"),
            status.특성_플래그(전투상태, 대상, "회피이점"),
        )
    )
    이점, 불리 = dice_utils.이점_합산(이점수, 불리수)
    눈 = dice_utils.d20_굴림(이점=이점, 불리=불리)
    치명타범위 = 유효_치명타범위(전투상태, 공격자)
    펌블범위 = 유효_펌블범위(전투상태, 공격자, 대상)
    # 최종 명중값과 대상 AC는 치명타/대실패로 정해지는 판정에도 담는다(전투 로그가 "값 vs AC"로 보여 준다)
    보정합 = _명중_보정합(전투상태, 공격자, 대상, 명중률종류, 명중보너스, 장비보너스)
    값 = {"명중결과": 눈 + 보정합 * 명중배수}
    값["대상AC"] = stats.최종AC(전투상태, 대상)
    if stats.상세로그(전투상태):  # [설정] 전투로그 "자세하게" - 계산 내역도 담는다
        값["명중내역"] = _명중_내역(
            전투상태,
            공격자,
            대상,
            명중률종류,
            명중보너스,
            눈,
            값["명중결과"],
            장비보너스,
            배수몫=보정합 * (명중배수 - 1),
        )
        값["AC내역"] = stats.AC_내역(전투상태, 대상)
    return _눈_판정(대상, 명중률종류, 눈, 값, 강제치명타, 치명타범위, 펌블범위)


def 불리점_재판정(전투상태, 공격자, 대상, 판정, 명중률종류):
    """이미 굴린 판정에 불리점을 준다(귀영보 #247) - d20을 한 번 더 굴려 낮은 눈으로 성공/치명타/대실패를
    다시 정한다. 명중결과는 보정 그대로 눈만 바꾼다. "불리점굴림"에 새로 굴린 눈을 남긴다."""
    새눈 = dice_utils.d20_굴림()
    눈 = min(판정["자연눈"], 새눈)
    값 = {
        k: v
        for k, v in 판정.items()
        if k not in ("성공", "자연눈", "치명타", "자동실패")
    }
    값["명중결과"] = 판정["명중결과"] - 판정["자연눈"] + 눈
    결과 = _눈_판정(
        대상,
        명중률종류,
        눈,
        값,
        status.상태이상_플래그(전투상태, 대상, "피격시강제치명타"),
        유효_치명타범위(전투상태, 공격자),
        유효_펌블범위(전투상태, 공격자, 대상),
    )
    return dict(결과, 불리점굴림=새눈)


def _눈_판정(대상, 명중률종류, 눈, 값, 강제치명타, 치명타범위, 펌블범위):
    """굴린 눈과 값(명중결과/대상AC 등)으로 성공·치명타·대실패를 정한다(명중_판정_계산의 마지막 단계)."""
    if 강제치명타:
        return {"성공": True, "자연눈": 눈, "치명타": True, "자동실패": False, **값}

    if 명중률종류 == "필중":
        return {
            "성공": True,
            "자연눈": 눈,
            "치명타": 눈 >= 치명타범위,
            "자동실패": False,
            **값,
        }

    if 눈 <= 펌블범위:
        return {"성공": False, "자연눈": 눈, "치명타": False, "자동실패": True, **값}
    if 대상.get("감옥") and 눈 < 치명타범위:  # 감옥(AC 1)은 대실패만 아니면 맞는다
        return {"성공": True, "자연눈": 눈, "치명타": False, "자동실패": False, **값}
    if 눈 >= 치명타범위:
        return {"성공": True, "자연눈": 눈, "치명타": True, "자동실패": False, **값}

    return {
        "성공": 값["명중결과"] >= 값["대상AC"],
        "자연눈": 눈,
        "치명타": False,
        "자동실패": False,
        **값,
    }


_보정치_이름 = {"보정명중률": "능력 보정", "주문시전명중률": "주문 보정"}


def _명중_내역(
    전투상태,
    공격자,
    대상,
    명중률종류,
    명중보너스,
    눈,
    명중결과,
    장비보너스=True,
    배수몫=0,
):
    """명중 굴림의 [(이름, 값)] - 주사위, 능력 보정, 기본/역할군/장비 명중률보너스, 출처별(버프/특성/칭호),
    스킬 명중보너스. 합은 명중결과(_명중_보정합과 같은 값, 남으면 "기타")."""
    내역 = [("주사위", 눈)]
    if 명중률종류 == "보정명중률":
        보정 = stats.평타_능력치_보정치(전투상태, 공격자)
    elif 명중률종류 == "주문시전명중률":
        보정 = stats.주문시전_보정치(전투상태, 공격자)
    elif isinstance(명중률종류, str) and 명중률종류.endswith("판정"):
        보정 = stats.유효_능력치_보정치(전투상태, 공격자, 명중률종류[:-2])
    else:
        보정 = 0
    이름 = _보정치_이름.get(명중률종류) or f"{str(명중률종류)[:-2]} 보정"
    기본 = 공격자["원본"].get("명중률보너스", 0)
    역할군 = (
        participants.몬스터_역할군_보너스(공격자["원본"], "명중률보너스")
        if 공격자["진영"] == "적"
        else 0
    )
    내역 += [
        (이름, 보정),
        ("기본 명중", 기본 if isinstance(기본, (int, float)) else 0),
        ("역할군", 역할군),
        ("장비", stats.장비_수치(공격자, "명중률보너스") if 장비보너스 else 0),
    ]
    내역 += stats.출처별_내역(
        전투상태, 공격자, "명중보너스", 명중률종류=명중률종류, 대상=대상
    )
    내역.append(("스킬", 명중보너스))
    내역.append(("원펀맨", 배수몫))  # 보정 전체 x 배수의 늘어난 몫
    return stats.기타_채우기([(n, v) for n, v in 내역 if v or n == "주사위"], 명중결과)


def 피해내역(전투상태, 공격자, 식, 굴림합, 합, 최종, 장비보너스=True):
    """자세한 로그용 피해 내역 - 데미지 수식과 굴린 값, 데미지보너스 출처(장비/버프/특성/칭호 - 그 밖은
    "기타"), 방어/속성 적용 전 합과 최종 피해. 상세로그가 아니면 None."""
    if not stats.상세로그(전투상태):
        return None
    추가 = [("장비", stats.장비_수치(공격자, "데미지보너스") if 장비보너스 else 0)]
    추가 += stats.출처별_내역(전투상태, 공격자, "데미지보너스")
    추가 = [(n, v) for n, v in 추가 if v]
    stats.기타_채우기(추가, 합 - 굴림합)
    return {"식": str(식), "굴림합": 굴림합, "추가": 추가, "합": 합, "최종": 최종}


def _명중_보정합(전투상태, 공격자, 대상, 명중률종류, 명중보너스, 장비보너스=True):
    """명중 굴림에 더하는 값 전부 - 능력치 보정치 + 명중률보너스(원본/역할군/장비/버프/특성/칭호)."""
    보정치 = 0
    if 명중률종류 == "보정명중률":
        보정치 = stats.평타_능력치_보정치(전투상태, 공격자)
    elif 명중률종류 == "주문시전명중률":
        보정치 = stats.주문시전_보정치(전투상태, 공격자)
    elif 명중률종류 == "기본명중률":
        보정치 = 0
    elif isinstance(명중률종류, str) and 명중률종류.endswith("판정"):
        보정치 = stats.유효_능력치_보정치(전투상태, 공격자, 명중률종류[:-2])

    명중률보너스 = 공격자["원본"].get("명중률보너스", 0)
    if not isinstance(명중률보너스, (int, float)):
        명중률보너스 = 0
    if 공격자["진영"] == "적":  # 몬스터 역할군(탱커 -1, 메이지 +1)
        명중률보너스 += participants.몬스터_역할군_보너스(
            공격자["원본"], "명중률보너스"
        )
    # 장비(전 부위+활성 세트) 명중률보너스 - 아군만, 투척 아이템을 뺀 모든 명중 굴림.
    if 장비보너스:
        명중률보너스 += stats.장비_수치(공격자, "명중률보너스")
    명중률보너스 += stats.버프디버프_수치(전투상태, 공격자, "명중보너스")
    명중률보너스 += traits.특성_수치(
        전투상태, 공격자, "명중보너스", 명중률종류=명중률종류, 대상=대상
    )
    명중률보너스 += traits.칭호_수치(전투상태, 공격자, "명중보너스")
    return 보정치 + 명중률보너스 + 명중보너스


def 최종피해_계산(원래피해, 방어력, 보호률):
    """비율(보호률) 감소를 먼저 적용하고, 고정(방어력) 감소를 나중에 뺀다.
    최종피해 = max(0, 원래피해 x (1-보호률) - 방어력)"""
    return max(0, formula.올림(원래피해 * (1 - 보호률) - 방어력))


