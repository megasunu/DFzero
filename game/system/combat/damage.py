def 경직_적용(전투상태, 대상, 태그=()):
    """경직(2026-10-20 사용자 결정) - 공격이 명중한 타격마다 맞은 대상의 이번 라운드 순서를 늦춘다.
    "잡기"·"경직" 태그 공격이면 우선도 -1, 그 밖의 공격이면 이니셔티브 -1. 슈퍼아머 상태(상태이상
    효과 "경직불가")나 특성 "경직불가"면 걸리지 않고, 특성 "잡기불가"는 "경직" 태그가 없는 "잡기"
    경직만 막는다. 아직 행동하지 않은 참가자(현재 차례 뒤)만 다시 줄 세우고, 다음 라운드에는
    flow.이니셔티브_재계산_및_정렬이 원래 값으로 되돌린다. 전투 기록에는 남기지 않는다."""
    if not 대상.get("생존") or status.상태이상_플래그(전투상태, 대상, "경직불가"):
        return
    if status.특성_플래그(전투상태, 대상, "경직불가"):
        return
    태그 = set(태그 or ())
    if "경직" in 태그:
        대상["우선도"] = 대상.get("우선도", 0) - 1
    elif "잡기" in 태그:
        if status.특성_플래그(전투상태, 대상, "잡기불가"):
            return
        대상["우선도"] = 대상.get("우선도", 0) - 1
    else:
        대상["이니셔티브"] -= 1
    남은_순서_정렬(전투상태)


def _순서키(p):
    return (p.get("우선도", 0), p["이니셔티브"])


def 남은_순서_정렬(전투상태):
    """현재 차례 뒤의 참가자만 (우선도, 이니셔티브) 내림차순으로 다시 세운다(같으면 원래 순서).
    이미 행동한 참가자와 지금 행동 중인 참가자의 자리는 그대로다 - 다만 이미 행동한 참가자가
    홀딩에 걸려 있고 경직으로 지금 참가자보다 순서가 낮아졌으면 뒤로 옮겨 "홀딩차례"를 단다.
    그 차례에는 홀딩 피해만 들어간다(flow.다음_턴, 2026-10-20 사용자 결정)."""
    참가자 = 전투상태["참가자"]
    현재 = 전투상태.get("현재턴", 0)
    if not 참가자 or 현재 >= len(참가자):
        return
    지금 = 참가자[현재]
    옮김 = [
        p
        for p in 참가자[:현재]
        if p["생존"]
        and not p.get("홀딩차례")
        and 홀딩_목록(p)
        and _순서키(p) < _순서키(지금)
    ]
    for p in 옮김:
        p["홀딩차례"] = True
    앞 = [p for p in 참가자[:현재] if not any(p is q for q in 옮김)]
    뒤 = sorted(참가자[현재 + 1 :] + 옮김, key=_순서키, reverse=True)
    참가자[:] = 앞 + [지금] + 뒤
    전투상태["현재턴"] = len(앞)


