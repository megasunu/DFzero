def 유효_흡혈(전투상태, 참가자):
    """입힌 피해의 1%당 회복하는 "흡혈" - 버프/디버프/특성과 장비의 합(기본 0, 0 아래는 0)."""
    값 = (
        stats.버프디버프_수치(전투상태, 참가자, "흡혈")
        + traits.특성_수치(전투상태, 참가자, "흡혈")
        + stats.장비_수치(참가자, "흡혈")
    )
    return max(0, 값)


def _부자유친(전투상태, 공격측, 대상, 최종피해):
    """포켓몬 특성 부자유친(특성 "공격후추가피해비율") - 공격 피해(타격마다)의 그 비율(1/4, 올림)만큼 추가 피해.
    명중굴림·치명타·추가 효과가 없다 - 공격한 참가자 없이 그대로 깎는다(방어·속성 없음, 다시 붙지 않음)."""
    비율 = sum(
        v
        for v in status.특성_변동값목록(전투상태, 공격측, "공격후추가피해비율")
        if isinstance(v, (int, float))
    )
    if 비율 <= 0 or 최종피해 <= 0 or 대상["현재HP"] <= 0:
        return
    추가 = formula.올림(최종피해 * 비율)
    실제 = 피해_적용(전투상태, 대상, 추가, 피해감소무시=True)
    전투상태.setdefault("뒤따를로그", []).append(
        {
            "공격자": 공격측["이름"],
            "대상": 대상["이름"],
            "피해": 실제,
            "비고": "부자유친",
            "종류": "비고",
        }
    )


@contextlib.contextmanager
def 몹몰이_공격대상(전투상태, 대상들):
    """한 공격이 함께 치는 대상들 - 그동안 이들끼리는 몹몰이 연결 피해를 주고받지 않는다(몹몰이_연결)."""
    이전 = 전투상태.get("몹몰이공격대상")
    전투상태["몹몰이공격대상"] = [p.get("id") for p in 대상들]
    try:
        yield
    finally:
        if 이전 is None:
            전투상태.pop("몹몰이공격대상", None)
        else:
            전투상태["몹몰이공격대상"] = 이전


def 몹몰이_연결(전투상태, 공격측, 대상, 최종피해):
    """몹몰이 - 몹몰이인 대상이 공격 피해를 받으면 같은 편의 다른 몹몰이도 그만큼 받는다(방어·속성 없이,
    다시 잇지 않는다). 지금 공격이 함께 치는 대상(전투상태["몹몰이공격대상"] - id)은 빼서 겹치지 않는다."""
    if 최종피해 <= 0 or not status.상태이상_판정(전투상태, 대상, "몹몰이"):
        return
    함께 = 전투상태.get("몹몰이공격대상") or ()
    for p in 전투상태["참가자"]:
        if (
            p is 대상
            or not p["생존"]
            or p["진영"] != 대상["진영"]
            or p.get("id") in 함께
            or not status.상태이상_판정(전투상태, p, "몹몰이")
        ):
            continue
        실제 = 피해_적용(전투상태, p, 최종피해, 피해감소무시=True)
        전투상태.setdefault("뒤따를로그", []).append(
            {
                "공격자": 공격측["이름"],
                "대상": p["이름"],
                "피해": 실제,
                "비고": f"몹몰이 - {대상['이름']}와(과) 함께",
                "종류": "비고",
            }
        )


def _속성흡수량(전투상태, 대상, 부분들):
    """포켓몬 흡수 특성(마중물/타오르는불꽃/피뢰침/정의의마음) - 특성 "속성흡수"에 든 속성으로 들어온 피해(속성
    배율 전, 올림)의 합. 그 속성은 면역이라 피해는 0이고 이만큼 회복한다."""
    흡수속성 = {
        element.속성_정식명(s)
        for s in traits.캐릭터특성_문자열값(전투상태, 대상, "속성흡수")
    }
    if not 흡수속성:
        return 0
    return sum(
        formula.올림(max(0, 값))
        for 값, s in 부분들
        if s is not None and element.속성_정식명(s) in 흡수속성
    )


def _속성흡수_회복(전투상태, 대상, 양):
    최대HP = formula.올림(stats.유효_최대HP(전투상태, 대상))
    실회복 = max(0, min(양, 최대HP - 대상["현재HP"]))
    대상["현재HP"] += 실회복
    # HP가 가득이어도 남긴다 - 면역으로 피해가 0이 된 까닭을 보여 준다
    전투상태.setdefault("뒤따를로그", []).append(
        {
            "대상": 대상["이름"],
            "회복": 실회복,
            "비고": "속성 흡수",
            "종류": "비고",
        }
    )


def _흡혈_발동(전투상태, 흡혈자, 대상, 최종피해):
    """흡혈: 입힌 최종피해 x 흡혈% 만큼(올림, 최대HP까지) 회복한다.
    출혈에 걸린 대상이면 두 배. 중독에 걸린 대상이면 흡혈자가 내성굴림 없이 1턴간 1차수
    중독에 걸린다(타격마다). 로그는 "뒤따를로그"로 공격 줄 뒤에 붙인다. 피해_적용이 공격한
    참가자가 있을 때만 부른다 - 지속피해형(출혈/중독 등)은 공격자가 없어 흡혈하지 않는다."""
    흡혈 = 유효_흡혈(전투상태, 흡혈자)
    if 흡혈 <= 0 or 최종피해 <= 0 or not 흡혈자.get("생존", True):
        return
    배수 = 2 if status.상태이상_판정(전투상태, 대상, "출혈") else 1
    양 = -(-최종피해 * 흡혈 * 배수 // 100)  # 올림
    최대HP = formula.올림(stats.유효_최대HP(전투상태, 흡혈자))
    실회복 = max(0, min(양, 최대HP - 흡혈자["현재HP"]))
    흡혈자["현재HP"] += 실회복
    뒤 = 전투상태.setdefault("뒤따를로그", [])
    if 실회복 > 0:
        뒤.append(
            {
                "공격자": 흡혈자["이름"],
                "대상": 대상["이름"],
                "회복": 실회복,
                "비고": "흡혈",
                "종류": "비고",
            }
        )
    if status.상태이상_판정(전투상태, 대상, "중독"):
        if status.상태이상_면역(전투상태, 흡혈자, "중독"):
            return
        흡혈자.setdefault("상태이상", []).append(
            {"이름": "중독", "지속턴": 1, "중첩": 1, "차수": 1}
        )
        뒤.append(
            {
                "공격자": 흡혈자["이름"],
                "대상": 흡혈자["이름"],
                "비고": "흡혈 - '중독' 상태이상 부여",
                "종류": "비고",
            }
        )
    if not 뒤:
        전투상태.pop("뒤따를로그")


def 피해내역(
    전투상태,
    공격자,
    식,
    굴림합,
    합,
    최종,
    앞항목=(),
    장비=0,
    대상=None,
    명중률종류=None,
    속성=None,
    스킬타입=None,
    배수=1,
):
    """자세한 로그용 피해 내역 - 데미지 수식과 굴린 값, 데미지보너스 출처, 방어/속성 적용 전 합과 최종 피해.
    출처는 부르는 쪽이 계산한 앞항목 [(이름, 값)](스킬/역할군/추가피해 굴림 등)과 장비 값, 그리고 출처별
    버프/특성/칭호(명중률종류/대상/속성/스킬타입 조건 반영 - 피해 계산과 같은 인수를 넘긴다). 배수(원펀맨)는
    장비·출처 몫에 곱하는 늘어난 몫을 따로 적는다. 그래도 남으면 "기타". 상세로그가 아니면 None."""
    if not stats.상세로그(전투상태):
        return None
    출처 = [("장비", 장비)] + stats.출처별_내역(
        전투상태,
        공격자,
        "데미지보너스",
        명중률종류=명중률종류,
        대상=대상,
        속성=속성,
        스킬타입=스킬타입,
    )
    추가 = list(앞항목) + 출처 + [("원펀맨", (배수 - 1) * sum(v for _, v in 출처))]
    추가 = [(n, v) for n, v in 추가 if v]
    stats.기타_채우기(추가, 합 - 굴림합)
    return {"식": str(식), "굴림합": 굴림합, "추가": 추가, "합": 합, "최종": 최종}


def 최종피해_계산(원래피해, 방어력, 보호률):
    """비율(보호률) 감소를 먼저 적용하고, 고정(방어력) 감소를 나중에 뺀다. 보호률 1당 10% - 출처끼리 더한다.
    최종피해 = max(0, 원래피해 x (1-보호률/10) - 방어력)"""
    return max(0, formula.올림(원래피해 * (1 - 보호률 / 10) - 방어력))


def _피해_부분들(전투상태, 공격측, 대상, 피해량, 속성, 추가피해목록, 무시):
    """피해_적용의 (부분들, 관통부분들, 흡수량) - 부분마다 (저항/취약/면역 반영 값, 속성). 방어를 무시하는
    추가피해(철갑탄)는 관통부분들로 따로 모은다(_관통_최종피해)."""
    부분들 = [(피해량 * element.피해_속성배율(전투상태, 대상, 속성, 무시), 속성)]
    흡수 = _속성흡수량(전투상태, 대상, [(피해량, 속성)])
    관통부분들 = []
    for 추가값, 추가속성, *관통 in 추가피해목록 or []:
        추가속성 = element.주속성(전투상태, 공격측, 대상, 추가속성)
        if 관통 and 관통[0]:
            관통부분들.append(
                (
                    추가값 * element.피해_속성배율(전투상태, 대상, 추가속성, True),
                    추가속성,
                )
            )
            continue
        부분들.append(
            (추가값 * element.피해_속성배율(전투상태, 대상, 추가속성, 무시), 추가속성)
        )
        흡수 += _속성흡수량(전투상태, 대상, [(추가값, 추가속성)])
    return 부분들, 관통부분들, 흡수


def _관통_최종피해(전투상태, 공격측, 대상, 부분들):
    """방어를 무시하는 추가피해(철갑탄)의 최종피해 - 위상력처럼 양수 보호율·속성저항·속성내성은 무시하고
    음수(피해를 키우는 값)는 그대로 쓴다. 방어력은 본 피해 쪽에 이미 한 번 적용했으므로 여기서는 뺀다."""
    피해량 = sum(값 for 값, _ in 부분들)
    if 피해량 <= 0:
        return 0
    최종피해 = 최종피해_계산(피해량, 0, min(0, stats.유효_보호률(전투상태, 대상)))
    return max(
        0,
        formula.올림(
            sum(
                최종피해
                * (값 / 피해량)
                * element.속성_최종배율(전투상태, 공격측, 대상, s, True)
                for 값, s in 부분들
            )
        ),
    )


def 양옆_이웃(전투상태, 대상):
    """대상 바로 양옆 칸의 살아 있는 같은 편(범위공격의 좌우 1체씩). 같은 편 전체(생존 무관)를 "대형위치" 순으로
    나열해 바로 옆 칸만 본다 - 중간에 죽은 참가자가 있어도 대열이 당겨지지 않고, 옆 칸이 죽었으면 빈다."""
    같은편전체 = sorted(
        (p for p in 전투상태["참가자"] if p["진영"] == 대상["진영"]),
        key=lambda p: p.get("대형위치", 0),
    )
    if 대상 not in 같은편전체:
        return []
    idx = 같은편전체.index(대상)
    return [
        같은편전체[i]
        for i in (idx - 1, idx + 1)
        if 0 <= i < len(같은편전체) and 같은편전체[i]["생존"]
    ]


def _피격_감소(전투상태, 공격자, 공격측, 대상, 최종피해, 피해감소무시):
    """적에게 받는 피해를 HP에 넣기 직전에 줄인다 - "피격시" 반응스킬(건가드/위상 변화, 공격자가 있을 때만),
    그다음 남은 피해에 오라 실드(지속피해 등 피해감소무시는 제외)."""
    if (
        공격자 is not None
        and 대상.get("진영") == "아군"
        and 공격자.get("진영") != "아군"
        and 최종피해 > 0
    ):
        최종피해 = reactions.피격피해_반응(전투상태, 공격자, 대상, 최종피해)
    if (
        not 피해감소무시
        and 공격측 is not None
        and 공격측.get("진영") != 대상.get("진영")
    ):
        최종피해 = traits.MP피해감소_적용(전투상태, 대상, 최종피해)
    return 최종피해


def 피해_적용(
    전투상태,
    대상,
    피해량,
    *,
    피해감소무시=False,
    방어력무시=False,
    속성=None,
    공격자=None,
    추가피해목록=None,
    공격측=None,
    최종피해배율=1,
    공격타입=None,
    공격분류=(),
):
    """방어력/보호률을 적용해 최종 피해를 계산하고 대상 HP에서 뺀다.
    피해감소무시=True면 방어력/보호률 자체를 무시한다(출혈 등 지속피해용).

    속성이 주어지면 대상["원본"]의 "저항"/"취약"(및 특성이 부여하는
    저항/취약 - 예: 종족:좀비)을 확인해 절반(저항)/2배(취약)로
    조정한다(둘 다 있으면 상쇄). 속성이 리스트면(예: 굴 구위시의
    ["무속성", "수속성", "암속성"]) 각 속성으로 계산했을 때 나오는
    배율 중 가장 큰 쪽을 쓴다("속성이 여러 개면 더 높은 데미지 쪽
    속성으로 공격한다" - 속성 다중판정의 기본 설정).
    속성=None(지속피해형 등 속성 정보가 없는 경우)이면 이 조정을
    받지 않는다.

    공격자: 적의 공격/능력으로 아군이 피해를 받으면 넘긴다 -
    그때만 "피격시" 반응스킬(건가드/위상 변화)을 적용한다(피격피해_반응).
    지속피해 등 공격자가 없는 피해는 반응 대상이 아니다.

    추가피해목록: [(값, 속성[, 방어무시]), ...] - 공격 속성과 따로 자기
    속성으로 저항/취약을 적용한 뒤 본 피해에 더한다(장전 탄의 추가피해).
    방어력/보호률은 합친 피해에 한 번만 적용한다. 방어무시가 참이면(철갑탄) 그 부분은
    _관통_최종피해로 따로 계산해 더한다.

    면역 속성이면 그 속성 피해는 0. 속성강화(공격측 - 없으면 공격자)/속성내성(대상)은
    방어력/보호률 뒤의 최종피해에 곱한다(속성_최종배율). 추가피해가 있으면 최종피해를
    부분(저항/취약 반영 후) 비율로 나눠 부분마다 자기 속성의 배율을 곱한다.
    공격측: 반응스킬 없이 속성강화만 볼 공격한 참가자(아군 공격 등).
    최종피해배율: 스킬강화(레벨 12)의 배율 - 속성 배율 뒤 최종피해에 곱한다(올림).
    공격타입: 타격의 "공격타입"(관통/참격 등) - 대상의 저항/취약/면역에 그 이름이 있으면 본 피해에
    속성과 같은 배율이 붙는다(종족:골렘의 관통·참격 저항). 추가피해목록에는 안 붙는다.
    공격분류: stats.공격_분류("무기공격"/"주사위공격") - 공격타입처럼 대상의 저항/취약/면역 배율이 붙는다(챔피언
    이뮨-물리·마법, 강화-물리·마법방어). 둘 다면 대상에게 유리한(작은) 배율 하나."""
    공격측 = 공격측 or 공격자
    무효사유 = (
        control.피해무효_사유(전투상태, 대상)
        if 공격측 is not None and 공격측.get("진영") != 대상.get("진영")
        else None
    )
    if 무효사유:
        core.로그(
            전투상태,
            {
                "공격자": 공격측["이름"],
                "대상": 대상["이름"],
                "비고": f"{무효사유} - 피해 무효",
            },
            종류="비고",
        )
        return 0
    속성 = element.주속성(전투상태, 공격측, 대상, 속성)
    무시 = element.방어무시(전투상태, 공격측) and 공격측.get("진영") != 대상.get("진영")
    피해량 *= element.공격타입_피해배율(전투상태, 대상, 공격타입, 무시)
    피해량 *= element.공격분류_피해배율(전투상태, 대상, 공격분류, 무시)
    # (저항/취약/면역 반영 값, 속성) - 속성마다 따로 계산하고 방어는 합에 한 번
    부분들, 관통부분들, 흡수 = _피해_부분들(
        전투상태, 공격측, 대상, 피해량, 속성, 추가피해목록, 무시
    )
    피해량 = sum(값 for 값, _ in 부분들)

    if 피해감소무시:
        최종피해 = max(0, formula.올림(피해량))
    else:
        방어력 = (
            0
            if 방어력무시
            else stats.유효_방어력(전투상태, 대상)
            + traits.공격타입_방어력(전투상태, 대상, 공격타입)
            + traits.속성_방어력(전투상태, 대상, 속성)
        )
        보호률 = stats.유효_보호률(전투상태, 대상)
        if 무시:  # 위상력 - 양수만 무시, 약해져 음수인 값은 그대로
            방어력, 보호률 = min(0, 방어력), min(0, 보호률)
        최종피해 = 최종피해_계산(피해량, 방어력, 보호률)
    if 피해량 > 0 and any(s is not None for _, s in 부분들):
        # 속성강화/속성내성은 방어 뒤 최종피해를 부분 비율로 나눠 각자 속성으로 곱한다
        최종피해 = max(
            0,
            formula.올림(
                sum(
                    최종피해
                    * (값 / 피해량)
                    * (
                        1
                        if s is None
                        else element.속성_최종배율(전투상태, 공격측, 대상, s, 무시)
                    )
                    for 값, s in 부분들
                )
            ),
        )
    if 관통부분들:
        최종피해 += _관통_최종피해(전투상태, 공격측, 대상, 관통부분들)
    if 최종피해배율 != 1:
        최종피해 = max(0, formula.올림(최종피해 * 최종피해배율))
    최종피해 = _받는피해배율_적용(전투상태, 대상, 최종피해)

    최종피해 = _피격_감소(전투상태, 공격자, 공격측, 대상, 최종피해, 피해감소무시)

    # 아군 공용 임시생명력(넨가드), 그다음 임시생명력이 현재HP보다 먼저 깎인다. 반환값(최종피해)은
    # 이 공격이 입힌 총 피해 그대로다 - 실제로 현재HP에서 빠지는 양만
    # 이것들이 흡수한 만큼 줄어든다.
    실HP피해 = 버프임시생명력_흡수(
        대상, 공용임시생명력_흡수(전투상태, 대상, 최종피해, 공격측), 전투상태
    )
    실HP피해 = resources.설치임시생명력_흡수(전투상태, 대상, 실HP피해)  # 카운트다운
    임시생명력 = 대상.get("임시생명력", 0)
    if 임시생명력 > 0:
        흡수량 = min(임시생명력, 실HP피해)
        대상["임시생명력"] = 임시생명력 - 흡수량
        실HP피해 -= 흡수량

    출혈중첩 = sum(
        항목.get("중첩", 1)
        for 항목 in 대상.get("상태이상") or []
        if 항목.get("이름") == "출혈"
    )
    전HP = 대상["현재HP"]
    _HP_깎기(대상, 실HP피해)
    _넘친피해_기록(전투상태, 대상, 실HP피해, 전HP)
    traits.체력_임시생명력(
        전투상태, 대상
    )  # 체력 절반 이하에서 임시생명력(특수패턴:지그하르트)
    if 흡수 > 0 and 대상["현재HP"] > 0:
        _속성흡수_회복(전투상태, 대상, 흡수)
    if (
        공격자 is not None
        and 최종피해 > 0
        and 대상["현재HP"] > 0
        and 공격자.get("진영") != 대상.get("진영")
    ):
        # 공격자의 "속성피해시" 몬스터특성(알비노 고블린 - 명속성 피해를 주면 감전, 쓰러진 대상 제외)
        traits.특성_속성피해시_발동(
            전투상태, 공격자, 대상, [s for _, s in 부분들 if s is not None]
        )
    if 공격측 is not None and 공격측.get("진영") != 대상.get("진영"):
        _흡혈_발동(전투상태, 공격측, 대상, 최종피해)
        _부자유친(전투상태, 공격측, 대상, 최종피해)
        몹몰이_연결(전투상태, 공격측, 대상, 최종피해)
    _폭주_검사(전투상태, 대상)
    _부활(전투상태, 대상)  # 되살아나면 HP가 차 아래 쓰러짐 처리를 건너뛴다
    if 대상["현재HP"] <= 0:
        if 대상.get(
            "생존"
        ):  # 이번 피해로 쓰러졌다 - 다음 전투 로그에 붙는다(core.로그)
            전투상태.setdefault("쓰러짐대기", []).append(대상["이름"])
            if 공격측 is not None and 공격측.get("진영") != 대상.get("진영"):
                _출혈처치_회복(전투상태, 공격측, 대상, 출혈중첩)
                _오라헌터_처치(전투상태, 공격측, 대상)
        대상["생존"] = False
        status.사망시_해제(전투상태, 대상)  # 암전
        resources.설치임시생명력_제거(전투상태, 대상)
        # 감옥이 부서지면 갇힌 사람이 풀리고, 갇힌 사람이 쓰러지면 감옥도 사라진다(벌칙 없음)
        감옥 = 대상 if 대상.get("감옥") else status.살아있는_감옥(전투상태, 대상)
        if 감옥 is not None:
            status.감옥_풀기(전투상태, 감옥)
    나선의넨_반격(전투상태, 대상, 공격자)
    reactions.피격설치_반응(전투상태, 대상, 공격자, 최종피해)  # 회심의 랜드러너
    return 최종피해


def _부활(전투상태, 대상):
    """챔피언 기타-부활 - 처음 쓰러질 때 한 번 최대체력으로 되살아난다. 되살아났으면 True."""
    if (
        대상["현재HP"] > 0
        or not 대상.get("생존")
        or 대상.get("부활함")
        or not status.특성_플래그(전투상태, 대상, "부활")
    ):
        return False
    대상["부활함"] = True
    대상["현재HP"] = formula.올림(stats.유효_최대HP(전투상태, 대상))
    core.로그(
        전투상태,
        {"공격자": 대상["이름"], "비고": "부활했다!", "회복": 대상["현재HP"]},
        종류="비고",
    )
    return True


def _폭주_검사(전투상태, 대상):
    """챔피언 폭주 - HP가 처음 최대의 절반 이하가 되면(쓰러지지 않고) 보너스 턴 대기에 넣는다.
    대기는 그 차례가 끝날 때(flow.턴_종료_처리) 몬스터 차례 한 번으로 쓴다."""
    if (
        not 대상.get("생존")
        or 대상["현재HP"] <= 0
        or 대상.get("폭주함")
        or 대상["현재HP"] * 2 > stats.유효_최대HP(전투상태, 대상)
        or not status.특성_플래그(전투상태, 대상, "폭주보너스턴")
    ):
        return
    대상["폭주함"] = True
    전투상태.setdefault("보너스턴대기", []).append(대상["이름"])


def 나선의넨_반격(전투상태, 대상, 공격자):
    """켜진 특성의 "피격반격"(나선의 넨) - 살아 있는 아군이 적에게 맞으면 그 적에게 원소 "명중률"로 굴려
    맞으면 "데미지"를 "피해속성"으로 준다. 반격마다 참가자 "피격반격스택"을 1 쓴다 - 칸이 없으면(전투 시작, 전투 중에
    켬) "최대스택"이다. 자기 턴마다 1씩 찬다(나선의넨_스택_충전)."""
    if (
        공격자 is None
        or 대상.get("진영") != "아군"
        or 공격자.get("진영") != "적"
        or not 대상["생존"]
        or not 공격자["생존"]
    ):
        return
    for 원소 in traits.캐릭터특성_무기효과(전투상태, 대상, "피격반격"):
        스택 = 대상.get("피격반격스택", 원소.get("최대스택", 1))
        if 스택 <= 0 or not 공격자["생존"]:
            return
        대상["피격반격스택"] = 스택 - 1
        판정 = hit.명중_판정(전투상태, 대상, 공격자, 원소.get("명중률", "자동"))
        속성 = 원소.get("피해속성")
        element.공격연출_기록(전투상태, 공격자, 판정, 속성, "마법")
        피해 = 0
        if 판정["성공"]:
            굴림 = formula.수식_평가(
                원소["데미지"], stats.기본_컨텍스트(전투상태, 대상)
            )
            피해 = 피해_적용(전투상태, 공격자, max(0, 굴림), 속성=속성, 공격측=대상)
        core.로그(
            전투상태,
            {
                "공격자": 대상["이름"],
                "대상": 공격자["이름"],
                "판정": 판정,
                "피해": 피해,
                "비고": "나선의 넨 반격" + ("" if 판정["성공"] else " - 빗나감"),
            },
            종류="비고",
        )


def 나선의넨_스택_충전(전투상태, 참가자):
    """자기 턴 시작에 "피격반격스택"을 1 채운다("최대스택"까지 - 나선의 넨).
    칸이 없으면 이미 최대라 그대로 둔다."""
    if "피격반격스택" not in 참가자:
        return
    for 원소 in traits.캐릭터특성_무기효과(전투상태, 참가자, "피격반격"):
        참가자["피격반격스택"] = min(
            원소.get("최대스택", 1), 참가자["피격반격스택"] + 1
        )
        return


def 버프임시생명력_흡수(대상, 피해, 전투상태=None):
    """대상 자신의 버프 인스턴스 "임시생명력"(신성한 빛/완충모듈 - skill_run이 채운다)이 피해를 먼저
    흡수한다. 다 닳으면 그 버프가 사라지고, 버프가 지속턴으로 사라지면 남은 임시생명력도 같이 사라진다.
    흡수하고 남은 피해를 돌려준다."""
    for 항목 in list(대상.get("버프") or []):
        남은 = 항목.get("임시생명력")
        if 남은 is None or 피해 <= 0:
            continue
        if 전투상태 is not None and core.꺼진_효과(전투상태, 대상, 항목):
            continue  # 버퍼의 버프를 끈 전투
        흡수 = min(남은, 피해)
        피해 -= 흡수
        항목["임시생명력"] = 남은 - 흡수
        if 항목["임시생명력"] <= 0:
            대상["버프"].remove(항목)
    return 피해


def 공용임시생명력_흡수(전투상태, 대상, 피해, 공격측=None):
    """같은 진영 참가자의 버프 인스턴스 "공용임시생명력"(넨가드 - skill_run이 채운다)이 그 진영 누가 맞든
    적의 공격 피해를 먼저 흡수한다 - 공격한 쪽이 없는 피해(지속피해)와 같은 진영(파티원·인형·시전자 자신)이 준
    피해는 막지 않는다. 다 닳으면 그 버프가 사라진다. 채널링이 풀렸으면(시전자가
    쓰러짐·무력화CC) 먼저 지운다(채널링_정리). 흡수하고 남은 피해를 돌려준다."""
    if 공격측 is None or 공격측.get("진영") == 대상.get("진영"):
        return 피해
    channeling.채널링_정리(전투상태)
    for 참가자 in 전투상태["참가자"]:
        if 피해 <= 0:
            break
        if 참가자.get("진영") != 대상.get("진영") or not 참가자.get("생존"):
            continue
        for 항목 in list(참가자.get("버프") or []):
            남은 = 항목.get("공용임시생명력")
            if 남은 is None or 피해 <= 0:
                continue
            if core.꺼진_효과(
                전투상태, 대상, 항목
            ):  # 끈 버퍼의 넨가드는 남을 막지 않는다
                continue
            흡수 = min(남은, 피해)
            피해 -= 흡수
            항목["공용임시생명력"] = 남은 - 흡수
            if 항목["공용임시생명력"] <= 0:
                참가자["버프"].remove(항목)
    return 피해


def _넘친피해_기록(전투상태, 대상, 실HP피해, 전HP):
    """체력에 들어간 피해 중 실제로 깎이지 못한 몫(쓰러뜨리고 남은 피해, 쓰러짐방지·불사로 1에서 멈춘 몫)을
    "넘친피해대기"({대상이름: 양})에 더한다 - core.로그가 다음 항목의 "넘친피해"로 붙인다(피해 집계가 뺀다)."""
    깎인 = max(0, 전HP) - max(0, 대상["현재HP"])
    넘친 = 실HP피해 - max(0, 깎인)
    if 넘친 > 0:
        대기 = 전투상태.setdefault("넘친피해대기", {})
        대기[대상["이름"]] = 대기.get(대상["이름"], 0) + 넘친


def _HP_깎기(대상, 양):
    """현재HP를 양만큼 깎는다 - 1 이하로 떨어지면 "쓰러짐방지" 버프(사무치는 광기)가 한 번 막는다."""
    대상["현재HP"] = max(min(대상["현재HP"], 0), 대상["현재HP"] - 양)
    if 양 > 0 and 대상["현재HP"] < 1 and _불사인가(대상):
        대상["현재HP"] = 1  # 불사(제아봉침) - 쓰러짐방지를 쓰지 않는다
    elif 양 > 0 and 대상["현재HP"] <= 1 and _쓰러짐방지_소모(대상):
        대상["현재HP"] = 1


def _불사인가(참가자):
    """버프 효과에 {"변동대상": "불사"}가 있나 - HP가 1 아래로 내려가지 않는다."""
    for 항목 in 참가자.get("버프") or []:
        효과 = (resources.효과정의_조회(항목.get("이름"))[0] or {}).get("효과")
        for 원소 in [효과] if isinstance(효과, dict) else 효과 or []:
            if isinstance(원소, dict) and 원소.get("변동대상") == "불사":
                return True
    return False


def _쓰러짐방지_소모(참가자):
    """버프 정의에 "쓰러짐방지"(사무치는 광기)가 있는 버프 하나를 지우고 True. 없으면 False -
    HP가 1 이하로 떨어질 피해를 한 번 막는다(HP 1로 남김)."""
    목록 = 참가자.get("버프") or []
    for 항목 in 목록:
        정의, _ = resources.효과정의_조회(항목.get("이름"))
        if (정의 or {}).get("쓰러짐방지"):
            목록.remove(항목)
            return True
    return False


def 체력_소모(전투상태, 참가자, 양):
    """스킬 비용/특성으로 스스로 HP를 깎는다(혈기왕성·프렌지) - 피해가 아니라 방어·반응을 받지 않고
    HP는 1 아래로 내려가지 않는다. 실제로 깎인 양을 돌려준다."""
    전 = 참가자["현재HP"]
    참가자["현재HP"] = max(min(전, 1), 전 - max(0, 양))
    return 전 - 참가자["현재HP"]


def _받는피해배율_적용(전투상태, 대상, 피해):
    """대상 특성 "받는피해배율"(라키우스 분신 2배)을 최종피해에 곱한다(올림)."""
    for 배율 in status.특성_변동값목록(전투상태, 대상, "받는피해배율"):
        피해 = max(0, formula.올림(피해 * 배율))
    return 피해


def _오라헌터_처치(전투상태, 공격측, 대상):
    """공격측의 특성 "처치시오라강화"(오라헌터 시우스) - 쓰러뜨린 대상이 내던 오라 하나마다 그 버프 목록에서
    하나를 무작위로 얻는다(지속턴 없음 - 전투 끝까지, 겹친다)."""
    목록 = traits.특성_항목(전투상태, 공격측, "처치시오라강화")
    if not 목록 or not 공격측.get("생존", True):
        return
    얻음 = [rng.대상.choice(목록) for _ in range(stats.낸_오라_수(대상))]
    for 이름 in 얻음:
        resources.몬스터_버프_부여(전투상태, 공격측, 이름, None)
    if 얻음:
        core.로그(
            전투상태,
            {
                "공격자": 공격측["이름"],
                "대상": 공격측["이름"],
                "비고": f"오라를 내던 {대상['이름']}을(를) 쓰러뜨려 {', '.join(얻음)}",
            },
            종류="비고",
        )


def _출혈처치_회복(전투상태, 공격측, 대상, 출혈중첩):
    """공격측의 특성 "출혈처치회복"(프렌지) - 출혈인 적을 쓰러뜨리면 "회복" 식("출혈중첩")만큼
    최대HP까지 회복한다."""
    if 공격측 is None or 출혈중첩 <= 0 or not 공격측.get("생존", True):
        return
    for 원소 in traits.캐릭터특성_무기효과(전투상태, 공격측, "출혈처치회복"):
        식 = str(원소.get("회복", "0")).replace("출혈중첩", str(출혈중첩))
        양 = formula.올림(formula.수식_평가(식, stats.기본_컨텍스트(전투상태, 공격측)))
        최대HP = formula.올림(stats.유효_최대HP(전투상태, 공격측))
        회복 = max(0, min(양, 최대HP - 공격측["현재HP"]))
        공격측["현재HP"] += 회복
        core.로그(
            전투상태,
            {
                "공격자": 공격측["이름"],
                "대상": 공격측["이름"],
                "비고": f"출혈인 {대상['이름']}을(를) 쓰러뜨려 HP {회복} 회복",
            },
            종류="비고",
        )


