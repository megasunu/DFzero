# 스킬 "타입"에 "채널링"이 있으면 시전자에게 건 버프 인스턴스에 "채널링"(과 쓴 턴 표시 "채널링시전턴")을
# 적는다(skill_run). 시전자의 다음 턴이 끝나면 사라지고, 그 턴에 다른 행동을 하면 바로 풀린다(쓴 턴의 다른
# 행동은 괜찮다). 시전자가 쓰러지거나 무력화CC에 걸려도 풀린다. 다음 턴 시작에 화면이 유지할지 묻는다
# (ctl_battle.채널링_확인대기/채널링_선택 - 묻고 나면 "채널링확인").


def _채널링_해제(전투상태, 참가자, 항목, 까닭):
    참가자["버프"].remove(항목)
    core.로그(
        전투상태,
        {
            "공격자": 참가자["이름"],
            "대상": 참가자["이름"],
            "비고": f"'{항목['이름']}' 채널링이 풀렸다({까닭}).",
        },
        종류="비고",
    )


def 채널링_목록(참가자):
    return [b for b in 참가자.get("버프") or [] if b.get("채널링")]


def 채널링_정리(전투상태):
    """시전자가 쓰러졌거나 무력화CC에 걸린 채널링을 푼다."""
    for 참가자 in 전투상태["참가자"]:
        if not 채널링_목록(참가자):
            continue
        까닭 = (
            "쓰러짐"
            if not 참가자.get("생존")
            else "무력화"
            if _무력화(전투상태, 참가자)
            else None
        )
        for 항목 in 채널링_목록(참가자) if 까닭 else []:
            _채널링_해제(전투상태, 참가자, 항목, 까닭)


def 채널링_행동해제(전투상태, 참가자, 까닭="다른 행동"):
    """자기 턴에 행동하면(스킬/일반공격/아이템) 쓴 턴이 지난 채널링이 풀린다. 다른 참가자의 턴(반응)은 해당 없음."""
    if 전투상태["참가자"][전투상태["현재턴"]] is not 참가자:
        return
    for 항목 in 채널링_목록(참가자):
        if not 항목.get("채널링시전턴"):
            _채널링_해제(전투상태, 참가자, 항목, 까닭)


def 채널링_턴종료(전투상태, 참가자):
    """쓴 턴이 끝나면 표시만 지우고, 다음 턴이 끝나면 채널링이 끝난다."""
    for 항목 in 채널링_목록(참가자):
        if 항목.pop("채널링시전턴", False):
            continue
        참가자["버프"].remove(항목)


def 분신_흡수(대상, 피해):
    """버프 인스턴스의 "분신실드"(분신 #278 - skill_grant._분신_기록)가 피해를 앞 분신부터 흡수한다. 실드를 넘는
    피해는 다음 분신으로 이어지고, 부서진 분신은 빠진다. 분신이 다 부서지면 그 버프도 사라진다.
    흡수하고 남은 피해를 돌려준다."""
    for 항목 in list(대상.get("버프") or []):
        실드들 = 항목.get("분신실드")
        if 실드들 is None:
            continue
        while 피해 > 0 and 실드들:
            흡수 = min(실드들[0], 피해)
            피해 -= 흡수
            실드들[0] -= 흡수
            if 실드들[0] <= 0:
                실드들.pop(0)
        if not 실드들:
            대상["버프"].remove(항목)
    return 피해


def _HP_깎기(대상, 양):
    """현재HP를 양만큼 깎는다 - 1 이하로 떨어지면 "쓰러짐방지" 버프(사무치는 광기)가 한 번 막는다."""
    대상["현재HP"] = max(min(대상["현재HP"], 0), 대상["현재HP"] - 양)
    if 양 > 0 and 대상["현재HP"] <= 1 and _쓰러짐방지_소모(대상):
        대상["현재HP"] = 1


def _쓰러짐방지_소모(참가자):
    """버프 정의에 "쓰러짐방지"(사무치는 광기)가 있는 버프 하나를 지우고 True. 없으면 False -
    HP가 1 이하로 떨어질 피해를 한 번 막는다(HP 1로 남김)."""
    목록 = 참가자.get("버프") or []
    for 항목 in 목록:
        정의, _ = resources.효과정의_조회(항목.get("이름"))
        if (정의 or {}).get("쓰러짐방지"):
            목록.remove(항목)
            return True
    return False


def 체력_소모(전투상태, 참가자, 양):
    """스킬 비용/특성으로 스스로 HP를 깎는다(혈기왕성·프렌지 #247) - 피해가 아니라 방어·반응을 받지 않고
    HP는 1 아래로 내려가지 않는다. 실제로 깎인 양을 돌려준다."""
    전 = 참가자["현재HP"]
    참가자["현재HP"] = max(min(전, 1), 전 - max(0, 양))
    return 전 - 참가자["현재HP"]


def _출혈처치_회복(전투상태, 공격측, 대상, 출혈중첩):
    """공격측의 특성 "출혈처치회복"(프렌지 #247) - 출혈인 적을 쓰러뜨리면 "회복" 식("출혈중첩")만큼
    최대HP까지 회복한다."""
    if 공격측 is None or 출혈중첩 <= 0 or not 공격측.get("생존", True):
        return
    for 원소 in traits.캐릭터특성_무기효과(전투상태, 공격측, "출혈처치회복"):
        식 = str(원소.get("회복", "0")).replace("출혈중첩", str(출혈중첩))
        양 = formula.올림(formula.수식_평가(식, stats.기본_컨텍스트(전투상태, 공격측)))
        최대HP = formula.올림(stats.유효_최대HP(전투상태, 공격측))
        회복 = max(0, min(양, 최대HP - 공격측["현재HP"]))
        공격측["현재HP"] += 회복
        core.로그(
            전투상태,
            {
                "공격자": 공격측["이름"],
                "대상": 공격측["이름"],
                "비고": f"출혈인 {대상['이름']}을(를) 쓰러뜨려 HP {회복} 회복",
            },
            종류="비고",
        )


def 집요함_발동(전투상태, 공격자, 대상, 속성=None, 판정=None, 배수=1):
    """빗나간 공격(펌블 포함)에 공격자의 집요함만큼 피해 - 일반 피해처럼 공격 속성,
    공격자의 속성강화, 대상의 방어력/보호률/저항/취약/내성/피격 반응을 받는다(2026-10-15 사용자 결정).
    데미지보너스는 더하지 않는다(2026-10-19 사용자 결정). 집요함이 0이면 아무 일도 없다.
    판정이 펌블(자동실패)이고 공격자에게 "펌블집요함증폭" 특성(얀데레)이 있으면 집요함 x
    (1 + 치명타_주사위수) - 치명타 때 더 굴리는 주사위 수만큼 집요함이 더해진다.
    배수는 원펀맨 일반공격의 합친 배수 - 집요함에 곱한다(얀데레와도 곱한다).
    명중 판정 직후(공격 줄을 쓰기 전)에 불리므로 집요함 줄은 "뒤따를로그"에 두어 공격 줄 뒤에
    붙게 한다(core.로그). 이 피해로 쓰러진 사람도 공격 줄이 아니라 집요함 줄에 붙인다."""
    if 공격자 is None or not 대상.get("생존", True):
        return
    값 = 유효_집요함(전투상태, 공격자)
    if 값 <= 0:
        return
    값 *= 배수
    펌블배수 = 1
    if (판정 or {}).get("자동실패") and traits.특성_수치(
        전투상태, 공격자, "펌블집요함증폭"
    ) > 0:
        펌블배수 = 1 + stats.치명타_주사위수(전투상태, 공격자)
        값 *= 펌블배수
    앞쓰러짐 = 전투상태.pop("쓰러짐대기", None)
    앞뒤 = len(전투상태.get("뒤따를로그", []))
    최종피해 = 피해_적용(전투상태, 대상, 값, 속성=속성, 공격자=공격자)
    항목 = {
        "공격자": 공격자["이름"],
        "대상": 대상["이름"],
        "피해": 최종피해,
        "비고": "집요함",
        "종류": "비고",
    }
    if 펌블배수 > 1:  # 얀데레 - 몇 배로 늘었는지(문장은 그대로)
        항목["펌블증폭"] = 펌블배수
    쓰러짐 = 전투상태.pop("쓰러짐대기", None)
    if 쓰러짐:
        항목["쓰러짐"] = 쓰러짐
    if 앞쓰러짐:
        전투상태["쓰러짐대기"] = 앞쓰러짐
    # 이 피해의 흡혈 줄(피해_적용이 붙임)보다 집요함 줄이 먼저 온다
    전투상태.setdefault("뒤따를로그", []).insert(앞뒤, 항목)


