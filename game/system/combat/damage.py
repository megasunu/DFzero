def 집요함_발동(전투상태, 공격자, 대상, 속성=None, 판정=None, 배수=1):
    """빗나간 공격(펌블 포함)에 공격자의 집요함만큼 피해 - 일반 피해처럼 공격 속성,
    공격자의 속성강화, 대상의 방어력/보호률/저항/취약/내성/피격 반응을 받는다(2026-10-15 사용자 결정).
    데미지보너스는 더하지 않는다(2026-10-19 사용자 결정). 집요함이 0이면 아무 일도 없다.
    판정이 펌블(자동실패)이고 공격자에게 "펌블집요함증폭" 특성(얀데레)이 있으면 집요함 x
    (1 + 치명타_주사위수) - 치명타 때 더 굴리는 주사위 수만큼 집요함이 더해진다.
    배수는 원펀맨 일반공격의 합친 배수 - 집요함에 곱한다(얀데레와도 곱한다).
    명중 판정 직후(공격 줄을 쓰기 전)에 불리므로 집요함 줄은 "뒤따를로그"에 두어 공격 줄 뒤에
    붙게 한다(core.로그). 이 피해로 쓰러진 사람도 공격 줄이 아니라 집요함 줄에 붙인다."""
    if 공격자 is None or not 대상.get("생존", True):
        return
    값 = 유효_집요함(전투상태, 공격자)
    if 값 <= 0:
        return
    값 *= 배수
    펌블배수 = 1
    if (판정 or {}).get("자동실패") and traits.특성_수치(
        전투상태, 공격자, "펌블집요함증폭"
    ) > 0:
        펌블배수 = 1 + stats.치명타_주사위수(전투상태, 공격자)
        값 *= 펌블배수
    앞쓰러짐 = 전투상태.pop("쓰러짐대기", None)
    앞뒤 = len(전투상태.get("뒤따를로그", []))
    최종피해 = 피해_적용(전투상태, 대상, 값, 속성=속성, 공격자=공격자)
    항목 = {
        "공격자": 공격자["이름"],
        "대상": 대상["이름"],
        "피해": 최종피해,
        "비고": "집요함",
        "종류": "비고",
    }
    if 펌블배수 > 1:  # 얀데레 - 몇 배로 늘었는지(문장은 그대로)
        항목["펌블증폭"] = 펌블배수
    쓰러짐 = 전투상태.pop("쓰러짐대기", None)
    if 쓰러짐:
        항목["쓰러짐"] = 쓰러짐
    if 앞쓰러짐:
        전투상태["쓰러짐대기"] = 앞쓰러짐
    # 이 피해의 흡혈 줄(피해_적용이 붙임)보다 집요함 줄이 먼저 온다
    전투상태.setdefault("뒤따를로그", []).insert(앞뒤, 항목)


