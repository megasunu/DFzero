def 지속피해_적용(전투상태, 대상, 항목, 정의):
    """지속피해형 상태이상(출혈/중독/화상/감전 등) 하나의 "턴시작시"/
    "턴종료시" 피해를 실제로 입힌다. "화상"의 "범위지속피해"(자신과
    주변2체)는 대상 진영과 무관하게 "대형위치" 기준 좌우 인접까지
    포함한다(아군도 몬스터처럼 전투_시작()에서 대형위치가 매겨진다).

    좌우 인접은 죽은 참가자를 빼고 당겨서 계산하지 않는다 - 같은 편
    전체(생존 무관)를 대형위치 순으로 늘어놓고 바로 옆 칸만 보며, 그
    칸이 죽은 참가자면 아무도 맞지 않는다(빈 칸 너머는 보지 않는다)."""
    효과 = 정의.get("효과", {})
    # 인스턴스에 "차수"가 있으면 그 차수로 굴린다(흡혈로 걸린 1차수 중독)
    차수 = 항목.get("차수", core.차수(대상))
    피해 = formula.수식_평가(효과.get("수식", "0"), {"차수": 차수})
    피해감소무시 = 효과.get("피해감소무시", False)
    방어력무시 = 효과.get("방어력무시", False)

    대상들 = [대상]
    if 효과.get("타입") == "범위지속피해":
        같은편전체 = sorted(
            (p for p in 전투상태["참가자"] if p["진영"] == 대상["진영"]),
            key=lambda p: p.get("대형위치", 0),
        )
        if 대상 in 같은편전체:
            idx = 같은편전체.index(대상)
            후보 = 같은편전체[max(0, idx - 1) : idx + 2]
            대상들 = [p for p in 후보 if p["생존"]]

    for 실제대상 in 대상들:
        최종피해 = 피해_적용(
            전투상태, 실제대상, 피해, 피해감소무시=피해감소무시, 방어력무시=방어력무시
        )
        core.로그(
            전투상태,
            {
                "공격자": 항목["이름"],
                "대상": 실제대상["이름"],
                "피해": 최종피해,
                "비고": "지속피해형 자동 발동",
            },
            종류="비고",
        )


def 지속피해_스킬_적용(전투상태, 대상, 항목):
    """job_skill_format.py <효과 하위 양식> "지속피해"(즉시데미지가 있는
    스킬에 곁들이는 커스텀 도트) 하나를 발동시킨다. status_effects.py
    기반 "지속피해형"(위 지속피해_적용)과 이름이 비슷하지만 다른
    개념이다 - 이쪽은 상태이상정의에 등록된 게 아니라, 항목 자체에
    skill_system.효과_적용이 저장해둔 "출처"(데미지/데미지보너스/속성/
    시전자id)를 쓴다.

    대상 자신의 턴 기준 "턴종료시" 발동하며, 매 턴 별도의 명중/내성
    판정 없이 무조건 피해를 입힌다(최초 적용 시 내성굴림 실패했을 때만
    이 항목이 걸린다). 지속턴 만료는 다른 상태이상과 동일하게
    턴_시작_처리가 처리한다."""
