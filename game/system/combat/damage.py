    피해 = formula.수식_평가(출처.get("데미지", "0"), 컨텍스트) + 출처.get(
        "데미지보너스", 0
    )
    최종피해 = 피해_적용(
        전투상태,
        대상,
        피해,
        속성=출처.get("속성"),
        최종피해배율=출처.get("최종피해배율", 1),
    )
    core.로그(
        전투상태,
        {
            "공격자": 시전자["이름"],
            "대상": 대상["이름"],
            "스킬": 항목.get("이름"),
            "피해": 최종피해,
            "비고": "지속피해 자동 발동",
        },
        종류="비고",
    )
