def _부자유친(전투상태, 공격측, 대상, 최종피해):
    """포켓몬 특성 부자유친(특성 "공격후추가피해비율") - 공격 피해(타격마다)의 그 비율(1/4, 올림)만큼 추가 피해.
    명중굴림·치명타·추가 효과가 없다 - 공격한 참가자 없이 그대로 깎는다(방어·속성 없음, 다시 붙지 않음)."""
    비율 = sum(
        v
        for v in status.특성_변동값목록(전투상태, 공격측, "공격후추가피해비율")
        if isinstance(v, (int, float))
    )
    if 비율 <= 0 or 최종피해 <= 0 or 대상["현재HP"] <= 0:
        return
    추가 = formula.올림(최종피해 * 비율)
    실제 = 피해_적용(전투상태, 대상, 추가, 피해감소무시=True)
    전투상태.setdefault("뒤따를로그", []).append(
        {
            "공격자": 공격측["이름"],
            "대상": 대상["이름"],
            "피해": 실제,
            "비고": "부자유친",
            "종류": "비고",
        }
    )


@contextlib.contextmanager
def 몹몰이_공격대상(전투상태, 대상들):
    """한 공격이 함께 치는 대상들 - 그동안 이들끼리는 몹몰이 연결 피해를 주고받지 않는다(몹몰이_연결)."""
    이전 = 전투상태.get("몹몰이공격대상")
    전투상태["몹몰이공격대상"] = [p.get("id") for p in 대상들]
    try:
        yield
    finally:
        if 이전 is None:
            전투상태.pop("몹몰이공격대상", None)
        else:
            전투상태["몹몰이공격대상"] = 이전


def 몹몰이_연결(전투상태, 공격측, 대상, 최종피해):
    """몹몰이(#378) - 몹몰이인 대상이 공격 피해를 받으면 같은 편의 다른 몹몰이도 그만큼 받는다(방어·속성 없이,
    다시 잇지 않는다). 지금 공격이 함께 치는 대상(전투상태["몹몰이공격대상"] - id)은 빼서 겹치지 않는다."""
    if 최종피해 <= 0 or not status.상태이상_판정(전투상태, 대상, "몹몰이"):
        return
    함께 = 전투상태.get("몹몰이공격대상") or ()
    for p in 전투상태["참가자"]:
        if (
            p is 대상
            or not p["생존"]
            or p["진영"] != 대상["진영"]
            or p.get("id") in 함께
            or not status.상태이상_판정(전투상태, p, "몹몰이")
        ):
            continue
        실제 = 피해_적용(전투상태, p, 최종피해, 피해감소무시=True)
        전투상태.setdefault("뒤따를로그", []).append(
            {
                "공격자": 공격측["이름"],
                "대상": p["이름"],
                "피해": 실제,
                "비고": f"몹몰이 - {대상['이름']}와(과) 함께",
                "종류": "비고",
            }
        )


def _속성흡수량(전투상태, 대상, 부분들):
    """포켓몬 흡수 특성(마중물/타오르는불꽃/피뢰침/정의의마음) - 특성 "속성흡수"에 든 속성으로 들어온 피해(속성
    배율 전, 올림)의 합. 그 속성은 면역이라 피해는 0이고 이만큼 회복한다(사용자 결정 2026-10-20)."""
    흡수속성 = {
        속성_정식명(s) for s in traits.캐릭터특성_문자열값(전투상태, 대상, "속성흡수")
    }
    if not 흡수속성:
        return 0
    return sum(
        formula.올림(max(0, 값))
        for 값, s in 부분들
        if s is not None and 속성_정식명(s) in 흡수속성
    )


def _속성흡수_회복(전투상태, 대상, 양):
    최대HP = formula.올림(stats.유효_최대HP(전투상태, 대상))
    실회복 = max(0, min(양, 최대HP - 대상["현재HP"]))
    대상["현재HP"] += 실회복
    # HP가 가득이어도 남긴다 - 면역으로 피해가 0이 된 까닭을 보여 준다
    전투상태.setdefault("뒤따를로그", []).append(
        {
            "대상": 대상["이름"],
            "회복": 실회복,
            "비고": "속성 흡수",
            "종류": "비고",
        }
    )


def _흡혈_발동(전투상태, 흡혈자, 대상, 최종피해):
    """흡혈(2026-10-19 사용자 결정): 입힌 최종피해 x 흡혈% 만큼(올림, 최대HP까지) 회복한다.
    출혈에 걸린 대상이면 두 배. 중독에 걸린 대상이면 흡혈자가 내성굴림 없이 1턴간 1차수
    중독에 걸린다(타격마다). 로그는 "뒤따를로그"로 공격 줄 뒤에 붙인다. 피해_적용이 공격한
    참가자가 있을 때만 부른다 - 지속피해형(출혈/중독 등)은 공격자가 없어 흡혈하지 않는다."""
    흡혈 = 유효_흡혈(전투상태, 흡혈자)
    if 흡혈 <= 0 or 최종피해 <= 0 or not 흡혈자.get("생존", True):
        return
    배수 = 2 if status.상태이상_판정(전투상태, 대상, "출혈") else 1
    양 = -(-최종피해 * 흡혈 * 배수 // 100)  # 올림
    최대HP = formula.올림(stats.유효_최대HP(전투상태, 흡혈자))
    실회복 = max(0, min(양, 최대HP - 흡혈자["현재HP"]))
    흡혈자["현재HP"] += 실회복
    뒤 = 전투상태.setdefault("뒤따를로그", [])
    if 실회복 > 0:
        뒤.append(
            {
                "공격자": 흡혈자["이름"],
                "대상": 대상["이름"],
                "회복": 실회복,
                "비고": "흡혈",
                "종류": "비고",
            }
        )
    if status.상태이상_판정(전투상태, 대상, "중독"):
        if status.상태이상_면역(전투상태, 흡혈자, "중독"):
            return
        흡혈자.setdefault("상태이상", []).append(
            {"이름": "중독", "지속턴": 1, "중첩": 1, "차수": 1}
        )
        뒤.append(
            {
                "공격자": 흡혈자["이름"],
                "대상": 흡혈자["이름"],
                "비고": "흡혈 - '중독' 상태이상 부여",
                "종류": "비고",
            }
        )
    if not 뒤:
        전투상태.pop("뒤따를로그")


def 유효_펌블범위(전투상태, 공격자, 대상=None):
    """자동실패(펌블)가 나는 최대 d20 눈. 기본 1(참가자 "펌블범위")에 공격자의
    버프/디버프/특성 "펌블범위"(펌블확률증가 +1, 펌블확률감소 -1)와, 대상이 있으면
    대상의 "피격펌블범위"(피격펌블증가 +1, 피격펌블감소 -1 - 나를 공격하는 쪽의
    펌블 확률)를 더한다. 0이면 자연 1도 펌블이 아니다(0 아래로는 안 내려감).
    "치명타펌블연동" 특성(얀데레)이 있으면 치명타범위가 20에서 낮아진 만큼 더한다
    (유효_치명타범위를 그때그때 본다 - 버프/특성/마봉 모두)."""
    기본 = 공격자.get("펌블범위", 1)
    증감 = stats.버프디버프_수치(전투상태, 공격자, "펌블범위") + traits.특성_수치(
        전투상태, 공격자, "펌블범위"
    )
    if traits.특성_수치(전투상태, 공격자, "치명타펌블연동") > 0:
        증감 += 20 - 유효_치명타범위(전투상태, 공격자)
    if 대상 is not None:
        증감 += stats.버프디버프_수치(
            전투상태, 대상, "피격펌블범위"
        ) + traits.특성_수치(전투상태, 대상, "피격펌블범위")
    return max(0, formula.올림(기본 + 증감))


def 명중_판정(
    전투상태,
    공격자,
    대상,
    명중률종류,
    명중보너스=0,
    장비보너스=True,
    명중배수=1,
    명중이점=False,
):
    """명중_판정_계산()으로 판정한 뒤, 아군이 적의 공격을 받는 경우
    캐릭터 반응스킬(회피형 - 크라우치 등, 회피성공시 반격 - 백스텝커터/
    리벤저)을 적용한다(피격판정_반응 참고). 장비보너스=False면 장비 명중률보너스를
    더하지 않는다(투척 아이템 - 소모품은 장비 보너스를 받지 않는다). 명중배수는 명중 보정
    전체에 곱한다(원펀맨 - 굴림은 한 번). 명중이점은 스킬의 "명중이점"(이혼일섬 #332)."""
    판정 = 명중_판정_계산(
        전투상태,
        공격자,
        대상,
        명중률종류,
        명중보너스,
        장비보너스=장비보너스,
        명중배수=명중배수,
        명중이점=명중이점,
    )
    if 대상.get("진영") == "아군" and 공격자.get("진영") != "아군":
        판정 = reactions.가드_반응(전투상태, 공격자, 대상, 판정)
        판정 = reactions.피격판정_반응(전투상태, 공격자, 대상, 판정, 명중률종류)
    return 판정


def 명중_판정_계산(
    전투상태,
    공격자,
    대상,
    명중률종류,
    명중보너스=0,
    장비보너스=True,
    명중배수=1,
    명중이점=False,
):
    """명중률종류(job_skill_format.py 값, 또는 몬스터 패턴의 "OO판정")에
    따라 판정한다. 반환값: {"성공", "자연눈", "치명타", "자동실패"}.

    "대상"이 "피격시강제치명타" 상태면 명중률종류와 상관없이 항상
    명중+치명타로 처리한다. "대상"의 "회피불리점"은 공격자에게 이점을,
    "공격자"의 "명중불리점"은 공격자 본인에게 불리를 준다. 특성의 "명중이점"
    (공격자)은 이점을, "회피이점"(대상)은 공격자에게 불리를 준다(심안). 버프의 "명중이점"(공격자)과
    "회피불리점"(대상)도 공격자에게 이점을 준다(폭주)."""
    홀딩_정리(전투상태)  # 끊긴 홀딩의 이점이 남지 않게
    강제치명타 = status.상태이상_플래그(전투상태, 대상, "피격시강제치명타")

    if 명중률종류 == "자동":
        return {"성공": True, "자연눈": None, "치명타": 강제치명타, "자동실패": False}

    # 이점·불리점은 출처마다 하나씩 세어 많은 쪽 하나만 적용한다(같으면 없음 - 사용자 결정)
    이점수 = sum(
        (
            status.상태이상_플래그(전투상태, 대상, "회피불리점"),
            status.특성_플래그(전투상태, 공격자, "명중이점"),
            # 버프 "명중이점"(공격자)/"회피불리점"(대상) - 폭주(#247)
            bool(stats.버프_효과원소목록(전투상태, 공격자, "명중이점")),
            bool(stats.버프_효과원소목록(전투상태, 대상, "회피불리점")),
            명중이점,  # 스킬의 "명중이점"(이혼일섬 #332)
        )
    )
    불리수 = sum(
        (
            status.상태이상_플래그(전투상태, 공격자, "명중불리점"),
            status.특성_플래그(전투상태, 대상, "회피이점"),
        )
    )
    이점, 불리 = dice_utils.이점_합산(이점수, 불리수)
    눈 = dice_utils.d20_굴림(이점=이점, 불리=불리)
    치명타범위 = 유효_치명타범위(전투상태, 공격자)
    펌블범위 = 유효_펌블범위(전투상태, 공격자, 대상)
    # 최종 명중값과 대상 AC는 치명타/대실패로 정해지는 판정에도 담는다(전투 로그가 "값 vs AC"로 보여 준다)
    보정합 = _명중_보정합(전투상태, 공격자, 대상, 명중률종류, 명중보너스, 장비보너스)
    값 = {"명중결과": 눈 + 보정합 * 명중배수}
    값["대상AC"] = stats.최종AC(전투상태, 대상)
    if stats.상세로그(전투상태):  # [설정] 전투로그 "자세하게" - 계산 내역도 담는다
        값["명중내역"] = _명중_내역(
            전투상태,
            공격자,
            대상,
            명중률종류,
            명중보너스,
            눈,
            값["명중결과"],
            장비보너스,
            배수몫=보정합 * (명중배수 - 1),
        )
        값["AC내역"] = stats.AC_내역(전투상태, 대상)
    return _눈_판정(대상, 명중률종류, 눈, 값, 강제치명타, 치명타범위, 펌블범위)


def 불리점_재판정(전투상태, 공격자, 대상, 판정, 명중률종류):
    """이미 굴린 판정에 불리점을 준다(귀영보 #247) - d20을 한 번 더 굴려 낮은 눈으로 성공/치명타/대실패를
    다시 정한다. 명중결과는 보정 그대로 눈만 바꾼다. "불리점굴림"에 새로 굴린 눈을 남긴다."""
    새눈 = dice_utils.d20_굴림()
    눈 = min(판정["자연눈"], 새눈)
    값 = {
        k: v
        for k, v in 판정.items()
        if k not in ("성공", "자연눈", "치명타", "자동실패")
    }
    값["명중결과"] = 판정["명중결과"] - 판정["자연눈"] + 눈
    결과 = _눈_판정(
        대상,
        명중률종류,
        눈,
        값,
        status.상태이상_플래그(전투상태, 대상, "피격시강제치명타"),
        유효_치명타범위(전투상태, 공격자),
        유효_펌블범위(전투상태, 공격자, 대상),
    )
    return dict(결과, 불리점굴림=새눈)


def _눈_판정(대상, 명중률종류, 눈, 값, 강제치명타, 치명타범위, 펌블범위):
    """굴린 눈과 값(명중결과/대상AC 등)으로 성공·치명타·대실패를 정한다(명중_판정_계산의 마지막 단계)."""
    if 강제치명타:
        return {"성공": True, "자연눈": 눈, "치명타": True, "자동실패": False, **값}

    if 명중률종류 == "필중":
        return {
            "성공": True,
            "자연눈": 눈,
            "치명타": 눈 >= 치명타범위,
            "자동실패": False,
            **값,
        }

    if 눈 <= 펌블범위:
        return {"성공": False, "자연눈": 눈, "치명타": False, "자동실패": True, **값}
    if 대상.get("감옥") and 눈 < 치명타범위:  # 감옥(AC 1)은 대실패만 아니면 맞는다
        return {"성공": True, "자연눈": 눈, "치명타": False, "자동실패": False, **값}
    if 눈 >= 치명타범위:
        return {"성공": True, "자연눈": 눈, "치명타": True, "자동실패": False, **값}

    return {
        "성공": 값["명중결과"] >= 값["대상AC"],
        "자연눈": 눈,
        "치명타": False,
        "자동실패": False,
        **값,
    }


_보정치_이름 = {"보정명중률": "능력 보정", "주문시전명중률": "주문 보정"}
# 명중률종류 -> 명중 굴림에 더하는 능력치 보정치(전투상태, 공격자). 키는 _보정치_이름과 같다.
# 표에 없으면 "…판정"(근력판정 등)은 그 능력치 보정치, 그 밖(기본명중률 등)은 0 - _명중_능력보정.
# stats와 서로 불러 import 때는 함수가 아직 없다 - 부를 때 찾는다.
_보정치_함수 = {
    "보정명중률": lambda 전투상태, 공격자: stats.평타_능력치_보정치(전투상태, 공격자),
    "주문시전명중률": lambda 전투상태, 공격자: stats.주문시전_보정치(전투상태, 공격자),
}


def _명중_능력보정(전투상태, 공격자, 명중률종류):
    if not isinstance(명중률종류, str):
        return 0
    if (함수 := _보정치_함수.get(명중률종류)) is not None:
        return 함수(전투상태, 공격자)
    if 명중률종류.endswith("판정"):
        return stats.유효_능력치_보정치(전투상태, 공격자, 명중률종류[:-2])
    return 0


def _명중_내역(
    전투상태,
    공격자,
    대상,
    명중률종류,
    명중보너스,
    눈,
    명중결과,
    장비보너스=True,
    배수몫=0,
):
    """명중 굴림의 [(이름, 값)] - 주사위, 능력 보정, 기본/역할군/장비 명중률보너스, 출처별(버프/특성/칭호),
    스킬 명중보너스. 합은 명중결과(_명중_보정합과 같은 값, 남으면 "기타")."""
    내역 = [("주사위", 눈)]
    보정 = _명중_능력보정(전투상태, 공격자, 명중률종류)
    이름 = _보정치_이름.get(명중률종류) or f"{str(명중률종류)[:-2]} 보정"
    기본 = 공격자["원본"].get("명중률보너스", 0)
    역할군 = (
        participants.몬스터_역할군_보너스(공격자["원본"], "명중률보너스")
        if 공격자["진영"] == "적"
        else 0
    )
    내역 += [
        (이름, 보정),
        ("기본 명중", 기본 if isinstance(기본, (int, float)) else 0),
        ("역할군", 역할군),
        ("장비", stats.장비_수치(공격자, "명중률보너스") if 장비보너스 else 0),
    ]
    내역 += stats.출처별_내역(
        전투상태, 공격자, "명중보너스", 명중률종류=명중률종류, 대상=대상
    )
    내역.append(("스킬", 명중보너스))
    내역.append(("원펀맨", 배수몫))  # 보정 전체 x 배수의 늘어난 몫
    return stats.기타_채우기([(n, v) for n, v in 내역 if v or n == "주사위"], 명중결과)


def 피해내역(
    전투상태,
    공격자,
    식,
    굴림합,
    합,
    최종,
    앞항목=(),
    장비=0,
    대상=None,
    명중률종류=None,
    속성=None,
    스킬타입=None,
    배수=1,
):
    """자세한 로그용 피해 내역 - 데미지 수식과 굴린 값, 데미지보너스 출처, 방어/속성 적용 전 합과 최종 피해.
    출처는 부르는 쪽이 계산한 앞항목 [(이름, 값)](스킬/역할군/추가피해 굴림 등)과 장비 값, 그리고 출처별
    버프/특성/칭호(명중률종류/대상/속성/스킬타입 조건 반영 - 피해 계산과 같은 인수를 넘긴다). 배수(원펀맨)는
    장비·출처 몫에 곱하는 늘어난 몫을 따로 적는다. 그래도 남으면 "기타". 상세로그가 아니면 None."""
    if not stats.상세로그(전투상태):
        return None
    출처 = [("장비", 장비)] + stats.출처별_내역(
        전투상태,
        공격자,
        "데미지보너스",
        명중률종류=명중률종류,
        대상=대상,
        속성=속성,
        스킬타입=스킬타입,
    )
    추가 = list(앞항목) + 출처 + [("원펀맨", (배수 - 1) * sum(v for _, v in 출처))]
    추가 = [(n, v) for n, v in 추가 if v]
    stats.기타_채우기(추가, 합 - 굴림합)
    return {"식": str(식), "굴림합": 굴림합, "추가": 추가, "합": 합, "최종": 최종}


def _명중_보정합(전투상태, 공격자, 대상, 명중률종류, 명중보너스, 장비보너스=True):
    """명중 굴림에 더하는 값 전부 - 능력치 보정치 + 명중률보너스(원본/역할군/장비/버프/특성/칭호)."""
    보정치 = _명중_능력보정(전투상태, 공격자, 명중률종류)

    명중률보너스 = 공격자["원본"].get("명중률보너스", 0)
    if not isinstance(명중률보너스, (int, float)):
        명중률보너스 = 0
    if 공격자["진영"] == "적":  # 몬스터 역할군(탱커 -1, 메이지 +1)
        명중률보너스 += participants.몬스터_역할군_보너스(
            공격자["원본"], "명중률보너스"
        )
    # 장비(전 부위+활성 세트) 명중률보너스 - 아군만, 투척 아이템을 뺀 모든 명중 굴림.
    if 장비보너스:
        명중률보너스 += stats.장비_수치(공격자, "명중률보너스")
    명중률보너스 += stats.버프디버프_수치(전투상태, 공격자, "명중보너스")
    명중률보너스 += traits.특성_수치(
        전투상태, 공격자, "명중보너스", 명중률종류=명중률종류, 대상=대상
    )
    명중률보너스 += traits.칭호_수치(전투상태, 공격자, "명중보너스")
    if "일반공격" in (
        공격자.get("_공격태그") or ()
    ):  # 빗자루 다루기 - 일반공격·일반공격취급만
        명중률보너스 += stats.스킬타입_조건_수치(
            전투상태, 공격자, "명중보너스", ("일반공격",)
        )
    return 보정치 + 명중률보너스 + 명중보너스


def 최종피해_계산(원래피해, 방어력, 보호률):
    """비율(보호률) 감소를 먼저 적용하고, 고정(방어력) 감소를 나중에 뺀다.
    최종피해 = max(0, 원래피해 x (1-보호률) - 방어력)"""
    return max(0, formula.올림(원래피해 * (1 - 보호률) - 방어력))


def 속성_정식명(속성):
    """속성 이름은 "무속성"/"화속성"/"수속성"/"명속성"/"암속성"으로 통일했다(데이터
    일괄 개명). 혹시 남은 줄임말("화" 등)은 정식명으로 바꾸고, 그 밖의 값은 그대로 둔다."""
    return common_names.속성_정식명.get(속성, 속성) if isinstance(속성, str) else 속성


# =====================================================
# 공격 연출 - 화면이 공격 대상 위에 잠깐 띄울 그림의 종류
# =====================================================
# 명중 굴림이 있는 공격(일반공격/스킬 타격/몬스터 패턴/소환수/반격)이 판정 직후
# 전투상태["공격연출"]에 {"대상id", "종류"}를 쌓고, 화면이 gameflow로 가져가 비운다.
# 종류: "모양:색" 또는 "실패"(빗나감). 모양은 공격의 "공격타입"(참격/타격/관통, 역장/마법은
# 마법 - stats.타격_공격타입), 색은 피해가 가장 크게 들어가는 속성(화/수/명/암, 그 밖은 무).

# 연출 색이 되는 속성(화/수/명/암 - 무속성은 "무"로 남는다)
_연출_색 = {s: common_names.속성_줄임말[s] for s in common_names.강화_속성}


def 연출_속성(전투상태, 대상, 속성):
    """여러 속성 중 대상에게 배율이 가장 큰 것(피해_속성배율이 고르는 것). 같으면
    화/수/명/암이 무속성보다 앞서고, 그다음은 적힌 순서."""
    후보 = [속성_정식명(s) for s in (속성 if isinstance(속성, list) else [속성])]
    return max(
        후보,
        key=lambda s: (속성_피해배율(전투상태, 대상, s) if s else 1.0, s in _연출_색),
        default=None,
    )


def 공격연출_종류(전투상태, 대상, 성공, 속성, 공격타입):
    if not 성공:
        return "실패"
    모양 = common_names.공격타입_연출모양.get(공격타입, "타격")
    return f"{모양}:{_연출_색.get(연출_속성(전투상태, 대상, 속성), '무')}"


def 공격연출_기록(전투상태, 대상, 판정, 속성, 공격타입):
    전투상태.setdefault("공격연출", []).append(
        {
            "대상id": 대상.get("id"),
            "종류": 공격연출_종류(전투상태, 대상, 판정["성공"], 속성, 공격타입),
        }
    )


def 피해_속성배율(전투상태, 대상, 속성, 방어무시=False):
    """속성이 리스트면 가장 큰 배율, None이면 1(피해_적용 공용)."""
    if isinstance(속성, list):
        return max(
            (속성_피해배율(전투상태, 대상, s, 방어무시) for s in 속성), default=1.0
        )
    if 속성 is None:
        return 1.0
    return 속성_피해배율(전투상태, 대상, 속성, 방어무시)


def 방어무시(전투상태, 공격측):
    """위상력 : 스트라이커(특성 "방어무시") - 이 참가자의 공격은 적의 방어력·보호율·속성내성(양수만)과 저항·면역을
    무시한다(사용자 결정 2026-10-20). 취약은 그대로."""
    return 공격측 is not None and status.특성_플래그(전투상태, 공격측, "방어무시")


def 속성_피해배율(전투상태, 대상, 속성, 방어무시=False):
    """단일 속성 하나에 대해, 대상의 "저항"/"취약"(원본 고정 리스트 +
    특성이 부여하는 리스트)을 반영한 배율을 계산한다(저항 0.5배/취약
    2배, 둘 다면 상쇄돼 1배). 비교 전에 속성을 짧은 표기로 맞춘다
    (속성_정식명 참고)."""
    속성 = 속성_정식명(속성)
    원본 = 대상.get("원본", {})
    저항목록 = list(원본.get("저항") or []) + traits.특성_문자열_변동값_목록(
        전투상태, 대상, "저항"
    )
    if (형태속성 := traits.형태_속성(전투상태, 대상)) is not None:  # 란마 1/2
        저항목록.append(형태속성)
    취약목록 = list(원본.get("취약") or []) + traits.특성_문자열_변동값_목록(
        전투상태, 대상, "취약"
    )
    면역목록 = list(원본.get("면역") or []) + traits.특성_문자열_변동값_목록(
        전투상태, 대상, "면역"
    )
    if 방어무시:  # 위상력 : 스트라이커 - 저항·면역 무시, 취약만
        return 2.0 if 속성 in [속성_정식명(s) for s in 취약목록] else 1.0
    if 속성 in [속성_정식명(s) for s in 면역목록]:
        return 0.0  # 면역: 그 속성 피해는 0
    저항목록 = [속성_정식명(s) for s in 저항목록]
    if 속성 in 저항목록 and status.특성_플래그(전투상태, 대상, "저항면역"):
        return 0.0  # 불가사의부적 - 저항은 면역으로 친다
    취약목록 = [속성_정식명(s) for s in 취약목록]
    배율 = 1.0
    if 속성 in 저항목록:
        배율 *= 0.5
    if 속성 in 취약목록:
        배율 *= 2
    return 배율


def 속성_최종배율(전투상태, 공격측, 대상, 속성, 방어무시=False):
    """방어력/보호률 뒤 최종피해에 곱하는 배율 - 공격측 속성강화와 대상 속성내성을 합연산:
    1 + 0.1 x (강화 - 내성), 0 아래로 안 내려감(내성이 더 크면 피해가 준다). 화/수/명/암에만
    붙고 무속성(과 속성 없음)은 1 - "전체" 속성강화(엘레멘탈 번)도 무속성에는 안 붙는다.
    저항/취약/면역과는 곱연산(사용자 결정 2026-10-12)."""
    속성 = 속성_정식명(속성)
    if 속성 not in common_names.강화_속성:  # 속성강화/속성내성은 무속성에 없다
        return 1.0
    강화 = stats.속성_보정합(전투상태, 공격측, "속성강화", 속성)
    내성 = stats.속성_보정합(전투상태, 대상, "속성내성", 속성)
    if 방어무시:  # 위상력 - 양수 내성만 무시
        내성 = min(0, 내성)
    return max(0.0, 1 + 0.1 * (강화 - 내성))


def 주속성(전투상태, 공격측, 대상, 속성):
    """속성이 여러 개면 저항/취약/면역 x 강화/내성이 가장 큰(가장 아픈) 속성 하나."""
    if not isinstance(속성, list):
        return 속성
    if not 속성:
        return None
    return max(
        속성,
        key=lambda s: (
            속성_피해배율(전투상태, 대상, s) * 속성_최종배율(전투상태, 공격측, 대상, s)
        ),
    )


def _피해_부분들(전투상태, 공격측, 대상, 피해량, 속성, 추가피해목록, 무시):
    """피해_적용의 (부분들, 관통부분들, 흡수량) - 부분마다 (저항/취약/면역 반영 값, 속성). 방어를 무시하는
    추가피해(철갑탄)는 관통부분들로 따로 모은다(_관통_최종피해)."""
    부분들 = [(피해량 * 피해_속성배율(전투상태, 대상, 속성, 무시), 속성)]
    흡수 = _속성흡수량(전투상태, 대상, [(피해량, 속성)])
    관통부분들 = []
    for 추가값, 추가속성, *관통 in 추가피해목록 or []:
        추가속성 = 주속성(전투상태, 공격측, 대상, 추가속성)
        if 관통 and 관통[0]:
            관통부분들.append(
                (추가값 * 피해_속성배율(전투상태, 대상, 추가속성, True), 추가속성)
            )
            continue
        부분들.append(
            (추가값 * 피해_속성배율(전투상태, 대상, 추가속성, 무시), 추가속성)
        )
        흡수 += _속성흡수량(전투상태, 대상, [(추가값, 추가속성)])
    return 부분들, 관통부분들, 흡수


def _관통_최종피해(전투상태, 공격측, 대상, 부분들):
    """방어를 무시하는 추가피해(철갑탄 #390)의 최종피해 - 위상력처럼 양수 보호율·속성저항·속성내성은 무시하고
    음수(피해를 키우는 값)는 그대로 쓴다. 방어력은 본 피해 쪽에 이미 한 번 적용했으므로 여기서는 뺀다."""
    피해량 = sum(값 for 값, _ in 부분들)
    if 피해량 <= 0:
        return 0
    최종피해 = 최종피해_계산(피해량, 0, min(0, stats.유효_보호률(전투상태, 대상)))
    return max(
        0,
        formula.올림(
            sum(
                최종피해
                * (값 / 피해량)
                * 속성_최종배율(전투상태, 공격측, 대상, s, True)
                for 값, s in 부분들
            )
        ),
    )


def 양옆_이웃(전투상태, 대상):
    """대상 바로 양옆 칸의 살아 있는 같은 편(범위공격의 좌우 1체씩). 같은 편 전체(생존 무관)를 "대형위치" 순으로
    나열해 바로 옆 칸만 본다 - 중간에 죽은 참가자가 있어도 대열이 당겨지지 않고, 옆 칸이 죽었으면 빈다."""
    같은편전체 = sorted(
        (p for p in 전투상태["참가자"] if p["진영"] == 대상["진영"]),
        key=lambda p: p.get("대형위치", 0),
    )
    if 대상 not in 같은편전체:
        return []
    idx = 같은편전체.index(대상)
    return [
        같은편전체[i]
        for i in (idx - 1, idx + 1)
        if 0 <= i < len(같은편전체) and 같은편전체[i]["생존"]
    ]


def 피해_적용(
    전투상태,
    대상,
    피해량,
    *,
    피해감소무시=False,
    방어력무시=False,
    속성=None,
    공격자=None,
    추가피해목록=None,
    공격측=None,
    최종피해배율=1,
):
    """방어력/보호률을 적용해 최종 피해를 계산하고 대상 HP에서 뺀다.
    피해감소무시=True면 방어력/보호률 자체를 무시한다(출혈 등 지속피해용).

    속성이 주어지면 대상["원본"]의 "저항"/"취약"(및 특성이 부여하는
    저항/취약 - 예: 종족:좀비)을 확인해 절반(저항)/2배(취약)로
    조정한다(둘 다 있으면 상쇄). 속성이 리스트면(예: 굴 구위시의
    ["무속성", "수속성", "암속성"]) 각 속성으로 계산했을 때 나오는
    배율 중 가장 큰 쪽을 쓴다("속성이 여러 개면 더 높은 데미지 쪽
    속성으로 공격한다" - 속성 다중판정의 기본 설정).
    속성=None(지속피해형 등 속성 정보가 없는 경우)이면 이 조정을
    받지 않는다.

    공격자: 적의 공격/능력으로 아군이 피해를 받으면 넘긴다 -
    그때만 "피격시" 반응스킬(건가드/위상 변화)을 적용한다(피격피해_반응).
    지속피해 등 공격자가 없는 피해는 반응 대상이 아니다.

    추가피해목록: [(값, 속성[, 방어무시]), ...] - 공격 속성과 따로 자기
    속성으로 저항/취약을 적용한 뒤 본 피해에 더한다(장전 탄의 추가피해).
    방어력/보호률은 합친 피해에 한 번만 적용한다. 방어무시가 참이면(철갑탄) 그 부분은
    _관통_최종피해로 따로 계산해 더한다.

    면역 속성이면 그 속성 피해는 0. 속성강화(공격측 - 없으면 공격자)/속성내성(대상)은
    방어력/보호률 뒤의 최종피해에 곱한다(속성_최종배율). 추가피해가 있으면 최종피해를
    부분(저항/취약 반영 후) 비율로 나눠 부분마다 자기 속성의 배율을 곱한다.
    공격측: 반응스킬 없이 속성강화만 볼 공격한 참가자(아군 공격 등).
    최종피해배율: 스킬강화(레벨 12)의 배율 - 속성 배율 뒤 최종피해에 곱한다(올림)."""
    공격측 = 공격측 or 공격자
    if (
        공격측 is not None
        and 공격측.get("진영") != 대상.get("진영")
        and 홀딩무적인가(전투상태, 대상)
    ):
        core.로그(
            전투상태,
            {
                "공격자": 공격측["이름"],
                "대상": 대상["이름"],
                "비고": "잡기 중 - 피해 무효",
            },
            종류="비고",
        )
        return 0
    속성 = 주속성(전투상태, 공격측, 대상, 속성)
    무시 = 방어무시(전투상태, 공격측) and 공격측.get("진영") != 대상.get("진영")
    # (저항/취약/면역 반영 값, 속성) - 속성마다 따로 계산하고 방어는 합에 한 번
    부분들, 관통부분들, 흡수 = _피해_부분들(
        전투상태, 공격측, 대상, 피해량, 속성, 추가피해목록, 무시
    )
    피해량 = sum(값 for 값, _ in 부분들)

    if 피해감소무시:
        최종피해 = max(0, formula.올림(피해량))
    else:
        방어력 = 0 if 방어력무시 else stats.유효_방어력(전투상태, 대상)
        보호률 = stats.유효_보호률(전투상태, 대상)
        if 무시:  # 위상력 - 양수만 무시, 약해져 음수인 값은 그대로
            방어력, 보호률 = min(0, 방어력), min(0, 보호률)
        최종피해 = 최종피해_계산(피해량, 방어력, 보호률)
    if 피해량 > 0 and any(s is not None for _, s in 부분들):
        # 속성강화/속성내성은 방어 뒤 최종피해를 부분 비율로 나눠 각자 속성으로 곱한다
        최종피해 = max(
            0,
            formula.올림(
                sum(
                    최종피해
                    * (값 / 피해량)
                    * (
                        1
                        if s is None
                        else 속성_최종배율(전투상태, 공격측, 대상, s, 무시)
                    )
                    for 값, s in 부분들
                )
            ),
        )
    if 관통부분들:
        최종피해 += _관통_최종피해(전투상태, 공격측, 대상, 관통부분들)
    if 최종피해배율 != 1:
        최종피해 = max(0, formula.올림(최종피해 * 최종피해배율))

    if (
        공격자 is not None
        and 대상.get("진영") == "아군"
        and 공격자.get("진영") != "아군"
        and 최종피해 > 0
    ):
        최종피해 = reactions.피격피해_반응(전투상태, 공격자, 대상, 최종피해)

    # 아군 공용 임시생명력(넨가드), 분신(#278), 그다음 임시생명력이 현재HP보다 먼저 깎인다. 반환값(최종피해)은
    # 이 공격이 입힌 총 피해 그대로다 - 실제로 현재HP에서 빠지는 양만
    # 이것들이 흡수한 만큼 줄어든다.
    실HP피해 = 버프임시생명력_흡수(
        대상, 분신_흡수(대상, 공용임시생명력_흡수(전투상태, 대상, 최종피해, 공격측))
    )
    임시생명력 = 대상.get("임시생명력", 0)
    if 임시생명력 > 0:
        흡수량 = min(임시생명력, 실HP피해)
        대상["임시생명력"] = 임시생명력 - 흡수량
        실HP피해 -= 흡수량

    출혈중첩 = sum(
        항목.get("중첩", 1)
        for 항목 in 대상.get("상태이상") or []
        if 항목.get("이름") == "출혈"
    )
    _HP_깎기(대상, 실HP피해)
    if 흡수 > 0 and 대상["현재HP"] > 0:
        _속성흡수_회복(전투상태, 대상, 흡수)
    if (
        공격자 is not None
        and 최종피해 > 0
        and 대상["현재HP"] > 0
        and 공격자.get("진영") != 대상.get("진영")
    ):
        # 공격자의 "속성피해시" 몬스터특성(알비노 고블린 - 명속성 피해를 주면 감전, 쓰러진 대상 제외)
        traits.특성_속성피해시_발동(
            전투상태, 공격자, 대상, [s for _, s in 부분들 if s is not None]
        )
    if 공격측 is not None and 공격측.get("진영") != 대상.get("진영"):
        _흡혈_발동(전투상태, 공격측, 대상, 최종피해)
        _부자유친(전투상태, 공격측, 대상, 최종피해)
        몹몰이_연결(전투상태, 공격측, 대상, 최종피해)
    if 대상["현재HP"] <= 0:
        if 대상.get(
            "생존"
        ):  # 이번 피해로 쓰러졌다 - 다음 전투 로그에 붙는다(core.로그)
            전투상태.setdefault("쓰러짐대기", []).append(대상["이름"])
            if 공격측 is not None and 공격측.get("진영") != 대상.get("진영"):
                _출혈처치_회복(전투상태, 공격측, 대상, 출혈중첩)
        대상["생존"] = False
        # 감옥이 부서지면 갇힌 사람이 풀리고, 갇힌 사람이 쓰러지면 감옥도 사라진다(벌칙 없음)
        감옥 = 대상 if 대상.get("감옥") else status.살아있는_감옥(전투상태, 대상)
        if 감옥 is not None:
            status.감옥_풀기(전투상태, 감옥)
    나선의넨_반격(전투상태, 대상, 공격자)
    reactions.피격설치_반응(전투상태, 대상, 공격자, 최종피해)  # 회심의 랜드러너
    return 최종피해


def 나선의넨_반격(전투상태, 대상, 공격자):
    """켜진 특성의 "피격반격"(나선의 넨 #280) - 살아 있는 아군이 적에게 맞으면 그 적에게 원소 "명중률"로 굴려
    맞으면 "데미지"를 "피해속성"으로 준다. 반격마다 참가자 "피격반격스택"을 1 쓴다 - 칸이 없으면(전투 시작, 전투 중에
    켬) "최대스택"이다. 자기 턴마다 1씩 찬다(나선의넨_스택_충전)."""
    if (
        공격자 is None
        or 대상.get("진영") != "아군"
        or 공격자.get("진영") != "적"
        or not 대상["생존"]
        or not 공격자["생존"]
    ):
        return
    for 원소 in traits.캐릭터특성_무기효과(전투상태, 대상, "피격반격"):
        스택 = 대상.get("피격반격스택", 원소.get("최대스택", 1))
        if 스택 <= 0 or not 공격자["생존"]:
            return
        대상["피격반격스택"] = 스택 - 1
        판정 = 명중_판정(전투상태, 대상, 공격자, 원소.get("명중률", "자동"))
        속성 = 원소.get("피해속성")
        공격연출_기록(전투상태, 공격자, 판정, 속성, "마법")
        피해 = 0
        if 판정["성공"]:
            굴림 = formula.수식_평가(
                원소["데미지"], stats.기본_컨텍스트(전투상태, 대상)
            )
            피해 = 피해_적용(전투상태, 공격자, max(0, 굴림), 속성=속성, 공격측=대상)
        core.로그(
            전투상태,
            {
                "공격자": 대상["이름"],
                "대상": 공격자["이름"],
                "판정": 판정,
                "피해": 피해,
                "비고": "나선의 넨 반격" + ("" if 판정["성공"] else " - 빗나감"),
            },
            종류="비고",
        )


def 나선의넨_스택_충전(전투상태, 참가자):
    """자기 턴 시작에 "피격반격스택"을 1 채운다("최대스택"까지 - 나선의 넨 2026-10-22 사용자 결정).
    칸이 없으면 이미 최대라 그대로 둔다."""
    if "피격반격스택" not in 참가자:
        return
    for 원소 in traits.캐릭터특성_무기효과(전투상태, 참가자, "피격반격"):
        참가자["피격반격스택"] = min(
            원소.get("최대스택", 1), 참가자["피격반격스택"] + 1
        )
        return


def 버프임시생명력_흡수(대상, 피해):
    """대상 자신의 버프 인스턴스 "임시생명력"(신성한 빛/완충모듈 #392 - skill_run이 채운다)이 피해를 먼저
    흡수한다. 다 닳으면 그 버프가 사라지고, 버프가 지속턴으로 사라지면 남은 임시생명력도 같이 사라진다.
    흡수하고 남은 피해를 돌려준다."""
    for 항목 in list(대상.get("버프") or []):
        남은 = 항목.get("임시생명력")
        if 남은 is None or 피해 <= 0:
            continue
        흡수 = min(남은, 피해)
        피해 -= 흡수
        항목["임시생명력"] = 남은 - 흡수
        if 항목["임시생명력"] <= 0:
            대상["버프"].remove(항목)
    return 피해


def 공용임시생명력_흡수(전투상태, 대상, 피해, 공격측=None):
    """같은 진영 참가자의 버프 인스턴스 "공용임시생명력"(넨가드 - skill_run이 채운다)이 그 진영 누가 맞든
    적의 공격 피해를 먼저 흡수한다 - 공격한 쪽이 없는 피해(지속피해)와 같은 진영(파티원·인형·시전자 자신)이 준
    피해는 막지 않는다(2026-10-22 사용자 결정). 다 닳으면 그 버프가 사라진다. 채널링이 풀렸으면(시전자가
    쓰러짐·무력화CC) 먼저 지운다(채널링_정리). 흡수하고 남은 피해를 돌려준다."""
    if 공격측 is None or 공격측.get("진영") == 대상.get("진영"):
        return 피해
    채널링_정리(전투상태)
    for 참가자 in 전투상태["참가자"]:
        if 피해 <= 0:
            break
        if 참가자.get("진영") != 대상.get("진영") or not 참가자.get("생존"):
            continue
        for 항목 in list(참가자.get("버프") or []):
            남은 = 항목.get("공용임시생명력")
            if 남은 is None or 피해 <= 0:
                continue
            흡수 = min(남은, 피해)
            피해 -= 흡수
            항목["공용임시생명력"] = 남은 - 흡수
            if 항목["공용임시생명력"] <= 0:
                참가자["버프"].remove(항목)
    return 피해


