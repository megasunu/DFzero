    core.로그(
        전투상태,
        {
            "공격자": 시전자["이름"],
            "대상": 대상["이름"],
            "스킬": 항목.get("이름"),
            "피해": 최종피해,
            "비고": "지속피해 자동 발동",
        },
        종류="비고",
    )
