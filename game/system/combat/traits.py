# 캐릭터는 몬스터와 달리 "특성"이 아니라 "보유특성" 키에 이름이 있고,
# 정의는 전투상태["캐릭터특성정의"](전투_시작()의 정의모음["캐릭터특성정의"])에서
# 찾는다. 능력치/이점/내성/어그로/평타스탯 등 "즉시(영구) 반영" 효과는
