def 특성_턴종료시_발동(전투상태, 참가자):
    """ "발동조건":"턴종료시"인 몬스터특성(냉기방출 등)을 참가자 자신의
    턴이 끝날 때 발동시킨다. "효과"가 "종류":"데미지"이고 "타겟":
    "적전체"인 것만 다룬다(지금까지 나온 유일한 형태). "내성성공시":
    "데미지절반"이면 내성굴림 성공 시 피해를 절반으로 줄인다."""
    for 이름, 정의 in _특성_목록(전투상태, 참가자):
        if 정의.get("분류") != "몬스터특성" or 정의.get("발동조건") != "턴종료시":
            continue
        효과 = 정의.get("효과")
        if not isinstance(효과, dict) or 효과.get("종류") != "데미지":
            continue
        if 효과.get("타겟") != "적전체":
            continue
        상대진영 = "아군" if 참가자["진영"] == "적" else "적"
        for 대상 in [
            p for p in 전투상태["참가자"] if p["진영"] == 상대진영 and p["생존"]
        ]:
            피해 = formula.수식_평가(
                str(효과.get("데미지", "0")), stats.기본_컨텍스트(전투상태, 참가자)
            )
            내성스탯 = 효과.get("내성")
            내성성공 = False
            내성 = None
            if 내성스탯:
                난이도 = formula.수식_평가(
                    str(효과.get("난이도", "10")), stats.기본_컨텍스트(전투상태, 참가자)
                )
                내성성공, 값, 내성보정치 = stats.대상_내성굴림(
                    전투상태, 대상, 내성스탯, 난이도
                )
                내성 = {"DC": 난이도, "값": 값, "성공": 내성성공} | _내성_계산칸(
                    전투상태, 효과.get("난이도", "10"), 내성스탯, 내성보정치
                )
            if 내성성공 and 효과.get("내성성공시") == "데미지절반":
                피해 *= 0.5
            # 내성 성공에도 절반을 맞으므로 늘 연출(사용자 지정 2026-10-14)
            damage.공격연출_기록(
                전투상태, 대상, {"성공": True}, 효과.get("속성"), 효과.get("공격타입")
            )
            최종피해 = damage.피해_적용(
                전투상태, 대상, 피해, 속성=효과.get("속성"), 공격자=참가자
            )
            core.로그(
                전투상태,
                {
                    "공격자": 참가자["이름"],
                    "대상": 대상["이름"],
                    "피해": 최종피해,
                    "비고": f"'{이름}' 특성 턴종료시 발동",
                    **({"내성": 내성} if 내성 else {}),
                },
                종류="비고",
            )


def 특성_피격시_발동(전투상태, 공격자, 피격자):
    """피격자의 몬스터특성 "피격시효과"([{"이름", "확률", "타겟", "효과"}])를, 피격자가 적의 공격에
    명중당할 때마다(피해가 0이어도) 항목마다 확률을 따로 굴려 발동시킨다 - 한 번에 여럿이 터질 수 있다.
    damage.피격_처리가 부르므로 지속피해 같은 공격이 아닌 피해로는 발동하지 않는다. "타겟"은
    "적전체"(피격자의 반대 진영 생존자) 또는 "공격자". "효과"는 상태이상형(내성 실패 시 부여)만 다룬다.
    예) 독샘의 주인 - 20% 독구름(적 전체), 50% 포이즌 블러드(공격자)."""
    if not 피격자.get("생존") or 공격자.get("진영") == 피격자.get("진영"):
        return
    목록 = (
        _특성_목록(전투상태, 피격자)
        + _캐릭터특성_이름정의(전투상태, 피격자)
        + _버프_이름정의(전투상태, 피격자)  # 라키우스 전기 방벽
    )
    for 이름, 정의 in 목록:
        for 항목 in 정의.get("피격시효과") or []:
            if 항목.get("타겟") == "자신":  # 정신이 번쩍!(#325)
                _자신_효과_발동(전투상태, 피격자, 이름, 항목, "피격시")
                continue
            if rng.확률.random() >= 항목.get("확률", 1):
                continue
            if 항목.get("타겟") == "공격자":
                대상들 = [공격자] if 공격자.get("생존") else []
            else:
                대상들 = [
                    p
                    for p in 전투상태["참가자"]
                    if p["진영"] != 피격자["진영"] and p["생존"]
                ]
            if (항목.get("효과") or {}).get(
                "종류"
            ) != "데미지":  # 데미지는 그 줄이 대신한다
                core.로그(
                    전투상태,
                    {
                        "공격자": 피격자["이름"],
                        "대상": [p["이름"] for p in 대상들],
                        "비고": f"'{이름}' 특성 - 피격시 '{항목.get('이름')}' 발동",
                    },
                    종류="비고",
                )
            for 대상 in 대상들:
                효과 = 항목.get("효과") or {}
                if (
                    효과.get("종류") == "데미지"
                ):  # 까칠한피부 - 때린 상대에게 피해(반응·특성 없음)
                    _피격시_반격피해(전투상태, 피격자, 대상, 효과, 항목.get("이름"))
                    continue
                상태이상_효과_적용(
                    전투상태, 피격자, 대상, 효과, f"'{항목.get('이름')}'"
                )


def 특성_스킬사용시_발동(전투상태, 시전자, 스킬이름, 중심대상=None):
    """아군 캐릭터 특성의 "스킬사용시효과"([{"이름", "스킬", "타겟": "자신", "전투당횟수", "효과"}])를,
    "스킬"(이름 목록)에 있는 스킬을 쓴 뒤에 발동시킨다(아수라 "정신이 번쩍!" - 살의의 파동, #325).
    효과 "종류"가 "충격파"면 지정한 적(중심대상 - 스킬이 그 적을 맞혔을 때만 넘어온다)과 양옆에 충격파를 굴린다
    (강렬한 테이크 다운 #381)."""
    for 이름, 정의 in _캐릭터특성_이름정의(전투상태, 시전자):
        for 항목 in 정의.get("스킬사용시효과") or []:
            if 스킬이름 not in (항목.get("스킬") or []):
                continue
            효과 = 항목.get("효과") or {}
            if 효과.get("종류") == "충격파":
                if 중심대상 is not None and 중심대상["진영"] != 시전자["진영"]:
                    damage.충격파_발동(전투상태, 시전자, 중심대상, 효과, 이름)
                continue
            _자신_효과_발동(전투상태, 시전자, 이름, 항목, f"'{스킬이름}' 사용")


def _자신_효과_발동(전투상태, 참가자, 특성이름, 항목, 계기):
    """특성 항목의 "효과"("종류": "버프" - 지속턴이 없으면 전투 끝까지)를 자신에게 건다. "전투당횟수"는
    참가자 "전투당_특성사용횟수"의 특성 이름 칸으로 센다 - 피격시효과와 스킬사용시효과가 함께 쓴다."""
    효과 = 항목.get("효과") or {}
    if 효과.get("종류") != "버프" or not 참가자.get("생존"):
        return
    기록 = 참가자.setdefault("전투당_특성사용횟수", {})
    횟수 = 항목.get("전투당횟수")
    if 횟수 is not None and 기록.get(특성이름, 0) >= 횟수:
        return
    기록[특성이름] = 기록.get(특성이름, 0) + 1
    resources.몬스터_버프_부여(전투상태, 참가자, 효과["이름"], 효과.get("지속턴"))
    core.로그(
        전투상태,
        {
            "공격자": 참가자["이름"],
            "대상": [참가자["이름"]],
            "비고": f"'{특성이름}' 특성 - {계기}로 '{효과['이름']}' 발동",
        },
        종류="비고",
    )


def _피격시_반격피해(전투상태, 피격자, 대상, 효과, 이름):
    """ "피격시효과"의 "종류":"데미지" - 굴린 피해를 대상(때린 상대)에게 준다. 공격자로 넘기지 않아
    반응·피격 특성이 다시 돌지 않는다(공격측은 넘겨 속성강화만)."""
    피해 = formula.수식_평가(str(효과.get("데미지", "0")), {"차수": core.차수(피격자)})
    damage.공격연출_기록(
        전투상태, 대상, {"성공": True}, 효과.get("속성"), 효과.get("공격타입")
    )
    최종피해 = damage.피해_적용(
        전투상태, 대상, 피해, 속성=효과.get("속성"), 공격측=피격자
    )
    core.로그(
        전투상태,
        {
            "공격자": 피격자["이름"],
            "대상": 대상["이름"],
            "피해": 최종피해,
            "비고": f"'{이름}' 피격시 반격 피해",
        },
        종류="비고",
    )


def _버프_이름정의(전투상태, 참가자):
    """참가자 버프 중 "피격시효과"가 있는 것의 (이름, 정의)."""
    결과 = []
    for 항목 in 참가자.get("버프") or []:
        정의 = (전투상태.get("버프정의") or {}).get(
            항목["이름"]
        ) or resources.효과정의_조회(항목["이름"])[0]
        if (정의 or {}).get("피격시효과"):
            결과.append((항목["이름"], 정의))
    return 결과


def _캐릭터특성_이름정의(전투상태, 참가자):
    """아군의 상시 캐릭터 특성 (이름, 정의) - 피격시효과처럼 이름이 필요한 곳용."""
    if 참가자.get("진영") != "아군":
        return []
    정의들 = _캐릭터특성_정의목록(전투상태, 참가자)
    모음 = 전투상태.get("캐릭터특성정의", {})
    return [
        (이름, 모음[이름])
        for 이름 in 참가자["원본"].get("보유특성") or []
        if 이름 in 모음 and any(모음[이름] is 정의 for 정의 in 정의들)
    ]


def 특성_속성피해시_발동(전투상태, 공격자, 대상, 속성들):
    """공격자의 몬스터특성 "속성피해시효과"({"속성", "효과"})를, 공격자가 그 속성 피해를
    적에게 입혔을 때(최종피해 > 0) 발동시킨다. 공격/패턴/소환수/특성 피해 모두 damage.피해_적용
    한 곳에서 부른다. "효과"는 상태이상형("종류":"상태이상" - 내성 실패 시 부여)만 다룬다.
    예) 알비노 고블린 - 명속성 피해를 주면 건강 내성(DC 10+지능보정치) 실패 시 3턴 감전."""
    if not 대상.get("생존"):
        return
    for 이름, 정의 in _특성_목록(전투상태, 공격자):
        조건 = 정의.get("속성피해시효과")
        if not isinstance(조건, dict) or 조건.get("속성") not in 속성들:
            continue
        상태이상_효과_적용(전투상태, 공격자, 대상, 조건.get("효과"), f"'{이름}' 특성")


def 특성_상태이상해제시_발동(전투상태, 참가자, 상태이상이름):
    """ "발동조건"에 "{상태이상이름} 해제시" 문자열이 들어있는 몬스터특성
    (기상 충격파 등)을, 참가자 자신에게서 그 상태이상이 사라질 때
    발동시킨다. "효과"가 "종류":"데미지+상태이상"(기상 충격파 - 피해는 늘, 내성 실패 시 상태이상)
    또는 "종류":"데미지"(알비노 고블린 - "내성성공시":"피해없음"이면 내성에 성공한 대상은 피하고
    실패한 대상만 맞는다)이고 "타겟":"적전체"인 것만 다룬다. 턴_시작_처리()의 지속턴 만료 시점에서 호출한다 -
    피격 등으로 인한 조기 해제는 아직 반영하지 않는다(TODO)."""
    for 이름, 정의 in _특성_목록(전투상태, 참가자):
        if 정의.get("분류") != "몬스터특성":
            continue
        조건 = 정의.get("발동조건")
        조건목록 = 조건 if isinstance(조건, list) else [조건]
        if f"{상태이상이름} 해제시" not in 조건목록:
            continue
        효과 = 정의.get("효과")
        if not isinstance(효과, dict) or 효과.get("종류") not in (
            "데미지+상태이상",
            "데미지",
        ):
            continue
        if 효과.get("타겟") != "적전체":
            continue
        상대진영 = "아군" if 참가자["진영"] == "적" else "적"
        for 대상 in [
            p for p in 전투상태["참가자"] if p["진영"] == 상대진영 and p["생존"]
        ]:
            if 효과.get("내성성공시") == "피해없음":
                _해제시_회피형_공격(전투상태, 참가자, 대상, 이름, 효과, 상태이상이름)
                continue
            피해 = formula.수식_평가(
                str(효과.get("데미지", "0")), stats.기본_컨텍스트(전투상태, 참가자)
            )
            # 피해는 늘 들어가므로 늘 연출(사용자 지정 2026-10-14)
            damage.공격연출_기록(
                전투상태, 대상, {"성공": True}, 효과.get("속성"), 효과.get("공격타입")
            )
            최종피해 = damage.피해_적용(
                전투상태, 대상, 피해, 속성=효과.get("속성"), 공격자=참가자
            )
            내성스탯 = 효과.get("내성")
            부여 = not 내성스탯
            내성 = None
            if 내성스탯:
                난이도 = formula.수식_평가(
                    str(효과.get("난이도", "10")), stats.기본_컨텍스트(전투상태, 참가자)
                )
                성공, 값, 내성보정치 = stats.대상_내성굴림(
                    전투상태, 대상, 내성스탯, 난이도, 효과.get("상태이상")
                )
                부여 = not 성공
                내성 = {"DC": 난이도, "값": 값, "성공": 성공} | _내성_계산칸(
                    전투상태, 효과.get("난이도", "10"), 내성스탯, 내성보정치
                )
            if (
                부여
                and 효과.get("상태이상")
                and status.상태이상_면역(전투상태, 대상, 효과["상태이상"])
            ):
                status.면역_로그(전투상태, 대상, 효과["상태이상"], f"'{이름}' 특성")
                부여 = False
            if (
                부여
                and 효과.get("적용시점") in (None, "실패시")
                and 효과.get("상태이상")
            ):
                대상.setdefault("상태이상", []).append(
                    {
                        "이름": 효과.get("상태이상"),
                        "지속턴": 효과.get("지속턴", 1),
                    }
                )
                status.영창_방해(전투상태, 대상, 효과.get("상태이상"))
            core.로그(
                전투상태,
                {
                    "공격자": 참가자["이름"],
                    "대상": 대상["이름"],
                    "피해": 최종피해,
                    "비고": f"'{이름}' 특성 발동 ('{상태이상이름}' 해제)",
                    **({"내성": 내성} if 내성 else {}),
                },
                종류="비고",
            )


def _해제시_회피형_공격(전투상태, 참가자, 대상, 이름, 효과, 상태이상이름):
    """해제시 특성의 "종류":"데미지" + "내성성공시":"피해없음" - 내성을 먼저 굴려 성공하면 피하고,
    실패하면 "데미지"를 그 속성으로 입힌다(알비노 고블린 넘어짐 해제)."""
    컨텍스트 = stats.기본_컨텍스트(전투상태, 참가자)
    내성스탯 = 효과.get("내성")
    난이도 = formula.수식_평가(str(효과.get("난이도", "10")), 컨텍스트)
    성공, 값, 내성보정치 = stats.대상_내성굴림(전투상태, 대상, 내성스탯, 난이도)
    # 내성으로 피하면 실패 연출(사용자 지정 2026-10-14)
    damage.공격연출_기록(
        전투상태, 대상, {"성공": not 성공}, 효과.get("속성"), 효과.get("공격타입")
    )
    최종피해 = 0
    if not 성공:
        피해 = formula.수식_평가(str(효과.get("데미지", "0")), 컨텍스트)
        최종피해 = damage.피해_적용(
            전투상태, 대상, 피해, 속성=효과.get("속성"), 공격자=참가자
        )
    core.로그(
        전투상태,
        {
            "공격자": 참가자["이름"],
            "대상": 대상["이름"],
            "피해": 최종피해,
            "비고": f"'{이름}' 특성 발동 ('{상태이상이름}' 해제)"
            + (" - 내성 성공으로 회피" if 성공 else ""),
            "내성": {"DC": 난이도, "값": 값, "성공": 성공}
            | _내성_계산칸(전투상태, 효과.get("난이도", "10"), 내성스탯, 내성보정치),
        },
        종류="비고",
    )


def _내성_계산칸(전투상태, 식, 스탯, 보정치):
    """자세한 로그용 - 내성 DC 식과 굴림의 스탯/보정치(상세로그가 아니면 빈 dict)."""
    if not 전투상태.get("상세로그"):
        return {}
    return {"식": str(식), "스탯": 스탯, "보정": 보정치}


def _집계_수(전투상태, 참가자, 집계조건):
    """몬스터특성 "집계조건"({"범위":"필드", "분류":..., "자신제외":...})에
    맞는 생존 참가자 수. "분류"는 몬스터 원본 "분류"와 비교한다."""
    수 = 0
    for p in 전투상태["참가자"]:
        if not p["생존"]:
            continue
        if 집계조건.get("자신제외") and p is 참가자:
            continue
        if 집계조건.get("분류") and p.get("원본", {}).get("분류") != 집계조건["분류"]:
            continue
        수 += 1
    return 수


def 전투시작_특성(전투상태):
    """ "발동조건":"전투시작시" 몬스터특성을 전투 시작 때 한 번 발동한다
    지금은 "종류":"임시생명력", "타겟":"자신"만 처리한다(겁쟁이).
    "수치" 수식의 "고블린수"는 "집계조건"으로 센 값으로 바꿔 평가한다."""
    for 참가자 in [p for p in 전투상태["참가자"] if p["생존"]]:
        # 아군 특성의 "전투시작버프"(트랜스포메이션 - G-1) - 지속턴 없이 건다
        if 참가자.get("진영") == "아군":
            for 정의 in _캐릭터특성_정의목록(전투상태, 참가자):
                if 정의.get("전투시작버프"):
                    resources.몬스터_버프_부여(
                        전투상태, 참가자, 정의["전투시작버프"], None
                    )
        for 이름, 정의 in _특성_목록(전투상태, 참가자):
            if 정의.get("전투시작상태"):  # 인형관의 주인 - 상시 슈퍼아머(지속턴 없음)
                참가자.setdefault("상태이상", []).append(
                    {"이름": 정의["전투시작상태"], "지속턴": None}
                )
            if 정의.get("분류") != "몬스터특성" or 정의.get("발동조건") != "전투시작시":
                continue
            효과 = 정의.get("효과")
            if not isinstance(효과, dict) or 효과.get("종류") != "임시생명력":
                continue
            if 효과.get("타겟", "자신") != "자신":
                continue
            수식 = str(효과.get("수치", "0"))
            집계조건 = 효과.get("집계조건") or {}
            if 집계조건:
                집계명 = f"{집계조건.get('분류', '')}수"
                수식 = 수식.replace(집계명, str(_집계_수(전투상태, 참가자, 집계조건)))
            양 = max(0, formula.올림(stats.몬스터_수식값(전투상태, 참가자, 수식)))
            if 양 <= 0:
                continue
            참가자["임시생명력"] = 참가자.get("임시생명력", 0) + 양
            core.로그(
                전투상태,
                {
                    "대상": 참가자["이름"],
                    "비고": f"'{이름}' 특성 - 임시생명력 {양} 획득",
                },
                종류="비고",
            )
