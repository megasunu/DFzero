def 장착무기_타입(참가자):
    무기 = (참가자.get("장비데이터") or {}).get("무기") or {}
    return equipment_system.무기_종류(무기)


def _캐릭터특성_정의목록(전투상태, 참가자):
    """상시 적용 대상인 캐릭터 특성 정의만 골라 반환한다."""
    정의모음 = 전투상태.get("캐릭터특성정의", {})
    결과 = []
    켜진특성 = 참가자["원본"].get("켜진특성") or []
    for 이름 in 참가자["원본"].get("보유특성") or []:
        정의 = 정의모음.get(이름)
        if 정의 is None or (정의.get("토글") and 이름 not in 켜진특성):
            continue
        if 정의.get("분류") == "강화특성":
            continue
        if 정의.get("발동조건") is not None:
            continue
        # 무기 마스터리 - 그 종류의 무기를 들었을 때만
        if 정의.get("무기조건") and 정의["무기조건"] != 장착무기_타입(참가자):
            continue
        # 방어구 숙련 - 방어구 5부위가 모두 그 재질일 때만
        if 정의.get("방어구조건") and 정의[
            "방어구조건"
        ] != equipment_system.방어구_세트재질(참가자.get("장비데이터") or {}):
            continue
        결과.append(정의)
    return 결과


def _형태(참가자):
    """란마 1/2 - 지금 형태("f"/"m"): 속성에 맞아 바뀐 "란마성별", 맞기 전에는 "성별"."""
    원본 = 참가자["원본"]
    return 원본.get("란마성별") or 원본.get("성별") or "m"


def _형태들(전투상태, 참가자):
    """보유 특성의 "형태"(야빠빠 야빠빠 - 하위 이름 낭익천/남익천 #462) 정의들 {"형태성별", "형태속성"}."""
    return [
        형태
        for 정의 in _캐릭터특성_정의목록(전투상태, 참가자)
        for 형태 in (정의.get("형태") or {}).values()
    ]


def 형태_속성(전투상태, 참가자):
    """란마 1/2 - 지금 형태와 "형태성별"이 같은 형태(낭익천/남익천)의 "형태속성". 없으면 None.
    그 속성에 저항(damage.속성_피해배율)하고 공격에 그 속성을 더한다(stats.공격_속성)."""
    if 참가자.get("진영") != "아군":
        return None
    형태 = _형태(참가자)
    for 정의 in _형태들(전투상태, 참가자):
        if 정의.get("형태성별") == 형태 and 정의.get("형태속성"):
            return 정의["형태속성"]
    return None


_형태_이름 = {"f": "여자", "m": "남자"}


def 형태_변환(전투상태, 대상, 속성들):
    """란마 1/2 - 맞은 공격의 속성 중 보유 특성 형태의 "형태속성"이 있으면 그 형태가 된다
    (캐릭터 "란마성별" - 전투가 끝나도 남는다). 피격_처리가 명중했을 때 부른다."""
    if 대상.get("진영") != "아군":
        return
    정의들 = _형태들(전투상태, 대상)
    for 속성 in 속성들:
        for 정의 in 정의들:
            if 정의.get("형태속성") != 속성 or not 정의.get("형태성별"):
                continue
            새형태 = 정의["형태성별"]
            if _형태(대상) != 새형태:
                대상["원본"]["란마성별"] = 새형태
                core.로그(
                    전투상태,
                    {
                        "대상": 대상["이름"],
                        "비고": f"{속성}에 맞아 {_형태_이름[새형태]}가 되었다",
                    },
                    종류="비고",
                )
            elif "란마성별" not in 대상["원본"]:
                대상["원본"]["란마성별"] = 새형태
            return


def 데미지이점(전투상태, 참가자):
    """아군의 상시 특성 중 "데미지이점": True가 있는지(전투 스타일 "강타")."""
    if 참가자.get("진영") != "아군":
        return False
    return any(
        정의.get("데미지이점") for 정의 in _캐릭터특성_정의목록(전투상태, 참가자)
    )


def 상태이상_내성이점(전투상태, 대상, 상태이상이름):
    """아군이 이 상태이상의 내성굴림에 이점을 갖는지 - 상시 특성의
    "상태이상내성이점"(상태이상 "분류" 목록, 예: 가죽숙달 ["지속피해형"])."""
    if 대상.get("진영") != "아군" or not 상태이상이름:
        return False
    분류 = (전투상태.get("상태이상정의", {}).get(상태이상이름) or {}).get("분류")
    if 분류 in status.버프_분류목록(전투상태, 대상, "상태이상내성이점"):
        return True  # 버프(폭주 #247 - 약화CC/지속피해형)
    return any(
        분류 in (정의.get("상태이상내성이점") or [])
        for 정의 in _캐릭터특성_정의목록(전투상태, 대상)
    )


def _캐릭터특성_항목목록(정의):
    """특성 "효과"를 (원래이름, 변동값, 원소) 튜플 리스트로 펼친다."""
    효과 = 정의.get("효과")
    원소들 = [효과] if isinstance(효과, dict) else (효과 or [])
    결과 = []
    for 원소 in 원소들:
        if not isinstance(원소, dict):
            continue
        if "변동대상" in 원소:
            결과.append((원소["변동대상"], 원소.get("변동값", 0), 원소))
        else:
            for 키, 값 in 원소.items():
                결과.append((키, 값, 원소))
    return 결과


def _캐릭터특성_조건충족(전투상태, 조건, 명중률종류, 대상, 속성):
    if 조건 is None:
        return True
    if 조건 == "주문":
        return 명중률종류 == "주문시전명중률"
    if 조건 == "첫턴":
        return 전투상태.get("라운드", 1) == 1
    if 조건 == "약점":
        if 대상 is None or 속성 is None:
            return False
        속성들 = 속성 if isinstance(속성, list) else [속성]
        return any(damage.속성_피해배율(전투상태, 대상, s) > 1 for s in 속성들)
    return False


def _원소_조건충족(참가자, 원소, 스킬타입):
    """효과 원소 단위 조건 - "스킬타입조건"(그 타입 스킬의 공격만, 메모라이즈)과 "상태조건"(참가자가 그
    상태이상일 때만, 이동캐스팅의 "캐스팅")."""
    조건타입 = 원소.get("스킬타입조건")
    if 조건타입 and not set(조건타입).intersection(스킬타입 or ()):
        return False
    상태 = 원소.get("상태조건")
    if 상태 and not any(s.get("이름") == 상태 for s in 참가자.get("상태이상") or []):
        return False
    버프 = 원소.get("버프조건")  # 니트로모터 - 공중사격 버프가 있을 때만(#391)
    if 버프 and not any(b.get("이름") == 버프 for b in 참가자.get("버프") or []):
        return False
    특성 = 원소.get("특성조건")  # 오라 실드 - 강화오라실드가 있을 때만(2026-10-26)
    return not 특성 or 특성 in ((참가자.get("원본") or {}).get("보유특성") or [])


def _캐릭터특성_수치(
    전투상태,
    참가자,
    변동대상,
    명중률종류=None,
    대상=None,
    속성=None,
    행동종류=None,
    스킬타입=None,
):
    합계 = 0
    컨텍스트 = None
    for 정의 in _캐릭터특성_정의목록(전투상태, 참가자):
        for 원래이름, 값, 원소 in _캐릭터특성_항목목록(정의):
            매핑 = _캐릭터특성_이름매핑.get(원래이름)
            if 매핑 is None or not common_names.같은_변동대상(매핑[0], 변동대상):
                continue
            if 원소.get("무기조건") and 원소["무기조건"] != 장착무기_타입(참가자):
                continue
            if not _원소_조건충족(참가자, 원소, 스킬타입):
                continue
            if (
                변동대상 == "행동보너스"
                and 행동종류 is not None
                and 원소.get("행동종류") != 행동종류
            ):
                continue
            if not _캐릭터특성_조건충족(전투상태, 매핑[1], 명중률종류, 대상, 속성):
                continue
            if isinstance(값, bool):
                continue
            if isinstance(값, str) and "쓰러진아군수" in 값:
                값 = 값.replace("쓰러진아군수", str(쓰러진아군수(전투상태, 참가자)))
            if isinstance(값, str) and "혈십자단계" in 값:
                값 = 값.replace(
                    "혈십자단계",
                    str(
                        혈십자_단계(
                            참가자["현재HP"], stats.유효_최대HP(전투상태, 참가자)
                        )
                    ),
                )
            if isinstance(값, str):
                if 컨텍스트 is None:
                    컨텍스트 = {
                        "차수": core.차수(참가자),
                        "레벨": 참가자["원본"].get("레벨") or 1,
                        "주문시전보정치": stats.주문시전_보정치(전투상태, 참가자),
                        "능력치": stats.유효_능력치(전투상태, 참가자),
                        "능력치보정치": 캐릭터데이터.보정치표(
                            참가자["원본"], stats.유효_능력치(전투상태, 참가자)
                        ),
                    }
                try:
                    값 = formula.수식_평가(값, 컨텍스트)
                except Exception:
                    continue
            if isinstance(값, (int, float)):
                합계 += 값
    return 합계


def 혈십자_단계(현재HP, 최대HP):
    """버서커 혈십자(#247) - HP 비율을 20%씩 5단계로 나눈다. 가득 차면 1단계, 20% 이하면 5단계,
    경계(80%/60%/40%/20%)는 높은 단계. 특성 수식의 "혈십자단계"가 이 값이다."""
    if 최대HP <= 0:
        return 1
    return min(5, max(1, 6 - formula.올림(현재HP * 5 / 최대HP)))


