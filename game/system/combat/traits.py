# 참가자 원본의 "특성"(이름 리스트)을 전투상태["특성정의"](전투_시작()의
# 정의모음["특성정의"])에서 찾아 실제 수치/트리거로 반영한다. "효과"가 리스트면
# (종족특성 공통형/일부 몬스터특성) 버프디버프_수치()와 같은 "변동대상"
# 어휘로 합산하고, "효과"가 딕셔너리("종류":"상태이상"/"데미지"/"데미지+
# 상태이상")면 트리거형이라 여기서 다루지 않는다(피격_처리/턴_종료_처리/
# 턴_시작_처리의 훅에서 별도 처리).


def _특성_목록(전투상태, 참가자):
    """참가자 원본의 "특성"을 전투상태["특성정의"]에서 찾아 (이름, 정의)
    튜플 리스트로 반환한다. 정의가 없는 이름(오타/미등록)은 건너뛴다."""
    결과 = []
    for 이름 in 참가자.get("원본", {}).get("특성") or []:
        정의 = 전투상태.get("특성정의", {}).get(이름)
        if 정의 is not None:
            결과.append((이름, 정의))
    return 결과


def 능력치특성_반영(특성정의모음, 몬스터원본):
    """특성 "효과" 리스트의 {"변동대상": "능력치", "변동값": n}(여섯 능력치 모두 +n,
    예: 황금도둑)을 몬스터 원본 사본에 더해 돌려준다. 전투_시작()이 참가자를 만들기
    전에 불러, 최대HP/AC/속도/특성 수식이 모두 올라간 능력치로 계산되게 한다.
    해당 효과가 없으면 원본을 그대로 돌려준다."""
    합계 = 0
    for 이름 in 몬스터원본.get("특성") or []:
        효과 = (특성정의모음.get(이름) or {}).get("효과")
        if not isinstance(효과, list):
            continue
        for 항목 in 효과:
            값 = 항목.get("변동값")
            if 항목.get("변동대상") == "능력치" and isinstance(값, (int, float)):
                합계 += 값
    if not 합계:
        return 몬스터원본
    사본 = dict(몬스터원본)
    for 이름 in common_names.능력치_목록:
        if isinstance(사본.get(이름), (int, float)):
            사본[이름] += 합계
    return 사본


def _도망턴(전투상태, 참가자):
    """특성의 "도망턴"(자신의 턴이 이 횟수만큼 끝나면 도망) 중 가장 작은 값, 없으면 None."""
    값들 = [
        정의["도망턴"]
        for _, 정의 in _특성_목록(전투상태, 참가자)
        if isinstance(정의.get("도망턴"), int)
    ]
    return min(값들) if 값들 else None


def 도망_검사(전투상태, 참가자):
    """자신의 턴이 끝날 때 불린다. "도망턴" 특성이 있는 적은 끝난 턴을 세다가 그
    횟수가 되면 전투에서 빠진다 - "생존"은 False가 되지만 "도망"이 True라 처치로
    치지 않는다(전투_종료_판정 / gameflow 전리품). 도망쳤으면 True."""
    if 참가자["진영"] != "적" or not 참가자["생존"]:
        return False
    도망턴 = _도망턴(전투상태, 참가자)
    if 도망턴 is None:
        return False
    참가자["끝난턴수"] = 참가자.get("끝난턴수", 0) + 1
    if 참가자["끝난턴수"] < 도망턴:
        return False
    참가자["생존"] = False
    참가자["도망"] = True
    core.로그(전투상태, {"공격자": 참가자["이름"], "행동": "도망쳤다!"}, 종류="행동")
    return True


def 체력소환(전투상태, 참가자):
    """특성의 "체력소환"({"몬스터", "체력비율", "캐스팅우선도"}) 첫 것, 없으면 None(인형사의 골렘 소환 #464 -
    monster_actions.소환_캐스팅_시작)."""
    return next(
        (
            정의["체력소환"]
            for _, 정의 in _특성_목록(전투상태, 참가자)
            if isinstance(정의.get("체력소환"), dict)
        ),
        None,
    )


def 특성_항목(전투상태, 참가자, 키):
    """몬스터 특성 정의의 그 키 값 중 첫 것, 없으면 None - 용인족의 "턴시작감옥"/"버프스킬반응"/
    "처치시오라강화"/"명중시버프강탈"(monster_actions, damage)."""
    return next(
        (
            정의[키]
            for _, 정의 in _특성_목록(전투상태, 참가자)
            if 정의.get(키) not in (None, False)
        ),
        None,
    )


def 주기상태_부여(전투상태, 참가자):
    """자신의 차례가 시작될 때(지속턴을 줄인 뒤) 불린다. 특성의 "주기상태"({"이름", "시작차례", "주기",
    "지속턴"})가 있으면 시작한 차례를 세다가 "시작차례"번째와 그 뒤 "주기"차례마다 상태이상 "이름"을
    "지속턴"만큼 건다(종족:골렘의 슈퍼아머 - 2026-10-29 사용자 지정)."""
    주기들 = [
        정의["주기상태"]
        for _, 정의 in _특성_목록(전투상태, 참가자)
        if isinstance(정의.get("주기상태"), dict)
    ]
    if not 주기들 or not 참가자["생존"]:
        return
    참가자["시작한차례수"] = 차례 = 참가자.get("시작한차례수", 0) + 1
    for 주기 in 주기들:
        시작 = 주기.get("시작차례", 1)
        if 차례 >= 시작 and (차례 - 시작) % max(1, 주기.get("주기", 1)) == 0:
            resources.몬스터_버프_부여(
                전투상태, 참가자, 주기["이름"], 주기.get("지속턴")
            )


def _조건부효과_충족(전투상태, 참가자, 조건부효과):
    """job_ability_format.py <일반특성 추가 키> "발동조건"+"조건값"
    패턴을 특성의 "조건부효과"에도 재사용한다. 지금은 "적상태"(반대
    진영 생존자 중 "조건값" 이름의 상태로 판정되는 자가 있는지 - 샹들리에의 상시
    공중에뜸 포함)만 다룬다(종족:좀비의 '출혈' 조건이 이 형태)."""
    if not 조건부효과:
        return False
    조건 = 조건부효과.get("발동조건")
    조건값 = 조건부효과.get("조건값")
    if 조건 == "적상태":
        상대진영 = "아군" if 참가자["진영"] == "적" else "적"
        return any(
            p["생존"] and status.상태이상_판정(전투상태, p, 조건값)
            for p in 전투상태["참가자"]
            if p["진영"] == 상대진영
        )
    return False


def _특성_효과리스트_모음(전투상태, 참가자):
    """참가자의 특성들 중 "효과"가 리스트인 것(상시), "상시효과" 리스트, "조건부효과"가
    있고 조건이 충족된 것의 "효과" 리스트를 전부 모아 반환한다."""
    모음 = []
    for _, 정의 in _특성_목록(전투상태, 참가자):
        효과 = 정의.get("효과")
        if isinstance(효과, list):
            모음.append(효과)
        # "효과"가 트리거(딕셔너리)인 특성의 상시 효과 리스트(화염의 마녀 저항/취약 등)
        if isinstance(정의.get("상시효과"), list):
            모음.append(정의["상시효과"])
        조건부 = 정의.get("조건부효과")
        if 조건부 and _조건부효과_충족(전투상태, 참가자, 조건부):
            조건부목록 = 조건부.get("효과")
            if isinstance(조건부목록, list):
                모음.append(조건부목록)
    return 모음


def 속성_특성_수치(전투상태, 참가자, 변동대상, 속성):
    """특성 효과 원소 중 변동대상이 같고 "속성"이 그 속성이거나 "전체"인 것의 숫자
    변동값 합(속성강화/속성내성). 몬스터 특성과 아군 상시 특성 모두."""
    원소들 = [원소 for 효과 in _특성_효과리스트_모음(전투상태, 참가자) for 원소 in 효과]
    if 참가자.get("진영") == "아군":
        for 정의 in _캐릭터특성_정의목록(전투상태, 참가자):
            원소들 += [원소 for _, _, 원소 in _캐릭터특성_항목목록(정의)]
    합계 = 0
    for 원소 in 원소들:
        if not isinstance(원소, dict) or not common_names.같은_변동대상(
            원소.get("변동대상"), 변동대상
        ):
            continue
        if 원소.get("속성") not in (속성, "전체"):
            continue
        값 = 원소.get("변동값", 0)
        if isinstance(값, str) and "쓰러진아군수" in 값:  # 주인공
            값 = formula.수식_평가(
                값.replace("쓰러진아군수", str(쓰러진아군수(전투상태, 참가자))), {}
            )
        if isinstance(값, (int, float)):
            합계 += 값
    return 합계


def 쓰러진아군수(전투상태, 참가자):
    """주인공의 운명(특성 "주인공") - 참가자와 같은 진영에서 쓰러진 참가자 수(자신 제외, 교체된 인형 제외).
    인형은 그 진영에 "내아내몬" 보유자가 있을 때만 아군으로 센다(사용자 결정 2026-10-20)."""
    같은편 = [p for p in 전투상태["참가자"] if p.get("진영") == 참가자.get("진영")]
    내아내몬 = any(
        "내아내몬" in ((p.get("원본") or {}).get("보유특성") or []) for p in 같은편
    )
    return sum(
        1
        for p in 같은편
        if p is not 참가자
        and not p.get("생존", True)
        and not p.get("교체됨")
        and (내아내몬 or not p.get("인형"))
    )


def 특성_수치(
    전투상태,
    참가자,
    변동대상,
    명중률종류=None,
    대상=None,
    속성=None,
    행동종류=None,
    스킬타입=None,
):
    """특성의 "변동대상"에 해당하는 (숫자) "변동값"을 전부 더한다 -
    버프디버프_수치()의 특성판. "변동대상" 이름은 별칭까지
    같은 것을 찾는다(common_names.같은_변동대상 - 예: "속도" = "속도보너스"). 변동값이 수식 문자열이면
    평가하되, "저항"/"취약"처럼 속성 이름 문자열(수식으로 평가할 수
    없는 값)이면 조용히 건너뛴다(그런 변동대상은
    특성_문자열_변동값_목록() 몫).

    아군이면 캐릭터 "보유특성"(job_ability_XX.py)도 더한다
    (_캐릭터특성_수치 참고). 명중률종류/대상/속성/행동종류/스킬타입은
    그쪽의 조건부 항목(공격주문 전용/약점속성/행동보너스 종류/"스킬타입조건")
    판정에만 쓴다."""
    합계 = 0
    if 참가자.get("진영") == "아군":
        합계 += _캐릭터특성_수치(
            전투상태,
            참가자,
            변동대상,
            명중률종류=명중률종류,
            대상=대상,
            속성=속성,
            행동종류=행동종류,
            스킬타입=스킬타입,
        )
    for 효과리스트 in _특성_효과리스트_모음(전투상태, 참가자):
        for 원소 in 효과리스트:
            if not common_names.같은_변동대상(원소.get("변동대상"), 변동대상):
                continue
            변동값 = 원소.get("변동값", 0)
            if isinstance(변동값, str):
                try:
                    변동값 = formula.수식_평가(
                        변동값,
                        {
                            "차수": core.차수(참가자),
                            "레벨": 참가자.get("원본", {}).get("레벨") or 1,
                            "능력치": 참가자["원본"],
                            "능력치보정치": 캐릭터데이터.보정치표(참가자["원본"]),
                        },
                    )
                except Exception:
                    continue
            if isinstance(변동값, (int, float)):
                합계 += 변동값
    return 합계


def 특성_문자열_변동값_목록(전투상태, 참가자, 변동대상):
    """ "저항"/"취약"처럼 변동값이 속성 이름 문자열인 특성 효과들을
    모아 리스트로 반환한다(특성_수치()의 문자열 버전 - 같은
    common_names.같은_변동대상으로 비교한다)."""
    결과 = []
    for 효과리스트 in _특성_효과리스트_모음(전투상태, 참가자):
        for 원소 in 효과리스트:
            if common_names.같은_변동대상(
                원소.get("변동대상"), 변동대상
            ) and isinstance(원소.get("변동값"), str):
                결과.append(원소["변동값"])
    return 결과


