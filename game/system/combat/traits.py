    개수 = 특성_수치(전투상태, 공격자, "명중시체이서") + stats.버프디버프_수치(
        전투상태, 공격자, "명중시체이서"
    )
    if 개수 > 0:
        resources.체이서_얻기(전투상태, 공격자, 개수)


