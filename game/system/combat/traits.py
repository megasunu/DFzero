# 참가자 원본의 "칭호"(예: "보스")를 전투상태["칭호정의"]에서 찾는다.
# 칭호가 None이거나 정의에 없는 이름("미정" 등)이면 아무 효과도 없다.
# "변동값"이 수식(예: "2×차수")이면 몬스터 원본의 레벨/차수/능력치로
# 평가한다. 칭호 데이터의 "명중률보너스"는 엔진이 쓰는 "명중보너스"로
# 맞춰 읽는다.


def _칭호_효과목록(전투상태, 참가자):
    칭호 = 참가자.get("원본", {}).get("칭호")
    if not isinstance(칭호, str):
        return []
    정의 = 전투상태.get("칭호정의", {}).get(칭호)
    if not 정의:
        return []
    효과 = 정의.get("효과")
    if isinstance(효과, dict):
        return [효과]
    return 효과 or []


def 칭호_수치(전투상태, 참가자, 변동대상):
    """칭호 효과 중 "변동대상"에 해당하는 "변동값"을 전부 더한다."""
    합계 = 0
    for 원소 in _칭호_효과목록(전투상태, 참가자):
        if (
            not common_names.같은_변동대상(원소.get("변동대상"), 변동대상)
            or "변동값" not in 원소
        ):
            continue
        값 = participants.몬스터_수식_평가(원소["변동값"], 참가자["원본"], 0)
        if isinstance(값, (int, float)):
            합계 += 값
    return 합계


def 특성_배율(전투상태, 참가자, 변동대상):
    """특성 효과 중 "변동대상"에 해당하는 "배율"을 전부 곱한다(없으면 1) - 칭호_배율()의
    특성판(돌연변이:거대화 최대HP 2배 - 사용자 지정 2026-10-14)."""
    배율 = 1
    for 효과리스트 in _특성_효과리스트_모음(전투상태, 참가자):
        for 원소 in 효과리스트:
            if common_names.같은_변동대상(
                원소.get("변동대상"), 변동대상
            ) and isinstance(원소.get("배율"), (int, float)):
                배율 *= 원소["배율"]
    return 배율


def 행동주기(전투상태, 참가자):
    """ "행동주기" 변동값이 있는 특성의 (주기, 특성 이름). 주기 N이면 자기 차례 N번에
    한 번(N, 2N, ...번째)만 행동한다. 없으면 (1, None)(돌연변이:거대화 - 사용자 지정 2026-10-14)."""
    for 이름, 정의 in _특성_목록(전투상태, 참가자):
        for 원소 in 정의.get("효과") if isinstance(정의.get("효과"), list) else []:
            if 원소.get("변동대상") == "행동주기" and isinstance(
                원소.get("변동값"), int
            ):
                return max(1, 원소["변동값"]), 이름
    return 1, None


def 대체행동(전투상태, 참가자, 상대들, 사용횟수=None):
    """ "대체행동" 특성의 조건이 맞으면 (패턴, 대상), 아니면 None.
    사용횟수({특성이름: 이번 턴에 쓴 횟수})를 주면 "대체횟수"(없으면 1, 숫자 또는 "전부")까지만 쓰고
    쓸 때마다 센다 - 몬스터는 한 턴에 차수만큼 행동한다(사용자 지정 2026-10-14).
    조건 {"적상태이상": 이름} - 상대들(생존자) 중 그 상태이상이 있는 대상 중 무작위 한 명(특수패턴:샤우타).
    조건 {"시전자상태이상": 이름} - 이 참가자가 건 그 상태이상이 있는 대상. "해제"면 그 상태이상을 지운다
    (특수패턴:펜릴의 들러붙음 -> 피니쉬!). 사용자 지정 2026-10-14."""
    for 특성이름, 정의 in _특성_목록(전투상태, 참가자):
        대체 = 정의.get("대체행동")
        if not isinstance(대체, dict):
            continue
        if 사용횟수 is not None:
            한도 = 대체.get("대체횟수", 1)
            if 한도 != "전부" and 사용횟수.get(특성이름, 0) >= 한도:
                continue
        선택 = _대체행동_대상(참가자, 상대들, 대체)
        if 선택 is not None:
            if 사용횟수 is not None:
                사용횟수[특성이름] = 사용횟수.get(특성이름, 0) + 1
            return 선택
    return None


def _대체행동_대상(참가자, 상대들, 대체):
    """대체행동 하나의 조건을 보고 (패턴, 대상) 또는 None. 대상이 None이면 평소처럼 고른다."""
    조건 = 대체.get("조건") or {}
    if (
        "자신상태이상" in 조건
    ):  # 특수패턴:케라하/비노슈 - 주문영창 상태면 그 주문을 시전하고 푼다
        상태이름 = 조건["자신상태이상"]
        if not any(s["이름"] == 상태이름 for s in 참가자.get("상태이상", [])):
            return None
        if 대체.get("해제"):
            참가자["상태이상"] = [
                s for s in 참가자["상태이상"] if s["이름"] != 상태이름
            ]
        return 대체["패턴"], None
    if "시전자상태이상" in 조건:
        상태이름 = 조건["시전자상태이상"]
        for p in 상대들:
            걸린것 = [
                s
                for s in p.get("상태이상", [])
                if s["이름"] == 상태이름 and s.get("시전자id") == 참가자["id"]
            ]
            if p["생존"] and 걸린것:
                if 대체.get("해제"):
                    p["상태이상"] = [s for s in p["상태이상"] if s not in 걸린것]
                return 대체["패턴"], p
        return None
    상태이름 = 조건.get("적상태이상")
    후보 = [
        p
        for p in 상대들
        if p["생존"] and any(s["이름"] == 상태이름 for s in p.get("상태이상", []))
    ]
    if 후보:
        return 대체["패턴"], rng.대상.choice(후보)
    return None


