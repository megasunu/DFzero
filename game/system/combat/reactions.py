# 캐릭터 반응스킬
# =====================================================
# job_skill_XX.py "분류":"반응스킬"(보유스킬)을 자동으로 발동한다(플레이어에게
# 묻지 않음 - 조건과 자원이 맞으면 바로 쓴다). 발동 시점:
#   - 회피형(효과 "회피성공":True, 발동조건 "0 <= 명중성공차이 <= 2" 류 -
#     크라우치/컷 인 대쉬/축지성촌/위빙): 적의 명중결과가 자신 AC를 0~2 넘겨
#     명중했을 때 빗나감으로 바꾼다(치명타 굴림은 제외). → 명중_판정
#   - "회피성공시" 반격(백스텝커터/리벤저): 적의 공격이 빗나가면 공격자에게
#     "효과"의 공격을 한다. 반격은 그 적의 공격 로그 뒤에 나오도록 반응대기에
#     넣었다가 반응대기_처리()에서 실행한다.
#   - "피격시"(건가드 피해감소 / 위상 변화 피해무효): 적의 공격·능력으로
#     피해를 받을 때. 자동 사용이면 피해무효를 쓰러지지 않는 피해에도 바로 쓰고,
#     쓸 수 없으면 피해감소형을 쓴다. → 피해_적용(공격자=...)
#   - "적상태" + 조건값(공중연속베기 - 공중에뜸): 그 상태의 적을 공격한 뒤
#     추가 공격. → 공격후_반응 (일반공격_실행, skill_system.공격_1회)
#   - "전투시작시"(패스티스트 건): 전투 시작 직후 무작위 적에게 공격하고
#     "디버프획득"을 "지속턴"만큼 자신에게 건다. → 전투시작_반응
# 자원: "행동"(반응행동 등)을 1 소모. "전투당횟수"는 참가자["전투당_특성사용횟수"],
# "휴식당횟수"는 스킬과 같은 캐릭터["횟수제한스킬"]["휴식제한스킬"](휴식 시
# 초기화)에 남은 횟수로 기록한다. "조건부효과"의 {"조건":"특성보유"}(강화
# 위상변화)는 "사용제한":"전투당1회"로 횟수 규칙을 바꾸고 "부여효과"(속도증가
# 등)를 자신에게 건다. 행동불가 상태면 반응하지 않는다.


def _반응스킬_목록(전투상태, 참가자):
    if 참가자.get("진영") != "아군":
        return []
    정의모음 = 전투상태.get("스킬정의", {})
    결과 = []
    for 이름 in 참가자["원본"].get("보유스킬") or []:
        정의 = 정의모음.get(이름)
        if 정의 and 정의.get("분류") == "반응스킬":
            결과.append((이름, 정의))
    return 결과


def _반응_횟수규칙(전투상태, 참가자, 정의):
    """(휴식당최대 또는 None, 전투당최대 또는 None, 부여효과 또는 None)."""
    휴식당 = 정의.get("휴식당횟수")
    전투당 = 정의.get("전투당횟수")
    부여효과 = None
    보유 = 참가자["원본"].get("보유특성") or []
    for 조건 in 정의.get("조건부효과") or []:
        if 조건.get("조건") == "특성보유" and 조건.get("조건값") in 보유:
            if 조건.get("사용제한") == "전투당1회":
                휴식당, 전투당 = None, 1
            부여효과 = 조건.get("부여효과") or 부여효과

    def 정수(값):
        if 값 is None or isinstance(값, (int, float)):
            return 값
        return int(formula.수식_평가(str(값), stats.기본_컨텍스트(전투상태, 참가자)))

    return 정수(휴식당), 정수(전투당), 부여효과


def _반응_사용가능(전투상태, 참가자, 이름, 정의):
    if not 참가자["생존"] or status.상태이상_플래그(전투상태, 참가자, "행동불가"):
        return False
    행동 = 정의.get("행동")
    if 행동 and 참가자["행동자원"].get(행동, 0) <= 0:
        return False
    휴식당, 전투당, _ = _반응_횟수규칙(전투상태, 참가자, 정의)
    if (
        전투당 is not None
        and 참가자.get("전투당_특성사용횟수", {}).get(이름, 0) >= 전투당
    ):
        return False
    if 휴식당 is not None:
        칸 = (
            참가자["원본"].setdefault("횟수제한스킬", {}).setdefault("휴식제한스킬", {})
        )
        if min(칸.get(이름, 휴식당), 휴식당) <= 0:
            return False
    return True


def _반응_소모(전투상태, 참가자, 이름, 정의):
    행동 = 정의.get("행동")
    if 행동:
        참가자["행동자원"][행동] = 참가자["행동자원"].get(행동, 0) - 1
    휴식당, 전투당, 부여효과 = _반응_횟수규칙(전투상태, 참가자, 정의)
    기록 = 참가자.setdefault("전투당_특성사용횟수", {})
    기록[이름] = 기록.get(이름, 0) + 1
    if 휴식당 is not None:
        칸 = (
            참가자["원본"].setdefault("횟수제한스킬", {}).setdefault("휴식제한스킬", {})
        )
        칸[이름] = max(0, min(칸.get(이름, 휴식당), 휴식당) - 1)
    if isinstance(부여효과, dict) and 부여효과.get("이름"):
        지속턴 = 부여효과.get("지속턴")
        resources.몬스터_버프_부여(
            전투상태,
            참가자,
            부여효과["이름"],
            지속턴 if isinstance(지속턴, int) else None,
        )


def _반응_선택(전투상태, 참가자, 후보, 상황):
    """반응행동을 쓰는 반응 후보 중 하나를 고른다.
    후보: [(이름, 정의 또는 None, 설명, 부가값)], 반환: 고른 후보 또는 None(사용 안 함).
    전투상태["반응선택"](화면이 넣는 콜백: (참가자, [(이름, 설명)], 상황) -> 번호 또는 None)이
    있으면 그걸로 묻고, 없으면(반응 자동 사용) 첫 후보를 쓴다."""
    if not 후보:
        return None
    콜백 = 전투상태.get("반응선택")
    if 콜백 is None:
        return 후보[0]
    번호 = 콜백(참가자, [(이름, 설명) for 이름, _, 설명, _ in 후보], 상황)
    if isinstance(번호, int) and 0 <= 번호 < len(후보):
        return 후보[번호]
    return None


def _반응_로그(전투상태, 참가자, 이름, 내용):
    core.로그(
        전투상태, {"공격자": 참가자["이름"], "반응": 이름, "비고": 내용}, 종류="반응"
    )


def _반응공격_실행(전투상태, 시전자, 대상, 효과, 이름):
    """반응스킬 "효과"(데미지/명중률/데미지보너스/명중보너스/속성)로 대상을
    1회 공격한다. 다른 반응을 다시 부르지 않도록 명중_판정_계산을 쓴다."""
    if not 대상["생존"]:
        return
    명중률 = 효과.get("명중률", "보정명중률")
    명중보너스 = 효과.get("명중보너스", 0) or 0
    데미지식 = str(효과.get("데미지", "보정공격력"))
    무기필요 = "보정공격력" in 데미지식 or "무기공격력" in 데미지식
    if 무기필요 and not 시전자.get("장비데이터", {}).get("무기"):
        return
    속성 = stats.공격_속성(시전자, 데미지식, 효과.get("속성"), 전투상태=전투상태)
    판정 = damage.명중_판정_계산(전투상태, 시전자, 대상, 명중률, 명중보너스)
    결과 = {
        "공격자": 시전자["이름"],
        "대상": 대상["이름"],
        "판정": 판정,
        "피해": 0,
        "반응": 이름,
    }
    damage.공격연출_기록(
        전투상태,
        대상,
        판정,
        속성,
        stats.타격_공격타입(시전자, 데미지식, 효과.get("공격타입")),
    )
    if not 판정["성공"]:
        damage.집요함_발동(전투상태, 시전자, 대상, 속성, 판정)
    if 판정["성공"]:
        컨텍스트 = stats.기본_컨텍스트(전투상태, 시전자, 무기공격력필요=무기필요)
        피해 = stats.피해_굴림(
            전투상태, 시전자, 데미지식, 컨텍스트, 치명타=판정["치명타"]
        )
        굴림 = 피해
        피해 += (효과.get("데미지보너스", 0) or 0) + stats.장비_수치(
            시전자, "데미지보너스"
        )
        피해 += stats.버프디버프_수치(전투상태, 시전자, "데미지보너스")
        피해 += traits.특성_수치(
            전투상태, 시전자, "데미지보너스", 명중률종류=명중률, 대상=대상, 속성=속성
        )
        결과["피해"] = damage.피해_적용(전투상태, 대상, 피해, 속성=속성, 공격측=시전자)
        내역 = damage.피해내역(전투상태, 시전자, 데미지식, 굴림, 피해, 결과["피해"])
        if 내역:
            결과["피해내역"] = 내역
        damage.피격_처리(전투상태, 시전자, 대상, 판정, 속성=속성)
        damage.무기_명중시효과(전투상태, 시전자, 대상, 판정, 데미지식)
    core.로그(전투상태, 결과, 종류="일반공격")


_회피범위_패턴 = re.compile(r"(-?\d+)\s*<=.*<=\s*(-?\d+)")


def 피격판정_반응(전투상태, 공격자, 대상, 판정):
    """적의 명중 판정 직후(반응 선택형):
    1) 명중했고 회피형 반응(크라우치 등)의 범위에 들면 쓸 수 있는 회피형 중에서 고른다.
    2) 빗나갔으면(원래 빗나갔거나 회피형/가드로 피했거나) 반격 후보 - 가드류 반격
       (가드_반응이 판정["가드반격"]에 넣음)과 "회피성공시" 반응스킬 - 중에서 고른다.
    반격은 반응대기에 넣어 적 공격 로그 뒤에 실행한다."""
    반응들 = _반응스킬_목록(전투상태, 대상)
    가드반격 = 판정.get("가드반격")
    if not 반응들 and not 가드반격:
        return 판정
    if 판정.get("성공") and not 판정.get("치명타") and "명중결과" in 판정:
        판정 = _회피_반응(전투상태, 공격자, 대상, 판정, 반응들)
    if (
        not 판정.get("성공")
        and 대상["생존"]
        and not status.상태이상_플래그(전투상태, 대상, "행동불가")
    ):
        _반격_반응(전투상태, 공격자, 대상, 반응들, 가드반격)
    판정.pop("가드반격", None)
    return 판정


def _회피_후보(전투상태, 대상, 반응들, 차이):
    """명중-AC 차이가 회피형 반응의 발동 범위(기본 0~2)에 드는, 지금 쓸 수 있는 회피형 반응."""
    후보 = []
    for 이름, 정의 in 반응들:
        효과 = 정의.get("효과")
        if not (isinstance(효과, dict) and 효과.get("회피성공")):
            continue
        범위 = _회피범위_패턴.search(str(정의.get("발동조건", "")))
        하한, 상한 = (int(범위.group(1)), int(범위.group(2))) if 범위 else (0, 2)
        if 하한 <= 차이 <= 상한 and _반응_사용가능(전투상태, 대상, 이름, 정의):
            후보.append((이름, 정의, "공격을 회피한다", None))
    return 후보


def _회피_반응(전투상태, 공격자, 대상, 판정, 반응들):
    """명중한 공격에 회피형 반응을 고르게 하고, 골랐으면 빗나간 판정(사본)을 돌려준다."""
    후보 = _회피_후보(전투상태, 대상, 반응들, 판정["명중결과"] - 판정["대상AC"])
    선택 = _반응_선택(
        전투상태,
        대상,
        후보,
        f"{공격자['이름']}의 공격이 {대상['이름']}에게 명중합니다 "
        f"(명중 {판정['명중결과']} vs AC {판정['대상AC']}).",
    )
    if not 선택:
        return 판정
    이름, 정의 = 선택[0], 선택[1]
    _반응_소모(전투상태, 대상, 이름, 정의)
    판정 = dict(판정, 성공=False, 반응회피=이름)
    _반응_로그(
        전투상태,
        대상,
        이름,
        f"{공격자['이름']}의 공격(명중 {판정['명중결과']} vs AC {판정['대상AC']})을 회피",
    )
    return 판정


def _반격_후보(전투상태, 대상, 반응들, 가드반격):
    """피한 뒤 쓸 수 있는 반격 - 가드류 반격(행동자원이 남았을 때)과 "회피성공시" 반응스킬.
    항목은 (이름, 정의, 설명, 부가) - 가드 반격은 정의 None, 부가 (행동, 효과)."""
    후보 = []
    if 가드반격:
        가드이름, 반격 = 가드반격
        행동 = 반격.get("행동", "반응행동")
        if 대상["행동자원"].get(행동, 0) > 0:
            효과 = {
                "데미지": 반격.get("데미지", "보정공격력"),
                "명중률": 반격.get("명중률", "보정명중률"),
            }
            후보.append((가드이름, None, f"반격({효과['데미지']})", (행동, 효과)))
    for 이름, 정의 in 반응들:
        효과 = 정의.get("효과")
        if 정의.get("발동조건") != "회피성공시" or not (
            isinstance(효과, dict) and 효과.get("데미지")
        ):
            continue
        if _반응_사용가능(전투상태, 대상, 이름, 정의):
            후보.append((이름, 정의, f"반격({효과.get('데미지')})", None))
    return 후보


def _반격_반응(전투상태, 공격자, 대상, 반응들, 가드반격):
    """반격을 고르게 하고, 골랐으면 자원을 쓰고 반응대기에 넣는다(적 공격 로그 뒤에 실행)."""
    선택 = _반응_선택(
        전투상태,
        대상,
        _반격_후보(전투상태, 대상, 반응들, 가드반격),
        f"{대상['이름']}이(가) {공격자['이름']}의 공격을 피했습니다. 반격할까요?",
    )
    if not 선택:
        return
    이름, 정의, _, 부가 = 선택
    if 정의 is None:
        행동, 효과 = 부가
        대상["행동자원"][행동] -= 1
    else:
        _반응_소모(전투상태, 대상, 이름, 정의)
        효과 = 정의["효과"]
    전투상태.setdefault("반응대기", []).append((대상, 공격자, 효과, 이름))


