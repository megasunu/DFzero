# =====================================================
# 채널링(넨가드)
# =====================================================
# 스킬 "타입"에 "채널링"이 있으면 시전자에게 건 버프 인스턴스에 "채널링"(과 쓴 턴 표시 "채널링시전턴")을
# 적는다(skill_run). 시전자의 다음 턴이 끝나면 사라지고, 그 턴에 다른 행동을 하면 바로 풀린다(쓴 턴의 다른
# 행동은 괜찮다). 시전자가 쓰러지거나 무력화CC에 걸려도 풀린다. 다음 턴 시작에 화면이 유지할지 묻는다
# (ctl_battle.채널링_확인대기/채널링_선택 - 묻고 나면 "채널링확인").


# 아리아(크루세이더 용맹의 아리아·재생의 아리아) - 스킬 "아리아"가 시전자에게 거는 채널링 버프(skill_run.아리아_시작).
# 인스턴스에 "아리아"가 붙는다. 넨가드와 같이 다른 행동·쓰러짐·무력화로 풀리지만, 다른 아리아를 쓰는 것은 다른
# 행동이 아니고(둘을 함께 채널링한다), 다음 턴이 끝나도 풀리지 않고 지속턴(3)이 끝날 때까지 남으며, 유지할지 묻지 않는다.
# 아리아가 하나라도 있으면 시전자는 슈퍼아머("아리아슈퍼아머" 표시가 붙은 인스턴스)이고, 풀리면 그 아리아가 아군에게
# 건 버프(출처스킬이 같은 것 - 용맹의 아리아의 근력·지능)도 함께 사라진다.


def 아리아_목록(참가자):
    return [b for b in 참가자.get("버프") or [] if b.get("아리아")]


def 아리아_슈퍼아머_정리(참가자):
    """아리아가 남지 않았으면 아리아가 준 슈퍼아머를 지운다(지속턴이 끝나 사라진 아리아 포함)."""
    if 아리아_목록(참가자):
        return
    참가자["상태이상"] = [
        s for s in 참가자.get("상태이상") or [] if not s.get("아리아슈퍼아머")
    ]


def _채널링_해제(전투상태, 참가자, 항목, 까닭):
    참가자["버프"].remove(항목)
    if 항목.get("아리아"):
        출처 = 항목.get("출처스킬")
        for p in 전투상태["참가자"]:
            p["버프"] = [
                b
                for b in p.get("버프") or []
                if not (
                    b.get("출처스킬") == 출처
                    and b.get("아리아시전자id") == 참가자.get("id")
                )
            ]
        아리아_슈퍼아머_정리(참가자)
    core.로그(
        전투상태,
        {
            "공격자": 참가자["이름"],
            "대상": 참가자["이름"],
            "비고": f"'{항목['이름']}' 채널링이 풀렸다({까닭}).",
        },
        종류="비고",
    )


def 채널링_목록(참가자):
    return [b for b in 참가자.get("버프") or [] if b.get("채널링")]


def 채널링_정리(전투상태):
    """시전자가 쓰러졌거나 무력화CC에 걸린 채널링을 푼다."""
    for 참가자 in 전투상태["참가자"]:
        if not 채널링_목록(참가자):
            continue
        까닭 = (
            "쓰러짐"
            if not 참가자.get("생존")
            else "무력화"
            if control.무력화_중인가(전투상태, 참가자)
            else None
        )
        for 항목 in 채널링_목록(참가자) if 까닭 else []:
            _채널링_해제(전투상태, 참가자, 항목, 까닭)


def 채널링_행동해제(전투상태, 참가자, 까닭="다른 행동", 아리아행동=False):
    """자기 턴에 행동하면(스킬/일반공격/아이템) 쓴 턴이 지난 채널링이 풀린다. 다른 참가자의 턴(반응)은 해당 없음.
    아리아행동(아리아 스킬을 쓸 때)이면 아리아는 풀리지 않는다."""
    if 전투상태["참가자"][전투상태["현재턴"]] is not 참가자:
        return
    for 항목 in 채널링_목록(참가자):
        if 아리아행동 and 항목.get("아리아"):
            continue
        if not 항목.get("채널링시전턴"):
            _채널링_해제(전투상태, 참가자, 항목, 까닭)


def 채널링_턴종료(전투상태, 참가자):
    """쓴 턴이 끝나면 표시만 지우고, 다음 턴이 끝나면 채널링이 끝난다."""
    for 항목 in 채널링_목록(참가자):
        if 항목.pop("채널링시전턴", False) or 항목.get("아리아"):
            continue  # 아리아는 지속턴이 끝날 때까지
        참가자["버프"].remove(항목)
