def 유효_최대HP(전투상태, 참가자):
    """회복 스킬의 최대치 계산용. 아군은 "기본최대HP", 몬스터는
    인스턴스의 "기본최대HP"(원본 "최대HP" 수식을 평가한 값)를 기준으로,
    몬스터는 칭호 배율을 먼저 곱한다. 거기에 버프/디버프 "최대HP"
    변동대상과 특성(체력증가/종족:타우 등)·칭호의 "최대HP" 변동값을
    더한다."""
    if 참가자["진영"] == "아군":
        # 장비 건강 보정치까지 반영한 최대HP(전투 밖 화면과 같은 값).
        기본 = equipment_system.장비반영_최대HP(
            참가자["원본"],
            참가자.get("장비데이터", {}),
            전투상태.get("세트정의"),
        )
        칭호보정 = 0
    else:
        기본 = 참가자.get("기본최대HP", 참가자["현재HP"])
        기본 = 기본 * traits.칭호_배율(전투상태, 참가자, "최대HP")
        칭호보정 = traits.칭호_수치(전투상태, 참가자, "최대HP")
    # 특성 "배율"(돌연변이:거대화 2배)은 다른 것을 다 더한 최종값에 곱한다(사용자 지정 2026-10-14)
    return (
        기본
        + 버프디버프_수치(전투상태, 참가자, "최대HP")
        + traits.특성_수치(전투상태, 참가자, "최대HP")
        + 칭호보정
    ) * traits.특성_배율(전투상태, 참가자, "최대HP")


# =====================================================
# 턴 순서: 우선도 + 이니셔티브 (매 라운드 재계산)
# =====================================================
# 우선도가 먼저고, 같은 우선도 안에서만 이니셔티브로 순서를 가른다.


def 유효_이니셔티브(전투상태, 참가자):
    """매 라운드 재계산하는 이니셔티브. "기본이니셔티브"에 "속도"
    변동대상(속도증가/속도감소, 특성의 속도 변동 포함)과 상태이상
    "이니셔티브보너스"(둔화 등)를 반영한다. "구속"은 이니셔티브가
    아니라 유효_우선도()에서 페널티를 받는다. 수식형 보너스는 이
    함수가 불릴 때마다 다시 굴린다."""
    기본 = 참가자.get("기본이니셔티브", 참가자.get("이니셔티브", 0))
    보정 = 버프디버프_수치(전투상태, 참가자, "속도") + traits.특성_수치(
        전투상태, 참가자, "속도"
    )
    for _, 정의 in status.상태이상_정의_목록(전투상태, 참가자):
        효과 = 정의.get("효과", {})
        if "이니셔티브보너스" in 효과:
            보정 += formula.수식_평가(
                효과["이니셔티브보너스"], {"차수": core.차수(참가자)}
            )
    return 기본 + 보정


def 속성_보정합(전투상태, 참가자, 변동대상, 속성):
    """ "속성강화"/"속성내성"처럼 속성별로 쌓이는 값 - 버프/디버프와 특성의 효과 원소 중
    "속성"이 그 속성이거나 "전체"인 것의 합."""
    if 참가자 is None or 속성 is None:
        return 0
    return (
        버프디버프_수치(전투상태, 참가자, 변동대상, 속성=속성)
        + traits.속성_특성_수치(전투상태, 참가자, 변동대상, 속성)
        + 마봉_수치(참가자, 변동대상, 속성=속성)
    )


def 공격_속성(참가자, 데미지식, 스킬속성, 속성변환=None):
    """한 번의 공격 피해 속성. 무기 주사위(무기공격력/보정공격력)를 쓰는 피해는 무기의
    "속성"을, 쓰지 않는 피해는 스킬(패턴/반응스킬)에 적힌 속성을 따른다(사용자 결정).
    장전 탄의 "속성변환"이 있으면 그것이 우선이고, 아무것도 없으면 "무속성". 장비 마봉효과
    "무기속성"(화 부여 등)이 있으면 무기 주사위 피해는 무기 속성 대신 그 속성이다."""
    if 속성변환:
        return 속성변환
    장비 = 참가자.get("장비데이터") or {}
    무기 = 장비.get("무기")
    식 = str(데미지식)
    if 무기 and ("보정공격력" in 식 or "무기공격력" in 식):
        for _, 원소 in equipment_system.마봉효과_목록(장비):
            if 원소.get("변동대상") == "무기속성" and 원소.get("속성"):
                return 원소["속성"]
        return 무기.get("속성") or "무속성"
    return 스킬속성 or "무속성"


def 타격_공격타입(참가자, 데미지식, 스킬공격타입):
    """공격 연출 모양을 정하는 "공격타입"(참격/타격/관통/역장/마법). 무기 주사위를 쓰는
    피해는 무기의 것, 아니면 스킬/패턴/반응스킬에 적힌 것(없으면 무기 것, 무기도 없으면 None)."""
    무기 = (참가자.get("장비데이터") or {}).get("무기") or {}
    식 = str(데미지식)
    if 무기 and ("보정공격력" in 식 or "무기공격력" in 식):
        return 무기.get("공격타입")
    return 스킬공격타입 or 무기.get("공격타입")


def 치명타_주사위수(전투상태, 공격자):
    """치명타 때 더 굴리는 피해 주사위 개수 - 참가자 "치명타주사위"(캐릭터/몬스터
    데이터, 기본 1) + 버프/디버프(치명타피해증가/감소, 강권)와
    특성의 "치명타주사위" + 장비(판금 벨트 -1). 0 아래로는 내려가지 않는다."""
    기본 = 공격자.get("치명타주사위", 1)
    증감 = (
        버프디버프_수치(전투상태, 공격자, "치명타주사위")
        + traits.특성_수치(전투상태, 공격자, "치명타주사위")
        + 장비_수치(공격자, "치명타주사위")
    )
    return max(0, int(기본 + 증감))


def 피해_굴림(전투상태, 공격자, 데미지식, 컨텍스트, 치명타=False):
    """공격 피해 수식을 굴린다. 아군 공격자가 "데미지이점" 특성(전투 스타일
    "강타")을 가졌으면 두 번 굴려 높은 값을 쓴다. 치명타면 주사위가
    치명타_주사위수()만큼 늘어난다."""
    if 치명타 is True:
        치명타 = 치명타_주사위수(전투상태, 공격자)
    피해 = formula.수식_평가(데미지식, 컨텍스트, 치명타=치명타)
    if traits.데미지이점(전투상태, 공격자):
        피해 = max(피해, formula.수식_평가(데미지식, 컨텍스트, 치명타=치명타))
    return 피해


def 유효_우선도(전투상태, 참가자):
    """포켓몬류 "우선도" - 기본값에 "우선도" 변동대상과 상태이상
    "우선도보너스"(예: "구속"의 -3)를 더한다. 이니셔티브와 달리 랜덤
    굴림 요소는 없다. 기본값은 "기본우선도"에서 읽는다 - 결과를 담는 "우선도"를
    다시 읽으면 라운드마다 보정이 누적된다."""
    기본 = 참가자.get("기본우선도", 0)
    보정 = 버프디버프_수치(전투상태, 참가자, "우선도") + traits.특성_수치(
        전투상태, 참가자, "우선도"
    )
    for _, 정의 in status.상태이상_정의_목록(전투상태, 참가자):
        효과 = 정의.get("효과", {})
        if "우선도보너스" in 효과:
            보정 += formula.수식_평가(효과["우선도보너스"], {"차수": core.차수(참가자)})
    return 기본 + 보정


# =====================================================
# 몬스터 패턴 수식
# =====================================================
# monster_actions가 쓰고 traits(몬스터 특성 수식)도 쓰는 헬퍼. monster_actions에 두면
# traits가 monster_actions를 불러 순환이 생겼다(구조 점검 R-3).


def 몬스터_패턴_컨텍스트(전투상태, 몬스터참가자):
    """버프/회복/내성 패턴 수식용 컨텍스트. "차수"/"레벨"은 gameflow가
    던전 데이터에서 채워 넣은 몬스터 원본 값을 쓰고(없으면 1), 능력치는
    버프가 반영된 값을 쓴다."""
    원본 = 몬스터참가자["원본"]
    return {
        "차수": 원본.get("차수") or 1,
        "레벨": 원본.get("레벨") or 1,
        "보정치": 유효_능력치_보정치(전투상태, 몬스터참가자, "근력"),
        "능력치": 유효_능력치(전투상태, 몬스터참가자),
    }


def 몬스터_수식값(전투상태, 몬스터참가자, 수식, 기본값=0):
    if isinstance(수식, (int, float)):
        return 수식
    try:
        값 = formula.수식_평가(str(수식), 몬스터_패턴_컨텍스트(전투상태, 몬스터참가자))
    except Exception:
        return 기본값
    return 값 if isinstance(값, (int, float)) else 기본값
