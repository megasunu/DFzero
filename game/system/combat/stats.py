def 출처별_내역(
    전투상태,
    참가자,
    변동대상,
    명중률종류=None,
    대상=None,
    속성=None,
    스킬타입=None,
):
    """버프/디버프/상태이상/특성/칭호가 변동대상에 더하는 값을 출처 이름별로 [(이름, 값)] (0은 뺀다).
    출처 하나만 남긴 참가자 사본으로 같은 합계 함수를 불러 구한다(계산 규칙을 따로 두지 않는다)."""
    내역 = []
    원본 = 참가자.get("원본") or {}
    for 칸 in ("버프", "디버프"):
        for 항목 in 참가자.get(칸) or []:
            사본 = dict(참가자, 버프=[], 디버프=[], 상태이상=[])
            사본[칸] = [항목]
            값 = _버프디버프_합(전투상태, 사본, 변동대상, None, 속성, 스킬타입)
            if 값:
                내역.append((항목["이름"], 값))
    for 항목 in 참가자.get("상태이상") or []:
        값 = _상태이상_추가효과_합(전투상태, dict(참가자, 상태이상=[항목]), 변동대상)
        if 값:
            내역.append((항목.get("이름", "상태이상"), 값))
    for 칸 in ("특성", "보유특성"):
        for 이름 in 원본.get(칸) or []:
            사본원본 = dict(원본, 특성=[], 보유특성=[])
            사본원본[칸] = [이름]
            값 = traits.특성_수치(
                전투상태,
                dict(참가자, 원본=사본원본),
                변동대상,
                명중률종류=명중률종류,
                대상=대상,
                속성=속성,
                스킬타입=스킬타입,
            )
            if 값:
                내역.append((이름, 값))
    칭호값 = traits.칭호_수치(전투상태, 참가자, 변동대상)
    if 칭호값:
        내역.append((f"칭호 {원본.get('칭호')}", 칭호값))
    return 내역


def 기타_채우기(내역, 합계):
    """내역 [(이름, 값)]의 합이 합계와 다르면 차이를 "기타"로 붙인다(로그 숫자가 늘 맞게)."""
    차이 = 합계 - sum(값 for _, 값 in 내역)
    if abs(차이) > 1e-9:
        내역.append(("기타", round(차이, 2) if isinstance(차이, float) else 차이))
    return 내역


def _몬스터_기본AC_내역(전투상태, 참가자):
    """역할군 AC 수식("9+차수+민첩보정치")을 항목별로 - [("메이지", 9), ("차수", 1), ("민첩", 1)].
    숫자 항은 역할군 이름, 민첩보정치는 "민첩"(버프 반영), 나머지는 수식 그대로를 이름으로 쓴다.
    "+"로만 이어진 수식이 아니면 None - 호출부가 "기본" 한 항목으로 쓴다."""
    원본 = 참가자["원본"]
    수식 = participants.몬스터_역할군_수식(원본, "AC")
    if not isinstance(수식, str) or any(기호 in 수식 for 기호 in "-()"):
        return None
    추가민첩 = 버프디버프_수치(전투상태, 참가자, "민첩") + 버프디버프_수치(
        전투상태, 참가자, "전체"
    )
    능력치사본 = _몬스터_AC_능력치(원본, 추가민첩)
    내역 = []
    for 항 in 수식.split("+"):
        if 항.isdigit():
            이름 = 원본["역할군"]
        elif 항 == "민첩보정치":
            이름 = "민첩"
        else:
            이름 = 항
        내역.append((이름, participants.몬스터_수식_평가(항, 능력치사본, 0)))
    return 내역


def AC_내역(전투상태, 참가자):
    """최종AC의 [(이름, 값)] - 아군 기본 10/장비/민첩, 몬스터 기본(역할군)/AC보너스, 그리고 출처별."""
    합계 = 최종AC(전투상태, 참가자)
    if 참가자.get("감옥"):
        return [("기본", 합계)]
    원본 = 참가자["원본"]
    내역 = []
    if 참가자["진영"] == "아군":
        장비AC = equipment_system.장비_보너스_합산(
            참가자["장비데이터"], 전투상태.get("세트정의")
        )["AC보너스"]
        내역 = [("기본", 10), ("장비", 장비AC)]
        추가민첩 = 버프디버프_수치(전투상태, 참가자, "민첩") + 버프디버프_수치(
            전투상태, 참가자, "전체"
        )
        기본AC = equipment_system.최종AC_계산(
            원본,
            참가자["장비데이터"],
            세트목록=전투상태.get("세트정의"),
            추가민첩=추가민첩,
        )
        패셔니스트AC = equipment_system.패셔니스트_수치(
            원본, 참가자["장비데이터"], "AC"
        )
        if 기본AC - 10 - 장비AC - 패셔니스트AC:
            내역.append(("민첩", 기본AC - 10 - 장비AC - 패셔니스트AC))
        if 패셔니스트AC:
            내역.append(("패셔니스트", 패셔니스트AC))
        내역 += [
            (이름, 값)
            for 이름, 값 in 출처별_내역(전투상태, 참가자, "AC")
            if not 이름.startswith("칭호 ")
        ]
    else:
        AC보너스 = 원본.get("AC보너스", 0)
        if not isinstance(AC보너스, (int, float)):
            AC보너스 = 0
        출처 = 출처별_내역(전투상태, 참가자, "AC")
        기본 = 합계 - AC보너스 - sum(값 for _, 값 in 출처)
        내역 = _몬스터_기본AC_내역(전투상태, 참가자) or [("기본", 기본)]
        if AC보너스:
            내역.append(("AC보너스", AC보너스))
        내역 += 출처
    return 기타_채우기([(n, v) for n, v in 내역 if v], 합계)


