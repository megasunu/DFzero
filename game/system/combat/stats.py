def 유효_이니셔티브(전투상태, 참가자):
    """매 라운드 재계산하는 이니셔티브. "기본이니셔티브"에 "속도"
    변동대상(속도증가/속도감소, 특성의 속도 변동 포함)과 상태이상
    "이니셔티브보너스"(둔화 등)를 반영한다. "구속"은 이니셔티브가
    아니라 유효_우선도()에서 페널티를 받는다. 수식형 보너스는 이
    함수가 불릴 때마다 다시 굴린다."""
    기본 = 참가자.get("기본이니셔티브", 참가자.get("이니셔티브", 0))
    보정 = 버프디버프_수치(전투상태, 참가자, "속도") + traits.특성_수치(
        전투상태, 참가자, "속도"
    )
    for _, 정의 in status.상태이상_정의_목록(전투상태, 참가자):
        효과 = 정의.get("효과", {})
        if "이니셔티브보너스" in 효과:
            보정 += formula.수식_평가(
                효과["이니셔티브보너스"], {"차수": core.차수(참가자)}
            )
    return 기본 + 보정


def 속성_보정합(전투상태, 참가자, 변동대상, 속성):
    """ "속성강화"/"속성내성"처럼 속성별로 쌓이는 값 - 버프/디버프와 특성의 효과 원소 중
    "속성"이 그 속성이거나 "전체"인 것의 합. 특성 "속성강화동기화"(듀얼 트리거 - ["화속성", "명속성"])에
    묶인 속성의 속성강화는 묶음 안에서 가장 높은 값이다."""
    if 참가자 is None or 속성 is None:
        return 0
    if 변동대상 == "속성강화":
        for 묶음 in traits.캐릭터특성_속성강화동기화(전투상태, 참가자):
            if 속성 in 묶음:
                return max(
                    _속성_보정합_원래(전투상태, 참가자, 변동대상, s) for s in 묶음
                )
    return _속성_보정합_원래(전투상태, 참가자, 변동대상, 속성)


def _속성_보정합_원래(전투상태, 참가자, 변동대상, 속성):
    return (
        버프디버프_수치(전투상태, 참가자, 변동대상, 속성=속성)
        + traits.속성_특성_수치(전투상태, 참가자, 변동대상, 속성)
        + 마봉_수치(참가자, 변동대상, 속성=속성)
        + (날씨_속성강화(전투상태, 속성) if 변동대상 == "속성강화" else 0)
        + (장비_수치(참가자, "모든속성내성") if 변동대상 == "속성내성" else 0)
        + (장비_수치(참가자, "모든속성강화") if 변동대상 == "속성강화" else 0)
    )


# 날씨(포켓몬 특성 잔비/가뭄) - 날씨 동안 모든 참가자의 속성강화
날씨_속성강화표 = {
    "비": {"수속성": 1, "화속성": -1},
    "햇살": {"화속성": 1, "수속성": -1},
}


def 날씨_속성강화(전투상태, 속성):
    날씨 = 전투상태.get("날씨") or {}
    return 날씨_속성강화표.get(날씨.get("이름"), {}).get(속성, 0)


def 공격_속성(참가자, 데미지식, 스킬속성, 속성변환=None, 전투상태=None):
    """한 번의 공격 피해 속성. 무기 주사위(무기공격력/보정공격력)를 쓰는 피해는 무기의
    "속성"을, 쓰지 않는 피해는 스킬(패턴/반응스킬)에 적힌 속성을 따른다(사용자 결정).
    장전 탄의 "속성변환"이 있으면 그것이 우선이고, 아무것도 없으면 "무속성". 장비 마봉효과
    "무기속성"(화 부여 등)이 있으면 무기 주사위 피해는 무기 속성 대신 그 속성이다.
    전투상태를 주면 란마 1/2의 지금 형태 속성(traits.형태_속성)을 더해 리스트로 돌려준다
    (속성이 여럿이면 피해_적용이 가장 아픈 것을 고른다)."""
    속성 = _기본_공격_속성(참가자, 데미지식, 스킬속성, 속성변환)
    추가 = traits.형태_속성(전투상태, 참가자) if 전투상태 is not None else None
    if 추가 is None:
        return 속성
    속성들 = list(속성) if isinstance(속성, list) else [속성]
    return 속성들 if 추가 in 속성들 else 속성들 + [추가]


def _기본_공격_속성(참가자, 데미지식, 스킬속성, 속성변환):
    if 속성변환:
        return 속성변환
    장비 = 참가자.get("장비데이터") or {}
    무기 = 장비.get("무기")
    식 = str(데미지식)
    if 무기 and ("보정공격력" in 식 or "무기공격력" in 식):
        for _, 원소 in equipment_system.마봉효과_목록(장비):
            if 원소.get("변동대상") == "무기속성" and 원소.get("속성"):
                return 원소["속성"]
        return 무기.get("속성") or "무속성"
    return 스킬속성 or "무속성"


def 타격_공격타입(참가자, 데미지식, 스킬공격타입):
    """공격 연출 모양을 정하는 "공격타입"(참격/타격/관통/역장/마법). 무기 주사위를 쓰는
    피해는 무기의 것, 아니면 스킬/패턴/반응스킬에 적힌 것(없으면 무기 것, 무기도 없으면 None)."""
    무기 = (참가자.get("장비데이터") or {}).get("무기") or {}
    식 = str(데미지식)
    if 무기 and ("보정공격력" in 식 or "무기공격력" in 식):
        return 무기.get("공격타입")
    return 스킬공격타입 or 무기.get("공격타입")


def 치명타_주사위수(전투상태, 공격자, 대상=None):
    """치명타 배수에 더하는 수 - 치명타면 피해 주사위 개수 x (1 + 이 값)(#440). 참가자 "치명타주사위"(캐릭터/몬스터
    데이터, 기본 1) + 버프/디버프(치명타피해증가/감소, 강권)와
    특성의 "치명타주사위" + 장비(판금 벨트 -1) + 맞는 대상의 장비 "피격치명타주사위"(레어 세트 초합금
    -1, 대상을 넘기는 곳만 - 몬스터·소환수 공격, 추가타격, 스킬 원소 타격). 0 아래로는 내려가지 않는다."""
    기본 = 공격자.get("치명타주사위", 1)
    증감 = (
        버프디버프_수치(전투상태, 공격자, "치명타주사위")
        + traits.특성_수치(전투상태, 공격자, "치명타주사위")
        + 장비_수치(공격자, "치명타주사위")
        + 공격태그_조건_수치(전투상태, 공격자, "치명타주사위")
        + (장비_수치(대상, "피격치명타주사위") if 대상 else 0)
    )
    return max(0, formula.올림(기본 + 증감))


def 스킬타입_조건_수치(전투상태, 참가자, 변동대상, 스킬타입):
    """특성/버프 효과 원소 중 "스킬타입조건"이 붙은 것만 - 그 스킬 "타입"(스킬타입)에 맞는 것의 합
    (중화기 마스터리/미라클 비전/로보틱스의 명중보너스). 조건 없는 원소는 명중 굴림이 따로 더하므로 뺀다."""
    if not 스킬타입:
        return 0
    return (
        traits.특성_수치(전투상태, 참가자, 변동대상, 스킬타입=스킬타입)
        - traits.특성_수치(전투상태, 참가자, 변동대상)
        + 버프디버프_수치(전투상태, 참가자, 변동대상, 스킬타입=스킬타입)
        - 버프디버프_수치(전투상태, 참가자, 변동대상)
    )


def 공격태그_조건_수치(전투상태, 참가자, 변동대상):
    """지금 하는 공격의 태그(참가자 "_공격태그" - 스킬 "타입", 장전 탄을 쓰면 "장전")에 맞는 "스킬타입조건"
    원소의 합(강화탄/매거진 드럼의 치명타범위·치명타주사위, 유탄 마스터리의 내성난이도 #391). 공격 중이 아니면 0.
    공격_1회/일반공격_실행이 공격하는 동안만 태그를 단다(공격태그_달기)."""
    return 스킬타입_조건_수치(전투상태, 참가자, 변동대상, 참가자.get("_공격태그"))


def 공격태그_달기(참가자, 태그):
    """공격하는 동안 참가자에 "_공격태그"를 단다(None이면 뗀다)."""
    if 태그 is None:
        참가자.pop("_공격태그", None)
    else:
        참가자["_공격태그"] = tuple(태그)


def 추가공격_보너스(전투상태, 참가자):
    """추가행동을 열 때 캐릭터 "추가공격"에 더하는 버프/특성 "추가공격"(니트로모터 - 공중사격 중 +1 #391)."""
    return 버프디버프_수치(전투상태, 참가자, "추가공격") + traits.특성_수치(
        전투상태, 참가자, "추가공격"
    )


def 피해이점인가(전투상태, 참가자, 스킬타입):
    """특성/버프의 "피해이점" 원소가 이 스킬 "타입"에 맞나 - 맞으면 피해식을 두 번 굴려 높은 쪽
    (파이어볼트 "메카", 미라클 비전 "중화기"). "스킬타입조건"이 없는 원소는 모든 스킬이다."""
    원소들 = [원소 for _, 원소 in 버프_효과원소목록(전투상태, 참가자, "피해이점")]
    원소들 += traits.캐릭터특성_효과원소(전투상태, 참가자, "피해이점")
    return any(
        not 원소.get("스킬타입조건")
        or set(원소["스킬타입조건"]).intersection(스킬타입 or ())
        for 원소 in 원소들
    )


def 피해_굴림(전투상태, 공격자, 데미지식, 컨텍스트, 치명타=False):
    """공격 피해 수식을 굴린다. 아군 공격자가 "데미지이점" 특성(전투 스타일
    "강타")을 가졌으면 두 번 굴려 높은 값을 쓴다. 치명타면 주사위 개수가
    (1 + 치명타_주사위수())배가 된다."""
    if 치명타 is True:
        치명타 = 치명타_주사위수(전투상태, 공격자)
    피해 = formula.수식_평가(데미지식, 컨텍스트, 치명타=치명타)
    if traits.데미지이점(전투상태, 공격자):
        피해 = max(피해, formula.수식_평가(데미지식, 컨텍스트, 치명타=치명타))
    return 피해


def 무기추가피해_굴림(전투상태, 공격자, 식, 치명타=False):
    """레어 무기 "스킬강화"의 "추가피해" 식 하나(#437) - 본 피해와 따로 굴린다. 무기 주사위(보정공격력)가 있으면
    무기 주사위를 넣은 컨텍스트로, 치명타 주사위는 그 식의 규칙대로(무기 주사위가 있으면 무기 주사위만)."""
    무기필요 = "보정공격력" in 식 or "무기공격력" in 식
    if 무기필요 and not (공격자.get("장비데이터") or {}).get("무기"):
        return 0
    컨텍스트 = 기본_컨텍스트(전투상태, 공격자, 무기공격력필요=무기필요)
    return 피해_굴림(전투상태, 공격자, 식, 컨텍스트, 치명타=치명타)


def 유효_우선도(전투상태, 참가자):
    """포켓몬류 "우선도" - 기본값에 "우선도" 변동대상과 상태이상
    "우선도보너스"(예: "구속"의 -3)를 더한다. 이니셔티브와 달리 랜덤
    굴림 요소는 없다. 기본값은 "기본우선도"에서 읽는다 - 결과를 담는 "우선도"를
    다시 읽으면 라운드마다 보정이 누적된다."""
    기본 = 참가자.get("기본우선도", 0)
    보정 = 버프디버프_수치(전투상태, 참가자, "우선도") + traits.특성_수치(
        전투상태, 참가자, "우선도"
    )
    if 참가자.get("질풍날개"):  # 라운드 시작에 HP가 가득이었다(flow.질풍날개_확인)
        보정 += 1
    for _, 정의 in status.상태이상_정의_목록(전투상태, 참가자):
        효과 = 정의.get("효과", {})
        if "우선도보너스" in 효과:
            보정 += formula.수식_평가(효과["우선도보너스"], {"차수": core.차수(참가자)})
    return 기본 + 보정


