def 유효_최대HP(전투상태, 참가자):
    """회복 스킬의 최대치 계산용. 아군은 "기본최대HP", 몬스터는
    인스턴스의 "기본최대HP"(원본 "최대HP" 수식을 평가한 값)를 기준으로,
    몬스터는 칭호 배율을 먼저 곱한다. 거기에 버프/디버프 "최대HP"
    변동대상과 특성(체력증가/종족:타우 등)·칭호의 "최대HP" 변동값을
    더한다."""
    if 참가자["진영"] == "아군":
        # 장비 건강 보정치까지 반영한 최대HP(전투 밖 화면과 같은 값).
        기본 = equipment_system.장비반영_최대HP(
            참가자["원본"],
            참가자.get("장비데이터", {}),
            전투상태.get("세트정의"),
        )
        칭호보정 = 0
    else:
        기본 = 참가자.get("기본최대HP", 참가자["현재HP"])
        기본 = 기본 * traits.칭호_배율(전투상태, 참가자, "최대HP")
        칭호보정 = traits.칭호_수치(전투상태, 참가자, "최대HP")
    # 특성 "배율"(돌연변이:거대화 2배)은 다른 것을 다 더한 최종값에 곱한다(사용자 지정 2026-10-14)
    return (
        기본
        + 버프디버프_수치(전투상태, 참가자, "최대HP")
        + traits.특성_수치(전투상태, 참가자, "최대HP")
        + 칭호보정
    ) * traits.특성_배율(전투상태, 참가자, "최대HP")


