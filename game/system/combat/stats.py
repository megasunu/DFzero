def 버프_수식_컨텍스트(전투상태, 시전자):
    """버프/디버프 "변동값" 수식(예: "1d(4+2차수)+주문시전보정치")을 평가할 때 쓰는
    컨텍스트 - 버프를 건 사람(시전자) 기준이다(B10)."""
    return {
        "차수": core.차수(시전자),
        "주문시전보정치": 주문시전_보정치(전투상태, 시전자),
        "능력치": 시전자["원본"],
        "능력치보정치": 캐릭터데이터.보정치표(시전자["원본"]),
    }


def 버프_고정값_계산(전투상태, 정의, 시전자, 차수=None):
    """버프/디버프 인스턴스를 걸 때 수식형 "변동값"을 한 번 굴려 고정한다(B11).
    효과 원소 순서대로 값(수식이 아니면 None)의 리스트. 정의나 수식이 없으면 None.
    차수를 주면 시전자 차수 대신 그 값으로 굴린다(마봉능력 축복 - 1차수 명중률증가)."""
    효과 = (정의 or {}).get("효과")
    if 효과 is None:
        return None
    효과리스트 = [효과] if isinstance(효과, dict) else 효과
    if not any(isinstance(원소.get("변동값"), str) for 원소 in 효과리스트):
        return None
    컨텍스트 = 버프_수식_컨텍스트(전투상태, 시전자)
    if 차수 is not None:
        컨텍스트["차수"] = 차수
    return [
        formula.수식_평가(원소["변동값"], 컨텍스트)
        if isinstance(원소.get("변동값"), str)
        else None
        for 원소 in 효과리스트
    ]


def 버프디버프_수치(
    전투상태, 참가자, 변동대상, 행동종류=None, 속성=None, 스킬타입=None
):
    """버프/디버프의 "변동대상"에 해당하는 "변동값"을 전부 더한다
    (수식 문자열이면 그 자리에서 평가). 지속피해형의 "추가효과"도
    같은 변동대상으로 매핑해 함께 더한다(_추가효과_변동대상_매핑 참고).

    변동대상="행동보너스"로 호출할 때 "행동종류"(일반행동/보조행동/
    반응행동/쇼타임행동)를 같이 넘기면 그 종류만 필터링해서 더한다
    (넘기지 않으면 전부 더한다).

    효과 원소에 "속성"이 있으면(속성강화/속성내성) 넘긴 속성과 같거나 "전체"일 때만
    더한다 - 속성을 넘기지 않으면 그런 원소는 건너뛴다.

    수식형 "변동값"은 인스턴스에 걸 때 굴려 둔 "고정값"을 쓴다(B10/B11 - 건 사람
    기준, 한 번만 굴림). 고정값이 없는 인스턴스만 그 자리에서 받는 쪽 기준으로 평가한다.

    "스킬타입조건"이 붙은 원소(미라클 비전)는 넘긴 스킬타입(스킬 "타입")과 겹칠 때만 더한다."""
    return (
        _버프디버프_합(전투상태, 참가자, 변동대상, 행동종류, 속성, 스킬타입)
        + _상태이상_추가효과_합(전투상태, 참가자, 변동대상)
        + 오라_수치(전투상태, 참가자, 변동대상, 행동종류, 속성, 스킬타입)
    )


def 오라_수치(전투상태, 참가자, 변동대상, 행동종류=None, 속성=None, 스킬타입=None):
    """살아 있는 아군이 장착한 무기 "오라"(나일블루/마젠타/지국천주/배틀마스터 - #437) 중 변동대상이 같은 것의
    가장 높은 값(같은 오라는 겹치지 않는다 - 2026-10-27 사용자 결정). 아군에게만 붙는다."""
    if 참가자.get("진영") != "아군":
        return 0
    값들 = [
        원소.get("변동값", 0)
        for p in 전투상태["참가자"]
        if p.get("진영") == "아군" and p.get("생존", True)
        for 원소 in equipment_system.오라_목록(p.get("장비데이터"))
        if _원소_해당(참가자, 원소, 변동대상, 행동종류, 속성, 스킬타입)
        and isinstance(원소.get("변동값"), (int, float))
    ]
    return max(값들, default=0)


def _원소_해당(참가자, 원소, 변동대상, 행동종류, 속성, 스킬타입=None):
    """버프/디버프 효과 원소 하나가 이번에 구하는 수치(변동대상/행동종류/속성/무기조건/스킬타입)에 해당하나."""
    if 원소.get("변동대상") != 변동대상:
        return False
    if 행동종류 is not None and 원소.get("행동종류") != 행동종류:
        return False
    조건타입 = 원소.get("스킬타입조건")
    if 조건타입 and not set(조건타입).intersection(스킬타입 or ()):
        return False
    if 원소.get("속성") is not None and 원소["속성"] not in (속성, "전체"):
        return False
    return not (
        원소.get("무기조건") and 원소["무기조건"] != traits.장착무기_타입(참가자)
    )


def _버프디버프_합(전투상태, 참가자, 변동대상, 행동종류, 속성, 스킬타입=None):
    합계 = 0
    목록들 = (
        (참가자["버프"], 전투상태["버프정의"]),
        (참가자["디버프"], 전투상태["디버프정의"]),
    )
    for 인스턴스목록, 정의모음 in 목록들:
        for 항목 in 인스턴스목록:
            # 기술효과(skill_effects - 카잔버프 등)는 버프정의에 없으므로 효과정의_조회로 찾는다
            정의 = (
                정의모음.get(항목["이름"]) or resources.효과정의_조회(항목["이름"])[0]
            )
            효과 = (정의 or {}).get("효과")
            if 효과 is None:
                continue
            # 인스턴스 무기조건(스킬 "버프무기조건" - 데스 바이 리볼버)
            if 항목.get("무기조건") and 항목["무기조건"] != traits.장착무기_타입(
                참가자
            ):
                continue
            효과리스트 = [효과] if isinstance(효과, dict) else 효과
            고정값 = 항목.get("고정값")
            for 순번, 원소 in enumerate(효과리스트):
                if not _원소_해당(참가자, 원소, 변동대상, 행동종류, 속성, 스킬타입):
                    continue
                변동값 = 원소.get("변동값", 0)
                # 고정값은 숫자 변동값도 덮는다(사슬 해제가 건 카잔버프 1+차수 - skill_grant)
                if 고정값 is not None and 고정값[순번] is not None:
                    변동값 = 고정값[순번]
                elif isinstance(변동값, str):
                    변동값 = formula.수식_평가(
                        변동값, 버프_수식_컨텍스트(전투상태, 참가자)
                    )
                합계 += 변동값 * 항목.get("중첩", 1)
    return 합계


def 버프_효과원소목록(전투상태, 참가자, 변동대상):
    """버프/디버프 효과 원소 중 변동대상이 맞는 것의 [(효과 이름, 원소)] - 숫자로 더하지 않는 효과용
    (잔영의 케이가의 "일반공격속성추가"/"타격추가피해"). 인스턴스 무기조건도 본다."""
    결과 = []
    for 목록이름, 정의모음키 in (("버프", "버프정의"), ("디버프", "디버프정의")):
        for 항목 in 참가자.get(목록이름) or []:
            정의 = (전투상태.get(정의모음키) or {}).get(
                항목["이름"]
            ) or resources.효과정의_조회(항목["이름"])[0]
            효과 = (정의 or {}).get("효과")
            if 효과 is None:
                continue
            if 항목.get("무기조건") and 항목["무기조건"] != traits.장착무기_타입(
                참가자
            ):
                continue
            for 원소 in [효과] if isinstance(효과, dict) else 효과:
                if isinstance(원소, dict) and 원소.get("변동대상") == 변동대상:
                    결과.append((항목["이름"], 원소))
    return 결과


def 일반공격_대체(전투상태, 참가자):
    """버프 "일반공격대체"(뇌명) 원소 - 일반공격이 무기 주사위 대신 이 원소의 "명중률"/"데미지"/"속성"으로 친다.
    없으면 None(여럿이면 마지막)."""
    원소들 = [원소 for _, 원소 in 버프_효과원소목록(전투상태, 참가자, "일반공격대체")]
    return 원소들[-1] if 원소들 else None


def _상태이상_추가효과_합(전투상태, 참가자, 변동대상):
    """지속피해형 상태이상의 "추가효과"를 변동대상으로 매핑해 더한다("중첩수"는 그 상태이상의 중첩)."""
    합계 = 0
    for 항목, 정의 in status.상태이상_정의_목록(전투상태, 참가자):
        추가효과 = 정의.get("효과", {}).get("추가효과", {})
        for 키, 수식 in 추가효과.items():
            if _추가효과_변동대상_매핑.get(키, 키) != 변동대상:
                continue
            if isinstance(수식, str):
                식 = 수식.replace("중첩수", str(항목.get("중첩", 1)))
                합계 += formula.수식_평가(식, {"차수": core.차수(참가자)})
            else:
                합계 += 수식
    return 합계


_능력치_목록 = ("근력", "민첩", "건강", "지능", "지혜", "매력")


def 장비_스탯보너스(참가자, 능력치이름):
    """전투_시작()이 캐싱한 장비(전 부위+세트) "스탯보너스" 중 해당
    능력치 값(아군 전용, 없으면 0)."""
    보너스 = 참가자.get("장비보너스") or {}
    값 = (보너스.get("스탯보너스") or {}).get(능력치이름, 0)
    return 값 if isinstance(값, (int, float)) else 0


def MP소모_배율(참가자):
    """중갑/판금 패널티의 MP 소모 배율(equipment_system.캐릭터_장비_보너스). 기본 1."""
    return (참가자.get("장비보너스") or {}).get("MP소모배율", 1)


def 몬스터_타입(대상):
    """대상 원본의 "타입"(하나 또는 리스트)을 튜플로. 없으면 ()."""
    타입 = ((대상 or {}).get("원본") or {}).get("타입")
    if not 타입:
        return ()
    return tuple(타입) if isinstance(타입, (list, tuple)) else (타입,)


def 마봉_수치(참가자, 변동대상, 대상=None, 속성=None):
    """참가자 장비의 상시 마봉효과 합(equipment_system.마봉_수치) - 대상을 넘기면 그 몬스터 "타입"으로
    대상타입 조건(사냥꾼 등)을 본다."""
    return equipment_system.마봉_수치(
        참가자.get("장비데이터") or {},
        변동대상,
        속성=속성,
        대상타입=몬스터_타입(대상),
    )


def 마봉_발동목록(참가자, 발동, 대상=None):
    """참가자 장비 마봉효과 중 "발동"이 그것("턴시작"/"공격"/"명중")인 [(아이템, 원소)] - 대상을 넘기면
    "대상타입" 조건이 맞는 것만."""
    타입 = 몬스터_타입(대상)
    return [
        (아이템, 원소)
        for 아이템, 원소 in equipment_system.마봉효과_목록(
            참가자.get("장비데이터") or {}
        )
        if 원소.get("발동") == 발동
        and ("대상타입" not in 원소 or 원소["대상타입"] in 타입)
    ]


def 마봉_추가피해(전투상태, 참가자, 대상):
    """명중한 공격에 더하는 장비 마봉효과 "발동":"공격"의 "추가피해"(필살 1d4, 추적자 등은 그 타입에만
    1d6) 굴림 합. 치명타여도 주사위는 늘지 않는다. 장비 데미지보너스가 붙는 공격에만 부른다."""
    return sum(
        formula.수식_평가(원소["추가피해"], 기본_컨텍스트(전투상태, 참가자))
        for _, 원소 in 마봉_발동목록(참가자, "공격", 대상)
        if 원소.get("추가피해")
        # "확률"(싸늘한 눈보라의 토템 10% - #437)이 있으면 그 확률로만
        and ("확률" not in 원소 or rng.확률.random() < 원소["확률"])
    )


def 장비버프_데미지보너스(전투상태, 참가자, 대상=None):
    """장비(장비_데미지보너스)와 버프/디버프의 데미지보너스 - 특성/칭호는 뺀다. 귀참드라이브와
    잔영의 케이가 추가 피해에 붙는다(2026-10-20 사용자 결정, #247)."""
    return 장비_데미지보너스(참가자, 대상, 전투상태) + 버프디버프_수치(
        전투상태, 참가자, "데미지보너스"
    )


def 장비_데미지보너스(참가자, 대상=None, 전투상태=None):
    """장비(전 부위 + 세트) 데미지보너스 + 대상타입이 맞는 마봉효과 데미지보너스(사냥꾼 등)
    + 위기데미지보너스(레어 세트 드래고닉 스킨 - 현재HP가 최대HP의 50% 이하일 때, 전투상태를 줄 때만)."""
    위기 = 장비_수치(참가자, "위기데미지보너스")
    if 위기 and (
        전투상태 is None or 참가자["현재HP"] * 2 > 유효_최대HP(전투상태, 참가자)
    ):
        위기 = 0
    return (
        장비_수치(참가자, "데미지보너스")
        + 마봉_수치(참가자, "데미지보너스", 대상=대상)
        + 위기
    )


def 마봉_최종피해배율(참가자):
    """장비 마봉효과 "최종피해배율"(강타 0.1)을 1에 더한 배율 - 장비 보너스가 붙는 공격의 최종피해에 곱한다."""
    return 1 + 마봉_수치(참가자, "최종피해배율")


def 장비_수치(참가자, 키):
    """전투_시작()이 캐싱한 장비(전 부위+활성 세트) 보너스 중 숫자 항목
    (명중률보너스/데미지보너스/속도보너스/AC보너스). 몬스터는 0."""
    값 = (참가자.get("장비보너스") or {}).get(키, 0)
    return 값 if isinstance(값, (int, float)) else 0


def 유효_능력치값(전투상태, 참가자, 능력치이름):
    """원본 능력치 + 장비 스탯보너스 + 버프/디버프(해당 능력치와 "전체"). 특성 "능력치동기화"(사공수련 -
    근력/지능)에 든 능력치는 그 묶음에서 가장 높은 값을 쓴다."""
    for 묶음 in traits.캐릭터특성_능력치동기화(전투상태, 참가자):
        if 능력치이름 in 묶음:
            return max(_능력치값(전투상태, 참가자, 이름) for 이름 in 묶음)
    return _능력치값(전투상태, 참가자, 능력치이름)


def _능력치값(전투상태, 참가자, 능력치이름):
    원본값 = 참가자["원본"].get(능력치이름, 10)
    if not isinstance(원본값, (int, float)):
        원본값 = 10
    return 캐릭터데이터.능력치_상한(
        참가자["원본"],
        능력치이름,
        원본값
        + 장비_스탯보너스(참가자, 능력치이름)
        + 버프디버프_수치(전투상태, 참가자, 능력치이름)
        + 버프디버프_수치(전투상태, 참가자, "전체")
        + _우선도_능력치(전투상태, 참가자, 능력치이름),
    )


def _우선도_능력치(전투상태, 참가자, 능력치이름):
    """말딸(우마무스메) - 특성 "우선도능력치"에 든 능력치는 그때의 실제 우선도만큼 오른다(0 이하면 0)."""
    if 능력치이름 not in traits.캐릭터특성_문자열값(전투상태, 참가자, "우선도능력치"):
        return 0
    return max(0, 유효_우선도(전투상태, 참가자))


def 유효_능력치_보정치(전투상태, 참가자, 능력치이름):
    return 캐릭터데이터.보정치_계산(
        참가자["원본"], 능력치이름, 유효_능력치값(전투상태, 참가자, 능력치이름)
    )


def 내성굴림_보정치(전투상태, 참가자, 능력치이름):
    """내성굴림에 더하는 값 - 그 능력치 보정치 + "내성보너스"(버프 내성증가/디버프 내성감소와 특성).
    내성굴림을 하는 곳은 모두 이것을 쓴다(그전에는 내성보너스를 아무도 읽지 않았다 - 10-15 수정)."""
    return (
        유효_능력치_보정치(전투상태, 참가자, 능력치이름)
        + 버프디버프_수치(전투상태, 참가자, "내성보너스")
        + traits.특성_수치(전투상태, 참가자, "내성보너스")
        + 마봉_수치(참가자, "내성보너스")
    )


def 내성굴림_이점불리(
    전투상태, 대상, 상태이상이름=None, 내성스탯=None, 시전자=None, 거는상태이상=None
):
    """내성굴림의 (이점 수, 불리점 수). 불리점: "내성굴림불리점" 상태이상(저주), 캐릭터의 약점스탯
    내성(약점제거면 약점이 아니다), 시전자 특성 "상태이상내성불리부여"에 거는상태이상이 있을 때(독에
    익숙함 - 중독). 이점: 상태이상을 막는 굴림이면(상태이상이름) 특성 "상태이상내성이점"
    (가죽숙달 등), 캐릭터의 주스탯 내성(사용자 결정 - 보조스탯은 없다, 몬스터는 스탯 지정이 없다)."""
    원본 = 대상.get("원본") or {}
    이점 = int(
        bool(상태이상이름) and traits.상태이상_내성이점(전투상태, 대상, 상태이상이름)
    ) + int(bool(내성스탯) and 내성스탯 == 원본.get("주스탯"))
    # 장비의 상태이상 저항/취약(복수의 영혼도·알트브라움 - 저주, #437)
    장비 = 대상.get("장비데이터") or {}
    이점 += int(
        bool(상태이상이름)
        and equipment_system.상태이상_내성_변동(장비, "상태이상내성이점", 상태이상이름)
    )
    불리 = (
        int(
            bool(상태이상이름)
            and equipment_system.상태이상_내성_변동(
                장비, "상태이상내성불리점", 상태이상이름
            )
        )
        + int(status.상태이상_플래그(전투상태, 대상, "내성굴림불리점"))
        + int(bool(내성스탯) and 내성스탯 in 캐릭터데이터.약점스탯_목록(원본))
        + int(
            시전자 is not None
            and 거는상태이상 is not None
            and 거는상태이상
            in status.특성_변동값목록(전투상태, 시전자, "상태이상내성불리부여")
        )
    )
    return 이점, 불리


def 상태이상_내성(대상, 상태이상이름):
    """그 상태이상을 막는 내성굴림에 더하는 장비 값 - 아이템의 상태이상 내성(빙결 등)과 세트의
    "모든상태이상내성"(레어 악세서리, #446). 상태이상을 막는 굴림이 아니면(이름 없음) 0. 몬스터는 0."""
    if not 상태이상이름:
        return 0
    return equipment_system.상태이상_내성_수치(
        대상.get("장비데이터") or {}, 상태이상이름
    ) + 장비_수치(대상, "모든상태이상내성")


def 대상_내성굴림(
    전투상태,
    대상,
    내성스탯,
    난이도,
    상태이상이름=None,
    시전자=None,
    거는상태이상=None,
    추가불리=False,
):
    """대상의 내성굴림 한 번 - (성공, 굴린 값, 보정치). 내성굴림을 하는 곳은 모두 이것을 쓴다
    (보정치는 내성굴림_보정치, 이점·불리점은 내성굴림_이점불리를 개수로 합산). 상태이상을 거는
    굴림이면 시전자와 거는상태이상을 넘긴다(독에 익숙함). 추가불리: 스킬 효과의 "내성불리점"(고각도 슬라이딩).
    상태이상을 막는 굴림(거는상태이상 또는 상태이상이름)이면 장비의 상태이상 내성을 보정치에 더한다(#446)."""
    보정치 = 내성굴림_보정치(전투상태, 대상, 내성스탯) + 상태이상_내성(
        대상, 거는상태이상 or 상태이상이름
    )
    이점수, 불리수 = 내성굴림_이점불리(
        전투상태, 대상, 상태이상이름, 내성스탯, 시전자, 거는상태이상
    )
    이점, 불리 = dice_utils.이점_합산(이점수, 불리수 + bool(추가불리))
    성공, 값 = dice_utils.내성_굴림(보정치, 난이도, 이점=이점, 불리=불리)
    return 성공, 값, 보정치


def 유효_능력치(전투상태, 참가자):
    """수식_평가 컨텍스트의 "능력치"로 쓰는 사본 - 6개 능력치를
    유효_능력치값()으로 바꿔 넣는다("근력보정치" 같은 키워드가 장비/버프를
    반영하게 된다)."""
    사본 = dict(참가자["원본"])
    for 이름 in _능력치_목록:
        사본[이름] = 유효_능력치값(전투상태, 참가자, 이름)
    return 사본


def 평타_능력치_보정치(전투상태, 참가자):
    """ "평타스탯" 후보 중 가장 높은 보정치를 쓴다. 몬스터는 평타스탯
    개념이 없어 근력을 기준으로 삼는다. 캐릭터 특성의 "평타스탯"(계시의
    지혜 등)도 후보에 더한다."""
    if 참가자["진영"] != "아군":
        return 유효_능력치_보정치(전투상태, 참가자, "근력")
    후보 = list(참가자["원본"]["평타스탯"])
    for 이름 in traits.캐릭터특성_평타스탯(전투상태, 참가자):
        if 이름 not in 후보:
            후보.append(이름)
    return max(유효_능력치_보정치(전투상태, 참가자, 이름) for 이름 in 후보)


def 주문시전_보정치(전투상태, 참가자):
    if 참가자["진영"] != "아군":
        return 0
    스탯 = 캐릭터데이터.주문시전능력치(참가자["원본"])
    return 유효_능력치_보정치(전투상태, 참가자, 스탯)


def 귀신_스킬목록(전투상태, 참가자):
    """참가자(캐릭터 원본)의 "보유스킬" 중 "타입"에 "귀신" 태그가 있는 스킬 이름(보유 순서).
    스킬정의가 없거나 몬스터면 빈 목록."""
    스킬정의 = 전투상태.get("스킬정의") or {}
    return [
        이름
        for 이름 in 참가자.get("원본", {}).get("보유스킬", [])
        if "귀신" in (스킬정의.get(이름) or {}).get("타입", [])
    ]


def 귀신보유수(전투상태, 참가자):
    """귀신 태그 스킬 개수. job_skill_format.py <데미지 문법>의 "(귀신보유수)d8"용 - 데이터에
    저장하지 않고 전투 시스템이 계산해 대입한다."""
    return len(귀신_스킬목록(전투상태, 참가자))


def 기본_컨텍스트(전투상태, 참가자, 무기공격력필요=False):
    """수식_평가용 기본 컨텍스트(차수/추가공격/보정치/주문시전보정치/
    능력치/[무기공격력])를 만든다. skill_system도 이 함수를 직접 쓴다."""
    컨텍스트 = {
        "차수": core.차수(참가자),
        # 공격횟수 "3+추가공격"(삼연참) - 이번 턴에 쓴 추가행동과 무관한 캐릭터 수치
        "추가공격": (참가자.get("원본") or {}).get("추가공격", 0)
        if 참가자.get("진영") == "아군"
        else 0,
        # 일반공격 보정치는 수식이 쓸 때만 계산한다(formula.평타_보정치) - 평타스탯이 없는 참가자(인형)도
        # 주문시전보정치만 쓰는 수식(넨탄 등)은 계산되게(#367)
        "보정치": lambda: 평타_능력치_보정치(전투상태, 참가자),
        "주문시전보정치": 주문시전_보정치(전투상태, 참가자),
        "능력치": 유효_능력치(전투상태, 참가자),
        "능력치보정치": 캐릭터데이터.보정치표(
            참가자["원본"], 유효_능력치(전투상태, 참가자)
        ),
        "귀신보유수": 귀신보유수(전투상태, 참가자),
        "스타일성장횟수": 캐릭터데이터.스타일성장횟수(참가자["원본"].get("레벨") or 1)
        if 참가자.get("진영") == "아군"
        else 0,
    }
    if 무기공격력필요:
        무기데이터 = 참가자.get("장비데이터", {}).get("무기")
        if 무기데이터 is None:
            raise ValueError(f"'{참가자['이름']}'은(는) 무기를 장착하지 않았다.")
        컨텍스트["무기공격력"] = 유효_무기공격력(전투상태, 참가자, 무기데이터)
        컨텍스트.update(무기_보정치_효과(전투상태, 참가자))
    return 컨텍스트


def 무기_보정치_효과(전투상태, 참가자):
    """무기 주사위(무기공격력/보정공격력)용 컨텍스트 값(#330) - formula.수식_평가가 읽는다.
    "무기보정치추가": 무기 주사위에 평타 보정치를 몇 번 더 더하나(버프 귀혼일체, 특성 검귀의 도 마스터리).
    "치명타보정치대체": 치명타 때 무기 주사위를 늘리지 않고 치명타 주사위마다 보정치를 더하나(특성 청혈투귀)."""
    return {
        "무기보정치추가": 버프디버프_수치(전투상태, 참가자, "무기보정치추가")
        + traits.특성_수치(전투상태, 참가자, "무기보정치추가"),
        "치명타보정치대체": traits.특성_수치(전투상태, 참가자, "치명타보정치대체") > 0,
    }


def 유효_무기공격력(전투상태, 참가자, 무기데이터):
    """무기 주사위 표기. 특성이 "무기공격력"을 바꾸면(무기의 극의 - 소검 d10)
    그 값을, 아니면 무기 데이터의 "무기공격력"을 쓴다."""
    for 원소 in traits.캐릭터특성_무기효과(전투상태, 참가자, "무기공격력"):
        return 원소["변동값"]
    return 무기데이터["무기공격력"]


def 일반공격_추가피해(전투상태, 참가자, 컨텍스트):
    """일반공격/일반공격취급 스킬이 명중했을 때 더하는 특성 피해(무기의 극의 -
    광검 1d6). 치명타여도 주사위는 늘지 않는다."""
    return sum(
        formula.수식_평가(원소["변동값"], 컨텍스트)
        for 원소 in traits.캐릭터특성_무기효과(전투상태, 참가자, "일반공격추가피해")
    )


def _몬스터_AC_능력치(원본, 추가민첩):
    """몬스터 AC 수식을 평가할 능력치 - 원본 사본에 버프로 바뀐 민첩을 넣는다."""
    능력치사본 = dict(원본)
    원래민첩 = 원본.get("민첩", 10)
    if not isinstance(원래민첩, (int, float)):
        원래민첩 = 10
    능력치사본["민첩"] = 원래민첩 + 추가민첩
    return 능력치사본


def 최종AC(전투상태, 참가자):
    """아군: 장비 전 부위+세트효과+(버프/장비로 바뀐)민첩. 캐릭터 특성
    AC(판금숙련/견문색/첫턴회피보너스)는 마지막 특성_수치가 더한다.
    몬스터: 역할군 "AC" 수식(버프로 바뀐 민첩으로 평가)+원본 "AC보너스"+칭호 AC.
    양쪽 공통으로 버프/디버프 AC와 몬스터 특성 AC를 더한다. 감옥 참가자는 1 고정."""
    if 참가자.get("감옥"):
        return 1
    원본 = 참가자["원본"]
    추가민첩 = 버프디버프_수치(전투상태, 참가자, "민첩") + 버프디버프_수치(
        전투상태, 참가자, "전체"
    )

    if 참가자["진영"] == "아군":
        기본AC = equipment_system.최종AC_계산(
            원본,
            참가자["장비데이터"],
            세트목록=전투상태.get("세트정의"),
            추가민첩=추가민첩,
        )
    else:
        능력치사본 = _몬스터_AC_능력치(원본, 추가민첩)
        기본AC = participants.몬스터_수식_평가(
            participants.몬스터_역할군_수식(원본, "AC"), 능력치사본, 10
        )
        if not isinstance(기본AC, (int, float)):
            기본AC = 10
        AC보너스 = 원본.get("AC보너스", 0)
        if not isinstance(AC보너스, (int, float)):
            AC보너스 = 0
        기본AC += AC보너스 + traits.칭호_수치(전투상태, 참가자, "AC")

    return (
        기본AC
        + 버프디버프_수치(전투상태, 참가자, "AC")
        + traits.특성_수치(전투상태, 참가자, "AC")
    )


