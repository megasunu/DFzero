def _몬스터_대상목록_실행(전투상태, 몬스터참가자, 패턴, 대상):
    """패턴의 "타겟"으로 대상 목록을 정해 실행한다(내성패턴/단일/다중). 대상이 한 명인
    단일·랜덤 공격은 대상의 프렌드 실드가 다른 아군에게 옮길 수 있다(범위·전체는 그대로)."""
    if 패턴.get("타겟") == "적랜덤반복":
        return _몬스터_랜덤반복_실행(전투상태, 몬스터참가자, 패턴)
    대상목록 = monster_patterns.몬스터_패턴_대상목록(전투상태, 몬스터참가자, 패턴, 대상)
    if 패턴.get("타겟", "적단일") in ("적단일", "적랜덤") and len(대상목록) == 1:
        대상 = reactions.공격대상_반응(전투상태, 몬스터참가자, 대상목록[0])
        대상목록 = [대상]
    if "실패시데미지" in 패턴 and "데미지" not in 패턴:
        return monster_patterns.몬스터_내성패턴_실행(
            전투상태, 몬스터참가자, 패턴, 대상목록, 대상
        )
    if len(대상목록) <= 1:
        return monster_patterns.몬스터_패턴_실행(
            전투상태, 몬스터참가자, 패턴, 대상목록[0] if 대상목록 else 대상
        )
    return monster_patterns.몬스터_패턴_실행_다중(
        전투상태, 몬스터참가자, 패턴, 대상목록, 대상
    )


def _몬스터_랜덤반복_실행(전투상태, 몬스터참가자, 패턴):
    """ "타겟": "적랜덤반복" - "공격횟수"번, 칠 때마다 살아 있는 적 중 무작위 한 명을 새로 골라 한 번씩
    친다(같은 적이 여러 번 맞을 수 있다). 고른 대상의 프렌드 실드는 타격마다 본다(스틸 골렘 강철탄환)."""
    공격횟수 = 패턴.get("공격횟수", 1)
    if not isinstance(공격횟수, int):
        공격횟수 = 1
    상대진영 = "아군" if 몬스터참가자["진영"] == "적" else "적"
    한번 = {**패턴, "공격횟수": 1}
    결과들 = []
    for _ in range(공격횟수):
        후보 = [p for p in 전투상태["참가자"] if p["진영"] == 상대진영 and p["생존"]]
        if not 후보 or not 몬스터참가자["생존"]:
            break
        대상 = reactions.공격대상_반응(전투상태, 몬스터참가자, rng.대상.choice(후보))
        결과들.append(
            monster_patterns.몬스터_패턴_실행(전투상태, 몬스터참가자, 한번, 대상)
        )
    return 결과들


def _몬스터_공격단계_실행(전투상태, 몬스터참가자, 패턴, 대상):
    """ "공격단계1", "공격단계2", ...를 차례로 실행한다(스킬 "분할공격" - 할로윈 버스터와 같은
    양식). 단계마다 "타겟"/명중굴림/"효과"를 따로 적용하고, "기준대상": "공격단계N"이면 그 단계의
    기준 대상을 중심으로 범위를 잡는다(없으면 이번 턴에 고른 대상). 하스 세리말리온 하강공격."""
    기준, 결과들 = {}, []
    번호 = 1
    while f"공격단계{번호}" in 패턴:
        키 = f"공격단계{번호}"
        단계 = {"이름": 패턴.get("이름"), **패턴[키]}
        기준[키] = 기준.get(단계.get("기준대상"), 대상)
        결과 = _몬스터_대상목록_실행(전투상태, 몬스터참가자, 단계, 기준[키])
        결과들 += 결과 if isinstance(결과, list) else [결과]
        번호 += 1
    return 결과들


def _몬스터_자신버프_처리(전투상태, 몬스터참가자, 패턴):
    """공격 패턴의 "자신버프해제"/"자신버프획득"(이름 또는 리스트)을 명중과 상관없이 적용한다.
    해제를 먼저, 획득을 나중에 한다. 획득 지속턴은 "자신버프지속턴"(없으면 버프 정의/무기한)."""

    def 이름들(키):
        값 = 패턴.get(키) or []
        return [값] if isinstance(값, str) else list(값)

    해제, 획득 = 이름들("자신버프해제"), 이름들("자신버프획득")
