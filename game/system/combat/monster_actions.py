# 체력소환 - 인형사의 골렘 소환
# =====================================================
# 특성 "체력소환"({"몬스터", "체력비율", "이하"})이 있는 몬스터는 자기 차례가 시작될 때(행동불가면 아님) 체력이
# "체력비율" 이하("이하"가 없으면 미만)면 전투당 한 번 곧바로 "몬스터"를 부르고 그 차례의 행동은 그대로 한다.
# 부른 몬스터는 소환한 몬스터의 레벨·차수로, 이번 라운드에 이미 지나간 자리에 넣어 다음 라운드부터 움직인다.
# 살아 있는 적이 다섯(화면 적 칸 수)이면 부르지 못하고 다음 차례에 다시 본다. 칸이 다섯 다 찼으면 쓰러진 적의
# 칸을 넘겨받는다(쓰러진 적은 "칸비움" - 화면 칸에서만 빠지고 보상에는 남는다).
적칸_최대 = 5


def _체력소환_조건(전투상태, 몬스터참가자):
    """지금 부를 "체력소환" 설정, 아니면 None."""
    if 몬스터참가자.get("소환사용"):
        return None
    소환 = traits.체력소환(전투상태, 몬스터참가자)
    if 소환 is None:
        return None
    최대 = stats.유효_최대HP(전투상태, 몬스터참가자)
    기준 = 최대 * 소환.get("체력비율", 0.5)
    if 소환.get("이하"):  # 라키우스 분신, 인형사 골렘 - "절반 이하"
        return 소환 if 몬스터참가자["현재HP"] <= 기준 else None
    return 소환 if 몬스터참가자["현재HP"] < 기준 else None


def 소환칸_있음(전투상태):
    """적_소환이 부를 자리가 있는가 - 화면 적 칸이 다섯 다 찼으면 그중 쓰러진 적의 칸이 있어야 한다."""
    칸 = [p for p in 전투상태["참가자"] if p["진영"] == "적" and not p.get("칸비움")]
    return len(칸) < 적칸_최대 or any(not p["생존"] for p in 칸)


def _몬스터_소환패턴_실행(전투상태, 몬스터참가자, 패턴):
    """ "소환패턴"(케라하 나이아스 소환/비노슈 아도르 소환): "소환몬스터"를 빈 칸이나 쓰러진 적의 칸에 부른다.
    부른 몬스터는 다음 라운드부터 움직인다(적_소환). 칸이 있는지는 부르는 쪽(소환칸_있음)이 본다."""
    새것 = 적_소환(전투상태, 몬스터참가자, 패턴["소환몬스터"])
    결과 = {"공격자": 몬스터참가자["이름"], "행동": f"{새것['이름']} 소환!"}
    core.로그(전투상태, 결과, 종류="행동")
    return 결과


def 골렘_소환(전투상태, 몬스터참가자, 소환):
    """ "체력소환"의 "몬스터"를 곧바로 부른다. 자리가 없으면 부르지 않는다(다음 차례에 다시 본다)."""
    if sum(p["진영"] == "적" and p["생존"] for p in 전투상태["참가자"]) >= 적칸_최대:
        return None
    몬스터참가자["소환사용"] = True
    새것 = 적_소환(전투상태, 몬스터참가자, 소환["몬스터"])
    결과 = {"공격자": 몬스터참가자["이름"], "행동": f"{새것['이름']} 소환!"}
    core.로그(전투상태, 결과, 종류="행동")
    return 결과


def _캐스팅_발사_후_이어서(전투상태, 몬스터참가자):
    """밀린 차례 - 캐스팅을 풀고 캐스팅한 패턴을 쓴 뒤(_패턴_캐스팅_발사) 그 차례의 남은 행동을 이어서 한다
    . 이어서 하는 행동에서 또 캐스팅하면 다시 밀린다. 캐스팅이 끊기면(행동불가) 남은 행동도 없다.
    피격으로 취소됐으면 쏘지 않고 남은 행동을 이어서 한다."""
    정보 = 몬스터참가자.pop("캐스팅", None) or {}
    몬스터참가자["상태이상"] = [
        s for s in 몬스터참가자["상태이상"] if s.get("이름") not in ("캐스팅", "차징")
    ]
    # 피격으로 취소됐으면(hit_effects.캐스팅_피격_취소) 쏘지 않고 남은 행동만 이어서 한다
    결과 = None if 정보.get("취소") else _패턴_캐스팅_발사(전투상태, 몬스터참가자, 정보)
    이어서 = 정보.get("이어서")
    if not 이어서:
        몬스터참가자.pop("_마지막고정", None)
        return 결과
    return (
        _차수_행동(
            전투상태,
            몬스터참가자,
            이어서["회차"],
            이어서["차수"],
            이어서["대체사용"],
        )
        or 결과
    )


