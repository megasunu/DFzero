def _몬스터_대상목록_실행(전투상태, 몬스터참가자, 패턴, 대상):
    """패턴의 "타겟"으로 대상 목록을 정해 실행한다(내성패턴/단일/다중)."""
    대상목록 = _몬스터_패턴_대상목록(전투상태, 몬스터참가자, 패턴, 대상)
