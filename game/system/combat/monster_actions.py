def 몬스터_턴_실행(전투상태, 몬스터참가자):
    """몬스터 턴 자동 처리. 행동/타겟 선택은 monster_ai.py에 맡기고
    명중/피해 계산은 여기서 한다. "행동불가" 상태면 곧바로 무행동.
    한 턴에 차수만큼 행동한다(매번 패턴을 새로 굴림). 돌려주는 것은 마지막 행동의 결과.

    monster_ai가 고른 것은 항상 단일 대상(아군 1체)이지만, 패턴의
    "타겟"이 "적전체"/"적3체"면 그 대상을 기준으로 실제 공격 범위를
    넓힌다(몬스터_패턴_대상목록 참고) - 신규."""
    전투상태["현재턴_행동완료"] = True
    몬스터참가자.pop("버프스킬반응함", None)  # 특수패턴:시우스 - 자기 차례마다 한 번
    if 몬스터참가자.pop(
        "캐스팅발사", False
    ):  # 캐스팅으로 밀린 차례 - 캐스팅한 패턴을 쓰고 남은 행동을 이어서 한다
        status.행동_은신해제(전투상태, 몬스터참가자)
        return _캐스팅_발사_후_이어서(전투상태, 몬스터참가자)
    몬스터참가자["몬스터턴카운트"] += 1
    생존아군 = [p for p in 전투상태["참가자"] if p["진영"] == "아군" and p["생존"]]
    if not 생존아군:
        return None
    # 차례 시작에 행동불가였으면 지속턴 감소로 막 풀렸어도 이 차례는 쉰다 - 아군과 같다
    차례시작_행동불가 = 몬스터참가자.pop("턴시작_행동불가", False)
    if 차례시작_행동불가 or status.상태이상_플래그(전투상태, 몬스터참가자, "행동불가"):
        # 피니쉬!도 패턴 사용이라 나가지 않고, 이 몬스터가 건 들러붙음만 사라진다(특수패턴:펜릴)
        traits.시전자_상태이상_해제(전투상태, 몬스터참가자, "들러붙음")
        status.주문영창_해제(전투상태, 몬스터참가자, "행동불가")
        결과 = {"공격자": 몬스터참가자["이름"], "행동": "행동불가 상태로 무행동"}
        core.로그(전투상태, 결과, 종류="행동")
        return 결과
    if 몬스터참가자["몬스터턴카운트"] == 1 and status.특성_플래그(
        전투상태, 몬스터참가자, "텔레포트"
    ):
        return _텔레포트(전투상태, 몬스터참가자)
    턴시작_감옥(전투상태, 몬스터참가자)
    소환 = _체력소환_조건(전투상태, 몬스터참가자)
    if 소환 is not None and 소환.get("분신"):
        분신_소환(
            전투상태, 몬스터참가자
        )  # 캐스팅 없이 부르고 그 차례의 행동은 그대로 한다
    elif 소환 is not None:
        골렘_소환(
            전투상태, 몬스터참가자, 소환
        )  # 차례 시작에 곧바로 부르고 행동은 그대로 한다

    # 행동주기 특성(돌연변이:거대화 2): 첫 차례는 쉬고 2, 4, 6...번째 차례에만 행동한다.
    # 쉬는 차례에도 턴_시작_처리가 지속턴을 줄인다
    주기, 특성이름 = traits.행동주기(전투상태, 몬스터참가자)
    if 몬스터참가자["몬스터턴카운트"] % 주기:
        결과 = {
            "공격자": 몬스터참가자["이름"],
            "행동": f"{특성이름.split(':')[-1]}로 쉼",
            "쉼": True,  # 화면 문장은 "OO는 쉬고있다."(ctl_battle_log._행동_문장)
        }
        core.로그(전투상태, 결과, 종류="행동")
        return 결과

    # 차수만큼 행동한다: 매번 1~6번을 새로 굴려 각각 실행. 턴 시작/종료 처리,
    # 행동불가 검사, 거대화의 쉬는 차례는 턴마다 한 번이다. 도중에 쓰러지거나 행동불가가 되거나
    # 살아 있는 적이 없으면 멈춘다.
    차수 = 몬스터참가자["원본"].get("차수") or 1
    # 특성 "추가행동"(하늘성의 친위대장 - 패턴 1회 추가)은 차수와 달리 AC·체력을 바꾸지 않고 행동만 늘린다
    차수 += int(traits.특성_수치(전투상태, 몬스터참가자, "추가행동"))
    status.행동_은신해제(전투상태, 몬스터참가자)  # 패턴을 쓰면 은신이 풀린다
    return _차수_행동(전투상태, 몬스터참가자, 0, 차수, {})


def _텔레포트(전투상태, 몬스터참가자):
    """챔피언 텔레포트 - 첫 자기 차례에 "OO는 텔레포트를 썼다!" 하고 전투에서 빠진다. 도망처럼 처치로
    치지 않아 보상이 없다(ctl_rewards)."""
    몬스터참가자["생존"] = False
    몬스터참가자["도망"] = True
    결과 = {
        "공격자": 몬스터참가자["이름"],
        "행동": "텔레포트를 썼다!",
        "텔레포트": True,
    }
    core.로그(전투상태, 결과, 종류="행동")
    return 결과


def 기습_실행(전투상태):
    """챔피언 기습 - 전투가 시작될 때 기습이 있는 몬스터마다 패턴을 한 번 쓴다(차례·턴 수와 상관없다)."""
    for 몬스터 in [p for p in 전투상태["참가자"] if p["진영"] == "적" and p["생존"]]:
        if not status.특성_플래그(전투상태, 몬스터, "기습"):
            continue
        생존아군 = [p for p in 전투상태["참가자"] if p["진영"] == "아군" and p["생존"]]
        if not 생존아군:
            return
        core.로그(전투상태, {"공격자": 몬스터["이름"], "행동": "기습!"}, 종류="행동")
        _몬스터_한번_행동(전투상태, 몬스터, 생존아군, {})
        몬스터.pop("_마지막고정", None)


def _차수_행동(전투상태, 몬스터참가자, 시작회차, 차수, 대체사용):
    """시작회차번째부터 차수번째 행동까지 한다. 패턴 캐스팅을 시작하면 남은 행동을 "캐스팅"의 "이어서"에 적고
    멈춘다 - 밀린 차례에 쏜 뒤 이어서 한다(_캐스팅_발사_후_이어서). 마지막이 아닌 행동에서 "마지막행동" 패턴이
    나와 고정해 둔 것("_마지막고정")은 차례가 끝나면 버린다."""
    결과 = None
    for 회차 in range(시작회차, 차수):
        if 회차 and (
            not 몬스터참가자["생존"]
            or status.상태이상_플래그(전투상태, 몬스터참가자, "행동불가")
        ):
            break
        생존아군 = [p for p in 전투상태["참가자"] if p["진영"] == "아군" and p["생존"]]
        if not 생존아군:
            break
        결과 = _몬스터_한번_행동(
            전투상태, 몬스터참가자, 생존아군, 대체사용, 회차 == 차수 - 1
        )
        if 몬스터참가자.get("캐스팅시작"):
            몬스터참가자["캐스팅"]["이어서"] = {
                "회차": 회차 + 1,
                "차수": 차수,
                "대체사용": 대체사용,
            }
            return 결과
        # 영창하거나 "한번만행동" 패턴(랜스 돌격)을 쓰면 그 턴은 끝난다
        if 몬스터참가자.pop("_한번만행동", False) or (
            isinstance(결과, dict) and 결과.get("종류") == "영창"
        ):
            break
    몬스터참가자.pop("_마지막고정", None)
    return 결과


