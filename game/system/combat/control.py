def 홀딩_목록(참가자):
    return [s for s in 참가자.get("상태이상", []) if s.get("이름") == "홀딩"]


def 홀딩_걸기(
    전투상태,
    시전자,
    대상,
    출처,
    피해,
    속성=None,
    추가피해목록=None,
    최종피해배율=1,
    무적=False,
    충격파=None,
    슈퍼아머=False,
    공격타입=None,
    공격분류=(),
    몹몰이=False,
    우선도=0,
):
    """홀딩을 건다 - 상태이상 "홀딩" 인스턴스. 피해가 있으면("홀딩" 태그 공격) 굴린 피해(방어/속성 전)를
    맡겨 두고 피해_적용은 대상의 다음 차례 시작(홀딩_발동)에 한다. 피해가 None이면 피해 없이 홀딩만 건다.
    우선도(스킬 "홀딩값")만큼 대상의 우선도를 내리고 남은 순서를 다시 세운다 - 경직과 따로라 경직배율·
    슈퍼아머·경직불가와 상관없다. 피격_처리(경직)보다 먼저 불러야
    이미 행동한 대상의 홀딩 전용 차례가 생긴다. 무적이면 이 홀딩이 남은 동안 시전자는 적의 공격 피해를
    받지 않고(홀딩무적인가), 충격파(스킬 "충격파")는 피해가 들어갈 때 이어서 굴린다(마운트).
    슈퍼아머면(반드시 잡는다!) 이 홀딩이 남은 동안 시전자는 "슈퍼아머" 상태다(지속턴 없이 "홀딩연동" -
    홀딩이 풀리면 _홀딩슈퍼아머_정리가 지운다). 몹몰이면(블러디 레이브) 이 홀딩이 남은 동안 대상이 "몹몰이"다
    (지속턴 없이 "홀딩몹몰이" - 홀딩이 풀릴 때 피해보다 먼저 홀딩몹몰이_정리가 지운다)."""
    항목 = {
        "이름": "홀딩",
        "지속턴": None,
        "시전자id": 시전자["id"],
        "출처": 출처,
        "보류피해": 피해,
        "속성": 속성,
        "추가피해목록": [list(항목) for 항목 in 추가피해목록 or []],
        "최종피해배율": 최종피해배율,
    }
    if 공격타입:
        항목["공격타입"] = 공격타입
    if 공격분류:
        항목["공격분류"] = list(공격분류)
    if 무적:
        항목["시전자무적"] = True
    if 충격파:
        항목["충격파"] = dict(충격파)
    대상.setdefault("상태이상", []).append(항목)
    if 우선도:
        대상["우선도"] = 대상.get("우선도", 0) - 우선도
        남은_순서_정렬(전투상태)
    if 몹몰이:
        항목["대상몹몰이"] = True
        if not any(s.get("홀딩몹몰이") for s in 대상["상태이상"]):
            대상["상태이상"].append(
                {"이름": "몹몰이", "지속턴": None, "홀딩몹몰이": True}
            )
    if 슈퍼아머:
        항목["시전자슈퍼아머"] = True
        if not any(s.get("홀딩연동") for s in 시전자.get("상태이상", [])):
            시전자.setdefault("상태이상", []).append(
                {"이름": "슈퍼아머", "홀딩연동": True}
            )


def 홀딩슈퍼아머_정리(전투상태):
    """ "시전자슈퍼아머" 홀딩이 하나도 남지 않은 시전자에게서 "홀딩연동" 슈퍼아머를 지운다."""
    남은시전자 = {
        항목.get("시전자id")
        for p in 전투상태["참가자"]
        for 항목 in 홀딩_목록(p)
        if 항목.get("시전자슈퍼아머")
    }
    for p in 전투상태["참가자"]:
        if p.get("id") in 남은시전자:
            continue
        if any(s.get("홀딩연동") for s in p.get("상태이상", [])):
            p["상태이상"] = [s for s in p["상태이상"] if not s.get("홀딩연동")]
    홀딩몹몰이_정리(전투상태)


def 홀딩몹몰이_정리(전투상태):
    """ "대상몹몰이" 홀딩이 하나도 남지 않은 대상에게서 "홀딩몹몰이" 몹몰이를 지운다."""
    for p in 전투상태["참가자"]:
        if any(항목.get("대상몹몰이") for 항목 in 홀딩_목록(p)):
            continue
        if any(s.get("홀딩몹몰이") for s in p.get("상태이상", [])):
            p["상태이상"] = [s for s in p["상태이상"] if not s.get("홀딩몹몰이")]


def 피해무효_사유(전투상태, 대상):
    """적의 공격 피해를 막는 까닭 - 상태이상 "무적"이면 "무적", 시전자무적 홀딩이면 "잡기 중",
    둘 다 아니면 None."""
    if status.상태이상_플래그(전투상태, 대상, "피해무효"):
        return "무적"
    if 홀딩무적인가(전투상태, 대상):
        return "잡기 중"
    return None


def 홀딩무적인가(전투상태, 참가자):
    """참가자가 건 "시전자무적" 홀딩(마운트)이 아직 남아 있나 - 그런 홀딩이 있을 때만 끊긴 홀딩을 먼저 정리한다."""

    def 남았나():
        return any(
            항목.get("시전자무적") and 항목.get("시전자id") == 참가자.get("id")
            for p in 전투상태["참가자"]
            for 항목 in 홀딩_목록(p)
        )

    if not 남았나():
        return False
    홀딩_정리(전투상태)
    return 남았나()


def 홀딩_시전자(전투상태, 항목):
    return next(
        (p for p in 전투상태["참가자"] if p.get("id") == 항목.get("시전자id")), None
    )


def 무력화_중인가(전투상태, 참가자):
    return any(
        (전투상태["상태이상정의"].get(s.get("이름")) or {}).get("분류") == "무력화CC"
        for s in 참가자.get("상태이상", [])
    )


def 홀딩_정리(전투상태):
    """건 사람이 쓰러졌거나 무력화CC에 걸린 홀딩은 피해 없이 푼다. 홀딩이 뜻을 갖는 곳
    (명중 판정의 이점, 차례 시작의 피해, 홀딩 전용 차례)마다 먼저 부른다."""
    for p in 전투상태["참가자"]:
        for 항목 in 홀딩_목록(p):
            시전자 = 홀딩_시전자(전투상태, 항목)
            if 시전자 is None or not 시전자["생존"] or 무력화_중인가(전투상태, 시전자):
                p["상태이상"].remove(항목)
    홀딩슈퍼아머_정리(전투상태)
