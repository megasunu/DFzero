def 다음_턴(전투상태):
    """현재 턴을 종료하고 다음 생존자에게 턴을 넘긴다. 참가자를 한
    바퀴 다 돌면 라운드가 1 증가하며, 그 시점에 이니셔티브/우선도를
    다시 계산해 재정렬한다. "턴즉시종료"(공중에뜸) 상태인 참가자는
    턴 시작/종료 처리는 받지만 실제 행동 기회 없이 곧바로 다음
    사람에게 넘어간다. 전투 종료 여부도 갱신한다.

    이미 끝난 전투면(마지막 적/아군이 방금 쓰러진 경우 포함) 아무것도 하지 않고
    현재 참가자를 그대로 돌려준다 - 승패가 난 뒤에 다음 참가자의 턴 시작 처리
    (지속피해, 라운드 증가)가 돌지 않게(B9)."""
    현재참가자 = 전투상태["참가자"][전투상태["현재턴"]]
    if core.종료판정_갱신(전투상태) is not None:
        return 현재참가자
    밀림 = bool(현재참가자.pop("캐스팅시작", False))
    if 밀림:
        # 캐스팅(축염포 #280) - 턴 종료 처리는 밀린 차례 끝에 한다
        다음인덱스 = _캐스팅_밀기(전투상태, 현재참가자)
    else:
        턴_종료_처리(전투상태, 현재참가자)
        # 방금 도망쳐 적이 모두 사라졌으면 다음 참가자의 턴을 시작하지 않고 끝낸다.
        if 현재참가자.get("도망") and core.종료판정_갱신(전투상태) is not None:
            return 현재참가자
        다음인덱스 = 전투상태["현재턴"]

    인원수 = len(전투상태["참가자"])
    최대반복 = 인원수 * 3 + 1  # 전원이 턴즉시종료 상태인 극단적 경우의 안전장치

    for 반복 in range(최대반복):
        다음인덱스 = (다음인덱스 + 1) % 인원수
        if 다음인덱스 == 0 and not (밀림 and 반복 == 0):
            전투상태["라운드"] += 1
            이니셔티브_재계산_및_정렬(전투상태)

        후보 = 전투상태["참가자"][다음인덱스]
        if 후보.pop("캐스팅차례", False):
            # 캐스팅으로 밀린 차례 - 턴 시작 처리 없이 돌려준다(쏘는 것은 skill_run.다음_턴)
            if not 후보["생존"] or 후보.get("감옥"):
                continue
            후보["캐스팅발사"] = True
            전투상태["현재턴"] = 다음인덱스
            core.종료판정_갱신(전투상태)
            return 후보
        if 후보.pop("홀딩차례", False):
            # 이미 행동한 뒤 홀딩으로 밀린 차례 - 홀딩 피해만(행동, 지속턴 감소, 지속피해 없음)
            if 후보["생존"]:
                damage.홀딩_발동(전투상태, 후보)
            if core.종료판정_갱신(전투상태) is not None:
                전투상태["현재턴"] = 다음인덱스
                return 후보
            continue
        if not 후보["생존"] or 후보.get("감옥"):  # 감옥 참가자는 턴이 없다
            continue

        턴_시작_처리(전투상태, 후보)
        if status.상태이상_플래그(전투상태, 후보, "턴즉시종료"):
            core.로그(
                전투상태,
                {"공격자": 후보["이름"], "행동": "무행동 (턴즉시종료 상태)"},
                종류="행동",
            )
            턴_종료_처리(전투상태, 후보)
            continue

        전투상태["현재턴"] = 다음인덱스
        core.종료판정_갱신(전투상태)
        return 후보

    전투상태["현재턴"] = 다음인덱스
    core.종료판정_갱신(전투상태)
    return 전투상태["참가자"][다음인덱스]


def 전투이탈_시도(전투상태, 참가자):
    """참가자가 파티를 대표해 전투 이탈(도망)을 시도한다. 성공하면
    파티 전체가 전투에서 빠져나온다. "도망불가" 상태면 판정 없이 실패.

    판정: 참가자의 민첩판정(1d20+보정치)이 생존한 적 중 가장 민첩한
    개체의 민첩보정치+10(난이도)과 같거나 높으면 성공(D&D 5판의 "상대적 민첩
    대결" 관례를 가져와 구현 - 확정된 공식은 아니다).

    성공하면 전투상태["종료"]를 "전투이탈"로 표시한다("아군승리"/
    "적승리"와 구분되는 결과값 - 호출부가 승패 없이 물러난 것으로
    처리해야 한다). 실패하면 로그만 남고 아무것도 바뀌지 않는다.

    반환값: (성공여부, 최종굴림값, 난이도). "도망불가"로 판정 자체를
    못 했으면 (False, None, None)."""
    if status.상태이상_플래그(전투상태, 참가자, "도망불가"):
        core.로그(
            전투상태,
            {"공격자": 참가자["이름"], "행동": "도망 시도 실패 (도망불가 상태)"},
            종류="행동",
        )
        return False, None, None

    적생존 = [p for p in 전투상태["참가자"] if p["진영"] == "적" and p["생존"]]
    난이도 = 10 + max(
        (stats.유효_능력치_보정치(전투상태, 적, "민첩") for 적 in 적생존), default=0
    )
    민첩보정치 = stats.유효_능력치_보정치(전투상태, 참가자, "민첩")
    최종값, _ = dice_utils.판정_굴림(민첩보정치)
    성공 = 최종값 >= 난이도

    if 성공:
        전투상태["종료"] = "전투이탈"
        core.전투종료시_보유자원_초기화(전투상태)
        core.로그(
            전투상태,
            {
                "공격자": 참가자["이름"],
                "행동": f"도망 성공 (파티 전체 전투 이탈, {최종값} vs DC{난이도})",
            },
            종류="행동",
        )
    else:
        core.로그(
            전투상태,
            {
                "공격자": 참가자["이름"],
                "행동": f"도망 실패 ({최종값} vs DC{난이도})",
            },
            종류="행동",
        )

    return 성공, 최종값, 난이도
