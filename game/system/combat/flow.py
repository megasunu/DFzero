# 전투_시작()의 정의모음에 넣을 수 있는 칸 - 이름 그대로 전투상태의 칸이 된다(생략하면 빈 딕셔너리).
정의_칸 = (
    "버프정의",
    "디버프정의",
    "상태이상정의",
    "특성정의",
    "캐릭터특성정의",
    "칭호정의",
    "세트정의",
    "스킬정의",
)


def 전투_시작(파티, 몬스터원본목록, 장비데이터모음, 정의모음=None, 시작반응_보류=False):
    """새 전투를 시작한다.

    파티: 생존자만 참가시킨다. 몬스터원본목록: 순서대로 참가시키며
    이 순서가 그대로 "대형위치"(좌우 인접 판정 기준)가 된다.
    장비데이터모음: {캐릭터명: {슬롯: 아이템데이터, ...}, ...}.
    정의모음: 데이터 정의 테이블 딕셔너리. 칸 이름은 정의_칸에 있는 것만 쓴다(오타는 ValueError).
    - 버프정의/디버프정의/상태이상정의: buff.py/debuff.py/status_effects.py의 각 목록.
    - 특성정의: 몬스터의 "특성" 이름을 찾을 정의 테이블(monster_ability.py
      "특성목록" 등). 생략 시 몬스터 특성은 아무 효과도 반영되지 않는다.
    - 캐릭터특성정의: 아군 캐릭터의 "보유특성" 이름을 찾을 정의 테이블
      (job_ability_XX.py "특성목록"들을 합친 것) - AC/명중/데미지/방어력/
      속도/치명타범위/행동보너스에 반영된다(_캐릭터특성_수치 참고).
    - 칭호정의: monster_title.py "칭호목록".
    - 세트정의: eq_02_armor_set.py "방어구세트목록" 등 - 활성화된 세트
      (구성품 전부 장착, 또는 방어구 5부위를 같은 재질로 - equipment_system.
      세트효과_목록)의 효과가 AC/속도 등에 더해진다.
    - 스킬정의: job_skill_XX.py "스킬목록"들을 합친 것 - 수식 변수
      "귀신보유수"(시전자가 보유한 "귀신" 태그 스킬 개수)를 셀 때 쓴다.
    """
    정의모음 = 정의모음 or {}
    모르는칸 = set(정의모음) - set(정의_칸)
    if 모르는칸:
        raise ValueError(f"전투_시작 정의모음에 모르는 칸: {sorted(모르는칸)}")
    전투상태 = {
        "참가자": [],
        "현재턴": 0,
        "라운드": 1,
        "로그": [],
        "공격연출": [],  # 화면이 가져가 비운다(damage.공격연출_기록)
        "종료": None,
        **{칸: 정의모음.get(칸) or {} for 칸 in 정의_칸},
    }

    아군들 = list(party_system.생존자_목록(파티))
    인형 = 파티.get("인형")
    if 인형 and 인형["현재HP"] > 0:  # 인형은 맨 마지막(5번째 칸)
        아군들.append(인형)
    for 대형위치, 캐릭터 in enumerate(아군들):
        전투상태["참가자"].append(
            _아군_인스턴스(
                전투상태, 캐릭터, 장비데이터모음.get(캐릭터["캐릭터명"], {}), 대형위치
            )
        )

    for 대형위치, 몬스터원본 in enumerate(몬스터원본목록):
        몬스터원본 = traits.능력치특성_반영(전투상태["특성정의"], 몬스터원본)
        인스턴스 = participants.적_참가자_생성(몬스터원본)
        인스턴스["대형위치"] = 대형위치
        속도수식 = 몬스터원본.get("속도", 0)
        기본값 = formula.수식_평가(속도수식, {"능력치": 몬스터원본})
        인스턴스["기본이니셔티브"] = 기본값
        인스턴스["이니셔티브"] = 기본값
        전투상태["참가자"].append(인스턴스)

    _참가자_구분(전투상태)

    # 몬스터 시작 HP를 특성(종족:타우/체력증가 등)과 칭호(보스 등)까지
    # 반영한 최대HP로 채운다 - 참가자가 전부 들어온 뒤에 계산해야
    # "조건부효과"(적상태 등) 판정도 정상적으로 된다.
    for 참가자 in 전투상태["참가자"]:
        if 참가자["진영"] == "적":
            참가자["현재HP"] = max(1, formula.올림(stats.유효_최대HP(전투상태, 참가자)))

    # 특성/버프의 "속도"(선빵필승/암살자/종족:루가루/계시 등)가 첫
    # 라운드 순서에도 반영되도록 시작 시점에 한 번 계산한다.
    for 참가자 in 전투상태["참가자"]:
        참가자["이니셔티브"] = stats.유효_이니셔티브(전투상태, 참가자)
        참가자["우선도"] = stats.유효_우선도(전투상태, 참가자)
    _턴순서_정렬(전투상태)
    traits.전투시작_특성(전투상태)
    # 시작반응_보류: 반응 선택 팝업을 띄울 화면이 아직 없으면(던전
    # 화면에서 전투가 시작됨) 전투시작 반응은 전투 화면이 전투시작_반응_처리로 한다.
    if 시작반응_보류:
        전투상태["시작반응_대기"] = True
    else:
        reactions.전투시작_반응(전투상태)
    core.종료판정_갱신(전투상태)
    if 전투상태["참가자"]:
        턴_시작_처리(전투상태, 전투상태["참가자"][0])
    return 전투상태


def _아군_인스턴스(전투상태, 캐릭터, 장비데이터, 대형위치):
    """아군 참가자 하나 - 장비 보너스와 이니셔티브(d20 + 기본속도 + 장비 속도)까지. 인형(파티["인형"],
    캐릭터 "인형" 칸이 있음)이면 참가자에도 "인형": True를 단다 - 조종하지 않고 행동표대로 움직인다."""
    인스턴스 = participants.아군_참가자_생성(캐릭터, 장비데이터)
    인스턴스["대형위치"] = 대형위치
    if 캐릭터.get("인형"):
        인스턴스["인형"] = True
    장비보너스 = equipment_system.캐릭터_장비_보너스(
        캐릭터, 인스턴스["장비데이터"], 전투상태["세트정의"]
    )
    인스턴스["장비보너스"] = 장비보너스
    기본값 = dice_utils.d20_굴림() + 캐릭터["기본속도"] + 장비보너스["속도보너스"]
    인스턴스["기본이니셔티브"] = 기본값
    인스턴스["이니셔티브"] = 기본값
    return 인스턴스


def 인형_참가(전투상태, 인형, 장비데이터=None):
    """전투 중에 인형을 불렀을 때 - 이미 있던 인형 참가자는 빼고("교체됨", 쓰러진 것으로 친다) 새
    인형을 참가자 목록 맨 뒤에 넣는다(이번 라운드는 마지막 차례, 다음 라운드부터 이니셔티브 순)."""
    for p in 전투상태["참가자"]:
        if p.get("인형") and not p.get("교체됨"):
            p["교체됨"] = True
            p["생존"] = False
    아군위치 = [p["대형위치"] for p in 전투상태["참가자"] if p["진영"] == "아군"]
    인스턴스 = _아군_인스턴스(
        전투상태, 인형, 장비데이터 or {}, max(아군위치, default=-1) + 1
    )
    인스턴스["id"] = max((p["id"] for p in 전투상태["참가자"]), default=-1) + 1
    인스턴스["이니셔티브"] = stats.유효_이니셔티브(전투상태, 인스턴스)
    인스턴스["우선도"] = stats.유효_우선도(전투상태, 인스턴스)
    전투상태["참가자"].append(인스턴스)
    return 인스턴스


def _참가자_구분(전투상태):
    """참가자마다 고유 "id"(순번)를 붙이고, 같은 이름의 몬스터는 대형위치 순으로
    "고블린 A"/"고블린 B"처럼 표시 이름을 나눈다(B8). 참가자를 다시 찾을 때는
    이름 대신 id(core.참가자_찾기)를 쓴다."""
    for 번호, 참가자 in enumerate(전투상태["참가자"]):
        참가자["id"] = 번호
    적 = sorted(
        (p for p in 전투상태["참가자"] if p["진영"] == "적"),
        key=lambda p: p["대형위치"],
    )
    개수 = {}
    for p in 적:
        개수[p["이름"]] = 개수.get(p["이름"], 0) + 1
    순번 = {}
    for p in 적:
        원래 = p["이름"]
        if 개수[원래] > 1:
            k = 순번.get(원래, 0)
            순번[원래] = k + 1
            p["이름"] = f"{원래} {chr(ord('A') + k)}"


def _턴순서_정렬(전투상태):
    """참가자 리스트를 (우선도, 이니셔티브) 순으로 내림차순 정렬한다 -
    우선도가 먼저고, 우선도가 같을 때만 이니셔티브로 가른다."""
    전투상태["참가자"].sort(
        key=lambda p: (p.get("우선도", 0), p["이니셔티브"]), reverse=True
    )


def _캐스팅_밀기(전투상태, 참가자):
    """캐스팅을 시작한 참가자(지금 차례)의 이번 라운드 우선도를 1 내리고 "캐스팅차례"를 달아 아직 행동하지 않은
    참가자들 사이 (우선도, 이니셔티브) 자리로 옮긴다(같으면 뒤). 다음 차례를 찾기 시작할 인덱스(한 칸 앞)를 돌려준다."""
    목록 = 전투상태["참가자"]
    현재 = 전투상태["현재턴"]
    참가자["우선도"] = 참가자.get("우선도", 0) - 1
    참가자["캐스팅차례"] = True
    뒤 = sorted(
        목록[현재 + 1 :] + [참가자],
        key=lambda p: (p.get("우선도", 0), p["이니셔티브"]),
        reverse=True,
    )
    목록[:] = 목록[:현재] + 뒤
    return 현재 - 1


def 이니셔티브_재계산_및_정렬(전투상태):
    """라운드 전환 시 다음_턴()이 호출한다. 생존자만 "이니셔티브"/
    "우선도"를 재계산해 다시 정렬한다(사망자는 재계산하지 않는다)."""
    for 참가자 in 전투상태["참가자"]:
        참가자.pop(
            "홀딩차례", None
        )  # 지난 라운드의 홀딩 전용 차례(damage.남은_순서_정렬)
        참가자.pop("캐스팅차례", None)  # 쏘기 전에 쓰러져 남은 표시
        if 참가자["생존"]:
            참가자["이니셔티브"] = stats.유효_이니셔티브(전투상태, 참가자)
            참가자["우선도"] = stats.유효_우선도(전투상태, 참가자)
    _턴순서_정렬(전투상태)


