def 주문영창_해제(전투상태, 참가자, 이유):
    """참가자의 "주문영창"을 지운다(있었으면 로그를 남기고 True)."""
    남길것 = [i for i in 참가자.get("상태이상", []) if i.get("이름") != "주문영창"]
    if len(남길것) == len(참가자.get("상태이상", [])):
        return False
    참가자["상태이상"] = 남길것
    core.로그(
        전투상태,
        {"대상": 참가자["이름"], "비고": f"{이유} 때문에 '주문영창'이 끊김"},
        종류="비고",
    )
    return True


def 영창_방해(전투상태, 대상, 상태이름):
    """방금 걸린 상태이상이 행동불가형이거나 "침묵"이면 대상의 주문영창을 푼다."""
    정의 = (전투상태.get("상태이상정의") or {}).get(상태이름) or {}
    if 상태이름 == "침묵" or (정의.get("효과") or {}).get("행동불가"):
        주문영창_해제(전투상태, 대상, f"'{상태이름}'")


def 살아있는_감옥(전투상태, 참가자):
    """참가자를 가둔(상태이상 "감옥"의 "감옥id") 살아 있는 감옥 참가자, 없으면 None."""
    for 항목 in 참가자.get("상태이상", []):
        if 항목.get("이름") == "감옥":
            감옥 = core.참가자_찾기(전투상태, 항목.get("감옥id"))
            if 감옥 is not None and 감옥["생존"]:
                return 감옥
    return None


def 감옥_대상(전투상태, 공격자, 대상):
    """갇힌 사람이 적을 노리면 그 몫은 감옥이 받는다 - 그 감옥을, 아니면 대상을 그대로 돌려준다."""
    if 대상 is None or 대상.get("진영") != "적":
        return 대상
    return 살아있는_감옥(전투상태, 공격자) or 대상


