def 로그(전투상태, 항목, *, 종류):
    """항목을 전투 로그에 쌓는다. "종류"(로그_종류 중 하나)를 항목에 적는다 - 항목 자체를 고치므로
    호출한 쪽이 돌려주는 결과에도 들어간다. 그 사이 쓰러진 참가자(damage.피해_적용이 "쓰러짐대기"에
    넣음)가 있으면 이 항목의 "쓰러짐"(이름 목록)으로 붙인다 - 전투 로그 문장이 "OO은 쓰러졌다!"를 쓴다.
    "뒤따를로그"(빗나간 공격의 집요함 - damage.집요함_발동)는 이 항목 바로 뒤에 붙인다."""
    항목["종류"] = 종류
    쓰러짐 = 전투상태.pop("쓰러짐대기", None)
    if 쓰러짐:
        항목["쓰러짐"] = 쓰러짐
    넘친 = 전투상태.pop("넘친피해대기", None)
    if 넘친:
        항목["넘친피해"] = 넘친
    전투상태["로그"].append(항목)
    전투상태["로그"] += 전투상태.pop("뒤따를로그", [])


# =====================================================
# 피해 집계 - 전투 로그에서 "누가 얼마를 넣었는지" (#밸런스 측정)
# =====================================================


def _수(값):
    return isinstance(값, (int, float)) and not isinstance(값, bool)


def _한_대상(대상):
    if isinstance(대상, list):
        return 대상[0] if len(대상) == 1 else None
    return 대상


def _항목_피해들(항목):
    """로그 항목 하나의 [(대상, 피해)]. 모양: "타격" 목록이 있으면 타격마다(타격에 "대상"이 없으면 항목의 대상 -
    몬스터 패턴), 없으면 "총피해"(지속공격 발동), 그것도 없으면 "피해"(일반공격, 비고 - 홀딩·반격·지속피해 등)."""
    타격들 = 항목.get("타격")
    if isinstance(타격들, list):
        기본 = _한_대상(항목.get("대상"))
        return [
            (t.get("대상") or 기본, t["피해"]) for t in 타격들 if _수(t.get("피해"))
        ]
    대상 = _한_대상(항목.get("대상"))
    for 칸 in ("총피해", "피해"):
        if _수(항목.get(칸)):
            return [(대상, 항목[칸])]
    return []


def 피해_내역(전투상태):
    """전투 로그의 피해를 [(귀속, 대상이름, 피해)]로 편다. 귀속은 항목의 "귀속"(상태이상 지속 피해 - 건 사람),
    없으면 "공격자"다. 흡수된 피해(임시생명력·분신 등)는 로그 피해에 들어 있어 그대로 센다.

    "넘친피해"({대상: 양})는 쓰러뜨린 타격의 귀속에게 음수 행으로 넣는다 - 합치면 넘친 피해를 뺀 값이 된다.
    넘친피해는 다음에 쌓이는 로그 항목에 붙으므로 쓰러뜨린 타격보다 앞 항목(명중 때 특성이 쓴 비고 줄)에 붙기도
    하고, 몹몰이처럼 뒤따르는 줄이 쓰러뜨리기도 한다. 그래서 붙은 항목부터 그 대상에게 양수 피해를 준 첫 행의
    귀속에게 돌린다(쓰러진 대상은 그 뒤로 더 맞지 않는다). 끝까지 없으면 그 대상의 마지막 양수 행이다."""
    행들, 대기 = [], {}
    for 항목 in 전투상태["로그"]:
        귀속 = 항목.get("귀속") or 항목.get("공격자")
        피해들 = _항목_피해들(항목)
        for 대상, 양 in (항목.get("넘친피해") or {}).items():
            대기[대상] = 대기.get(대상, 0) + 양
        행들 += [(귀속, 대상, 피해) for 대상, 피해 in 피해들]
        for 대상 in [t for t in 대기 if any(d > 0 and u == t for u, d in 피해들)]:
            행들.append((귀속, 대상, -대기.pop(대상)))
    for 대상, 양 in 대기.items():
        마지막 = next((r[0] for r in reversed(행들) if r[1] == 대상 and r[2] > 0), None)
        행들.append((마지막, 대상, -양))
    return 행들


def 피해_집계(전투상태):
    """아군 참가자(캐릭터와 인형 - 인형은 누가 불렀든 인형 이름으로 따로)마다 적 진영에게 넣은 피해 합
    {이름: 피해}. 넘친 피해는 빼고 흡수된 피해는 센다. 아군끼리(혼란)나 감옥에 들어간 피해는 세지 않는다."""
    진영 = {p["이름"]: p["진영"] for p in 전투상태["참가자"]}
    집계 = {이름: 0 for 이름, 편 in 진영.items() if 편 == "아군"}
    for 귀속, 대상, 피해 in 피해_내역(전투상태):
        if 귀속 in 집계 and 진영.get(대상) == "적":
            집계[귀속] += 피해
    return 집계


