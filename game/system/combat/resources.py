# 체이서 (배틀메이지, 2026-10-26 사용자 결정)
# =====================================================
# 버프 "체이서 : 화/수/명/암" 인스턴스 하나가 체이서 하나다. 합쳐 최대 9개, 쓸 때는 버프 목록에서 먼저
# 생긴(앞에 있는) 것부터.

체이서_최대 = 9
_체이서_속성 = {common_names.속성_줄임말[s]: s for s in common_names.강화_속성}


def 체이서_목록(참가자):
    return [
        항목
        for 항목 in 참가자.get("버프") or []
        if 항목["이름"].startswith("체이서 : ")
    ]


def 체이서_얻기(전투상태, 참가자, 개수):
    """무작위 속성 체이서를 개수만큼 얻는다(최대 9개 - 넘치는 것은 버린다). 얻은 이름 목록."""
    얻음 = []
    for _ in range(max(0, int(개수))):
        if len(체이서_목록(참가자)) >= 체이서_최대:
            break
        이름 = f"체이서 : {rng.확률.choice(list(_체이서_속성))}"
        몬스터_버프_부여(전투상태, 참가자, 이름, None)
        얻음.append(이름)
    if 얻음:
        core.로그(
            전투상태,
            {
                "공격자": 참가자["이름"],
                "대상": [참가자["이름"]],
                "비고": f"{', '.join(얻음)}을(를) 얻었다.",
            },
            종류="비고",
        )
    return 얻음


def 체이서_소모(참가자, 개수=None):
    """먼저 생긴 체이서부터 개수만큼(None이면 전부) 지우고 그 속성 이름("화속성" 등) 목록을 돌려준다."""
    쓸것 = 체이서_목록(참가자)
    if 개수 is not None:
        쓸것 = 쓸것[:개수]
    for 항목 in 쓸것:
        참가자["버프"].remove(항목)
    return [_체이서_속성[항목["이름"][len("체이서 : ") :]] for 항목 in 쓸것]


