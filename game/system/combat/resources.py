# 설치소환수 (메카닉 랜드러너/카운트다운 - summon_00.py "설치소환")
# =====================================================
# 적 하나에 붙는 소환수. 전투상태["설치소환수"]에 하나씩 쌓이고, 정해진 라운드가 끝날 때(또는 로봇전폭이
# 바로) skill_run.설치소환수_폭발이 자폭시킨다. 반응(회심의 랜드러너)도 붙여야 해서 combat 쪽에 둔다.


def 설치소환수_설치(전투상태, 시전자, 이름, 대상, 차수=None):
    """시전자가 대상(적)에게 소환수 이름을 붙인다 - 정의의 "자폭라운드"만큼 뒤 라운드가 끝날 때 터진다.
    차수를 주면 자폭 피해식의 "차수"를 그 값으로 굴린다(회심의 랜드러너 - 1차수). 붙인 항목을 돌려준다."""
    정의 = summon_00.소환수목록[이름]
    항목 = {
        "이름": 이름,
        "시전자id": 시전자.get("id"),
        "대상id": 대상.get("id"),
        "폭발라운드": 전투상태.get("라운드", 1) + 정의.get("자폭라운드", 0),
    }
    if 차수 is not None:
        항목["차수"] = 차수
    전투상태.setdefault("설치소환수", []).append(항목)
    return 항목
