# 추가행동 (DnD 5판의 추가 공격, 2026-10-16 사용자 결정)
# =====================================================
# 턴 시작 때 참가자["추가공격_사용가능"]이 캐릭터 "추가공격"(레벨 6/11/16/21, 밀리·하이브리드)으로
# 채워진다(flow.행동자원_채우기). 진짜 일반행동으로 일반공격이나 일반공격취급 스킬을 쓰면 그만큼이
# 참가자["기타행동"]["추가행동"]으로 열리고(한 턴에 한 번), 같은 턴 안에서 일반공격/일반공격취급
# 스킬을 일반행동 대신 낼 수 있다. 쇼타임행동/보조행동으로 낸 것은 열지 않는다. 턴이 끝나면 사라진다.


def 추가행동_남은수(참가자):
    return (참가자.get("기타행동") or {}).get("추가행동", 0)


def 추가행동_열기(참가자, 보너스=0):
    """일반행동으로 일반공격(취급)을 했을 때 부른다. 추가공격이 없으면 칸을 만들지 않는다.
    보너스: 버프/특성 "추가공격"(stats.추가공격_보너스 - 니트로모터 #391) - 열 때 더한다."""
    수 = 참가자.get("추가공격_사용가능", 0)
    if 수 > 0:
        수 += 보너스
        참가자.setdefault("기타행동", {})["추가행동"] = 수
        참가자["추가공격_사용가능"] = 0  # 한 턴에 한 번만 열린다


def 추가행동_소모(참가자):
    참가자["기타행동"]["추가행동"] -= 1


def 원펀맨_합치기(참가자):
    """원펀맨(2026-10-19 사용자 결정): 남은 일반행동을 모두 쓰고, 일반행동마다 캐릭터 "추가공격"이
    붙은 것으로 쳐서 배수 = 일반행동 수 x (1 + 추가공격)을 돌려준다. 이 턴에 추가공격은 더 없다."""
    일반행동 = 참가자["행동자원"].get("일반행동", 0)
    배수 = 일반행동 * (1 + 참가자["원본"].get("추가공격", 0))
    참가자["행동자원"]["일반행동"] = 0
    참가자["추가공격_사용가능"] = 0
    if 추가행동_남은수(참가자):
        참가자["기타행동"]["추가행동"] = 0
    return max(1, 배수)


