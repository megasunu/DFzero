def 효과정의_조회(이름):
    """이름을 기술효과목록 → 버프목록 → 디버프목록 순으로 찾아
    (정의, 출처) 튜플을 반환한다. 출처는 "기술효과"/"버프"/"디버프" 중
    하나. 없으면 (None, None)."""
    if 이름 in skill_effects.기술효과목록:
        return skill_effects.기술효과목록[이름], "기술효과"
    if 이름 in buff.버프목록:
        return buff.버프목록[이름], "버프"
    if 이름 in debuff.디버프목록:
        return debuff.디버프목록[이름], "디버프"
    return None, None


def 클래스자원_채우기(전투상태, 참가자):
    """클래스 공유 자원(skill_effects.클래스자원목록 - 탄약/수류탄)을 최대값으로 채운다. "사용태그" 타입의
    스킬을 가진 아군만(장전 -> 탄약, 류탄 -> 수류탄, #393). 전투를 시작할 때 부르고, 전투가 끝나면
    core.전투종료시_보유자원_초기화가 이 시작값으로 되돌린다 - 그래서 전투마다 가득 찬 채로 시작한다."""
    스킬정의 = 전투상태.get("스킬정의") or {}
    태그들 = {
        태그
        for 이름 in 참가자["원본"].get("보유스킬") or []
        for 태그 in (스킬정의.get(이름) or {}).get("타입") or []
    }
    보유자원 = 참가자.setdefault("보유자원", {})
    for 이름, 정의 in skill_effects.클래스자원목록.items():
        if 정의.get("사용태그") in 태그들:
            보유자원[이름] = formula.올림(
                formula.수식_평가(정의["최대값"], {"차수": core.차수(참가자)})
            )
    참가자["보유자원_전투시작값"] = dict(보유자원)


def 자원_보유량(전투상태, 참가자, 이름):
    정의, 출처 = 효과정의_조회(이름)
    if 출처 == "기술효과":
        for 항목 in 참가자["버프"]:
            if 항목["이름"] == 이름:
                return 항목.get("중첩", 1)
        return 0
    return 참가자.get("보유자원", {}).get(이름, 0)


def 자원_소모(전투상태, 참가자, 이름, 개수=1):
    """자원이 부족해도 에러를 내지 않고 (성공여부, 실제소모량)을 반환한다
    - 소모 가능 여부 자체는 skill_system.사용_가능여부()가 미리 검사한다."""
    정의, 출처 = 효과정의_조회(이름)
    if 출처 == "기술효과":
        for 항목 in list(참가자["버프"]):
            if 항목["이름"] == 이름:
                보유 = 항목.get("중첩", 1)
                if 보유 <= 개수:
                    참가자["버프"].remove(항목)
                else:
                    항목["중첩"] = 보유 - 개수
                return True, min(보유, 개수)
        return False, 0

    보유자원 = 참가자.setdefault("보유자원", {})
    보유 = 보유자원.get(이름, 0)
    if 보유 <= 0:
        return False, 0
    실제소모 = min(보유, 개수)
    보유자원[이름] = 보유 - 실제소모
    return True, 실제소모


def 턴종료_효과_제거(참가자):
    """자기 턴이 끝날 때 "버프종료": "턴종료"인 효과(원귀 #332)를 지운다(flow.턴_종료_처리)."""
    참가자["버프"] = [
        항목
        for 항목 in 참가자.get("버프", [])
        if (효과정의_조회(항목["이름"])[0] or {}).get("버프종료") != "턴종료"
    ]


