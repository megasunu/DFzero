def 명중확률(보정합, AC, 치명타범위=20, 펌블범위=1):
    """d20 + 보정합 >= AC일 확률. 펌블범위 이하는 빗나가고 치명타범위 이상은 맞는다(damage._눈_판정과 같은 순서)."""
    맞음 = 0
    for 눈 in range(1, 21):
        if 눈 <= 펌블범위:
            continue
        if 눈 >= 치명타범위 or 눈 + 보정합 >= AC:
            맞음 += 1
    return 맞음 / 20


def _방어_후(전투상태, 대상, 피해):
    return max(
        0,
        damage.최종피해_계산(
            피해, stats.유효_방어력(전투상태, 대상), stats.유효_보호률(전투상태, 대상)
        ),
    )


def 일반공격_기대피해(전투상태, 공격자, 대상):
    """아군 일반공격 1회의 기대 피해 = 명중확률 x 방어 뒤 평균 피해(무기 주사위 평균 + 보정 + 데미지보너스).
    치명타의 추가 주사위, 속성 배율, 장전 탄은 넣지 않는다. 무기가 없거나 계산할 수 없으면 0."""
    if not (공격자.get("장비데이터") or {}).get("무기"):
        return 0
    try:
        컨텍스트 = stats.기본_컨텍스트(전투상태, 공격자, 무기공격력필요=True)
        평균 = formula.수식_평가("보정공격력", 컨텍스트, 평균=True)
    except (ValueError, ZeroDivisionError, SyntaxError, TypeError):
        return 0
    평균 += (
        stats.장비_데미지보너스(공격자, 대상, 전투상태)
        + stats.버프디버프_수치(전투상태, 공격자, "데미지보너스")
        + traits.칭호_수치(전투상태, 공격자, "데미지보너스")
    )
    보정합 = damage.명중_보정합(전투상태, 공격자, 대상, "보정명중률")
    확률 = 명중확률(
        보정합,
        stats.최종AC(전투상태, 대상),
        damage.유효_치명타범위(전투상태, 공격자),
        damage.유효_펌블범위(전투상태, 공격자, 대상),
    )
    return 확률 * _방어_후(전투상태, 대상, 평균)


def 몬스터_기대피해(전투상태, 몬스터, 대상):
    """몬스터가 대상을 한 번 공격할 때의 기대 피해 - "공격패턴"들의 평균(명중확률 x 방어 뒤 평균 피해 x 공격횟수)."""
    값들 = []
    for 패턴 in (몬스터["원본"].get("패턴") or {}).values():
        if not isinstance(패턴, dict) or 패턴.get("타입") != "공격패턴":
            continue
        try:
            평균 = formula.수식_평가(
                str(패턴.get("데미지", "0")),
                stats.몬스터_패턴_컨텍스트(전투상태, 몬스터),
                평균=True,
            )
        except (ValueError, ZeroDivisionError, SyntaxError, TypeError):
            continue
        평균 += 패턴.get("데미지보너스") or 0
        횟수 = 패턴.get("공격횟수", 1)
        횟수 = 횟수 if isinstance(횟수, int) else 1
        보정합 = damage.명중_보정합(
            전투상태,
            몬스터,
            대상,
            패턴.get("명중률", "근력판정"),
            패턴.get("명중보너스") or 0,
        )
        확률 = 명중확률(
            보정합,
            stats.최종AC(전투상태, 대상),
            damage.유효_치명타범위(전투상태, 몬스터),
            damage.유효_펌블범위(전투상태, 몬스터, 대상),
        )
        값들.append(확률 * _방어_후(전투상태, 대상, 평균) * 횟수)
    return sum(값들) / len(값들) if 값들 else 0
