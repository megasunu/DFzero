def 받은피해_집계(전투상태):
    """아군 참가자(캐릭터와 인형)마다 받은 피해 {이름: 피해} - 넘친 피해는 빼고 흡수된 피해는 센다(core.피해_내역).
    누가 줬는지는 가리지 않는다(적, 지속 피해, 혼란한 아군)."""
    진영 = {p["이름"]: p["진영"] for p in 전투상태["참가자"]}
    집계 = {이름: 0 for 이름, 편 in 진영.items() if 편 == "아군"}
    for _, 대상, 피해 in core.피해_내역(전투상태):
        if 대상 in 집계:
            집계[대상] += 피해
    return 집계


