def 지표_계산(본, 끈):
    """본 = {"딜": {이름: 판당 피해}, "받음": {이름: 판당 받은 피해}} - 아무도 끄지 않은 전투의 평균.
    끈 = {버퍼 이름: 같은 모양} - 그 버퍼를 끈 전투의 평균(같은 시드들).

    B의 딜기여 = 다른 아군 A마다 (본 딜 A - B를 끈 딜 A)의 합. A의 딜지분 = (본 딜 A - 남들이 A에게 준 기여) ÷ 파티 딜.
    B의 탱기여 = A마다 (B를 끈 받은 피해 A - 본 받은 피해 A)의 합 - B 덕분에 덜 받은 피해. A의 탱지분 = (본 받은 피해 A +
    남들이 막아 준 피해) ÷ 그 합 - 버프 없이 받았을 피해의 몫이다(2026-11-09 사용자 결정). 자기를 끈 전투에서
    자기 값이 바뀐 것은 세지 않는다. 결과는 백분율 {이름: {"딜지분", "딜기여도", "탱지분", "탱기여도"}}."""
    딜, 받음 = 본["딜"], 본["받음"]
    이름들 = list(dict.fromkeys(list(딜) + list(받음)))
    딜기여 = {이름: 0.0 for 이름 in 이름들}
    탱기여 = {이름: 0.0 for 이름 in 이름들}
    딜지분 = {이름: float(딜.get(이름, 0)) for 이름 in 이름들}
    탱지분 = {이름: float(받음.get(이름, 0)) for 이름 in 이름들}
    for 버퍼, 결과 in 끈.items():
        for 이름 in 이름들:
            if 이름 == 버퍼:
                continue
            d = 딜.get(이름, 0) - 결과["딜"].get(이름, 0)
            t = 결과["받음"].get(이름, 0) - 받음.get(이름, 0)
            딜기여[버퍼] += d
            딜지분[이름] -= d
            탱기여[버퍼] += t
            탱지분[이름] += t
    딜합 = sum(딜.values()) or 1
    탱합 = sum(탱지분.values()) or 1
    return {
        이름: {
            "딜지분": 100 * 딜지분[이름] / 딜합,
            "딜기여도": 100 * 딜기여[이름] / 딜합,
            "탱지분": 100 * 탱지분[이름] / 탱합,
            "탱기여도": 100 * 탱기여[이름] / 탱합,
        }
        for 이름 in 이름들
    }


