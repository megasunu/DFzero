def 일반공격_실행(전투상태, 공격자, 대상, 배수=1):
    """장착 무기 기반 일반공격 1회(아군 전용) - 몬스터는 monster_ai.py로
    고른 "패턴"을 몬스터_턴_실행()에서 처리한다.

    "장전 : OO"(은탄 등) 버프가 있으면 명중 여부와 무관하게 소모하고, 명중하면 그 추가피해를 같은
    치명타 굴림으로 더한다(장전_소모/장전_추가피해/장전_명중후).

    배수(원펀맨 - 여러 공격을 한 번에 합친 수): 명중 굴림은 한 번, 명중 보정 전체 x 배수,
    보정공격력을 배수만큼 굴려 더하고(치명타면 굴림마다 주사위가 는다) 데미지보너스 x 배수,
    빗나가면 집요함 x 배수. 추가피해(장전/일반공격 추가피해/마봉)와 상태이상은 한 번이다.

    버프 "일반공격대체"(뇌명)가 있으면 그 원소의 "명중률"로 굴리고 무기 주사위 대신 "데미지"를 "속성"으로 준다
    (무기가 아니라서 무기 명중시효과는 없다. 데미지보너스·일반공격 추가피해·마봉은 그대로)."""
    무기데이터 = 공격자["장비데이터"].get("무기")
    if 무기데이터 is None:
        raise ValueError(f"'{공격자['이름']}'은(는) 무기를 장착하지 않았다.")
    동료 = status.혼란_반전_굴림(전투상태, 공격자)  # 혼란 - 자기 편 동료를 친다
    if 동료:
        대상 = rng.대상.choice(동료)
    대상 = status.감옥_대상(전투상태, 공격자, 대상)  # 갇힌 사람의 공격은 감옥이 받는다
    damage.채널링_행동해제(전투상태, 공격자)  # 넨가드 - 다음 턴에 행동하면 풀린다

    장전 = 장전_소모(전투상태, 공격자)
    # 장전 탄을 쓴 공격은 "장전" 태그 - 강화탄의 치명타범위·주사위(#391). 공격이 끝나면 뗀다.
    # "일반공격" 태그 - 빗자루 다루기의 명중(damage._명중_보정합)
    stats.공격태그_달기(공격자, ("일반공격",) + (("장전",) if 장전 else ()))
    대체 = stats.일반공격_대체(전투상태, 공격자)
    명중률종류 = 대체["명중률"] if 대체 else "보정명중률"
    속성 = (
        대체["속성"]
        if 대체
        else 일반공격_속성(전투상태, 공격자, 대상, (장전 or {}).get("속성변환"))
    )
    공격전상태 = reactions.상태이상_이름목록(전투상태, 대상)

    판정 = damage.명중_판정(전투상태, 공격자, 대상, 명중률종류, 명중배수=배수)
    결과 = {"공격자": 공격자["이름"], "대상": 대상["이름"], "판정": 판정, "피해": 0}
    if 배수 > 1:  # 원펀맨 - 합친 공격 수(문장은 그대로)
        결과["배수"] = 배수
    공격타입 = (
        대체.get("공격타입")
        if 대체
        else stats.타격_공격타입(공격자, "보정공격력", None)
    )
    damage.공격연출_기록(전투상태, 대상, 판정, 속성, 공격타입)

    if not 판정["성공"]:
        damage.집요함_발동(전투상태, 공격자, 대상, 속성, 판정, 배수=배수)
    if 판정["성공"]:
        보정치 = stats.평타_능력치_보정치(전투상태, 공격자)
        컨텍스트 = {
            "보정치": 보정치,
            "무기공격력": stats.유효_무기공격력(전투상태, 공격자, 무기데이터),
            **stats.무기_보정치_효과(전투상태, 공격자),
        }
        피해 = sum(
            _대체_피해_굴림(전투상태, 공격자, 대체, 판정)
            if 대체
            else stats.피해_굴림(
                전투상태, 공격자, "보정공격력", 컨텍스트, 치명타=판정["치명타"]
            )
            for _ in range(배수)
        )
        굴림 = 피해
        앞항목 = [
            ("일반공격 추가피해", stats.일반공격_추가피해(전투상태, 공격자, 컨텍스트)),
            ("마봉 추가피해", stats.마봉_추가피해(전투상태, 공격자, 대상)),
        ]
        피해 += sum(값 for _, 값 in 앞항목)

        추가피해목록 = 장전_추가피해(전투상태, 공격자, 장전, 판정["치명타"])
        # 무기만이 아니라 장비 전 부위+활성 세트의 데미지보너스.
        장비 = stats.장비_데미지보너스(공격자, 대상, 전투상태)
        피해 += 배수 * (
            장비
            + stats.버프디버프_수치(전투상태, 공격자, "데미지보너스")
            + traits.특성_수치(
                전투상태,
                공격자,
                "데미지보너스",
                명중률종류=명중률종류,
                대상=대상,
                속성=속성,
            )
            + traits.칭호_수치(전투상태, 공격자, "데미지보너스")
        )

        결과["피해"] = damage.피해_적용(
            전투상태,
            대상,
            피해,
            속성=속성,
            추가피해목록=추가피해목록,
            공격측=공격자,
            최종피해배율=stats.마봉_최종피해배율(공격자),
            공격타입=공격타입,
        )
        내역 = damage.피해내역(
            전투상태,
            공격자,
            (
                대체["데미지"]
                if 대체
                else f"{컨텍스트['무기공격력']}{컨텍스트['보정치']:+}"
            )
            + (f" x{배수}" if 배수 > 1 else ""),
            굴림,
            피해,
            결과["피해"],
            앞항목=앞항목,
            장비=장비,
            대상=대상,
            명중률종류=명중률종류,
            속성=속성,
            배수=배수,
        )
        if 내역:
            결과["피해내역"] = 내역
        damage.피격_처리(전투상태, 공격자, 대상, 판정, 속성=속성)
        if not 대체:
            damage.무기_명중시효과(전투상태, 공격자, 대상, 판정, "보정공격력")
        damage.마봉_명중시효과(전투상태, 공격자, 대상, 판정)
        장전_명중후(전투상태, 공격자, 대상, 장전, 추가피해목록)

    core.로그(전투상태, 결과, 종류="일반공격")
    추가타격들 = 타격추가피해_발동(전투상태, 공격자, 대상)
    if 추가타격들:
        core.로그(
            전투상태,
            {
                "공격자": 공격자["이름"],
                "스킬": 추가타격들[0]["추가타격"],
                "타격": 추가타격들,
                "총피해": sum(t["피해"] for t in 추가타격들),
            },
            종류="타격",
        )
    reactions.공격후_반응(전투상태, 공격자, 대상, 공격전상태)
    stats.공격태그_달기(공격자, None)
    return 결과


def _대체_피해_굴림(전투상태, 공격자, 대체, 판정):
    """버프 "일반공격대체"(뇌명)의 "데미지" 한 번 - 치명타면 치명타 주사위만큼 더 굴린다."""
    치명 = stats.치명타_주사위수(전투상태, 공격자) if 판정["치명타"] else 0
    return formula.수식_평가(
        대체["데미지"], stats.기본_컨텍스트(전투상태, 공격자), 치명타=치명
    )


def 일반공격_속성(전투상태, 공격자, 대상, 장전속성변환=None):
    """일반공격의 피해 속성 - 무기 속성(장전 속성변환이 우선)에 버프 "일반공격속성추가"(잔영의 케이가 - 암속성)와
    "무기속성추가"(카이 - 명속성)를 더해 가장 아픈 속성 하나(damage.주속성)."""
    속성 = stats.공격_속성(공격자, "보정공격력", None, 장전속성변환, 전투상태=전투상태)
    추가 = (
        [
            원소["추가속성"]
            for 변동대상 in (
                "일반공격속성추가",
                "무기속성추가",
            )  # 카이(#280)는 무기 공격 전부
            for _, 원소 in stats.버프_효과원소목록(전투상태, 공격자, 변동대상)
        ]
        + [  # 특성 퍼페티어(2026-10-26)
            원소["추가속성"]
            for 원소 in traits.캐릭터특성_무기효과(전투상태, 공격자, "무기속성추가")
        ]
        + stats.부여_무기속성(공격자)
    )  # 속성 플라스크(#506)
    if not 추가:
        return 속성
    속성들 = (
        속성 if isinstance(속성, list) else [속성]
    )  # 란마 형태 속성이면 이미 리스트
    return damage.주속성(전투상태, 공격자, 대상, [*속성들, *추가])


def 타격추가피해_발동(전투상태, 공격자, 대상):
    """버프 "타격추가피해"(잔영의 케이가) - 일반공격이나 무기 주사위 스킬의 타격 하나마다 원소의 "명중률"로
    따로 굴려, 맞으면 "데미지"를 "피해속성"으로 준다. 본 타격이 빗나가도 굴린다(2026-10-20 사용자 결정).
    장비/버프의 데미지보너스가 붙는다(#247, 특성/칭호는 안 붙음). 타격 모양 결과 리스트(각각 "추가타격": 버프 이름)."""
    결과들 = []
    for 이름, 원소 in stats.버프_효과원소목록(전투상태, 공격자, "타격추가피해"):
        if not 대상["생존"]:
            break
        판정 = damage.명중_판정(전투상태, 공격자, 대상, 원소.get("명중률", "자동"))
        속성 = 원소.get("피해속성")
        결과 = {
            "공격자": 공격자["이름"],
            "대상": 대상["이름"],
            "판정": 판정,
            "피해": 0,
            "효과로그": [],
            "추가타격": 이름,
        }
        damage.공격연출_기록(전투상태, 대상, 판정, 속성, 원소.get("공격타입"))
        if 판정["성공"]:
            치명 = (
                stats.치명타_주사위수(전투상태, 공격자, 대상) if 판정["치명타"] else 0
            )
            피해 = formula.수식_평가(
                원소["데미지"], stats.기본_컨텍스트(전투상태, 공격자), 치명타=치명
            ) + stats.장비버프_데미지보너스(전투상태, 공격자, 대상)
            결과["피해"] = damage.피해_적용(
                전투상태,
                대상,
                max(0, 피해),
                속성=속성,
                공격측=공격자,
                공격타입=원소.get("공격타입"),
            )
            damage.피격_처리(전투상태, 공격자, 대상, 판정, 속성=속성)
        결과들.append(결과)
    return 결과들


def 라운드종료_지속공격(전투상태):
    """발동시점이 "라운드종료"인 지속공격(장판스킬 - 귀신 : 사야 #350)을 라운드가 끝날 때 친다. 장판스킬
    지속공격은 명중 굴림 없이 걸린 대상이 "내성"으로 굴려 실패하면 "데미지"와 "내성실패효과", 성공하면
    "내성성공시"대로 절반을 받는다(_턴시작_내성공격_1회). 건 사람이 쓰러졌으면 치지 않는다. 친 뒤(치지
    않았어도) 지속턴을 1 줄여 0이면 지운다 - 라운드마다 한 번이라 3턴이면 세 라운드를 친다.
    한 번이라도 쳤으면 True."""
    살아있음 = {p["id"]: p for p in 전투상태["참가자"] if p["생존"]}
    쳤음 = False
    추가 = {}  # 대성공 장판(마도학자) - (시전자, 장판)마다 라운드에 한 번
    for 대상 in 전투상태["참가자"]:
        끝남 = []
        for 항목 in list(대상.get("상태이상") or []):
            if 항목.get("종류") != "지속공격" or 항목.get("발동시점") != "라운드종료":
                continue
            시전자 = 살아있음.get(항목.get("시전자id"))
            if 시전자 is not None and 대상["생존"]:
                상세 = 항목.get("출처스킬") or {}
                원소 = {
                    "데미지": 상세.get("데미지", "0"),
                    "내성": 상세["내성"],
                    "난이도": 상세.get("난이도", "10"),
                    "내성성공시": 상세.get("내성성공시"),
                    "피해속성": 상세.get("속성"),
                    "공격타입": 상세.get("공격타입"),
                    "효과": 상세.get("내성실패효과"),
                }
                _턴시작_내성공격_1회(전투상태, 시전자, 대상, 항목["이름"], 원소)
                쳤음 = True
                if 상세.get("라운드추가타격"):
                    추가.setdefault((시전자["id"], 항목["이름"]), (시전자, 상세))
            항목["지속턴"] = (항목.get("지속턴") or 1) - 1
            if 항목["지속턴"] <= 0:
                끝남.append(항목)
        if 끝남:  # 내성 실패로 방금 건 빙결은 그대로 두고 끝난 항목만 뺀다
            대상["상태이상"] = [
                i for i in 대상["상태이상"] if not any(i is x for x in 끝남)
            ]
    for (_, 이름), (시전자, 상세) in 추가.items():
        _장판_추가타격(전투상태, 시전자, 이름, 상세)
    return 쳤음


def _장판_추가타격(전투상태, 시전자, 이름, 상세):
    """장판 "라운드추가타격"({"데미지"}) - 시전자의 살아 있는 적 1체(무작위)에게 명중 굴림 없이 그 속성으로 준다."""
    적들 = [
        p
        for p in 전투상태["참가자"]
        if p["생존"] and p["진영"] not in (시전자["진영"], "감옥")
    ]
    if not 적들:
        return
    대상 = rng.대상.choice(적들)
    피해 = formula.수식_평가(
        str(상세["라운드추가타격"]["데미지"]), stats.기본_컨텍스트(전투상태, 시전자)
    )
    최종 = damage.피해_적용(
        전투상태, 대상, 피해, 속성=상세.get("속성"), 공격자=시전자, 공격측=시전자
    )
    core.로그(
        전투상태,
        {
            "공격자": 시전자["이름"],
            "대상": 대상["이름"],
            "피해": 최종,
            "비고": f"'{이름}' 대성공 추가 피해",
        },
        종류="비고",
    )


def 턴시작_오라공격(전투상태, 대상):
    """반대 진영 참가자가 건 상태변화의 "적턴시작공격"(아수라 살의의 파동 #325, #462) - 대상의 턴이 시작될 때,
    살아 있는 반대 진영 참가자 중 그 상태를 자기가 건(인스턴스 "시전자id"가 자기) 사람마다 한 번 친다.
    아군 전체에 걸린 같은 상태의 다른 사람 인스턴스는 치지 않는다 - 건 사람의 상태가 없으면 피해도 없다."""
    정의모음 = 전투상태.get("상태이상정의") or {}
    for 시전자 in list(전투상태["참가자"]):
        if 시전자.get("진영") == 대상.get("진영") or not 시전자.get("생존"):
            continue
        for 항목 in list(시전자.get("상태이상") or []):
            if 항목.get("시전자id") != 시전자["id"]:
                continue
            원소 = (
                (정의모음.get(항목["이름"]) or {}).get("효과", {}).get("적턴시작공격")
            )
            if 원소 and 대상["생존"]:
                _턴시작_내성공격_1회(전투상태, 시전자, 대상, 항목["이름"], 원소)


def _턴시작_내성공격_1회(전투상태, 시전자, 대상, 이름, 원소):
    """명중 굴림 없이 대상이 "내성"으로 굴려(DC "난이도", 건 사람 기준 식), 실패하면 "데미지"를, 성공하면
    "내성성공시": "데미지절반"일 때 절반(내림)을 "피해속성"으로 준다. 실패하면 "효과"(상태이상)도 건다.
    기록 모양은 몬스터 포효와 같다."""
    컨텍스트 = stats.기본_컨텍스트(전투상태, 시전자)
    난이도 = formula.수식_평가(str(원소.get("난이도", "10")), 컨텍스트)
    성공, 값, 보정치 = stats.대상_내성굴림(전투상태, 대상, 원소["내성"], 난이도)
    절반 = 원소.get("내성성공시") == "데미지절반"
    속성 = 원소.get("피해속성")
    damage.공격연출_기록(
        전투상태, 대상, {"성공": not (성공 and not 절반)}, 속성, 원소.get("공격타입")
    )
    피해 = 0
    if not 성공 or 절반:
        # 소수는 올린 뒤(게임 규칙) 절반을 내린다 - ÷가 든 식(사야)
        피해 = max(0, formula.올림(formula.수식_평가(원소["데미지"], 컨텍스트)))
        if 성공:
            피해 //= 2
        피해 = damage.피해_적용(
            전투상태, 대상, 피해, 속성=속성, 공격자=시전자, 공격측=시전자
        )
    if not 성공 and 대상["생존"] and 원소.get("효과"):
        traits.상태이상_효과_적용(전투상태, 시전자, 대상, 원소["효과"], f"'{이름}'")
    타격 = {"대상": 대상["이름"], "내성": "성공" if 성공 else "실패", "내성값": 값}
    if stats.상세로그(전투상태):
        타격 |= {"내성스탯": 원소["내성"], "내성보정": 보정치}
    core.로그(
        전투상태,
        {
            "공격자": 시전자["이름"],
            "스킬": 이름,
            "난이도": 난이도,
            "DC식": 원소.get("난이도"),
            "대상": [대상["이름"]],
            "타격": [타격 | {"피해": 피해}],
        },
        종류="타격",
    )


def 장전_소모(전투상태, 참가자, 종류="일반공격"):
    """소모형 버프("소모조건"이 있는 자원 - 장전 : OO(은탄 등), 마도학자 파우더) 중 이 공격의 종류("일반공격" |
    "사격" | "일반공격취급")가 "소모조건"에 있는 것이 있으면 1개 소모하고 그 버프의 "효과"(+ "이름")를 돌려준다 -
    없으면 None. 타격마다 명중 여부와 무관하게 쓴다(2026-10-23 사용자 결정 #390).
    버프 "스택유지"(오버차지 #391)면 줄이지 않는다.
    일반공격_실행/skill_attack.공격_1회가 함께 쓴다."""
    for 항목 in list(참가자["버프"]):
        효과 = (resources.효과정의_조회(항목["이름"])[0] or {}).get("효과")
        if isinstance(효과, dict) and 종류 in (효과.get("소모조건") or ()):
            if not stats.버프_효과원소목록(전투상태, 참가자, "스택유지"):  # 오버차지
                resources.자원_소모(전투상태, 참가자, 항목["이름"], 1)
            정의, _ = resources.효과정의_조회(항목["이름"])
            return {**(정의 or {}).get("효과", {}), "이름": 항목["이름"]}
    return None


def 장전_추가피해(전투상태, 참가자, 장전, 치명타):
    """명중한 공격의 장전 추가피해 - [(값, 속성, 방어무시)] 한 항목(피해_적용의 추가피해목록). 공격과 같은
    치명타 굴림을 쓴다(치명타면 치명타 주사위만큼 더 굴린다). 장전이 없거나 추가피해가 없으면 []."""
    if not 장전 or not 장전.get("추가피해"):
        return []
    치명 = stats.치명타_주사위수(전투상태, 참가자) if 치명타 else 0
    값 = formula.수식_평가(
        장전["추가피해"], stats.기본_컨텍스트(전투상태, 참가자), 치명타=치명
    )
    return [(값, 장전.get("추가피해속성") or "무속성", bool(장전.get("방어무시")))]


def 장전_명중후(전투상태, 공격자, 대상, 장전, 추가피해목록):
    """명중한 공격의 장전 뒷처리 - "범위"(작열탄)면 주대상 양옆에도 같은 추가피해를 넣고, "명중시상태이상"
    (냉동탄 빙결/작열탄 화상)은 맞은 대상마다 내성굴림으로 건다. 범위의 양옆은 명중 굴림 없이 주대상의
    명중을 따른다."""
    if not 장전:
        return
    맞은 = [대상]
    if 장전.get("범위") and 추가피해목록:
        for 이웃 in damage.양옆_이웃(전투상태, 대상):
            피해 = damage.피해_적용(
                전투상태,
                이웃,
                0,
                추가피해목록=추가피해목록,
                공격측=공격자,
            )
            core.로그(
                전투상태,
                {
                    "공격자": 공격자["이름"],
                    "대상": 이웃["이름"],
                    "비고": f"'{장전['이름']}' 범위 피해 {피해}",
                },
                종류="비고",
            )
            맞은.append(이웃)
    효과 = 장전.get("명중시상태이상")
    if not 효과:
        return
    for p in 맞은:
        if p.get("생존", True):
            traits.상태이상_효과_적용(
                전투상태, 공격자, p, {"종류": "상태이상", **효과}, f"'{장전['이름']}'"
            )
