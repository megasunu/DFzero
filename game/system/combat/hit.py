def 유효_치명타범위(전투상태, 참가자):
    """치명타가 나는 최소 d20 눈. 기본 20에서 버프/특성의 "치명타범위"
    (치명타확률증가/급소지정 등, 양수 = 범위 확장)와 지금 하는 스킬 공격의 "치명타범위"만큼 내려간다."""
    기본 = 참가자.get("치명타범위", 20)
    확장 = (
        stats.버프디버프_수치(전투상태, 참가자, "치명타범위")
        + traits.특성_수치(전투상태, 참가자, "치명타범위")
        + stats.마봉_수치(참가자, "치명타범위")
        + stats.공격태그_조건_수치(전투상태, 참가자, "치명타범위")
        + 참가자.get(
            "_공격치명타범위", 0
        )  # 지금 하는 스킬 공격의 "치명타범위"(할로우 백)
    )
    return max(2, 기본 - 확장)


def 유효_펌블범위(전투상태, 공격자, 대상=None):
    """자동실패(펌블)가 나는 최대 d20 눈. 기본 1(참가자 "펌블범위")에 공격자의
    버프/디버프/특성 "펌블범위"(펌블확률증가 +1, 펌블확률감소 -1)와, 대상이 있으면
    대상의 "피격펌블범위"(피격펌블증가 +1, 피격펌블감소 -1 - 나를 공격하는 쪽의
    펌블 확률)를 더한다. 0이면 자연 1도 펌블이 아니다(0 아래로는 안 내려감).
    "치명타펌블연동" 특성(얀데레)이 있으면 치명타범위가 20에서 낮아진 만큼 더한다
    (유효_치명타범위를 그때그때 본다 - 버프/특성/마봉 모두)."""
    기본 = 공격자.get("펌블범위", 1)
    증감 = stats.버프디버프_수치(전투상태, 공격자, "펌블범위") + traits.특성_수치(
        전투상태, 공격자, "펌블범위"
    )
    if traits.특성_수치(전투상태, 공격자, "치명타펌블연동") > 0:
        증감 += 20 - 유효_치명타범위(전투상태, 공격자)
    if 대상 is not None:
        증감 += stats.버프디버프_수치(
            전투상태, 대상, "피격펌블범위"
        ) + traits.특성_수치(전투상태, 대상, "피격펌블범위")
    return max(0, formula.올림(기본 + 증감))


def 명중_판정(
    전투상태,
    공격자,
    대상,
    명중률종류,
    명중보너스=0,
    장비보너스=True,
    명중배수=1,
    명중이점=False,
    AC추가=0,
    명중불리점=False,
):
    """명중_판정_계산()으로 판정한 뒤, 아군이 적의 공격을 받는 경우
    캐릭터 반응스킬(회피형 - 크라우치 등, 회피성공시 반격 - 백스텝커터/
    리벤저)을 적용한다(피격판정_반응 참고). 장비보너스=False면 장비 명중률보너스를
    더하지 않는다(투척 아이템 - 소모품은 장비 보너스를 받지 않는다). 명중배수는 명중 보정
    전체에 곱한다(원펀맨 - 굴림은 한 번). 명중이점/명중불리점은 스킬의 "명중이점"(이혼일섬)/"명중불리점"(난사).
    AC추가는 이 판정에서만 대상 AC에 더한다(라키우스 감옥 - 속도보너스)."""
    판정 = 명중_판정_계산(
        전투상태,
        공격자,
        대상,
        명중률종류,
        명중보너스,
        장비보너스=장비보너스,
        명중배수=명중배수,
        명중이점=명중이점,
        AC추가=AC추가,
        명중불리점=명중불리점,
    )
    if 대상.get("진영") == "아군" and 공격자.get("진영") != "아군":
        판정 = reactions.가드_반응(전투상태, 공격자, 대상, 판정)
        판정 = reactions.피격판정_반응(전투상태, 공격자, 대상, 판정, 명중률종류)
    if not 판정.get("성공") and 공격자.get("진영") != 대상.get("진영"):
        분신_회피(전투상태, 대상)  # 분신 - 피할 때마다 1개
    return 판정


def 명중_판정_계산(
    전투상태,
    공격자,
    대상,
    명중률종류,
    명중보너스=0,
    장비보너스=True,
    명중배수=1,
    명중이점=False,
    AC추가=0,
    명중불리점=False,
):
    """명중률종류(job_skill_format.py 값, 또는 몬스터 패턴의 "OO판정")에
    따라 판정한다. 반환값: {"성공", "자연눈", "치명타", "자동실패"}.

    "대상"이 "피격시강제치명타" 상태면 명중률종류와 상관없이 항상
    명중+치명타로 처리한다. "대상"의 "회피불리점"은 공격자에게 이점을,
    "공격자"의 "명중불리점"은 공격자 본인에게 불리를 준다. 특성의 "명중이점"
    (공격자)은 이점을, "회피이점"(대상)은 공격자에게 불리를 준다(심안). 버프의 "명중이점"(공격자)과
    "회피불리점"(대상)도 공격자에게 이점을 준다(폭주)."""
    control.홀딩_정리(전투상태)  # 끊긴 홀딩의 이점이 남지 않게
    강제치명타 = status.상태이상_플래그(전투상태, 대상, "피격시강제치명타")

    if 명중률종류 == "자동":
        return 극점_판정(
            전투상태,
            공격자,
            {"성공": True, "자연눈": None, "치명타": 강제치명타, "자동실패": False},
        )
    if 명중률종류 == "주사위20":
        return _주사위20_판정(전투상태, 공격자, 대상)

    # 이점·불리점은 출처마다 하나씩 세어 많은 쪽 하나만 적용한다(같으면 없음)
    이점수 = sum(
        (
            status.상태이상_플래그(전투상태, 대상, "회피불리점"),
            status.특성_플래그(전투상태, 대상, "회피불리점"),  # 라키우스 분신
            status.특성_플래그(전투상태, 공격자, "명중이점"),
            # 오라헌터 - 오라(장착 무기의 "오라")를 낸 대상을 칠 때
            status.특성_플래그(전투상태, 공격자, "오라대상명중이점")
            and bool(stats.낸_오라_수(대상)),
            # 버프 "명중이점"(공격자)/"회피불리점"(대상) - 폭주
            bool(stats.버프_효과원소목록(전투상태, 공격자, "명중이점")),
            bool(stats.버프_효과원소목록(전투상태, 대상, "회피불리점")),
            명중이점,  # 스킬의 "명중이점"(이혼일섬)
        )
    )
    불리수 = sum(
        (
            status.상태이상_플래그(전투상태, 공격자, "명중불리점"),
            status.특성_플래그(전투상태, 대상, "회피이점"),
            # 암전 - 암전이 없는 대상을 공격할 때
            any(불리 for _, _, 불리 in status.대상조건_명중(전투상태, 공격자, 대상)),
            명중불리점,  # 스킬의 "명중불리점"(난사)
        )
    )
    이점, 불리 = dice_utils.이점_합산(이점수, 불리수)
    눈 = dice_utils.d20_굴림(이점=이점, 불리=불리)
    치명타범위 = 유효_치명타범위(전투상태, 공격자)
    펌블범위 = 유효_펌블범위(전투상태, 공격자, 대상)
    # 최종 명중값과 대상 AC는 치명타/대실패로 정해지는 판정에도 담는다(전투 로그가 "값 vs AC"로 보여 준다)
    보정합 = _명중_보정합(전투상태, 공격자, 대상, 명중률종류, 명중보너스, 장비보너스)
    값 = {"명중결과": 눈 + 보정합 * 명중배수}
    값["대상AC"] = stats.최종AC(전투상태, 대상) + AC추가
    if stat_breakdown.상세로그(
        전투상태
    ):  # [설정] 전투로그 "자세하게" - 계산 내역도 담는다
        값["명중내역"] = _명중_내역(
            전투상태,
            공격자,
            대상,
            명중률종류,
            명중보너스,
            눈,
            값["명중결과"],
            장비보너스,
            배수몫=보정합 * (명중배수 - 1),
        )
        값["AC내역"] = stat_breakdown.AC_내역(전투상태, 대상)
    판정 = _눈_판정(대상, 명중률종류, 눈, 값, 강제치명타, 치명타범위, 펌블범위)
    return 극점_판정(전투상태, 공격자, 정밀한공격_판정(전투상태, 공격자, 판정))


def 주사위20_성공(눈, 대상, 펌블범위):
    """명중률 "주사위20"(백팔염주): 눈 20에만 맞는다. 감옥(AC 1) 대상은 감옥 규칙대로 대실패만 아니면 맞는다."""
    if 대상.get("감옥"):
        return 눈 > 펌블범위
    return 눈 == 20


def _주사위20_판정(전투상태, 공격자, 대상):
    """명중률 "주사위20" - AC·명중보너스·이점/불리점·치명타범위 확장·피격시강제치명타를 보지 않고 d20을 한 번
    굴린다. 맞아도 치명타가 아니고, 정밀한공격·이중극점도 보지 않는다(2026-11-24 사용자 결정)."""
    눈 = dice_utils.d20_굴림()
    펌블범위 = 유효_펌블범위(전투상태, 공격자, 대상)
    성공 = 주사위20_성공(눈, 대상, 펌블범위)
    return {
        "성공": 성공,
        "자연눈": 눈,
        "치명타": False,
        "자동실패": not 성공 and 눈 <= 펌블범위,
        "명중결과": 눈,
        "대상AC": 1 if 대상.get("감옥") else 20,
    }


def 정밀한공격_판정(전투상태, 공격자, 판정):
    """ "발동조건":"명중성공차이 >= N" 특성(정밀한공격) - 맞은 공격의 명중결과가 대상 AC보다 N 이상 높으면
    "치명타확정"으로 치명타로 바꾸고 판정에 "정밀한공격"(특성 이름)을 남긴다(전투 기록 문장이 보여 준다)."""
    if not 판정["성공"] or 판정["치명타"] or "명중결과" not in 판정:
        return 판정
    차이 = 판정["명중결과"] - 판정["대상AC"]
    for 이름, 정의 in traits.트리거특성_목록(전투상태, 공격자, "명중성공차이"):
        기준 = int(정의["발동조건"].split(">=")[1])
        if 차이 >= 기준 and (정의.get("효과") or {}).get("치명타확정"):
            return dict(판정, 치명타=True, 정밀한공격=이름)
    return 판정


def 극점_판정(전투상태, 공격자, 판정):
    """ "발동조건":"치명타성공시" 치명타연쇄 특성(이중극점)과 그 뒤를 잇는 "<특성>성공시" 특성(삼중극점) -.
    치명타면 특성마다 d20을 다시 굴려 치명타범위 이상이면 이번 공격의 치명타 주사위 +1, 실패하면 연쇄가 끊긴다.
    특성 하나는 한 번만 굴리므로 연쇄는 보유 특성 수에서 끝난다. 굴림은 판정 "극점"([{"특성","눈","성공"}])에,
    더한 수는 공격자 "_극점추가"에 둔다(stats.치명타_주사위수가 더한다 - 다음 판정이 다시 정한다)."""
    공격자.pop("_극점추가", None)
    if not 판정["치명타"]:
        return 판정
    굴림들 = []
    조건 = "치명타성공시"
    쓴것 = set()
    while True:
        다음 = next(
            (
                (이름, 정의)
                for 이름, 정의 in traits.트리거특성_목록(전투상태, 공격자, 조건)
                if 이름 not in 쓴것
                and (정의.get("효과") or {}).get("타입") == "치명타연쇄"
            ),
            None,
        )
        if 다음 is None:
            break
        이름, 정의 = 다음
        쓴것.add(이름)
        눈 = dice_utils.d20_굴림()
        성공 = 눈 >= 유효_치명타범위(전투상태, 공격자)
        # "성공시":"치명타주사위+N" - 성공하면 더하는 치명타 주사위 수
        더함 = int(str(정의["효과"].get("성공시", "치명타주사위+1")).split("+")[-1])
        굴림들.append({"특성": 이름, "눈": 눈, "성공": 성공, "더함": 더함})
        if not 성공:
            break
        조건 = f"{이름}성공시"
    if not 굴림들:
        return 판정
    추가 = sum(r["더함"] for r in 굴림들 if r["성공"])
    if 추가:
        공격자["_극점추가"] = 추가
    return dict(판정, 극점=굴림들)


def _눈_판정(대상, 명중률종류, 눈, 값, 강제치명타, 치명타범위, 펌블범위):
    """굴린 눈과 값(명중결과/대상AC 등)으로 성공·치명타·대실패를 정한다(명중_판정_계산의 마지막 단계)."""
    if 강제치명타:
        return {"성공": True, "자연눈": 눈, "치명타": True, "자동실패": False, **값}

    if 명중률종류 == "필중":
        return {
            "성공": True,
            "자연눈": 눈,
            "치명타": 눈 >= 치명타범위,
            "자동실패": False,
            **값,
        }

    if 눈 <= 펌블범위:
        return {"성공": False, "자연눈": 눈, "치명타": False, "자동실패": True, **값}
    if 대상.get("감옥") and 눈 < 치명타범위:  # 감옥(AC 1)은 대실패만 아니면 맞는다
        return {"성공": True, "자연눈": 눈, "치명타": False, "자동실패": False, **값}
    if 눈 >= 치명타범위:
        return {"성공": True, "자연눈": 눈, "치명타": True, "자동실패": False, **값}

    return {
        "성공": 값["명중결과"] >= 값["대상AC"],
        "자연눈": 눈,
        "치명타": False,
        "자동실패": False,
        **값,
    }


_보정치_이름 = {"보정명중률": "능력 보정", "주문시전명중률": "주문 보정"}
# 명중률종류 -> 명중 굴림에 더하는 능력치 보정치(전투상태, 공격자). 키는 _보정치_이름과 같다.
# 표에 없으면 "…판정"(근력판정 등)은 그 능력치 보정치, 그 밖(기본명중률 등)은 0 - _명중_능력보정.
# stats와 서로 불러 import 때는 함수가 아직 없다 - 부를 때 찾는다.
_보정치_함수 = {
    "보정명중률": lambda 전투상태, 공격자: stats.평타_능력치_보정치(전투상태, 공격자),
    "주문시전명중률": lambda 전투상태, 공격자: stats.주문시전_보정치(전투상태, 공격자),
}


def _명중_능력보정(전투상태, 공격자, 명중률종류):
    if not isinstance(명중률종류, str):
        return 0
    if (함수 := _보정치_함수.get(명중률종류)) is not None:
        return 함수(전투상태, 공격자)
    if 명중률종류.endswith("판정"):
        return stats.유효_능력치_보정치(전투상태, 공격자, 명중률종류[:-2])
    return 0


def _명중_내역(
    전투상태,
    공격자,
    대상,
    명중률종류,
    명중보너스,
    눈,
    명중결과,
    장비보너스=True,
    배수몫=0,
):
    """명중 굴림의 [(이름, 값)] - 주사위, 능력 보정, 기본/역할군/차수/장비 명중률보너스, 출처별(버프/특성/칭호),
    스킬 명중보너스. 합은 명중결과(_명중_보정합과 같은 값, 남으면 "기타")."""
    내역 = [("주사위", 눈)]
    보정 = _명중_능력보정(전투상태, 공격자, 명중률종류)
    이름 = _보정치_이름.get(명중률종류) or f"{str(명중률종류)[:-2]} 보정"
    기본 = 공격자["원본"].get("명중률보너스", 0)
    역할군 = (
        participants.몬스터_역할군_보너스(공격자["원본"], "명중률보너스")
        if 공격자["진영"] == "적"
        else 0
    )
    차수 = (
        participants.몬스터_차수_명중보너스(공격자["원본"])
        if 공격자["진영"] == "적"
        else 0
    )
    내역 += [
        (이름, 보정),
        ("기본 명중", 기본 if isinstance(기본, (int, float)) else 0),
        ("역할군", 역할군),
        ("차수", 차수),
        ("장비", stats.장비_수치(공격자, "명중률보너스") if 장비보너스 else 0),
    ]
    내역 += stat_breakdown.출처별_내역(
        전투상태, 공격자, "명중보너스", 명중률종류=명중률종류, 대상=대상
    )
    내역 += [(n, v) for n, v, _ in status.대상조건_명중(전투상태, 공격자, 대상)]
    내역.append(("스킬", 명중보너스))
    내역.append(("원펀맨", 배수몫))  # 보정 전체 x 배수의 늘어난 몫
    return stat_breakdown.기타_채우기(
        [(n, v) for n, v in 내역 if v or n == "주사위"], 명중결과
    )


def _명중_보정합(전투상태, 공격자, 대상, 명중률종류, 명중보너스, 장비보너스=True):
    """명중 굴림에 더하는 값 전부 - 능력치 보정치 + 명중률보너스(원본/역할군/적 차수/장비/버프/특성/칭호)."""
    보정치 = _명중_능력보정(전투상태, 공격자, 명중률종류)

    명중률보너스 = 공격자["원본"].get("명중률보너스", 0)
    if not isinstance(명중률보너스, (int, float)):
        명중률보너스 = 0
    if 공격자["진영"] == "적":  # 몬스터 역할군(탱커 -1, 메이지 +1)과 +차수
        명중률보너스 += participants.몬스터_역할군_보너스(
            공격자["원본"], "명중률보너스"
        ) + participants.몬스터_차수_명중보너스(공격자["원본"])
    # 장비(전 부위+활성 세트) 명중률보너스 - 아군만, 투척 아이템을 뺀 모든 명중 굴림.
    if 장비보너스:
        명중률보너스 += stats.장비_수치(공격자, "명중률보너스")
    명중률보너스 += stats.버프디버프_수치(전투상태, 공격자, "명중보너스")
    명중률보너스 += traits.특성_수치(
        전투상태, 공격자, "명중보너스", 명중률종류=명중률종류, 대상=대상
    )
    명중률보너스 += traits.칭호_수치(전투상태, 공격자, "명중보너스")
    if "일반공격" in (
        공격자.get("_공격태그") or ()
    ):  # 빗자루 다루기 - 일반공격·일반공격취급만
        명중률보너스 += stats.스킬타입_조건_수치(
            전투상태, 공격자, "명중보너스", ("일반공격",)
        )
    명중률보너스 += sum(v for _, v, _ in status.대상조건_명중(전투상태, 공격자, 대상))
    return 보정치 + 명중률보너스 + 명중보너스


def 명중_보정합(전투상태, 공격자, 대상, 명중률종류, 명중보너스=0):
    """명중 굴림에 더하는 값 전부(_명중_보정합) - 기대값 계산(contribution)이 쓴다."""
    return _명중_보정합(전투상태, 공격자, 대상, 명중률종류, 명중보너스)


