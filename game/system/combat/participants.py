def _몬스터_수식_컨텍스트(몬스터원본):
    """몬스터의 역할군 "최대HP"/"AC" 수식(예: "레벨×(6+건강보정치)",
    "9+차수+민첩보정치")을 평가할 때 쓰는 컨텍스트. "레벨"/"차수"는
    몬스터 데이터 자신에는 없고(항상 None) 호출부(gameflow.py의
    _몬스터원본목록_생성)가 던전 맵의 인카운트/오브젝트 데이터에서 값을
    가져와 몬스터 원본 사본에 덮어써 넘긴다 - 없으면 1로 가정한다."""
    return {
        "레벨": 몬스터원본.get("레벨") or 1,
        "차수": 몬스터원본.get("차수") or 1,
        "능력치": 몬스터원본,
    }


def 몬스터_수식_평가(수식, 몬스터원본, 기본값):
    """수식_평가()를 몬스터 데이터에 대해 안전하게 호출한다 - 이미
    숫자면 그대로 쓰고, 문자열 수식이면 평가하되 평가할 수 없는
    표현(아직 "미정"인 데이터 등)이면 기본값으로 조용히 대체한다."""
    if isinstance(수식, (int, float)):
        return 수식
    if not isinstance(수식, str):
        return 기본값
    try:
        결과 = formula.수식_평가(수식, _몬스터_수식_컨텍스트(몬스터원본))
    except Exception:
        return 기본값
    if not isinstance(결과, (int, float)):
        return 기본값
    return 결과


def 몬스터_역할군_수식(몬스터원본, 항목):
    """몬스터의 "역할군"에 해당하는 "최대HP"/"AC" 수식(monster_format.py
    역할군공식). 데이터의 "최대HP"/"AC" 값은 보지 않는다. 역할군이 없거나
    표에 없으면 None - 호출부가 기본값(HP 1, AC 10)을 쓴다."""
    역할군 = 몬스터원본.get("역할군")
    if not isinstance(역할군, str) or 역할군 not in 역할군공식:
        return None
    return 역할군공식[역할군][항목]


def 몬스터_역할군_보너스(몬스터원본, 항목):
    """몬스터의 "역할군"이 정하는 "데미지보너스"/"명중률보너스"(monster_format.py
    역할군공식). 데이터 파일의 같은 이름 값과 따로 더한다. 역할군이 없으면 0."""
    역할군 = 몬스터원본.get("역할군")
    if not isinstance(역할군, str) or 역할군 not in 역할군공식:
        return 0
    return 역할군공식[역할군].get(항목, 0)


def 적_참가자_생성(몬스터원본):
    """ "기본최대HP"에는 역할군 "최대HP" 수식을 평가한 값만 담는다. 특성/칭호
    반영 뒤의 실제 시작 HP는 전투_시작()이 유효_최대HP()로 다시 채운다.
    몬스터는 MP를 쓰지 않는다 - 적 참가자에는 "현재MP" 칸이 없다."""
    최대HP = 몬스터_수식_평가(몬스터_역할군_수식(몬스터원본, "최대HP"), 몬스터원본, 1)
    if not isinstance(최대HP, (int, float)):
        최대HP = 1
    최대HP = max(1, formula.올림(최대HP))

    return {
        "이름": 몬스터원본["몬스터명"],
        "진영": "적",
        "원본": 몬스터원본,
        "기본최대HP": 최대HP,
        "현재HP": 최대HP,
        "이니셔티브": 0,
        "기본이니셔티브": 0,
        "우선도": 0,  # 아군과 같은 개념 - 유효_우선도() 참고.
        "기본우선도": 0,
        "행동자원": dict.fromkeys(common_names.행동자원_종류, 1),
        "추가공격_사용가능": 0,
        "상태이상": [],
        "버프": [],
        "디버프": [],
        "버프스택": {},  # 몬스터 전용 이름 있는 스택 카운터 (예: "광포")
        "치명타범위": 20,
        "치명타주사위": 몬스터원본.get("치명타주사위", 1),
        "펌블범위": 1,
        "생존": True,
        "몬스터턴카운트": 0,
        # 범위 스킬 좌우 인접 판정용 대형 위치(정렬과 무관, 전투 시작 시 고정).
        "대형위치": 0,
    }
