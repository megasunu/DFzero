# =====================
# 마법부여
# =====================
# 마을 [전문직업] > [마법부여](#178, 2026-11-11 사용자 결정). 규칙은 docs/game-rules.md "마법부여",
# 데이터는 game/data/enchant/(부위 구역별 enchant_01~04, 양식은 enchant_00_format.py) - 아래 _표_합치기가 합친다.
#
# - 부위 탭마다 소지품과 장착 장비 목록(장비강화와 같은 모양) -> 장비를 고르면 그 장비에 걸 수 있는
#   마법부여 목록 -> [부여]. 비용(골드)을 내고 항상 성공한다.
# - 한 장비에 하나 - 다른 것을 걸면 덮어쓴다(낸 비용은 돌아오지 않는다). 같은 것은 다시 걸 수 없다.
#   봉인된 장비는 목록에 없다(먼저 봉인해제).
# - 저장은 이름 방식(장비강화와 같다): "강철 소검 [비노슈]"처럼 이름 뒤에 붙이고, 장비강화 머리는 그 앞에 온다
#   ("+1강 강철 소검 [비노슈]"). 그 이름의 장비 데이터를 카탈로그에 만들어 넣는다(카탈로그_등록) - 부여한
#   장비를 먼저 만들고 그것을 장비강화가 강화한다. 세이브 형식은 그대로.
#   만든 데이터는 "부여원본"(원래 이름)과 "마법부여"(딕셔너리 - 부여정보)를 가지며 상점 구매/도감/드랍/봉인변환에
#   나오지 않는다. 장비 원래 수치는 그대로이고 부여 효과는 "마법부여" 딕셔너리 안에만 있다.
#   가격·레어도·티어는 원래 그대로라 판매가와 해체 결과도 원래 장비와 같다.

import copy
import re

from game.data import common_names
from game.data.enchant.enchant_01_weapon import 무기마법부여
from game.data.enchant.enchant_02_armor import 방어구마법부여
from game.data.enchant.enchant_03_accessory import 악세서리마법부여
from game.data.enchant.enchant_04_special import 특수장비마법부여
from game.system import enhance_system


def _속성강화(속성):
    """데이터의 {"속성강화": 속성} 표시를 채운 항목(enchant_00_format.py "속성강화 표시")."""
    return {
        "부위": list(common_names.악세서리_부위),
        "비용": {"골드": 100},
        "설명": f"{속성} 강화 +1",
        "효과": [{"변동대상": "속성강화", "속성": 속성, "변동값": 1}],
    }


def _표_합치기(*구역들):
    """부위 구역별 데이터 딕셔너리를 하나의 마법부여 표로 합친다. 이름이 겹치면 실패한다."""
    표 = {}
    for 구역 in 구역들:
        for 이름, 정의 in 구역.items():
            if 이름 in 표:
                raise ValueError(f"마법부여 이름이 겹침: {이름}")
            표[이름] = _속성강화(정의["속성강화"]) if "속성강화" in 정의 else 정의
    return 표


마법부여 = _표_합치기(무기마법부여, 방어구마법부여, 악세서리마법부여, 특수장비마법부여)

부위들 = [
    "무기",
    *common_names.방어구_부위,
    *common_names.악세서리_부위,
    *common_names.특수장비_부위,
]
없음_사유 = "적용할 수 있는 마법부여가 없습니다."
이미_사유 = "이미 부여됨"
_봉인머리 = "마법으로 봉인된 "
_이름식 = re.compile(r"^(.+) \[([^\[\]]+)\]$")
_효과칸 = ("속성", "보너스", "효과")


def 이름_풀기(이름):
    """ "+1강 강철 소검 [비노슈]" -> ("강철 소검", "비노슈", {"강화": 1, ...}). 부여가 없으면 가운데가 None."""
    본이름, 수치 = enhance_system.이름_풀기(이름)
    맞음 = _이름식.match(본이름 or "")
    if 맞음 and 맞음.group(2) in 마법부여:
        return 맞음.group(1), 맞음.group(2), 수치
    return 본이름, None, 수치


def 원래_이름(아이템):
    """강화·마법부여를 모두 벗긴 원래 장비 이름 - 세트 구성품과 견줄 때 쓴다(#699)."""
    return 이름_풀기((아이템 or {}).get("이름"))[0]


def 이름_짓기(원본, 부여, 수치):
    본이름 = f"{원본} [{부여}]" if 부여 else 원본
    return enhance_system.이름_짓기(본이름, 수치)


def 장비_생성(원본데이터, 부여):
    """원래 장비 데이터 + 마법부여 -> 부여한 장비 데이터(새 dict)."""
    아이템 = copy.deepcopy(원본데이터)
    아이템["이름"] = 이름_짓기(원본데이터["이름"], 부여, {})
    아이템["부여원본"] = 원본데이터["이름"]
    아이템["마법부여"] = 부여정보(부여)
    return 아이템


def 부여정보(부여):
    """장비에 넣는 "마법부여" 딕셔너리 - {"이름", "설명", 효과 칸(_효과칸 중 정의에 있는 것)}. 장비 원래
    수치는 건드리지 않고 효과는 여기에만 둔다(계산: equipment_system, 표시: 상세보기 맨 아래)."""
    정의 = 마법부여[부여]
    return {
        "이름": 부여,
        "설명": 정의["설명"],
        **{칸: copy.deepcopy(정의[칸]) for 칸 in _효과칸 if 칸 in 정의},
    }


def 카탈로그_등록(장비카탈로그, 이름):
    """그 이름의 장비가 카탈로그에 없고 부여 이름이면 만들어 넣는다(제자리 - 부여한 장비, 그다음 강화).
    들어 있는 탭(없으면 None)."""
    for 탭, 아이템들 in 장비카탈로그.items():
        if 이름 in 아이템들:
            return 탭
    원본, 부여, _ = 이름_풀기(이름)
    if 부여 is None:
        return None
    본이름 = 이름_짓기(원본, 부여, {})
    for 탭, 아이템들 in 장비카탈로그.items():
        if 원본 in 아이템들:
            if 본이름 not in 아이템들:
                아이템들[본이름] = 장비_생성(아이템들[원본], 부여)
            return enhance_system.카탈로그_등록(장비카탈로그, 이름)
    return None


def 카탈로그_복원(장비카탈로그, 이름들):
    """불러오기 - 소지품/장착 칸의 부여 이름들을 카탈로그에 다시 만든다(장비강화 복원보다 먼저)."""
    for 이름 in 이름들:
        if 이름:
            카탈로그_등록(장비카탈로그, 이름)


def 부위_마법부여(탭):
    return [이름 for 이름, 정의 in 마법부여.items() if 탭 in 정의["부위"]]


def 비용글(비용값):
    return enhance_system.비용글(비용값)


def 대상목록(플레이어, 장비카탈로그, 탭, 숙소=()):
    """[{"이름", "아이템", "탭", "캐릭터", "슬롯", "수량", "불가"}] - 그 부위의 소지품과 장착 장비(봉인된 장비
    제외). 장착 중인 것은 캐릭터마다 한 줄(수량 1), 남은 것은 소지품 한 줄. 걸 수 있는 마법부여가 없는
    부위면 "불가"가 없음_사유."""
    보유 = 플레이어.get("소지품", {}).get("장비", {})
    캐릭터들 = list(플레이어.get("파티", {}).get("파티원", [])) + list(숙소)
    아이템들 = 장비카탈로그.get(탭, {})
    불가 = None if 부위_마법부여(탭) else 없음_사유
    결과 = []
    for 이름, 개수 in 보유.items():
        if 이름 not in 아이템들 or 개수 <= 0 or 이름.startswith(_봉인머리):
            continue
        공통 = {"이름": 이름, "아이템": 아이템들[이름], "탭": 탭, "불가": 불가}
        장착 = [
            (c, 슬롯)
            for c in 캐릭터들
            for 슬롯, 장착이름 in c.get("장착장비", {}).items()
            if 장착이름 == 이름 and 슬롯 == 탭
        ]
        for c, 슬롯 in 장착:
            결과.append({**공통, "캐릭터": c, "슬롯": 슬롯, "수량": 1})
        if 개수 - len(장착) > 0:
            결과.append(
                {**공통, "캐릭터": None, "슬롯": None, "수량": 개수 - len(장착)}
            )
    return 결과


def 선택지(항목):
    """그 장비에 걸 수 있는 마법부여 [{"이름", "설명", "비용", "비용글", "불가"}] - 지금 걸린 것은 "불가"."""
    지금 = (항목["아이템"].get("마법부여") or {}).get("이름")
    return [
        {
            "이름": 이름,
            "설명": 마법부여[이름]["설명"],
            "비용": dict(마법부여[이름]["비용"]),
            "비용글": 비용글(마법부여[이름]["비용"]),
            "불가": 이미_사유 if 이름 == 지금 else None,
        }
        for 이름 in 부위_마법부여(항목["탭"])
    ]


def 실행(플레이어, 장비카탈로그, 항목, 부여):
    """항목(대상목록의 한 줄) 하나에 마법부여를 건다. 새 이름을 돌려준다. 걸 수 없거나 골드가 모자라면
    ValueError(아무것도 바뀌지 않는다)."""
    고를것 = {s["이름"]: s for s in 선택지(항목)}
    if 부여 not in 고를것:
        raise ValueError(없음_사유)
    if 고를것[부여]["불가"]:
        raise ValueError(고를것[부여]["불가"])
    골드 = 고를것[부여]["비용"].get("골드", 0)
    소지품 = 플레이어["소지품"]
    if 소지품.get("골드", 0) < 골드:
        raise ValueError(f"골드가 부족합니다({골드}G 필요).")
    원본, _, 수치 = 이름_풀기(항목["이름"])
    새이름 = 이름_짓기(원본, 부여, 수치)
    if 카탈로그_등록(장비카탈로그, 새이름) is None:
        raise ValueError(없음_사유)
    소지품["골드"] -= 골드
    보유 = 소지품["장비"]
    보유[항목["이름"]] -= 1
    if 보유[항목["이름"]] <= 0:
        del 보유[항목["이름"]]
    보유[새이름] = 보유.get(새이름, 0) + 1
    if 항목["캐릭터"] is not None:
        항목["캐릭터"]["장착장비"][항목["슬롯"]] = 새이름
    return 새이름
