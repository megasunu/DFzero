# 프로젝트 전반에서 쓰이는 "주사위를 굴린다" 자체만 담당하는 공용
# 함수 모음이다. "차수", "보정치", "주문시전보정치" 같은 변수가 섞인
# 데미지/명중 계산식(job_skill_XX.py의 "데미지"/"명중률" 문자열 등)을
# 실제 숫자로 풀어내는 건 이 파일의 역할이 아니다. 그건 캐릭터 데이터를
# 알아야 하는 작업이라 combat 패키지 쪽에서 처리한다. 여기서는
# 순수하게 난수만 다룬다.

from game.system import rng


def 주사위_굴림(개수, 면수):
    """개수만큼 면수짜리 주사위를 굴려 각 눈금을 리스트로 반환한다.
    예: 주사위_굴림(2, 8) -> [주사위 눈금, 주사위 눈금] (각 눈금은 1~8)"""
    return [rng.주사위.randint(1, 면수) for _ in range(개수)]


def 주사위_합(개수, 면수):
    """개수만큼 면수짜리 주사위를 굴려 합을 반환한다.
    예: 주사위_합(2, 8) -> 2d8 결과값 (2~16 사이 정수)"""
    return sum(주사위_굴림(개수, 면수))


def d20_굴림(이점=False, 불리=False):
    """d20 1회. 이점/불리가 둘 다 있으면 서로 상쇄되어 그냥 1회 굴림과
    같다. 이점이면 2회 굴려 높은 값, 불리면 2회 굴려 낮은 값을
    반환한다."""
    if 이점 and 불리:
        이점 = 불리 = False

    if not 이점 and not 불리:
        return rng.주사위.randint(1, 20)

    굴림값들 = [rng.주사위.randint(1, 20), rng.주사위.randint(1, 20)]
    return max(굴림값들) if 이점 else min(굴림값들)


def 판정_굴림(보정치, 이점=False, 불리=False):
    """d20 + 보정치 형태의 판정(명중, 내성 등)에 공통으로 쓴다.
    (최종값, d20눈) 튜플을 반환한다. d20눈은 자연 1/자연 20 같은
    특수 처리가 필요할 때 호출한 쪽에서 참고한다."""
    눈 = d20_굴림(이점, 불리)
    return 눈 + 보정치, 눈


def 이점_합산(이점수, 불리수):
    """이점·불리점 개수를 굴림 하나로 - 많은 쪽 하나만 적용하고 같으면 둘 다 없다. (이점, 불리) 튜플."""
    return 이점수 > 불리수, 불리수 > 이점수


def 내성_굴림(보정치, 난이도, 이점=False, 불리=False):
    """내성굴림 - (성공 여부, 최종값). 전투 로그가 "DC vs 굴린 값"을 보여 줄 때 쓴다."""
    최종값, _ = 판정_굴림(보정치, 이점, 불리)
    return 최종값 >= 난이도, 최종값


def 내성_성공(보정치, 난이도, 이점=False, 불리=False):
    """내성굴림이 난이도(DC) 이상인지 여부만 bool로 반환한다."""
    return 내성_굴림(보정치, 난이도, 이점, 불리)[0]
