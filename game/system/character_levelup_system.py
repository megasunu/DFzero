# =====================
# 캐릭터 레벨업 시스템
# =====================
# job_level_XX.py "레벨업테이블"의 항목 하나를 받아서 캐릭터에 반영하는
# 처리를 담당한다. 레벨별 "타입" 순서는 job_level_format.py 참고(1차수는
# 특성획득 → 마스터리선택 → 특성획득 → 퍽획득 → 스탯성장).
# 스킬은 레벨업으로 배우지 않는다 - 파티 화면 [스킬습득]으로 골드를 내고
# 배운다(skill_learn_system.py).
#
# "스탯획득"/"스탯성장"(능력치 배분)과 "퍽획득"(퍽 선택)은 사용자가 직접 골라야
# 하는 부분이라 이 시스템이 자동으로 결정하지 않는다. 호출하는 쪽이
# 이미 정해진 값(배분할 능력치, 고른 퍽 이름과 그 정의)을 넘겨준다고
# 가정한다.
#
# character_creation_system.py와 마찬가지로 "직업 이름 →
# job_level_XX.py", "퍽 이름 → perks_class_XX.py 정의", "특성 이름 →
# job_ability_XX.py 정의" 같은 연결은 스스로 찾아가지 않고, 호출하는
# 쪽이 직접 찾아 넘겨준다고 가정한다.

import copy

from game.system import character_data_system as 캐릭터데이터
from game.system import effect_engine


def 약점스탯_투자가능(캐릭터, 스탯이름):
    """ "스탯이름"이 이 캐릭터의 "약점스탯"이면, "약점제거" 특성을 배우기
    전까지는 배분 포인트를 투자할 수 없다 (job_ability_00.py "약점제거"
    참고 - 그 특성을 배우면 약점스탯이 즉시 +2 되고 이후 투자 제한도
    풀린다). 약점스탯이 아닌 능력치는 항상 투자 가능하다."""
    if 스탯이름 != 캐릭터.get("약점스탯"):
        return True
    return "약점제거" in 캐릭터["보유특성"]


def 캐릭터_레벨업(캐릭터, 레벨업항목, 레벨당체력증가, **선택):
    """레벨업 항목 하나를 캐릭터에 적용하고 레벨을 1 올린다. "타입"에
    따라 처리가 갈라진다.

    레벨업항목       : job_level_XX.py "레벨업테이블"의 항목 하나.
    레벨당체력증가   : 캐릭터가 속한 1차 계열 job_level_XX.py 레벨 1
                        항목의 값. 2차전직 이후에도 원래 1차 계열의
                        값을 계속 넘겨줘야 한다 (job_level_format.py 참고).
    선택             : "타입"별로 필요한 추가 정보를 키워드 인자로 넘긴다.
        - "특성획득" : 특성정의모음={특성이름: 특성정의, ...}
        - "마스터리선택": 무기마스터리="소검숙련", 방어구마스터리="천갑숙련",
                       특성정의모음={이름: 특성정의} (공용 특성 포함)
        - "스타일선택": 스타일="강타" 등, 스타일정의모음={이름: 특성정의}
                       (job_level_000x_style.py "전투스타일"). 항목에
                       "스타일선택지"가 있는 레벨(전직 레벨 6)도 같은 두 값을
                       받는다 - 기존 스타일과 교체.
        - "스탯성장" : 배분={"근력": 1, "민첩": 1} - 약점스탯 제외, 한 능력치에
                       1점까지(서로 다른 2개).
        - "스탯획득" : 배분={"근력": 1, "건강": 1}처럼 스탯이름→증가폭.
                       합이 "배분점수"와 같아야 한다. 약점스탯에는
                       "약점제거" 특성 없이는 투자할 수 없다
                       (약점스탯_투자가능 참고).
        - "퍽획득"   : 퍽이름=문자열, 퍽정의=선택된 퍽의 정의
                       (perks_class_XX.py "퍽목록" 항목). 퍽정의의
                       "분류"가 "특성획득"이면 특성정의=그 특성의
                       job_ability_XX.py 정의도 함께 넘겨야 즉시
                       효과가 반영된다. "분류"가 "스탯획득"이고
                       "획득스탯포인트"가 있는 퍽(예: "능력치향상")이면
                       배분={"근력": 1, "건강": 1}처럼 이미 정해진
                       배분을 함께 넘겨야 한다 (합이 "획득스탯포인트"와
                       같아야 하고, 이때도 약점스탯 투자 제한이 똑같이
                       적용된다). 퍽정의의 "분류"가 "스킬획득"이고
                       "획득스킬"이 None(예: 훔쳐배우기처럼 캐릭터
                       상태에 따라 목록이 달라지는 퍽)이면 선택스킬=
                       이미 고른 스킬 이름을 함께 넘겨야 한다
                       (job_skill_format.py "훔쳐배우기스킬" 참고).
        - "행동획득" : (추가 정보 필요 없음)
        - "스킬획득" : (추가 정보 필요 없음 - "획득스킬"을 보유스킬에 넣는다)
        - "미정"     : (추가 정보 필요 없음 - 레벨만 오른다)
        - "스타일강화": (추가 정보 필요 없음 - 직업스타일 성장만 다시 계산된다)
        - "스킬개화" : (지금은 추가 정보 필요 없음 - 선택지가 미정이라 레벨만 오른다)
        - "스킬강화" : 강화스킬=스킬이름, 스킬강화선택지=[고를 수 있는 스킬 이름]
                       (차수 판정은 호출하는 쪽 - gameflow.스킬강화_선택지)

    도중에 오류(배분 합/약점스탯 등)가 나면 캐릭터는 하나도 바뀌지 않는다 -
    사본에 끝까지 적용해 본 뒤 성공했을 때만 원본(같은 객체)에 옮긴다(B5).
    """
    작업본 = copy.deepcopy(캐릭터)
    _레벨업_적용(작업본, 레벨업항목, 레벨당체력증가, 선택)
    캐릭터.clear()
    캐릭터.update(작업본)
    return 캐릭터


def _레벨업_적용(캐릭터, 레벨업항목, 레벨당체력증가, 선택):
    캐릭터["레벨"] += 1

    타입 = 레벨업항목["타입"]
    if 타입 == "특성획득":
        _특성획득_처리(캐릭터, 레벨업항목, 선택["특성정의모음"])
    elif 타입 == "스탯획득":
        _스탯획득_처리(캐릭터, 레벨업항목, 선택["배분"])
    elif 타입 == "스탯성장":
        _스탯성장_처리(캐릭터, 레벨업항목, 선택["배분"])
    elif 타입 == "마스터리선택":
        _마스터리선택_처리(
            캐릭터,
            레벨업항목,
            선택.get("무기마스터리"),
            선택.get("방어구마스터리"),
            선택["특성정의모음"],
        )
    elif 타입 == "스타일선택":
        _스타일_교체(
            캐릭터,
            선택.get("스타일"),
            레벨업항목["획득"]["선택지"],
            선택["스타일정의모음"],
        )
    elif 타입 == "스킬획득":
        _스킬_보유(캐릭터, 레벨업항목["획득"]["획득스킬"])
    elif 타입 == "스킬강화":
        _스킬강화_처리(캐릭터, 레벨업항목, 선택.get("강화스킬"), 선택["스킬강화선택지"])
    elif 타입 in ("미정", "스타일강화", "스킬개화"):
        # 미정: 아직 정해지지 않은 레벨. 스타일강화(전직 레벨 11): 따로 얻는 것이 없고
        # 아래에서 다시 계산하는 직업스타일 성장(추가공격/최대MP)이 그 내용이다.
        # 스킬개화(전직 레벨 17): 고를 조건부 추가효과가 아직 미정이다.
        pass
    elif 타입 == "퍽획득":
        _퍽획득_처리(
            캐릭터,
            선택["퍽이름"],
            선택["퍽정의"],
            선택.get("특성정의"),
            선택.get("배분"),
            선택.get("선택스킬"),
        )
    elif 타입 == "행동획득":
        _행동획득_처리(캐릭터, 레벨업항목)
    else:
        raise ValueError(f"알 수 없는 레벨업 타입: {타입}")

    # 전직 레벨(6)처럼 다른 타입 항목에 붙은 스타일 재선택
    if 레벨업항목.get("스타일선택지"):
        _스타일_교체(
            캐릭터,
            선택.get("스타일"),
            레벨업항목["스타일선택지"],
            선택["스타일정의모음"],
        )

    캐릭터["기본최대HP"] = 캐릭터데이터.기본최대HP_계산(캐릭터, 레벨당체력증가)
    캐릭터["추가공격"] = 캐릭터데이터.추가공격_계산(캐릭터)  # 직업스타일 성장
    # 능력치 배분/특성(약점제거 +2 등)으로 주문시전능력치가 바뀌었을 수 있다(B6).
    캐릭터["기본최대MP"] = 캐릭터데이터.기본최대MP_계산(캐릭터)
    캐릭터["현재MP"] = min(캐릭터["현재MP"], 캐릭터["기본최대MP"])


def _배분_적용(캐릭터, 배분, 필요합계):
    """ "배분"({스탯이름: 증가폭})의 합이 필요합계와 같은지, 약점스탯이
    섞여 있으면 "약점제거" 특성을 배웠는지 확인한 뒤 반영한다
    (_스탯획득_처리와 _퍽획득_처리의 "능력치향상"류 퍽에서 공용으로
    쓰던 검증+적용 로직을 한 곳으로 모은 것)."""
    if sum(배분.values()) != 필요합계:
        raise ValueError(
            f"배분한 능력치 합({sum(배분.values())})이 필요합계({필요합계})와 다르다."
        )
    for 스탯이름 in 배분:
        if not 약점스탯_투자가능(캐릭터, 스탯이름):
            raise ValueError(
                f"'{스탯이름}'은(는) 약점스탯이라 '약점제거' 특성을 배우기 "
                f"전에는 포인트를 투자할 수 없다."
            )
    for 스탯이름, 증가폭 in 배분.items():
        캐릭터[스탯이름] += 증가폭


def _특성획득_처리(캐릭터, 레벨업항목, 특성정의모음):
    """job_level_format.py <획득 하위 양식> 1) "특성" 처리.
    character_creation_system.py의 레벨 1 처리와 같은 방식이다.
    "획득스킬"(1차 계열 레벨 2)이 있으면 그 스킬도 보유스킬에 넣는다."""
    획득 = 레벨업항목["획득"]
    특성이름들 = 획득["획득특성"]
    if isinstance(특성이름들, str):
        특성이름들 = [특성이름들]

    for 특성이름 in 특성이름들:
        effect_engine.특성_부여(캐릭터, 특성이름, 특성정의모음[특성이름])
    _스킬_보유(캐릭터, 획득.get("획득스킬", []))


def _스킬_보유(캐릭터, 스킬이름들):
    """레벨진행으로 얻는 스킬(1차 계열 레벨 3 "획득스킬", 2차수 레벨 8
    "스킬획득")을 보유스킬에 넣는다. 이미 있으면 건너뛴다."""
    for 스킬이름 in 스킬이름들:
        if 스킬이름 not in 캐릭터["보유스킬"]:
            캐릭터["보유스킬"].append(스킬이름)


def _스킬강화_처리(캐릭터, 레벨업항목, 강화스킬, 선택지):
    """job_level_format.py <획득 하위 양식> 9) "스킬강화" 처리 - 고른 스킬과 배율을
    캐릭터["스킬강화"]에 기록한다(전투에서 skill_system이 읽는다). 이미 있으면 교체."""
    if not 선택지 and 강화스킬 is None:
        return  # 강화할 스킬이 하나도 없으면 레벨만 오른다
    if 강화스킬 not in 선택지:
        raise ValueError(f"강화할 스킬은 {선택지} 중 하나여야 한다: {강화스킬!r}")
    획득 = 레벨업항목["획득"]
    캐릭터["스킬강화"] = {
        "스킬": 강화스킬,
        "최종피해배율": 획득["최종피해배율"],
        "MP소모배율": 획득["MP소모배율"],
    }


def _스탯획득_처리(캐릭터, 레벨업항목, 배분):
    """job_level_format.py <획득 하위 양식> 2) "능력치배분" 처리."""
    _배분_적용(캐릭터, 배분, 레벨업항목["획득"]["배분점수"])


def 마스터리_선택지(캐릭터, 레벨업항목):
    """레벨 2 "마스터리선택"에서 고를 수 있는 (무기 숙련 목록, 방어구 숙련 목록).
    무기는 캐릭터 "가용무기"마다 "OO숙련", 방어구는 항목의 "방어구선택지".
    이미 가진 숙련은 뺀다(중복 불가)."""
    보유 = 캐릭터["보유특성"]
    무기 = [f"{종류}숙련" for 종류 in 캐릭터.get("가용무기", [])]
    방어구 = 레벨업항목["획득"]["방어구선택지"]
    return (
        [이름 for 이름 in 무기 if 이름 not in 보유],
        [이름 for 이름 in 방어구 if 이름 not in 보유],
    )


def _마스터리선택_처리(캐릭터, 레벨업항목, 무기마스터리, 방어구마스터리, 특성정의모음):
    """job_level_format.py <획득 하위 양식> 8) "마스터리" 처리 - 무기/방어구 숙련을
    하나씩 특성으로 부여한다(job_ability_0000.py)."""
    무기후보, 방어구후보 = 마스터리_선택지(캐릭터, 레벨업항목)
    if 무기마스터리 not in 무기후보:
        raise ValueError(
            f"무기 마스터리는 {무기후보} 중 하나여야 한다: {무기마스터리!r}"
        )
    if 방어구마스터리 not in 방어구후보:
        raise ValueError(
            f"방어구 마스터리는 {방어구후보} 중 하나여야 한다: {방어구마스터리!r}"
        )
    for 이름 in (무기마스터리, 방어구마스터리):
        effect_engine.특성_부여(캐릭터, 이름, 특성정의모음[이름])


def _스타일_교체(캐릭터, 스타일, 선택지, 스타일정의모음):
    """레벨 2 "스타일선택"과 전직 레벨(6)의 "스타일선택지" 처리 - 이전 전투
    스타일 특성을 빼고(효과도 되돌림) 고른 스타일을 캐릭터["스타일"]에 기록하며
    같은 이름의 특성으로 부여한다(정의는 job_level_000x_style.py "전투스타일")."""
    if 스타일 not in 선택지:
        raise ValueError(f"스타일은 {선택지} 중 하나여야 한다: {스타일!r}")
    이전 = 캐릭터.get("스타일")
    if 이전 in 스타일정의모음:
        effect_engine.특성_제거(캐릭터, 이전, 스타일정의모음[이전])
    캐릭터["스타일"] = 스타일
    effect_engine.특성_부여(캐릭터, 스타일, 스타일정의모음[스타일])


def _스탯성장_처리(캐릭터, 레벨업항목, 배분):
    """job_level_format.py <획득 하위 양식> 6) "능력치성장" 처리. "스탯획득"과
    달리 약점스탯에는 (약점제거가 있어도) 넣을 수 없고, 한 능력치에
    "스탯당최대"(1)보다 많이 넣을 수 없다 - 서로 다른 능력치 2개에 1점씩."""
    획득 = 레벨업항목["획득"]
    if 캐릭터.get("약점스탯") in 배분:
        raise ValueError(f"'{캐릭터['약점스탯']}'은(는) 약점스탯이라 올릴 수 없다.")
    if any(값 > 획득["스탯당최대"] for 값 in 배분.values()):
        raise ValueError(f"한 능력치에는 {획득['스탯당최대']}점까지만 넣을 수 있다.")
    _배분_적용(캐릭터, 배분, 획득["배분점수"])


def _퍽획득_처리(캐릭터, 퍽이름, 퍽정의, 특성정의=None, 배분=None, 선택스킬=None):
    """job_level_format.py <획득 하위 양식> 4) "퍽선택" 처리.
    perks_class_format.py 기준 퍽정의의 "분류"에 따라 처리가 갈라진다.

    캐릭터가 어떤 퍽을 선택했었는지 자체를 기록해두는 필드는
    character_format.py에 아직 없어서, 여기서는 그 퍽이 실제로 주는
    것(특성/스킬/스탯포인트)만 반영한다.

    배분   : "분류"가 "스탯획득"이고 "획득스탯포인트"가 있는 퍽(예:
             "능력치향상")에서만 쓴다. 그런 퍽은 얻는 즉시 능력치를
             고르는 선택지가 나오므로, 여기서는 이미 정해진 배분
             ({스탯이름: 증가폭})을 받아서 바로 반영한다. 이때도
             약점스탯에는 "약점제거" 특성 없이는 투자할 수 없다
             (약점스탯_투자가능 참고).
    선택스킬 : "분류"가 "스킬획득"이고 퍽정의의 "획득스킬"이 None인
             퍽(예: "훔쳐배우기" - 캐릭터의 직업군에 따라 고를 수 있는
             스킬 목록 자체가 달라짐)에서만 쓴다. 얻는 즉시 목록에서
             하나를 고르는 선택지가 나오므로, 여기서는 이미 고른
             스킬 이름을 받아서 바로 반영한다."""
    분류 = 퍽정의["분류"]

    if 분류 == "특성획득":
        # 특성정의가 없으면 "보유특성"에만 추가되고 효과는 나중에
        # 따로 반영해야 한다 (TODO) - 특성_부여()가 그 경우를 처리한다.
        effect_engine.특성_부여(캐릭터, 퍽정의["획득특성"], 특성정의)
        _스킬_보유(캐릭터, 퍽정의.get("획득스킬", []))  # 광기 - 특성과 스킬을 함께

    elif 분류 == "스탯획득":
        if "획득스탯포인트" in 퍽정의:
            # "능력치향상"류 퍽: 얻는 즉시 능력치를 고르는 선택지가
            # 나오므로, _스탯획득_처리와 같은 방식으로 이미 정해진
            # 배분을 그대로 받아 반영한다.
            _배분_적용(캐릭터, 배분, 퍽정의["획득스탯포인트"])
        elif "획득특성" in 퍽정의:
            effect_engine.특성_부여(캐릭터, 퍽정의["획득특성"], 특성정의)

    elif 분류 == "스킬획득":
        스킬이름 = 퍽정의["획득스킬"]
        if 스킬이름 is None:
            # 훔쳐배우기처럼 고정된 스킬이 아니라 목록에서 즉시 고르는
            # 퍽. 이미 고른 스킬 이름을 선택스킬로 받아서 반영한다.
            스킬이름 = 선택스킬
        if 스킬이름 not in 캐릭터["보유스킬"]:
            캐릭터["보유스킬"].append(스킬이름)

    elif 분류 == "일반퍽":
        # 표준화되지 않은 퍽. 퍽마다 구조가 달라서 여기서 일괄 처리할
        # 수 없다 (TODO. perks_class_format.py "일반퍽" 참고).
        raise NotImplementedError(
            f"'일반퍽' 분류는 퍽마다 개별 처리가 필요하다: {퍽이름}"
        )


