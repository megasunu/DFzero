# =====================
# 효과 적용 엔진
# =====================
# 특성/버프/디버프/장비가 정의한 "효과"(job_ability_format.py의
# <특성효과 하위 양식> 등)를 실제로 캐릭터에 반영하는 처리를 모아둔다.
#
# 두 종류로 나뉜다.
# - 즉시(영구) 반영: 능력치(근력~매력) 자체를 바꾸거나, 이점/내성/저항/
#   취약/면역/숙련/숙달처럼 한번 얻으면 계속 유지되는 목록에 값을
#   추가하는 효과. 특성을 얻는 순간 바로 캐릭터 데이터에 반영해서
#   저장해둔다. "어그로"도 여기 포함되는데, "변동값"(더하기)과
#   "배율"(곱하기, 캐릭터 "어그로배율"에 누적) 두 형식을 모두 쓴다.
#   "약점제거"(job_ability_00.py)처럼 "약점스탯보너스" 키를 쓰는 효과도
#   여기 포함된다 - 캐릭터의 "약점스탯"에 해당하는 능력치에 그 값을
#   더한다.
# - 그때그때 계산: AC, 데미지보너스, 명중률보너스, 방어력, 보호률, 속도,
#   최대HP/MP, 일반행동/보조행동/반응행동처럼 "기본"이 붙은 값에 붙는
#   보너스. 이런 값은 저장해두지 않고, 필요할 때마다 "기본" 값과
#   보유특성/버프/디버프/장착장비가 주는 보너스를 그때그때 합산해서
#   계산한다 (character_data_system.py 참고). 이 계산 함수는 아직
#   만들지 않았다 - 장비/버프 쪽 데이터가 더 정리된 뒤에 채운다.

from game.system import character_data_system as 캐릭터데이터

능력치_이름 = {"근력", "민첩", "건강", "지능", "지혜", "매력"}
리스트형_변동대상 = {"이점", "내성", "저항", "취약", "면역", "숙련", "숙달"}


def _고정어그로_배율(캐릭터, 변동값):
    """고정치 어그로 변동(+N/-N)에 곱할 배율 - 증가면 "어그로증가배율"(수호 2),
    감소면 "어그로감소배율"(은밀 2). 예전 세이브처럼 키가 없으면 1."""
    키 = "어그로증가배율" if 변동값 > 0 else "어그로감소배율"
    return 캐릭터.get(키, 1.0)


def 효과_즉시_적용(캐릭터, 효과):
    """ "효과" 항목 하나를 받아서, 즉시(영구) 반영 대상이면 캐릭터에
    반영한다. 그 외(AC, 데미지보너스 등 그때그때 계산하는 값)는
    여기서 처리하지 않고 그냥 넘어간다.

    "어그로"는 두 형식을 구분해서 처리한다.
    - {"변동대상": "어그로", "변동값": N} : 캐릭터["어그로"]에 더한다.
    - {"변동대상": "어그로", "배율": N}   : 캐릭터["어그로배율"]에 곱한다
      (천갑숙련 0.5, 판금숙련 2 등).

    "약점스탯보너스"는 "변동대상" 형식이 아니라 job_ability_00.py
    "약점제거"처럼 {"약점스탯보너스": 2, "약점패널티상쇄": True} 형태로
    직접 온다. 캐릭터["약점스탯"]에 해당하는 능력치에 그 값만큼 더한다
    ("약점패널티상쇄"는 여기서 다루지 않는다 - 약점스탯 투자 제한 해제는
    character_levelup_system.py의 약점스탯_투자가능()이 "약점제거"
    특성 보유 여부를 직접 확인하는 방식으로 처리한다)."""
    변동대상 = 효과.get("변동대상")
    변동값 = 효과.get("변동값")
    배율 = 효과.get("배율")

    if 변동대상 == "어그로":
        if 배율 is not None:
            캐릭터["어그로배율"] *= 배율
        elif isinstance(변동값, (int, float)):
            캐릭터["어그로"] += 변동값 * _고정어그로_배율(캐릭터, 변동값)
    elif 변동대상 in ("어그로증가배율", "어그로감소배율") and 배율 is not None:
        캐릭터[변동대상] = 캐릭터.get(변동대상, 1.0) * 배율
    elif 변동대상 in 능력치_이름 and isinstance(변동값, (int, float)):
        캐릭터[변동대상] += 변동값
    elif 변동대상 == "추가공격획득" and isinstance(변동값, (int, float)):
        # 유연함 - 레벨업 끝의 추가공격_계산이 직업스타일 성장과 합산한다
        캐릭터["추가공격획득"] = 캐릭터.get("추가공격획득", 0) + 변동값
    elif 변동대상 in 리스트형_변동대상:
        if 변동값 not in 캐릭터[변동대상]:
            캐릭터[변동대상].append(변동값)
    elif "약점스탯보너스" in 효과:
        약점스탯 = 캐릭터.get("약점스탯")
        if 약점스탯 is not None:
            캐릭터[약점스탯] += 효과["약점스탯보너스"]
    elif "약점스탯상한" in 효과:
        # 약점증가(사용자 결정 2026-10-20): 약점이 된 능력치를 즉시 상한(8)으로 내린다
        for 이름 in 캐릭터데이터.약점스탯_목록(캐릭터):
            캐릭터[이름] = min(캐릭터[이름], 효과["약점스탯상한"])
    # 그 외의 변동대상(AC, 데미지보너스, 명중률보너스, 방어력, 보호률,
    # 속도 등)은 여기서 처리하지 않는다.


def 특성_부여(캐릭터, 특성이름, 특성정의=None):
    """ "보유특성"에 이름을 추가하고(이미 있으면 건너뜀) 특성정의를
    주면 즉시 효과까지 반영한다. 캐릭터 생성/레벨업/퍽 처리 여러
    곳에서 반복되던 "추가 + 효과 적용" 패턴을 한 곳으로 모은 것."""
    if 특성이름 not in 캐릭터["보유특성"]:
        캐릭터["보유특성"].append(특성이름)
    if 특성정의 is not None:
        특성_효과_적용(캐릭터, 특성정의)


def 특성_제거(캐릭터, 특성이름, 특성정의=None):
    """특성_부여의 반대 - "보유특성"에서 빼고, 특성정의를 주면 즉시 반영됐던
    효과(어그로/어그로배율, 능력치 고정값, 리스트형, "가용무기")를 되돌린다. 전투 스타일 교체와
    대체특성(character_levelup_system._스타일_교체/_대체특성_제거)에 쓴다."""
    if 특성이름 in 캐릭터["보유특성"]:
        캐릭터["보유특성"].remove(특성이름)
    if 특성정의 is None:
        return
    for 무기 in 특성정의.get(
        "가용무기", []
    ):  # 광검 마스터리(검귀의 도 마스터리가 뺀다 #330)
        if 무기 in 캐릭터.get("가용무기", []):
            캐릭터["가용무기"].remove(무기)
    효과 = 특성정의.get("효과") or []
    if isinstance(효과, dict):
        효과 = [효과]
    for 항목 in 효과:
        변동대상 = 항목.get("변동대상")
        변동값 = 항목.get("변동값")
        if 변동대상 == "어그로":
            if 항목.get("배율") is not None:
                캐릭터["어그로배율"] /= 항목["배율"]
            elif isinstance(변동값, (int, float)):
                캐릭터["어그로"] -= 변동값 * _고정어그로_배율(캐릭터, 변동값)
        elif 변동대상 in ("어그로증가배율", "어그로감소배율") and 항목.get("배율"):
            캐릭터[변동대상] = 캐릭터.get(변동대상, 1.0) / 항목["배율"]
        elif 변동대상 in 능력치_이름 and isinstance(변동값, (int, float)):
            캐릭터[변동대상] -= 변동값
        elif 변동대상 in 리스트형_변동대상 and 변동값 in 캐릭터[변동대상]:
            캐릭터[변동대상].remove(변동값)


def 특성_효과_적용(캐릭터, 특성정의):
    """특성정의(job_ability_XX.py "특성목록"의 항목 하나)를 읽어서 즉시
    반영이 필요한 부분만 적용한다.

    - "효과"는 딕셔너리 하나거나 리스트일 수 있다 (job_ability_format.py
      참고). 각 항목을 효과_즉시_적용으로 반영한다.
    - "민첩상한해제"는 "효과"와 별개인 최상위 키다(예: "경갑숙련"의
      "민첩상한해제": ["경갑"]). 여기 적힌 재질을 캐릭터["민첩상한해제"]
      목록에 추가한다 (equipment_system.py 민첩상한_계산이 참고).
    - "가용무기"도 최상위 키다(무기 종류 리스트, 예: "광검 마스터리"의 ["광검"]).
      캐릭터["가용무기"]에 추가한다(equipment_system.장착_가능여부가 참고)."""
    효과 = 특성정의.get("효과")
    # 방어구 숙련 효과는 5부위가 모두 그 재질일 때만 발동하므로 영구 반영하지
    # 않는다(equipment_system.방어구숙련_발동, combat.traits가 그때그때 계산).
    if 특성정의.get("방어구조건"):
        효과 = None
    if 효과 is not None:
        if isinstance(효과, dict):
            효과 = [효과]
        for 항목 in 효과:
            효과_즉시_적용(캐릭터, 항목)

    for 재질 in 특성정의.get("민첩상한해제", []):
        if 재질 not in 캐릭터["민첩상한해제"]:
            캐릭터["민첩상한해제"].append(재질)

    # 쓸 수 있는 무기 종류를 늘린다
    for 무기 in 특성정의.get("가용무기", []):
        if 무기 not in 캐릭터.setdefault("가용무기", []):
            캐릭터["가용무기"].append(무기)


def 특성_전환(캐릭터, 특성이름):
    """토글 특성(프렌지 #247)을 켜거나 끈다 - 캐릭터 "켜진특성"(선택 칸, 없으면 다 꺼짐)에 넣고 뺀다.
    켜졌으면 True. 전투 [스킬]과 던전 [스킬]의 "전환스킬"이 함께 쓴다."""
    켜진 = 캐릭터.setdefault("켜진특성", [])
    if 특성이름 in 켜진:
        켜진.remove(특성이름)
        return False
    켜진.append(특성이름)
    return True
