# 업적 시스템
# =====================
# 메뉴 [업적]의 판정과 보상. 업적 목록은 game/data/achievement/achievement_list.py.
# 진행도에 남기는 것(세이브에 들어간다):
#   "업적기록": {"일반전투승리": n, "보스전투승리": n} - ctl_rewards.전투_결과_정리가 센다.
#               승리 = "아군승리" 또는 "적도망"(적이 모두 도망침). 패배/내가 도망친 전투는 세지 않는다.
#               보스 = 보스전투 오브젝트로 시작한 전투(같은 보스를 다시 이겨도 센다).
#   "받은업적": [업적 ID, ...] - 보상을 받은 업적.
# 나머지 조건(플레이어 레벨, 몬스터 도감, 오브젝트 클리어)은 이미 있는 진행도 값을 읽는다 -
# 그래서 옛 세이브도 레벨/세리아 구출은 불러오자마자 달성으로 보인다.
# 보상은 골드, 아이템(장비/포션/재료/소모품), 랜덤장비(부위·레어도에서 하나) - 양식은 achievement_list.py.
# 받은 아이템은 소지품에 넣고 도감에도 등록한다. 줄 수 없는 보상(카탈로그에 없는 이름, 후보가 없는
# 랜덤장비)은 받음으로 적기 전에 ValueError - 보상이 조용히 사라지지 않게.

from game.system import rng

from game.data.achievement.achievement_list import 이름있는_보상
from game.system import collection_system, player_system, shop_system

조건_종류 = (
    "플레이어레벨",
    "몬스터도감",
    "일반전투승리",
    "보스전투승리",
    "오브젝트클리어",
)


def 빈_업적기록():
    return {"일반전투승리": 0, "보스전투승리": 0}


def 빈_진행기록():
    """새 게임 진행도에 더할 도감/업적 칸."""
    return {
        "도감": collection_system.빈_도감(),
        "업적기록": 빈_업적기록(),
        "받은업적": [],
    }


def _업적기록(진행도):
    기록 = 진행도.setdefault("업적기록", 빈_업적기록())
    for 키, 값 in 빈_업적기록().items():
        기록.setdefault(키, 값)
    return 기록


def _받은업적(진행도):
    return 진행도.setdefault("받은업적", [])


def 전투승리_기록(진행도, 보스):
    _업적기록(진행도)["보스전투승리" if 보스 else "일반전투승리"] += 1


def _현재값(진행도, 조건):
    종류 = 조건["종류"]
    if 종류 == "플레이어레벨":
        return 진행도.get("플레이어레벨", 1)
    if 종류 == "몬스터도감":
        return len((진행도.get("도감") or {}).get("몬스터", []))
    if 종류 in ("일반전투승리", "보스전투승리"):
        return _업적기록(진행도)[종류]
    if 종류 == "오브젝트클리어":
        대상 = (조건["던전파일명"], tuple(조건["좌표"]))
        return 1 if 대상 in 진행도.get("클리어한오브젝트", set()) else 0
    raise ValueError(f"모르는 업적 조건 종류: {종류}")


def 진행값(진행도, 업적):
    """(지금 값, 목표) - 지금 값은 목표를 넘지 않게 자른다(화면에 "3/3"처럼 보인다)."""
    목표 = 업적["조건"]["목표"]
    return min(_현재값(진행도, 업적["조건"]), 목표), 목표


def 달성(진행도, 업적):
    값, 목표 = 진행값(진행도, 업적)
    return 값 >= 목표


def 받음(진행도, 업적):
    return 업적["ID"] in _받은업적(진행도)


def 받을_수_있음(진행도, 업적):
    return 달성(진행도, 업적) and not 받음(진행도, 업적)


def 보상_내용(업적):
    """업적 "보상"을 딕셔너리로 - 이름(문자열)이면 이름있는_보상에서 찾는다."""
    보상 = 업적["보상"]
    if isinstance(보상, str):
        if 보상 not in 이름있는_보상:
            raise ValueError(f"모르는 보상 이름: {보상}")
        return 이름있는_보상[보상]
    return 보상


def 보상_이름(업적):
    """화면에 보이는 보상 - 이름있는 보상은 그 이름, 아니면 "10G, 강철 소검" 같은 글."""
    보상 = 업적["보상"]
    if isinstance(보상, str):
        return 보상
    return 보상_문구({"골드": 보상.get("골드", 0), "아이템": 보상.get("아이템", [])})


def 보상_문구(받음):
    """받은 보상 {"골드", "아이템"}을 "10G, 강철 소검, 초보자용 HP 포션 x2"처럼."""
    글 = [f"{받음['골드']}G"] if 받음.get("골드") else []
    글 += [
        이름 if 개수 == 1 else f"{이름} x{개수}"
        for 이름, 개수 in 받음.get("아이템", [])
    ]
    return ", ".join(글)


def 소지품_칸(상점카탈로그, 이름):
    """아이템 이름이 들어갈 소지품 칸(장비/포션/재료/소모품). 카탈로그에 없으면 None."""
    for 대분류, 탭모음 in 상점카탈로그.items():
        for 탭, 아이템들 in 탭모음.items():
            if 이름 in 아이템들:
                return shop_system.소지품_카테고리(대분류, 탭)
    return None


def 랜덤장비_후보(상점카탈로그, 조건):
    """{"부위", "레어도", "이름시작"(선택)}에 맞는 장비 이름들(카탈로그 순서)."""
    아이템들 = 상점카탈로그.get("장비", {}).get(조건["부위"], {})
    return [
        이름
        for 이름, a in 아이템들.items()
        if a.get("레어도") == 조건["레어도"]
        and 이름.startswith(조건.get("이름시작", ""))
    ]


def _줄_아이템(상점카탈로그, 보상):
    """[(이름, 개수, 소지품 칸)] - 랜덤장비는 여기서 하나를 고른다. 줄 수 없으면 ValueError."""
    아이템 = list(보상.get("아이템", []))
    if "랜덤장비" in 보상:
        후보 = 랜덤장비_후보(상점카탈로그, 보상["랜덤장비"])
        if not 후보:
            raise ValueError("보상으로 줄 장비가 아직 없습니다.")
        아이템.append((rng.보상.choice(후보), 1))
    결과 = []
    for 이름, 개수 in 아이템:
        칸 = 소지품_칸(상점카탈로그, 이름)
        if 칸 is None:
            raise ValueError(f"'{이름}'은(는) 아이템 데이터에 없습니다.")
        결과.append((이름, 개수, 칸))
    return 결과


def 보상_받기(진행도, 플레이어, 업적, 상점카탈로그=None):
    """보상을 플레이어 소지품에 넣고 {"골드": n, "아이템": [(이름, 개수), ...]}를 돌려준다.
    아이템은 도감에도 등록한다. 달성 전/이미 받음/줄 수 없는 보상이면 ValueError(받음으로 적지 않는다).
    상점카탈로그는 아이템/랜덤장비 보상에만 필요하다."""
    if 받음(진행도, 업적):
        raise ValueError("이미 보상을 받은 업적입니다.")
    if not 달성(진행도, 업적):
        raise ValueError("아직 달성하지 못한 업적입니다.")
    보상 = 보상_내용(업적)
    아이템 = _줄_아이템(상점카탈로그 or {}, 보상) if set(보상) - {"골드"} else []
    골드 = 보상.get("골드", 0)
    if 골드:
        player_system.골드_추가(플레이어, 골드)
    for 이름, 개수, 칸 in 아이템:
        player_system.아이템_추가(플레이어, 칸, 이름, 개수)
        collection_system.아이템_등록(진행도, 칸, 이름)
    _받은업적(진행도).append(업적["ID"])
    return {"골드": 골드, "아이템": [(이름, 개수) for 이름, 개수, _ in 아이템]}


def 전부_받기(진행도, 플레이어, 업적목록, 상점카탈로그=None):
    """받을 수 있는 보상을 전부 받는다. (받은 업적 수, {"골드": 합, "아이템": [...]}).
    줄 수 없는 보상(후보가 없는 랜덤장비 등)은 건너뛰고 받지 않은 채로 둔다."""
    수 = 0
    합 = {"골드": 0, "아이템": []}
    for 업적 in 업적목록:
        if not 받을_수_있음(진행도, 업적):
            continue
        try:
            받은 = 보상_받기(진행도, 플레이어, 업적, 상점카탈로그)
        except ValueError:
            continue
        합["골드"] += 받은["골드"]
        합["아이템"] += 받은["아이템"]
        수 += 1
    return 수, 합
