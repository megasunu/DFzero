# 전투 승리 후 쓰러뜨린 적마다 "획득골드"와 "드랍표"를 굴린다. 골드는 대부분
# "공식"(몬스터_골드 - 레벨/적등급/보스, 0.7~1.3배 랜덤)이다.
# 데이터 양식은 monster_format.py "몬스터 드랍표 항목 양식"과
# monster_drop.py 머리 설명을 따른다.
#
# "미정"(또는 해석할 수 없는 값)은 골드 0 / 드랍 없음으로 처리한다
# (사용자 결정 2026-09-30) - 발동확률/드랍비율/드랍확률/아이템이름 어느
# 하나라도 "미정"이면 그 항목은 건너뛴다.

import random
from fractions import Fraction

from game.system.combat import formula

# 드랍표 "아이템조건"의 "카테고리" 키워드 -> 장비 카탈로그의 탭들
# ("장비"는 모든 탭 - 무기/방어구/악세서리/특수장비 전체)
조건_카테고리_탭 = {
    "방어구": ["상의", "하의", "어깨", "벨트", "신발"],
}


def _확률값(값):
    """0.3, "1/25" 같은 값을 Fraction으로. "미정" 등 해석 불가면 None."""
    if isinstance(값, bool):
        return None
    if isinstance(값, (int, float)):
        return Fraction(값).limit_denominator()
    if isinstance(값, str):
        try:
            return Fraction(값.strip())
        except (ValueError, ZeroDivisionError):
            return None
    return None


def _차수(몬스터원본):
    return (몬스터원본 or {}).get("차수") or 1


def _골드_수식(식, 몬스터원본):
    """ "레벨×100" 같은 수식을 몬스터의 레벨/차수/능력치로 평가한다(레벨/차수가
    없으면 1 - combat.participants의 몬스터 수식과 같은 가정). 평가할 수 없으면 0."""
    원본 = 몬스터원본 or {}
    컨텍스트 = {"레벨": 원본.get("레벨") or 1, "차수": _차수(원본), "능력치": 원본}
    try:
        값 = formula.수식_평가(식, 컨텍스트)
    except Exception:
        return 0
    if isinstance(값, bool) or not isinstance(값, (int, float)):
        return 0
    return max(0, formula.올림(값))


def _미정인가(값):
    """아직 정하지 않은 데이터 값인가 - None 또는 "미정"(앞뒤 공백 무시). 대체 동작은 game-rules "미정 처리"."""
    return 값 is None or (isinstance(값, str) and 값.strip() == "미정")


def 골드_굴림(획득골드, 몬스터원본=None):
    """ "1~10" -> 1~10 균등, 정수 -> 그 값, "레벨×100" 같은 수식 -> 몬스터원본의
    레벨/차수로 평가, "미정"/None/해석 불가 -> 0."""
    if isinstance(획득골드, bool):
        return 0
    if isinstance(획득골드, int):
        return max(0, 획득골드)
    if not isinstance(획득골드, str):
        return 0
    if _미정인가(획득골드):
        return 0
    조각 = 획득골드.split("~")
    try:
        숫자들 = [int(x.strip()) for x in 조각]
    except ValueError:
        return 0 if len(조각) > 1 else _골드_수식(획득골드, 몬스터원본)
    if len(숫자들) == 1:
        return max(0, 숫자들[0])
    if len(숫자들) != 2 or 숫자들[0] > 숫자들[1]:
        return 0
    return max(0, random.randint(숫자들[0], 숫자들[1]))


# 골드 공식 - (10 + 레벨) × 등급배수 × 보스배수 × 랜덤(0.7~1.3) (monster_format.py 참고)
골드_기본 = 10
등급배수 = {"일반": 1, "엘리트": 1.5, "네임드": 2}
보스배수 = 2
골드_랜덤범위 = (0.7, 1.3)


def 공식_골드(몬스터원본):
    """랜덤을 곱하기 전 골드 공식 값. 등급이 "미정"/없음이면 일반(1배)."""
    원본 = 몬스터원본 or {}
    레벨 = 원본.get("레벨") or 1
    배수 = 등급배수.get(원본.get("적등급"), 1)
    if 원본.get("칭호") == "보스":
        배수 *= 보스배수
    return (골드_기본 + 레벨) * 배수


def 몬스터_골드(몬스터원본):
    """몬스터 한 마리가 주는 골드. "획득골드"가 "공식"이면 골드 공식, 아니면
    골드_굴림(수식/범위/고정값) - 어느 쪽이든 랜덤(0.7~1.3)을 곱해 올림한다."""
    획득골드 = (몬스터원본 or {}).get("획득골드")
    if 획득골드 == "공식":
        기본 = 공식_골드(몬스터원본)
    else:
        기본 = 골드_굴림(획득골드, 몬스터원본)
    if 기본 <= 0:
        return 0
    return formula.올림(기본 * random.uniform(*골드_랜덤범위))


def _통과(확률):
    return 확률 is not None and random.random() < 확률


def _조건_후보(조건, 장비카탈로그):
    if 조건.get("카테고리") == "장비":
        탭들 = list(장비카탈로그)
    else:
        탭들 = 조건_카테고리_탭.get(조건.get("카테고리"), [])
    후보 = []
    for 탭 in 탭들:
        for 이름, 아이템 in 장비카탈로그.get(탭, {}).items():
            if "마봉능력" in 아이템:  # 봉인을 푼 마법의 장비는 드랍/항아리로 안 나온다
                continue
            if "레어도" in 조건 and 아이템.get("레어도") != 조건["레어도"]:
                continue
            if "티어" in 조건 and 아이템.get("티어") != 조건["티어"]:
                continue
            후보.append(이름)
    return 후보


def 레어도_장비_뽑기(장비카탈로그, 레어도):
    """그 레어도 장비 전체(모든 부위 탭)에서 하나를 고르게 뽑아 이름을 돌려준다.
    그 레어도 장비가 없으면 None(항아리 - ctl_potion.항아리_열기)."""
    후보 = list(
        dict.fromkeys(_조건_후보({"카테고리": "장비", "레어도": 레어도}, 장비카탈로그))
    )
    return random.choice(후보) if 후보 else None


def _항목_아이템(항목, 장비카탈로그):
    """드랍표 항목 하나에서 아이템 이름 하나를 정한다(없으면 None)."""
    if "아이템이름" in 항목:
        이름 = 항목["아이템이름"]
        return None if _미정인가(이름) else 이름
    조건 = 항목.get("아이템조건")
    if isinstance(조건, dict):
        후보 = _조건_후보(조건, 장비카탈로그)
        return random.choice(후보) if 후보 else None
    return None


def _드랍표_본문(드랍표, 차수):
    """ "타입": "차수별"이면 잡은 몬스터의 차수에 맞는 드랍표를 고른다(없으면 빈 표)."""
    if 드랍표.get("타입") == "차수별":
        return (드랍표.get("차수표") or {}).get(차수) or {}
    return 드랍표


# 드랍표 항목이 다른 드랍표를 가리킬 수 있다({"드랍표": 이름, "드랍비율"/"드랍확률"}) -
# 그 항목이 뽑히면 가리킨 표를 굴린다. 잘못된 데이터로 서로를 가리켜도 멈추게 깊이를 제한한다
# (test_data_integrity가 순환을 따로 막는다).
최대_중첩깊이 = 5


def _항목_아이템들(항목, 장비카탈로그, 차수, 드랍표_모음, 깊이):
    """드랍표 항목 하나에서 나온 아이템 이름 리스트. "드랍표" 항목은 그 표를 굴린다."""
    if "드랍표" in 항목:
        하위 = (드랍표_모음 or {}).get(항목["드랍표"])
        if 하위 is None or 깊이 >= 최대_중첩깊이:
            return []
        return 드랍표_굴림(하위, 장비카탈로그, 차수, 드랍표_모음, 깊이 + 1)
    이름 = _항목_아이템(항목, 장비카탈로그)
    return [이름] if 이름 else []


def 드랍표_굴림(드랍표, 장비카탈로그, 차수=1, 드랍표_모음=None, 깊이=0):
    """드랍표 본문(monster_drop.py 드랍표_모음의 값) 하나를 굴려 나온
    아이템 이름 리스트를 돌려준다. "차수별"이면 차수에 맞는 표를 굴린다.
    다른 표를 가리키는 항목은 드랍표_모음에서 찾아 굴린다(없으면 아무것도 안 준다)."""
    드랍표 = _드랍표_본문(드랍표, 차수)
    항목들 = 드랍표.get("아이템", [])
    if 드랍표.get("타입") == "가중형":
        후보 = [(항목, _확률값(항목.get("드랍비율"))) for 항목 in 항목들]
        후보 = [(항목, w) for 항목, w in 후보 if w is not None and w > 0]
        if not 후보:
            return []
        항목 = random.choices(
            [h for h, _ in 후보], weights=[float(w) for _, w in 후보], k=1
        )[0]
        return _항목_아이템들(항목, 장비카탈로그, 차수, 드랍표_모음, 깊이)
    if 드랍표.get("타입") == "독립형":
        결과 = []
        for 항목 in 항목들:
            if _통과(_확률값(항목.get("드랍확률"))):
                결과.extend(_항목_아이템들(항목, 장비카탈로그, 차수, 드랍표_모음, 깊이))
        return 결과
    return []


def 몬스터_전리품(몬스터원본, 드랍표_모음, 장비카탈로그):
    """몬스터 한 마리의 (골드, [아이템 이름...])."""
    골드 = 몬스터_골드(몬스터원본)
    아이템들 = []
    for 참조 in 몬스터원본.get("드랍표") or []:
        드랍표 = 드랍표_모음.get(참조.get("이름"))
        if 드랍표 is None:
            continue
        if _통과(_확률값(참조.get("발동확률"))):
            아이템들.extend(
                드랍표_굴림(드랍표, 장비카탈로그, _차수(몬스터원본), 드랍표_모음)
            )
    return 골드, 아이템들


def 전리품_판정(몬스터원본목록, 드랍표_모음, 장비카탈로그):
    """쓰러뜨린 몬스터 전부의 전리품. {"골드": 합계, "아이템": [(이름, 개수), ...]}
    - 아이템은 처음 나온 순서대로, 같은 이름은 개수로 묶는다."""
    골드합 = 0
    개수 = {}
    for 원본 in 몬스터원본목록:
        골드, 아이템들 = 몬스터_전리품(원본, 드랍표_모음, 장비카탈로그)
        골드합 += 골드
        for 이름 in 아이템들:
            개수[이름] = 개수.get(이름, 0) + 1
    return {"골드": 골드합, "아이템": list(개수.items())}


# =====================================================
# 전투 보상 - 드랍표 후보 중 3칸을 보여주고 1개를 고른다
# =====================================================
# 무작위 드랍(전리품_판정)과 별개로 승리할 때마다 주는 확정 보상이다.
# 후보는 몬스터마다 따로 넣는다(같은 드랍표의 몬스터가 둘이면 같은 아이템이
# 두 번 들어간다). 가중치는 드랍표 안의 "드랍비율"/"드랍확률"만 쓰고 몬스터 쪽
# "발동확률"은 보지 않는다(확정 보상이므로). "아이템조건" 항목은 조건에 맞는
# 아이템 전부로 풀고 그 항목의 가중치를 똑같이 나눈다. 다른 드랍표를 가리키는 항목은
# 그 표의 후보로 풀고 항목의 가중치를 그 표 안의 비율대로 나눈다. 보상은 장비만이라 장비가
# 아닌 후보는 ctl_rewards._전투_보상_준비가 뺀다.

보상_칸수 = 3


def _표_후보(드랍표, 차수, 드랍표_모음, 장비카탈로그, 깊이=0):
    """드랍표 하나의 [(아이템이름, 가중치), ...] - 가중치 없는("미정") 항목은 뺀다."""
    드랍표 = _드랍표_본문(드랍표, 차수)
    키 = "드랍비율" if 드랍표.get("타입") == "가중형" else "드랍확률"
    후보 = []
    for 항목 in 드랍표.get("아이템", []):
        가중치 = _확률값(항목.get(키))
        if 가중치 is None or 가중치 <= 0:
            continue
        if "드랍표" in 항목:
            하위 = 드랍표_모음.get(항목["드랍표"])
            if 하위 is None or 깊이 >= 최대_중첩깊이:
                continue
            하위후보 = _표_후보(하위, 차수, 드랍표_모음, 장비카탈로그, 깊이 + 1)
            합 = sum(w for _, w in 하위후보)
            후보 += [(이름, float(가중치) * w / 합) for 이름, w in 하위후보 if 합]
            continue
        if "아이템이름" in 항목:
            이름 = 항목["아이템이름"]
            if not _미정인가(이름):
                후보.append((이름, float(가중치)))
            continue
        조건 = 항목.get("아이템조건")
        이름들 = _조건_후보(조건, 장비카탈로그) if isinstance(조건, dict) else []
        for 이름 in 이름들:
            후보.append((이름, float(가중치) / len(이름들)))
    return 후보


def 보상_후보목록(몬스터원본목록, 드랍표_모음, 장비카탈로그):
    """[(아이템이름, 가중치), ...] - 가중치 없는("미정") 항목은 뺀다."""
    후보 = []
    for 원본 in 몬스터원본목록:
        for 참조 in 원본.get("드랍표") or []:
            드랍표 = 드랍표_모음.get(참조.get("이름"))
            if 드랍표 is not None:
                후보 += _표_후보(드랍표, _차수(원본), 드랍표_모음, 장비카탈로그)
    return 후보


def 보상_뽑기(후보, 칸수=보상_칸수):
    """후보(보상_후보목록)에서 가중치로 칸수만큼 뽑는다. 한 번 뽑힌 후보 항목은
    다시 뽑지 않는다(같은 아이템이 여러 항목에 있으면 여러 칸에 나올 수 있다).
    후보가 모자라면 남는 칸은 None."""
    남은 = list(후보)
    결과 = []
    for _ in range(칸수):
        if not 남은:
            결과.append(None)
            continue
        번호 = random.choices(range(len(남은)), weights=[w for _, w in 남은], k=1)[0]
        결과.append(남은.pop(번호)[0])
    return 결과
