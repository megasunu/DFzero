# =====================
# 장비 해체 시스템
# =====================
# 상점 [해체]: 장비를 분해해 재료(item_materials.py)를 얻는다. 장비 1개당
#   - 레어도에 맞는 소울 1개(커먼 소울 ~ 에픽 소울)
#   - 큐브 조각 - 무기 10개, 방어구 2개, 악세서리/특수장비 3개. 조각마다 색을 따로
#     굴린다: 무색 80%, 적색/청색/백색/흑색 5%씩(황금은 해체로 나오지 않는다).
# 장착 중인 장비(파티원 + 모험단 숙소)는 해체할 수 없다(shop_system.판매목록과 같은
# 기준). 레어도에 맞는 소울이 없는 장비(예: "치트")도 해체할 수 없다.

from game.data import common_names
from game.system import rng

from game.system import player_system
from game.system import shop_system

# 해체하면 소울이 나오는 레어도 - 크로니클은 소울을 주지 않는다(사용자 규칙)
소울_레어도 = [r for r in common_names.레어도_순서 if r != "크로니클"]

조각개수_무기 = 10
조각개수_방어구 = 2
조각개수_악세서리_특수 = 3

# (색, 확률) - 합 1.0. 황금은 0%라 넣지 않는다.
조각_색확률 = [
    ("무색", 0.8),
    ("적색", 0.05),
    ("청색", 0.05),
    ("백색", 0.05),
    ("흑색", 0.05),
]


def 소울_이름(아이템):
    레어도 = 아이템.get("레어도")
    return f"{레어도} 소울" if 레어도 in 소울_레어도 else None


def 조각_개수(탭):
    if 탭 == "무기":
        return 조각개수_무기
    if 탭 in common_names.방어구_부위:
        return 조각개수_방어구
    return 조각개수_악세서리_특수


전체_탭 = "전체"


def 해체_탭목록():
    """해체 화면 탭 - [전체] + 장비 부위 탭."""
    return [전체_탭] + list(shop_system.장비_탭순서)


def 해체목록(플레이어, 카탈로그, 탭):
    """[(아이템데이터, 해체가능수량, 부위탭), ...] - 장착 중이 아닌 보유 장비 중 소울이
    있는 것. 탭이 "전체"면 모든 부위(부위 탭 순서)."""
    탭들 = shop_system.장비_탭순서 if 탭 == 전체_탭 else [탭]
    return [
        (아이템, 개수, 부위)
        for 부위 in 탭들
        for 아이템, 개수 in shop_system.판매목록(플레이어, 카탈로그, "장비", 부위)
        if 소울_이름(아이템)
    ]


def 해체_처리(플레이어, 카탈로그, 탭, 이름, 수량):
    """장비를 수량만큼 해체한다. 얻은 재료 {이름: 개수}(소울 먼저, 조각은 색 순서)를
    반환한다. 해체할 수 없으면 아무것도 바꾸지 않고 ValueError."""
    if not isinstance(수량, int) or 수량 < 1:
        raise ValueError("수량은 1 이상이어야 한다.")
    가능 = {
        아이템["이름"]: (아이템, 개수)
        for 아이템, 개수, _ in 해체목록(플레이어, 카탈로그, 탭)
    }
    if 이름 not in 가능:
        raise ValueError(f"'{이름}'은(는) 해체할 수 없다.")
    아이템, 개수 = 가능[이름]
    if 수량 > 개수:
        raise ValueError(f"해체할 수 있는 수량은 {개수}개까지다.")

    색들 = [색 for 색, _ in 조각_색확률]
    확률들 = [확률 for _, 확률 in 조각_색확률]
    뽑힌색 = rng.보상.choices(색들, weights=확률들, k=조각_개수(탭) * 수량)
    결과 = {소울_이름(아이템): 수량}
    for 색 in 색들:
        if 뽑힌색.count(색):
            결과[f"{색} 큐브 조각"] = 뽑힌색.count(색)

    장비칸 = 플레이어["소지품"]["장비"]
    장비칸[이름] -= 수량
    if 장비칸[이름] <= 0:
        del 장비칸[이름]
    for 재료, 재료개수 in 결과.items():
        player_system.아이템_추가(플레이어, "재료", 재료, 재료개수)
    return 결과


def 일괄해체_대상(플레이어, 카탈로그, 레어도, 탭):
    """[(이름, 수량, 부위탭), ...] - 그 레어도 + 부위(또는 "전체")의 해체 가능한 장비 전부."""
    return [
        (아이템["이름"], 개수, 부위)
        for 아이템, 개수, 부위 in 해체목록(플레이어, 카탈로그, 탭)
        if 아이템.get("레어도") == 레어도
    ]


def 일괄해체(플레이어, 카탈로그, 레어도, 탭):
    """일괄해체_대상을 전부 해체한다. (해체한 장비 수, {재료: 개수})를 반환한다.
    대상이 없으면 ValueError."""
    대상 = 일괄해체_대상(플레이어, 카탈로그, 레어도, 탭)
    if not 대상:
        raise ValueError("조건에 맞는 해체할 장비가 없다.")
    합계 = {}
    for 이름, 수량, 부위 in 대상:
        for 재료, 개수 in 해체_처리(플레이어, 카탈로그, 부위, 이름, 수량).items():
            합계[재료] = 합계.get(재료, 0) + 개수
    # 소울 먼저, 조각은 색 순서
    순서 = [f"{r} 소울" for r in 소울_레어도] + [
        f"{색} 큐브 조각" for 색, _ in 조각_색확률
    ]
    return sum(수량 for _, 수량, _ in 대상), {k: 합계[k] for k in 순서 if k in 합계}
