# 이번 작업에서 실제로 구현한 범위 (중요 - 검토 시 참고)
# -----------------------------------------------------
# - "분류"의 6종(공격스킬/버프스킬/자원스킬/소환스킬/해제스킬/회복스킬)과
#   공격스킬의 "분할공격"/"지속공격" 태그, "효과" 하위 5종(상태이상/자동상태/
#   지속피해/아군버프/버프해제·디버프해제), "조건부효과" 5종(자원보유/적상태/
#   아군상태/HP비율이하/특성보유)을 전부 다룬다.
# - 행동자원/MP/자원소모 소비, 턴당사용제한/전투당횟수/휴식당횟수 검사
#   (휴식당횟수는 캐릭터 "횟수제한스킬"["휴식제한스킬"]에 남은 횟수를
#   저장 - 휴식_남은횟수 참고), 타겟 자동 확장
#   (중심 대상 1개만 받아 적3체/적전체/적랜덤 등을 여기서 계산), 조건부효과
#   오버라이드(데미지보너스/명중보너스/MP소모/자원소모/타겟/타겟제한/
#   일반공격취급/버프해제·디버프해제/상태이상해제)를 구현했다.
#   ("상태이상해제"는 명중한 대상의 상태이상 목록에서 그 이름을 지운다.
#   상태이상_해제() 참고.)
# - "버프획득"/"자원획득"/"자원소모"의 이름은 buff.py/debuff.py/
#   skill_effects.py(기술효과목록 + 클래스자원목록)를 이름으로 합쳐서 찾는다
#   (효과정의_조회 참고). 데이터에는 출처 표시가 없으므로, 이름이
#   같은 항목이 여러 목록에 동시에 있으면 아래 효과정의_조회()가 정한 순서
#   (기술효과 → 버프 → 디버프)로 하나를 고른다.
# - buff.py/debuff.py의 "타입":"스택버프"(중첩:True) 항목은 문서화된 설계
#   의도대로 "인스턴스형"으로 추적한다 - 이름있는효과_부여()가 이런 항목은
#   기존 인스턴스에 병합하지 않고 매번 새 인스턴스를 추가한다. 먼저 받은
#   인스턴스가 먼저 만료되는 건 combat.flow.턴_시작_처리가 각 인스턴스의
#   "지속턴"을 개별적으로 줄이기 때문에 별도 처리 없이 자연히 성립한다.
#   (skill_effects.py 기술효과 자원류는 "중첩" 필드에 병합한다 - 그쪽은
#   buff.py가 말하는 "스택버프"가 아니라 자원 개수 카운터라서 인스턴스
#   분리 대상이 아니다.)
# - status_effects.py 상태이상(기절/공중에뜸/수면/빙결/석화/둔화/구속/암흑/
#   혼란/저주/은신/이목집중/집중/출혈/중독/화상/감전)의 실제 동작은
#   combat 패키지에서 처리한다(모듈 docstring 참고) - 이 파일은 "상태이상"/
#   "자동상태" 효과가 그 이름들을 걸 때 전투상태["상태이상정의"]를 찾아
#   "중첩":True인 항목이면 인스턴스를 병합(자원류와 같은 방식)하고,
#   "부여버프"(석화의 피해량감소 등)가 있으면 그 버프도 같이 준다
#   (상태이상_부여 참고). "혼란"의 "행동제한"(일반공격만)은 사용_가능여부가
#   강제하고, "은신"의 "지정불가"는 타겟_확장이 단일 지정을 막는다. "타겟반전"
#   (혼란)의 실제 "반대 진영 강제 타겟팅"은 UI/AI가 결정할 몫이라 플래그
#   조회 이상은 만들지 않았다 (TODO). "출혈"/"중독"/"화상"/"감전"(지속피해형,
#   "중첩":True)은 buff.py 스택버프와 같은 인스턴스형으로 부여한다
#   - 같은 이름이 다시 걸리면 병합 대신 새 인스턴스를 추가한다.
#
# - "지속공격"(job_skill_format.py <지속공격 양식>, 예: 보이드/나이트
#   할로우)은 매 턴 자동 발동한다. status_effects.py 4분류
#   DOT와 달리 "대상"이 아니라 "시전자의 턴이 끝날 때" 발동해야 해서
#   (job_skill_format.py 설명), combat.flow.턴_종료_처리(대상 기준)
#   안에서는 처리할 수 없다 - combat 패키지는 skill_system.py를
#   부르지 않는 구조라 그 안에 넣을 수도 없다. 그래서 이 파일의
#   skill_system.다음_턴()이 combat.flow.다음_턴()을 감싸고,
#   턴이 넘어가기 직전에 방금 턴이 끝난 시전자가 걸어둔 지속공격들을
#   찾아 _지속공격_발동()으로 실행한다(내부적으로 공격_1회를 그대로
#   재사용해 효과/조건부효과/치명타 등을 똑같이 반영한다). "매턴명중굴림"이
#   False면 최초 1회만 판정해서 그 결과를 지속턴 동안 그대로 재사용하고,
#   True면 매번 새로 판정한다 - 어느 쪽이든 판정에 실패하면 그 즉시
