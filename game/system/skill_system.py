# 파일을 불러오지 않는다(순환 참조 방지). 실제 사용 순서: 호출하는 쪽
# (게임 루프/UI)이 combat.flow.전투_시작()으로 전투상태를 만든 뒤, 각
# 아군 턴에 이 파일의 스킬_실행()을 직접 부른다.
