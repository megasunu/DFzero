def 능력치_보정치(캐릭터, 능력치이름):
    """D&D 5판 방식 능력치 보정치. (능력치값 - 10) // 2
    예) 근력 8 → -1, 근력 10 → 0, 근력 18 → 4"""
    능력치값 = 캐릭터[능력치이름]
    return (능력치값 - 10) // 2


def 약점스탯_목록(캐릭터):
    """지금 약점인 능력치들 - "약점제거" 특성이 있으면 약점이 아니다(사용자 결정). 몬스터는 없다."""
    if "약점제거" in (캐릭터.get("보유특성") or []):
        return []
    약점 = 캐릭터.get("약점스탯")
    return [약점] if 약점 else []


def 차수_계산(캐릭터):
    """레벨 1~5는 1차수(비전직), 6~10은 2차수(1차전직), 11~15는 3차수(각성),
    16~20은 4차수(2차각성)다 (job_level_format.py 참고)."""
    return ((캐릭터["레벨"] - 1) // 5) + 1


def 최대HP_공식(레벨, 레벨당체력증가, 건강보정치):
    """기본체력(레벨당체력증가 + 건강보정치) + 올림(레벨 x 기본체력 / 2), 최소 1.
    올림은 총합에 한 번만 한다(레벨마다 0.5가 쌓이지 않는다). 아군과 몬스터
    역할군 공통(job_level_format.py / monster_format.py 참고)."""
    기본체력 = 레벨당체력증가 + 건강보정치
    return max(1, 기본체력 + math.ceil(레벨 * 기본체력 / 2))


def 기본최대HP_계산(캐릭터, 레벨당체력증가):
    """HP 계산 - 최대HP_공식(레벨, 레벨당체력증가, 건강보정치).

    "레벨당체력증가"는 캐릭터가 속한 1차 계열 job_level_XX.py 레벨 1
    항목에만 있는 값이라, 2차전직 이후에도 호출하는 쪽이 원래 1차 계열의
    값을 계속 넘겨줘야 한다. 장비 건강 반영(equipment_system.장비반영_최대HP)이
    다시 계산할 수 있게 캐릭터 "레벨당체력증가"에도 남긴다."""
    캐릭터["레벨당체력증가"] = 레벨당체력증가
    return 최대HP_공식(캐릭터["레벨"], 레벨당체력증가, 능력치_보정치(캐릭터, "건강"))


def 주문시전능력치(캐릭터):
    """캐릭터의 주문시전능력치. 직업이 따로 지정하지 않았으면(None) 지능이다
    (job_level_format.py "주문시전능력치" 참고)."""
    return 캐릭터.get("주문시전능력치") or "지능"


def 스타일성장횟수(레벨):
    """직업스타일_성장레벨(6/11/16/21) 중 이 레벨까지 도달한 수."""
    return sum(1 for 성장레벨 in 직업스타일_성장레벨 if 레벨 >= 성장레벨)


def 직업스타일_성장값(캐릭터, 항목):
    """캐릭터 직업스타일의 "성장"[항목] 수식("스타일성장횟수"를 쓴다)을 계산한다.
    항목: "추가공격"/"최대MP". 없으면 0."""
    정의 = 직업스타일.get(캐릭터.get("직업스타일") or "비전직") or {}
    식 = (정의.get("성장") or {}).get(항목)
    if 식 is None:
        return 0
    return formula.수식_평가(
        식,
        {
            "스타일성장횟수": 스타일성장횟수(캐릭터["레벨"]),
            "레벨": 캐릭터["레벨"],
            "차수": 차수_계산(캐릭터),
        },
    )


def 추가공격_계산(캐릭터):
    """추가공격 = 직업스타일 성장 추가공격 + "추가공격획득"(행동획득 레벨업)."""
    return int(직업스타일_성장값(캐릭터, "추가공격")) + 캐릭터.get("추가공격획득", 0)


def 기본최대MP_계산(캐릭터):
    """프로젝트 공식 최대MP = 25 + (레벨-1) × (3 + 주문시전보정치) + 직업스타일
    성장 최대MP(캐스터 6/11/16/21레벨마다 +10).
    레벨 1은 25, 레벨업마다 3 + 주문시전보정치만큼 오른다.
    HP와 마찬가지로 현재 능력치를 따른다 - 생성/레벨업/전직 때마다 다시 부른다
    (equipment_system.장비반영_최대MP도 이 전제로 보정치 차이만 더한다)."""
    보정치 = 능력치_보정치(캐릭터, 주문시전능력치(캐릭터))
    return (
        25
        + (캐릭터["레벨"] - 1) * (3 + 보정치)
        + int(직업스타일_성장값(캐릭터, "최대MP"))
    )


