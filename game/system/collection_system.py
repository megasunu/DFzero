# 장비 선택형 필터 - {"상위", "중위", "하위", "레어도"}
# -----------------------------------------------------
장비_상위분류 = {
    "무기": ["무기"],
    "방어구": list(equipment_system.방어구_슬롯),
    "악세서리": ["목걸이", "반지", "팔찌"],
    "특수장비": ["보조장비", "마법석", "귀걸이"],
}
장비필터_순서 = ("상위", "중위", "하위", "레어도")
장비필터_기본 = dict.fromkeys(장비필터_순서, 전체_탭)


def _고름(값):
    return 값 not in (None, 전체_탭)


def 장비필터_바꾸기(필터, 키, 값):
    """키를 값으로 바꾼 새 필터. 상위/중위/하위를 바꾸면 그 아래 분류(레어도 빼고)는 전체로."""
    새 = dict(필터)
    새[키] = 값
    if 키 in ("상위", "중위"):
        for 아래 in 장비필터_순서[장비필터_순서.index(키) + 1 : 3]:
            새[아래] = 전체_탭
    return 새


def _무기들(장비카탈로그):
    return 장비_목록(장비카탈로그, "무기")


def 장비필터_선택지(장비카탈로그, 필터):
    """상자마다 고를 수 있는 값([전체] + ...). 고를 수 없는 상자는 []."""
    상위 = 필터.get("상위")
    중위 = 필터.get("중위")
    선택지 = {
        "상위": [전체_탭] + list(장비_상위분류),
        "중위": [],
        "하위": [],
        "레어도": [전체_탭] + 레어도_순서,
    }
    if 상위 == "무기":
        무기들 = _무기들(장비카탈로그)
        직업군들 = equipment_system.무기_직업군_목록(무기들)
        선택지["중위"] = [전체_탭] + 직업군들
        종류 = []
        for 직업군 in [중위] if _고름(중위) else 직업군들:
            종류 += equipment_system.직업군_무기종류(무기들, 직업군)
        선택지["하위"] = [전체_탭] + 종류
    elif 상위 == "방어구":
        선택지["중위"] = [전체_탭] + equipment_system.방어구_재질
        선택지["하위"] = [전체_탭] + 장비_상위분류["방어구"]
    elif 상위 in 장비_상위분류:
        선택지["하위"] = [전체_탭] + 장비_상위분류[상위]
    return 선택지


def 장비필터_일치(아이템, 부위, 필터):
    """부위(카탈로그 탭)의 아이템이 필터를 통과하는지."""
    상위, 중위, 하위 = 필터.get("상위"), 필터.get("중위"), 필터.get("하위")
    if _고름(상위) and 부위 not in 장비_상위분류.get(상위, []):
        return False
    if 부위 == "무기":
        if _고름(중위) and equipment_system.무기_직업군(아이템) != 중위:
            return False
        if _고름(하위) and not equipment_system.분류탭_일치(아이템, 부위, 하위):
            return False
    else:
        if _고름(중위) and not equipment_system.분류탭_일치(아이템, 부위, 중위):
            return False
        if _고름(하위) and 부위 != 하위:
            return False
    return 레어도_일치(아이템, 필터.get("레어도"))


def 장비필터_목록(장비카탈로그, 부위목록, 필터):
    """부위목록(탭 순서) 차례로 필터를 통과한 도감 장비."""
    return [
        a
        for 부위 in 부위목록
        for a in 장비_목록(장비카탈로그, 부위)
        if 장비필터_일치(a, 부위, 필터)
    ]


def 레어도_일치(아이템, 레어도):
    return 레어도 in (None, 전체_탭) or 아이템.get("레어도") == 레어도
