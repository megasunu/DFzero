# 도감 시스템
# =====================
# 메뉴 [도감]의 기록과 목록. 기록은 진행도["도감"] = {대분류: [이름, ...]}이고 세이브에 그대로 들어간다
# (JSON이 담을 수 있게 set이 아니라 등록 순서대로의 리스트).
#
# - 몬스터: 전투에서 처치(도망 제외)했을 때 등록(ctl_rewards.전투_결과_정리). 소분류는 종족(몬스터 "분류").
# - 장비/소모품/재료: 처음 소지품에 들어왔을 때 등록(드랍, 전투 보상, 상점 구매, 항아리, 새 게임/영입 시작 장비).
#   장비는 고르는 상자 4개로 거른다(2026-10-19 사용자 결정, 장비필터_*): 상위(무기/방어구/악세서리/특수장비),
#   중위(무기 직업군, 방어구 재질 - 악세서리/특수장비는 없음), 하위(무기 종류 - 중위로 좁혀짐, 부위), 레어도.
#   모두 "전체"로 시작하고, 상위가 "전체"면 중위/하위는 고를 수 없다. 레어도는 그 등급 장비가 없어도 다 둔다.
#   소모품은 지금 HP/MP 회복포션만, 재료는 몬스터 개인 드랍표에 나오는 재료만 목록에 있다.
#   레어도 "치트" 장비는 사용자 전용이라 도감 목록에 넣지 않는다.
# 등록은 이름만 적는다 - 목록(어떤 항목이 도감에 보이나)은 데이터에서 매번 계산한다.

from game.system import equipment_system

도감_대분류 = ["몬스터", "장비", "소모품", "재료"]

# 소지품 칸 -> 도감 대분류. "소모품" 칸(투척/소환/음식/주류/항아리)은 도감에 없다.
_소지품칸_대분류 = {"장비": "장비", "포션": "소모품", "재료": "재료"}

레어도_순서 = ["커먼", "언커먼", "레어", "유니크", "크로니클", "레전더리", "에픽"]
전체_탭 = "전체"
_제외_레어도 = ("치트",)


def 빈_도감():
    return {대분류: [] for 대분류 in 도감_대분류}


def _기록(진행도):
    도감 = 진행도.setdefault("도감", 빈_도감())
    for 대분류 in 도감_대분류:
        도감.setdefault(대분류, [])
    return 도감


def 등록(진행도, 대분류, 이름):
    """처음이면 등록하고 True, 이미 있으면 False."""
    목록 = _기록(진행도)[대분류]
    if 이름 in 목록:
        return False
    목록.append(이름)
    return True


def 아이템_등록(진행도, 소지품칸, 이름):
    """소지품 칸(장비/포션/재료/...)에 들어온 아이템을 등록한다. 도감에 없는 칸이면 False."""
    대분류 = _소지품칸_대분류.get(소지품칸)
    return 등록(진행도, 대분류, 이름) if 대분류 else False


def 등록됨(진행도, 대분류, 이름):
    return 이름 in _기록(진행도)[대분류]


# ------------------------------------------------------------------ 목록


def 몬스터_종족목록(몬스터목록):
    """몬스터 "분류"(종족)를 처음 나온 순서대로."""
    return list(dict.fromkeys(m["분류"] for m in 몬스터목록.values()))


def 몬스터_목록(몬스터목록, 종족):
    return [m for m in 몬스터목록.values() if m["분류"] == 종족]


def 장비_목록(장비카탈로그, 부위):
    return [
        a
        for a in 장비카탈로그.get(부위, {}).values()
        if a.get("레어도") not in _제외_레어도
        and "마봉능력" not in a  # 봉인을 푼 마법의 장비(1천여 종)는 도감에 없다
    ]


def 소모품_목록(소모품카탈로그):
    """HP/MP 회복포션(카탈로그 순서)."""
    return [
        a
        for a in 소모품카탈로그.get("포션", {}).values()
        if a.get("분류") == "회복포션"
    ]


def _드랍표_아이템이름(표이름, 드랍표모음, 지나온=()):
    if 표이름 in 지나온:
        return []
    표 = 드랍표모음.get(표이름) or {}
    묶음들 = list(표.get("차수표", {}).values()) if "차수표" in 표 else [표]
    이름들 = []
    for 묶음 in 묶음들:
        for 항목 in 묶음.get("아이템", []):
            if "아이템이름" in 항목:
                이름들.append(항목["아이템이름"])
            elif "드랍표" in 항목:
                이름들 += _드랍표_아이템이름(
                    항목["드랍표"], 드랍표모음, 지나온 + (표이름,)
                )
    return 이름들


def 재료_탭목록(재료카탈로그, 몬스터목록, 드랍표모음):
    """{재료 탭: [재료 데이터]} - 몬스터 개인 드랍표(종족 공용 포함)에 나오는 재료만, 카탈로그 순서."""
    드랍 = {
        이름
        for m in 몬스터목록.values()
        for 참조 in m.get("드랍표") or []
        for 이름 in _드랍표_아이템이름(참조["이름"], 드랍표모음)
    }
    결과 = {}
    for 탭, 아이템들 in 재료카탈로그.items():
        목록 = [a for 이름, a in 아이템들.items() if 이름 in 드랍]
        if 목록:
            결과[탭] = 목록
    return 결과


