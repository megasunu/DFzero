# 4인 파티 구성/관리. 캐릭터 능력치/장비는 character_data_system.py/
# equipment_system.py가 담당하고, 여기서는 파티원 목록과 파티 단위
# 조회(생존자/전멸 여부/어그로 합계)만 다룬다. 파티원 데이터는 참조로만
# 갖고 있어 캐릭터를 직접 바꾸면 파티 쪽에도 그대로 반영된다. 골드 등
# 소지품은 player_system.py 소속이다.
#
# 인형(인형사, item_doll.py)은 파티원이 아니라 파티["인형"] 한 칸에 붙는다(없으면 None). 전투에서는
# 아군 5번째 칸으로 들어가고(combat.flow.전투_시작), 마을 휴식이나 전투에서 쓰러지면 사라진다.

from game.system import character_data_system as 캐릭터데이터

파티_최대인원 = 4
_능력치_이름 = ("근력", "민첩", "건강", "지능", "지혜", "매력")


def 빈_파티():
    """파티원이 없는 빈 파티를 만든다."""
    return {"파티원": [], "인형": None}


def 인형_만들기(인형데이터, 레벨, 레벨당체력증가, 능력치증가=0):
    """인형 데이터(item_doll.py 항목 하나)로 파티에 붙일 인형을 만든다 - 캐릭터와 같은 칸을 가진
    딕셔너리(character_data_system.빈_캐릭터)라 전투 계산이 아군 캐릭터와 같은 길로 간다.
    "인형"에 데이터 이름을 남겨 행동표 등은 그때그때 데이터에서 찾는다. HP는 가득 찬 상태."""
    인형 = 캐릭터데이터.빈_캐릭터()
    # 주/보조/약점스탯은 레벨업에만 쓰여 인형에는 의미가 없다 - 캐릭터 칸 모양만 맞춘다(높은 순/낮은 것)
    순서 = sorted(_능력치_이름, key=lambda n: -인형데이터["능력치"][n])
    인형.update(
        {
            "캐릭터명": 인형데이터["이름"],
            "직업": "인형",
            "인형": 인형데이터["이름"],
            "성별": "",
            "전직": None,
            "주스탯": 순서[0],
            "보조스탯": 순서[1],
            "약점스탯": 순서[-1],
            "주문시전능력치": 인형데이터.get("주문시전능력치"),
            "기본AC": 인형데이터.get("기본AC", 10),
            "보유특성": list(인형데이터.get("특성") or []),
            "평타스탯": [],
        }
    )
    인형_갱신(인형, 인형데이터, 레벨, 레벨당체력증가, 능력치증가)
    인형["현재HP"] = 인형["기본최대HP"]
    return 인형


def 인형_갱신(인형, 인형데이터, 레벨, 레벨당체력증가, 능력치증가=0):
    """레벨(= 플레이어 레벨)과 능력치증가(내아내몬)를 다시 반영한다 - 능력치 = 데이터 값 + 증가,
    최대HP = 최대HP_공식(레벨, 레벨당체력증가, 건강 보정치), 속도(이니셔티브) = 민첩 보정치.
    현재HP는 새 최대치를 넘지 않게 자른다(늘어난 최대치만큼 채우지는 않는다)."""
    for 이름 in _능력치_이름:
        인형[이름] = 인형데이터["능력치"][이름] + 능력치증가
    인형["레벨"] = 레벨
    인형["기본최대HP"] = 캐릭터데이터.기본최대HP_계산(인형, 레벨당체력증가)
    인형["기본속도"] = 캐릭터데이터.능력치_보정치(인형, "민첩")
    인형["현재HP"] = min(인형.get("현재HP", 0), 인형["기본최대HP"])


def 파티원_추가(파티, 캐릭터):
    """파티에 캐릭터를 추가한다. 이미 4명이 꽉 찼거나, 같은 캐릭터가
    이미 있으면 ValueError를 낸다."""
    if len(파티["파티원"]) >= 파티_최대인원:
        raise ValueError(f"파티는 최대 {파티_최대인원}명까지만 구성할 수 있다.")
    # "in"은 딕셔너리 값 비교(==)라 이름/직업이 같은 새 캐릭터 둘을 같은
    # 캐릭터로 본다(B4). 같은 객체인지(is)로 비교한다.
    if any(c is 캐릭터 for c in 파티["파티원"]):
        raise ValueError(f"'{캐릭터.get('캐릭터명')}'은(는) 이미 파티에 있다.")
    파티["파티원"].append(캐릭터)


def 파티원_제거(파티, 캐릭터):
    """파티에서 캐릭터를 뺀다. 파티에 없으면 ValueError를 낸다."""
    for i, c in enumerate(파티["파티원"]):
        if c is 캐릭터:
            del 파티["파티원"][i]
            return
    raise ValueError(f"'{캐릭터.get('캐릭터명')}'은(는) 파티에 없다.")


def 생존자_목록(파티):
    """ "현재HP"가 0보다 큰 파티원만 반환한다."""
    return [캐릭터 for 캐릭터 in 파티["파티원"] if 캐릭터["현재HP"] > 0]
