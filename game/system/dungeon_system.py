def _짝_포탈(레지스트리, 대상, 출발, 출발좌표):
    """대상 맵에서 출발 맵으로 돌아가는 연결지역 좌표. 여러 개면 "진입좌표"가
    출발좌표와 같은 것을 고르고, 없으면 첫 번째. 하나도 없으면 None."""
    후보 = [
        (좌표, 연결)
        for 좌표, 연결 in 레지스트리[대상]["연결지역"].items()
        if 연결.get("연결맵") == 출발
    ]
    for 좌표, 연결 in 후보:
        if 연결.get("진입좌표") == 출발좌표:
            return 좌표
    return 후보[0][0] if 후보 else None


def 이어진_맵_배치(레지스트리, 던전파일명):
    """던전파일명의 맵에서 연결지역("#")으로 이어진 다른 던전들을, 몇 단계를
    건너든 이어져 있으면 전부, 포탈 칸이 같은 칸에 겹치도록 놓은 자리를
    돌려준다: [(던전파일명, (dx, dy)), ...] - 그 던전의 (x, y) 칸은 시작 맵
    좌표로 (x + dx, y + dy)에 놓인다. 가까운(먼저 닿는) 맵이 앞에 온다.
    시작 맵 자신과 마을(레지스트리에 없는 연결맵)은 빠진다."""
    배치 = {던전파일명: (0, 0)}
    순서 = []
    할일 = [던전파일명]
    while 할일:
        출발 = 할일.pop(0)
        ox, oy = 배치[출발]
        for (px, py), 연결 in 레지스트리[출발]["연결지역"].items():
            대상 = 연결.get("연결맵")
            if 대상 not in 레지스트리 or 대상 in 배치:
                continue
            짝 = _짝_포탈(레지스트리, 대상, 출발, (px, py))
            if 짝 is None:
                continue
            배치[대상] = (ox + px - 짝[0], oy + py - 짝[1])
            순서.append((대상, 배치[대상]))
            할일.append(대상)
    return 순서
