_방향_이동 = {"위": (0, -1), "아래": (0, 1), "왼쪽": (-1, 0), "오른쪽": (1, 0)}


def 그리드_생성(맵정보):
    """맵정보["지도"]를 좌표별로 고쳐 쓸 수 있는 문자 리스트의 리스트로
    복사한다(오브젝트 클리어/숏컷 해금 등으로 칸이 바뀔 수 있어서)."""
    return [list(행) for 행 in 맵정보["지도"]]


def 칸_문자(그리드, 위치):
    x, y = 위치
    if y < 0 or y >= len(그리드):
        return None
    행 = 그리드[y]
    if x < 0 or x >= len(행):
        return None
    return 행[x]


def _기본_시작좌표(그리드):
    """그리드에서 처음 만나는 이동 가능한 칸을 시작 위치로 쓴다."""
    for y, 행 in enumerate(그리드):
        for x, 문자 in enumerate(행):
            if 문자 in ("O", "#"):
                return (x, y)
    return (0, 0)


def 던전_시작(맵정보, 던전파일명, 시작좌표=None, 진행도=None):
    """던전 진입 시 만드는 상태(게임상태["던전상태"]로 들고 있다가 다시
    넘기면 위치/그리드/걸음수가 이어진다). 던전파일명은 진행도
    ["클리어한오브젝트"] 조회 키. 진행도를 주면 해금상태_적용()을 바로
    실행해 "숏컷" 오브젝트를 최신 상태로 맞춘다.

    시작좌표를 안 주면(연결지역을 거치지 않고, 마을의 [던전 이동]
    목록에서 직접 들어온 경우가 대표적) 맵정보["입장좌표"]를 쓴다.
    "입장좌표"도 없으면(아직 안 정해준 맵) 그리드에서 처음
    만나는 이동 가능 칸을 대신 쓴다(_기본_시작좌표)."""
    그리드 = 그리드_생성(맵정보)
    if 시작좌표 is not None:
        위치 = 시작좌표
    elif 맵정보.get("입장좌표") is not None:
        위치 = 맵정보["입장좌표"]
    else:
        위치 = _기본_시작좌표(그리드)
    던전상태 = {
        "맵정보": 맵정보,
        "던전파일명": 던전파일명,
        "그리드": 그리드,
        "위치": 위치,
        "걸음수": 0,
        "봉절걸음": 0,  # 남은 봉절 걸음(던전스킬 봉절) - 새 던전상태라 나가면 끝난다
        # 쓴 스프레이마다 남은 걸음(None은 던전을 나갈 때까지, #506) - 각각 따로 줄어든다
        "스프레이": [],
    }
    해금상태_적용(던전상태, 진행도)
    return 던전상태


def 해금상태_적용(던전상태, 진행도):
    """ "숏컷" 타입 오브젝트를 진행도 기준으로 재검사해 조건(해금조건
    "필요오브젝트좌표")을 만족한 좌표를 "@"에서 "O"로 바꾼다(한 번
    열리면 계속 열려 있음). 진행도가 None이면 아무것도 하지 않는다.

    해금조건의 "필요오브젝트좌표"가 가리키는 던전은 기본적으로 이 던전
    자신(던전상태["던전파일명"])이지만, 해금조건에 "필요던전파일명"이
    있으면 그 던전 파일명을 대신 쓴다 - 다른 던전의 오브젝트를 깨야
    열리는 지름길(예: 머크우드의 지름길이 포이즌 선더랜드의 전투이벤트
    클리어를 요구하는 경우)에 쓴다."""
    if 진행도 is None:
        return
    던전파일명 = 던전상태.get("던전파일명")
    for 좌표, 오브젝트 in 던전상태["맵정보"]["오브젝트"].items():
        if 오브젝트.get("타입") != "숏컷":
            continue
        해금조건 = 오브젝트.get("해금조건", {})
        필요좌표 = 해금조건.get("필요오브젝트좌표")
        if 필요좌표 is None:
            continue
        필요던전파일명 = 해금조건.get("필요던전파일명", 던전파일명)
        if town_system.오브젝트_클리어됨(진행도, 필요던전파일명, 필요좌표):
            x, y = 좌표
            던전상태["그리드"][y][x] = "O"


# 인카운트가 나면 이 확률로 등장 적 중 무작위 한 마리가 이 몬스터로 바뀐다(항상 한 마리,
# 다른 적과 함께 나올 수 있다 - 사용자 결정 2026-09-30). 보스 등 오브젝트 전투에는 없다.
인카운트_교체몬스터 = "황금 고블린"
인카운트_교체확률 = 0.01


def 인카운트_판정(던전상태):
    """이 던전상태의 현재 걸음수를 기준으로 인카운트 발생 여부를 판정한다.
    발생하면 {"등장몬스터": [몬스터이름, ...]}를, 아니면 None을 반환한다.

    "출현그룹"(신규 - dungeon_format.py <출현그룹 항목 양식> 참고)에서 먼저
    그룹 하나를 "그룹확률" 가중치로 뽑고(전투 1회당 한 번만 - 마리마다
    다시 뽑지 않는다), "출현마리수" 전부를 그 그룹의 "출현몬스터"에서만
    뽑는다."""
    인카운트 = 던전상태["맵정보"].get("인카운트")
    if 인카운트 is None:
        return None

    안전걸음 = 인카운트["인카운트확률"]["안전걸음"]
    걸음당증가율 = 인카운트["인카운트확률"]["걸음당증가율"]
    초과걸음 = 던전상태["걸음수"] - 안전걸음
    if 초과걸음 <= 0:
        return None

    확률 = min(1.0, 초과걸음 * 걸음당증가율)
    if rng.던전.random() >= 확률:
        return None

    최소, 최대 = 인카운트["출현마리수"]
    마리수 = rng.던전.randint(최소, 최대)

    출현그룹들 = 인카운트["출현그룹"]
    그룹가중치들 = [그룹["그룹확률"] for 그룹 in 출현그룹들]
    그룹 = rng.던전.choices(출현그룹들, weights=그룹가중치들, k=1)[0]

    이름들 = list(그룹["출현몬스터"].keys())
    확률들 = list(그룹["출현몬스터"].values())
    등장몬스터 = rng.던전.choices(이름들, weights=확률들, k=마리수)
    if rng.던전.random() < 인카운트_교체확률:
        등장몬스터[rng.던전.randrange(len(등장몬스터))] = 인카운트_교체몬스터

    return {"등장몬스터": 등장몬스터}


def 이동_시도(던전상태, 방향, 인카운트없음=False):
    """방향("위"/"아래"/"왼쪽"/"오른쪽")으로 한 칸 이동을 시도한다.
    인카운트없음이면(치트용 마법석 등) 걸음수를 쌓지 않고 인카운트도
    판정하지 않는다. 던전상태["봉절걸음"]이 남아 있어도(던전스킬 봉절) 같고, 한 걸음마다
    하나씩 줄어 0이 되는 걸음의 결과에 "봉절해제": True가 붙는다. 던전상태["스프레이"]에 남은 스프레이가
    있어도 같다 - 스프레이마다 따로 줄고, 마지막 하나가 끝나는 걸음에 "스프레이해제": True가 붙는다.
    반환값은 다음 중 하나다.

    - {"결과": "이동불가"}
    - {"결과": "오브젝트", "위치": (x, y), "오브젝트": <오브젝트 항목>}
    - {"결과": "이동", "위치": (x, y),
       "인카운트": None 또는 인카운트_판정()의 반환값,
       "연결지역": None 또는 <연결지역 항목>}
    """
    dx, dy = _방향_이동[방향]
    x, y = 던전상태["위치"]
    새위치 = (x + dx, y + dy)
    문자 = 칸_문자(던전상태["그리드"], 새위치)

    if 문자 == "@":
        오브젝트 = 던전상태["맵정보"]["오브젝트"][새위치]
        return {"결과": "오브젝트", "위치": 새위치, "오브젝트": 오브젝트}

    if 문자 not in ("O", "#"):
        return {"결과": "이동불가"}

    던전상태["위치"] = 새위치
    봉절해제 = False
    if 던전상태.get("봉절걸음", 0) > 0:
        던전상태["봉절걸음"] -= 1
        봉절해제 = 던전상태["봉절걸음"] == 0
        인카운트없음 = True
    스프레이해제 = False
    if 던전상태.get("스프레이"):
        인카운트없음 = True
        던전상태["스프레이"] = [
            n if n is None else n - 1
            for n in 던전상태["스프레이"]
            if n is None or n > 1
        ]
        스프레이해제 = not 던전상태["스프레이"]
    if 인카운트없음:
        인카운트결과 = None
    else:
        던전상태["걸음수"] += 1
        인카운트결과 = 인카운트_판정(던전상태) if 문자 == "O" else None
    if 인카운트결과 is not None:
        # 인카운트가 발생하면 걸음수를 다시 0부터 센다 - 그렇지 않으면
        # "초과걸음 x 걸음당증가율"이 계속 누적돼 안전걸음을 한참 지난
        # 뒤로는(이 던전은 15걸음째부터) 확률이 영구히 100%로 고정되어
        # 버려서, 던전을 나갈 때까지 한 걸음도 못 걷고 매번 전투가
        # 시작되는 문제가 있었다.
        던전상태["걸음수"] = 0
    연결정보 = 던전상태["맵정보"]["연결지역"][새위치] if 문자 == "#" else None

    결과 = {
        "결과": "이동",
        "위치": 새위치,
        "인카운트": 인카운트결과,
        "연결지역": 연결정보,
    }
    if 봉절해제:
        결과["봉절해제"] = True
    if 스프레이해제:
        결과["스프레이해제"] = True
    return 결과


def 스프레이_사용(던전상태, 걸음):
    """스프레이 하나의 효과를 더한다(걸음 None은 던전을 나갈 때까지). 이미 쓴 것과 따로 센다."""
    던전상태.setdefault("스프레이", []).append(걸음)


def 스프레이_남은걸음(던전상태):
    """가장 오래 남은 스프레이의 걸음 - 나갈 때까지면 "∞", 남은 것이 없으면(던전 밖 포함) None."""
    남은 = (던전상태 or {}).get("스프레이") or []
    if not 남은:
        return None
    return "∞" if None in 남은 else max(남은)


def 오브젝트_클리어_처리(던전상태, 위치):
    """전투 승리 등 이후 호출한다. "클리어시" 효과 두 가지: "통행가능화"
    (@→O)와 "연결지역화"(@→#, 미리 등록된 "연결지역" 정보로 다른 맵/
    마을로 이어짐). 여기서는 그리드만 바꾸고, 진행도(클리어 영구 기록)는
    건드리지 않는다 - 그건 town_system.오브젝트_클리어_기록()의 몫이다."""
    오브젝트 = 던전상태["맵정보"]["오브젝트"].get(위치)
    if 오브젝트 is None:
        return
    x, y = 위치
    클리어시 = 오브젝트.get("클리어시")
    if 클리어시 == "통행가능화":
        던전상태["그리드"][y][x] = "O"
    elif 클리어시 == "연결지역화":
        던전상태["그리드"][y][x] = "#"


