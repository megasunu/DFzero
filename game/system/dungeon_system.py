# 던전(그리드형 소형지도, dungeon_format.py "맵정보")을 다룬다. 한 칸씩
# 이동하며 인카운트가 발생하고, 오브젝트(NPC/보스전투/숏컷/상자 등)와
# 연결지역(다른 맵 이동)을 만난다.
#
# 가정(문서에 명시 안 돼 확인 필요할 수 있음):
# - 던전 진입 시작 좌표를 안 주면(시작좌표=None) 맵정보["입장좌표"]를 쓰고,
#   그것도 없으면 그리드에서 처음 만나는 이동 가능 칸을 씀(dungeon_system.
#   던전_시작 참고). 마을의 [던전 이동] 목록으로 처음 들어갈 때가 바로
#   시작좌표를 안 주는 경우다 - 연결지역을 통해 들어올 때는 그 연결지역의
#   "진입좌표"가 항상 명시적으로 넘어온다.
# - "@" 칸은 이동 불가 - 제자리에서 상호작용만 가능.
# - 인카운트 확률 = "안전걸음 초과분 × 걸음당증가율"(누적 공식 미정).
# - "숏컷" 오브젝트는 던전_시작() 시점에 해금상태_적용()으로 열림 판정.
#   해금조건의 "필요오브젝트좌표"는 기본적으로 같은 던전 안의 좌표를
#   가리키지만, "필요던전파일명"을 같이 적으면 다른 던전 파일의 오브젝트
#   클리어 여부를 볼 수 있다(dungeon_format.py <해금조건 항목 양식> 참고 -
#   머크우드→프로스트 머크우드처럼, 다른 던전(포이즌 선더랜드)의 보스를
#   깨야 열리는 지름길에 쓴다).
# - "클리어시":"연결지역화" 오브젝트는 해당 좌표가 맵정보 "연결지역"에도
#   등록돼 있어야 한다(안 그러면 이동_시도()가 KeyError).

