# =====================
# 난수 흐름
# =====================
# 게임의 모든 무작위는 여기의 흐름 중 하나에서 나온다. 용도마다 흐름을 따로 두어서,
# 한 곳에 굴림이 하나 늘거나 줄어도 다른 용도의 난수는 밀리지 않게 한다
# (예: 스킬에 주사위를 하나 더 굴려도 몬스터가 대상을 고르는 순서는 그대로).
# 테스트와 재현은 시드(값) 하나로 모든 흐름을 고정한다.

import random

주사위 = random.Random()  # d20, XdY 굴림(dice_utils), 굴림으로 정하는 지속 턴
확률 = random.Random()  # "확률" 판정 - random() < p
대상 = random.Random()  # 대상·행동·효과 고르기(choice, sample, shuffle, 가중치 고르기)
던전 = random.Random()  # 인카운트(나올지, 몇 마리, 어떤 몬스터)
보상 = random.Random()  # 전리품, 골드, 분해 조각, 업적 보상, 마법 봉인 이름

흐름들 = {"주사위": 주사위, "확률": 확률, "대상": 대상, "던전": 던전, "보상": 보상}


def 시드(값=None):
    """모든 흐름을 값 하나로 고정한다(흐름마다 다른 시드가 나온다). None이면 운영체제 난수로 다시 섞는다.

    전역 random도 같은 값으로 고정한다 - 게임 코드는 쓰지 않지만, 테스트의 플레이어 정책처럼
    게임 밖의 무작위가 같은 시드를 따르게.
    """
    random.seed(값)
    for 이름, 흐름 in 흐름들.items():
        흐름.seed(None if 값 is None else f"{값}:{이름}")


def 상태():
    """모든 흐름(과 전역 random)의 현재 자리 - 상태_복원으로 되돌린다."""
    return {
        "전역": random.getstate(),
        **{이름: 흐름.getstate() for 이름, 흐름 in 흐름들.items()},
    }


def 상태_복원(저장):
    random.setstate(저장["전역"])
    for 이름, 흐름 in 흐름들.items():
        흐름.setstate(저장[이름])
