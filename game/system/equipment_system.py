def 장착_가능여부(캐릭터, 슬롯, 아이템데이터):
    """해당 슬롯에 이 아이템을 장착할 수 있는지 (가능여부, 사유) 튜플로
    반환한다. 사유는 불가능할 때만 문자열로 채워진다.

    - 무기는 "타입"(소검/도/둔기/대검/광검 등)이 캐릭터의 "가용무기"
      목록에 있어야 한다.
    - 상의/하의/어깨/벨트/신발은 재질과 상관없이 누구나 착용한다.
    - 목걸이/반지/팔찌/보조장비/마법석/귀걸이는 슬롯과 "분류"만
      일치하면 된다 (착용 제한 없음).
    """
    if 슬롯 not in 캐릭터["장착장비"]:
        return False, f"존재하지 않는 슬롯: {슬롯}"

    기대분류 = 슬롯별_분류.get(슬롯)
    if 기대분류 is not None and 아이템데이터.get("분류") != 기대분류:
        return False, f"'{아이템데이터.get('이름')}'은(는) {슬롯} 슬롯에 맞지 않는다."

    if 슬롯 == "무기":
        if 무기_종류(아이템데이터) not in 캐릭터["가용무기"]:
            return False, (
                f"'{아이템데이터.get('이름')}'"
                f"({무기_종류(아이템데이터)}) 종류의 무기는 "
                f"아직 사용할 수 없다."
            )

    return True, None


def 장비_장착(캐릭터, 슬롯, 아이템데이터):
    """장착 가능하면 "장착장비"[슬롯]에 아이템 이름을 기록한다.
    불가능하면 ValueError를 낸다."""
    가능, 사유 = 장착_가능여부(캐릭터, 슬롯, 아이템데이터)
    if not 가능:
        raise ValueError(사유)
    캐릭터["장착장비"][슬롯] = 아이템데이터["이름"]


def 장비_해제(캐릭터, 슬롯):
    """해당 슬롯을 비운다. 이미 비어 있어도 에러 없이 넘어간다."""
    if 슬롯 not in 캐릭터["장착장비"]:
        raise ValueError(f"존재하지 않는 슬롯: {슬롯}")
    캐릭터["장착장비"][슬롯] = None


