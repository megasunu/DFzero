# 이름 색 분류 - 화면이 아이템 이름을 레어도 색으로 칠할 때 쓴다
# =====================================================
# 커먼 방어구 중 세트 아이템(이름이 방어구 세트명에서 " 세트"를 뺀 말로 시작 - 예:
# "티타늄 세트" -> "티타늄 흉갑")은 "세트"(초록), 나머지는 아이템의 "레어도" 그대로.
# 악세서리/특수장비 세트는 레어도 색 그대로 둔다(2026-10-07 사용자 결정).

색분류_세트 = "세트"


def 방어구세트_이름머리(방어구세트목록):
    return [
        세트명[: -len(" 세트")] if 세트명.endswith(" 세트") else 세트명
        for 세트명 in (방어구세트목록 or {})
    ]


def 아이템_색분류(아이템데이터, 방어구세트목록=None):
    레어도 = 아이템데이터.get("레어도", "커먼")
    if (
        레어도 == "커먼"
        and 아이템데이터.get("분류") in 방어구_슬롯
        and any(
            아이템데이터.get("이름", "").startswith(머리 + " ")
            for 머리 in 방어구세트_이름머리(방어구세트목록)
        )
    ):
        return 색분류_세트
    return 레어도
