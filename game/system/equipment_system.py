# 세트목록 : eq_02_armor_set.py "방어구세트목록"처럼 {세트명: 세트정의}
# 딕셔너리. 세트정의의 "구성품"(아이템 이름 리스트)에 적힌 아이템을
# 전부 장착하고 있으면 그 세트가 활성화된다. 여러 세트 목록을
# 함께 검사하려면 호출하는 쪽이 딕셔너리를 합쳐서 넘긴다.


def 세트효과_목록(장착아이템데이터, 세트목록):
    """활성화된 세트정의들을 리스트로 반환한다. 세트목록이 없으면 빈 리스트.

    세트가 활성화되는 조건은 두 가지 형식 중 하나다.
    - "구성품"(아이템 이름 리스트)이 있으면: 그 아이템을 전부 장착했을 때.
      "구성품"이 비어 있으면 활성화되지 않는다.
    - "구성품"이 없는 방어구세트("분류": "방어구세트", "타입": 재질): 방어구 5부위
      (방어구_슬롯)를 전부 그 재질로 입었을 때 - eq_02_armor_set.py 머리말의
      "재질 5부위를 전부 갖추면 발동" 규칙."""
    if not 세트목록:
        return []
    장착이름들 = {
        아이템데이터.get("이름")
        for 아이템데이터 in 장착아이템데이터.values()
        if 아이템데이터 is not None
    }
    return [
        세트정의
        for 세트정의 in 세트목록.values()
        if _세트_충족(세트정의, 장착아이템데이터, 장착이름들)
    ]


def _세트_충족(세트정의, 장착아이템데이터, 장착이름들):
    if "구성품" in 세트정의:
        구성품 = 세트정의.get("구성품") or []
        return bool(구성품) and all(이름 in 장착이름들 for 이름 in 구성품)
    재질 = 세트정의.get("타입")
    if 세트정의.get("분류") != "방어구세트" or not 재질:
        return False
    return all(
        (장착아이템데이터.get(슬롯) or {}).get("재질") == 재질 for 슬롯 in 방어구_슬롯
    )


# =====================================================
# 장착 중인 장비의 보너스 합산
# =====================================================
# 아래 함수들은 캐릭터["장착장비"]에 적힌 "이름"이 아니라, 그 이름에
# 해당하는 실제 아이템 데이터 자체를 인자로 받는다.
#
# 장착아이템데이터 : {슬롯: 아이템데이터 또는 None, ...} 형태.
# 빈 슬롯은 값이 None이거나 아예 키가 없어도 된다. (이름 -> 데이터
# 조회는 장비 데이터 전체를 아는 호출하는 쪽의 몫이다.)


def _보너스_더하기(합계, 원천):
    for 키 in _보너스_키:
        값 = 원천.get(키, 0)
        if isinstance(값, (int, float)):
            합계[키] += 값
    for 스탯이름, 증가폭 in (원천.get("스탯보너스") or {}).items():
        if isinstance(증가폭, (int, float)):
            합계["스탯보너스"][스탯이름] = 합계["스탯보너스"].get(스탯이름, 0) + 증가폭


def _보너스_빼기(합계, 원천):
    _보너스_더하기(
        합계,
        {
            **{키: -값 for 키, 값 in 원천.items() if isinstance(값, (int, float))},
            "스탯보너스": {
                이름: -값 for 이름, 값 in (원천.get("스탯보너스") or {}).items()
            },
        },
    )


def 방어구_세트재질(장착아이템데이터):
    """방어구 5부위를 전부 입었고 모두 같은 재질이면 그 재질, 아니면 None."""
    재질들 = {(장착아이템데이터.get(슬롯) or {}).get("재질") for 슬롯 in 방어구_슬롯}
    if len(재질들) != 1:
        return None
    return next(iter(재질들))


def 방어구숙련_발동(캐릭터, 장착아이템데이터):
    """방어구 숙련이 발동 중인 재질 - 5부위가 모두 같은 재질이고 그 재질의
    숙련("OO숙련")을 가졌으면 그 재질, 아니면 None(사실상 세트 효과)."""
    재질 = 방어구_세트재질(장착아이템데이터)
    if 재질 and f"{재질}숙련" in 캐릭터.get("보유특성", []):
        return 재질
    return None


def _방어구숙련_효과(캐릭터, 장착아이템데이터):
    """발동 중인 방어구 숙련(+ 그 재질의 숙달을 가졌으면 숙달)의 "효과" 리스트.
    발동 안 하면 []."""
    재질 = 방어구숙련_발동(캐릭터, 장착아이템데이터)
    if not 재질:
        return []
    효과 = list(_공용특성[f"{재질}숙련"].get("효과") or [])
    if f"{재질}숙달" in 캐릭터.get("보유특성", []):
        효과 += _공용특성[f"{재질}숙달"].get("효과") or []
    return 효과


def _방어구숙련_최대MP(캐릭터, 장착아이템데이터):
    """발동 중인 방어구 숙련의 "최대MP" 효과(천갑숙련 10x차수) 합."""
    합계 = 0
    for 항목 in _방어구숙련_효과(캐릭터, 장착아이템데이터):
        if 항목.get("변동대상") != "최대MP":
            continue
        값 = 항목.get("변동값", 0)
        if isinstance(값, str):
            식 = 값.replace("x", "*").replace(
                "차수", str(캐릭터데이터.차수_계산(캐릭터))
            )
            값 = formula.안전_평가(식)
        합계 += 값
    return 합계


def 방어구_재질수(장착아이템데이터):
    """입은 방어구 부위의 서로 다른 재질 수(입지 않은 부위는 세지 않는다)."""
    재질들 = {(장착아이템데이터.get(슬롯) or {}).get("재질") for 슬롯 in 방어구_슬롯}
    재질들.discard(None)
    return len(재질들)


def _패셔니스트_단계(캐릭터, 장착아이템데이터):
    """특성 "패셔니스트"의 "재질수효과" 중 지금 재질 수로 도달한 단계들(누적)."""
    if "패셔니스트" not in 캐릭터.get("보유특성", []):
        return []
    재질수 = 방어구_재질수(장착아이템데이터)
    return [
        단계
        for 단계 in _공용특성["패셔니스트"]["재질수효과"]
        if 재질수 >= 단계["재질수"]
    ]


def 패셔니스트_수치(캐릭터, 장착아이템데이터, 변동대상):
    """도달한 패셔니스트 단계들의 그 변동대상(AC/매력) 합."""
    return sum(
        항목.get("변동값", 0)
        for 단계 in _패셔니스트_단계(캐릭터, 장착아이템데이터)
        for 항목 in 단계.get("효과") or []
        if 항목.get("변동대상") == 변동대상
    )


def _방어구숙련_스탯보너스(캐릭터, 장착아이템데이터):
    """발동 중인 방어구 숙련/숙달의 능력치 효과(예: 가죽숙달 민첩 +1)와 패셔니스트의
    능력치 효과(매력). "주문시전능력치"는 그 캐릭터의 주문시전능력치(천갑숙달)."""
    결과 = {}
    패셔니스트 = [
        항목
        for 단계 in _패셔니스트_단계(캐릭터, 장착아이템데이터)
        for 항목 in 단계.get("효과") or []
    ]
    for 항목 in _방어구숙련_효과(캐릭터, 장착아이템데이터) + 패셔니스트:
        대상, 값 = 항목.get("변동대상"), 항목.get("변동값")
        if 대상 == "주문시전능력치":
            대상 = 캐릭터데이터.주문시전능력치(캐릭터)
        if 대상 in 능력치_이름목록 and isinstance(값, (int, float)):
            결과[대상] = 결과.get(대상, 0) + 값
    return 결과


# 중갑/판금 패널티 - 방어구 5부위 중 하나라도 중갑/판금이면 받는다. 5부위가 모두
# 그 재질이고 그 재질의 숙련(중갑숙련/판금숙련)이 있으면 패널티가 없다. 패셔니스트가
# 재질 3종류 이상에 도달해도 없다(판금 부위별 패널티는 아이템 수치라 그대로).
중갑_재질 = ("중갑", "판금")
중갑_패널티 = {"명중률보너스": -1, "속도보너스": -5, "MP소모배율": 2}


def 중갑_패널티_재질(캐릭터, 장착아이템데이터):
    """패널티를 주는 재질 목록(입은 중갑/판금 중 숙련 발동으로 면제되지 않은 것).
    패셔니스트의 "중갑패널티면제" 단계에 도달했으면 빈 목록."""
    if any(
        단계.get("중갑패널티면제")
        for 단계 in _패셔니스트_단계(캐릭터, 장착아이템데이터)
    ):
        return []
    면제 = 방어구숙련_발동(캐릭터, 장착아이템데이터)
    결과 = []
    for 슬롯 in 방어구_슬롯:
        재질 = (장착아이템데이터.get(슬롯) or {}).get("재질")
        if 재질 in 중갑_재질 and 재질 != 면제 and 재질 not in 결과:
            결과.append(재질)
    return 결과


def 캐릭터_장비_보너스(캐릭터, 장착아이템데이터, 세트목록=None):
    """장비_보너스_합산 + 방어구 숙련 능력치(세트 발동 시) + 중갑/판금 패널티
    (명중률보너스 -1, 속도보너스 -5, "MP소모배율" 2). 전투 참가자의 "장비보너스"로 쓴다."""
    합계 = 장비_보너스_합산(장착아이템데이터, 세트목록)
    for 이름, 값 in _방어구숙련_스탯보너스(캐릭터, 장착아이템데이터).items():
        합계["스탯보너스"][이름] += 값
    합계["MP소모배율"] = 1
    if 중갑_패널티_재질(캐릭터, 장착아이템데이터):
        합계["명중률보너스"] += 중갑_패널티["명중률보너스"]
        합계["속도보너스"] += 중갑_패널티["속도보너스"]
        합계["MP소모배율"] = 중갑_패널티["MP소모배율"]
    return 합계


def 장비_보너스_합산(장착아이템데이터, 세트목록=None):
    """장착 중인 모든 아이템의 AC보너스/데미지보너스/명중률보너스/
    속도보너스/치명타주사위/스탯보너스를 전부 더한 딕셔너리를 반환한다. 아이템에
    해당 키가 없으면 0(스탯보너스는 미기재 스탯 0)으로 취급한다.
    세트목록을 주면 활성화된 세트(세트효과_목록)의 "효과"도 같은 키로
    더한다."""
    합계 = {
        "AC보너스": 0,
        "데미지보너스": 0,
        "명중률보너스": 0,
        "속도보너스": 0,
        "치명타주사위": 0,
        "집요함": 0,
        "스탯보너스": {
            "근력": 0,
            "민첩": 0,
            "건강": 0,
            "지능": 0,
            "지혜": 0,
            "매력": 0,
        },
    }

    겹친것 = _마봉_겹친_장비(장착아이템데이터)
    for 슬롯, 아이템데이터 in 장착아이템데이터.items():
        if 아이템데이터 is None:
            continue
        _보너스_더하기(합계, 아이템데이터)
        if 슬롯 in 겹친것:
            _보너스_빼기(합계, 아이템데이터.get("마봉보너스") or {})

    for 세트정의 in 세트효과_목록(장착아이템데이터, 세트목록):
        _보너스_더하기(합계, 세트정의.get("효과") or {})

    return 합계


def 민첩상한_계산(캐릭터, 장착아이템데이터):
    """장착 중인 방어구들의 "민첩상한"(eq_02_armor_format.py 기준) 중
    가장 낮은 값을 최종 상한으로 쓴다. None은 "제한 없음"이라 비교에서
    제외한다. 방어구를 하나도 안 입었거나 전부 제한이 없으면
    None(제한 없음)을 반환한다.

    "경갑숙련" 같은 특성으로 "민첩상한해제"를 받은 재질(캐릭터
    "민첩상한해제" 목록, effect_engine.py가 채워준다)의 방어구는 그
    아이템의 "민첩상한"을 아예 집계에서 제외한다 - 그 슬롯만큼은
    상한이 없는 것으로 취급한다는 뜻이다."""
    # 경갑숙련의 상한 해제도 방어구 숙련이라 5부위가 모두 그 재질일 때만
    발동재질 = 방어구숙련_발동(캐릭터, 장착아이템데이터)
    민첩상한해제된_재질 = [
        재질 for 재질 in 캐릭터.get("민첩상한해제", []) if 재질 == 발동재질
    ]
    상한값들 = [
        아이템데이터.get("민첩상한")
        for 아이템데이터 in 장착아이템데이터.values()
        if 아이템데이터 is not None
        and "민첩상한" in 아이템데이터
        and 아이템데이터.get("재질") not in 민첩상한해제된_재질
    ]
    상한값들 = [값 for 값 in 상한값들 if 값 is not None]

    if not 상한값들:
        return None
    return min(상한값들)


def 최종AC_계산(캐릭터, 장착아이템데이터, 세트목록=None, 추가민첩=0):
    """eq_02_armor_format.py 공식 그대로 계산한다.
    최종 AC = 기본AC + AC보너스(장비+세트) + min(민첩수정치, 민첩상한)
    (민첩상한이 없으면 민첩수정치를 제한 없이 전부 더한다.)

    민첩수정치는 캐릭터 원래 민첩에 장비(+세트) "스탯보너스"의 민첩과
    추가민첩(전투 중 버프/디버프로 늘거나 준 민첩 - combat.stats.최종AC가
    계산해 넘긴다)을 더한 값으로 계산한다. 전투 밖에서
    부를 때는 추가민첩을 생략하면 된다.

    패셔니스트의 AC(재질 2종류 이상 +1)도 여기서 더한다 - 전투 안팎이 이 함수를 같이 쓴다."""
    보너스 = 장비_보너스_합산(장착아이템데이터, 세트목록)
    민첩상한 = 민첩상한_계산(캐릭터, 장착아이템데이터)
    민첩값 = 캐릭터["민첩"] + 보너스["스탯보너스"].get("민첩", 0) + 추가민첩
    민첩수정치 = (민첩값 - 10) // 2

    if 민첩상한 is not None:
        민첩수정치 = min(민첩수정치, 민첩상한)

    return (
        캐릭터["기본AC"]
        + 보너스["AC보너스"]
        + 민첩수정치
        + 패셔니스트_수치(캐릭터, 장착아이템데이터, "AC")
    )


