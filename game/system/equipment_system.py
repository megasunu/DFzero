# =====================================================
# 분류 탭 - 장비 교체 팝업과 상점 목록이 같이 쓴다
# =====================================================
# 방어구는 재질로, 무기는 직업군(무기 "분류"의 "귀검사 무기" -> "귀검사") 안의
# "타입"(소검/도/...)으로 나눈다. 맨 앞은 항상 전체_탭.

전체_탭 = "전체"
방어구_재질 = ["천갑", "가죽", "경갑", "중갑", "판금"]
_무기분류_꼬리 = " 무기"


def 무기_직업군(아이템데이터):
    """무기 "분류"("귀검사 무기")의 직업군("귀검사"). 무기가 아니면 None."""
    분류 = 아이템데이터.get("분류") or ""
    return 분류[: -len(_무기분류_꼬리)] if 분류.endswith(_무기분류_꼬리) else None


def 무기_종류(아이템데이터):
    """무기 "타입"의 종류(소검/도/...). 봉인 무기의 "타입"은 ["소검", "마법봉인"]처럼 목록이고
    맨 앞이 종류다(2026-10-19 사용자 결정 - 봉인을 풀어도 그대로)."""
    타입 = 아이템데이터.get("타입")
    return 타입[0] if isinstance(타입, list) and 타입 else 타입


def 무기_직업군_목록(무기들):
    """무기 데이터들에 나오는 직업군을 처음 나온 순서대로."""
    목록 = []
    for 무기 in 무기들:
        직업군 = 무기_직업군(무기)
        if 직업군 and 직업군 not in 목록:
            목록.append(직업군)
    return 목록


def 직업군_무기종류(무기들, 직업군):
    """그 직업군 무기의 "타입"을 처음 나온 순서대로(데이터 파일 순서 = 소검, 도, ...)."""
    목록 = []
    for 무기 in 무기들:
        if 무기_직업군(무기) == 직업군 and 무기_종류(무기) not in 목록:
            목록.append(무기_종류(무기))
    return 목록


def 분류탭_목록(슬롯, 슬롯아이템들, 직업군=None):
    """그 부위의 분류 탭. 무기는 [전체] + 직업군의 무기 종류, 방어구는 [전체] + 재질,
    악세서리/특수장비는 탭 없음([])."""
    if 슬롯 == "무기":
        return [전체_탭] + 직업군_무기종류(슬롯아이템들, 직업군)
    if 슬롯 in 방어구_슬롯:
        return [전체_탭] + 방어구_재질
    return []


def 분류탭_일치(아이템데이터, 슬롯, 탭):
    """아이템이 그 탭에 들어가는지. 전체_탭(또는 None)이면 항상 True."""
    if 탭 in (None, 전체_탭):
        return True
    if 슬롯 == "무기":
        return 무기_종류(아이템데이터) == 탭
    if 슬롯 in 방어구_슬롯:
        return 아이템데이터.get("재질") == 탭
    return True


