# 마봉효과 - 봉인을 푼 "마법의 ~" 장비의, 장비 칸으로 못 더한 효과 원소
# =====================================================
# magic_seal_system.마법의_장비_생성이 남긴 "마봉효과"(eq_00_magic_seal.py 원소 양식). 상시 숫자
# 효과는 마봉_수치로 더하고, "발동" 원소(턴시작/공격/명중)는 전투가 마봉효과_목록으로 찾아 처리한다
# (combat.flow 턴 시작, combat.damage 공격·명중 - 2026-10-15 사용자 결정).


def _마봉_겹친_장비(장착아이템데이터):
    """같은 마봉능력이 앞 슬롯에 이미 있는 장비의 슬롯들 - 같은 능력은 한 캐릭터에 한 번만 적용된다
    (2026-10-16 사용자 결정, 슬롯 순서로 처음 것만 남긴다)."""
    본것, 겹친것 = set(), set()
    for 슬롯, 아이템 in 장착아이템데이터.items():
        능력 = (아이템 or {}).get("마봉능력")
        if 능력 is None:
            continue
        if 능력 in 본것:
            겹친것.add(슬롯)
        본것.add(능력)
    return 겹친것


def 마봉효과_목록(장착아이템데이터):
    """[(아이템데이터, 효과 원소)] - 장착 중인 장비들의 "마봉효과"(슬롯 순서, 같은 마봉능력은 처음 것만)."""
    겹친것 = _마봉_겹친_장비(장착아이템데이터)
    return [
        (아이템, 원소)
        for 슬롯, 아이템 in 장착아이템데이터.items()
        if 아이템 and 슬롯 not in 겹친것
        for 원소 in 아이템.get("마봉효과") or []
    ]


def 마봉_수치(장착아이템데이터, 변동대상, 속성=None, 대상타입=()):
    """상시(발동이 없는) 마봉효과 중 변동대상이 같은 숫자 변동값의 합. 원소에 "속성"이 있으면
    넘긴 속성과 같거나 원소가 "전체"일 때만(속성을 안 넘기면 뺀다), "대상타입"이 있으면 그 타입이
    대상타입(대상 몬스터의 "타입" 목록)에 있을 때만 더한다."""
    합계 = 0
    for _, 원소 in 마봉효과_목록(장착아이템데이터):
        if "발동" in 원소 or 원소.get("변동대상") != 변동대상:
            continue
        if "속성" in 원소 and (속성 is None or 원소["속성"] not in (속성, "전체")):
            continue
        if "대상타입" in 원소 and 원소["대상타입"] not in 대상타입:
            continue
        값 = 원소.get("변동값")
        if isinstance(값, (int, float)):
            합계 += 값
    return 합계


# =====================================================
# 장비 반영 능력치 / 최대HP / 최대MP (전투 밖 공용)
# =====================================================
# 캐릭터에 저장된 능력치/"기본최대HP"/"기본최대MP"는 장비를 뺀 값이다.
# 아래 함수들은 장비(+세트) "스탯보너스"를 더한 값을 그때그때 계산한다 -
# 캐릭터 데이터 자체는 바꾸지 않으므로 장비를 바꿔도 되돌릴 필요가 없다.

능력치_이름목록 = ("근력", "민첩", "건강", "지능", "지혜", "매력")


def _보정치(값):
    return (값 - 10) // 2


def 장비반영_능력치(캐릭터, 장착아이템데이터, 세트목록=None):
    """{능력치이름: 원래값 + 장비 스탯보너스(+ 발동 중인 방어구 숙련)} 딕셔너리."""
    보너스 = 장비_보너스_합산(장착아이템데이터, 세트목록)["스탯보너스"]
    숙련 = _방어구숙련_스탯보너스(캐릭터, 장착아이템데이터)
    return {
        이름: 캐릭터[이름] + 보너스.get(이름, 0) + 숙련.get(이름, 0)
        for 이름 in 능력치_이름목록
    }


def 장비반영_최대HP(캐릭터, 장착아이템데이터, 세트목록=None):
    """기본최대HP(character_data_system.최대HP_공식)를 장비로 바뀐 건강보정치로
    다시 계산했을 때와의 차이만큼 더한다. 캐릭터 "레벨당체력증가"가 없으면(그 칸이
    생기기 전 데이터) 장비 건강은 반영하지 않는다. 마봉효과의 "최대HP"(기력/참선)도 더한다."""
    레벨당 = 캐릭터.get("레벨당체력증가")
    마봉 = 마봉_수치(장착아이템데이터, "최대HP")
    if 레벨당 is None:
        return max(1, 캐릭터["기본최대HP"] + 마봉)
    능력치 = 장비반영_능력치(캐릭터, 장착아이템데이터, 세트목록)
    레벨 = 캐릭터.get("레벨", 1)
    차이 = 캐릭터데이터.최대HP_공식(
        레벨, 레벨당, _보정치(능력치["건강"])
    ) - 캐릭터데이터.최대HP_공식(레벨, 레벨당, _보정치(캐릭터["건강"]))
    return max(1, 캐릭터["기본최대HP"] + 차이 + 마봉)


def 장비반영_최대MP(캐릭터, 장착아이템데이터, 세트목록=None):
    """최대MP = 25 + (레벨-1)×(3+주문시전보정치)이므로, 장비로 바뀐 주문시전
    능력치 보정치의 차이 × (레벨-1)만큼 더한다. 발동 중인 방어구 숙련의 최대MP
    (천갑숙련 10x차수)도 더한다."""
    스탯 = 캐릭터.get("주문시전능력치") or "지능"  # 미지정이면 지능
    능력치 = 장비반영_능력치(캐릭터, 장착아이템데이터, 세트목록)
    차이 = _보정치(능력치[스탯]) - _보정치(캐릭터[스탯])
    return max(
        0,
        캐릭터["기본최대MP"]
        + 차이 * (캐릭터.get("레벨", 1) - 1)
        + _방어구숙련_최대MP(캐릭터, 장착아이템데이터),
    )


# =====================================================
# 소지품 연동 - 장비 교체
# =====================================================
# 소지품["장비"]는 "아이템이름 -> 개수"이고, 장착 중인 아이템도 그 개수에
# 포함되어 있다(장착품_소지품_동기화 참고). 그래서 교체 후보는 "소지품
# 개수 - 파티 전체가 장착 중인 개수"가 1개 이상인 아이템이고, 교체 자체는
# 소지품 개수를 바꾸지 않고 캐릭터의 장착 슬롯 이름만 바꾼다.


def 장착_캐릭터목록(플레이어):
    """장비를 끼고 있을 수 있는 캐릭터 전부 - 파티원 + 모험단 숙소 동료."""
    return list(플레이어.get("파티", {}).get("파티원", [])) + list(
        플레이어.get("숙소", [])
    )


def 장착중_개수(플레이어, 이름):
    """파티원과 숙소 동료가 이 이름의 아이템을 장착하고 있는 개수 합계."""
    개수 = 0
    for 캐릭터 in 장착_캐릭터목록(플레이어):
        for 장착이름 in 캐릭터.get("장착장비", {}).values():
            if 장착이름 == 이름:
                개수 += 1
    return 개수


def 장착품_소지품_동기화(플레이어):
    """장착 중인 아이템이 소지품["장비"] 개수에 포함되도록 맞춘다.
    개수가 모자란 아이템만 부족분을 더한다(시작 장비처럼 캐릭터 생성 때
    소지품 없이 바로 장착된 아이템 대비). 게임을 시작/불러올 때 한 번
    부른다."""
    장비칸 = 플레이어.setdefault("소지품", {}).setdefault("장비", {})
    장착집계 = {}
    for 캐릭터 in 장착_캐릭터목록(플레이어):
        for 이름 in 캐릭터.get("장착장비", {}).values():
            if 이름:
                장착집계[이름] = 장착집계.get(이름, 0) + 1
    for 이름, 장착수 in 장착집계.items():
        부족 = 장착수 - 장비칸.get(이름, 0)
        if 부족 > 0:
            장비칸[이름] = 장비칸.get(이름, 0) + 부족


def 교체_후보목록(플레이어, 캐릭터, 슬롯, 슬롯아이템들):
    """[(아이템데이터, 교체가능수량, 착용가능, 사유), ...].
    슬롯아이템들은 이 슬롯에 들어가는 아이템 데이터 {이름: 데이터}
    (예: 상점 카탈로그["장비"][슬롯]). 소지품에 있어도 그 부위 아이템이
    아니면 나오지 않고, 장착 중인 것(누가 끼고 있든)은 뺀 개수만 센다.
    착용할 수 없는 아이템도 나오며 착용가능=False, 사유에 이유가 담긴다."""
    장비칸 = 플레이어.get("소지품", {}).get("장비", {})
    결과 = []
    for 이름, 개수 in 장비칸.items():
        아이템 = 슬롯아이템들.get(이름)
        if 아이템 is None:
            continue
        가능수량 = 개수 - 장착중_개수(플레이어, 이름)
        if 가능수량 <= 0:
            continue
        착용가능, 사유 = 장착_가능여부(캐릭터, 슬롯, 아이템)
        결과.append((아이템, 가능수량, 착용가능, 사유))
    return 결과


def 장비_교체(플레이어, 캐릭터, 슬롯, 아이템데이터):
    """소지품에서 남는 아이템으로 슬롯 장비를 교체한다. 소지품에 없거나
    다 다른 곳에 장착 중이거나 착용할 수 없으면 아무것도 바꾸지 않고
    ValueError를 낸다. 원래 끼던 장비는 소지품 개수에 그대로 남아 있으므로
    자동으로 교체 후보가 된다."""
    이름 = 아이템데이터["이름"]
    보유 = 플레이어.get("소지품", {}).get("장비", {}).get(이름, 0)
    if 보유 - 장착중_개수(플레이어, 이름) <= 0:
        raise ValueError(f"'{이름}'은(는) 소지품에 남은 것이 없다.")
    장비_장착(캐릭터, 슬롯, 아이템데이터)


