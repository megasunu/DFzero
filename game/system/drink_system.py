# item_food.py "주류"를 마셔 HP/MP를 회복하고 상태이상 "취기"/"만취"(status_effects.py
# 음주목록)를 받는다.
#   - 회복량 = "회복값"의 대상별 수식(예: "(2차수)d4+건강보정치")을 굴린 값. "차수"는
#     마시는 캐릭터의 전직 차수다. HP는 건강보정치, MP는 주문시전보정치를 쓰고, 보정치는
#     호출하는 쪽이 넘긴다(전투 중이면 버프/장비 반영 값). HP와 MP는 따로 굴린다.
#   - 회복을 먼저 계산한 뒤 취기를 건다(취기의 매력 감소가 이번 회복에는 안 들어간다).
#   - 취기는 마실 때마다 1중첩, 최대중첩(3)에서 또 마시면 만취가 더해진다. 취기 3중첩은
#     그대로 남는다(모든 캐릭터, 2026-10-16 사용자 결정 - 만취가 더 불리해진다).
#     만취 중에 마시면 회복만 하고 취기는 쌓이지 않는다.
#   - 쓰러졌거나(HP 0) 소지품에 없으면 마실 수 없다. 가득 차 있어도 마실 수는 있다.
# 전투 중에는 보조행동 1개를 쓰고 자기 자신만 마신다(gameflow.아군_주류사용).
# 전투 밖에서는 파티원 아무나 마신다(gameflow.캐릭터_주류사용).
#
# "전투후유지" 상태이상(취기/만취)은 캐릭터["상태이상"]에 남는다 - 전투를 시작하면
# 참가자에게 옮기고(combat.participants), 전투가 끝나면 되돌려 쓰고(유지_상태이상),
# 마을에서 휴식하면 "휴식시해제"인 것을 지운다(휴식_해제).

from game.system.combat import formula, status

소지품_카테고리 = "소모품"
보정치_키워드 = {"HP": "건강보정치", "MP": "주문시전보정치"}


def 회복대상들(주류):
    """회복값이 정해진 대상 목록(["HP"], ["HP", "MP"] ...). "미정"이면 빈 목록."""
    회복값 = 주류.get("회복값")
    return list(회복값) if isinstance(회복값, dict) else []


def 회복량_굴림(주류, 대상, 보정치, 차수):
    """대상("HP"/"MP")의 회복 수식을 굴린다(0 밑으로는 안 내려간다)."""
    식 = 주류["회복값"][대상].replace(보정치_키워드[대상], f"({보정치})")
    return max(0, formula.올림(formula.수식_평가(식, {"차수": 차수})))


def 사용불가_사유(현재HP, 보유수):
    """마실 수 없으면 사유 문자열, 마실 수 있으면 None."""
    if 보유수 <= 0:
        return "소지품에 없다."
    if 현재HP <= 0:
        return "쓰러진 캐릭터는 마실 수 없다."
    return None


def 회복_적용(대상, 주류, 보정치들, 최대값들, 차수):
    """대상(캐릭터 또는 전투 참가자)의 "현재HP"/"현재MP"를 대상별로 굴려 올린다.
    보정치들/최대값들: {"HP": 값, "MP": 값}. 실제로 오른 양 {"HP": n, ...}을 돌려준다."""
    결과 = {}
    for 종류 in 회복대상들(주류):
        키 = f"현재{종류}"
        전 = 대상[키]
        굴림 = 회복량_굴림(주류, 종류, 보정치들[종류], 차수)
        대상[키] = max(전, min(최대값들[종류], 전 + 굴림))
        결과[종류] = 대상[키] - 전
    return 결과


def _찾기(상태이상목록, 이름):
    return next((항목 for 항목 in 상태이상목록 if 항목.get("이름") == 이름), None)


def 음주_상태이상_적용(상태이상목록, 이름, 정의모음):
    """상태이상목록에 주류의 상태이상(취기)을 1중첩 더한다. 최대중첩에서 또 마시면
    그 상태이상은 최대중첩으로 남기고 "초과시상태이상"(만취)을 더한다. 이미 초과 상태이상이면 아무것도
    더하지 않는다. 결과 문구("취기 2" / "만취" / "만취 상태라 취기가 쌓이지 않는다")."""
    정의 = 정의모음[이름]
    초과 = 정의.get("초과시상태이상")
    if 초과 and _찾기(상태이상목록, 초과) is not None:
        return f"{초과} 상태라 {이름}가 쌓이지 않는다"
    기존 = _찾기(상태이상목록, 이름)
    if 기존 is None:
        상태이상목록.append({"이름": 이름, "중첩": 1})
        return f"{이름} 1"
    최대 = 정의.get("최대중첩")
    if 최대 is None or 기존.get("중첩", 1) < 최대:
        기존["중첩"] = 기존.get("중첩", 1) + 1
        return f"{이름} {기존['중첩']}"
    상태이상목록.append({"이름": 초과})
    return 초과


def 유지_상태이상(상태이상목록, 정의모음):
    """전투가 끝날 때 캐릭터에 남길 "전투후유지" 상태이상의 사본 목록."""
    return [
        dict(항목)
        for 항목 in 상태이상목록
        if (정의모음.get(항목.get("이름")) or {}).get("전투후유지")
    ]


def 휴식_해제(상태이상목록, 정의모음):
    """마을 휴식 - "휴식시해제" 상태이상을 뺀 목록."""
    return [
        항목
        for 항목 in 상태이상목록
        if not (정의모음.get(항목.get("이름")) or {}).get("휴식시해제")
    ]


def 능력치_변동(상태이상목록, 정의모음, 능력치이름, 보유특성=None):
    """전투 밖 능력치에 더할 상태이상 "추가효과" 합(취기의 매력 -중첩수 등). 전투 중에는
    combat.stats가 같은 값을 더한다. 보유특성의 상태이상 보정(취권)도 같이 반영한다."""
    합계 = 0
    for 항목 in 상태이상목록:
        정의 = 정의모음.get(항목.get("이름"))
        if 정의 is None:
            continue
        정의 = status.특성_보정_정의(항목.get("이름"), 정의, 보유특성)
        추가효과 = (정의.get("효과") or {}).get("추가효과") or {}
        수식 = 추가효과.get(능력치이름)
        if 수식 is None:
            continue
        if isinstance(수식, str):
            수식 = formula.수식_평가(
                수식.replace("중첩수", str(항목.get("중첩", 1))), {}
            )
        합계 += 수식
    return formula.올림(합계)
