소지품_소모품_탭순서 = 소모품_탭순서 + ["인형"]
대분류_목록 = ["장비", "소모품", "재료"]

판매가_비율_분모 = 5  # 판매가 = 가격 / 5 (20%)를 올림
최대_구매수량 = 99


# =====================================================
# 카탈로그
# =====================================================


def _이름으로_정리(아이템딕셔너리):
    """딕셔너리의 키가 아니라 아이템의 "이름" 값을 기준으로 다시 묶는다
    (키와 "이름"이 다른 항목이 있어도 소지품과 이름이 어긋나지 않게)."""
    return {아이템.get("이름", 키): 아이템 for 키, 아이템 in 아이템딕셔너리.items()}


def 카탈로그_생성(
    장비탭모음, 포션데이터, 소모품데이터, 음식데이터, 재료데이터=None, 인형데이터=None
):
    """장비탭모음   : {부위탭이름: {이름: 데이터}} (무기 탭은 직업별 무기
                      목록을 합쳐서 넘긴다).
    포션데이터   : item_potion.포션_데이터 ({"회복포션": {...}, "샤프아이 포션": {...}, ...})
                      - 묶음("회복포션")과 낱개 아이템(버프포션)을 "포션" 탭 하나로 합친다.
                      값에 "이름"이 있으면 아이템 하나, 없으면 묶음이다.
    소모품데이터 : item_consumable.소모품_데이터 ({"투척 아이템": {...}, "항아리": {...}, ...}).
    음식데이터   : item_food.음식_데이터 ({"음식": {...}, "주류": {...}}).
    재료데이터   : item_materials.재료_데이터 ({"큐브 조각": {...}, ...}) - 묶음이 그대로 탭.
    인형데이터   : item_doll.인형_데이터 ({이름: 데이터}) - 소모품 "인형" 탭(소지품 화면에만 보인다).
    """
    포션탭 = {}
    for 키, 값 in 포션데이터.items():
        포션탭.update(_이름으로_정리(값 if "이름" not in 값 else {키: 값}))

    return {
        "장비": {탭: _이름으로_정리(장비탭모음.get(탭, {})) for 탭 in 장비_탭순서},
        "소모품": {
            "포션": 포션탭,
            "투척 아이템": _이름으로_정리(소모품데이터.get("투척 아이템", {})),
            "소환 아이템": _이름으로_정리(소모품데이터.get("소환 아이템", {})),
            "음식": _이름으로_정리(음식데이터.get("음식", {})),
            "주류": _이름으로_정리(음식데이터.get("주류", {})),
            "항아리": _이름으로_정리(소모품데이터.get("항아리", {})),
            "스프레이": _이름으로_정리(소모품데이터.get("스프레이", {})),
            "부여": _이름으로_정리(소모품데이터.get("부여", {})),
            "특수": _이름으로_정리(
                소모품데이터.get("특수", {})
            ),  # 레테의 강물·눈물(#351)
            "인형": _이름으로_정리(인형데이터 or {}),
        },
        "재료": {
            탭: _이름으로_정리(아이템들) for 탭, 아이템들 in (재료데이터 or {}).items()
        },
    }


def 탭_목록(대분류):
    if 대분류 == "장비":
        return list(장비_탭순서)
    if 대분류 == "소모품":
        return list(소모품_탭순서)
    return []


# =====================================================
# 가격 / 소지품 대응
# =====================================================


def 판매가(아이템):
    return -(-int(아이템.get("가격", 0)) // 판매가_비율_분모)


def 소지품_카테고리(대분류, 탭):
    if 대분류 == "장비":
        return "장비"
    if 대분류 == "재료":
        return "재료"
    if 탭 == "포션":
        return "포션"
    return "소모품"


def _탭_아이템들(카탈로그, 대분류, 탭):
    return 카탈로그.get(대분류, {}).get(탭, {})


def _소지품(플레이어):
    return 플레이어.setdefault("소지품", player_system.빈_소지품())


def 보유_골드(플레이어):
    return _소지품(플레이어).get("골드", 0)


