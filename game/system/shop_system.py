# =====================
# 상점 시스템
# =====================
# 상점의 구매/판매 로직. 화면은 gameflow.상점_*()을 거쳐 이 파일의 함수만
# 부르고, 골드/소지품을 직접 바꾸지 않는다.
#
# 다른 시스템 파일들과 같은 이유로, 이 파일도 아이템 데이터를 스스로
# import하지 않는다. gameflow.py가 eq_XX / item_XX 데이터를 모아
# 카탈로그_생성()에 넘겨준다.
#
# -----------------------------------------------------
# 카탈로그 구조
# -----------------------------------------------------
# {
#     "장비":   {부위탭이름: {아이템이름: 아이템데이터, ...}, ...},
#     "소모품": {"포션": {...}, "투척 아이템": {...}, "음식": {...}, "주류": {...}},
#     "재료":   {"큐브 조각": {...}, "큐브": {...}, "소울": {...}, "잡템": {...}},
# }
# 부위탭이름은 장비_탭순서, 소모품 탭은 소모품_탭순서를 따른다.
# 무기 탭에는 모든 직업의 무기가 한 탭에 합쳐 들어간다.
# 재료는 상점이 팔지 않는다(구매목록이 늘 빈 목록) - 드랍/해체로 얻은 것을 팔 수만 있다.
# 상점 화면의 재료 탭은 아직 미구현이라 탭_목록("재료")는 빈 목록이다.
#
# -----------------------------------------------------
# 상점판매목록 (town 파일의 "상점판매목록")
# -----------------------------------------------------
# 그 마을 상점이 파는 아이템 "이름"의 리스트. None(town 파일에 키가
# 없음)이면 카탈로그의 가격이 0보다 큰 아이템 전부를 판다(임시 동작).
# 구매 목록에만 적용되고, 판매 목록은 소지품 기준이라 영향받지 않는다.
# 레어 이상 장비(레어/유니크/크로니클/레전더리/에픽)는 상점에서 팔지 않는다 - 상점판매목록에
# 넣지 않는다(2026-10-27 사용자 결정, test_rare_armor_sets.py가 지킨다). 드랍/항아리 등으로만 얻는다.
#
# -----------------------------------------------------
# 소지품 카테고리 대응 (player_system.py 소지품_카테고리 기준)
# -----------------------------------------------------
# 장비 탭 전부        -> 소지품["장비"]
# 소모품 - 포션 탭    -> 소지품["포션"]
# 소모품 - 투척 아이템/소환 아이템/음식/주류/항아리/스프레이/부여/특수/인형 탭 -> 소지품["소모품"]
# 재료 탭 전부        -> 소지품["재료"]
#
# 판매가는 가격의 20%를 1골드 단위로 올림(1~5골드 아이템은 1골드, 가격 0/없음은 0골드).

