def 구매목록(카탈로그, 대분류, 탭, 상점판매목록=None):
    """이 상점이 파는 아이템 데이터 리스트. 가격이 0 이하인 아이템은
    (치트용 아이템 등) 원칙적으로 나오지 않지만, 마을 "상점판매목록"에
    이름이 직접 적혀 있으면 나온다(치트용 소검 테스트용, 0골드에 살 수
    있다). 재료는 상점이 팔지 않는다(늘 빈 목록)."""
    if 대분류 == "재료":
        return []
    결과 = []
    for 이름, 아이템 in _탭_아이템들(카탈로그, 대분류, 탭).items():
        if 아이템.get("타입") == "인형":  # 인형은 상점에서 사고팔지 않는다(가격만 있다)
            continue
        if 아이템.get("가격", 0) <= 0 and not (상점판매목록 and 이름 in 상점판매목록):
            continue
        if 상점판매목록 is not None and 이름 not in 상점판매목록:
            continue
        결과.append(아이템)
    return 결과


def 장착중_개수(플레이어, 이름):
    """파티원과 모험단 숙소 동료가 이 이름의 아이템을 장착하고 있는 개수 합계."""
    개수 = 0
    for 캐릭터 in list(플레이어.get("파티", {}).get("파티원", [])) + list(
        플레이어.get("숙소", [])
    ):
        for 장착이름 in 캐릭터.get("장착장비", {}).values():
            if 장착이름 == 이름:
                개수 += 1
    return 개수


def 보유목록(플레이어, 카탈로그, 대분류, 탭):
    """[(아이템데이터, 보유수량), ...] - 소지품 화면용. 이 탭에 속한 보유 아이템을
    카탈로그 순서대로. 장비는 장착 중인 것도 센다(판매목록과 다르다)."""
    보유칸 = _소지품(플레이어).get(소지품_카테고리(대분류, 탭), {})
    return [
        (아이템, 보유칸[이름])
        for 이름, 아이템 in _탭_아이템들(카탈로그, 대분류, 탭).items()
        if 보유칸.get(이름, 0) > 0
    ]


def 판매목록(플레이어, 카탈로그, 대분류, 탭):
    """[(아이템데이터, 판매가능수량), ...]. 소지품에 있는 아이템만
    나온다. 장비는 장착 중인 개수를 뺀 나머지만 판매할 수 있다(소지품
    "장비"에 장착 중인 것도 함께 들어 있다고 보고 뺀다)."""
    카테고리 = 소지품_카테고리(대분류, 탭)
    보유칸 = _소지품(플레이어).get(카테고리, {})
    아이템들 = _탭_아이템들(카탈로그, 대분류, 탭)

    결과 = []
    for 이름, 개수 in 보유칸.items():
        아이템 = 아이템들.get(이름)
        if 아이템 is None or 아이템.get("타입") == "인형":
            continue
        가능 = 개수
        if 대분류 == "장비":
            가능 -= 장착중_개수(플레이어, 이름)
        if 가능 > 0:
            결과.append((아이템, 가능))
    return 결과


# =====================================================
# 구매 / 판매
# =====================================================


def 구매_처리(플레이어, 카탈로그, 대분류, 탭, 이름, 수량, 상점판매목록=None):
    """골드를 차감하고 소지품에 아이템을 더한다. 실패하면(상품 없음/
    수량 오류/골드 부족) 아무것도 바꾸지 않고 ValueError를 낸다.
    성공하면 지불한 총 골드를 반환한다."""
    if not isinstance(수량, int) or 수량 < 1:
        raise ValueError("수량은 1 이상이어야 한다.")
    if 수량 > 최대_구매수량:
        raise ValueError(f"한 번에 {최대_구매수량}개까지만 살 수 있다.")

    판매중 = {
        아이템["이름"]: 아이템
        for 아이템 in 구매목록(카탈로그, 대분류, 탭, 상점판매목록)
    }
    아이템 = 판매중.get(이름)
    if 아이템 is None:
        raise ValueError(f"'{이름}'은(는) 이 상점에서 팔지 않는다.")

    총가 = 아이템["가격"] * 수량
    소지품 = _소지품(플레이어)
    if 소지품.get("골드", 0) < 총가:
        raise ValueError("골드가 부족하다.")

    소지품["골드"] -= 총가
    player_system.아이템_추가(플레이어, 소지품_카테고리(대분류, 탭), 이름, 수량)
    return 총가


def 판매_처리(플레이어, 카탈로그, 대분류, 탭, 이름, 수량):
    """소지품에서 아이템을 빼고 판매가만큼 골드를 더한다. 실패하면
    아무것도 바꾸지 않고 ValueError를 낸다. 성공하면 받은 총 골드를
    반환한다."""
    if not isinstance(수량, int) or 수량 < 1:
        raise ValueError("수량은 1 이상이어야 한다.")

    가능수량 = {
        아이템["이름"]: (아이템, 가능)
        for 아이템, 가능 in 판매목록(플레이어, 카탈로그, 대분류, 탭)
    }
    if 이름 not in 가능수량:
        raise ValueError(f"'{이름}'은(는) 팔 수 없다.")
    아이템, 가능 = 가능수량[이름]
    if 수량 > 가능:
        raise ValueError(f"팔 수 있는 수량은 {가능}개까지다.")

    카테고리 = 소지품_카테고리(대분류, 탭)
    보유칸 = _소지품(플레이어)[카테고리]
    보유칸[이름] -= 수량
    if 보유칸[이름] <= 0:
        del 보유칸[이름]

    총액 = 판매가(아이템) * 수량
    player_system.골드_추가(플레이어, 총액)
    return 총액
