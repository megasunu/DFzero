# =====================
# 장비강화 - 강화 / 증폭 / 재련
# =====================
# 마을 [전문직업] > [장비강화](#636, 2026-11-10 사용자 결정). 규칙은 docs/game-rules.md "장비강화".
#
# - 무기: 강화(1당 무기 주사위 +1d4) / 증폭(1당 장착 시 차수 +1) / 재련(1당 명중 보너스 +1).
#   강화와 증폭은 둘 중 하나만, 재련은 어느 쪽과도 함께 된다.
# - 방어구는 강화만(장착한 방어구 강화 합계 5당 AC +1), 악세서리는 재련만(장착한 악세 재련 합계 3당
#   방어력 +1), 특수장비는 증폭만(장착한 특수장비 증폭 합계 3당 주스탯 +1).
# - 커먼(과 소울이 없는 치트) 장비는 안 된다. 최대 수치는 그 장비의 차수(티어)까지. 실패는 없다.
# - 비용: 장비 가격 x (지금 수치+1)^2 골드 + 같은 수의 그 레어도 소울(크로니클은 레전더리 소울).
# - 저장은 이름 방식(봉인해제와 같다): "+3강1재 녹슨 소검"처럼 이름 앞에 붙이고, 그 이름의 장비 데이터를
#   카탈로그에 만들어 넣는다(카탈로그_등록). 불러오면 소지품/장착 칸의 이름으로 다시 만든다 - 세이브 형식은 그대로.
#   만든 데이터는 "강화원본"(원래 이름)을 가지며 상점 구매/도감/드랍에 나오지 않는다. 가격·레어도·티어는 원래
#   그대로라 판매가와 해체 결과도 원래 장비와 같다.

import copy
import re

from game.data import common_names

종류들 = ("강화", "증폭", "재련")
_글자 = {"강화": "강", "증폭": "증", "재련": "재"}

# 화면 선택지 -> (부위 탭들, 종류)
메뉴 = {
    "무기강화": (("무기",), "강화"),
    "무기증폭": (("무기",), "증폭"),
    "무기재련": (("무기",), "재련"),
    "방어구강화": (tuple(common_names.방어구_부위), "강화"),
    "악세재련": (tuple(common_names.악세서리_부위), "재련"),
    "특수장비증폭": (tuple(common_names.특수장비_부위), "증폭"),
}

# 장착한 부위들의 종합 수치 -> 보너스 (몇 당 1)
방어구_AC_단위 = 5
악세_방어력_단위 = 3
특수_주스탯_단위 = 3

_소울 = {
    "언커먼": "언커먼 소울",
    "레어": "레어 소울",
    "유니크": "유니크 소울",
    "크로니클": "레전더리 소울",
    "레전더리": "레전더리 소울",
    "에픽": "에픽 소울",
}

_이름식 = re.compile(r"^\+(?:(\d+)강)?(?:(\d+)증)?(?:(\d+)재)? (.+)$")


def 이름_짓기(원본, 수치):
    """("녹슨 소검", {"강화": 3, "재련": 1}) -> "+3강1재 녹슨 소검". 수치가 모두 0이면 원본 그대로."""
    머리 = "".join(f"{수치[k]}{_글자[k]}" for k in 종류들 if 수치.get(k))
    return f"+{머리} {원본}" if 머리 else 원본


def 이름_풀기(이름):
    """ "+3강1재 녹슨 소검" -> ("녹슨 소검", {"강화": 3, "증폭": 0, "재련": 1}). 강화 이름이 아니면 (이름, 모두 0)."""
    맞음 = _이름식.match(이름 or "")
    if not 맞음 or not any(맞음.group(1, 2, 3)):
        return 이름, dict.fromkeys(종류들, 0)
    return 맞음.group(4), {k: int(v or 0) for k, v in zip(종류들, 맞음.group(1, 2, 3))}


def 수치(아이템):
    return {k: (아이템 or {}).get(k, 0) for k in 종류들}


def 강화한_장비인가(아이템):
    return "강화원본" in 아이템


def 무기_증폭(장착장비):
    """캐릭터 "장착장비"(슬롯 -> 이름)의 무기 증폭 수치 - 차수에 더한다(character_data_system.차수_계산)."""
    return 이름_풀기((장착장비 or {}).get("무기"))[1]["증폭"]


def 장비_생성(원본데이터, 탭, 새수치):
    """원래 장비 데이터 + 수치 -> 강화한 장비 데이터(새 dict). 무기는 강화만큼 무기 주사위에 d4를,
    재련만큼 명중률보너스를 더한다. 나머지 부위의 보너스는 장착한 부위 합계로 정해진다(종합_보너스)."""
    아이템 = copy.deepcopy(원본데이터)
    아이템["이름"] = 이름_짓기(원본데이터["이름"], 새수치)
    아이템["강화원본"] = 원본데이터["이름"]
    for k in 종류들:
        if 새수치.get(k):
            아이템[k] = 새수치[k]
    if 탭 == "무기":
        if 새수치.get("강화"):
            아이템["무기공격력"] = f"{아이템['무기공격력']}+{새수치['강화']}d4"
        아이템["명중률보너스"] = 아이템.get("명중률보너스", 0) + 새수치.get("재련", 0)
    return 아이템


def 카탈로그_등록(장비카탈로그, 이름):
    """그 이름의 장비가 카탈로그에 없고 강화 이름이면 만들어 넣는다(제자리). 들어 있는 탭(없으면 None)."""
    for 탭, 아이템들 in 장비카탈로그.items():
        if 이름 in 아이템들:
            return 탭
    원본, 새수치 = 이름_풀기(이름)
    if 원본 == 이름:
        return None
    for 탭, 아이템들 in 장비카탈로그.items():
        if 원본 in 아이템들:
            아이템들[이름] = 장비_생성(아이템들[원본], 탭, 새수치)
            return 탭
    return None


def 카탈로그_복원(장비카탈로그, 이름들):
    """불러오기 - 소지품/장착 칸의 강화 이름들을 카탈로그에 다시 만든다."""
    for 이름 in 이름들:
        if 이름:
            카탈로그_등록(장비카탈로그, 이름)


def 비용(아이템, 종류):
    """{"골드": 가격 x (지금+1)^2, "<레어도> 소울": (지금+1)^2}."""
    배수 = (수치(아이템)[종류] + 1) ** 2
    return {"골드": 아이템.get("가격", 0) * 배수, _소울[아이템["레어도"]]: 배수}


def 불가_사유(아이템, 종류):
    """그 종류를 할 수 없으면 이유 글, 되면 None(부위가 맞는지는 메뉴가 정한다)."""
    레어도 = 아이템.get("레어도")
    if 레어도 == "커먼":
        return f"커먼 장비는 {종류}할 수 없습니다."
    if 레어도 not in _소울:
        return f"{종류}할 수 없는 장비입니다."
    지금 = 수치(아이템)
    for 하나, 다른 in (("강화", "증폭"), ("증폭", "강화")):
        if 종류 == 하나 and 지금[다른]:
            return f"{다른}한 무기는 {하나}할 수 없습니다."
    최대 = 아이템.get("티어", 1)
    if 지금[종류] >= 최대:
        return f"최대 수치입니다(+{최대})."
    return None


def _대상인가(아이템):
    return 아이템.get("레어도") in _소울 and not 아이템.get("이름", "").startswith(
        "마법으로 봉인된 "
    )


def 대상목록(플레이어, 장비카탈로그, 선택지, 숙소=()):
    """[{"이름", "아이템", "탭", "캐릭터", "슬롯", "수량", "비용", "불가"}] - 그 선택지 부위의 소지품과
    장착 장비(커먼/치트/봉인된 장비 제외). 장착 중인 것은 캐릭터마다 한 줄(수량 1), 남은 것은 소지품 한 줄."""
    탭들, 종류 = 메뉴[선택지]
    보유 = 플레이어.get("소지품", {}).get("장비", {})
    캐릭터들 = list(플레이어.get("파티", {}).get("파티원", [])) + list(숙소)
    결과 = []
    for 이름, 개수 in 보유.items():
        탭 = next((t for t in 탭들 if 이름 in 장비카탈로그.get(t, {})), None)
        if 탭 is None or 개수 <= 0 or not _대상인가(장비카탈로그[탭][이름]):
            continue
        아이템 = 장비카탈로그[탭][이름]
        공통 = {
            "이름": 이름,
            "아이템": 아이템,
            "탭": 탭,
            "비용": 비용(아이템, 종류),
            "불가": 불가_사유(아이템, 종류),
        }
        장착 = [
            (c, 슬롯)
            for c in 캐릭터들
            for 슬롯, 장착이름 in c.get("장착장비", {}).items()
            if 장착이름 == 이름 and 슬롯 in 탭들
        ]
        for c, 슬롯 in 장착:
            결과.append({**공통, "캐릭터": c, "슬롯": 슬롯, "수량": 1})
        if 개수 - len(장착) > 0:
            결과.append(
                {**공통, "캐릭터": None, "슬롯": None, "수량": 개수 - len(장착)}
            )
    return 결과


def 비용글(비용값):
    return " + ".join(
        f"{v}G" if k == "골드" else f"{k} {v}개" for k, v in 비용값.items()
    )


def 실행(플레이어, 장비카탈로그, 항목, 선택지):
    """항목(대상목록의 한 줄) 하나를 1 올린다. 새 이름을 돌려준다. 안 되거나 비용이 모자라면
    ValueError(아무것도 바뀌지 않는다)."""
    _, 종류 = 메뉴[선택지]
    아이템 = 항목["아이템"]
    사유 = 불가_사유(아이템, 종류)
    if 사유:
        raise ValueError(사유)
    값 = 비용(아이템, 종류)
    소지품 = 플레이어["소지품"]
    재료 = 소지품.setdefault("재료", {})
    if 소지품.get("골드", 0) < 값["골드"]:
        raise ValueError(f"골드가 부족합니다({값['골드']}G 필요).")
    for 이름, 개수 in 값.items():
        if 이름 != "골드" and 재료.get(이름, 0) < 개수:
            raise ValueError(f"{이름}이 부족합니다({개수}개 필요).")
    원본, 지금 = 이름_풀기(항목["이름"])
    새이름 = 이름_짓기(원본, {**지금, 종류: 지금[종류] + 1})
    for 이름, 개수 in 값.items():
        if 이름 == "골드":
            소지품["골드"] -= 개수
            continue
        재료[이름] -= 개수
        if 재료[이름] <= 0:
            del 재료[이름]
    카탈로그_등록(장비카탈로그, 새이름)
    보유 = 소지품["장비"]
    보유[항목["이름"]] -= 1
    if 보유[항목["이름"]] <= 0:
        del 보유[항목["이름"]]
    보유[새이름] = 보유.get(새이름, 0) + 1
    if 항목["캐릭터"] is not None:
        항목["캐릭터"]["장착장비"][항목["슬롯"]] = 새이름
    return 새이름


def _합계(장착아이템데이터, 부위들, 종류):
    return sum(
        (장착아이템데이터.get(슬롯) or {}).get(종류, 0)
        for 슬롯 in 부위들
        if 슬롯 in 장착아이템데이터
    )


def 종합_보너스(장착아이템데이터):
    """장착한 방어구 강화 합계 5당 AC보너스 +1, 악세 재련 합계 3당 방어력 +1(장비 보너스 합산에 더한다)."""
    return {
        "AC보너스": _합계(장착아이템데이터, common_names.방어구_부위, "강화")
        // 방어구_AC_단위,
        "방어력": _합계(장착아이템데이터, common_names.악세서리_부위, "재련")
        // 악세_방어력_단위,
    }


def 주스탯_보너스(캐릭터, 장착아이템데이터):
    """{주스탯: 장착한 특수장비 증폭 합계 // 3} - 주스탯이 없으면(인형 등) 빈 dict."""
    주스탯 = 캐릭터.get("주스탯")
    값 = _합계(장착아이템데이터, common_names.특수장비_부위, "증폭") // 특수_주스탯_단위
    return {주스탯: 값} if 주스탯 and 값 else {}
