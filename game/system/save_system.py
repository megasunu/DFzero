def _마이그레이션_적용(저장데이터, 슬롯번호):
    """저장데이터를 제자리에서 현재 버전으로 올린다. 더 높은 버전이면 세이브_버전오류."""
    버전 = 저장데이터.get("버전", 0)
    if 버전 > 세이브_버전:
        raise 세이브_버전오류(슬롯번호, 버전)
    for 새버전, 변환 in _마이그레이션:
        if 버전 < 새버전:
            변환(저장데이터)
            버전 = 새버전
    저장데이터["버전"] = 버전


def _백업_경로(슬롯번호):
    return _세이브_경로(슬롯번호) + ".bak"


def 세이브_존재(슬롯번호):
    return os.path.isfile(_세이브_경로(슬롯번호))


def _파일_읽기(경로):
    """경로의 세이브를 읽어 딕셔너리로 돌려준다. 파일이 없거나(OSError) JSON이 아니거나
    세이브 형태가 아니면(ValueError) 예외 - 호출하는 쪽이 손상으로 다룬다."""
    with open(경로, "r", encoding="utf-8") as f:
        데이터 = json.load(f)
    if not isinstance(데이터, dict) or not isinstance(데이터.get("진행도"), dict):
        raise ValueError("세이브 형태가 아니다")
    버전 = 데이터.get("버전", 0)
    if not isinstance(버전, int) or isinstance(버전, bool) or 버전 < 0:
        raise ValueError("세이브 버전이 올바르지 않다")
    return 데이터


# 파일이 없거나, JSON이 아니거나, 세이브 형태가 틀려 변환하다 실패한 경우 - 모두 "못 읽음"
_읽기_실패 = (OSError, ValueError, KeyError, TypeError, AttributeError, IndexError)


def _읽고_올리기(경로, 슬롯번호):
    """파일을 읽어 현재 버전으로 올린다. 못 읽으면 _읽기_실패에 든 예외, 더 새로운
    버전이면 세이브_버전오류(그대로 올라간다 - 백업으로 돌아가지 않는다)."""
    저장데이터 = _파일_읽기(경로)
    _마이그레이션_적용(저장데이터, 슬롯번호)
    문제 = state_schema.세이브_핵심_문제목록(저장데이터)
    if 문제:  # 캐릭터의 핵심 칸이 없으면 화면/전투가 어차피 KeyError로 죽는다 - 손상으로 보고 백업으로 돌아간다
        raise ValueError("세이브의 필수 칸이 없다: " + "; ".join(문제[:3]))
    return 저장데이터


def _슬롯_읽기(슬롯번호):
    """(저장데이터, 복구본여부) - 현재 버전으로 올린 데이터. 본 파일을 못 읽으면 .bak을
    쓴다(복구본 True). 슬롯 파일이 없으면 FileNotFoundError, 본 파일도 .bak도 못 읽으면
    세이브_손상오류, 더 새로운 버전이면 세이브_버전오류."""
    경로 = _세이브_경로(슬롯번호)
    if not os.path.isfile(경로):
        raise FileNotFoundError(f"{슬롯번호}번 슬롯에는 저장된 게임이 없다.")
    try:
        return _읽고_올리기(경로, 슬롯번호), False
    except _읽기_실패:
        pass
    try:
        return _읽고_올리기(_백업_경로(슬롯번호), 슬롯번호), True
    except _읽기_실패:
        raise 세이브_손상오류(슬롯번호) from None


def _원자적_쓰기(경로, 텍스트):
    """임시 파일에 다 쓴 뒤 바꿔치기한다. 이전 세이브가 읽을 수 있는 상태면 .bak으로 남긴다.
    중간에 실패하면 임시 파일을 지우고 예외를 그대로 올린다(본 파일은 그대로)."""
    임시 = 경로 + ".tmp"
    try:
        with open(임시, "w", encoding="utf-8") as f:
            f.write(텍스트)
            f.flush()
            os.fsync(f.fileno())
        try:
            _파일_읽기(경로)
            이전은_정상 = True
        except (OSError, ValueError):
            이전은_정상 = False  # 없거나 망가진 파일은 좋은 .bak을 덮어쓰지 않는다
        if 이전은_정상:
            shutil.copyfile(경로, 경로 + ".bak.tmp")
            os.replace(경로 + ".bak.tmp", 경로 + ".bak")
        os.replace(임시, 경로)
    except BaseException:
        for 남은 in (임시, 경로 + ".bak.tmp"):
            if os.path.exists(남은):
                os.remove(남은)
        raise


def 게임_저장(슬롯번호, 플레이어, 진행도, 던전위치=None):
    """플레이어와 진행도를 슬롯번호 파일에 저장한다(기존 저장 있으면 덮어씀).
    던전위치: 던전 안에서 저장하면 {"던전파일명", "위치": [x, y], "걸음수", "봉절걸음"}, 마을이면 None."""
    os.makedirs(_세이브_폴더(), exist_ok=True)

    저장할_진행도 = dict(진행도)
    저장할_진행도["클리어한던전"] = sorted(진행도.get("클리어한던전", set()))
    저장할_진행도["클리어한오브젝트"] = sorted(
        [던전파일명, list(좌표)]
        for 던전파일명, 좌표 in 진행도.get("클리어한오브젝트", set())
    )

    저장데이터 = {
        "버전": 세이브_버전,
        "플레이어": {
            "레벨": 플레이어.get("레벨", 1),
            "파티": {
                "파티원": 플레이어["파티"]["파티원"],
                "인형": 플레이어["파티"].get("인형"),
            },
            "숙소": 플레이어.get("숙소", []),
            "소지품": 플레이어.get("소지품", player_system.빈_소지품()),
            "선택된초상화": 플레이어.get("선택된초상화", "001m"),
        },
        "진행도": 저장할_진행도,
        "던전위치": 던전위치,
        "저장시각": datetime.now().isoformat(timespec="seconds"),
    }
    # 직렬화를 먼저 끝낸다 - 직렬화 중 예외가 나도 파일을 건드리지 않는다.
    텍스트 = json.dumps(저장데이터, ensure_ascii=False, indent=2)
    _원자적_쓰기(_세이브_경로(슬롯번호), 텍스트)


def 게임_불러오기(슬롯번호):
    """(플레이어, 진행도)를 반환한다(현재 세이브 버전으로 변환한 값). 던전 안에서 저장했으면
    플레이어["던전위치"]에 {"던전파일명", "위치", "걸음수", "봉절걸음"}, 아니면 None. 슬롯이 비어 있으면
    FileNotFoundError, 본 파일과 백업을 둘 다 못 읽으면 세이브_손상오류(본 파일만
    망가졌으면 백업으로 불러온다), 더 새로운 버전이면 세이브_버전오류. 진행도의
    "클리어한던전"/"클리어한오브젝트"는 JSON 리스트를 set으로 되돌린다."""
    저장데이터, _ = _슬롯_읽기(슬롯번호)
    플레이어 = dict(저장데이터["플레이어"], 던전위치=저장데이터.get("던전위치"))
    진행도 = dict(저장데이터["진행도"])
    진행도["클리어한던전"] = set(진행도["클리어한던전"])
    진행도["클리어한오브젝트"] = {
        (항목[0], tuple(항목[1])) for 항목 in 진행도["클리어한오브젝트"]
    }
    return 플레이어, 진행도


def 세이브_삭제(슬롯번호):
    """슬롯을 비운다(백업/임시 파일 포함). 이미 비어 있으면 아무 일도 하지 않는다."""
    경로 = _세이브_경로(슬롯번호)
    for 대상 in (경로, 경로 + ".bak", 경로 + ".tmp", 경로 + ".bak.tmp"):
        if os.path.isfile(대상):
            os.remove(대상)


def 세이브_요약(슬롯번호):
    """슬롯 선택 화면용 요약. 비어 있으면 None, 있으면 {"슬롯번호",
    "저장시각", "현재마을", "대표캐릭터명", "파티인원수"}. 본 파일이 망가져 백업으로
    읽었으면 "복구본": True가 더 붙고, 백업도 못 읽으면 {"슬롯번호", "손상": True}다
    (예외를 내지 않는다 - 슬롯 하나가 메인 메뉴/슬롯 목록을 막으면 안 된다)."""
    경로 = _세이브_경로(슬롯번호)
    if not os.path.isfile(경로):
        return None

    try:
        저장데이터, 복구본 = _슬롯_읽기(슬롯번호)
    except 세이브_버전오류:
        return {"슬롯번호": 슬롯번호, "손상": True, "새버전": True}
    except 세이브_손상오류:
        return {"슬롯번호": 슬롯번호, "손상": True}

    try:
        파티원 = 저장데이터["플레이어"]["파티"]["파티원"]
        요약 = {
            "슬롯번호": 슬롯번호,
            "저장시각": 저장데이터.get("저장시각"),
            "현재마을": 저장데이터["진행도"].get("현재마을"),
            "대표캐릭터명": 파티원[0]["캐릭터명"] if 파티원 else "-",
            "파티인원수": len(파티원),
        }
        if 저장데이터.get("던전위치"):  # 던전 안에서 저장한 슬롯
            요약["던전파일명"] = 저장데이터["던전위치"]["던전파일명"]
    except _읽기_실패:  # 변환은 됐는데 요약에 쓸 칸이 망가진 경우
        return {"슬롯번호": 슬롯번호, "손상": True}
    if 복구본:
        요약["복구본"] = True
    return 요약


def 전체_세이브_요약():
    """전체 슬롯의 세이브_요약() 리스트. 빈 슬롯은 {"슬롯번호": n,
    "비어있음": True}로 채운다."""
    결과 = []
    for 슬롯번호 in range(1, 최대세이브슬롯 + 1):
        요약 = 세이브_요약(슬롯번호)
        결과.append(요약 or {"슬롯번호": 슬롯번호, "비어있음": True})
    return 결과
