def _마이그레이션_4_5(저장데이터):
    """반응특성을 보유특성에서 보유스킬로 옮긴다(이미 있으면 한 번만, 순서 유지)."""
    플레이어 = 저장데이터["플레이어"]
    for 캐릭터 in 플레이어["파티"].get("파티원", []) + 플레이어.get("숙소", []):
        특성 = 캐릭터.get("보유특성") or []
        스킬 = 캐릭터.setdefault("보유스킬", [])
        for 이름 in 특성:
            if 이름 in _반응스킬로_옮긴_특성_4_5 and 이름 not in 스킬:
                스킬.append(이름)
        캐릭터["보유특성"] = [n for n in 특성 if n not in _반응스킬로_옮긴_특성_4_5]


def _마이그레이션_5_6(저장데이터):
    """인형사 도입 - 그전 세이브의 파티에는 인형이 없다(파티["인형"] = None)."""
    저장데이터["플레이어"].setdefault("파티", {"파티원": []}).setdefault("인형", None)


def _마이그레이션_6_7(저장데이터):
    """봉절 도입 - 그전에 던전 안에서 저장한 세이브는 남은 봉절 걸음이 0이다."""
