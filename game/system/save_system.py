# =====================
# 세이브 시스템
# =====================
# 진행 상황을 파일로 저장/불러온다. 슬롯 3개 지원(최대세이브슬롯 상수로
# 조정 가능). 슬롯 하나에 "플레이어"(레벨/파티/소지품)와 "진행도"를 함께
# 저장한다. 아직 없는 시스템(퀘스트 등)의 데이터는 저장 대상에 없다 -
# 생기면 여기도 같이 추가해야 한다.
#
# 모험단 프로필(SD 초상화)은 두 가지가 서로 별개다.
# 1) 캐릭터별 "직업 기반 초상화" - 캐릭터 딕셔너리마다 "성별" 키로
#    붙어 있고(gameflow.py 초상화_코드() 참고), "파티"["파티원"]
#    리스트를 그대로 저장하는 아래 로직만으로 자동 저장/복원된다 -
#    이 파일을 따로 손댈 필요가 없다.
# 2) 던전 지도용 "플레이어 초상화" - 직업과 무관하게 65장 그리드에서
#    직접 고르는 값이라 캐릭터 딕셔너리에 없고 게임상태 최상위
#    "선택된초상화" 키에 있다(gameflow.초상화_설정() 참고) - 아래
#    "플레이어" 저장 블록에 별도로 담아야 한다.
#
# 저장 형식은 JSON(한국어 키 그대로 저장 가능). 진행도의
# "클리어한던전"(문자열 set)과 "클리어한오브젝트"((던전파일명,(x,y))
# 튜플 set)는 JSON이 못 담는 타입이라 저장/불러오기 시 리스트로
# 변환한다.
#
# 세이브 파일은 slot_N.json이고 폴더가 없으면 자동 생성한다. 폴더는 기본이 game/saves/(이
# 파일 기준)이지만 앱은 시작할 때 세이브_폴더_설정()으로 앱 데이터 폴더(Kivy user_data_dir -
# 앱 업데이트에도 남는다)로 바꾸고, 옛 위치의 세이브를 한 번 복사해 온다.
#
# 쓰기는 원자적이다: 임시 파일(slot_N.json.tmp)에 다 쓰고 fsync한 뒤 os.replace로
# 바꿔치기하므로, 쓰다가 앱이 죽어도 이전 세이브가 그대로 남는다. 덮어쓰기 직전에
# 읽을 수 있는 이전 세이브를 slot_N.json.bak으로 남긴다. 읽을 때 본 파일이 망가졌으면
# .bak으로 돌아가고, 둘 다 못 읽으면 세이브_손상오류다(슬롯 목록은 예외 없이 "손상"으로
# 표시한다 - 슬롯 하나가 메인 메뉴를 막으면 안 된다).
#
# 세이브에는 "버전"(정수)이 들어 있다. 세이브 형식을 바꿀 때는 세이브_버전을 올리고
# _마이그레이션 표에 (새 버전, 변환 함수)를 더한다 - 읽을 때 저장된 버전보다 높은 변환만
# 순서대로 적용한다. "버전"이 없는 세이브는 0(버전 도입 전)이다. 현재 형식보다 높은
# 버전(더 새로운 앱이 저장한 것)은 세이브_버전오류로 막는다.
# 불러올 때마다 새 규칙으로 다시 계산하는 값(최대HP 등)은 형식이 아니라 규칙이라
# 변환이 아니라 gameflow.게임_불러오기가 한다.

import json
