def 휴식_처리(파티):
    """마을 공용 메뉴의 "휴식". 파티원 전원의 HP/MP를 최대치로 채운다.

    - MP는 프로젝트 규칙("MP: ... 휴식 시 전량 회복")을 그대로 따른다.
    - HP도 MP와 동일하게 전량 회복시킨다(D&D 장기 휴식 관례).
    - 전투 중 쓰러진(현재HP 0) 캐릭터도 그냥 살아있는 것처럼 회복시킨다
      - 별도의 "부활" 판정/제약이 아직 없어서, 마을에 있다는 것 자체를
        "무사히 돌아왔다"로 취급하는 임시 가정이다(나중에 부활 조건/
        페널티가 생기면 이 부분을 바꿔야 한다).
    - 스킬의 "휴식당횟수" 제한 카운터(캐릭터["횟수제한스킬"]
      ["휴식제한스킬"])를 비운다 - 기록이 없으면 최대치로 보는
      규칙이라(skill_system.휴식_남은횟수) 비우면 전부 최대치로 돌아간다.
    - 던전 오브젝트(보스 등)의 리젠은 이 함수와 무관하다 - 휴식을 하든
      안 하든 던전을 나갔다가 다시 들어오기만 해도
      dungeon_system.던전_시작이 그리드를 처음부터 새로 만들어서 이미
      리젠된다(오브젝트_클리어_기록으로 남긴 "최소 1회 클리어" 기록만
      영구히 남고, 오브젝트 자체의 "@"/"O" 상태는 영구히 남지 않는다).
    """
    for 캐릭터 in 파티["파티원"]:
        캐릭터["현재HP"] = 캐릭터["기본최대HP"]
        캐릭터["현재MP"] = 캐릭터["기본최대MP"]
        캐릭터.setdefault("횟수제한스킬", {})["휴식제한스킬"] = {}
