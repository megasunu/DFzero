# =====================
# 마을 시스템
# =====================
# town_format.py 양식을 따르는 "마을정보"를 다루는 함수들과, 마을에서
# 이루어지는 공용 동작(휴식) 및 게임 진행도("진행도")를 다룬다.
#
# 아직 정해지지 않아서 임시로 가정하고 작성한 부분:
# - 진행도["클리어한던전"]은 클리어한 던전 파일명들의 집합(set)이라고
#   가정한다. save_system.py가 저장 시에는 JSON 호환을 위해 리스트로
#   바꿨다가 불러올 때 다시 set으로 되돌린다.
# - 진행도["클리어한오브젝트"]는 (던전파일명, 좌표) 튜플들의 집합(set)이다 -
#   던전 맵 안의 특정 몬스터 오브젝트(예: 보스)를 최소 1회 이상 클리어한
#   적이 있는지를 영구히 기록해둔다(오브젝트_클리어_기록/오브젝트_클리어됨
#   참고). dungeon_system.던전_시작이 재입장할 때마다 그리드 자체는 처음부터
#   새로 만들어서 오브젝트가 다시 "@"로 리셋되지만(=휴식 여부와 무관하게
#   던전을 나갔다 들어오기만 해도 리젠됨), 이 기록만은
#   남아서 dungeon_format.py "해금" 종류 오브젝트의 조건 판정에 쓰인다
#   (dungeon_system.해금상태_적용 참고). save_system.py가 이것도 JSON 호환을
#   위해 저장 시 [던전파일명, [x, y]] 리스트들의 리스트로 바꿨다가 불러올
#   때 다시 (던전파일명, (x, y)) 튜플들의 set으로 되돌린다.
# - 진행도["현재마을"]은 마을 파일명이 아니라 마을정보["마을명"](예:
#   "엘븐가드")을 그대로 쓴다 - town_XX.py 파일 자체는 자기 파일명을
#   모르고 "마을명" 필드만 갖고 있어서다.
# - 기본_마을목록()은 지금 존재하는 마을 파일(town_01A_T01_Elvengard.py,
#   town_01A_T02_hendonmyre.py, town_02A_T03_westcoast.py)을 담는다. 이 프로젝트는 아직 여러 파일에
#   흩어진 데이터를 자동 스캔해서 모으는 레지스트리 패턴이 없어서, 새 마을
#   파일이 추가되면 이 함수에도 손으로 import/등록을 추가해야 한다.

from game.data.town.town_01A_T01_Elvengard import 마을정보 as _엘븐가드
from game.data.town.town_01A_T02_hendonmyre import 마을정보 as _헨돈마이어
from game.data.town.town_02A_T03_westcoast import 마을정보 as _웨스트코스트

_시작_마을명 = "엘븐가드"  # 기본_마을목록() 중 "개방조건"이 None인 시작 마을


def 개방조건만족(마을정보, 진행도):
    """
    이 마을이 [마을이동] 목록에 뜰 수 있는지 확인한다.
    개방조건이 None이면 항상 뜬다 (시작 마을 등).
    """
    조건 = 마을정보.get("개방조건")
    if 조건 is None:
        return True

    if 조건["타입"] == "던전클리어":
        return 조건["대상"] in 진행도.get("클리어한던전", set())

    # 아직 정의되지 않은 타입
    return False


def 이동가능마을목록(전체마을목록, 진행도):
    """
    전체마을목록(마을정보 딕셔너리들의 리스트) 중에서
    현재 진행도로 갈 수 있는 마을들만 걸러서 반환한다.
    """
    return [마을 for 마을 in 전체마을목록 if 개방조건만족(마을, 진행도)]


def 이동가능던전목록(마을정보):
    """
    이 마을에서 [던전이동]으로 갈 수 있는 던전(소형지도) 파일명 목록을 반환한다.
    """
    return 마을정보["던전목록"]


# 던전 순서 해금 - D02~D10, D12~D17은 바로 앞 번호 던전의 보스를 깨야(진행도["클리어한던전"])
# 열린다. 마을 던전 목록에는 보이지만 그 전엔 비활성. 지역의 첫 던전 D01과 D11(하늘성 -
# 웨스트코스트 개방조건으로만)은 이 규칙 밖(항상 열림).
순서해금_범위 = [*range(2, 11), *range(12, 18)]


def 던전_번호(던전파일명):
    """ "dungeon_01A_D05_thunderland" -> 5. 형식이 다르면 None."""
    for 조각 in 던전파일명.split("_"):
        if len(조각) > 1 and 조각[0] == "D" and 조각[1:].isdigit():
            return int(조각[1:])
    return None


def 던전_열림(던전파일명, 진행도, 전체던전파일명들):
    """순서 해금 규칙으로 그 던전에 들어갈 수 있는지. 바로 앞 번호 던전 파일이 없으면 열림."""
    번호 = 던전_번호(던전파일명)
    if 번호 not in 순서해금_범위:
        return True
    앞던전 = next(
        (f for f in 전체던전파일명들 if 던전_번호(f) == 번호 - 1),
        None,
    )
    return 앞던전 is None or 앞던전 in 진행도.get("클리어한던전", set())


# =====================================================
# 마을 레지스트리 / 진행도
# =====================================================


def 기본_마을목록():
    """현재 게임에 존재하는 마을정보 전체 목록. 새 마을 파일이 추가되면
    이 함수에도 import + 리스트 추가를 손으로 해줘야 한다(위 모듈
    설명 참고)."""
    return [_엘븐가드, _헨돈마이어, _웨스트코스트]


def 새_진행도():
    """새 게임을 시작할 때 쓰는 초기 진행도. 클리어한 던전/오브젝트
    없음, 현재 위치는 시작 마을."""
    return {
        "클리어한던전": set(),
        "클리어한오브젝트": set(),
        "현재마을": _시작_마을명,
    }


def 던전_클리어_처리(진행도, 던전파일명):
    """던전을 클리어했을 때 호출한다. 진행도["클리어한던전"]에 추가한다
    (개방조건만족()의 "던전클리어" 타입 판정이 이 집합을 그대로 읽는다).
    이미 클리어한 던전이면 아무 변화 없다."""
    진행도.setdefault("클리어한던전", set()).add(던전파일명)


def 오브젝트_클리어_기록(진행도, 던전파일명, 좌표):
    """던전 맵 안의 특정 좌표 오브젝트(주로 몬스터 오브젝트 - 보스 등)를
    최소 1회 이상 클리어했다는 사실을 진행도에 영구적으로 기록한다.
    오브젝트 자체는 던전을 나갔다 다시 들어오면 그리드가 통째로 새로
    만들어지며 다시 "@"로 리셋되지만(dungeon_system.던전_시작 참고), 이
    기록만은 계속 남아서 dungeon_format.py "해금" 종류 오브젝트의 조건
    판정(dungeon_system.해금상태_적용)에 쓰인다. 이미 기록돼 있으면 아무
    변화 없다."""
    진행도.setdefault("클리어한오브젝트", set()).add((던전파일명, 좌표))


def 오브젝트_클리어됨(진행도, 던전파일명, 좌표):
    """오브젝트_클리어_기록()으로 기록된 적이 있는지 확인한다. "몇 번"이
    아니라 "한 번이라도 있었는지"만 본다."""
    return (던전파일명, 좌표) in 진행도.get("클리어한오브젝트", set())


def 마을_이동(진행도, 목표마을명, 전체마을목록=None):
    """진행도["현재마을"]을 목표마을명으로 바꾼다. 목표 마을이
    이동가능마을목록()에 없으면(=아직 개방되지 않았으면) ValueError를
    낸다. 전체마을목록을 생략하면 기본_마을목록()을 쓴다."""
    if 전체마을목록 is None:
        전체마을목록 = 기본_마을목록()

    이동가능_마을명들 = {
        마을["마을명"] for 마을 in 이동가능마을목록(전체마을목록, 진행도)
    }
    if 목표마을명 not in 이동가능_마을명들:
        raise ValueError(f"'{목표마을명}'(으)로 이동할 수 없다 (개방 조건 미충족).")

    진행도["현재마을"] = 목표마을명


