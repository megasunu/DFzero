# =====================
# 마법으로 봉인된 장비 - 봉인해제 / 봉인변환
# =====================
# 마을 [전문직업]의 [봉인해제]/[봉인변환](2026-10-15 사용자 결정). 데이터는
# game/data/equipment/eq_00_magic_seal.py(마봉능력, 봉인장비_해제이름).
#
# - "마법의 <마봉능력> <타입>"(예: "마법의 강타 소검")은 봉인 장비 + 마봉능력 하나로 정해지는
#   장비다. 봉인 장비마다 그 부위에 나올 수 있는 마봉능력 전부를 카탈로그에 미리 만들어 둔다
#   (카탈로그_추가) - 그래서 소지품/장착/세이브는 다른 장비처럼 이름만 다루고, 불러오면
#   카탈로그가 같은 장비를 다시 만든다(세이브 구조는 그대로).
# - 마법의 장비 = 봉인 장비 수치 + 장비 칸으로 바로 되는 효과(능력치/AC/명중/속도/데미지보너스/
#   집요함). 그 밖의 효과(대상타입, 발동, 최대HP 등)는 "마봉효과"에 그대로 둔다.
#   "마봉능력" 칸이 있는 장비는 도감/드랍/항아리 목록에 넣지 않는다.
# - 같은 마봉능력은 한 캐릭터에 한 번만 적용된다(10-16 사용자 결정 - 안젤루스 10개도 +1).
#   장비 칸에 더한 몫은 "마봉보너스"에 따로 적어 두고 equipment_system이 겹친 장비에서 뺀다.
# - 봉인해제: 봉인 장비 -> 그 부위 마봉능력 중 무작위 하나. 봉인변환: 마법의 장비 -> 지금 능력을
#   뺀 무작위 하나. 둘 다 100골드 + 레어 소울 1개. 소지품의 것이든 장착 중인 것이든 된다.

import copy
from game.system import rng

from game.data.equipment.eq_00_magic_seal import 마봉능력, 봉인장비_해제이름

비용 = {"골드": 100, "레어 소울": 1}
_봉인머리 = "마법으로 봉인된 "
_능력치 = ("근력", "민첩", "건강", "지능", "지혜", "매력")
# 마봉능력 효과의 변동대상 -> 장비 칸(대상타입/발동/속성이 없는 숫자 효과만)
_장비칸 = {
    "AC": "AC보너스",
    "명중보너스": "명중률보너스",
    "속도보너스": "속도보너스",
    "데미지보너스": "데미지보너스",
    "집요함": "집요함",
}


def 마법의_이름(봉인이름, 능력이름):
    """ "마법으로 봉인된 소검" + 강타 -> "마법의 강타 소검"."""
    return f"마법의 {능력이름} {봉인이름[len(_봉인머리) :]}"


def 봉인인가(아이템):
    return 아이템.get("이름") in 봉인장비_해제이름


def 마법의_장비인가(아이템):
    return "마봉능력" in 아이템


def _장비칸_효과(효과):
    """장비 칸으로 바로 더할 수 있는 효과면 (칸, 값), 아니면 None."""
    if "발동" in 효과 or "대상타입" in 효과 or "속성" in 효과:
        return None
    대상, 값 = 효과.get("변동대상"), 효과.get("변동값")
    if not isinstance(값, (int, float)):
        return None
    if 대상 in _능력치:
        return ("스탯보너스", 대상), 값
    if 대상 in _장비칸:
        return (_장비칸[대상], None), 값
    return None


def 마법의_장비_생성(봉인아이템, 능력이름):
    """봉인 장비 데이터 + 마봉능력 하나 -> 마법의 장비 데이터(새 dict)."""
    능력 = 마봉능력[능력이름]
    아이템 = copy.deepcopy(봉인아이템)
    아이템["이름"] = 마법의_이름(봉인아이템["이름"], 능력이름)
    아이템["봉인원본"] = 봉인아이템["이름"]
    아이템["마봉능력"] = 능력이름
    아이템["마봉설명"] = 능력["설명"]
    남은효과 = []
    더한것 = {}  # 장비 칸에 더한 몫 - 같은 능력이 겹치면 equipment_system이 이만큼 뺀다
    for 효과 in 능력["효과"]:
        칸값 = _장비칸_효과(효과)
        if 칸값 is None:
            남은효과.append(copy.deepcopy(효과))
            continue
        (칸, 능력치), 값 = 칸값
        for 대상 in (아이템, 더한것):
            if 능력치:
                스탯 = 대상.setdefault("스탯보너스", {})
                스탯[능력치] = 스탯.get(능력치, 0) + 값
            else:
                대상[칸] = 대상.get(칸, 0) + 값
    아이템["마봉효과"] = 남은효과
    아이템["마봉보너스"] = 더한것
    return 아이템


def 부위_능력목록(탭):
    """그 장비 탭에 나올 수 있는 마봉능력 이름(데이터 순서)."""
    return [이름 for 이름, 능력 in 마봉능력.items() if 탭 in 능력["부위"]]


def 카탈로그_추가(장비카탈로그):
    """장비 카탈로그 {탭: {이름: 데이터}}에 마법의 장비를 전부 더한다(제자리)."""
    for 탭, 아이템들 in 장비카탈로그.items():
        봉인들 = [a for a in 아이템들.values() if 봉인인가(a)]
        for 봉인 in 봉인들:
            for 능력이름 in 부위_능력목록(탭):
                새 = 마법의_장비_생성(봉인, 능력이름)
                아이템들[새["이름"]] = 새
    return 장비카탈로그


def _부위탭(장비카탈로그, 이름):
    return next((탭 for 탭, 아이템들 in 장비카탈로그.items() if 이름 in 아이템들), None)


def 대상목록(플레이어, 장비카탈로그, 모드, 숙소=()):
    """[{"이름", "아이템", "탭", "캐릭터", "슬롯", "수량"}] - 모드 "봉인해제"는 봉인 장비,
    "봉인변환"은 마법의 장비. 장착 중인 것은 캐릭터마다 한 줄(수량 1), 남은 것은 소지품 한 줄."""
    맞나 = 봉인인가 if 모드 == "봉인해제" else 마법의_장비인가
    보유 = 플레이어.get("소지품", {}).get("장비", {})
    캐릭터들 = list(플레이어.get("파티", {}).get("파티원", [])) + list(숙소)
    결과 = []
    for 이름, 개수 in 보유.items():
        탭 = _부위탭(장비카탈로그, 이름)
        if 탭 is None or 개수 <= 0 or not 맞나(장비카탈로그[탭][이름]):
            continue
        아이템 = 장비카탈로그[탭][이름]
        장착 = [
            (c, 슬롯)
            for c in 캐릭터들
            for 슬롯, 장착이름 in c.get("장착장비", {}).items()
            if 장착이름 == 이름
        ]
        for c, 슬롯 in 장착:
            결과.append(
                {
                    "이름": 이름,
                    "아이템": 아이템,
                    "탭": 탭,
                    "캐릭터": c,
                    "슬롯": 슬롯,
                    "수량": 1,
                }
            )
        남음 = 개수 - len(장착)
        if 남음 > 0:
            결과.append(
                {
                    "이름": 이름,
                    "아이템": 아이템,
                    "탭": 탭,
                    "캐릭터": None,
                    "슬롯": None,
                    "수량": 남음,
                }
            )
    return 결과


def _비용_확인(플레이어):
    소지품 = 플레이어.get("소지품", {})
    if 소지품.get("골드", 0) < 비용["골드"]:
        raise ValueError(f"골드가 부족합니다({비용['골드']}G 필요).")
    if 소지품.get("재료", {}).get("레어 소울", 0) < 비용["레어 소울"]:
        raise ValueError("레어 소울이 부족합니다(1개 필요).")


def _비용_치르기(플레이어):
    소지품 = 플레이어["소지품"]
    소지품["골드"] -= 비용["골드"]
    재료 = 소지품["재료"]
    재료["레어 소울"] -= 비용["레어 소울"]
    if 재료["레어 소울"] <= 0:
        del 재료["레어 소울"]


def _바꾸기(플레이어, 항목, 새이름):
    보유 = 플레이어["소지품"]["장비"]
    보유[항목["이름"]] -= 1
    if 보유[항목["이름"]] <= 0:
        del 보유[항목["이름"]]
    보유[새이름] = 보유.get(새이름, 0) + 1
    if 항목["캐릭터"] is not None:
        항목["캐릭터"]["장착장비"][항목["슬롯"]] = 새이름


def _능력_고르고_바꾸기(플레이어, 항목, 후보, 봉인이름):
    if not 후보:
        raise ValueError("붙일 수 있는 마봉능력이 없습니다.")
    _비용_확인(플레이어)
    새이름 = 마법의_이름(봉인이름, rng.보상.choice(후보))
    _비용_치르기(플레이어)
    _바꾸기(플레이어, 항목, 새이름)
    return 새이름


def 봉인해제(플레이어, 항목):
    """봉인 장비 하나를 마법의 장비로. 새 이름을 돌려준다. 비용이 모자라면 ValueError."""
    if not 봉인인가(항목["아이템"]):
        raise ValueError(f"'{항목['이름']}'은(는) 봉인된 장비가 아닙니다.")
    return _능력_고르고_바꾸기(플레이어, 항목, 부위_능력목록(항목["탭"]), 항목["이름"])


def 봉인변환(플레이어, 항목):
    """마법의 장비의 마봉능력을 지금 것을 뺀 무작위 하나로. 새 이름을 돌려준다."""
    아이템 = 항목["아이템"]
    if not 마법의_장비인가(아이템):
        raise ValueError(f"'{항목['이름']}'은(는) 봉인을 푼 장비가 아닙니다.")
    후보 = [n for n in 부위_능력목록(항목["탭"]) if n != 아이템["마봉능력"]]
    return _능력_고르고_바꾸기(플레이어, 항목, 후보, 아이템["봉인원본"])
