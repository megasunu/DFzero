def 세이브_핵심_문제목록(저장데이터):
    """save_system이 세이브를 읽을 때 쓰는 좁은 검사 - 파티원/숙소의 캐릭터가 핵심 칸(이름/직업/레벨/HP/MP)을
    갖고 있는지만 본다. 변환(마이그레이션) 뒤의 저장데이터를 받는다."""
    플레이어 = 저장데이터.get("플레이어")
    if not isinstance(플레이어, dict):
        return ["플레이어: 딕셔너리가 아니다"]
    문제 = []
    파티원 = (플레이어.get("파티") or {}).get("파티원")
    숙소 = 플레이어.get("숙소")
    for 이름, 목록 in (("파티원", 파티원), ("숙소", 숙소)):
        if not isinstance(목록, list):
            문제.append(f"{이름}: 목록이 아니다")
            continue
        for 번호, 캐릭터 in enumerate(목록):
            문제 += 문제목록(캐릭터, 캐릭터_핵심, 이름=f"{이름}[{번호}]")
    return 문제
