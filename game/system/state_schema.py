def _타입_맞음(값, 타입들):
    if isinstance(값, bool) and bool not in 타입들:
        return False
    return isinstance(값, 타입들)


def 문제목록(값, 스키마, 선택칸=None, 이름="값", 모르는칸_허용=True):
    """값(딕셔너리)이 스키마(칸 -> 허용 타입들)대로인지 보고 문제 목록(문자열)을 돌려준다. 없는 칸,
    타입이 다른 칸을 찾는다. 모르는 칸(스키마에 없는 것)은 모르는칸_허용이 False일 때만 문제로 본다 -
    새 칸이 생기면 표에 더하라고 알려 주려는 용도다."""
    if not isinstance(값, dict):
        return [f"{이름}: 딕셔너리가 아니다({type(값).__name__})"]
    선택칸 = 선택칸 or {}
    문제 = []
    for 칸, 타입들 in 스키마.items():
        if 칸 not in 값:
            문제.append(f"{이름}: '{칸}' 칸이 없다")
        elif not _타입_맞음(값[칸], 타입들):
            문제.append(
                f"{이름}: '{칸}'은 {_타입_이름(타입들)}여야 하는데 {type(값[칸]).__name__}"
            )
    for 칸, 타입들 in 선택칸.items():
        if 칸 in 값 and not _타입_맞음(값[칸], 타입들):
            문제.append(
                f"{이름}: '{칸}'은 {_타입_이름(타입들)}여야 하는데 {type(값[칸]).__name__}"
            )
    if not 모르는칸_허용:
        모르는 = sorted(set(값) - set(스키마) - set(선택칸))
        if 모르는:
            문제.append(f"{이름}: 표에 없는 칸 {모르는}")
    return 문제


def _타입_이름(타입들):
    return "/".join(t.__name__ for t in 타입들)


def 캐릭터_문제목록(캐릭터, 엄격=False):
    """표준 모양 검사(테스트용). 엄격이면 표에 없는 칸도 문제로 본다."""
    이름 = (
        f"캐릭터 {캐릭터.get('캐릭터명', '?')}"
        if isinstance(캐릭터, dict)
        else "캐릭터"
    )
    return 문제목록(캐릭터, 캐릭터_스키마, 캐릭터_선택칸, 이름, 모르는칸_허용=not 엄격)


