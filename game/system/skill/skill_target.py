_중심대상_필요 = ("아군단일", "적단일", "적3체")


def 하단공격_빗나감인가(전투상태, 대상, 태그):
    """ "하단공격" 타입 공격이 공중에뜸 상태인 대상에게 닿지 않는가(2026-10-21 사용자 결정, #325) -
    그 대상은 지정할 수 없고 범위에 들어 있어도 피해를 받지 않는다."""
    return "하단공격" in (태그 or ()) and "공중에뜸" in status.상태이상_이름들(
        전투상태, 대상
    )


def 대상_검증(전투상태, 타겟종류, 중심대상=None, 태그=()):
    """타겟_확장이 거부할 대상을 무작위/부작용 없이 미리 거부한다(ValueError).
    스킬_실행이 비용을 쓰기 전에 부른다(B7). 이미 쓰러진 참가자는 단일 대상으로
    지정할 수 없다 - 부활 규칙이 없으므로(B12). 태그(스킬 "타입")에 "하단공격"이 있으면
    공중에뜸 상태인 대상을 지정할 수 없다(범위 공격의 중심 대상도)."""
    if 타겟종류 in _중심대상_필요 and 중심대상 is None:
        raise ValueError(f"'{타겟종류}' 타겟은 대상을 지정해야 한다.")
    if 타겟종류 in ("아군단일", "적단일") and not 중심대상["생존"]:
        raise ValueError(f"'{중심대상['이름']}'은(는) 이미 쓰러져 지정할 수 없다.")
    if 타겟종류 in ("아군단일", "적단일") and status.상태이상_플래그(
        전투상태, 중심대상, "지정불가"
    ):
        raise ValueError(
            f"'{중심대상['이름']}'은(는) 지정 불가 상태(은신 등)라 단일 대상으로 지정할 수 없다."
        )
    if 중심대상 is not None and 하단공격_빗나감인가(전투상태, 중심대상, 태그):
        raise ValueError(
            f"'{중심대상['이름']}'은(는) 공중에 떠 있어 하단공격으로 지정할 수 없다."
        )


def 스킬_타겟종류(스킬데이터, 타겟종류오버라이드=None):
    """스킬_실행이 실제로 쓸 (첫) 타겟 종류 - 실행 함수들의 선택과 같다."""
    타입목록 = 스킬데이터.get("타입", [])
    if 스킬데이터["분류"] == "공격스킬":
        if "분할공격" in 타입목록:
            return 스킬데이터["공격단계1"].get("타겟")
        if "지속공격" in 타입목록:
            return 스킬데이터["지속공격"]["타겟"]
        return 타겟종류오버라이드 or 스킬데이터.get("타겟")
    return 스킬데이터.get("타겟")


def 타겟_확장(전투상태, 시전자, 타겟종류, 중심대상=None):
    """job_skill_format.py <타겟 종류>를 실제 참가자 리스트로 풀어낸다.
    "적랜덤반복"/"적반복지정"은 공격마다 다시 골라야 해서 여기서는 후보
    풀(생존한 적 전체)만 반환하고, 실제 선택은 공격스킬_실행()이 한다.

    "적단일"/"아군단일"처럼 대상을 직접 지정해야 하는 타겟은, 그 대상이
    "지정불가"(은신) 상태면 거부한다 - "적3체"/"적전체" 같은 범위 타겟은
    은신 대상도 그대로 포함한다("범위공격피격" 설명대로, 범위 공격에는
    은신이 걸린 채로도 맞을 수 있어야 하기 때문이다)."""
    참가자들 = 전투상태["참가자"]
    대상_검증(전투상태, 타겟종류, 중심대상)

    if 타겟종류 == "자신":
        return [시전자]
    if 타겟종류 == "아군단일":
        return [중심대상]
    if 타겟종류 == "아군전체":
        return [p for p in 참가자들 if p["진영"] == "아군" and p["생존"]]

    적생존 = [p for p in 참가자들 if p["진영"] == "적" and p["생존"]]
    if 시전자.get(
        "_혼란반전"
    ):  # 혼란 - "적"은 자기 편 동료(자신 제외, 스킬_실행이 중심대상을 동료로 바꿨다)
        동료 = status.혼란_동료들(전투상태, 시전자)
        if 타겟종류 == "적3체":
            줄 = sorted(
                (p for p in 참가자들 if p["진영"] == 시전자["진영"]),
                key=lambda p: p.get("대형위치", 0),
            )
            idx = 줄.index(중심대상)
            return [
                p
                for p in 줄[max(0, idx - 1) : idx + 2]
                if p["생존"] and p is not 시전자
            ]
        if 타겟종류 in ("적전체", "적랜덤반복", "적반복지정"):
            return 동료
        if 타겟종류 == "적랜덤":
            return [rng.대상.choice(동료)] if 동료 else []
        return [중심대상]

    # 감옥(사용자 지정 2026-10-14): 갇힌 사람이 지정한 대상 몫은 그 감옥이 받고, 아군의 전체 공격은 감옥에도 맞는다
    if 타겟종류 == "적단일":
        return [status.감옥_대상(전투상태, 시전자, 중심대상)]
    if 타겟종류 == "적전체":
        return 적생존 + [p for p in 참가자들 if p.get("감옥") and p["생존"]]
    if 타겟종류 == "적랜덤":
        return [rng.대상.choice(적생존)] if 적생존 else []
    if 타겟종류 == "적3체":
        # "구석이면 2체" - 적 전체(생존 여부 무관)를 "대형위치" 순으로
        # 나열한 뒤, 중심 대상의 바로 앞/뒤 칸만 포함한다. 죽은 적이 빠져도
        # 대열이 당겨지지 않는다 - 그 칸이 죽은 참가자면
        # 그냥 대상에서 빠질 뿐, 그 너머 참가자를 대신 끌어오지 않는다.
        적전체 = sorted(
            (p for p in 참가자들 if p["진영"] == "적"),
            key=lambda p: p.get("대형위치", 0),
        )
        if 중심대상 not in 적전체:
            return [중심대상]
        idx = 적전체.index(중심대상)
        후보 = 적전체[max(0, idx - 1) : idx + 2]
        감옥 = status.감옥_대상(전투상태, 시전자, 중심대상)
        return [감옥 if p is 중심대상 else p for p in 후보 if p["생존"]]
    if 타겟종류 in ("적랜덤반복", "적반복지정"):
        return 적생존

    raise ValueError(f"알 수 없는 타겟 종류: {타겟종류!r}")


