def _행동종류목록(행동):
    if 행동 is None:
        return []
    if isinstance(행동, list):
        return 행동
    return [행동]


# "쇼타임행동"(buff.py "쇼타임행동증가", job_skill_40_mage.py "쇼타임" 버프스킬로
# 획득)이 있으면, 아래 타입이 붙은 스킬(job_skill_41_elemental_master.py의
# "중급마법"/"상급마법" 태그 등 실 데이터로 확인)의 "일반행동" 요구를
# 참가자["기타행동"]["쇼타임행동"]으로 대신 낼 수 있다 - 진짜 일반행동보다
# 우선 소모한다.
_쇼타임_적용_타입 = {"하급마법", "중급마법", "상급마법"}


def _쇼타임_대상스킬인가(스킬데이터):
    return bool(_쇼타임_적용_타입.intersection(스킬데이터.get("타입", [])))


def 일반행동_지불수단_목록(전투상태, 참가자, 스킬데이터):
    """스킬의 "일반행동"을 지금 낼 수 있는 수단 목록(기본 순서) - "추가행동"(일반공격취급
    스킬, 이번 턴에 열렸을 때 - combat.resources 추가행동) / "쇼타임행동"(쇼타임 대상 마법) /
    "일반행동". 추가행동이 남아
    있으면 일반행동은 빼서(턴이 끝나면 사라지는 쪽을 먼저 쓴다) 고르는 팝업을 띄우지 않는다.
    스킬이 "일반행동"을 요구하지 않으면 빈 리스트. 둘 이상이면 화면이 고르게 한다(gameflow.스킬_행동선택지)."""
    행동들 = _행동종류목록(스킬데이터.get("행동"))
    if "일반행동" not in 행동들:
        return []
    결과 = []
    if (
        스킬데이터.get("분류") == "소환스킬"
        and 참가자.get("기타행동", {}).get("교감행동", 0) > 0
    ):
        결과.append("교감행동")  # 교감 - 턴당 (차수-1)번
    추가 = 스킬데이터.get("일반공격취급") and resources.추가행동_남은수(참가자) > 0
    if 추가:
        결과.append("추가행동")
    if (
        _쇼타임_대상스킬인가(스킬데이터)
        and 참가자.get("기타행동", {}).get("쇼타임행동", 0) > 0
    ):
        결과.append("쇼타임행동")
    if not 추가 and 참가자["행동자원"].get("일반행동", 0) > 0:
        결과.append("일반행동")
    return 결과


def _일반행동_지불수단(전투상태, 참가자, 스킬데이터, 행동지불=None):
    """스킬의 "일반행동"을 무엇으로 낼지. 행동지불(고른 수단)이 낼 수 있는 수단이면
    그것, 아니면 기본 순서(추가행동 -> 쇼타임행동 -> 일반행동)의 첫 번째. 없으면 None."""
    목록 = 일반행동_지불수단_목록(전투상태, 참가자, 스킬데이터)
    if 행동지불 in 목록:
        return 행동지불
    return 목록[0] if 목록 else None


def 스킬강화(참가자, 스킬데이터):
    """참가자(아군)가 레벨 12 "스킬강화"로 이 스킬을 강화했으면 그 기록
    ({"스킬", "최종피해배율", "MP소모배율"} - character_levelup_system._스킬강화_처리),
    아니면 None."""
    강화 = (참가자.get("원본") or {}).get("스킬강화")
    if 강화 and 강화.get("스킬") == 스킬데이터.get("_이름"):
        return 강화
    return None


def MP소모_배율(참가자, 스킬데이터):
    """중갑/판금 패널티 x 스킬강화 - 곱연산."""
    강화 = 스킬강화(참가자, 스킬데이터)
    return stats.MP소모_배율(참가자) * (강화["MP소모배율"] if 강화 else 1)


def _상태_제한_사유(전투상태, 참가자, 스킬데이터):
    """ "행동불가"(기절/공중에뜸/수면/빙결/석화)와 "혼란"(일반공격만)으로 못 쓰는 사유. 쓸 수 있으면 None."""
    if status.상태이상_플래그(전투상태, 참가자, "행동불가"):
        return "행동불가 상태라 아무 것도 할 수 없다."
    행동제한 = status.상태이상_행동제한(전투상태, 참가자)
    if 행동제한 == "일반공격만" and not 스킬데이터.get("일반공격취급"):
        return "혼란 상태라 일반공격(취급 스킬)만 쓸 수 있다."
    # 버프 "스킬제한"(공중사격 #391) - "허용스킬" 이름이나 "허용타입" 타입의 스킬만
    태그 = set(스킬데이터.get("타입") or ())
    for 버프이름, 원소 in stats.버프_효과원소목록(전투상태, 참가자, "스킬제한"):
        if 스킬데이터.get("_이름") not in (원소.get("허용스킬") or ()) and not (
            태그 & set(원소.get("허용타입") or ())
        ):
            return f"'{버프이름}' 상태라 이 스킬을 쓸 수 없다."
    return None


def _행동_자원_사유(전투상태, 참가자, 스킬데이터):
    """스킬이 쓰는 행동(일반/보조/반응/전체소모)이 남아 있지 않은 사유. 있으면 None."""
    행동들 = _행동종류목록(스킬데이터.get("행동"))
    if "전체소모" in 행동들:
        if all(참가자["행동자원"].get(k, 0) <= 0 for k in common_names.행동자원_종류):
            return "소모할 행동이 하나도 남아있지 않다."
        return None
    for 행동 in 행동들:
        if 행동 == "일반행동":
            if _일반행동_지불수단(전투상태, 참가자, 스킬데이터) is None:
                return f"'{행동}'이(가) 남아있지 않다."
            continue
        if 참가자["행동자원"].get(행동, 0) <= 0:
            return f"'{행동}'이(가) 남아있지 않다."
    return None


def 스킬_비용(전투상태, 참가자, 스킬데이터, MP소모오버라이드=None):
    """("MP" | "HP", 양) - 스킬을 쓸 때 실제로 드는 것. MP소모(오버라이드)에 중갑/판금·스킬강화 배율을
    곱하고, 특성 "MP소모체력전환"(버서커 혈기왕성 #247)이 있으면 그 배율을 곱해 올림한 HP로 바꾼다."""
    MP소모 = MP소모오버라이드
    if MP소모 is None:
        MP소모 = 스킬데이터.get("MP소모", 0)
    MP소모 *= MP소모_배율(참가자, 스킬데이터)  # 중갑/판금 패널티, 스킬강화
    전환 = status.특성_변동값목록(전투상태, 참가자, "MP소모체력전환")
    if 전환 and MP소모:
        return "HP", formula.올림(MP소모 * 전환[0])
    return "MP", MP소모


def _MP_사유(전투상태, 참가자, 스킬데이터, MP소모오버라이드):
    종류, MP소모 = 스킬_비용(전투상태, 참가자, 스킬데이터, MP소모오버라이드)
    # HP로 내는 비용(혈기왕성)은 다 내고도 HP가 1 이상 남을 때만 낸다 - 현재 HP > 비용(사용자 결정 2026-10-26, #400).
    if 종류 == "HP" and MP소모 and 참가자["현재HP"] <= MP소모:
        return f"HP가 부족하다 (필요 {MP소모}, 보유 {참가자['현재HP']})."
    # MP 칸이 없는 참가자(몬스터)는 보유 0으로 본다 - MP가 드는 스킬은 못 쓴다.
    if 종류 == "MP" and MP소모 and 참가자.get("현재MP", 0) < MP소모:
        return f"MP가 부족하다 (필요 {MP소모}, 보유 {참가자.get('현재MP', 0)})."
    켤때 = 스킬데이터.get("켤때MP")  # 전환스킬(나선의 넨 #280) - 켤 때만 드는 MP
    if 켤때 and not _전환특성_켜짐(참가자, 스킬데이터):
        if 참가자.get("현재MP", 0) < 켤때:
            return f"MP가 부족하다 (켤 때 {켤때}, 보유 {참가자.get('현재MP', 0)})."
    return None


def _전환특성_켜짐(참가자, 스킬데이터):
    원본 = 참가자.get("원본") or {}
    return 스킬데이터.get("전환특성") in (원본.get("켜진특성") or [])


def _자원소모_사유(전투상태, 참가자, 스킬데이터, 자원소모오버라이드):
    자원소모 = (
        자원소모오버라이드
        if 자원소모오버라이드 is not None
        else 스킬데이터.get("자원소모")
    )
    for 이름, 개수 in (자원소모 or {}).items():
        if resources.자원_보유량(전투상태, 참가자, 이름) < 개수:
            return f"'{이름}' 자원이 부족하다."
    return None


def _사용횟수_사유(전투상태, 참가자, 스킬데이터):
    """턴당사용제한/전투당횟수/휴식당횟수를 다 쓴 사유. 아직 쓸 수 있으면 None.
    켜고 끄는 "전환스킬"은 따로 적지 않아도 턴당 1회다(2026-10-21 사용자 결정) - 행동을 쓰지 않는
    프렌지도 한 차례에 한 번만 바꾼다. 던전 화면에서 바꾸는 것은 전투 밖이라 제한이 없다."""
    스킬이름 = 스킬데이터.get("_이름", "이스킬")
    턴당제한 = 스킬데이터.get(
        "턴당사용제한", 1 if 스킬데이터.get("분류") == "전환스킬" else None
    )
    if 턴당제한 is not None:
        이번턴 = 참가자.get("이번턴_스킬사용횟수", {}).get(스킬이름, 0)
        if 이번턴 >= 정수_평가(턴당제한, 전투상태, 참가자):
            return "이번 턴에 더 쓸 수 없다 (턴당사용제한)."

    전투당제한 = 스킬데이터.get("전투당횟수")
    if 전투당제한 is not None:
        이번전투 = 참가자.get("전투당_스킬사용횟수", {}).get(스킬이름, 0)
        if 이번전투 >= 정수_평가(전투당제한, 전투상태, 참가자):
            return "이번 전투에 더 쓸 수 없다 (전투당횟수)."
    # 휴식당횟수: 캐릭터["횟수제한스킬"]["휴식제한스킬"]에 남은
    # 횟수를 영구 저장한다(휴식_남은횟수 참고). 다 쓰면 휴식 전까지 못 쓴다.
    남은정보 = 휴식_남은횟수(전투상태, 참가자, 스킬데이터)
    if 남은정보 is not None and 남은정보[0] <= 0:
        return f"휴식당 사용 횟수({남은정보[1]}회)를 모두 썼다. 휴식하면 회복된다."
    return None


def 사용_가능여부(
    전투상태, 참가자, 스킬데이터, MP소모오버라이드=None, 자원소모오버라이드=None
):
    """행동자원/MP/자원소모/턴당사용제한/전투당횟수를 검사한다. "행동불가"
    (기절/공중에뜸/수면/빙결/석화)면 어떤 스킬도 쓸 수 없고, "혼란"의
    "행동제한"(일반공격만)이면 "일반공격취급"이 아닌 스킬은 쓸 수 없다.
    "하급마법"/"중급마법"/"상급마법" 타입 스킬은 "일반행동" 대신
    참가자["기타행동"]["쇼타임행동"]이 있으면 그걸로 대신 낼 수 있다(_일반행동_지불수단 참고).
    (가능여부, 사유) 튜플을 반환하며, 불가능할 때만 사유가 채워진다.
    "반응스킬"은 조건이 맞으면 저절로 쓰여서(combat.reactions), "연계스킬"은 앞 스킬에 이어 쓰여서
    (skill_attack.특성_후속공격) 직접 쓸 수 없다.
    검사는 위에서부터 차례로 하고 처음 걸린 사유를 돌려준다(뒤 검사는 하지 않는다)."""
    if 스킬데이터.get("분류") == "반응스킬":
        return False, "반응스킬은 조건이 맞으면 저절로 쓰인다."
    if 스킬데이터.get("분류") == "던전스킬":
        return False, "던전스킬은 던전 화면에서만 쓴다."
    if 스킬데이터.get("분류") == "특성스킬":
        return False, "특성으로 얻는 항목이라 쓰는 스킬이 아니다."
    if "연계스킬" in (스킬데이터.get("타입") or []):
        return False, "연계스킬은 앞 스킬에 이어 저절로 쓰인다."
    사유 = (
        _상태_제한_사유(전투상태, 참가자, 스킬데이터)
        or _행동_자원_사유(전투상태, 참가자, 스킬데이터)
        or _MP_사유(전투상태, 참가자, 스킬데이터, MP소모오버라이드)
        or _자원소모_사유(전투상태, 참가자, 스킬데이터, 자원소모오버라이드)
        or _사용횟수_사유(전투상태, 참가자, 스킬데이터)
        or _체이서_사유(참가자, 스킬데이터)
        or _사용무기_사유(참가자, 스킬데이터)
        or _소환조건_사유(참가자, 스킬데이터)
    )
    return (False, 사유) if 사유 else (True, None)


def 소환그룹_이름들(그룹):
    """summon_00 "소환한도그룹"이 그 그룹인 소환수 이름들(하급정령 4종 / 아우쿠소)."""
    return [
        이름
        for 이름, 정의 in summon_00.소환수목록.items()
        if 정의.get("소환한도그룹") == 그룹
    ]


def _소환조건_사유(참가자, 스킬데이터):
    """정령/계약소환(#413) - 상급정령은 "필요소환수"가 있어야, 환수희생은 하급정령이 있어야 쓴다.
    "소환한도"가 없는 소환스킬(상급·계약)은 이미 그 소환수가 있으면 또 부르지 않는다(한 마리씩)."""
    필요 = 스킬데이터.get("필요소환수")
    if 필요 and 소환수_마릿수(참가자, 필요) <= 0:
        return f"하급정령 '{필요}'이(가) 있어야 한다."
    그룹 = 스킬데이터.get("환수희생")
    if 그룹 and not any(소환수_마릿수(참가자, n) for n in 소환그룹_이름들(그룹)):
        return "돌려보낼 하급정령이 없다."
    if 스킬데이터.get("분류") == "소환스킬" and not 스킬데이터.get("소환한도"):
        버프 = 스킬데이터.get("버프획득")
        효과 = (
            (resources.효과정의_조회(버프)[0] or {}).get("효과")
            if isinstance(버프, str)
            else None
        )
        if (
            isinstance(효과, dict)
            and 효과.get("타입") == "소환수"
            and not 효과.get("중첩당공격")
            and 소환수_마릿수(참가자, 효과.get("소환수이름")) > 0
        ):
            return f"'{효과['소환수이름']}'은(는) 이미 소환되어 있다."
    return None


def _사용무기_사유(참가자, 스킬데이터):
    """ "사용무기"(마도학자 파우더·빗자루 스핀 - 빗자루)가 있으면 그 무기를 들어야 쓴다."""
    무기 = 스킬데이터.get("사용무기")
    if 무기 and traits.장착무기_타입(참가자) != 무기:
        return f"무기 '{무기}'를 들어야 쓸 수 있다."
    return None


def _체이서_사유(참가자, 스킬데이터):
    """ "체이서소모" 스킬(배틀메이지)은 체이서가 하나도 없으면 쓸 수 없다."""
    if 스킬데이터.get("체이서소모") and not resources.체이서_목록(참가자):
        return "체이서가 없다."
    return None


def _휴식제한_칸(참가자):
    """캐릭터 원본의 "횟수제한스킬"["휴식제한스킬"] 딕셔너리(스킬이름 ->
    남은횟수). 필드가 없는 캐릭터(구버전 세이브)도 여기서 만들어 준다. 몬스터는 None."""
    if 참가자.get("진영") != "아군":
        return None
    원본 = 참가자["원본"]
    return 원본.setdefault("횟수제한스킬", {}).setdefault("휴식제한스킬", {})


def 휴식_남은횟수(전투상태, 참가자, 스킬데이터):
    """ "휴식당횟수"가 있는 스킬이면 (남은횟수, 최대횟수), 아니면 None.
    칸에 기록이 없으면 아직 안 쓴 것으로 보고 최대횟수를 남은횟수로 쓴다
    (character_data_system.py "횟수제한스킬" 설명). 최대횟수 수식("2+차수")은
    지금 차수로 평가한다."""
    제한 = 스킬데이터.get("휴식당횟수")
    칸 = _휴식제한_칸(참가자)
    if 제한 is None or 칸 is None:
        return None
    최대 = 정수_평가(제한, 전투상태, 참가자)
    스킬이름 = 스킬데이터.get("_이름", "이스킬")
    return min(칸.get(스킬이름, 최대), 최대), 최대


def 자원_소비_처리(
    전투상태,
    참가자,
    스킬데이터,
    MP소모오버라이드=None,
    자원소모오버라이드=None,
    행동지불=None,
):
    """행동자원/MP/자원소모를 실제로 깎고 사용 횟수를 기록한다.
    사용_가능여부()로 가능하다고 확인한 뒤에만 불러야 한다. "일반행동"은
    _일반행동_지불수단() 순서(추가행동 -> 쇼타임행동 -> 일반행동)로 깎는다 -
    행동지불을 주면(화면에서 고른 수단) 그것으로 낸다."""
    행동들 = _행동종류목록(스킬데이터.get("행동"))
    if "전체소모" in 행동들:
        for k in common_names.행동자원_종류:
            참가자["행동자원"][k] = 0
    else:
        for 행동 in 행동들:
            if 행동 == "일반행동":
                수단 = _일반행동_지불수단(전투상태, 참가자, 스킬데이터, 행동지불)
                if 수단 in ("쇼타임행동", "교감행동"):
                    참가자["기타행동"][수단] -= 1
                    continue
                if 수단 == "추가행동":
                    resources.추가행동_소모(참가자)
                    continue
                행동 = 수단 or "일반행동"
                if 행동 == "일반행동" and 스킬데이터.get("일반공격취급"):
                    resources.추가행동_열기(
                        참가자, stats.추가공격_보너스(전투상태, 참가자)
                    )
            참가자["행동자원"][행동] = 참가자["행동자원"].get(행동, 0) - 1

    종류, 양 = 스킬_비용(전투상태, 참가자, 스킬데이터, MP소모오버라이드)
    if 종류 == "HP":
        damage.체력_소모(전투상태, 참가자, 양)
    elif 양:
        참가자["현재MP"] -= 양

    자원소모 = (
        자원소모오버라이드
        if 자원소모오버라이드 is not None
        else 스킬데이터.get("자원소모")
    )
    if 자원소모:
        # 오버차지("스택유지" #391) 동안은 류탄의 수류탄이 줄지 않는다
        유지 = bool(stats.버프_효과원소목록(전투상태, 참가자, "스택유지"))
        for 이름, 개수 in 자원소모.items():
            if not (유지 and 이름 == "수류탄"):
                resources.자원_소모(전투상태, 참가자, 이름, 개수)

    스킬이름 = 스킬데이터.get("_이름", "이스킬")
    남은정보 = 휴식_남은횟수(전투상태, 참가자, 스킬데이터)
    if 남은정보 is not None:
        _휴식제한_칸(참가자)[스킬이름] = max(0, 남은정보[0] - 1)
    참가자.setdefault("이번턴_스킬사용횟수", {})
    참가자.setdefault("전투당_스킬사용횟수", {})
    참가자["이번턴_스킬사용횟수"][스킬이름] = (
        참가자["이번턴_스킬사용횟수"].get(스킬이름, 0) + 1
    )
    참가자["전투당_스킬사용횟수"][스킬이름] = (
        참가자["전투당_스킬사용횟수"].get(스킬이름, 0) + 1
    )
