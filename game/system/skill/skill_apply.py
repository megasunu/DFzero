@dataclass
class _효과문맥:
    """효과_적용 한 번 동안 효과 항목마다 같은 값들(처리기가 공유한다)."""

    전투상태: dict
    시전자: dict
    대상: dict
    주대상피해: int = 0
    속성: str | None = None
    데미지식: str | None = None
    데미지보너스: int = 0
    최종피해배율: float = 1


def _내성_실패인가(문맥, 항목, 이점검사):
    """ "상태이상"/"지속피해" 효과의 내성굴림. 난이도는 수식이면 시전자 기준으로 평가하고,
    대상이 "저주"(내성굴림불리점)면 불리하게 굴린다. 이점검사가 True면 대상의 상태이상내성이점
    특성(가죽숙달 등)도 반영한다. (내성에 실패했는가, "DC 난이도 vs 굴린 값", 계산 줄들) 튜플 -
    계산 줄은 상세로그일 때만("DC 계산: 식 = 값", "내성 계산: 주사위(눈)+스탯 보정(값) = 합")."""
    난이도 = 항목.get("난이도", 10)
    원식 = 난이도
    if isinstance(난이도, str):
        난이도 = formula.수식_평가(
            난이도, stats.기본_컨텍스트(문맥.전투상태, 문맥.시전자)
        )
    내성보정치 = stats.내성굴림_보정치(문맥.전투상태, 문맥.대상, 항목["내성"])
    불리 = status.상태이상_플래그(문맥.전투상태, 문맥.대상, "내성굴림불리점")
    이점 = (
        traits.상태이상_내성이점(문맥.전투상태, 문맥.대상, 항목["이름"])
        if 이점검사
        else False
    )
    성공, 값 = dice_utils.내성_굴림(내성보정치, 난이도, 이점=이점, 불리=불리)
    계산 = []
    if stats.상세로그(문맥.전투상태):
        계산 = [
            f"DC 계산: {원식} = {난이도}"
            if isinstance(원식, str)
            else f"DC 계산: {난이도}",
            f"내성 계산: 주사위({값 - 내성보정치})+{항목['내성']} 보정({내성보정치}) = {값}",
        ]
    return not 성공, f"DC {난이도} vs {값}", 계산


def _효과_상태이상(문맥, 항목, 로그):
    대상 = 문맥.대상
    실패, 굴림, 계산 = _내성_실패인가(문맥, 항목, 이점검사=True)
    로그 += 계산
    if 실패:
        상태이상_부여(
            문맥.전투상태,
            대상,
            항목["이름"],
            정수_평가(항목.get("지속턴", 1), 문맥.전투상태, 대상),
            해제난이도=항목.get("해제난이도"),
        )
        로그.append(f"{굴림}, 내성 실패! {대상['이름']}에게 '{항목['이름']}' 부여")
    else:
        로그.append(
            f"{굴림}, 내성 성공! {대상['이름']}이(가) '{항목['이름']}'을(를) 피함"
        )


def _효과_자동상태(문맥, 항목, 로그):
    대상 = 문맥.대상
    상태이상_부여(
        문맥.전투상태,
        대상,
        항목["이름"],
        정수_평가(항목.get("지속턴", 1), 문맥.전투상태, 대상),
        해제난이도=항목.get("해제난이도"),
    )
    로그.append(f"{대상['이름']}에게 '{항목['이름']}' 자동 부여")


def _효과_지속피해(문맥, 항목, 로그):
    # 이 "지속피해"는 status_effects.py 4분류(지속피해형)와는 다른,
    # 스킬이 직접 정의하는 커스텀 지속피해다. "상태이상" 종류와 같은
    # 방식으로 최초 적용될 때만 "내성"/"난이도"로 내성굴림을 하고
    # (지속공격과 달리 매 턴 재판정하지 않는다),
    # 실패해야만 걸린다. 한 번 걸리면 지속턴이 다 될 때까지(또는
    # 디버프해제로 없어질 때까지) 매 턴 그대로 피해를 입는다 - 대상
    # 본인 턴종료시 combat.damage.지속피해_스킬_적용이 "출처"에
    # 저장된 값으로 실제 발동시킨다(combat 패키지 모듈 docstring
    # 참고).
    대상 = 문맥.대상
    실패, 굴림, 계산 = _내성_실패인가(문맥, 항목, 이점검사=False)
    로그 += 계산
    if not 실패:
        로그.append(
            f"{굴림}, 내성 성공! {대상['이름']}이(가) 지속피해 '{항목['이름']}'을(를) 피함"
        )
        return
    대상.setdefault("상태이상", []).append(
        {
            "이름": 항목["이름"],
            "종류": "지속피해",
            "지속턴": 정수_평가(항목.get("지속턴", 1), 문맥.전투상태, 대상),
            "출처": {
                "데미지": 문맥.데미지식,
                "데미지보너스": 문맥.데미지보너스,
                "속성": 문맥.속성,
                "시전자이름": 문맥.시전자["이름"],
                "시전자id": 문맥.시전자.get("id"),
                # 스킬강화한 스킬일 때만(키가 없으면 1)
                **(
                    {"최종피해배율": 문맥.최종피해배율}
                    if 문맥.최종피해배율 != 1
                    else {}
                ),
            },
        }
    )
    로그.append(f"{대상['이름']}에게 지속피해 '{항목['이름']}' 등록 (내성 실패)")


def _효과_아군버프(문맥, 항목, 로그):
    대상들 = 타겟_확장(문맥.전투상태, 문맥.시전자, 항목.get("타겟", "아군전체"))
    for 아군 in 대상들:
        이름있는효과_부여(
            문맥.전투상태,
            아군,
            항목["이름"],
            지속턴오버라이드=정수_평가(항목.get("지속턴", 1), 문맥.전투상태, 아군),
            시전자=문맥.시전자,
        )
    로그.append(f"'{항목['이름']}' 버프를 {항목.get('타겟')}에 부여")


def _효과_해제(문맥, 항목, 로그):
    """ "버프해제"/"디버프해제" - 이름 지정이면 그것을, 아니면 해제개수만큼 무작위로 뗀다."""
    대상 = 문맥.대상
    종류 = 항목["종류"]
    목록이름 = "버프" if 종류 == "버프해제" else "디버프"
    if 항목.get("대상") == "지정":
        이름있는효과_해제(대상, 목록이름, 항목["이름"])
    else:
        해제개수 = 정수_평가(항목.get("해제개수", 1), 문맥.전투상태, 대상)
        후보 = [
            i
            for i in 대상[목록이름]
            if not 자원류_효과인가(resources.효과정의_조회(i["이름"])[0])
        ]
        rng.대상.shuffle(후보)
        for i in 후보[:해제개수]:
            대상[목록이름].remove(i)
    로그.append(f"{대상['이름']}의 {종류} 처리")


def _효과_범위분배(문맥, 항목, 로그):
    대상 = 문맥.대상
    대상지정 = 항목.get("대상")
    if 대상지정 != "양옆1체씩":
        로그.append(f"'범위분배' 대상 표기 '{대상지정}'은 아직 지원하지 않는다 (TODO)")
        return
    # 같은 편 전체(생존 여부 무관)를 "대형위치" 순으로 나열해
    # 바로 옆 칸만 본다 - 중간에 죽은 참가자가 있어도 대열이
    # 당겨지지 않는다. 그 옆 칸이 죽은 참가자면
    # 그냥 아무도 피해를 받지 않는다.
    같은편전체 = sorted(
        (p for p in 문맥.전투상태["참가자"] if p["진영"] == 대상["진영"]),
        key=lambda p: p.get("대형위치", 0),
    )
    이웃들 = []
    if 대상 in 같은편전체:
        idx = 같은편전체.index(대상)
        if idx > 0 and 같은편전체[idx - 1]["생존"]:
            이웃들.append(같은편전체[idx - 1])
        if idx < len(같은편전체) - 1 and 같은편전체[idx + 1]["생존"]:
            이웃들.append(같은편전체[idx + 1])

    피해량식 = 항목.get("피해량", 0)
    if isinstance(피해량식, str):
        식 = 피해량식.replace("주대상피해", str(문맥.주대상피해))
        분배피해 = formula.수식_평가(식, {"차수": core.차수(문맥.시전자)})
    elif isinstance(피해량식, (int, float)):
        분배피해 = 피해량식 * 문맥.주대상피해
    else:
        분배피해 = 0

    for 이웃 in 이웃들:
        최종피해 = damage.피해_적용(
            문맥.전투상태, 이웃, 분배피해, 속성=문맥.속성, 공격측=문맥.시전자
        )
        로그.append(f"{이웃['이름']}에게 범위분배 피해 {최종피해}")


# 효과 "종류" -> 처리기. 모르는 종류는 조용히 건너뛴다(예전 if/elif 체인과 같다).
_효과_처리기 = {
    "상태이상": _효과_상태이상,
    "자동상태": _효과_자동상태,
    "지속피해": _효과_지속피해,
    "아군버프": _효과_아군버프,
    "버프해제": _효과_해제,
    "디버프해제": _효과_해제,
    "범위분배": _효과_범위분배,
}


def 효과_적용(
    전투상태,
    시전자,
    대상,
    효과리스트,
    *,
    주대상피해=0,
    속성=None,
    데미지식=None,
    데미지보너스=0,
    최종피해배율=1,
):
    """공격/해제 스킬의 "효과" 리스트를 대상 하나에 적용한다. 명중 후
    상황(상태이상/자동상태/지속피해 부여, 아군버프, 버프해제/디버프해제,
    범위분배)을 다룬다. 효과 "종류"마다 처리기(_효과_상태이상 등)가 있고
    _효과_처리기 표가 이어 준다.

    "주대상피해"는 이 효과가 곁들여진 공격이 "대상"에게 실제로 입힌
    피해량이다("범위분배"의 "주대상피해" 수식 키워드에 쓴다 - 공격_1회가
    이미 계산해둔 결과["피해"]를 그대로 넘겨준다). "속성"도 마찬가지로
    범위분배 피해에 그대로 반영해 저항/취약이 적용되게 한다.

    "데미지식"/"데미지보너스"/"최종피해배율"은 "지속피해"
    종류에만 쓰인다 - job_skill_format.py에 "턴당 피해량은 스킬 자신의
    '데미지' 키 값을 그대로 사용한다"고 돼 있어서, 이 효과가 곁들여진
    스킬(공격_1회) 쪽의 값을 그대로 받아 항목에 저장해둔다(대상 본인
    턴종료시 combat.damage.지속피해_스킬_적용이 나중에 이 값으로
    재계산한다).

    "상태이상" 종류의 내성굴림은 대상이 "저주"(내성굴림불리점) 상태면
    불리하게 굴린다. 실제 상태이상 부여는 상태이상_부여()에 맡긴다 -
    status_effects.py에 정의된 이름(기절/공중에뜸 등)이면 그 정의를 보고
    지속피해형 중첩 병합/부여버프까지 같이 처리해 준다."""
    문맥 = _효과문맥(
        전투상태, 시전자, 대상, 주대상피해, 속성, 데미지식, 데미지보너스, 최종피해배율
    )
    로그 = []
    for 항목 in 효과리스트 or []:
        종류 = 항목.get("종류")

        if 종류 in ("상태이상", "자동상태") and status.상태이상_면역(
            전투상태, 대상, 항목.get("이름")
        ):
            로그.append(f"{대상['이름']}은(는) '{항목['이름']}' 상태이상에 면역")
            continue

        처리기 = _효과_처리기.get(종류)
        if 처리기 is not None:
            처리기(문맥, 항목, 로그)
    return 로그
