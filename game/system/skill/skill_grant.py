# 자원 (보유자원 딕셔너리 / 이름있는 버프-자원) 조회·소모·획득
# =====================================================
# "자원소모"/"자원획득"이 가리키는 이름은 두 가지 방식 중 하나로 저장된다.
# - skill_effects.기술효과목록에 있는 이름(류심자세/강화류심/장전 : 은탄 등)은
#   참가자["버프"] 리스트에 이름 있는 인스턴스로 들어간다("중첩"이 곧
#   보유 개수/스택이다). "버프획득"도 결국 이 저장 방식을 그대로 쓴다.
# - skill_effects.클래스자원목록에 있는 이름(탄약/수류탄)이거나 아무 정의도
#   찾을 수 없는 이름은 참가자["보유자원"] 딕셔너리(이름 -> 개수)에 숫자로
#   저장한다.


def 이름있는효과_부여(
    전투상태,
    참가자,
    이름,
    중첩량=1,
    지속턴오버라이드=None,
    시전자=None,
    무기조건=None,
    출처스킬=None,
):
    """ "버프획득"/"자원획득"을 이름으로 처리한다. 정의를 기술효과목록 →
    버프목록 → 디버프목록 순으로 찾아서, 버프목록/기술효과목록 쪽이면
    참가자["버프"]에, 디버프목록 쪽이면 참가자["디버프"]에 인스턴스를
    추가한다. buff.py/debuff.py의 "중첩":True(스택버프) 항목은 항상 새
    인스턴스를 추가한다(_스택형인가 참고 - 인스턴스별로 분리 추적하기로
    확정됨). 그 외(기술효과 자원류 등)는 기존과 같이 이름이 같은 기존
    인스턴스에 중첩을 더하는 방식으로 병합한다. "최대값"(skill_effects.py)이
    있으면 그 값을 넘지 않게 자른다(병합형에만 의미가 있다).

    시전자: 버프를 건 참가자. 수식형 "변동값"(1d(4+2차수)+주문시전보정치 등)은
    이 사람 기준으로 지금 한 번 굴려 인스턴스 "고정값"에 저장한다(B10/B11). 없으면
    받는 참가자 자신 기준(상태이상이 주는 버프 등).

    무기조건: 스킬 "버프무기조건" - 인스턴스에 저장해 그 무기를 들었을 때만
    효과가 적용되게 한다(stats.버프디버프_수치).

    출처스킬: 이 버프를 건 버프스킬 이름. buff.py/debuff.py 버프는 같은 스킬이 이미
    건 인스턴스가 있으면 중첩하지 않고 지속턴만 갱신한다(다른 스킬/출처면 기존대로
    중첩). 기술효과(skill_effects.py 자원류)는 해당 없음."""
    정의, 출처 = resources.효과정의_조회(이름)
    목록이름 = "디버프" if 출처 == "디버프" else "버프"
    출처스킬 = (
        출처스킬 if 출처 in ("버프", "디버프") else None
    )  # 기술효과(자원류)는 해당 없음
    if 출처스킬 and _같은_출처_효과_갱신(
        참가자, 목록이름, 이름, 출처스킬, 정의, 지속턴오버라이드
    ):
        return
    고정값 = _특성_버프변동값(전투상태, 시전자, 이름, 정의) or stats.버프_고정값_계산(
        전투상태, 정의, 시전자 or 참가자
    )
    지속턴 = _효과_지속턴(전투상태, 참가자, 정의, 지속턴오버라이드)
    # "중첩불가"(장전 탄끼리 #390) - 새로 거는 효과가 그 목록의 효과를 밀어낸다
    for 항목 in [
        i for i in 참가자[목록이름] if i["이름"] in ((정의 or {}).get("중첩불가") or ())
    ]:
        참가자[목록이름].remove(항목)

    if _스택형인가(정의, 출처):
        최대중첩 = 정의.get("최대중첩")
        if 최대중첩 is not None and (
            sum(1 for 항목 in 참가자[목록이름] if 항목["이름"] == 이름) >= 최대중첩
        ):
            return  # "최대중첩"(귀참 : 브레멘 등)까지 쌓였으면 더 걸지 않는다
        참가자[목록이름].append(
            _새_효과_항목(이름, 중첩량, 지속턴, 고정값, 무기조건, 출처스킬)
        )
        return

    최대값 = None
    if 정의 is not None and "최대값" in 정의:
        최대값 = 정수_평가(정의["최대값"], 전투상태, 참가자)

    기존 = next((항목 for 항목 in 참가자[목록이름] if 항목["이름"] == 이름), None)
    if 기존 is not None:
        _기존_효과_병합(기존, 중첩량, 최대값, 지속턴, 고정값)
    else:
        새항목 = _새_효과_항목(이름, 중첩량, 지속턴, 고정값, 무기조건, 출처스킬)
        if 최대값 is not None:
            새항목["중첩"] = min(새항목["중첩"], 최대값)
        참가자[목록이름].append(새항목)
    _분신_기록(전투상태, 참가자, 목록이름, 이름, 정의, 시전자)
    if (정의 or {}).get(
        "시전자기록"
    ) and 시전자 is not None:  # 귀신 : 사야 - 건 사람이 친다
        for 항목 in 참가자[목록이름]:
            if 항목["이름"] == 이름:
                항목["시전자id"] = 시전자["id"]
    _소환수_등록(참가자, 정의)


def _특성_버프변동값(전투상태, 시전자, 이름, 정의):
    """시전자 특성의 "버프변동값"(사슬 해제 - 카잔버프 1+차수)이 이 효과를 가리키면 효과 원소마다 그 식을
    건 사람 기준으로 굴린 고정값 리스트. 없으면 None."""
    효과 = (정의 or {}).get("효과")
    if 시전자 is None or 효과 is None:
        return None
    원소 = next(
        (
            o
            for o in traits.캐릭터특성_무기효과(전투상태, 시전자, "버프변동값")
            if o.get("버프") == 이름
        ),
        None,
    )
    if 원소 is None:
        return None
    값 = formula.수식_평가(원소["변동값"], stats.버프_수식_컨텍스트(전투상태, 시전자))
    return [값] * (1 if isinstance(효과, dict) else len(효과))


def _분신_기록(전투상태, 참가자, 목록이름, 이름, 정의, 시전자):
    """ "분신수"가 있는 효과(skill_effects.py "분신" #278)면 인스턴스 "분신실드"를 새로 채운다 - 분신마다
    "개당실드량"(건 사람 기준)의 실드. 다시 걸면 처음부터 다시 채운다. 피해는 damage.분신_흡수가 깎는다."""
    효과 = (정의 or {}).get("효과")
    if not isinstance(효과, dict) or "분신수" not in 효과:
        return
    기준 = 시전자 or 참가자
    개수 = 정수_평가(효과["분신수"], 전투상태, 기준)
    실드 = max(0, 정수_평가(효과.get("개당실드량", 0), 전투상태, 기준, 기본값=0))
    for 항목 in 참가자[목록이름]:
        if 항목["이름"] == 이름:
            항목["분신실드"] = [실드] * max(0, 개수)


def _기존_효과_병합(기존, 중첩량, 최대값, 지속턴, 고정값):
    """병합형 효과를 다시 걸 때 - 중첩을 더하고(최대값까지) 지속턴/고정값을 새 값으로 바꾼다."""
    기존["중첩"] = 기존.get("중첩", 1) + 중첩량
    if 최대값 is not None:
        기존["중첩"] = min(기존["중첩"], 최대값)
    if 지속턴 is not None:
        기존["지속턴"] = 지속턴
    if 고정값 is not None:  # 다시 걸면 새로 굴린 값으로 바꾼다
        기존["고정값"] = 고정값


def _소환수_등록(참가자, 정의):
    """소환수 타입 효과면 참가자["소환수"]에 소환수 이름을 (한 번만) 등록한다."""
    효과 = (정의 or {}).get("효과")
    if isinstance(효과, dict) and 효과.get("타입") == "소환수":
        참가자.setdefault("소환수", [])
        소환수이름 = 효과.get("소환수이름")
        if 소환수이름 and 소환수이름 not in 참가자["소환수"]:
            참가자["소환수"].append(소환수이름)


def _같은_출처_효과_갱신(참가자, 목록이름, 이름, 출처스킬, 정의, 지속턴오버라이드):
    """같은 버프스킬이 이미 건 인스턴스가 있으면 중첩하지 않고 지속턴만 갱신한다. 갱신했으면 True."""
    기존 = next(
        (
            항목
            for 항목 in 참가자[목록이름]
            if 항목["이름"] == 이름 and 항목.get("출처스킬") == 출처스킬
        ),
        None,
    )
    if 기존 is None:
        return False
    if 지속턴오버라이드 is not None:
        기존["지속턴"] = 지속턴오버라이드
    elif isinstance((정의 or {}).get("지속턴"), (int, float)):
        기존["지속턴"] = int(정의["지속턴"])
    return True


def _효과_지속턴(전투상태, 참가자, 정의, 지속턴오버라이드):
    """새 인스턴스의 지속턴(숫자 또는 None). 수식이면 받는 참가자 기준으로 평가한다."""
    지속턴 = 지속턴오버라이드
    if 지속턴 is None and 정의 is not None:
        원지속턴 = 정의.get("지속턴")
        if isinstance(원지속턴, str) and 원지속턴 not in ("소모시", "전투종료"):
            지속턴 = 정수_평가(원지속턴, 전투상태, 참가자)
        elif isinstance(원지속턴, (int, float)):
            지속턴 = int(원지속턴)
        # "소모시"/"전투종료"는 지속턴을 숫자로 관리하지 않는다 - None으로
        # 남겨 두면 combat.flow.턴_시작_처리가 만료 처리를 하지 않는다
        # (자원_소모()로 직접 없어지거나, 전투가 끝나야 사라진다는 뜻).
    return 지속턴


def _새_효과_항목(이름, 중첩, 지속턴, 고정값, 무기조건, 출처스킬):
    """참가자["버프"]/["디버프"]에 넣을 인스턴스. 값이 없는 칸은 만들지 않는다."""
    항목 = {"이름": 이름, "중첩": 중첩}
    if 지속턴 is not None:
        항목["지속턴"] = 지속턴
    if 고정값 is not None:
        항목["고정값"] = 고정값
    if 무기조건:
        항목["무기조건"] = 무기조건
    if 출처스킬:
        항목["출처스킬"] = 출처스킬
    return 항목


def 이름있는효과_해제(참가자, 목록이름, 이름):
    for 항목 in list(참가자[목록이름]):
        if 항목["이름"] == 이름:
            정의, _ = resources.효과정의_조회(이름)
            if 자원류_효과인가(정의):
                continue  # 자원버프/소환버프는 해제 대상이 아니다.
            참가자[목록이름].remove(항목)


def 상태이상_해제(전투상태, 대상, 이름):
    """대상의 "상태이상" 목록에서 이름이 같은 항목을 전부 없앤다(조건부효과
    "상태이상해제" - 예: 홀리 스매쉬의 공중에뜸). 지속턴과 무관하게 즉시
    해제하며, 하나라도 없앴으면 "OO 해제시" 몬스터특성(기상 충격파 등)을
    combat.traits.특성_상태이상해제시_발동으로 한 번 발동시킨다(지속턴
    만료로 사라질 때와 같은 훅). 없앤 것이 있으면 True.

    버프/디버프 목록은 건드리지 않는다 - 그쪽은 "버프해제"/"디버프해제" 몫.
    상태이상이 부여할 때 같이 준 "부여버프"(석화의 보호률증가 등)도 여기서는
    거두지 않는다(지속턴 만료 시에도 거두지 않는 기존 동작과 같다)."""
    남길것 = [i for i in 대상.get("상태이상", []) if i.get("이름") != 이름]
    해제됨 = len(남길것) != len(대상.get("상태이상", []))
    if not 해제됨:
        return False
    대상["상태이상"] = 남길것
    traits.특성_상태이상해제시_발동(전투상태, 대상, 이름)
    return True


def 상태이상_부여(전투상태, 대상, 이름, 지속턴, 해제난이도=None):
    """status_effects.py 상태이상 하나를 대상에게 실제로 부여한다.
    정의(전투상태["상태이상정의"])에 "중첩":True가 있는 항목(출혈/중독/
    화상/감전 등 지속피해형)은 buff.py "스택버프"와 똑같은 방식으로
    "인스턴스형"으로 추적한다(지속피해는 스택버프와 마찬가지로 턴과
    스택을 따로 관리한다) - 기존 인스턴스에
    병합하지 않고 매번 새 인스턴스를 추가해서, 각 인스턴스가 자기
    "지속턴"이 다 되면 개별적으로 만료된다(먼저 건 게 먼저 사라진다).
    "몇 스택인지"는 그냥 같은 이름의 인스턴스 개수가 된다.
    "부여버프"(석화의 피해량감소 등)가 정의돼 있으면 그 버프도 같이
    준다. "해제난이도"는 은신/집중처럼 "피격 시 내성굴림 실패하면
    해제"되는 상태이상의 그 내성굴림 DC를 이 상태이상을 거는 스킬이
    정해서 넘겨주는 값이다(생략하면 combat.damage.피격_처리가 기본값
    10을 쓴다)."""
    정의 = 전투상태.get("상태이상정의", {}).get(이름)
    대상.setdefault("상태이상", [])
    if status.상태이상_면역(전투상태, 대상, 이름):
        return False

    if 정의 is not None and 정의.get("갱신") == "긴쪽":
        # 겹치지 않고 남은 지속턴과 새 지속턴 중 긴 쪽으로(몹몰이 #378)
        기존 = next((i for i in 대상["상태이상"] if i.get("이름") == 이름), None)
        if 기존 is not None:
            if 지속턴 is not None and 지속턴 > (기존.get("지속턴") or 0):
                기존["지속턴"] = 지속턴
            return True

    새항목 = {"이름": 이름}
    if 지속턴 is not None:
        새항목["지속턴"] = 지속턴
    if 해제난이도 is not None:
        새항목["해제난이도"] = 해제난이도
    if 정의 is not None and 정의.get("중첩"):
        새항목["중첩"] = 1
    대상["상태이상"].append(새항목)
    status.영창_방해(전투상태, 대상, 이름)  # 행동불가형/침묵이면 주문영창이 끊긴다

    if 정의 is not None:
        부여버프 = 정의.get("효과", {}).get("부여버프")
        if 부여버프:
            이름있는효과_부여(전투상태, 대상, 부여버프)
    return True
