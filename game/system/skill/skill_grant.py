def 자원류_효과인가(정의):
    """job_skill_format.py <효과 하위 양식> 5번 설명대로, "자원버프"/
    "소환버프"는 버프해제/디버프해제 대상이 되지 않는다. skill_effects.py
    데이터에는 "분류" 표시가 없어서, "효과"."타입"이 "자원보유" 또는
    "소환수"인 항목을 그 판정 기준으로 쓴다."""
    if 정의 is None:
        return False
    효과 = 정의.get("효과", {})
    return isinstance(효과, dict) and 효과.get("타입") in ("자원보유", "소환수")


def _스택형인가(정의, 출처):
    """buff.py/debuff.py 문서화된 설계 의도: "타입"에 "스택버프"가
    포함된(="중첩":True인) 버프/디버프는 받을 때마다 별도 인스턴스로
    추적한다. skill_effects.py 기술효과(자원류)는 "중첩"이 있어도 이
    인스턴스 분리 대상이 아니다 - 그건 자원 개수 카운터일 뿐이다."""
    return 출처 in ("버프", "디버프") and 정의 is not None and 정의.get("중첩") is True


