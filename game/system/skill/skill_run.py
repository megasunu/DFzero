# 캐스팅 (넨마스터 축염포 #280, 엘리멘탈마스터 중급/상급마법)
# =====================================================
# 쓰는 순간 MP와 일반행동을 내고, 남은 행동자원은 맡겨 둔 채 0으로 만든다(턴이 끝난다 - 부르는 쪽은 그냥
# 턴을 넘긴다). "캐스팅시작" 표시를 본 combat.flow.다음_턴이 턴 종료 처리 없이 그 참가자를 "밀림"(스킬
# "캐스팅시간" - 이동캐스팅이면 우선도 대신 이니셔티브)만큼 내린 자리로 옮겨 밀린 차례("캐스팅차례")를 만들고,
# 그 차례에는 턴 시작 처리(행동 채우기, 지속턴 감소) 없이 돌려준다. 아래 다음_턴이 그때 맡겨 둔 행동을
# 돌려주고 쏜다. 쓰러졌거나 무력화(행동불가)면 쏘지 않는다. "캐스팅" 상태는 쏘고 난 뒤에 풀린다(이동캐스팅의
# 캐스팅 중 명중보너스가 쏘는 스킬에 붙는다 - 2026-10-22 사용자 결정).


def 캐스팅_밀림(전투상태, 시전자, 스킬데이터):
    """{"우선도", "이니셔티브"} - 캐스팅으로 이번 라운드에 내려갈 값. 스킬 "캐스팅시간"의 우선도(축염포·중급마법
    -1, 상급마법 -2)를 그대로 쓰고, 특성 "캐스팅이니셔티브"(이동캐스팅)가 있으면 우선도 대신 우선도 1당 그 값만큼
    이니셔티브를 내린다(0이면 둘 다 0 - 바로 다음 차례에 쏜다)."""
    우선도 = (스킬데이터.get("캐스팅시간") or {}).get("우선도", -1)
    감소 = traits.캐스팅_이니셔티브감소(전투상태, 시전자)
    if 감소 is None:
        return {"우선도": 우선도, "이니셔티브": 0}
    return {"우선도": 0, "이니셔티브": 우선도 * 감소}


def _밀림_글(밀림):
    글 = [f"{k} {v}" for k, v in 밀림.items() if v]
    return ", ".join(글) if 글 else "바로"


def 캐스팅_시작(전투상태, 시전자, 스킬데이터, 중심대상=None, 지정대상목록=None):
    밀림 = 캐스팅_밀림(전투상태, 시전자, 스킬데이터)
    시전자["캐스팅"] = {
        "스킬": 스킬데이터["_이름"],
        "대상id": None if 중심대상 is None else 중심대상.get("id"),
        # "적반복지정"(썬더콜링)에서 고른 대상들 - 쏠 때 살아 있는 대상만 친다
        "지정대상id": [p.get("id") for p in 지정대상목록 or []],
        "밀림": 밀림,
        "행동자원": dict(시전자["행동자원"]),
        "기타행동": dict(시전자.get("기타행동") or {}),
    }
    시전자["행동자원"] = {k: 0 for k in 시전자["행동자원"]}
    if 시전자.get("기타행동"):
        시전자["기타행동"] = {k: 0 for k in 시전자["기타행동"]}
    시전자.setdefault("상태이상", []).append({"이름": "캐스팅", "지속턴": None})
    시전자["캐스팅시작"] = True
    결과 = {
        "공격자": 시전자["이름"],
        "대상": 시전자["이름"],
        "스킬": 스킬데이터["_이름"],
        "비고": f"{스킬데이터['_이름']} 캐스팅을 시작했다({_밀림_글(밀림)}, 밀린 차례에 발사).",
        "캐스팅": True,
    }
    core.로그(전투상태, 결과, 종류="비고")
    return 결과


def _캐스팅_풀기(시전자):
    시전자["상태이상"] = [
        s for s in 시전자.get("상태이상", []) if s.get("이름") != "캐스팅"
    ]


def 캐스팅_발사(전투상태, 시전자):
    """밀린 차례 - 맡겨 둔 행동을 돌려주고 캐스팅한 스킬을 쏜다. 무력화(행동불가)면 끊긴다."""
    정보 = 시전자.pop("캐스팅", None)
    if 정보 is None:
        _캐스팅_풀기(시전자)
        return None
    시전자["행동자원"] = 정보["행동자원"]
    if 정보["기타행동"]:
        시전자["기타행동"] = 정보["기타행동"]
    이름 = 정보["스킬"]
    if status.상태이상_플래그(전투상태, 시전자, "행동불가"):
        _캐스팅_풀기(시전자)
        core.로그(
            전투상태,
            {
                "공격자": 시전자["이름"],
                "대상": 시전자["이름"],
                "비고": f"{이름} 캐스팅이 끊겼다.",
            },
            종류="비고",
        )
        return None
    적들 = [p for p in 전투상태["참가자"] if p["진영"] == "적" and p["생존"]]
    if not 적들:
        _캐스팅_풀기(시전자)
        return None
    중심 = next((p for p in 적들 if p.get("id") == 정보["대상id"]), 적들[0])
    지정 = [p for i in 정보.get("지정대상id") or [] for p in 적들 if p.get("id") == i]
    스킬데이터 = dict((전투상태.get("스킬정의") or {})[이름], _이름=이름)
    강화 = 스킬강화(시전자, 스킬데이터)
    if 강화:
        스킬데이터["최종피해배율"] = 강화["최종피해배율"]
    결과 = _공격스킬_분기(전투상태, 시전자, 스킬데이터, 중심, 지정 or None)
    _캐스팅_풀기(시전자)
    return 결과


def 다음_턴(전투상태):
    """combat.flow.다음_턴()을 감싼다. 위 _지속공격_발동()/
    _소환수_행동_실행()이 "combat 패키지는 skill_system을 부르지 않는다"는
    순환 참조 방지 원칙 때문에 combat.flow.턴_종료_처리 안에 들어갈 수
    없어서, 이 파일에 별도로 감싸는 함수를 두었다. 지속공격 스킬이나
    소환스킬을 쓰는 프로젝트라면 앞으로 턴을 넘길 때 combat.flow.다음_턴
    대신 반드시 이 함수를 호출해야 한다."""
    현재참가자 = flow.현재_턴_참가자(전투상태)
    if not 현재참가자.get(
        "캐스팅시작"
    ):  # 캐스팅으로 끝난 턴은 턴 종료 효과를 밀린 차례 끝으로 미룬다
        _지속공격_발동(전투상태, 현재참가자)
        _소환수_행동_실행(전투상태, 현재참가자)
        턴종료_버프공격(전투상태, 현재참가자)
    다음 = flow.다음_턴(전투상태, 라운드종료=라운드종료_처리)
    if 다음.pop("캐스팅발사", False):
        캐스팅_발사(전투상태, 다음)
        core.종료판정_갱신(전투상태)
    return 다음


