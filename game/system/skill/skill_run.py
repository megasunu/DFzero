# 지속공격 / 소환수 자동 발동 (시전자 턴 종료 시)
# =====================================================
# 둘 다 "대상"이 아니라 "시전자의 턴이 끝날 때" 발동해야 하는데,
# combat.flow.턴_종료_처리는 대상 기준(참가자 자신에게 걸린 상태이상)
# 으로만 순회하고, combat 패키지는 skill_system.py를 부르지 않는 구조라
# 그 안에 넣을 수도 없다. 그래서 아래 두 함수는 이 파일에서 combat 패키지를
# 불러 쓰는 방향으로만 두고, 공용 다음_턴()이 combat.flow.다음_턴()을
# 부르기 직전에 호출해준다.


def _저놈잡아라_표적(전투상태):
    """디버프 "저놈잡아라"가 걸린 살아 있는 적(먼저 찾은 하나). 없으면 None."""
    return next(
        (
            p
            for p in 전투상태["참가자"]
            if p["진영"] == "적"
            and p["생존"]
            and any(d["이름"] == "저놈잡아라" for d in p.get("디버프") or [])
        ),
        None,
    )


def 소환수_태그(소환수이름):
    """소환수 정의의 "태그"(메카)에, 소환사의 정령/계약소환이면 "환수"를 더한 목록(퍽 원포올)."""
    정의 = summon_00.소환수목록.get(소환수이름) or {}
    타입 = 정의.get("타입")
    타입들 = 타입 if isinstance(타입, list) else [타입]
    환수 = ["환수"] if any(t in ("정령소환", "계약소환") for t in 타입들) else []
    return list(정의.get("태그") or []) + 환수


def 원포올_보유(전투상태, 참가자):
    return traits.특성_수치(전투상태, 참가자, "원포올") > 0


def 소환수_한번_행동(전투상태, 시전자, 소환수이름, 행동표, 눈=None):
    """원포올이면 메카/환수 소환수가 치는 동안 시전자의 주문시전보정치를 여섯 능력치 보정치 합으로 바꾼다
    (stats.주문시전_보정치가 "_주문시전보정치대체"를 읽는다)."""
    if not (
        원포올_보유(전투상태, 시전자)
        and {"메카", "환수"} & set(소환수_태그(소환수이름))
    ):
        return _소환수_한번_행동(전투상태, 시전자, 소환수이름, 행동표, 눈)
    시전자["_주문시전보정치대체"] = stats.모든_능력치_보정치_합(전투상태, 시전자)
    try:
        return _소환수_한번_행동(전투상태, 시전자, 소환수이름, 행동표, 눈)
    finally:
        시전자.pop("_주문시전보정치대체", None)


def _소환수_한번_행동(전투상태, 시전자, 소환수이름, 행동표, 눈=None):
    """소환수 한 마리가 1d6을 굴려(눈을 주면 그 번호 - 교감은 6) 행동표의 행동을 한 번 한다
    (_소환수_행동_실행 참고). "타입" "효과"(혼란가스)는 해제스킬처럼 대상마다 "효과"를, "버프"(디펜스)는
    버프스킬처럼 시전자에게 "버프획득"을 건다."""
    if 눈 is None:
        눈 = dice_utils.주사위_합(1, 6)
    행동 = 행동표.get(눈)
    if 행동 is None:
        return
    이름 = 행동.get("이름", "행동")
    if not 이름.startswith(f"{소환수이름}의 "):  # 정령의 일격은 이미 붙어 있다
        이름 = f"{소환수이름}의 {이름}"
    if 행동.get("타입") == "효과":
        해제스킬_실행(전투상태, 시전자, dict(행동, _이름=이름))
        return
    if 행동.get("타입") == "버프":
        버프자원소환_스킬_실행(
            전투상태, 시전자, dict(행동, 분류="버프스킬", 명중률="자동", _이름=이름)
        )
        return
    if 행동.get("타입") != "공격":
        return

    스킬데이터 = dict(행동)
    스킬데이터["분류"] = "공격스킬"
    스킬데이터.setdefault("효과", [])
    스킬데이터.setdefault("조건부효과", [])
    스킬데이터.setdefault("일반공격취급", False)
    # 환수강화오라/환수폭주의 "스킬타입조건": ["소환수"]
    # 행동표의 "스킬타입"(메카 - 파이어볼트 피해 이점)도 스킬 타입에 더한다
    스킬데이터["타입"] = (
        list(스킬데이터.get("타입") or [])
        + list(스킬데이터.pop("스킬타입", None) or [])
        + ["소환수"]
    )
    스킬데이터["_이름"] = 이름
    표적 = _저놈잡아라_표적(전투상태)
    if 표적 is not None and str(스킬데이터.get("타겟", "")).startswith("적"):
        # 저놈잡아라 - 랜덤/단일 대상 공격은 표적만 친다(전체·범위는 표적이 중심)
        if 스킬데이터["타겟"] != "적전체":
            if 스킬데이터["타겟"] != "적3체":
                스킬데이터["타겟"] = "적단일"
            공격스킬_실행(전투상태, 시전자, 스킬데이터, 표적)
            return
    # 소환수는 대상을 직접 고르지 않는다 - "적단일"/"적3체"는 지정
    # 가능한(은신 아닌) 생존 적 중 무작위를 중심으로 삼는다(중심대상
    # 없이 부르면 ValueError).
    중심 = None
    if 스킬데이터.get("타겟") in ("적단일", "적3체"):
        후보 = [p for p in 전투상태["참가자"] if p["진영"] == "적" and p["생존"]]
        지정가능 = [
            p for p in 후보 if not status.상태이상_플래그(전투상태, p, "지정불가")
        ]
        후보 = 지정가능 or 후보
        if not 후보:
            return
        중심 = rng.대상.choice(후보)
        if not 지정가능:
            스킬데이터["타겟"] = "적3체" if 스킬데이터["타겟"] == "적3체" else "적랜덤"
    공격스킬_실행(전투상태, 시전자, 스킬데이터, 중심)


