def _패턴_덮어쓰기(스킬데이터, 패턴):
    return {**스킬데이터, **스킬데이터["패턴"][패턴]}


def 패턴_적용(전투상태, 시전자, 스킬데이터):
    """ "패턴분기" 스킬(합격)이면 시전자의 자원이 기억한 패턴으로 정해지는 패턴을 덮어쓴 데이터와 그 패턴
    이름, 아니면(자원이 없거나 무작위패턴/보통 스킬) (스킬데이터, None). 전투 화면의 스킬 이름·타겟과
    자동전투도 이것으로 본다."""
    if "형태전환" in 스킬데이터.get("타입", []):  # 트랜스폼 - 다음 형태의 패턴
        패턴 = 형태_패턴(시전자, 스킬데이터)
        return _패턴_덮어쓰기(스킬데이터, 패턴), 패턴
    분기 = 스킬데이터.get("패턴분기")
    if not 분기 or "패턴분기" not in 스킬데이터.get("타입", []):
        return 스킬데이터, None
    기억 = next(
        (b.get("패턴") for b in 시전자.get("버프", []) if b["이름"] == 분기["자원"]),
        None,
    )
    패턴 = 분기["선택"].get(기억)
    if 패턴 is None:
        return 스킬데이터, None
    return _패턴_덮어쓰기(스킬데이터, 패턴), 패턴


def _무작위패턴_고르기(스킬데이터, 스킬이름, 패턴):
    """ "무작위패턴"(원귀)이면 비용을 낸 뒤 패턴 하나를 무작위로 골라 덮어쓴다. 패턴이 정해졌으면(합격 포함)
    로그/문장의 이름을 "스킬 : 패턴"으로 바꾼다 - 사용 횟수 기록(자원_소비_처리)이 끝난 뒤라 기록은 그대로."""
    if "무작위패턴" in 스킬데이터.get("타입", []):
        패턴 = rng.대상.choice(list(스킬데이터["패턴"]))
        스킬데이터 = _패턴_덮어쓰기(스킬데이터, 패턴)
    if 패턴:
        스킬데이터["_이름"] = f"{스킬이름} : {패턴}"
    return 스킬데이터, 패턴


def _패턴자원_부여(전투상태, 시전자, 스킬데이터, 패턴):
    """ "패턴자원"(원귀)이 있으면 그 자원을 얻고 인스턴스 "패턴"에 이번에 낸 패턴을 적는다(이미 있으면 새
    패턴으로 바꾼다) - 합격이 읽는다."""
    if 패턴 and "형태전환" in 스킬데이터.get(
        "타입", []
    ):  # 트랜스폼 - 이전 형태는 사라진다
        형태_전환(시전자, 스킬데이터, 패턴)
    자원 = 스킬데이터.get("패턴자원")
    if not (패턴 and 자원):
        return
    이름있는효과_부여(전투상태, 시전자, 자원, 시전자=시전자)
    for 항목 in 시전자["버프"]:
        if 항목["이름"] == 자원:
            항목["패턴"] = 패턴
