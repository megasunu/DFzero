# 둘 다 "대상"이 아니라 "시전자의 턴이 끝날 때" 발동해야 하는데,
# combat.flow.턴_종료_처리는 대상 기준(참가자 자신에게 걸린 상태이상)
# 으로만 순회하고, combat 패키지는 skill_system.py를 부르지 않는 구조라
# 그 안에 넣을 수도 없다. 그래서 아래 두 함수는 이 파일에서 combat 패키지를
# 불러 쓰는 방향으로만 두고, 공용 다음_턴()이 combat.flow.다음_턴()을
# 부르기 직전에 호출해준다.


def _지속공격_발동(전투상태, 시전자):
    """job_skill_format.py <지속공격 양식>(예: 보이드, 나이트 할로우)이
    걸어둔 지속공격을 실제로 발동시킨다. 전투상태의 모든 참가자를 돌며,
    "종류":"지속공격"이고 "시전자id"가 이 시전자인 항목을 찾아
    공격_1회를 그대로 재사용해 타격한다(효과/조건부효과/치명타 등이
    일반 공격스킬과 동일하게 반영된다).

    "매턴명중굴림"이 False면 항목에 저장해둔 첫 판정 결과를 계속
    재사용하고(재판정 없음), True면 매번 새로 판정한다. 어느 쪽이든
    판정에 실패하면 그 시점에 항목을 제거해 효과를 끝낸다."""
    for 참가자 in 전투상태["참가자"]:
        for 항목 in list(참가자.get("상태이상", [])):
            if 항목.get("종류") != "지속공격" or 항목.get("시전자id") != 시전자.get(
                "id"
            ):
                continue

            출처스킬 = 항목.get("출처스킬", {})
            매턴명중굴림 = 출처스킬.get("매턴명중굴림", False)
            공격횟수 = 정수_평가(출처스킬.get("공격횟수", 1), 전투상태, 시전자)
            옵션 = 공격옵션(
                데미지보너스=출처스킬.get("데미지보너스", 0),
                명중보너스=출처스킬.get("명중보너스", 0),
                강제치명타=출처스킬.get("강제치명타", False),
                치명타체크=출처스킬.get("치명타체크", False),
                효과리스트=출처스킬.get("효과", []),
                조건부효과리스트=출처스킬.get("조건부효과", []),
                속성=출처스킬.get("속성"),
                공격타입=출처스킬.get("공격타입"),
                속성추가피해=출처스킬.get("속성추가피해"),
                최종피해배율=항목.get("최종피해배율", 1),
            )

            총피해 = 0
            중단됨 = False
            공유판정 = 항목.get("명중판정")
            for i in range(공격횟수):
                재판정필요 = 매턴명중굴림 or 공유판정 is None
                미리계산된판정 = None if 재판정필요 else 공유판정
                결과 = 공격_1회(
                    전투상태,
                    시전자,
                    참가자,
                    값_또는_리스트(출처스킬.get("데미지", "0"), i),
                    값_또는_리스트(출처스킬.get("명중률", "자동"), i),
                    옵션,
                    미리계산된판정=미리계산된판정,
                )
                if i == 0:
                    공유판정 = 결과["판정"]
                    항목["명중판정"] = 공유판정
                총피해 += 결과.get("피해", 0)
                if not 결과["판정"]["성공"]:
                    중단됨 = True
                    break

            core.로그(
                전투상태,
                {
                    "공격자": 시전자["이름"],
                    "대상": 참가자["이름"],
                    "스킬": 항목.get("이름"),
                    "총피해": 총피해,
                    "비고": "지속공격 자동 발동"
                    + (" (판정 실패로 해제)" if 중단됨 else ""),
                },
                종류="지속공격발동",
            )
            if 중단됨 and 항목 in 참가자.get("상태이상", []):
                참가자["상태이상"].remove(항목)


def _소환수_행동횟수(시전자, 소환수이름):
    """그 소환수를 건 버프의 정의 "효과"에 "중첩당공격":True가 있으면(고블린소환) 버프 중첩 수,
    없으면 1(효도르/정령 - 이름당 한 마리). 몬스터 쪽 monster_actions._몬스터_소환수_목록과 같은 규칙."""
    for 항목 in 시전자.get("버프", []):
        정의, _ = resources.효과정의_조회(항목.get("이름"))
        효과 = (정의 or {}).get("효과") or {}
        if (
            isinstance(효과, dict)
            and 효과.get("타입") == "소환수"
            and 효과.get("소환수이름") == 소환수이름
            and 효과.get("중첩당공격")
        ):
            return max(1, int(항목.get("중첩", 1)))
    return 1


def _소환수_행동_실행(전투상태, 시전자):
    """summon_00.py "소환수목록"의 "행동표"를, 시전자가 부린 소환수마다
    1d6을 굴려 나온 행동을 자동으로 실행한다. "능력치참조":"시전자"라
    소환수 자체의 참가자 인스턴스나 이니셔티브가 없다 - 공격스킬_실행을
    시전자 명의로 그대로 재사용해서, 시전자의 능력치/버프가 그대로
    쓰이게 한다(stats.기본_컨텍스트가 어차피 "시전자"를 기준으로 계산하므로
    별도 처리가 필요 없다). "타입"이 "공격"이 아닌 행동표 항목(현재
    데이터에는 없음)은 아직 지원하지 않아 건너뛴다."""
    for 소환수이름 in list(시전자.get("소환수", [])):
        정의 = summon_00.소환수목록.get(소환수이름)
        행동표 = (정의 or {}).get("행동표")
        if not 행동표:
            continue
        for _ in range(_소환수_행동횟수(시전자, 소환수이름)):
            _소환수_한번_행동(전투상태, 시전자, 소환수이름, 행동표)


def _소환수_한번_행동(전투상태, 시전자, 소환수이름, 행동표):
    """소환수 한 마리가 1d6을 굴려 행동표의 행동을 한 번 한다(_소환수_행동_실행 참고)."""
    눈 = dice_utils.주사위_합(1, 6)
    행동 = 행동표.get(눈)
    if 행동 is None or 행동.get("타입") != "공격":
        return

    스킬데이터 = dict(행동)
    스킬데이터["분류"] = "공격스킬"
    스킬데이터.setdefault("효과", [])
    스킬데이터.setdefault("조건부효과", [])
    스킬데이터.setdefault("일반공격취급", False)
    스킬데이터["_이름"] = f"{소환수이름}의 {행동.get('이름', '행동')}"
    # 소환수는 대상을 직접 고르지 않는다 - "적단일"/"적3체"는 지정
    # 가능한(은신 아닌) 생존 적 중 무작위를 중심으로 삼는다(중심대상
    # 없이 부르면 ValueError).
    중심 = None
    if 스킬데이터.get("타겟") in ("적단일", "적3체"):
        후보 = [p for p in 전투상태["참가자"] if p["진영"] == "적" and p["생존"]]
        지정가능 = [
            p for p in 후보 if not status.상태이상_플래그(전투상태, p, "지정불가")
        ]
        후보 = 지정가능 or 후보
        if not 후보:
            return
        중심 = random.choice(후보)
        if not 지정가능:
            스킬데이터["타겟"] = "적3체" if 스킬데이터["타겟"] == "적3체" else "적랜덤"
    공격스킬_실행(전투상태, 시전자, 스킬데이터, 중심)


def 다음_턴(전투상태):
    """combat.flow.다음_턴()을 감싼다. 위 _지속공격_발동()/
    _소환수_행동_실행()이 "combat 패키지는 skill_system을 부르지 않는다"는
    순환 참조 방지 원칙 때문에 combat.flow.턴_종료_처리 안에 들어갈 수
    없어서, 이 파일에 별도로 감싸는 함수를 두었다. 지속공격 스킬이나
    소환스킬을 쓰는 프로젝트라면 앞으로 턴을 넘길 때 combat.flow.다음_턴
    대신 반드시 이 함수를 호출해야 한다."""
    현재참가자 = flow.현재_턴_참가자(전투상태)
    _지속공격_발동(전투상태, 현재참가자)
    _소환수_행동_실행(전투상태, 현재참가자)
    return flow.다음_턴(전투상태)


def 버프자원소환_스킬_실행(전투상태, 시전자, 스킬데이터, 중심대상=None):
    명중률 = 스킬데이터.get("명중률", "자동")
    if 명중률 != "자동":
        raise NotImplementedError(
            f"버프/자원/소환스킬의 명중률 '{명중률}'은 지원하지 않는다 "
            f"(버프/자원/소환스킬은 항상 '자동'만 쓰는 것으로 확정됨 - 사용자 확인)."
        )

    대상목록 = 타겟_확장(전투상태, 시전자, 스킬데이터["타겟"], 중심대상)
    지속턴 = 스킬데이터.get("지속턴")
    지속턴값 = 정수_평가(지속턴, 전투상태, 시전자) if 지속턴 is not None else None
    if 지속턴값 is not None and "귀신" in 스킬데이터.get("타입", []):
        # 사슬 해제(소울브링어) - 귀신 타입 스킬의 지속턴 +5. 전투 끝까지인 귀신(카잔)은 해당 없음.
        지속턴값 += sum(
            원소.get("변동값", 0)
            for 원소 in traits.캐릭터특성_무기효과(전투상태, 시전자, "귀신지속턴")
        )

    버프이름들 = 스킬데이터.get("버프획득") or (
        [스킬데이터["자원획득"]] if "자원획득" in 스킬데이터 else []
    )
    if isinstance(버프이름들, str):
        버프이름들 = [버프이름들]

    # 중첩량 수식("주문시전보정치" 등)은 건 사람(시전자) 기준이다 - 용맹의 축복처럼
    # 시전자의 보정치만큼 거는 스킬. 0 이하면 걸지 않는다(음수 중첩 방지).
    중첩량 = 정수_평가(스킬데이터.get("중첩량", 1), 전투상태, 시전자)
    for 대상 in 대상목록:
        for 이름 in 버프이름들:
            if 중첩량 <= 0:
                continue
            이름있는효과_부여(
                전투상태,
                대상,
                이름,
                중첩량=중첩량,
                지속턴오버라이드=지속턴값,
                시전자=시전자,
                무기조건=스킬데이터.get("버프무기조건"),
                출처스킬=스킬데이터.get("_이름"),
            )

        if "임시생명력" in 스킬데이터:
            양 = formula.올림(
                formula.수식_평가(
                    스킬데이터["임시생명력"], stats.기본_컨텍스트(전투상태, 대상)
                )
            )
            대상["임시생명력"] = 대상.get("임시생명력", 0) + 양

    결과 = {
        "공격자": 시전자["이름"],
        "스킬": 스킬데이터.get("_이름"),
        "대상": [p["이름"] for p in 대상목록],
        "버프": 버프이름들,
    }
    core.로그(전투상태, 결과, 종류="버프")
    return 결과


def 해제스킬_실행(전투상태, 시전자, 스킬데이터, 중심대상=None):
    대상목록 = 타겟_확장(전투상태, 시전자, 스킬데이터["타겟"], 중심대상)
    로그모음 = []
    for 대상 in 대상목록:
        로그모음 += 효과_적용(전투상태, 시전자, 대상, 스킬데이터.get("효과", []))

    결과 = {
        "공격자": 시전자["이름"],
        "스킬": 스킬데이터.get("_이름"),
        "대상": [p["이름"] for p in 대상목록],
        "로그": 로그모음,
    }
    core.로그(전투상태, 결과, 종류="효과로그")
    return 결과


def 회복스킬_실행(전투상태, 시전자, 스킬데이터, 중심대상=None):
    대상목록 = 타겟_확장(전투상태, 시전자, 스킬데이터["타겟"], 중심대상)
    총회복 = 0
    for 대상 in 대상목록:
        양 = formula.올림(
            formula.수식_평가(
                스킬데이터["회복량"], stats.기본_컨텍스트(전투상태, 시전자)
            )
        )
        최대HP = stats.유효_최대HP(전투상태, 대상)
        회복량 = max(0, min(양, 최대HP - 대상["현재HP"]))
        대상["현재HP"] += 회복량
        총회복 += 회복량

    결과 = {
        "공격자": 시전자["이름"],
        "스킬": 스킬데이터.get("_이름"),
        "대상": [p["이름"] for p in 대상목록],
        "총회복": 총회복,
    }
    core.로그(전투상태, 결과, 종류="회복")
    return 결과


