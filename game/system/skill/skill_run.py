def 그랩캐넌_피해식(스킬데이터):
    """그랩 캐넌 피해 - 스킬에 든 비용으로(스킬 밸런스 기준표): 일반행동 보정공격력, 보조행동 1d8,
    MP 10마다 보정공격력, 10으로 나눈 나머지 5 이상이면 보정치."""
    MP = 스킬데이터.get("MP소모") or 0
    MP = MP if isinstance(MP, int) else 0
    횟수 = (1 if 스킬데이터.get("행동") == "일반행동" else 0) + MP // 10
    항 = [f"보정공격력x{횟수}"] if 횟수 else []
    if 스킬데이터.get("행동") == "보조행동":
        항.append("1d8")
    if MP % 10 >= 5:
        항.append("보정치")
    return "+".join(항) or "0"


