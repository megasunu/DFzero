def 회복스킬_실행(전투상태, 시전자, 스킬데이터, 중심대상=None):
    대상목록 = 타겟_확장(전투상태, 시전자, 스킬데이터["타겟"], 중심대상)
    회복식 = str(스킬데이터["회복량"])
    if "자기체력소모비율" in 스킬데이터:  # 새크리파이스 - 원래 양만큼 회복(덜 잃어도)
        소모 = formula.올림(
            stats.유효_최대HP(전투상태, 시전자) * 스킬데이터["자기체력소모비율"]
        )
        damage.체력_소모(전투상태, 시전자, 소모)
        회복식 = 회복식.replace("자기체력소모량", str(소모))
    총회복 = 0
    for 대상 in 대상목록:
        양 = formula.올림(
            formula.수식_평가(회복식, stats.기본_컨텍스트(전투상태, 시전자))
        )
        최대HP = stats.유효_최대HP(전투상태, 대상)
        회복량 = max(0, min(양, 최대HP - 대상["현재HP"]))
        대상["현재HP"] += 회복량
        총회복 += 회복량

    결과 = {
        "공격자": 시전자["이름"],
        "스킬": 스킬데이터.get("_이름"),
        "대상": [p["이름"] for p in 대상목록],
        "총회복": 총회복,
    }
    core.로그(전투상태, 결과, 종류="회복")
    return 결과


