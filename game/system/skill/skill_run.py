def 스킬_실행(
    전투상태,
    시전자,
    스킬이름,
    스킬데이터,
    중심대상=None,
    지정대상목록=None,
    행동지불=None,
):
    """job_skill_XX.py "스킬목록"의 스킬 하나를 실행한다.

    시전자        : combat 패키지의 참가자 인스턴스 (진영 "아군"만 지원).
    스킬이름      : job_skill_XX.py "스킬목록" 딕셔너리의 키 (턴당사용제한/
                     전투당횟수 추적, 로그 표시용).
    스킬데이터    : 그 키의 값 (job_skill_format.py 양식을 따르는 딕셔너리).
    중심대상      : "적단일"/"적3체"/"아군단일" 등에 쓸 중심 대상 1개.
                     "자신"/"아군전체"/"적전체"처럼 대상이 필요 없는
                     타겟이면 생략해도 된다.
    지정대상목록  : "적반복지정" 타겟일 때만 쓰는, 타격별로 이미 정해둔
                     대상 리스트 (없으면 중심대상 하나를 전부 재사용한다 -
                     실제 매 타격 대상 선택은 UI가 결정해야 정확하다).
    행동지불      : 스킬의 "일반행동"을 낼 수단("쇼타임행동"/"일반행동"/"보조행동").
                     생략하면 기본 순서(일반행동_지불수단_목록 참고).
    """
    스킬데이터 = dict(스킬데이터)
    스킬데이터["_이름"] = 스킬이름
    강화 = 스킬강화(시전자, 스킬데이터)
    if 강화:
        # 피해 계산 끝(방어/속성 배율 뒤)에 곱한다 - 공격_1회/지속피해/지속공격까지
        스킬데이터["최종피해배율"] = 강화["최종피해배율"]

    # 여기서 구하는 전역오버라이드는 대상 없이(대상=None) 판정 가능한
    # 조건("자원보유"/"아군상태"/"HP비율이하"/"특성보유")만 반영된다. 이걸로
    # "MP소모"/"타겟"/"타겟제한"/"일반공격취급"의 스킬 전체 레벨 오버라이드를
    # 구한다. 단, 조건부효과의 "자원소모"는 여기서 미리 소모하지 않는다 -
    # 그 자원소모는 "조건이 실제로 적용되는 순간"(대상별 데미지/명중 보너스가
    # 실제로 붙는 그 타격)에 딸린 대가라서, 공격_1회()가 각 타격마다 다시
    # 조건을 확인하며 그때 소모한다(위 조건부효과_평가/공격_1회 참고).
    # 여기서 미리 소모해버리면 그 다음에 하는 대상별 재판정에서 자원이 이미
    # 사라진 걸로 보여 보너스가 아예 적용되지 않는 문제가 생긴다.
    전역오버라이드 = 조건부효과_평가(
        전투상태, 시전자, None, 스킬데이터.get("조건부효과", [])
    )
    MP소모오버라이드 = 전역오버라이드.get("MP소모")

    가능, 사유 = 사용_가능여부(전투상태, 시전자, 스킬데이터, MP소모오버라이드)
    if not 가능:
        raise ValueError(f"'{스킬이름}' 사용 불가: {사유}")

    if 행동지불 is not None and 행동지불 not in 일반행동_지불수단_목록(
        전투상태, 시전자, 스킬데이터
    ):
        raise ValueError(f"'{스킬이름}'은(는) 지금 '{행동지불}'(으)로 쓸 수 없다.")

    타겟종류오버라이드 = 전역오버라이드.get("타겟")
    # 대상이 잘못됐으면 비용(MP/행동/횟수)을 쓰기 전에 거부한다(B7).
    대상_검증(전투상태, 스킬_타겟종류(스킬데이터, 타겟종류오버라이드), 중심대상)

    자원_소비_처리(전투상태, 시전자, 스킬데이터, MP소모오버라이드, 행동지불=행동지불)

    분류 = 스킬데이터["분류"]
    타입목록 = 스킬데이터.get("타입", [])

    if 분류 == "공격스킬":
        if "분할공격" in 타입목록:
            결과 = 분할공격_실행(전투상태, 시전자, 스킬데이터, 중심대상)
        elif "지속공격" in 타입목록:
            결과 = 지속공격_등록(전투상태, 시전자, 스킬데이터, 중심대상)
        else:
            결과 = 공격스킬_실행(
                전투상태, 시전자, 스킬데이터, 중심대상, 지정대상목록, 타겟종류오버라이드
            )
            후속 = 특성_후속공격(전투상태, 시전자, 스킬이름, 중심대상)
            if 후속:
                결과["후속공격"] = 후속
    elif 분류 in ("버프스킬", "자원스킬", "소환스킬"):
        결과 = 버프자원소환_스킬_실행(전투상태, 시전자, 스킬데이터, 중심대상)
    elif 분류 == "해제스킬":
        결과 = 해제스킬_실행(전투상태, 시전자, 스킬데이터, 중심대상)
    elif 분류 == "회복스킬":
        결과 = 회복스킬_실행(전투상태, 시전자, 스킬데이터, 중심대상)
    else:
        raise ValueError(f"알 수 없는 스킬 분류: {분류!r}")

    return 결과
