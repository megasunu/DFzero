def _공격스킬_분기(
    전투상태,
    시전자,
    스킬데이터,
    중심대상=None,
    지정대상목록=None,
    타겟종류오버라이드=None,
):
    """공격스킬을 "타입"에 맞는 길로 친다 - 분할공격/지속공격(등록)/그 밖(공격스킬_실행). 스킬_실행과
    캐스팅_발사(밀린 차례)가 같이 쓴다."""
    타입목록 = 스킬데이터.get("타입", [])
    if 스킬데이터.get("설치소환수"):
        return _설치소환_실행(전투상태, 시전자, 스킬데이터, 중심대상)
    if "분할공격" in 타입목록:
        return 분할공격_실행(전투상태, 시전자, 스킬데이터, 중심대상)
    if "지속공격" in 타입목록:
        return 지속공격_등록(전투상태, 시전자, 스킬데이터, 중심대상)
    결과 = 공격스킬_실행(
        전투상태, 시전자, 스킬데이터, 중심대상, 지정대상목록, 타겟종류오버라이드
    )
    던지기 = 던지기_발동(전투상태, 시전자, 스킬데이터, 중심대상, 결과)  # 로플링(#381)
    if 던지기:
        결과["던지기"] = 던지기
    return 결과


