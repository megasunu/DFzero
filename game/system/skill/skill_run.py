def 이중투척_적용(전투상태, 시전자, 스킬데이터):
    """시전자에게 버프 "이중투척"이 있고 "투척" 태그 스킬(투척 아이템 포함)이면 바꾼 데이터 사본, 아니면 그대로.
    스킬의 "이중투척변형"이 있으면 두 번 대신 그 키들을 덮어쓴다(천라지망 - 적 전체). 그 밖에는 버프
    원소의 "명중보너스"(-5)를 더하고 "_이중투척": 2 - 스킬_실행이 한 번 더 친다(MP·행동은 한 번).
    "_단일투척"(남은 투척 아이템이 1개)이면 바꾸지 않는다. 한 번 바꾼 데이터는 다시 바꾸지 않는다."""
    if "_이중투척" in 스킬데이터 or "투척" not in (스킬데이터.get("타입") or []):
        return 스킬데이터
    원소들 = stats.버프_효과원소목록(전투상태, 시전자, "이중투척")
    if not 원소들:
        return 스킬데이터
    변형 = 스킬데이터.get("이중투척변형")
    if 변형:
        return {**스킬데이터, **변형, "_이중투척": 1}
    if 스킬데이터.get("_단일투척"):
        return 스킬데이터
    명중 = 스킬데이터.get("명중보너스", 0) + 원소들[0][1].get("명중보너스", 0)
    return {**스킬데이터, "명중보너스": 명중, "_이중투척": 2}


def 대체_적용(전투상태, 스킬데이터, 중심대상):
    """스킬의 "대체": 중심 대상이 "조건"에 맞으면 "대체"의 나머지 키를 덮어쓴 사본, 아니면 그대로.
    - "대상상태분류"(마운트 -> 크레이지 발칸 #378): 그 분류의 상태이상이 하나라도 있으면. 이름은 "대체"의 "이름",
      공격횟수는 그 상태이상 종류 수만큼 더한다.
    - "대상상태"(에어슈타이너 #381): 그 이름의 상태이상이 하나라도 있으면. "이름"이 없으면 스킬 이름 그대로."""
    대체 = 스킬데이터.get("대체")
    if not 대체 or 중심대상 is None:
        return 스킬데이터
    조건 = 대체["조건"]
    정의 = 전투상태.get("상태이상정의") or {}
    걸린것 = [i["이름"] for i in 중심대상.get("상태이상") or []]
    if "대상상태" in 조건:
        종류 = {이름 for 이름 in 걸린것 if 이름 in 조건["대상상태"]}
    else:
        종류 = {
            이름
            for 이름 in 걸린것
            if (정의.get(이름) or {}).get("분류") in 조건["대상상태분류"]
        }
    if not 종류:
        return 스킬데이터
    덮어쓸것 = {k: v for k, v in 대체.items() if k not in ("이름", "조건")}
    새 = {**스킬데이터, **덮어쓸것, "_이름": 대체.get("이름", 스킬데이터.get("_이름"))}
    새.pop("대체")
    if "대상상태분류" in 조건:
        새["공격횟수"] = f"({스킬데이터.get('공격횟수', 1)})+{len(종류)}"
    return 새


def 잡기필중_적용(전투상태, 시전자, 스킬데이터):
    """시전자에게 버프 "잡기필중"(반드시 잡는다! #381)이 있고 "잡기" 태그 스킬이면 명중률을 "필중"으로 바꾸고
    "_홀딩슈퍼아머"를 단 사본(홀딩이 남은 동안 시전자는 슈퍼아머 - damage.홀딩_걸기), 아니면 그대로."""
    if "잡기" not in (스킬데이터.get("타입") or []):
        return 스킬데이터
    if not stats.버프_효과원소목록(전투상태, 시전자, "잡기필중"):
        return 스킬데이터
    return {**스킬데이터, "명중률": "필중", "_홀딩슈퍼아머": True}


def _한번_더_던지나(전투상태, 중심대상):
    """두 번째 투척 - 중심 대상이 쓰러졌거나 적이 모두 쓰러졌으면 던지지 않는다."""
    if 중심대상 is not None and not 중심대상.get("생존"):
        return False
    return any(p["생존"] for p in 전투상태["참가자"] if p["진영"] == "적")


