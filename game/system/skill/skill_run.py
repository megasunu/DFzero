def 행동전부소모_적용(전투상태, 시전자, 스킬데이터):
    """조건부효과의 "행동전부소모"(환영검무): 스킬 비용을 낸 뒤 조건이 맞으면 그 행동자원을 모두 쓰고,
    쓴 수 x "소모당공격횟수"만큼 공격횟수를 더한 사본을 돌려준다. 없으면 그대로."""
    for 항목 in 스킬데이터.get("조건부효과") or []:
        행동 = 항목.get("행동전부소모")
        if not 행동 or not 조건_확인(
            전투상태, 시전자, None, 항목.get("조건"), 항목.get("조건값")
        ):
            continue
        수 = 시전자["행동자원"].get(행동, 0)
        if 수 <= 0:
            continue
        시전자["행동자원"][행동] = 0
        추가 = 수 * 항목.get("소모당공격횟수", 1)
        스킬데이터 = dict(
            스킬데이터, 공격횟수=f"({스킬데이터.get('공격횟수', 1)})+{추가}"
        )
        core.로그(
            전투상태,
            {
                "공격자": 시전자["이름"],
                "비고": f"{행동} {수}개를 모두 써서 공격 횟수 +{추가}",
            },
            종류="비고",
        )
    return 스킬데이터


