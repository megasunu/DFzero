# 캐스팅과 차징 (캐스팅: 넨마스터 축염포, 엘리멘탈마스터 중급/상급마법 / 차징: 레이저 라이플, 슬로스 바디)
# =====================================================
# 쓰는 순간 MP와 일반행동을 내고, 남은 행동자원은 맡겨 둔 채 0으로 만든다(턴이 끝난다 - 부르는 쪽은 그냥
# 턴을 넘긴다). "캐스팅시작" 표시를 본 combat.flow.다음_턴이 턴 종료 처리 없이 그 참가자를 "밀림"(캐스팅은
# 스킬 "캐스트"만큼 이니셔티브, 차징은 "차지"만큼 우선도)만큼 내린 자리로 옮겨 밀린 차례("캐스팅차례")를 만들고,
# 그 차례에는 턴 시작 처리(행동 채우기, 지속턴 감소) 없이 돌려준다. 아래 다음_턴이 그때 맡겨 둔 행동을
# 돌려주고 쏜다. 쓰러졌거나 무력화(행동불가)면 쏘지 않고, 피격으로 취소됐어도(hit_effects.캐스팅_피격_취소 -
# 캐스팅 지혜, 차징 건강 내성 DC 10) 쏘지 않는다. "캐스팅"/"차징" 상태는 쏘고 난 뒤에 풀린다(이동캐스팅의
# 캐스팅 중 명중보너스가 쏘는 스킬에 붙는다).


def 캐스팅_종류(스킬데이터):
    """ "캐스팅"(스킬 타입 "캐스팅" - 이니셔티브를 "캐스트"만큼) / "차징"(타입 "차징" - 우선도를 "차지"만큼) / None."""
    타입목록 = 스킬데이터.get("타입") or []
    if "차징" in 타입목록:
        return "차징"
    return "캐스팅" if "캐스팅" in 타입목록 else None


def 캐스팅_밀림(전투상태, 시전자, 스킬데이터):
    """{"우선도", "이니셔티브"} - 캐스팅/차징으로 이번 라운드에 내려갈 값.
    차징: 스킬 "차지"의 우선도(레이저 라이플·슬로스 바디 -1)를 그대로 내린다.
    캐스팅: 스킬 "캐스트"의 이니셔티브(축염포·중급마법 -5, 상급마법 -10)를 캐스팅속도 1당 2(화끈한 애정, 법력강화),
    특성 "캐스팅이니셔티브"(이동캐스팅)만큼 덜 내린다(0 위로는 안 감 - 0이면 바로 다음 차례에 쏜다)."""
    if 캐스팅_종류(스킬데이터) == "차징":
        return {
            "우선도": (스킬데이터.get("차지") or {}).get("우선도", -1),
            "이니셔티브": 0,
        }
    이니셔티브 = (스킬데이터.get("캐스트") or {}).get("이니셔티브", 0)
    이니셔티브 += 2 * _캐스팅속도(전투상태, 시전자)
    이니셔티브 += traits.캐스팅_이니셔티브감소(전투상태, 시전자) or 0
    return {"우선도": 0, "이니셔티브": min(0, 이니셔티브)}


def _캐스팅속도(전투상태, 시전자):
    return max(
        0,
        stats.버프디버프_수치(전투상태, 시전자, "캐스팅속도")
        + traits.특성_수치(전투상태, 시전자, "캐스팅속도"),
    )


def 캐스팅_바로쏨(전투상태, 시전자, 스킬데이터):
    """캐스팅속도로 캐스팅의 밀림이 0이 되면 캐스팅 없이 바로 쏜다(차징은 늘 차징한다)."""
    if 캐스팅_종류(스킬데이터) != "캐스팅":
        return False
    return _캐스팅속도(전투상태, 시전자) > 0 and not any(
        캐스팅_밀림(전투상태, 시전자, 스킬데이터).values()
    )


def _밀림_글(밀림):
    글 = [f"{k} {v}" for k, v in 밀림.items() if v]
    return ", ".join(글) if 글 else "바로"


def 캐스팅_시작(전투상태, 시전자, 스킬데이터, 중심대상=None, 지정대상목록=None):
    밀림 = 캐스팅_밀림(전투상태, 시전자, 스킬데이터)
    종류 = 캐스팅_종류(스킬데이터) or "캐스팅"
    시전자["캐스팅"] = {
        "스킬": 스킬데이터["_이름"],
        "종류": 종류,
        "대상id": None if 중심대상 is None else 중심대상.get("id"),
        # "적반복지정"(썬더콜링)에서 고른 대상들 - 쏠 때 살아 있는 대상만 친다
        "지정대상id": [p.get("id") for p in 지정대상목록 or []],
        "밀림": 밀림,
        "행동자원": dict(시전자["행동자원"]),
        "기타행동": dict(시전자.get("기타행동") or {}),
    }
    시전자["행동자원"] = {k: 0 for k in 시전자["행동자원"]}
    if 시전자.get("기타행동"):
        시전자["기타행동"] = {k: 0 for k in 시전자["기타행동"]}
    시전자.setdefault("상태이상", []).append({"이름": 종류, "지속턴": None})
    # 악귀참수 - 차징하는 동안만 슈퍼아머(쏘거나 끊기면 _캐스팅_풀기가 뗀다). 중화기 마스터리는 특성으로
    # 그 타입 스킬의 차징에 준다.
    if 스킬데이터.get("차징슈퍼아머") or (
        종류 == "차징"
        and traits.차징_슈퍼아머인가(전투상태, 시전자, 스킬데이터.get("타입"))
    ):
        시전자["상태이상"].append(
            {"이름": "슈퍼아머", "지속턴": None, "차징연동": True}
        )
    시전자["캐스팅시작"] = True
    결과 = {
        "공격자": 시전자["이름"],
        "대상": 시전자["이름"],
        "스킬": 스킬데이터["_이름"],
        "비고": f"{스킬데이터['_이름']} {종류}을 시작했다({_밀림_글(밀림)}, 밀린 차례에 발사).",
        "캐스팅": True,
    }
    core.로그(전투상태, 결과, 종류="비고")
    if 스킬데이터.get("차징시작효과"):
        결과["차징시작"] = _차징시작효과(전투상태, 시전자, 스킬데이터)
    return 결과


def _차징시작효과(전투상태, 시전자, 스킬데이터):
    """스킬 "차징시작효과"(익스트루더) - 차징을 시작할 때 "타겟"마다 "명중률"로 굴려 맞힌 대상에게 "효과"를
    건다(피해 없음). [(대상 이름, 맞았나)]를 돌려준다."""
    원소 = 스킬데이터["차징시작효과"]
    기록 = []
    for 대상 in 타겟_확장(전투상태, 시전자, 원소["타겟"]):
        판정 = 스킬_명중_판정(
            전투상태, 시전자, 대상, 원소["명중률"], 원소.get("명중보너스", 0)
        )
        효과로그 = (
            효과_적용(전투상태, 시전자, 대상, 원소.get("효과")) if 판정["성공"] else []
        )
        기록.append((대상["이름"], 판정["성공"]))
        core.로그(
            전투상태,
            {
                "공격자": 시전자["이름"],
                "대상": 대상["이름"],
                "스킬": 스킬데이터["_이름"],
                "비고": "; ".join(효과로그)
                if 판정["성공"]
                else f"{대상['이름']}에게 빗나갔다.",
            },
            종류="비고",
        )
    return 기록


# =====================================================
# 채널링 공격(광충노도) - 스킬 "최대채널링"
# =====================================================
# 쓰면 시전자가 "채널링버프"를 얻고 인스턴스에 쓴 횟수("채널링횟수")와 이번 자기 턴에 썼다는 표시("채널링이번턴"),
# 풀릴 때 칠 "채널링종료공격"을 적는다. "최대채널링"번째로 쓰거나, 자기 차례에 쓰지 않고 턴을 끝내거나, 쓰러지거나
# 무력화되면 풀리면서 그 공격으로 친다(쓰러진 시전자도 친다). "채널링종료공격"이 없는 스킬(마도학자 메가 드릴 등)은
# 풀릴 때 치지 않는다. 넨가드의 채널링(channeling.py)과는 따로다.


def 채널링공격_진행(전투상태, 시전자, 스킬데이터):
    """채널링 공격을 쓴 뒤 - 채널링을 시작하거나 횟수를 센다. 최대 횟수면 풀리며 터진다."""
    최대 = 스킬데이터.get("최대채널링")
    if not 최대:
        return
    이름 = 스킬데이터["채널링버프"]
    항목 = next((b for b in 시전자["버프"] if b["이름"] == 이름), None)
    if 항목 is None:
        이름있는효과_부여(전투상태, 시전자, 이름, 시전자=시전자)
        항목 = next(b for b in 시전자["버프"] if b["이름"] == 이름)
        항목["채널링횟수"] = 0
        종료공격 = 스킬데이터.get("채널링종료공격")
        항목["채널링종료공격"] = (
            dict(
                종료공격,
                분류="공격스킬",
                _이름=f"{스킬데이터.get('_이름')} (채널링 종료)",
            )
            if 종료공격
            else None
        )
    항목["채널링횟수"] += 1
    항목["채널링이번턴"] = True
    if 항목["채널링횟수"] >= 최대:
        채널링공격_종료(전투상태, 시전자, 항목, f"{최대}회째")


def 채널링공격_종료(전투상태, 시전자, 항목, 까닭):
    if 항목 in 시전자["버프"]:
        시전자["버프"].remove(항목)
    core.로그(
        전투상태,
        {
            "공격자": 시전자["이름"],
            "대상": 시전자["이름"],
            "비고": f"'{항목['이름']}' 채널링이 풀렸다({까닭}).",
        },
        종류="비고",
    )
    if 항목.get("채널링종료공격"):
        공격스킬_실행(전투상태, 시전자, dict(항목["채널링종료공격"]))


