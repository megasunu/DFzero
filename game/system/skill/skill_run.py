def 무작위_적(전투상태, 시전자):
    """시전자의 반대 진영에서 살아 있는 적 하나(지정 가능한 적 우선). 없으면 None."""
    상대 = "적" if 시전자["진영"] == "아군" else "아군"
    후보 = [p for p in 전투상태["참가자"] if p["진영"] == 상대 and p["생존"]]
    지정가능 = [p for p in 후보 if not status.상태이상_플래그(전투상태, p, "지정불가")]
    후보 = 지정가능 or 후보
    return rng.대상.choice(후보) if 후보 else None


def 설치소환수_붙이기(
    전투상태, 시전자, 이름, 대상, 스킬이름, 차수=None, 임시생명력식=None
):
    """임시생명력식(스킬 "설치임시생명력" - 카운트다운)이 있으면 그 양을 붙인 항목에 시전자의
    임시생명력으로 담는다(resources.설치임시생명력_흡수)."""
    항목 = resources.설치소환수_설치(전투상태, 시전자, 이름, 대상, 차수)
    비고 = f"{대상['이름']}에게 {이름}을(를) 붙였다."
    if 임시생명력식 is not None:
        양 = max(0, 정수_평가(임시생명력식, 전투상태, 시전자, 기본값=0))
        if 양:
            항목["임시생명력"] = 양
            비고 += f" 임시생명력 {양} 획득."
    결과 = {
        "공격자": 시전자["이름"],
        "대상": 대상["이름"],
        "스킬": 스킬이름,
        "비고": 비고,
    }
    core.로그(전투상태, 결과, 종류="비고")
    return 결과


def 설치소환수_폭발(전투상태, 항목, 추가피해=None):
    """설치소환수 하나를 자폭시킨다 - 붙은 적(쓰러졌으면 살아 있는 적 무작위)에게 정의 "자폭스킬"의 공격을
    한 번. 항목에 "차수"가 있으면 피해식의 차수를 그 값으로, 추가피해(로봇전폭)가 있으면 피해식에 더한다.
    시전자가 쓰러졌거나 칠 적이 없으면 터지지 않는다(None). 목록에서 빼는 것은 부르는 쪽이다."""
    시전자 = core.참가자_찾기(전투상태, 항목["시전자id"])
    if 시전자 is None or not 시전자["생존"] or 원포올_보유(전투상태, 시전자):
        return None  # 원포올 - 자폭 피해가 없다
    대상 = core.참가자_찾기(전투상태, 항목["대상id"])
    if 대상 is None or not 대상["생존"]:
        대상 = 무작위_적(전투상태, 시전자)
    if 대상 is None:
        return None
    정의 = summon_00.소환수목록[항목["이름"]]
    스킬데이터 = dict(전투상태["스킬정의"][정의["자폭스킬"]])
    스킬데이터.pop("설치소환수", None)
    데미지 = str(스킬데이터["데미지"])
    if "차수" in 항목:
        데미지 = 데미지.replace("차수", str(항목["차수"]))
    if 추가피해:
        데미지 = f"{데미지}+{추가피해}"
    스킬데이터.update(
        데미지=데미지, 타겟="적단일", 공격횟수=1, _이름=f"{항목['이름']} 자폭"
    )
    return 공격스킬_실행(전투상태, 시전자, 스킬데이터, 대상)


# combat은 스킬 공격을 부를 수 없어 임시생명력이 다 닳은 카운트다운의 폭발을 이 함수로 맡긴다
resources.설치소환수_폭발기 = 설치소환수_폭발


def 설치소환수_목록(전투상태):
    return 전투상태.setdefault("설치소환수", [])


def 올포원_추가피해(전투상태, 시전자, 식=None):
    """퍽 올포원 - 소환수 하나의 피해식에 더할 여섯 능력치 보정치 합(없으면 식 그대로)."""
    if traits.특성_수치(전투상태, 시전자, "올포원") <= 0:
        return 식
    합 = stats.모든_능력치_보정치_합(전투상태, 시전자)
    return f"{식}+{합}" if 식 else str(합)


def 메카소환수_폭발(전투상태, 시전자, 소환수이름, 추가피해=None):
    """자신에게 붙은 메카(템페스트/게일포스/스패로우 팩토리/바이퍼)를 돌려보내고, 정의 "자폭공격"으로 무작위 적
    1체를 친다. 원포올이거나 칠 적이 없으면 치지 않는다. 쳤으면 공격 결과, 아니면 None.
    버프는 이미 끝났는데 등록만 남은 메카(지속턴 메카가 캐스팅으로 마지막 공격을 건너뛴 때)도 등록을 지우고 터진다."""
    if not 소환수_해제(시전자, 소환수이름, 소환수_마릿수(시전자, 소환수이름)):
        if 소환수이름 not in 시전자.get("소환수", []):
            return None
        시전자["소환수"].remove(소환수이름)
    if 원포올_보유(전투상태, 시전자) or not 시전자["생존"]:
        return None
    대상 = 무작위_적(전투상태, 시전자)
    if 대상 is None:
        return None
    스킬데이터 = dict(summon_00.소환수목록[소환수이름]["자폭공격"])
    타입 = list(스킬데이터.pop("스킬타입", None) or [])
    데미지 = str(스킬데이터["데미지"]) + (f"+{추가피해}" if 추가피해 else "")
    스킬데이터.update(
        분류="공격스킬",
        타입=타입,
        데미지=데미지,
        공격횟수=1,
        효과=[],
        조건부효과=[],
        일반공격취급=False,
        _이름=f"{소환수이름} 자폭",
    )
    return 공격스킬_실행(전투상태, 시전자, 스킬데이터, 대상)


def 붙은_메카소환수(전투상태):
    """(시전자, 소환수이름) - 살아 있는 참가자에게 붙은 "메카" 태그 소환수, 참가자 순서대로."""
    return [
        (p, 이름)
        for p in 전투상태["참가자"]
        if p["생존"]
        for 이름 in list(p.get("소환수", []))
        if "메카" in 소환수_태그(이름)
    ]


def 메카짝_처리(전투상태, 시전자, 스킬데이터):
    """ "짝소환수"(템페스트/게일포스) - 특성 자비스가 있으면 짝도 함께 부르고, 없으면 짝이 있을 때 짝을
    자폭시킨다(로봇전폭의 추가피해 없이)."""
    짝 = 스킬데이터.get("짝소환수")
    if not 짝:
        return
    if traits.특성_수치(전투상태, 시전자, "자비스") > 0:
        if 소환수_마릿수(시전자, 짝) <= 0:
            짝스킬 = dict(전투상태["스킬정의"][짝], _이름=짝)
            짝스킬.pop("짝소환수", None)
            버프자원소환_스킬_실행(전투상태, 시전자, 짝스킬)
        return
    if 소환수_마릿수(시전자, 짝) > 0:
        메카소환수_폭발(전투상태, 시전자, 짝)


def 메카_전폭(전투상태, 시전자, 스킬데이터):
    """로봇전폭 - 맵의 모든 "메카" 설치소환수(누가 붙였든)를 붙인 순서대로 바로 자폭시키고, 이어 참가자에게
    붙은 메카 소환수(템페스트 등)도 자폭시킨다. 자폭마다 스킬 "메카자폭" 식(올포원이면 여섯 능력치 보정치 합도)을
    피해에 더한다."""
    추가 = 올포원_추가피해(전투상태, 시전자, 스킬데이터["메카자폭"])
    메카 = [
        항목
        for 항목 in 설치소환수_목록(전투상태)
        if "메카" in summon_00.소환수목록[항목["이름"]].get("태그", [])
    ]
    전투상태["설치소환수"] = [
        항목 for 항목 in 설치소환수_목록(전투상태) if not any(항목 is m for m in 메카)
    ]
    붙은것 = 붙은_메카소환수(전투상태)
    터짐 = sum(1 for 항목 in 메카 if 설치소환수_폭발(전투상태, 항목, 추가))
    터짐 += sum(
        1 for 주인, 이름 in 붙은것 if 메카소환수_폭발(전투상태, 주인, 이름, 추가)
    )
    결과 = {
        "공격자": 시전자["이름"],
        "스킬": 스킬데이터["_이름"],
        "비고": f"메카 {터짐}개가 자폭했다." if 터짐 else "자폭할 메카가 없다.",
    }
    core.로그(전투상태, 결과, 종류="비고")
    return 결과


def 형태_패턴(시전자, 스킬데이터):
    """ "형태전환"(트랜스폼) - 시전자가 지금 가진 형태(형태순서의 상태변화) 다음 형태의 이름. 없으면 첫 형태."""
    순서 = 스킬데이터["형태순서"]
    지금 = next(
        (b["이름"] for b in 시전자.get("상태이상", []) if b["이름"] in 순서), None
    )
    if 지금 is None:
        return 순서[0]
    return 순서[(순서.index(지금) + 1) % len(순서)]


def 형태_전환(시전자, 스킬데이터, 패턴):
    """이전 형태를 지우고 새 형태(상태변화)를 지속턴 없이 건다."""
    순서 = 스킬데이터["형태순서"]
    목록 = 시전자.setdefault("상태이상", [])
    목록[:] = [b for b in 목록 if b["이름"] not in 순서]
    목록.append({"이름": 패턴})


def _설치소환_실행(전투상태, 시전자, 스킬데이터, 중심대상):
    """ "설치소환수" 공격스킬(랜드러너/카운트다운) - 지금 치지 않고 지정한 적에게 소환수를 붙인다."""
