def 공격스킬_분기(
    전투상태,
    시전자,
    스킬데이터,
    중심대상=None,
    지정대상목록=None,
    타겟종류오버라이드=None,
):
    """공격스킬을 "타입"에 맞는 길로 친다 - 분할공격/지속공격(등록)/그 밖(공격스킬_실행). 스킬_실행과
    캐스팅_발사(밀린 차례)가 같이 쓴다."""
    if 스킬데이터.get("체이서소모"):  # 배틀메이지 - 체이서마다 한 번씩
        return _체이서_공격(
            전투상태, 시전자, 스킬데이터, 중심대상, 지정대상목록, 타겟종류오버라이드
        )
    타입목록 = 스킬데이터.get("타입", [])
    if 스킬데이터.get("설치소환수"):
        return _설치소환_실행(전투상태, 시전자, 스킬데이터, 중심대상)
    if 스킬데이터.get("환수희생"):
        return _환수희생_실행(전투상태, 시전자, 스킬데이터)
    if "지뢰" in 타입목록:  # 베놈 마인 - 지금은 깔기만 한다(예약타격_발동)
        return 지뢰_설치(전투상태, 시전자, 스킬데이터)
    if 스킬데이터.get(
        "라운드종료저격"
    ):  # 닐 스나이핑 - 지금은 등록만(skill_turn.라운드종료_처리)
        return 저격_등록(전투상태, 시전자, 스킬데이터)
    if "분할공격" in 타입목록:
        return 분할공격_실행(전투상태, 시전자, 스킬데이터, 중심대상)
    if "지속공격" in 타입목록:
        return 지속공격_등록(전투상태, 시전자, 스킬데이터, 중심대상)
    결과 = 공격스킬_실행(
        전투상태, 시전자, 스킬데이터, 중심대상, 지정대상목록, 타겟종류오버라이드
    )
    던지기 = 던지기_발동(전투상태, 시전자, 스킬데이터, 중심대상, 결과)  # 로플링
    if 던지기:
        결과["던지기"] = 던지기
    return 결과


def _체이서_공격(전투상태, 시전자, 스킬데이터, 중심대상, 지정대상목록, 오버라이드):
    """ "체이서소모"(1 | "전부" - 배틀메이지) - 그만큼 체이서를 먼저 생긴 것부터 쓰고 체이서마다 그 속성으로
    한 번씩 친다. 대상이 쓰러지면 남은 타격은 하지 않는다(쓴 체이서는 돌아오지 않는다)."""
    개수 = 스킬데이터["체이서소모"]
    속성들 = resources.체이서_소모(시전자, None if 개수 == "전부" else int(개수))
    결과들 = []
    for 속성 in 속성들:
        if 중심대상 is not None and not 중심대상["생존"]:
            break
        결과들.append(
            공격스킬_분기(
                전투상태,
                시전자,
                {**스킬데이터, "속성": 속성, "체이서소모": None},
                중심대상,
                지정대상목록,
                오버라이드,
            )
        )
    결과 = dict(결과들[0]) if 결과들 else {"공격자": 시전자["이름"]}
    결과["체이서"] = 속성들
    if len(결과들) > 1:
        결과["추가타격"] = 결과들[1:]
    return 결과


def 다른전직_적용(시전자, 스킬데이터):
    """ "전용전직"이 아닌 캐릭터(훔쳐 배운 다른 전직)가 쓰면 "다른전직변형"의 키로 덮어쓴다(바디블로)."""
    전용 = 스킬데이터.get("전용전직")
    if not 전용 or (시전자.get("원본") or {}).get("전직") == 전용:
        return 스킬데이터
    return {**스킬데이터, **(스킬데이터.get("다른전직변형") or {})}


def _다음턴_추가공격_등록(시전자, 스킬데이터, 중심대상):
    """공격스킬 "다음턴추가공격"(공력의 구) - 시전자의 다음 턴 시작에 같은 대상을 그 공격 데이터로 친다
    (다음_턴 -> 다음턴_추가공격)."""
    원소 = 스킬데이터.get("다음턴추가공격")
    if 원소 and 중심대상 is not None:
        시전자.setdefault("다음턴추가공격", []).append(
            {"원소": 원소, "대상id": 중심대상.get("id")}
        )


def 공격_시전자버프(전투상태, 시전자, 스킬이름, 스킬데이터):
    """공격스킬의 "시전자버프획득"(후퇴기동) - 명중과 상관없이 쓴 뒤 시전자에게 건다
    ("시전자버프중첩량"/"시전자버프지속턴"). 채널링버프(비트 드라이브)는 이미 걸려 있으면 새로 걸지 않는다 -
    지속턴은 처음 쓴 때부터 센다."""
    채널 = 스킬데이터.get("채널링버프")
    for 이름 in 스킬데이터.get("시전자버프획득") or []:
        if 이름 == 채널 and any(b["이름"] == 채널 for b in 시전자["버프"]):
            continue
        이름있는효과_부여(
            전투상태,
            시전자,
            이름,
            중첩량=스킬데이터.get("시전자버프중첩량", 1),
            지속턴오버라이드=스킬데이터.get("시전자버프지속턴"),
            시전자=시전자,
            출처스킬=스킬이름,
        )
    # "시전자전투버프"(죄악 스킬의 죄업) - 지속턴 없이 전투가 끝날 때까지. 상태이상 이름(슈퍼아머)도 된다
    for 이름 in 스킬데이터.get("시전자전투버프") or []:
        resources.몬스터_버프_부여(전투상태, 시전자, 이름, None)
    if 스킬데이터.get("임시생명력부여"):
        _임시생명력_부여(전투상태, 시전자, 스킬이름, 스킬데이터["임시생명력부여"])
    # "시전자버프소모"(비트 드라이브 피니쉬) - 쓴 뒤 시전자의 그 버프를 지운다(채널링이 끝난다)
    소모 = 스킬데이터.get("시전자버프소모") or []
    if 소모:
        시전자["버프"] = [b for b in 시전자["버프"] if b["이름"] not in 소모]


def 인형_소환자(전투상태, 시전자):
    """스킬로 부른 인형(원본 "소환자" - 매드)이면 그 인형을 부른 아군 참가자, 아니면 None."""
    이름 = 시전자["원본"].get("소환자")
    if not 이름:
        return None
    return next(
        (
            p
            for p in 전투상태["참가자"]
            if p is not 시전자 and p["원본"].get("캐릭터명") == 이름
        ),
        None,
    )


def 인형패턴_강화_적용(전투상태, 시전자, 스킬이름, 스킬데이터):
    """인형이 쓰는 패턴은 그 인형을 부른 사람 무기의 "인형패턴" 강화도 받는다(인형사의 청소도구)."""
    소환자 = 인형_소환자(전투상태, 시전자)
    if 소환자 is None:
        return 스킬데이터
    return equipment_system.스킬강화_적용(
        소환자.get("장비데이터"), 스킬이름, 스킬데이터, 인형패턴만=True
    )


def _임시생명력_부여(전투상태, 시전자, 스킬이름, 상세):
    """공격스킬 "임시생명력부여"({"양", "버프", "지속턴"} - 매디 가드) - 시전자와 그 인형을 부른 사람(원본
    "소환자")에게 "버프"를 걸고 그 인스턴스에 임시생명력 "양"(시전자 기준 식)을 담는다."""
    양 = formula.올림(
        formula.수식_평가(str(상세["양"]), stats.기본_컨텍스트(전투상태, 시전자))
    )
    소환자 = 시전자["원본"].get("소환자")
    대상들 = [시전자] + [
        p
        for p in 전투상태["참가자"]
        if 소환자
        and p["생존"]
        and p is not 시전자
        and p["원본"].get("캐릭터명") == 소환자
    ]
    for 대상 in 대상들:
        이름있는효과_부여(
            전투상태,
            대상,
            상세["버프"],
            지속턴오버라이드=상세.get("지속턴"),
            시전자=시전자,
            출처스킬=스킬이름,
        )
        for 항목 in 대상["버프"]:
            if 항목["이름"] == 상세["버프"]:
                항목["임시생명력"] = 양


def _스킬사용후_스택(전투상태, 시전자, 스킬데이터):
    """스킬을 쓰고 나서 쌓는 스택 - 인파이터 텐션, 호신연격(스킬 자체나 공격단계가 일반공격취급)."""
    traits.텐션_쌓기(전투상태, 시전자, 스킬데이터)
    if 일반공격취급인가(스킬데이터):
        traits.호신연격_스택(전투상태, 시전자, "일반공격취급스킬")


def 스킬_실행(
    전투상태,
    시전자,
    스킬이름,
    스킬데이터,
    중심대상=None,
    지정대상목록=None,
    행동지불=None,
):
    """job_skill_XX.py "스킬목록"의 스킬 하나를 실행한다.

    시전자        : combat 패키지의 참가자 인스턴스 (진영 "아군"만 지원).
    스킬이름      : job_skill_XX.py "스킬목록" 딕셔너리의 키 (턴당사용제한/
                     전투당횟수 추적, 로그 표시용).
    스킬데이터    : 그 키의 값 (job_skill_format.py 양식을 따르는 딕셔너리).
    중심대상      : "적단일"/"적3체"/"아군단일" 등에 쓸 중심 대상 1개.
                     "자신"/"아군전체"/"적전체"처럼 대상이 필요 없는
                     타겟이면 생략해도 된다.
    지정대상목록  : "적반복지정" 타겟일 때만 쓰는, 타격별로 이미 정해둔
                     대상 리스트 (없으면 중심대상 하나를 전부 재사용한다 -
                     실제 매 타격 대상 선택은 UI가 결정해야 정확하다).
    행동지불      : 스킬의 "일반행동"을 낼 수단("쇼타임행동"/"일반행동"/"보조행동").
                     생략하면 기본 순서(일반행동_지불수단_목록 참고).
    """
    스킬데이터 = dict(스킬데이터)
    스킬데이터["_이름"] = 스킬이름
    # 합격 - 원귀가 기억한 패턴을 대상 검증과 자원 소모(원귀가 사라진다) 전에 읽는다
    스킬데이터, 패턴 = 패턴_적용(전투상태, 시전자, 스킬데이터)
    스킬데이터 = 이중투척_적용(전투상태, 시전자, 스킬데이터)
    스킬데이터 = 대체_적용(전투상태, 스킬데이터, 중심대상)
    스킬데이터 = 그랩캐넌_적용(전투상태, 시전자, 스킬데이터, 중심대상)
    스킬데이터 = 잡기이점_적용(전투상태, 시전자, 스킬데이터)
    스킬데이터 = 특성강화_적용(시전자, 스킬데이터)
    스킬데이터 = 다른전직_적용(시전자, 스킬데이터)
    # 레어 무기의 "스킬강화"(데스 바이 수플렉스·강룡완 등)
    스킬데이터 = equipment_system.스킬강화_적용(
        시전자.get("장비데이터"), 스킬이름, 스킬데이터
    )
    스킬데이터 = 인형패턴_강화_적용(전투상태, 시전자, 스킬이름, 스킬데이터)
    스킬데이터 = 양쪽대상_적용(시전자, 스킬데이터, 중심대상)
    강화 = 스킬강화(시전자, 스킬데이터)
    if 강화:
        # 피해 계산 끝(방어/속성 배율 뒤)에 곱한다 - 공격_1회/지속피해/지속공격까지
        스킬데이터["최종피해배율"] = 강화["최종피해배율"]

    # 여기서 구하는 전역오버라이드는 대상 없이(대상=None) 판정 가능한
    # 조건("자원보유"/"아군상태"/"HP비율이하"/"특성보유")만 반영된다. 이걸로
    # "MP소모"/"타겟"/"타겟제한"/"일반공격취급"의 스킬 전체 레벨 오버라이드를
    # 구한다. 단, 조건부효과의 "자원소모"는 여기서 미리 소모하지 않는다 -
    # 그 자원소모는 "조건이 실제로 적용되는 순간"(대상별 데미지/명중 보너스가
    # 실제로 붙는 그 타격)에 딸린 대가라서, 공격_1회()가 각 타격마다 다시
    # 조건을 확인하며 그때 소모한다(위 조건부효과_평가/공격_1회 참고).
    # 여기서 미리 소모해버리면 그 다음에 하는 대상별 재판정에서 자원이 이미
    # 사라진 걸로 보여 보너스가 아예 적용되지 않는 문제가 생긴다.
    전역오버라이드 = 조건부효과_평가(
        전투상태, 시전자, None, 스킬데이터.get("조건부효과", [])
    )
    MP소모오버라이드 = 전역오버라이드.get("MP소모")

    가능, 사유 = 사용_가능여부(전투상태, 시전자, 스킬데이터, MP소모오버라이드)
    if not 가능:
        raise ValueError(f"'{스킬이름}' 사용 불가: {사유}")

    if 행동지불 is not None and 행동지불 not in 일반행동_지불수단_목록(
        전투상태, 시전자, 스킬데이터
    ):
        raise ValueError(f"'{스킬이름}'은(는) 지금 '{행동지불}'(으)로 쓸 수 없다.")

    타겟종류오버라이드 = 전역오버라이드.get("타겟")
    # 대상이 잘못됐으면 비용(MP/행동/횟수)을 쓰기 전에 거부한다(B7).
    대상_검증(
        전투상태,
        스킬_타겟종류(스킬데이터, 타겟종류오버라이드),
        중심대상,
        스킬데이터.get("타입"),
    )
    if 스킬데이터.get("타겟제한") == "자신제외" and 중심대상 is 시전자:
        raise ValueError(f"'{스킬이름}'은(는) 자신을 대상으로 쓸 수 없다.")

    if "분신폭파" in 스킬데이터.get("타입", []):
        # 환영폭쇄 - 자원소모(분신)로 버프가 지워지기 전에 분신 수만큼 친다
        스킬데이터["공격횟수"] = max(
            (b.get("분신수", 0) for b in 시전자["버프"] if b["이름"] == "분신"),
            default=0,
        )
    channeling.채널링_행동해제(전투상태, 시전자)  # 넨가드 - 다음 턴에 행동하면 풀린다
    자원_소비_처리(전투상태, 시전자, 스킬데이터, MP소모오버라이드, 행동지불=행동지불)
    스킬데이터 = 행동전부소모_적용(전투상태, 시전자, 스킬데이터)
    스킬데이터, 패턴 = _무작위패턴_고르기(스킬데이터, 스킬이름, 패턴)
    스킬데이터 = 퍼밀리어_굴림(전투상태, 시전자, 스킬데이터)

    분류 = 스킬데이터["분류"]
    타입목록 = 스킬데이터.get("타입", [])
    if "위상력" in 타입목록:  # 위상력 각성 계열 결전기 - 대사(설명)를 먼저 쓴다
        core.로그(
            전투상태,
            {
                "공격자": 시전자["이름"],
                "비고": 스킬데이터.get("설명", ""),
                "대사": 스킬데이터.get("설명", ""),
            },
            종류="비고",
        )

    if 캐스팅_종류(스킬데이터) and not 캐스팅_바로쏨(
        전투상태, 시전자, 스킬데이터
    ):  # 캐스팅·차징 - 턴을 끝내고 밀린 차례에 쏜다
        return 캐스팅_시작(전투상태, 시전자, 스킬데이터, 중심대상, 지정대상목록)
    if 분류 == "공격스킬":
        연속홀딩_시작(전투상태, 시전자, 스킬데이터, 중심대상)  # 정크 스핀만
        분기 = _명중반복_실행 if 스킬데이터.get("명중반복") else _혼란_공격스킬_분기
        결과 = 분기(
            전투상태, 시전자, 스킬데이터, 중심대상, 지정대상목록, 타겟종류오버라이드
        )
        if 스킬데이터.get("_이중투척") == 2 and _한번_더_던지나(전투상태, 중심대상):
            두번째 = 공격스킬_분기(
                전투상태, 시전자, 스킬데이터, 중심대상, 지정대상목록, 타겟종류오버라이드
            )
            결과 = dict(결과, 투척횟수=2, 두번째=두번째)
        if not {"분할공격", "지속공격"}.intersection(타입목록):
            후속 = 특성_후속공격(전투상태, 시전자, 스킬이름, 중심대상, 결과)
            if 후속:
                결과["후속공격"] = 후속
        공격_시전자버프(전투상태, 시전자, 스킬이름, 스킬데이터)
        _다음턴_추가공격_등록(시전자, 스킬데이터, 중심대상)
        채널링공격_진행(전투상태, 시전자, 스킬데이터)
    elif 분류 in ("버프스킬", "자원스킬", "소환스킬") or (
        분류 == "디버프스킬" and "버프획득" in 스킬데이터
    ):  # 적에게 디버프를 "버프획득"으로 거는 디버프스킬(브레멘)은 버프스킬과 같다
        결과 = _버프류_스킬_실행(전투상태, 시전자, 스킬데이터, 중심대상)
    elif 분류 == "전환스킬":
        결과 = 전환스킬_실행(전투상태, 시전자, 스킬데이터)
    elif 분류 in ("해제스킬", "디버프스킬"):
        # 디버프스킬(도발)도 해제스킬처럼 대상마다 "효과"(상태이상 - 내성굴림)를 적용한다
        결과 = 해제스킬_실행(전투상태, 시전자, 스킬데이터, 중심대상)
    elif 분류 == "회복스킬":
        결과 = 회복스킬_실행(전투상태, 시전자, 스킬데이터, 중심대상)
    else:
        raise ValueError(f"알 수 없는 스킬 분류: {분류!r}")

    _패턴자원_부여(전투상태, 시전자, 스킬데이터, 패턴)
    _특수행동_부여(전투상태, 시전자, 스킬데이터)

