def 설치소환수_폭발(전투상태, 항목, 추가피해=None):
    """설치소환수 하나를 자폭시킨다 - 붙은 적(쓰러졌으면 살아 있는 적 무작위)에게 정의 "자폭스킬"의 공격을
    한 번. 항목에 "차수"가 있으면 피해식의 차수를 그 값으로, 추가피해(로봇전폭)가 있으면 피해식에 더한다.
    시전자가 쓰러졌거나 칠 적이 없으면 터지지 않는다(None). 목록에서 빼는 것은 부르는 쪽이다."""
    시전자 = core.참가자_찾기(전투상태, 항목["시전자id"])
    if 시전자 is None or not 시전자["생존"]:
        return None
    대상 = core.참가자_찾기(전투상태, 항목["대상id"])
    if 대상 is None or not 대상["생존"]:
        대상 = _무작위_적(전투상태, 시전자)
    if 대상 is None:
        return None
    정의 = summon_00.소환수목록[항목["이름"]]
    스킬데이터 = dict(전투상태["스킬정의"][정의["자폭스킬"]])
    스킬데이터.pop("설치소환수", None)
    데미지 = str(스킬데이터["데미지"])
    if "차수" in 항목:
        데미지 = 데미지.replace("차수", str(항목["차수"]))
    if 추가피해:
        데미지 = f"{데미지}+{추가피해}"
    스킬데이터.update(
        데미지=데미지, 타겟="적단일", 공격횟수=1, _이름=f"{항목['이름']} 자폭"
    )
    return 공격스킬_실행(전투상태, 시전자, 스킬데이터, 대상)


def 설치소환수_목록(전투상태):
    return 전투상태.setdefault("설치소환수", [])


def 메카_전폭(전투상태, 시전자, 스킬데이터):
    """로봇전폭 - 맵의 모든 "메카" 설치소환수(누가 붙였든)를 붙인 순서대로 바로 자폭시키고, 자폭마다
    스킬 "메카자폭" 식을 피해에 더한다."""
    메카 = [
        항목
        for 항목 in 설치소환수_목록(전투상태)
        if "메카" in summon_00.소환수목록[항목["이름"]].get("태그", [])
    ]
    전투상태["설치소환수"] = [
        항목 for 항목 in 설치소환수_목록(전투상태) if not any(항목 is m for m in 메카)
    ]
    터짐 = sum(
        1 for 항목 in 메카 if 설치소환수_폭발(전투상태, 항목, 스킬데이터["메카자폭"])
    )
    결과 = {
        "공격자": 시전자["이름"],
        "스킬": 스킬데이터["_이름"],
        "비고": f"메카 {터짐}개가 자폭했다." if 터짐 else "자폭할 메카가 없다.",
    }
    core.로그(전투상태, 결과, 종류="비고")
    return 결과


def _형태_공격(전투상태, 시전자, 이름, 공격):
    """버프 원소의 "공격"을 무작위 적 하나에게 "공격횟수"만큼 - 맞을 적이 쓰러지면 다른 적 무작위."""
    대상 = None
    쳤음 = False
    for _ in range(공격.get("공격횟수", 1)):
        if 대상 is None or not 대상["생존"]:
            대상 = _무작위_적(전투상태, 시전자)
        if 대상 is None:
            break
        스킬데이터 = {
            "분류": "공격스킬",
            "데미지보너스": 0,
            "명중보너스": 0,
            "각공격명중굴림": False,
            "일반공격취급": False,
            "효과": [],
            "조건부효과": [],
            **공격,
            "타겟": "적단일",
            "공격횟수": 1,
            "_이름": 이름,
        }
        공격스킬_실행(전투상태, 시전자, 스킬데이터, 대상)
        쳤음 = True
    return 쳤음


def _버프_원소들(시전자, 변동대상):
    for 항목 in list(시전자.get("버프") or []):
        정의 = resources.효과정의_조회(항목["이름"])[0] or {}
        효과 = 정의.get("효과")
        for 원소 in [효과] if isinstance(효과, dict) else 효과 or []:
            if isinstance(원소, dict) and 원소.get("변동대상") == 변동대상:
                yield 항목["이름"], 원소


def 턴종료_버프공격(전투상태, 시전자):
    """시전자의 턴이 끝날 때 - 버프 "턴종료공격"(G-1)과 "턴종료설치"(메카드롭). 스킬 공격이라 아군만."""
    if not 시전자["생존"] or 시전자["진영"] != "아군":
        return
    for 이름, 원소 in list(_버프_원소들(시전자, "턴종료공격")):
        _형태_공격(전투상태, 시전자, 이름, 원소["공격"])
    for 이름, 원소 in list(_버프_원소들(시전자, "턴종료설치")):
        for _ in range(원소.get("개수", 1)):
            대상 = _무작위_적(전투상태, 시전자)
            if 대상 is None:
                break
            설치소환수_붙이기(전투상태, 시전자, 원소["소환수"], 대상, 이름)


def 라운드종료_처리(전투상태):
    """라운드가 끝날 때(combat.flow.다음_턴이 부른다) - 폭발라운드가 된 설치소환수를 붙인 순서대로 자폭시키고,
    살아 있는 참가자의 버프 "라운드종료공격"(G-3)을 친다. 한 번이라도 쳤으면 True."""
    라운드 = 전투상태.get("라운드", 1)
    목록 = 설치소환수_목록(전투상태)
    터질것 = [항목 for 항목 in 목록 if 항목["폭발라운드"] <= 라운드]
    전투상태["설치소환수"] = [
        항목 for 항목 in 목록 if not any(항목 is t for t in 터질것)
    ]
    쳤음 = False
    for 항목 in 터질것:
        쳤음 = bool(설치소환수_폭발(전투상태, 항목)) or 쳤음
    for 참가자 in list(전투상태["참가자"]):
        if not 참가자["생존"] or 참가자["진영"] != "아군":  # 스킬 공격이라 아군만
            continue
        for 이름, 원소 in list(_버프_원소들(참가자, "라운드종료공격")):
            쳤음 = _형태_공격(전투상태, 참가자, 이름, 원소["공격"]) or 쳤음
    return 쳤음


def 형태_패턴(시전자, 스킬데이터):
    """ "형태전환"(트랜스폼) - 시전자가 지금 가진 형태(형태순서의 버프) 다음 형태의 이름. 없으면 첫 형태."""
    순서 = 스킬데이터["형태순서"]
    지금 = next((b["이름"] for b in 시전자.get("버프", []) if b["이름"] in 순서), None)
    if 지금 is None:
        return 순서[0]
    return 순서[(순서.index(지금) + 1) % len(순서)]


def 형태_전환(시전자, 스킬데이터, 패턴):
    """이전 형태를 지우고 새 형태 버프를 지속턴 없이 건다."""
    순서 = 스킬데이터["형태순서"]
    시전자["버프"] = [b for b in 시전자["버프"] if b["이름"] not in 순서]
    시전자["버프"].append({"이름": 패턴, "중첩": 1})


def _설치소환_실행(전투상태, 시전자, 스킬데이터, 중심대상):
    """ "설치소환수" 공격스킬(랜드러너/카운트다운) - 지금 치지 않고 지정한 적에게 소환수를 붙인다."""
    return 설치소환수_붙이기(
        전투상태,
        시전자,
        스킬데이터["설치소환수"],
        중심대상,
        스킬데이터["_이름"],
    )


def _시전자버프_표시(전투상태, 시전자, 스킬데이터, 버프이름들):
    """이 스킬이 시전자에게 건 버프 인스턴스에 넨가드의 표시를 적는다.
    "공용임시생명력" - 아군 공용 임시생명력을 새로 채운다(damage.공용임시생명력_흡수).
    "타입" "채널링" - 다음 자기 턴이 끝나면 사라지는 채널링으로 적는다(damage.채널링_*)."""
    내것 = [
        항목
        for 항목 in 시전자["버프"]
        if 항목["이름"] in 버프이름들
        and 항목.get("출처스킬") == 스킬데이터.get("_이름")
    ]
    if "공용임시생명력" in 스킬데이터:
        양 = max(0, 정수_평가(스킬데이터["공용임시생명력"], 전투상태, 시전자, 기본값=0))
        for 항목 in 내것:
            항목["공용임시생명력"] = 양
    if "채널링" in (스킬데이터.get("타입") or []):
        for 항목 in 내것:
            항목.update(채널링=True, 채널링시전턴=True)
            항목.pop("채널링확인", None)


def _버프군(스킬데이터):
    return {
        t
        for t in 스킬데이터.get("타입") or ()
        if t.startswith("버프") and t.endswith("군")
    }


def 버프군_정리(전투상태, 대상, 스킬데이터):
    """같은 "버프X군" 타입(버프A군 등 #392) 다른 스킬이 대상에게 건 버프를 지운다 - 같은 군끼리는 겹치지
    않고 나중에 건 것이 남는다. 같은 스킬이 건 것은 이름있는효과_부여가 지속턴만 갱신한다."""
    군 = _버프군(스킬데이터)
    if not 군:
        return
    정의모음 = 전투상태.get("스킬정의") or {}
    for 항목 in list(대상["버프"]):
        출처 = 항목.get("출처스킬")
        if (
            출처
            and 출처 != 스킬데이터.get("_이름")
            and 군 & _버프군(정의모음.get(출처) or {})
        ):
            대상["버프"].remove(항목)


def 버프자원소환_스킬_실행(전투상태, 시전자, 스킬데이터, 중심대상=None):
    if 스킬데이터.get("메카자폭"):  # 로봇전폭 - 거는 버프 없이 메카를 자폭시킨다
        return 메카_전폭(전투상태, 시전자, 스킬데이터)
    명중률 = 스킬데이터.get("명중률", "자동")
    if 명중률 != "자동":
        raise NotImplementedError(
            f"버프/자원/소환스킬의 명중률 '{명중률}'은 지원하지 않는다 "
            f"(버프/자원/소환스킬은 항상 '자동'만 쓰는 것으로 확정됨 - 사용자 확인)."
        )

    대상목록 = 타겟_확장(전투상태, 시전자, 스킬데이터["타겟"], 중심대상)
    지속턴 = 스킬데이터.get("지속턴")
    지속턴값 = 정수_평가(지속턴, 전투상태, 시전자) if 지속턴 is not None else None
    if 지속턴값 is not None:
        # 사슬 해제 - 전투 끝까지인 귀신(카잔)은 해당 없음
        지속턴값 += 귀신_지속턴_보너스(전투상태, 시전자, 스킬데이터)
        # 특성 "스킬지속턴"(니트로모터 - 공중사격 +1턴 #391)
        지속턴값 += sum(
            원소.get("변동값", 0)
            for 원소 in traits.캐릭터특성_무기효과(전투상태, 시전자, "스킬지속턴")
            if 원소.get("스킬") == 스킬데이터.get("_이름")
        )

    버프이름들 = 스킬데이터.get("버프획득") or (
        [스킬데이터["자원획득"]] if "자원획득" in 스킬데이터 else []
    )
    if isinstance(버프이름들, str):
        버프이름들 = [버프이름들]

    # 중첩량 수식("주문시전보정치" 등)은 건 사람(시전자) 기준이다 - 용맹의 축복처럼
    # 시전자의 보정치만큼 거는 스킬. 0 이하면 걸지 않는다(음수 중첩 방지).
    중첩량 = 정수_평가(스킬데이터.get("중첩량", 1), 전투상태, 시전자)
    for 대상 in 대상목록:
        버프군_정리(전투상태, 대상, 스킬데이터)
        for 이름 in 버프이름들:
            if 중첩량 <= 0:
                continue
            이름있는효과_부여(
                전투상태,
                대상,
                이름,
                중첩량=중첩량,
                지속턴오버라이드=지속턴값,
                시전자=시전자,
                무기조건=스킬데이터.get("버프무기조건"),
                출처스킬=스킬데이터.get("_이름"),
            )

        if "임시생명력" in 스킬데이터:
            양 = formula.올림(
                formula.수식_평가(
                    스킬데이터["임시생명력"], stats.기본_컨텍스트(전투상태, 대상)
                )
            )
            담을버프 = next(
                (
                    항목
                    for 항목 in 대상["버프"]
                    if 버프이름들
                    and 항목["이름"] == 버프이름들[0]
                    and 항목.get("출처스킬") == 스킬데이터.get("_이름")
                ),
                None,
            )
            if 담을버프 is not None:  # 신성한 빛/완충모듈 - 버프와 함께 사라진다(#392)
                담을버프["임시생명력"] = 양
            else:
                대상["임시생명력"] = 대상.get("임시생명력", 0) + 양

    _시전자버프_표시(전투상태, 시전자, 스킬데이터, 버프이름들)
    # "시전자버프획득"(태양의 커튼 #280) - 대상들과 따로 시전자 자신에게만 같은 지속턴으로 건다
    for 이름 in 스킬데이터.get("시전자버프획득") or []:
        이름있는효과_부여(
            전투상태,
            시전자,
            이름,
            지속턴오버라이드=지속턴값,
            시전자=시전자,
            출처스킬=스킬데이터.get("_이름"),
        )
    # "즉시이니셔티브"(활성화 숨결 #280) - 이번 라운드 이니셔티브를 올리고 아직 행동하지 않은 순서를 다시 세운다
    if 스킬데이터.get("즉시이니셔티브"):
        for 대상 in 대상목록:
            대상["이니셔티브"] += 스킬데이터["즉시이니셔티브"]
        damage.남은_순서_정렬(전투상태)

    결과 = {
        "공격자": 시전자["이름"],
        "스킬": 스킬데이터.get("_이름"),
        "대상": [p["이름"] for p in 대상목록],
        "버프": 버프이름들 + list(스킬데이터.get("시전자버프획득") or []),
    }
    core.로그(전투상태, 결과, 종류="버프")
    return 결과


def 전환스킬_실행(전투상태, 시전자, 스킬데이터):
    """ "전환특성"(토글 특성 - 프렌지)을 켜거나 끈다. 상태는 캐릭터 원본에 남는다(전투가 끝나도)."""
    특성 = 스킬데이터["전환특성"]
    켜짐 = effect_engine.특성_전환(시전자["원본"], 특성)
    if 켜짐 and 스킬데이터.get("켤때MP"):  # 나선의 넨(#280) - 켤 때만 MP
        시전자["현재MP"] = max(0, 시전자["현재MP"] - 스킬데이터["켤때MP"])
    if 켜짐:  # 나선의 넨 - 켜면 반격 스택이 최대로 찬다(칸이 없으면 최대, damage.나선의넨_반격)
        시전자.pop("피격반격스택", None)
    결과 = {
        "공격자": 시전자["이름"],
        "대상": 시전자["이름"],
        "스킬": 스킬데이터.get("_이름"),
        "비고": f"'{특성}'을(를) {'켰다' if 켜짐 else '껐다'}.",
    }
    core.로그(전투상태, 결과, 종류="비고")
    return 결과


