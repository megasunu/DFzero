def _공격옵션_만들기(전투상태, 시전자, 스킬데이터):
    """스킬 데이터에서 타격마다 같은 값(공격옵션)을 만든다. "일반공격취급"/"장전소모" 스킬이면
    장전 버프(은탄 등)를 1개 소모해 속성변환/추가피해를 반영한다(명중 여부와 무관)."""
    데미지보너스 = 스킬데이터.get("데미지보너스", 0)
    속성변환 = None
    추가피해목록 = None
    if 스킬데이터.get("일반공격취급") or 스킬데이터.get("장전소모"):
        _, 장전속성변환, 장전추가피해, 장전추가피해속성 = attacks.장전소모_처리(
            전투상태, 시전자
        )
        속성변환 = 장전속성변환
        if 장전추가피해속성 and 장전추가피해:
            # 은탄: 추가피해는 공격 속성과 따로 명속성으로 계산.
            추가피해목록 = [(장전추가피해, 장전추가피해속성)]
        else:
            데미지보너스 += 장전추가피해
    # 귀참드라이브 - 카잔 장판이면 귀참 자신도 명중 +1, 피해 이점(장판별 "본스킬")
    드라이브 = next(
        (
            귀참드라이브_구성(전투상태, 시전자, 원소)
            for 원소 in _장판연계(전투상태, 시전자, 스킬데이터.get("_이름"))
        ),
        None,
    ) or {"본스킬명중보너스": 0, "본스킬이점": False}
    return 공격옵션(
        데미지보너스=데미지보너스,
        명중보너스=정수_평가(스킬데이터.get("명중보너스", 0), 전투상태, 시전자, 0)
        + 드라이브["본스킬명중보너스"],
        강제치명타=스킬데이터.get("강제치명타", False),
        치명타체크=스킬데이터.get("치명타체크", False),
        효과리스트=스킬데이터.get("효과", []),
        조건부효과리스트=스킬데이터.get("조건부효과", []),
        속성=스킬데이터.get("속성"),
        공격타입=스킬데이터.get("공격타입"),
        추가피해목록=추가피해목록,
        속성변환=속성변환,
        속성추가피해=스킬데이터.get("속성추가피해"),
        일반공격취급=bool(스킬데이터.get("일반공격취급")),
        최종피해배율=스킬데이터.get("최종피해배율", 1),
        장비보너스=not 스킬데이터.get("장비보너스제외"),
        타격추가피해=not 스킬데이터.get("타격추가피해제외"),
        태그=tuple(스킬데이터.get("타입") or ()),
        이름=스킬데이터.get("_이름"),
        명중이점=bool(스킬데이터.get("명중이점")),
        피해이점=드라이브["본스킬이점"],
    )


def _반복_대상_고르기(후보풀, 타겟종류, 지정대상목록, 번호, 대상당제한, 선택횟수):
    """ "적랜덤반복"/"적반복지정"의 번호째 타격 대상. 고를 수 있는 적이 없으면 None."""
    if 타겟종류 == "적반복지정" and 지정대상목록:
        대상 = 지정대상목록[번호] if 번호 < len(지정대상목록) else 지정대상목록[-1]
        if not 대상["생존"]:
            # 앞선 타격으로 지정 대상이 쓰러지면 남은 적 중 무작위로
            # 대신 맞힌다(가정 - 헛치지 않게).
            남은적 = [p for p in 후보풀 if p["생존"]]
            대상 = rng.대상.choice(남은적) if 남은적 else None
        return 대상
    유효후보 = [
        p
        for p in 후보풀
        if p["생존"] and (대상당제한 is None or 선택횟수.get(id(p), 0) < 대상당제한)
    ]
    if not 유효후보:
        유효후보 = [p for p in 후보풀 if p["생존"]]
    return rng.대상.choice(유효후보) if 유효후보 else None


@dataclass
class _스킬타격문맥:
    """공격스킬_실행 한 번 동안 타격 반복 처리기들이 같이 쓰는 값."""

    전투상태: dict
    시전자: dict
    스킬데이터: dict
    옵션: 공격옵션
    공격횟수: int
    대상기록: list | None = None


def _번호째_옵션(옵션, 번호):
    """효과 원소에 "적용타격"(1부터 센 타격 번호 목록)이 있으면 그 타격에만 건다(달빛베기 2타의 공중에뜸)."""
    if not any("적용타격" in 효과 for 효과 in 옵션.효과리스트):
        return 옵션
    return replace(
        옵션,
        효과리스트=[
            효과
            for 효과 in 옵션.효과리스트
            if 번호 + 1 in 효과.get("적용타격", [번호 + 1])
        ],
    )


def _타격(문맥, 대상, 번호, 미리계산된판정=None):
    """번호째 타격 1회 - 데미지식/명중률은 스킬 데이터의 리스트 값이면 번호째를 쓴다."""
    스킬데이터 = 문맥.스킬데이터
    return 공격_1회(
        문맥.전투상태,
        문맥.시전자,
        대상,
        값_또는_리스트(스킬데이터["데미지"], 번호),
        값_또는_리스트(스킬데이터["명중률"], 번호),
        _번호째_옵션(문맥.옵션, 번호),
        미리계산된판정=미리계산된판정,
    )


def _반복_타격들(문맥, 타겟종류, 중심대상, 지정대상목록, 대상당제한):
    """ "적랜덤반복"/"적반복지정" - 타격마다 대상을 새로 고른다."""
    타격들 = []
    후보풀 = 타겟_확장(문맥.전투상태, 문맥.시전자, 타겟종류, 중심대상)
    선택횟수 = {}
    for i in range(문맥.공격횟수):
        대상 = _반복_대상_고르기(
            후보풀, 타겟종류, 지정대상목록, i, 대상당제한, 선택횟수
        )
        if 대상 is None:
            타격들.append({"비고": "대상 없음"})
            continue
        선택횟수[id(대상)] = 선택횟수.get(id(대상), 0) + 1
        결과 = _타격(문맥, 대상, i)
        타격들 += [결과, *결과.pop("추가타격들", [])]
        if 문맥.대상기록 is not None:
            문맥.대상기록.append(대상)
    return 타격들


def _대상별_타격들(문맥, 타겟종류, 중심대상, 각개별굴림):
    """대상 목록을 정해 놓고 대상마다 공격횟수만큼 친다("크기별공격횟수"가 있으면 대상의 크기로 정한다).
    첫 타격의 명중 판정을 나머지 타격이 공유한다(각공격명중굴림이면 타격마다 새로 굴린다)."""
    타격들 = []
    크기별 = 문맥.스킬데이터.get("크기별공격횟수")
    for 대상 in 타겟_확장(문맥.전투상태, 문맥.시전자, 타겟종류, 중심대상):
        공유판정 = None
        공격횟수 = 문맥.공격횟수
        if 크기별:  # 진공참(#325) - 몬스터 "크기"(없으면 중형)마다 타격 수
            공격횟수 = 크기별.get(대상["원본"].get("크기") or "중형", 공격횟수)
        for i in range(공격횟수):
            미리계산된판정 = None if (i == 0 or 각개별굴림) else 공유판정
            결과 = _타격(문맥, 대상, i, 미리계산된판정)
            if i == 0:
                공유판정 = 결과.get("판정")  # 하단공격의 공중회피는 판정이 없다
            타격들 += [결과, *결과.pop("추가타격들", [])]
            if 문맥.대상기록 is not None:
                문맥.대상기록.append(대상)
    return 타격들


def 공격스킬_실행(
    전투상태,
    시전자,
    스킬데이터,
    중심대상=None,
    지정대상목록=None,
    타겟종류오버라이드=None,
    대상기록=None,
):
    """대상기록: 리스트를 넘기면 실제로 친 참가자를 타격 순서대로 담는다
    (분할공격 2단계가 1단계 대상을 이름 대신 객체로 이어받는 데 쓴다 - B8)."""
    타겟종류 = 타겟종류오버라이드 or 스킬데이터["타겟"]
    각개별굴림 = 스킬데이터.get("각공격명중굴림", False)
    공격횟수 = 정수_평가(스킬데이터.get("공격횟수", 1), 전투상태, 시전자)
    대상당제한 = 스킬데이터.get("대상당피격제한")
    if 대상당제한 is not None:
        대상당제한 = 정수_평가(대상당제한, 전투상태, 시전자)
    문맥 = _스킬타격문맥(
        전투상태,
        시전자,
        스킬데이터,
        _공격옵션_만들기(전투상태, 시전자, 스킬데이터),
        공격횟수,
        대상기록,
    )

    if 타겟종류 in ("적랜덤반복", "적반복지정"):
        타격들 = _반복_타격들(문맥, 타겟종류, 중심대상, 지정대상목록, 대상당제한)
    else:
        타격들 = _대상별_타격들(문맥, 타겟종류, 중심대상, 각개별굴림)

    총피해 = sum(t.get("피해", 0) for t in 타격들)
    결과 = {
        "공격자": 시전자["이름"],
        "스킬": 스킬데이터.get("_이름"),
        "타격": 타격들,
        "총피해": 총피해,
    }
    core.로그(전투상태, 결과, 종류="타격")
    return 결과


def 분할공격_실행(전투상태, 시전자, 스킬데이터, 중심대상=None):
    # 단계의 "타입"은 그 단계 전용 태그 - 스킬 전체 태그와 합쳐 경직(잡기 등)을 본다
    상위타입 = list(스킬데이터.get("타입") or [])
    단계1 = dict(스킬데이터["공격단계1"])
    단계1["타입"] = 상위타입 + list(단계1.get("타입") or [])
    단계1["_이름"] = f"{스킬데이터.get('_이름')} (1단계)"
    단계1["최종피해배율"] = 스킬데이터.get("최종피해배율", 1)
    단계1대상 = []
    결과1 = 공격스킬_실행(전투상태, 시전자, 단계1, 중심대상, 대상기록=단계1대상)

    단계2 = dict(스킬데이터["공격단계2"])
    단계2["타입"] = 상위타입 + list(단계2.get("타입") or [])
    단계2["_이름"] = f"{스킬데이터.get('_이름')} (2단계)"
    단계2["최종피해배율"] = 스킬데이터.get("최종피해배율", 1)
    단계2중심 = 중심대상
    if 단계2.get("기준대상") == "공격단계1" and 단계1대상:
        단계2중심 = 단계1대상[0]
    if 단계2.get("앞단계명중필요") and not any(
        (t.get("판정") or {}).get("성공") for t in 결과1["타격"]
    ):
        # 블러드 러스트 - 1단계가 하나도 맞지 않으면 2단계는 나가지 않는다
        결과2 = {
            "공격자": 시전자["이름"],
            "스킬": 단계2["_이름"],
            "타격": [],
            "총피해": 0,
        }
        core.로그(전투상태, dict(결과2, 비고="1단계가 빗나가 2단계 없음"), 종류="타격")
    elif 단계2.get("타겟") in ("아군단일", "적단일") and not 단계2중심["생존"]:
        # 1단계에서 기준 대상이 쓰러졌다 - 단일 대상 2단계는 칠 대상이 없다(B12).
        결과2 = {
            "공격자": 시전자["이름"],
            "스킬": 단계2["_이름"],
            "타격": [],
            "총피해": 0,
        }
        core.로그(
            전투상태, dict(결과2, 비고="기준 대상이 쓰러져 2단계 없음"), 종류="타격"
        )
    else:
        결과2 = 공격스킬_실행(전투상태, 시전자, 단계2, 단계2중심)

    return {
        "공격자": 시전자["이름"],
        "스킬": 스킬데이터.get("_이름"),
        "1단계": 결과1,
        "2단계": 결과2,
        "총피해": 결과1["총피해"] + 결과2["총피해"],
    }


def 귀신_지속턴_보너스(전투상태, 시전자, 스킬데이터):
    """사슬 해제(소울브링어) - 귀신 타입 스킬의 지속턴에 더하는 값(특성 "귀신지속턴"). 귀신이 아니면 0."""
    if "귀신" not in 스킬데이터.get("타입", []):
        return 0
    return sum(
        원소.get("변동값", 0)
        for 원소 in traits.캐릭터특성_무기효과(전투상태, 시전자, "귀신지속턴")
    )


def 지속공격_등록(전투상태, 시전자, 스킬데이터, 중심대상=None):
    """즉시 데미지 없이 지속 데미지만 주는 순수 지속형 공격("지속공격"
    태그)을 대상에게 등록한다. 실제 매 턴 발동은 _지속공격_발동()이
    맡는다 - 여기서는 상태이상 자료구조에 등록만 한다.

    "출처스킬"에는 스킬데이터 전체가 아니라 그 안의 "지속공격" 상세
    (job_skill_format.py <지속공격 양식>의 데미지/명중률/공격횟수 등이
    실제로 들어있는 자리)를 저장해야 한다 - _지속공격_발동()이
    출처스킬.get("데미지")처럼 그 안의 값을 바로 읽기 때문이다."""
    상세 = 스킬데이터["지속공격"]
    대상목록 = 타겟_확장(전투상태, 시전자, 상세["타겟"], 중심대상)
    보너스 = 귀신_지속턴_보너스(전투상태, 시전자, 스킬데이터)
    for 대상 in 대상목록:
        대상.setdefault("상태이상", []).append(
            {
                "이름": 스킬데이터.get("_이름"),
                "지속턴": 정수_평가(상세.get("지속턴", 1), 전투상태, 대상) + 보너스,
                "종류": "지속공격",
                "출처스킬": 상세,
                "시전자이름": 시전자["이름"],
                "시전자id": 시전자.get("id"),
                "매턴명중굴림": 상세.get("매턴명중굴림", False),
                # 스킬 "타입" - 매 턴 타격의 태그(메모라이즈 "스킬타입조건" 데미지보너스)
                "출처타입": list(스킬데이터.get("타입") or []),
                # "라운드종료"(장판스킬 - 사야 #350)면 attacks.라운드종료_지속공격이 친다
                **({"발동시점": 상세["발동시점"]} if "발동시점" in 상세 else {}),
                # 스킬강화한 스킬일 때만(키가 없으면 1)
                **(
                    {"최종피해배율": 스킬데이터["최종피해배율"]}
                    if "최종피해배율" in 스킬데이터
                    else {}
                ),
            }
        )
    결과 = {
        "공격자": 시전자["이름"],
        "스킬": 스킬데이터.get("_이름"),
        "대상": [p["이름"] for p in 대상목록],
        "비고": "지속공격 등록됨 (실제 발동은 시전자 턴 종료 시 - 아래 다음_턴 참고)",
    }
    core.로그(전투상태, 결과, 종류="지속공격등록")
    return 결과
