def _공격옵션_만들기(전투상태, 시전자, 스킬데이터):
    """스킬 데이터에서 타격마다 같은 값(공격옵션)을 만든다. "일반공격취급"/"장전소모" 스킬이면
    장전 버프(은탄 등)를 1개 소모해 속성변환/추가피해를 반영한다(명중 여부와 무관)."""
    데미지보너스 = 스킬데이터.get("데미지보너스", 0)
    속성변환 = None
    추가피해목록 = None
    if 스킬데이터.get("일반공격취급") or 스킬데이터.get("장전소모"):
        _, 장전속성변환, 장전추가피해, 장전추가피해속성 = attacks.장전소모_처리(
            전투상태, 시전자
        )
        속성변환 = 장전속성변환
        if 장전추가피해속성 and 장전추가피해:
            # 은탄: 추가피해는 공격 속성과 따로 명속성으로 계산.
            추가피해목록 = [(장전추가피해, 장전추가피해속성)]
