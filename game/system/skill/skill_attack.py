def 스킬_명중_판정(
    전투상태,
    시전자,
    대상,
    명중률종류,
    명중보너스=0,
    강제치명타=False,
    치명타체크=False,
    장비보너스=True,
    명중이점=False,
):
    if 명중률종류 == "자동" and 치명타체크:
        눈 = dice_utils.d20_굴림()
        치명타범위 = damage.유효_치명타범위(전투상태, 시전자)
        return {
            "성공": True,
            "자연눈": 눈,
            "치명타": 눈 >= 치명타범위,
            "자동실패": False,
        }

    판정 = damage.명중_판정(
        전투상태,
        시전자,
        대상,
        명중률종류,
        명중보너스,
        장비보너스=장비보너스,
        명중이점=명중이점,
    )
    if 강제치명타 and 판정["성공"]:
        판정 = dict(판정)
        판정["치명타"] = True
    return 판정


