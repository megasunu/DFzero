    상황 = f"{원소['스킬']}에 이어 {대상['이름']}에게 {원소['이름']}을(를) 쓸까요?"
    비용 = f"{원소.get('행동') or '행동 없음'} · MP {원소.get('MP소모', 0)}"  # 팝업 버튼 한 줄
    return 콜백(시전자, [(원소["이름"], 비용)], 상황) == 0


