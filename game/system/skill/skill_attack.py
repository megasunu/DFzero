# 공격스킬을 쓰고 나면 같은 대상에게 이어 친다. 스킬_실행이 공격스킬 뒤에 부른다.
# - 연계스킬(타입 "연계스킬" - 수플렉스 썬더, 귀참드라이브. 2026-10-22 사용자 결정): 보유스킬 중 "연계"가 방금 쓴
#   스킬인 것. "연계조건" "명중"이면 그 대상이 맞았을 때만. 행동/MP를 낼 수 있으면 저절로 나가고, 전투상태
#   ["연계선택"](화면이 넣는 콜백 - 설정 "연계 자동"을 끄면)이 있으면 그걸로 쓸지 묻는다. "장판별"이 있으면
#   귀참드라이브처럼 깔린 장판에 따라 효과가 붙는다.
