@dataclass(frozen=True)
class 공격옵션:
    """공격_1회에 넘기는 값 중 한 스킬을 쓰는 동안 타격마다 같은 것들(스킬 데이터에서 만든다).
    타격마다 달라지는 데미지식/명중률종류/미리 계산된 판정은 공격_1회의 인자로 따로 넘긴다.

    속성추가피해: 스킬 "속성추가피해"([{"데미지": 식, "속성": 속성}]) - 본 피해와
    따로 그 속성으로 계산해 더한다(귀참의 귀신 d8 = 암속성). 본 피해식에 무기 주사위가
    있으면 치명타 주사위는 본 피해(무기 주사위)에만 붙는다.
    최종피해배율: 스킬강화(레벨 12) - 방어/속성 배율 뒤 최종피해에 곱한다. 이 타격이
    거는 "지속피해" 효과에도 저장돼 매 턴 피해에 곱한다.
    공격타입: 스킬 "공격타입" - 무기 주사위를 쓰지 않는 피해의 연출 모양(stats.타격_공격타입).
    장비보너스: False면 장비의 명중률보너스/데미지보너스를 더하지 않는다(스킬 데이터
    "장비보너스제외" - 투척 아이템, 사용자 지정 2026-10-13).
    타격추가피해: False면 버프 "타격추가피해"(잔영의 케이가)를 굴리지 않는다(스킬 데이터
    "타격추가피해제외" - 귀참, 2026-10-20 사용자 결정)."""

    데미지보너스: int = 0
    명중보너스: int = 0
    강제치명타: bool = False
    치명타체크: bool = False
    효과리스트: list = field(default_factory=list)
    조건부효과리스트: list = field(default_factory=list)
    속성: str | None = None
    공격타입: str | None = None
    추가피해목록: list | None = None
    속성변환: str | None = None
    속성추가피해: list | None = None
    일반공격취급: bool = False
    최종피해배율: float = 1
    장비보너스: bool = True
    타격추가피해: bool = True


def _무기식(데미지식):
    """무기 주사위(무기공격력/보정공격력)를 쓰는 피해식인가."""
    return "보정공격력" in str(데미지식) or "무기공격력" in str(데미지식)


def _타격_속성(전투상태, 시전자, 대상, 데미지식, 옵션):
    """이 타격의 피해 속성. 무기 주사위를 쓰면 무기 속성, 아니면 스킬 속성(stats.공격_속성).
    무기 주사위가 없는 피해에는 특성 "스킬속성추가"(어둠의 친화 - 암속성)를 더해 가장 아픈 속성 하나를 고른다."""
    속성 = stats.공격_속성(시전자, 데미지식, 옵션.속성, 옵션.속성변환)
    if _무기식(데미지식):
        return 속성
    추가 = [
        원소["변동값"]
        for 원소 in traits.캐릭터특성_무기효과(전투상태, 시전자, "스킬속성추가")
    ]
    if not 추가:
        return 속성
    return damage.주속성(전투상태, 시전자, 대상, [속성, *추가])


def _타격_피해_계산(전투상태, 시전자, 대상, 데미지식, 명중률종류, 옵션, 치명타, 속성):
    """명중한 타격의 (본 피해, 추가피해목록, 데미지식 굴림값). 주사위를 굴리는 순서는 그대로다(본 피해 ->
    일반공격 추가피해 -> 속성추가피해). 조건부효과의 데미지보너스는 부르는 쪽(공격_1회)이 더한다."""
    무기필요 = _무기식(데미지식)
    컨텍스트 = stats.기본_컨텍스트(전투상태, 시전자, 무기공격력필요=무기필요)
    # combat.formula.수식_평가에 치명타 여부를 그대로 넘긴다 - 이전에는
    # 여기서 데미지식을 통째로 한 번 더 평가해 더하는 방식(보정치/차수까지
    # 2배가 되는 버그)을 썼는데, 이제 combat.attacks.일반공격_실행/
    # _몬스터_패턴_실행과 같은 방식(다이스만, 그것도 1개 추가)으로 통일했다.
    피해 = stats.피해_굴림(전투상태, 시전자, 데미지식, 컨텍스트, 치명타=치명타)
    굴림 = 피해
    if 옵션.일반공격취급:
        # 일반공격취급 스킬에만 붙는 특성 피해(무기의 극의 - 광검 1d6)
        피해 += stats.일반공격_추가피해(전투상태, 시전자, 컨텍스트)
    피해 += 옵션.데미지보너스
    피해 += stats.버프디버프_수치(전투상태, 시전자, "데미지보너스")
    # 캐릭터 특성(무기의 극의/패황색 등)과 몬스터 특성 -
    # 주문 전용/약점속성 조건은 명중률종류/대상/속성으로 판정한다.
    피해 += traits.특성_수치(
        전투상태, 시전자, "데미지보너스", 명중률종류=명중률종류, 대상=대상, 속성=속성
    )
    # 장비(전 부위+활성 세트) 데미지보너스 - 주문 포함 모든 공격 스킬(투척 아이템은 빼고).
    if 옵션.장비보너스:
        피해 += stats.장비_데미지보너스(시전자, 대상)
        피해 += stats.마봉_추가피해(전투상태, 시전자, 대상)
    추가피해목록 = 옵션.추가피해목록
    if 옵션.속성추가피해:
        추가치명 = (
            stats.치명타_주사위수(전투상태, 시전자) if 치명타 and not 무기필요 else 0
        )
        추가피해목록 = list(추가피해목록 or []) + [
            (
                formula.수식_평가(항목["데미지"], 컨텍스트, 치명타=추가치명),
                항목.get("속성") or "무속성",
            )
            for 항목 in 옵션.속성추가피해
        ]
    return 피해, 추가피해목록, 굴림


def _조건부_해제_적용(전투상태, 대상, 조건부오버라이드, 효과로그):
    """조건부효과가 지정한 디버프/버프/상태이상 해제를 대상에게 적용한다(상태이상은 로그를 남긴다)."""
    for 디버프이름 in 조건부오버라이드["디버프해제"]:
        이름있는효과_해제(대상, "디버프", 디버프이름)
    for 버프이름 in 조건부오버라이드["버프해제"]:
        이름있는효과_해제(대상, "버프", 버프이름)
    for 상태이상이름 in 조건부오버라이드["상태이상해제"]:
        if 상태이상_해제(전투상태, 대상, 상태이상이름):
            효과로그.append(f"{대상['이름']}의 '{상태이상이름}' 상태이상 해제")


def 공격_1회(
    전투상태,
    시전자,
    대상,
    데미지식,
    명중률종류,
    옵션=공격옵션(),
    미리계산된판정=None,
):
    """공격 1회(일반 공격스킬/분할공격 단계/지속공격에 공용). 데미지식/명중률종류는 타격마다
    다를 수 있어 따로 받고(분할/다단 스킬의 리스트 값), 나머지 스킬 공통 값은 공격옵션이다.
    미리계산된판정이 있으면 명중 굴림을 다시 하지 않는다(여러 번 치는 스킬의 공유 판정).

    무기 주사위 피해나 일반공격취급 스킬이면 이어서 버프 "타격추가피해"(잔영의 케이가)를 굴린다 - 맞든
    빗나가든. 그 타격들은 결과["추가타격들"]에 담고, 스킬 타격 목록이 본 타격 뒤에 펼친다."""
    결과 = _공격_1회_본문(
        전투상태, 시전자, 대상, 데미지식, 명중률종류, 옵션, 미리계산된판정
    )
    if 옵션.타격추가피해 and (_무기식(데미지식) or 옵션.일반공격취급):
        추가타격들 = attacks.타격추가피해_발동(전투상태, 시전자, 대상)
        if 추가타격들:
            결과["추가타격들"] = 추가타격들
    return 결과


def _공격_1회_본문(전투상태, 시전자, 대상, 데미지식, 명중률종류, 옵션, 미리계산된판정):
    속성 = _타격_속성(전투상태, 시전자, 대상, 데미지식, 옵션)
    조건부오버라이드 = 조건부효과_평가(전투상태, 시전자, 대상, 옵션.조건부효과리스트)
    for 이름 in 조건부오버라이드["자원소모추가"]:
        resources.자원_소모(전투상태, 시전자, 이름, 1)
    공격전상태 = reactions.상태이상_이름목록(전투상태, 대상)

    판정 = 미리계산된판정 or 스킬_명중_판정(
        전투상태,
        시전자,
        대상,
        명중률종류,
        옵션.명중보너스 + 조건부오버라이드["명중보너스"],
        옵션.강제치명타,
        옵션.치명타체크,
        장비보너스=옵션.장비보너스,
    )

    결과 = {
        "공격자": 시전자["이름"],
        "대상": 대상["이름"],
        "판정": 판정,
        "피해": 0,
        "효과로그": [],
    }
    damage.공격연출_기록(
        전투상태,
        대상,
        판정,
        속성,
        stats.타격_공격타입(시전자, 데미지식, 옵션.공격타입),
    )
    if not 판정["성공"]:
        damage.집요함_발동(전투상태, 시전자, 대상, 속성, 판정)
        reactions.공격후_반응(전투상태, 시전자, 대상, 공격전상태)
        return 결과

    피해, 추가피해목록, 굴림 = _타격_피해_계산(
        전투상태, 시전자, 대상, 데미지식, 명중률종류, 옵션, 판정["치명타"], 속성
    )
    피해 += 조건부오버라이드["데미지보너스"]
    결과["피해"] = damage.피해_적용(
        전투상태,
        대상,
        피해,
        속성=속성,
        추가피해목록=추가피해목록,
        공격측=시전자,
        최종피해배율=옵션.최종피해배율
        * (stats.마봉_최종피해배율(시전자) if 옵션.장비보너스 else 1),
    )
    내역 = damage.피해내역(
        전투상태, 시전자, 데미지식, 굴림, 피해, 결과["피해"], 옵션.장비보너스
    )
    if 내역:
        결과["피해내역"] = 내역
    damage.피격_처리(전투상태, 시전자, 대상, 판정, 속성=속성)
    damage.무기_명중시효과(전투상태, 시전자, 대상, 판정, 데미지식)
    if 옵션.장비보너스:  # 장비 데미지보너스가 붙는 공격만(투척 아이템 제외)
        damage.마봉_명중시효과(전투상태, 시전자, 대상, 판정)
    결과["효과로그"] = 효과_적용(
        전투상태,
        시전자,
        대상,
        옵션.효과리스트,
        주대상피해=결과["피해"],
        속성=속성,
        데미지식=데미지식,
        데미지보너스=옵션.데미지보너스,
        최종피해배율=옵션.최종피해배율,
    )
