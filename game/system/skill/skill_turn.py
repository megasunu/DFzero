def _지속공격_발동(전투상태, 시전자):
    """job_skill_format.py <지속공격 양식>(예: 보이드, 나이트 할로우)이
    걸어둔 지속공격을 실제로 발동시킨다. 전투상태의 모든 참가자를 돌며,
    "종류":"지속공격"이고 "시전자id"가 이 시전자인 항목을 찾아
    공격_1회를 그대로 재사용해 타격한다(효과/조건부효과/치명타 등이
    일반 공격스킬과 동일하게 반영된다).

    "매턴명중굴림"이 False면 항목에 저장해둔 첫 판정 결과를 계속
    재사용하고(재판정 없음), True면 매번 새로 판정한다. 어느 쪽이든
    판정에 실패하면 그 시점에 항목을 제거해 효과를 끝낸다 - "빗나감유지"면
    그 타격만 빗나가고 남는다."""
    for 참가자 in 전투상태["참가자"]:
        for 항목 in list(참가자.get("상태이상", [])):
            if 항목.get("종류") != "지속공격" or 항목.get("시전자id") != 시전자.get(
                "id"
            ):
                continue
            if 항목.get("발동시점") == "라운드종료":
                continue  # 장판스킬(사야) - 라운드 끝에 attacks.라운드종료_지속공격이 친다

            출처스킬 = 항목.get("출처스킬", {})
            매턴명중굴림 = 출처스킬.get("매턴명중굴림", False)
            공격횟수 = 정수_평가(출처스킬.get("공격횟수", 1), 전투상태, 시전자)
            항목["발동회차"] = (
                항목.get("발동회차", 0) + 1
            )  # 받기(reactions.지속공격_받기)가 본다
            옵션 = 공격옵션(
                데미지보너스=출처스킬.get("데미지보너스", 0),
                명중보너스=출처스킬.get("명중보너스", 0),
                강제치명타=출처스킬.get("강제치명타", False),
                치명타체크=출처스킬.get("치명타체크", False),
                효과리스트=출처스킬.get("효과", []),
                조건부효과리스트=출처스킬.get("조건부효과", []),
                속성=출처스킬.get("속성"),
                공격타입=출처스킬.get("공격타입"),
                속성추가피해=출처스킬.get("속성추가피해"),
                최종피해배율=항목.get("최종피해배율", 1),
                태그=tuple(항목.get("출처타입") or ()),
            )

            총피해 = 0
            중단됨 = False
            공유판정 = 항목.get("명중판정")
            for i in range(공격횟수):
                재판정필요 = 매턴명중굴림 or 공유판정 is None
                미리계산된판정 = None if 재판정필요 else 공유판정
                결과 = 공격_1회(
                    전투상태,
                    시전자,
                    참가자,
                    값_또는_리스트(출처스킬.get("데미지", "0"), i),
                    값_또는_리스트(출처스킬.get("명중률", "자동"), i),
                    옵션,
                    미리계산된판정=미리계산된판정,
                )
                if i == 0:
                    공유판정 = 결과["판정"]
                    항목["명중판정"] = 공유판정
                총피해 += 결과.get("피해", 0)
                # "빗나감유지"(더블 건호크) - 빗나가도 그 회차만 빗나가고 끝나지 않는다
                if not 결과["판정"]["성공"] and not 출처스킬.get("빗나감유지"):
                    중단됨 = True
                    break

            core.로그(
                전투상태,
                {
                    "공격자": 시전자["이름"],
                    "대상": 참가자["이름"],
                    "스킬": 항목.get("이름"),
                    "총피해": 총피해,
                    "비고": "지속공격 자동 발동"
                    + (" (판정 실패로 해제)" if 중단됨 else ""),
                },
                종류="지속공격발동",
            )
            if 중단됨 and 항목 in 참가자.get("상태이상", []):
                참가자["상태이상"].remove(항목)


def _소환수_행동횟수(시전자, 소환수이름):
    """그 소환수를 건 버프의 정의 "효과"에 "중첩당공격":True가 있으면(고블린소환) 버프 중첩 수,
    없으면 1(효도르/정령 - 이름당 한 마리). 몬스터 쪽 monster_actions._몬스터_소환수_목록과 같은 규칙."""
    for 항목 in 시전자.get("버프", []):
        정의, _ = resources.효과정의_조회(항목.get("이름"))
        효과 = (정의 or {}).get("효과") or {}
        if (
            isinstance(효과, dict)
            and 효과.get("타입") == "소환수"
            and 효과.get("소환수이름") == 소환수이름
            and 효과.get("중첩당공격")
        ):
            return max(1, int(항목.get("중첩", 1)))
    return 1


def _소환수_행동_실행(전투상태, 시전자):
    """summon_00.py "소환수목록"의 "행동표"를, 시전자가 부린 소환수마다
    1d6을 굴려 나온 행동을 자동으로 실행한다. "능력치참조":"시전자"라
    소환수 자체의 참가자 인스턴스나 이니셔티브가 없다 - 공격스킬_실행을
    시전자 명의로 그대로 재사용해서, 시전자의 능력치/버프가 그대로
    쓰이게 한다(stats.기본_컨텍스트가 어차피 "시전자"를 기준으로 계산하므로
    별도 처리가 필요 없다). "타입"이 "공격"이 아닌 행동표 항목(현재
    데이터에는 없음)은 아직 지원하지 않아 건너뛴다."""
    for 소환수이름 in list(시전자.get("소환수", [])):
        정의 = summon_00.소환수목록.get(소환수이름)
        행동표 = (정의 or {}).get("행동표")
        if not 행동표:
            continue
        추가 = max(
            0,
            int(
                stats.버프디버프_수치(전투상태, 시전자, "소환수추가행동")
                + traits.특성_수치(전투상태, 시전자, "소환수추가행동")
            ),
        )  # 환수폭주
        for _ in range(_소환수_행동횟수(시전자, 소환수이름) + 추가):
            소환수_한번_행동(전투상태, 시전자, 소환수이름, 행동표)


def _캐스팅_풀기(시전자):
    시전자["상태이상"] = [
        s
        for s in 시전자.get("상태이상", [])
        if s.get("이름") not in ("캐스팅", "차징") and not s.get("차징연동")
    ]


def 캐스팅_발사(전투상태, 시전자):
    """밀린 차례 - 맡겨 둔 행동을 돌려주고 캐스팅/차징한 스킬을 쏜다. 무력화(행동불가)면 끊기고, 피격으로
    취소됐으면(hit_effects.캐스팅_피격_취소) 쏘지 않는다."""
    정보 = 시전자.pop("캐스팅", None)
    if 정보 is None:
        _캐스팅_풀기(시전자)
        return None
    시전자["행동자원"] = 정보["행동자원"]
    if 정보["기타행동"]:
        시전자["기타행동"] = 정보["기타행동"]
    이름 = 정보["스킬"]
    if 정보.get("취소"):
        _캐스팅_풀기(시전자)
        return None
    if status.상태이상_플래그(전투상태, 시전자, "행동불가"):
        _캐스팅_풀기(시전자)
        core.로그(
            전투상태,
            {
                "공격자": 시전자["이름"],
                "대상": 시전자["이름"],
                "비고": f"{이름} {정보.get('종류', '캐스팅')}이 끊겼다.",
            },
            종류="비고",
        )
        return None
    적들 = [p for p in 전투상태["참가자"] if p["진영"] == "적" and p["생존"]]
    if not 적들:
        _캐스팅_풀기(시전자)
        return None
    중심 = next((p for p in 적들 if p.get("id") == 정보["대상id"]), 적들[0])
    지정 = [p for i in 정보.get("지정대상id") or [] for p in 적들 if p.get("id") == i]
    스킬데이터 = dict((전투상태.get("스킬정의") or {})[이름], _이름=이름)
    강화 = 스킬강화(시전자, 스킬데이터)
    if 강화:
        스킬데이터["최종피해배율"] = 강화["최종피해배율"]
    결과 = 공격스킬_분기(전투상태, 시전자, 스킬데이터, 중심, 지정 or None)
    공격_시전자버프(전투상태, 시전자, 이름, 스킬데이터)  # 슬로스 바디의 죄업
    _캐스팅_풀기(시전자)
    return 결과


def _채널링공격_항목들(참가자):
    return [b for b in 참가자.get("버프") or [] if "채널링종료공격" in b]


def 채널링공격_턴종료(전투상태, 참가자):
    """자기 턴이 끝날 때 - 이번 턴에 쓰지 않았으면 풀리며 터지고, 썼으면 표시만 지운다."""
    for 항목 in _채널링공격_항목들(참가자):
        if not 항목.pop("채널링이번턴", False):
            채널링공격_종료(전투상태, 참가자, 항목, "쓰지 않고 턴 종료")


def 채널링공격_정리(전투상태):
    """쓰러졌거나 무력화된 시전자의 채널링 공격을 풀며 터뜨린다. 전투가 끝났으면 하지 않는다."""
    목록 = [(p, 항목) for p in 전투상태["참가자"] for 항목 in _채널링공격_항목들(p)]
    if not 목록 or core.종료판정_갱신(전투상태) is not None:
        return
    for 참가자, 항목 in 목록:
        까닭 = (
            "쓰러짐"
            if not 참가자.get("생존")
            else "무력화"
            if control.무력화_중인가(전투상태, 참가자)
            else None
        )
        if 까닭:
            채널링공격_종료(전투상태, 참가자, 항목, 까닭)


def _예약_키(항목):
    return (항목.get("우선도", 0), 항목.get("이니셔티브", 0))


def _연속홀딩_다음(전투상태, 후보):
    """지금 칠 정크 스핀 예약 - 후보(다음 차례)보다 (우선도, 이니셔티브)가 높은 것 중 가장 높은 것.
    후보가 None(라운드 끝)이면 남은 것 중 가장 높은 것."""
    목록 = [h for h in 예약목록(전투상태) if h["종류"] == "연속홀딩"]
    if 후보 is not None:
        기준 = (후보.get("우선도", 0), 후보["이니셔티브"])
        목록 = [h for h in 목록 if _예약_키(h) > 기준]
    return max(목록, key=_예약_키, default=None)


def _연속홀딩_발동(전투상태, 항목):
    목록 = 예약목록(전투상태)
    목록.remove(항목)
    시전자 = core.참가자_찾기(전투상태, 항목["시전자id"])
    대상 = core.참가자_찾기(전투상태, 항목["대상id"])
    if (
        시전자 is None
        or not 시전자["생존"]
        or control.무력화_중인가(전투상태, 시전자)
        or 대상 is None
        or not 대상["생존"]
    ):
        목록[:] = [h for h in 목록 if h.get("묶음") != 항목["묶음"]]
        return
    데이터 = dict(항목["스킬데이터"])
    이름 = 데이터["_이름"]
    core.로그(
        전투상태,
        {
            "공격자": 시전자["이름"],
            "대상": 대상["이름"],
            "비고": f"{이름} - {항목['타격']}번째 타격",
        },
        종류="비고",
    )
    control.홀딩_걸기(전투상태, 시전자, 대상, 이름, None, 우선도=1)
    for _ in range(항목["횟수"]):
        if not 대상["생존"]:
            break
        공격스킬_실행(전투상태, 시전자, 데이터, 대상)


def _지뢰_발동(전투상태, 항목, 대상):
    예약목록(전투상태).remove(항목)
    시전자 = core.참가자_찾기(전투상태, 항목["시전자id"])
    if 시전자 is None:
        return
    데이터 = dict(항목["스킬데이터"])
    데이터["타겟"] = 데이터.get("지뢰타겟", 데이터.get("타겟"))
    core.로그(
        전투상태,
        {
            "공격자": 시전자["이름"],
            "대상": 대상["이름"],
            "비고": f"{데이터['_이름']} - 지뢰가 터졌다.",
        },
        종류="비고",
    )
    공격스킬_실행(전투상태, 시전자, 데이터, 대상)


def _지뢰를_밟나(항목, 후보):
    return (
        후보 is not None
        and 후보["생존"]
        and not 후보.get("감옥")
        and not 후보.get("캐스팅차례")
        and not 후보.get("홀딩차례")
        and 후보["진영"] != 항목["진영"]
    )


def 예약타격_발동(전투상태, 후보):
    """combat.flow.다음_턴이 차례를 열기 전에 부른다 - 예약 하나를 쳤으면(지웠으면) True."""
    항목 = _연속홀딩_다음(전투상태, 후보)
    if 항목 is not None:
        _연속홀딩_발동(전투상태, 항목)
        return True
    # 그 차례를 맞은 적이 밟은 지뢰는 한꺼번에 터진다 - 앞 지뢰의 경직으로 차례가 밀려도 뒤 지뢰도 그 적에게
    지뢰들 = [
        h for h in 예약목록(전투상태) if h["종류"] == "지뢰" and _지뢰를_밟나(h, 후보)
    ]
    for 지뢰 in 지뢰들:
        if core.종료판정_갱신(전투상태) is not None:
            break
        if 후보["생존"]:
            _지뢰_발동(전투상태, 지뢰, 후보)
        else:
            예약목록(전투상태).remove(지뢰)
    return bool(지뢰들)


def 다음_턴(전투상태):
    """combat.flow.다음_턴()을 감싼다. 위 _지속공격_발동()/
    _소환수_행동_실행()이 "combat 패키지는 skill_system을 부르지 않는다"는
    순환 참조 방지 원칙 때문에 combat.flow.턴_종료_처리 안에 들어갈 수
    없어서, 이 파일에 별도로 감싸는 함수를 두었다. 지속공격 스킬이나
    소환스킬을 쓰는 프로젝트라면 앞으로 턴을 넘길 때 combat.flow.다음_턴
    대신 반드시 이 함수를 호출해야 한다."""
    현재참가자 = flow.현재_턴_참가자(전투상태)
    채널링공격_정리(전투상태)  # 이번 차례에 쓰러지거나 무력화된 시전자
    if not 현재참가자.get(
        "캐스팅시작"
    ):  # 캐스팅으로 끝난 턴은 턴 종료 효과를 밀린 차례 끝으로 미룬다
        _지속공격_발동(전투상태, 현재참가자)
        _소환수_행동_실행(전투상태, 현재참가자)
        턴종료_버프공격(전투상태, 현재참가자)
        채널링공격_턴종료(전투상태, 현재참가자)
    다음 = flow.다음_턴(전투상태, 라운드종료=라운드종료_처리, 예약발동=예약타격_발동)
    채널링공격_정리(전투상태)  # 차례 시작(지속피해·무력화)에 쓰러지거나 무력화된 시전자
    # 턴 시작 지속피해로 카운트다운 임시생명력이 다 닳았으면 여기서 터진다
    resources.설치소환수_즉시폭발_처리(전투상태)
    # 몬스터의 캐스팅(인형사의 골렘 소환)은 밀린 차례의 몬스터_턴_실행이 쏜다
    if 다음["진영"] != "적" and 다음.pop("캐스팅발사", False):
        캐스팅_발사(전투상태, 다음)
        core.종료판정_갱신(전투상태)
    elif 다음.get("다음턴추가공격"):  # 공력의 구 2단계 - 자기 턴 시작
        다음턴_추가공격(전투상태, 다음)
    return 다음


def _형태_공격(전투상태, 시전자, 이름, 공격):
    """상태변화(G-1/G-3)의 "공격"을 무작위 적 하나에게 "공격횟수"만큼 - 맞을 적이 쓰러지면 다른 적 무작위."""
    대상 = None
    쳤음 = False
    for _ in range(공격.get("공격횟수", 1)):
        if 대상 is None or not 대상["생존"]:
            대상 = 무작위_적(전투상태, 시전자)
        if 대상 is None:
            break
        스킬데이터 = {
            "분류": "공격스킬",
            "데미지보너스": 0,
            "명중보너스": 0,
            "각공격명중굴림": False,
            "일반공격취급": False,
            "효과": [],
            "조건부효과": [],
            **공격,
            "타겟": "적단일",
            "공격횟수": 1,
            "_이름": 이름,
        }
        공격스킬_실행(전투상태, 시전자, 스킬데이터, 대상)
        쳤음 = True
    return 쳤음


def _버프_원소들(시전자, 변동대상):
    for 항목 in list(시전자.get("버프") or []):
        정의 = resources.효과정의_조회(항목["이름"])[0] or {}
        효과 = 정의.get("효과")
        for 원소 in [효과] if isinstance(효과, dict) else 효과 or []:
            if isinstance(원소, dict) and common_names.같은_변동대상(
                원소.get("변동대상"), 변동대상
            ):
                yield 항목["이름"], 원소


def _상태변화_공격들(전투상태, 참가자, 키):
    """참가자에게 걸린 상태변화 정의 "효과"의 "턴종료공격"/"라운드종료공격"(G-1/G-3) - (이름, 공격)."""
    정의모음 = 전투상태.get("상태이상정의") or {}
    for 항목 in list(참가자.get("상태이상") or []):
        공격 = (정의모음.get(항목["이름"]) or {}).get("효과", {}).get(키)
        if 공격:
            yield 항목["이름"], 공격


def 턴종료_버프공격(전투상태, 시전자):
    """시전자의 턴이 끝날 때 - 상태변화 "턴종료공격"(G-1)과 버프 "턴종료설치"(메카드롭). 스킬 공격이라 아군만."""
    if not 시전자["생존"] or 시전자["진영"] != "아군":
        return
    for 이름, 공격 in list(_상태변화_공격들(전투상태, 시전자, "턴종료공격")):
        _형태_공격(전투상태, 시전자, 이름, 공격)
    for 이름, 원소 in list(_버프_원소들(시전자, "턴종료설치")):
        for _ in range(원소.get("개수", 1)):
            대상 = 무작위_적(전투상태, 시전자)
            if 대상 is None:
                break
            설치소환수_붙이기(전투상태, 시전자, 원소["소환수"], 대상, 이름)


def _라운드종료_저격(전투상태):
    """닐 스나이핑(#801) - 등록된 저격마다 가장 강한 적 하나를 시전자 명의로 쏘고 남은 횟수를 줄인다(0이면 뺀다).
    시전자가 쓰러져도 계속 쏜다. 한 번이라도 쐈으면 True."""
    쳤음 = False
    for 항목 in list(저격_목록(전투상태)):
        if core.종료판정_갱신(전투상태) is not None:
            break
        시전자 = core.참가자_찾기(전투상태, 항목["시전자id"])
        대상 = 저격_대상(전투상태, 시전자) if 시전자 is not None else None
        if 대상 is not None:
            데이터 = dict(항목["스킬데이터"], 타겟="적단일", 공격횟수=1)
            공격스킬_실행(전투상태, 시전자, 데이터, 대상)
            쳤음 = True
        항목["남은"] -= 1
        if 항목["남은"] <= 0:
            전투상태["라운드종료저격"] = [
                h for h in 저격_목록(전투상태) if h is not 항목
            ]
    return 쳤음


def 라운드종료_처리(전투상태):
    """라운드가 끝날 때(combat.flow.다음_턴이 부른다) - 폭발라운드가 된 설치소환수를 붙인 순서대로 자폭시키고,
    살아 있는 참가자의 상태변화 "라운드종료공격"(G-3)을 친다. 한 번이라도 쳤으면 True."""
    라운드 = 전투상태.get("라운드", 1)
    목록 = 설치소환수_목록(전투상태)
    터질것 = [항목 for 항목 in 목록 if 항목["폭발라운드"] <= 라운드]
    전투상태["설치소환수"] = [
        항목 for 항목 in 목록 if not any(항목 is t for t in 터질것)
    ]
    쳤음 = False
    for 항목 in 터질것:
        쳤음 = bool(설치소환수_폭발(전투상태, 항목)) or 쳤음
    쳤음 = _라운드종료_저격(전투상태) or 쳤음
    for 참가자 in list(전투상태["참가자"]):
        if not 참가자["생존"] or 참가자["진영"] != "아군":  # 스킬 공격이라 아군만
            continue
        for 이름, 공격 in list(_상태변화_공격들(전투상태, 참가자, "라운드종료공격")):
            쳤음 = _형태_공격(전투상태, 참가자, 이름, 공격) or 쳤음
    return 쳤음


def 다음턴_추가공격(전투상태, 시전자):
    """맡겨 둔 "다음턴추가공격"을 친다. 시전자가 행동불가면 끊기고, 대상이 쓰러졌으면 나가지 않는다."""
    목록 = 시전자.pop("다음턴추가공격", None)
    if not 목록 or not 시전자["생존"]:
        return []
    if status.상태이상_플래그(전투상태, 시전자, "행동불가"):
        return []
    결과들 = []
    for 항목 in 목록:
        대상 = next(
            (
                p
                for p in 전투상태["참가자"]
                if p.get("id") == 항목["대상id"] and p["생존"]
            ),
            None,
        )
        if 대상 is not None:
            원소 = dict(항목["원소"], _이름=항목["원소"]["이름"])
            결과들.append(공격스킬_실행(전투상태, 시전자, 원소, 대상))
    core.종료판정_갱신(전투상태)
    return 결과들
