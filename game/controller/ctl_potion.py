def _캐릭터_주류값(게임상태, 캐릭터):
    """전투 밖 ({"HP": 보정치, "MP": 보정치}, {"HP": 최대, "MP": 최대}) - 장비와 캐릭터에
    남은 상태이상(취기의 매력 감소) 반영."""
    스탯 = 캐릭터데이터.주문시전능력치(캐릭터)
    보정치 = {
        "HP": 캐릭터_능력치_보정치(게임상태, 캐릭터, "건강"),
        "MP": 캐릭터_능력치_보정치(게임상태, 캐릭터, 스탯),
    }
    최대 = {
        "HP": 캐릭터_최대HP(게임상태, 캐릭터),
        "MP": 캐릭터_최대MP(게임상태, 캐릭터),
    }
    return 보정치, 최대


