def 아군_소환아이템사용(게임상태, 이름):
    """현재 턴 아군이 소환 아이템 1개를 쓴다(보조행동 1개, 전투 중에만, 자기 자신). 소환 버프를
    스킬과 같은 길(skill_system.이름있는효과_부여)로 건다 - "중첩":True 소환 버프(고블린소환)는 쓸
    때마다 중첩이 늘어 턴 끝에 그 수만큼 행동한다. 전투 로그에 남긴다."""
    전투상태 = 게임상태.get("전투상태")
    if not 전투상태:
        raise ValueError("소환 아이템은 전투 중에만 쓸 수 있다.")
    참가자 = 현재_턴_참가자(게임상태)
    if 참가자["진영"] != "아군":
        raise ValueError("아군 차례가 아니다.")
    아이템 = _소환아이템(이름)
    보유수 = 게임상태["소지품"].get(drink_system.소지품_카테고리, {}).get(이름, 0)
    사유 = _버프포션_사유(참가자, 보유수)
    if 사유:
        raise ValueError(사유)
    skill_system.이름있는효과_부여(전투상태, 참가자, 아이템["버프이름"])
    potion_system.소지품_차감_카테고리(
        게임상태["소지품"], drink_system.소지품_카테고리, 이름
    )
    참가자["행동자원"]["보조행동"] -= 1
    정의, _ = resources.효과정의_조회(아이템["버프이름"])
    소환수이름 = ((정의 or {}).get("효과") or {}).get("소환수이름", "")
    마리 = next(
        (b.get("중첩", 1) for b in 참가자["버프"] if b["이름"] == 아이템["버프이름"]), 1
    )
    core.로그(
        전투상태,
        {
            "공격자": 참가자["이름"],
            "행동": f"{이름} 사용 - {소환수이름} 소환({마리}마리)",
            "아이템": 이름,
            "결과": f"{소환수이름} 소환({마리}마리)",
        },
        종류="아이템",
    )


