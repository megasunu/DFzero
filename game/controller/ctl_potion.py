def 주류_결과_문구(회복, 결과):
    """ "HP 5 회복, MP 3 회복 / 취기 2" 같은 한 줄."""
    조각 = [f"{종류} {양} 회복" for 종류, 양 in 회복.items()]
    return ", ".join(조각 or ["회복 없음"]) + f" / {결과}"


def 음주_표시(목록):
    """화면 표시용 "취기 2" / "만취" (음주 상태이상이 없으면 빈 글)."""
    조각 = []
    for 항목 in 목록 or []:
        if (상태이상목록.get(항목.get("이름")) or {}).get("분류") != "음주":
            continue
        중첩 = 항목.get("중첩")
        조각.append(f"{항목['이름']} {중첩}" if 중첩 else 항목["이름"])
    return ", ".join(조각)


