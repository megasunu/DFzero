def _버프포션(포션이름):
    포션 = 포션_데이터.get(포션이름)
    if not 포션 or 포션.get("분류") != "버프포션":
        raise ValueError(f"'{포션이름}'은(는) 버프포션이 아니다.")
    return 포션


def _버프포션_사유(참가자, 보유수):
    if 보유수 <= 0:
        return "소지하고 있지 않다."
    if 참가자["행동자원"].get("보조행동", 0) <= 0:
        return "보조행동이 남아있지 않다."
    return None


def 아군_버프포션_목록(게임상태):
    """전투 화면 [아이템]용 - 현재 턴 아군 기준 [(이름, 개수, 사유 또는 None)]. 데이터 순서대로."""
    참가자 = 현재_턴_참가자(게임상태)
    보유 = 게임상태["소지품"].get(potion_system.소지품_카테고리, {})
    return [
        (이름, 보유[이름], _버프포션_사유(참가자, 보유[이름]))
        for 이름, 포션 in 포션_데이터.items()
        if 포션.get("분류") == "버프포션" and 보유.get(이름, 0) > 0
    ]


def _행동보너스들(전투상태, 참가자):
    return {
        종류: stats.버프디버프_수치(전투상태, 참가자, "행동보너스", 행동종류=종류)
        for 종류 in ("일반행동", "보조행동", "반응행동")
    }


def 아군_버프포션사용(게임상태, 포션이름):
    """현재 턴 아군이 버프포션 1개를 자신에게 쓴다(보조행동 1개). 버프는 스킬 버프와 같은
    길(skill_system.이름있는효과_부여)로 건다 - 출처를 포션 이름으로 두어 같은 포션을 다시
    마시면 중첩되지 않고 지속턴만 갱신된다. 행동버프로 는 행동은 이번 턴에 바로 더한다
    (원래 행동보너스는 턴 시작에만 계산된다). 전투 로그에 남긴다."""
    전투상태 = 게임상태["전투상태"]
    참가자 = 현재_턴_참가자(게임상태)
    if 참가자["진영"] != "아군":
        raise ValueError("아군 차례가 아니다.")
    포션 = _버프포션(포션이름)
    보유수 = 게임상태["소지품"].get(potion_system.소지품_카테고리, {}).get(포션이름, 0)
    사유 = _버프포션_사유(참가자, 보유수)
    if 사유:
        raise ValueError(사유)
    중첩 = 포션.get("중첩", 1)
    이전 = _행동보너스들(전투상태, 참가자)
    skill_system.이름있는효과_부여(
        전투상태,
        참가자,
        포션["버프이름"],
        중첩량=중첩,
        지속턴오버라이드=포션["지속턴"],
        출처스킬=포션이름,
    )
    for 종류, 값 in _행동보너스들(전투상태, 참가자).items():
        if 값 > 이전[종류]:
            참가자["행동자원"][종류] = 참가자["행동자원"].get(종류, 0) + 값 - 이전[종류]
    potion_system.소지품_차감(게임상태["소지품"], 포션이름)
    참가자["행동자원"]["보조행동"] -= 1
    core.로그(
        전투상태,
        {
            "공격자": 참가자["이름"],
            "행동": f"{포션이름} 사용 - {포션['버프이름']}"
            + (f" {중첩}중첩" if 중첩 > 1 else "")
            + f" {포션['지속턴']}턴",
            "아이템": 포션이름,
            "결과": f"{포션['버프이름']}"
            + (f" {중첩}중첩" if 중첩 > 1 else "")
            + f" {포션['지속턴']}턴",
        },
        종류="아이템",
    )


