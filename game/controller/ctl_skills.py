# 지금 직업 계열의 스킬을 골드(50 x 차수)를 내고 배운다 - skill_learn_system.py.
# 전직한 뒤에는 같은 계열 다른 전직의 훔쳐배우기 스킬·특성도 5배 값으로 산다(#365).

from game.system import skill_learn_system
from game.controller.ctl_registry import 전직_레지스트리, 직업_레지스트리

__all__ = [
    "_차수별_스킬목록",
    "_상세값",
    "_스킬_상세글",
    "캐릭터_습득가능_스킬",
    "캐릭터_스킬_습득",
    "캐릭터_배운스킬_골드",
    "캐릭터_훔쳐배우기_후보",
    "_훔쳐배우기목록",
    "_훔쳐배우기_인자",
    "_특성_구매항목",
]


def _차수별_스킬목록(캐릭터):
    """[(1, 1차 계열 스킬목록), (2, 1차 전직 스킬목록)] - 전직 전이면 1차만."""
    결과 = [(1, 직업_레지스트리[캐릭터["직업"]]["스킬목록"])]
    전직정보 = 전직_레지스트리.get(캐릭터["직업"], {}).get(캐릭터.get("전직"))
    if 전직정보:
        결과.append((2, 전직정보["스킬목록"]))
    return 결과


def _특성_구매항목(정의):
    """훔쳐배우기 특성을 [스킬습득]이 파는 "특성스킬"처럼 - 배우면 그 특성을 얻는다. 특성에는 차수가 없어
    1차 전직(차수 2)의 값과 레벨로 판다."""
    return {
        "분류": "특성스킬",
        "타입": list(정의.get("타입") or []),
        "습득방법": "구매습득",
        "습득레벨": skill_learn_system.구매습득_레벨(2),
        "설명": 정의.get("설명", ""),
    }


def _훔쳐배우기목록(캐릭터):
    """[(차수, {이름: 스킬데이터}, 전직명)] - 전직한 캐릭터만. 같은 1차 계열의 다른(구현된) 1차 전직
    스킬목록, 그리고 계열 특성목록에서 "전직"이 다른 전직인 특성(_특성_구매항목). 태그는 system이 본다."""
    내전직 = 캐릭터.get("전직")
    if not 내전직:
        return []
    직업 = 캐릭터["직업"]
    결과 = [
        (2, 정보["스킬목록"], 전직명)
        for 전직명, 정보 in 전직_레지스트리.get(직업, {}).items()
        if 전직명 != 내전직 and 정보["구현"]
    ]
    특성별 = {}
    for 이름, 정의 in 직업_레지스트리[직업]["특성목록"].items():
        전직명 = 정의.get("전직")
        if 전직명 and 전직명 != 내전직:
            특성별.setdefault(전직명, {})[이름] = dict(
                _특성_구매항목(정의), 획득특성=이름
            )
    결과 += [(2, 목록, 전직명) for 전직명, 목록 in 특성별.items()]
    return 결과


def _훔쳐배우기_인자(캐릭터):
    return [(차수, 목록) for 차수, 목록, _ in _훔쳐배우기목록(캐릭터)]


def 캐릭터_훔쳐배우기_후보(캐릭터):
    """[스킬습득]에서 지금 5배 값으로 살 수 있는 다른 전직의 것
    [{"이름", "종류": "스킬"|"특성", "전직", "비용", "설명"}] - 이미 가진 것, 레벨이 모자란 것은 뺀다."""
    출처 = {}
    for _차수, 목록, 전직명 in _훔쳐배우기목록(캐릭터):
        for 이름 in 목록:
            출처.setdefault(이름, 전직명)
    return [
        {
            "이름": 이름,
            "종류": "특성" if 스킬.get("획득특성") == 이름 else "스킬",
            "전직": 출처[이름],
            "비용": 비용,
            "설명": 스킬.get("설명", ""),
        }
        for 이름, _차수, 비용, 스킬 in skill_learn_system.습득가능_스킬목록(
            캐릭터, [], _훔쳐배우기_인자(캐릭터)
        )
    ]


def _상세값(값):
    if isinstance(값, bool):
        return "예" if 값 else "아니오"
    if isinstance(값, dict):
        return "{" + ", ".join(f"{k}: {_상세값(v)}" for k, v in 값.items()) + "}"
    if isinstance(값, (list, tuple)):
        return ", ".join(_상세값(v) for v in 값) if 값 else "없음"
    return "없음" if 값 is None else str(값)


def _스킬_상세글(스킬):
    """[스킬습득] 상세보기 팝업 글 - 설명을 먼저, 그 밖의 스킬 데이터를 전부
    "키: 값" 줄로(데이터 순서)."""
    줄 = [f"{키}: {_상세값(값)}" for 키, 값 in 스킬.items() if 키 != "설명"]
    return "\n\n".join(글 for 글 in (스킬.get("설명", ""), "\n".join(줄)) if 글)


def 캐릭터_습득가능_스킬(캐릭터):
    """[(스킬이름, 비용, 상세글)] - [스킬습득] 팝업 목록. 훔쳐배우기는 맨 뒤, 상세글 첫 줄에 어느 전직의 것인지."""
    훔친것 = {h["이름"]: h for h in 캐릭터_훔쳐배우기_후보(캐릭터)}
    결과 = []
    for 이름, _차수, 비용, 스킬 in skill_learn_system.습득가능_스킬목록(
        캐릭터, _차수별_스킬목록(캐릭터), _훔쳐배우기_인자(캐릭터)
    ):
        글 = _스킬_상세글(스킬)
        if 이름 in 훔친것:
            h = 훔친것[이름]
            글 = f"훔쳐배우기 - {h['전직']} {h['종류']}(원래 값의 5배)\n\n{글}"
        결과.append((이름, 비용, 글))
    return 결과


def 캐릭터_스킬_습득(게임상태, 캐릭터, 스킬이름):
    """골드를 내고 스킬을 배운다. 낸 골드를 반환한다. 실패하면 ValueError."""
    return skill_learn_system.스킬_습득(
        캐릭터,
        게임상태["소지품"],
        스킬이름,
        _차수별_스킬목록(캐릭터),
        특성정의모음=직업_레지스트리[캐릭터["직업"]]["특성목록"],
        훔쳐배우기목록=_훔쳐배우기_인자(캐릭터),
    )


def 캐릭터_배운스킬_골드(캐릭터):
    """[스킬습득]으로 배운 스킬 값의 합 - 레테의 강물이 돌려준다(skill_learn_system.배운스킬_골드)."""
    return skill_learn_system.배운스킬_골드(
        캐릭터, _차수별_스킬목록(캐릭터), _훔쳐배우기_인자(캐릭터)
    )
