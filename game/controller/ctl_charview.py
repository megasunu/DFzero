def 캐릭터_퍽목록(캐릭터):
    """[(퍽이름, 설명)]"""
    전체 = 캐릭터_전체퍽(캐릭터)
    return [
        (이름, (전체.get(이름) or {}).get("설명", "")) for 이름 in 캐릭터_보유퍽(캐릭터)
    ]


def 캐릭터_특성목록(캐릭터):
    """[(특성이름, 설명)] - 보유특성 순서 그대로."""
    return [
        (이름, (전투용_캐릭터특성정의.get(이름) or {}).get("설명", "(설명 없음)"))
        for 이름 in 캐릭터["보유특성"]
    ]


def 캐릭터_스킬목록(게임상태, 캐릭터):
    """[(스킬이름, 요약, 설명)] - 요약은 "행동 · MP · 휴식당 횟수", 반응스킬은 앞에 "반응스킬"."""
    모음 = 게임상태.get("스킬데이터모음") or {}
    강화 = 캐릭터.get("스킬강화") or {}
    결과 = []
    for 이름 in 캐릭터["보유스킬"]:
        데이터 = 모음.get(이름) or {}
        조각 = ["반응스킬"] if 데이터.get("분류") == "반응스킬" else []
        강화됨 = 강화.get("스킬") == 이름
        if 강화됨:
            조각.append(f"강화(최종피해 x{강화['최종피해배율']})")
        행동 = 데이터.get("행동")
        if 행동:
            조각.append("/".join(행동) if isinstance(행동, list) else str(행동))
        if 데이터.get("MP소모"):
            MP = 데이터["MP소모"] * (강화["MP소모배율"] if 강화됨 else 1)
            조각.append(f"MP {MP}")
        if 데이터.get("휴식당횟수") is not None:
            남은 = (캐릭터.get("횟수제한스킬", {}).get("휴식제한스킬", {}) or {}).get(
                이름
            )
            조각.append(
                f"휴식당 {데이터['휴식당횟수']}회"
                + (f" (남은 {남은})" if 남은 is not None else "")
            )
        결과.append((이름, " · ".join(조각), 데이터.get("설명", "")))
    return 결과


def _상세용_참가자(게임상태, 캐릭터):
    """전투 밖에서 전투 공식(특성/장비/세트 반영)을 그대로 쓰기 위한 임시
    전투상태와 참가자. 캐릭터 사본을 써서 원본은 바꾸지 않는다. 라운드는
    0으로 둬서 첫턴 전용 보너스는 빠진다."""
    전투상태 = {
        "참가자": [],
        "현재턴": 0,
        "라운드": 0,
        "로그": [],
        "종료": None,
        "버프정의": 버프목록,
        "디버프정의": 디버프목록,
        "상태이상정의": 상태이상목록,
        "특성정의": 전투용_몬스터특성정의,
        "캐릭터특성정의": 전투용_캐릭터특성정의,
        "칭호정의": 칭호목록,
        "세트정의": 방어구세트목록,
    }
    참가자 = participants.아군_참가자_생성(
        copy.deepcopy(캐릭터), 캐릭터_장비데이터(게임상태, 캐릭터)
    )
    참가자["장비보너스"] = equipment_system.캐릭터_장비_보너스(
        캐릭터, 참가자["장비데이터"], 방어구세트목록
    )
    전투상태["참가자"].append(참가자)
    return 전투상태, 참가자


def _부호(값):
    return f"{값:+d}" if isinstance(값, int) else f"{값:+g}"


def 캐릭터_마스터리_선택지(캐릭터):
    """레벨 2 마스터리 선택 팝업용 - ([(무기 마스터리, 설명)], [(방어구 숙련, 설명)])."""
    항목 = 캐릭터_다음_레벨업_항목(캐릭터)
    무기, 방어구 = 캐릭터레벨업.마스터리_선택지(캐릭터, 항목)
    설명 = lambda 이름: 전투용_캐릭터특성정의[이름].get("설명", "")  # noqa: E731
    return [(n, 설명(n)) for n in 무기], [(n, 설명(n)) for n in 방어구]


def 전투스타일_목록():
    """레벨 2 스타일 선택 팝업용 - [(이름, 설명)]."""
    return [(이름, 정의["설명"]) for 이름, 정의 in 전투스타일.items()]


def 캐릭터_전투스타일(캐릭터):
    """지금 전투 스타일. 고르기 전(또는 예전 세이브의 값)이면 "노력"."""
    스타일 = 캐릭터.get("스타일")
    return 스타일 if 스타일 in 전투스타일 else "노력"


def 캐릭터_상세정보(게임상태, 캐릭터):
    """스탯 상세보기 창 내용 - [(제목, [줄, ...]), ...]."""
    전투상태, 참가자 = _상세용_참가자(게임상태, 캐릭터)
    장비 = 참가자["장비보너스"]
    유효 = 캐릭터_유효능력치(게임상태, 캐릭터)

    기본 = [
        f"이름: {캐릭터['캐릭터명']}",
        f"직업: {캐릭터['직업']}"
        + (f" → {캐릭터['전직']}" if 캐릭터.get("전직") else ""),
        f"레벨: {캐릭터['레벨']}   차수: {core.차수(참가자)}"
        + f"   스타일: {캐릭터_전투스타일(캐릭터)}"
        + (
            f"   직업스타일: {캐릭터_직업스타일(캐릭터)}"
            if 캐릭터_직업스타일(캐릭터)
            else ""
        ),
        f"HP: {캐릭터['현재HP']}/{캐릭터_최대HP(게임상태, 캐릭터)}   "
        f"MP: {캐릭터['현재MP']}/{캐릭터_최대MP(게임상태, 캐릭터)}",
    ]

    능력치줄 = []
    for 이름 in ("근력", "민첩", "건강", "지능", "지혜", "매력"):
        원래 = 캐릭터[이름]
        차이 = 유효[이름] - 원래
        보정 = 캐릭터데이터.보정치_계산(캐릭터, 이름, 유효[이름])
        능력치줄.append(
            f"{이름}: {유효[이름]}"
            + (f" (기본 {원래} {_부호(차이)})" if 차이 else "")
            + f"   보정치 {_부호(보정)}"
        )

    치명 = damage.유효_치명타범위(전투상태, 참가자)
    # 남아 있는 상태이상(취기/만취 - 취권이면 이득)의 명중/데미지도 전투처럼 더한다
    명중_평타 = (
        stats.평타_능력치_보정치(전투상태, 참가자)
        + stats.장비_수치(참가자, "명중률보너스")
        + stats.버프디버프_수치(전투상태, 참가자, "명중보너스")
        + traits.특성_수치(전투상태, 참가자, "명중보너스", 명중률종류="보정명중률")
    )
    데미지 = (
        stats.장비_수치(참가자, "데미지보너스")
        + stats.버프디버프_수치(전투상태, 참가자, "데미지보너스")
        + traits.특성_수치(전투상태, 참가자, "데미지보너스", 명중률종류="보정명중률")
    )
    속도 = (
        캐릭터.get("기본속도", 0)
        + 장비.get("속도보너스", 0)
        + traits.특성_수치(전투상태, 참가자, "속도")
    )
    전투 = [
        f"AC: {stats.최종AC(전투상태, 참가자)}",
        f"명중 보정(보정명중률): {_부호(명중_평타)}  (평타 능력치: {'/'.join(캐릭터.get('평타스탯') or [])})",
        f"데미지보너스: {_부호(데미지)}",
        f"속도: {_부호(속도)}",
        f"방어력: {stats.유효_방어력(전투상태, 참가자)}   보호률: {stats.유효_보호률(전투상태, 참가자)}",
        f"치명타범위: {치명}~20" if 치명 < 20 else "치명타범위: 20",
    ]
    주문스탯 = 캐릭터데이터.주문시전능력치(캐릭터)
    if 주문스탯:
        주문보정 = stats.주문시전_보정치(전투상태, 참가자)
        주문명중 = (
            주문보정
            + stats.장비_수치(참가자, "명중률보너스")
            + traits.특성_수치(
                전투상태, 참가자, "명중보너스", 명중률종류="주문시전명중률"
            )
        )
        주문데미지 = stats.장비_수치(참가자, "데미지보너스") + traits.특성_수치(
            전투상태, 참가자, "데미지보너스", 명중률종류="주문시전명중률"
        )
        전투 += [
            f"주문시전능력치: {주문스탯} (보정치 {_부호(주문보정)})",
            f"주문 명중 보정: {_부호(주문명중)}   주문 데미지보너스: {_부호(주문데미지)}",
        ]
    else:
        전투.append("주문시전능력치: 없음")

    행동 = []
    for 종류, 키 in (
        ("일반행동", "기본일반행동"),
        ("보조행동", "기본보조행동"),
        ("반응행동", "기본반응행동"),
    ):
        보너스 = traits.특성_수치(전투상태, 참가자, "행동보너스", 행동종류=종류)
        행동.append(f"{종류}: {캐릭터.get(키, 0) + 보너스}")
    행동.append(f"추가공격: {캐릭터.get('추가공격', 0)}회")

    장비줄 = [
        f"AC {_부호(장비.get('AC보너스', 0))}   명중 {_부호(장비.get('명중률보너스', 0))}   "
        f"데미지 {_부호(장비.get('데미지보너스', 0))}   속도 {_부호(장비.get('속도보너스', 0))}",
    ]
    스탯보너스 = {k: v for k, v in (장비.get("스탯보너스") or {}).items() if v}
    if 스탯보너스:
        장비줄.append(
            "능력치 " + "  ".join(f"{k} {_부호(v)}" for k, v in 스탯보너스.items())
        )
    세트 = equipment_system.세트효과_목록(
        캐릭터_장비데이터(게임상태, 캐릭터), 방어구세트목록
    )
    if 세트:
        장비줄.append(
            "세트효과: " + ", ".join(정의.get("세트명", "?") for 정의 in 세트)
        )

    return [
        ("기본", 기본),
        ("능력치", 능력치줄),
        ("전투", 전투),
        ("행동", 행동),
        ("장비 보너스 합계", 장비줄),
    ]
