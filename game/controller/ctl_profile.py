# 컨트롤러 - 모험단 프로필 - 캐릭터별 SD 초상화(직업 분류번호 기반)
# (gameflow.py에서 분리 - N5. 화면은 gameflow.py 창구만 부른다. 설명은 gameflow.py 머리말)

import os

from game.controller.ctl_registry import 전직_레지스트리, 직업_데이터파일

__all__ = [
    "_직업_분류번호",
    "초상화_설정",
    "캐릭터_성별_설정",
    "초상화_코드",
    "_그림_폴더",
    "_그림_있음",
    "_보이는_분류번호",
]


# 초상화 코드 = "{직업 분류번호}{성별}". 분류번호는 job_skill/job_level
# 파일명의 계열 번호(01 귀검사/02 격투가/03 거너/04 마법사/05 프리스트)를
# 그대로 쓰고, 비전직은 끝자리 0을 붙인다(예: 격투가 비전직 = "020").
# 아래 표는 비전직 5개이고, 전직한 캐릭터는 전직_레지스트리의 "분류번호"를
# 쓴다. 전직 분류번호는 임의로 추측해서 채우지 않는다.
#
# 주의: 캐릭터 에셋에는 "XX0" 코드의 SD 원화 파일이 없다. 분류번호 자체는
# XX0이 맞지만, 화면에 보여줄 파일이 없을 때 대신 쓸 파일을 고르는 처리는
# screens_common.py의 _캐릭터이미지_경로()가 맡는다(있는 파일로 자동
# 대체) - 이 함수는 "논리적으로 맞는" 분류번호만 돌려준다.
_직업_분류번호 = {직업: 분류코드[:3] for 직업, (분류코드, _) in 직업_데이터파일.items()}


def 초상화_설정(게임상태, 코드):
    """던전 지도에 쓸 "플레이어 초상화"(직업과 무관, 65장 그리드에서
    직접 고른 값)를 바꾼다. 캐릭터별 직업 기반 초상화(초상화_코드)와는
    별개다."""
    게임상태["선택된초상화"] = 코드


def 캐릭터_성별_설정(캐릭터, 성별):
    캐릭터["성별"] = 성별


def 초상화_코드(캐릭터):
    """캐릭터["직업"]과 캐릭터["성별"]로 SD 초상화 분류번호(예: "020f")를
    계산한다. 아직 분류번호를 모르는 직업(_직업_분류번호에 없음)은
    기본/공용 초상화 "001"+성별로 대체한다. 이 코드에 대응하는 실제 파일이
    없을 때 대신 보여줄 파일을 고르는 처리는 여기가 아니라
    screens_common._캐릭터이미지_경로()에서 한다."""
    분류번호 = _직업_분류번호.get(캐릭터["직업"], "001")
    전직정보 = 전직_레지스트리.get(캐릭터["직업"], {}).get(캐릭터.get("전직"))
    if 전직정보:
        분류번호 = 전직정보["분류번호"]
    성별 = 캐릭터.get("성별", "m")
    # 란마 1/2 - 바뀐 형태("란마성별")의 그림은 지금 보이는 그림의 반대 성별 파일이 있을 때만
    # 쓴다(없으면 그림만 그대로, 효과는 combat.traits.형태_속성이 형태를 따른다)
    형태 = 캐릭터.get("란마성별")
    if (
        형태
        and 형태 != 성별
        and _그림_있음(f"{_보이는_분류번호(분류번호, 성별)}{형태}")
    ):
        성별 = 형태
    return f"{분류번호}{성별}"


_그림_폴더 = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "assets", "character"
)


def _그림_있음(코드):
    return os.path.isfile(os.path.join(_그림_폴더, f"asset_sd_character_{코드}.webp"))


def _보이는_분류번호(분류번호, 성별):
    """그 코드로 실제로 보이는 그림의 분류번호 - screens_common._캐릭터이미지_경로와 같은 대체
    (그림이 없으면 같은 계열 같은 성별의 첫 그림, 그마저 없으면 공용 001)."""
    if _그림_있음(f"{분류번호}{성별}"):
        return 분류번호
    for 순번 in "123456789":
        if _그림_있음(f"{분류번호[:2]}{순번}{성별}"):
            return f"{분류번호[:2]}{순번}"
    return "001"
