def _맞는_적_수(타겟, 적수):
    if 타겟 == "적전체":
        return 적수
    if 타겟 == "적3체":
        return min(3, 적수)
    return 1 if 적수 else 0


def 스킬_기대피해(게임상태, 참가자, 스킬이름, 적수=None):
    """공격 스킬의 기대 피해 - 데미지 수식의 평균(주사위를 굴리지 않는다) x 공격 횟수 x 맞는 적 수.
    적수를 안 주면 지금 칠 수 있는 적 수. 계산할 수 없는 수식이면 0. 패턴 스킬(#332)은 정해진 패턴(합격),
    무작위면 패턴들의 평균(원귀)."""
    데이터 = 게임상태["스킬데이터모음"][스킬이름]
    전투상태 = 게임상태["전투상태"]
    데이터, 패턴 = skill_system.패턴_적용(전투상태, 참가자, 데이터)
    if 패턴 is None and "무작위패턴" in (데이터.get("타입") or []):
        목록 = [{**데이터, **덮어쓸것} for 덮어쓸것 in 데이터["패턴"].values()]
        return sum(_기대피해(게임상태, 참가자, d, 적수) for d in 목록) / len(목록)
    return _기대피해(게임상태, 참가자, 데이터, 적수)


def _기대피해(게임상태, 참가자, 데이터, 적수):
    상세 = 데이터.get("공격단계1") or 데이터.get("지속공격") or 데이터
    전투상태 = 게임상태["전투상태"]
    데미지 = 상세.get("데미지", "0")
    식들 = 데미지 if isinstance(데미지, list) else [데미지]
    try:
        무기 = any("공격력" in str(식) for 식 in 식들)
        컨텍스트 = stats.기본_컨텍스트(전투상태, 참가자, 무기공격력필요=무기)
        한번 = sum(formula.수식_평가(str(식), 컨텍스트, 평균=True) for 식 in 식들)
        횟수 = 상세.get("공격횟수", 1)
        if not isinstance(횟수, int):
            횟수 = formula.올림(formula.수식_평가(str(횟수), 컨텍스트, 평균=True))
    except (ValueError, ZeroDivisionError, SyntaxError, TypeError):
        return 0
    if isinstance(데미지, list):  # 타격마다 다른 식이면 리스트 합이 이미 전체 타수
        횟수 = 1
    if 적수 is None:
        적수 = len(_칠_수_있는_적(게임상태))
    타겟 = 상세.get("타겟") or 데이터.get("타겟")
    # 라운드 끝에 치는 장판 지속공격(귀신 : 사야)은 빗나가도 끝나지 않아 지속턴만큼 친다(#602)
    라운드수 = 1
    if 상세.get("발동시점") == "라운드종료" and isinstance(상세.get("지속턴"), int):
        라운드수 = max(상세["지속턴"], 1)
    return (
        (한번 + (상세.get("데미지보너스") or 0))
        * max(횟수, 1)
        * _맞는_적_수(타겟, 적수)
        * 라운드수
    )


def 일반공격_기대피해(게임상태, 참가자):
    """일반공격 1회의 기대 피해(무기 주사위 평균 + 보정치 - 뇌명이면 그 "데미지" 평균). 무기가 없으면 0."""
    if not (참가자.get("장비데이터") or {}).get("무기"):
        return 0
    try:
        대체 = stats.일반공격_대체(게임상태["전투상태"], 참가자)
        컨텍스트 = stats.기본_컨텍스트(
            게임상태["전투상태"], 참가자, 무기공격력필요=not 대체
        )
        식 = 대체["데미지"] if 대체 else "보정공격력"
        return formula.수식_평가(식, 컨텍스트, 평균=True)
    except (ValueError, ZeroDivisionError, SyntaxError, TypeError):
        return 0


def _전력전투_기록(게임상태):
    return 게임상태["전투상태"].setdefault("전력전투기록", {})


def _전력전투_쓸만한가(게임상태, 참가자, 이름, 데이터):
    """해제/회복/버프/자원/소환은 효과가 있을 때만, 공격은 일반공격보다 나을 때만(일반행동 스킬)."""
    분류 = 데이터.get("분류")
    if 데이터.get("자동전투금지"):
        return False  # 쓰면 죽는 스킬(제아봉칩이십오만배 #311)은 플레이어만 고른다
    if 분류 == "해제스킬":
        if str(스킬_실제_타겟(게임상태, 데이터)).startswith("적"):
            return any(e["생존"] and e.get("버프") for e in 적_목록(게임상태))
        # 해로운 효과 하나에 일반행동을 쓰면 손해라 합이 둘 이상일 때만(#602)
        return (
            sum(
                len(a.get("상태이상") or []) + len(a.get("디버프") or [])
                for a in 아군_목록(게임상태)
                if a["생존"]
            )
            >= _아군해제_최소
        )
    if 분류 == "회복스킬":
        return bool(_다친_아군(게임상태))
    if 분류 in ("버프스킬", "디버프스킬"):
        return _버프_쓸만한가(게임상태, 참가자, 이름, 데이터)
    if 분류 == "자원스킬":
        return not 참가자.get("보유자원")
    if 분류 == "소환스킬":
        return not 참가자.get("소환수")
    if 분류 == "공격스킬":
        기대 = 공격_평가(게임상태, 참가자, 이름)
        if 기대 <= 0:
            return False
        if 데이터.get("행동") == "일반행동":
            return 기대 >= 일반공격_기대피해(게임상태, 참가자)
        return True
    return False


def _버프_쓸만한가(게임상태, 참가자, 이름, 데이터):
    """버프·디버프스킬을 지금 쓸 만한가(_전력전투_쓸만한가에서 나눔)."""
    분류 = 데이터.get("분류")
    전투상태 = 게임상태["전투상태"]
    if 데이터.get("방어스킬") and not _공격하는_적이_있나(게임상태):
        return False  # 맞을 일이 없으면 방어는 헛수고(샌드백 공격 끔 - #401)
    # 가드·무기막기는 공격 한 번을 버리니 HP가 절반 이하일 때만(#602)
    if _자기_방어_일반행동인가(게임상태, 데이터) and not _위험한가(게임상태, 참가자):
        return False
    if _막히는_공격이_더_센가(게임상태, 참가자, 데이터):
        return False  # 공중사격 - 걸면 양자폭탄을 못 쓴다(#602)
    # 이미 걸린 버프·약화를 덮어쓰지 않는다 - 다른 아군이 건 것, 같은 버프군도(#606)
    if 분류 == "버프스킬" and not _새로_받는_대상(게임상태, 참가자, 이름, 데이터):
        return False
    if 분류 == "디버프스킬" and _적에게_다_걸렸나(게임상태, 데이터):
        return False
    직전 = _전력전투_기록(게임상태).get(f"{참가자.get('id')}:{이름}")
    if 직전 is None:
        return True
    지속 = 데이터.get("지속턴")
    if not isinstance(지속, int):
        return False  # 지속이 정해지지 않은(전투 동안 가는) 버프는 한 번
    return 전투상태["라운드"] >= 직전 + 지속


def _자기_방어_일반행동인가(게임상태, 데이터):
    """자기만 지키는 방어스킬이 일반행동을 쓰나(가드·무기막기) - 아군 전체 방어(수호의 축복)는 아니다."""
    return (
        bool(데이터.get("방어스킬"))
        and 스킬_실제_타겟(게임상태, 데이터) == "자신"
        and 데이터.get("행동") == "일반행동"
    )


def _스킬제한_원소들(게임상태, 데이터):
    """버프스킬이 거는 버프의 "스킬제한" 효과 원소들(공중사격 #391)."""
    획득 = 데이터.get("버프획득") or []
    정의모음 = 게임상태["전투상태"].get("버프정의") or {}
    결과 = []
    for 버프 in [획득] if isinstance(획득, str) else 획득:
        정의 = 정의모음.get(버프) or resources.효과정의_조회(버프)[0] or {}
        효과 = 정의.get("효과") or []
        for 원소 in [효과] if isinstance(효과, dict) else 효과:
            if isinstance(원소, dict) and 원소.get("변동대상") == "스킬제한":
                결과.append(원소)
    return 결과


def _막히는_공격이_더_센가(게임상태, 참가자, 데이터):
    """스킬제한 버프를 걸면 못 쓰게 되는 공격스킬의 기대 피해가, 제한 안에서 쓸 수 있는 공격(일반공격 포함)
    보다 큰가. 지금 쓸 수 있는 공격스킬만 본다."""
    제한들 = _스킬제한_원소들(게임상태, 데이터)
    if not 제한들:
        return False
    막힘, 허용 = 0, 일반공격_기대피해(게임상태, 참가자)
    for 이름 in 참가자["원본"].get("보유스킬", []):
        스킬 = 게임상태["스킬데이터모음"].get(이름) or {}
        if 스킬.get("분류") != "공격스킬" or 스킬.get("자동전투금지"):
            continue
        if not 스킬_사용_가능여부(게임상태, 참가자, 이름)[0]:
            continue
        기대 = 스킬_기대피해(게임상태, 참가자, 이름)
        태그 = set(스킬.get("타입") or ())
        막히나 = any(
            이름 not in (원소.get("허용스킬") or ())
            and not 태그 & set(원소.get("허용타입") or ())
            for 원소 in 제한들
        )
        if 막히나:
            막힘 = max(막힘, 기대)
        else:
            허용 = max(허용, 기대)
    return 막힘 > 허용


def _위험한가(게임상태, 참가자):
    """참가자 HP가 절반 이하인가(전력전투 회복과 같은 기준)."""
    return 참가자["현재HP"] * 2 <= 캐릭터_최대HP(게임상태, 참가자["원본"])


def _공격하는_적이_있나(게임상태):
    """살아 있는 적 중 패턴이 있는 적이 있나 - 모두 비었으면(샌드백 전투 공격 끔) 아무도 아군을 치지 않는다."""
    return any(e["생존"] and (e["원본"].get("패턴") or {}) for e in 적_목록(게임상태))


def _다친_아군(게임상태):
    """HP가 절반 이하인 살아 있는 아군, HP 비율이 낮은 순."""
    다친 = [
        a
        for a in 아군_목록(게임상태)
        if a["생존"] and a["현재HP"] * 2 <= 캐릭터_최대HP(게임상태, a["원본"])
    ]
    return sorted(
        다친, key=lambda a: a["현재HP"] / max(1, 캐릭터_최대HP(게임상태, a["원본"]))
    )


def _전력전투_인수(게임상태, 데이터, 참가자=None):
    """스킬을 낼 인수(중심대상). 낼 수 없으면 None. "타겟제한" "자신제외"(새크리파이스)면 참가자는 빼고 고른다."""
    타겟 = 스킬_실제_타겟(게임상태, 데이터)
    if 타겟 in _전력전투_제외타겟:
        return None
    if 타겟 and str(타겟).startswith("적"):
        적들 = [
            p
            for p in _칠_수_있는_적(게임상태)
            if not 스킬_지정불가인가(게임상태, 데이터, p)
        ]
        return {"중심대상": 적들[0]} if 적들 else None
    if 타겟 == "아군단일":
        다친 = _다친_아군(게임상태)
        if 데이터.get("타겟제한") == "자신제외":
            다친 = [a for a in 다친 if a is not 참가자]
        return {"중심대상": 다친[0]} if 다친 else None
    return {}


def _버프_점수(게임상태, 참가자, 이름):
    """버프 고르기 순서(#602, #606) - (행동을 쓰지 않나, 위험할 때 거는 자기 방어인가, 새로 받는 대상 수 x
    얻는 버프 수 x 중첩량 x 지속 가중). 새로 받는 대상은 _새로_받는_대상. 중첩량이 식이면 평균, 계산할 수
    없으면 1. 지속 가중은 지속턴(최대 3), 지속이 정해지지 않은(전투 동안 가는) 버프는 3."""
    데이터 = 게임상태["스킬데이터모음"][이름]
    대상수 = len(_새로_받는_대상(게임상태, 참가자, 이름, 데이터))
    지속 = 데이터.get("지속턴")
    지속가중 = min(max(지속, 1), _지속가중_최대) if isinstance(지속, int) else 3
    획득 = 데이터.get("버프획득") or []
    개수 = max(1, len([획득] if isinstance(획득, str) else 획득))
    중첩 = 데이터.get("중첩량", 1)
    if not isinstance(중첩, (int, float)):
        try:
            중첩 = formula.수식_평가(
                str(중첩),
                stats.기본_컨텍스트(게임상태["전투상태"], 참가자),
                평균=True,
            )
        except (ValueError, ZeroDivisionError, SyntaxError, TypeError):
            중첩 = 1
    return (
        데이터.get("행동") is None,
        _자기_방어_일반행동인가(게임상태, 데이터),  # 후보면 HP가 절반 이하라 급하다
        대상수 * 개수 * max(중첩, 1) * 지속가중,
    )


_지속가중_최대 = (
    3  # 버프 점수의 지속 가중 상한(#606) - 그보다 긴 지속은 전투가 먼저 끝나기 쉽다
)


def _남아_있나(항목):
    """효과 항목이 다음 라운드에도 남나 - 지속턴이 2 이상이거나 정해지지 않았다(전투 동안)."""
    지속 = 항목.get("지속턴")
    return not isinstance(지속, int) or 지속 >= 2


def _새로_받는_대상(게임상태, 참가자, 이름, 데이터):
    """버프스킬을 지금 걸면 새로 받는 아군 - 대상(아군 전체면 살아 있는 아군, 아니면 자신) 중 이 스킬이나 같은
    버프군(skill_run.버프군_정리) 스킬이 건 버프가 남아 있는 아군은 뺀다(누가 걸었든, #606). 거는 버프가 없는
    스킬(분신 등)은 대상 전부."""
    if 스킬_실제_타겟(게임상태, 데이터) == "아군전체":
        대상 = [a for a in 아군_목록(게임상태) if a["생존"]]
    else:
        대상 = [참가자]
    if not 데이터.get("버프획득"):
        return 대상
    군 = _버프군(데이터)
    모음 = 게임상태["스킬데이터모음"]

    def 덮이나(출처):
        return 출처 == 이름 or bool(군 & _버프군(모음.get(출처) or {}))

    return [
        a
        for a in 대상
        if not any(
            덮이나(항목.get("출처스킬")) and _남아_있나(항목)
            for 항목 in a.get("버프") or []
        )
    ]


def _버프군(데이터):
    return {
        t for t in 데이터.get("타입") or () if t.startswith("버프") and t.endswith("군")
    }


def _적에게_다_걸렸나(게임상태, 데이터):
    """적 대상 약화 스킬이 거는 효과(버프획득 이름, 효과의 상태이상 이름)가 지정할 수 있는 살아 있는 적 모두에게
    남아 있나(#606). 거는 효과 이름이 없으면 False."""
    획득 = 데이터.get("버프획득") or []
    이름들 = set([획득] if isinstance(획득, str) else 획득)
    이름들 |= {
        원소["이름"]
        for 원소 in 데이터.get("효과") or []
        if isinstance(원소, dict)
        and 원소.get("종류") == "상태이상"
        and 원소.get("이름")
    }
    적들 = _칠_수_있는_적(게임상태)
    if not 이름들 or not 적들:
        return False
    return all(
        any(
            항목.get("이름") in 이름들 and _남아_있나(항목)
            for 칸 in ("버프", "디버프", "상태이상")
            for 항목 in e.get(칸) or []
        )
        for e in 적들
    )


def _장판_지속공격인가(데이터):
    """라운드 끝에 치는 장판 지속공격(귀신 : 사야) - 공격스킬이지만 "장판공격" 차례에 깐다(#650)."""
    return (
        데이터.get("분류") == "공격스킬"
        and (데이터.get("지속공격") or {}).get("발동시점") == "라운드종료"
    )


def _전력전투_단계(데이터):
    """스킬이 드는 _전력전투_차례 단계 - 보통은 분류, 장판 지속공격은 "장판공격", 일반행동 약화는 "행동약화"(#650)."""
    분류 = 데이터.get("분류")
    if _장판_지속공격인가(데이터):
        return "장판공격"
    if 분류 == "디버프스킬" and 데이터.get("행동") == "일반행동":
        return "행동약화"
    return 분류


def _장판_안_깔린_적이_있나(게임상태, 이름):
    """이 장판 지속공격이 아직 걸려 있지 않은 칠 수 있는 적이 있나(누가 깔았든, #650)."""
    return any(
        not any(
            항목.get("이름") == 이름 and _남아_있나(항목)
            for 항목 in e.get("상태이상") or []
        )
        for e in _칠_수_있는_적(게임상태)
    )


def 공격_평가(게임상태, 참가자, 이름):
    """공격스킬 고르기의 평가 - 스킬_기대피해에 그 스킬에 이어 나갈 연계스킬(귀참드라이브, 수플렉스 썬더)의 기대 피해를
    따로 계산해 더한다. 연계는 같은 적 하나를 치고, 그 행동·MP를 낼 수 있을 때만 더한다(#650)."""
    값 = 스킬_기대피해(게임상태, 참가자, 이름)
    if 값 <= 0:
        return 값
    for 연계이름 in 참가자["원본"].get("보유스킬", []):
        데이터 = 게임상태["스킬데이터모음"].get(연계이름) or {}
        if "연계스킬" not in (데이터.get("타입") or []) or 데이터.get("연계") != 이름:
            continue
        비용 = {
            "_이름": 연계이름,
            "행동": 데이터.get("행동"),
            "MP소모": 데이터.get("MP소모", 0)
            + (게임상태["스킬데이터모음"][이름].get("MP소모") or 0),
        }
        if not skill_system.사용_가능여부(게임상태["전투상태"], 참가자, 비용)[0]:
            continue
        값 += 스킬_기대피해(게임상태, 참가자, 연계이름, 적수=1)
    return 값


def 전력전투_고르기(게임상태, 참가자):
    """지금 쓸 스킬 (이름, 인수) - 단계(_전력전투_차례) 차례대로, 공격은 공격_평가가 가장 큰 것. 없으면 None."""
    for 단계 in _전력전투_차례:
        후보 = []
        for 이름 in 참가자["원본"].get("보유스킬", []):
            데이터 = 게임상태["스킬데이터모음"].get(이름) or {}
            if _전력전투_단계(데이터) != 단계:
                continue
            if 단계 == "장판공격" and not _장판_안_깔린_적이_있나(게임상태, 이름):
                continue
            if not 스킬_사용_가능여부(게임상태, 참가자, 이름)[0]:
                continue
            if not _전력전투_쓸만한가(게임상태, 참가자, 이름, 데이터):
                continue
            인수 = _전력전투_인수(게임상태, 데이터, 참가자)
            if 인수 is not None:
                후보.append((이름, 인수))
        if 후보:
            if 단계 in ("장판공격", "공격스킬"):
                return max(후보, key=lambda c: 공격_평가(게임상태, 참가자, c[0]))
            if 단계 == "버프스킬":  # 점수가 같으면 max는 앞의 것 - 보유 목록 순서
                return max(후보, key=lambda c: _버프_점수(게임상태, 참가자, c[0]))
            return 후보[0]
    return None


def 전력전투_한_차례(게임상태):
    """현재 아군이 쓸 수 있는 스킬을 전력전투 차례대로 쓴다(남은 일반행동은 자동전투_한_턴이 친다)."""
    전투상태 = 게임상태["전투상태"]
    참가자 = 현재_턴_참가자(게임상태)
    for _ in range(20):  # 행동이 줄지 않는 스킬이 있어도 멈춘다
        if 전투상태["종료"] is not None or not 참가자["생존"]:
            return
        선택 = 전력전투_고르기(게임상태, 참가자)
        if 선택 is None:
            return
        이름, 인수 = 선택
        try:
            아군_스킬사용(게임상태, 이름, **인수)
        except ValueError:
            return  # 쓸 수 없다고 나오면(예상 밖) 일반공격으로 넘긴다
        _전력전투_기록(게임상태)[f"{참가자.get('id')}:{이름}"] = 전투상태["라운드"]
