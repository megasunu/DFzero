#   2 회복 - HP가 절반 이하인 아군 중 HP 비율이 가장 낮은 아군에게
#   3 버프 - 지속 턴이 지나야 다시(지속이 정해지지 않은 버프는 전투당 한 번). 자기만 지키는 일반행동
#      방어(가드·무기막기)는 자기 HP가 절반 이하일 때만. 여럿이면 행동을 쓰지 않는 것, 그다음
#      새로 받는 대상 수 x 얻는 버프 수 x 중첩량 x 지속(최대 3)이 큰 것(_버프_점수, #602 #606). 같은 버프나
#      같은 버프군이 남은 아군은 새로 받지 않고, 모두 남았으면(적 약화는 모든 적에게 걸렸으면) 걸지 않는다. 스킬을 막는 버프(공중사격)는 막히는
#      공격이 제한 안의 공격보다 셀 때 걸지 않는다
#   4 자원/소환 - 자원이 없을 때 / 소환수가 없을 때
#   5 장판 - 장판 지속공격(사야)은 아직 깔리지 않은 적이 있으면 다른 공격보다 먼저 깐다(깔려 있으면 다시 깔지 않는다, #650)
#   6 공격 - 평가(기대 피해 = 평균 피해 x 공격 횟수 x 맞는 적 수, 더하기 이어 나갈 연계스킬의 기대 피해 - 공격_평가 #650)가
#      가장 큰 스킬을 가장 약한 적에게. 장판 지속공격(사야)은 지속턴만큼 센다(#602). 일반행동을 쓰는 스킬은 일반공격보다
#      평가가 클 때만(보조행동 등 다른 행동을 쓰면 덤이라 늘). MP는 아끼지 않는다. 대상을 하나씩 고르는 "적반복지정"은 쓰지 않는다.
#   7 행동 약화 - 일반행동을 쓰는 약화 스킬(브레멘)은 공격스킬이 없을 때만(행동 하나를 버려 손해, #650). 보조행동
#      약화(도발)는 3의 버프 다음 차례("디버프스킬") 그대로
