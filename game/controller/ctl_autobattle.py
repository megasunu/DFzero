# [자동전투]에서 일반공격 대신 쓰는 스킬 - 캐릭터의 1차 직업 기준(전직해도 같다).
# 값은 game/data/character/job_info.py 직업정보의 "자동전투_대체스킬".
_자동전투_대체스킬 = {
    직업: 정보["자동전투_대체스킬"]
    for 직업, 정보 in 직업정보.items()
    if 정보["자동전투_대체스킬"]
}


def _자동전투_스킬(게임상태, 참가자):
    """자동전투에서 일반공격 대신 쓸 스킬 이름 - 없거나 지금 쓸 수 없으면 None(일반공격)."""
    이름 = _자동전투_대체스킬.get((참가자.get("원본") or {}).get("직업"))
    if not 이름 or 이름 not in (참가자.get("원본") or {}).get("보유스킬", []):
        return None
    return 이름 if 스킬_사용_가능여부(게임상태, 참가자, 이름)[0] else None


def _자동전투_포션(게임상태, 참가자):
    """설정 "자동전투 포션"이 켜져 있고 참가자 HP가 절반 이하면(전력전투 회복과 같은 기준) 지금 쓸 수 있는
    HP 회복포션 중 데이터 순서 첫 것(가장 낮은 티어)을 하나 마신다(보조행동 1, #177). 마신 이름 또는 None."""
    if not 자동전투_포션_여부():
        return None
    if 참가자["현재HP"] * 2 > 캐릭터_최대HP(게임상태, 참가자["원본"]):
        return None
    for 이름, _, 사유 in 아군_회복포션_목록(게임상태):
        if 사유 is None and 포션_데이터["회복포션"][이름]["회복대상"] == "HP":
            아군_포션사용(게임상태, 이름)
            return 이름
    return None


def 자동전투_한_턴(게임상태):
    """[자동전투] - 현재 턴의 아군이 일반행동(과 열린 추가행동)이 남아 있는 동안 지정 가능한 적
    중 무작위 하나를 일반공격하고(마법사 계열은 매직미사일 - _자동전투_대체스킬),
    더 할 수 없으면 턴을 넘긴다(턴_넘기기 -
    이어지는 몬스터 턴도 진행). 전투가 끝나면 바로 멈춘다. 반응은
    전투상태["반응선택"] 콜백이 없으면 자동으로 쓴다(화면이 비워서 부른다).
    공격할 적이 없으면(모두 은신 등) 공격 없이 턴을 넘긴다. 설정 "자동전투 포션"이 켜져 있으면
    HP 절반 이하일 때 먼저 HP 회복포션을 마신다(_자동전투_포션)."""
    전투상태 = 게임상태["전투상태"]
    if 전투상태["종료"] is not None:
        return
    현재 = 현재_턴_참가자(게임상태)
    if 현재["진영"] != "아군" or not 현재["생존"]:
        raise ValueError("자동전투는 아군 차례에만 진행한다.")
    _자동전투_포션(게임상태, 현재)
    if 자동전투_방식() == "전력전투":
        전력전투_한_차례(게임상태)
    while 전투상태["종료"] is None and 일반공격_가능여부(게임상태, 현재):
        후보 = _칠_수_있는_적(게임상태)
        if not 후보:
            break
        # 일반공격 방식은 무작위, 전력전투는 남은 일반행동도 가장 약한 적에게
        대상 = 후보[0] if 자동전투_방식() == "전력전투" else rng.대상.choice(후보)
        스킬 = _자동전투_스킬(게임상태, 현재)
        if 스킬:
            아군_스킬사용(게임상태, 스킬, 중심대상=대상)
        else:
            아군_일반공격(게임상태, 대상)
    if 전투상태["종료"] is None:
        턴_넘기기(게임상태)


def _칠_수_있는_적(게임상태):
    """지정할 수 있는 살아 있는 적 - 일반공격 방식은 이 목록에서 무작위로, 전력전투는 앞(가장 약한 적)부터."""
    후보 = [
        p for p in 적_목록(게임상태) if p["생존"] and not 지정불가_상태인가(게임상태, p)
    ]
    if 자동전투_방식() == "전력전투":
        후보.sort(key=lambda p: (p["현재HP"], p["이름"]))
    return 후보


