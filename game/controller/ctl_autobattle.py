# 전력전투 - [설정]의 자동전투 "전력전투"(스킬 우선)
# =====================================================
# 한 차례에 쓸 수 있는 스킬을 이 순서로 쓰고(행동이 남는 동안), 남은 일반행동은 일반공격(마법사
# 계열은 매직미사일)으로 가장 약한 적을 친다:
#   1 해제 - 아군에게 상태이상/디버프가 있으면(아군 해제), 적에게 버프가 있으면(적 해제)
#   2 회복 - HP가 절반 이하인 아군 중 HP 비율이 가장 낮은 아군에게
#   3 버프 - 지속 턴이 지나야 다시(지속이 정해지지 않은 버프는 전투당 한 번)
#   4 자원/소환 - 자원이 없을 때 / 소환수가 없을 때
#   5 공격 - 기대 피해(평균 피해 x 공격 횟수 x 맞는 적 수)가 가장 큰 스킬을 가장 약한 적에게.
#      일반행동을 쓰는 스킬은 일반공격보다 기대 피해가 클 때만(보조행동 등 다른 행동을 쓰면 덤이라
#      늘). MP는 아끼지 않는다. 대상을 하나씩 고르는 "적반복지정"은 쓰지 않는다.
_전력전투_차례 = (
    "해제스킬",
    "회복스킬",
    "버프스킬",
    "디버프스킬",
    "자원스킬",
    "소환스킬",
    "공격스킬",
)
_전력전투_제외타겟 = ("적반복지정",)


def _맞는_적_수(타겟, 적수):
    if 타겟 == "적전체":
        return 적수
    if 타겟 == "적3체":
        return min(3, 적수)
    return 1 if 적수 else 0


def 스킬_기대피해(게임상태, 참가자, 스킬이름, 적수=None):
    """공격 스킬의 기대 피해 - 데미지 수식의 평균(주사위를 굴리지 않는다) x 공격 횟수 x 맞는 적 수.
    적수를 안 주면 지금 칠 수 있는 적 수. 계산할 수 없는 수식이면 0. 패턴 스킬(#332)은 정해진 패턴(합격),
    무작위면 패턴들의 평균(원귀)."""
    데이터 = 게임상태["스킬데이터모음"][스킬이름]
    전투상태 = 게임상태["전투상태"]
    데이터, 패턴 = skill_system.패턴_적용(전투상태, 참가자, 데이터)
    if 패턴 is None and "무작위패턴" in (데이터.get("타입") or []):
        목록 = [{**데이터, **덮어쓸것} for 덮어쓸것 in 데이터["패턴"].values()]
        return sum(_기대피해(게임상태, 참가자, d, 적수) for d in 목록) / len(목록)
    return _기대피해(게임상태, 참가자, 데이터, 적수)


def _기대피해(게임상태, 참가자, 데이터, 적수):
    상세 = 데이터.get("공격단계1") or 데이터.get("지속공격") or 데이터
    전투상태 = 게임상태["전투상태"]
    데미지 = 상세.get("데미지", "0")
    식들 = 데미지 if isinstance(데미지, list) else [데미지]
    try:
        무기 = any("공격력" in str(식) for 식 in 식들)
        컨텍스트 = stats.기본_컨텍스트(전투상태, 참가자, 무기공격력필요=무기)
        한번 = sum(formula.수식_평가(str(식), 컨텍스트, 평균=True) for 식 in 식들)
        횟수 = 상세.get("공격횟수", 1)
        if not isinstance(횟수, int):
            횟수 = formula.올림(formula.수식_평가(str(횟수), 컨텍스트, 평균=True))
    except (ValueError, ZeroDivisionError, SyntaxError, TypeError):
        return 0
    if isinstance(데미지, list):  # 타격마다 다른 식이면 리스트 합이 이미 전체 타수
        횟수 = 1
    if 적수 is None:
        적수 = len(_칠_수_있는_적(게임상태))
    타겟 = 상세.get("타겟") or 데이터.get("타겟")
    return (
        (한번 + (상세.get("데미지보너스") or 0))
        * max(횟수, 1)
        * _맞는_적_수(타겟, 적수)
    )


def 일반공격_기대피해(게임상태, 참가자):
    """일반공격 1회의 기대 피해(무기 주사위 평균 + 보정치). 무기가 없으면 0."""
    if not (참가자.get("장비데이터") or {}).get("무기"):
        return 0
    try:
        컨텍스트 = stats.기본_컨텍스트(
            게임상태["전투상태"], 참가자, 무기공격력필요=True
        )
        return formula.수식_평가("보정공격력", 컨텍스트, 평균=True)
    except (ValueError, ZeroDivisionError, SyntaxError, TypeError):
        return 0


def _전력전투_기록(게임상태):
    return 게임상태["전투상태"].setdefault("전력전투기록", {})


def _전력전투_쓸만한가(게임상태, 참가자, 이름, 데이터):
    """해제/회복/버프/자원/소환은 효과가 있을 때만, 공격은 일반공격보다 나을 때만(일반행동 스킬)."""
    분류 = 데이터.get("분류")
    전투상태 = 게임상태["전투상태"]
    if 분류 == "해제스킬":
        if str(스킬_실제_타겟(게임상태, 데이터)).startswith("적"):
            return any(e["생존"] and e.get("버프") for e in 적_목록(게임상태))
        return any(
            a["생존"] and (a.get("상태이상") or a.get("디버프"))
            for a in 아군_목록(게임상태)
        )
    if 분류 == "회복스킬":
        return bool(_다친_아군(게임상태))
    if 분류 in ("버프스킬", "디버프스킬"):
        직전 = _전력전투_기록(게임상태).get(f"{참가자.get('id')}:{이름}")
        if 직전 is None:
            return True
        지속 = 데이터.get("지속턴")
        if not isinstance(지속, int):
            return False  # 지속이 정해지지 않은(전투 동안 가는) 버프는 한 번
        return 전투상태["라운드"] >= 직전 + 지속
    if 분류 == "자원스킬":
        return not 참가자.get("보유자원")
    if 분류 == "소환스킬":
        return not 참가자.get("소환수")
    if 분류 == "공격스킬":
        기대 = 스킬_기대피해(게임상태, 참가자, 이름)
        if 기대 <= 0:
            return False
        if 데이터.get("행동") == "일반행동":
            return 기대 >= 일반공격_기대피해(게임상태, 참가자)
        return True
    return False


def _다친_아군(게임상태):
    """HP가 절반 이하인 살아 있는 아군, HP 비율이 낮은 순."""
    다친 = [
        a
        for a in 아군_목록(게임상태)
        if a["생존"] and a["현재HP"] * 2 <= 캐릭터_최대HP(게임상태, a["원본"])
    ]
    return sorted(
        다친, key=lambda a: a["현재HP"] / max(1, 캐릭터_최대HP(게임상태, a["원본"]))
    )


def _전력전투_인수(게임상태, 데이터, 참가자=None):
    """스킬을 낼 인수(중심대상). 낼 수 없으면 None. "타겟제한" "자신제외"(새크리파이스)면 참가자는 빼고 고른다."""
    타겟 = 스킬_실제_타겟(게임상태, 데이터)
    if 타겟 in _전력전투_제외타겟:
        return None
    if 타겟 and str(타겟).startswith("적"):
        적들 = [
            p
            for p in _칠_수_있는_적(게임상태)
            if not 스킬_지정불가인가(게임상태, 데이터, p)
        ]
        return {"중심대상": 적들[0]} if 적들 else None
    if 타겟 == "아군단일":
        다친 = _다친_아군(게임상태)
        if 데이터.get("타겟제한") == "자신제외":
            다친 = [a for a in 다친 if a is not 참가자]
        return {"중심대상": 다친[0]} if 다친 else None
    return {}


def 전력전투_고르기(게임상태, 참가자):
    """지금 쓸 스킬 (이름, 인수) - 분류 차례대로, 공격은 기대 피해가 가장 큰 것. 없으면 None."""
    for 분류 in _전력전투_차례:
        후보 = []
        for 이름 in 참가자["원본"].get("보유스킬", []):
            데이터 = 게임상태["스킬데이터모음"].get(이름) or {}
            if 데이터.get("분류") != 분류:
                continue
            if not 스킬_사용_가능여부(게임상태, 참가자, 이름)[0]:
                continue
            if not _전력전투_쓸만한가(게임상태, 참가자, 이름, 데이터):
                continue
            인수 = _전력전투_인수(게임상태, 데이터, 참가자)
            if 인수 is not None:
                후보.append((이름, 인수))
        if 후보:
            if 분류 == "공격스킬":
                return max(후보, key=lambda c: 스킬_기대피해(게임상태, 참가자, c[0]))
            return 후보[0]
    return None


def 전력전투_한_차례(게임상태):
    """현재 아군이 쓸 수 있는 스킬을 전력전투 차례대로 쓴다(남은 일반행동은 자동전투_한_턴이 친다)."""
    전투상태 = 게임상태["전투상태"]
    참가자 = 현재_턴_참가자(게임상태)
    for _ in range(20):  # 행동이 줄지 않는 스킬이 있어도 멈춘다
        if 전투상태["종료"] is not None or not 참가자["생존"]:
            return
        선택 = 전력전투_고르기(게임상태, 참가자)
        if 선택 is None:
            return
        이름, 인수 = 선택
        try:
            아군_스킬사용(게임상태, 이름, **인수)
        except ValueError:
            return  # 쓸 수 없다고 나오면(예상 밖) 일반공격으로 넘긴다
        _전력전투_기록(게임상태)[f"{참가자.get('id')}:{이름}"] = 전투상태["라운드"]
