def _이름들(값):
    """퍽 "획득특성" - 이름 하나거나 이름 리스트."""
    return 값 if isinstance(값, list) else [값]


def 약점스탯_투자가능(캐릭터, 스탯이름):
    """약점스탯은 '약점제거' 특성 전에는 배분할 수 없다(능력치 배분 팝업용)."""
    return 캐릭터레벨업.약점스탯_투자가능(캐릭터, 스탯이름)


def 성장불가_스탯(캐릭터):
    """ "능력치성장"에서 못 올리는 능력치(원래 약점스탯, 약점증가로 약점이 된 것) - 화면의 배분 팝업용."""
    return 캐릭터레벨업.성장불가_스탯(캐릭터)


def _선행조건_만족(캐릭터, 선행조건):
    """퍽 선행조건 판정. None=항상 만족,
    문자열=해당 특성 보유, dict={"특성보유"|"스킬보유"|"전직"|"가용무기"|"최소능력치": ...}."""
    if 선행조건 is None:
        return True
    if isinstance(선행조건, str):
        return 선행조건 in 캐릭터["보유특성"]
    if isinstance(선행조건, dict):
        if "특성보유" in 선행조건:
            return 선행조건["특성보유"] in 캐릭터["보유특성"]
        if "스킬보유" in 선행조건:
            return 선행조건["스킬보유"] in 캐릭터.get("보유스킬", [])
        if "전직" in 선행조건:  # 그 전직만(버서커 광기 #247)
            return 캐릭터.get("전직") == 선행조건["전직"]
        if "가용무기" in 선행조건:
            return 선행조건["가용무기"] in 캐릭터.get("가용무기", [])
        if "최소능력치" in 선행조건:
            return all(
                캐릭터.get(스탯, 0) >= 값 for 스탯, 값 in 선행조건["최소능력치"].items()
            )
    return True


def _직업때문에_숨김(캐릭터, 선행조건):
    """다른 전직의 퍽, 무기 마스터리를 대신한 특성(검귀의 도 마스터리 #330)을 가진 캐릭터의 무기 마스터리 퍽."""
    if not isinstance(선행조건, dict):
        return False
    if "전직" in 선행조건 and not _선행조건_만족(캐릭터, 선행조건):
        return True
    return "가용무기" in 선행조건 and _무기마스터리_대체됨(캐릭터)


def _무기마스터리_대체됨(캐릭터):
    """무기 마스터리를 대신하는 특성("대체특성타입": "무기마스터리" - 검귀의 도 마스터리)을 가졌나."""
    특성목록 = 직업_레지스트리[캐릭터["직업"]]["특성목록"]
    return any(
        (특성목록.get(이름) or {}).get("대체특성타입") == "무기마스터리"
        for 이름 in 캐릭터["보유특성"]
    )


def 퍽_처리타입(퍽정의):
    """퍽의 처리 종류(특성획득/스탯획득/스킬획득/일반퍽) - 화면이 능력치 배분 팝업을 띄울지 정할 때."""
    return 캐릭터레벨업.퍽_처리타입(퍽정의)


def 퍽_선택상태(캐릭터, 퍽정의):
    """퍽 선택 화면에서 이 퍽을 어떻게 보일지(사용자 결정 2026-10-20):
    None = 숨김(이미 배웠다, 전직이 다르다 - 직업 때문에 못 고르는 퍽),
    "" = 고를 수 있음, 그 밖의 문자열 = 회색(못 고르는 이유 - 차수, 선행조건, 같은 "배타묶음"의
    다른 퍽을 배움, 아직 지원하지 않는 퍽)."""
    분류 = 캐릭터레벨업.퍽_처리타입(퍽정의)
    선행조건 = 퍽정의.get("선행조건")
    if _직업때문에_숨김(캐릭터, 선행조건):
        return None
    if 특성선택_퍽인가(퍽정의):
        pass  # 여러 번 배운다 - 고를 특성이 다 떨어지면 회색(아래)
    elif "획득특성" in 퍽정의:
        if all(n in 캐릭터["보유특성"] for n in _이름들(퍽정의["획득특성"])):
            return None
    elif 분류 == "스킬획득" and not 훔쳐배우기_퍽인가(퍽정의):
        if 퍽정의.get("획득스킬") in 캐릭터["보유스킬"]:
            return None
    if 분류 == "일반퍽":
        return "아직 지원하지 않는 퍽"
    if 퍽정의.get("차수", 1) > 캐릭터데이터.차수_계산(캐릭터):
        return f"{퍽정의.get('차수', 1)}차수부터"  # 스킬처럼 자기 차수보다 높은 퍽은 못 고른다
    if not _선행조건_만족(캐릭터, 선행조건):
        return "선행조건 미충족"
    묶음 = 퍽정의.get("배타묶음")
    if 묶음:
        전체 = 캐릭터_전체퍽(캐릭터)
        배운것 = 캐릭터.get("보유퍽")
        if 배운것 is None:
            배운것 = _보유퍽_추정(캐릭터)
        막은것 = next(
            (n for n in 배운것 if (전체.get(n) or {}).get("배타묶음") == 묶음), None
        )
        if 막은것:
            return f"'{막은것}'과(와) 함께 배울 수 없음"
    if 분류 == "스킬획득" and 훔쳐배우기_퍽인가(퍽정의) and not 훔쳐배우기_후보(캐릭터):
        return "훔쳐배울 것이 없음"
    if 특성선택_퍽인가(퍽정의) and not 퍽_선택특성_후보(캐릭터, 퍽정의):
        return "고를 특성이 없음"
    return ""


def 특성선택_퍽인가(퍽정의):
    """배울 때 "선택특성" 목록에서 특성 하나를 고르는 퍽(포켓몬) - 여러 번 배울 수 있다."""
    return bool(퍽정의.get("선택특성")) and 퍽정의.get("획득특성") is None


def 퍽_선택특성_후보(캐릭터, 퍽정의):
    """특성선택 퍽에서 지금 고를 수 있는 특성 [{"이름", "설명", "정의"}] - 이미 가진 것은 뺀다(목록 순서).
    정의는 그 직업 특성목록 -> 공용 특성목록 순으로 찾는다."""
    모음 = {**공용특성, **직업_레지스트리[캐릭터["직업"]]["특성목록"]}
    return [
        {"이름": 이름, "설명": 모음[이름].get("설명", ""), "정의": 모음[이름]}
        for 이름 in 퍽정의.get("선택특성") or []
        if 이름 in 모음 and 이름 not in 캐릭터["보유특성"]
    ]


def _퍽_선택가능(캐릭터, 퍽정의):
    return 퍽_선택상태(캐릭터, 퍽정의) == ""


def _타입들(정의):
    타입 = 정의.get("타입") or []
    return 타입 if isinstance(타입, list) else [타입]


def 훔쳐배우기_퍽인가(퍽정의):
    return (퍽정의.get("효과") or {}).get("타입") == "타클래스스킬습득"


def 훔쳐배우기_후보(캐릭터):
    """공용 퍽 "훔쳐배우기"(#279)로 고를 수 있는 것 - 같은 1차 계열의 다른(구현된) 1차 전직이 가진
    "훔쳐배우기스킬" 태그 스킬, 그리고 계열 특성목록에서 태그와 "전직"(자기 전직이 아닌)이 붙은 특성.
    이미 가진 것은 뺀다. [{"이름", "종류": "스킬"|"특성", "전직", "설명", "정의"}]"""
    직업 = 캐릭터["직업"]
    내전직 = 캐릭터.get("전직")
    후보 = []
    for 전직명, 정보 in 전직_레지스트리.get(직업, {}).items():
        if 전직명 == 내전직 or not 정보["구현"]:
            continue
        for 이름, 정의 in 정보["스킬목록"].items():
            if "훔쳐배우기스킬" in _타입들(정의) and 이름 not in 캐릭터["보유스킬"]:
                후보.append(_후보(이름, "스킬", 전직명, 정의))
    for 이름, 정의 in 직업_레지스트리[직업]["특성목록"].items():
        전직명 = 정의.get("전직")
        if (
            "훔쳐배우기스킬" in _타입들(정의)
            and 전직명
            and 전직명 != 내전직
            and 이름 not in 캐릭터["보유특성"]
        ):
            후보.append(_후보(이름, "특성", 전직명, 정의))
    return 후보


def _후보(이름, 종류, 전직명, 정의):
    return {
        "이름": 이름,
        "종류": 종류,
        "전직": 전직명,
        "설명": 정의.get("설명", ""),
        "정의": 정의,
    }


def 선택가능_퍽목록(캐릭터):
    """이 캐릭터가 지금 고를 수 있는 (퍽이름, 퍽정의) 목록 - 퍽_표시목록 중 회색이 아닌 것."""
    return [(이름, 정의) for 이름, 정의, 이유 in 퍽_표시목록(캐릭터) if not 이유]


def 퍽_표시목록(캐릭터):
    """퍽 선택 화면에 보일 [(퍽이름, 퍽정의, 회색 이유)] - 공용퍽(perks_class_0000) + 그 직업
    퍽목록 중 숨기는 것(퍽_선택상태 None)을 뺀다. 이유가 ""이면 고를 수 있다."""
    직업퍽 = 직업_레지스트리[캐릭터["직업"]]["퍽목록"]
    전체 = list(공용퍽.items()) + list(직업퍽.items())
    결과 = []
    for 이름, 정의 in 전체:
        이유 = 퍽_선택상태(캐릭터, 정의)
        if 이유 is not None:
            결과.append((이름, 정의, 이유))
    return 결과


def _스킬차수(스킬이름):
    """스킬의 차수 - 1차 계열 스킬목록이면 1, 1차 전직 스킬목록이면 2(skill_learn_system과
    같은 기준). 어느 목록에도 없으면 None."""
    for 정보 in 직업_레지스트리.values():
        if 스킬이름 in 정보["스킬목록"]:
            return 1
    for 전직들 in 전직_레지스트리.values():
        for 정보 in 전직들.values():
            if 스킬이름 in 정보["스킬목록"]:
                return 2
    return None


def 스킬강화_선택지(캐릭터, 레벨업항목=None):
    """ "스킬강화" 레벨에서 고를 수 있는 [(스킬이름, 설명)] - 보유스킬 중 차수가
    "최대차수" 이하인 것(보유 순서, 반응스킬 제외). 레벨업항목을 생략하면 다음 레벨업 항목을 쓴다."""
    항목 = 레벨업항목 or 캐릭터_다음_레벨업_항목(캐릭터)
    최대차수 = 항목["획득"]["최대차수"]
    모음 = 스킬데이터모음_생성()
    결과 = []
    for 이름 in 캐릭터["보유스킬"]:
        차수 = _스킬차수(이름)
        if (모음.get(이름) or {}).get("분류") == "반응스킬":
            continue  # 특성이던 때도 강화 대상이 아니었다
        if 차수 is not None and 차수 <= 최대차수:
            결과.append((이름, (모음.get(이름) or {}).get("설명", "")))
    return 결과


def 퍽_특성정의_찾기(캐릭터, 퍽정의):
    """퍽정의["획득특성"]의 실제 특성 정의를 그 직업의 특성목록에서
    먼저 찾고, 없으면 공용특성(job_ability_0000)에서 찾는다. "획득특성"이
    없는 퍽이면 None. 획득특성이 리스트면(란마 1/2) {이름: 정의}."""
    특성이름 = 퍽정의.get("획득특성")
    if 특성이름 is None:
        return None
    직업특성목록 = 직업_레지스트리[캐릭터["직업"]]["특성목록"]
    if isinstance(특성이름, list):
        return {n: 직업특성목록.get(n) or 공용특성.get(n) for n in 특성이름}
    return 직업특성목록.get(특성이름) or 공용특성.get(특성이름)


def 캐릭터_직업표시(캐릭터):
    """화면 표시용 직업 이름 - 전직했으면 전직명, 아니면 1차 계열 직업명."""
    return 캐릭터.get("전직") or 캐릭터["직업"]


def _전직_레벨업테이블(캐릭터, 전직명=None):
    전직명 = 전직명 or 캐릭터.get("전직")
    정보 = 전직_레지스트리.get(캐릭터["직업"], {}).get(전직명)
    return 정보["레벨업테이블"] if 정보 else None


def 선택가능_전직목록(캐릭터):
    """[(전직명, 설명, 구현여부)] - 그 직업의 1차 전직 목록(데이터 순서).
    구현된 전직의 설명은 레벨 6 항목의 "획득" 설명(얻는 특성), 미구현은
    "미구현"."""
    결과 = []
    for 전직명, 정보 in 전직_레지스트리.get(캐릭터["직업"], {}).items():
        if 정보["구현"]:
            항목 = 정보["레벨업테이블"].get(전직_시작레벨, {})
            결과.append((전직명, 항목.get("획득", {}).get("설명", ""), True))
        else:
            결과.append((전직명, "미구현", False))
    return 결과


def 캐릭터_전직_필요(캐릭터):
    """다음 레벨업이 전직(레벨 5 → 6)이라 전직 선택창을 띄워야 하는가
    (구현된 전직이 하나라도 있어야 한다)."""
    return (
        캐릭터["레벨"] + 1 == 전직_시작레벨
        and not 캐릭터.get("전직")
        and any(
            정보["구현"] for 정보 in 전직_레지스트리.get(캐릭터["직업"], {}).values()
        )
    )


def 캐릭터_다음_레벨업_항목(캐릭터, 전직명=None):
    """이 캐릭터가 다음에 배울 레벨업테이블(job_level_XX.py) 항목(다음
    레벨의 항목)을 반환한다. 레벨 5까지는 1차 계열 표, 레벨 6부터는
    전직 표를 쓴다(아직 전직 전이면 전직명을 넘겨야 레벨 6 항목이 나온다).
    그 레벨 데이터가 없으면 None."""
    다음레벨 = 캐릭터["레벨"] + 1
    if 다음레벨 >= 전직_시작레벨:
        표 = _전직_레벨업테이블(캐릭터, 전직명)
        return 표.get(다음레벨) if 표 else None
    레벨업테이블 = 직업_레지스트리[캐릭터["직업"]]["레벨업테이블"]
    return 레벨업테이블.get(다음레벨)


def 캐릭터_레벨업_가능(게임상태, 캐릭터):
    """캐릭터 레벨이 플레이어 레벨보다 낮고, 다음 레벨의 레벨업테이블
    항목이 있거나 전직 선택이 가능해야 [레벨업]을 시도할 수 있다."""
    if 캐릭터["레벨"] >= 게임상태["진행도"]["플레이어레벨"]:
        return False
    if 캐릭터_전직_필요(캐릭터):
        return True
    return 캐릭터_다음_레벨업_항목(캐릭터) is not None


def 캐릭터_레벨업_적용(캐릭터, **선택):
    """[레벨업] 확정 시 호출한다. 타입별로 필요한 선택 인자는
    character_levelup_system.캐릭터_레벨업()의 문서를 그대로 따라
    호출하는 쪽이 채워 넘긴다("스탯획득"=배분=.., "퍽획득"=퍽이름=..
    퍽정의=.. 등). 다만 "특성획득" 타입만은 특성정의모음(그 직업의
    전체 특성목록 - 캐릭터 생성 때와 동일)을 이 함수가 직접 채운다.

    도중에 실패하면(ValueError 등) 캐릭터는 하나도 바뀌지 않는다 - 전직 분기가
    전직/주문시전능력치/최대MP를 바꾼 뒤 레벨업이 실패하면 전직만 반쯤 적용되던
    문제(B5). 사본에 끝까지 적용한 뒤 성공하면 원본(같은 객체)에 옮긴다."""
    작업본 = copy.deepcopy(캐릭터)
    _캐릭터_레벨업_적용(작업본, dict(선택))
    캐릭터.clear()
    캐릭터.update(작업본)
    return 캐릭터


def _전직_이름(이름, 직업, 전직명):
    """전직 전 이름이 직업명(이름을 비웠을 때 붙는 A~D 포함)이면 - 직접 입력했어도 -
    직업 부분을 전직명으로 바꾼다(귀검사A -> 웨펀마스터A, 귀검사 -> 웨펀마스터).
    그 밖의 이름은 그대로."""
    if 이름 == 직업 or (이름[:-1] == 직업 and 이름[-1:] in ("A", "B", "C", "D")):
        return 전직명 + 이름[len(직업) :]
    return 이름


def _고른것_특성정의(캐릭터, 선택):
    """배울 때 고르는 퍽(훔쳐배우기 #279, 특성선택 - 포켓몬)의 고른 것을 확인하고, 특성이면 그 정의를 선택에 넣는다."""
    퍽정의 = 선택.get("퍽정의") or {}
    if 훔쳐배우기_퍽인가(퍽정의):
        고른것 = next(
            (h for h in 훔쳐배우기_후보(캐릭터) if h["이름"] == 선택.get("선택스킬")),
            None,
        )
        if 고른것 is None:
            raise ValueError(f"훔쳐배우기로 고를 수 없다: {선택.get('선택스킬')}")
        if 고른것["종류"] == "특성":
            선택["특성정의"] = 고른것["정의"]

    if 특성선택_퍽인가(퍽정의):
        고른것 = next(
            (
                h
                for h in 퍽_선택특성_후보(캐릭터, 선택["퍽정의"])
                if h["이름"] == 선택.get("선택특성")
            ),
            None,
        )
        if 고른것 is None:
            raise ValueError(f"고를 수 없는 특성: {선택.get('선택특성')}")
        선택["특성정의"] = 고른것["정의"]


def _캐릭터_레벨업_적용(캐릭터, 선택):
    전직명 = 선택.pop("전직", None)
    if 캐릭터_전직_필요(캐릭터):
        # 레벨 5 → 6: 전직 선택. 고른 전직의 레벨 6 항목으로
        # 레벨업하고, 전직 표에 "주문시전능력치"가 있으면 바꾼 뒤 기본최대MP
        # (25 + (레벨-1)×(3+주문시전보정치))를 다시 계산한다.
        정보 = 전직_레지스트리[캐릭터["직업"]].get(전직명)
        if not 정보:
            raise ValueError("전직을 선택해야 한다.")
        if not 정보["구현"]:
            raise ValueError(f"'{전직명}'은(는) 아직 구현되지 않은 전직이다.")
        레벨업항목 = 캐릭터_다음_레벨업_항목(캐릭터, 전직명)
        if 레벨업항목 is None:
            raise ValueError(f"'{전직명}'의 레벨 6 레벨업 항목이 없다.")
        캐릭터["전직"] = 전직명
        캐릭터["직업스타일"] = 정보.get("직업스타일") or "비전직"
        캐릭터["캐릭터명"] = _전직_이름(캐릭터["캐릭터명"], 캐릭터["직업"], 전직명)
        새스탯 = 레벨업항목.get("주문시전능력치")
        if 새스탯:
            # 기본최대MP는 레벨업 끝에서 새 주문시전능력치로 다시 계산된다.
            캐릭터["주문시전능력치"] = 새스탯
    else:
        레벨업항목 = 캐릭터_다음_레벨업_항목(캐릭터)
    if 레벨업항목 is None:
        raise ValueError("더 이상 배울 레벨업 항목이 없다.")

    레벨1_항목 = 직업_레지스트리[캐릭터["직업"]]["레벨업테이블"][1]
    레벨당체력증가 = 레벨1_항목["레벨당체력증가"]

    if 레벨업항목["타입"] == "특성획득":
        # 직업 특성 + 공용 특성(광검 마스터리처럼 착용과 함께 얻는 무기 마스터리)
        선택.setdefault(
            "특성정의모음",
            {**공용특성, **직업_레지스트리[캐릭터["직업"]]["특성목록"]},
        )
    if 레벨업항목["타입"] == "마스터리선택":
        선택.setdefault("특성정의모음", 전투용_캐릭터특성정의)
    if 레벨업항목["타입"] == "스타일선택" or 레벨업항목.get("스타일선택지"):
        선택.setdefault("스타일정의모음", 전투스타일)
    if 레벨업항목["타입"] == "스킬강화":
        선택.setdefault(
            "스킬강화선택지",
            [이름 for 이름, _ in 스킬강화_선택지(캐릭터, 레벨업항목)],
        )

    if 레벨업항목["타입"] == "퍽획득":
        _고른것_특성정의(캐릭터, 선택)

    # 고른 퍽 이름을 기록한다(파티원 화면 퍽 탭). 기록이 없던 캐릭터는
    # 먼저 지금까지의 퍽을 추정해 채운다(_보유퍽_추정).
    캐릭터_보유퍽(캐릭터)
    결과 = 캐릭터레벨업.캐릭터_레벨업(
        캐릭터,
        레벨업항목,
        레벨당체력증가,
        **선택,
    )
    if 레벨업항목["타입"] == "퍽획득" and 선택.get("퍽이름"):
        캐릭터["보유퍽"].append(선택["퍽이름"])
    return 결과


