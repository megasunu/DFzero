# 캐릭터_보유퍽만 "보유퍽" 키가 없을 때 추정값으로 채운다).
def 캐릭터_전체퍽(캐릭터):
    return {**공용퍽, **직업_레지스트리[캐릭터["직업"]]["퍽목록"]}


def _보유퍽_추정(캐릭터):
    """ "보유퍽" 기록이 생기기 전 캐릭터용 - 퍽이 주는 특성/스킬을 이미 가진
    퍽을 고른 것으로 본다. 능력치향상처럼 흔적이 남지 않는 퍽은 알 수 없다."""
    결과 = []
    for 이름, 정의 in 캐릭터_전체퍽(캐릭터).items():
        if 캐릭터레벨업.퍽_처리타입(정의) == "일반퍽":
            continue
        획득특성 = 정의.get("획득특성")
        획득스킬 = 정의.get("획득스킬")
        if (획득특성 and all(n in 캐릭터["보유특성"] for n in _이름들(획득특성))) or (
            획득스킬 and 획득스킬 in 캐릭터["보유스킬"]
        ):
            결과.append(이름)
    return 결과


def 캐릭터_보유퍽(캐릭터):
    if "보유퍽" not in 캐릭터:
        캐릭터["보유퍽"] = _보유퍽_추정(캐릭터)
    return 캐릭터["보유퍽"]
