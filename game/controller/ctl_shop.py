def 상점_일괄해체(게임상태, 레어도, 탭):
    """그 레어도 + 부위(또는 "전체")의 해체 가능한 장비를 전부 해체한다.
    (해체한 수, {재료: 개수}). 대상이 없으면 ValueError."""
