def 전문직업_봉인목록(게임상태, 모드):
    """[{"이름", "아이템", "탭", "캐릭터", "슬롯", "수량"}] - "봉인해제"는 봉인 장비, "봉인변환"은
    봉인을 푼 마법의 장비. 장착 중인 것(파티원/숙소 동료)은 캐릭터마다 한 줄."""
    return magic_seal_system.대상목록(
        플레이어뷰(게임상태),
        게임상태["상점카탈로그"]["장비"],
        모드,
        숙소=게임상태.get("모험단숙소", []),
    )


def _실행(게임상태, 항목, 처리):
    새이름 = 처리(플레이어뷰(게임상태), 항목)
    if 항목["캐릭터"] is not None:
        장비변경_후처리(게임상태)
    return 새이름


def 전문직업_봉인해제(게임상태, 항목):
    """봉인 장비 하나를 푼다(100G + 레어 소울 1). 새 이름. 모자라면 ValueError."""
    return _실행(게임상태, 항목, magic_seal_system.봉인해제)


def 전문직업_봉인변환(게임상태, 항목):
    """마법의 장비의 마봉능력을 다른 것으로(100G + 레어 소울 1). 새 이름."""
    return _실행(게임상태, 항목, magic_seal_system.봉인변환)


def 전문직업_인형목록(게임상태):
    """[인형사] 인형제작 목록 - [{"이름", "재료": [(재료, 필요, 보유)], "재료글", "제작가능"}]."""
    플레이어 = 플레이어뷰(게임상태)
    목록 = []
    for 이름, 인형 in 인형_데이터.items():
        재료 = player_system.재료_현황(플레이어, 인형["제작재료"])
        목록.append(
            {
                "이름": 이름,
                "재료": 재료,
                "재료글": ", ".join(f"{n} {보유}/{필요}" for n, 필요, 보유 in 재료),
                "제작가능": all(보유 >= 필요 for _, 필요, 보유 in 재료),
            }
        )
    return 목록


def 전문직업_인형상세(이름):
    """[인형사] 상세보기 줄들 - 이름, 직업스타일, HP/AC 수식(레벨 = 플레이어 레벨), 능력치, 명중/데미지보너스,
    행동표 1~6의 패턴 이름. 값은 item_doll.py 데이터 그대로(내아내몬 보정은 쓰지 않는다)."""
    인형 = 인형_데이터[이름]
    체력 = 직업_레지스트리[인형["체력"]]["레벨업테이블"][1]["레벨당체력증가"]
    기본체력 = f"({체력} + 건강보정)"
    return [
        f"이름: {인형['이름']}",
        f"직업스타일: {인형['스타일']}",
        f"HP = {기본체력} + 올림(레벨 × {기본체력} ÷ 2)",
        f"AC = {인형['기본AC']} + 민첩보정",
        "  ".join(f"{n} {v}" for n, v in 인형["능력치"].items()),
        f"명중보너스 {인형['명중보너스']:+d}   데미지보너스 {인형['데미지보너스']:+d}",
        *([f"무기: {인형['인형무기']} (바꿀 수 없음)"] if 인형.get("인형무기") else []),
        "패턴",
        *(f"{번호}. {패턴}" for 번호, 패턴 in sorted(인형["행동표"].items())),
    ]


def 전문직업_인형제작(게임상태, 이름):
    """인형 1개를 만든다 - 제작재료를 빼고 소지품 소모품에 넣는다(골드는 안 든다). 처음이면 도감에
    등록. 재료가 모자라면 ValueError(아무것도 바뀌지 않는다)."""
    player_system.재료로_제작(
        플레이어뷰(게임상태), "소모품", 이름, 인형_데이터[이름]["제작재료"]
    )
    collection_system.등록(게임상태["진행도"], "인형", 이름)


def 전문직업_강화목록(게임상태, 선택지):
    """[장비강화] 선택지(무기강화 등)의 대상 - [{"이름", "아이템", "탭", "캐릭터", "슬롯", "수량", "비용",
    "비용글", "불가"}]. 장착 중인 것(파티원/숙소 동료)은 캐릭터마다 한 줄. 커먼/봉인된 장비는 없다."""
    목록 = enhance_system.대상목록(
        플레이어뷰(게임상태),
        게임상태["상점카탈로그"]["장비"],
        선택지,
        숙소=게임상태.get("모험단숙소", []),
    )
    for 항목 in 목록:
        항목["비용글"] = enhance_system.비용글(항목["비용"])
    return 목록


def 전문직업_강화(게임상태, 항목, 선택지):
    """항목 하나를 1 올린다(항상 성공). 새 이름. 안 되거나 비용이 모자라면 ValueError."""
    return _실행(
        게임상태,
        항목,
        lambda 플레이어, 항목: enhance_system.실행(
            플레이어, 게임상태["상점카탈로그"]["장비"], 항목, 선택지
        ),
    )


def 전문직업_연금술목록(게임상태, 탭):
    """[연금술] 탭(전체/재료/소모품)의 목록 - [{"이름", "칸", "재료": [(재료, 필요, 보유)], "재료글", "제작가능",
    "레시피"}]. 한 번에 1개를 만든다."""
    플레이어 = 플레이어뷰(게임상태)
    목록 = []
    for 레시피 in alchemy_system.레시피목록(탭):
        재료 = player_system.재료_현황(플레이어, 레시피["재료"])
        목록.append(
            {
                "이름": 레시피["이름"],
                "칸": 레시피["칸"],
                "재료": 재료,
                "재료글": ", ".join(f"{n} {보유}/{필요}" for n, 필요, 보유 in 재료),
                "제작가능": all(보유 >= 필요 for _, 필요, 보유 in 재료),
                "레시피": 레시피,
            }
        )
    return 목록


def 전문직업_연금술(게임상태, 항목):
    """항목(전문직업_연금술목록의 한 줄) 하나를 1개 만든다 - 처음이면 도감에 등록. 재료가 모자라면
    ValueError(아무것도 바뀌지 않는다)."""
    alchemy_system.제작(플레이어뷰(게임상태), 항목["레시피"])
    collection_system.아이템_등록(게임상태["진행도"], 항목["칸"], 항목["이름"])
