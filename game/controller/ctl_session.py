def _새_게임_이름목록(파티구성):
    """파티구성의 최종 캐릭터 이름 목록. 입력 이름은 앞뒤 공백을 빼고
    캐릭터명_최대폭(한글 6자/영문 12자)으로 자르고, 비운 이름은 직업 이름(같은 직업 무명이 둘
    이상이면 A/B/C/D)으로 채운다. 최종 이름이 겹치면 ValueError - 장비/전투가
    이름으로 캐릭터를 구분하므로 같은 이름 둘은 서로 섞인다(B4)."""
    직업별_무명개수 = {}
    for 캐릭터명, 직업, *_ in 파티구성:
        if not (캐릭터명 or "").strip():
            직업별_무명개수[직업] = 직업별_무명개수.get(직업, 0) + 1

    이름목록 = []
    직업별_순번 = {}
    for 캐릭터명, 직업, *_ in 파티구성:
        입력이름 = 이름_자르기((캐릭터명 or "").strip())
        if 입력이름:
            이름 = 입력이름
        elif 직업별_무명개수[직업] > 1:
            순번 = 직업별_순번.get(직업, 0)
            직업별_순번[직업] = 순번 + 1
            이름 = f"{직업}{'ABCD'[순번]}"
        else:
            이름 = 직업
        if 이름 in 이름목록:
            raise ValueError(
                f"이름 '{이름}'이(가) 겹칩니다. 다른 이름을 입력해 주세요."
            )
        이름목록.append(이름)
    return 이름목록


def 새_게임_시작(파티구성):
    """파티구성 : [(캐릭터명, 직업), ...] 형태의 리스트(1~4명). 세 번째 칸에
    플레이어가 고른 스탯구성({"주스탯", "보조스탯", "약점스탯"})을 줄 수 있고,
    없으면 직업 기본값이다(덜 골랐으면 ValueError, 아무것도 안 만든다). 캐릭터명이
    빈 문자열이면 직업 이름을 그대로 쓰되, 이름을 비워둔 채 같은 직업을
    여러 명 고르면(예: 귀검사 두 명) 겹치는 이름끼리 알파벳(A/B/C/D)을
    붙여 구분한다 - "귀검사"/"귀검사" 대신 "귀검사A"/"귀검사B". 이름을 직접 입력한 경우는 그대로 쓰되,
    캐릭터명_최대폭(한글 6자/영문 12자, 섞으면 영문 2자 = 한글 1자)을 넘는
    부분은 잘라낸다. A/B/C/D는 이 제한과 별개로 붙는다. 캐릭터 생성 + 파티
    구성 + 시작 마을(엘븐가드) 진행도 초기화까지 한 번에 처리하고,
    화면들이 계속 들고 있을 "게임상태" 딕셔너리를 돌려준다. 최종 이름이
    겹치면 아무것도 만들지 않고 ValueError를 낸다(_새_게임_이름목록)."""
    파티 = party_system.빈_파티()
    이름목록 = _새_게임_이름목록(파티구성)
    # 다 만들어 본 뒤에 파티에 넣는다 - 스탯구성이 틀린 칸이 있으면 아무도 안 만든다
    캐릭터목록 = [
        캐릭터_생성(이름, 직업, *스탯구성)
        for 이름, (_, 직업, *스탯구성) in zip(이름목록, 파티구성)
    ]
    for 캐릭터 in 캐릭터목록:
        party_system.파티원_추가(파티, 캐릭터)

    진행도 = town_system.새_진행도()
    # town_system.새_진행도()에는 "플레이어레벨" 개념이 없어(캐릭터 레벨과
    # 별개로 던전 보스 클리어로 오르는 값) 여기서 직접 채운다. town_system.py(공용 시스템 파일)는 건드리지 않는다.
    진행도["플레이어레벨"] = 1
    진행도.update(achievement_system.빈_진행기록())  # 도감/업적 기록
    게임상태 = 새_게임상태(파티, 진행도)
    # 시작 장비도 소지품 "장비" 개수에 넣어 둔다 - 장비 교체 때 원래 끼던
    # 장비가 사라지지 않게(equipment_system.장착품_소지품_동기화).
    equipment_system.장착품_소지품_동기화(플레이어뷰(게임상태))
    for 이름 in 게임상태["소지품"]["장비"]:  # 시작 장비도 얻은 것 - 도감에 등록
        collection_system.아이템_등록(진행도, "장비", 이름)
    # 시작 장비의 스탯(건강/주문시전 능력치)까지 반영한 최대치로 시작한다.
    파티_최대치로_회복(게임상태)
    return 게임상태


def 게임_저장(게임상태, 슬롯번호):
    """마을이든 던전 안이든 저장한다 - 던전 안이면 던전 파일/위치/걸음수도 담는다."""
    던전 = 게임상태.get("던전상태")
    던전위치 = (
        {
            "던전파일명": 던전["던전파일명"],
            "위치": list(던전["위치"]),
            "걸음수": 던전.get("걸음수", 0),
        }
        if 던전
        else None
    )
    save_system.게임_저장(
        슬롯번호, 플레이어뷰(게임상태), 게임상태["진행도"], 던전위치=던전위치
    )


def _최대HP_재계산(캐릭터):
    레벨당 = 직업_레지스트리[캐릭터["직업"]]["레벨업테이블"][1]["레벨당체력증가"]
    캐릭터["기본최대HP"] = 캐릭터데이터.기본최대HP_계산(캐릭터, 레벨당)
    캐릭터["현재HP"] = min(캐릭터.get("현재HP", 0), 캐릭터["기본최대HP"])


def _직업스타일_성장_재계산(캐릭터):
    """직업스타일 성장(추가공격/최대MP) 도입 전 세이브 호환 - 직업스타일을 채우고,
    예전 레벨 10 "행동획득" 추가공격은 버린 뒤(추가공격획득 0) 다시 계산한다."""
    if "직업스타일" not in 캐릭터:
        캐릭터["직업스타일"] = 캐릭터_직업스타일(캐릭터) or "비전직"
        캐릭터["추가공격획득"] = 0
    캐릭터.setdefault("추가공격획득", 0)
    캐릭터["추가공격"] = 캐릭터데이터.추가공격_계산(캐릭터)
    캐릭터["기본최대MP"] = 캐릭터데이터.기본최대MP_계산(캐릭터)
    캐릭터["현재MP"] = min(캐릭터.get("현재MP", 0), 캐릭터["기본최대MP"])


def 게임_불러오기(슬롯번호):
    # 세이브 형식 호환(옛 구조, 빠진 키, 바뀐 특성 이름, 던전 파일명)은 save_system의
    # 버전별 마이그레이션이 이미 처리한 상태로 온다. 여기서는 형식이 아니라 "규칙"이
    # 바뀔 때마다 새 규칙으로 다시 계산해야 하는 값만 맞춘다.
    플레이어, 진행도 = save_system.게임_불러오기(슬롯번호)
    게임상태 = 새_게임상태(플레이어["파티"], 진행도)
    게임상태["소지품"] = 플레이어["소지품"]
    게임상태["선택된초상화"] = 플레이어["선택된초상화"]
    게임상태["모험단숙소"] = 플레이어["숙소"]
    for 캐릭터 in 게임상태["파티"]["파티원"] + 게임상태["모험단숙소"]:
        # 최대HP 공식이 바뀌면(2026-10-06 기본체력 + 올림(레벨x기본체력/2)) 불러올 때
        # 새 공식으로 다시 계산한다 - 현재HP는 새 최대치를 넘지 않게 자른다.
        _최대HP_재계산(캐릭터)
        _직업스타일_성장_재계산(캐릭터)
        # 레벨 1 스킬이 나중에 추가되면(2026-10-13 공중에뜸 스킬 5종) 옛 캐릭터에게도 준다.
        character_creation_system.레벨1_스킬_습득(
            캐릭터, 직업_레지스트리[캐릭터["직업"]]["스킬목록"]
        )
    equipment_system.장착품_소지품_동기화(플레이어뷰(게임상태))
    인형_동기화(
        게임상태
    )  # 인형 레벨/능력치 규칙(플레이어 레벨, 내아내몬)으로 다시 계산
    _던전위치_복원(게임상태, 플레이어.get("던전위치"))
    return 게임상태


def _던전위치_복원(게임상태, 던전위치):
    """던전 안에서 저장한 세이브면 그 던전의 그 위치로 던전상태를 다시 만든다(없는 던전이면 마을)."""
    if not 던전위치 or 던전위치.get("던전파일명") not in 던전_레지스트리:
        return
    던전 = dungeon_system.던전_시작(
        던전_레지스트리[던전위치["던전파일명"]],
        던전위치["던전파일명"],
        시작좌표=tuple(던전위치["위치"]),
        진행도=게임상태["진행도"],
    )
    던전["걸음수"] = 던전위치.get("걸음수", 0)
    게임상태["던전상태"] = 던전


