def 던전_진입(게임상태, 던전파일명):
    맵정보 = 던전_레지스트리[던전파일명]
    게임상태["던전상태"] = dungeon_system.던전_시작(
        맵정보,
        던전파일명,
        진행도=게임상태["진행도"],
    )
    return 게임상태["던전상태"]


def 연결지역_처리(게임상태, 연결정보):
    """ "#" 칸(연결지역)에 들어섰을 때 처리한다. 목적지가 마을이면 던전상태를
    비우고 현재마을을 그 마을로 바꿔 {"타입": "마을", "마을명": ...}을,
    다른 던전이면 "진입좌표"로 새 던전상태를 만들어 {"타입": "던전",
    "지도명": ...}을 돌려준다. 레지스트리에 없는 곳이면 {"타입": "미지원"}."""
    연결맵 = 연결정보.get("연결맵")
    if 연결맵 in 마을파일_레지스트리:
        # 던전 끝으로 나가면 그 연결점이 가리키는 마을로 돌아간다(예:
        # 머크우드 깊숙한곳 동쪽 끝 -> 헨돈마이어). 개방조건과 무관하게
        # 이동한다 - 그 던전에 들어와 있다는 것 자체가 이미 갈 수 있다는 뜻.
        게임상태["던전상태"] = None
        마을명 = 마을파일_레지스트리[연결맵]["마을명"]
        게임상태["진행도"]["현재마을"] = 마을명
        return {"타입": "마을", "마을명": 마을명}
    if 연결맵 in 던전_레지스트리:
        # 던전 -> 던전 연결(로리엔 -> 로리엔 안쪽, 숏컷 등). "진입좌표"로
        # 다음 던전에 들어간다.
        게임상태["던전상태"] = dungeon_system.던전_시작(
            던전_레지스트리[연결맵],
            연결맵,
            시작좌표=연결정보.get("진입좌표"),
            진행도=게임상태["진행도"],
        )
        return {"타입": "던전", "지도명": 던전_레지스트리[연결맵].get("지도명", 연결맵)}
    return {"타입": "미지원", "연결맵": 연결맵}


def 파티_인카운트없음(게임상태):
    """파티원 중 한 명이라도 "특수효과"에 "인카운트없음"이 있는 장비(치트용
    마법석)를 착용하고 있으면 True."""
    return any(
        (아이템 or {}).get("특수효과", {}).get("인카운트없음")
        for 캐릭터 in 게임상태["파티"]["파티원"]
        for 아이템 in 캐릭터_장비데이터(게임상태, 캐릭터).values()
    )


def 던전_이동(게임상태, 방향):
    """방향("위"/"아래"/"왼쪽"/"오른쪽")으로 한 칸 이동을 시도한다.
    dungeon_system.이동_시도()의 결과를 그대로 돌려주되, 이동 중 무작위
    인카운트가 뜨면 그 자리에서 전투를 시작하고 "결과"를 "전투시작"으로
    바꿔서 알려준다. "연결지역"(마을/다음 던전 연결)이 함께 오면
    화면 쪽에서 연결지역_처리()를 호출해 실제로 마을로 돌아갈지, 아직
    지원하지 않는 곳인지 판단한다. 파티_인카운트없음()이면 무작위
    인카운트가 없다(오브젝트/보스 등 이벤트 전투는 그대로)."""
    이동결과 = dungeon_system.이동_시도(
        게임상태["던전상태"], 방향, 인카운트없음=파티_인카운트없음(게임상태)
    )

    if 이동결과["결과"] == "오브젝트":
        return 이동결과

    if 이동결과["결과"] == "이동" and 이동결과.get("인카운트"):
        인카운트정보 = 게임상태["던전상태"]["맵정보"].get("인카운트") or {}
        전투상태 = 전투_시작(
            게임상태,
            이동결과["인카운트"]["등장몬스터"],
            레벨=인카운트정보.get("레벨"),
            차수=인카운트정보.get("차수"),
        )
        if 전투상태 is not None:
            return {"결과": "전투시작", "위치": 이동결과["위치"]}

    return 이동결과


def 오브젝트_상호작용(게임상태, 위치, 오브젝트):
    """ "@" 칸에 말을 걸었을 때 처리한다. 이번 프로토타입은 "보스전투"
    타입만 다룬다 - 보물상자 등 다른 타입은 아직 범위 밖이라 안내
    문구만 돌려준다."""
    if 오브젝트.get("타입") != "보스전투":
        return {"결과": "미지원", "설명": 오브젝트.get("설명")}

    전투상태 = 전투_시작(
        게임상태,
        오브젝트["전투몬스터"],
        클리어위치=위치,
        레벨=오브젝트.get("레벨"),
        차수=오브젝트.get("차수"),
    )
    if 전투상태 is None:
        return {"결과": "몬스터데이터없음"}
    return {"결과": "전투시작"}


def 이어진_맵_목록(게임상태):
    """지금 던전과 포탈로 이어진 다른 던전들(몇 단계를 건너도)을 화면에 함께
    그리기 위한 목록. 각 항목은 {"던전파일명", "지도", "타일", "오프셋"} -
    "지도"는 이벤트("@")를 감춰 발판("O")으로 바꾼 것, "오프셋"은 그 맵의 칸을
    지금 맵 좌표로 옮기는 (dx, dy). 가까운 맵이 앞에 온다(겹치면 앞이 우선,
    지금 맵이 가장 우선). 던전 밖이면 빈 목록."""
    던전상태 = 게임상태.get("던전상태")
    if not 던전상태 or 던전상태.get("던전파일명") not in 던전_레지스트리:
        return []
    목록 = []
    for 파일명, 오프셋 in dungeon_system.이어진_맵_배치(
        던전_레지스트리, 던전상태["던전파일명"]
    ):
        맵 = 던전_레지스트리[파일명]
        목록.append(
            {
                "던전파일명": 파일명,
                "지도": [행.replace("@", "O") for 행 in 맵["지도"]],
                "타일": 맵.get("타일") or {},
                "오프셋": 오프셋,
            }
        )
    return 목록


def _보스_그림(오브젝트):
    """보스전투 오브젝트의 보스 몬스터(칭호 "보스", 없으면 첫 몬스터) 그림 파일명."""
    몬스터들 = 오브젝트.get("전투몬스터") or []
    보스 = next((m for m in 몬스터들 if m.get("칭호") == "보스"), None)
    보스 = 보스 or (몬스터들[0] if 몬스터들 else None)
    if 보스 is None:
        return None
    return (몬스터목록.get(보스["이름"]) or {}).get("이미지")


def 던전_오브젝트_표시(게임상태):
    """지금 맵의 오브젝트를 화면에 그릴 정보로. 원본과 같되, 전용 "타일"(감옥 등)이 있는
    보스전투는 한 번 클리어했으면(진행도에 영구 기록) 그 타일 대신 보스 몬스터 그림을
    "보스그림"에 담는다 - 처음 만날 때만 감옥이고 다음부터는 보스가 보인다."""
    던전상태 = 게임상태.get("던전상태") or {}
    파일명 = 던전상태.get("던전파일명")
    결과 = {}
    for 좌표, 오브젝트 in (던전상태.get("맵정보", {}).get("오브젝트") or {}).items():
        표시 = dict(오브젝트)
        if (
            오브젝트.get("타입") == "보스전투"
            and 오브젝트.get("타일")
            and town_system.오브젝트_클리어됨(게임상태["진행도"], 파일명, 좌표)
        ):
            그림 = _보스_그림(오브젝트)
            if 그림:
                표시["보스그림"] = 그림
        결과[좌표] = 표시
    return 결과


# -------------------------------------------------------------- 던전 화면 스킬("분류":"던전스킬")
# 던전 화면 [스킬]에서 전투 밖에 쓴다(2026-10-19 사용자 결정 - 유루캠 "던전 캠핑"). 전투에서는
# skill_usage.사용_가능여부가 막는다. "휴식당횟수"는 전투 스킬과 같은 캐릭터["횟수제한스킬"]
# ["휴식제한스킬"]에 남은 횟수를 적고, 마을 휴식(town_system.휴식_처리)이 비운다.


def _던전스킬_쓸_때인가(게임상태):
    """던전 안이고 전투 중이 아닐 때."""
    return 게임상태.get("던전상태") is not None and 게임상태.get("전투상태") is None


def _휴식제한_칸(캐릭터):
    return 캐릭터.setdefault("횟수제한스킬", {}).setdefault("휴식제한스킬", {})


def _휴식_남은횟수(캐릭터, 스킬이름, 데이터):
    """(남은, 최대) - "휴식당횟수"가 없으면 None. 기록이 없으면 아직 안 쓴 것(최대)."""
    최대 = 데이터.get("휴식당횟수")
    if 최대 is None:
        return None
    return min(_휴식제한_칸(캐릭터).get(스킬이름, 최대), 최대), 최대


def _던전스킬_사유(캐릭터, 스킬이름, 데이터, 해제=False):
    """지금 쓸 수 없는 사유. 쓸 수 있으면 None. 해제(남은 효과를 풀기)는 횟수/MP를 보지 않는다."""
    if 캐릭터.get("현재HP", 0) <= 0:
        return "쓰러져서 쓸 수 없다."
    if 해제:
        return None
    남은 = _휴식_남은횟수(캐릭터, 스킬이름, 데이터)
    if 남은 is not None and 남은[0] <= 0:
        return f"휴식당 사용 횟수({남은[1]}회)를 모두 썼다. 마을에서 휴식하면 회복된다."
    if 캐릭터.get("현재MP", 0) < 데이터.get("MP소모", 0):
        return "MP가 부족하다."
    return None


def 던전스킬_목록(게임상태):
    """던전 화면 [스킬] 팝업의 줄들 - 파티원 순서, 보유 순서.
    [{"캐릭터", "스킬", "가능", "사유", "해제", "남은": (남은, 최대) | None, "MP", "전환", "설명"}].
    "해제"면 효과가 남아 있어 누르면 MP 없이 푼다(봉절). "전환"은 전환스킬(프렌지 - 특성 켜고 끄기)의
    지금 상태 "켜짐"/"꺼짐", 던전스킬이면 None.
    던전 밖(마을)이나 전투 중이면 빈 목록."""
    if not _던전스킬_쓸_때인가(게임상태):
        return []
    모음 = 게임상태["스킬데이터모음"]
    결과 = []
    for 캐릭터 in 게임상태["파티"]["파티원"]:
        for 이름 in 캐릭터.get("보유스킬") or []:
            데이터 = 모음.get(이름) or {}
            if 데이터.get("분류") not in ("던전스킬", "전환스킬"):
                continue
            if 데이터.get("분류") == "전환스킬":
                결과.append(_전환스킬_줄(캐릭터, 이름, 데이터))
                continue
            해제 = _해제할_효과(게임상태, 데이터) is not None
            사유 = _던전스킬_사유(캐릭터, 이름, 데이터, 해제)
            결과.append(
                {
                    "캐릭터": 캐릭터,
                    "스킬": 이름,
                    "가능": 사유 is None,
                    "사유": 사유,
                    "해제": 해제,
                    "남은": _휴식_남은횟수(캐릭터, 이름, 데이터),
                    "MP": 데이터.get("MP소모", 0),
                    "전환": None,
                    "설명": 데이터.get("설명", ""),
                }
            )
    return 결과


def _파티HP_최대회복(게임상태, 캐릭터, 값):
    """던전 캠핑 - 파티원 전체 HP를 장비 반영 최대치로(쓰러진 파티원도). MP/상태이상은 그대로."""
    for 파티원 in 게임상태["파티"]["파티원"]:
        파티원["현재HP"] = 캐릭터_최대HP(게임상태, 파티원)
    return "파티원 전체의 HP가 가득 찼다."


def _인카운트봉인(게임상태, 캐릭터, 값):
    """봉절 - 값(수식, 예: "10+레벨" - 쓴 캐릭터의 레벨) 걸음 동안 인카운트도 걸음수도 없다
    (dungeon_system.이동_시도가 던전상태["봉절걸음"]을 줄인다)."""
    걸음 = formula.올림(formula.수식_평가(str(값), {"레벨": 캐릭터.get("레벨", 1)}))
    게임상태["던전상태"]["봉절걸음"] = 걸음
    return f"{걸음}걸음 동안 적이 나타나지 않는다."


def _봉절_해제(게임상태):
    게임상태["던전상태"]["봉절걸음"] = 0
    return "봉절이 풀렸다."


# 던전스킬 "효과"의 키 -> 처리(게임상태, 쓴 캐릭터, 값) -> 화면 문구
_던전스킬_효과 = {"파티HP최대회복": _파티HP_최대회복, "인카운트봉인": _인카운트봉인}

# 효과가 남아 있으면 다시 쓸 때 MP/횟수 없이 푸는 효과 - 키 -> (남아 있나(게임상태), 풀기(게임상태) -> 문구)
_던전스킬_해제 = {
    "인카운트봉인": (lambda 상태: 상태["던전상태"].get("봉절걸음", 0) > 0, _봉절_해제)
}


def _해제할_효과(게임상태, 데이터):
    """스킬의 효과 중 아직 남아 있어 다시 쓰면 풀리는 것의 키. 없으면 None."""
    for 키 in 데이터.get("효과") or {}:
        if 키 in _던전스킬_해제 and _던전스킬_해제[키][0](게임상태):
            return 키
    return None


def 던전스킬_사용(게임상태, 캐릭터, 스킬이름):
    """던전 화면 [스킬]에서 캐릭터가 던전스킬을 쓴다. {"성공": bool, "문구": 화면 문구}.
    MP를 내고 휴식당 횟수를 하나 쓴 뒤 "효과"를 차례로 처리한다. 효과가 아직 남아 있으면
    (봉절) MP/횟수 없이 그 효과를 푼다."""
    데이터 = 게임상태["스킬데이터모음"].get(스킬이름) or {}
    if (
        not _던전스킬_쓸_때인가(게임상태)
        or 데이터.get("분류") not in ("던전스킬", "전환스킬")
        or 스킬이름 not in (캐릭터.get("보유스킬") or [])
    ):
        return {"성공": False, "문구": "지금은 쓸 수 없다."}
    if 데이터.get("분류") == "전환스킬":
        return _전환(캐릭터, 데이터)
    해제 = _해제할_효과(게임상태, 데이터)
    사유 = _던전스킬_사유(캐릭터, 스킬이름, 데이터, 해제 is not None)
    if 사유 is not None:
        return {"성공": False, "문구": 사유}
    if 해제 is not None:
        return {"성공": True, "문구": _던전스킬_해제[해제][1](게임상태)}
    캐릭터["현재MP"] = 캐릭터.get("현재MP", 0) - 데이터.get("MP소모", 0)
    남은 = _휴식_남은횟수(캐릭터, 스킬이름, 데이터)
    if 남은 is not None:
        _휴식제한_칸(캐릭터)[스킬이름] = 남은[0] - 1
    문구들 = [
        _던전스킬_효과[키](게임상태, 캐릭터, 값)
        for 키, 값 in (데이터.get("효과") or {}).items()
    ]
    이름 = 캐릭터.get("캐릭터명") or 캐릭터.get("직업", "")
    return {"성공": True, "문구": " ".join([f"{이름}의 '{스킬이름}'!"] + 문구들)}


