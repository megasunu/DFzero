# 같은 처리(_전환스킬_줄/_전환)를 쓴다: 행동/MP 없이 캐릭터 "켜진특성"만 바꾸고(켤때MP는 전투에서만),
# 그 칸은 세이브와 다음 전투로 그대로 이어진다.


def _전환스킬_줄(캐릭터, 이름, 데이터):
    """전환스킬 한 줄 - 던전스킬_목록과 같은 모양. "전환"은 지금 상태 "켜짐"/"꺼짐"."""
    사유 = "쓰러져서 쓸 수 없다." if 캐릭터.get("현재HP", 0) <= 0 else None
    켜짐 = 데이터.get("전환특성") in (캐릭터.get("켜진특성") or [])
    return {
        "캐릭터": 캐릭터,
        "스킬": 이름,
        "가능": 사유 is None,
        "사유": 사유,
        "해제": False,
        "남은": None,
        "MP": 0,
        "전환": "켜짐" if 켜짐 else "꺼짐",
        "설명": 데이터.get("설명", ""),
    }


def _전환(캐릭터, 데이터):
    if 캐릭터.get("현재HP", 0) <= 0:
        return {"성공": False, "문구": "쓰러져서 쓸 수 없다."}
    켜짐 = effect_engine.특성_전환(캐릭터, 데이터["전환특성"])
    이름 = 캐릭터.get("캐릭터명") or 캐릭터.get("직업", "")
    상태 = "켰다" if 켜짐 else "껐다"
    return {"성공": True, "문구": f"{이름}은(는) '{데이터['전환특성']}'을(를) {상태}."}
