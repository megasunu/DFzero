def 일반공격_가능여부(게임상태, 참가자):
    """[일반공격]을 낼 수 있나 - 열린 추가행동이나 일반행동이 남아 있으면."""
    return (
        resources.추가행동_남은수(참가자) > 0
        or 참가자["행동자원"].get("일반행동", 0) > 0
    )


def 아군_일반공격(게임상태, 대상참가자):
    """combat.attacks.일반공격_실행() 자체는 행동자원을 소모하지 않으므로(무기 명중/피해
    계산만 한다), 여기서 직접 낸다 - 이번 턴에 열린 추가행동이 있으면 그것을, 없으면 일반행동
    1개를 깎고 추가행동을 연다(DnD 추가 공격, combat.resources 추가행동). 원펀맨 특성이면 일반행동으로
    낸 일반공격에 남은 일반행동과 그 추가공격을 모두 합친다(resources.원펀맨_합치기)."""
    전투상태 = 게임상태["전투상태"]
    공격자 = 현재_턴_참가자(게임상태)
    if not 일반공격_가능여부(게임상태, 공격자):
        raise ValueError("일반행동이 남아있지 않다.")
    if not 대상참가자["생존"]:  # B12 - 부활 규칙이 없으므로 로직에서 거부한다
        raise ValueError(f"'{대상참가자['이름']}'은(는) 이미 쓰러져 지정할 수 없다.")
    배수 = 1
    if resources.추가행동_남은수(공격자) > 0:
        resources.추가행동_소모(공격자)
    elif traits.특성_수치(전투상태, 공격자, "원펀맨") > 0:
        배수 = resources.원펀맨_합치기(공격자)
    else:
        공격자["행동자원"]["일반행동"] -= 1
        resources.추가행동_열기(공격자, stats.추가공격_보너스(전투상태, 공격자))
    결과 = attacks.일반공격_실행(전투상태, 공격자, 대상참가자, 배수=배수)
    core.종료판정_갱신(전투상태)  # 마지막 적을 쓰러뜨렸으면 바로 끝낸다(B9)
    return 결과


def 아군_스킬사용(게임상태, 스킬이름, 중심대상=None, 지정대상목록=None, 행동지불=None):
    """지정대상목록: "적반복지정" 스킬에서 타격 순서대로 고른 대상 리스트.
    행동지불: 행동 선택 팝업에서 고른 수단(스킬_행동선택지 참고), 없으면 기본 순서."""
    전투상태 = 게임상태["전투상태"]
    시전자 = 현재_턴_참가자(게임상태)
    스킬데이터모음 = 게임상태["스킬데이터모음"]
    스킬데이터 = 스킬데이터모음[스킬이름]
    결과 = skill_system.스킬_실행(
        전투상태,
        시전자,
        스킬이름,
        스킬데이터,
        중심대상=중심대상,
        지정대상목록=지정대상목록,
        행동지불=행동지불,
    )
    core.종료판정_갱신(전투상태)  # B9
    return 결과


def 도망_막는_상태이상(게임상태):
    """생존한 아군 중 도망을 막는 상태이상("도망불가" 효과, 예: 구속)에
    걸린 사람마다 (이름, [상태이상 이름...])을 돌려준다. 한 명이라도
    있으면 파티 전체가 도망칠 수 없다. 빈 리스트면 도망칠 수 있다."""
    전투상태 = 게임상태["전투상태"]
    결과 = []
    for p in 아군_목록(게임상태):
        if not p["생존"]:
            continue
        이름들 = status.상태이상_플래그_이름들(전투상태, p, "도망불가")
        if 이름들:
            결과.append((p["이름"], 이름들))
    return 결과


def 아군_도망시도(게임상태):
    """현재 턴의 아군이 파티를 대표해 전투이탈(도망)을 시도한다. 판정식
    (DC = 10 + 생존한 적 중 가장 민첩한 개체의 민첩보정치)은
    combat.flow.전투이탈_시도()를 그대로 쓴다. 반환값도 그 함수와 동일 -
    (성공여부, 최종굴림값, 난이도).

    파티 중 한 명이라도 도망을 막는 상태이상이면 시도 자체를 거부한다
    (ValueError, 턴은 그대로). 판정에 실패하면 현재 캐릭터의 턴을 끝낸다
    (턴_넘기기 - 이어지는 몬스터 턴도 진행된다). 그래서 한 턴에 여러 번
    다시 시도할 수 없다(B1)."""
    전투상태 = 게임상태["전투상태"]
    현재 = 전투상태["참가자"][전투상태["현재턴"]]
    if 현재["진영"] != "아군" or not 현재["생존"]:
        raise ValueError("도망을 시도할 아군 차례가 아니다.")
    if 도망_막는_상태이상(게임상태):
        raise ValueError("도망 칠 수 없습니다.")
    결과 = flow.전투이탈_시도(전투상태, 현재)
    if not 결과[0]:
        턴_넘기기(게임상태)
    return 결과


def 무작위행동_상태인가(게임상태, 참가자):
    """만취처럼 "무작위행동" 상태이상이면 True(조종 불가, _만취_턴이 대신 행동)."""
    return bool(status.상태이상_플래그(게임상태["전투상태"], 참가자, "무작위행동"))


def _만취_대상후보(게임상태, 참가자):
    """자신을 뺀 생존 참가자 중 단일 대상으로 지정할 수 있는 쪽(적/아군 구분 없음)."""
    return [
        p
        for p in 게임상태["전투상태"]["참가자"]
        if p is not 참가자 and p["생존"] and not 지정불가_상태인가(게임상태, p)
    ]


def _만취_스킬후보(게임상태, 참가자):
    """지금 쓸 수 있는 보유 스킬 이름들(MP/쿨타임/행동자원/상태이상 검사 통과)."""
    스킬데이터모음 = 게임상태["스킬데이터모음"]
    return [
        이름
        for 이름 in 참가자["원본"].get("보유스킬", [])
        if 이름 in 스킬데이터모음 and 스킬_사용_가능여부(게임상태, 참가자, 이름)[0]
    ]


def _만취_스킬사용(게임상태, 참가자, 이름):
    """무작위 대상에게 스킬을 쓴다. 대상이 "자신"이면 자신에게, 단일 대상이면 적/아군 중
    무작위, "적3체"는 무작위 적이 중심, 범위/전체는 스킬이 정한 대로."""
    스킬데이터 = 게임상태["스킬데이터모음"][이름]
    타겟 = 스킬_실제_타겟(게임상태, 스킬데이터)
    후보 = _만취_대상후보(게임상태, 참가자)
    중심대상 = 지정대상목록 = None
    if 타겟 in ("적단일", "아군단일", "적또는아군단일"):
        if not 후보:
            raise ValueError("대상이 없다.")
        중심대상 = rng.대상.choice(후보)
    elif 타겟 == "적3체":
        적들 = [p for p in 후보 if p["진영"] == "적"]
        if not 적들:
            raise ValueError("대상이 없다.")
        중심대상 = rng.대상.choice(적들)
    elif 타겟 == "적반복지정":
        if not 후보:
            raise ValueError("대상이 없다.")
        횟수 = max(1, 현재참가자_수치(게임상태, 스킬데이터.get("공격횟수", 1)))
        지정대상목록 = [rng.대상.choice(후보) for _ in range(횟수)]
    return 아군_스킬사용(게임상태, 이름, 중심대상=중심대상, 지정대상목록=지정대상목록)


def _만취_턴(게임상태, 참가자):
    """만취 아군의 차례 - 플레이어 대신 한 번 행동한다(status_effects.py "만취").
    잠들어 있으면(행동불가) 아무것도 안 한다. 아니면 "수면확률"로 "수면지속턴" 범위의
    무작위 턴 동안 잠들고(이번 턴 포함), 그렇지 않으면 일반공격과 쓸 수 있는 스킬 중
    하나를 골라 무작위 대상에게 쓴다. 스킬이 실패하면 일반공격으로 대신한다."""
    전투상태 = 게임상태["전투상태"]
    전투상태["현재턴_행동완료"] = True
    if status.상태이상_플래그(전투상태, 참가자, "행동불가"):
        core.로그(
            전투상태,
            {"공격자": 참가자["이름"], "행동": "만취 - 잠들어 있다"},
            종류="행동",
        )
        return
    효과 = 상태이상목록["만취"]["효과"]
    if rng.확률.random() < formula.수식_평가(효과["수면확률"], {}):
        지속턴 = rng.주사위.randint(*효과["수면지속턴"])
        resources.몬스터_버프_부여(전투상태, 참가자, "수면", 지속턴)
        if status.상태이상_플래그(전투상태, 참가자, "행동불가"):
            참가자["행동자원"] = {"일반행동": 0, "보조행동": 0, "반응행동": 0}
        core.로그(
            전투상태,
            {"공격자": 참가자["이름"], "행동": f"만취 - 곯아떨어졌다(수면 {지속턴}턴)"},
            종류="행동",
        )
        return
    선택지 = ["일반공격"] + _만취_스킬후보(게임상태, 참가자)
    고른것 = rng.대상.choice(선택지)
    core.로그(
        전투상태, {"공격자": 참가자["이름"], "행동": f"만취 - {고른것}"}, 종류="행동"
    )
    if 고른것 != "일반공격":
        try:
            _만취_스킬사용(게임상태, 참가자, 고른것)
            return
        except ValueError:
            pass
    후보 = _만취_대상후보(게임상태, 참가자)
    if 후보 and 참가자["행동자원"].get("일반행동", 0) > 0:
        아군_일반공격(게임상태, rng.대상.choice(후보))


def 인형_턴(게임상태, 참가자):
    """인형의 차례 - 몬스터처럼 행동표(item_doll.py "행동표")에서 d6을 굴려 고른다. 스킬 이름이면
    그 스킬을 MP 소모 없이 살아 있는 적 하나에게 쓰고(넨탄 - 차수 = 플레이어 레벨의 차수), 아직
    없는(미정) 패턴이면 그 한 번은 쉰다. 행동불가면 아무것도 안 한다.
    "스타일"이 캐스터면 한 번, 밀리/하이브리드면 차수만큼 d6을 새로 굴려 행동한다(살아 있는 적이
    없거나 인형이 쓰러지면 남은 행동은 하지 않는다)."""
    전투상태 = 게임상태["전투상태"]
    전투상태["현재턴_행동완료"] = True
    if status.상태이상_플래그(전투상태, 참가자, "행동불가"):
        return
    인형 = 인형_데이터[참가자["원본"]["인형"]]
    횟수 = 1 if 인형.get("스타일", "캐스터") == "캐스터" else core.차수(참가자)
    for 번째 in range(횟수):
        대상후보 = 공격대상_목록(게임상태)
        if 번째 and (not 대상후보 or not 참가자["생존"]):
            return
        패턴 = 인형["행동표"][dice_utils.주사위_합(1, 6)]
        스킬데이터 = 게임상태["스킬데이터모음"].get(패턴)
        if 스킬데이터 is None or not 대상후보:
            core.로그(전투상태, {"공격자": 참가자["이름"], "쉼": True}, 종류="행동")
            continue
        skill_system.스킬_실행(
            전투상태,
            참가자,
            패턴,
            {**스킬데이터, "MP소모": 0},
            중심대상=rng.대상.choice(대상후보),
        )


def 턴_넘기기(게임상태):
    """현재 참가자의 턴을 끝낸다. 다음이 몬스터나 만취 아군이면 자동으로 행동시키고
    계속 넘겨서, 다시 조종할 아군 차례가 되거나 전투가 끝나면 멈춘다(화면 갱신
    타이밍 없이 한 번에 끝까지 진행한다).

    현재 참가자가 아직 행동하지 않은 몬스터나 만취 아군이면(선공 몬스터의 첫 턴, 이번
    턴에 만취가 된 아군) 먼저 행동시킨 뒤 넘긴다 - 그러지 않으면 그 턴이 행동 없이
    끝난다(B2)."""
    전투상태 = 게임상태["전투상태"]

    현재 = 전투상태["참가자"][전투상태["현재턴"]]
    if (
        전투상태["종료"] is None
        and 현재["생존"]
        and not 전투상태.get("현재턴_행동완료", True)
    ):
        if 현재["진영"] == "적":
            monster_actions.몬스터_턴_실행(전투상태, 현재)
        elif 현재.get("인형"):
            인형_턴(게임상태, 현재)
        elif 무작위행동_상태인가(게임상태, 현재):
            _만취_턴(게임상태, 현재)
        if core.종료판정_갱신(전투상태) is not None:
            return

    while True:
        참가자 = skill_system.다음_턴(전투상태)
        if 전투상태["종료"] is not None:
            return
        if 참가자.get("인형"):
            인형_턴(게임상태, 참가자)
        elif 참가자["진영"] == "아군":
            if not 무작위행동_상태인가(게임상태, 참가자):
                return
            _만취_턴(게임상태, 참가자)
        else:
            monster_actions.몬스터_턴_실행(전투상태, 참가자)
        if core.종료판정_갱신(전투상태) is not None:
            return


