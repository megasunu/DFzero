def 자동전투_방식_설정(값):
    """모르는 값이면 기본값(일반공격)."""
    _설정["자동전투방식"] = 값 if 값 in 자동전투_방식_목록 else 자동전투_방식_목록[0]


def 전투로그_방식():
    return _설정["전투로그방식"]


def 전투로그_방식_설정(값):
    """모르는 값이면 기본값(간략하게)."""
    _설정["전투로그방식"] = 값 if 값 in 전투로그_방식_목록 else 전투로그_방식_목록[0]


def 설정_파일_불러오기(경로):
    """설정 파일을 읽어 네 값을 넣고 읽은 설정을 돌려준다. 없거나 깨졌거나 모르는 값이면 기본값."""
    설정 = settings_system.설정_읽기(경로)
    반응_자동_설정(설정.get("반응자동", False))
    연계_자동_설정(설정.get("연계자동", True))
    자동전투_방식_설정(설정.get("자동전투방식"))
    전투로그_방식_설정(설정.get("전투로그방식"))
    return 설정


def 설정_파일_저장(경로, 키, 값):
    """설정 파일의 한 키만 바꿔 쓴다(다른 키는 그대로). 못 쓰면 False - 이번 실행에는 이미 반영돼 있다."""
    설정 = settings_system.설정_읽기(경로)
    설정[키] = 값
    return settings_system.설정_쓰기(경로, 설정)


