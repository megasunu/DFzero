def _몬스터항목_정규화(항목):
    """인카운트 결과("출현몬스터" 이름 문자열)와 오브젝트의
    "전투몬스터"({"이름":..,"칭호":..} 딕셔너리) 두 형태를 하나로
    맞춘다."""
    if isinstance(항목, str):
        return {"이름": 항목}
    return 항목


def _몬스터원본목록_생성(몬스터항목목록, 레벨=None, 차수=None):
    """레벨/차수를 주면 몬스터 원본 데이터 사본에 덮어쓴다 - 몬스터
    데이터(monster_race_*.py) 자신은 "레벨"/"차수"가 항상 None이고,
    실제 값은 던전 맵의 인카운트/오브젝트 데이터가 갖고 있다
    (monster_format.py 설명 참고). combat.participants.적_참가자_생성()이
    "최대HP"/"AC" 수식(예: "레벨×(6+건강보정치)")을 평가할 때 이 값을
    읽는다."""
    몬스터원본목록 = []
    for 원항목 in 몬스터항목목록:
        항목 = _몬스터항목_정규화(원항목)
        원본 = 몬스터목록.get(항목["이름"])
        if 원본 is None:
            # 종족별 몬스터 파일(monster_race_*.py)에 없는 몬스터
            # (원본에도 "미정" 상태인 몬스터일 수 있다) - 조용히 건너뛴다.
            continue
        덮어쓰기 = {}
        칭호 = 항목.get("칭호")
        if 칭호 is not None:
            덮어쓰기["칭호"] = 칭호
        if 레벨 is not None:
            덮어쓰기["레벨"] = 레벨
        if 차수 is not None:
            덮어쓰기["차수"] = 차수
        if 덮어쓰기:
            원본 = dict(원본, **덮어쓰기)
        몬스터원본목록.append(원본)
    return 몬스터원본목록


# [설정] 화면의 기기 설정 - 값은 화면이 기기 설정 파일(settings_system)에서 읽어 넣는다
# (설정_파일_불러오기). 키는 설정 파일의 키와 같다.
# 반응자동: False(기본)면 반응행동을 쓰는 반응을 화면이 팝업으로 묻는다(전투상태["반응선택"]
#   콜백). True면 묻지 않고 자동으로 쓴다.
# 연계자동: True(기본)면 연계스킬(수플렉스 썬더·귀참드라이브)을 행동/MP가 있으면 저절로 쓴다. False면 화면이
#   쓸지 묻는다(전투상태["연계선택"] 콜백, skill_attack.특성_후속공격 - 2026-10-22 사용자 결정).
# 자동전투방식: "일반공격"(일반공격 + 마법사 계열 매직미사일) / "전력전투"(스킬 우선, 전력전투_스킬).
# 전투로그방식: "간략하게"(지금 문장) / "자세하게"(굴림마다 기본값+추가값 계산 줄을 더한다).
자동전투_방식_목록 = ("일반공격", "전력전투")
전투로그_방식_목록 = ("간략하게", "자세하게")
_설정_기본값 = {
    "반응자동": False,
    "연계자동": True,
    "자동전투방식": 자동전투_방식_목록[0],
    "전투로그방식": 전투로그_방식_목록[0],
}
_설정 = dict(_설정_기본값)  # 테스트는 conftest가 매번 기본값으로 되돌린다


