def 전투시작_반응_처리(게임상태):
    """전투 화면에 들어온 뒤 미뤄 둔 전투시작 반응(패스티스트 건)을 처리한다."""
    reactions.전투시작_반응_처리(게임상태["전투상태"])


def 전투_시작(게임상태, 몬스터항목목록, 클리어위치=None, 레벨=None, 차수=None):
    몬스터원본목록 = _몬스터원본목록_생성(몬스터항목목록, 레벨=레벨, 차수=차수)
    if not 몬스터원본목록:
        return None

    인형_동기화(게임상태)  # 인형 레벨 = 지금 플레이어 레벨
    # 캐릭터명이 키라 전직으로 이름이 바뀌었을 수 있다 - 전투 전에 새로 만든다.
    게임상태["장비데이터모음"] = 장비데이터모음_생성(
        게임상태["파티"], 게임상태["상점카탈로그"]
    )
    게임상태["전투상태"] = flow.전투_시작(
        게임상태["파티"],
        몬스터원본목록,
        게임상태["장비데이터모음"],
        정의모음={
            "버프정의": 버프목록,
            "디버프정의": 디버프목록,
            "상태이상정의": 상태이상목록,
            "특성정의": 전투용_몬스터특성정의,
            "캐릭터특성정의": 전투용_캐릭터특성정의,
            "칭호정의": 칭호목록,
            "세트정의": 방어구세트목록,
            "스킬정의": 게임상태["스킬데이터모음"],
        },
        시작반응_보류=not _설정["반응자동"],
    )
    if (
        _설정["전투로그방식"] == "자세하게"
    ):  # 엔진이 계산 내역(명중/AC/피해/내성)도 담는다
        게임상태["전투상태"]["상세로그"] = True
    게임상태["전투_클리어위치"] = 클리어위치
    게임상태["전투_로그커서"] = 0
    return 게임상태["전투상태"]


def 현재_턴_참가자(게임상태):
    return flow.현재_턴_참가자(게임상태["전투상태"])


def 아군_차례인가(게임상태):
    """플레이어가 조종할 아군의 차례인가. 만취("무작위행동") 아군과 인형은 조종할 수 없어
    False - 화면은 몬스터 차례처럼 턴_넘기기로 진행하고, 그 행동은 _만취_턴/인형_턴이 한다."""
    참가자 = 현재_턴_참가자(게임상태)
    return (
        참가자["진영"] == "아군"
        and 참가자["생존"]
        and not 참가자.get("인형")
        and not 무작위행동_상태인가(게임상태, 참가자)
    )


def 채널링_확인대기(게임상태):
    """지금 차례 아군의, 아직 유지할지 묻지 않은 채널링 버프 이름들(넨가드 - 쓴 다음 턴 시작에 묻는다)."""
    참가자 = 현재_턴_참가자(게임상태)
    if 참가자 is None or 참가자.get("진영") != "아군":
        return []
    return [
        b["이름"]
        for b in damage.채널링_목록(참가자)
        if not b.get("채널링시전턴") and not b.get("채널링확인")
    ]


def 채널링_선택(게임상태, 유지):
    """채널링 유지 여부 - 유지하면 이번 턴이 끝날 때까지 남고(다른 행동을 하면 풀린다), 아니면 바로 푼다."""
    전투상태 = 게임상태["전투상태"]
    참가자 = 현재_턴_참가자(게임상태)
    for 항목 in damage.채널링_목록(참가자):
        항목["채널링확인"] = True
    if not 유지:
        damage.채널링_행동해제(전투상태, 참가자, 까닭="해제")


def 적_목록(게임상태):
    return [p for p in 게임상태["전투상태"]["참가자"] if p["진영"] == "적"]


def 공격대상_목록(게임상태):
    """아군이 공격할 대상 고르기 목록 - 살아 있는 적과 감옥(케라하 얼음감옥/비노슈 운석, 사용자 지정
    2026-10-14). 감옥은 적 그림 칸(적_목록)에는 그리지 않는다."""
    return [
        p
        for p in 게임상태["전투상태"]["참가자"]
        if p["생존"] and (p["진영"] == "적" or p.get("감옥"))
    ]


def 양쪽대상_목록(게임상태):
    """타겟 "적또는아군단일"(채찍질) 대상 고르기 목록 - 공격대상_목록 뒤에 살아 있는 아군."""
    return 공격대상_목록(게임상태) + [
        p for p in 게임상태["전투상태"]["참가자"] if p["생존"] and p["진영"] == "아군"
    ]


def 감옥_그림(게임상태, 아군참가자):
    """갇힌 아군의 그림 칸에 겹칠 감옥 그림 파일 이름(game/assets/monster/ 안) (뒤, 앞).
    뒤는 캐릭터 그림 뒤, 앞은 캐릭터 위에 그린다. 감옥이 없거나 부서졌으면 (None, None)."""
