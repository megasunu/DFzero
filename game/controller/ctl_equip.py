장비_슬롯목록 = list(equipment_system.슬롯별_분류.keys())


def 캐릭터_장착아이템(게임상태, 캐릭터, 슬롯):
    """슬롯에 장착 중인 아이템 데이터(없으면 None)."""
    return 캐릭터_장비데이터(게임상태, 캐릭터).get(슬롯)


def 장비_교체_탭목록(게임상태, 캐릭터, 슬롯):
    """교체 팝업의 분류 탭 - 무기는 [전체] + 그 캐릭터 기본 직업군(전직 전)의 무기 종류
    전부(지금 못 쓰는 종류 포함), 방어구는 [전체] + 재질, 그 밖은 탭 없음."""
    슬롯아이템들 = 게임상태["상점카탈로그"]["장비"].get(슬롯, {})
    return equipment_system.분류탭_목록(
        슬롯, list(슬롯아이템들.values()), 캐릭터["직업"]
    )


def 장비_교체_처음탭(게임상태, 캐릭터, 슬롯):
    """교체 팝업을 처음 열 때 고를 탭(#682) - 방어구는 캐릭터가 가진 "OO숙련" 재질의 탭(여러 개면 탭 순서로
    처음 것), 없으면 [전체]. 무기는 [전체], 탭 없는 부위는 None."""
    탭목록 = 장비_교체_탭목록(게임상태, 캐릭터, 슬롯)
    if not 탭목록:
        return None
    if 슬롯 in common_names.방어구_부위:
        for 탭 in 탭목록:
            if f"{탭}숙련" in 캐릭터.get("보유특성", []):
                return 탭
    return 탭목록[0]


# 세트 효과 표시 이름(상세보기) - 없는 키는 키 이름 그대로
_세트효과_표시 = {"AC보너스": "AC", "명중률보너스": "명중", "데미지보너스": "데미지"}


def 아이템_세트정보(게임상태, 아이템):
    """상세보기 아래에 적을 세트 설명(#682) - 세트 장비가 아니면 None. {"세트명", "구성": [장비 이름],
    "효과": ["AC +1", ...], "조건": 문자열}. "구성품"이 있는 세트(악세서리·레어 방어구)는 구성품 전부를 끼면
    발동한다. 커먼 방어구 세트는 이름 머리가 같은 장비들(브론델의 흉갑·각반·신발 - 주인 결정)을 구성으로
    적지만, 실제 발동은 그 재질 5부위를 모두 입을 때다(equipment_system._세트_충족) - 조건에 그렇게 적는다."""
    이름 = 아이템.get("강화원본", 아이템.get("이름"))
    장비 = 게임상태["상점카탈로그"]["장비"]
    for 세트 in 장비세트목록.values():
        if 이름 in (세트.get("구성품") or []):
            구성 = list(세트["구성품"])
            조건 = "구성 장비를 모두 착용하면 발동"
            break
        머리 = 세트["세트명"].removesuffix(" 세트")
        if (
            "구성품" not in 세트
            and 아이템.get("분류") in common_names.방어구_부위
            and 이름.startswith(머리 + " ")
        ):
            구성 = [
                n
                for 부위 in common_names.방어구_부위
                for n in 장비.get(부위, {})
                if n.startswith(머리 + " ")
            ]
            부위들 = "·".join(common_names.방어구_부위)
            조건 = f"{세트['타입']} 방어구 5부위({부위들})를 모두 착용하면 발동"
            break
    else:
        return None
    효과 = [
        f"{_세트효과_표시.get(키, 키)} {값:+d}" if isinstance(값, int) else f"{키} {값}"
        for 키, 값 in (세트.get("효과") or {}).items()
    ]
    return {"세트명": 세트["세트명"], "구성": 구성, "효과": 효과, "조건": 조건}


def 아이템_마법부여정보(아이템):
    """상세보기 맨 아래에 따로 적을 마법부여(#698) - {"이름", "설명"}, 부여하지 않은 장비면 None."""
    부여 = 아이템.get("마법부여")
    if not 부여:
        return None
    return {"이름": 부여["이름"], "설명": 부여["설명"]}


def 장비_교체_후보(게임상태, 캐릭터, 슬롯, 탭=equipment_system.전체_탭):
    """[(아이템데이터, 교체가능수량, 착용가능, 사유), ...] - 소지품에 남은
    그 부위 아이템 중 탭에 드는 것. 같은 직업군인데 아직 못 쓰는 무기(가용무기가
    아님)는 사유와 함께 나오고, 다른 직업군의 무기는 아예 나오지 않는다."""
    슬롯아이템들 = 게임상태["상점카탈로그"]["장비"].get(슬롯, {})
    후보 = equipment_system.교체_후보목록(
        플레이어뷰(게임상태),
        캐릭터,
        슬롯,
        슬롯아이템들,
    )
    if 슬롯 == "무기":
        후보 = [h for h in 후보 if equipment_system.무기_직업군(h[0]) == 캐릭터["직업"]]
    return [h for h in 후보 if equipment_system.분류탭_일치(h[0], 슬롯, 탭)]


def 장비변경_후처리(게임상태):
    게임상태["장비데이터모음"] = 장비데이터모음_생성(
        게임상태["파티"],
        게임상태["상점카탈로그"],
    )
    for 캐릭터 in 게임상태["파티"]["파티원"]:
        캐릭터["현재HP"] = min(캐릭터["현재HP"], 캐릭터_최대HP(게임상태, 캐릭터))
        캐릭터["현재MP"] = min(캐릭터["현재MP"], 캐릭터_최대MP(게임상태, 캐릭터))


def 장비_교체(게임상태, 캐릭터, 슬롯, 이름):
    """소지품의 이름 아이템으로 슬롯 장비를 바꾼다. 불가능하면 ValueError."""
    아이템 = 게임상태["상점카탈로그"]["장비"].get(슬롯, {}).get(이름)
    if 아이템 is None:
        raise ValueError(f"'{이름}'은(는) {슬롯} 슬롯 아이템이 아니다.")
    equipment_system.장비_교체(플레이어뷰(게임상태), 캐릭터, 슬롯, 아이템)
    장비변경_후처리(게임상태)


def 장비_해제(게임상태, 캐릭터, 슬롯):
    """슬롯을 비운다(장비는 소지품에 남는다). 무기는 일반공격에 꼭 필요해
    해제할 수 없다 - 다른 무기로 교체만 가능."""
    if 슬롯 == "무기":
        raise ValueError("무기는 해제할 수 없다. 다른 무기로 교체하세요.")
    equipment_system.장비_해제(캐릭터, 슬롯)
    장비변경_후처리(게임상태)


def 아이템_색분류(아이템):
    """이름 색을 정하는 분류 - 레어도("커먼"/"언커먼"/.../"치트") 또는 커먼 방어구 세트면 "세트"."""
    return equipment_system.아이템_색분류(아이템, 방어구세트목록)


def 아이템_찾기(게임상태, 이름):
    """상점 카탈로그(장비/소모품/재료)에서 이름으로 아이템 데이터를 찾는다. 없으면 None."""
    for 대분류 in 게임상태["상점카탈로그"].values():
        for 묶음 in 대분류.values():
            if isinstance(묶음, dict) and 이름 in 묶음:
                return 묶음[이름]
    return None
