def 로그_문장들(항목):
    """전투 로그 항목 하나(core.로그의 dict)를 화면에 보여 줄 문장 목록으로."""
    처리 = _종류별_문장.get(항목.get("종류")) if isinstance(항목, dict) else None
    if 처리 is None:
        return [str(항목)]
    남은쓰러짐 = list(항목.get("쓰러짐") or [])
    줄들 = 처리(
        항목, 항목.get("공격자", "?"), 항목.get("스킬") or 항목.get("패턴"), 남은쓰러짐
    )
    return 줄들 + [f"{_은는(n)} 쓰러졌다!" for n in 남은쓰러짐]
