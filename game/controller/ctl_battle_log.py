# 전투 로그 문장 (화면의 전투 기록 칸)
# =====================================================
# 엔진은 로그를 dict로 쌓고(core.로그), 화면은 여기서 만든 문장을 줄마다 보여 준다.
# 공격: "공격자의 공격이름!!" / "명중 명중값 vs AC 대상AC, 성공!(치명타!/실패!/대실패!)" /
#       "대상은 N의 데미지를 받았다." 또는 "대상은 공격을 피했다." - 명중 굴림마다 판정 줄 + 결과 줄.
# 내성: "DC 난이도 vs 굴린 값, 내성 성공!/실패!". 공격이 아닌 스킬/아이템: "시전자는 OO을 시전/사용했다!"
# 와 결과 줄. 쓰러지면 "대상은 쓰러졌다!"(core.로그가 붙인 "쓰러짐").

_받침있는_글자 = set("0136780LMNRlmnr")


def _받침(이름):
    """마지막 글자에 받침이 있는가(한글은 종성, 숫자/영문은 읽는 소리 기준)."""
    글자 = str(이름).rstrip()[-1:] or "가"
    if "가" <= 글자 <= "힣":
        return (ord(글자) - ord("가")) % 28 != 0
    return 글자 in _받침있는_글자


def _은는(이름):
    return f"{이름}{'은' if _받침(이름) else '는'}"


def _이가(이름):
    return f"{이름}{'이' if _받침(이름) else '가'}"


def _을를(이름):
    return f"{이름}{'을' if _받침(이름) else '를'}"


def _으로(이름):
    글자 = str(이름).rstrip()[-1:]
    ㄹ받침 = "가" <= 글자 <= "힣" and (ord(글자) - ord("가")) % 28 == 8
    return f"{이름}{'으로' if _받침(이름) and not ㄹ받침 else '로'}"


def _수(값):
    return int(값) if isinstance(값, float) and 값.is_integer() else 값


def _판정_줄(판정):
    if 판정.get("자연눈") is None and "명중결과" not in 판정:
        return "자동 명중!"
    if "명중결과" not in 판정:  # 옛 로그
        return "명중!" if 판정.get("성공") else "빗나감!"
    앞 = f"명중 {_수(판정['명중결과'])} vs AC {_수(판정['대상AC'])}"
    if 판정.get("자동실패"):
        return f"{앞}, 대실패!"
    if 판정.get("치명타") and 판정.get("성공"):
        return f"{앞}, 치명타!"
    # 반응(회피/가드)으로 피한 공격은 굴림 자체는 맞았다
    return f"{앞}, {'성공!' if 판정.get('성공') or 판정.get('반응회피') else '실패!'}"


def _내역_글(내역):
    return "+".join(f"{이름}({_수(값)})" for 이름, 값 in 내역)


def _명중_계산_줄들(판정):
    """자세하게 - 판정 줄 앞에 "주사위(15)+능력 보정(2)+버프(1)"과 "AC 계산: 기본(10)+장비(4)+..."
    (엔진이 상세로그일 때 담은 명중내역/AC내역이 있을 때만)."""
    줄들 = []
    if 판정.get("명중내역"):
        줄들.append(_내역_글(판정["명중내역"]))
    if 판정.get("AC내역"):
        줄들.append("AC 계산: " + _내역_글(판정["AC내역"]))
    return 줄들


def _피해_계산_줄들(내역):
    """자세하게 - "피해 계산: 식(굴린 값)+출처(값) = 합 → 최종 N"(방어/속성으로 바뀌었으면)."""
    if not 내역:
        return []
    글 = f"피해 계산: {내역['식']}({_수(내역['굴림합'])})"
    글 += "".join(f"+{이름}({_수(값)})" for 이름, 값 in 내역.get("추가", []))
    글 += f" = {_수(내역['합'])}"
    if 내역.get("최종") != 내역.get("합"):
        글 += f" → 최종 {_수(내역['최종'])}"
    return [글]


def _내성_계산_줄들(식, DC, 스탯, 보정, 값):
    return [
        f"DC 계산: {식} = {_수(DC)}",
        f"내성 계산: 주사위({_수(값 - 보정)})+{스탯} 보정({_수(보정)}) = {_수(값)}",
    ]


def _공격_한번_줄들(대상, 판정, 피해, 피해내역=None):
    """명중 굴림 한 번 - (계산 줄) / 판정 줄 / (피해 계산 줄) / 결과 줄."""
    줄들 = _명중_계산_줄들(판정) + [_판정_줄(판정)]
    if 판정.get("성공"):
        줄들 += _피해_계산_줄들(피해내역)
    return 줄들 + [_결과_줄(대상, 판정, 피해)]


def _결과_줄(대상, 판정, 피해):
    if 판정.get("반응회피"):
        return f"{_은는(대상)} {_으로(판정['반응회피'])} 공격을 피했다."
    if not 판정.get("성공"):
        return f"{_은는(대상)} 공격을 피했다."
    return f"{_은는(대상)} {피해}의 데미지를 받았다."


def _데미지_줄(대상, 피해):
    return f"{_은는(대상)} {피해}의 데미지를 받았다."


def _내성_줄(난이도, 값, 성공):
    return f"DC {_수(난이도)} vs {_수(값)}, 내성 {'성공' if 성공 else '실패'}!"


def _대상_이름들(대상):
    return ", ".join(대상) if isinstance(대상, list) else str(대상)


def _쓰러짐_넣기(줄들, 대상, 남은쓰러짐):
    if 대상 in 남은쓰러짐:
        남은쓰러짐.remove(대상)
        줄들.append(f"{_은는(대상)} 쓰러졌다!")


def _타격_문장(항목, 남은쓰러짐):
    줄들 = []
    if "폭사수" in 항목:  # 자폭 명령
        for 타격 in 항목["타격"]:
            줄들.append(f"{_이가(타격.get('폭사자', '?'))} 폭발했다!")
            줄들.append(_데미지_줄(타격["대상"], 타격.get("피해", 0)))
            _쓰러짐_넣기(줄들, 타격["대상"], 남은쓰러짐)
        return 줄들
    for 타격 in 항목["타격"]:
        대상 = 타격.get("대상") or 항목.get("대상", "?")
        if "내성" in 타격 and "판정" not in 타격:  # 내성 굴림 공격(포효 등)
            성공 = 타격["내성"] == "성공"
            if 타격.get("내성스탯") and 타격.get("내성값") is not None:  # 자세하게
                줄들 += _내성_계산_줄들(
                    항목.get("DC식", 항목.get("난이도")),
                    항목.get("난이도"),
                    타격["내성스탯"],
                    타격.get("내성보정", 0),
                    타격["내성값"],
                )
            if 타격.get("내성값") is not None:
                줄들.append(_내성_줄(항목.get("난이도"), 타격["내성값"], 성공))
            줄들.append(
                f"{_은는(대상)} 공격을 피했다."
                if 성공
                else _데미지_줄(대상, 타격.get("피해", 0))
            )
        else:
            판정 = 타격.get("판정") or {}
            # 스킬 타격 사이에 끼는 버프 추가 타격(잔영의 케이가) - 그 이름을 먼저 밝힌다
            if 타격.get("추가타격") and 타격["추가타격"] != 항목.get("스킬"):
                줄들.append(f"{타격['추가타격']}의 추가 공격!")
            if 타격.get("홀딩") and 판정.get("성공"):  # 피해는 대상의 차례 시작에(홀딩)
                줄들 += _명중_계산_줄들(판정) + [_판정_줄(판정)]
                줄들.append(
                    f"{_을를(대상)} 붙잡았다! 피해는 {_이가(대상)} 움직일 때 들어간다."
                )
            else:
                줄들 += _공격_한번_줄들(
                    대상, 판정, 타격.get("피해", 0), 타격.get("피해내역")
                )
            줄들 += [str(e) for e in 타격.get("효과로그") or []]
        _쓰러짐_넣기(줄들, 대상, 남은쓰러짐)
    return 줄들


def _아이템_문장(항목, 공격자, 이름, 남은쓰러짐):
    줄들 = [f"{_은는(공격자)} {_을를(항목['아이템'])} 사용했다!"]
    if 항목.get("결과"):
        줄들.append(str(항목["결과"]))
    return 줄들


def _일반공격_문장(항목, 공격자, 이름, 남은쓰러짐):
    """일반공격 1회, 반응 반격 - "판정" 하나."""
    대상 = 항목.get("대상", "?")
    줄들 = [f"{공격자}의 {항목.get('반응') or '일반공격'}!!"] + _공격_한번_줄들(
        대상, 항목["판정"], 항목.get("피해", 0), 항목.get("피해내역")
    )
    _쓰러짐_넣기(줄들, 대상, 남은쓰러짐)
    return 줄들


def _반응_문장(항목, 공격자, 이름, 남은쓰러짐):
    """가드/회피처럼 공격이 아닌 반응."""
    줄들 = [f"{_은는(공격자)} {_을를(항목['반응'])} 시전했다!"]
    if 항목.get("비고"):
        줄들.append(str(항목["비고"]))
    return 줄들


def _타격_목록_문장(항목, 공격자, 이름, 남은쓰러짐):
    """스킬/몬스터 패턴/소환수 공격 - 명중 굴림마다 줄."""
    줄들 = [f"{공격자}의 {이름 or '공격'}!!"] + _타격_문장(항목, 남은쓰러짐)
    if not 항목["타격"] and 항목.get("비고"):
        줄들.append(str(항목["비고"]))
    return 줄들


def _버프_문장(항목, 공격자, 이름, 남은쓰러짐):
    return [
        f"{_은는(공격자)} {_을를(이름)} 시전했다!",
        f"{_대상_이름들(항목.get('대상', []))}에게 "
        + ", ".join(f"'{b}'" for b in 항목["버프"])
        + " 부여",
    ]


def _회복_문장(항목, 공격자, 이름, 남은쓰러짐):
    대상 = 항목.get("대상") or []
    받는쪽 = 대상[0] if len(대상) == 1 else _대상_이름들(대상)
    return [
        f"{_은는(공격자)} {_을를(이름)} 시전했다!",
        f"{_은는(받는쪽)} {'' if len(대상) == 1 else '합계 '}{항목['총회복']} 회복했다.",
    ]


def _몬스터회복_문장(항목, 공격자, 이름, 남은쓰러짐):
    return [f"{_은는(공격자)} {_을를(이름)} 시전했다!"] + [
        f"{_은는(r.get('대상', '?'))} {r.get('회복', 0)} 회복했다."
        for r in 항목["회복"]
    ]


def _효과로그_문장(항목, 공격자, 이름, 남은쓰러짐):
    """해제 등 효과 스킬 - 엔진이 담은 "로그" 문장들."""
    return [f"{_은는(공격자)} {_을를(이름)} 시전했다!"] + [str(e) for e in 항목["로그"]]


def _지속공격등록_문장(항목, 공격자, 이름, 남은쓰러짐):
    return [
        f"{_은는(공격자)} {_을를(이름)} 시전했다!",
        f"{_대상_이름들(항목.get('대상', []))}에게 지속 공격이 걸렸다.",
    ]


def _지속공격발동_문장(항목, 공격자, 이름, 남은쓰러짐):
    대상 = 항목.get("대상", "?")
    줄들 = [f"{공격자}의 {이름} 지속 공격!", _데미지_줄(대상, 항목.get("총피해", 0))]
    _쓰러짐_넣기(줄들, 대상, 남은쓰러짐)
    if "판정 실패로 해제" in 항목.get("비고", ""):  # 엔진이 풀림을 비고 글에만 적는다
        줄들.append(f"'{이름}' 지속 공격이 풀렸다.")
    return 줄들


def _행동_문장(항목, 공격자, 이름, 남은쓰러짐):
    if 항목.get(
        "쉼"
    ):  # 행동주기 특성(돌연변이:거대화)으로 쉬는 차례 - 사용자 지정 2026-10-14
        return [f"{_은는(공격자)} 쉬고있다."]
    return [f"{공격자}: {항목['행동']}"]


def _비고_문장(항목, 공격자, 이름, 남은쓰러짐):
    """특성 발동, 지속피해형, 상태이상 부여/면역 등."""
    if (
        항목.get("비고") == "집요함"
    ):  # 빗나간 공격의 집요함(2026-10-15 사용자 지정 문장)
        줄들 = [f"집요한 공격으로 {항목.get('피해', 0)}의 데미지를 입었다."]
        _쓰러짐_넣기(줄들, 항목.get("대상"), 남은쓰러짐)
        return 줄들
    if 항목.get("비고") == "흡혈":  # damage._흡혈_발동 (2026-10-19)
        return [f"{_은는(공격자)} 흡혈로 HP를 {항목.get('회복', 0)} 회복했다."]
    머리 = 항목.get("공격자") or 항목.get("대상", "?")
    줄들 = [f"{머리}: {항목['비고']}"]
    내성 = 항목.get("내성")
    if isinstance(내성, dict):
        if 내성.get("스탯"):  # 자세하게
            줄들 += _내성_계산_줄들(
                내성["식"], 내성["DC"], 내성["스탯"], 내성["보정"], 내성["값"]
            )
        줄들.append(_내성_줄(내성["DC"], 내성["값"], 내성["성공"]))
    if "피해" in 항목 and "대상" in 항목:
        줄들.append(_데미지_줄(항목["대상"], 항목["피해"]))
        _쓰러짐_넣기(줄들, 항목["대상"], 남은쓰러짐)
    return 줄들


def _영창_문장(항목, 공격자, 이름, 남은쓰러짐):
    """몬스터 "영창패턴"(케라하 블리자드/비노슈 메테오) - 사용자 지정 2026-10-14."""
    return [f"{공격자}의 {이름}!", f"{_은는(공격자)} 주문영창을 시작했다!"]


def _날것_문장(항목, 공격자, 이름, 남은쓰러짐):
    """문장이 아직 없는 항목(몬스터 패턴의 자신버프해제/획득 - 이슈 #166)은 항목을 그대로 보인다."""
    return [str({k: v for k, v in 항목.items() if k != "종류"})]


