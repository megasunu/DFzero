def 캐릭터_생성(캐릭터명, 직업, 스탯구성=None):
    """레벨 1 캐릭터. 스탯구성은 플레이어가 고른 {"주스탯", "보조스탯",
    "약점스탯"}이고 생략하면 직업 기본값이다. 덜 골랐거나 겹치면 ValueError."""
    if 스탯구성 is not None:
        캐릭터생성.스탯구성_검사(스탯구성)
    return _캐릭터_만들기(캐릭터명, 직업, 스탯구성)


def 캐릭터_미리보기(직업, 스탯구성):
    """화면 미리보기(시작 HP/MP/능력치)용 캐릭터 - 고르는 도중이라 주/보조/
    약점이 비어 있어도 만든다(빈 역할은 10점). 게임상태에는 넣지 않는다."""
    return _캐릭터_만들기("", 직업, 스탯구성)


def _캐릭터_만들기(캐릭터명, 직업, 스탯구성):
    정보 = 직업_레지스트리[직업]
    레벨업테이블 = 정보["레벨업테이블"]
    레벨1_항목 = 레벨업테이블[1]

    획득특성이름들 = 레벨1_항목["획득"]["획득특성"]
    if isinstance(획득특성이름들, str):
        획득특성이름들 = [획득특성이름들]
    특성정의모음 = {이름: 정보["특성목록"][이름] for 이름 in 획득특성이름들}

    시작무기데이터 = 정보["무기목록"][레벨1_항목["시작장비"]]
    주문시전능력치 = 레벨1_항목.get("주문시전능력치")

    캐릭터 = 캐릭터생성.캐릭터_생성(
        캐릭터명,
        직업,
        레벨1_항목,
        특성정의모음,
        시작무기데이터,
        주문시전능력치=주문시전능력치,
        직업스킬목록=정보["스킬목록"],
        스탯구성=스탯구성,
    )

    # 레벨 1 그대로 시작한다.
    캐릭터["현재HP"] = 캐릭터["기본최대HP"]
    캐릭터["현재MP"] = 캐릭터["기본최대MP"]

    # 모험단 프로필(SD 초상화)의 성별 - 기본값은 귀검사만 "m", 나머지
    # 직업은 "f"이고, 모험단 화면에서 캐릭터별로 "m"/"f" 토글 가능. 이 값은
    # 캐릭터 딕셔너리에 그대로 붙어 파티원 목록과 함께 세이브된다.
    캐릭터["성별"] = "m" if 직업 == "귀검사" else "f"
    # 전직 전에는 None. 새 캐릭터와 불러온 캐릭터가 같은 모양이 되게 처음부터 넣는다
    # (게임_불러오기의 setdefault는 이 키가 없던 구버전 세이브용으로 남겨 둔다).
    캐릭터["전직"] = None

    return 캐릭터


def 장비데이터모음_생성(파티, 상점카탈로그):
    """캐릭터별 장비 데이터({캐릭터명: {슬롯: 아이템데이터}}). 캐릭터
    "장착장비"의 이름을 상점 카탈로그(무기는 5직업 무기 합본)에서 찾아
    실제 데이터로 바꾼다. 방어구/악세서리/특수장비도 들어가므로 전투의
    최종AC 계산 등에 장비 보너스가 반영된다. 빈 슬롯이나 데이터가 없는
    이름은 뺀다."""
    장비카탈로그 = 상점카탈로그["장비"]
    결과 = {}
    인형 = 파티.get("인형")
    if (
        인형
    ):  # 인형은 장비가 없다 - 이름 칸만 둔다(캐릭터_장비데이터가 다시 만들지 않게)
        결과[인형["캐릭터명"]] = {}
    for 캐릭터 in 파티["파티원"]:
        슬롯데이터 = {}
        for 슬롯, 이름 in 캐릭터["장착장비"].items():
            if not 이름:
                continue
            아이템 = 장비카탈로그.get(슬롯, {}).get(이름)
            if 아이템 is not None:
                슬롯데이터[슬롯] = 아이템
        결과[캐릭터["캐릭터명"]] = 슬롯데이터
    return 결과


# 캐릭터 데이터의 능력치/"기본최대HP"/"기본최대MP"는 장비를 뺀 값 그대로
# 두고, 화면 표시/휴식/던전 판정에서는 아래 함수로 장비(+방어구 세트)를
# 더한 값을 쓴다(equipment_system.장비반영_* 참고).
def 캐릭터_장비데이터(게임상태, 캐릭터):
    if 캐릭터["캐릭터명"] not in 게임상태["장비데이터모음"]:
        # 전직으로 이름이 바뀐 뒤(_전직_이름) - 새 이름으로 다시 만든다
        게임상태["장비데이터모음"] = 장비데이터모음_생성(
            게임상태["파티"], 게임상태["상점카탈로그"]
        )
    return 게임상태["장비데이터모음"].get(캐릭터["캐릭터명"], {})


def 캐릭터_유효능력치(게임상태, 캐릭터):
    """{능력치이름: 장비 반영 값} - 캐릭터에 남아 있는 상태이상(취기의 매력 감소 등)도 더한다."""
    능력치 = equipment_system.장비반영_능력치(
        캐릭터,
        캐릭터_장비데이터(게임상태, 캐릭터),
        방어구세트목록,
    )
    상태이상 = 캐릭터.get("상태이상") or []
    for 이름 in 능력치:
        능력치[이름] += drink_system.능력치_변동(
            상태이상, 상태이상목록, 이름, 캐릭터.get("보유특성")
        )
    return 능력치


def 캐릭터_능력치_보정치(게임상태, 캐릭터, 능력치이름):
    """던전 판정(오브젝트/함정 등)용 장비 반영 보정치."""
    return (캐릭터_유효능력치(게임상태, 캐릭터)[능력치이름] - 10) // 2


