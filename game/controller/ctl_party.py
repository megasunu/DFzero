def 이름_폭(글):
    return sum(1 if ord(글자) < 128 else 2 for 글자 in 글)


def 이름_자르기(글):
    """캐릭터명_최대폭을 넘지 않게 앞에서부터 자른다(겹침 방지 알파벳은 따로 붙는다)."""
    결과, 폭 = "", 0
    for 글자 in 글:
        폭 += 이름_폭(글자)
        if 폭 > 캐릭터명_최대폭:
            break
        결과 += 글자
    return 결과


