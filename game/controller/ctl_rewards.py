def _아이템_소지품_카테고리(게임상태, 이름):
    """상점 카탈로그에서 아이템 이름의 소지품 카테고리를 찾는다(없으면 None)."""
    for 대분류, 탭모음 in 게임상태["상점카탈로그"].items():
        for 탭, 아이템들 in 탭모음.items():
            if 이름 in 아이템들:
                return shop_system.소지품_카테고리(대분류, 탭)
    return None


def _전리품_대상(게임상태, 전투상태):
    """쓰러뜨린(도망치지 않은) 적의 원본 사본 - "드랍표"는 던전 공용 드랍표(맵정보
    "드랍표")를 앞에, 몬스터 개인 드랍표를 뒤에 붙인 것."""
    던전상태 = 게임상태.get("던전상태")
    던전드랍 = list((던전상태 or {}).get("맵정보", {}).get("드랍표") or [])
    return [
        {**p["원본"], "드랍표": 던전드랍 + list(p["원본"].get("드랍표") or [])}
        for p in 전투상태["참가자"]
        if p["진영"] == "적" and p.get("원본") and not p.get("도망")
    ]


def _전리품_지급(게임상태, 전투상태):
    """쓰러뜨린 적 전부의 획득골드/드랍표를 굴려 소지품에 넣고, 넣은 것을
    {"골드": n, "아이템": [(이름, 개수), ...]}로 돌려준다. 카탈로그에 없는
    아이템 이름은 지급하지도 보여주지도 않는다."""
    몬스터원본목록 = _전리품_대상(게임상태, 전투상태)
    전리품 = loot_system.전리품_판정(
        몬스터원본목록, 드랍표_모음, 게임상태["상점카탈로그"]["장비"]
    )
    전리품["아이템"] += [(이름, 1) for 이름 in _특별드랍(게임상태, len(몬스터원본목록))]
    플레이어 = 플레이어뷰(게임상태)
    if 전리품["골드"]:
        player_system.골드_추가(플레이어, 전리품["골드"])
    지급 = []
    for 이름, 개수 in 전리품["아이템"]:
        카테고리 = _아이템_소지품_카테고리(게임상태, 이름)
        if 카테고리 is None:
            continue
        player_system.아이템_추가(플레이어, 카테고리, 이름, 개수)
        collection_system.아이템_등록(게임상태["진행도"], 카테고리, 이름)
        지급.append((이름, 개수))
    return {"골드": 전리품["골드"], "아이템": 지급}


def _특별드랍(게임상태, 처치수):
    """던전 맵정보 "특별드랍"(스위트 민트 - #437) - "한번만"은 도감에 등록된 아이템이면 다시 나오지 않는다."""
    맵정보 = (게임상태.get("던전상태") or {}).get("맵정보") or {}

    def 얻은적있나(이름):
        카테고리 = _아이템_소지품_카테고리(게임상태, 이름)
        return bool(카테고리) and collection_system.아이템_등록됨(
            게임상태["진행도"], 카테고리, 이름
        )

    return loot_system.특별드랍_판정(맵정보.get("특별드랍"), 처치수, 얻은적있나)


보상_포기_골드 = 10


def _전투_보상_준비(게임상태, 전투상태):
    """승리한 전투의 몬스터 드랍표 후보에서 보상 3칸을 뽑아 둔다. 보상은 장비만이라
    장비가 아닌 이름(포션/투척 아이템/재료)과 카탈로그에 없는 이름은 후보에서 뺀다
    (무작위 드랍 _전리품_지급에는 그대로 나온다). {"칸": [이름 또는 None] x3, "완료": False}"""
    몬스터원본목록 = _전리품_대상(게임상태, 전투상태)
    후보 = [
        (이름, 가중치)
        for 이름, 가중치 in loot_system.보상_후보목록(
            몬스터원본목록, 드랍표_모음, 게임상태["상점카탈로그"]["장비"]
        )
        if _아이템_소지품_카테고리(게임상태, 이름) == "장비"
    ]
    return {"칸": loot_system.보상_뽑기(후보), "완료": False}


def 전투_보상_대기중(게임상태):
    """승리 후 전투 보상을 아직 받거나 포기하지 않았으면 True."""
    보상 = 게임상태.get("전투_보상")
    return 보상 is not None and not 보상["완료"]


def 전투_보상_칸(게임상태):
    """보상 칸 3개의 아이템 이름(빈칸은 None)."""
    보상 = 게임상태.get("전투_보상")
    return list(보상["칸"]) if 보상 else [None] * loot_system.보상_칸수


def 전투_보상_보유표시(게임상태, 이름):
    """보상 칸 아이템 이름 아래 줄 - 지금 갖고 있는 개수. 착용하지 않고 소지품에 있는 것은
    "보유 N", 누군가(파티원/숙소 동료) 착용 중인 것은 "착용 N", 둘 다 있으면 "보유 N / 착용 M",
    하나도 없으면 빈 글."""
    카테고리 = _아이템_소지품_카테고리(게임상태, 이름)
    소지 = (게임상태["소지품"].get(카테고리) or {}).get(이름, 0) if 카테고리 else 0
    착용 = equipment_system.장착중_개수(플레이어뷰(게임상태), 이름)
    보유 = max(0, 소지 - 착용)  # 소지품 장비 개수에는 착용 중인 것도 들어 있다
    조각 = []
    if 보유:
        조각.append(f"보유 {보유}")
    if 착용:
        조각.append(f"착용 {착용}")
    return " / ".join(조각)


def 전투_보상_부위(게임상태, 이름):
    """보상 칸 둘째 줄 - 장비는 부위(무기는 "무기(소검)"처럼 종류까지), 그 밖은 소지품 탭 이름."""
    for 대분류, 탭모음 in 게임상태["상점카탈로그"].items():
        for 탭, 아이템들 in 탭모음.items():
            if 이름 in 아이템들:
                타입 = equipment_system.무기_종류(아이템들[이름])
                return f"{탭}({타입})" if 탭 == "무기" and 타입 else 탭
    return ""


def 전투_보상_받기(게임상태, 칸번호):
    """칸번호(0 왼쪽/1 중앙/2 오른쪽)의 아이템 1개를 소지품에 넣는다. 나머지는 없다."""
    if not 전투_보상_대기중(게임상태):
        raise ValueError("받을 전투 보상이 없다.")
    보상 = 게임상태["전투_보상"]
    if not 0 <= 칸번호 < len(보상["칸"]) or 보상["칸"][칸번호] is None:
        raise ValueError("빈칸은 고를 수 없습니다.")
    이름 = 보상["칸"][칸번호]
    카테고리 = _아이템_소지품_카테고리(게임상태, 이름)
    player_system.아이템_추가(플레이어뷰(게임상태), 카테고리, 이름)
    collection_system.아이템_등록(게임상태["진행도"], 카테고리, 이름)
    보상["완료"] = True
    보상["받은아이템"] = 이름  # 전투_종료_문구가 전리품 줄에 함께 보여 준다
    return 이름


def 전투_보상_포기(게임상태):
    """보상을 고르지 않는 대신 보상_포기_골드를 받는다."""
    if not 전투_보상_대기중(게임상태):
        raise ValueError("받을 전투 보상이 없다.")
    player_system.골드_추가(플레이어뷰(게임상태), 보상_포기_골드)
    게임상태["전투_보상"]["완료"] = True
    return 보상_포기_골드


def 전투_종료_문구(게임상태, 종료결과):
    """전투 종료 팝업의 줄 목록. 전투_결과_정리() 뒤에 부른다(승리면 그때
    지급한 전리품을 보여준다)."""
    if 종료결과 == "적승리":
        return ["전투 패배!"]
    if 종료결과 == "전투이탈":
        return ["도망쳤다!"]
    if 종료결과 == "적도망":
        return ["적이 도망쳤다!"]
    전리품 = 게임상태.get("전투_전리품") or {"골드": 0, "아이템": []}
    줄들 = ["전투 승리!", "전리품"]
    if 전리품["골드"]:
        줄들.append(f"골드 {전리품['골드']}")
    아이템 = dict()  # 이름 -> 개수(드랍 순서 유지), 전투 보상으로 받은 것도 더한다
    for 이름, 개수 in 전리품["아이템"]:
        아이템[이름] = 아이템.get(이름, 0) + 개수
    받은것 = (게임상태.get("전투_보상") or {}).get("받은아이템")
    if 받은것:
        아이템[받은것] = 아이템.get(받은것, 0) + 1
    for 이름, 개수 in 아이템.items():
        줄들.append(이름 if 개수 == 1 else f"{이름} x{개수}")
    if len(줄들) == 2:
        줄들.append("없음")
    return 줄들


def 전투_결과_정리(게임상태):
    """전투가 끝난 뒤, 참가자 인스턴스에만 반영돼 있던 HP/MP를 캐릭터
    원본 데이터로 되돌려 쓴다. combat 패키지/skill_system.py는 이
    동기화를 하지 않는다 - 참가자 인스턴스는 전투 동안만 쓰는 사본이라,
    다음 전투/던전 진행에 반영하려면 호출하는 쪽이 직접 챙겨야 한다.

    승리 시, 이 전투가 던전 오브젝트(보스 등) 클리어로 시작됐다면
    dungeon_system.오브젝트_클리어_처리()(타일 상태 변경)와 함께
    town_system.오브젝트_클리어_기록()(진행도에 영구 기록 - 세이브에
    반영되고, dungeon_format.py "숏컷" 해금 조건에도 쓰인다)도 같이
    호출한다.

    승리하면 전리품(쓰러뜨린 적의 획득골드/드랍표)도 굴려 소지품에 넣고
    게임상태["전투_전리품"]에 남긴다(전투_종료_문구가 읽는다)."""
    전투상태 = 게임상태["전투상태"]
    종료결과 = 전투상태["종료"]

    for 참가자 in 아군_목록(게임상태):
        캐릭터 = 참가자["원본"]
        캐릭터["현재HP"] = 참가자["현재HP"]
        캐릭터["현재MP"] = 참가자["현재MP"]
        # 취기/만취처럼 전투 뒤에도 남는 상태이상만 캐릭터에 되돌려 쓴다
        캐릭터["상태이상"] = drink_system.유지_상태이상(
            참가자["상태이상"], 상태이상목록
        )
    인형 = 게임상태["파티"].get("인형")
    # 전투에서 쓰러진 인형은 사라진다(인형사) - 내아내몬이면 HP 0으로 남는다(캐릭터처럼)
    if 인형 and 인형["현재HP"] <= 0 and not 내아내몬_보유(게임상태):
        게임상태["파티"]["인형"] = None

    # 도감/업적: 처치한 적(도망 제외)은 결과와 상관없이 몬스터 도감에 등록하고, 이긴 전투
    # (적이 모두 도망친 "적도망" 포함)는 보스/일반으로 나눠 센다. 패배/내가 도망친 전투는 세지 않는다.
    진행도 = 게임상태["진행도"]
    for 적 in 전투상태["참가자"]:
        if 적["진영"] == "적" and not 적["생존"] and not 적.get("도망"):
            이름 = (적.get("원본") or {}).get("몬스터명")
            if 이름:
                collection_system.등록(진행도, "몬스터", 이름)
    if 종료결과 in ("아군승리", "적도망"):
        achievement_system.전투승리_기록(
            진행도, 보스=게임상태.get("전투_클리어위치") is not None
        )

    게임상태["전투_전리품"] = None
    게임상태["전투_보상"] = None
    if 종료결과 == "아군승리":
        게임상태["전투_전리품"] = _전리품_지급(게임상태, 전투상태)
        게임상태["전투_보상"] = _전투_보상_준비(게임상태, 전투상태)
        클리어위치 = 게임상태.get("전투_클리어위치")
        if 클리어위치 is not None:
            던전상태 = 게임상태["던전상태"]
            던전파일명 = 던전상태["던전파일명"]
            처음클리어 = not town_system.오브젝트_클리어됨(
                게임상태["진행도"],
                던전파일명,
                클리어위치,
            )
            dungeon_system.오브젝트_클리어_처리(던전상태, 클리어위치)
            town_system.오브젝트_클리어_기록(
                게임상태["진행도"],
                던전파일명,
                클리어위치,
            )
            # 던전의 보스전투 오브젝트 클리어 = 그 던전 클리어로 기록한다
            # - 헨돈마이어 "개방조건"(로리엔 안쪽 클리어)이 이
            # 기록을 읽는다(town_system.개방조건만족).
            town_system.던전_클리어_처리(게임상태["진행도"], 던전파일명)

            # 보스를 "처음" 클리어했을 때만 플레이어 레벨을 올린다(재도전은
            # 해당 안 됨 - 플레이어레벨업_트리거 참고). 캐릭터 개별 레벨은
            # 파티관리 화면에서 [레벨업]으로 직접 올려야 한다.
            목표레벨 = 플레이어레벨업_트리거.get((던전파일명, 클리어위치))
            if 처음클리어 and 목표레벨 is not None:
                게임상태["진행도"]["플레이어레벨"] = max(
                    게임상태["진행도"]["플레이어레벨"],
                    목표레벨,
                )

    게임상태["전투상태"] = None
    게임상태["전투_클리어위치"] = None
    게임상태["전투_로그커서"] = 0
    return 종료결과
