def _메카소환수(속성):
    """템페스트/게일포스 - 속성만 다르다. 1~3 머신건, 4~6 미사일. 둘 다 데미지보너스 +1, 명중보너스 +1
    (2026-11-22 사용자 결정 - 전에는 머신건 1d4, 미사일 1d8, 보너스 없음). 자폭에는 보너스가 없다."""
