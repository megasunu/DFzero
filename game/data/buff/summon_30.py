    return {
        "분류": "소환수",
        "타입": "메카소환",
        "태그": ["메카"],
        "지속": "자폭까지",
        "능력치참조": "시전자",
        "행동표": {눈: dict(머신건 if 눈 <= 3 else 미사일) for 눈 in range(1, 7)},
        "자폭공격": _메카공격("자폭", "(차수)d12+주문시전보정치", 속성),
    }


