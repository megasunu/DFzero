# 참고: "중첩":True 항목은 받을 때마다 별도 인스턴스로 추적한다
#       (스택 수·잔여 지속턴을 인스턴스별로 관리, 합산은 표시할 때만).
#
# 방어력 = 고정치 감소, 보호률 = 비율 감소
# (최종피해 = 원래피해/보호률 - 방어력)
#
# 효과 공통 키: "변동대상"(증감 항목), "변동값"(고정치 또는 수식, 양수=버프 방향).
#             debuff.py는 같은 "변동대상"에 부호만 반대로 쓴다.
#             "무기조건"(선택): 그 종류의 무기(eq_01_weapon_XX.py "타입")를 들고 있을
#             때만 그 효과 원소가 적용된다.
#             (버프 인스턴스 전체에 거는 무기 조건은 스킬의 "버프무기조건" - 예: 데스 바이
#             리볼버가 건 치명타피해증가/치명타확률증가는 리볼버를 들었을 때만 적용)
#             "효과"가 리스트면 원소마다 따로 적용된다.
#
# 변동대상 메모:
#   "치명타주사위" - 치명타 때 더 굴리는 피해 주사위 개수. 캐릭터/몬스터의
#                    "치명타주사위"(기본 1)에 이 값만큼 증감한다(stats.치명타_주사위수).
#   "피격펌블범위" - 이 효과를 가진 쪽을 공격할 때 공격자의 펌블범위에 더해진다
#                    (damage.유효_펌블범위). "펌블범위"는 내가 공격할 때의 펌블.
#   "집요함"       - 공격이 빗나가면(펌블 포함) 그 값만큼(데미지보너스 없이) 대상에게 피해를 준다. 일반 피해처럼 공격 속성,
#                    시전자의 속성강화, 대상의 방어력/보호률/저항/취약/속성내성을 받는다(damage.집요함_발동).
#                    버프/디버프/특성과 장비의 "집요함"(마봉능력 맹타)을 더한다. 몬스터도 같다.
#   "속성강화"     - 효과 원소의 "속성"(정식명 또는 "전체")으로 공격할 때 1당 최종피해
#                    +10%. "속성내성"은 그 속성 피해를 받을 때 1당 최종피해 -10%.
#                    강화와 내성은 합연산: 1 + 0.1 x (강화 - 내성), 내성이 크면 피해가 준다.
#                    화/수/명/암에만 붙고 무속성에는 없다("전체"도 무속성 제외).
#                    방어력/보호률 뒤에 곱하고 저항(0.5)/취약(2)/면역(0)과 곱연산
#                    (damage.속성_최종배율). 0 아래로는 안 내려간다.
#
