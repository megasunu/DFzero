# =====================
# NPC 데이터 양식
# =====================
# 마을 [NPC]에서 만나는 인물 하나의 구조를 정의하는 참고용 파일이다(실제 데이터는 없다).
# NPC마다 npc_<이름>.py 파일 하나에 "NPC정보" 딕셔너리 하나를 담는다 - 대사, 상점, 퀘스트 내용이 전부 여기 있다.
# 새 NPC 파일을 만들면 game/system/quest_system.py의 NPC 목록에 import + 추가를 손으로 한다(목록 순서 = 화면 순서).
# 규칙은 docs/game-rules.md "NPC / 퀘스트".

# =====================================================
# <NPC정보 항목 양식>
# =====================================================
#
# "이름"       : 문자열 (NPC끼리 겹치지 않는다)
# "마을"       : "모든마을" 또는 [마을명, ...] (town 파일의 "마을명")
# "대화조건"   : None(항상) 또는 <조건 항목> - 채우지 못하면 [NPC] 목록에 나오지 않는다
# "대화"       : 말을 걸면 하는 말
# "완료후대화" : (선택) 이 NPC의 퀘스트를 전부 끝낸 뒤 하는 말
# "일러스트"   : [대화] 장면에서 마을 배경 가운데에 띄울 그림. game/assets/npc/ 안의 파일명만 적는다.
#                "미정"이거나 파일이 없으면 그림 없이 대화창만 뜬다.
# "상점판매목록": [아이템 이름, ...] - 이 NPC의 [상점]이 파는 품목(마을 "상점판매목록"과 따로).
#                비어 있으면 [상점] 버튼이 없다.
# "퀘스트"     : [<퀘스트 항목>, ...] (없으면 빈 리스트, 비어 있으면 [퀘스트] 버튼이 없다)
#
# NPC 메뉴 팝업의 버튼은 [대화](늘) + [퀘스트](퀘스트가 있으면) + [상점](판매목록이 있으면).

# =====================================================
# <퀘스트 항목 양식>
# =====================================================
#
# {
#     "ID"   : 문자열 (세이브의 진행도["퀘스트"] 키 - 바꾸면 세이브 변환이 필요하다. 모든 NPC에서 겹치지 않는다)
#     "이름" : 화면에 보이는 이름
#     "설명" : 할 일
#     "조건" : 완료 조건 <조건 항목>
#     "보상" : {"골드": 정수}
# }

