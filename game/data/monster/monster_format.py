# 플레이어 성장(보정치, 명중률, 몬스터 방어력)에 맞춰 몬스터 AC가 얼마여야
# 무기 다이스(1d8/1d10/1d12/2d6) 간 기대데미지 격차가 가장 작은지 계산한 기준표.
#
# <성장 공식>
# 기준 무기: 1d8 (명중률보너스 없음, 무기공격력 기준)
# 보정치 = 차수 + 1   (공격/명중에 모두 적용되는 능력치 보정치)
# 명중률 = 차수 - 1   (데미지에는 안 붙고 명중에만 붙는 별도 성장치, 프리셔런시 보너스 개념)
# 방어력 = 차수       (몬스터가 매 피격마다 데미지를 깎는 값, 최종 데미지는 0 미만으로 안 내려감)
# → 1차수는 보정치2/명중률0/방어력1로 시작하고, 차수마다 셋 다 1씩 오른다.
#
# <무기별 명중률보너스> (다이스가 클수록 명중이 나빠지는 트레이드오프)
# 1d8  = 0   (기준)
# 1d10 = -2
# 1d12 = -4
# 2d6  = -4  (1d12와 동일 취급)
# ※ 1d4/1d6 계열은 이 등급별 페널티 대상이 아니고, 무기 타입별 개별 플레이버 보너스만 따로 붙는다.
#
# <계산 조건>
# - 명중굴림 = 1d20 + 보정치 + 명중률 + 무기별 명중률보너스
# - 데미지 = max(0, 무기주사위 + 보정치 - 방어력)  (자연1 항상 빗나감 / 자연20 항상 명중 + 주사위만 2배 치명타)
# - "격차"는 같은 AC에서 네 무기(1d8/1d10/1d12/2d6)의 기대데미지 중 최대값-최소값

