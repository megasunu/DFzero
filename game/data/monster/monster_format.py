# 몬스터 역할군별 체력·AC 공식
# =====================
# 몬스터는 "탱커"/"딜러"/"메이지" 셋 중 하나의 역할군으로 분류되고,
# 최대HP와 AC는 고정값을 직접 적지 않고 아래 공식으로 계산한다.
#
# 공식에 쓰이는 "레벨"과 "차수"는 몬스터 자신의 데이터(monster_tier_XX.py)에
# 고정되어 있지 않다 - 같은 몬스터라도 등장하는 던전에 따라 레벨/차수가
# 달라질 수 있어서, 실제 값은 던전 맵의 인카운트/오브젝트 데이터 쪽에서
# 정한다 (dungeon_format.py의 <인카운트 항목 양식>, <오브젝트 항목 양식> 참고).
# 몬스터는 한 턴에 차수만큼 행동한다 - 매번 1~6번 패턴을 새로 굴려 각각 쓴다(2026-10-14 사용자 지정).
# 그래서 패턴의 데미지/회복량 식에는 차수 계수를 쓰지 않는다(턴 시작/종료 처리는 턴마다 한 번).
#
# monster_tier_XX.py 쪽 "레벨"/"차수" 필드는 그래서 기본값 None으로 비워
# 두고, 실제 전투에 들어갈 때 던전 맵이 지정한 값으로 채운다.
#
# "건강보정치"는 그 몬스터 자신의 "건강" 능력치에서 나오는 보정치다
# (D&D 5판 방식: (건강 - 10) // 2, 내림).
#
# <최대HP 공식> - 기본체력 + 올림(레벨 × 기본체력 / 2) (아군과 같은 공식)
# 탱커   : 기본체력 = 6 + 건강보정치
# 딜러   : 기본체력 = 5 + 건강보정치
# 메이지 : 기본체력 = 4 + 건강보정치
# (올림은 총합에 한 번만. 수식의 "올림(...)"은 combat.formula.수식_평가가 처리한다)
#
# <AC 공식> - 역할군 모두 9 + 차수 + 민첩보정치(1차수면 기본 10). 2026-10-14 사용자 지정 -
# 전에는 탱커 7+2×차수 / 딜러 7+차수 / 메이지 6+차수였다. 역할군 차이는 AC가 아닌 다른 쪽에서 둔다.
#
# <데미지보너스 / 명중률보너스> - 역할군이 정하는 공격 보정(2026-10-07 사용자 지정)
# 탱커   : 데미지 -1, 명중 -1
# 딜러   : 0, 0
# 메이지 : 데미지 0, 명중 +1 (서포터 역할)
# 몬스터 데이터 파일의 "데미지보너스"/"명중률보너스"는 역할군을 반영하지 않은 기본값(0)이고,
# 전투에서 역할군 값이 더해진다(monster_actions.몬스터_데미지보너스, damage.명중_판정_계산).
# 명중에는 역할군과 따로 +차수가 붙는다(모든 적 몬스터, 2026-11-03 사용자 결정 #534 -
# participants.몬스터_차수_명중보너스).
#
# 몬스터 데이터의 "최대HP"/"AC"는 None으로 비워 두고, 전투에 들어갈 때
# 몬스터의 "역할군"으로 아래 역할군공식에서 수식을 가져와 평가한다
# (game/system/combat/participants.py의 몬스터_역할군_수식). 몬스터별 예외는
# 없다 - 데이터에 값을 적어도 쓰지 않는다(2026-09-30 사용자 지정).
# 역할군이 없거나 표에 없는 값이면 최대HP 1, AC 10으로 등장한다.

