# =====================
# 몬스터 드랍표 항목 양식
# =====================
# 드랍은 던전 공용 드랍(맵정보 "드랍표" - dungeon_format.py)과 몬스터 개인 드랍
# (여기 "드랍표")으로 나뉜다. 몬스터 쪽에는 그 몬스터만 주는(공용이 아닌)
# 드랍표만 적는다(예: 황금 고블린의 "황금고블린군"). 둘 다 같은 형식이고,
# 전투에서 쓰러뜨린 몬스터마다 던전 + 개인 드랍표를 모두 굴린다.
#
# 드랍 데이터는 두 단계로 나뉜다.
#   1) "드랍표" 참조 (몬스터 monster_race_XX.py / 던전 맵정보) - 어떤 드랍표를 몇 % 확률로 굴릴지
#   2) 드랍표 본문 (monster_drop.py "드랍표_모음") - 그 드랍표에서 무엇이 나오는지
#
# <1) 몬스터 쪽 "드랍표">
# 몬스터 항목의 "드랍표"는 {"이름", "발동확률"} 딕셔너리의 리스트다.
#   "이름"     : monster_drop.py "드랍표_모음"의 키 (예: "커먼장비군")
#   "발동확률" : 0~1 사이 숫자 (예: 0.3 = 30%). 아직 정하지 않았으면 "미정".
# 리스트의 각 항목은 서로 독립적으로 판정한다 - 여러 드랍표가 동시에 발동할
# 수도, 하나도 발동하지 않을 수도 있다.
#   예) "드랍표": [
#           {"이름": "커먼장비군", "발동확률": 0.3},
#       ],
#
# <2) 드랍표 본문 - monster_drop.py>
# 발동한 드랍표는 monster_drop.py에서 이름으로 찾고, 그 표의 "타입"에 따라
# 아이템을 뽑는다.
#   "가중형" : 표 안에서 아이템 하나만 뽑는다. 각 아이템의 "드랍비율"
#              (예: "1/25")이 가중치다.
#   "독립형" : 표 안 아이템을 각각 따로 굴려 통과한 것을 전부 얻는다.
#              각 아이템의 "드랍확률"이 그 아이템의 실제 확률이다.
# 아이템은 "아이템이름"(특정 아이템 하나), "아이템조건"(범위 지정), "드랍표"(다른 드랍표
# 이름 - 뽑히면 그 표를 굴린다) 중 하나로 적는다.
#   "아이템조건": {
#       "카테고리": "방어구",   (eq_02_armor_XX.py 5개 파일 - 상의/하의/어깨/
#                                벨트/신발 - 전체를 뜻하는 조건 전용 키워드.
#                                실제 아이템 데이터의 "분류" 값과는 다르다.)
#       "레어도"  : "커먼",     (아이템의 "레어도" 값과 비교)
#       "티어"    : 1,         (아이템의 "티어" 값과 비교)
#   }
#   → 조건에 맞는 아이템 중 하나를 균등 확률로 고른다는 뜻이다.
# 드랍표 본문의 자세한 예시는 monster_drop.py 머리 설명 참고.
#
# 전투 승리 후 쓰러뜨린 적마다 "획득골드"와 이 드랍표를 굴려 소지품에
# 넣는다(game/system/loot_system.py, gameflow.전투_결과_정리). "미정"인 드랍표
# 값은 드랍 없음으로 처리한다.
#
# "적등급" : "일반" | "엘리트" | "네임드"  (골드 공식의 등급배수. "미정"은 일반과 같다)
# "획득골드" : "공식" - 골드 공식(아래). 수식 문자열(예: "(10+레벨)×10" - 황금 고블린)이나
#              정수/"1~10" 범위도 쓸 수 있다. "미정"이면 0.
#   골드 공식 = (10 + 레벨) × 등급배수 × 보스배수 × 랜덤(0.7~1.3), 반올림
#     등급배수: 일반 1, 엘리트 1.5, 네임드 2 / 보스배수: 칭호 "보스"면 2, 아니면 1
#     랜덤(0.7~1.3)은 수식/고정값으로 정한 골드에도 똑같이 곱한다.
