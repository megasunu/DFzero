# =====================
# 공용 정의 / 퍽 양식
# =====================
# perks_class_XX.py 파일들의 공통 구조를 모아둔 참고용 파일이다. 실제
# 데이터는 없다. 실제 퍽 파일 6개와 character_levelup_system.py /
# gameflow.py의 퍽 처리 코드를 기준으로 정리했다.
#
# 퍽으로 얻는 스킬의 상세 정의는 job_skill_XX.py의 "스킬목록"에,
# 퍽으로 얻는 특성의 상세 정의는 job_ability_XX.py의 "특성목록"에 둔다.
# 퍽 파일에는 "무엇을 얻는지"만 적고, 얻은 것의 실제 효과는 적지 않는다.
# (스킬 양식은 job_skill_format.py, 특성 양식은 job_ability_format.py 참고)

# =====================
# 파일 구조
# =====================
# 각 파일은 "퍽목록" 딕셔너리 하나만 담는다. 키는 퍽 이름(문자열),
# 값은 <퍽 항목 양식>이다.
#
# 파일 이름은 perks_class_{분류번호}.py 이다.
#   perks_class_0000.py - 공용 퍽 (모든 직업이 고를 수 있다)
#   perks_class_XXXx.py - 직업 계열 퍽 (예: 010m 귀검사, 020f 격투가,
#                         030f 거너, 040f 마법사, 050f 프리스트)
# (분류번호 규칙은 job_level_format.py <차수 구분> 참고)
#
# 레벨업 테이블의 "퍽획득" 레벨(각 차수의 시작레벨+3)에서 캐릭터는
# 공용 퍽 + 자기 직업 계열 퍽 중 하나를 고른다(gameflow.선택가능_퍽목록).
#
# 파일 머리 주석은 아래 형태로 통일한다.
#   # =====================
#   # (직업) 계열 클래스 퍽
#   # 분류번호: XXXx
#   # =====================
#   # (공용 퍽 양식은 perks_class_format.py 참고)
#   # 퍽으로 얻는 스킬의 상세 정의는 job_skill_XXXx_(직업).py의 스킬목록에,
#   # 퍽으로 얻는 특성의 상세 정의는 job_ability_XXXx.py의 특성목록에 있다.

# =====================
# <퍽 항목 양식> - 공통 키 (항상 존재)
# =====================
# "분류"     : "특성획득" | "스킬획득" | "스탯획득" | "일반퍽"
#              (아래 <분류 종류> 참고)
# "차수"     : 1~4 정수. 캐릭터 차수(character_data_system.차수_계산)보다 높으면
#              고를 수 없다(스킬과 같음 - gameflow._퍽_선택가능). 퍽획득 레벨
#              4/9/14/19가 각각 1/2/3/4차수다. 직업 퍽은 무기 숙련 1, 나머지 2.
# "선행조건" : None | 문자열 | 딕셔너리  (아래 <선행조건 양식> 참고)
# "설명"     : 문자열. 퍽 선택 화면에 그대로 보인다.
#              보통 "특성 'OO'을 얻는다." / "스킬 'OO'를 얻는다." 형태로 쓰고,
#              선행조건이 있으면 "'OO'을 먼저 습득해야 한다."를 덧붙인다.

# =====================
# <분류 종류> - 분류별 추가 키
# =====================
# 1) "특성획득" - 특성 하나를 얻는다.
#    "획득특성" : 문자열 (job_ability_XX.py "특성목록"의 키와 일치)
#    예)
#    "철금강": {
#        "분류": "특성획득",
#        "선행조건": None,
#        "획득특성": "철금강",
#        "설명": "특성 '철금강'을 얻는다."
#    },
#    "획득스킬" : [스킬이름, ...] (선택) - 특성과 함께 보유스킬에 넣는다(광기 - 프렌지 전환/사무치는 광기)
#    ↳ 얻을 때 특성 정의를 찾는 순서: 그 직업의 특성목록 → 공용 특성목록
#      (job_ability_0000.py) (gameflow.퍽_특성정의_찾기).
#    ↳ 이미 가진 특성이면 선택 목록에서 빠진다.
#
# 2) "스킬획득" - 스킬 하나를 얻는다.
#    "획득스킬" : 문자열 (job_skill_XX.py "스킬목록"의 키와 일치,
#                 그 스킬은 "습득방법":"퍽습득", "습득퍽":이 퍽 이름)
#                 | None (고정된 스킬이 아니라 얻는 순간 목록에서 고르는 퍽)
#    "효과"     : 딕셔너리 (선택. "획득스킬"이 None일 때 고를 범위를 적는다)
#    예)
#    "디스인챈트": {
#        "분류": "스킬획득",
#        "선행조건": None,
#        "획득스킬": "디스인챈트",
#        "설명": "주문 '디스인챈트'를 얻는다. 적 전체의 버프를 (차수)개 제거한다."
#    },
#    ↳ 이미 가진 스킬이면 선택 목록에서 빠진다.
#    ↳ "획득스킬": None 예) 공용 퍽 "훔쳐배우기" - 후보는 각 직업 스킬
#      "타입"의 "훔쳐배우기스킬" 태그로 찾는다(job_skill_format.py 참고).
#      지금 화면(gameflow)은 이런 퍽을 선택 목록에서 빼고 있다(미지원).
#
# 3) "스탯획득" - 능력치를 올린다. 두 가지 형태가 있다.
#    (a) "획득스탯포인트" : 정수. 얻는 즉시 그만큼 능력치를 배분한다.
#        예)
#        "능력치향상": {
#            "분류": "스탯획득",
#            "선행조건": None,
#            "획득스탯포인트": 2,
#            "설명": "스탯포인트 2점을 얻는다. 원하는 능력치에 자유롭게 배분할 수 있다."
#        },
#        ↳ 약점스탯에는 특성 "약점제거" 없이는 배분할 수 없다.
#    (b) "획득특성" : 문자열. 능력치 관련 특성을 얻는 경우.
#        예) 공용 퍽 "약점제거" (특성 "약점제거"를 얻는다)
#        ↳ 처리는 "특성획득"과 같다(character_levelup_system._퍽획득_처리).
#    (a)/(b) 중 하나만 쓴다. 둘 다 있으면 (a)만 적용된다.
#
# 4) "일반퍽" - 위 세 분류로 표현할 수 없는 퍽. 퍽마다 구조가 다르다.
#    지금 데이터에는 없고, 엔진도 처리하지 않는다(선택 목록에서 빠지고,
#    레벨업 처리에서 NotImplementedError). 쓰게 되면 엔진 작업이 먼저 필요하다.

# =====================
# <선행조건 양식>
# =====================
# None
#     조건 없음.
# 문자열
#     그 이름의 특성을 보유해야 한다.
#     예) "선행조건": "이중극점"   (삼중극점)
# {"특성보유": 특성이름}
#     문자열과 같은 뜻을 명시적으로 쓴 형태.
#     예) "선행조건": {"특성보유": "이중극점"}   (삼중극점)
# {"스킬보유": 스킬이름}
#     그 이름의 스킬을 보유("보유스킬")해야 한다.
#     예) "선행조건": {"스킬보유": "가드"}   (오토가드)
# {"최소능력치": {능력치이름: 값, ...}}
#     적은 능력치가 전부 그 값 이상이어야 한다.
#     예) "선행조건": {"최소능력치": {"근력": 18}}   (초대형무기)
# {"전직": 전직이름}
#     그 전직이어야 한다(같은 계열 퍽 파일을 쓰는 다른 전직은 못 고른다).
#     예) "선행조건": {"전직": "버서커"}   (광기)
# {"가용무기": 무기종류}
#     그 무기를 쓸 수 있어야("가용무기") 한다.
#     예) "선행조건": {"가용무기": "소검"}   (소검숙련)
#
# 판정은 gameflow._선행조건_만족 참고.

# =====================
# 작성 순서 / 주석
# =====================
# - 공용 퍽(0000)은 기능별로 묶고, 묶음 사이에 "# ====" 구분 주석을 둔다.
#   (예: 방어구 숙련 / 무기 숙련)
# - 구조가 아직 확정되지 않은 항목은 그 항목 옆에 주석으로 표시한다.
