# =====================
# 공용 정의 / 레벨업 테이블 양식
# =====================
# job_level_XX 파일들의 공통 구조(차수 구분, 5단계 고정 패턴, "획득" 타입별
# 하위 양식)를 모아둔 참고용 파일이다. 실제 데이터는 없다.

# =====================
# 차수 구분
# =====================
# 차수는 5레벨마다 1씩 오른다: 차수 = (레벨 - 1) // 5 + 1
# (character_data_system.차수_계산)
#   1차수 : 레벨 1~5
#   2차수 : 레벨 6~10
#   3차수 : 레벨 11~15
#   4차수 : 레벨 16~20
#
# 레벨업 테이블 파일은 차수와 따로 나뉜다:
#   1차 계열 파일(분류번호 X-0, 예: job_level_010m_ghost_swordsman.py) : 레벨 1~5 (비전직)
#   전직 파일(분류번호 X-1~, 예: job_level_011m_weapon_master.py)      : 레벨 6~20
#     - 한 파일이 2차수(6~10), 3차수(11~15), 4차수(16~20)를 함께 담는다
# (분류번호 앞자리는 1차 계열 번호, 뒷자리는 그 계열 안의 전직 순번)

# =====================
# 파일 구조
# =====================
# 각 파일은 "레벨업테이블" 딕셔너리 하나만 담는다. 키는 레벨(정수),
# 값은 <레벨 항목 하위 양식>이다.
#
# 1차수(레벨 1~5):
#   레벨 1 : "특성획득"
#   레벨 2 : "마스터리선택" - 무기 마스터리(가용무기의 "OO 마스터리") 하나 + 방어구
#            마스터리(천갑/가죽/경갑/중갑/판금숙련) 하나. 이미 가진 것은 못 고른다.
#            (전투 스타일은 전직 레벨 7에 고른다, job_level_000x_style.py.
#             직업스타일은 전직 레벨 파일의 "직업스타일"로 레벨 6에 정해진다)
#   레벨 3 : "특성획득" - 직업별 방어 스킬/특성(귀검사 가드, 격투가 분신, 거너
#            건가드, 마법사 오라 실드+위상 변화, 프리스트 치유의 기도+큐어)
#   레벨 4 : "퍽획득"
#   레벨 5 : "스탯성장" - 약점스탯 뺀 서로 다른 능력치 2개에 1점씩 (추가공격 없음)
# 2차수 이후(전직 파일)는 아래 5단계가 차수마다 이 순서로 반복된다(3차수는
# 아래 "전직 레벨 파일" 목록처럼 일부를 바꿔 쓴다).
#   1단계 (시작레벨)   : "타입" = "특성획득"
#   2단계 (시작레벨+1) : 2차수(레벨 7)는 "스타일선택" - 전투 스타일 하나를 고른다
#                        (다시 고르면 교체)
#   3단계 (시작레벨+2) : "타입" = "스킬획득" (2차수 레벨 8 - 직업 버프 스킬 하나,
#                        그 밖의 스킬은 파티 화면 [스킬습득]으로 배운다)
#   4단계 (시작레벨+3) : "타입" = "퍽획득"
#   5단계 (시작레벨+4) : 2차수(레벨 10)는 "스탯성장"(레벨 5와 같음). 추가공격은
#                        직업스타일 성장(6/11/16/21레벨, job_level_000x_style.py)
#
# 전직 레벨 파일(job_level_XXXx_전직.py)은 레벨 6~20을 담는다:
#   6 특성획득 / 7 스타일선택 / 8 스킬획득(버프) / 9 퍽획득 / 10 스탯성장 /
#   11 스타일강화 / 12 스킬강화 / 13 스킬획득(스킬 미정) / 14 퍽획득 / 15 스탯성장 /
#   16 특성획득(각성 특성 미정 - 직업스타일 성장 3회째도 이 레벨) / 17 스킬개화(선택지 미정) /
#   18 스킬획득(각성 스킬 미정) / 19 퍽획득 / 20 스탯성장

# =====================
# <레벨 항목 하위 양식> - 공통 키
# =====================
# "분류"           : "레벨진행" (고정값)
# "타입"           : 위 5단계 중 하나 (순서 고정)
# "클래스"         : 문자열 (해당 파일의 클래스 이름)
# "획득"           : <획득 하위 양식> (아래 참고)
# "주문시전능력치" : 문자열 (선택. 주문 클래스의 "특성획득" 레벨에만 명시,
#                    기본값 "지능". 전직으로 바뀌면 2차수 이상에 새로 명시.
#                    예) 프리스트 "지능" → 크루세이더 "지혜")
# "레벨당체력증가" : 정수 (선택. 레벨 1 "특성획득" 항목에만. 전직 레벨에는
#                    새로 적지 않고 1차 계열 값을 따른다.)
#                    기본체력 = 레벨당체력증가 + 건강보정치
#                    기본최대HP = 기본체력 + 올림(레벨 x 기본체력 / 2), 최소 1
#                    (올림은 총합에 한 번만 - 레벨마다 쌓이지 않는다.
#                    character_data_system.최대HP_공식, 몬스터 역할군도 같은 공식)
# "기본가용무기"   : 문자열 리스트 (선택. 레벨 1에만. eq_weapon_XX.py의
#                    무기 종류와 일치. 특성으로 별도 해금하는 무기는 제외)
# "시작장비"       : 문자열 (선택. 레벨 1에만. eq_weapon_XX.py 커먼 등급과 일치)

# =====================
# <타입 종류>
# =====================
# "특성획득" - 차수 시작 레벨. 해당 차수 특성 획득. ("획득"."타입"="특성")
# "스탯획득" - 능력치 배분. ("획득"."타입"="능력치배분")
# "스탯성장" - 약점스탯 뺀 서로 다른 능력치에 1점씩. ("획득"."타입"="능력치성장")
# "스타일선택" - 전투 스타일 하나 선택. ("획득"."타입"="스타일") - 2차수 레벨 7
# "마스터리선택" - 무기/방어구 숙련 하나씩. ("획득"."타입"="마스터리")
# "스킬획득" - 스킬을 자동으로 얻는다. ("획득"."타입"="스킬")
# "미정"     - 아직 정하지 않은 레벨. 레벨만 오른다. ("획득" = {"설명": "미정"})
# "스타일강화" - 전직 레벨 11. 따로 얻는 것은 없고 직업스타일 성장(추가공격/최대MP)이
#             두 번째로 적용된다. ("획득" = {"설명": 문자열})
# "스킬강화" - 전직 레벨 12. 보유 스킬 하나를 골라 강화한다. ("획득"."타입"="스킬강화")
# "스킬개화" - 전직 레벨 17. 조건부 추가효과 하나를 고른다. ("획득"."타입"="스킬개화")
#             선택지가 아직 미정이라 지금은 레벨만 오른다("미정"과 같은 처리).
# "퍽획득"   - 공용/클래스 퍽 목록에서 하나 선택. ("획득"."타입"="퍽선택")
# "행동획득" - 추가공격 횟수 +1. ("획득"."타입"="추가공격") - 지금 쓰는 레벨 없음
#             (캐릭터 "추가공격획득"에 쌓이고, 직업스타일 성장 추가공격과 합산된다)

# =====================
# <획득 하위 양식> - "획득" 키의 값, "타입"으로 형태 구분
# =====================
# 1) "특성" ("특성획득" 전용)
#    {"타입": "특성", "습득방법": "레벨진행", "획득특성": 이름 또는 리스트,
#     "획득스킬": 리스트(선택. 1차수 레벨 3), "설명": 문자열}
#    (job_ability_XX.py "특성목록" 키와 일치해야 함. 전용 파일 없는
#    서브클래스 특성은 상위 계열 job_ability_XX.py에 넣고 그대로 참조)
#
# 2) "능력치배분" ("스탯획득" 전용, 모든 차수/클래스 동일)
#    {"타입": "능력치배분", "배분점수": 2, "설명": "능력치 2점을 원하는
#     스탯에 배분한다. 1점씩 나눠서 두 스탯에 배분할 수도 있다."}
#
# 3) "스킬" ("스킬획득" 전용)
#    {"타입": "스킬", "습득방법": "레벨진행", "획득스킬": [스킬 이름, ...],
#     "설명": 문자열}
#    job_skill_XX.py 스킬목록 키와 일치해야 하고, 그 스킬은 "습득방법":"레벨진행"
#    ([스킬습득]에서 팔지 않음). 2차수 레벨 8: 웨펀마스터 오버드라이브, 스트라이커
#    강권, 레인저 데스 바이 리볼버, 엘리멘탈마스터 엘레멘탈 번, 크루세이더 용맹의 축복.
#
# 4) "퍽선택" ("퍽획득" 전용, 모든 차수/클래스 동일)
#    {"타입": "퍽선택", "설명": "공용 퍽 또는 클래스 퍽 목록에서 하나를 선택한다."}
#
# 5) "추가공격" ("행동획득" 전용, 모든 차수/클래스 동일)
#    {"타입": "추가공격", "추가횟수": 1, "누적공격횟수": 정수(1차수에는 없음,
#     2차수 끝=2, ...), "설명": 문자열}
#
# 6) "능력치성장" ("스탯성장" 전용)
#    {"타입": "능력치성장", "배분점수": 2, "스탯당최대": 1, "설명": 문자열}
#    약점스탯에는 ("약점제거"가 있어도) 넣을 수 없다.
#
# 7) "스타일" ("스타일선택" 전용)
#    {"타입": "스타일", "선택지": list(전투스타일), "설명": 문자열}
#    고른 값은 캐릭터["스타일"]에 기록하고, 같은 이름의 특성으로 부여한다
#    (기존 스타일 특성은 빠진다 - 교체). 시작값은 "노력"(효과 없음).
#    다른 타입 항목에 "스타일선택지": [...] 를 붙이면 그 레벨에서도 다시
#    고른다(지금 쓰는 레벨 없음).
#
# 8) "마스터리" ("마스터리선택" 전용)
#    {"타입": "마스터리", "방어구선택지": [방어구 숙련 이름, ...], "설명": 문자열}
#    무기 마스터리 선택지는 캐릭터 "가용무기"에서 만든다(character_levelup_system.
#    마스터리_선택지). 둘 다 이미 가진 것은 고를 수 없다.
#
# 9) "스킬강화" ("스킬강화" 전용)
#    {"타입": "스킬강화", "최대차수": 3, "최종피해배율": 1.5, "MP소모배율": 2,
#     "설명": 문자열}
#    보유스킬 중 차수(1차 계열 1, 1차 전직 2 - gameflow._스킬차수)가 "최대차수"
#    이하인 것 하나를 고른다(피해 없는 버프 스킬도 된다). 캐릭터["스킬강화"] =
#    {"스킬": 이름, "최종피해배율": .., "MP소모배율": ..}로 기록하고(다시 고르면 교체),
#    전투에서 그 스킬의 MP소모(중갑/판금 배율과 곱연산)와 최종피해(방어·속성 배율
#    뒤, 그 스킬이 건 지속피해/지속공격 포함)에 곱한다(skill_usage.스킬강화).
#
# 10) "스킬개화" ("스킬개화" 전용)
#    {"타입": "스킬개화", "선택지": [], "설명": 문자열}
#    고를 조건부 추가효과 목록 - 아직 미정(빈 리스트)이라 처리는 "미정"과 같다.
