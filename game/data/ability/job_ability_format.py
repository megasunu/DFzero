# =====================
# 공용 정의 / 특성 양식
# =====================
# 특성(일반특성/강화특성)의 공용 양식. 실제 데이터는 없다.
# 각 job_ability_XX.py의 "특성목록"이 이 양식을 따른다.
# 퍽 자체 양식은 perks_class_format.py 참고.
#
# 특성목록 순서: 차수순 직업별 "레벨진행" 특성 → 퍽으로 얻는 특성.
# 직업별 구간은 "# ㅇㅇ(x-x) 계열 특성" 주석으로 구분한다.

# =====================
# 분류: "일반특성" | "강화특성"
# =====================
# 일반특성 - 상시 적용되거나 조건 충족 시 자동발동(행동 소모 없음)
# 강화특성 - 보유 스킬/특성 하나를 강화(자체 효과 없음)
# (행동을 소모해 발동하는 것은 특성이 아니라 스킬이다 - job_skill_format.py
#  "반응스킬" 분류. 2026-10-16 "반응특성" 분류를 없애고 옮겼다.)
#
# "출처":"레벨진행" 특성은 "분류" 대신 차수 등급을 쓴다:
#   1차수 비전직특성 / 2차수 전직특성 / 3차수 1각특성 / 4차수 2각특성
#
# 공통 키
# "분류"     : 위 참고
# "타입"     : 전투 역할 분류(자유 추가 가능, 여러 개면 리스트).
#             공격특성/방어특성/면역특성/선택특성/스탯획득/내성획득/이점획득/
#             숙련획득/숙달획득/평타스탯획득/보정획득/가용장비/무기마스터리/
#             방어구마스터리/행동획득 등
# "발동조건" : None | 문자열 | 리스트. 구체값이 필요하면 "조건값"을 함께 적는다
#             (예: "적상태"+"조건값":"공중에뜸"). 수치비교 조건은 조건식을
#             문자열로 적고 "발동조건_변수설명"으로 변수를 설명한다.
#             표준 변수: "명중성공차이"(명중결과-AC), "명중실패차이"(AC-명중결과).
#             이 둘을 쓸 때는 "발동조건_주체"(자신/적), "발동조건_상황"(공격시/피격시)도 적는다.
# "출처"     : 퍽 이름(perks_class_XX와 동일) | "레벨진행" | 기타 경로
# "설명"     : 문자열
#
# 일반특성 추가 키
# "효과"     : buff.py/debuff.py와 같은 {"변동대상","변동값"} 형식(리스트 가능).
#             "내성"/"이점"/"숙련"/"숙달"은 해당 판정 이름을 "변동값"에 적는다.
#             "평타스탯"은 일반공격 명중/보정치 계산에 쓸 능력치 후보 추가.
#             "어그로"는 고정 증감이면 "변동값", 배율 증감이면 "배율" 키.
#             장비 착용 종류 추가는 "효과"가 아니라 "가용무기" 키(방어구는 제한 없음).
#             원소에 "무기조건"을 붙이면 그 무기를 들었을 때만 적용된다(무기의 극의).
#             무기 전용 변동대상: "무기공격력"(무기 주사위 대체, 예: "1d10"),
#             "일반공격추가피해"(일반공격/일반공격취급 스킬에 더할 피해식),
#             "명중시상태이상"("발동확률" + 상태이상 "효과" - 명중할 때마다 굴림).
#             상태이상 면역은 "상태이상면역"(변동값 = 상태이상 이름, combat.status.상태이상_면역).
#             "명중이점"/"회피이점"(변동값 1): 공격할 때 명중굴림 이점 / 나를 치는 상대가 불리점(심안).
#             "명중시대상변동"(변동값 "데미지보너스"|"방어력", "최대중첩"): 명중할 때마다 대상에게
#             중첩 디버프 -1, 전투 끝까지(웨펀/아머브레이커 - damage.특성_명중시_대상변동).
# "타겟"     : "효과" 리스트 공통 타겟(선택)
# "버프획득"/"디버프획득" : skill_effects.py/buff.py/debuff.py 항목 이름
# "면역"     : 상시 면역 상태이상 / "면역획득": 기간 한정 면역(버프 방식)
# "중첩량"/"적용대상"/"토글"/"발동확률"/"가용무기"/"무기조건"/"방어구조건"/
# "상태이상내성이점"(상태이상 분류 리스트 - 그 분류의 내성굴림 이점)/
# "민첩상한해제"/"전투당횟수"/"휴식당횟수" : 필요 시 사용(선택)
# "재질수효과" : [{"재질수": n, "효과": [...] | "중갑패널티면제": True}, ...] - 입은 방어구의
#             서로 다른 재질 수가 n 이상인 단계가 누적 적용된다(패셔니스트, equipment_system).
# "상태이상보정" : {상태이상이름: {"추가효과반전": True | "무시효과": [효과 키] |
#             "추가효과": {키: 값}}} - 그 상태이상에 걸렸을 때 효과를 바꾼다(취권:
#             취기 감소를 증가로, 만취의 무작위행동 무시 + 데미지보너스/AC). combat.status
# "보조행동대체타입" : 스킬 "타입" 리스트 - 그 타입 스킬의 "일반행동"을 보조행동으로
#             대신 낼 수 있다(쇼타임행동/일반행동이 남아 있으면 그쪽 먼저). 예) 메모라이즈
#
# 강화특성 추가 키
# "대상"     : 강화 대상 스킬/특성 이름
# "대상종류" : "스킬" | "특성"
# "효과"     : {"타입": 강화종류, ...} 자유 형식 (예: 자동발동 - 발동확률/행동소모/MP소모)
# "전투당횟수"/"휴식당횟수" : 선택
#
# (참고: "선행조건", "특성보유" 조건부효과 등은 job_skill_format.py 공용 정의를 따른다.)
