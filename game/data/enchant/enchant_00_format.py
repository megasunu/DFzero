# 마법부여 양식
# =====================
# 마법부여(#178, 2026-11-11 사용자 결정) 데이터 파일들의 공용 양식을 모아둔 참고용 파일이다.
# 실제 마법부여 데이터는 들어있지 않다. 마을 [전문직업] > [마법부여]에서 장비에 거는 효과이고,
# 규칙은 game/system/enchant_system.py와 docs/game-rules.md "마법부여".
#
# 파일명과 부위 구역 대응 (장비 파일 eq_01~04 번호 체계와 동일):
#   enchant_01_weapon    - 무기          (무기마법부여)
#   enchant_02_armor     - 방어구        (방어구마법부여)
#   enchant_03_accessory - 악세서리      (악세서리마법부여)
#   enchant_04_special   - 특수장비      (특수장비마법부여)
# enchant_system이 네 딕셔너리를 하나의 마법부여 표로 합친다. 이름은 파일끼리 겹치면 안 된다.
# 데이터 파일에는 함수를 두지 않는다 - 반복되는 모양은 아래 "속성강화" 같은 표시로 적고 시스템이 채운다.

# -----------------------------------------------------
# <마법부여 항목 양식>
# -----------------------------------------------------
# 이름 -> {
#     "부위"  : 리스트, 걸 수 있는 장비 부위(common_names의 무기/방어구/악세서리/특수장비 부위)
#               - 그 파일 구역의 부위만 쓴다
#     "비용"  : {"골드": n} - 걸 때마다 낸다
#     "설명"  : 화면에 보이는 효과 글
#     "속성"  : (선택) 무기 주사위를 쓰는 피해의 속성을 이 값으로(stats.공격_속성 - 마봉 무기속성 다음)
#     "보너스": (선택) {장비 보너스 키: 값} - 장비 능력치 합산에 더한다(equipment_system._보너스_키)
#     "효과"  : (선택) [효과 원소] - 장비 효과 목록에 붙는다(마봉효과와 같은 원소, 예: 속성강화)
# }
#
# <속성강화 표시> (악세서리)
#   이름 -> {"속성강화": 속성}
#   한 줄만 적으면 enchant_system이 아래 항목으로 채운다:
#   {"부위": 악세서리 부위 전부, "비용": {"골드": 100}, "설명": "<속성> 강화 +1",
#    "효과": [{"변동대상": "속성강화", "속성": 속성, "변동값": 1}]}

# -----------------------------------------------------
# <공통 규칙>
# -----------------------------------------------------
# 부여한 장비는 원래 수치를 그대로 두고 이 효과를 "마법부여" 딕셔너리에만 담는다(enchant_system.부여정보).
