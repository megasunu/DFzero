# =====================
# 경직 태그 ("잡기" / "경직", 2026-10-20 사용자 결정)
# =====================
# 모든 공격은 명중한 타격마다 맞은 대상을 경직시킨다 - 보통은 이번 라운드 이니셔티브 -1.
# "타입"에 "잡기" 또는 "경직"이 있는 공격(분할공격이면 그 단계의 "타입"과 합쳐서)은
# 우선도 -1이다. 슈퍼아머 상태나 특성 "경직불가"면 걸리지 않고, 특성 "잡기불가"는 "경직"
# 태그가 없는 "잡기" 경직만 막는다(combat.damage.경직_적용). 몬스터 패턴의 "타입"도 같다.
#
# "홀딩"(잡기와 따로 붙는 태그) - 맞으면 피해는 굴리기만 하고 대상의 다음 차례 시작에 넣는다.
# 그때까지 대상은 상태이상 "홀딩"(대상을 노리는 공격은 명중굴림에 이점). 이미 행동한 대상이
# 경직으로 현재 차례 뒤로 밀리면 그 라운드에 홀딩 전용 차례가 온다. 건 사람이 쓰러지거나
# 무력화CC에 걸리면 피해 없이 풀린다(combat.damage.홀딩_걸기/홀딩_발동/홀딩_정리).
# 경직량은 1에 대상의 버프/디버프 "경직배율"(경직증가 2, 경직감소 1/2)을 곱한 값 - 1 이하면 버림(#378).
#
# 스트리트 파이터 키(#378)
# "투척" 태그        - 버프 "이중투척"이면 명중 -5로 두 번(MP·행동은 한 번, skill_run.이중투척_적용).
#                      투척 아이템도 이 태그다(아이템 2개를 쓴다).
# "이중투척변형"      - {키: 값} - 이중투척이면 두 번 대신 이 키들을 덮어쓴다(천라지망 - 적전체, 명중이점).
# "데미지": None      - 피해 없는 공격. 명중 굴림·경직·명중시 효과는 그대로(히든 스팅).
# "홀딩무적": True    - 이 홀딩이 남은 동안 시전자는 적의 공격 피해를 받지 않는다(마운트).
# "충격파"            - {"데미지", "공격타입", "명중률", "내성", "난이도"} - 홀딩 피해가 들어갈 때 타격마다 대상과
#                      양옆에 따로 굴리는 범위 피해, 내성 성공 시 절반(damage.홀딩_발동).
# "대체"              - {"이름", "조건": {"대상상태분류": [분류...]}, 덮어쓸 키...} - 중심 대상에게 그 분류의 상태이상이
#                      있으면 이 스킬 대신 나간다. 공격횟수에 그 상태이상 종류 수를 더한다(마운트 -> 크레이지 발칸).
#                      "조건": {"대상상태": [이름...]}이면 그 이름의 상태이상이 있을 때 키만 덮어쓰고 공격횟수는
#                      그대로, "이름"이 없으면 스킬 이름도 그대로(에어슈타이너 - 공중에뜸이면 d12, #381).
#
# 그래플러 키(#381)
# "경직량"            - 정수. 명중하면 경직이 1 대신 이만큼(넥스냅 20 - 이니셔티브 -20, damage.경직_적용).
# "던지기"            - {"데미지", "효과", "몹몰이": 지속턴} - 중심 대상이 맞으면 다른 적 1체(무작위)에게 스킬의 명중률로
#                      친다. 맞으면 두 적에게 몹몰이를 건다(로플링, skill_attack.던지기_발동).
# 버프 "잡기필중"(반드시 잡는다!)이면 "잡기" 태그 스킬은 명중률 "필중"이고, 그 스킬이 건 홀딩이 남은 동안 시전자는
# 슈퍼아머다(skill_run.잡기필중_적용, damage.홀딩_걸기).

