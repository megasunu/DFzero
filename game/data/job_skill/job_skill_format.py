# 패턴 스킬 ("무작위패턴" / "패턴분기", 2026-10-21 사용자 결정, #332 - 검귀 원귀/합격)
# =====================
# "패턴": {패턴이름: {덮어쓸 키...}} - 쓸 때 고른 패턴의 키(타겟/데미지/공격횟수/각공격명중굴림/명중이점 등)를
#   스킬 데이터에 덮어써 실행한다(skill_run.스킬_실행). 로그와 문장의 스킬 이름은 "스킬 : 패턴"이다.
# "타입"에 "무작위패턴" - 대상을 고른 뒤(스킬의 "타겟") 패턴 하나를 무작위로 고른다. "패턴자원"이 있으면
#   그 자원(skill_effects.py)을 얻고 인스턴스 "패턴"에 고른 패턴 이름을 적는다(원귀).
# "타입"에 "패턴분기" - "패턴분기": {"자원": 이름, "선택": {자원의 패턴: 이 스킬의 패턴}}. 그 자원이 기억한
#   패턴으로 이 스킬의 패턴이 정해진다(합격). 자원이 있으면 스킬 목록에도 "스킬 : 패턴"으로, 그 패턴의
#   타겟으로 보인다(skill_run.패턴_적용 - 전투 화면과 자동전투도 같은 판정).
# "명중이점": True - 이 스킬(패턴)의 명중굴림에 이점(이혼일섬).

