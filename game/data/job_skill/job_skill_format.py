# =====================
# 조건부 효과 조건 종류
# =====================
# "자원보유"   - 시전자가 해당 자원을 보유 중일 때
# "적상태"     - 대상 적이 해당 상태이상일 때
# "아군상태"   - 시전자가 해당 상태이상/버프일 때
# "HP비율이하" - 시전자 HP가 해당 비율 이하일 때
# "특성보유"   - 시전자가 해당 특성을 보유(활성화)했을 때

# =====================
# 차수별 데미지 성장 표기법
# =====================
# "(차수)dN"            - 차수만큼 주사위 개수 증가 (1차수 1dN / 2차수 2dN / ...)
# "(차수+K)dN"          - 차수 + K개의 주사위 (K+차수 순서로 써도 동일)
# "(차수+K)x보정공격력" - 보정공격력을 (차수+K)회 적용
# 실제 주사위 크기(d4~d12)는 직업/스킬마다 다르다.

# =====================
# 스킬 양식 - "공격스킬" 분류
# =====================
# 적에게 데미지를 입히는 것이 주된 기능인 스킬. 버프/디버프가 곁들여져도
# 공격이 주기능이면 이 분류에 포함된다. (예: 칠링팬스 - 공격 + 아군 버프)

# =====================
# 필수 키 (모든 공격스킬에 항상 존재)
# =====================
# "분류"           : "공격스킬"                         (고정값)
