# =====================
# 습득방법
# =====================
# "초기습득" - 캐릭터를 만들 때 자동으로 배우는 1레벨 시작 스킬(직업마다 둘 - 귀검사 어퍼 슬래쉬,
#              귀참 등). 적힌 순서대로 배운다(character_creation_system.레벨1_스킬_습득).
# "레벨습득" - 레벨업으로 자동으로 얻는 스킬(job_level_XX.py 1차 계열 레벨 3
#              "획득스킬", 2차수 레벨 8 "스킬획득" - 8레벨 버프 등). [스킬습득]으로 사지 않는다.
# "구매습득" - 파티 화면 [스킬습득]에서 골드(50 x 차수 - 1차 계열 1, 1차 전직 2)를 내고 배운다
#              (skill_learn_system.py). job_skill_XX의 스킬목록은 이것이 대부분이다.
#              "습득레벨"은 그 차수의 시작 레벨(1+5x(차수-1) - 1차 계열 1, 1차 전직 6)이고
#              그 레벨부터 살 수 있다(2026-10-22 사용자 결정, #365).
#              "습득차수"를 적으면 목록의 차수 대신 그 차수로 값과 습득레벨을 정한다
#              (전직 목록의 3차수 스킬 - 넨마스터 뇌명: 150골드, 레벨 11).
# "퍽습득"   - 퍽으로 얻는 스킬. 스킬목록에 다른 스킬과 함께 들어있으며
#              "습득방법":"퍽습득", "습득퍽"으로 퍽 이름을 적는다.
#              그 퍽의 요약은 perks_class_XX.py의 퍽목록에서 확인.
# "미정"     - 아직 얻는 곳이 없다(반응스킬 컷 인 대쉬/축지성촌/위빙 - 전직 미구현).

