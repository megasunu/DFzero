# <데미지 문법>
# =====================
# "+", "-", "x", "÷" 사칙연산으로 아래 항목을 조합한 문자열.
# 곱셈/나눗셈을 덧셈/뺄셈보다 먼저 계산하며, 순서를 명확히 하려면 괄호로 묶는다.
#
#   무기공격력       - 무기 주사위만 (스탯 보정 없음)
#   보정공격력       - 무기 주사위 + 능력치 보정치
#   1d8, 2d6 등       - 고정 주사위 표기
#   (차수)d8          - 차수만큼 주사위 개수 증가
#   (차수+N)d8        - 차수 + N개 주사위 (N+차수 순서도 동일)
#   (차수-N)d8        - 차수 - N개 주사위 (0 이하면 0으로 취급)
#   주문시전보정치    - 주문시전 능력치 수정치
#   보정치            - 근접/사격 등 무기공격력 계산에 쓰이는 능력치 보정치
#   (귀신보유수)d8    - 시전자가 보유한 "귀신" 태그 스킬 개수만큼 주사위 증가
#                       (전투 시스템이 계산해 대입하는 변수. 데이터엔 저장 안 함)
#   (대상상태이상수)d8 - 맞는 대상에게 걸린 지속피해형·무력화CC·약화CC 상태이상의 이름 수만큼
#                       주사위 증가(같은 이름은 하나, 일발화약성 #398. 피해 식에서만 대입)
#
#   예) "무기공격력+1d8"
#   예) "(1+차수)d12+주문시전보정치"
#   예) "보정공격력x2"
#   예) "보정공격력x(2+차수)"
#   예) "(차수)d10-(차수-1)x보정치"
#   예) "보정공격력÷2"
#   예) "(차수)x(1d6+주문시전보정치)"           (괄호로 묶은 그룹에 차수를 곱함)
#
# 타격마다 데미지 자체가 다르면 위 "데미지" 필수 키 설명대로 문자열 리스트로.
# 예) ["(차수)x(1d6+주문시전보정치)", "1d6"]
#
# <치명타 규칙>
# 치명타 발생 시 보정치/차수/주문시전보정치 등 고정 값은 1회분만 그대로 반영되고,
# 무기 주사위와 스킬 자신의 "NdM" 다이스만 개수가 1개 늘어서 굴러간다
# (다이스를 통째로 2배 굴리는 게 아니라 "다이스 1개 추가"). 예) 1d8 무기가 치명타면
# 2d8. combat.formula.수식_평가(수식, 컨텍스트, 치명타=True)가 이 계산을 담당한다.

