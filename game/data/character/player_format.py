#
# "레벨"   : 정수                (파티 대표 레벨. 캐릭터 개별 "레벨"과 항상 같다고 보는 표시값 -
#            레벨업 자체는 캐릭터마다 job_level_XX.py로 받는다. 동기화를 검증하는 코드는 없다)
#
# "파티"   : party_system.py 파티 딕셔너리 ({"파티원": [...]})
#
# "소지품" : {
#                "골드"        : 정수,
#                "장비"        : {아이템이름: 개수, ...},
#                "소모품"      : {아이템이름: 개수, ...},
#                "포션"        : {아이템이름: 개수, ...},
#                "재료"        : {아이템이름: 개수, ...},
#                "퀘스트아이템" : {아이템이름: 개수, ...},
#            }
#            (모든 카테고리를 "아이템이름 -> 개수"로 통일했다. 장비가 개체별 고유값을 가져야 하게 되면
#            이 형태로는 부족할 수 있다)
