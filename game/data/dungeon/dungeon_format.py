# =====================
# 맵 데이터 양식
# =====================
# 소형지도(필드형 맵: 숲, 던전 등) 하나의 구조를 정의하는 참고용 파일이다(실제 데이터 없음).
# 마을은 이 격자 방식이 아니라 화면(배경 + 선택지) 양식(town_format.py)을 쓴다.
# 그래서 이 양식의 맵은 전부 "이동 가능한 곳 = 인카운트 위험 지역"이다.
#
# 각 파일은 "맵정보" 딕셔너리 하나만 담는다. 여기서는 통행가능여부·인카운트·오브젝트·연결지역만 다룬다.

# =====================================================
# <맵정보 항목 양식>
# =====================================================
#
# "지도명"   : 문자열                     예) "로리엔"
#
# "목록그림" : 파일명 (선택 - game/assets/dungeon/의 배너 그림. 마을 [던전 이동] 목록에서 이름 버튼 대신
#              쓴다. 생략하면 지도명을 적은 버튼)  예) "asset_banner_mirkwood.webp"
#
# "상세지역" : 문자열의 리스트             (이 맵이 속한 상위 지역들을, 큰 것부터 작은 순서로)
#                                        예) ["아라드", "벨마이어 공국 북부"]
#
# "지도"     : 문자열의 리스트             (각 문자열이 한 행, 문자 하나가 한 칸)
#              좌표는 (x, y) = (열, 행), 왼쪽 위가 (0, 0). 기호는 아래 <지도 기호>
#
# "입장좌표" : (x, y)  (선택 - 연결지역을 거치지 않고(마을 [던전 이동] 등) 들어올 때 나타날 좌표.
#              생략하면 처음 만나는 이동 가능 칸이라 대개 의도한 입구가 아니므로, 마을에서 바로 가는
#              던전에는 채워 둔다. 연결지역으로 들어올 때는 그 "진입좌표"가 우선. dungeon_system.던전_시작)
#
# "오브젝트" : { (x, y): <오브젝트 항목>, ... } - "지도"에서 "@"인 칸의 상세 정보.
#              ("클리어시":"연결지역화" 좌표는 "연결지역"에도 미리 등록한다 - 아래 참고)
#
# "연결지역" : { (x, y): <연결지역 항목>, ... } - "지도"에서 "#"인 칸의 상세 정보.
#              예외로 "클리어시":"연결지역화" 오브젝트 좌표도 미리 등록해 둔다.
#
# "타일"     : {지도 기호: 타일 파일명, ...} (선택) - 이 맵에서 그 기호의 칸에 깔
#              한 칸짜리(8x8) 타일 그림. game/assets/dungeon/ 안의 파일명만 적는다.
#              예) {"O": "asset_tile_emerald.webp", "Y": "asset_tile_skyyellow.webp"}
#              값을 리스트로 쓰면 아래층부터 겹쳐 그린다 - 배경이 투명한 그림 밑에
#              바닥을 깔 때 쓴다. 예) {"#": ["asset_tile_skycastlewall.webp",
#              "asset_tile_gate_skycastle.webp"]}
#              적지 않은 기호는 공용 그림("O"=풀밭/흙길, "X"=나무, "#"=게이트, "@"=색)으로 그리고,
#              적은 기호에는 공용 나무/게이트 그림을 올리지 않는다. 출입구("#")는 나무/큰 오브젝트보다
#              위(플레이어 아래)에 그린다. 파일이 없으면 그 기호의 색으로 칠한다(screens_dungeon.py).
#
# "드랍표"   : [{"이름", "발동확률"}, ...] (선택) - 이 던전의 공용 드랍. 쓰러뜨린 몬스터마다 굴린다
#              (몬스터 개인 "드랍표"와 별개). 형식은 monster_format.py <몬스터 드랍표 항목 양식> 1)과 같다.
# "특별드랍" : [{"아이템", "확률", "한번만"}, ...] (선택) - 쓰러뜨린 몬스터마다 "확률"로 그 아이템 하나.
#              한 전투에 하나만 나오고, "한번만"이면 도감에 등록된 아이템은 다시 나오지 않는다.
#              전투 보상 후보에는 들어가지 않는다(loot_system.특별드랍_판정).
#
# "연속전투" : <연속전투 항목> (선택) - "조건몬스터"를 처치하고 이긴 인카운트 전투가 끝날 때, 보상 전에
#               잡은 조건몬스터 1마리당 "마리당확률"로 "등장몬스터"와 바로 다시 싸운다. 레벨/차수는 이 맵
#               "인카운트"를 따른다. 둘 다 이기면 보상을 차례로 받고, 이어진 전투에서 지거나 도망치면
#               첫 전투 보상도 없다(dungeon_system.연속전투_판정).
#   {"조건몬스터": [이름, ...], "마리당확률": 0.01, "등장몬스터": [이름 또는 {"이름", "칭호"}, ...]}
# "인카운트" : <인카운트 항목> (선택 - 없으면 무작위 조우가 없다. dungeon_system.인카운트_판정)
#              맵 전체에 하나만 정의한다.

# =====================================================
# <지도 기호>
# =====================================================
#
# "X" - 이동불가
# "Y" - 이동불가 ("X"와 같고 배경만 하늘 - 탑 던전 바깥쪽 등)
# "O" - 이동 가능, 인카운트 위험 지역 (이 맵의 "인카운트" 값을 그대로 적용)
# "@" - 오브젝트 있음, 이동불가 (상세는 "오브젝트"에서 좌표로 조회)
# "#" - 연결지역, 이동 가능 (상세는 "연결지역"에서 좌표로 조회)

# =====================================================
# <오브젝트 항목 양식> - "오브젝트" 딕셔너리의 값
# =====================================================
#
# {
#     "분류" : "이벤트",                    (지금은 이 값 하나뿐)
#     "타입" : "NPC" | "보스전투" | "숏컷" | "상자" | 기타 문자열,  (실제로 하는 일)
#     "이름" : 문자열,                      예) "세리아"
#     "설명" : 문자열,                      (선택)
# }
#
# "타일"       : 파일명 문자열 (선택)     예) "asset_tile_prison_seria.webp"
#                이 "@" 칸에 겹쳐 그릴 전용 타일(game/assets/dungeon/, 배경 투명). 생략하거나 파일이
#                없으면 "@" 색으로 칠한다. 클리어돼 칸이 "O"/"#"으로 바뀌면 그리지 않는다.
#
# "타일크기"   : 정수 (선택, 기본 1)  "타일"을 몇 x 몇 칸 크기로 그릴지. 2 이상이면 칸 정중앙에 맞춰
#                크게 그리고 삐져나온 부분은 바닥/나무 위, 플레이어 아래에 보인다. 통행/상호작용은 한 칸뿐.
#
# "발동방식"   : "말걸기" (선택 - "보스전투"/"상자" 공통)
#                생략하면 그 칸에 부딪히는 순간 곧바로 동작(전투 시작/상자 개봉)이 일어난다.
#                "말걸기"면 "설명"만 먼저 보여주고 "말걸기" 행동을 골라야 동작한다.
#
# "타입"이 "상자"인 경우 아래 키가 추가된다.
#
#     "보상" : {"골드": 정수, ...}   (지금은 "골드" 하나뿐 - player_system.골드_추가)
#
# 상자를 열면 town_system.오브젝트_클리어_기록()으로 진행도["클리어한오브젝트"]에 영구히 기록된다
# ("보스전투"와 같은 기록). 상자는 "클리어시"를 쓰지 않고 칸은 "@"로 남지만, 이미 연 상자는 보상을
# 다시 주지 않는다. ※ 지금 화면 흐름(gameflow.오브젝트_상호작용)은 "보스전투"만 처리하고 "상자"는 없다.
#
# "타입"이 "보스전투"인 경우 아래 키가 추가된다.
#
#     "전투몬스터" : 몬스터 이름 / 몬스터 이름의 리스트 / 아래 형태의 리스트
#                    [{"이름": 몬스터이름, "칭호": 칭호이름 또는 None}, ...]
#                    - 특정 개체에만 칭호(monster_title.py)를 붙일 때 쓴다("칭호" 생략 = None).
#     "레벨"       : 정수                  (몬스터 레벨 - monster_format.py 역할군별 체력 공식이 쓴다)
#     "차수"       : 정수                  (몬스터 차수 - monster_format.py 역할군별 AC 공식이 쓴다)
#     "클리어시"   : "통행가능화" | "연결지역화"
#                    - "통행가능화": 이 좌표가 "@"에서 "O"로 바뀐다. 던전을 나갔다 들어오면 다시 "@"
#                      (이번 방문에서만). 영구 기록이 필요하면 "숏컷" 타입을 쓴다.
#                    - "연결지역화": 이 좌표가 "@"에서 "#"로 바뀌어 다른 맵/마을로 가는 길이 된다.
#                      같은 좌표로 "연결지역"에 <연결지역 항목>을 미리 등록해 둬야 한다.
#
# "타입"이 "숏컷"인 경우 (다른 오브젝트가 1회 이상 클리어됐으면 자동으로 "@"에서 "O"로 열리는 지름길)
# 아래 키가 추가된다. "전투몬스터"/"발동방식"/"클리어시"는 쓰지 않는다.
#
#     "해금조건" : <해금조건 항목>
#
# <해금조건 항목 양식>
# {
#     "필요오브젝트좌표" : (x, y),   (그 던전 "오브젝트"의 좌표, 보통 "보스전투". 진행도
#                                    "클리어한오브젝트"에 1회 이상 클리어 기록이 있으면 만족)
#     "필요던전파일명"   : 문자열,   (선택 - 생략하면 이 숏컷이 있는 던전 자신.
#                                    dungeon_system.해금상태_적용)
# }
#
# 판정은 이 던전에 들어올 때(dungeon_system.던전_시작 -> 해금상태_적용) 하고, 한 번 열리면 계속 열려 있다.
# 보스전투 오브젝트는 재입장하면 리젠되지만 클리어 기록은 영구라 숏컷은 계속 열려 있다.

# =====================================================
# <연결지역 항목 양식> - "연결지역" 딕셔너리의 값
# =====================================================
#
# {
#     "연결맵"   : 문자열,                  (연결되는 맵의 파일명)
#     "진입좌표" : (x, y),                  (연결된 맵에서 플레이어가 나타날 좌표, 마을이면 None)
# }

# =====================================================
# <인카운트 항목 양식> - "인카운트" 키의 값
# =====================================================
#
# {
#     "출현그룹"     : [ <출현그룹 항목>, ... ],
#                      (인카운트 1회마다 그룹을 하나 뽑고("그룹확률" 가중치), 그 그룹의 "출현몬스터"에서만
#                      "출현마리수" 전부를 뽑는다 - dungeon_system.인카운트_판정. 그룹 하나만 넣어도 된다)
#     "출현마리수"   : (최소, 최대),           (인카운트 1회에 등장하는 몬스터 수의 범위)
#     "레벨"         : 정수,                  (몬스터 레벨 - 역할군별 체력 공식이 쓴다, 모든 그룹 공통)
#     "차수"         : 정수,                  (몬스터 차수 - 역할군별 AC 공식이 쓴다)
#     "인카운트확률" : {
#         "안전걸음"   : 정수,                 (이 맵에 들어온 뒤 인카운트가 발생하지 않는 걸음 수)
#         "걸음당증가율": 실수,                 (안전걸음을 넘은 뒤, 걸음마다 인카운트 확률에 누적으로 더해지는 값)
#     },
# }

# =====================================================
# <출현그룹 항목 양식> - "출현그룹" 리스트의 원소
# =====================================================
#
# {
#     "그룹확률"   : 실수,                    (이 그룹이 뽑힐 상대 가중치)
#     "출현몬스터" : { 몬스터 이름: 등장확률, ... },
#                    (몬스터 데이터의 이름과 일치, 그룹 안 확률 합계는 1.0)
# }
