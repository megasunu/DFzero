# =====================
# 맵 데이터 양식
# =====================
# 소형지도(필드형 맵: 숲, 던전 등) 하나의 구조를 정의하는 참고용 파일이다.
# 실제 맵 데이터는 들어있지 않다.
#
# 마을처럼 안전지대가 필요한 곳은 이 격자 이동 방식을 쓰지 않고,
# 화면(배경 + 선택지) 형태의 별도 양식을 쓴다 (추후 별도로 정의 예정).
# 즉 이 양식이 다루는 맵은 전부 "이동 가능한 곳 = 인카운트 위험 지역"이다.
#
# 각 파일은 "맵정보" 딕셔너리 하나만 담는다.
# 지형(숲/바위/산 등 시각적 구분)은 이 파일이 아니라 별도의 시각적 이미지 레이어 파일에서 다룬다.
# 여기서는 통행가능여부·인카운트·오브젝트·연결지역만 다룬다.

# =====================================================
# <맵정보 항목 양식>
# =====================================================
#
# "지도명"   : 문자열                     예) "로리엔"
#
# "상세지역" : 문자열의 리스트             (이 맵이 속한 상위 지역들을, 큰 것부터 작은 순서로)
#                                        예) ["아라드", "벨마이어 공국 북부"]
#
# "지도"     : 문자열의 리스트             (각 문자열이 한 행, 문자 하나가 한 칸)
#              좌표는 (x, y) = (열, 행), 왼쪽 위가 (0, 0)
#              사용 가능한 기호는 아래 <지도 기호> 참고
#
# "입장좌표" : (x, y)  (선택 - 마을의 [던전 이동] 목록에서 곧바로 들어올
#              때처럼, 어느 연결지역을 거치지 않고 이 던전에 들어올 때
#              플레이어가 나타날 좌표. 생략하면 dungeon_system._기본_시작좌표()가
#              그리드에서 처음 만나는 이동 가능 칸을 대신 쓴다 - 대개
#              의도한 입구가 아니라서, 마을에서 바로 들어갈 수 있는
#              던전에는 이 값을 채워두는 게 좋다. 연결지역을 거쳐 들어올
#              때는 그 <연결지역 항목>의 "진입좌표"가 우선이고 이 값은
#              쓰이지 않는다. dungeon_system.던전_시작() 참고.)
#
# "오브젝트" : { (x, y): <오브젝트 항목>, ... }
#              "지도"에서 "@"로 표시된 칸의 상세 정보.
#              "@"가 아닌 칸의 좌표는 키로 넣지 않는다. 다만 예외가 하나
#              있다 - 아래 "클리어시":"연결지역화" 참고: 그 경우 "지도"엔
#              "@"로 있는 좌표를, "연결지역" 딕셔너리에도 미리 등록해 둔다.
#
# "연결지역" : { (x, y): <연결지역 항목>, ... }
#              "지도"에서 "#"으로 표시된 칸의 상세 정보.
#              "#"이 아닌 칸의 좌표는 키로 넣지 않는 것이 원칙이지만,
#              "오브젝트"의 "클리어시":"연결지역화" 좌표만은 예외로 미리
#              등록해 둔다(그 오브젝트가 클리어되기 전까지는 "지도"상
#              "@"라서 도달할 수 없으니 헷갈리지 않는다).
#
# "타일"     : {지도 기호: 타일 파일명, ...} (선택) - 이 맵에서 그 기호의 칸에 깔
#              한 칸짜리(8x8) 타일 그림. game/assets/dungeon/ 안의 파일명만 적는다.
#              예) {"O": "asset_tile_emerald.webp", "Y": "asset_tile_skyyellow.webp"}
#              값을 리스트로 쓰면 아래층부터 겹쳐 그린다 - 배경이 투명한 그림 밑에
#              바닥을 깔 때 쓴다. 예) {"#": ["asset_tile_skycastlewall.webp",
#              "asset_tile_gate_skycastle.webp"]}
#              같은 기호라도 맵마다 다른 그림을 쓸 수 있다. 적지 않은 기호는 공용
#              그림("O"=풀밭/흙길, "X"=나무, "#"=게이트, "@"=색)으로 그리고, 적은
#              기호에는 공용 나무/게이트 그림을 올리지 않는다. 출입구("#")는 어느 쪽이든
#              나무/큰 오브젝트보다 위(플레이어 아래)에 그린다. 파일이
#              없으면 그 기호의 색으로 칠한다(screens_dungeon.py 던전맵위젯 참고).
#
# "드랍표"   : [{"이름", "발동확률"}, ...] (선택) - 이 던전의 공용 드랍. 여기서
#              쓰러뜨린 몬스터마다 굴린다(몬스터 개인 "드랍표"와 별개, 둘 다 굴림).
#              형식은 monster_format.py <몬스터 드랍표 항목 양식> 1)과 같다.
# "특별드랍" : [{"아이템", "확률", "한번만"}, ...] (선택) - 드랍표와 별개로 쓰러뜨린 몬스터마다 "확률"로
#              그 아이템 하나. 한 전투에서 여럿을 쓰러뜨려도 하나만 나오고, "한번만"이면 도감에 등록된
#              (한 번이라도 얻은) 아이템은 다시 나오지 않는다. 전투 보상 후보에는 들어가지 않는다
#              (loot_system.특별드랍_판정 - 스위트 민트, #437).
#
# "인카운트" : <인카운트 항목> (선택 - 없으면 이 맵은 걸어 다녀도 무작위
#              조우가 발생하지 않는다. dungeon_system.인카운트_판정() 참고.)
#              이 맵 전체에서 공통으로 쓰는 인카운트 테이블 하나.
#              (파일 하나 = 맵 하나 = 등장 몬스터 구성이 항상 동일하므로,
#              구역별로 나누지 않고 맵 전체에 하나만 정의한다.)

# =====================================================
# <지도 기호>
# =====================================================
#
# "X" - 이동불가
# "Y" - 이동불가 ("X"와 같은 역할, 배경만 다르다 - 하늘이 보이는 칸. 탑 던전의
#        바깥쪽 등에 쓴다. 화면은 하늘색으로 칠한다 - screens_dungeon.py _칸_색)
# "O" - 이동 가능, 인카운트 위험 지역 (이 맵의 "인카운트" 값을 그대로 적용)
# "@" - 오브젝트 있음, 이동불가 (상세는 "오브젝트"에서 좌표로 조회)
# "#" - 연결지역, 이동 가능 (상세는 "연결지역"에서 좌표로 조회)

# =====================================================
# <오브젝트 항목 양식> - "오브젝트" 딕셔너리의 값
# =====================================================
#
# "분류"(이 오브젝트가 속한 큰 갈래)와 "타입"(그 갈래 안에서 실제로
# 무엇을 하는지)으로 나눈다. "종류" 필드는 쓰지 않는다.
#
# {
#     "분류" : "이벤트",                    (지금은 "@" 오브젝트 전부가 이
#                    값 하나뿐이다 - 다른 분류가 생기면 여기에 추가한다.)
#     "타입" : "NPC" | "보스전투" | "숏컷" | "상자" | 기타 문자열,
#                    (이 오브젝트가 실제로 무엇을 하는지.)
#     "이름" : 문자열,                      예) "세리아"
#     "설명" : 문자열,                      (선택. 대사·판매목록 등 상세 정의는 추후 확장)
# }
#
# "타일"       : 파일명 문자열 (선택)     예) "asset_tile_prison_seria.webp"
#                던전 지도에서 이 "@" 칸에 그릴 전용 타일 이미지.
#                game/assets/dungeon/ 안의 파일명만 적는다. 한 칸 크기로
#                풀밭 위에 겹쳐 그린다(배경이 투명한 이미지를 쓴다).
#                생략하거나 파일이 없으면 기존 "@" 색으로 칠한다
#                (screens_dungeon.py 던전맵위젯 참고). 오브젝트가 클리어돼
#                칸이 "O"/"#"으로 바뀌면 더 이상 그려지지 않는다.
#
# "타일크기"   : 정수 (선택, 기본 1)  "타일" 그림을 몇 x 몇 칸 크기로 그릴지. 2 이상이면
#                그 칸의 정중앙에 맞춰 크게 그리고, 삐져나온 부분은 바닥/나무보다 위,
#                플레이어보다 아래에 보인다(감옥처럼 한 칸을 차지하지만 큰 그림).
#                통행/상호작용은 여전히 그 한 칸뿐이다.
#
# "발동방식"   : "말걸기" (선택 - "보스전투"/"상자" 공통으로 쓸 수 있다)
#                생략하면 그 오브젝트 방향으로 이동을 시도한 순간(=인접한
#                칸에서 그 칸에 부딪히는 순간) 곧바로 실제 동작(전투 시작
#                / 상자 개봉 등)이 일어난다. "말걸기"로 적으면 그 순간에는
#                오브젝트의 "설명"만 먼저 보여주고, 플레이어가 그 자리에서
#                별도의 "말걸기" 행동을 골라야만 그때 실제 동작이
#                일어난다("말걸기" 버튼 자체는 "타입"과 무관하게 공용이고,
#                버튼을 누른 뒤 실제로 무슨 일이 일어나는지만 "타입"에
#                따라 갈린다). ※ 현재 Kivy 화면(screens_dungeon.py)에는
#                "말걸기"가 아직 구현되어 있지 않다.
#
# "타입"이 "상자"인 경우 (상호작용하면 보상을 지급하는 오브젝트) 아래
# 키가 추가된다.
#
#     "보상" : {"골드": 정수, ...}   (상자를 열면 지급할 보상. 지금은
#              "골드" 하나뿐이다 - player_system.골드_추가()로 플레이어
#              소지품의 골드에 더한다. 다른 보상(장비/소모품/포션/재료/
#              퀘스트아이템)은 player_system.아이템_추가()로 넣을 수
#              있다 - 다만 골드 이외의 보상을 실제로 지급하는 맵은
#              아직 없다.)
#
# 상자를 열면(=보상을 지급받으면) town_system.오브젝트_클리어_기록()으로
# 진행도["클리어한오브젝트"]에 영구히 기록된다("보스전투"를 이겼을 때와
# 완전히 같은 기록 방식 - town_system.오브젝트_클리어됨() 참고). 상자
# 오브젝트는 "클리어시" 키를 쓰지 않는다 - 그리드 상태 자체는 바꾸지
# 않고(칸은 계속 "@"로 남아 다시 부딪힐 수 있다), 대신 말을 걸 때마다
# 이 기록을 먼저 확인해서, 이미 연 적이 있으면 보상을 다시 주지 않고
# 안내 메시지만 보여준다. 던전을 나갔다 다시 들어와도(그리드가 리셋돼도)
# 이 기록만은 영구히 남아서 같은 상자를 여러 번 열어 보상을 반복해서
# 받을 수는 없다. ※ 현재 Kivy판(gameflow.오브젝트_상호작용)은 "보스전투"
# 타입만 처리하고, "상자"는 아직 구현되어 있지 않다.
#
# "타입"이 "보스전투"인 경우 (만나면 전투가 발생하는 오브젝트) 아래 키가 추가된다.
# 필드/체크 필드 이름은 잠정 - 실제 전투 시스템 제작 시 바뀔 수 있다.
#
#     "전투몬스터" : 몬스터 이름 / 몬스터 이름의 리스트 / 아래 형태의 리스트
#                    (monster_tier_XX.py에 정의된 몬스터명과 일치해야 함)
#                    [{"이름": 몬스터이름, "칭호": 칭호이름 또는 None}, ...]
#                    - 같은 오브젝트에 여러 마리가 섞여 있을 때, 그 중 특정
#                    개체 하나에만 칭호(monster_title.py 칭호목록)를 붙이고
#                    싶으면 이 딕셔너리 리스트 형태를 쓴다("칭호" 키를 생략하면
#                    None과 같다).
#     "레벨"       : 정수                  (이 오브젝트의 몬스터가 등장하는 레벨.
#                    monster_tier_XX.py 쪽 몬스터 데이터의 "레벨" 필드는 비워
#                    두고, 실제 값은 여기서 정한다 - monster_format.py의
#                    역할군별 체력 공식이 이 값을 쓴다.)
#     "차수"       : 정수                  (이 오브젝트의 몬스터가 등장하는 차수.
#                    마찬가지로 monster_format.py의 역할군별 AC 공식이 쓴다.)
#     "클리어시"   : "통행가능화" | "연결지역화"
#                    - "통행가능화": "지도"에서 이 오브젝트의 좌표가 "@"에서
#                      "O"로 바뀐다. 다만 이 "O"는 던전을 나갔다가 다시
#                      들어오면(dungeon_system.던전_시작이 매번 그리드를 새로
#                      만들기 때문에) 다시 "@"로 리셋된다 - 즉 "이번
#                      방문에서만" 유지되는 임시 상태다. 방문과 무관하게
#                      영구히 남는 기록이 필요하면 위 "숏컷" 타입을 참고.
#                    - "연결지역화": "지도"에서 이 오브젝트의 좌표가 "@"에서
#                      "#"로 바뀐다 - 그 자리가 곧장 다른 맵/마을로 가는
#                      연결지역이 된다는 뜻이다(주로 "이 보스를 깨면 그
#                      자리가 마을로 돌아가는 길이 된다" 같은 경우에 쓴다).
#                      이 값을 쓰려면 같은 맵정보의 "연결지역" 딕셔너리에도
#                      이 오브젝트와 같은 좌표로 <연결지역 항목>을 미리
#                      등록해 둬야 한다("지도" 문자열엔 아직 "@"라서
#                      평소엔 도달할 수 없다가, 클리어되는 순간부터 그
#                      항목이 실제로 쓰이게 된다).
#
# "타입"이 "숏컷"인 경우 (전투 없이, 다른 오브젝트가 최소 1회 이상
# 클리어된 적이 있는지만 보고 자동으로 "@"에서 "O"로 열리는 오브젝트 -
# 지름길에 쓴다) 아래 키가 추가된다. "전투몬스터"/"발동방식"/
# "클리어시" 키는 쓰지 않는다.
#
#     "해금조건" : <해금조건 항목>
#
# <해금조건 항목 양식>
# {
#     "필요오브젝트좌표" : (x, y),   ("필요던전파일명"이 가리키는 던전의
#                                    "오브젝트"에 있는 좌표 - 보통
#                                    "타입":"보스전투" 오브젝트. 그 좌표의
#                                    오브젝트가 이 진행도(town_system.py
#                                    "클리어한오브젝트") 기준으로 최소 1회
#                                    이상 클리어된 적이 있으면 조건을
#                                    만족한 것으로 본다.)
#     "필요던전파일명"   : 문자열,   (선택 - 생략하면 이 "숏컷" 오브젝트가
#                                    속한 던전 자신을 가리킨다. 다른 던전의
#                                    오브젝트 클리어 여부를 봐야 하면
#                                    (예: 머크우드의 지름길이 포이즌
#                                    선더랜드의 보스를 요구하는 경우) 그
#                                    던전 파일명을 여기에 적는다.
#                                    dungeon_system.해금상태_적용() 참고.)
# }
