# 조건을 만족하면 dungeon_system.던전_시작() 시점(더 정확히는 그 안에서 호출하는
# dungeon_system.해금상태_적용())에 이 오브젝트 좌표가 자동으로 "@"에서 "O"로
# 바뀐다. 한 번 열리면 계속 열려 있는 것으로 취급한다(다시 잠기는 경우는
# 상정하지 않음). "필요던전파일명"이 다른 던전을 가리키는 경우에도 판정
# 시점은 동일하다 - 이 숏컷이 있는 던전에 "들어올 때" 확인하므로, 그
# 사이에 다른 던전에서 조건을 채웠다면 다음에 이 던전에 들어올 때 바로
# 반영된다(실시간으로 즉시 열리는 것은 아니다).
#
# 참고: "필요오브젝트좌표"가 가리키는 보스전투 오브젝트 자체는 위 "클리어시"
# 설명대로 던전을 나갔다가 다시 들어오면 매번 "@"로 다시 리셋된다(재입장하면
# 바로 리젠하는 지금 방식을 그대로 쓰기로 확인함 - 별도의 "휴식해야 리젠"
# 로직은 없다). 하지만 "최소 1회 이상 클리어했는지" 자체는
# town_system.오브젝트_클리어_기록()으로 진행도에 영구히 남기 때문에, "숏컷"
# 타입 오브젝트는 그 보스전투 오브젝트가 리젠되어 있는지와 무관하게 계속
# 열려 있다. (참고: "상자"도 같은 오브젝트_클리어_기록()을 쓰지만, "상자"
# 자신이 이 기록을 재획득 방지에 쓸 뿐, "숏컷"의 "필요오브젝트좌표"로 상자를
# 가리키는 것도 구조상 가능하다 - 지금은 그런 조합을 쓰는 맵이 없다.)

