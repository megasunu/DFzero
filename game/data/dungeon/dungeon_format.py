#     "차수"         : 정수,                  (이 인카운트로 나오는 몬스터들의 차수.
#                      마찬가지로 monster_format.py의 역할군별 AC 공식이 쓴다.)
#     "인카운트확률" : {
#         "안전걸음"   : 정수,                 (이 맵에 들어온 뒤 인카운트가 발생하지 않는 걸음 수)
#         "걸음당증가율": 실수,                 (안전걸음을 넘은 뒤, 걸음마다 인카운트 확률에 누적으로 더해지는 값)
