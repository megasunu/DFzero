# 변동대상 별칭
# =====================================================
# 정식 이름은 "AC보너스"/"명중보너스"/"속도보너스"(사용자 결정 #455, #459). 엔진은 정식 이름으로 조회하고,
# 데이터에 남은 옛 이름(별칭)도 받는다 - 별칭 -> 정식 이름. 몬스터 특성·칭호·버프/디버프·상태이상 추가효과·
# 아군 상시 특성·장비 효과 모든 경로가 이 표를 거쳐 비교한다(같은_변동대상).
변동대상_별칭 = {"AC": "AC보너스", "명중률보너스": "명중보너스", "속도": "속도보너스"}


def 정식_변동대상(이름):
    """별칭이면 정식 이름, 아니면 그대로(문자열이 아닌 값도 그대로)."""
    return 변동대상_별칭.get(이름, 이름) if isinstance(이름, str) else 이름


def 같은_변동대상(가, 나):
    """두 변동대상 이름이 별칭까지 같은 것을 가리키나."""
    return 정식_변동대상(가) == 정식_변동대상(나)
