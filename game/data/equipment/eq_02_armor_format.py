# =====================
# 방어구 재질별 AC 기준
# =====================
# 방어구 부위는 상의, 하의, 어깨, 벨트, 신발 5개.
# 재질은 천갑 / 가죽 / 경갑 / 중갑 / 판금 5단계.
#
# 하의, 어깨, 벨트, 신발은 마법 부여가 없는 한 아무 능력치도 없다 - 판금만 예외로 AC 1씩
# (기타부위_재질별_AC보너스).
#
# 캐릭터 기본AC는 10이고, 방어구 착용으로 얻는 값은 전부 "AC보너스"로 붙는다.
# 최종 AC = 10 + AC보너스 + min(민첩수정치, 민첩상한)
# 민첩상한이 None이면 민첩수정치를 제한 없이 전부 더한다.
# 민첩상한이 0이면 민첩수정치를 아예 더할 수 없다.
#
# 천갑 : AC보너스 0, 민첩 제한 없음
# 가죽 : AC보너스 1, 민첩 제한 없음
# 경갑 : AC보너스 2, 민첩수정치는 +2까지만
# 중갑 : AC보너스 4, 민첩수정치 적용 불가
# 판금 : AC보너스 5, 민첩수정치 적용 불가 (+ 다른 4부위 AC 1씩 = 합 9), 부위별 해제 불가 패널티(아래)
#
# 중갑과 판금 (2026-10-12 사용자 결정): 마스터리(숙련/숙달), 세트 효과, 공용 패널티(명중 -1,
# 속도 -5, MP 소모 2배 - 숙련으로 해제, equipment_system.중갑_패널티)는 같다. 판금은 기본 AC가
# 더 높고(중갑 4 대 판금 5+1x4), 대신 부위마다 아이템 수치로 붙은 패널티가 있어 숙련으로도 없어지지 않는다:
#   상의 데미지보너스 -2 / 하의 민첩 -1 / 어깨 명중률보너스 -1 / 벨트 치명타주사위 -1
#   (디버프 치명타피해감소를 늘 가진 셈) / 신발 속도보너스 -2
#
# 커먼은 낡은 장비라 모든 부위에서 위 값보다 AC 1이 낮다(0 아래로는 안 내려감). 그래서 커먼
# 판금은 상의 4, 나머지 0 - 패널티만 더 있어 커먼 중갑(상의 3)보다 입을 이유가 거의 없다(의도).
#
# "타입"은 [부위, 재질](예: ["상의", "천갑"]), 악세서리/특수장비는 [부위](예: ["목걸이"]).
# "마법으로 봉인된 ~"은 끝에 "마법봉인"이 붙고 봉인을 풀어도 그대로다(2026-10-19 사용자 결정).
#
# 방어구 항목에는 "가격"(골드)이 들어간다.
# 가격 = 티어 x 레어도배수 x 10 (레어도배수는 eq_01_weapon_format.py 참고)

