# =====================
# 마법으로 봉인된 장비 - 마봉능력
# =====================
# "마법으로 봉인된 소검" 같은 레어 장비의 봉인을 풀면 그 부위에 나올 수 있는 마봉능력 중 하나가
# 무작위로 붙고, 이름이 "마법의 <마봉능력> <타입>"으로 바뀐다(예: 강타 -> "마법의 강타 소검",
# 근력 -> "마법의 근력 천갑 상의"). "마법의 <타입>"은 아래 봉인장비_해제이름.
#
# <마봉능력 항목> (2026-10-15 사용자 결정)
#   "부위" : 이 능력이 나올 수 있는 장비 탭 목록(따로 정하지 않은 능력은 전부위)
#   "효과" : 효과 원소 리스트. 버프와 같은 "변동대상"/"변동값"(속성강화/속성내성은 "속성"), 그 밖에
#            "대상타입"      그 몬스터 "타입"(야수형/언데드형/악마형/정령/용족)을 공격할 때만
#            "무기속성"      무기 공격의 "속성"을 바꾼다(공격타입은 그대로 - 참격 -> 참격 + 화속성)
#            "최종피해배율"  최종 데미지에 더하는 비율(0.1 = +10%)
#            ("집요함"은 버프와 같은 변동대상 - 공격이 빗나가면 그만큼 피해, buff.py 변동대상 메모)
#            "발동"          "턴시작" | "공격" | "명중" - 그때 일어나는 일:
#                            "확률"(없으면 항상), "버프"+"지속턴"(+"차수"), "추가피해"(주사위),
#                            "고정피해"+"빗나가도", "상태이상"+"내성"{능력치, DC}+"지속턴",
#                            "대상변동"(대상에게 거는 변동)+"최대중첩", "버프제거"(개수)
#   "설명" : 화면에 보일 글
#   상태이상 지속턴: 무력화CC 1턴, 약화CC 2턴, 그 밖(지속피해형) 3턴.
