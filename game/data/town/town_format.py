# =====================
# 마을 데이터 양식
# =====================
# 마을(배경 일러스트 + 선택지 화면) 하나의 구조를 정의하는 참고용 파일이다(실제 데이터 없음).
# NPC/상점/파티구성/창고/휴식 메뉴와 파티 상태 표시는 모든 마을 공용이라 이 양식에 넣지 않는다.
# 각 파일은 "마을정보" 딕셔너리 하나만 담는다.

# =====================================================
# <마을정보 항목 양식>
# =====================================================
#
# "마을명"     : 문자열                   예) "엘븐가드"
#
# "상세지역"   : 문자열의 리스트           (이 마을이 속한 상위 지역들을, 큰 것부터 작은 순서로)
#                                        예) ["아라드", "벨마이어 공국 북부"]
#
# "배경이미지" : 문자열                   (마을 화면 배경 그림. game/assets/town/ 안의 파일명만 적는다.
#                                        예) "asset_town_elvengard.webp"
#                                        "미정"이거나 파일이 없으면 그림 없이 표시한다)
#
# "던전목록"   : [던전 맵 파일명, ...]     (이 마을에서 [던전이동]으로 갈 수 있는 소형지도 목록.
#                                        dungeon_01A_DXX 형식의 파일명과 일치해야 함)
#
# "개방조건"   : <개방조건 항목> 또는 None (이 마을이 [마을이동] 목록에 뜨기 위한 조건.
#                                        시작 마을처럼 조건이 없으면 None)

# =====================================================
# <개방조건 항목 양식>
# =====================================================
#
# {
#     "타입" : "던전클리어" | 기타 문자열,
#     "대상" : 문자열,                     (예: 던전 맵 파일명. "타입"에 따라 의미가 달라짐)
# }
