# 소모품류 아이템 데이터.
#
# 음식은 item_food.py로 옮겼다.
#
# <투척 아이템 항목 양식>
#   "이름", "분류": "투척 아이템", "행동": "일반행동", "타겟": "적단일" | "적3체"(범위 - 주대상+좌우),
#   "속성": "무속성", "데미지": 수식 문자열, "명중률": "보정명중률",
#   "명중능력치": "근력", "가격": 정수(골드), "효과"(선택): 명중한 대상에게 거는 효과 리스트
#   (job_skill_format.py <효과 하위 양식>, 예: 표창의 출혈)
#   전투 중 [아이템]에서 현재 턴 캐릭터가 일반행동 1개로 던진다(ctl_potion.아군_투척아이템사용).
#   명중은 d20+명중능력치 보정치, 대상마다 따로 굴린다. 스킬과 같은 길(skill_system.스킬_실행)로 처리한다.
#
# <소환 아이템 항목 양식>
#   "이름", "분류": "소환 아이템", "버프이름": skill_effects.py의 소환 버프 이름, "가격": 정수(골드)
#   전투 중에만, 현재 턴 캐릭터가 보조행동 1개로 자신에게 쓴다(ctl_potion.아군_소환아이템사용).
#   소환수는 사용자의 능력치로 행동한다(summon_00.py "능력치참조": "시전자").
#
# <항아리 항목 양식>
#   "이름", "분류": "항아리", "장비레어도": 레어도(eq_01_weapon_format.py), "가격": 정수(골드)
#   마을/던전 소지품에서 쓰면 그 레어도 장비 전체에서 하나가 나온다(ctl_potion.항아리_열기).
#   그 레어도 장비가 아직 없으면 "데이터 없음" - 항아리는 그대로 남는다.
#   가격은 만진(언커먼) 20골드부터 등급마다 5배, 크로니클과 레전더리는 같은 가격(사용자 지정 2026-10-12).

# <스프레이 항목 양식> (#506)
#   "이름", "분류": "스프레이", "걸음": 정수 또는 None(던전을 나갈 때까지), "가격": 정수(골드)
#   던전 안 소지품에서만 쓴다(ctl_potion.스프레이_사용). 그 걸음 동안 인카운트가 없고 걸음수도 쌓이지 않는다
#   (dungeon_system.이동_시도, 던전상태["스프레이"]). 여러 개를 쓰면 각각 따로 센다(봉절과도 따로).
#   이어진 던전으로 옮겨도 남고, 마을로 나가면 사라진다.
#
# <부여 항목 양식> (#506)
#   "이름", "분류": "부여 아이템", "부여속성": 속성 이름(common_names), "가격": 정수(골드)
#   캐릭터["무기속성부여"]에 속성을 더한다 - 무기 공격(일반공격, 무기 주사위 스킬)에 그 속성을 더해 가장 아픈
#   속성으로 친다(버프 "무기속성추가"와 같다). 다른 속성을 또 쓰면 더 쌓인다. 마을 휴식으로 풀린다.
#   마을/던전 소지품에서는 캐릭터를 골라(ctl_potion.캐릭터_부여아이템사용), 전투 중에는 현재 턴 캐릭터가
#   보조행동 1개로 자신에게 쓴다(ctl_potion.아군_부여아이템사용).

